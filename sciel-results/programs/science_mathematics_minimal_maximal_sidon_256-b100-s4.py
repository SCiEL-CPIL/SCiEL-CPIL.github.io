import time
import random

N = 256

def construct():
    start_time = time.time()
    deadline = start_time + 25.0
    
    best_size = N + 1
    best_set = []
    
    # We will run multiple random restarts
    # The greedy choice is: pick z that blocks the most available elements.
    # To introduce randomness, we can shuffle available or add noise to the score.
    
    for iter in range(200): # Limit iterations to ensure we finish
        if time.time() > deadline:
            break
            
        random.seed(iter)
        
        S_mask = 0
        sums_mask = 0
        available_mask = (1 << (N + 1)) - 2 # Bits 1..N set. Bit 0 unused.
        # Actually, 1 << (N+1) creates a number with bit N+1 set.
        # We want bits 1 to N.
        # (1 << (N + 1)) - 1 gives bits 0..N.
        # So available_mask = ((1 << (N + 1)) - 1) & ~1 # Clear bit 0.
        available_mask = ((1 << (N + 1)) - 1) ^ 1
        
        S_list = []
        
        while available_mask:
            # Find best z
            best_z = -1
            max_blocked = -1
            
            # Get list of available elements
            avail_list = []
            temp_mask = available_mask
            while temp_mask:
                # Get lowest set bit
                lsb = temp_mask & -temp_mask
                z = lsb.bit_length() - 1
                avail_list.append(z)
                temp_mask ^= lsb
            
            random.shuffle(avail_list)
            
            for z in avail_list:
                # Check if z is valid to add
                # 1. 2z not in sums
                if (sums_mask >> (2*z)) & 1:
                    continue
                # 2. No collision with existing sums
                # (sums_mask >> z) & S_mask == 0
                if (sums_mask >> z) & S_mask:
                    continue
                
                # Simulate adding z
                new_S_mask = S_mask | (1 << z)
                new_sums_mask = sums_mask | (1 << (2*z))
                # Add z + a for a in S
                # This is sums_mask shifted by z, masked by S_mask
                # Wait, sums_mask contains a+b.
                # We need to add z+a.
                # The set of new sums is {z+a | a in S} U {2z}.
                # We can compute the bits for z+a by shifting sums? No.
                # We need to iterate a in S?
                # Or: new_sums_mask |= (sums_mask >> z) ... no.
                
                # Let's compute the new sums bits properly.
                # The new sums are generated by pairs (z, a) and (z, z).
                # (z, z) -> 2z.
                # (z, a) -> z+a.
                # We already have sums from S.
                # So new_sums_mask = sums_mask | (1 << 2z) | (bits for z+a).
                
                # How to get bits for z+a efficiently?
                # We can iterate a in S. S is small (<20).
                add_bits = 0
                temp_S = S_mask
                while temp_S:
                    lsb_S = temp_S & -temp_S
                    a = lsb_S.bit_length() - 1
                    add_bits |= (1 << (z + a))
                    temp_S ^= lsb_S
                
                new_sums_mask |= add_bits
                
                # Count blocked w in available_mask (excluding z)
                blocked_count = 0
                # Iterate w in avail_list (excluding z)
                # To speed up, we can just iterate avail_list
                for w in avail_list:
                    if w == z:
                        continue
                    # Check if w is blocked by new_S_mask and new_sums_mask
                    # 1. 2w in new_sums_mask
                    if (new_sums_mask >> (2*w)) & 1:
                        blocked_count += 1
                        continue
                    # 2. w+a in new_sums_mask for some a in new_S_mask
                    # Check: (new_sums_mask >> w) & new_S_mask != 0
                    if (new_sums_mask >> w) & new_S_mask:
                        blocked_count += 1
                
                # Heuristic: Maximize blocked_count
                # Add small random noise to break ties and encourage diversity
                score = blocked_count + random.random() * 0.5
                
                if score > max_blocked:
                    max_blocked = score
                    best_z = z
            
            if best_z == -1:
                # Should not happen if available is not empty and we start with empty S
                # But if no z is valid, we break?
                # Actually, if available is not empty, there must be a valid z?
                # Not necessarily. If S is not empty, some available z might be invalid.
                # But we are picking from available, which was filtered to be valid for current S?
                # No, we update available_mask after each step.
                # So all z in avail_list should be valid?
                # Let's ensure available_mask only contains valid elements.
                
                # If we break here, it means we couldn't pick any.
                break
            
            # Commit best_z
            S_mask |= (1 << best_z)
            S_list.append(best_z)
            
            # Update sums_mask
            # Add 2*best_z
            sums_mask |= (1 << (2*best_z))
            # Add best_z + a for a in old S
            temp_S = S_mask ^ (1 << best_z) # Old S
            while temp_S:
                lsb_S = temp_S & -temp_S
                a = lsb_S.bit_length() - 1
                sums_mask |= (1 << (best_z + a))
                temp_S ^= lsb_S
            
            # Update available_mask
            # Remove best_z
            available_mask &= ~(1 << best_z)
            
            # Remove any w that is now blocked
            # Iterate remaining available
            temp_avail = available_mask
            new_avail_mask = 0
            while temp_avail:
                lsb_w = temp_avail & -temp_avail
                w = lsb_w.bit_length() - 1
                # Check if w is still valid
                # 1. 2w not in sums_mask
                if not ((sums_mask >> (2*w)) & 1):
                    # 2. No collision
                    if not ((sums_mask >> w) & S_mask):
                        new_avail_mask |= lsb_w
                temp_avail ^= lsb_w
            
            available_mask = new_avail_mask
        
        if len(S_list) < best_size:
            best_size = len(S_list)
            best_set = S_list[:]
            
    return best_set
