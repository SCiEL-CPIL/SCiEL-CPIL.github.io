        if n_target <= len(pos_55):
            # Remove atoms
            # Sort by distance from center
            dists = np.linalg.norm(pos_55, axis=1)
            sort_idx = np.argsort(dists)[::-1] # Farthest first
            # Remove (len - n_target) atoms
            num_to_remove = len(pos_55) - n_target
