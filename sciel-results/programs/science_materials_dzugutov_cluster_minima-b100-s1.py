    rng = np.random.default_rng(size + 100)
    
    # 1. Generate a high-quality icosahedral seed
    # We will generate a 55-atom cluster as a master template.
    # If size is close to 55, we modify it.
    
    def generate_icosahedral_seed(n_target):
        """
        Generate a seed structure of size n_target based on icosahedral symmetry.
        """
        # Generate 13-atom icosahedron
        verts = _get_icosahedron_vertices()
        # Scale to typical bond length ~1.1
        verts = verts * 1.1
        center = np.array([0.0, 0.0, 0.0])
        atoms_13 = np.vstack([center, verts])
        
        if n_target == 13:
            return atoms_13
            
        # For larger clusters, we build up from 13.
        # We want to create a 55-atom master if n_target is in [38..60].
        # Let's generate a 55-atom cluster first.
        
        # Generate 55-atom cluster:
        # Start with 13. Add 42 atoms.
        # We will use rejection sampling to add atoms in a shell.
        current_atoms = atoms_13.copy()
        min_dist = 0.5
        radius_inner = 1.1
        radius_outer = 1.1 * 1.8 # Approximate radius for 55 atoms
        
        attempts = 0
        max_attempts = 5000
        while len(current_atoms) < 55 and attempts < max_attempts:
            # Sample in a shell
            r = rng.uniform(radius_inner, radius_outer)
            theta = rng.uniform(0, 2*np.pi)
            phi = np.arccos(rng.uniform(-1, 1))
            p = np.array([
                r * np.sin(phi) * np.cos(theta),
                r * np.sin(phi) * np.sin(theta),
                r * np.cos(phi)
            ])
            
            # Check distance to all existing atoms
            dists = np.linalg.norm(current_atoms - p, axis=1)
            if np.min(dists) >= min_dist:
                current_atoms = np.vstack([current_atoms, p])
            attempts += 1
            
        # If we couldn't get 55, we have what we have.
        # Relax this 55-atom (or less) cluster
        try:
            e, pos_55 = relax(current_atoms, POTENTIAL)
        except:
            pos_55 = current_atoms
            
