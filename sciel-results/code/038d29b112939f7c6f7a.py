"""
B_3[1] set construction using Batched Backtracking Search.

Strategy:
  1. Partition the range [1, 4096] into small batches.
  2. For each batch, perform a depth-first backtracking search to find the
     maximum cardinality subset that is internally valid AND compatible
     with the sums generated by the previously accepted elements.
  3. This avoids the "greedy trap" where early small numbers block many
     future options, by exploring alternative combinations within the batch.
"""
import time
import sys
from functools import lru_cache

N_MAX = 4096

def _triple_sums(S):
    """Compute set of all unordered triple sums for sorted list S."""
    sums = set()
    n = len(S)
    for i in range(n):
        for j in range(i, n):
            for k in range(j, n):
                sums.add(S[i] + S[j] + S[k])
    return sums

def _is_valid(S):
    """Verify all unordered triple sums are unique."""
    n = len(S)
    seen = set()
    for i in range(n):
        for j in range(i, n):
            for k in range(j, n):
                s = S[i] + S[j] + S[k]
                if s in seen:
                    return False
                seen.add(s)
    return True

def _construct_batch(batch, forbidden_sums, deadline, rng_seed):
    """
    Find the maximum valid subset of 'batch' that does not conflict
    with 'forbidden_sums' (sums from previous batches).
    
    Uses backtracking with pruning.
    """
    # Pre-compute internal triple sums for the batch to speed up checks
    # We need to check:
    # 1. Internal conflicts within the chosen subset.
    # 2. Conflicts with forbidden_sums (sums involving 1 or 2 elements from subset + 1 or 2 from previous).
    
    # To make this tractable, we use a greedy-with-backtracking approach.
    # We process elements in the batch.
    
    best_subset = []
    best_size = 0
    
    # Sort batch
    batch_sorted = sorted(batch)
    n = len(batch_sorted)
    
    # State for backtracking
    # current_subset: list of chosen elements so far
    # current_sums: set of sums generated by current_subset (internal)
    # We also need to check against forbidden_sums for new triples.
    
    # Optimization: If we just add x to a set S, the new sums are:
    # 3x, 2x+y, x+2y, x+y+z for y,z in S.
    # Any of these must not be in forbidden_sums AND must not be in current_sums.
    
    def backtrack(idx, current_subset, current_sums):
        nonlocal best_subset, best_size
        
        if time.time() > deadline:
            return
        
        # Pruning: if remaining elements + current size <= best_size, stop
        if idx + (n - idx) <= best_size:
            return
            
        if idx == n:
            if len(current_subset) > best_size:
                best_size = len(current_subset)
                best_subset = list(current_subset)
            return
        
        # Option 1: Exclude batch_sorted[idx]
        backtrack(idx + 1, current_subset, current_sums)
        
        # Option 2: Include batch_sorted[idx]
        x = batch_sorted[idx]
        
        # Check if x can be added
        valid = True
        new_sums = set()
        
        # Check 3x
        if 3*x in current_sums or 3*x in forbidden_sums:
            valid = False
        else:
            new_sums.add(3*x)
        
        # Check 2x+y and x+2y
        if valid:
            for y in current_subset:
                s1 = 2*x + y
                s2 = x + 2*y
                if s1 in current_sums or s1 in forbidden_sums:
                    valid = False
                    break
                if s2 in current_sums or s2 in forbidden_sums:
                    valid = False
                    break
                new_sums.add(s1)
                new_sums.add(s2)
        
        # Check x+y+z
        if valid:
            n_sub = len(current_subset)
            for i in range(n_sub):
                for j in range(i, n_sub):
                    s = x + current_subset[i] + current_subset[j]
                    if s in current_sums or s in forbidden_sums:
                        valid = False
                        break
                    new_sums.add(s)
                if not valid:
                    break
        
        if valid:
            # Add x to subset and recurse
            current_subset.append(x)
            current_sums.update(new_sums)
            backtrack(idx + 1, current_subset, current_sums)
            current_subset.pop()
            for s in new_sums:
                current_sums.discard(s)

    backtrack(0, [], set())
    return best_subset

def construct():
    start_time = time.time()
    deadline = start_time + 85  # Safety margin
    
    # Strategy: Divide [1, 4096] into batches.
    # Smaller batches allow for more effective backtracking.
    # However, conflicts can span batches.
    # The "forbidden_sums" approach handles cross-batch conflicts.
    
    # Let's try a batch size of 10-20.
    # If batch size is too large, backtracking is exponential.
    # If too small, we might miss global optimizations, but forbidden_sums
    # ensures validity.
    
    batch_size = 12
    num_batches = (N_MAX + batch_size - 1) // batch_size
    
    all_elements = []
    forbidden_sums = set()
    
    for b in range(num_batches):
        if time.time() > deadline:
            break
            
        start_val = b * batch_size + 1
        end_val = min((b + 1) * batch_size, N_MAX)
        batch = list(range(start_val, end_val + 1))
        
        # Find best subset in this batch
        subset = _construct_batch(batch, forbidden_sums, deadline, 42)
        
        all_elements.extend(subset)
        
        # Update forbidden_sums with all triple sums involving any element from this batch
        # and any combination of elements from previous batches (or within this batch).
        # Actually, we just need to add ALL triple sums of the new global set to forbidden_sums
        # for the next batch? No, that's O(N^3) memory/time if we store all.
        # But N_MAX is 4096. Max size ~80.
        # The number of triple sums is ~80^3/6 ~ 85k. This is small.
        # So we can maintain the full set of sums of all_elements.
        
        # Rebuild sums for efficiency (since all_elements is small)
        forbidden_sums = _triple_sums(all_elements)
        
        # Optimization: If we are running out of time, switch to greedy for remaining
        if time.time() > deadline - 10:
            # Greedy fill for the rest
            for x in range(end_val + 1, N_MAX + 1):
                if time.time() > deadline:
                    break
                # Check if x is valid against all_elements
                # Fast check
                valid = True
                # 3x
                if 3*x in forbidden_sums:
                    valid = False
                else:
                    # 2x+y
                    for y in all_elements:
                        if 2*x + y in forbidden_sums or x + 2*y in forbidden_sums:
                            valid = False
                            break
                    if valid:
                        # x+y+z
                        n = len(all_elements)
                        for i in range(n):
                            for j in range(i, n):
                                if x + all_elements[i] + all_elements[j] in forbidden_sums:
                                    valid = False
                                    break
                            if not valid:
                                break
                
                if valid:
                    all_elements.append(x)
                    # Update forbidden sums incrementally for speed in greedy phase?
                    # Or just rebuild at the end?
                    # Rebuilding is O(N^3) ~ 80^3 = 512k ops. Very fast.
                    forbidden_sums = _triple_sums(all_elements)
            break
    
    # Final verification
    if not _is_valid(all_elements):
        # Fallback to simple greedy if something went wrong
        S = []
        sums = set()
        for x in range(1, N_MAX + 1):
            if time.time() > deadline:
                break
            valid = True
            if 3*x in sums:
                valid = False
            else:
                for y in S:
                    if 2*x + y in sums or x + 2*y in sums:
                        valid = False
                        break
                if valid:
                    for i in range(len(S)):
                        for j in range(i, len(S)):
                            if x + S[i] + S[j] in sums:
                                valid = False
                                break
                        if not valid:
                            break
            if valid:
                S.append(x)
                sums.add(3*x)
                for y in S:
                    sums.add(2*x + y)
                    sums.add(x + 2*y)
                for i in range(len(S)):
                    for j in range(i, len(S)):
                        sums.add(x + S[i] + S[j])
        all_elements = S
    
    return all_elements

if __name__ == "__main__":
    s = time.time()
    res = construct()
    print(f"Time: {time.time()-s:.2f}s, Size: {len(res)}")
    if _is_valid(res):
        print("Valid")
    else:
        print("Invalid")
