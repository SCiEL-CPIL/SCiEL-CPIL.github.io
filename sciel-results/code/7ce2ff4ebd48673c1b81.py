import numpy as np
from scipy.optimize import minimize


class Optimizer:
    """Derivative-free optimization using Nelder-Mead with multiple restarts."""

    def __init__(self, budget, dim):
        self.budget, self.dim = budget, dim

    def __call__(self, func):
        rng = np.random.default_rng(42)
        
        # We have a total budget of 500 function evaluations.
        # Nelder-Mead is a derivative-free method that works well for smooth-ish functions.
        # Since the function is unknown but bounded, we use multiple restarts to avoid local minima.
        
        # Strategy:
        # 1. Use a portion of the budget for an initial coarse search or just start with a few random restarts.
        # 2. Each restart uses Nelder-Mead.
        
        # Let's allocate the budget among restarts.
        # A good heuristic is to have several restarts, each with a limited number of iterations.
        # Nelder-Mead in scipy uses `maxiter` and `maxfev`.
        
        # Let's try 5 restarts, each with a budget of ~100 evaluations.
        # Or adaptively: keep the best point and restart if progress stalls.
        
        # Simpler robust approach:
        # Split budget into chunks. For each chunk, run Nelder-Mead starting from a random point or the previous best.
        
        num_restarts = 5
        evals_per_restart = self.budget // num_restarts
        
        best_x = None
        best_f = np.inf
        
        for i in range(num_restarts):
            # Initialize starting point
            if i == 0:
                # First restart: random point
                x0 = rng.uniform(-5, 5, self.dim)
            else:
                # Subsequent restarts: perturb the current best
                # Use a larger perturbation to explore new areas
                x0 = np.clip(best_x + rng.normal(0, 2.0, self.dim), -5, 5)
            
            # Define the function for scipy
            # scipy's minimize counts function calls.
            # We need to ensure we don't exceed the total budget.
            # We'll track calls manually or just rely on maxfev.
            
            # Nelder-Mead parameters
            # initial_simplex is generated by scipy if not provided.
            # We can provide an initial simplex to control the initial step size.
            # Default initial step is 0.05 * x0 + 0.00025 if x0 is 0.
            # Let's use a reasonable initial step size, e.g., 1.0.
            
            # Create initial simplex
            simplex = []
            for j in range(self.dim + 1):
                if j == 0:
                    simplex.append(x0)
                else:
                    xj = x0.copy()
                    xj[j-1] += 1.0
                    xj = np.clip(xj, -5, 5)
                    simplex.append(xj)
            
            # Run Nelder-Mead
            # maxfev is the maximum number of function evaluations.
            result = minimize(
                func, 
                x0, 
                method='Nelder-Mead',
                options={'maxiter': evals_per_restart * self.dim, 
                         'maxfev': evals_per_restart,
                         'xatol': 1e-4,
                         'fatol': 1e-4,
                         'initial_simplex': simplex}
            )
            
            if result.fun < best_f:
                best_f = result.fun
                best_x = result.x
        
        return best_x, best_f

