import math
import time
import random
from collections import defaultdict

def _line_key(p1, p2):
    x1, y1 = p1
    x2, y2 = p2
    dx = x2 - x1
    dy = y2 - y1
    g = math.gcd(abs(dx), abs(dy))
    if g == 0:
        return (0, 0, 0)
    dx //= g
    dy //= g
    if dx < 0 or (dx == 0 and dy < 0):
        dx = -dx
        dy = -dy
    A = dy
    B = -dx
    C = A * x1 + B * y1
    g2 = math.gcd(math.gcd(abs(A), abs(B)), abs(C))
    if g2 != 0:
        A //= g2
        B //= g2
        C //= g2
    if A < 0 or (A == 0 and B < 0) or (A == 0 and B == 0 and C < 0):
        A = -A
        B = -B
        C = -C
    return (A, B, C)

def _full_score(pts):
    """Calculate score and validity for a set of points."""
    lines = defaultdict(set)
    n = len(pts)
    for i in range(n):
        for j in range(i + 1, n):
            key = _line_key(pts[i], pts[j])
            lines[key].add(i)
            lines[key].add(j)
    
    score = 0
    valid = True
    for key, indices in lines.items():
        cnt = len(indices)
        if cnt >= 5:
            valid = False
            return -1, False
        elif cnt == 4:
            score += 1
    return score, valid

def _init_line_structures(pts):
    """Build line counts and point sets."""
    line_counts = defaultdict(int)
    line_points = defaultdict(set)
    n = len(pts)
    for i in range(n):
        for j in range(i + 1, n):
            key = _line_key(pts[i], pts[j])
            line_counts[key] += 1
            line_points[key].add(i)
            line_points[key].add(j)
    return line_counts, line_points

def _delta_move(pts, idx, new_pos, line_counts, line_points):
    """
    Calculate the change in score and validity when moving pts[idx] to new_pos.
    Returns (delta_score, new_valid).
    """
    old_pos = pts[idx]
    if old_pos == new_pos:
        return 0, True
    
    # 1. Remove old contributions
    # For each other point j, the line (old_pos, pts[j]) is no longer present for idx
    # We need to decrement the count for that line.
    # But careful: if multiple j's define the same line, we decrement once per j?
    # No, line_counts[key] is the total number of points on that line.
    # If we move idx, it leaves all lines that contained it.
    
    # Identify lines containing idx at old_pos
    old_lines_to_remove = {}
    for j in range(len(pts)):
        if j == idx:
            continue
        key = _line_key(old_pos, pts[j])
        # We need to know how many times this line key appears in the "removal" set
        # Actually, for each j, we are removing idx from the line (old_pos, pts[j]).
        # So for each unique line key generated by (old_pos, pts[j]), we decrement count by 1.
        # Wait, if two different j's lie on the same line with old_pos, they share the same key.
        # So we should decrement by 1 for each unique key?
        # No. The count is the number of points.
        # If line L has points {idx, j1, j2}, count is 3.
        # If idx moves, count becomes 2.
        # So we decrement by 1 for the line L.
        # It doesn't matter how many j's are on L, we just remove idx once.
        
        if key not in old_lines_to_remove:
            old_lines_to_remove[key] = 0
        old_lines_to_remove[key] += 1 # This logic is slightly off if we just want to decrement once per line.
        
    # Correct logic:
    # The set of lines that idx was on is determined by the other points.
    # For each unique line key L that idx was on, we decrement line_counts[L] by 1.
    
    unique_old_keys = set()
    for j in range(len(pts)):
        if j == idx:
            continue
        key = _line_key(old_pos, pts[j])
        unique_old_keys.add(key)
        
    delta = 0
    valid = True
    
    for key in unique_old_keys:
        old_count = line_counts[key]
        # Before move, this line had old_count points.
        # After move, it will have old_count - 1 points.
        
        # Score impact:
        if old_count == 4:
            # Was a 4-line, becomes 3-line. Lose 1 point.
            delta -= 1
        elif old_count == 5:
            # Was invalid, becomes 4-line. But we assume current state is valid.
            # If current state is valid, old_count cannot be 5.
            pass
        elif old_count > 5:
            # Invalid state, shouldn't happen if we maintain validity.
            pass
            
        # Update count for subsequent checks (conceptually)
        # We don't update the dict yet, we just calculate delta.
        
    # 2. Add new contributions
    unique_new_keys = set()
    for j in range(len(pts)):
        if j == idx:
            continue
        key = _line_key(new_pos, pts[j])
        unique_new_keys.add(key)
        
    for key in unique_new_keys:
        # Current count in line_counts[key] is the count WITHOUT idx (since we conceptually removed it)
        # Wait, line_counts[key] currently reflects the state BEFORE the move.
        # So if key is in unique_old_keys, line_counts[key] includes idx.
        # If key is NOT in unique_old_keys, line_counts[key] does NOT include idx.
        
        if key in unique_old_keys:
            # The line existed before, and idx was on it.
            # Current count in dict = old_count.
            # New count = old_count - 1 + 1 = old_count.
            # Wait, if idx moves from old_pos to new_pos, and the line key is the SAME?
            # This implies old_pos, new_pos, and pts[j] are collinear.
            # In this case, the line count doesn't change for this specific line.
            # But did the line identity change? No, the key is the same.
            # So the count remains the same.
            # Score impact: 0 for this line.
            pass
        else:
            # The line did NOT contain idx before.
            # Current count in dict = count without idx.
            # New count = current_count + 1.
            new_count = line_counts[key] + 1
            
            if new_count == 4:
                # Becomes a 4-line. Gain 1 point.
                delta += 1
            elif new_count == 5:
                # Becomes invalid.
                valid = False
            elif new_count > 5:
                valid = False
                
    return delta, valid

def _sa_search(pts, deadline, seed):
    rng = random.Random(seed)
    
    # Initialize line structures
    line_counts, line_points = _init_line_structures(pts)
    current_score, current_valid = _full_score(pts)
    
    if not current_valid:
        # If initial is invalid, try to fix it quickly or restart
        # For simplicity, we'll just run and hope it fixes, or we can do a repair step.
        # Let's do a quick repair: move points that are in 5-lines to random spots.
        pass

    best_pts = [list(p) for p in pts]
    best_score = current_score
    
    T = 50.0
    T_min = 0.1
    steps = 50000 # Adjust based on time
    
    # Determine max steps based on time budget
    # Each step is fast. Let's just run until deadline.
    
    for step in range(steps):
        if time.time() > deadline:
            break
            
        # Cooling
        T = max(T_min, T * 0.999)
        
        # Pick a random point to move
        idx = rng.randint(0, 15)
        old_pos = pts[idx]
        
        # Pick a new position
        # Neighborhood: random offset
        # To explore larger space, occasionally jump further
        if rng.random() < 0.1:
            # Jump
            dx = rng.randint(-10, 10)
            dy = rng.randint(-10, 10)
        else:
            # Local move
            dx = rng.randint(-2, 2)
            dy = rng.randint(-2, 2)
            
        new_pos = (old_pos[0] + dx, old_pos[1] + dy)
        
        # Check bounds
        if not (-1000 <= new_pos[0] <= 1000 and -1000 <= new_pos[1] <= 1000):
            continue
            
        # Check collision with other points
        if any(new_pos == pts[j] for j in range(16) if j != idx):
            continue
            
        # Calculate delta
        delta, new_valid = _delta_move(pts, idx, new_pos, line_counts, line_points)
        
        if not new_valid:
            # Reject invalid moves (unless we want to allow them temporarily? 
            # No, hard constraint is better for this problem size)
            continue
            
        new_score = current_score + delta
        
        # Acceptance criterion
        if new_score > current_score or rng.random() < math.exp((new_score - current_score) / T):
            # Accept move
            pts[idx] = list(new_pos)
            current_score = new_score
            
            # Update line structures
            # Remove old lines
            unique_old_keys = set()
            for j in range(16):
                if j == idx:
                    continue
                key = _line_key(old_pos, pts[j])
                unique_old_keys.add(key)
                
            for key in unique_old_keys:
                line_counts[key] -= 1
                line_points[key].discard(idx)
                if line_counts[key] == 0:
                    del line_counts[key]
                    del line_points[key]
                    
            # Add new lines
            unique_new_keys = set()
            for j in range(16):
                if j == idx:
                    continue
                key = _line_key(new_pos, pts[j])
                unique_new_keys.add(key)
                
            for key in unique_new_keys:
                if key not in line_counts:
                    line_counts[key] = 0
                    line_points[key] = set()
                line_counts[key] += 1
                line_points[key].add(idx)
                
            if current_score > best_score:
                best_score = current_score
                best_pts = [list(p) for p in pts]
                
    return best_pts, best_score

def construct():
    start_time = time.time()
    deadline = start_time + 140.0 # Safety margin
    
    best_pts_global = None
    best_score_global = -1
    
    # Try multiple seeds and grid initializations
    for seed in range(50):
        if time.time() > deadline:
            break
            
        rng = random.Random(seed)
        
        # Initialize points in a grid
        # Use a 15x15 grid centered at 0
        grid_size = 15
        offset = -grid_size // 2
        points = []
        used = set()
        for _ in range(16):
            x = rng.randint(offset, offset + grid_size - 1)
            y = rng.randint(offset, offset + grid_size - 1)
            p = (x, y)
            if p not in used:
                used.add(p)
                points.append(p)
        
        # Ensure 16 distinct points
        while len(points) < 16:
            x = rng.randint(-10, 10)
            y = rng.randint(-10, 10)
            p = (x, y)
            if p not in used:
                used.add(p)
                points.append(p)
                
        # Run SA
        pts, score = _sa_search(points, deadline, seed)
        
        if score > best_score_global:
            best_score_global = score
            best_pts_global = pts
            
    # Fallback: 4x4 grid
    if best_pts_global is None or best_score_global < 10:
        pts = [[x, y] for x in range(4) for y in range(4)]
        best_pts_global = pts
        best_score_global, _ = _full_score(pts)
        
    return best_pts_global

