import time
import random
import sys

def construct(n):
    if n <= 1:
        return "1"
    
    # Deadline guard
    start_time = time.time()
    deadline = start_time + 110  # 10s margin
    
    # 1. Generate standard superpermutation for n-1
    # This is needed to get the list of permutations in a valid order 
    # that we can then reorder.
    # Actually, we just need the list of all permutations of 1..n-1.
    # The order doesn't matter for the *set*, only for the initial guess.
    
    # Standard construction for n-1 to get a valid starting order
    word = [1]
    for m in range(2, n):
        perms, seen = [], set()
        for i in range(len(word) - m + 2):
            window = tuple(word[i:i + m - 1])
            if len(set(window)) == m - 1 and window not in seen:
                seen.add(window)
                perms.append(window)
        
        new = []
        for p in perms:
            block = list(p) + [m] + list(p)
            # Find max overlap
            max_overlap = 0
            for o in range(min(len(new), len(block)), -1, -1):
                if new[len(new) - o:] == block[:o]:
                    max_overlap = o
                    break
            new += block[max_overlap:]
        word = new
    
    # word is S_{n-1}
    # Extract the sequence of permutations of length n-1
    # Note: The standard construction ensures all perms are present.
    # We extract them in order of appearance.
    perms_seq = []
    seen = set()
    perm_len = n - 1
    for i in range(len(word) - perm_len + 1):
        window = tuple(word[i:i + perm_len])
        if len(set(window)) == perm_len and window not in seen:
            seen.add(window)
            perms_seq.append(window)
            
    # perms_seq contains all (n-1)! permutations.
    # We will now construct S_n by merging blocks p + [n] + p for p in some order.
    # We start with the order from perms_seq.
    
    current_order = perms_seq
    
    def calc_length(order):
        """Calculates length of the superpermutation generated by 'order'."""
        if not order:
            return 0
        # First block
        first_block = list(order[0]) + [n] + list(order[0])
        total_len = len(first_block)
        current_suffix = first_block
        
        for p in order[1:]:
            block = list(p) + [n] + list(p)
            # Find max overlap between current_suffix and block
            # Max possible overlap is len(p) = n-1
            # Actually, could be more?
            # Suffix of previous block is p_prev.
            # Prefix of current block is p_curr.
            # Overlap is limited by min(len(p_prev), len(p_curr)) = n-1.
            max_ov = 0
            # Check overlaps from max possible down to 0
            # Max overlap is n-1
            for o in range(n - 1, -1, -1):
                if current_suffix[-o:] == block[:o]:
                    max_ov = o
                    break
            total_len += len(block) - max_ov
            # Update suffix
            # The new suffix is the end of the merged string
            # Merged string ends with block
            # But we only need the last n-1 characters for next overlap?
            # Actually, the next overlap depends on the suffix of the *entire* word so far.
            # The suffix of the merged word is the suffix of `block`.
            # Because block is appended (with overlap).
            # So current_suffix = block
            current_suffix = block
            
        return total_len

    # Local Search
    best_order = current_order
    best_len = calc_length(best_order)
    
    # Heuristic: 2-opt or swap local search
    # We need to be careful with time.
    # calc_length is O(N * (n-1)^2) roughly. N=5040, n=7.
    # 5040 * 36 ~ 180k ops per evaluation.
    # 120s / 180k ~ 660 evaluations?
    # Python is slow. 180k ops might take 0.1s?
    # So ~1000 evaluations in 100s.
    # We need efficient local search.
    
    # Optimized calc_length?
    # We can precompute overlaps between all pairs?
    # 720 * 720 = 518,400 pairs.
    # Overlap depends on suffix of p_i and prefix of p_j.
    # Suffix of block i is p_i.
    # Prefix of block j is p_j.
    # Overlap(p_i, p_j) = max k such that p_i[-k:] == p_j[:k].
    # This is independent of the sequence!
    # So we can precompute a matrix M[i][j] = overlap(p_i, p_j).
    # Then length = sum(len(block)) - sum(M[order[k]][order[k+1]]).
    # len(block) is constant (2n-1).
    # So we want to maximize sum of M[order[k]][order[k+1]].
    # This is the Maximum Weight Hamiltonian Path problem on a complete directed graph.
    
    # Precompute M
    print(f"Precomputing overlaps for {len(current_order)} perms...", file=sys.stderr)
    num_perms = len(current_order)
    # Map perm tuple to index
    perm_to_idx = {p: i for i, p in enumerate(current_order)}
    
    # M[i][j] = overlap between perm i and perm j
    # Suffix of block i is perm_i.
    # Prefix of block j is perm_j.
    M = [[0] * num_perms for _ in range(num_perms)]
    
    # This loop is 720*720*6 ~ 3M ops. Fast.
    for i in range(num_perms):
        p_i = current_order[i]
        for j in range(num_perms):
            p_j = current_order[j]
            # Find max overlap
            max_ov = 0
            for k in range(n - 1, -1, -1):
                if p_i[-k:] == p_j[:k]:
                    max_ov = k
                    break
            M[i][j] = max_ov
            
    # Now we want to find order maximizing sum M[order[k]][order[k+1]].
    # Initial order is current_order.
    # Let's convert to indices for faster lookup.
    # current_order is already the list.
    
    def calc_score(order_indices):
        # Returns total overlap sum
        total = 0
        for k in range(len(order_indices) - 1):
            total += M[order_indices[k]][order_indices[k+1]]
        return total

    # Initial score
    # current_order is list of tuples.
    # We need to work with indices or just use the tuples directly in M?
    # M is indexed by position in current_order.
    # So if we swap elements in current_order, the indices change.
    # Better to work with a list of indices 0..719.
    
    init_indices = list(range(num_perms))
    
    # We need to map the "standard order" to indices.
    # current_order IS the standard order.
    # So init_indices corresponds to the standard order.
    
    best_indices = init_indices
    best_score = calc_score(best_indices)
    
    # Local search on indices
    # Swap adjacent
    improved = True
    while improved and time.time() < deadline:
        improved = False
        # Randomize start position?
        # Just scan left to right.
        for i in range(num_perms - 1):
            # Try swapping i and i+1
            old_score = best_score
            # Calculate delta
            # Remove edges (i-1, i), (i, i+1), (i+1, i+2)
            # Add edges (i-1, i+1), (i+1, i), (i, i+2)
            
            # Indices in best_indices
            idx_i = best_indices[i]
            idx_j = best_indices[i+1]
            
            # Left neighbor
            if i > 0:
                idx_l = best_indices[i-1]
                old_left = M[idx_l][idx_i]
                new_left = M[idx_l][idx_j]
            else:
                old_left = 0
                new_left = 0
                
            # Middle
            old_mid = M[idx_i][idx_j]
            new_mid = M[idx_j][idx_i]
            
            # Right neighbor
            if i + 2 < num_perms:
                idx_r = best_indices[i+2]
                old_right = M[idx_j][idx_r]
                new_right = M[idx_i][idx_r]
            else:
                old_right = 0
                new_right = 0
                
            delta = (new_left + new_mid + new_right) - (old_left + old_mid + old_right)
            
            if delta > 0:
                # Swap
                best_indices[i], best_indices[i+1] = best_indices[i+1], best_indices[i]
                best_score += delta
                improved = True
                # Don't break, keep scanning? Or restart?
                # Restarting is safer to find global minima, but slow.
                # Let's just continue.
                
    # Reconstruct the word
    # Order of permutations is best_indices
    # final_order = [current_order[idx] for idx in best_indices]
    
    # Build the word
    final_order = [current_order[idx] for idx in best_indices]
    
    # Construct word
    if not final_order:
        return ""
        
    first_block = list(final_order[0]) + [n] + list(final_order[0])
    result = first_block
    
    for p in final_order[1:]:
        block = list(p) + [n] + list(p)
        # Find max overlap
        max_ov = 0
        for o in range(n - 1, -1, -1):
            if result[-o:] == block[:o]:
                max_ov = o
                break
        result += block[max_ov:]
        
    return "".join(map(str, result))
