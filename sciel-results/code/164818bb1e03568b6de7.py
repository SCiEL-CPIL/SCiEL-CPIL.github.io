import time
import numpy as np

N = 18
MIN_DISTANCE = 6
DEADLINE_SECONDS = 55  # safety margin under 60s wall-clock limit

def _bits_to_matrix(words):
    """Convert list of ints to (n, N) uint8 bit matrix, bit i = (w >> i) & 1."""
    words = np.asarray(words, dtype=np.uint64)
    m = np.zeros((len(words), N), dtype=np.uint8)
    for i in range(N):
        m[:, i] = ((words >> i) & 1).astype(np.uint8)
    return m

def _hamming_to_matrix(candidate_bits, code_bits):
    """candidate_bits: (N,) uint8 ; code_bits: (n, N) uint8 -> (n,) distances."""
    return np.sum(candidate_bits[None, :] ^ code_bits, axis=1)

def _qr17_base():
    """Extended quadratic-residue code: QR(17) (256 words, length 17, d=7) + one zero bit -> length 18."""
    # QR(17) generator polynomial / construction via the standard [17,10,5] QR code is complex;
    # instead build it from the known property: it's the [17,10,5] code. We construct it
    # using the standard generator matrix from the quadratic residues mod 17.
    # Quadratic residues mod 17: {1,2,4,8,16,13,9,15}
    # The QR(17) code is generated by shifts of the generator polynomial g(x) of degree 7.
    # g(x) for QR(17): x^7 + x^6 + x^3 + x^2 + x + 1  (one common form)
    # We build the generator matrix by taking g and its 9 shifts (10 rows total for [17,10,5]).
    # Actually [17,10,5] means 10 information bits, so 10 generator rows.

    # Use the well-known generator polynomial for QR(17):
    # g = 0b10000111 (degree 7) -> coefficients for x^7..x^0
    # Let's use the standard: g(x) = x^7 + x^6 + x^3 + x^2 + x + 1
    g_poly = [1, 1, 0, 1, 1, 1, 0, 1]  # x^7 x^6 x^5 x^4 x^3 x^2 x^1 x^0
    # Build generator matrix: row i = g shifted by i, for i in 0..9 (10 rows), truncated to 17 bits
    G = []
    for i in range(10):
        row = [0]*17
        for j, c in enumerate(g_poly):
            pos = i + j
            if pos < 17:
                row[pos] = c
        G.append(row)
    G = np.array(G, dtype=np.uint8)
    # All 2^10 = 1024 combinations? No, that's the full code of size 2^10=1024, but QR(17) has 256 words.
    # QR(17) is [17,10,5]? Let me reconsider: the quadratic residue code of length 17 has parameters [17,10,5] with 2^10=1024 codewords? 
    # Actually the "quadratic residue code" QR(17) is typically [17,10,5] with 1024 words, OR the [17,11,5] extended... 
    # Let me use a safer, verified base: the [18,11,6] extended Golay-like or use the known A2(18,6) reference.
    # To be safe and verifiable, I'll build the base from a smaller, definitely-correct code and let greedy do the work.
    # Use the [18,11,6] code if I can, else fall back to a verified smaller base.

    # Safer: build base from the first-order Reed-Muller RM(1,4) extended (32 words, d=8 on 16 bits, +2 zeros = d=8 on 18)
    # and ALSO include the all-ones and a few more, then let greedy expand. But 32 is small.
    # Let me instead construct the [18,11,6] extended quadratic residue code properly.
    # The extended QR(17) code is [18,11,6] with 2^11 = 2048 words? That seems large. 
    # Actually the extended quadratic residue code of length 18 is [18,11,6] with 2048 codewords.
    # But the task says "512-word extended quadratic-residue construction is independently verified as a reference."
    # So the reference is 512 words. That's 2^9. So it's a [18,9,6] subcode? Or a specific 512-word code.
    # Given uncertainty, I'll use a robust smaller base and rely on greedy to grow it.

    # Build a base from RM(1,4) (32 words) plus their complements and some structured additions,
    # all verified to have pairwise distance >= 6, then greedy expands.
    base = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            base.append(word)
    # Add complements of these 32 (flip all 18 bits) -> 64 words, still d>=8 within, and d between a word and its complement is 18.
    for w in list(base):
        base.append(w ^ ((1 << 18) - 1))
    # Deduplicate
    base = list(dict.fromkeys(base))
    return base

def _verify_code(words):
    """Return True if all pairwise Hamming distances >= MIN_DISTANCE."""
    n = len(words)
    bits = _bits_to_matrix(words)
    # Compute all pairwise distances via XOR popcount on the matrix
    # Use broadcasting: bits[i] ^ bits[j]
    # For memory, do in chunks
    for i in range(n):
        dists = np.sum(bits[i][None, :] ^ bits[i+1:], axis=1)
        if np.any(dists < MIN_DISTANCE):
            return False
    return True

def construct():
    start = time.time()
    deadline = start + DEADLINE_SECONDS

    base = _qr17_base()
    # Verify base; if invalid, fall back to just RM(1,4) 32 words
    if not _verify_code(base):
        base = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                base.append(word)

    words = list(base)
    code_bits = _bits_to_matrix(words)

    # Candidate pool: generate a large set of candidate words to try.
    # Use structured candidates: all weight-k words for various k, plus random.
    # To keep it fast, generate candidates in batches and vectorize the distance check.

    # Precompute a pool of candidate words. We'll use:
    #  - all weight 9 words? That's C(18,9)=48620, manageable.
    #  - all weight 8 and 10 words.
    #  - random words.
    # Build a candidate list, dedupe against existing.

    import itertools
    candidates = []
    # Weight 8, 9, 10 candidates (balanced weights are good for distance 6)
    for w in (7, 8, 9, 10, 11):
        for combo in itertools.combinations(range(N), w):
            word = 0
            for i in combo:
                word |= (1 << i)
            candidates.append(word)
    # Add all-zero and all-one
    candidates.append(0)
    candidates.append((1 << N) - 1)
    # Add random candidates
    rng = np.random.default_rng(12345)
    for _ in range(20000):
        bits = (rng.random(N) < 0.5).astype(np.uint64)
        word = 0
        for i in range(N):
            if bits[i]:
                word |= (1 << i)
        candidates.append(word)

    # Deduplicate and remove those already in words
    word_set = set(words)
    seen = set()
    unique_candidates = []
    for c in candidates:
        if c not in word_set and c not in seen:
            seen.add(c)
            unique_candidates.append(c)

    # Greedy: repeatedly add the candidate with max min-distance to current code.
    # Vectorize: for a batch of candidates, compute min distance to code for each.
    BATCH = 4096
    cand_idx = 0
    while cand_idx < len(unique_candidates):
        if time.time() > deadline - 2:
            break
        end = min(cand_idx + BATCH, len(unique_candidates))
        batch = unique_candidates[cand_idx:end]
        cand_bits = _bits_to_matrix(batch)
        # Compute pairwise distances: (len(batch), n) matrix
        # dist[i,j] = popcount(cand_bits[i] ^ code_bits[j])
        # Use broadcasting in chunks over code to limit memory
        n_code = code_bits.shape[0]
        min_dists = np.full(len(batch), N + 1, dtype=np.int32)
        # Chunk over code words to limit memory: cand_bits (B, N) ^ code_bits_chunk (C, N) -> (B, C)
        CHUNK = 256
        for c0 in range(0, n_code, CHUNK):
            c1 = min(c0 + CHUNK, n_code)
            diff = cand_bits[:, None, :] ^ code_bits[None, c0:c1, :]
            dists = np.sum(diff, axis=2)  # (B, C)
            batch_min = np.min(dists, axis=1)  # (B,)
            min_dists = np.minimum(min_dists, batch_min)
            del diff, dists, batch_min
        # Find candidates with min_dist >= MIN_DISTANCE
        good = np.where(min_dists >= MIN_DISTANCE)[0]
        if len(good) > 0:
            # Add the one with the largest min distance
            best_local = good[np.argmax(min_dists[good])]
            new_word = batch[best_local]
            words.append(new_word)
            word_set.add(new_word)
            code_bits = np.vstack([code_bits, _bits_to_matrix([new_word])])
            # Remove this candidate from the pool
            unique_candidates[end - 1 - (len(batch) - 1 - best_local)] = -1  # mark; we'll filter
            # Actually simpler: mark by setting to a sentinel and filter later. To avoid complexity,
            # just note it's used; since we dedupe by word_set, re-encountering is fine.
        cand_idx = end
        # Remove used candidates to keep pool clean
        unique_candidates = [c for c in unique_candidates if c != -1]

    # Final polish: try a few more random candidates near the deadline
    if time.time() < deadline - 1:
        rng2 = np.random.default_rng(999)
        for _ in range(2000):
            if time.time() > deadline - 1:
                break
            bits = (rng2.random(N) < 0.5).astype(np.uint64)
            word = 0
            for i in range(N):
                if bits[i]:
                    word |= (1 << i)
            if word in word_set:
                continue
            cb = _bits_to_matrix([word])
            dists = np.sum(cb ^ code_bits, axis=1)
            if np.min(dists) >= MIN_DISTANCE:
                words.append(word)
                word_set.add(word)
                code_bits = np.vstack([code_bits, cb])

    return words

if __name__ == "__main__":
    res = construct()
    print(len(res))
