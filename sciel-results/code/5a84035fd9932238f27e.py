import time
import random
from collections import deque

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    # Target: 4-regular graph of girth 10
    if k != 4 or g != 10:
        # Fallback to seed logic for other params, though task is specific
        return _construct_seed(k, g)
        
    # GF(4) Arithmetic
    # Represent elements as 0, 1, 2, 3
    # 0=0, 1=1, 2=alpha, 3=alpha+1
    # alpha^2 = alpha + 1 = 3
    # alpha^3 = 1
    gf4_add = [
        [0, 1, 2, 3],
        [1, 0, 3, 2],
        [2, 3, 0, 1],
        [3, 2, 1, 0]
    ]
    gf4_mul = [
        [0, 0, 0, 0],
        [0, 1, 2, 3],
        [0, 2, 3, 1],
        [0, 3, 1, 2]
    ]
    
    def gf4_add_vec(v1, v2):
        return [gf4_add[v1[i]][v2[i]] for i in range(len(v1))]
        
    def gf4_mul_vec_scalar(v, s):
        if s == 0: return [0]*len(v)
        if s == 1: return v[:]
        return [gf4_mul[s][x] for x in v]

    # LUW Construction Parameters
    q = 4
    d = 5
    # Rule for LUW
    # y[c] = x[c] + y[a]*x[b] for points
    # The rule definition in seed:
    # rule[c] = (a, b)
    # For d=5:
    # c=2: (1,1) ? No, seed uses:
    # rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    # for c in range(5, d+1): ...
    # d=5, so c=5 is added.
    # Let's replicate the seed's rule generation exactly.
    
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        # The seed logic:
        # r = (c-5)%4. For c=5, r=0.
        # c0 = c - r. For c=5, c0=5.
        # List: [(1, c0-2), (c0-1, 1), (c0, 1), (1, c0+1)]
        # Index r=0 -> (1, 3).
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]
        
    # Generate Points and Lines of LUW(4,5)
    # Points: (0, x) where x in GF(4)^d
    # Lines: (1, y) where y in GF(4)^d
    # Edge between (0, x) and (1, y) if for all c in 2..d:
    # y[c] = x[c] + y[a]*x[b]  (Point side)
    # OR
    # y[c] = x[c] - x[a]*y[b]  (Line side)
    # The seed uses:
    # if side==0: y[c] = x[c] + y[a]*x[b]
    # else: y[c] = x[c] - x[a]*y[b]
    
    # We will generate the full graph, then quotient.
    
    num_points = q ** d
    # Total vertices = 2 * num_points
    
    # To save memory/time, we don't build the full 2048-node graph explicitly if we can avoid it.
    # But 2048 nodes is small.
    
    # Let's define the coset mapping.
    # We work in GF(4)^d.
    # We want a subgroup H of the additive group (GF(4)^d, +).
    # Additive group is (Z2 x Z2)^5.
    # We can represent a vector in GF(4)^d as a tuple of 4 elements.
    # To define a subgroup, we can pick basis vectors in the "bit" representation.
    # But it's easier to just pick vectors in GF(4)^d.
    # Since the group is elementary abelian 2-group, any set of linearly independent vectors (over Z2) forms a subgroup.
    # Independence over Z2 means that no non-trivial sum is 0.
    # In GF(4), addition is XOR of the bits.
    # So we can just pick random vectors and check independence.
    
    # Strategy: Try several random subgroups of size 8 (generated by 3 vectors).
    # Size 8 => Quotient size 2048/8 = 256.
    
    def get_coset(x, H):
        # H is a list of vectors in GF(4)^d
        # We need to find which coset x belongs to.
        # Since H is small (size 8), we can just check all h in H.
        # x is in coset C if x - h is in H for some h?
        # No, x is in coset represented by x if x is in H.
        # Better: Map x to a canonical representative.
        # Since H is a group, we can just return the tuple of x mod H.
        # Simplest: Just use the vector x itself as key, but identify x and x+h.
        # We will create a dictionary mapping coset_representative -> index.
        pass

    best_graph = None
    
    # Try to find a valid quotient
    # We need to generate the LUW edges on the fly or store them.
    # Storing 2048 nodes and ~4000 edges is fine.
    
    # Let's build the LUW graph first.
    points = [tuple([0]*d) for _ in range(num_points)]
    # Actually, we need to enumerate all vectors in GF(4)^d.
    # 4^5 = 1024 vectors.
    
    def gen_vectors(d, q):
        if d == 0:
            yield ()
            return
        for v in gen_vectors(d-1, q):
            for i in range(q):
                yield v + (i,)
                
    all_vectors = list(gen_vectors(d, q))
    # Map vector to index
    vec_to_idx = {v: i for i, v in enumerate(all_vectors)}
    
    # Build adjacency for Points (side 0) and Lines (side 1)
    # Adjacency: point i is connected to line j if condition holds.
    
    # To speed up, we can precompute the "image" of each point under the rule?
    # No, the condition is:
    # y[c] = x[c] + y[a]*x[b]
    # This defines y given x? No, y is on the other side.
    # For a fixed point x, the lines y connected to it are those satisfying the equations.
    # The equations are linear in y?
    # y[c] - y[a]*x[b] = x[c].
    # This is a system of linear equations for y.
    # Since the LUW construction is regular, each point has exactly q neighbors.
    
    # We can just iterate over all y for each x? 1024*1024 = 1M checks. Fast enough.
    
    edges = []
    adj = [[] for _ in range(2 * num_points)]
    
    # Indexing:
    # Points: 0 .. num_points-1
    # Lines: num_points .. 2*num_points-1
    
    for i, x in enumerate(all_vectors):
        for j, y in enumerate(all_vectors):
            is_edge = True
            for c in range(2, d+1):
                a, b = rule[c]
                # y[c] == x[c] + y[a]*x[b]
                lhs = y[c]
                rhs = gf4_add[x[c]][gf4_mul[y[a]][x[b]]]
                if lhs != rhs:
                    is_edge = False
                    break
            if is_edge:
                p_idx = i
                l_idx = num_points + j
                edges.append((p_idx, l_idx))
                adj[p_idx].append(l_idx)
                adj[l_idx].append(p_idx)
                
    # Now we have the LUW graph.
    # Check time
    if time.time() > deadline:
         return len(adj), edges
         
    # Try Quotients
    # We need a subgroup H of the additive group of GF(4)^d.
    # Additive group is (Z2)^10.
    # We can represent a vector in GF(4)^d as a tuple of 5 elements in {0,1,2,3}.
    # Addition is component-wise XOR (in GF(4)).
    
    def add_vec(u, v):
        return tuple(gf4_add[u[i]][v[i]] for i in range(d))
        
    def sub_vec(u, v):
        # In char 2, sub = add
        return add_vec(u, v)
        
    # Generate random subgroups of size 8 (3 generators)
    # A random vector is in GF(4)^d.
    # We need 3 linearly independent vectors over Z2.
    # Independence: v1, v2, v3 such that no non-trivial sum is 0.
    # Since we are in char 2, we just need to check sums.
    
    def is_independent(v1, v2, v3):
        # Check all 7 non-zero combinations
        combos = [
            (v1, v2, 0), (v1, 0, v3), (0, v2, v3),
            (v1, v2, v3), (v1, v1, v2), # v1+v1=0, so this is v2. Bad check.
        ]
        # Better: Just compute the span size.
        # Start with {0}
        span = {tuple([0]*d)}
        span.add(v1)
        for v in span:
            span.add(add_vec(v, v1))
        # Now add v2
        new_span = set(span)
        for v in span:
            new_span.add(add_vec(v, v2))
        if len(new_span) == len(span):
            return False
        span = new_span
        # Now add v3
        new_span2 = set(span)
        for v in span:
            new_span2.add(add_vec(v, v3))
        if len(new_span2) == len(span):
            return False
        return True
        
    # Try a few random subgroups
    for _ in range(50):
        if time.time() > deadline: break
        
        # Pick 3 random vectors
        v1 = tuple(random.randint(0, 3) for _ in range(d))
        v2 = tuple(random.randint(0, 3) for _ in range(d))
        v3 = tuple(random.randint(0, 3) for _ in range(d))
        
        if not is_independent(v1, v2, v3):
            continue
            
        # Generate H
        H = set()
        H.add(tuple([0]*d))
        H.add(v1)
        H.add(v2)
        H.add(v3)
        H.add(add_vec(v1, v2))
        H.add(add_vec(v1, v3))
        H.add(add_vec(v2, v3))
        H.add(add_vec(v1, v2, v3) if False else add_vec(add_vec(v1, v2), v3))
        
        # Map each vertex to its coset representative
        # We pick the "smallest" vector in the coset as the representative?
        # Or just use the coset itself (frozenset) as key?
        # Coset of x is {x + h | h in H}.
        # We can map x to min(x + h for h in H).
        
        coset_rep = {}
        for i, x in enumerate(all_vectors):
            # Find min in coset
            min_rep = None
            for h in H:
                y = add_vec(x, h)
                if min_rep is None or y < min_rep:
                    min_rep = y
            coset_rep[i] = min_rep
            
        # Now build quotient graph
        # Vertices are the unique coset representatives.
        unique_reps = list(set(coset_rep.values()))
        rep_to_idx = {r: i for i, r in enumerate(unique_reps)}
        
        n_q = 2 * len(unique_reps)
        adj_q = [[] for _ in range(n_q)]
        edge_set_q = set()
        
        for u, v in edges:
            # u is point index, v is line index
            # Get their coset reps
            ru = coset_rep[u]
            rv = coset_rep[v - num_points]
            
            # Map to quotient indices
            # Point side: 0..len(unique_reps)-1
            # Line side: len(unique_reps)..2*len(unique_reps)-1
            qu = rep_to_idx[ru]
            qv = rep_to_idx[rv] + len(unique_reps)
            
            if qu > qv:
                qu, qv = qv, qu
                
            if (qu, qv) in edge_set_q:
                # Multi-edge found!
                # This quotient is not simple.
                break
            edge_set_q.add((qu, qv))
            adj_q[qu].append(qv)
            adj_q[qv].append(qu)
        else:
            # No multi-edges. Check regularity and girth.
            # Check regularity
            is_regular = all(len(nei) == k for nei in adj_q)
            if not is_regular:
                continue
                
            # Check girth
            # BFS from each vertex up to depth 4
            girth_ok = True
            for start in range(n_q):
                # BFS
                dist = {start: 0}
                q = deque([start])
                while q:
                    node = q.popleft()
                    if dist[node] >= 4:
                        continue
                    for nei in adj_q[node]:
                        if nei not in dist:
                            dist[nei] = dist[node] + 1
                            q.append(nei)
                        else:
                            # Found a cycle?
                            # If we revisit a node, we have a cycle.
                            # Length = dist[node] + 1 + dist[nei]
                            # But BFS finds shortest path.
                            # If we encounter a neighbor that is already visited,
                            # and it's not the parent, we have a cycle.
                            # We need to track parent.
                            pass
                # Simpler girth check:
                # For each edge (u,v), remove it, find shortest path u->v.
                # If dist < g-1, cycle exists.
                # This is O(E * (V+E)). 640 * (256+640) ~ 500k. Fast.
                
            # Let's do the proper girth check
            girth_ok = True
            for u, v in edge_set_q:
                # Temporarily remove edge
                # BFS from u to v
                dist = {u: 0}
                parent = {u: -1}
                q = deque([u])
                found = False
                while q:
                    node = q.popleft()
                    if node == v:
                        found = True
                        break
                    for nei in adj_q[node]:
                        if nei == u and node == v: continue # Skip removed edge? 
                        # Actually, just don't traverse (u,v) or (v,u)
                        if (node == u and nei == v) or (node == v and nei == u):
                            continue
                        if nei not in dist:
                            dist[nei] = dist[node] + 1
                            q.append(nei)
                if found:
                    cycle_len = dist[v] + 1
                    if cycle_len < g:
                        girth_ok = False
                        break
                else:
                    # Disconnected?
                    girth_ok = False
                    break
                    
            if girth_ok:
                # Valid graph found!
                final_edges = list(edge_set_q)
                return n_q, final_edges
                
    # Fallback: Return the full LUW graph
    return len(adj), edges

def _construct_seed(k, g):
    # Copy of original seed logic for fallback
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
