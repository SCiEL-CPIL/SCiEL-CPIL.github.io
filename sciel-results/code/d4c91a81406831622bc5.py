import numpy as np
import time

class Optimizer:
    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 290
        N = self.budget
        m = self.n_obj
        n = self.dim

        # Strategy:
        # The DTLZ7 Pareto front is a 2D surface parameterized by x_0 and x_1.
        # Specifically, for x_{m..n-1} = 0 (which minimizes g), the objectives are:
        # f0 = x_0
        # f1 = x_1
        # f2 = (1 + g) * h(x_0, x_1, y)
        # With g=0, f2 = h(x_0, x_1, y).
        # To maximize hypervolume, we need to sample the (x_0, x_1) space uniformly
        # to cover the entire non-convex Pareto front.
        
        # We use a Fibonacci lattice (golden ratio spiral) on the unit square [0,1]^2
        # for x_0 and x_1. This provides excellent space-filling properties in 2D.
        
        # Generate N points in [0, 1]^2 using Fibonacci lattice
        # The i-th point is at:
        # u_i = (i + 0.5) / N
        # v_i = (i * phi + 0.5) / N mod 1  (or similar low-discrepancy mapping)
        
        # Actually, a standard Fibonacci lattice in 2D can be generated by:
        # theta_i = i * 2 * pi * (1 - 1/sqrt(N))  -- this is for polar coordinates
        # But we want a square grid mapping.
        
        # Let's use a simple Halton sequence in 2D for x_0 and x_1, or a Fibonacci lattice.
        # The prompt suggests "Fibonacci lattice on the unit disk" but we are in a square [0,1]^2.
        # A 2D Halton sequence (bases 2 and 3) is robust and simple.
        
        def halton(index, base):
            result = 0.0
            f = 1.0 / base
            i = index
            while i > 0:
                result += f * (i % base)
                i = i // base
                f /= base
            return result

        # Generate N points in [0,1]^2 for x_0 and x_1
        # We use indices 1..N to avoid the origin (0,0) which is a corner, 
        # though corners are valid. Halton starting at 1 is standard.
        
        x0_vals = np.zeros(N)
        x1_vals = np.zeros(N)
        
        for i in range(N):
            idx = i + 1
            x0_vals[i] = halton(idx, 2)
            x1_vals[i] = halton(idx, 3)
            
        # Construct decision vectors
        # x_0 = x0_vals
        # x_1 = x1_vals
        # x_2 .. x_{n-1} = 0 (to ensure g=0 and stay on the Pareto front)
        
        # Map to bounds
        # Bounds are [0, 1] for all variables, so no scaling needed if Halton is in [0,1].
        # However, to be safe and general, we map [0,1] to [low, high].
        
        X = np.zeros((N, n))
        
        for j in range(m):
            lo_j = bounds[j][0]
            hi_j = bounds[j][1]
            if j == 0:
                X[:, j] = lo_j + (hi_j - lo_j) * x0_vals
            else:
                X[:, j] = lo_j + (hi_j - lo_j) * x1_vals
        
        # Variables m to n-1 are set to 0.
        # Since bounds are [0,1], 0 is within bounds.
        # If bounds were different, we should set to the lower bound or a value that minimizes g.
        # For DTLZ7, g is minimized when x_m..x_n-1 are on the Pareto front of the subproblem,
        # which is typically at the boundary. Setting to 0 is a standard assumption for the analytic front.
        
        # Evaluate all points
        for i in range(N):
            if time.time() > deadline:
                break
            problem(X[i])

        return X

