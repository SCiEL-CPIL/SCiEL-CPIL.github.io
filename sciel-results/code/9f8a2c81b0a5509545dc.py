"""Program for the Witt design S(5,6,12) packing task.

Strategy: Deterministic algebraic construction via the binary Golay code.
Build the [23,12,7] Golay code generator matrix, shorten to [12,6,6],
and extract weight-6 codewords as the 132 blocks of S(5,6,12).
"""
# EVOLVE-BLOCK-START
import time
import itertools
import numpy as np


def _build_golay_generator():
    """Build the 12x23 generator matrix for the [23,12,7] binary Golay code."""
    n = 23
    k = 12
    # Check vector: all-ones of length 23 (weight 23, divisible by 7)
    check = np.ones(n, dtype=np.uint8)
    
    # Generate all 2^11 = 2048 cyclic shifts of the check vector
    shifts = []
    for i in range(2048):
        # Determine which positions to flip based on binary representation of i
        # Flip positions 0..10 according to bits of i
        flip_mask = np.zeros(n, dtype=np.uint8)
        for j in range(11):
            if (i >> j) & 1:
                flip_mask[j] = 1
        vec = (check + flip_mask) % 2
        shifts.append(vec)
    
    # Sort lexicographically (as integer values)
    shifts.sort(key=lambda v: int(''.join(map(str, v)), 2))
    
    # Take the first 12 as the first 12 rows of the generator
    G = np.zeros((k, n), dtype=np.uint8)
    for i in range(k):
        G[i, :] = shifts[i]
    
    # Append the check vector as the 13th row for the systematic part
    # Actually, we need exactly 12 rows. Let's use a different approach:
    # Use the standard [12, 11, 0, check] structure
    
    # Standard construction: G = [I_12 | A] where A is 12x11
    # The columns of A are the first 11 coordinates of the 12 generator vectors
    # derived from the cyclic code approach.
    
    # Let me use a cleaner standard construction:
    # The [23,12,7] code can be generated by:
    # g(x) = 1 + x^4 + x^6 + x^7 + x^8 + x^10 + x^12 (the defining polynomial)
    # Generator matrix rows are x^i * g(x) mod (x^23+1) for i=0..11
    
    g = np.zeros(n, dtype=np.uint8)
    g[0] = 1
    g[4] = 1
    g[6] = 1
    g[7] = 1
    g[8] = 1
    g[10] = 1
    g[12] = 1
    
    G = np.zeros((k, n), dtype=np.uint8)
    for i in range(k):
        row = np.zeros(n, dtype=np.uint8)
        for j in range(n):
            if g[j] == 1:
                row[(j + i) % n] = 1
        G[i, :] = row
    
    return G


def _shorten_and_extract():
    """Shorten the Golay code to [12,6,6] and extract weight-6 codewords."""
    G23 = _build_golay_generator()
    
    # Shortening: fix coordinate 0 to be 0.
    # A codeword c is in the shortened code if c[0] = 0.
    # c = sum_{i in S} G[i] where sum_{i in S} G[i, 0] = 0 (mod 2)
    # The shortened code has dimension 6 (since half the codewords have c[0]=0).
    # We need to find a basis for the subspace of codewords with c[0]=0.
    
    # Find which generator rows have G[i,0] = 0
    # Then find combinations that sum to 0 in the 0th coordinate.
    
    # Actually, for the shortened code [12,6,6]:
    # We take all codewords of the [23,12,7] code with first coordinate 0,
    # and drop the first coordinate to get [12,6,6].
    # Then take weight-6 words.
    
    # Enumerate all 2^12 = 4096 codewords
    # Filter those with c[0] = 0
    # Drop coordinate 0
    # Check weight = 6
    
    blocks = []
    seen = set()
    
    for mask in range(4096):
        # Compute codeword
        cw = np.zeros(23, dtype=np.uint8)
        for i in range(12):
            if (mask >> i) & 1:
                cw = (cw + G23[i]) % 2
        
        if cw[0] != 0:
            continue
        
        # Drop first coordinate
        short_cw = cw[1:]
        w = int(np.sum(short_cw))
        
        if w == 6:
            block = tuple(int(x) for x in np.where(short_cw == 1)[0])
            if block not in seen:
                seen.add(block)
                blocks.append(block)
    
    return blocks


def _verify_packing(blocks):
    """Verify that no 5-subset appears in two blocks."""
    covered = set()
    for b in blocks:
        for sub in itertools.combinations(b, 5):
            if sub in covered:
                return False
            covered.add(sub)
    return True


def _greedy_fallback():
    """Randomized greedy fallback in case algebraic construction fails."""
    import random
    best_blocks = []
    start = time.time()
    deadline = 130.0
    
    for seed in range(200):
        if time.time() - start > deadline:
            break
        random.seed(seed)
        covered = set()
        blocks = []
        candidates = list(itertools.combinations(range(12), 6))
        random.shuffle(candidates)
        
        for b in candidates:
            valid = True
            for s in itertools.combinations(b, 5):
                if s in covered:
                    valid = False
                    break
            if valid:
                blocks.append(b)
                for s in itertools.combinations(b, 5):
                    covered.add(s)
        
        if len(blocks) > len(best_blocks):
            best_blocks = blocks[:]
            if len(best_blocks) == 132:
                break
    
    return [list(b) for b in best_blocks]


def construct():
    """Return a list of distinct 6-subsets of 0..11 (as lists) that form a
    packing with no repeated 5-subset, maximizing the number of blocks.
    """
    start_time = time.time()
    deadline = 140.0
    
    try:
        blocks = _shorten_and_extract()
        
        if len(blocks) == 132 and _verify_packing(blocks):
            return [list(b) for b in blocks]
        
        # If we got a different number, still check validity
        if len(blocks) > 0 and _verify_packing(blocks):
            # Check if it's actually 132 (the construction should give exactly 132)
            if len(blocks) == 132:
                return [list(b) for b in blocks]
            # If not 132, fall through to greedy
    except Exception:
        pass
    
    # Fallback to greedy
    if time.time() - start_time < deadline - 10:
        result = _greedy_fallback()
        if result:
            return result
    
    # Last resort: return empty or best effort
    return []

