import time
import numpy as np

def construct():
    N = 18
    MIN_DIST = 6
    TOTAL_BUDGET = 55.0
    t_start = time.time()
    deadline = t_start + TOTAL_BUDGET

    # Pre-compute popcount for all 18-bit values for fast verification
    # 2^18 = 262144, fits in memory easily
    # Using list comprehension and np.array is fast enough for this size
    popcount_all = np.array([i.bit_count() for i in range(2**N)], dtype=np.uint8)

    def popcount18(arr):
        """
        arr: numpy array of uint32 (or int) values < 2^18
        Returns: numpy array of popcounts
        """
        return popcount_all[arr.astype(np.intp)]

    # ============================================================
    # Construction: Extended Quadratic Residue Code [18,9,6]
    # This is the known optimal construction for A_2(18,6).
    # ============================================================
    
    # Generator polynomial for QR(17) shortened to length 18? 
    # The standard QR code of length 11 is [11,6,5].
    # The extended QR code of length 12 is [12,6,6] (not optimal for dist 6, size 64).
    # Wait, the prompt says "512-word extended quadratic-residue construction".
    # A [18, 9, 6] code has size 2^9 = 512.
    # This corresponds to a linear code.
    # The generator polynomial provided in the current program:
    # g_poly bits at 0, 1, 3, 4, 5, 7, 8.
    # This is a degree 9 polynomial? No, bits are set at those positions.
    # Let's trust the current program's generator as it produced score 8.3125.
    
    g_poly = 0
    for bit_pos in [0, 1, 3, 4, 5, 7, 8]:
        g_poly |= (1 << bit_pos)

    def poly_mul_17(m, g):
        result = 0
        for i in range(9):
            if m & (1 << i):
                result ^= (g << i)
        return result & 0x1FFFF

    qr_codewords_17 = []
    for m in range(512):
        cw = poly_mul_17(m, g_poly)
        qr_codewords_17.append(cw)

    qr_codewords_18 = []
    for cw in qr_codewords_17:
        parity = cw.bit_count() % 2
        extended = cw | (parity << 17)
        qr_codewords_18.append(extended)

    # Verify the QR construction
    # We expect 512 words.
    if len(qr_codewords_18) == 512:
        # Check minimum weight of non-zero codewords
        # For a linear code, min distance = min weight of non-zero codewords
        # But this is a linear code? Yes, generated by polynomial multiplication.
        # So we just need to check min weight >= 6.
        
        # However, to be absolutely safe against any potential non-linearity or bug,
        # we do a quick pairwise check on a subset or the whole set if fast.
        # With 512 words, full pairwise check is O(512^2) ~ 260k pairs.
        # Vectorized, this is very fast.
        
        words_arr = np.array(qr_codewords_18, dtype=np.uint32)
        valid = True
        
        # Optimization: Since it's linear, min distance is min weight.
        # But let's stick to the prompt's requirement: "Every pair is checked exactly".
        # We can do this efficiently.
        
        # Check all pairs
        for i in range(len(words_arr)):
            if time.time() > deadline - 1.0:
                valid = False
                break
            
            xor_vals = np.bitwise_xor(words_arr, np.uint32(words_arr[i]))
            bit_counts = popcount18(xor_vals)
            
            # Exclude self (distance 0)
            if bit_counts.min() < MIN_DIST:
                # Find if the min is 0 (self) or actually < 6
                # Since we compare against all, self is included.
                # self distance is 0. So min will always be 0.
                # We need to check min EXCLUDING self.
                # Or simply: check if any j != i has dist < 6.
                
                # Efficient way: 
                # The min of bit_counts is 0 (self).
                # The second min (or min excluding index i) must be >= 6.
                
                # np.partition or sort?
                # For 512 elements, just finding the min excluding the 0 is enough.
                # Since only one element is 0 (the self XOR), the min of the rest is the 2nd smallest.
                
                # bit_counts is an array of 512 uint8s.
                # We can do:
                # min_val = bit_counts.min()
                # if min_val == 0:
                #     # check if there are any other values < 6
                #     # count of values < 6 should be exactly 1 (the self)
                #     if np.sum(bit_counts < MIN_DIST) > 1:
                #         valid = False
                #         break
                # else:
                #     valid = False
                #     break
                
                # Simpler:
                # Since we know the code is linear and likely valid, 
                # and we want to be fast:
                # Check min weight of non-zero codewords.
                # For linear code, this is sufficient.
                
                # Let's verify linearity assumption.
                # If it's linear, min_dist = min(weight(c) for c in code if c!=0).
                # Let's just compute min weight of all codewords (excluding 0).
                # This is O(N).
                
                pass # We will use the linear property for speed, but verify with a few random pairs if paranoid.
                
        # Actually, the previous loop logic in the current program was:
        # if bit_counts.min() < MIN_DIST: valid = False
        # This would ALWAYS trigger because self-XOR is 0.
        # So the current program's verification logic is BUGGY?
        # "if bit_counts.min() < MIN_DIST:"
        # bit_counts includes the XOR of word[i] with itself, which is 0.
        # 0 < 6 is True.
        # So `valid` would ALWAYS be False.
        # If `valid` is False, `best_words` becomes `[]`.
        # Then it runs the greedy search.
        # The greedy search starts from empty.
        # It finds some words.
        # Score 8.3125 comes from the greedy search result?
        # If the greedy search finds ~512 words, that's impressive.
        # But greedy is slow.
        
        # Let's re-read the current program carefully.
        # "if bit_counts.min() < MIN_DIST: valid = False; break"
        # Yes, this is a bug. It checks the minimum distance including the self-pair (distance 0).
        # So the QR code is REJECTED.
        # The program falls back to greedy.
        # The greedy search is what generates the score 8.3125.
        
        # STRUCTURAL CHANGE: Fix the verification logic.
        # If we fix the verification, the QR code (512 words) will be accepted.
        # We can then return immediately, skipping the slow greedy search.
        # This will be MUCH faster and likely yield the same or better score (512 words).
        
        # Correct Verification:
        valid = True
        for i in range(len(words_arr)):
            if time.time() > deadline - 1.0:
                valid = False
                break
            
            xor_vals = np.bitwise_xor(words_arr, np.uint32(words_arr[i]))
            bit_counts = popcount18(xor_vals)
            
            # Check if any distance is < MIN_DIST, EXCLUDING the self-pair (which is 0).
            # Since the code is linear, we can just check min weight of non-zero codewords.
            # But to be general:
            # The minimum of bit_counts is 0 (self).
            # We need to ensure all OTHER distances are >= MIN_DIST.
            # This is equivalent to: the number of distances < MIN_DIST is exactly 1 (the self).
            
            # Optimization: 
            # We can check min weight of the code directly if we trust linearity.
            # min_w = min(cw.bit_count() for cw in qr_codewords_18 if cw != 0)
            # if min_w >= MIN_DIST: valid = True
            
            # Let's use the linear property for speed, as QR codes are linear.
            # If we want to be 100% safe against non-linear bugs:
            # count_invalid = np.sum(bit_counts < MIN_DIST)
            # if count_invalid > 1: # One is self (0), others must be >= 6
            #     valid = False
            #     break
            
            # Using the count method is O(N) per row, total O(N^2).
            # For N=512, this is fast.
            
            count_invalid = np.sum(bit_counts < MIN_DIST)
            if count_invalid > 1:
                valid = False
                break
        
        if valid:
            return qr_codewords_18[:]

    # Fallback: If QR fails or is invalid, use a fast greedy search
    # But since we expect QR to be valid, this is unlikely to be hit.
    
    best_words = []
    rng = np.random.default_rng(42)
    
    # Simple greedy fallback
    candidates = list(range(2**N))
    rng.shuffle(candidates)
    
    for c in candidates:
        if time.time() > deadline - 1.0:
            break
        
        if len(best_words) == 0:
            best_words.append(c)
            continue
            
        # Check against all current words
        # This is slow, so we limit the number of checks or use vectorization if we had an array.
        # For fallback, keep it simple.
        compatible = True
        for w in best_words:
            if (c ^ w).bit_count() < MIN_DIST:
                compatible = False
                break
        
        if compatible:
            best_words.append(c)
            
    return best_words
