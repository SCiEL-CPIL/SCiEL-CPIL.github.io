def _spherical_harmonics(theta, phi, l, m):
    """
    Compute spherical harmonics Y_l^m(theta, phi) for real-valued basis.
    theta: polar angle (0 to pi)
    phi: azimuthal angle (0 to 2pi)
    l: degree
    m: order (0 to l)
    Returns real part of Y_l^m * sqrt(2) for m>0, Y_l^m for m=0.
    """
    # Recurrence for associated Legendre polynomials is complex, 
    # but for low L we can use scipy.special.lpmv
    # Y_l^m(theta, phi) = N_l^m P_l^m(cos(theta)) e^{im phi}
    # For real harmonics:
    # m=0: Y_l^0 = sqrt((2l+1)/(4pi)) P_l(cos(theta))
    # m>0: Y_l^m_real = sqrt(2) * sqrt((2l+1)/(4pi) * (l-m)!/(l+m)!) P_l^m(cos(theta)) cos(m phi)
    
    cos_theta = np.cos(theta)
    
    # Precompute normalization
    norm = np.sqrt((2*l + 1) / (4 * np.pi))
    
    if m == 0:
        # P_l^0(x) = P_l(x)
        # lpmv(0, l, x) gives P_l(x)
        p = lpmv(0, l, cos_theta)
        return norm * p
    
    else:
        # P_l^m(x)
        # Note: lpmv(m, l, x) returns P_l^m(x)
        # We need (l-m)!/(l+m)!
        # Using gamma or factorial
        # scipy.special.factorial is exact for integers
        fact_ratio = factorial(l - m, exact=True) / factorial(l + m, exact=True)
        norm_m = np.sqrt(2) * norm * np.sqrt(fact_ratio)
        
        p = lpmv(m, l, cos_theta)
        return norm_m * p * np.cos(m * phi)

def _potential_field(pts_theta, pts_phi, coeffs, L_max):
    """
    Evaluate the potential V(theta, phi) = sum_{l,m} c_lm Y_l^m(theta, phi).
    coeffs: array of shape (L_max+1, L_max+1) where coeffs[l, m] corresponds to Y_l^m.
    We only use m >= 0 real harmonics.
    """
    V = np.zeros_like(pts_theta)
    for l in range(L_max + 1):
        for m in range(l + 1):
            c = coeffs[l, m]
            if np.abs(c) > 1e-15:
                V += c * _spherical_harmonics(pts_theta, pts_phi, l, m)
    return V

