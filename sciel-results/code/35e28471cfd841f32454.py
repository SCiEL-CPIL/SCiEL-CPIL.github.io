    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin
    
    # Initial state: Fibonacci sphere
    current_pts = _fibonacci_sphere(N)
    current_energy = _energy(current_pts)
    best_pts = current_pts.copy()
    best_energy = current_energy
    
    # Initialize velocity to zero
    velocities = np.zeros_like(current_pts)
    forces = _project_tangent(current_pts, _energy_grad(current_pts))
    
    # MD Parameters
    dt = 0.01
    cooling_rate = 0.999
    T = 1.0 # Artificial temperature for damping/velocity scaling?
    # In MD for energy minimization, we often add a damping term to velocity
    # or use a "cooling" schedule for the step size.
    
    max_steps = 5000
    steps = 0
    
    # We will use a damped MD approach.
    # v_new = v_new * damping + ...
    # Or simply reduce dt over time.
    
    while time.time() < deadline and steps < max_steps:
        steps += 1
        
        # Adaptive step size: reduce dt as we get closer to minimum
        # Simple heuristic: if energy increases, revert and reduce dt
        trial_pts, trial_vel, trial_forces = _md_step(current_pts, velocities, forces, dt)
        trial_energy = _energy(trial_pts)
        
        if trial_energy < current_energy:
            current_pts = trial_pts
            velocities = trial_vel
            forces = trial_forces
            current_energy = trial_energy
            
            if current_energy < best_energy:
                best_energy = current_energy
                best_pts = current_pts.copy()
                
            # Cool down: reduce step size
            dt *= 0.995
        else:
            # Rejected step: reduce step size and try again (or just wait)
            dt *= 0.5
            # Add a small random kick to escape local minima?
            # This makes it a hybrid MD-SA.
            if dt < 1e-4:
                # Reset dt and add noise
                dt = 0.01
                noise = np.random.randn(N, 3) * 0.01
                noise = _project_tangent(current_pts, noise)
                current_pts = current_pts + noise
                norms = np.linalg.norm(current_pts, axis=1, keepdims=True)
                current_pts = current_pts / norms
                velocities = np.zeros_like(current_pts)
                forces = _project_tangent(current_pts, _energy_grad(current_pts))
                current_energy = _energy(current_pts)
                
    # Final polish with L-BFGS on the best found point
    # This ensures we are at a local minimum of the landscape found by MD
    from scipy.optimize import minimize
    
    x0 = best_pts.flatten()
    
    def fun_and_grad(x):
        p = x.reshape(-1, 3)
        norms = np.linalg.norm(p, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        p = p / norms
        e = _energy(p)
        g = _energy_grad(p)
        g_tan = _project_tangent(p, g)
        return e, g_tan.flatten()
    
    res = minimize(
        fun_and_grad, 
        x0, 
        method='L-BFGS-B', 
        jac=True, 
        options={'maxiter': 50, 'ftol': 1e-12, 'gtol': 1e-8, 'disp': False}
    )
    
    final_pts = res.x.reshape(-1, 3)
    norms = np.linalg.norm(final_pts, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    final_pts = final_pts / norms
    
    final_energy = _energy(final_pts)
    
    # Validity check
    if np.all(np.isfinite(final_pts)):
        diff = final_pts[:, np.newaxis, :] - final_pts[np.newaxis, :, :]
        dists = np.linalg.norm(diff, axis=-1)
        np.fill_diagonal(dists, 1.0)
        if np.min(dists) > 1e-9 and final_energy < best_energy:
            best_energy = final_energy
            best_pts = final_pts
    
    # Fallback
    if not np.all(np.isfinite(best_pts)):
        best_pts = _fibonacci_sphere(N)
        
    return best_pts

