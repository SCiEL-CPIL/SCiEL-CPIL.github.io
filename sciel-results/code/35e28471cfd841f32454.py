def _energy(pts):
    """Compute logarithmic energy."""
    n = len(pts)
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    np.fill_diagonal(dist_sq, 1.0)
    dist = np.sqrt(dist_sq)
    mask = np.triu(np.ones((n, n), dtype=bool), k=1)
    valid_dists = dist[mask]
    energy = -np.sum(np.log(valid_dists))
    return energy

def _energy_grad(pts):
    """Compute gradient of logarithmic energy."""
    n = len(pts)
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    np.fill_diagonal(dist_sq, 1.0)
    grad_terms = diff / dist_sq[..., np.newaxis]
    grad = np.sum(grad_terms, axis=1)
    return grad

def _project_tangent(pts, vec):
    """Project vector onto tangent space."""
    dot = np.sum(pts * vec, axis=1, keepdims=True)
    return vec - dot * pts

def _fibonacci_sphere(n):
    i = np.arange(n) + 0.5
    z = 1.0 - 2.0 * i / n
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(1.0 - z * z)
    return np.column_stack([r * np.cos(phi), r * np.sin(phi), z])

def _md_step(pts, velocities, forces, dt):
    """
    Perform one Velocity Verlet step on the sphere.
    1. v_half = v + 0.5 * dt * F
    2. x_new = x + dt * v_half (project to sphere)
    3. F_new = Force(x_new)
    4. v_new = v_half + 0.5 * dt * F_new
    5. Project v_new to tangent space
    """
    # 1. Half step velocity
    v_half = velocities + 0.5 * dt * forces
    
    # 2. Update position
    new_pts = pts + dt * v_half
    # Normalize to sphere
    norms = np.linalg.norm(new_pts, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    new_pts = new_pts / norms
    
    # 3. New forces
    new_forces = _energy_grad(new_pts)
    # Project forces to tangent space
    new_forces = _project_tangent(new_pts, new_forces)
    
    # 4. Full step velocity
    v_new = v_half + 0.5 * dt * new_forces
    # Project velocity to tangent space
    v_new = _project_tangent(new_pts, v_new)
    
    return new_pts, v_new, new_forces

