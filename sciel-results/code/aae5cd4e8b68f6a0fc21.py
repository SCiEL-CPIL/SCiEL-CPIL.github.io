def _build_strassen():
    n, m, p = 4, 5, 5
    nm, mp, pn = n * m, m * p, p * n
    R = len(STRASSEN)
    U = np.zeros((nm, R), dtype=int)
    V = np.zeros((mp, R), dtype=int)
    W = np.zeros((pn, R), dtype=int)
    for r, (af, ab, ai, aj, bf, bb, bi, bj, cf, cb, ci, cj) in enumerate(STRASSEN):
        a_row = 3 * ab + ai * 2 + aj
        b_col = 3 * bb + bi * 2 + bj
        c_row = 3 * cb + ci * 2 + cj
        U[a_row, r] = af
        V[b_col, r] = bf
        W[c_row, r] = cf
    return U, V, W


def _verify(U, V, W, tol=1e-9):
    n, m, p = 4, 5, 5
    ok = True
    for i in range(n):
        for j in range(m):
            for k in range(p):
                s = 0.0
                for r in range(U.shape[1]):
                    s += U[i * m + j, r] * V[j * p + k, r] * W[k * n + i, r]
                if abs(s - 1.0) > tol:
                    ok = False
                    break
            if not ok:
                break
        if not ok:
            break
    return ok


