import time
import random
import sys
from collections import deque

N = 12
FULL_MASK = (1 << N) - 1
DEADLINE_SECONDS = 85.0  # safety margin before 90s kill

def _build_subset_trans(trans):
    """Precompute subset transitions for one letter using dynamic programming."""
    size = 1 << N
    next_subset = [0] * size
    for mask in range(1, size):
        lsb = mask & (-mask)
        i = lsb.bit_length() - 1
        rest = mask ^ lsb
        next_subset[mask] = next_subset[rest] | (1 << trans[i])
    return next_subset

def compute_threshold(trans_a, trans_b):
    """
    Computes the length of the shortest reset word for the automaton defined by trans_a and trans_b.
    Returns 0 if not synchronizing.
    Uses BFS on the subset automaton with precomputed transitions.
    """
    next_a = _build_subset_trans(trans_a)
    next_b = _build_subset_trans(trans_b)

    # BFS from FULL_MASK
    size = 1 << N
    dist = [-1] * size
    dist[FULL_MASK] = 0
    queue = deque([FULL_MASK])
    
    while queue:
        cur = queue.popleft()
        
        # Check if singleton
        if cur & (cur - 1) == 0:
            return dist[cur]
        
        nxt_a = next_a[cur]
        if dist[nxt_a] == -1:
            dist[nxt_a] = dist[cur] + 1
            queue.append(nxt_a)
            
        nxt_b = next_b[cur]
        if dist[nxt_b] == -1:
            dist[nxt_b] = dist[cur] + 1
            queue.append(nxt_b)
            
    return 0

def _is_permutation(arr):
    """Check if arr is a permutation of 0..N-1."""
    seen = [False] * N
    for x in arr:
        if x < 0 or x >= N or seen[x]:
            return False
        seen[x] = True
    return True

def _generate_permutation_structures():
    """
    Generate permutation-based structures that preserve high-entropy subset dynamics.
    Both letters are bijections, which prevents premature collapse.
    """
    structures = []
    
    # Strategy 1: Two interleaved cycles of length N/2
    # a cycles within first half and second half separately
    # b interleaves: maps first half to second half and vice versa with offset
    for offset_a in range(1, N//2):
        for offset_b in range(1, N//2):
            a = [0] * N
            b = [0] * N
            half = N // 2
            # a: two independent cycles
            for i in range(half):
                a[i] = (i + offset_a) % half
                a[half + i] = half + (i + offset_a) % half
            # b: interleaving permutation
            for i in range(half):
                # Map first half to second half with offset
                b[i] = half + (i + offset_b) % half
                # Map second half to first half with offset
                b[half + i] = (i + offset_b) % half
            if _is_permutation(a) and _is_permutation(b):
                structures.append((a[:], b[:]))
    
    # Strategy 2: Full N-cycle for a, different N-cycle for b
    # Both are single cycles of length N
    for shift_a in range(1, N):
        for shift_b in range(1, N):
            if shift_a == shift_b:
                continue
            a = [(i + shift_a) % N for i in range(N)]
            b = [(i + shift_b) % N for i in range(N)]
            structures.append((a[:], b[:]))
    
    # Strategy 3: a is N-cycle, b is product of two (N/2)-cycles that cross
    for cross_offset in range(1, N//2):
        a = [(i + 1) % N for i in range(N)]
        b = [0] * N
        half = N // 2
        # b creates a "crossing" pattern
        for i in range(half):
            b[i] = half + i  # first half to second half
            b[half + i] = i  # second half to first half
        # Apply offset to make it non-trivial
        if cross_offset != 1:
            # Rotate the second half mapping
            for i in range(half):
                b[i] = half + (i + cross_offset) % half
                b[half + i] = (i + cross_offset) % half
        if _is_permutation(b):
            structures.append((a[:], b[:]))
    
    # Strategy 4: Random permutations with constraint that they generate a transitive group
    # Try many random permutation pairs
    for _ in range(200):
        a = list(range(N))
        b = list(range(N))
        random.shuffle(a)
        random.shuffle(b)
        # Ensure transitivity: the group generated by a and b acts transitively
        # Quick check: can we reach all states from state 0 using a and b?
        visited = {0}
        queue = [0]
        while queue:
            cur = queue.pop()
            na = a[cur]
            nb = b[cur]
            if na not in visited:
                visited.add(na)
                queue.append(na)
            if nb not in visited:
                visited.add(nb)
                queue.append(nb)
        if len(visited) == N:  # Transitive
            structures.append((a[:], b[:]))
    
    return structures

def _constraint_aware_mutation(cur_a, cur_b, best_score):
    """
    Perform a mutation that tries to avoid creating shortcuts.
    Returns (new_a, new_b, is_valid)
    """
    # Choose which letter to mutate
    if random.random() < 0.5:
        letter = 'a'
        cur = cur_a[:]
        other = cur_b[:]
    else:
        letter = 'b'
        cur = cur_b[:]
        other = cur_a[:]
    
    # Choose a state to mutate
    state = random.randint(0, N-1)
    
    # Generate candidate new destination
    # Prefer destinations that maintain high subset diversity
    candidates = []
    for dest in range(N):
        if dest == cur[state]:
            continue
        # Heuristic: prefer destinations that are "far" from current in cycle structure
        # This is a simple heuristic; we'll validate with actual threshold computation
        candidates.append(dest)
    
    if not candidates:
        return None, None, False
    
    new_dest = random.choice(candidates)
    cur[state] = new_dest
    
    # Check if this creates a permutation (if we want to maintain permutation property)
    # For now, allow non-permutations but prefer them
    if letter == 'a':
        new_a, new_b = cur, other
    else:
        new_a, new_b = other, cur
    
    # Quick check: does this still synchronize? (cheap BFS depth limit)
    # If it doesn't synchronize within a reasonable depth, reject
    threshold = compute_threshold(new_a, new_b)
    if threshold == 0:
        return None, None, False
    
    # Accept if it improves or maintains score
    if threshold >= best_score:
        return new_a, new_b, True
    
    return None, None, False

def _refine_automaton(a, b, start_time, deadline):
    """
    Local search to refine an automaton, trying to maximize threshold.
    Uses constraint-aware mutations that preserve high-entropy dynamics.
    """
    cur_a = a[:]
    cur_b = b[:]
    cur_score = compute_threshold(cur_a, cur_b)
    
    if cur_score == 0:
        return None, None, 0
    
    best_a = cur_a[:]
    best_b = cur_b[:]
    best_score = cur_score
    
    no_improve = 0
    max_no_improve = 30  # Reduce to allow more diverse exploration
    
    while time.time() < deadline:
        if no_improve > max_no_improve:
            break
        
        # Try constraint-aware mutation
        new_a, new_b, valid = _constraint_aware_mutation(cur_a, cur_b, best_score)
        
        if valid:
            new_score = compute_threshold(new_a, new_b)
            if new_score > cur_score:
                cur_a = new_a
                cur_b = new_b
                cur_score = new_score
                no_improve = 0
                if cur_score > best_score:
                    best_score = cur_score
                    best_a = cur_a[:]
                    best_b = cur_b[:]
            else:
                no_improve += 1
        else:
            no_improve += 1
        
        # Occasionally try a more aggressive mutation: swap two destinations
        if no_improve % 5 == 0 and no_improve > 0:
            letter = random.choice(['a', 'b'])
            if letter == 'a':
                i, j = random.sample(range(N), 2)
                old_ai, old_aj = cur_a[i], cur_a[j]
                cur_a[i], cur_a[j] = old_aj, old_ai
                new_score = compute_threshold(cur_a, cur_b)
                if new_score > cur_score:
                    cur_score = new_score
                    no_improve = 0
                    if cur_score > best_score:
                        best_score = cur_score
                        best_a = cur_a[:]
                        best_b = cur_b[:]
                else:
                    cur_a[i], cur_a[j] = old_ai, old_aj
                    no_improve += 1
            else:
                i, j = random.sample(range(N), 2)
                old_bi, old_bj = cur_b[i], cur_b[j]
                cur_b[i], cur_b[j] = old_bj, old_bi
                new_score = compute_threshold(cur_a, cur_b)
                if new_score > cur_score:
                    cur_score = new_score
                    no_improve = 0
                    if cur_score > best_score:
                        best_score = cur_score
                        best_a = cur_a[:]
                        best_b = cur_b[:]
                else:
                    cur_b[i], cur_b[j] = old_bi, old_bj
                    no_improve += 1
    
    return best_a, best_b, best_score

def construct():
    start_time = time.time()
    deadline = start_time + DEADLINE_SECONDS
    
    random.seed(42)
    
    best_a = None
    best_b = None
    best_score = 0
    
    # Phase 1: Evaluate permutation-based structured candidates
    structures = _generate_permutation_structures()
    
    # Shuffle to explore different regions
    random.shuffle(structures)
    
    for a_struct, b_struct in structures:
        if time.time() > deadline - 10.0:
            break
        
        score = compute_threshold(a_struct, b_struct)
        if score > best_score:
            best_score = score
            best_a = a_struct[:]
            best_b = b_struct[:]
    
    # Phase 2: Local search refinement from best structured candidate
    if best_a is not None and time.time() < deadline - 5.0:
        refined_a, refined_b, refined_score = _refine_automaton(
            best_a, best_b, start_time, deadline - 5.0
        )
        if refined_score > best_score:
            best_score = refined_score
            best_a = refined_a
            best_b = refined_b
    
    # Phase 3: Try additional random permutation starts with refinement
    remaining_time = deadline - time.time()
    if remaining_time > 8.0:
        num_random_starts = min(8, int(remaining_time / 4))
        for _ in range(num_random_starts):
            if time.time() > deadline - 5.0:
                break
            
            # Generate random permutation pair
            a_rand = list(range(N))
            b_rand = list(range(N))
            random.shuffle(a_rand)
            random.shuffle(b_rand)
            
            # Check transitivity
            visited = {0}
            queue = [0]
            while queue:
                cur = queue.pop()
                na = a_rand[cur]
                nb = b_rand[cur]
                if na not in visited:
                    visited.add(na)
                    queue.append(na)
                if nb not in visited:
                    visited.add(nb)
                    queue.append(nb)
            
            if len(visited) != N:
                continue
            
            score = compute_threshold(a_rand, b_rand)
            if score == 0:
                continue
            
            if score > best_score:
                best_score = score
                best_a = a_rand[:]
                best_b = b_rand[:]
            
            # Refine if promising
            if score >= best_score - 3 and time.time() < deadline - 5.0:
                refined_a, refined_b, refined_score = _refine_automaton(
                    a_rand, b_rand, start_time, deadline - 5.0
                )
                if refined_score > best_score:
                    best_score = refined_score
                    best_a = refined_a
                    best_b = refined_b
    
    # Fallback: ensure we return a valid synchronizing automaton
    if best_score == 0 or best_a is None:
        # Simple synchronizing automaton with permutation a
        a = [(i + 1) % N for i in range(N)]
        b = [0] * N
        return [a, b]
    
    return [best_a, best_b]

