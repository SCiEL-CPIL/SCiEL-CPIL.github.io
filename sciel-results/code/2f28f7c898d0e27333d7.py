import time
import sys

def construct():
    start_time = time.time()
    deadline = start_time + 85  # Safety margin for 90s limit
    
    # We want to find the maximum size K such that there exists a set S of size K
    # satisfying the constraint.
    # We will search for K=60 down to K=1, or rather up from a known good lower bound.
    # Since 8 is known valid, we start checking from 9 upwards.
    
    # To make the search efficient, we use backtracking with pruning.
    # State: current set S, list of available candidates C.
    # Pruning: If adding x to S causes any subset sum collision between different cardinalities, reject x.
    
    # Helper: Check if a set S is valid and return the DP table for incremental use if needed.
    # Actually, for backtracking, we need to check validity of S + {x} quickly.
    # We can maintain the DP table incrementally.
    
    def check_validity_incremental(dp, s, x):
        """
        Check if adding x to set s (with current dp) maintains validity.
        Returns new_dp if valid, None otherwise.
        dp is a list of sets: dp[c] contains sums of subsets of s of size c.
        """
        # We need to check if any sum in new_dp[c] collides with any sum in new_dp[c'] for c != c'.
        # It is sufficient to check if the new sums (generated by adding x to dp[c-1]) 
        # collide with existing sums in dp[c] (from s) or other new sums?
        # Actually, the condition is global: all_sums = union(dp[c] for all c).
        # If S is valid, union(dp[c]) are disjoint.
        # When we add x, new sums are generated for each c: new_sums_c = {u + x | u in dp[c-1]}.
        # The new total set of sums is union(existing dp[c]) U union(new_sums_c).
        # Since existing dp[c] are disjoint, we only need to check if new_sums_c 
        # intersects with any dp[c'] for c' != c, OR if new_sums_c intersects with other new_sums_{c''}?
        # Wait. The condition is: if c != c', then sum_c != sum_c'.
        # So for a specific new sum value v in new_sums_c:
        # 1. v must not be in any dp[c'] for c' != c. (Collision with old sums)
        # 2. v must not be in new_sums_{c''} for c'' != c. (Collision with other new sums)
        # Note: v CAN be in dp[c] (old sums of same cardinality) - this is allowed.
        # Note: v CAN be in new_sums_c (other new sums of same cardinality) - this is allowed.
        
        # So the check is:
        # For each c, for each v in new_sums_c:
        #   if v is in (Union of dp[c'] for c' != c) OR (Union of new_sums_{c''} for c'' != c):
        #       return None
        
        # To make this fast, we can precompute a "forbidden" set for each c?
        # Forbidden for c = (Union of all dp[c'] for c' != c).
        # But we also need to check against other new_sums.
        
        # Let's construct the new_dp first.
        new_dp = [set(dp[c]) for c in range(len(s) + 1)]
        # Add x to subsets
        # dp[c] uses c elements from s.
        # new_dp[c+1] will contain old sums from dp[c+1] PLUS {u+x | u in dp[c]}.
        
        # We need to check collisions.
        # Let's build the new sums for each cardinality.
        new_sums_by_card = [set() for _ in range(len(s) + 2)]
        
        for c in range(len(s) + 1):
            # New sums for cardinality c+1 come from dp[c] + x
            if dp[c]:
                new_sums_by_card[c+1].update(u + x for u in dp[c])
            
            # Also, the old sums for cardinality c+1 are already in dp[c+1] (if c+1 <= len(s))
            # We don't need to add them to "new_sums_by_card" for collision checking 
            # against *other* new sums? 
            # Wait. The condition is about the FINAL set of sums.
            # Final sums for cardinality k = dp[k] (old) U new_sums_by_card[k].
            # Let's call FinalSums[k] = dp[k] U new_sums_by_card[k].
            
        # Now check for collisions between FinalSums[c] and FinalSums[c'] for c != c'.
        # Since dp[c] and dp[c'] were disjoint, and new_sums_by_card[c] and new_sums_by_card[c'] 
        # might collide with each other or with old sums.
        
        # Efficient check:
        # 1. Check if any v in new_sums_by_card[c] is in dp[c'] for c' != c.
        # 2. Check if any v in new_sums_by_card[c] is in new_sums_by_card[c'] for c' != c.
        
        # Let's combine all new sums into one set for step 2? No, we need to distinguish cardinality.
        
        # Step 1:
        # Precompute a set of all old sums? 
        # old_all_sums = union(dp). 
        # If v in new_sums_by_card[c] is in old_all_sums, is it a violation?
        # Only if v is in dp[c'] where c' != c.
        # If v is in dp[c], it's fine.
        
        # So for each c, let's check new_sums_by_card[c] against (old_all_sums - dp[c]).
        
        old_all_sums = set()
        for c in range(len(s) + 1):
            old_all_sums.update(dp[c])
            
        for c in range(len(s) + 2):
            if not new_sums_by_card[c]:
                continue
            # The forbidden old sums are old_all_sums minus dp[c] (if c <= len(s), else old_all_sums)
            if c <= len(s):
                forbidden_old = old_all_sums.difference(dp[c])
            else:
                forbidden_old = old_all_sums
                
            # Check intersection
            if new_sums_by_card[c].intersection(forbidden_old):
                return None
                
        # Step 2: Check collisions between new_sums_by_card[c] and new_sums_by_card[c']
        # We can iterate over pairs? Or maintain a global set of seen new sums?
        # If we see a sum v in new_sums_by_card[c], and we've already seen v in new_sums_by_card[c'] with c' != c, it's a collision.
        
        seen_new_sums = {} # value -> cardinality
        for c in range(len(s) + 2):
            for v in new_sums_by_card[c]:
                if v in seen_new_sums:
                    if seen_new_sums[v] != c:
                        return None
                else:
                    seen_new_sums[v] = c
                    
        # If we get here, it's valid.
        # Construct the final new_dp
        for c in range(len(s) + 2):
            if c <= len(s):
                new_dp[c].update(new_sums_by_card[c])
            else:
                # c = len(s)+1, only new sums exist
                new_dp[c] = new_sums_by_card[c]
                
        return new_dp

    def backtrack(s, candidates, target_size, dp, depth=0):
        """
        Try to build a set of size target_size starting from s.
        s: list of current elements
        candidates: list of available elements (sorted)
        target_size: desired final size
        dp: current DP table for s
        """
        if time.time() > deadline:
            return None
            
        if len(s) == target_size:
            return s
            
        # Heuristic: Order candidates to minimize "damage"
        # We want candidates that don't push sums too high or create tight collisions.
        # A simple heuristic: try smaller numbers first? Or numbers that create unique sums?
        # Let's try sorting by value. Smaller numbers usually allow more room.
        
        # To improve search, we can filter candidates first.
        # If a candidate x is such that x + min_sum(dp[0]) > max_possible_sum? No, max is bounded by 256*60.
        
        # Let's iterate through candidates.
        # Optimization: If we have time, we can shuffle or reorder?
        # For deterministic backtracking, sorted order is good.
        
        for i, x in enumerate(candidates):
            if time.time() > deadline:
                return None
                
            # Try adding x
            new_dp = check_validity_incremental(dp, s, x)
            if new_dp is not None:
                # Recurse
                # Pass remaining candidates
                # We can pass candidates[i+1:] to avoid duplicates? 
                # Since elements must be distinct, and we are picking from a sorted list,
                # picking x means we can only pick elements > x from the remaining list 
                # IF we enforce sorted order to avoid permutations.
                # Yes, to avoid checking {1,2} and {2,1}, we enforce s is sorted and we only pick from candidates > s[-1].
                
                # Wait, `candidates` passed in should already be filtered to be > s[-1].
                # So we just pass candidates[i+1:].
                
                result = backtrack(s + [x], candidates[i+1:], target_size, new_dp, depth+1)
                if result is not None:
                    return result
                    
        return None

    # Main Logic
    # We know size 8 is possible. Let's try to find larger sizes.
    # Max possible size is 60.
    # We will iterate target_size from 60 down to 9? 
    # Or from 9 up to 60?
    # Searching for a LARGE set is hard. Searching for a SMALL set is easy.
    # But we want to MAXIMIZE size.
    # If we search for K=60 and fail, we try K=59, etc. This might take a long time if 60 is impossible.
    # If we search for K=9 and succeed, we try K=10, etc. This is better because we can build on success?
    # No, backtracking doesn't build on success directly, but finding a valid set of size K is a prerequisite for K+1.
    # However, the specific set of size K might not be extendable to K+1.
    
    # Strategy: 
    # 1. Start with target_size = 9.
    # 2. If found, try target_size = 10.
    # 3. Continue until time runs out or we reach 60.
    
    # To speed up the search for larger K, we can use the found set of size K as a "seed" 
    # or constraint? No, backtracking restarts.
    
    # Better: Use the fact that if a set of size K is valid, its subsets are valid.
    # But we need to find the MAX size.
    
    # Let's try a range of target sizes.
    # We'll start from a high estimate and go down? 
    # No, let's start from 9 and go up. 
    # Why? Because the search space for K=9 is smaller than K=10.
    # If we find a set of size 9, we can try to extend it?
    # The backtrack function above doesn't extend, it builds from scratch.
    
    # Let's modify: 
    # 1. Find any valid set of size 9.
    # 2. If found, try to find a valid set of size 10.
    # ...
    
    # To make the search faster for larger K, we can restrict the candidate pool.
    # For K=10, the sum of the smallest 10 distinct ints is 55. Max sum is 256*10.
    
    # Let's just run backtrack for increasing K.
    
    all_candidates = list(range(1, 257))
    
    best_set = [1, 2, 4, 8, 16, 32, 64, 128] # Fallback
    best_size = 8
    
    for target_k in range(9, 61):
        if time.time() > deadline:
            break
            
        # Initial DP for empty set
        init_dp = [set() for _ in range(1)]
        init_dp[0].add(0)
        
        # We need to be careful with the candidate list.
        # If we just pass all candidates, the branching factor is 256.
        # Depth is K. 256^K is huge.
        # Pruning is critical.
        
        # To improve pruning, we can sort candidates by a heuristic.
        # "Smallest sum impact"?
        
        # Let's try to limit the candidate pool for the first few elements.
        # For K=9, we need 9 numbers. 
        # If we pick 1, 2, 4... we are close to powers of 2.
        
        # Let's run the backtracking.
        # To avoid timeout on large K, we can add a node limit or rely on the time check.
        
        # Optimization: If K is large, the numbers must be small?
        # Sum of K smallest distinct integers in 1..256 is K(K+1)/2.
        # If K(K+1)/2 > 256*K? No.
        
        # Let's just run it. The time check inside backtrack will abort if it takes too long.
        
        # One issue: Backtracking might get stuck in a bad branch for a long time.
        # To mitigate this, we can randomize the order of candidates slightly?
        # Or use a heuristic ordering.
        
        # Heuristic: Sort candidates by (x, x^2)? 
        # Let's stick to sorted order for determinism and speed (small numbers first).
        
        found = backtrack([], all_candidates, target_k, init_dp)
        
        if found:
            best_set = found
            best_size = target_k
            # If we found a set of size K, we can continue to K+1.
            # Note: The found set is just one solution. There might be others.
            # But finding ANY solution of size K proves K is possible.
            
            # If we run out of time, break.
            if time.time() > deadline - 5:
                break
        else:
            # If we didn't find a set of size K, it's likely no set of size > K exists?
            # Not necessarily, but in practice, if the search space for K is exhausted 
            # without finding a solution, K+1 is even harder.
            # However, a poor search might fail to find K even if it exists.
            # Given the time limit, if we fail K=9 quickly, we might try K=10? 
            # No, if K=9 is impossible, K=10 is impossible.
            # If K=9 is possible but we missed it due to time/pruning, we might still miss K=10.
            # So we break if we fail to find K? 
            # Risky. Let's assume if we run out of time, we return best.
            # If we finish search for K without finding a solution (not timeout), 
            # then K is impossible.
            
            # How to distinguish timeout from "no solution"?
            # The backtrack function returns None in both cases.
            # We can check time.
            if time.time() < deadline:
                # We finished the search for this K without timeout.
                # So K is impossible.
                # Therefore K+1 is impossible.
                break
            else:
                # Timed out. We don't know if K is possible.
                # But we also don't know if K+1 is possible.
                # We should probably stop searching for larger K because we are running out of time.
                break

    # Final validation of best_set
    def is_valid_final(s):
        dp = [set() for _ in range(len(s) + 1)]
        dp[0].add(0)
        for x in s:
            for c in range(len(s) - 1, -1, -1):
                dp[c + 1].update(sum_val + x for sum_val in dp[c])
        all_sums = set()
        for c in range(len(s) + 1):
            if not all_sums.isdisjoint(dp[c]):
                return False
            all_sums.update(dp[c])
        return True

    if not is_valid_final(best_set):
        # Fallback to known valid set
        best_set = [1, 2, 4, 8, 16, 32, 64, 128]
        
    return [int(x) for x in best_set]

