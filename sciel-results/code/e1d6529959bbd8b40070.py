def priority(vector, n):
    if time.time() > _DEADLINE:
        return 0.0

    # 1. Balance Score (Centrality)
    c0 = sum(1 for x in vector if x == 0)
    c1 = sum(1 for x in vector if x == 1)
    c2 = sum(1 for x in vector if x == 2)
    
    ideal = n / 3.0
    var = (c0 - ideal)**2 + (c1 - ideal)**2 + (c2 - ideal)**2
    max_var = 2 * n * n / 3.0
    if max_var > 0:
        norm_var = var / max_var
    else:
        norm_var = 0.0
    balance_score = 1.0 - norm_var

    # 2. Periodicity Penalty
    # Check if the vector is periodic with small periods.
    # Period k means v[i] == v[i+k] for all i < n-k.
    # We check k = 1, 2, ..., min(n//2, 10).
    periodic_penalty = 0.0
    max_k = min(n // 2, 10)
    
    for k in range(1, max_k + 1):
        is_periodic = True
        # Check a few samples to speed up? 
        # For n <= 20, full check is fast.
        for i in range(n - k):
            if vector[i] != vector[i + k]:
                is_periodic = False
                break
        if is_periodic:
            # Penalize based on how "strong" the period is.
            # Smaller k is worse.
            periodic_penalty += 1.0 / k
            
    # 3. Randomness / Entropy Proxy
    # High entropy is good.
    # We already have balance.
    
    # 4. Combine
    # We want high balance, low periodicity.
    score = balance_score - 0.5 * periodic_penalty
    
    # Tie-breaker
    h = 0
    for val in vector:
        h = (h * 37 + val) & 0xFFFFFFFF
    score += (h / 4294967296.0) * 0.1
    
    return float(score)
