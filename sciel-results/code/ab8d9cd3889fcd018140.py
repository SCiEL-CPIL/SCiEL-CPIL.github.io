def construct(n):
    if n <= 4:
        # Classic construction is optimal for small n
        word = [1]
        for m in range(2, n + 1):
            perms, seen = [], set()
            for i in range(len(word) - m + 2):
                window = tuple(word[i:i + m - 1])
                if len(set(window)) == m - 1 and window not in seen:
                    seen.add(window)
                    perms.append(window)
            new = []
            for p in perms:
                block = list(p) + [m] + list(p)
                overlap = next(o for o in range(min(len(new), len(block)), -1, -1) if new[len(new) - o:] == block[:o])
                new += block[overlap:]
            word = new
        return "".join(map(str, word))

    # Generate all permutations
    perms = list(itertools.permutations(range(1, n + 1)))
    N = len(perms)
    
    # Convert to strings for faster comparison/slicing
    perm_strs = ["".join(map(str, p)) for p in perms]
    
    def get_overlap_idx(i, j):
        a = perm_strs[i]
        b = perm_strs[j]
        max_k = 0
        # Check overlap from largest to smallest
        for k in range(n - 1, 0, -1):
            if a[n-k:] == b[:k]:
                return k
        return 0

    # 1. Generate Classic Order
    # The classic order is generated by the recursive algorithm.
    # We can simulate the indices.
    # Actually, it's easier to just run the classic construction to get the string,
    # but we need the *order of permutations* to compare costs.
    # Alternatively, we can just compute the cost of the classic string directly?
    # No, we need to compare paths.
    
    # Let's just run the heuristic and compare the final string length.
    # We don't strictly need the classic *path* indices if we just build the string
    # from the heuristic path and compare its length to the classic string length.
    
    # Build Classic String
    word_classic = [1]
    for m in range(2, n + 1):
        perms_local, seen = [], set()
        for i in range(len(word_classic) - m + 2):
            window = tuple(word_classic[i:i + m - 1])
            if len(set(window)) == m - 1 and window not in seen:
                seen.add(window)
                perms_local.append(window)
        new = []
        for p in perms_local:
            block = list(p) + [m] + list(p)
            overlap = next(o for o in range(min(len(new), len(block)), -1, -1) if new[len(new) - o:] == block[:o])
            new += block[overlap:]
        word_classic = new
    classic_len = len(word_classic)
    classic_str = "".join(map(str, word_classic))

    # 2. Heuristic Search
    # Nearest Neighbor
    unvisited = set(range(N))
    unvisited.remove(0)
    path = [0]
    current = 0
    
    for _ in range(N - 1):
        best_next = -1
        best_overlap = -1
        for j in unvisited:
            ov = get_overlap_idx(current, j)
            if ov > best_overlap:
                best_overlap = ov
                best_next = j
        path.append(best_next)
        unvisited.remove(best_next)
        current = best_next
        
    # 2-Opt Improvement
    # Simple 1-Opt (swap adjacent) or 2-Opt (reverse segment)
    # Let's do a few passes of 2-Opt
    
    def path_cost(p):
        total = n # First perm
        for i in range(len(p) - 1):
            total += n - get_overlap_idx(p[i], p[i+1])
        return total

    improved = True
    iterations = 0
    max_iterations = 5 # Limit to avoid timeout
    
    while improved and iterations < max_iterations:
        improved = False
        iterations += 1
        for i in range(N - 1):
            for j in range(i + 1, N):
                # Check if reversing path[i:j+1] improves cost
                # Old edges: (path[i-1], path[i]) and (path[j], path[j+1])
                # New edges: (path[i-1], path[j]) and (path[i], path[j+1])
                # Handle boundaries
                old_cost = 0
                new_cost = 0
                
                # Cost of entering i
                if i > 0:
                    old_cost += n - get_overlap_idx(path[i-1], path[i])
                    new_cost += n - get_overlap_idx(path[i-1], path[j])
                else:
                    # No cost for start, but we care about the internal structure
                    pass

                # Cost of exiting j
                if j < N - 1:
                    old_cost += n - get_overlap_idx(path[j], path[j+1])
                    new_cost += n - get_overlap_idx(path[i], path[j+1])
                
                # Cost of internal edges?
                # Reversing a segment changes the internal edges.
                # However, the cost of a path is sum of edge costs.
                # The internal edges of the segment are reversed.
                # Cost(A->B) is not necessarily equal to Cost(B->A).
                # So we must calculate the full cost of the new segment vs old segment.
                # This is O(N) per check.
                # With N=5040, N^2 checks * N cost = N^3 = 10^11. Too slow.
                
