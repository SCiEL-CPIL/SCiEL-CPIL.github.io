"""Multi-objective optimizer on DTLZ1 with simplex-constrained Pareto front sampling."""
# EVOLVE-BLOCK-START
import numpy as np
import time


class Optimizer:
    """
    Multi-objective optimizer for DTLZ1 using analytical Pareto front sampling
    on the simplex constraint x1 + x2 + x3 = 1.
    
    DTLZ1 Pareto front: when g(x) = 0, the objectives are:
    f1 = 0.5 * x1 * (1 + g)
    f2 = 0.5 * x2 * (1 + g)  
    f3 = 0.5 * x3 * (1 + g)
    
    With g = 0: f1 = 0.5*x1, f2 = 0.5*x2, f3 = 0.5*x3
    The Pareto front is the 2D simplex x1 + x2 + x3 = 1, xi >= 0.
    
    Strategy: Sample points uniformly on the 2D simplex using Dirichlet(1,1,1),
    set aggregation variables to 0.5, and evaluate all points.
    """

    def __init__(self, budget, dim, n_obj):
        self.budget, self.dim, self.n_obj = budget, dim, n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 280  # 300s limit, 20s safety margin
        
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        n = self.budget
        
        # Strategy: Sample points on the analytical Pareto front (simplex)
        # For DTLZ1 with 7 variables: x1, x2, x3 are position vars on simplex
        # x4-x7 are aggregation vars set to 0.5
        # The Pareto front is the 2D simplex: x1+x2+x3=1, xi>=0
        
        rng = np.random.default_rng(42)
        
        # Generate uniform samples on the 2D simplex
        # Method: generate 3 exponential random variables and normalize
        # Or: use the fact that uniform on simplex can be generated by
        # sorting 2 uniform random numbers in [0,1]
        
        n_samples = n
        # Generate uniform points on simplex using Dirichlet(1,1,1)
        # This gives uniform distribution on the 2D simplex
        # Method: generate 3 gamma(1,1) = exponential(1) variables, normalize
        exp_samples = rng.exponential(scale=1.0, size=(n_samples, 3))
        simplex_points = exp_samples / exp_samples.sum(axis=1, keepdims=True)
        
        x1 = simplex_points[:, 0]
        x2 = simplex_points[:, 1]
        x3 = simplex_points[:, 2]
        
        # Build full decision vectors
        # x = [x1, x2, x3, 0.5, 0.5, 0.5, 0.5]
        X = np.zeros((n_samples, self.dim))
        X[:, 0] = x1
        X[:, 1] = x2
        X[:, 2] = x3
        X[:, 3:] = 0.5  # Aggregation variables at midpoint
        
        # Clip to bounds
        X = np.clip(X, lo, hi)
        
        # Evaluate all points
        F = np.array([problem(x) for x in X])
        
        # Check time
        elapsed = time.time() - start_time
        if elapsed > deadline - start_time:
            return X
        
        return X
