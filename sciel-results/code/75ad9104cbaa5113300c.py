def _lcm(a, b):
    return a * b // gcd(a, b)

def _lcm_range(n):
    return reduce(_lcm, range(1, n + 1), 1)

def _lll_reduce(basis):
    """
    Lattice basis reduction using LLL algorithm.
    basis: list of integer vectors (as tuples or lists)
    Returns: reduced basis
    """
    if len(basis) <= 1:
        return basis
    
