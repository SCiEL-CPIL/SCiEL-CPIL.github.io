    B = [list(b) for b in basis]
    n = len(B)
    d = len(B[0]) if n > 0 else 0
    
    # Initialize delta = 0.99
    delta = 0.99
    
    # Compute Gram-Schmidt data
    mu = [[0.0] * n for _ in range(n)]
    Bp = [list(b) for b in B]
    bpd = []  # Bp dot data
    
    def dot(u, v):
        return sum(ui * vi for ui, vi in zip(u, v))
    
    def norm_sq(v):
        return sum(vi * vi for vi in v)
    
    # Initialize
    for i in range(n):
        Bp[i] = [float(x) for x in B[i]]
    
    # Initialize mu and Bp
    for i in range(n):
        mu[i][i] = 1.0
        Bp[i] = [float(x) for x in B[i]]
    
    # Compute initial Gram-Schmidt
    for j in range(1, n):
        for i in range(j):
            if norm_sq(Bp[i]) > 0:
                mu[j][i] = dot(Bp[j], Bp[i]) / norm_sq(Bp[i])
                Bp[j] = [Bp[j][k] - mu[j][i] * Bp[i][k] for k in range(d)]
    
    # LLL main loop
    k = 1
    while k < n:
        # Size reduction step
        for j in range(k - 1, -1, -1):
            mu[k][j] = round(mu[k][j])
            for i in range(j, -1, -1):
                B[k] = [B[k][m] - mu[k][j] * B[j][m] for m in range(d)]
                Bp[k] = [Bp[k][m] - mu[k][j] * Bp[j][m] for m in range(d)]
        
        # Check Lovasz condition
        if norm_sq(Bp[k]) >= (delta - mu[k][k-1]**2) * norm_sq(Bp[k-1]):
            k += 1
            continue
        
        # Swap B[k-1] and B[k]
        B[k-1], B[k] = B[k], B[k-1]
        Bp[k-1], Bp[k] = Bp[k], Bp[k-1]
        
        # Recompute mu for affected rows
        for i in range(k, n):
            for j in range(k):
                if norm_sq(Bp[j]) > 0:
                    mu[i][j] = dot(Bp[i], Bp[j]) / norm_sq(Bp[j])
        
        # Recompute Bp for affected rows
        for i in range(k, n):
            for j in range(i):
                if norm_sq(Bp[j]) > 0:
                    Bp[i] = [Bp[i][m] - mu[i][j] * Bp[j][m] for m in range(d)]
        
        # Move k back
        if k > 1:
            k -= 1
    
    return [tuple(b) for b in B]

