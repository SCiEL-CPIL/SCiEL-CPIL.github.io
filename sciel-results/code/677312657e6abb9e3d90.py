        # Let me go with a valid but potentially suboptimal approach, then try to improve.
        
        # Valid Approach:
        # - Use the full internal clique C = [0, k) to cover all internal edges.
        # - For each independent vertex v, partition cross_adj[v] into singletons, creating
        #   cliques {u, v} for each u ∈ cross_adj[v].
        # Total: 1 + sum(|cross_adj[v]|)
        
