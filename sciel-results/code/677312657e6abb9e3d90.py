import time
from random import Random

def construct():
    # Keep the exact generator under the name instance
    def instance(n, k, p, seed):
        rng = Random(seed)
        edges = [(u, v) for u in range(k) for v in range(u + 1, k)]
        edges += [(u, v) for v in range(k, n) for u in range(k) if rng.random() < p]
        return sorted(edges)

    def solve_split(n, k, p, seed):
        # Rebuild the same graph deterministically
        rng = Random(seed)
        # Internal clique edges: all pairs in [0, k)
        # Cross edges: for each independent vertex v in [k, n), for each u in [0, k)
        # with probability p
        # We need to reproduce the exact same edge set as instance()
        # instance() does:
        #   edges = [(u,v) for u in range(k) for v in range(u+1, k)]
        #   edges += [(u, v) for v in range(k, n) for u in range(k) if rng.random() < p]
        # The cross edges are generated by iterating v from k to n-1, and for each v,
        # iterating u from 0 to k-1, calling rng.random() for each (u, v) pair.
        
        # Build adjacency for cross edges
        # cross_adj[v] = set of u in [0,k) such that (u,v) is an edge
        cross_adj = {}
        for v in range(k, n):
            neighbors = []
            for u in range(k):
                if rng.random() < p:
                    neighbors.append(u)
            cross_adj[v] = set(neighbors)
        
        # Now we have:
        # - Clique C = {0, 1, ..., k-1} (all internal edges present)
        # - Independent set I = {k, k+1, ..., n-1} (no edges among them)
        # - Cross edges as defined by cross_adj
        
        # The graph is a split graph. We need to partition all edges into cliques.
        # Every edge must be in exactly one clique.
        # Every clique must have at least 2 vertices.
        # Minimize total number of cliques.
        
        # Strategy:
        # 1. The internal clique edges form the complete graph K_k on vertices [0, k).
        #    We can cover these with one clique C = [0, k) if we don't need to break it up.
        #    But if we include some independent vertices in cliques with internal vertices,
        #    we might be able to reduce the total count.
        
        # Key insight: An edge (u, v) where u < k <= v is a cross edge.
        # An edge (u, u') where u, u' < k is an internal edge.
        
        # A clique in a split graph can contain:
        # - Only internal vertices (subset of C)
        # - Only one independent vertex and some internal vertices (since independent set has no edges)
        # - It cannot contain two or more independent vertices (no edges between them)
        
        # So every clique is either:
        # (a) A subset of C (internal clique)
        # (b) {v} ∪ S where v is an independent vertex and S ⊆ C is a clique in the 
        #     subgraph induced by C (which is complete, so any S ⊆ C works) AND 
        #     all vertices in S are adjacent to v (i.e., S ⊆ cross_adj[v])
        
        # The internal edges must be covered by cliques of type (a) and possibly type (b)
        # (type (b) cliques also cover internal edges within S).
        
        # Cross edges (u, v) must be covered by cliques of type (b) that contain both u and v.
        
        # Approach:
        # - Start with the full internal clique C covering all internal edges: 1 clique.
        # - For each independent vertex v, the cross edges (u, v) for u in cross_adj[v]
        #   need to be covered. We can cover them all with one clique {v} ∪ cross_adj[v],
        #   but this clique also covers internal edges within cross_adj[v], which were
        #   already covered by C. This would violate the "exactly one" constraint.
        
        # So we need a more careful partition. Let me think differently.
        
        # Each edge must be in exactly one clique. Let's think of it as:
        # We assign each edge to exactly one clique.
        
        # For internal edge (u, u'): it can be assigned to any clique containing both u and u'.
        # For cross edge (u, v): it must be assigned to a clique containing both u and v.
        
        # A clique of type (b) = {v} ∪ S covers:
        # - Cross edges (u, v) for u ∈ S
        # - Internal edges (u, u') for u, u' ∈ S
        
        # A clique of type (a) = S ⊆ C covers:
        # - Internal edges (u, u') for u, u' ∈ S
        
        # We want to minimize the number of cliques.
        
        # Greedy approach:
        # 1. For each independent vertex v, we must cover all cross edges (u, v) for u ∈ cross_adj[v].
        #    We can do this with one clique {v} ∪ cross_adj[v], but this "steals" internal edges
        #    within cross_adj[v].
        #    
        #    Alternatively, we can split cross_adj[v] into multiple cliques, each of form {v} ∪ S_i,
        #    where S_i ⊆ cross_adj[v]. This uses more cliques for v but leaves more internal edges
        #    to be covered by internal cliques.
        
        # 2. After assigning cross edges to type-(b) cliques, the remaining internal edges
        #    (those not covered by any type-(b) clique) must be covered by type-(a) cliques.
        
        # Let's try: for each v, use one clique {v} ∪ cross_adj[v]. This covers all cross edges
        # and some internal edges. Then cover remaining internal edges.
        
        # But wait: if we use {v} ∪ cross_adj[v] for every v, and cross_adj[v] is large,
        # we might be covering many internal edges multiple times (once per v that includes them).
        # This violates the "exactly one" rule.
        
        # So we need to ensure that each internal edge is covered by at most one clique.
        
        # Revised approach:
        # - Decide which internal edges are covered by type-(b) cliques and which by type-(a).
        # - For each v, choose a subset S_v ⊆ cross_adj[v] such that the cross edges (u,v) for
        #   u ∈ S_v are covered by clique {v} ∪ S_v.
        # - The remaining cross edges (u, v) for u ∈ cross_adj[v] \ S_v must be covered by other
        #   type-(b) cliques for v, i.e., we need to partition cross_adj[v] into subsets.
        # - Actually, all cross edges for v must be covered, so we need to partition cross_adj[v]
        #   into one or more subsets S_{v,1}, S_{v,2}, ..., S_{v,m_v}, and create cliques 
        #   {v} ∪ S_{v,i} for each i.
        # - The internal edges covered by type-(b) cliques are those within each S_{v,i}.
        # - These internal edges must not be covered by any other clique.
        # - The remaining internal edges must be covered by type-(a) cliques.
        
        # To minimize total cliques:
        # - We want to maximize the number of internal edges covered by type-(b) cliques
        #   (to reduce the number of type-(a) cliques needed).
        # - But we also want to minimize the number of type-(b) cliques.
        
        # Simple heuristic:
        # For each v, use one clique {v} ∪ cross_adj[v]. This gives n-k type-(b) cliques.
        # The internal edges covered are the union over v of edges within cross_adj[v].
        # The remaining internal edges form a graph G_rem on [0, k).
        # We need to cover G_rem with type-(a) cliques.
        
        # But the problem is that an internal edge (u, u') might be in cross_adj[v] for multiple v,
        # meaning it's covered by multiple type-(b) cliques. This is invalid.
        
        # So we need to ensure that each internal edge is in at most one S_{v,i}.
        
