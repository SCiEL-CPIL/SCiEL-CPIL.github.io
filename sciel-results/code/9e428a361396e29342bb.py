    deadline = start_time + 140.0  # 10s safety margin before 150s limit
    
    def _elapsed():
        return time.time() - start_time
    
    def _remaining():
        return deadline - time.time()
    
    # Initialize with Fibonacci spiral
    i = np.arange(N) + 0.5
    z = 1.0 - 2.0 * i / N
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(np.clip(1.0 - z * z, 0, None))
    pts = np.column_stack([r * np.cos(phi), r * np.sin(phi), z])
    
    best_pts = pts.copy()
    best_radius = _cover_radius_grid(best_pts, 5000)
    
    # Strategy 1: Refined optimization using a combination of approaches
    # Use a potential energy / repulsion-based approach combined with covering radius minimization
    
    def _potential_energy(pts, k_repel=2.0, k_cover=1.0):
        """Compute a combined objective: repulsion + covering radius."""
        norms = np.linalg.norm(pts, axis=1, keepdims=True)
        pts = pts / norms
        
        # Repulsion energy: sum of 1/d^k for all pairs
        # Use dot products: d = arccos(dot), so 1/d^k is hard to compute directly
        # Instead, use (1-dot)^k as a proxy for close points
        dots = pts @ pts.T
        np.fill_diagonal(dots, 0)
        # For close points, dot is close to 1, so (1-dot) is small
        # We want to maximize the minimum distance, so minimize max(1-dot)
        # Use a soft version: log-sum-exp of (1-dot)^beta
        one_minus_dots = 1.0 - dots
        one_minus_dots = np.clip(one_minus_dots, 1e-10, None)
        beta = 10.0
        log_sum_exp = np.log(np.sum(np.exp(beta * one_minus_dots), axis=1)) / beta
        repulsion = np.mean(log_sum_exp)
        
        # Covering radius via grid
        cover_r = _cover_radius_grid(pts, 3000)
        
        return k_repel * repulsion + k_cover * cover_r, cover_r
    
