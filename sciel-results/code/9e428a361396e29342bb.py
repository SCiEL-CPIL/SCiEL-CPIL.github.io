def _cover_radius_exact(pts):
    """Compute the exact covering radius in radians using convex hull facets."""
    pts = np.array(pts, dtype=np.float64)
    norms = np.linalg.norm(pts, axis=1, keepdims=True)
    pts = pts / norms
    
    # Check for coincident points
    n_pts = len(pts)
    if n_pts < 4:
        return np.pi
    
    # Check for coincident points
    for i in range(n_pts):
        for j in range(i+1, n_pts):
            if np.linalg.norm(pts[i] - pts[j]) < 1e-12:
                return np.pi
    
    # Check if all points are in a closed hemisphere
    # If there exists a plane through the origin such that all points are on one side
    # We can check this by seeing if the origin is inside the convex hull
    try:
        hull = ConvexHull(pts)
    except Exception:
        return np.pi
    
    # Check if origin is inside the convex hull
    # Use the fact that for a convex polytope containing the origin,
    # the origin can be expressed as a convex combination of vertices
    # Alternatively, check if all facet normals point away from origin
    
    # For each facet, compute the normal and check it points away from origin
    # If all normals point in roughly the same direction, points are in a hemisphere
    facet_normals = []
    for simplex in hull.simplices:
        if len(simplex) == 3:
            a, b, c = pts[simplex[0]], pts[simplex[1]], pts[simplex[2]]
            n = np.cross(b - a, c - a)
            n_norm = np.linalg.norm(n)
            if n_norm > 1e-15:
                n = n / n_norm
                # Ensure normal points outward (away from centroid)
                centroid = (a + b + c) / 3.0
                if np.dot(n, centroid) < 0:
                    n = -n
                facet_normals.append(n)
    
