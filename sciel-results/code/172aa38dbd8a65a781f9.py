# EVOLVE-BLOCK-START
import numpy as np
import time

def construct():
    """
    Construct the extended quadratic residue code of length 18.
    This is a linear [18, 9, 6] code with 512 codewords.
    
    Strategy:
    1. Use the generator polynomial for QR(17) to generate a cyclic [17, 9, 5] code.
    2. Extend each codeword with a parity bit to form an [18, 9, 6] code.
    3. Verify the minimum distance to ensure validity.
    4. If verification fails (should not happen with correct constants), fallback to a known valid smaller code.
    """
    N = 18
    MIN_DIST = 6
    start_time = time.time()
    deadline = 60.0  # 60 second deadline, keep 5s buffer
    
    # The generator polynomial for the QR(17) code is g(x) = x^8 + x^5 + x^4 + x^3 + 1
    # Coefficients for x^0 to x^8: 1, 0, 0, 1, 1, 1, 0, 0, 1
    # As an integer (LSB is x^0): 1 + 8 + 16 + 32 + 256 = 313
    g_poly = 313
    
    # Alternative generator polynomial (the other factor of x^17+1 of degree 8)
    # g_alt(x) = x^8 + x^7 + x^6 + x^4 + 1
    # Coeffs: 1, 0, 0, 0, 1, 0, 1, 1, 1
    # Int: 1 + 16 + 64 + 128 + 256 = 465
    g_alt_poly = 465

    def generate_extended_qr(g_poly):
        """
        Generates the extended QR code from a given generator polynomial.
        Returns a list of 512 integers.
        """
        # Generate the 9 basis vectors for the length-17 cyclic code
        # The basis vectors are x^i * g(x) for i = 0..8
        basis_17 = []
        for i in range(9):
            cw = g_poly << i
            # Mask to 17 bits
            cw &= (1 << 17) - 1
            basis_17.append(cw)
        
        # Extend to length 18 by adding a parity bit
        # The parity bit is 1 if the weight of the 17-bit vector is odd, 0 otherwise
        # We append it as the 18th bit (bit 17)
        basis_18 = []
        for cw in basis_17:
            weight = cw.bit_count()
            parity = weight % 2
            cw_18 = cw | (parity << 17)
            basis_18.append(cw_18)
            
        # Generate all 512 codewords
        code = []
        for mask in range(1 << 9):
            cw = 0
            # Unrolled XOR for speed
            if mask & 1: cw ^= basis_18[0]
            if mask & 2: cw ^= basis_18[1]
            if mask & 4: cw ^= basis_18[2]
            if mask & 8: cw ^= basis_18[3]
            if mask & 16: cw ^= basis_18[4]
            if mask & 32: cw ^= basis_18[5]
            if mask & 64: cw ^= basis_18[6]
            if mask & 128: cw ^= basis_18[7]
            if mask & 256: cw ^= basis_18[8]
            code.append(cw)
            
        return code

    def verify_code(code, min_dist):
        """
        Checks if all pairwise distances are >= min_dist.
        For linear codes, it suffices to check the weight of all non-zero codewords.
        """
        if not code:
            return False
        # Since it's a linear code (generated by basis), min distance is min weight of non-zero codewords
        min_w = N + 1
        for cw in code:
            if cw != 0:
                w = cw.bit_count()
                if w < min_w:
                    min_w = w
                    if min_w < min_dist:
                        return False
        return min_w >= min_dist

    # Primary attempt: Standard QR(17) generator
    code = generate_extended_qr(g_poly)
    
    if verify_code(code, MIN_DIST):
        return code

    # Fallback attempt: Alternative QR(17) generator
    code_alt = generate_extended_qr(g_alt_poly)
    if verify_code(code_alt, MIN_DIST):
        return code_alt

    # Emergency Fallback: Reed-Muller RM(1,4) padded to 18 bits
    # RM(1,4) is [16, 5, 8]. Padded with 2 zeros -> [18, 5, 8]. Size 32.
    # This is always valid for d=6.
    rm_basis = [
        0b1111111111111111, # 1
        0b1010101010101010, # x1
        0b0110011001100110, # x2
        0b0011001100110011, # x3
        0b0001000100010001  # x4
    ]
    
    rm_code = []
    for m in range(32):
        cw = 0
        if m & 1: cw ^= rm_basis[0]
        if m & 2: cw ^= rm_basis[1]
        if m & 4: cw ^= rm_basis[2]
        if m & 8: cw ^= rm_basis[3]
        if m & 16: cw ^= rm_basis[4]
        rm_code.append(cw)
        
    return rm_code

