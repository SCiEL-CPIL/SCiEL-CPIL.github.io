import time
import numpy as np
import random

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    max_val = 4096
    max_sum = 3 * max_val + 1
    
    def is_valid_add(x, S, used_sums):
        """
        Check if x can be added to S.
        Returns (valid, new_sums_array) if valid.
        new_sums_array is the list of sums generated by adding x.
        """
        if len(S) == 0:
            new_sums = np.array([3*x], dtype=np.int32)
            if used_sums[3*x]:
                return False, None
            if len(np.unique(new_sums)) != len(new_sums):
                return False, None
            return True, new_sums
        
        S_arr = np.array(S, dtype=np.int32)
        
        # 3*x
        s1 = np.array([3*x], dtype=np.int32)
        
        # 2*x + s_i
        s2 = 2*x + S_arr
        
        # x + s_i + s_j (i <= j)
        i_idx, j_idx = np.triu_indices(len(S_arr))
        s3 = x + S_arr[i_idx] + S_arr[j_idx]
        
        new_sums = np.concatenate((s1, s2, s3))
        
        # Check for duplicates within new sums
        if len(np.unique(new_sums)) != len(new_sums):
            return False, None
            
        # Check against used_sums
        if np.any(used_sums[new_sums]):
            return False, None
            
        return True, new_sums

    def get_initial_set():
        # Start with powers of 2, which are always valid
        # 1, 2, 4, ..., 2048 (2^11)
        S = [2**i for i in range(12)]
        used_sums = np.zeros(max_sum, dtype=bool)
        
        # Mark all sums for this initial set
        S_arr = np.array(S, dtype=np.int32)
        n = len(S_arr)
        
        # 3*s_i
        sums = 3 * S_arr
        used_sums[sums] = True
        
        # 2*s_i + s_j
        for i in range(n):
            for j in range(n):
                s = 2*S_arr[i] + S_arr[j]
                used_sums[s] = True
                
        # s_i + s_j + s_k
        for i in range(n):
            for j in range(n):
                for k in range(n):
                    s = S_arr[i] + S_arr[j] + S_arr[k]
                    used_sums[s] = True
                    
        return S, used_sums

    best_set, best_used = get_initial_set()
    best_len = len(best_set)
    
    # Simulated Annealing
    T = 10.0
    cooling_rate = 0.999
    
    while time.time() < deadline - 5.0:
        current_set, current_used = best_set.copy(), best_used.copy()
        current_len = len(current_set)
        current_set_set = set(current_set)
        
        # Run annealing for this restart
        steps = 0
        while time.time() < deadline - 5.0 and steps < 20000:
            steps += 1
            move_type = random.choice(['add', 'remove', 'swap'])
            
            if move_type == 'add':
                # Pick a random candidate to add
                candidates = [x for x in range(1, max_val + 1) if x not in current_set_set]
                if not candidates:
                    continue
                x = random.choice(candidates)
                
                valid, new_sums = is_valid_add(x, current_set, current_used)
                if valid:
                    # Accept
                    current_set.append(x)
                    current_set_set.add(x)
                    current_used[new_sums] = True
                    current_len += 1
                    
                    if current_len > best_len:
                        best_len = current_len
                        best_set = current_set.copy()
                        best_used = current_used.copy()
                else:
                    # Reject (or accept with prob 0 since energy increases)
                    pass
                    
            elif move_type == 'remove':
                if not current_set:
                    continue
                idx = random.randint(0, len(current_set) - 1)
                x = current_set[idx]
                
                # Remove x from set and used_sums
                # We need to unmark the sums generated by x
                S_without_x = current_set[:idx] + current_set[idx+1:]
                S_arr = np.array(S_without_x, dtype=np.int32)
                n = len(S_arr)
                
                # Sums to unmark:
                # 3*x
                sums_to_unmark = [3*x]
                # 2*x + s_i
                if n > 0:
                    sums_to_unmark.extend((2*x + S_arr).tolist())
                # x + s_i + s_j
                if n > 0:
                    i_idx, j_idx = np.triu_indices(n)
                    sums_to_unmark.extend((x + S_arr[i_idx] + S_arr[j_idx]).tolist())
                
                # Also, if x was part of sums with other elements, those sums are still valid 
                # but we only need to unmark the sums that *became* unique to x? 
                # No, used_sums contains ALL sums from the current set.
                # When we remove x, the sums that involved x are no longer present.
                # So we unmark exactly the sums that would have been added by x to S_without_x.
                
                for s in sums_to_unmark:
                    if 0 <= s < max_sum:
                        current_used[s] = False
                        
                current_set.pop(idx)
                current_set_set.remove(x)
                current_len -= 1
                
            else: # swap
                if not current_set:
                    continue
                idx = random.randint(0, len(current_set) - 1)
                x = current_set[idx]
                
                candidates = [v for v in range(1, max_val + 1) if v not in current_set_set]
                if not candidates:
                    continue
                v = random.choice(candidates)
                
                # Try to swap x with v
                # Remove x, then try to add v
                S_without_x = current_set[:idx] + current_set[idx+1:]
                
                # Unmark sums of x in S_without_x
                S_arr = np.array(S_without_x, dtype=np.int32)
                n = len(S_arr)
                
                sums_to_unmark = [3*x]
                if n > 0:
                    sums_to_unmark.extend((2*x + S_arr).tolist())
                if n > 0:
                    i_idx, j_idx = np.triu_indices(n)
                    sums_to_unmark.extend((x + S_arr[i_idx] + S_arr[j_idx]).tolist())
                
                for s in sums_to_unmark:
                    if 0 <= s < max_sum:
                        current_used[s] = False
                        
                # Now try to add v to S_without_x
                valid, new_sums = is_valid_add(v, S_without_x, current_used)
                if valid:
                    # Accept swap
                    current_set.pop(idx)
                    current_set_set.remove(x)
                    current_set.append(v)
                    current_set_set.add(v)
                    current_used[new_sums] = True
                    # current_len stays same
                else:
                    # Reject swap, restore x
                    # We need to re-mark sums of x in S_without_x
                    for s in sums_to_unmark:
                        if 0 <= s < max_sum:
                            current_used[s] = True
                            
            # Cooling
            T *= cooling_rate
            if T < 0.1:
                break
        
        # Restart with a new random set or modified best set
        # To diversify, we can start a new restart from a slightly perturbed best set
        # Or just keep the best found so far as the starting point for the next restart
        # But to escape local optima, it's better to start fresh or from a random valid set
        # Given the time, starting from the current best is efficient if we allow 'remove' moves
        # But if we are stuck, we might need a fresh start.
        # Let's restart from a random small valid set every few iterations
        if random.random() < 0.2:
            # Generate a new random initial set
            # Pick 10-20 random numbers, sort, check validity, keep valid subset
            S_init = random.sample(range(1, max_val + 1), 20)
            S_init.sort()
            S_valid = []
            used_sums_init = np.zeros(max_sum, dtype=bool)
            for x in S_init:
                valid, new_sums = is_valid_add(x, S_valid, used_sums_init)
                if valid:
                    S_valid.append(x)
                    used_sums_init[new_sums] = True
            
            if len(S_valid) > 5: # Ensure it's not too small
                best_set, best_used = S_valid, used_sums_init
                best_len = len(best_set)
                T = 10.0 # Reset temperature

    return best_set
