"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 14

# EVOLVE-BLOCK-START
import time
import numpy as np
from scipy.optimize import differential_evolution, minimize
from scipy.spatial import ConvexHull

# ---------- Core geometry ----------

def _min_triangle_area_vec(points):
    """Vectorized minimum triangle area for N points. Returns min area (not doubled)."""
    n = len(points)
    min_area = float('inf')
    x = points[:, 0]
    y = points[:, 1]
    # We can optimize this by noting that for a convex set, the minimum area
    # triangle often involves vertices that are close in index if sorted by angle,
    # but here we just do the full O(N^3) check vectorized over the last dimension.
    # N=14 is small enough that full check is fast.
    for i in range(n):
        for j in range(i + 1, n):
            if j + 1 >= n:
                continue
            dx_ji = x[j] - x[i]
            dy_ji = y[j] - y[i]
            dx_ki = x[j+1:] - x[i]
            dy_ki = y[j+1:] - y[i]
            cross = dx_ji * dy_ki - dx_ki * dy_ji
            areas = 0.5 * np.abs(cross)
            local_min = np.min(areas)
            if local_min < min_area:
                min_area = local_min
    return min_area

def _hull_area_fast(points):
    """Compute convex hull area. Returns 0 if degenerate."""
    try:
        hull = ConvexHull(points)
        return hull.volume
    except Exception:
        return 0.0

def _score(points):
    """Minimum triangle area divided by convex hull area."""
    hull_area = _hull_area_fast(points)
    if hull_area < 1e-10:
        return 0.0
    min_area = _min_triangle_area_vec(points)
    return min_area / hull_area

def _all_triangle_areas(points):
    """Compute all triangle areas as a flat array."""
    n = len(points)
    x = points[:, 0]
    y = points[:, 1]
    areas_list = []
    for i in range(n):
        for j in range(i + 1, n):
            if j + 1 >= n:
                continue
            dx_ji = x[j] - x[i]
            dy_ji = y[j] - y[i]
            dx_ki = x[j+1:] - x[i]
            dy_ki = y[j+1:] - y[i]
            cross = dx_ji * dy_ki - dx_ki * dy_ji
            tri_areas = 0.5 * np.abs(cross)
            if len(tri_areas) > 0:
                areas_list.append(tri_areas)
    if not areas_list:
        return np.array([0.0])
    return np.concatenate(areas_list)

def _objective_hard(points_flat):
    """Minimize hull_area / min_triangle_area (scale-invariant)."""
    points = points_flat.reshape(N, 2)
    if np.any(np.isnan(points)) or np.any(np.isinf(points)):
        return 1e10
    min_area = _min_triangle_area_vec(points)
    if min_area < 1e-12:
        return 1e10
    hull_area = _hull_area_fast(points)
    if hull_area < 1e-10:
        return 1e10
    return hull_area / min_area

def _objective_soft(points_flat, beta=150.0):
    """Soft-min objective for smoother optimization."""
    points = points_flat.reshape(N, 2)
    if np.any(np.isnan(points)) or np.any(np.isinf(points)):
        return 1e10
    areas = _all_triangle_areas(points)
    if len(areas) == 0 or np.min(areas) < 1e-12:
        return 1e10
    z = -beta * areas
    max_z = np.max(z)
    if max_z < -500:
        log_sum = max_z
    else:
        log_sum = max_z + np.log(np.sum(np.exp(z - max_z)))
    soft_min_val = -log_sum / beta
    if soft_min_val < 1e-12:
        return 1e10
    hull_area = _hull_area_fast(points)
    if hull_area < 1e-10:
        return 1e10
    return hull_area / soft_min_val

def _normalize_unit_area(points):
    """Scale points so convex hull area = 1."""
    try:
        hull = ConvexHull(points)
        hull_area = hull.volume
        if hull_area > 1e-10:
            scale = np.sqrt(1.0 / hull_area)
            return points * scale
    except Exception:
        pass
    xs = points[:, 0]
    ys = points[:, 1]
    w = xs.max() - xs.min()
    h = ys.max() - ys.min()
    if w > 1e-10 and h > 1e-10:
        scale = 1.0 / np.sqrt(w * h)
        return points * scale
    return points

# ---------- Symmetry-aware objective for DE ----------

def _decode_symmetric(params):
    """
    Decode parameters representing the first N/2 points.
    The other N/2 points are generated by central symmetry: p_{i+N/2} = -p_i.
    This enforces the centroid to be at (0,0).
    """
    n_half = N // 2
    pts_half = params.reshape(n_half, 2)
    # The symmetric points are -pts_half
    pts_sym = -pts_half
    # Concatenate to form full set
    # Note: The order matters for convex hull and triangle calculation consistency,
    # but since we compute min area over ALL triples, the set of points is what matters.
    # However, to ensure a valid convex position, we should probably sort them or
    # just let the optimizer figure out the geometry.
    # For DE, the topology is flexible.
    full_pts = np.vstack([pts_half, pts_sym])
    return full_pts

def _objective_symmetric(params):
    """
    Objective function for Differential Evolution.
    Input: flat array of length N (N/2 points * 2 coords).
    Output: hull_area / min_triangle_area (to be minimized).
    """
    points = _decode_symmetric(params)
    if np.any(np.isnan(points)) or np.any(np.isinf(points)):
        return 1e10
    
    # Check for degeneracy (points too close)
    # We can check if hull area is small
    hull_area = _hull_area_fast(points)
    if hull_area < 1e-8:
        return 1e10
        
    min_area = _min_triangle_area_vec(points)
    if min_area < 1e-12:
        return 1e10
        
    return hull_area / min_area

# ---------- Optimizers ----------

def _nm(x0, deadline, max_iter=3000, obj_func=None):
    """Run Nelder-Mead from x0."""
    if obj_func is None:
        obj_func = _objective_hard
    remaining = deadline - time.time()
    if remaining < 2.0:
        return None
    try:
        res = minimize(
            obj_func, x0, method='Nelder-Mead',
            options={'maxiter': max_iter, 'xatol': 1e-9, 'fatol': 1e-11, 'adaptive': True}
        )
        return res.x
    except Exception:
        return None

def _powell(x0, deadline, max_iter=1000, obj_func=None):
    """Run Powell from x0."""
    if obj_func is None:
        obj_func = _objective_hard
    remaining = deadline - time.time()
    if remaining < 3.0:
        return None
    try:
        res = minimize(
            obj_func, x0, method='Powell',
            options={'maxiter': max_iter, 'xtol': 1e-11, 'ftol': 1e-13}
        )
        return res.x
    except Exception:
        return None

def _coordinate_descent(pts, deadline, max_rounds=30):
    """Cyclic coordinate descent on the hard score (maximize min_tri/hull)."""
    pts = pts.copy()
    n = len(pts)
    step0 = 0.05
    for rnd in range(max_rounds):
        if time.time() > deadline - 8:
            break
        improved = False
        for i in range(n):
            if time.time() > deadline - 8:
                break
            for coord in range(2):
                orig = pts[i, coord]
                step = step0
                for _ in range(25):
                    pts[i, coord] = orig + step
                    s_plus = _score(pts)
                    pts[i, coord] = orig - step
                    s_minus = _score(pts)
                    pts[i, coord] = orig
                    if s_plus > s_minus:
                        pts[i, coord] = orig + step
                    elif s_minus > s_plus:
                        pts[i, coord] = orig - step
                    else:
                        break
                    improved = True
                    step *= 0.5
                    if step < 1e-9:
                        break
        if not improved:
            break
    return pts

def construct():
    """
    Generate 14 points in a planar convex region normalized to unit area
    to maximize the minimum area over all triples.
    """
    start_time = time.time()
    # Evaluator kills at 150s. We target finishing by 145s to be safe.
    deadline = start_time + 145.0

    best_x = None
    best_obj = float('inf')
    
    n_half = N // 2
    
    # --- Phase 1: Differential Evolution on Symmetric Space ---
    # The search space is 14D (7 points * 2 coords).
    # Bounds: We can restrict to a square [-2, 2] x [-2, 2] for the half-points.
    # Since we normalize later, scale doesn't matter for the ratio, but helps DE converge.
    bounds = [(-2, 2)] * (n_half * 2)
    
    # Use multiple DE runs with different random seeds/strategies if time permits,
    # but one robust run is usually best.
    
    try:
        # maxiter is in generations. popsize=10 means 10*14=140 evals per gen.
        # Let's aim for ~500-1000 generations if possible, but cap by time.
        # DE is stochastic, so we check time inside the callback.
        
        def de_callback(xk, convergence):
            if time.time() > deadline - 10.0:
                raise Exception("Time limit reached for DE")

        res_de = differential_evolution(
            _objective_symmetric,
            bounds,
            maxiter=500,
            popsize=15,
            tol=1e-6,
            mutation=(0.5, 1.0),
            recombination=0.7,
            seed=42,
            callback=de_callback,
            polish=True  # This runs L-BFGS-B at the end, which is good
        )
        
        if res_de.success or res_de.x is not None:
            # res_de.x is the symmetric parameters (length 14)
            sym_params = res_de.x
            full_points = _decode_symmetric(sym_params)
            
            # Evaluate hard objective
            obj_val = _objective_hard(full_points.flatten())
            if obj_val < best_obj:
                best_obj = obj_val
                best_x = full_points.flatten()
                
    except Exception as e:
        # If DE failed or timed out, we might have a partial result?
        # DifferentialEvolution doesn't easily return partial best on exception.
        # We rely on the other phases or a fallback.
        pass

    # --- Phase 2: Local Optimization from Best DE Result ---
    if best_x is not None and time.time() < deadline - 20:
        # Polish with Powell on the full 28D space starting from the symmetric solution
        # This allows breaking symmetry slightly if it helps (though symmetry is usually optimal)
        res_powell = _powell(best_x, deadline, max_iter=2000)
        if res_powell is not None:
            obj_val = _objective_hard(res_powell)
            if obj_val < best_obj:
                best_obj = obj_val
                best_x = res_powell.copy()

    # --- Phase 3: Coordinate Descent Refinement ---
    if best_x is not None and time.time() < deadline - 10:
        pts_cd = best_x.reshape(N, 2)
        pts_cd = _coordinate_descent(pts_cd, deadline)
        obj_val = _objective_hard(pts_cd.flatten())
        if obj_val < best_obj:
            best_obj = obj_val
            best_x = pts_cd.flatten()

    # --- Phase 4: Fallback / Diverse Starts if DE failed or score is poor ---
    # If DE didn't find a good solution (e.g. score < 40), try standard random starts + NM.
    # But DE usually finds > 50.
    
    if best_x is None or best_obj > 50.0:
         # Fallback: Regular polygon + NM
         angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
         reg_points = np.column_stack([np.cos(angles), np.sin(angles)])
         x0 = reg_points.flatten()
         
         res_nm = _nm(x0, deadline, max_iter=2000)
         if res_nm is not None:
             obj_val = _objective_hard(res_nm)
             if obj_val < best_obj:
                 best_obj = obj_val
                 best_x = res_nm.copy()
                 
         if best_x is None:
             best_x = x0

    # --- Phase 5: Final Polish ---
    if best_x is not None and time.time() < deadline - 5:
         res_final_nm = _nm(best_x, deadline, max_iter=1000)
         if res_final_nm is not None:
             obj_val = _objective_hard(res_final_nm)
             if obj_val < best_obj:
                 best_obj = obj_val
                 best_x = res_final_nm.copy()

    # --- Finalization ---
    if best_x is None:
        # Ultimate fallback: Regular 14-gon
        angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
        best_x = np.column_stack([np.cos(angles), np.sin(angles)]).flatten()

    final_points = best_x.reshape(N, 2)
    final_points = _normalize_unit_area(final_points)

    # Safety check
    try:
        hull = ConvexHull(final_points)
        if hull.volume < 1e-10:
            angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
            reg_points = np.column_stack([np.cos(angles), np.sin(angles)])
            final_points = _normalize_unit_area(reg_points)
    except Exception:
        angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
        reg_points = np.column_stack([np.cos(angles), np.sin(angles)])
        final_points = _normalize_unit_area(reg_points)

    return final_points
