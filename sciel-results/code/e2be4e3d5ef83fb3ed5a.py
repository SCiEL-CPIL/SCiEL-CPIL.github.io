import numpy as np

def _construct_2x2x3_rank11():
    U = np.zeros((4, 11))
    V = np.zeros((6, 11))
    W = np.zeros((6, 11))
    
    # Strassen terms
    # M1: (a+d)(e+h) -> C00 + C11
    U[:, 0] = [1, 0, 0, 1]
    V[:, 0] = [1, 0, 0, 1, 0, 0]
    W[:, 0] = [1, 0, 0, 1, 0, 0]
    
    # M2: (c+d)e -> C10 - C11
    U[:, 1] = [0, 0, 1, 1]
    V[:, 1] = [1, 0, 0, 0, 0, 0]
    W[:, 1] = [0, 0, 1, -1, 0, 0]
    
    # M3: a(f-h) -> C01
    U[:, 2] = [1, 0, 0, 0]
    V[:, 2] = [0, 1, 0, -1, 0, 0]
    W[:, 2] = [0, 1, 0, 0, 0, 0]
    
    # M4: d(g-e) -> -C00 + C11
    U[:, 3] = [0, 0, 0, 1]
    V[:, 3] = [0, 0, 1, -1, 0, 0]
    W[:, 3] = [-1, 0, 0, 1, 0, 0]
    
    # M5: (a+b)h -> C00
    U[:, 4] = [1, 1, 0, 0]
    V[:, 4] = [0, 0, 0, 1, 0, 0]
    W[:, 4] = [1, 0, 0, 0, 0, 0]
    
    # M6: (c-a)(e+f) -> C10 + C11
    U[:, 5] = [0, 0, 1, -1]
    V[:, 5] = [1, 1, 0, 0, 0, 0]
    W[:, 5] = [0, 0, 1, 1, 0, 0]
    
    # M7: (b-d)(g+h) -> -C00 + C01
    U[:, 6] = [0, 1, 0, -1]
    V[:, 6] = [0, 0, 1, 1, 0, 0]
    W[:, 6] = [-1, 1, 0, 0, 0, 0]
    
    # Schoolbook for col 2
    # a*x -> C02
    U[:, 7] = [1, 0, 0, 0]
    V[:, 7] = [0, 0, 0, 0, 1, 0]
    W[:, 7] = [0, 0, 0, 0, 1, 0]
    
    # b*y -> C02
    U[:, 8] = [0, 1, 0, 0]
    V[:, 8] = [0, 0, 0, 0, 0, 1]
    W[:, 8] = [0, 0, 0, 0, 1, 0]
    
    # c*x -> C12
    U[:, 9] = [0, 0, 1, 0]
    V[:, 9] = [0, 0, 0, 0, 1, 0]
    W[:, 9] = [0, 0, 0, 0, 0, 1]
    
    # d*y -> C12
    U[:, 10] = [0, 0, 0, 1]
    V[:, 10] = [0, 0, 0, 0, 0, 1]
    W[:, 10] = [0, 0, 0, 0, 0, 1]
    
    return U, V, W
