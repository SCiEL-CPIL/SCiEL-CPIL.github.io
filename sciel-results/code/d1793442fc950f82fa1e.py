import numpy as np
import time
from autoresearch_suite.chem_clusters import relax, dzugutov_energy_gradient

_START_TIME = time.time()
_TOTAL_BUDGET = 290.0  # Safety margin below 300s (evaluator kills at 330s, task says 300s)


def _remaining_time():
    return _TOTAL_BUDGET - (time.time() - _START_TIME)


def _icosahedron_vertices(scale=1.0):
    phi = (1.0 + np.sqrt(5.0)) / 2.0
    v = np.array([
        [0.0, 1.0, phi], [0.0, -1.0, phi], [0.0, 1.0, -phi], [0.0, -1.0, -phi],
        [1.0, phi, 0.0], [-1.0, phi, 0.0], [1.0, -phi, 0.0], [-1.0, -phi, 0.0],
        [phi, 0.0, 1.0], [phi, 0.0, -1.0], [-phi, 0.0, 1.0], [-phi, 0.0, -1.0],
    ], dtype=float)
    # Normalize to unit sphere then scale
    norms = np.linalg.norm(v, axis=1, keepdims=True)
    v = v / norms * scale
    return v


def _mackay_icosahedron_55(spacing=1.0):
    """
    Generate a 55-atom Mackay Icosahedron.
    Structure: 1 center + 12 first shell + 42 second shell.
    """
    pts = [np.zeros(3)]
    
    # Shell 1: 12 atoms at radius ~ spacing * 1.0 (relative to center)
    # In Mackay icosahedra, the distance to the first shell vertices is often set by the nearest neighbor distance.
    # Let's define spacing as the distance to the first shell.
    shell1 = _icosahedron_vertices(scale=spacing)
    pts.extend([p for p in shell1])
    
    # Shell 2: 42 atoms.
    # The 42 atoms are located at:
    # - 12 at the vertices of a larger icosahedron (radius ~ spacing * 1.618? No, that's not right for Mackay)
    # - 30 at the face centers of the larger icosahedron?
    # Actually, the 42 atoms in the second shell of a Mackay icosahedron are:
    # 12 atoms at the vertices of an icosahedron of radius R2.
    # 30 atoms at the centers of the faces of that icosahedron? No, that would be 12+20=32.
    # The 42 atoms are: 12 at the vertices of an icosahedron, and 30 at the edge midpoints?
    # Let's use the known coordinates or construct them.
    # A simpler way: The 55-atom icosahedron is a subset of the 147-atom one.
    # Or we can construct the 42-atom shell as:
    # 12 atoms at the icosahedron vertices at radius R2.
    # 30 atoms at the midpoints of the edges of the icosahedron defined by R2?
    # No, the 42 atoms are: 12 vertices + 30 face centers? No, icosahedron has 20 faces.
    # The 42 atoms are: 12 vertices + 30 edge midpoints? 12+30=42.
    # Let's check the radius.
    # If R1 = 1.0, the edge length of the first icosahedron is a = R1 * sqrt(2 + 2/phi) ?
    # Let's just use the standard Mackay construction.
    # The second shell atoms are at the vertices of a larger icosahedron (12) and the centers of the faces of the *first* icosahedron? No.
    
    # Let's use a robust method: 
    # The 42 atoms are the vertices of a "Mackay" second shell.
    # They can be generated by taking the 12 icosahedron vertices and 30 edge midpoints of an icosahedron with radius R2.
    # What is R2?
    # In a close-packed icosahedron, the ratio R2/R1 is often ~ 1.618 (phi) or similar.
    # Let's try R2 = spacing * 1.618.
    
    # 12 vertices
    shell2_verts = _icosahedron_vertices(scale=spacing * 1.618)
    pts.extend([p for p in shell2_verts])
    
    # 30 edge midpoints
    # We need the edges of the icosahedron.
    # An icosahedron has 30 edges.
    # We can find them by checking distances between shell2_verts.
    # The nearest neighbors in an icosahedron shell are at a specific distance.
    # Let's compute the distance between the first two vertices.
    d_edge = np.linalg.norm(shell2_verts[0] - shell2_verts[1])
    # Find all pairs with distance approx d_edge
    midpoints = []
    for i in range(12):
        for j in range(i+1, 12):
            d = np.linalg.norm(shell2_verts[i] - shell2_verts[j])
            if np.isclose(d, d_edge, rtol=1e-3):
                mid = (shell2_verts[i] + shell2_verts[j]) / 2.0
                midpoints.append(mid)
                
    # There should be 30 midpoints
    if len(midpoints) == 30:
        pts.extend(midpoints)
    else:
        # Fallback: add random points if construction fails
        # But it shouldn't fail.
        pass
        
    pts = np.array(pts, dtype=float)
    return pts


def _make_seed(n, spacing=1.0, rng=None):
    """
    Generate a seed for n atoms.
    For n=55, use Mackay icosahedron.
    For n<55, remove atoms from the outer shell of the 55-atom structure.
    For n>55, add atoms to the 55-atom structure.
    """
    if rng is None:
        rng = np.random.default_rng(0)
        
    if n == 55:
        return _mackay_icosahedron_55(spacing)
    
    if n < 55:
        # Start with 55 atoms
        pts = _mackay_icosahedron_55(spacing)
        # Identify outer shell atoms (indices 13 to 54)
        outer_indices = np.arange(13, 55)
        # Randomly select 55-n atoms to remove
        num_remove = 55 - n
        to_remove = rng.choice(outer_indices, size=num_remove, replace=False)
        keep_mask = np.ones(55, dtype=bool)
        keep_mask[to_remove] = False
        return pts[keep_mask]
        
    if n > 55:
        # Start with 55 atoms
        pts = _mackay_icosahedron_55(spacing)
        num_add = n - 55
        new_pts = []
        # Add atoms at random positions near the surface
        # Surface radius is approx spacing * 1.618
        for _ in range(num_add):
            # Pick a random direction
            dir = rng.normal(0, 1, 3)
            dir = dir / np.linalg.norm(dir)
            # Pick a random radius slightly larger than the shell
            r = spacing * 1.618 * (1.0 + rng.uniform(0.1, 0.3))
            p = dir * r
            new_pts.append(p)
        pts = np.vstack([pts, np.array(new_pts)])
        return pts

    # Fallback for other n (should not happen for this task)
    # Generate random compact cluster
    radius = spacing * n ** (1.0/3.0)
    pts = []
    for _ in range(n):
        p = rng.uniform(-radius, radius, 3)
        pts.append(p)
    return np.array(pts)


def construct(instance):
    size = instance["n"]
    potential = instance["potential"]
    parameter = instance.get("rho", instance.get("kind"))

    remaining = _remaining_time()
    # Allocate time for this instance, leaving some buffer for others
    # There are 6 instances. We can't know the order, so we assume equal distribution.
    # However, the function is called sequentially.
    # Let's use a fraction of the remaining time.
    instance_budget = remaining * 0.9  # Use 90% of remaining time for this instance? 
    # No, that's greedy. If this is the first instance, we use 90% of 290s = 261s.
    # Then the next has 29s left. That's bad.
    
    # Better: Estimate time per instance.
    # Total budget 290s. 6 instances. ~48s per instance.
    # Let's cap the instance budget at 45s.
    instance_budget = min(45.0, remaining - 10.0)
    if instance_budget < 5.0:
        instance_budget = max(5.0, remaining * 0.1)

    t0 = time.time()
    best_energy = np.inf
    best_positions = None
    
    # Generate multiple diverse seeds
    # We want seeds that are close to icosahedral symmetry.
    # Vary the spacing slightly to explore different local minima.
    spacings = [0.95, 1.0, 1.05, 1.1]
    
    seeds = []
    for sp in spacings:
        for _ in range(2): # 2 seeds per spacing
            rng = np.random.default_rng(np.random.randint(0, 10000))
            seed = _make_seed(size, spacing=sp, rng=rng)
            seeds.append(seed)
            
    # Basin Hopping
    # We will iterate through the seeds, relax them, and then perform a few BH steps from the best.
    
    current_best_energy = np.inf
    current_best_pos = None
    
    for seed in seeds:
        if (time.time() - t0) > instance_budget:
            break
            
        try:
            # Relax the seed
            energy, positions = relax(seed, potential, parameter)
        except Exception:
            continue
            
        if energy < current_best_energy:
            current_best_energy = energy
            current_best_pos = positions
            
        # Check time
        if (time.time() - t0) > instance_budget * 0.8:
            break

    if current_best_pos is None:
        # Fallback: return a random relaxed seed
        seed = _make_seed(size, spacing=1.0, rng=np.random.default_rng(1))
        try:
            _, current_best_pos = relax(seed, potential, parameter)
        except Exception:
            current_best_pos = _make_seed(size, spacing=1.0, rng=np.random.default_rng(1))
        return current_best_pos

    # Now perform Basin Hopping from the best solution found
    # This helps escape local minima.
    bh_rng = np.random.default_rng(size + 100)
    current_energy = current_best_energy
    current_pos = current_best_pos
    best_energy = current_best_energy
    best_pos = current_best_pos
    
    # Temperature for Metropolis (if we used it, but we'll just do greedy + random restarts)
    # Let's do a simple loop:
    # 1. Perturb current_pos
    # 2. Relax
    # 3. If better than best, update best.
    # 4. If better than current, update current.
    
    while (time.time() - t0) < instance_budget:
        # Perturb
        # Scale of perturbation: 0.1 to 0.3
        scale = 0.15
        perturbed = current_pos + bh_rng.normal(0, scale, current_pos.shape)
        
        try:
            energy, positions = relax(perturbed, potential, parameter)
        except Exception:
            continue
            
        if energy < best_energy:
            best_energy = energy
            best_pos = positions
            current_energy = energy
            current_pos = positions
        elif energy < current_energy:
            # Accept if it improves the current state (greedy)
            current_energy = energy
            current_pos = positions
        else:
            # With some probability, accept worse solutions to escape local minima (Simulated Annealing style)
            # But we don't have a temperature schedule easily. 
            # Let's just do greedy for simplicity and speed.
            # If we want to be more robust, we can accept worse solutions with prob exp(-(E_new-E_old)/T).
            # Let's try a simple Metropolis step.
            T = 0.1
            if bh_rng.random() < np.exp(-(energy - current_energy) / T):
                current_energy = energy
                current_pos = positions

    return best_pos
