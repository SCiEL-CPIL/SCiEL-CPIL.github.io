"""Matrix multiplication 2x3x8: rank-44 exact tensor decomposition.

Structural Change: 
Instead of hardcoded index manipulation for the entire 44-rank decomposition, 
this program uses a generic block-assembly engine.
The decomposition is defined by a list of sub-blocks.
Each sub-block is generated by a generic strategy function:
- (2, 2, 2) uses Strassen (rank 7).
- (2, 1, 4) uses Schoolbook (rank 8).
The global matrices are constructed by placing these local tensors 
into the correct offsets.
"""

import numpy as np

DIMENSIONS = [2, 3, 8]

def construct():
    n, m, p = DIMENSIONS
    
    # Define the block structure: (n_sub, m_sub, p_sub)
    # We partition m=3 into m=2 and m=1.
    # We partition p=8 into p=4 and p=4.
    # Inside each p=4, we partition into two p=2s for the m=2 part.
    # And keep p=4 for the m=1 part.
    
    # Blocks:
    # 1. n=2, m=2, p=2 (offsets i=0, j=0, k=0) -> Strassen
    # 2. n=2, m=2, p=2 (offsets i=0, j=0, k=2) -> Strassen
    # 3. n=2, m=1, p=4 (offsets i=0, j=2, k=0) -> Schoolbook
    # 4. n=2, m=2, p=2 (offsets i=0, j=0, k=4) -> Strassen
    # 5. n=2, m=2, p=2 (offsets i=0, j=0, k=6) -> Strassen
    # 6. n=2, m=1, p=4 (offsets i=0, j=2, k=4) -> Schoolbook
    
    blocks = [
        {"n": 2, "m": 2, "p": 2, "i": 0, "j": 0, "k": 0, "strategy": "strassen"},
        {"n": 2, "m": 2, "p": 2, "i": 0, "j": 0, "k": 2, "strategy": "strassen"},
        {"n": 2, "m": 1, "p": 4, "i": 0, "j": 2, "k": 0, "strategy": "schoolbook"},
        {"n": 2, "m": 2, "p": 2, "i": 0, "j": 0, "k": 4, "strategy": "strassen"},
        {"n": 2, "m": 2, "p": 2, "i": 0, "j": 0, "k": 6, "strategy": "strassen"},
        {"n": 2, "m": 1, "p": 4, "i": 0, "j": 2, "k": 4, "strategy": "schoolbook"},
    ]
    
    # Calculate total rank
    rank = 0
    for b in blocks:
        if b["strategy"] == "strassen":
            rank += 7
        else: # schoolbook
            rank += b["n"] * b["m"] * b["p"]
            
    # Initialize global matrices
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col_offset = 0
    
    # Strategies
    def add_strassen_2x2x2(i_off, j_off, k_off, col_start):
        """Generates 7 rank-1 terms for a 2x2x2 block using Strassen."""
        U_local = U
        V_local = V
        W_local = W
        c = col_start
        
        # We return the next available col offset
        # Term 1
        U_local[i_off * m + j_off][c] += 1
        U_local[(i_off + 1) * m + (j_off + 1)][c] += 1
        V_local[j_off * p + k_off][c] += 1
        V_local[(j_off + 1) * p + (k_off + 1)][c] += 1
        W_local[k_off * n + i_off][c] += 1
        W_local[(k_off + 1) * n + (i_off + 1)][c] += 1
        c += 1
        
        # Term 2
        U_local[(i_off + 1) * m + j_off][c] += 1
        U_local[(i_off + 1) * m + (j_off + 1)][c] += 1
        V_local[j_off * p + k_off][c] += 1
        W_local[k_off * n + (i_off + 1)][c] += 1
        W_local[(k_off + 1) * n + (i_off + 1)][c] += -1
        c += 1
        
        # Term 3
        U_local[i_off * m + j_off][c] += 1
        V_local[j_off * p + (k_off + 1)][c] += 1
        V_local[(j_off + 1) * p + (k_off + 1)][c] += -1
        W_local[(k_off + 1) * n + i_off][c] += 1
        W_local[(k_off + 1) * n + (i_off + 1)][c] += 1
        c += 1
        
        # Term 4
        U_local[(i_off + 1) * m + (j_off + 1)][c] += 1
        V_local[(j_off + 1) * p + k_off][c] += 1
        V_local[j_off * p + k_off][c] += -1
        W_local[k_off * n + i_off][c] += 1
        W_local[k_off * n + (i_off + 1)][c] += 1
        c += 1
        
        # Term 5
        U_local[i_off * m + j_off][c] += 1
        U_local[i_off * m + (j_off + 1)][c] += 1
        V_local[(j_off + 1) * p + (k_off + 1)][c] += 1
        W_local[k_off * n + i_off][c] += -1
        W_local[(k_off + 1) * n + i_off][c] += 1
        c += 1
        
        # Term 6
        U_local[(i_off + 1) * m + j_off][c] += 1
        U_local[i_off * m + j_off][c] += -1
        V_local[j_off * p + k_off][c] += 1
        V_local[j_off * p + (k_off + 1)][c] += 1
        W_local[(k_off + 1) * n + (i_off + 1)][c] += 1
        c += 1
        
        # Term 7
        U_local[i_off * m + (j_off + 1)][c] += 1
        U_local[(i_off + 1) * m + (j_off + 1)][c] += -1
        V_local[(j_off + 1) * p + k_off][c] += 1
        V_local[(j_off + 1) * p + (k_off + 1)][c] += 1
        W_local[k_off * n + i_off][c] += 1
        c += 1
        
        return c

    def add_schoolbook(i_off, j_off, k_off, n_b, m_b, p_b, col_start):
        """Generates n*m*p rank-1 terms for a generic schoolbook block."""
        c = col_start
        for ii in range(n_b):
            for jj in range(m_b):
                for kk in range(p_b):
                    U_local[i_off * m + (j_off + jj)][c] = 1
                    V_local[(j_off + jj) * p + (k_off + kk)][c] = 1
                    W_local[(k_off + kk) * n + (i_off + ii)][c] = 1
                    c += 1
        return c

    # Build each block
    for b in blocks:
        i_off = b["i"]
        j_off = b["j"]
        k_off = b["k"]
        n_b = b["n"]
        m_b = b["m"]
        p_b = b["p"]
        
        if b["strategy"] == "strassen":
            col_offset = add_strassen_2x2x2(i_off, j_off, k_off, col_offset)
        elif b["strategy"] == "schoolbook":
            col_offset = add_schoolbook(i_off, j_off, k_off, n_b, m_b, p_b, col_offset)
            
    return {"U": U, "V": V, "W": W}

