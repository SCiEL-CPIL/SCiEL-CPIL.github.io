def _row_diffs(row):
    """Return list of all positive differences within a row (i<j)."""
    n = len(row)
    diffs = []
    for i in range(n):
        ri = row[i]
        for j in range(i + 1, n):
            diffs.append(row[j] - ri)
    return diffs

def _is_valid(rows):
    """Check all positive differences are globally distinct."""
    all_diffs = []
    for row in rows:
        all_diffs.extend(_row_diffs(row))
    return len(all_diffs) == len(set(all_diffs))

def _scope(rows):
    return max(r[-1] for r in rows)

def construct(n_rows, k):
    """
    Construct n_rows rows of k+1 increasing integers starting at 0
    such that all positive differences within rows are distinct globally.
    Minimize the largest entry (scope).
    
    Strategy: CSP Backtracking with Forward Checking.
    We search for the smallest M such that a valid set of rows exists with max entry <= M.
    """
    start_time = time.time()
    DEADLINE = start_time + 145.0  # Safety margin for 150s limit
    
    num_elements = k + 1
    # Number of differences per row
    diffs_per_row = num_elements * (num_elements - 1) // 2
    total_diffs_needed = n_rows * diffs_per_row
    
    # Theoretical lower bound:
    # All differences must be distinct and <= M.
    # Max possible distinct differences in [1, M] is M.
    # So M >= total_diffs_needed.
    # However, differences are generated by elements in [0, M].
    # A tighter bound: The largest difference in a row is <= M.
    # The set of all differences must be a subset of {1, ..., M}.
    # Thus M >= total_diffs_needed.
    
    lower_bound = total_diffs_needed
    # For (7, 5): n_rows=7, k=5 -> num_elements=6.
    # diffs_per_row = 15. total = 105.
    # Known best is 112.
    
    # Upper bound estimate:
    # Start with a reasonable guess. If we can't find a solution, increase M.
    # A simple construction might give a higher bound, but let's start near LB.
    current_M = lower_bound
    
    # We will iterate M upwards until we find a solution or hit deadline.
    # To be efficient, we can jump M by 1 or 2.
    
    # Pre-compute valid rows for a given M? No, M changes.
    # Instead, use a backtracker that takes M as a parameter.
    
    def solve_csp(M):
        """
        Try to construct n_rows rows with max element <= M.
        Uses backtracking with forward checking.
        """
        used_diffs = set()
        rows = []
        
        # To speed up, we can pre-filter potential rows? 
        # There are C(M, k) potential rows. For M=105, k=5, that's ~10^9. Too many.
        # So we must generate rows on the fly during backtracking.
        
        # Heuristic: 
        # 1. Try to place rows that use "small" differences first? Or "large"?
        # 2. Actually, since we want to minimize M, and we are fixing M, 
        #    we just need ANY valid set.
        # 3. Symmetry breaking: The first row must start with 0. 
        #    We can enforce that the smallest non-zero element in the first row is 1?
        #    Not necessarily, but it often helps.
        #    Let's enforce: The set of all elements across all rows must include 0.
        #    Actually, each row starts with 0.
        
        # Recursive helper
        # State: current_row_idx, current_elements_in_row, used_diffs, rows
        # To avoid deep recursion overhead in Python, we might use a stack or optimize.
        # But for n_rows=7, depth is 7*6=42. Recursion is fine.
        
        # Optimization: 
        # If we run out of time, return None.
        
        def backtrack(row_idx, elem_idx, current_row, used_diffs, rows):
            if time.time() > DEADLINE - 2:
                return False
            
            if row_idx == n_rows:
                # All rows constructed
                return True
            
            if elem_idx == num_elements:
                # Row complete
                # Check if this row is valid (internal diffs distinct)
                # We checked during construction, so it should be valid internally.
                # But we need to ensure no conflict with used_diffs.
                # We checked that during construction too.
                # So just proceed to next row.
                rows.append(current_row)
                # Symmetry breaking: 
                # The first row can be assumed to have the smallest possible second element?
                # Or we can just let it be.
                
                # Forward Checking:
                # Do we have enough room for remaining rows?
                # Remaining rows need (n_rows - row_idx - 1) * diffs_per_row diffs.
                # Available diffs are those in [1, M] not in used_diffs.
                # This check is expensive to do exactly.
                # Simple check: len(used_diffs) + (n_rows - row_idx - 1) * diffs_per_row <= M
                # If this fails, prune.
                if len(used_diffs) + (n_rows - row_idx - 1) * diffs_per_row > M:
                    rows.pop()
                    return False
                
                if backtrack(row_idx + 1, 0, [0], used_diffs, rows):
                    return True
                
                rows.pop()
                return False
            
            # Determine next element
            # If elem_idx == 0, next is 0
            # If elem_idx > 0, next is > current_row[-1] and <= M
            
            if elem_idx == 0:
                next_val = 0
                # Recurse
                if backtrack(row_idx, 1, current_row + [next_val], used_diffs, rows):
                    return True
                return False
            
            prev_val = current_row[-1]
            # Next value must be in (prev_val, M]
            # To reduce branching, we can iterate candidates.
            # Which candidates first?
            # Smallest first tends to keep the row "tight", potentially leaving larger gaps for other rows?
            # Or largest first?
            # Let's try smallest first, but with a randomization factor to escape local traps.
            
            # Heuristic: 
            # Calculate new diffs if we pick x.
            # new_diffs = {x - y for y in current_row}
            # If any in used_diffs, skip.
            
            # To avoid checking every x from prev_val+1 to M, we can be smarter?
            # Not really, the constraint is hard.
            
            # Randomization: 
            # Instead of strictly increasing x, we can shuffle the candidate range 
            # or pick a random subset to explore first.
            # For determinism in finding a solution, we stick to increasing, 
            # but we can restart with different random seeds if this fails.
            
            # Let's use a "diverse" search: 
            # Pick candidates in a random order? 
            # If we pick random order, we might find a solution faster on average?
            # Or we might waste time.
            # Given the tight bound, systematic search with good pruning is better.
            
            # Pruning: 
            # If we pick x, the new diffs are x - y for y in current_row.
            # These must be distinct from each other (guaranteed if x > prev_val and current_row is increasing? 
            # No, x-y1 and x-y2 are distinct if y1!=y2. Yes.)
            # And they must not be in used_diffs.
            
            # Additional Pruning: 
            # The remaining elements in this row must be > x.
            # The maximum possible difference in this row will be at most M - 0 = M.
            
            # Let's iterate x from prev_val + 1 to M.
            # To speed up, we can break early if we can't fit the remaining elements?
            # Remaining elements count: rem_elems = num_elements - elem_idx - 1
            # We need rem_elems distinct integers in (x, M].
            # So M - x >= rem_elems.
            # x <= M - rem_elems.
            
            max_x = M - (num_elements - elem_idx - 1)
            
            for x in range(prev_val + 1, max_x + 1):
                # Check conflicts
                new_diffs = []
                conflict = False
                for y in current_row:
                    d = x - y
                    if d in used_diffs:
                        conflict = True
                        break
                    new_diffs.append(d)
                
                if conflict:
                    continue
                
                # Also check if new_diffs have internal conflicts?
                # Since current_row is strictly increasing, x-y is strictly decreasing as y increases.
                # So new_diffs are distinct.
                
                # Try this x
                new_used_diffs = used_diffs.union(new_diffs)
                
                # Heuristic: 
                # If this is the first row, we can enforce some symmetry breaking.
                # e.g., the first row's second element must be the minimum possible?
                # Let's not over-constrain.
                
                if backtrack(row_idx, elem_idx + 1, current_row + [x], new_used_diffs, rows):
                    return True
            
            return False
        
        # Start backtracking
        # Symmetry breaking for the very first row:
        # The first element is 0.
        # The second element of the first row can be assumed to be 1?
        # Not necessarily. But if we have a solution where the first row is [0, 2, ...], 
        # and 1 is not used in any difference, we could potentially shift?
        # Actually, if 1 is not a difference in any row, it's "wasted".
        # But 1 might be a difference in another row.
        
        # Let's just start with [0] and let the backtracker pick the next.
        # To speed up, we can try to place the "hardest" rows first?
        # All rows are symmetric in terms of constraints, only the specific values matter.
        
        # One optimization: 
        # If we fail to find a solution for M, we return None.
        
        # To handle the "randomness" and avoid getting stuck in one branch,
        # we can randomize the order of x candidates slightly?
        # No, for a CSP with a unique or few solutions, systematic is safer.
        # But if the search space is huge, we might time out.
        
        # Let's add a node limit per M?
        # No, just rely on the global deadline.
        
        return backtrack(0, 0, [], set(), [])

    # Main loop: increase M
    # Start from lower bound
    # If (7,5), LB=105.
    # We know 112 works.
    # We will try 105, 106, ...
    
    # Optimization: 
    # If M is very small, it fails fast.
    # We can jump M if we fail? 
    # No, the solution might exist at M=105.
    
    # However, backtracking on M=105 might take a long time if no solution exists.
    # We should limit the time spent on a single M.
    
    time_per_M = 5.0 # seconds
    last_M = lower_bound
    
    while current_M <= 200: # Hard cap
        if time.time() > DEADLINE - 10:
            break
            
        start_M_time = time.time()
        
        # Try to solve for this M
        # We use a fresh state for each M
        # Note: The backtrack function uses the global DEADLINE.
        # We should probably make it aware of a local limit?
        # Or just let it run. If it takes too long, it will hit the global deadline.
        # But if M=105 is impossible, it might waste all time.
        # Better to have a local limit.
        
        def solve_with_limit(M, time_limit):
            # Re-define or wrap to check time limit
            # Python closures can be tricky with mutable state for time.
            # Let's just use the global deadline for now, but add a counter.
            
            nodes_visited = 0
            MAX_NODES = 500000 # Arbitrary limit per M
            
            def backtrack_limited(row_idx, elem_idx, current_row, used_diffs, rows):
                nonlocal nodes_visited
                if time.time() > time_limit or nodes_visited > MAX_NODES:
                    return False
                
                nodes_visited += 1
                
                if row_idx == n_rows:
                    return True
                
                if elem_idx == num_elements:
                    rows.append(current_row)
                    if len(used_diffs) + (n_rows - row_idx - 1) * diffs_per_row > M:
                        rows.pop()
                        return False
                    
                    if backtrack_limited(row_idx + 1, 0, [0], used_diffs, rows):
                        return True
                    rows.pop()
                    return False
                
                if elem_idx == 0:
                    if backtrack_limited(row_idx, 1, current_row + [0], used_diffs, rows):
                        return True
                    return False
                
                prev_val = current_row[-1]
                max_x = M - (num_elements - elem_idx - 1)
                
                for x in range(prev_val + 1, max_x + 1):
                    new_diffs = []
                    conflict = False
                    for y in current_row:
                        d = x - y
                        if d in used_diffs:
                            conflict = True
                            break
                        new_diffs.append(d)
                    
                    if conflict:
                        continue
                    
                    new_used_diffs = used_diffs.union(new_diffs)
                    
                    if backtrack_limited(row_idx, elem_idx + 1, current_row + [x], new_used_diffs, rows):
                        return True
                
                return False
            
            return backtrack_limited(0, 0, [], set(), [])

        # Execute
        # We need to capture the result. 
        # The function above returns True/False. We need the rows.
        # Let's modify to return rows.
        
        def solve_and_return(M, time_limit):
            nodes_visited = 0
            MAX_NODES = 500000
            
            def backtrack_limited(row_idx, elem_idx, current_row, used_diffs, rows):
                nonlocal nodes_visited
                if time.time() > time_limit or nodes_visited > MAX_NODES:
                    return None
                
                nodes_visited += 1
                
                if row_idx == n_rows:
                    return rows
                
                if elem_idx == num_elements:
                    rows.append(current_row)
                    if len(used_diffs) + (n_rows - row_idx - 1) * diffs_per_row > M:
                        rows.pop()
                        return None
                    
                    res = backtrack_limited(row_idx + 1, 0, [0], used_diffs, rows)
                    if res:
                        return res
                    rows.pop()
                    return None
                
                if elem_idx == 0:
                    res = backtrack_limited(row_idx, 1, current_row + [0], used_diffs, rows)
                    if res:
                        return res
                    return None
                
                prev_val = current_row[-1]
                max_x = M - (num_elements - elem_idx - 1)
                
                for x in range(prev_val + 1, max_x + 1):
                    new_diffs = []
                    conflict = False
                    for y in current_row:
                        d = x - y
                        if d in used_diffs:
                            conflict = True
                            break
                        new_diffs.append(d)
                    
                    if conflict:
                        continue
                    
                    new_used_diffs = used_diffs.union(new_diffs)
                    
                    res = backtrack_limited(row_idx, elem_idx + 1, current_row + [x], new_used_diffs, rows)
                    if res:
                        return res
                
                return None
            
            return backtrack_limited(0, 0, [], set(), [])

        # Run solver
        # Limit time to 5 seconds per M to allow trying multiple M
        solution = solve_and_return(current_M, start_M_time + time_per_M)
        
        if solution:
            # Verify
            if _is_valid(solution) and _scope(solution) <= current_M:
                return solution
        
        # If failed, increase M
        current_M += 1
        
    # Fallback: If we didn't find a solution with the tight CSP,
    # use a looser heuristic or the previous best known.
    # For (7,5), 112 is known.
    # Let's try a greedy construction with a larger scope as fallback.
    
    # Fallback Greedy
    rng = random.Random(42)
    max_scope_limit = 200
    best_rows = None
    best_scope = float('inf')
    
    # Try to construct with increasing scope
    for scope in range(100, max_scope_limit + 1):
        if time.time() > DEADLINE - 5:
            break
        used_mask = 0
        rows = []
        success = True
        for _ in range(n_rows):
            # Greedy pick
            row = None
            for _ in range(100): # 100 attempts
                if num_elements - 1 > scope:
                    break
                vals = sorted(rng.sample(range(1, scope + 1), num_elements - 1))
                cand = [0] + vals
                if cand[-1] > scope:
                    continue
                diffs = _row_diffs(cand)
                if len(diffs) != len(set(diffs)):
                    continue
                # Check mask
                m = 0
                for d in diffs:
                    m |= (1 << d)
                if m & used_mask:
                    continue
                row = cand
                break
            if row is None:
                success = False
                break
            rows.append(row)
            used_mask |= 0 # Re-calc mask properly
            m = 0
            for d in _row_diffs(row):
                m |= (1 << d)
            used_mask |= m
        if success:
            s = _scope(rows)
            if s < best_scope:
                best_scope = s
                best_rows = rows
            break # Found one, return it? Or try to improve?
            # Since CSP failed, this is a valid solution. Return it.
            return rows

    # If even greedy failed (unlikely), return a trivial invalid one? 
    # No, must return valid.
    # Construct a valid one with large scope.
    rows = []
    used = set()
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < num_elements:
            x += 1
            new_diffs = {x - a for a in row}
            if not new_diffs & used:
                row.append(x)
                used |= new_diffs
        rows.append(row)
    return rows

