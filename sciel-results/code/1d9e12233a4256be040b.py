import random
import numpy as np
from collections import defaultdict, deque
import time

def construct(q, n, radius):
    """
    Construct a covering code of length n over alphabet size q with covering radius radius.
    Uses randomized local search with multiple restarts.
    """
    if n == 0:
        return [[]]
    
    total_words = q ** n
    
    def int_to_word(val, n, q):
        word = []
        for _ in range(n):
            word.append(val % q)
            val //= q
        return word
    
    def word_to_int(word, q):
        val = 0
        for i in range(len(word) - 1, -1, -1):
            val = val * q + word[i]
        return val

    # Precompute basis vectors for fast neighbor generation
    # A neighbor at distance d can be generated by adding linear combinations of basis vectors
    # But for small radius, explicit enumeration is faster if we do it smartly.
    # Let's use a precomputed list of offsets for radius <= 1 or 2.
    # For q=3, n=8, radius=1:
    # Offsets: 0, and +/- 1, +/- q, +/- q^2 ... etc for each position, excluding 0.
    
    # Actually, for radius 1, neighbors of x are x + sum_{i in S} (v_i * (pos_i)) where |S| <= radius.
    # Let's generate all possible "difference vectors" for the given radius.
    diff_vectors = []
    # Generate all vectors of length n with l1 norm <= radius over integers? No, it's Hamming distance.
    # Hamming distance <= radius means we change at most 'radius' positions.
    # For each position i, we can change the value to any of q-1 other values.
    
    # Precompute all possible "masks" of positions to change?
    # Since n=8 and radius is small (usually 1 or 2), we can just iterate.
    
    # Let's stick to a robust method:
    # Precompute neighbors for all words? 
    # 6561 words * (1 + 8*2 + 28*4) ~ 6561 * 117 ~ 767k neighbors.
    # Storing this as a list of lists of ints is feasible and fast to access.
    # Let's try to optimize the neighbor generation.
    
    neighbors_list = [[] for _ in range(total_words)]
    
    # Precompute powers of q for position weights
    powers = [1] * n
    for i in range(1, n):
        powers[i] = powers[i-1] * q
    
    # Generate all difference vectors for Hamming distance <= radius
    diffs = [0]
    if radius >= 1:
        for pos in range(n):
            for delta in range(-q, q):
                if delta == 0: continue
                # We need to be careful with modular arithmetic.
                # Instead of delta, let's just generate the actual neighbor values.
                pass
    
    # Better approach:
    # For each word w, generate neighbors by modifying positions.
    # To speed this up, we can precompute the "steps" for each position.
    # step[pos][val] = list of (new_val, diff_int)
    
    # Let's just do the explicit generation but optimized.
    # We will store neighbors as a list of arrays for faster iteration?
    # Or just a list of lists.
    
    # Optimization: Use a precomputed table of neighbors for each word.
    # This takes ~1s for 6561 words.
    
    for w in range(total_words):
        word = int_to_word(w, n, q)
        neigh = [w]
        
        # Radius 1
        if radius >= 1:
            for pos in range(n):
                for val in range(q):
                    if val == word[pos]:
                        continue
                    new_word = word[:]
                    new_word[pos] = val
                    neigh.append(word_to_int(new_word, q))
        
        # Radius 2
        if radius >= 2:
            for pos1 in range(n):
                for pos2 in range(pos1 + 1, n):
                    for val1 in range(q):
                        if val1 == word[pos1]:
                            continue
                        for val2 in range(q):
                            if val2 == word[pos2]:
                                continue
                            new_word = word[:]
                            new_word[pos1] = val1
                            new_word[pos2] = val2
                            neigh.append(word_to_int(new_word, q))
        
        neighbors_list[w] = neigh
    
    # Convert to sets for fast membership testing?
    # Sets are slower to iterate than lists.
    # We need membership testing for "is this word already a codeword?".
    # We need iteration for "update coverage".
    # Let's keep lists for iteration and use a separate set for codewords.
    
    def greedy_init():
        covered = np.zeros(total_words, dtype=bool)
        codewords = []
        uncovered_count = total_words
        remaining = list(range(total_words))
        random.shuffle(remaining)
        
        while uncovered_count > 0:
            best_word = -1
            best_new_coverage = -1
            
            # Heuristic: Pick a random word from remaining, or one that covers most uncovered.
            # Scanning all remaining is O(N^2). 
            # For 6561 words, N^2 is ~43M. In Python, this might be slow if done naively.
            # But we only do this for the initial greedy.
            # We can sample.
            
            # Let's sample 100 candidates to find a good one quickly.
            # If uncovered_count is small, scan all.
            if len(remaining) > 100:
                candidates = random.sample(remaining, 100)
            else:
                candidates = remaining
                
            for w in candidates:
                new_cov = 0
                for u in neighbors_list[w]:
                    if not covered[u]:
                        new_cov += 1
                if new_cov > best_new_coverage:
                    best_new_coverage = new_cov
                    best_word = w
                    
            if best_word == -1:
                break
            
            codewords.append(best_word)
            remaining.remove(best_word) # This is O(N). Use a set for remaining?
            # Let's use a set for remaining for O(1) removal.
            # But we need to sample from it.
            # Let's restart with a set-based remaining.
            
            for u in neighbors_list[best_word]:
                if not covered[u]:
                    covered[u] = True
                    uncovered_count -= 1
        
        return codewords

    # Refine greedy_init to use a set for remaining
    def greedy_init_fast():
        covered = np.zeros(total_words, dtype=bool)
        codewords = []
        uncovered_count = total_words
        remaining_set = set(range(total_words))
        
        while uncovered_count > 0:
            best_word = -1
            best_new_coverage = -1
            
            if len(remaining_set) > 100:
                candidates = random.sample(list(remaining_set), 100)
            else:
                candidates = list(remaining_set)
                
            for w in candidates:
                new_cov = 0
                for u in neighbors_list[w]:
                    if not covered[u]:
                        new_cov += 1
                if new_cov > best_new_coverage:
                    best_new_coverage = new_cov
                    best_word = w
                    
            if best_word == -1:
                break
            
            codewords.append(best_word)
            remaining_set.remove(best_word)
            
            for u in neighbors_list[best_word]:
                if not covered[u]:
                    covered[u] = True
                    uncovered_count -= 1
        
        return codewords

    def optimize(codewords, time_limit):
        # coverage_count[i] = number of codewords covering word i
        coverage_count = np.zeros(total_words, dtype=np.int32)
        for cw in codewords:
            for u in neighbors_list[cw]:
                coverage_count[u] += 1
                
        cw_set = set(codewords)
        
        def try_remove_redundant():
            removed_any = False
            changed = True
            while changed:
                changed = False
                indices = list(range(len(codewords)))
                random.shuffle(indices)
                for i in indices:
                    cw = codewords[i]
                    can_remove = True
                    # Check if any neighbor is covered only by this codeword
                    for u in neighbors_list[cw]:
                        if coverage_count[u] == 1:
                            can_remove = False
                            break
                    if can_remove:
                        for u in neighbors_list[cw]:
                            coverage_count[u] -= 1
                        codewords.pop(i)
                        cw_set.discard(cw)
                        changed = True
                        removed_any = True
                        break
            return removed_any
        
        try_remove_redundant()
        
        start_time = time.time()
        
        while time.time() - start_time < time_limit:
            if try_remove_redundant():
                continue
                
            if len(codewords) == 0:
                break
                
            idx = random.randint(0, len(codewords) - 1)
            old_cw = codewords[idx]
            
            # Find words that would become uncovered if we remove old_cw
            would_uncover = []
            for u in neighbors_list[old_cw]:
                if coverage_count[u] == 1:
                    would_uncover.append(u)
            
            if len(would_uncover) == 0:
                # Safe to remove
                for u in neighbors_list[old_cw]:
                    coverage_count[u] -= 1
                codewords.pop(idx)
                cw_set.discard(old_cw)
                continue
            
            # We need to find a replacement new_cw that covers all words in would_uncover
            # and ideally covers other words to maintain/increase redundancy.
            
            # Candidate generation:
            # The new codeword must be within distance radius of all words in would_uncover.
            # Intersection of balls.
            # Simple heuristic: Pick a random word from would_uncover, 
            # and look at its neighbors.
            
            # To escape local minima, we can also try random swaps.
            
            best_new_cw = -1
            best_score = -1
            
            # Get candidates from neighbors of the first uncovered word
            first_uncovered = would_uncover[0]
            potential_candidates = neighbors_list[first_uncovered]
            random.shuffle(potential_candidates)
            
            # Limit candidates to speed up
            max_candidates = 50
            for new_cw in potential_candidates[:max_candidates]:
                if new_cw in cw_set or new_cw == old_cw:
                    continue
                
                # Check if new_cw covers all would_uncover
                valid = True
                for u in would_uncover:
                    if u not in neighbors_list[new_cw]:
                        valid = False
                        break
                
                if not valid:
                    continue
                
                # Score: 
                # We remove old_cw and add new_cw.
                # Net change in coverage for word v:
                # delta[v] = (1 if v in N(new) else 0) - (1 if v in N(old) else 0)
                # We want to minimize the number of words where coverage drops to 0.
                # But we already ensured would_uncover is covered by new_cw.
                # So for u in would_uncover, coverage_count[u] stays >= 1 (it was 1, we remove 1, add 1).
                # For other words:
                # If v is in N(old) but not N(new), coverage drops by 1. If it was 1, it becomes 0 (BAD).
                # If v is in N(new) but not N(old), coverage increases by 1.
                
                # We want to avoid creating new "uncovered" words.
                # Words that are in N(old) but not N(new) and have coverage 1 will become uncovered.
                
                bad_count = 0
                for u in neighbors_list[old_cw]:
                    if u not in neighbors_list[new_cw]:
                        if coverage_count[u] == 1:
                            bad_count += 1
                            if bad_count > 0:
                                # This swap creates uncovered words. We should avoid unless we allow repair?
                                # The problem requires a valid covering at the end.
                                # So we must not create uncovered words.
                                # Therefore, we require bad_count == 0.
                                break
                
                if bad_count > 0:
                    continue
                
                # If valid, score based on how many new redundancies we create
                # Words in N(new) but not N(old) that are already covered (count > 0)
                # increase our robustness.
                score = 0
                for u in neighbors_list[new_cw]:
                    if u not in neighbors_list[old_cw]:
                        if coverage_count[u] > 0:
                            score += 1
                            
                if score > best_score:
                    best_score = score
                    best_new_cw = new_cw
            
            if best_new_cw != -1:
                # Perform swap
                for u in neighbors_list[old_cw]:
                    coverage_count[u] -= 1
                for u in neighbors_list[best_new_cw]:
                    coverage_count[u] += 1
                codewords[idx] = best_new_cw
                cw_set.discard(old_cw)
                cw_set.add(best_new_cw)
            else:
                # No good swap found. Try a random move?
                # Or just skip.
                # To escape local optima, we can try to add a random codeword and then remove a redundant one?
                # This increases size temporarily.
                # Let's try: Pick a random word w. Add it. Then try to remove a redundant codeword.
                # If size decreases, keep it.
                pass
        
        try_remove_redundant()
        return codewords
    
    # Multiple restarts
    start_time = time.time()
    time_limit = 115
    best_codewords = []
    
    while time.time() - start_time < time_limit:
        # Allocate time for this iteration
        iter_time = min(15, time_limit - (time.time() - start_time))
        if iter_time <= 0:
            break
        
        cw = greedy_init_fast()
        cw = optimize(cw, iter_time - 2)
        
        if len(cw) < len(best_codewords) or not best_codewords:
            best_codewords = cw
        
        if time.time() - start_time > time_limit - 5:
            break
    
    result = [int_to_word(cw, n, q) for cw in best_codewords]
    return result
