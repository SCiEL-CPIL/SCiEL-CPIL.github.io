def _verify_block(terms, n=3, m=3, p=3):
    """Check that sum_r u[i,j]*v[j,k]*w[i,k] == 1 for all (i,j,k)."""
    for i in range(n):
        for j in range(m):
            for k in range(p):
                s = 0
                for u, v, w in terms:
                    a = u.get((i, j), 0)
                    b = v.get((j, k), 0)
                    c = w.get((i, k), 0)
                    if a and b and c:
                        s += a * b * c
                if s != 1:
                    return False
    return True

def _schoolbook_3x3x3():
    terms = []
    for i in range(3):
        for j in range(3):
            for k in range(3):
                terms.append(( {(i,j):1}, {(j,k):1}, {(i,k):1} ))
    return terms

def construct():
    n, m, p = DIMENSIONS
    deadline = time.time() + 110  # safety margin before the 120s limit

    # Structural idea: the (3,3,6) multiplication tensor is two independent
    # (3,3,3) block-diagonal tensors.  rank(3,3,6) = 2 * rank(3,3,3).
    # Use the verified rank-23 Bläser 3x3x3 decomposition for each block.
    block_terms = None
    try:
        cand = _blasers_3x3x3_terms()
        if len(cand) == 23 and _verify_block(cand):
            block_terms = cand
    except Exception:
        block_terms = None
    if block_terms is None:
        # Fallback: guaranteed-correct schoolbook 3x3x3 (rank 27)
        block_terms = _schoolbook_3x3x3()

    total_rank = 2 * len(block_terms)

    U = [[0] * total_rank for _ in range(n * m)]
    V = [[0] * total_rank for _ in range(m * p)]
    W = [[0] * total_rank for _ in range(p * n)]

    def emit(terms, k_off, col):
        for u, v, w in terms:
            for (i, j), c in u.items():
                U[i * m + j][col] += c
            for (j, k0), c in v.items():
                k = k0 + k_off
                V[j * p + k][col] += c
            for (i, k0), c in w.items():
                k = k0 + k_off
                W[k * n + i][col] += c
            col += 1

    col = 0
    col = emit(block_terms, 0, col)      # output rows k = 0,1,2
    col = emit(block_terms, 3, col)      # output rows k = 3,4,5

    return {"U": U, "V": V, "W": W}
