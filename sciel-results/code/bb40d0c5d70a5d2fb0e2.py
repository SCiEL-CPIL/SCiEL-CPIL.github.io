    """
    Return (U, V, W) for Strassen's rank-7 decomposition of 2x2x2.
    U: (4, 7), V: (4, 7), W: (4, 7)
    Indexing: U[i*2+j], V[j*2+k], W[k*2+i]
    
    Verification: For A (2x2), B (2x2), C = A*B (2x2)
    C[k,i] = sum_c U[i*2+j, c] * A[i,j] * V[j*2+k, c] * B[j,k] * W[k*2+i, c]
    """
    U = np.zeros((4, 7), dtype=float)
    V = np.zeros((4, 7), dtype=float)
    W = np.zeros((4, 7), dtype=float)
    
    # Define the 7 products explicitly
    # Product 0: M1 = (A00+A11)(B00+B11)
    # U: A00=1, A11=1
    U[0, 0] = 1.0  # A[0,0]
    U[3, 0] = 1.0  # A[1,1]
    # V: B00=1, B11=1
    V[0, 0] = 1.0  # B[0,0]
    V[3, 0] = 1.0  # B[1,1]
    # W: C00 += 1, C11 += 1
    W[0, 0] = 1.0  # C[0,0]
    W[3, 0] = 1.0  # C[1,1]
    
