    U[2, 1] = 1.0  # A[1,0]
    U[3, 1] = 1.0  # A[1,1]
    V[0, 1] = 1.0  # B[0,0]
    W[2, 1] = 1.0  # C[1,0]
    W[3, 1] = -1.0  # C[1,1]
    
