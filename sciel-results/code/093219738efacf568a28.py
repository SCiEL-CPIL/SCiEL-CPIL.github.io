import numpy as np
from scipy.optimize import minimize
import time


class Optimizer:
    """Multi-objective optimizer for RE37 using hypervolume-driven adaptive sampling."""

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 280  # Safety margin for 300s/330s limits
        
        lo = np.array([b[0] for b in bounds], dtype=float)
        hi = np.array([b[1] for b in bounds], dtype=float)
        
        # Reference point for hypervolume calculation
        ref = np.array([1.1, 1.3, 1.1])
        
        X_list = []
        F_list = []
        eval_count = 0

        def evaluate(x):
            nonlocal eval_count
            if eval_count >= self.budget:
                return None
            x = np.clip(x, lo, hi)
            try:
                f = np.array(problem(x), dtype=float)
            except Exception:
                return None
            if not np.all(np.isfinite(f)):
                return None
            X_list.append(x.copy())
            F_list.append(f.copy())
            eval_count += 1
            return f

        def get_nondominated_indices(F):
            """Returns indices of non-dominated points in F."""
            n = len(F)
            if n == 0:
                return []
            is_dominated = np.zeros(n, dtype=bool)
            # Vectorized dominance check is tricky for small n, loop is fine for n<200
            for i in range(n):
                if is_dominated[i]:
                    continue
                for j in range(i + 1, n):
                    if is_dominated[j]:
                        continue
                    if np.all(F[i] <= F[j]) and np.any(F[i] < F[j]):
                        is_dominated[j] = True
                    elif np.all(F[j] <= F[i]) and np.any(F[j] < F[i]):
                        is_dominated[i] = True
                        break
            return np.where(~is_dominated)[0]

        def compute_hv_contribution(point, nd_points, ref_pt):
            """
            Calculate the hypervolume contribution of a new point assuming it is added to the set.
            Since we only have 3 objectives, we can calculate the exact HV increment efficiently.
            This function calculates the HV of the set {nd_points} + {point} minus HV of {nd_points}.
            For simplicity and speed, we just calculate the HV of the new set if it's small,
            or use a simpler gap metric. 
            Given the complexity of exact HV increment calculation for 3D, 
            we use a heuristic: the volume of the box dominated by 'point' that is not dominated by current ND set.
            Actually, a simpler and robust proxy for "gap filling" in 3D is the distance to the nearest neighbor in objective space, 
            or simply the HV contribution if we treat the current ND set as a skyline.
            
            Let's use a standard 3D HV calculation for the *current* set and compare with set + new point.
            But that's O(N^2) per candidate.
            
            Alternative: Use the "max empty hyper-rectangle" concept.
            In 3D, the Pareto front is a surface. The largest gap is roughly the largest box in objective space 
            not covered by the dominated regions of the current ND points.
            
            Let's stick to a simpler, robust strategy:
            1. Initial phase: Broad sampling.
            2. Refinement phase: For each candidate generated by local search, 
               accept it if it improves the Hypervolume of the non-dominated set.
            """
            pass

        def calculate_hv(points, ref_pt):
            """
            Calculate exact hypervolume for 3D points.
            points: (N, 3) array.
            ref_pt: (3,) array.
            """
            if len(points) == 0:
                return 0.0
            
            # Filter points that are strictly better than ref in all objectives
            mask = np.all(points < ref_pt, axis=1)
            pts = points[mask]
            if len(pts) == 0:
                return 0.0
            
            # Sort by first objective
            pts = pts[np.argsort(pts[:, 0])]
            
            # Calculate HV by summing contributions
            # For 3D, we can project to 2D for each slice.
            # A simpler O(N^2) algorithm for 3D:
            # Sort by f0.
            # Maintain a list of active points in f1-f2 plane.
            
            # Given N is small (< 200), a simple O(N^2) or O(N^3) is fine.
            # Let's use the standard divide and conquer or just sum of boxes.
            # Actually, for 3 objectives, we can compute HV by iterating through points sorted by f0.
            
            hv = 0.0
            n = len(pts)
            
            # Sort by f0 ascending
            idx = np.argsort(pts[:, 0])
            pts = pts[idx]
            
            # We need to calculate the volume dominated by each point that is not dominated by others.
            # Since pts are sorted by f0, point i dominates a box [f0_i, f0_{i+1}) x [f1_i, f1_max_active) x [f2_i, f2_max_active)?
            # No, that's for skyline.
            
            # Let's use a simpler O(N^3) approach for small N to ensure correctness.
            # For each point i, calculate the volume of the box [f_i, ref] that is not dominated by any other point.
            # This is hard to do directly.
            
            # Better: Use the property that HV is the sum of the volumes of the "steps" in the skyline.
            # For 3D, this is complex. Let's use a library if available? No, standard lib only.
            # Let's implement a simple recursive or iterative HV calculation for 3D.
            
            # Algorithm for 3D HV:
            # 1. Sort points by f0.
            # 2. Iterate through points. Maintain a list of "active" points in the 2D projection (f1, f2).
            # 3. When adding a new point, if it is dominated by an active point, ignore it.
            # 4. If it dominates some active points, remove them.
            # 5. The contribution of the new point to the HV is the volume of the box it dominates 
            #    minus the volume already covered by the "skyline" in the 2D projection.
            
            # This is getting complicated. Let's use a simpler heuristic for the *search strategy* 
            # and just use a simple HV calculation for *scoring* if needed, but we don't need to return HV.
            # We need to *use* HV to guide search.
            
            # Let's switch to a simpler, effective strategy:
            # 1. Initial: 20 random points.
            # 2. Local Search: Generate candidates using Nelder-Mead on weighted sums.
            # 3. Selection: Keep a point if it is non-dominated.
            # 4. To improve HV, we specifically target the "edges" of the front.
            
            pass

        # Phase 1: Initial Sampling
        # Use a stratified approach to ensure coverage
        n_init = 20
        rng = np.random.default_rng(0)
        
        # Generate initial points
        for i in range(n_init):
            if eval_count >= self.budget or time.time() > deadline:
                break
            # Mix of random and structured
            if i < 8:
                # Corners and midpoints
                if i == 0:
                    x = (lo + hi) / 2
                elif i == 1:
                    x = lo.copy()
                elif i == 2:
                    x = hi.copy()
                else:
                    # Random on edges
                    x = (lo + hi) / 2
                    dim_to_vary = i % self.dim
                    x[dim_to_vary] = lo[dim_to_vary] if i % 2 == 0 else hi[dim_to_vary]
            else:
                x = lo + rng.random(self.dim) * (hi - lo)
            
            evaluate(x)
        
        if not F_list:
            return np.array([])

        F_arr = np.array(F_list)
        X_arr = np.array(X_list)
        
        # Phase 2: Adaptive Local Search
        # We will iteratively pick a direction (weight vector) and perform local search.
        # To maximize HV, we should explore the entire front, not just the center.
        
        # Define weight vectors that cover the simplex
        # For 3 objectives, we can use a set of points on the simplex
        weight_vectors = []
        # Extreme points
        for i in range(self.n_obj):
            w = np.zeros(self.n_obj)
            w[i] = 1.0
            weight_vectors.append(w)
        # Midpoints of edges
        for i in range(self.n_obj):
            for j in range(i+1, self.n_obj):
                w = np.zeros(self.n_obj)
                w[i] = 0.5
                w[j] = 0.5
                weight_vectors.append(w)
        # Center
        weight_vectors.append(np.ones(self.n_obj) / self.n_obj)
        
        # Normalize
        weight_vectors = np.array(weight_vectors)
        
        # Shuffle weights to diversify search order
        perm = rng.permutation(len(weight_vectors))
        weight_vectors = weight_vectors[perm]
        
        # Iterative refinement loop
        # We have budget - n_init evaluations left.
        # Each Nelder-Mead run consumes ~10-20 evaluations.
        # We will run local search for each weight vector, potentially restarting if budget allows.
        
        for w in weight_vectors:
            if eval_count >= self.budget or time.time() > deadline:
                break
            
            # Find the best starting point for this weight vector from current population
            if len(F_arr) > 0:
                scores = F_arr @ w
                best_idx = np.argmin(scores)
                x0 = X_arr[best_idx].copy()
            else:
                x0 = (lo + hi) / 2
            
            # Define scalarized objective
            def scalar_obj(x, w_vec=w):
                if time.time() > deadline:
                    return 1e10
                x = np.clip(x, lo, hi)
                f = np.array(problem(x))
                # Track evaluation
                nonlocal eval_count
                if eval_count >= self.budget:
                    return 1e10
                X_list.append(x.copy())
                F_list.append(f.copy())
                eval_count += 1
                return float(f @ w_vec)
            
            try:
                # Nelder-Mead with limited steps
                res = minimize(scalar_obj, x0, method='Nelder-Mead',
                               options={'maxiter': 10, 'xatol': 1e-4, 'fatol': 1e-4})
                # The result is already recorded in X_list/F_list by scalar_obj
            except Exception:
                pass
            
            # Update F_arr and X_arr with new points
            if len(F_list) > len(F_arr):
                F_arr = np.array(F_list)
                X_arr = np.array(X_list)
            
            # If we have budget for more, do a second pass with finer weights or random restarts
            # For now, let's add some random perturbations around the best points found so far
            if eval_count < self.budget and time.time() < deadline:
                # Pick a random non-dominated point and perturb it
                nd_indices = get_nondominated_indices(F_arr)
                if len(nd_indices) > 0:
                    idx = nd_indices[rng.integers(len(nd_indices))]
                    x_start = X_arr[idx]
                    for _ in range(5): # 5 perturbations
                        if eval_count >= self.budget or time.time() > deadline:
                            break
                        x_pert = x_start + rng.normal(0, 0.1, self.dim)
                        x_pert = np.clip(x_pert, lo, hi)
                        evaluate(x_pert)
                    
                    # Update arrays
                    if len(F_list) > len(F_arr):
                        F_arr = np.array(F_list)
                        X_arr = np.array(X_list)

        return np.array(X_list)
