"""Optimized solver for spectral graph lifts on prism graphs."""
import time
import numpy as np

# We will implement a custom fast solver.
# The task is to find signs s_e in {-1, 1} for edges of a prism graph P_m.
# Prism graph P_m has 2m vertices.
# Vertices 0..m-1 form a cycle C_m (bottom).
# Vertices m..2m-1 form a cycle C_m (top).
# Edges (i, i+m) for i in 0..m-1 form the matching.

# The signed adjacency matrix A_s of the base graph is 2m x 2m.
# A_s[u, v] = s_e if (u, v) is an edge, else 0.
# We want to minimize the spectral radius rho(A_s).

# The lift is connected if and only if the signs on the "vertical" edges (matching)
# and the cycles are consistent with a single connected component in the 2-lift.
# Actually, the 2-lift connectivity condition is:
# The lift is connected iff the subgroup generated by the edge signs (viewed as elements of Z2)
# in the fundamental group of the graph is the whole Z2.
# For a graph with a cycle basis, the product of signs around any cycle must be -1 for at least one cycle
# in a basis? No.
# The lift is disconnected if and only if there is a "signing" such that the product of signs around every cycle is +1.
# In that case, the lift splits into two components corresponding to the two "sides" being decoupled.
# More precisely, the lift is connected iff there exists at least one cycle in the graph whose product of edge signs is -1.
# Wait, let's verify.
# Vertices in lift are (v, 0), (v, 1).
# Edge (u, v) with sign s:
# If s=+1: (u,0)-(v,0) and (u,1)-(v,1).
# If s=-1: (u,0)-(v,1) and (u,1)-(v,0).
# This is a double cover.
# The cover is connected iff the subgroup of Z2 generated by the products of signs around cycles is Z2.
# Since Z2 has only two elements {0, 1} (or {+1, -1}), this means there must be at least one cycle with product -1.
# If all cycles have product +1, the lift is disconnected (two disjoint copies of the base graph).
# So validity condition: At least one cycle in the graph has an odd number of -1 signs.

# The prism graph P_m has cycles:
# 1. Bottom cycle C_b: edges (0,1), (1,2), ..., (m-1,0).
# 2. Top cycle C_t: edges (m, m+1), ..., (2m-1, m).
# 3. Vertical edges: (i, i+m).
# A fundamental cycle basis can be formed by:
# - The bottom cycle.
# - The top cycle.
# - For each i, the cycle formed by (i, i+m) and a path in the top/bottom?
# Actually, the cycle space dimension is E - V + 1 = 3m - 2m + 1 = m + 1.
# The product of signs around the bottom cycle is P_b.
# The product of signs around the top cycle is P_t.
# If we flip signs on the vertical edges, how does it affect?
# Let s_v[i] be the sign of vertical edge i.
# Let s_b[i] be the sign of bottom edge i (between i and i+1 mod m).
# Let s_t[i] be the sign of top edge i (between m+i and m+i+1 mod m).
#
# The product around the bottom cycle is prod(s_b).
# The product around the top cycle is prod(s_t).
#
# Consider a cycle that goes from i to i+m via vertical edge, then along top cycle from m+i to m+j,
# then vertical edge j to j, then along bottom cycle from j to i.
# This is a cycle in the prism.
# Its sign product is s_v[i] * (product of top edges from i to j) * s_v[j] * (product of bottom edges from j to i).
#
# Connectivity requires that not ALL such products are +1.
# In particular, if prod(s_b) = +1 and prod(s_t) = +1, does that imply all cycles have product +1?
# Not necessarily.
# However, if we set all s_b = +1 and all s_t = +1, then the bottom and top cycles have product +1.
# The "ladder" cycles (using two verticals and paths on cycles) will have product s_v[i] * s_v[j].
# If we set all s_v = +1, then all these are +1.
# So all +1 is disconnected.
#
# If we set one s_v = -1 and rest +1, and s_b, s_t all +1:
# Then the cycle using vertical i (the -1 one) and vertical j (a +1 one) has product -1 * 1 = -1.
# So it is connected.
#
# What is the spectral radius in this case?
# The matrix is block-circulant if we order vertices appropriately?
# For m=4, 5, 7, 9.
#
# Let's try to construct a low spectral radius matrix.
# The ideal is to make the eigenvalues as close to 0 as possible.
# The trace is 0. The sum of squares of eigenvalues is 2 * (sum of squares of entries) = 2 * (3m * 1) = 6m.
# So sum lambda_i^2 = 6m.
# If eigenvalues are symmetric around 0 (which they are for signed graphs? No, not necessarily.
# But for bipartite graphs, they are. Prism graphs are not necessarily bipartite if m is odd.
# If m is even, P_m is bipartite. If m is odd, P_m is not.
#
# Let's use random search with a strong local improvement heuristic.
# We can use simulated annealing or simple hill climbing.
# Objective: spectral radius.
# Constraint: connected (at least one cycle has product -1).

def sign_edges(graph, budget):
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    n = graph['n']
    edges = graph['edges']
    m = n // 2
    E = len(edges)
    
    # Build adjacency list for fast neighborhood access
    adj = [[] for _ in range(n)]
    for idx, (u, v) in enumerate(edges):
        adj[u].append((v, idx))
        adj[v].append((u, idx))
        
    # Identify edge types for potential structured initialization
    # Bottom edges: u < m, v < m
    # Top edges: u >= m, v >= m
    # Vertical: one < m, one >= m
    
    def get_spectral_radius(signs):
        # Build matrix
        A = np.zeros((n, n), dtype=float)
        for idx, (u, v) in enumerate(edges):
            s = signs[idx]
            A[u, v] = s
            A[v, u] = s
        # Symmetric matrix
        vals = np.linalg.eigvalsh(A)
        return np.max(np.abs(vals))
    
    def is_connected(signs):
        # Check if there is a cycle with product -1.
        # We can do a BFS/DFS on the base graph, tracking the product of signs from the root.
        # If we reach a visited node with a different parity (product), we have a cycle with product -1.
        # Actually, simpler:
        # Build the lift graph explicitly? No, that's 2n nodes.
        # We can just check the fundamental cycles.
        # Let's use the property: The lift is disconnected iff the signs are "bipartite consistent"
        # i.e., there exists a labeling c: V -> {+1, -1} such that for every edge (u, v), s(u, v) = c(u) c(v).
        # If such a labeling exists, the lift is two disjoint copies.
        # So, is_connected is False iff the system s(u, v) = c(u) c(v) is consistent.
        # This is equivalent to: product of signs around every cycle is +1.
        
        # We can check this by DFS.
        # Assign c[0] = 1.
        # For each edge (u, v), c(v) = c(u) * s(u, v).
        # If we encounter a contradiction, it's connected.
        # If we finish without contradiction, it's disconnected.
        
        color = [-1] * n
        color[0] = 1
        stack = [0]
        
        while stack:
            u = stack.pop()
            for v, idx in adj[u]:
                s = signs[idx]
                expected = color[u] * s
                if color[v] == -1:
                    color[v] = expected
                    stack.append(v)
                else:
                    if color[v] != expected:
                        return True # Contradiction found, so it IS connected.
        
        return False # No contradiction, so it is DISCONNECTED.

    def flip_edge(signs, idx):
        signs[idx] = -signs[idx]
        
    # Initialization: Random
    rng = np.random.default_rng(3)
    
    best_signs = None
    best_radius = float('inf')
    
    # Try a few structured starts
    # 1. All +1 (disconnected, but good starting point for flips)
    # 2. One -1 vertical (connected)
    # 3. Random
    
    candidates = []
    
    # Structured 1: All +1, then flip one vertical to make connected
    # Vertical edges are those where one end is < m and other >= m
    vert_indices = []
    for idx, (u, v) in enumerate(edges):
        if (u < m and v >= m) or (u >= m and v < m):
            vert_indices.append(idx)
            
    if vert_indices:
        s_init = np.ones(E, dtype=int)
        s_init[vert_indices[0]] = -1
        candidates.append(s_init.copy())
        
        # Try flipping different verticals
        for vi in vert_indices[:5]:
            s_init = np.ones(E, dtype=int)
            s_init[vi] = -1
            candidates.append(s_init.copy())

    # Random starts
    for _ in range(20):
        s_rand = rng.choice([-1, 1], size=E)
        candidates.append(s_rand)
        
    # Evaluate candidates
    for s in candidates:
        if is_connected(s):
            r = get_spectral_radius(s)
            if r < best_radius:
                best_radius = r
                best_signs = s.copy()
                
    if best_signs is None:
        # Fallback: force connectivity
        s_init = np.ones(E, dtype=int)
        s_init[vert_indices[0]] = -1
        best_signs = s_init
        best_radius = get_spectral_radius(best_signs)
        
    current_signs = best_signs.copy()
    current_radius = best_radius
    
    # Local Search: Hill Climbing with Random Restarts
    # Since the landscape is discrete, we can try flipping one edge at a time.
    # To escape local minima, we can use simulated annealing or just random restarts.
    # Given the small size (m=9, E=27), 1-flip neighborhood is 27 options.
    # 2-flip is ~350.
    
    def local_search(signs, radius, time_limit):
        cur_signs = signs.copy()
        cur_radius = radius
        improved = True
        while improved and time.time() < time_limit:
            improved = False
            # Try all single flips
            for idx in range(E):
                # Flip
                old_val = cur_signs[idx]
                cur_signs[idx] = -old_val
                
                if is_connected(cur_signs):
                    new_radius = get_spectral_radius(cur_signs)
                    if new_radius < cur_radius - 1e-12:
                        cur_radius = new_radius
                        improved = True
                        # Keep the flip
                        # Continue searching from this new state
                        break
                    else:
                        # Revert
                        cur_signs[idx] = old_val
                else:
                    # Revert
                    cur_signs[idx] = old_val
            
            # If no single flip improved, try 2-flips?
            # Or just stop?
            # 2-flips might be necessary to escape local minima.
            if not improved:
                # Try random 2-flips
                found = False
                for _ in range(50): # Limit attempts
                    if time.time() > time_limit:
                        break
                    i, j = rng.choice(E, size=2, replace=False)
                    cur_signs[i] = -cur_signs[i]
                    cur_signs[j] = -cur_signs[j]
                    
                    if is_connected(cur_signs):
                        new_radius = get_spectral_radius(cur_signs)
                        if new_radius < cur_radius - 1e-12:
                            cur_radius = new_radius
                            found = True
                            break
                        else:
                            cur_signs[i] = -cur_signs[i]
                            cur_signs[j] = -cur_signs[j]
                    else:
                        cur_signs[i] = -cur_signs[i]
                        cur_signs[j] = -cur_signs[j]
                
                if not found:
                    break # Stuck in local minimum
                    
        return cur_signs, cur_radius

    # Run multiple local searches from different starting points
    # We already have best_signs. Let's run local search from it.
    # And from a few random connected points.
    
    starts = [best_signs]
    for _ in range(10):
        s_rand = rng.choice([-1, 1], size=E)
        if is_connected(s_rand):
            starts.append(s_rand)
            
    for s_start in starts:
        if time.time() > deadline:
            break
        s_res, r_res = local_search(s_start, get_spectral_radius(s_start), deadline)
        if r_res < best_radius:
            best_radius = r_res
            best_signs = s_res.copy()
            
    # Final check
    if not is_connected(best_signs):
        # Should not happen, but just in case
        best_signs[vert_indices[0]] = -1
        
    return best_signs
