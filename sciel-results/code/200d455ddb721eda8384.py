from fractions import Fraction

def _ceil_div(a, b):
    return (a + b - 1) // b

def _max_sum(d, r):
    """Upper bound: sum_{i=0}^{r-1} 1/(d+i) >= r/(d+r-1)."""
    return Fraction(r, d + r - 1)

def _min_sum(d, r):
    """Lower bound: sum_{i=0}^{r-1} 1/(d+i) <= r/d."""
    return Fraction(r, d)

def _search(k, time_limit):
    """Find k distinct denominators >= 5 summing to 1."""
    start = time.time()
    memo = {}

    def dfs(S, r, m):
        if time.time() - start > time_limit:
            raise TimeoutError
        if r == 0:
            return [] if S == 0 else None
        if S <= 0:
            return None

        key = (S.numerator, S.denominator, r, m)
        if key in memo:
            return memo[key]

        # Lower bound for next denominator:
        # We need S - 1/d >= 0, so d >= ceil(1/S)
        # Also d >= m
        # But more precisely, we need 1/d <= S, so d >= ceil(1/S)
        p, q = S.numerator, S.denominator
        d_min = max(m, _ceil_div(q, p))

        # Upper bound for next denominator:
        # We need max possible sum of remaining r-1 terms >= S - 1/d
        # max_sum(d+1, r-1) >= S - 1/d
        # This is hard to solve directly, so we use a heuristic upper bound.
        # Since all remaining terms are at most 1/(d+1), we need (r-1)/(d+1) >= S - 1/d
        # Approximate: d is at most around (r-1) / (S - 1/d)
        # Use a safe upper bound: d_max where max_sum(d+1, r-1) >= S - 1/d
        # Let's try: for d to be valid, we need S - 1/d <= _max_sum(d+1, r-1)
        # i.e., S - 1/d <= (r-1)/(d+r-1)
        # This gives an equation we can solve, but let's use a simpler approach.
        # Start with a reasonable upper bound and increase if needed.
        # Since denominators are >= 5 and sum to 1, no single denominator can be too large.
        # A safe upper bound: if d is very large, 1/d is tiny, and we need r-1 terms to sum to ~S.
        # The largest possible sum with r-1 terms starting at d+1 is (r-1)/(d+1).
        # So we need (r-1)/(d+1) >= S - 1/d.
        # For large d, 1/d ~ 0, so (r-1)/(d+1) >= S, giving d+1 <= (r-1)/S.
        # So d <= (r-1)/S - 1.
        d_max = int((r - 1) / S.numerator * S.denominator) + 100
        d_max = min(d_max, 10**7)
        
        if d_max < d_min:
            memo[key] = None
            return None

        # Try denominators from d_min to d_max
        # We want to find a valid d such that the remaining sum S - 1/d can be achieved
        # with r-1 distinct denominators > d.
        for d in range(d_min, d_max + 1):
            S2 = S - Fraction(1, d)
            if S2 < 0:
                break
            # Check if it's possible: max_sum(d+1, r-1) >= S2
            if _max_sum(d + 1, r - 1) < S2:
                continue
            # Check if it's possible: min_sum(d+1, r-1) <= S2 (always true for positive S2)
            # But also need S2 > 0 and achievable
            if S2 == 0:
                if r - 1 == 0:
                    res = [d]
                    memo[key] = res
                    return res
                continue
            
            res = dfs(S2, r - 1, d + 1)
            if res is not None:
                res = [d] + res
                memo[key] = res
                return res

        memo[key] = None
        return None

    res = dfs(Fraction(1, 1), k, 5)
    return res

