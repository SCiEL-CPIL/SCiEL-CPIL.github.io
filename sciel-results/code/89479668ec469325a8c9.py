N = 24
_edge_idx = {}
for i, (u, v) in enumerate(_edge_order):
    _edge_idx[(min(u, v), max(u, v))] = i + 1

def _es(u, v):
    return _edge_idx[(min(u, v), max(u, v))]

def _score(cyc):
    m = 0
    for i in range(N):
        s = _es(cyc[i], cyc[(i + 1) % N])
        if s > m:
            m = s
    return m

def _local_search(cyc, deadline):
    best = list(cyc)
    best_s = _score(best)
    while time.time() < deadline:
        improved = False
        es = [_es(best[i], best[(i + 1) % N]) for i in range(N)]
        for i in range(N - 1):
            if time.time() > deadline:
                return best, best_s
            for j in range(i + 1, N - 1):
                ne1 = _es(best[i], best[j])
                ne2 = _es(best[i + 1], best[(j + 1) % N])
                mo = 0
                for k in range(N):
                    if k != i and k != j:
                        if es[k] > mo:
                            mo = es[k]
                nm = max(mo, ne1, ne2)
                if nm < best_s:
                    best[i + 1:j + 1] = best[i + 1:j + 1][::-1]
                    es = [_es(best[k], best[(k + 1) % N]) for k in range(N)]
                    best_s = nm
                    improved = True
                    break
            if improved:
                break
        if not improved:
            break
    return best, best_s

def construct():
    deadline = time.time() + 85.0
    rng = random.Random(614)
    best_cycle = list(range(N))
    best_score = _score(best_cycle)

    while time.time() < deadline:
        cyc = list(range(N))
        rng.shuffle(cyc)
        cyc, s = _local_search(cyc, deadline)
        if s < best_score:
            best_score = s
            best_cycle = cyc
        if best_score <= 30:
            break

    return best_cycle
