def _strassen_2x2x2():
    """Return Strassen decomposition of M_{2,2,2} with rank 7."""
    # U[i*2+j, r], V[j*2+k, r], W[k*2+i, r]
    # Strassen's 7 terms
    U = [
        [1, 0, 0, 0, 0, 0, 0],  # i=0,j=0
        [0, 1, 0, 0, 0, 0, 0],  # i=0,j=1
        [0, 0, 1, 0, 0, 0, 0],  # i=1,j=0
        [0, 0, 0, 1, 1, 0, 0],  # i=1,j=1
    ]
    V = [
        [1, 0, 0, 0, 0, 0, 0],  # j=0,k=0
        [0, 0, 0, 1, 0, 0, 0],  # j=0,k=1
        [0, 0, 0, 0, 1, 0, 0],  # j=1,k=0
        [0, 1, 1, 0, 0, 1, 1],  # j=1,k=1
    ]
    W = [
        [0, 0, 1, 0, 0, 0, 0],  # k=0,i=0
        [0, 0, 0, 1, 0, 0, 0],  # k=0,i=1
        [0, 0, 0, 0, 0, 1, 0],  # k=1,i=0
        [0, 1, 1, 0, 1, 0, 1],  # k=1,i=1
    ]
    return U, V, W
