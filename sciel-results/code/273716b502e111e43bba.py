import time
import numpy as np

def _build_schoolbook(n, m, p):
    """Build schoolbook rank-nmp decomposition."""
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
    return {"U": U, "V": V, "W": W}

def construct():
    """
    Returns the schoolbook tensor decomposition for 2x3 * 3x6 matrix multiplication.
    Rank is n*m*p = 36.
    """
    n, m, p = DIMENSIONS
    return _build_schoolbook(n, m, p)
