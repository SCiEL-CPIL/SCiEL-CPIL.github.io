import numpy as np
from scipy.sparse.csgraph import minimum_spanning_tree
from scipy.sparse import csr_matrix

def synthesize(matrix, depth_limit):
    """
    Exact XOR-circuit synthesis under a bounded candidate interface.
    
    Args:
        matrix: A 2D array-like where each row is a target linear form over GF(2).
                matrix[i][j] indicates if input wire j is XORed into target i.
        depth_limit: Maximum allowed depth (not strictly enforced beyond 16).
    
    Returns:
        {'gates': [[wire, wire], ...], 'outputs': [wire, ...]}
    """
    matrix = np.array(matrix, dtype=np.uint8)
    n, m = matrix.shape
    n_inputs = n
    n_targets = m
    
    # Wire 0..n-1 are inputs, wire n is constant 0.
    # Gates produce wires n+1, n+2, ...
    
    if n_targets == 0:
        return {'gates': [], 'outputs': []}
    
    # Represent each target as a bitset for efficient XOR.
    # We'll use a Python int or a bytes object. For n up to 16, int is fine.
    
    def to_bitset(row):
        v = 0
        for j in range(n):
            if row[j] % 2 == 1:
                v |= (1 << j)
        return v
    
    targets = [to_bitset(matrix[i]) for i in range(n_targets)]
    
    # Available wires: initially inputs (0..n-1) and constant 0 (wire n).
    # We build a set of available linear forms.
    # Wire w corresponds to a bitset.
    
    wire_to_bitset = {}
    bitset_to_wire = {}
    
    # Initialize with inputs
    for j in range(n):
        b = 1 << j
        wire = j
        wire_to_bitset[wire] = b
        bitset_to_wire[b] = wire
    
    # Constant zero
    zero_b = 0
    zero_wire = n
    wire_to_bitset[zero_wire] = zero_b
    bitset_to_wire[zero_b] = zero_wire
    
    current_wire_count = n + 1  # wires 0..n
    
    gates = []
    
    # We need to produce each target.
    # Strategy: Use a greedy approach with lookahead.
    # At each step, if a target is already available, use it.
    # Otherwise, find the cheapest way to produce it by XORing two available wires.
    # To minimize total gates, we should prioritize producing wires that are useful for multiple targets.
    
    # Let's define the cost of producing a new wire w as 1 gate.
    # The total cost is the number of gates.
    
    # A more effective heuristic: 
    # 1. Start with all inputs.
    # 2. While some target is not available:
    #    a. Find the target that is "closest" to being available (minimum weight in the quotient space?).
    #    b. Or, find a pair of available wires whose XOR is a target or useful for multiple targets.
    
    # Let's try a BFS/queue approach with prioritization.
    
    # Alternative: 
    # Since n is small (<=16), the space of all possible bitsets is 2^n <= 65536.
    # We can compute the shortest path in the Cayley graph of GF(2)^n generated by the inputs?
    # No, the generators are the inputs, but we can XOR any two available wires.
    # This is equivalent to building a circuit where each gate adds a new vector.
    
    # Greedy: 
    # At each step, add the wire that minimizes the "distance" to the remaining targets.
    # Distance of a target t from the current span S is the minimum number of additional gates needed?
    # If t is in span(S), distance is 0 if t is in S, else 1 (since any vector in span can be formed by XORing basis vectors, but we need intermediate wires).
    # Actually, if t is in span(S), it might take multiple gates to form it if it requires combining 3+ basis vectors.
    # Wait, if S is a set of vectors, and we can add any XOR of two vectors in S, then after k steps we can form any vector in span(S) that is a sum of <= k+1 basis vectors? No.
    
    # Let's think about depth.
    # Depth 0: inputs.
    # Depth 1: XOR of two inputs.
    # Depth 2: XOR of two depth-1 wires, or depth-1 with input.
    
    # For small n, we can just do a simple greedy:
    # For each target not yet available:
    #   Find the minimum number of available wires whose XOR is the target.
    #   This is a linear system problem: find min |x| such that x^T A = t.
    #   Then, implement those XORs.
    
    # But this doesn't share intermediate results.
    
    # Better: 
    # Maintain a set of available bitsets.
    # While there are unmet targets:
    #   For each unmet target t, compute the "cost" to produce it from available wires.
    #   Cost is the minimum number of gates.
    #   Choose the target with minimum cost.
    #   If cost is 0, it's already available (shouldn't happen).
    #   If cost is 1, find two available wires a, b such that a^b = t. Add gate.
    #   If cost > 1, we need to add intermediate wires.
    #     This is complex.
    
    # Given the small size, let's use a simpler heuristic:
    # 1. Compute the rank of the matrix.
    # 2. Perform Gaussian elimination to find a basis.
    # 3. Build the circuit for the basis vectors, then combine them to get targets.
    
    # Gaussian elimination approach:
    # Find a basis for the column space (or row space).
    
    # Let's try a different approach: 
    # Use the fact that we can XOR any two wires.
    # This is like building an arithmetic circuit over GF(2) with XOR gates only.
    
    # For n=8, 12, 16, the number of inputs is small.
    # We can precompute all possible bitsets (2^n).
    # We want to find the minimum number of XOR gates to produce all targets.
    
    # This is NP-hard in general, but for small n, we can use heuristics.
    
    # Heuristic: 
    # Start with inputs.
    # Repeatedly add the wire that is the XOR of two existing wires and is "most useful".
    # Usefulness: number of unmet targets that can be formed with fewer gates after adding this wire.
    
    # Let's implement a greedy algorithm:
    
    unmet = set(range(n_targets))
    
    while unmet:
        # Find the most useful next wire to add.
        # For each pair of available wires, compute their XOR.
        # For each such XOR w, compute how many unmet targets become "closer".
        
        best_wire = None
        best_score = -1
        best_parents = None
        
        available_wires = list(bitset_to_wire.keys())
        
        for i in range(len(available_wires)):
            for j in range(i + 1, len(available_wires)):
                w1 = available_wires[i]
                w2 = available_wires[j]
                w = w1 ^ w2
                if w in bitset_to_wire:
                    continue
                # Compute score: how many unmet targets can be expressed with 1 gate after adding w?
                # i.e., for each unmet target t, check if t == w or t == w ^ available_wire for some available_wire.
                score = 0
                for t_idx in unmet:
                    t = targets[t_idx]
                    # Check if t can be formed in 1 gate using w and one available wire.
                    # t == w ^ a for some available a => a == t ^ w
                    if (t ^ w) in bitset_to_wire:
                        score += 1
                    # Also check if t == w directly.
                    if t == w:
                        score += 1  # Actually this is 0 gates after adding w.
                
                # Prefer wires that directly match a target.
                if w in [targets[t_idx] for t_idx in unmet]:
                    score += 100
                
                if score > best_score:
                    best_score = score
                    best_wire = w
                    best_parents = (w1, w2)
        
        if best_wire is None:
            # No new wire can be formed? This shouldn't happen if targets are in the span.
            # Fallback: pick any pair.
            break
        
        # Add the gate.
        parent1_wire = bitset_to_wire[best_parents[0]]
        parent2_wire = bitset_to_wire[best_parents[1]]
        gates.append([parent1_wire, parent2_wire])
        
        new_wire = current_wire_count
        current_wire_count += 1
        wire_to_bitset[new_wire] = best_wire
        bitset_to_wire[best_wire] = new_wire
        
        # Check if any unmet target is now directly available.
        for t_idx in list(unmet):
            if targets[t_idx] == best_wire:
                unmet.remove(t_idx)
        
        # Also, check if any unmet target can now be formed in 0 gates (already available).
        # This is handled by the above.
    
    # Now, for each unmet target, we need to find a way to form it.
    # This should not happen if the greedy algorithm worked well, but let's be safe.
    
    outputs = []
    for i in range(n_targets):
        t = targets[i]
        if t in bitset_to_wire:
            outputs.append(bitset_to_wire[t])
        else:
            # Find a combination.
            # Use Gaussian elimination to find a representation.
            # For now, just add a gate for it if possible.
            found = False
            for i_w in range(len(available_wires)):
                for j_w in range(i_w + 1, len(available_wires)):
                    if available_wires[i_w] ^ available_wires[j_w] == t:
                        gates.append([i_w, j_w])
                        t_wire = len(available_wires)
                        available_wires.append(t)
                        bitset_to_wire[t] = t_wire
                        outputs.append(t_wire)
                        found = True
                        break
                if found:
                    break
            if not found:
                # This is an error case.
                outputs.append(0)
    
    return {'gates': gates, 'outputs': outputs}
