import time
from itertools import combinations
from math import gcd

def count_ordinary_lines(points):
    n = len(points)
    if n < 3:
        return 0
    
    lines = {}
    
    def get_line_key(p1, p2):
        x1, y1 = p1
        x2, y2 = p2
        A = y1 - y2
        B = x2 - x1
        C = x1 * y2 - x2 * y1
        
        g = gcd(gcd(abs(A), abs(B)), abs(C))
        if g != 0:
            A //= g
            B //= g
            C //= g
            
        if A < 0 or (A == 0 and B < 0) or (A == 0 and B == 0 and C < 0):
            A = -A
            B = -B
            C = -C
            
        return (A, B, C)

    for i in range(n):
        for j in range(i + 1, n):
            key = get_line_key(points[i], points[j])
            lines[key] = lines.get(key, 0) + 1
            
    ordinary = 0
    for key, pair_count in lines.items():
        if pair_count == 1:
            ordinary += 1
            
    return ordinary

def gcd(a, b):
    while b:
        a, b = b, a % b
    return a

def construct():
    # Base 3x3 grid
    base = [[x, y] for x in range(3) for y in range(3)]
    
    # Pre-computed set of candidates that are known to form good configurations
    # We search for 3 points from a small pool of "extensions"
    # The pool is generated by extending the 8 ordinary lines of the base grid
    # by small integer steps.
    
    def get_ordinary_lines_pts(pts):
        lines = {}
        for i in range(len(pts)):
            for j in range(i+1, len(pts)):
                key = get_line_key(pts[i], pts[j])
                if key not in lines:
                    lines[key] = []
                lines[key].append((i, j))
        
        ord_lines = []
        for key, pairs in lines.items():
            if len(pairs) == 1:
                i, j = pairs[0]
                ord_lines.append((pts[i], pts[j]))
        return ord_lines

    ord_lines = get_ordinary_lines_pts(base)
    
    candidates = set()
    for p1, p2 in ord_lines:
        x1, y1 = p1
        x2, y2 = p2
        dx = x2 - x1
        dy = y2 - y1
        for k in [-2, -1, 1, 2, 3]:
            if k == 0: continue
            px = x1 + k * dx
            py = y1 + k * dy
            if abs(px) <= 10**9 and abs(py) <= 10**9:
                if [px, py] not in base:
                    candidates.add((px, py))
                    
    # Also add some random nearby points to break symmetry if needed
    for x in range(-2, 5):
        for y in range(-2, 5):
            if [x, y] not in base:
                candidates.add((x, y))
                
    cand_list = list(candidates)
    
    best_score = float('inf')
    best_pts = None
    
    # Exhaustive search over combinations of 3
    # |cand_list| is small (approx 50-100)
    # C(100, 3) = 161,700. Fast.
    
    for i in range(len(cand_list)):
        for j in range(i+1, len(cand_list)):
            for k in range(j+1, len(cand_list)):
                p1 = cand_list[i]
                p2 = cand_list[j]
                p3 = cand_list[k]
                
                new_pts = base + [list(p1), list(p2), list(p3)]
                
                # Check distinctness
                if len(set(map(tuple, new_pts))) != 12:
                    continue
                
                score = count_ordinary_lines(new_pts)
                if score < best_score:
                    best_score = score
                    best_pts = new_pts
                    
                # Early exit if we hit the theoretical minimum
                if best_score == 6:
                    return best_pts
                    
    return best_pts
