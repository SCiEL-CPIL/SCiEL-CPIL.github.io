import time
import itertools
import random

N = 40

def construct():
    start_time = time.time()
    deadline = start_time + 85.0

    def get_lengths(S):
        """
        Calculate the set of cycle lengths generated by chords S on a rim of N.
        S is a set of integers (chord endpoints relative to 0).
        """
        lengths = {N}  # The rim
        for k in S:
            lengths.add(k + 1)
            lengths.add(N - k + 1)
        for u, v in itertools.combinations(S, 2):
            lengths.add(abs(u - v) + 2)
        return lengths

    def is_pancyclic(S):
        lengths = get_lengths(S)
        for L in range(3, N + 1):
            if L not in lengths:
                return False
        return True

    def missing_lengths(S):
        lengths = get_lengths(S)
        return set(range(3, N)) - lengths

    def build_result(S):
        edges = []
        # Rim
        for i in range(N):
            edges.append((i, (i + 1) % N))
        # Chords
        for k in sorted(S):
            edges.append((0, k))
        
        # Generate cycles
        cycles = []
        length_map = {}
        
        for k in S:
            l1 = k + 1
            l2 = N - k + 1
            if l1 not in length_map:
                length_map[l1] = ('chord_short', k)
            if l2 not in length_map:
                length_map[l2] = ('chord_long', k)
                
        for u, v in itertools.combinations(S, 2):
            l = abs(u - v) + 2
            if l not in length_map:
                length_map[l] = ('chord_pair', min(u, v), max(u, v))
                
        # Rim
        length_map[N] = ('rim',)
        
        # Construct cycles 3..N
        for L in range(3, N + 1):
            if L not in length_map:
                return None
            
            typ = length_map[L]
            if typ[0] == 'rim':
                cycles.append(list(range(N)))
            elif typ[0] == 'chord_short':
                k = typ[1]
                cycles.append([0] + list(range(1, k + 1)))
            elif typ[0] == 'chord_long':
                k = typ[1]
                cycles.append([0] + list(range(N - 1, k - 1, -1)))
            elif typ[0] == 'chord_pair':
                u, v = typ[1], typ[2]
                cycles.append([0, u] + list(range(u + 1, v + 1)))
                
        return {'edges': edges, 'cycles': cycles}

    def greedy_find_S(m, seed=0):
        """
        Greedy search for a set S of size m that covers all lengths 3..N.
        """
        target_lengths = set(range(3, N))  # Rim covers N
        candidates = list(range(2, N - 1))
        S = set()
        
        for _ in range(m):
            best_k = None
            best_gain = -1
            
            current_lengths = get_lengths(S)
            current_covered = current_lengths.intersection(target_lengths)
            
            for k in candidates:
                if k in S:
                    continue
                new_S = S.union({k})
                new_lengths = get_lengths(new_S)
                new_covered = new_lengths.intersection(target_lengths)
                gain = len(new_covered) - len(current_covered)
                
                if gain > best_gain:
                    best_gain = gain
                    best_k = k
            
            if best_k is None:
                return None
            
            S.add(best_k)
            
            if len(get_lengths(S).intersection(target_lengths)) == len(target_lengths):
                break
                
        if is_pancyclic(S):
            return S
        return None

    def local_search(S, max_iters=10000, seed=0):
        """
        Local search to try to fix a nearly-complete set S.
        """
        if time.time() > deadline:
            return None
            
        rng = random.Random(seed)
        current_S = set(S)
        
        for iteration in range(max_iters):
            if time.time() > deadline:
                return None
                
            if is_pancyclic(current_S):
                return current_S
                
            missing = missing_lengths(current_S)
            if not missing:
                return current_S
            
            improved = False
            for k in list(current_S):
                for new_k in range(2, N - 1):
                    if new_k in current_S:
                        continue
                    new_S = (current_S - {k}) | {new_k}
                    new_missing = missing_lengths(new_S)
                    if len(new_missing) < len(missing):
                        current_S = new_S
                        missing = new_missing
                        improved = True
                        break
                if improved:
                    break
            
            if not improved:
                k = rng.choice(list(current_S))
                new_k = rng.randint(2, N - 2)
                if new_k not in current_S:
                    current_S = (current_S - {k}) | {new_k}
                    missing = missing_lengths(current_S)
        
        if is_pancyclic(current_S):
            return current_S
        return None

    # First: try a known-good construction with 19 chords {2..20}
    S_known = set(range(2, 21))  # {2, 3, ..., 20}
    if is_pancyclic(S_known):
        result = build_result(S_known)
        if result:
            return result

    # Try to find minimal m with improved search
    # Use smarter initial sets and more aggressive local search
    candidates = list(range(2, N - 1))
    
    for m in [12, 13, 14, 15, 16, 17, 18]:
        if time.time() > deadline:
            break
        
        best_S = None
        best_missing_count = None
        
        # Try multiple random initializations
        for attempt in range(200):
            if time.time() > deadline:
                break
            
            rng = random.Random(1000 + m * 100 + attempt)
            
            if attempt < 5:
                # Structured starts
                if attempt == 0:
                    S = set(range(2, m + 2))  # {2, 3, ..., m+1}
                elif attempt == 1:
                    S = set(range(2, N - 1, (N - 3) // m))
                    if len(S) > m:
                        S = set(list(S)[:m])
                elif attempt == 2:
                    # Symmetric around N/2
                    half = N // 2
                    S = set()
                    for i in range(m):
                        k = 2 + i
                        S.add(k)
                elif attempt == 3:
                    # Spread out
                    S = set()
                    for i in range(m):
                        k = 2 + int(i * (N - 4) / max(1, m - 1))
                        S.add(k)
                else:
                    S = set(rng.sample(candidates, m))
            else:
                S = set(rng.sample(candidates, m))
            
            ml = len(missing_lengths(S))
            if best_missing_count is None or ml < best_missing_count:
                best_missing_count = ml
                best_S = set(S)
                if ml == 0:
                    result = build_result(S)
                    if result:
                        return result
            
            # Local search from this starting point
            if ml <= 5:
                S_fixed = local_search(S, max_iters=5000, seed=attempt)
                if S_fixed and is_pancyclic(S_fixed):
                    result = build_result(S_fixed)
                    if result:
                        return result
        
        # Final local search from best found
        if best_S is not None:
            S_fixed = local_search(best_S, max_iters=20000, seed=42)
            if S_fixed and is_pancyclic(S_fixed):
                result = build_result(S_fixed)
                if result:
                    return result

    # Fallback: the known 19-chord solution
    S_known = set(range(2, 21))
    result = build_result(S_known)
    if result:
        return result

    # Ultimate fallback: Fan Graph
    edges = [(0, i) for i in range(1, N)] + [(i, i + 1) for i in range(1, N - 1)]
    cycles = []
    for L in range(3, N + 1):
        cycles.append(list(range(L)))
        
    return {'edges': edges, 'cycles': cycles}
