def _build_4x4x4_burgisser():
    """Build rank-19 decomposition for 4x4x4 using Bürgisser's terms.
    Returns U (16,19), V (16,19), W (16,19) with integer entries.
    Indexing: U[i*4+j, r], V[j*4+k, r], W[k*4+i, r]
    """
    terms = _burgisser_19_terms_4x4x4()
    rank = len(terms)
    U = [[0] * rank for _ in range(16)]
    V = [[0] * rank for _ in range(16)]
    W = [[0] * rank for _ in range(16)]
    
    for r, term in enumerate(terms):
        for (i, j), val in term['U'].items():
            U[i * 4 + j][r] += val
        for (j, k), val in term['V'].items():
            V[j * 4 + k][r] += val
        for (k, i), val in term['W'].items():
            W[k * 4 + i][r] += val
    return U, V, W

def _verify(U, V, W, n, m, p):
    """Verify decomposition correctness."""
    U_mat = np.array(U, dtype=float)
    V_mat = np.array(V, dtype=float)
    W_mat = np.array(W, dtype=float)
    
    rng = np.random.RandomState(42)
    A = rng.randint(-5, 6, size=(n, m)).astype(float)
    B = rng.randint(-5, 6, size=(m, p)).astype(float)
    C_expected = A @ B
    
    C_computed = np.zeros((n, p))
    for r in range(len(U[0])):
        u = U_mat[:, r].reshape(n, m)
        v = V_mat[:, r].reshape(m, p)
        w = W_mat[:, r].reshape(p, n)
        a_proj = np.sum(A * u)
        b_proj = np.sum(B * v)
        C_computed += a_proj * b_proj * w.T
    
    return np.allclose(C_computed, C_expected, atol=1e-9)

def construct():
    """Construct rank-minimal decomposition for 4x4x8 matrix multiplication."""
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin before 150s kill
    
    n, m, p = DIMENSIONS
    
    # Strategy: Split p=8 into two halves of 4, use Bürgisser 19-rank for each 4x4x4
    # This gives rank 19*2 = 38
    U_444, V_444, W_444 = _build_4x4x4_burgisser()
    
    U_444_np = np.array(U_444, dtype=float)
    V_444_np = np.array(V_444, dtype=float)
    W_444_np = np.array(W_444, dtype=float)
    
    rank = 38
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # First half: C_left = A @ B_left
    U[:, :19] = U_444_np
    
    # V: j*8+k where k in 0..3 (left half)
    for r in range(19):
        for row in range(16):
            j = row // 4
            k = row % 4
            V[j * 8 + k, r] = V_444_np[row, r]
            
    # W: k*4+i where k in 0..3 (left half of output)
    W[:16, :19] = W_444_np
    
    # Second half: C_right = A @ B_right
    U[:, 19:] = U_444_np
    
    # V: j*8+k where k in 4..7 (right half)
    for r in range(19):
        for row in range(16):
            j = row // 4
            k = row % 4
            V[j * 8 + (k + 4), 19 + r] = V_444_np[row, r]
            
    # W: k*4+i where k in 4..7 (right half of output)
    W[16:, 19:] = W_444_np
    
    U_list = U.tolist()
    V_list = V.tolist()
    W_list = W.tolist()
    
    # Verify
    if time.time() < deadline - 10.0:
        if not _verify(U_list, V_list, W_list, n, m, p):
            # Fallback to schoolbook
            rank_fb = n * m * p
            U_fb = np.zeros((n * m, rank_fb))
            V_fb = np.zeros((m * p, rank_fb))
            W_fb = np.zeros((p * n, rank_fb))
            col = 0
            for i in range(n):
                for j in range(m):
                    for k in range(p):
                        U_fb[i * m + j, col] = 1
                        V_fb[j * p + k, col] = 1
                        W_fb[k * n + i, col] = 1
                        col += 1
            return {"U": U_fb.tolist(), "V": V_fb.tolist(), "W": W_fb.tolist()}
    
    return {"U": U_list, "V": V_list, "W": W_list}
