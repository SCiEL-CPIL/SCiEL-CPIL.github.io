def _build_3x3x6_from_3x3x3(U3, V3, W3):
    """Construct 3x3x6 decomposition from two 3x3x3 blocks."""
    n, m, p = 3, 3, 6
    rank = 46
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # Block 1: k in 0..2
    U[:, 0:23] = U3
    for j in range(3):
        for k in range(3):
            V[j * 6 + k, 0:23] = V3[j * 3 + k, 0:23]
    for k in range(3):
        for i in range(3):
            W[k * 3 + i, 0:23] = W3[k * 3 + i, 0:23]
            
    # Block 2: k in 3..5
    U[:, 23:46] = U3
    for j in range(3):
        for k in range(3):
            V[j * 6 + (k + 3), 23:46] = V3[j * 3 + k, 0:23]
    for k in range(3):
        for i in range(3):
            W[(k + 3) * 3 + i, 23:46] = W3[k * 3 + i, 0:23]
            
    return U, V, W

def construct():
    start_time = time.time()
    n, m, p = DIMENSIONS
    
    # Try BCLR
    try:
        U3, V3, W3 = _build_bclr_3x3x3()
        U, V, W = _build_3x3x6_from_3x3x3(U3, V3, W3)
        if _verify(U, V, W, n, m, p):
            return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
    except Exception:
        pass
        
    # Fallback to Schoolbook
    U, V, W = _build_schoolbook(n, m, p)
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
