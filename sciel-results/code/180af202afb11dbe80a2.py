"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import numpy as np
import time
import random

def priority(adjacency):
    """
    Computes priority scores for vertices to maximize the size of the
    independent set generated by a greedy decoder.
    
    Args:
        adjacency: A boolean matrix or array-like where adjacency[i][j] is True
                   if vertex i is connected to vertex j.
    
    Returns:
        A numpy array of scores, one per vertex.
    """
    # Ensure adjacency is a numpy boolean array
    adj = np.array(adjacency, dtype=bool)
    n = adj.shape[0]
    
    # Precompute neighbor lists for faster evaluation
    # Using lists of lists for O(1) neighbor iteration
    neighbors = [list(np.where(adj[i])[0]) for i in range(n)]
    
    def evaluate(scores):
        """
        Simulates the greedy decoder:
        1. Sort vertices by score descending.
        2. Iterate, selecting vertex if not blocked.
        3. Block neighbors of selected vertex.
        Returns the size of the independent set.
        """
        # Sort indices by score descending
        # stable sort is not strictly necessary but good for consistency
        order = np.argsort(-scores, kind='stable')
        
        blocked = np.zeros(n, dtype=bool)
        count = 0
        
        for v in order:
            if not blocked[v]:
                count += 1
                # Block all neighbors
                for u in neighbors[v]:
                    blocked[u] = True
                # Also block the vertex itself to prevent re-selection if logic changed, 
                # but since we iterate unique vertices, it's not strictly needed 
                # unless we had duplicates, which we don't. 
                # However, marking it blocked ensures if we had a different loop structure it'd be safe.
                blocked[v] = True
                
        return count

    # Initial scores: negative degree (baseline)
    degrees = adj.sum(axis=1)
    best_scores = -degrees.astype(float)
    current_scores = best_scores.copy()
    
    best_size = evaluate(best_scores)
    current_size = best_size
    
    # Randomness seed for reproducibility in local search (optional but good)
    # Using a fixed seed might be better for deterministic behavior, 
    # but random is fine too. Let's use random module.
    
    start_time = time.time()
    time_limit = 140.0  # Safety margin for 150s limit
    
    temperature = 1.0
    cooling_rate = 0.999
    
    # Local search loop
    while time.time() - start_time < time_limit:
        # Generate a neighbor solution
        # Strategy: Swap two random vertices' scores
        i, j = random.sample(range(n), 2)
        new_scores = current_scores.copy()
        new_scores[i], new_scores[j] = current_scores[j], current_scores[i]
        
        new_size = evaluate(new_scores)
        
        delta = new_size - current_size
        
        # Accept if better or with probability exp(delta/T)
        if delta > 0 or random.random() < np.exp(delta / temperature):
            current_scores = new_scores
            current_size = new_size
            
            if current_size > best_size:
                best_size = current_size
                best_scores = current_scores.copy()
        
        # Cool down
        temperature *= cooling_rate
        
        # If temperature gets too low, reheat or stop?
        # Given time limit, just keep going.
        
    return best_scores

# EVOLVE-BLOCK-END
