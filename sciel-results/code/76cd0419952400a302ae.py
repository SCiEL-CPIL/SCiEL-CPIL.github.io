def count_ordinary_lines(points):
    """
    Count the number of lines containing exactly two of the given points.
    points: list of [x, y]
    """
    n = len(points)
    if n < 2:
        return 0
    
    # Map from line representation to count of points on that line
    # Line representation: (A, B, C) for Ax + By + C = 0, normalized
    # To avoid floating point, use integers.
    # For two points (x1, y1) and (x2, y2):
    # A = y2 - y1
    # B = x1 - x2
    # C = -(A*x1 + B*y1)
    # Normalize: divide by gcd(A, B, C) and ensure a canonical sign.
    
    lines = {}
    
    for i in range(n):
        for j in range(i + 1, n):
            x1, y1 = points[i]
            x2, y2 = points[j]
            
            A = y2 - y1
            B = x1 - x2
            C = -(A * x1 + B * y1)
            
            # Normalize
            # Find GCD of A, B, C
            # Handle zeros
            g = 0
            def gcd(a, b):
                while b:
                    a, b = b, a % b
                return abs(a)
            
            g = gcd(gcd(A, B), C)
            if g == 0:
                # Should not happen for distinct points
                continue
            A //= g
            B //= g
            C //= g
            
            # Canonical sign: first non-zero of A, B, C should be positive
            if A < 0 or (A == 0 and B < 0) or (A == 0 and B == 0 and C < 0):
                A = -A
                B = -B
                C = -C
            
            key = (A, B, C)
            lines[key] = lines.get(key, 0) + 1
    
    ordinary_count = 0
    for key, count in lines.items():
        if count == 1:
            # This line was generated by exactly 1 pair.
            # Since each line with k points generates k*(k-1)/2 pairs,
            # if count==1, it means k=2 (since 2*1/2 = 1).
            # If k>=3, count >= 3.
            ordinary_count += 1
            
    return ordinary_count

