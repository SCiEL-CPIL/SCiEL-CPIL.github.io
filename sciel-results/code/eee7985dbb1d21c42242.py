import time
import itertools
import random

N = 40

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin for evaluator's 60s limit

    # Precompute candidate chords and their generated cycle lengths
    # Chord k (0 < k < N/2, since chords are symmetric) generates lengths:
    #   - k+1 (short path along rim + chord)
    #   - N-k+1 (long path along rim + chord)
    # Two chords k1, k2 (k1 < k2) generate additional length:
    #   - abs(k2-k1)+2 (path through chord1 -> rim segment -> chord2)

    # For the "general" case where chords don't all share a common vertex,
    # we need a different approach. But let's first optimize the fan-based
    # approach, then try a small perturbation search.

    all_chords = list(range(2, N // 2 + 1))  # 2..20

    def chord_lengths(k):
        """Lengths generated by single chord k from vertex 0."""
        s = set()
        s.add(k + 1)
        s.add(N - k + 1)
        return s

    def pair_lengths(k1, k2):
        """Length generated by two chords k1, k2 from vertex 0 (k1 < k2)."""
        return abs(k2 - k1) + 2

    # Target lengths: 3..N-1 (the rim covers N)
    target = set(range(3, N))

    # Precompute for each chord k the set of target lengths it covers alone
    chord_cover = {}
    for k in all_chords:
        chord_cover[k] = chord_lengths(k) & target

    # Precompute pair coverage
    pair_cover = {}
    for i, k1 in enumerate(all_chords):
        for k2 in all_chords[i+1:]:
            l = pair_lengths(k1, k2)
            if l in target:
                pair_cover[(k1, k2)] = {l}
            else:
                pair_cover[(k1, k2)] = set()

    # Function to compute total coverage for a set S of chords
    def total_coverage(S):
        covered = set()
        for k in S:
            covered |= chord_cover[k]
        for u in S:
            for v in S:
                if u < v:
                    covered |= pair_cover[(u, v)]
                elif v < u:
                    covered |= pair_cover[(v, u)]
        return covered & target

    # Greedy search with randomization for multiple trials
    def greedy_search(m, seed=None):
        rng = random.Random(seed)
        S = set()
        candidates = all_chords[:]

        for step in range(m):
            if time.time() > deadline:
                return None
            best_gain = -1
            best_k = None
            # Randomize candidate order for diversity
            shuffled = candidates[:]
            rng.shuffle(shuffled)
            for k in shuffled:
                if k in S:
                    continue
                new_S = S | {k}
                cov = total_coverage(new_S)
                gain = len(cov)
                if gain > best_gain:
                    best_gain = gain
                    best_k = k
            if best_k is None:
                return None
            S.add(best_k)
            if best_gain >= len(target):
                break

        if len(total_coverage(S)) >= len(target):
            return S
        return None

    # Also try a more systematic approach: pick chords that together
    # produce exactly the needed lengths.

    # Key insight: With m chords from vertex 0, we get:
    # - m values of form k+1
    # - m values of form N-k+1 = N+1-k
    # - C(m,2) values of form |k_i - k_j| + 2
    # Total distinct lengths: up to 2m + C(m,2)
    # Need to cover 37 lengths (3..39)
    # 2m + m(m-1)/2 >= 37
    # m=8: 16+28=44 >= 37 ✓
    # m=7: 14+21=35 < 37 ✗ (if all distinct)
    # So minimum possible is m=8.

    best_S = None

    # First try systematic: find S of size 8 via greedy with different seeds
    for seed in range(50):
        if time.time() > deadline:
            break
        S = greedy_search(8, seed)
        if S is not None:
            best_S = S
            break

    # If not found, try m=9
    if best_S is None:
        for seed in range(50):
            if time.time() > deadline:
                break
            S = greedy_search(9, seed)
            if S is not None:
                best_S = S
                break

    # If still not found, use a known construction
    if best_S is None:
        # Try specific known-good sets
        test_sets = [
            set([2, 3, 4, 5, 6, 8, 10, 13]),
            set([2, 3, 4, 5, 7, 9, 12, 16]),
            set([2, 4, 5, 7, 9, 11, 14, 17]),
            set([2, 3, 4, 5, 6, 7, 9, 12]),
            set([2, 3, 4, 6, 7, 9, 11, 15]),
            set([2, 3, 5, 6, 8, 10, 13, 16]),
            set([3, 4, 5, 6, 7, 9, 11, 14]),
            set([2, 4, 6, 7, 9, 11, 13, 16]),
        ]
        for S_test in test_sets:
            if len(total_coverage(S_test)) >= len(target):
                best_S = S_test
                break

    # Fallback fan
    if best_S is None:
        edges = [(0, i) for i in range(1, N)] + [(i, i + 1) for i in range(1, N - 1)]
        cycles = []
        for L in range(3, N + 1):
            cycles.append(list(range(L)))
        return {'edges': edges, 'cycles': cycles}

    # Build the result from best_S
    S = best_S
    S_sorted = sorted(S)

    edges = []
    # Rim
    for i in range(N):
        edges.append((i, (i + 1) % N))
    # Chords from vertex 0
    for k in S_sorted:
        edges.append((0, k))

    # Map each length 3..N to how to construct the cycle
    length_to_cycle = {}

    # Rim gives length N
    length_to_cycle[N] = list(range(N))

    for k in S_sorted:
        # Short cycle: 0, 1, 2, ..., k
        l1 = k + 1
        if l1 not in length_to_cycle and l1 in target:
            length_to_cycle[l1] = list(range(k + 1))

        # Long cycle: 0, N-1, N-2, ..., k, then back
        l2 = N - k + 1
        if l2 not in length_to_cycle and l2 in target:
            # Cycle: 0, N-1, N-2, ..., k (going the long way)
            # Vertices: 0, then N-1 down to k
            # That's 0 + (N-1-k+1) vertices = N-k+1 vertices
            cyc = [0]
            for v in range(N - 1, k - 1, -1):
                cyc.append(v)
            # Check: len(cyc) should be N-k+1
            # cyc = [0, N-1, N-2, ..., k]
            # Number of elements: 1 + (N-1-k+1) = N-k+1 ✓
            if len(cyc) == l2:
                length_to_cycle[l2] = cyc

    for i, u in enumerate(S_sorted):
        for v in S_sorted[i + 1:]:
            l = abs(v - u) + 2
            if l not in length_to_cycle and l in target:
                # Cycle: 0 -> u -> u+1 -> ... -> v -> 0
                # That's 0, u, u+1, ..., v: length = 1 + (v-u) + 1 = v-u+2 = |v-u|+2 ✓
                cyc = [0] + list(range(u, v + 1))
                if len(cyc) == l:
                    length_to_cycle[l] = cyc

    # Check if we covered everything
    missing = target - set(length_to_cycle.keys())
    if missing:
        # Fallback: use fan
        edges = [(0, i) for i in range(1, N)] + [(i, i + 1) for i in range(1, N - 1)]
        cycles = []
        for L in range(3, N + 1):
            cycles.append(list(range(L)))
        return {'edges': edges, 'cycles': cycles}

    # Build cycles list in order 3..N
    cycles = []
    for L in range(3, N + 1):
        if L in length_to_cycle:
            cycles.append(length_to_cycle[L])
        else:
            # Should not happen, but fallback
            cycles.append(list(range(L)))

    return {'edges': edges, 'cycles': cycles}
