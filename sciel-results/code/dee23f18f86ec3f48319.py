import numpy as np

DIMENSIONS = [3, 3, 3]

def construct():
    n, m, p = 3, 3, 3
    R = n * m * p
    U = np.zeros((n * m, R), dtype=float)
    V = np.zeros((m * p, R), dtype=float)
    W = np.zeros((p * n, R), dtype=float)
    
    c = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j, c] = 1.0
                V[j * p + k, c] = 1.0
                W[k * n + i, c] = 1.0
                c += 1
    
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
