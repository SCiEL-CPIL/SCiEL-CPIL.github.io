DIMENSIONS = [2, 3, 9]

# EVOLVE-BLOCK-START
def construct():
    # Schoolbook decomposition of rank n*m*p for matrix multiplication A(n x m) * B(m x p)
    # U has shape (n*m, rank), V has shape (m*p, rank), W has shape (p*n, rank)
    n, m, p = DIMENSIONS
    r = n * m * p
    U = [[0.0] * r for _ in range(n * m)]
    V = [[0.0] * r for _ in range(m * p)]
    W = [[0.0] * r for _ in range(p * n)]
    c = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][c] = 1.0
                V[j * p + k][c] = 1.0
                W[k * n + i][c] = 1.0
                c += 1
    return {"U": U, "V": V, "W": W}
# EVOLVE-BLOCK-END
