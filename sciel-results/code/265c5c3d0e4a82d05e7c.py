import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    N = 1000
    max_sum = 2 * N
    
    # Bitset representation for S and Tight Sums
    # S_mask: bit i set if i in S
    # TightMask: bit s set if sum s has count == 2
    
    def greedy_with_order(order):
        S_mask = 0
        TightMask = 0
        counts = np.zeros(max_sum + 1, dtype=np.int32)
        S_set = set() # For fast membership and iteration if needed, though we can extract from mask
        # Actually, maintaining a list or set for iteration in update is fine.
        
        for x in order:
            # Check validity using bitsets
            # Sums generated by x + y for y in S are bits in (S_mask << x)
            # We need to ensure none of these sums are already tight (count == 2)
            # And 2*x is not tight
            
            # Check if (S_mask << x) intersects with TightMask
            # Note: S_mask has bits 0..N. Shifting by x gives bits x..N+x.
            # TightMask has bits 2..2N.
            
            # Optimization: Only check bits that could be tight.
            # If ((S_mask << x) & TightMask) != 0, invalid.
            # Also check 2*x.
            
            if ((S_mask << x) & TightMask) != 0:
                continue
            if (TightMask >> (2 * x)) & 1:
                continue
                
            # Valid, add x
            S_mask |= (1 << x)
            S_set.add(x)
            
            # Update counts and TightMask
            # For each y in S, sum = x + y
            # counts[sum] += 1
            # If counts[sum] becomes 2, set bit in TightMask
            # If counts[sum] becomes > 2, this shouldn't happen if check was correct
            
            # We iterate through current S
            # To make this fast, we can iterate through the bits of S_mask?
            # Or just keep a list of elements.
            # Since S is small (~300), iterating a list is fast.
            for y in list(S_set):
                s = x + y
                old_count = counts[s]
                new_count = old_count + 1
                counts[s] = new_count
                if new_count == 2:
                    TightMask |= (1 << s)
                    # If it was 1, it's now 2.
                    # It cannot go from 2 to 3 because we checked that s was not in TightMask (count != 2).
                    # Wait, the check was ((S_mask << x) & TightMask) == 0.
                    # This means for all y in S, x+y is NOT in TightMask.
                    # So counts[x+y] was 0 or 1.
                    # So new_count is 1 or 2.
                    # If new_count == 2, we set the bit.
            
            # Handle 2*x
            s = 2 * x
            old_count = counts[s]
            new_count = old_count + 1
            counts[s] = new_count
            if new_count == 2:
                TightMask |= (1 << s)
                
        return len(S_set), S_set, S_mask, TightMask, counts

    best_size = 0
    best_set = set()
    
    # Phase 1: Greedy Restarts
    # Different orderings
    orders = [
        list(range(1, N + 1)),
        list(range(N, 0, -1)),
    ]
    
    random.seed(42)
    # Generate random orders
    for i in range(20):
        o = list(range(1, N + 1))
        random.shuffle(o)
        orders.append(o)
        
    # Also try "density" based order? E.g. prefer numbers with fewer small factors?
    # Or just random is good enough with bitsets.
    
    for order in orders:
        if time.time() > deadline - 10:
            break
        size, S_set, S_mask, TightMask, counts = greedy_with_order(order)
        if size > best_size:
            best_size = size
            best_set = S_set.copy()
            
    # Phase 2: Local Search / Improvement
    # Try to add more elements to the best set found
    # Rebuild state from best_set
    S_mask = 0
    for x in best_set:
        S_mask |= (1 << x)
        
    counts = np.zeros(max_sum + 1, dtype=np.int32)
    TightMask = 0
    S_list = sorted(best_set)
    for i in range(len(S_list)):
        for j in range(i, len(S_list)):
            s = S_list[i] + S_list[j]
            counts[s] += 1
            if counts[s] == 2:
                TightMask |= (1 << s)
                
    # Try to add any remaining elements
    # We can try all elements 1..N and see if they fit
    added = True
    while added and time.time() < deadline - 5:
        added = False
        for x in range(1, N + 1):
            if x in best_set:
                continue
            if ((S_mask << x) & TightMask) != 0:
                continue
            if (TightMask >> (2 * x)) & 1:
                continue
                
            # Add x
            best_set.add(x)
            S_mask |= (1 << x)
            
            for y in best_set:
                if y == x:
                    continue
                s = x + y
                counts[s] += 1
                if counts[s] == 2:
                    TightMask |= (1 << s)
                    
            s = 2 * x
            counts[s] += 1
            if counts[s] == 2:
                TightMask |= (1 << s)
                
            added = True
            # Restart loop to check if more can be added
            break
            
    best_size = len(best_set)
    
    # Phase 3: Swap-based Local Search
    # Try to swap an element to allow more additions
    # This is complex. Given time constraints, the greedy + fill should be strong.
    # Let's try a few random swaps if time permits.
    
    if time.time() < deadline - 2:
        current_size = len(best_set)
        # We need to be able to remove elements quickly.
        # Let's stick to the current set and just return.
        # The "fill" phase usually finds the local optimum for the greedy seed.
        
    return sorted(best_set)
