def _schoolbook_3x3():
    """Schoolbook rank-27 for 3x3x3."""
    n, m, p = 3, 3, 3
    rank = 27
    U = np.zeros((9, rank), dtype=float)
    V = np.zeros((9, rank), dtype=float)
    W = np.zeros((9, rank), dtype=float)
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j, col] = 1.0
                V[j * p + k, col] = 1.0
                W[k * n + i, col] = 1.0
                col += 1
    return U, V, W

def _kronecker_product(U1, V1, W1, U2, V2, W2, n1, m1, p1, n2, m2, p2):
    """
    Kronecker product of two tensor decompositions.
    """
    r1 = U1.shape[1]
    r2 = U2.shape[1]
    r = r1 * r2
    
    n = n1 * n2
    m = m1 * m2
    p = p1 * p2
    
    U = np.zeros((n * m, r), dtype=float)
    V = np.zeros((m * p, r), dtype=float)
    W = np.zeros((p * n, r), dtype=float)
    
    for c1 in range(r1):
        for c2 in range(r2):
            c = c1 * r2 + c2
            for i1 in range(n1):
                for j1 in range(m1):
                    for i2 in range(n2):
                        for j2 in range(m2):
                            u_val = U1[i1 * m1 + j1, c1] * U2[i2 * m2 + j2, c2]
                            if u_val != 0:
                                idx = (i1 * n2 + i2) * m + (j1 * m2 + j2)
                                U[idx, c] = u_val
            for j1 in range(m1):
                for k1 in range(p1):
                    for j2 in range(m2):
                        for k2 in range(p2):
                            v_val = V1[j1 * p1 + k1, c1] * V2[j2 * p2 + k2, c2]
                            if v_val != 0:
                                idx = (j1 * m2 + j2) * p + (k1 * p2 + k2)
                                V[idx, c] = v_val
            for k1 in range(p1):
                for i1 in range(n1):
                    for k2 in range(p2):
                        for i2 in range(n2):
                            w_val = W1[k1 * n1 + i1, c1] * W2[k2 * n2 + i2, c2]
                            if w_val != 0:
                                idx = (k1 * p2 + k2) * n + (i1 * n2 + i2)
                                W[idx, c] = w_val
    
    return U, V, W

