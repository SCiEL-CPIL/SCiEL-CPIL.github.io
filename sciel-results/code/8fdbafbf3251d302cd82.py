def _validate(U, V, W, n, m, p):
    """Exact check: for every (i,k), M[i,k] = sum_j U[i*m+j]*V[j*p+k] must equal W[k*n+i].
    
    The tensor decomposition requires:
    For all i in [0,n), j in [0,m), k in [0,p):
        sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] = 1 if this is a valid multiplication triple
    And for all other combinations, the sum should be 0.
    
    Actually, the correct condition is:
    For all i, j, k: sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] should equal
    the (i,k) entry of A*B, which is sum_j A[i,j]*B[j,k].
    
    But since we're decomposing the multiplication tensor, the condition is:
    For all i in [0,n), k in [0,p):
        sum_j sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] = 1 (for the standard basis)
    
    Wait, I need to think about this more carefully. The matrix multiplication tensor T is defined as:
    T[i,j,k] = 1 if i,j,k form a valid triple (i.e., they're all in range), else 0.
    
    Actually no. The multiplication tensor for C^{n x m} * C^{m x p} -> C^{n x p} has entries:
    T[(i,k), j] = 1 if we're computing C[i,k] = sum_j A[i,j] * B[j,k]
    
    So the tensor has dimensions (n*p) x m, and T[(i,k), j] = 1 for all valid i,j,k.
    
    A rank-r decomposition gives matrices U (n*m x r), V (m*p x r), W (p*n x r) such that:
    For all i in [0,n), j in [0,m), k in [0,p):
        sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] = 1
    
    And for all other index combinations (where the triple doesn't correspond to a valid multiplication),
    the sum should be 0. But actually, since we're only indexing valid triples, we just need:
    For all i in [0,n), j in [0,m), k in [0,p):
        sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] = 1
    """
    r = len(U[0])
    for i in range(n):
        for j in range(m):
            for k in range(p):
                s = 0
                for c in range(r):
                    s += U[i * m + j][c] * V[j * p + k][c] * W[k * n + i][c]
                if s != 1:
                    return False
    return True


def _schoolbook(n, m, p):
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
    return {"U": U, "V": V, "W": W}


