"""
Closed-loop feedback control pulse synthesis for 3-level transmon X-pi gate.
The pulse is generated by a PID controller that tracks the ideal unitary trajectory,
suppressing leakage to |2> via error feedback. Only 5 controller gains are optimized.
"""
# EVOLVE-BLOCK-START
import numpy as np
import scipy.linalg as sla
import time
from scipy.optimize import minimize

# --- Constants ---
DT = 0.5
N_STEPS = 80
GATE_TIME = 40.0
T1 = 25000.0
Tphi = 40000.0
ANHARMONICITY = -2 * np.pi * 0.25
DETUNING_VALUES = np.array([-2 * np.pi * 0.002, 0, 2 * np.pi * 0.002])
SCALE_VALUES = np.array([0.97, 1.0, 1.03])
AMP_BOUND = 0.4
SLEW_BOUND = 0.12

# Precompute constant matrices
A_MAT = np.array([[0, 1, 0],
                  [0, 0, np.sqrt(2)],
                  [0, 0, 0]], dtype=complex)
AD_MAT = A_MAT.conj().T
N_MAT = AD_MAT @ A_MAT
I3 = np.eye(3, dtype=complex)

# Lindblad operators
G1 = A_MAT / np.sqrt(T1)
G2 = N_MAT * np.sqrt(2.0 / Tphi)
G1DAG = G1.conj().T
G2DAG = G2.conj().T
G1DAG_G1 = G1DAG @ G1
G2DAG_G2 = G2DAG @ G2

DISS_L = (np.kron(G1, G1.conj()) - 0.5 * (np.kron(G1DAG_G1, I3) + np.kron(I3, G1DAG_G1.T)) +
          np.kron(G2, G2.conj()) - 0.5 * (np.kron(G2DAG_G2, I3) + np.kron(I3, G2DAG_G2.T)))

# Target operator X
X3 = np.array([[0, 1, 0],
               [1, 0, 0],
               [0, 0, 1]], dtype=complex)

# Test states
STATES = [
    np.array([1, 0, 0], dtype=complex),
    np.array([0, 1, 0], dtype=complex),
    np.array([1, 1, 0], dtype=complex) / np.sqrt(2),
    np.array([1, -1, 0], dtype=complex) / np.sqrt(2),
    np.array([1, 1j, 0], dtype=complex) / np.sqrt(2),
    np.array([1, -1j, 0], dtype=complex) / np.sqrt(2),
]

def build_hamiltonian(detuning, scale, I_val, Q_val):
    NN1 = N_MAT @ (N_MAT - I3)
    H = (detuning * N_MAT + 0.5 * ANHARMONICITY * NN1 +
         0.5 * scale * (I_val * (A_MAT + AD_MAT) + 1j * Q_val * (A_MAT - AD_MAT)))
    return H

def build_liouvillian_full(H):
    coh_L = -1j * (np.kron(H, I3) - np.kron(I3, H.T))
    return coh_L + DISS_L

def check_validity(pulse):
    for i in range(len(pulse)):
        amp = np.sqrt(pulse[i, 0]**2 + pulse[i, 1]**2)
        if amp > AMP_BOUND + 1e-9:
            return False
    prev = np.array([0.0, 0.0])
    for i in range(len(pulse)):
        curr = pulse[i]
        diff = np.linalg.norm(curr - prev) / DT
        if diff > SLEW_BOUND + 1e-9:
            return False
        prev = curr
    diff = np.linalg.norm(prev - np.array([0.0, 0.0])) / DT
    if diff > SLEW_BOUND + 1e-9:
        return False
    return True

def enforce_constraints(pulse):
    pulse = pulse.copy()
    for i in range(N_STEPS):
        amp = np.sqrt(pulse[i, 0]**2 + pulse[i, 1]**2)
        if amp > AMP_BOUND:
            pulse[i] *= AMP_BOUND / amp
    prev = np.array([0.0, 0.0])
    for i in range(N_STEPS):
        diff = pulse[i] - prev
        dn = np.linalg.norm(diff)
        max_d = SLEW_BOUND * DT
        if dn > max_d:
            pulse[i] = prev + diff * (max_d / dn)
        prev = pulse[i]
    prev = np.array([0.0, 0.0])
    for i in range(N_STEPS - 1, -1, -1):
        diff = pulse[i] - prev
        dn = np.linalg.norm(diff)
        max_d = SLEW_BOUND * DT
        if dn > max_d:
            pulse[i] = prev + diff * (max_d / dn)
        prev = pulse[i]
    for i in range(N_STEPS):
        amp = np.sqrt(pulse[i, 0]**2 + pulse[i, 1]**2)
        if amp > AMP_BOUND:
            pulse[i] *= AMP_BOUND / amp
    return pulse

def generate_pulse_feedback(gains, detuning=0.0, scale=1.0):
    """
    Generate a pulse using closed-loop feedback control.
    gains = [Kp, Ki, Kd, ff_gain, drag_gain]
    
    The controller tracks the ideal unitary trajectory of the 2-level subspace.
    Error is measured as deviation of the actual state from the target trajectory.
    The control signal corrects this error in real-time.
    """
    Kp, Ki, Kd, ff_gain, drag_gain = gains
    
    # Ideal 2-level trajectory: Rabi oscillation at resonance
    # For an X-pi gate, the ideal drive is a constant amplitude for the full duration
    # with a DRAG correction term to suppress |2> leakage
    t = np.arange(N_STEPS) * DT
    center = GATE_TIME / 2.0
    
    # Feedforward: ideal Rabi drive (constant for pi gate)
    # Area must be pi: A * GATE_TIME = pi => A = pi/40
    ff_amp = np.pi / GATE_TIME  # ~0.0785
    
    # Gaussian envelope for smoother edges (helps with slew constraint)
    sigma = 8.0
    envelope = np.exp(-0.5 * ((t - center) / sigma)**2)
    edge_val = envelope[0]
    envelope = envelope - edge_val
    if np.max(envelope) > 0:
        envelope = envelope / np.max(envelope)
    
    # Feedforward signal
    I_ff = ff_gain * ff_amp * envelope
    Q_ff = np.zeros(N_STEPS)
    
    # DRAG term from feedforward
    d_envelope = np.gradient(envelope) / DT
    Q_drag = drag_gain * ff_amp * d_envelope * sigma**2
    
    # Now simulate with feedback
    # State vector in 3-level system, starting from |0>
    # Target: track the ideal 2-level evolution
    # The ideal trajectory in the 2-level subspace for X-pi:
    # |psi_ideal(t)> = cos(pi*t/(2*T)) |0> + i sin(pi*t/(2*T)) |1> (up to phase)
    # Actually for X-pi: |0> -> |1>, so at time t: cos(pi t / T) |0> + i sin(pi t / T) |1>
    
    # We'll use a simple feedback: measure the |2> component and the deviation
    # from the ideal 2-level trajectory, and apply corrective drive.
    
    # For efficiency, we simulate the actual evolution and use the state error
    # to generate the feedback signal. This is a "digital" feedback where we
    # compute the pulse step-by-step.
    
    I_pulse = np.zeros(N_STEPS)
    Q_pulse = np.zeros(N_STEPS)
    
    # State: density matrix vector (9 elements)
    rho = np.zeros(9, dtype=complex)
    rho[0] = 1.0  # |0><0|
    
    # Integral term for PID
    integral_error = 0.0
    prev_error = 0.0
    
    # Precompute target trajectory amplitudes
    # Ideal: the drive that would produce perfect X-pi in 2-level
    # For feedback, we track the population in |2> and correct
    
    for i in range(N_STEPS):
        # Compute target state at this time (ideal 2-level)
        theta = np.pi * (i * DT) / GATE_TIME
        # Ideal state: cos(theta)|0> + i*sin(theta)|1>
        # Target density matrix elements (only 0-1 subspace)
        # The error signal: how much is in |2> and how much deviates from ideal
        
        # Measure current state populations
        rho_mat = rho.reshape(3, 3)
        pop_2 = np.real(rho_mat[2, 2])
        
        # Measure deviation from ideal 2-level trajectory
        # Ideal: rho_00 = cos^2(theta), rho_11 = sin^2(theta), rho_01 = -i cos(theta)sin(theta)
        ideal_rho_01 = -1j * np.cos(theta) * np.sin(theta)
        actual_rho_01 = rho_mat[0, 1]
        
        # Error in coherence
        coherence_error = np.real(np.conj(ideal_rho_01) * actual_rho_01) - np.cos(theta)**2 * np.sin(theta)**2
        # Simpler: just use |2> population as primary error
        error = pop_2 - 0.0  # Want to suppress |2>
        
        # PID control
        integral_error += error * DT
        derivative_error = (error - prev_error) / DT if i > 0 else 0.0
        prev_error = error
        
        # Feedback correction (negative to suppress leakage)
        # The feedback acts on Q channel primarily (to correct phase/leakage)
        fb_I = -Kp * error - Ki * integral_error - Kd * derivative_error
        fb_Q = -Kp * error * 0.5 - Ki * integral_error * 0.5 - Kd * derivative_error * 0.5
        
        # Total pulse
        I_pulse[i] = I_ff[i] + fb_I
        Q_pulse[i] = Q_ff[i] + Q_drag[i] + fb_Q
        
        # Evolve state by one step
        H = build_hamiltonian(detuning, scale, I_pulse[i], Q_pulse[i])
        L = build_liouvillian_full(H)
        E = sla.expm(L * DT)
        rho = E @ rho
    
    pulse = np.column_stack((I_pulse, Q_pulse))
    return pulse

def compute_score(pulse, verbose=False):
    """Compute the score: mean + max infidelity over 9 cases."""
    case_infidelities = []
    
    for detuning in DETUNING_VALUES:
        for scale in SCALE_VALUES:
            # Evolve all 6 states
            infidelities = []
            for psi0 in STATES:
                rho0 = np.outer(psi0, psi0.conj()).reshape(-1)
                rho_vec = rho0.copy()
                
                for i in range(N_STEPS):
                    I_val, Q_val = pulse[i]
                    H = build_hamiltonian(detuning, scale, I_val, Q_val)
                    L = build_liouvillian_full(H)
                    E = sla.expm(L * DT)
                    rho_vec = E @ rho_vec
                
                rho = rho_vec.reshape(3, 3)
                psi_target = X3 @ psi0
                f = np.vdot(psi_target, rho @ psi_target).real
                f = np.clip(f, 0, 1)
                infidelities.append(1.0 - f)
            
            mean_inf = np.mean(infidelities)
            case_infidelities.append(mean_inf)
    
    mean_all = np.mean(case_infidelities)
    max_case = np.max(case_infidelities)
    score = mean_all + max_case
    return score

def pulse(target_gate, hardware_model):
    """Main entry point."""
    if target_gate != 'X_pi':
        return np.zeros((80, 2))
    
    start_time = time.time()
    deadline = start_time + 290  # 40s margin
    
    # Strategy: 
    # 1. Grid search over 5 gain parameters (coarse)
    # 2. Local refinement with L-BFGS-B
    # 3. Return best valid pulse
    
    best_pulse = None
    best_score = np.inf
    
    # Grid search ranges for gains
    # Kp: proportional gain for |2> suppression
    # Ki: integral gain
    # Kd: derivative gain
    # ff_gain: feedforward scaling
    # drag_gain: DRAG term strength
    
    # Coarse grid
    Kp_vals = [0.1, 0.5, 1.0, 2.0, 5.0]
    Ki_vals = [0.0, 0.1, 0.5]
    Kd_vals = [0.0, 0.1, 0.5]
    ff_vals = [0.8, 1.0, 1.2]
    drag_vals = [-0.1, -0.05, 0.0, 0.05, 0.1]
    
    # Limit grid size for speed
    n_grid = len(Kp_vals) * len(Ki_vals) * len(Kd_vals) * len(ff_vals) * len(drag_vals)
    if n_grid > 200:
        # Subsample
        Kp_vals = Kp_vals[::2]
        Ki_vals = Ki_vals[::2]
        Kd_vals = Kd_vals[::2]
        drag_vals = drag_vals[::2]
    
    # Evaluate grid points
    # To save time, evaluate at nominal conditions (detuning=0, scale=1) first
    # then verify best candidates at all 9 conditions
    
    candidates = []
    
    for Kp in Kp_vals:
        for Ki in Ki_vals:
            for Kd in Kd_vals:
                for ff in ff_vals:
                    for drag in drag_vals:
                        if time.time() > deadline - 60:
                            break
                        gains = [Kp, Ki, Kd, ff, drag]
                        p = generate_pulse_feedback(gains)
                        p = enforce_constraints(p)
                        if not check_validity(p):
                            continue
                        
                        # Quick score at nominal
                        s_nom = compute_score(p)
                        candidates.append((s_nom, gains, p))
        
        if time.time() > deadline - 60:
            break
    
    if time.time() > deadline - 60:
        break_outer = True
    else:
        break_outer = False
    
    if break_outer and not candidates:
        # Fallback: use a simple DRAG seed
        t = np.arange(N_STEPS) * DT
        sigma = 5.0
        center = 20.0
        g = np.exp(-0.5 * ((t - center) / sigma)**2)
        edge_val = g[0]
        g = g - edge_val
        area = np.sum(g) * DT
        if area > 0:
            g = g * (np.pi / area)
        I = 0.2 * g
        dg = (t - center) / (sigma**2) * g
        if np.max(np.abs(dg)) > 0:
            dg = dg / np.max(np.abs(dg))
        Q = 0.2 * (-0.1) * dg
        p = np.column_stack((I, Q))
        p = enforce_constraints(p)
        if check_validity(p):
            return p
        return np.zeros((80, 2))
    
    # Sort by nominal score and take top candidates for full evaluation
    candidates.sort(key=lambda x: x[0])
    top_n = min(20, len(candidates))
    
    for s_nom, gains, p in candidates[:top_n]:
        if time.time() > deadline - 30:
            break
        # Full score at all 9 conditions
        s_full = compute_score(p)
        if s_full < best_score:
            best_score = s_full
            best_pulse = p.copy()
    
    # Local refinement with L-BFGS-B on the best candidate
    if best_pulse is not None and time.time() < deadline - 30:
        # Use the gains from the best candidate
        best_gains = None
        for s_nom, gains, p in candidates[:top_n]:
            if np.allclose(p, best_pulse, atol=1e-10):
                best_gains = gains
                break
        if best_gains is None:
            best_gains = [1.0, 0.1, 0.1, 1.0, 0.0]
        
        def obj(gains_arr):
            if time.time() > deadline - 10:
                return best_score
            g = list(gains_arr)
            p = generate_pulse_feedback(g)
            p = enforce_constraints(p)
            if not check_validity(p):
                return 1.0
            return compute_score(p)
        
        try:
            result = minimize(
                obj,
                np.array(best_gains),
                method='Nelder-Mead',
                options={'maxiter': 200, 'xatol': 1e-4, 'fatol': 1e-6}
            )
            if result.fun < best_score:
                p_new = generate_pulse_feedback(list(result.x))
                p_new = enforce_constraints(p_new)
                if check_validity(p_new):
                    s_new = compute_score(p_new)
                    if s_new < best_score:
                        best_score = s_new
                        best_pulse = p_new
        except Exception:
            pass
    
    if best_pulse is None:
        # Ultimate fallback
        t = np.arange(N_STEPS) * DT
        sigma = 5.0
        center = 20.0
        g = np.exp(-0.5 * ((t - center) / sigma)**2)
        edge_val = g[0]
        g = g - edge_val
        area = np.sum(g) * DT
        if area > 0:
            g = g * (np.pi / area)
        I = 0.2 * g
        Q = np.zeros(N_STEPS)
        p = np.column_stack((I, Q))
        p = enforce_constraints(p)
        if check_validity(p):
            return p
        return np.zeros((80, 2))
    
    return best_pulse
