        # returns: np.array of shape (len(words), 17), dtype uint8
        n_words = len(words)
        bits = np.zeros((n_words, N), dtype=np.uint8)
        for i, w in enumerate(words):
            for j in range(N):
                if w & (1 << j):
                    bits[i, j] = 1
        return bits
    
