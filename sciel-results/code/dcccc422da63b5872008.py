        # We can use broadcasting.
        # bits[:, np.newaxis, :] ^ bits[np.newaxis, :, :]
        # This is (M, 1, N) ^ (1, M, N) -> (M, M, N)
        # Sum over last axis -> (M, M)
        # Min of off-diagonal elements.
        
        # To save memory/time, we can compute in blocks or just use the fact that M is small.
        # Let's try the direct vectorized approach.
        
        # Optimization: We only need to check if min dist >= MIN_DIST.
        # We can compute the distance matrix.
        
        # Actually, for the search loop, we need to check a NEW candidate against ALL existing words.
        # So we need a function: min_dist_to_code(candidate, bits)
        
    def min_dist_to_code(candidate_int, bits):
        # candidate_int: int
        # bits: np.array (M, N)
        # Returns min hamming distance between candidate and any word in bits.
        
        # Convert candidate to bits
        cand_bits = np.zeros(N, dtype=np.uint8)
        for j in range(N):
            if candidate_int & (1 << j):
                cand_bits[j] = 1
        
        # XOR with all words
        # bits: (M, N)
        # cand_bits: (N,)
        # xor: (M, N)
        xor = bits ^ cand_bits
        # Sum over columns
        dists = xor.sum(axis=1)
        return np.min(dists)
    
    def is_valid(candidate_int, bits):
        return min_dist_to_code(candidate_int, bits) >= MIN_DIST
    
    # Initial code
