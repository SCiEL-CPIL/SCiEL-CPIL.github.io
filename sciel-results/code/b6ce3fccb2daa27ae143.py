"""Matrix multiplication 3,4,6 rank-minimal decomposition."""

def construct():
    n, m, p = 3, 4, 6
    
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    # Full schoolbook decomposition
    # For each i in range(n), j in range(m), k in range(p):
    # C[i,k] += A[i,j] * B[j,k]
    # This corresponds to a tensor term with:
    # U[i*m + j, col] = 1
    # V[j*p + k, col] = 1
    # W[k*n + i, col] = 1
    
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u_idx = i * m + j
                v_idx = j * p + k
                w_idx = k * n + i
                
                U[u_idx][col] = 1
                V[v_idx][col] = 1
                W[w_idx][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
