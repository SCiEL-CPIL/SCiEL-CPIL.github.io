def construct():
    n, m, p = 3, 4, 8
    rank = 88
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    # Part 1: i=0, schoolbook 1x4x8 = 32 terms
    for j in range(4):
        for k in range(8):
            U[0 * m + j][col] = 1
            V[j * p + k][col] = 1
            W[k * n + 0][col] = 1
            col += 1
    
    # Part 2: i=1,2 using 4 Strassen blocks (each 2x2x2, rank 7) = 28 terms
    # j split into [0,1] and [2,3], k split into [0,1],[2,3],[4,5],[6,7]
    
    # Strassen factors for 2x2x2
    # M1 = (A00+A11)(B00+B11)
    # M2 = (A10+A11)B00
    # M3 = A00(B10-B00)
    # M4 = A11(B01-B10)
    # M5 = (A00+A01)B11
    # M6 = (A10-A00)(B00+B10)
    # M7 = (A01-A11)(B01+B11)
    
    strassen_U = [
        [1, 0, 0, 1],   # M1
        [0, 0, 1, 1],   # M2
        [1, 0, 0, 0],   # M3
        [0, 0, 0, 1],   # M4
        [1, 1, 0, 0],   # M5
        [-1, 0, 1, 0],  # M6
        [0, 1, 0, -1]   # M7
    ]
    strassen_V = [
        [1, 0, 0, 1],   # M1
        [1, 0, 0, 0],   # M2
        [0, 1, 0, -1],  # M3
        [-1, 0, 1, 0],  # M4
        [0, 0, 0, 1],   # M5
        [1, 1, 0, 0],   # M6
        [0, 0, 1, 1]    # M7
    ]
    strassen_W = [
        [1, 0, 0, 1],   # M1: C00+=M1, C11+=M1
        [0, 0, 1, -1],  # M2: C10+=M2, C11-=M2
        [0, 1, 0, 1],   # M3: C01+=M3, C11+=M3
        [1, 0, 1, 0],   # M4: C00+=M4, C10+=M4
        [-1, 1, 0, 0],  # M5: C00-=M5, C01+=M5
        [0, 0, 0, 1],   # M6: C11+=M6
        [1, 0, 0, 0]    # M7: C00+=M7
    ]
    
    for j_block in range(2):
        j_start = j_block * 2
        for k_block in range(4):
            k_start = k_block * 2
            
            for t in range(7):
                for l in range(4):
                    if strassen_U[t][l] != 0:
                        li = l // 2
                        lj = l % 2
                        gi = 1 + li
                        gj = j_start + lj
                        U[gi * m + gj][col] += strassen_U[t][l]
                    
                    if strassen_V[t][l] != 0:
                        lj = l // 2
                        lk = l % 2
                        gj = j_start + lj
                        gk = k_start + lk
                        V[gj * p + gk][col] += strassen_V[t][l]
                    
                    if strassen_W[t][l] != 0:
                        li = l // 2
                        lk = l % 2
                        gi = 1 + li
                        gk = k_start + lk
                        W[gk * n + gi][col] += strassen_W[t][l]
                
                col += 1
    
    return {"U": U, "V": V, "W": W}
