import time

DIMENSIONS = [5, 5, 5]

def construct():
    """
    Returns a rank-minimal exact tensor decomposition for multiplying a 5 by 5 matrix 
    by a 5 by 5 matrix. 
    Currently returns the schoolbook decomposition of rank 125.
    """
    n, m, p = DIMENSIONS
    rank = n * m * p
    
    # Initialize U, V, W with zeros
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
                
    return {"U": U, "V": V, "W": W}
