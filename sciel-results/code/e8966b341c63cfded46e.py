def _build_adj(n, edges):
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    return adj

def _check_girth_fast(n, edges, min_girth):
    """
    Optimized girth check.
    Uses BFS from each vertex up to depth (min_girth-1)//2.
    """
    if n == 0:
        return True
    adj = _build_adj(n, edges)
    max_depth = (min_girth - 1) // 2
    
    # Check degree first
