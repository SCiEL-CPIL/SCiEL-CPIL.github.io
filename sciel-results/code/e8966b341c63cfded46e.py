    # In a voltage lift, a cycle of length L in the base graph lifts to cycles of length
    # L * m / gcd(sum_voltages, m).
    # If sum_voltages = 0 mod m, the cycle stays length L.
    # If sum_voltages != 0, the cycle length is L * m / d where d = gcd(sum, m).
    # We need all lifted cycles to have length >= g.
    # So for every cycle C in base graph with length L < g * m (which is always true for small L),
