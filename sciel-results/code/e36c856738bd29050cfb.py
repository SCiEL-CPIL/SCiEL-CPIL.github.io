import time

DIMENSIONS = [2, 2, 7]

def construct():
    n, m, p = DIMENSIONS
    # Rank 25 decomposition
    rank = 25
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to add a term
    # u_vec, v_vec, w_vec are lists of indices or values
    # We will build them explicitly
    
    # Block 1: cols 0, 1. Strassen.
    # A indices: 00:0, 01:1, 10:2, 11:3
    # B indices: 00:0, 01:1, 10:7, 11:8
    # C indices: 00:0, 01:1, 10:2, 11:3
    
    # P1 = (A00+A11)(B00+B11)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[8][0] = 1
    W[0][0] = 1; W[3][0] = 1
    
    # P2 = (A10+A11)B00
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[2][1] = 1 # c10 = P2 + P4
    
    # P3 = A00(B01-B10)
    U[0][2] = 1
    V[1][2] = 1; V[7][2] = -1
    W[1][2] = 1 # c01 = P3 + P5
    
    # P4 = A11(B10-B00)
    U[3][3] = 1
    V[7][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[2][3] = 1 # c00 += P4, c10 += P4
    
    # P5 = (A00+A01)B11
    U[0][4] = 1; U[1][4] = 1
    V[8][4] = 1
    W[0][4] = -1; W[1][4] = 1 # c00 -= P5, c01 += P5
    
    # P6 = (A10-A00)(B00+B01)
    U[2][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    W[3][5] = 1 # c11 = P1 - P2 + P3 + P6
    
    # P7 = (A01-A11)(B10+B11)
    U[1][6] = 1; U[3][6] = -1
    V[7][6] = 1; V[8][6] = 1
    W[0][6] = 1 # c00 = P1 + P4 - P5 + P7

    # Block 2: cols 2, 3. Strassen.
    # B indices: 02:2, 03:3, 12:9, 13:10
    # C indices: 02:4, 03:5, 12:6, 13:7
    
    # P1
    U[0][7] = 1; U[3][7] = 1
    V[2][7] = 1; V[10][7] = 1
    W[4][7] = 1; W[7][7] = 1
    
    # P2
    U[2][8] = 1; U[3][8] = 1
    V[2][8] = 1
    W[6][8] = 1
    
    # P3
    U[0][9] = 1
    V[3][9] = 1; V[9][9] = -1
    W[5][9] = 1
    
    # P4
    U[3][10] = 1
    V[9][10] = 1; V[2][10] = -1
    W[4][10] = 1; W[6][10] = 1
    
    # P5
    U[0][11] = 1; U[1][11] = 1
    V[10][11] = 1
    W[4][11] = -1; W[5][11] = 1
    
    # P6
    U[2][12] = 1; U[0][12] = -1
    V[2][12] = 1; V[3][12] = 1
    W[7][12] = 1
    
    # P7
    U[1][13] = 1; U[3][13] = -1
    V[9][13] = 1; V[10][13] = 1
    W[4][13] = 1

    # Block 3: cols 4, 5. Strassen.
    # B indices: 04:4, 05:5, 14:11, 15:12
    # C indices: 04:8, 05:9, 14:10, 15:11
    
    # P1
    U[0][14] = 1; U[3][14] = 1
    V[4][14] = 1; V[12][14] = 1
    W[8][14] = 1; W[11][14] = 1
    
    # P2
    U[2][15] = 1; U[3][15] = 1
    V[4][15] = 1
    W[10][15] = 1
    
    # P3
    U[0][16] = 1
    V[5][16] = 1; V[11][16] = -1
    W[9][16] = 1
    
    # P4
    U[3][17] = 1
    V[11][17] = 1; V[4][17] = -1
    W[8][17] = 1; W[10][17] = 1
    
    # P5
    U[0][18] = 1; U[1][18] = 1
    V[12][18] = 1
    W[8][18] = -1; W[9][18] = 1
    
    # P6
    U[2][19] = 1; U[0][19] = -1
    V[4][19] = 1; V[5][19] = 1
    W[11][19] = 1
    
    # P7
    U[1][20] = 1; U[3][20] = -1
    V[11][20] = 1; V[12][20] = 1
    W[8][20] = 1

    # Block 4: col 6. Schoolbook.
    # B indices: 06:6, 16:13
    # C indices: 06:12, 16:13
    
    # Q1 = A00 B06
    U[0][21] = 1
    V[6][21] = 1
    W[12][21] = 1
    
    # Q2 = A01 B16
    U[1][22] = 1
    V[13][22] = 1
    W[12][22] = 1
    
    # Q3 = A10 B06
    U[2][23] = 1
    V[6][23] = 1
    W[13][23] = 1
    
    # Q4 = A11 B16
    U[3][24] = 1
    V[13][24] = 1
    W[13][24] = 1

    return {"U": U, "V": V, "W": W}
