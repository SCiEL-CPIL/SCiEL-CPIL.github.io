N = 14

# EVOLVE-BLOCK-START
import time
import numpy as np
from scipy.optimize import minimize
from scipy.spatial import ConvexHull

def _convex_hull_area(points):
    """Compute convex hull area of points."""
    try:
        hull = ConvexHull(points)
        return hull.volume
    except Exception:
        # Fallback: Andrew's monotone chain
        pts = np.array(points)
        pts = pts[np.lexsort((pts[:, 1], pts[:, 0]))]
        if len(pts) <= 1:
            return 0.0
        def cross(o, a, b):
            return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
        lower = []
        for p in pts:
            while len(lower) >= 2 and cross(lower[-2], lower[-1], p) <= 0:
                lower.pop()
            lower.append(p)
        upper = []
        for p in reversed(pts):
            while len(upper) >= 2 and cross(upper[-2], upper[-1], p) <= 0:
                upper.pop()
            upper.append(p)
        hull = lower[:-1] + upper[:-1]
        if len(hull) < 3:
            return 0.0
        x = hull[:, 0]
        y = hull[:, 1]
        return 0.5 * np.abs(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))

def _min_triangle_area(points):
    """Compute minimum triangle area among all triples."""
    n = len(points)
    min_area = float('inf')
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                p1 = points[i]
                p2 = points[j]
                p3 = points[k]
                area = 0.5 * np.abs((p2[0] - p1[0]) * (p3[1] - p1[1]) - (p3[0] - p1[0]) * (p2[1] - p1[1]))
                if area < min_area:
                    min_area = area
    return min_area

def _score(points):
    """Compute the minimum triangle area divided by the convex hull area."""
    hull_area = _convex_hull_area(points)
    if hull_area < 1e-15:
        return 0.0
    min_area = _min_triangle_area(points)
    return min_area / hull_area

def _edge_vector_points(params):
    """
    Convert edge vector parameters to point coordinates.
    params: array of shape (N, 2) representing edge vectors in order.
    The points are generated by accumulating edge vectors, starting from origin.
    To ensure the polygon is closed, we adjust the last edge vector.
    Returns: array of shape (N, 2) representing the vertices.
    """
    edges = params.copy()
    # Adjust last edge to close the polygon
    total = np.sum(edges, axis=0)
    edges[-1] -= total
    
    # Generate points by cumulative sum, starting from origin
    points = np.zeros((N, 2))
    for i in range(1, N):
        points[i] = points[i-1] + edges[i-1]
    
    # Center the points
    centroid = np.mean(points, axis=0)
    points -= centroid
    
    return points

def _check_convexity(points):
    """Check if points form a strictly convex polygon."""
    n = len(points)
    if n < 3:
        return False
    for i in range(n):
        p1 = points[i]
        p2 = points[(i+1) % n]
        p3 = points[(i+2) % n]
        cross = (p2[0] - p1[0]) * (p3[1] - p1[1]) - (p2[1] - p1[1]) * (p3[0] - p1[0])
        if cross <= 0:
            return False
    return True

def _edge_objective(params, beta=50.0):
    """
    Objective function for edge vector optimization.
    Minimizes negative soft-min triangle area / hull area, with convexity penalty.
    """
    points = _edge_vector_points(params)
    
    # Check convexity
    if not _check_convexity(points):
        return 1e6
    
    # Compute all triangle areas
    n = len(points)
    areas = np.zeros((n*(n-1)*(n-2)//6))
    idx = 0
    for i in range(n):
        for j in range(i+1, n):
            for k in range(j+1, n):
                p1 = points[i]
                p2 = points[j]
                p3 = points[k]
                areas[idx] = 0.5 * np.abs((p2[0] - p1[0]) * (p3[1] - p1[1]) - (p3[0] - p1[0]) * (p2[1] - p1[1]))
                idx += 1
    
    # Soft-min approximation
    max_area = np.max(areas)
    if max_area < 1e-15:
        return 1e6
    log_sum_exp = np.log(np.sum(np.exp(-beta * (areas - max_area))))
    soft_min = max_area - log_sum_exp / beta
    
    # Compute hull area
    hull_area = _convex_hull_area(points)
    if hull_area < 1e-15:
        return 1e6
    
    return -soft_min / hull_area

def construct():
    """
    Generate 14 points using edge vector parameterization.
    Exploits centrally symmetric structure for even N.
    """
    start_time = time.time()
    deadline = start_time + 140.0
    
    best_points = None
    best_score = -1
    
    rng = np.random.RandomState(42)
    
    # Initialize with regular polygon edge vectors
    angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
    regular_pts = np.column_stack([np.cos(angles), np.sin(angles)])
    regular_edges = np.zeros((N, 2))
    for i in range(N):
        regular_edges[i] = regular_pts[(i+1) % N] - regular_pts[i]
    
    # Normalize
    hull_area = _convex_hull_area(regular_pts)
    if hull_area > 1e-15:
        scale = np.sqrt(1.0 / hull_area)
        regular_pts = regular_pts * scale
        regular_edges = regular_edges * scale
    
    best_points = regular_pts.copy()
    best_score = _score(regular_pts)
    
    # Multiple restarts with different initializations
    for restart in range(8):
        if time.time() > deadline - 30:
            break
        
        if restart == 0:
            init_edges = regular_edges.copy()
        elif restart == 1:
            # Perturbed regular
            init_edges = regular_edges + rng.normal(0, 0.05, (N, 2))
        elif restart == 2:
            # Ellipse-like
            a, b = 1.5, 0.8
            angles = np.linspace(0, 2 * np.pi, N, endpoint=False)
            pts = np.column_stack([a * np.cos(angles), b * np.sin(angles)])
            edges = np.zeros((N, 2))
            for i in range(N):
                edges[i] = pts[(i+1) % N] - pts[i]
            hull_area = _convex_hull_area(pts)
            if hull_area > 1e-15:
                scale = np.sqrt(1.0 / hull_area)
                init_edges = edges * scale
            else:
                init_edges = regular_edges.copy()
        elif restart == 3:
            # Random convex
            angles = np.sort(rng.uniform(0, 2 * np.pi, N))
            radii = rng.uniform(0.7, 1.0, N)
            pts = np.column_stack([radii * np.cos(angles), radii * np.sin(angles)])
            edges = np.zeros((N, 2))
            for i in range(N):
                edges[i] = pts[(i+1) % N] - pts[i]
            hull_area = _convex_hull_area(pts)
            if hull_area > 1e-15:
                scale = np.sqrt(1.0 / hull_area)
                init_edges = edges * scale
            else:
                init_edges = regular_edges.copy()
        else:
            # More random
            init_edges = regular_edges + rng.normal(0, 0.1, (N, 2))
        
        # Optimize using Powell
        try:
            result = minimize(
                _edge_objective,
                init_edges.flatten(),
                method='Powell',
                options={'maxiter': 300, 'xatol': 1e-8, 'fatol': 1e-10}
            )
            
            if result.fun < 0:
                opt_edges = result.x.reshape(-1, 2)
                opt_points = _edge_vector_points(opt_edges)
                
                if _check_convexity(opt_points):
                    hull_area = _convex_hull_area(opt_points)
                    if hull_area > 1e-15:
                        scale = np.sqrt(1.0 / hull_area)
                        opt_points = opt_points * scale
                    
                    opt_score = _score(opt_points)
                    if opt_score > best_score:
                        best_score = opt_score
                        best_points = opt_points.copy()
        except Exception:
            pass
    
    # Local refinement
    if time.time() < deadline - 15:
        # Convert best points to edge vectors
        edges = np.zeros((N, 2))
        for i in range(N):
            edges[i] = best_points[(i+1) % N] - best_points[i]
        
        try:
            result = minimize(
                _edge_objective,
                edges.flatten(),
                method='Nelder-Mead',
                options={'maxiter': 500, 'xatol': 1e-8, 'fatol': 1e-10}
            )
            
            if result.fun < 0:
                opt_edges = result.x.reshape(-1, 2)
                opt_points = _edge_vector_points(opt_edges)
                
                if _check_convexity(opt_points):
                    hull_area = _convex_hull_area(opt_points)
                    if hull_area > 1e-15:
                        scale = np.sqrt(1.0 / hull_area)
                        opt_points = opt_points * scale
                    
                    opt_score = _score(opt_points)
                    if opt_score > best_score:
                        best_score = opt_score
                        best_points = opt_points.copy()
        except Exception:
            pass
    
    return best_points
