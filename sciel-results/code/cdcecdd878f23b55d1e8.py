import time
import numpy as np

DIMENSIONS = [4, 4, 9]

def construct():
    deadline = time.time() + 140.0
    n, m, p = DIMENSIONS  # 4, 4, 9

    # We will build a decomposition using Strassen for the 4x4x4 blocks.
    # Specifically, we split B into B1 (4x4), B2 (4x4), B3 (4x1).
    # C = A*B1 + A*B2 + A*B3.
    # Rank(A*B1) = 28 (Strassen 4x4x4)
    # Rank(A*B2) = 28 (Strassen 4x4x4)
    # Rank(A*B3) = 16 (Schoolbook 4x4x1)
    # Total Rank = 72.
    
    # The tensor equation is:
    # sum_r U[i*m+j, r] * V[j*p+k, r] * W[k*n+i, r] = 1 for all i, j, k
    
    # We will accumulate the terms for U, V, W in lists of dictionaries or sparse structures, 
    # but since the matrices are small (16x72, 36x72, 36x72), we can just use dense arrays.
    
    rank_est = 72
    U = np.zeros((n * m, rank_est))
    V = np.zeros((m * p, rank_est))
    W = np.zeros((p * n, rank_est))
    
    col = 0
    
    # Helper to add a Strassen 4x4x4 block
    # A is 4x4 (indices i,j in 0..3)
    # B is 4x4 (indices j,k in 0..3) -- note: k is local to the block
    # C is 4x4 (indices i,k in 0..3)
    # b_offset: the global column offset in B for this block (0 or 4)
    
    def add_strassen_4x4(b_offset):
        nonlocal col
        
        # Strassen 4x4x4 is derived from 2x2x2 Strassen applied to 2x2 blocks.
        # Let's define the 2x2 Strassen terms first.
        # For 2x2 matrices A, B:
        # M1 = A00 * (B01 - B11)
        # M2 = (A00 + A10) * B11
        # M3 = (A01 - A11) * (B10 + B11)
        # M4 = A11 * (B00 - B01)
        # M5 = (A00 + A01) * B00
        # M6 = (A10 - A00) * (B00 + B01)
        # M7 = (A11 - A10) * (B10 - B11)
        
        # C00 = M1 + M4 - M5 + M7
        # C01 = M3 + M5
        # C10 = M2 + M4
        # C11 = M1 - M2 + M3 + M6
        
        # In the 4x4 case, A and B are 2x2 blocks of 2x2 matrices.
        # A = [[A00, A01], [A10, A11]]
        # B = [[B00, B01], [B10, B11]]
        # Each Axx and Bxx is a 2x2 matrix.
        
        # The product of two 2x2 matrices (say X and Y) is decomposed into 4 rank-1 terms (schoolbook).
        # X[0,0]*Y[0,0] -> C[0,0]
        # X[0,1]*Y[1,0] -> C[0,0]
        # X[0,0]*Y[0,1] -> C[0,1]
        # ... etc.
        
        # So for each of the 7 Strassen "block products" (e.g., A00 * (B01-B11)),
        # we have a linear combination of A-blocks and a linear combination of B-blocks.
        # Let U_block = sum c_a A_pa and V_block = sum c_b B_pb.
        # The product U_block * V_block is a 2x2 matrix.
        # We expand this into 4 rank-1 terms for the scalar multiplication of the 2x2 blocks.
        
        # Actually, it's easier to just iterate over the 7 Strassen terms, 
        # and for each term, iterate over the 4 schoolbook terms of the 2x2 block multiplication.
        
        # Let's define the 7 Strassen terms in terms of (A_block_idx, B_block_idx, coeff).
        # A_block_idx: (r, c) where r,c in 0..1. Global A index: (2r+i, 2c+j)
        # B_block_idx: (r, c) where r,c in 0..1. Global B index: (2r+i, b_offset + 2c + j)
        
        # Term 1: A00 * (B01 - B11)
        # U_part: A00 (coeff 1)
        # V_part: B01 (coeff 1), B11 (coeff -1)
        
        # This is getting complicated to manage with nested loops and indices.
        # Let's use a more direct approach: generate the 28 terms explicitly.
        
        # The 28 terms for 4x4x4 Strassen can be generated by taking the 7 outer terms
        # and expanding each 2x2x2 product into 4 terms.
        
        # Let's define a function to add a 2x2x2 schoolbook product.
        # Inputs: 
        #   a_rows: list of (global_i, global_j, coeff) for the A part
        #   b_rows: list of (global_j, global_k, coeff) for the B part
        #   c_rows: list of (global_i, global_k, coeff) for the C part
        # Wait, the C part is determined by the Strassen formula.
        
        # Let's do it this way:
        # For each of the 7 Strassen terms M_t:
        #   M_t = (sum_a c_a A_a) * (sum_b d_b B_b)
        #   This contributes to the C blocks according to the Strassen formula.
        #   The product (sum_a c_a A_a) * (sum_b d_b B_b) is a 2x2 matrix.
        #   Let's call this 2x2 matrix P_t.
        #   P_t[i', k'] = sum_{a,b} c_a d_b (A_a * B_b)[i', k']
        #   (A_a * B_b)[i', k'] = sum_{j'} A_a[i', j'] * B_b[j', k']
        
        # So P_t[i', k'] = sum_{a,b,j'} c_a d_b A_a[i', j'] B_b[j', k']
        
        # The contribution to the global C matrix is sum_t (coeff_t_for_C_block * P_t).
        
        # Let's just generate the 28 rank-1 terms directly.
        # A rank-1 term is defined by a specific (i, j, k) in the 4x4x4 space, but with coefficients.
        
        # Let's list the 7 Strassen terms again, with their contributions to C blocks.
        # M1: C00(+1), C11(-1)
        # M2: C10(+1), C11(-1)
        # M3: C01(+1), C11(+1)
        # M4: C00(+1), C10(+1)
        # M5: C00(-1), C01(+1)
        # M6: C11(+1)
        # M7: C00(+1), C11(+1)
        
        # Wait, let me double check the Strassen C formulas.
        # C00 = M1 + M4 - M5 + M7
        # C01 = M3 + M5
        # C10 = M2 + M4
        # C11 = M1 - M2 + M3 + M6
        
        # Yes, that looks correct.
        
        # Now, for each M_t, we have:
        # M1 = A00 * (B01 - B11)
        # M2 = (A00 + A10) * B11
        # M3 = (A01 - A11) * (B10 + B11)
        # M4 = A11 * (B00 - B01)
        # M5 = (A00 + A01) * B00
        # M6 = (A10 - A00) * (B00 + B01)
        # M7 = (A11 - A10) * (B10 - B11)
        
        # Let's iterate t from 0 to 6.
        # For each t, we have a set of A-blocks and B-blocks with coefficients.
        # We need to expand the product of these linear combinations into 4 rank-1 terms.
        
        # Actually, the product of two linear combinations of 2x2 matrices is not just 4 terms.
        # It is a sum of products of individual 2x2 matrices.
        # Each product of two 2x2 matrices is 4 rank-1 terms.
        # So if M_t has k_a A-blocks and k_b B-blocks, it has k_a * k_b * 4 rank-1 terms.
        
        # M1: 1 A-block, 2 B-blocks -> 1*2*4 = 8 terms.
        # M2: 2 A-blocks, 1 B-block -> 2*1*4 = 8 terms.
        # M3: 2 A-blocks, 2 B-blocks -> 2*2*4 = 16 terms.
        # M4: 1 A-block, 2 B-blocks -> 1*2*4 = 8 terms.
        # M5: 2 A-blocks, 1 B-block -> 2*1*4 = 8 terms.
        # M6: 2 A-blocks, 2 B-blocks -> 2*2*4 = 16 terms.
        # M7: 2 A-blocks, 2 B-blocks -> 2*2*4 = 16 terms.
        
        # Total terms = 8+8+16+8+8+16+16 = 80 terms?
        # That's not 28. What is wrong?
        
        # Ah, the "rank" of the 4x4x4 multiplication is 28, not 80.
        # This implies that the terms are not independent, or I am misunderstanding the decomposition.
        
        # The rank of the tensor product of two rank-7 tensors is 49.
        # The rank of the 4x4x4 tensor is at most 49.
        # The rank of the 4x4x4 tensor is actually 28? No, the lower bound is 27, upper bound 49.
        # The "Strassen" decomposition for 4x4x4 usually refers to the recursive application, which gives 49.
        # Is there a rank 28 decomposition?
        # Yes, the rank of 4x4x4 is known to be 28 (or less).
        # But the recursive Strassen gives 49.
        
        # If I use the recursive Strassen (rank 49), then:
        # Rank(A*B1) = 49
        # Rank(A*B2) = 49
        # Rank(A*B3) = 16
        # Total Rank = 114.
        
        # This is still better than 144 (schoolbook).
        # And it is much easier to implement correctly than finding a rank 28 decomposition.
        
        # Let's implement the rank 49 decomposition for 4x4x4.
        # This is the tensor square of the rank 7 decomposition for 2x2x2.
        
        # The 7 terms for 2x2x2 are:
        # T1 = A00 * (B01 - B11)
        # T2 = (A00 + A10) * B11
        # T3 = (A01 - A11) * (B10 + B11)
        # T4 = A11 * (B00 - B01)
        # T5 = (A00 + A01) * B00
        # T6 = (A10 - A00) * (B00 + B01)
        # T7 = (A11 - A10) * (B10 - B11)
        
        # For 4x4x4, A and B are 2x2 blocks of 2x2 matrices.
        # The 49 terms are Ti * Tj for i,j in 1..7.
        # Wait, no. The tensor product T4x4 = T2x2 \otimes T2x2.
        # The rank is rank(T2x2) * rank(T2x2) = 7 * 7 = 49.
        
        # So we have 49 terms.
        # Each term is of the form:
        # (sum_{a} c_a A_a) * (sum_{b} d_b B_b) * (sum_{c} e_c C_c)
        # where A_a, B_b, C_c are 2x2 blocks.
        
        # This is still complex. Let's just use the schoolbook for the inner 2x2 blocks.
        # No, that gives rank 49 * 4 = 196? No.
        
        # Let's stick to the simplest improvement: Rank 114.
        # This uses rank 49 for the two 4x4x4 blocks and rank 16 for the 4x4x1 block.
        
        # To implement rank 49 for 4x4x4:
        # We can just use the schoolbook for the 4x4x4 block, which is rank 64.
        # 64 + 64 + 16 = 144. That's the same as the full schoolbook.
        
        # So I MUST implement the rank 49 decomposition to get an improvement.
        
        # Let's try to implement the rank 49 decomposition by iterating over the 7x7 combinations.
        
        # The 7 terms for 2x2x2 in terms of indices (i, j, k) in 0..1:
        # We can represent each term as a set of (u_idx, v_idx, w_idx, coeff).
        
        # Let's define the 7 terms for 2x2x2.
        # u is 2x2, v is 2x2, w is 2x2.
        # u_idx = i*2+j, v_idx = j*2+k, w_idx = k*2+i.
        
        # Term 1: A00 * (B01 - B11)
        # u: A00 -> (0,0) -> idx 0
        # v: B01 -> (0,1) -> idx 1, B11 -> (1,1) -> idx 3
        # w: C00 -> (0,0) -> idx 0, C11 -> (1,1) -> idx 3
        # This is not a rank-1 term. It's a sum of rank-1 terms.
        
        # Actually, the Strassen decomposition is a sum of 7 rank-1 terms for the 2x2x2 tensor.
        # Each term is (u, v, w) where u, v, w are vectors of length 4.
        
        # Let's find the 7 rank-1 terms for 2x2x2.
        # T1: u = [1,0,0,0] (A00), v = [0,1,0,-1] (B01-B11), w = [1,0,0,1] (C00+C11)
        # Wait, the C part of T1 contributes to C00 and C11.
        # C00 = M1 + M4 - M5 + M7
        # C11 = M1 - M2 + M3 + M6
        # So M1 contributes +1 to C00 and +1 to C11.
        # So w = [1,0,0,1].
        
        # Let's verify this.
        # sum_r U[i,j] V[j,k] W[k,i] = 1 for all i,j,k.
        
        # If I use the 7 rank-1 terms for 2x2x2, I can verify them.
        
        # Let's generate the 7 terms for 2x2x2.
        
        terms_2x2 = []
        
        # T1: A00 * (B01 - B11) -> C00 + C11
        u = [1,0,0,0]
        v = [0,1,0,-1]
        w = [1,0,0,1]
        terms_2x2.append((u, v, w))
        
        # T2: (A00 + A10) * B11 -> C10 - C11
        u = [1,0,1,0]
        v = [0,0,0,1]
        w = [0,0,1,-1] # C10 is (1,0) in 2x2? No.
        # C is 2x2. C[i,k].
        # C00 is (0,0), C01 is (0,1), C10 is (1,0), C11 is (1,1).
        # w_idx = k*2+i.
        # C00: k=0, i=0 -> 0
        # C01: k=1, i=0 -> 2
        # C10: k=0, i=1 -> 1
        # C11: k=1, i=1 -> 3
        
        # T2 contributes to C10 (+1) and C11 (-1).
        # w = [0, 1, 0, -1]
        terms_2x2[1] = ([1,0,1,0], [0,0,0,1], [0,1,0,-1])
        
        # T3: (A01 - A11) * (B10 + B11) -> C01 + C11
        u = [0,1,0,-1]
        v = [0,0,1,1]
        w = [0,0,1,1] # C01 (+1), C11 (+1)
        terms_2x2.append((u, v, w))
        
        # T4: A11 * (B00 - B01) -> C00 + C10
        u = [0,0,0,1]
        v = [1,-1,0,0]
        w = [1,1,0,0] # C00 (+1), C10 (+1)
        terms_2x2.append((u, v, w))
        
        # T5: (A00 + A01) * B00 -> -C00 + C01
        u = [1,1,0,0]
        v = [1,0,0,0]
        w = [-1,0,1,0] # C00 (-1), C01 (+1)
        terms_2x2.append((u, v, w))
        
        # T6: (A10 - A00) * (B00 + B01) -> C11
        u = [-1,0,1,0]
        v = [1,1,0,0]
        w = [0,0,0,1] # C11 (+1)
        terms_2x2.append((u, v, w))
        
        # T7: (A11 - A10) * (B10 - B11) -> C00 + C11
        u = [0,0,-1,1]
        v = [0,0,1,-1]
        w = [1,0,0,1] # C00 (+1), C11 (+1)
        terms_2x2.append((u, v, w))
        
        # Now, for 4x4x4, we take the tensor product of these 7 terms.
        # The 49 terms are Ti * Tj for i,j in 0..6.
        # u_4x4 = u_i \otimes u_j
        # v_4x4 = v_i \otimes v_j
        # w_4x4 = w_i \otimes w_j
        
        # u_i is length 4, u_j is length 4.
        # u_4x4 is length 16.
        
        # Let's generate the 49 terms for 4x4x4.
        
        for i in range(7):
            for j in range(7):
                u_i, v_i, w_i = terms_2x2[i]
                u_j, v_j, w_j = terms_2x2[j]
                
                u_4x4 = np.kron(u_i, u_j)
                v_4x4 = np.kron(v_i, v_j)
                w_4x4 = np.kron(w_i, w_j)
                
                # Now, map these to the global indices.
                # u_4x4[k] corresponds to U[i*m+j, col]
                # The index k in u_4x4 is (i_block * 2 + i_local) * 2 + j_local?
                # No, np.kron(u_i, u_j) where u_i is [A00, A01, A10, A11]
                # u_4x4 is [A00*A00, A00*A01, A00*A10, A00*A11, A01*A00, ...]
                # This is not the standard row-major order of a 4x4 matrix.
                # The standard order is A00, A01, A02, A03, A10, ...
                # The kron order is A00, A01, A10, A11, A01, A02, ...
                # We need to permute the indices.
                
                # Let's check the index mapping.
                # u_i index: 0=A00, 1=A01, 2=A10, 3=A11
                # u_j index: 0=A00, 1=A01, 2=A10, 3=A11
                # kron index: i*4 + j
                # i=0, j=0 -> 0 -> A00*A00 -> Global A[0,0] -> idx 0
                # i=0, j=1 -> 1 -> A00*A01 -> Global A[0,1] -> idx 1
                # i=0, j=2 -> 2 -> A00*A10 -> Global A[1,0] -> idx 4
                # i=0, j=3 -> 3 -> A00*A11 -> Global A[1,1] -> idx 5
                # i=1, j=0 -> 4 -> A01*A00 -> Global A[0,2] -> idx 2
                # i=1, j=1 -> 5 -> A01*A01 -> Global A[0,3] -> idx 3
                # i=1, j=2 -> 6 -> A01*A10 -> Global A[1,2] -> idx 6
                # i=1, j=3 -> 7 -> A01*A11 -> Global A[1,3] -> idx 7
                # ...
                
                # So we need a permutation of the 16 indices.
                # Let perm_u be the permutation such that u_4x4[perm_u[k]] is the coefficient for Global A[k].
                
                # Global A index k = i*4 + j.
                # i = k // 4, j = k % 4.
                # i_block = i // 2, i_local = i % 2.
                # j_block = j // 2, j_local = j % 2.
                # u_i index = i_block * 2 + i_local.
                # u_j index = j_block * 2 + j_local.
                # kron index = u_i_index * 4 + u_j_index.
                
                # So for each global index k, we can find the kron index.
                # And we can assign u_4x4[kron_index] to U[k, col].
                
                for k in range(16):
                    i = k // 4
                    j = k % 4
                    i_block = i // 2
                    i_local = i % 2
                    j_block = j // 2
                    j_local = j % 2
                    u_i_index = i_block * 2 + i_local
                    u_j_index = j_block * 2 + j_local
                    kron_index = u_i_index * 4 + u_j_index
                    U[k, col] = u_4x4[kron_index]
                
                # Similarly for V and W.
                # V index: j*p + k. Here p=4 for the block.
                # j = j_block * 2 + j_local
                # k = k_block * 2 + k_local
                # v_i index = j_block * 2 + j_local
                # v_j index = k_block * 2 + k_local
                # kron index = v_i_index * 4 + v_j_index
                
                for k in range(16):
                    j = k // 4
                    l = k % 4
                    j_block = j // 2
                    j_local = j % 2
                    l_block = l // 2
                    l_local = l % 2
                    v_i_index = j_block * 2 + j_local
                    v_j_index = l_block * 2 + l_local
                    kron_index = v_i_index * 4 + v_j_index
                    # Global V index: j * 4 + l
                    V[j * 4 + l + b_offset * 4, col] = v_4x4[kron_index]
                
                # W index: k*n + i. Here n=4.
                # k = k_block * 2 + k_local
                # i = i_block * 2 + i_local
                # w_i index = k_block * 2 + k_local
                # w_j index = i_block * 2 + i_local
                # kron index = w_i_index * 4 + w_j_index
                
                for k in range(16):
                    l = k // 4
                    i = k % 4
                    l_block = l // 2
                    l_local = l % 2
                    i_block = i // 2
                    i_local = i % 2
                    w_i_index = l_block * 2 + l_local
                    w_j_index = i_block * 2 + i_local
                    kron_index = w_i_index * 4 + w_j_index
                    # Global W index: l * 4 + i
                    W[l * 4 + i, col] = w_4x4[kron_index]
                
                col += 1
        
        return col

    # Apply Strassen to the first two 4x4 blocks of B
    col = add_strassen_4x4(0)
    col = add_strassen_4x4(4)
    
    # Schoolbook for the last column (k=8)
    for i in range(4):
        for j in range(4):
            U[i * 4 + j, col] = 1
            V[j * 9 + 8, col] = 1
            W[8 * 4 + i, col] = 1
            col += 1
    
    # The rank is col (which should be 49 + 49 + 16 = 114)
    
    # Trim the arrays to the actual rank
    U = U[:, :col]
    V = V[:, :col]
    W = W[:, :col]
    
    # Convert to lists of integers
    U_list = [[int(x) for x in row] for row in U]
    V_list = [[int(x) for x in row] for row in V]
    W_list = [[int(x) for x in row] for row in W]
    
    return {"U": U_list, "V": V_list, "W": W_list}
