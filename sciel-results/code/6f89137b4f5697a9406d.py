"""
Constructs a sparse pancyclic graph on 40 vertices.
Target: Minimize (edge_count - 40).

Theoretical analysis:
- A pancyclic graph on N vertices must contain cycles of lengths 3..N.
- A Hamiltonian cycle provides length N.
- Each added chord to the Hamiltonian cycle can create at most 2 new cycle lengths (the two paths between the chord endpoints, plus the chord itself).
- We need cycles of lengths 3..N-1 (38 lengths for N=40).
- Let k be the number of chords. Max new lengths = 2k.
- So 2k >= 38 => k >= 19.
- Total edges = N + k = 40 + 19 = 59.
- Value = edges - 40 = 19.

This is the theoretical minimum. The current program already achieves this value.
The strategy is:
1. Base Hamiltonian cycle: 0-1-...-39-0.
2. Add chords (0, k) for k in 2..20.
   - Chord (0, 2) creates cycles of length 3 (0-1-2-0) and 39 (0-39-...-2-0).
   - Chord (0, 3) creates cycles of length 4 (0-1-2-3-0) and 38.
   - ...
   - Chord (0, 19) creates cycles of length 20 and 22.
   - Chord (0, 20) creates cycles of length 21 and 21 (duplicate length, but we only need one cycle of length 21).
   
   Wait, let's re-verify the lengths generated by chords (0, k) for k=2..20:
   - k=2: lengths 3, 39
   - k=3: lengths 4, 38
   - k=4: lengths 5, 37
   - ...
   - k=19: lengths 20, 22
   - k=20: lengths 21, 21
   
   Union of lengths: {3, 39, 4, 38, ..., 20, 22, 21} = {3, 4, ..., 21, 22, ..., 39}.
   This covers all lengths from 3 to 39.
   The Hamiltonian cycle covers length 40.
   So all lengths 3..40 are covered.

The program below implements this construction and verifies it.
"""

import time

N = 40

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    
    # 1. Construct Edges
    edges = set()
    
    # Base Hamiltonian Cycle: (i, i+1) mod N
    for i in range(N):
        edges.add((i, (i + 1) % N))
        
    # Chords (0, k) for k in 2..20
    for k in range(2, 21):
        edges.add((0, k))
        
    # Convert to list of sorted tuples for consistent output
    edge_list = [tuple(sorted(e)) for e in edges]
    
    # 2. Construct Cycles
    cycles = []
    
    # L from 3 to 40
    for L in range(3, N + 1):
        if L == N:
            # Hamiltonian cycle: 0, 1, ..., 39
            cyc = list(range(N))
        elif L <= 21:
            # Short path + chord
            # Vertices 0, 1, ..., L-1
            # Chord is (0, L-1)
            cyc = list(range(L))
        else:
            # Long path + chord
            # We need a cycle of length L.
            # From chord (0, k) where k = 41 - L.
            # The long path is 0 -> 39 -> 38 -> ... -> k.
            # Length = (39 - k + 1) + 1 = 41 - k = L.
            k = 41 - L
            # Vertices: 0, 39, 38, ..., k
            cyc = [0] + list(range(N - 1, k - 1, -1))
            
        cycles.append(cyc)
        
    # Verification
    edge_set = set(tuple(sorted(e)) for e in edge_list)
    for cyc in cycles:
        # Check distinct vertices
        if len(set(cyc)) != len(cyc):
            raise ValueError("Cycle contains duplicate vertices")
        # Check edges
        for i in range(len(cyc)):
            u = cyc[i]
            v = cyc[(i + 1) % len(cyc)]
            if (u, v) not in edge_set and (v, u) not in edge_set:
                raise ValueError(f"Missing edge ({u}, {v}) in cycle of length {len(cyc)}")
    
    return {'edges': edge_list, 'cycles': cycles}
# EVOLVE-BLOCK-END
