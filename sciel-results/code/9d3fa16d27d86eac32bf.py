def construct():
    t0 = time.time()
    n, m, p = 3, 3, 6
    
    # Try rank-46 decomposition: two copies of rank-23 3x3x3
    U23, V23, W23 = _rank23_333()
    rank = 46
    U = [[0] * rank for _ in range(n * m)]  # 9 x 46
    V = [[0] * rank for _ in range(m * p)]  # 18 x 46
    W = [[0] * rank for _ in range(p * n)]  # 18 x 46
    
    # First copy: k = 0, 1, 2 (columns 0-2 of B)
    for r in range(23):
        for ij in range(9):
            U[ij][r] = U23[ij][r]
        for jk in range(9):
            j = jk // 3
            k = jk % 3
            V[j * p + k][r] = V23[jk][r]
        for ki in range(9):
            k = ki // 3
            i = ki % 3
            W[k * n + i][r] = W23[ki][r]
    
    # Second copy: k = 3, 4, 5 (columns 3-5 of B), offset by 23
    for r in range(23):
        for ij in range(9):
            U[ij][23 + r] = U23[ij][r]
        for jk in range(9):
            j = jk // 3
            k = jk % 3
            V[j * p + (3 + k)][23 + r] = V23[jk][r]
        for ki in range(9):
            k = ki // 3
            i = ki % 3
            W[(3 + k) * n + i][23 + r] = W23[ki][r]
    
    # Verify
    if time.time() - t0 < 100:  # safety margin
        if _verify(U, V, W):
            return {"U": U, "V": V, "W": W}
    
    # Fallback: schoolbook rank 54
    return _schoolbook()
