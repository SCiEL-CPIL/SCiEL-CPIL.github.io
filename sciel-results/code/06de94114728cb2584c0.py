import time
import random
import math
from collections import deque
import numpy as np

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 145.0
    if k == 3:
        return _construct_nonabelian_lift(g, deadline, start_time)
    else:
        return _construct_luw(k, g, d=7)

def _construct_nonabelian_lift(g, deadline, start_time):
    # Petersen graph
    pet_edges = [
        (0,1),(1,2),(2,3),(3,4),(4,0),
        (5,7),(7,9),(9,6),(6,8),(8,5),
        (0,5),(1,6),(2,7),(3,8),(4,9)
    ]
    n_base = 10
    edge_index = {}
    for i,(u,v) in enumerate(pet_edges):
        edge_index[(u,v)] = i
        edge_index[(v,u)] = i
    adj = [[] for _ in range(n_base)]
    for u,v in pet_edges:
        adj[u].append(v); adj[v].append(u)

    # Enumerate non-backtracking closed walks of length < g
    # State: (vertex, prev_vertex, length, product_tuple)
    # Product is a tuple of 15 integers in Z_m (commutative for now)
    # For non-abelian, we'd use group elements, but let's first try
    # a different approach: use the fact that we need ALL walks to have
    # non-trivial product.

    # Actually, let me think differently. The constraint is:
    # For every non-backtracking closed walk w of length < g,
    # the product of voltages along w (in order) must be non-identity.
    #
    # For abelian group: product = sum of (coeff_i * voltage_i) mod m
    # For non-abelian: product = g_{e1} * g_{e2} * ... * g_{eL}
    #
    # Key difference: in non-abelian, the ORDER matters and different
    # walks of same length can give different products.
    #
    # Strategy: Use a small non-abelian group. The simplest is S3 (order 6).
    # We assign each of the 15 edges a generator of S3.
    # S3 = {e, (12), (13), (23), (123), (132)}
    # Generated by a=(12), b=(123). Relations: a^2=e, b^3=e, (ab)^2=e.
    #
    # Each edge gets one of {a, b, a*b, ...} - but we need the voltage to
    # be invertible (it is, since all group elements are).
    #
    # Actually, for a regular cover, each directed edge (u,v) gets a group
    # element g_{uv}, and g_{vu} = g_{uv}^{-1}.
    #
    # Let me use S3 with generators. Represent elements as permutations.
    # S3 elements:
    # 0: identity
    # 1: (12)
    # 2: (13)
    # 3: (23)
    # 4: (123)
    # 5: (132)
    #
    # Multiplication table for S3:
    # Let me label: e=0, s1=(12)=1, s2=(13)=2, s3=(23)=3, r=(123)=4, r2=(132)=5

    # S3 multiplication table (row * col):
    #     e  s1 s2 s3  r  r2
    # e:  0   1  2  3  4   5
    # s1: 1   0  4  5  3   2
    # s2: 2   5  0  4  2   3
    # s3: 3   4  5  0  1   2
    # r:  4   3  2  1  5   0
    # r2: 5   2  3  4  0   1

    S3_mul = np.array([
        [0,1,2,3,4,5],
        [1,0,4,5,3,2],
        [2,5,0,4,2,3],
        [3,4,5,0,1,2],
        [4,3,2,1,5,0],
        [5,2,3,4,0,1]
    ], dtype=np.int64)

    S3_inv = np.array([0,1,2,3,5,4], dtype=np.int64)

    # For the Petersen graph, we assign voltages to the 15 edges.
    # Each voltage is an element of S3 (one of 6 elements).
    # The constraint: for every non-backtracking closed walk of length < g,
    # the product of voltages (in traversal order) != identity (0).

    # Enumerate all non-backtracking closed walks of length < g
    # and record the sequence of edge indices traversed.
    # Then the constraint is: product of S3_mul over the sequence != 0.

    # This is a constraint satisfaction problem: assign each of 15 edges
    # one of 6 values such that all walk products are non-identity.

    # Let's enumerate walks and get edge sequences:
    max_walk_len = g - 1
    walk_edge_seqs = set()  # frozenset won't work, need ordered

    for start_v in range(n_base):
        stack = [(start_v, -1, 0, [])]
        while stack:
            v, prev_v, l, path = stack.pop()
            if l >= max_walk_len:
                continue
            for next_v in adj[v]:
                if next_v == prev_v:
                    continue
                e_idx = edge_index.get((v, next_v))
                if e_idx is None:
                    continue
                new_path = path + [e_idx]
                new_l = l + 1

                if next_v == start_v and new_l >= 5:
                    walk_edge_seqs.add(tuple(new_path))

                stack.append((next_v, v, new_l, new_path))

    # Convert to list
    walk_list = list(walk_edge_seqs)
    n_walks = len(walk_list)

    # Now solve: assign voltage[0..14] in {0,1,2,3,4,5} such that
    # for each walk, the product of voltage[e] for e in walk (with proper
    # direction handling) != 0.
    #
    # Wait - direction matters! When traversing edge (u,v) from u to v,
    # we use voltage (u,v). When traversing from v to u, we use voltage(v,u) = inv(voltage(u,v)).
    #
    # So I need to track the direction. Let me re-enumerate with directions.

    # Re-enumerate: each step records (edge_index, direction) where direction
    # is 0 for forward (u->v as in pet_edges) and 1 for backward.
    walk_edge_dir_seqs = set()

    for start_v in range(n_base):
        stack = [(start_v, -1, 0, [])]
        while stack:
            v, prev_v, l, path = stack.pop()
            if l >= max_walk_len:
                continue
            for next_v in adj[v]:
                if next_v == prev_v:
                    continue
                e_idx = edge_index.get((v, next_v))
                if e_idx is None:
                    continue
                # Determine direction
                u_e, v_e = pet_edges[e_idx]
                if v == u_e and next_v == v_e:
                    direction = 0  # forward
                else:
                    direction = 1  # backward, use inverse

                new_path = path + [(e_idx, direction)]
                new_l = l + 1

                if next_v == start_v and new_l >= 5:
                    walk_edge_dir_seqs.add(tuple(new_path))

                stack.append((next_v, v, new_l, new_path))

    walk_list = list(walk_edge_dir_seqs)
    n_walks = len(walk_list)

    # Now use constraint propagation / local search
    # Variables: voltage[0..14] in {0,1,2,3,4,5}
    # Constraints: for each walk, product != 0

    def evaluate_assignment(volt):
        """Count violated constraints."""
        violations = 0
        for walk in walk_list:
            prod = 0  # identity
            for e_idx, dir in walk:
                val = volt[e_idx]
                if dir == 1:
                    val = S3_inv[val]
                prod = S3_mul[prod, val]
            if prod == 0:
                violations += 1
        return violations

    def try_local_search(volt, max_iter, deadline):
        """Local search to find assignment with 0 violations."""
        volt = volt.copy()
        cost = evaluate_assignment(volt)
        T = 1.0
        cooling = 0.998
        min_T = 0.001

        for i in range(max_iter):
            if time.time() > deadline:
                return volt, cost
            if cost == 0:
                return volt, 0

            j = random.randint(0, 14)
            old_val = volt[j]
            new_val = random.randint(0, 5)
            if new_val == old_val:
                continue

            volt[j] = new_val
            new_cost = evaluate_assignment(volt)
            delta = new_cost - cost

            if delta <= 0 or random.random() < math.exp(-delta / T):
                cost = new_cost
            else:
                volt[j] = old_val

            T *= cooling
            if T < min_T:
                T = min_T

        return volt, cost

    # Try multiple random initializations
    best_volt = None
    best_cost = float('inf')

    n_restarts = 200
    for r in range(n_restarts):
        if time.time() > deadline:
            break
        volt = np.array([random.randint(0, 5) for _ in range(15)], dtype=np.int64)
        volt, cost = try_local_search(volt, 3000, deadline)
        if cost < best_cost:
            best_cost = cost
            best_volt = volt.copy()
        if cost == 0:
            break

    if best_cost == 0 and best_volt is not None:
        # Build the graph
        n_total = 10 * 6  # 60 vertices
        edges = []
        seen = set()
        for i, (u, v) in enumerate(pet_edges):
            vol = int(best_volt[i])
            vol_inv = int(S3_inv[vol])
            for t in range(6):
                u_node = t * 10 + u
                v_node = ((t + vol) % 6) * 10 + v
                edge = (min(u_node, v_node), max(u_node, v_node))
                if edge not in seen:
                    seen.add(edge)
                    edges.append(edge)

        # Verify
        if _verify_girth(n_total, edges, g):
            return n_total, edges

    # If S3 doesn't work, try a larger group or fall back
    # Try Z_p abelian as fallback (current approach but optimized)
    return _construct_abelian_optimized(g, deadline, start_time)


def _construct_abelian_optimized(g, deadline, start_time):
    """Optimized abelian voltage lift on Petersen graph."""
    pet_edges = [
        (0,1),(1,2),(2,3),(3,4),(4,0),
        (5,7),(7,9),(9,6),(6,8),(8,5),
        (0,5),(1,6),(2,7),(3,8),(4,9)
    ]
    n_base = 10
    edge_index = {}
    for i,(u,v) in enumerate(pet_edges):
        edge_index[(u,v)] = i
        edge_index[(v,u)] = i
    adj = [[] for _ in range(n_base)]
    for u,v in pet_edges:
        adj[u].append(v); adj[v].append(u)

    # Enumerate non-backtracking closed walks, get coefficient vectors
    max_walk_len = g - 1
    coeff_vectors = set()

    for start_v in range(n_base):
        stack = [(start_v, -1, 0, [0]*15)]
        while stack:
            v, prev_v, l, counts = stack.pop()
            if l >= max_walk_len:
                continue
            for next_v in adj[v]:
                if next_v == prev_v:
                    continue
                e_idx = edge_index.get((v, next_v))
                if e_idx is None:
                    continue
                u_e, v_e = pet_edges[e_idx]
                if v == u_e and next_v == v_e:
                    sign = 1
                else:
                    sign = -1

                new_counts = counts.copy()
                new_counts[e_idx] += sign
                new_l = l + 1

                if next_v == start_v and new_l >= 5:
                    coeff_vectors.add(tuple(new_counts))

                stack.append((next_v, v, new_l, new_counts))

    # Normalize
    unique_coeffs = set()
    for c in coeff_vectors:
        if all(x == 0 for x in c):
            continue
        for i in range(15):
            if c[i] != 0:
                if c[i] < 0:
                    c = tuple(-x for x in c)
                unique_coeffs.add(c)
                break
    coeff_list = list(unique_coeffs)
    A = np.array(coeff_list, dtype=np.int64)
    n_constraints = len(A)

    def is_prime(n):
        if n < 2: return False
        if n == 2: return True
        if n % 2 == 0: return False
        for i in range(3, int(n**0.5) + 1, 2):
            if n % i == 0: return False
        return True

    primes = []
    candidate = 79
    while len(primes) < 30:
        if is_prime(candidate):
            primes.append(candidate)
        candidate += 1

    best_n = float('inf')
    best_edges = None

    for m in primes:
        if time.time() > deadline:
            break
        n_candidate = 10 * m
        if n_candidate >= best_n:
            continue

        found = False
        voltages = None

        max_restarts = 10
        for restart in range(max_restarts):
            if time.time() > deadline:
                break

            v = np.array([random.randint(1, m-1) for _ in range(15)], dtype=np.int64)
            prod = (A @ v) % m
            cost = np.sum(prod == 0)

            T = 1.0
            cooling = 0.997
            min_T = 0.001
            max_iter = 12000

            for i in range(max_iter):
                if time.time() > deadline:
                    break
                if cost == 0:
                    found = True
                    voltages = v
                    break

                j = random.randint(0, 14)
                old_val = v[j]
                new_val = random.randint(1, m-1)
                if new_val == old_val:
                    continue

                delta = (A[:, j] * (new_val - old_val)) % m
                new_prod = (prod + delta) % m
                old_viol = prod == 0
                new_viol = new_prod == 0
                delta_cost = np.sum(new_viol) - np.sum(old_viol)

                if delta_cost <= 0 or random.random() < math.exp(-delta_cost / T):
                    v[j] = new_val
                    prod = new_prod
                    cost += delta_cost

                T *= cooling
                if T < min_T:
                    T = min_T

            if found:
                break

        if found:
            edges = _build_lifted_graph(pet_edges, voltages, m)
            if _verify_girth(n_candidate, edges, g):
                return n_candidate, edges

    return _construct_luw(k=3, g=g, d=11)


def _build_lifted_graph(pet_edges, voltages, m):
    n_base = 10
    edge_index = {}
    for i,(u,v) in enumerate(pet_edges):
        edge_index[(u,v)] = i
        edge_index[(v,u)] = i

    edges = []
    seen = set()
    for i,(u,v) in enumerate(pet_edges):
        vol = int(voltages[i])
        for t in range(m):
            u_node = t * n_base + u
            v_node = ((t + vol) % m) * n_base + v
            edge = (min(u_node, v_node), max(u_node, v_node))
            if edge not in seen:
                seen.add(edge)
                edges.append(edge)
    return edges


def _verify_girth(n, edges, g):
    adj = [[] for _ in range(n)]
    for u,v in edges:
        adj[u].append(v)
        adj[v].append(u)

    for start in range(n):
        dist = [-1] * n
        parent = [-1] * n
        queue = deque()
        queue.append((start, 0))
        dist[start] = 0
        while queue:
            u, d = queue.popleft()
            if d >= g:
                continue
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = d + 1
                    parent[v] = u
                    queue.append((v, d+1))
                elif v != parent[u]:
                    cycle_len = dist[u] + dist[v] + 1
                    if cycle_len < g:
                        return False
    return True


def _construct_luw(k, g, d=None, variant=0):
    if d is None:
        d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    q = k
    if q == 4:
        table = [[0,0,0,0],[0,1,2,3],[0,2,3,1],[0,3,1,2]]
        add = lambda x,y: x ^ y
        sub = lambda x,y: x ^ y
        mul = lambda x,y: table[x][y]
    else:
        add = lambda x,y: (x+y) % q
        sub = lambda x,y: (x-y) % q
        mul = lambda x,y: x*y % q

    rule = {2:(1,1), 3:(2,1), 4:(1,2)}
    offset = variant % 4
    for c in range(5, d+1):
        r = (c - 5 + offset) % 4
        c0 = c - (c-5) % 4
        rule[c] = [(1, c0-2),(c0-1, 1),(c0, 1),(1, c0+1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0]*(d-1)
            for c in range(2, d+1):
                a, b = rule[c]
                if side == 0:
                    y[c] = add(x[c], mul(y[a], x[b]))
                else:
                    y[c] = sub(x[c], mul(x[a], y[b]))
            yield 1-side, tuple(y)

    start = (0, (None,) + (0,)*d)
    index = {start: 0}
    order = [start]
    edges = []
    for i, vertex in enumerate(order):
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
