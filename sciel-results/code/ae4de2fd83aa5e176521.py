"""Construct A_2(18,6) code via shortening the [24,12,8] Golay code."""

# EVOLVE-BLOCK-START
import time

_START = time.time()
_DEADLINE = _START + 80.0  # safety margin before 90s kill


def _golay_generator_poly():
    """Return the 24-bit generator polynomial for the [24,12,8] Golay code.

    The generator polynomial is g(x) = x^12 + x^11 + x^10 + x^6 + x^5 + x + 1.
    This is the product of the minimal polynomials of alpha and alpha^3
    over GF(2), where alpha is a primitive element of GF(16).
    """
    # g(x) = x^12 + x^11 + x^10 + x^6 + x^5 + x + 1
    g = 0
    for bit in (0, 1, 5, 6, 10, 11, 12):
        g |= 1 << bit
    return g


def _gf2_poly_mult(a, b):
    """Multiply two polynomials over GF(2)."""
    result = 0
    while a:
        if a & 1:
            result ^= b
        a >>= 1
        b <<= 1
    return result


def _gf2_poly_mod(a, m):
    """Compute a mod m over GF(2), where m is monic."""
    # Find degree of m
    deg_m = m.bit_length() - 1
    while a.bit_length() > deg_m:
        shift = a.bit_length() - 1 - deg_m
        a ^= m << shift
    return a


def _build_golay_code():
    """Build all 4096 codewords of the [24,12,8] binary Golay code.

    The code is generated by g(x) = x^12 + x^11 + x^10 + x^6 + x^5 + x + 1.
    Every codeword is m(x) * g(x) mod (x^24 - 1) for some degree-12 message m(x).
    """
    g = _golay_generator_poly()
    # x^24 - 1 over GF(2) is x^24 + 1 (since char 2, -1 = 1)
    mod_poly = (1 << 24) | 1  # x^24 + 1

    codewords = []
    for msg in range(4096):
        # Multiply msg * g
        cw = _gf2_poly_mult(msg, g)
        # Reduce mod (x^24 + 1)
        cw = _gf2_poly_mod(cw, mod_poly)
        codewords.append(cw)

    # Deduplicate (shouldn't be needed but safe)
    unique = list(set(codewords))
    return unique


def _shorten_and_extend(golay_words, n_target=18):
    """Shorten the Golay code to length 18 by fixing 6 coordinates to 0.

    We fix the first 6 coordinates (positions 0-5) to 0, giving an
    18-bit code. Since the Golay code has min distance 8, the shortened
    code has min distance at least 8 >= 6.
    
    Actually, shortening by fixing coordinates to 0: we keep only codewords
    that have 0 in those positions, then remove those positions.
    """
    # Fix positions 0..5 to zero: keep only words with those bits = 0
    mask = (1 << 6) - 1  # lower 6 bits
    shortened = []
    for w in golay_words:
        if (w & mask) == 0:
            # Remove the fixed 6 bits, keep bits 6..23
            new_w = (w >> 6) & ((1 << 18) - 1)
            shortened.append(new_w)

    # Deduplicate
    return list(set(shortened))


def _verify_min_distance(words, min_dist=6):
    """Verify all pairs have Hamming distance >= min_dist."""
    n = len(words)
    for i in range(n):
        for j in range(i + 1, n):
            d = (words[i] ^ words[j]).bit_count()
            if d < min_dist:
                return False
    return True


def _greedy_extend(words, n_bits=18, min_dist=6, time_limit=75.0):
    """Try to greedily add words to the code."""
    words = list(words)
    n = len(words)
    # Precompute distances from new candidates to all existing words
    # For efficiency, try random words
    import random
    rng = random.Random(42)
    
    while time.time() < time_limit:
        # Try a batch of random candidates
        added = False
        for _ in range(20000):
            candidate = rng.getrandbits(n_bits)
            ok = True
            for w in words:
                if (candidate ^ w).bit_count() < min_dist:
                    ok = False
                    break
            if ok:
                words.append(candidate)
                added = True
                if len(words) >= 512:
                    return words
        if not added and time.time() > time_limit - 5:
            break
    return words


def construct():
    """Construct the largest possible collection of 18-bit words with
    pairwise Hamming distance at least 6."""
    
    # Build the Golay code
    golay = _build_golay_code()
    
    # Shorten to 18 bits by fixing 6 coordinates to 0
    code = _shorten_and_extend(golay, n_target=18)
    
    # Verify
    if not _verify_min_distance(code, min_dist=6):
        # Fallback to Reed-Muller if something went wrong
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words
    
    # Try to extend with greedy search if time permits
    if time.time() < _DEADLINE - 10 and len(code) < 512:
        code = _greedy_extend(code, n_bits=18, min_dist=6, 
                             time_limit=_DEADLINE - 5)
    
    return code
