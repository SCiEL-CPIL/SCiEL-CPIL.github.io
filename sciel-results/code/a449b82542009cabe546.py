import time
import random
import math
from collections import defaultdict

def construct():
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    def gcd(a, b):
        while b:
            a, b = b, a % b
        return a

    def line_key(p1, p2):
        x1, y1 = p1
        x2, y2 = p2
        dx = x2 - x1
        dy = y2 - y1
        g = gcd(abs(dx), abs(dy))
        if g == 0:
            return None
        dx //= g
        dy //= g
        # Normalize direction
        if dx < 0 or (dx == 0 and dy < 0):
            dx = -dx
            dy = -dy
        # Equation: dy*x - dx*y = C
        # C = dy*x1 - dx*y1
        C = dy * x1 - dx * y1
        return (dx, dy, C)

    def evaluate(points):
        # points: list of 16 tuples (x, y)
        # Check distinctness
        if len(set(points)) != 16:
            return -1
        
        # Check bounds
        for x, y in points:
            if abs(x) > 1000 or abs(y) > 1000:
                return -1
        
        line_counts = defaultdict(int)
        # Map point index to line keys? No, just count points per line.
        # We need to identify unique lines and count how many points are on them.
        # A line is defined by its key.
        # But a line might be generated by multiple pairs.
        # So, collect all unique line keys from all pairs.
        # Then, for each line key, count how many points lie on it.
        
        unique_lines = set()
        for i in range(16):
            for j in range(i + 1, 16):
                key = line_key(points[i], points[j])
                if key:
                    unique_lines.add(key)
        
        # Now count points on each line
        # This is O(16^2 * 16) = 4096 ops per eval. Very fast.
        score = 0
        for key in unique_lines:
            dx, dy, C = key
            count = 0
            for p in points:
                x, y = p
                if dx * x - dy * y == C:
                    count += 1
            if count == 4:
                score += 1
            elif count >= 5:
                return -1  # Invalid
        
        return score

    def random_point():
        return (random.randint(-1000, 1000), random.randint(-1000, 1000))

    def local_search(points, max_iters=10000):
        current_score = evaluate(points)
        if current_score < 0:
            return points, 0
        
        best_points = points
        best_score = current_score
        current_points = list(points)
        
        for _ in range(max_iters):
            if time.time() > deadline:
                break
            
            # Pick a random point to move
            idx = random.randint(0, 15)
            old_p = current_points[idx]
            
            # Generate a new position
            # Strategy: Small perturbation or random jump
            if random.random() < 0.5:
                # Small perturbation
                new_p = (old_p[0] + random.randint(-5, 5), old_p[1] + random.randint(-5, 5))
            else:
                # Random jump
                new_p = random_point()
            
            # Ensure distinctness and bounds
            if new_p in current_points:
                continue
            if abs(new_p[0]) > 1000 or abs(new_p[1]) > 1000:
                continue
                
            current_points[idx] = new_p
            new_score = evaluate(current_points)
            
            if new_score > best_score:
                best_score = new_score
                best_points = list(current_points)
                current_score = new_score
            elif new_score == best_score:
                # Accept equal score to explore
                if random.random() < 0.5:
                    current_score = new_score
                else:
                    current_points[idx] = old_p
            else:
                # Worse score, revert
                current_points[idx] = old_p
        
        return best_points, best_score

    # Initial configurations
    best_overall_score = 0
    best_overall_points = None
    
    # 1. 4x4 Grid
    grid_points = [(x, y) for x in range(4) for y in range(4)]
    p, s = local_search(grid_points, max_iters=5000)
    if s > best_overall_score:
        best_overall_score = s
        best_overall_points = p
    
    # 2. Random restarts
    for _ in range(10):
        if time.time() > deadline:
            break
        random_points = [random_point() for _ in range(16)]
        # Ensure distinct
        while len(set(random_points)) < 16:
            random_points[random.randint(0, 15)] = random_point()
        p, s = local_search(random_points, max_iters=2000)
        if s > best_overall_score:
            best_overall_score = s
            best_overall_points = p
    
    # 3. Try specific known good structures if we have time
    # e.g. points on a circle? No, integer points.
    # Try a 5x4 grid subset?
    
    if best_overall_points is None:
        return [[x, y] for x in range(4) for y in range(4)]
    
    return [[x, y] for x, y in best_overall_points]
