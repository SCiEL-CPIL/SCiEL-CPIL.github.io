import numpy as np
import itertools

def construct(q, n, radius):
    # For this specific task, q=3, n=8, radius=1.
    # General implementation for the given parameters.
    
    # Generate all words in the space
    all_words = np.array(list(itertools.product(range(q), repeat=n)))
    total_words = len(all_words)
    
    # Precompute the index mapping from word tuple to index
    # Since q^n can be large, we map directly.
    # For q=3, n=8, 3^8 = 6561.
    # We can use a dictionary or just rely on the array indices if we generate them systematically.
    # itertools.product generates in lexicographic order.
    
    # Precompute the coverage masks for each codeword.
    # A codeword covers itself and all words at Hamming distance <= radius.
    # For radius=1, it covers the word itself and words differing in exactly 1 position.
    
    # We will store masks as a 2D boolean array of shape (total_words, total_words)
    # masks[i, j] is True if codeword i covers word j.
    
    # This might be memory heavy for large n, but for n=8, it's fine.
    # 6561 * 6561 * 1 byte = ~43 MB.
    
    masks = np.zeros((total_words, total_words), dtype=bool)
    
    for i, word in enumerate(all_words):
        # Cover self
        masks[i, i] = True
        if radius >= 1:
            # Cover neighbors
            for pos in range(n):
                original_val = word[pos]
                for new_val in range(q):
                    if new_val == original_val:
                        continue
                    # Create the neighbor word
                    # We need to find the index of this neighbor in all_words.
                    # Since all_words is generated by itertools.product, the index is the base-q number.
                    # Let's compute the index directly.
                    # index = sum(digit * q^(n-1-pos) for pos, digit in enumerate(word))
                    # This is faster than searching.
                    
                    # Actually, let's just precompute the indices for all words.
                    # We can map the word to an integer index.
                    # index = 0
                    # for d in word:
                    #   index = index * q + d
                    # This matches itertools.product order.
                    
                    # So we can compute the neighbor's index directly.
                    # Let's do this to avoid storing the full all_words array for lookup, 
                    # although we already have it.
                    
                    # To compute index of neighbor:
                    # We can take the index of the original word and adjust it.
                    # index = sum(w[k] * q^(n-1-k) for k in range(n))
                    # diff = (new_val - original_val) * q^(n-1-pos)
                    # neighbor_index = index + diff
                    
                    # We need the powers of q.
                    pass
        
    # Let's optimize the mask generation.
    # Instead of iterating and creating neighbors, we can iterate over all pairs? No.
    # Let's stick to the direct index calculation.
    
    powers = [q ** (n - 1 - i) for i in range(n)]
    
    # Precompute indices for all words? 
    # The i-th word in itertools.product(range(q), repeat=n) has index i.
    # So all_words[i] is the word with index i.
    
    for i in range(total_words):
        word = all_words[i]
        masks[i, i] = True
        for pos in range(n):
            orig = word[pos]
            for new_val in range(q):
                if new_val == orig:
                    continue
                # Calculate index of the neighbor
                # index = sum(all_words[i][k] * powers[k] for k in range(n))
                # We can compute the index of the current word i?
                # Actually, i IS the index.
                # So neighbor_index = i + (new_val - orig) * powers[pos]
                n_idx = i + (new_val - orig) * powers[pos]
                masks[i, n_idx] = True

    # Greedy Set Cover
    uncovered = np.ones(total_words, dtype=bool)
    selected = []
    
    while np.any(uncovered):
        # Calculate gain for each codeword
        # gain[i] = sum(masks[i] & uncovered)
        # This is a dot product of rows of masks with uncovered
        gains = np.sum(masks & uncovered[:, None], axis=1)
        
        # Find the best codeword
        best_idx = np.argmax(gains)
        
        # If no gain, break (should not happen if uncovered is not empty and masks are valid)
        if gains[best_idx] == 0:
            break
            
        selected.append(all_words[best_idx].tolist())
        
        # Update uncovered
        uncovered[masks[best_idx]] = False
        
    return selected
