import random
import time
import math

def construct():
    initial = [1, 2, 5, 11]
    fixed = set(initial)
    
    start_time = time.time()
    time_limit = 115.0
    
    best_set = initial[:]
    best_size = len(initial)
    
    def get_conflicts(x, S, sums):
        """Return True if x can be added to S without conflict."""
        if 2 * x in sums:
            return False
        for y in S:
            if x + y in sums:
                return False
        return True

    def add_to_sums(x, S, sums):
        sums.add(2 * x)
        for y in S:
            sums.add(x + y)

    def remove_from_sums(x, S, sums):
        # We need to be careful not to remove sums that are generated by other pairs
        # This is tricky with a set. It's safer to recalculate sums if size is small.
        # Or, maintain a count dictionary for sums.
        pass # We will use a count dict for sums to make removal easy.

    # Let's use a dictionary for sum counts to allow O(1) removal.
    
    def make_valid_start():
        S = initial[:]
        sums_count = {}
        for i in range(len(S)):
            for j in range(i, len(S)):
                s = S[i] + S[j]
                sums_count[s] = sums_count.get(s, 0) + 1
        return S, sums_count

    S, sums_count = make_valid_start()
    
    T = 10.0
    cooling = 0.999
    
    while time.time() - start_time < time_limit:
        if T < 0.1:
            T = 10.0 # Restart or just keep going? Let's just keep going with low T.
            # Actually, for SA, we usually cool down. If we hit 0, we are stuck.
            # Let's allow T to go low and then maybe random restart if stuck?
            # For now, just cool down.
            
        # Generate a random move
        move_type = random.random()
        
        new_S = S[:]
        new_sums_count = dict(sums_count)
        accepted = False
        size_delta = 0
        
        if move_type < 0.4:
            # Try to add an element
            candidates = [x for x in range(1, 285) if x not in S]
            if candidates:
                x = random.choice(candidates)
                # Check validity
                valid = True
                if new_sums_count.get(2 * x, 0) > 0:
                    valid = False
                else:
                    for y in S:
                        if new_sums_count.get(x + y, 0) > 0:
                            valid = False
                            break
                if valid:
                    new_S.append(x)
                    new_sums_count[2 * x] = new_sums_count.get(2 * x, 0) + 1
                    for y in S:
                        new_sums_count[x + y] = new_sums_count.get(x + y, 0) + 1
                    size_delta = 1
                    accepted = True # Always accept size increase
                else:
                    # Reject
                    accepted = False
        elif move_type < 0.7:
            # Try to remove an element (non-fixed)
            removable = [x for x in S if x not in fixed]
            if removable:
                x = random.choice(removable)
                # Remove x from new_S and new_sums_count
                new_S.remove(x)
                new_sums_count[2 * x] -= 1
                if new_sums_count[2 * x] == 0:
                    del new_sums_count[2 * x]
                for y in S:
                    if y != x:
                        new_sums_count[x + y] -= 1
                        if new_sums_count[x + y] == 0:
                            del new_sums_count[x + y]
                size_delta = -1
                # Accept with probability based on T
                delta_E = -size_delta # Cost increases by 1 (size decreases)
                prob = math.exp(-delta_E / T) if T > 0 else 0
                if random.random() < prob:
                    accepted = True
        else:
            # Try to swap an element
            removable = [x for x in S if x not in fixed]
            if removable:
                x = random.choice(removable)
                candidates = [y for y in range(1, 285) if y not in S]
                if candidates:
                    y = random.choice(candidates)
                    # Check if swapping x with y is valid
                    # Remove x, add y
                    temp_sums = dict(new_sums_count)
                    # Remove x
                    temp_sums[2 * x] -= 1
                    if temp_sums[2 * x] == 0:
                        del temp_sums[2 * x]
                    for z in S:
                        if z != x:
                            temp_sums[x + z] -= 1
                            if temp_sums[x + z] == 0:
                                del temp_sums[x + z]
                    
                    # Check if y can be added
                    valid = True
                    if temp_sums.get(2 * y, 0) > 0:
                        valid = False
                    else:
                        for z in S:
                            if z != x:
                                if temp_sums.get(y + z, 0) > 0:
                                    valid = False
                                    break
                    if valid:
                        # Add y
                        temp_sums[2 * y] = temp_sums.get(2 * y, 0) + 1
                        for z in S:
                            if z != x:
                                temp_sums[y + z] = temp_sums.get(y + z, 0) + 1
                        
                        new_S.remove(x)
                        new_S.append(y)
                        new_sums_count = temp_sums
                        size_delta = 0
                        accepted = True # Always accept same size? Or with prob?
                        # To explore, accept with prob 1.0 initially, maybe lower later?
                        # Let's accept to allow movement.
                    else:
                        accepted = False

        if accepted:
            S = new_S
            sums_count = new_sums_count
            if len(S) > best_size:
                best_size = len(S)
                best_set = S[:]
        
        T *= cooling

    return best_set
