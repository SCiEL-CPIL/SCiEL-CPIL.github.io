DIMENSIONS = [3, 3, 5]

def construct():
    n, m, p = DIMENSIONS
    # Rank 33: 27 for 3x3x3 + 6 for 3x3x2
    rank = 33
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Part 1: 3x3x3 schoolbook
    # i, j, k in 0..2
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(3):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
                
    # Part 2: 3x3x2 schoolbook for k=3,4
    # i, j in 0..2, k in 3,4
    for i in range(n):
        for j in range(m):
            for k in range(3, p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
