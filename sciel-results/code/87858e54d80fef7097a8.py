"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 100
TARGET_SUM = N / 2.0

# EVOLVE-BLOCK-START
import numpy as np
import time
from scipy.optimize import minimize

def _get_linear_overlaps(h):
    """
    Compute linear cross-correlation of h with (1-h) for all non-zero shifts.
    Returns an array of overlap values C_k for k != 0.
    C_k = sum_i h_i * (1 - h_{i+k})
    """
    g = 1.0 - h
    c = np.correlate(h, g, mode='full')
    c_neg = c[:N-1]
    c_pos = c[N:]
    return np.concatenate([c_neg, c_pos])

def _max_overlap(h):
    """Return the maximum linear overlap value."""
    overlaps = _get_linear_overlaps(h)
    if len(overlaps) == 0:
        return 0.0
    return np.max(overlaps)

def _project_to_feasible(h):
    """
    Project h onto the feasible set: 0 <= h_i <= 1 and sum(h) = N/2.
    Uses exact convex projection via bisection on Lagrange multiplier.
    """
    h = np.clip(h, 0.0, 1.0).copy()
    target = TARGET_SUM
    
    def _sum_with_shift(shift):
        return np.sum(np.clip(h + shift, 0.0, 1.0))
    
    current = np.sum(h)
    if abs(current - target) < 1e-14:
        return h
    
    # Bisection to find shift that makes sum = target
    lo, hi = -1.0, 1.0
    for _ in range(60):
        mid = (lo + hi) / 2.0
        s = _sum_with_shift(mid)
        if s < target:
            lo = mid
        else:
            hi = mid
    h = np.clip(h + (lo + hi) / 2.0, 0.0, 1.0)
    
    # Final tiny correction
    diff = target - np.sum(h)
    if abs(diff) > 1e-14:
        # Distribute among non-saturated elements
        free = (h > 1e-10) & (h < 1.0 - 1e-10)
        if np.any(free):
            h[free] += diff / np.sum(free)
            h = np.clip(h, 0.0, 1.0)
    
    return h

def _objective_lse(x, beta, lam_sum):
    """
    Objective function using LogSumExp approximation of the max overlap.
    """
    h = np.clip(x, 0, 1)
    overlaps = _get_linear_overlaps(h)
    
    if len(overlaps) == 0:
        max_ov = 0.0
    else:
        max_ov = np.max(overlaps)
        
    if max_ov > 1000:
        max_ov = 1000
        
    if beta > 0:
        shifted = overlaps - max_ov
        lse = max_ov + np.log(np.sum(np.exp(beta * shifted))) / beta
    else:
        lse = max_ov
    
    sum_penalty = lam_sum * (np.sum(h) - TARGET_SUM) ** 2
    return lse + sum_penalty

def _generate_h_rational(theta):
    """
    Generate h from rational generating function parameters.
    theta = [a1, a2, a3, b1, b2, b3, c0]
    where h is generated by the rational filter:
      H(z) = (1 + a1*z + a2*z^2 + a3*z^3) / (1 + b1*z + b2*z^2 + b3*z^3)
    applied to an impulse, then scaled and shifted.
    """
    a1, a2, a3 = theta[0], theta[1], theta[2]
    b1, b2, b3 = theta[3], theta[4], theta[5]
    c0 = theta[6]
    
    # Generate impulse response of the rational filter
    # y[n] = x[n] - b1*y[n-1] - b2*y[n-2] - b3*y[n-3]
    # with x[0]=1, x[n]=0 for n>0
    # Actually for transfer function H(z) = (1+a1 z + a2 z^2 + a3 z^3)/(1+b1 z + b2 z^2 + b3 z^3)
    # y[n] + b1*y[n-1] + b2*y[n-2] + b3*y[n-3] = x[n] + a1*x[n-1] + a2*x[n-2] + a3*x[n-3]
    
    y = np.zeros(N)
    x = np.zeros(N)
    x[0] = 1.0
    
    for n in range(N):
        val = x[n]
        if n >= 1:
            val += a1 * x[n-1]
        if n >= 2:
            val += a2 * x[n-2]
        if n >= 3:
            val += a3 * x[n-3]
        if n >= 1:
            val -= b1 * y[n-1]
        if n >= 2:
            val -= b2 * y[n-2]
        if n >= 3:
            val -= b3 * y[n-3]
        y[n] = val
    
    # Normalize: shift and scale to get mean 0.5 and bounded in [0,1]
    y_mean = np.mean(y)
    y_std = np.std(y)
    if y_std < 1e-10:
        h = np.full(N, 0.5)
    else:
        # Scale so that c0 controls the amplitude
        h = 0.5 + c0 * (y - y_mean) / y_std
    
    h = _project_to_feasible(h)
    return h

def _objective_rational(theta):
    """
    Objective for rational parameter optimization.
    """
    h = _generate_h_rational(theta)
    return _objective_lse(h, 50.0, 0.0)

def construct():
    """
    Construct the step heights h to minimize the maximum overlap of h with shifted 1-h.
    
    Strategy:
    1. Low-dimensional search over rational generating function parameters.
    2. Full-dimensional L-BFGS-B refinement from that point.
    """
    start_time = time.time()
    deadline = start_time + 115.0
    
    best_h_low_dim = None
    best_score_low_dim = float('inf')
    
    rng = np.random.default_rng(42)
    
    # Parameters: [a1, a2, a3, b1, b2, b3, c0]
    # a's in [-0.8, 0.8], b's in [-0.8, 0.8] (for stability), c0 in [0.1, 0.45]
    bounds_theta = [
        (-0.8, 0.8), (-0.8, 0.8), (-0.8, 0.8),
        (-0.8, 0.8), (-0.8, 0.8), (-0.8, 0.8),
        (0.1, 0.45)
    ]
    
    # Try multiple random starts for the low-dim optimization
    num_starts = 30
    for i in range(num_starts):
        if time.time() > deadline - 35.0:
            break
            
        # Random start
        theta0 = np.array([
            rng.uniform(-0.5, 0.5), rng.uniform(-0.3, 0.3), rng.uniform(-0.2, 0.2),
            rng.uniform(-0.5, 0.5), rng.uniform(-0.3, 0.3), rng.uniform(-0.2, 0.2),
            rng.uniform(0.15, 0.4)
        ])
        
        try:
            res = minimize(
                _objective_rational, 
                theta0, 
                method='Powell', 
                bounds=bounds_theta,
                options={'maxiter': 300, 'xtol': 1e-7, 'ftol': 1e-7}
            )
            h_cand = _generate_h_rational(res.x)
            score_cand = _max_overlap(h_cand)
            
            if score_cand < best_score_low_dim:
                best_score_low_dim = score_cand
                best_h_low_dim = h_cand
        except Exception:
            pass

    # If low-dim search failed, fallback to simple sinusoid
    if best_h_low_dim is None:
        best_h_low_dim = _project_to_feasible(0.5 + 0.3 * np.sin(2 * np.pi * 5 * np.arange(N) / N))
        best_score_low_dim = _max_overlap(best_h_low_dim)

    # 2. Full-dimensional refinement
    best_h = best_h_low_dim.copy()
    best_score = best_score_low_dim
    
    bounds = [(0.0, 1.0) for _ in range(N)]
    
    # Refinement phases with increasing beta
    beta_schedule = [20, 50, 100, 200, 500]
    
    for beta in beta_schedule:
        if time.time() > deadline - 10.0:
            break
        
        def obj_func(x):
            return _objective_lse(x, beta, 100.0)
        
        try:
            result = minimize(
                obj_func, best_h, method='L-BFGS-B', bounds=bounds,
                options={'maxiter': 200, 'ftol': 1e-10, 'gtol': 1e-8}
            )
            h_new = _project_to_feasible(result.x)
            score_new = _max_overlap(h_new)
            if score_new < best_score:
                best_score = score_new
                best_h = h_new
        except Exception:
            pass

    # Final precision polish
    if time.time() < deadline - 5.0:
        def obj_polish(x):
            return _objective_lse(x, 1000.0, 1000.0)
        
        try:
            result = minimize(
                obj_polish, best_h, method='L-BFGS-B', bounds=bounds,
                options={'maxiter': 500, 'ftol': 1e-12, 'gtol': 1e-10}
            )
            h_polished = _project_to_feasible(result.x)
            score_polished = _max_overlap(h_polished)
            if score_polished < best_score:
                best_score = score_polished
                best_h = h_polished
        except Exception:
            pass
    
    # Ensure final validity
    best_h = _project_to_feasible(best_h)
    
    # Final precision polish: ensure sum is exactly N/2
    sum_h = np.sum(best_h)
    diff = TARGET_SUM - sum_h
    if abs(diff) > 1e-12:
        if best_h[0] + diff <= 1.0 and best_h[0] + diff >= 0.0:
            best_h[0] += diff
        else:
            best_h = best_h * (TARGET_SUM / sum_h)
            best_h = np.clip(best_h, 0.0, 1.0)
            best_h = _project_to_feasible(best_h)
    
    return best_h

