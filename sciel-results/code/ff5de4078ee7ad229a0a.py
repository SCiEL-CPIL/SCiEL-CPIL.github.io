import time

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    timeout = 115  # Safety margin

    mandatory = [1, 2, 5, 11]
    used_sums = set()
    for i in range(len(mandatory)):
        for j in range(i, len(mandatory)):
            used_sums.add(mandatory[i] + mandatory[j])
    
    # Candidates sorted. 
    # Let's try sorting by value.
    candidates = [x for x in range(1, 285) if x not in mandatory]
    
    best_set = mandatory[:]
    best_size = len(mandatory)

    # We want to maximize size.
    # Max possible is 20.
    # We try total sizes from 20 down to 4.
    
    # To speed up, we can pre-compute conflicts?
    # Or just do it in DFS.
    
    def dfs(current_set, used_sums, remaining_candidates, target_size):
        nonlocal best_set, best_size, timeout, start_time
        
        if time.time() - start_time > timeout:
            return False

        current_size = len(current_set)
        if current_size == target_size:
            best_set = current_set[:]
            best_size = target_size
            return True
        
        # Pruning: not enough candidates left
        if current_size + len(remaining_candidates) < target_size:
            return False
            
        # Heuristic: Try candidates that are "good".
        # A simple heuristic is to just iterate.
        # But we can sort remaining_candidates dynamically?
        # Maybe try values that are far from existing ones?
        # Let's stick to the given order (ascending) for now, but use forward checking.
        
        for i, x in enumerate(remaining_candidates):
            # Check if x is valid with current_set
            new_sums = set()
            valid = True
            for y in current_set:
                s = x + y
                if s in used_sums or s in new_sums:
                    valid = False
                    break
                new_sums.add(s)
            if valid:
                s = 2 * x
                if s in used_sums or s in new_sums:
                    valid = False
                else:
                    new_sums.add(s)
            
            if valid:
                # If we add x, which other candidates become invalid?
                # A candidate y is invalid if x+y is in used_sums (including new_sums from x)
                # Or if 2y is in used_sums? No, 2y is only checked when y is added.
                # But if x+y is in used_sums, y cannot be added later because x is in the set.
                # So we filter remaining_candidates[i+1:]
                
                new_used_sums = used_sums | new_sums
                
                filtered_remaining = []
                for y in remaining_candidates[i+1:]:
                    # Check if y conflicts with x
                    # If x + y is in new_used_sums, then y cannot be added.
                    # Note: new_used_sums contains sums involving x.
                    # If x+y is in new_used_sums, it means either x+y was already used (impossible, x is new) 
                    # or x+y is one of the sums generated by adding x (i.e., x+y = x+z for some z in current_set -> y=z, but y is in remaining so y not in current_set)
                    # Wait. new_sums contains {x+z | z in current_set} and {2x}.
                    # If x+y is in new_sums, then x+y = x+z for some z in current_set => y=z. But y is in remaining, z is in current. So y != z.
                    # Or x+y = 2x => y=x. But y != x.
                    # So x+y cannot be in new_sums?
                    # Let's re-evaluate.
                    # new_sums = {x+z for z in current_set} U {2x}.
                    # If we try to add y later, we check sums {y+z' for z' in (current_set U {x})} U {2y}.
                    # One of these sums is y+x.
                    # If y+x is in new_used_sums, it's a conflict.
                    # new_used_sums = old_used_sums U new_sums.
                    # y+x is in old_used_sums? If so, y is invalid.
                    # y+x is in new_sums? 
                    # new_sums has x+z. So y+x = x+z => y=z. Impossible.
                    # new_sums has 2x. So y+x = 2x => y=x. Impossible.
                    # So y+x is in new_used_sums ONLY if it was in old_used_sums.
                    
                    # Therefore, adding x does NOT invalidate any y based on the sum x+y being in new_sums.
                    # It only invalidates y if x+y was ALREADY in used_sums.
                    
                    # Wait, is that right?
                    # If x+y is in used_sums, then adding x makes the sum x+y "occupied".
                    # When we later try to add y, we will compute y+x. Since x is in the set, we check if y+x is in used_sums.
                    # It IS in used_sums. So y is invalid.
                    # So yes, if x+y is in used_sums (before adding x), then y is invalid after adding x.
                    
                    if x + y in used_sums:
                        continue
                    filtered_remaining.append(y)
                
                if dfs(current_set + [x], new_used_sums, filtered_remaining, target_size):
                    return True
        
        return False

    # Try sizes from 20 down
    for total_size in range(20, 3, -1):
        k = total_size - 4
        if k < 0:
            continue
        # We need to select k candidates.
        # The DFS above takes `remaining_candidates` which shrinks.
        # Initial remaining is all candidates.
        # We don't explicitly limit the number of picks to k in the signature, 
        # but the pruning `current_size + len(remaining) < target_size` handles it.
        # However, we might pick more than k? No, we stop when current_size == target_size.
        
        # One issue: The order of candidates.
        # If we just use the sorted list, we might miss solutions if the "good" candidates are later.
        # But DFS explores all permutations effectively (by skipping or taking).
        
        if dfs(mandatory[:], used_sums, candidates, total_size):
            return best_set
            
    return best_set
# EVOLVE-BLOCK-END
