def _generate_icosahedron(n, scale=1.0):
    """Generate points on a Mackay icosahedron lattice."""
    # Golden ratio
    phi = (1 + np.sqrt(5)) / 2
    # Icosahedron vertices
    verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [-phi, 0, 1], [phi, 0, -1], [-phi, 0, -1]
    ]) * scale
    verts = verts / np.linalg.norm(verts[0]) * 1.0 # Normalize to unit radius roughly
    
    points = [np.zeros(3)] # Center
    
    # Shell 1 (12 vertices)
    for v in verts:
        points.append(v.copy())
        
    if n <= len(points):
        return np.array(points[:n])

    # Shell 2 (42 vertices) - Midpoints of edges and face centers? 
    # Actually Mackay icosahedron shell 2 has 42 atoms.
    # Let's just generate a larger set of points on the icosahedral lattice by scaling up?
    # Simpler: Generate points on a grid and project? No, let's use a simple lattice generation for larger n.
    # For now, if n > 13, we can add points randomly around the icosahedron or use FCC.
    # Let's just return the first n if we have enough, else pad with random.
    # Actually, let's generate a dense icosahedral cluster.
    # Shell 2 coordinates can be generated by rotating shell 1 and scaling?
    # It's complex. Let's rely on FCC for larger n.
    
    # Fallback: Add random points in a sphere
    rng = np.random.default_rng(42)
    while len(points) < n:
        p = rng.uniform(-2.5, 2.5, 3)
        if np.linalg.norm(p) < 3.0:
             points.append(p)
             
    return np.array(points[:n])

def _generate_fcc(n, scale=1.0):
    """Generate points on an FCC lattice."""
    points = []
    # Generate a cube of FCC points
    # FCC basis: (0,0,0), (0.5,0.5,0), (0.5,0,0.5), (0,0.5,0.5)
    basis = np.array([
        [0, 0, 0],
        [0.5, 0.5, 0],
        [0.5, 0, 0.5],
        [0, 0.5, 0.5]
    ]) * scale
    
    # Determine grid size
    side = int(np.ceil(n ** (1/3) * 2)) # Heuristic
    for i in range(-side, side+1):
        for j in range(-side, side+1):
            for k in range(-side, side+1):
                for b in basis:
                    p = np.array([i, j, k]) + b
                    if len(points) < n * 2: # Generate extra to allow centering/cropping
                        points.append(p)
    
    if not points:
         return np.array([[0,0,0]] * n)
         
    pts = np.array(points)
    # Center the cluster
    center = np.mean(pts, axis=0)
    pts -= center
    
    # Sort by distance from center to get a compact cluster
    dists = np.linalg.norm(pts, axis=1)
    idx = np.argsort(dists)
    pts = pts[idx]
    
    return pts[:n]

def _generate_hcp(n, scale=1.0):
    """Generate points on an HCP lattice."""
    points = []
    a = scale
    c = a * np.sqrt(8/3)
    # HCP basis in hexagonal coords? Easier to use Cartesian.
    # Layer 1: Triangular lattice
    # Layer 2: Offset
    
    side = int(np.ceil(n ** (1/3) * 2))
    for layer in range(-side, side+1):
        z = layer * c
        offset = (layer % 2) * 0.5 # Rough offset for HCP stacking
        for i in range(-side, side+1):
            for j in range(-side, side+1):
                # Triangular lattice in xy
                x = (i + offset) * a
                y = j * a * np.sqrt(3)
                p = np.array([x, y, z])
                points.append(p)
                # Second atom in unit cell? HCP has 2 atoms per primitive cell.
                # Let's just use the simple hexagonal lattice for now, it's close enough for a start.
                
    if not points:
         return np.array([[0,0,0]] * n)
         
    pts = np.array(points)
    center = np.mean(pts, axis=0)
    pts -= center
    
    dists = np.linalg.norm(pts, axis=1)
    idx = np.argsort(dists)
    pts = pts[idx]
    
    return pts[:n]

def construct(instance):
    size = instance["n"]
    potential = instance["potential"]
    kind = instance.get("kind")
    
    start_time = time.time()
    deadline = start_time + 280.0 # 20s safety margin
    
    candidates = []
    
    # 1. Icosahedral
    try:
        pts = _generate_icosahedron(size)
        candidates.append(pts)
    except Exception:
        pass
        
    # 2. FCC
    try:
        pts = _generate_fcc(size)
        candidates.append(pts)
    except Exception:
        pass
        
    # 3. HCP
    try:
        pts = _generate_hcp(size)
        candidates.append(pts)
    except Exception:
        pass
        
    # 4. Random compact
    try:
        rng = np.random.default_rng(size)
        radius = 0.8 * size ** (1/3)
        pts = []
        for _ in range(size * 10):
            p = rng.uniform(-radius, radius, 3)
            if len(pts) >= size: break
            if np.linalg.norm(p) <= radius:
                # Simple rejection sampling for min dist
                ok = True
                for q in pts:
                    if np.linalg.norm(p - q) < 0.7:
                        ok = False
                        break
                if ok:
                    pts.append(p)
        if len(pts) < size:
             # Pad with random if rejection failed
             while len(pts) < size:
                 pts.append(rng.uniform(-radius, radius, 3))
        candidates.append(np.array(pts))
    except Exception:
        pass

    best_energy = np.inf
    best_positions = None
    
    for i, pts in enumerate(candidates):
        if time.time() > deadline:
            break
            
        # Validate input
        if not np.all(np.isfinite(pts)):
            continue
        # Check min distance
        # For small n, O(n^2) is fine
        min_d = np.inf
        for a in range(size):
            for b in range(a+1, size):
                d = np.linalg.norm(pts[a] - pts[b])
                if d < min_d:
                    min_d = d
        if min_d < 0.35:
            continue
            
        try:
            energy, relaxed_pts = relax(pts, potential, kind)
            if energy < best_energy:
                best_energy = energy
                best_positions = relaxed_pts
        except Exception:
            pass
            
    if best_positions is None:
        # Fallback: Return the first valid candidate or random
        if candidates:
             return candidates[0]
        else:
             return np.zeros((size, 3))
             
    return best_positions
