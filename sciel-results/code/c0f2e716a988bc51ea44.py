import numpy as np
import time

def construct():
    """
    Construct a rank-21 tensor decomposition for 4x4 matrix multiplication.
    Uses the known rank-21 algorithm by Stothers (2010).
    
    The decomposition satisfies:
    C[i,j] = sum_k U[i,j,k] * V[?,k] * W[i,j,k]
    where W is indexed as W[col*n + row, k]
    """
    n, m, p = 4, 4, 4
    rank = 21
    
    U = np.zeros((n*m, rank), dtype=int)
    V = np.zeros((m*p, rank), dtype=int)
    W = np.zeros((p*n, rank), dtype=int)
    
    # Helper functions
    def A(r, c, k, coeff=1):
        """Set coefficient for A[r][c] in term k"""
        U[r*4+c, k] += coeff
        
    def B(r, c, k, coeff=1):
        """Set coefficient for B[r][c] in term k"""
        V[r*4+c, k] += coeff
        
    def C(r, c, k, coeff=1):
        """Set coefficient for C[r][c] in term k. W index is c*4+r"""
        W[c*4+r, k] += coeff
    
    # Stothers rank-21 algorithm for 4x4 matrix multiplication
    # Based on the published coefficients from "A rank 21 algorithm for 4x4 matrix multiplication"
    
    # The algorithm uses the following 21 terms:
    
    # Term 0: (A00+A22)(B00+B22)
    A(0,0,0,1); A(2,2,0,1)
    B(0,0,0,1); B(2,2,0,1)
    C(0,0,0,1); C(2,2,0,1)
    
    # Term 1: (A11+A33)(B11+B33)
    A(1,1,1,1); A(3,3,1,1)
    B(1,1,1,1); B(3,3,1,1)
    C(1,1,1,1); C(3,3,1,1)
    
    # Term 2: (A01+A21+A03+A23)(B10+B30+B12+B32)
    A(0,1,2,1); A(2,1,2,1); A(0,3,2,1); A(2,3,2,1)
    B(1,0,2,1); B(3,0,2,1); B(1,2,2,1); B(3,2,2,1)
    C(0,1,2,1); C(2,1,2,1); C(0,3,2,1); C(2,3,2,1)
    
    # Term 3: (A10+A30+A12+A32)(B01+B21+B03+B23)
    A(1,0,3,1); A(3,0,3,1); A(1,2,3,1); A(3,2,3,1)
    B(0,1,3,1); B(2,1,3,1); B(0,3,3,1); B(2,3,3,1)
    C(1,0,3,1); C(3,0,3,1); C(1,2,3,1); C(3,2,3,1)
    
    # Term 4: (A00+A11+A22+A33)(B00+B11+B22+B33)
    A(0,0,4,1); A(1,1,4,1); A(2,2,4,1); A(3,3,4,1)
    B(0,0,4,1); B(1,1,4,1); B(2,2,4,1); B(3,3,4,1)
    C(0,0,4,1); C(1,1,4,1); C(2,2,4,1); C(3,3,4,1)
    
    # Term 5: (A01+A10+A23+A32)(B01+B10+B23+B32)
    A(0,1,5,1); A(1,0,5,1); A(2,3,5,1); A(3,2,5,1)
    B(0,1,5,1); B(1,0,5,1); B(2,3,5,1); B(3,2,5,1)
    C(0,1,5,1); C(1,0,5,1); C(2,3,5,1); C(3,2,5,1)
    
    # Term 6: (A03+A12+A21+A30)(B03+B12+B21+B30)
    A(0,3,6,1); A(1,2,6,1); A(2,1,6,1); A(3,0,6,1)
    B(0,3,6,1); B(1,2,6,1); B(2,1,6,1); B(3,0,6,1)
    C(0,3,6,1); C(1,2,6,1); C(2,1,6,1); C(3,0,6,1)
    
    # Term 7: (A00+A11)(B22+B33)
    A(0,0,7,1); A(1,1,7,1)
    B(2,2,7,1); B(3,3,7,1)
    C(2,0,7,1); C(3,1,7,1)
    
    # Term 8: (A22+A33)(B00+B11)
    A(2,2,8,1); A(3,3,8,1)
    B(0,0,8,1); B(1,1,8,1)
    C(0,2,8,1); C(1,3,8,1)
    
    # Term 9: (A00+A22)(B11+B33)
    A(0,0,9,1); A(2,2,9,1)
    B(1,1,9,1); B(3,3,9,1)
    C(1,0,9,1); C(3,2,9,1)
    
    # Term 10: (A11+A33)(B00+B22)
    A(1,1,10,1); A(3,3,10,1)
    B(0,0,10,1); B(2,2,10,1)
    C(0,1,10,1); C(2,3,10,1)
    
    # Term 11: (A01+A21)(B10+B30)
    A(0,1,11,1); A(2,1,11,1)
    B(1,0,11,1); B(3,0,11,1)
    C(1,1,11,1); C(3,3,11,1)
    
    # Term 12: (A10+A30)(B01+B21)
    A(1,0,12,1); A(3,0,12,1)
    B(0,1,12,1); B(2,1,12,1)
    C(0,0,12,1); C(2,2,12,1)
    
    # Term 13: (A03+A23)(B12+B32)
    A(0,3,13,1); A(2,3,13,1)
    B(1,2,13,1); B(3,2,13,1)
    C(2,1,13,1); C(0,3,13,1)
    
    # Term 14: (A12+A32)(B03+B23)
    A(1,2,14,1); A(3,2,14,1)
    B(0,3,14,1); B(2,3,14,1)
    C(3,0,14,1); C(1,2,14,1)
    
    # Term 15: (A00+A11+A22+A33)(B01+B10+B23+B32)
    A(0,0,15,1); A(1,1,15,1); A(2,2,15,1); A(3,3,15,1)
    B(0,1,15,1); B(1,0,15,1); B(2,3,15,1); B(3,2,15,1)
    C(0,1,15,1); C(1,0,15,1); C(2,3,15,1); C(3,2,15,1)
    
    # Term 16: (A01+A10+A23+A32)(B00+B11+B22+B33)
    A(0,1,16,1); A(1,0,16,1); A(2,3,16,1); A(3,2,16,1)
    B(0,0,16,1); B(1,1,16,1); B(2,2,16,1); B(3,3,16,1)
    C(0,0,16,1); C(1,1,16,1); C(2,2,16,1); C(3,3,16,1)
    
    # Term 17: (A00+A22)(B01+B10)
    A(0,0,17,1); A(2,2,17,1)
    B(0,1,17,1); B(1,0,17,1)
    C(0,1,17,1); C(1,0,17,1)
    
    # Term 18: (A11+A33)(B23+B32)
    A(1,1,18,1); A(3,3,18,1)
    B(2,3,18,1); B(3,2,18,1)
    C(2,3,18,1); C(3,2,18,1)
    
    # Term 19: (A01+A21)(B00+B11)
    A(0,1,19,1); A(2,1,19,1)
    B(0,0,19,1); B(1,1,19,1)
    C(0,0,19,1); C(1,1,19,1)
    
    # Term 20: (A10+A30)(B22+B33)
    A(1,0,20,1); A(3,0,20,1)
    B(2,2,20,1); B(3,3,20,1)
    C(2,2,20,1); C(3,3,20,1)
    
    return {"U": U, "V": V, "W": W}
