    current_bound = best_max - 1 if best_sol else initial_bound - 10
    
    # We will try bounds in decreasing order.
    # To avoid too many slow calls, we can check every few units or use binary search.
    # Given the discrete nature, binary search on M is good.
    
    low = 30
    high = best_max if best_sol else initial_bound
    
    # We know high works (if best_sol exists).
