import time
import sys
from itertools import combinations

_DEADLINE = 145.0
_MARGIN = 5.0

def _check_sidon_and_cover(S):
    """
    Check if S is a Sidon set and covers differences 1..30.
    Returns True if valid.
    """
    if 0 not in S:
        return False
    n = len(S)
    if n > 32:
        return False
    diffs = set()
    for i in range(n):
        for j in range(i + 1, n):
            d = S[j] - S[i]
            if d in diffs:
                return False
            diffs.add(d)
    for d in range(1, 31):
        if d not in diffs:
            return False
    return True

def _solve_csp(max_elem, deadline):
    """
    Finds a Sidon set containing 0, covering diffs 1..30, with max element <= max_elem.
    Uses backtracking with forward checking and MRV-like heuristics.
    """
    # We don't know the size of the set. 
    # Min size is 9 (since C(8,2)=28 < 30).
    # Max size is 32.
    # We try sizes from 9 up to 15 (likely small enough).
    
    # State:
    # S: list of chosen elements, sorted. 0 is always first.
    # used_diffs: set of differences generated by S.
    # covered: set of differences from 1..30 that are in used_diffs.
    # need: set(range(1, 31)) - covered
    
    def backtrack(S, used_diffs, covered, need, depth, max_depth):
        if time.time() > deadline - _MARGIN:
            return None
        
        # Success condition
        if not need:
            return list(S)
        
        # If we've reached max_depth, we must have covered everything or fail
        if depth >= max_depth:
            return None
            
        # Heuristic: Pick the next element to add.
        # We want to cover 'need' differences.
        # Candidate x must be > S[-1] (if S is not just [0]) and <= max_elem.
        # Also x must not create duplicate differences.
        
        # Generate candidates.
        # A good candidate x creates differences with all s in S.
        # These differences must not be in used_diffs.
        # Ideally, some of these differences are in 'need'.
        
        candidates = []
        
        # We can restrict the search space significantly.
        # If we haven't placed many elements, the range is wide.
        # If we have placed many, the range is tight.
        
        # Simple candidate generation:
        # Try x such that x - s is in need for some s in S.
        # This ensures we make progress on covering 1..30.
        
        for s in S:
            for d in need:
                x = s + d
                if x > S[-1] if len(S) > 1 else x > 0:
                    if x <= max_elem:
                        # Check validity of x
                        valid = True
                        new_diffs = []
                        for s2 in S:
                            dd = abs(x - s2)
                            if dd in used_diffs:
                                valid = False
                                break
                            new_diffs.append(dd)
                        if valid:
                            # Score: how many new 'need' diffs does x cover?
                            new_covered = 0
                            for dd in new_diffs:
                                if dd in need:
                                    new_covered += 1
                            candidates.append((x, new_covered, new_diffs))
        
        # If no candidates from 'need', we might need to add an element that doesn't cover new need diffs immediately?
        # No, if we don't cover need diffs, we just waste a slot. 
        # However, sometimes we need to "bridge" gaps.
        # But given the density, usually covering need is the right move.
        # If candidates is empty, we might be stuck or need to allow non-need covering moves.
        # Let's add a fallback: try random x in (S[-1], max_elem] if candidates is empty and depth < max_depth - 2.
        # Actually, if candidates is empty, it means no x in range creates a needed diff without conflict.
        # This is a dead end for this branch if we strictly require progress.
        # But we can add x that creates NO new need diffs, as long as it doesn't conflict.
        # This is risky. Let's stick to progress first. If that fails, the backtracking will unwind.
        
        if not candidates:
            # Try to find ANY valid x, even if it doesn't cover need diffs.
            # This is expensive. Let's limit this.
            if depth < max_depth - 1:
                start = S[-1] + 1 if S else 1
                # Sample a few
                import random
                rng = random.Random(depth) # Pseudo-random based on depth for determinism in retries? 
                # Actually, let's just iterate a small window to keep it fast
                for x in range(start, min(start + 50, max_elem + 1)):
                    if x in S: continue
                    valid = True
                    new_diffs = []
                    for s2 in S:
                        dd = abs(x - s2)
                        if dd in used_diffs:
                            valid = False
                            break
                        new_diffs.append(dd)
                    if valid:
                        candidates.append((x, 0, new_diffs))
                if not candidates:
                    return None

        # Sort candidates by score (desc)
        candidates.sort(key=lambda t: t[1], reverse=True)
        
        # Deduplicate candidates (same x might appear multiple times)
        seen_x = set()
        unique_candidates = []
        for x, score, nds in candidates:
            if x not in seen_x:
                seen_x.add(x)
                unique_candidates.append((x, score, nds))
        
        for x, score, new_diffs in unique_candidates:
            new_S = S + [x]
            new_used = used_diffs.union(new_diffs)
            new_covered = covered.union([d for d in new_diffs if d in need])
            new_need = need - new_covered
            
            res = backtrack(new_S, new_used, new_covered, new_need, depth + 1, max_depth)
            if res is not None:
                return res
                
        return None

    # Try different set sizes
    # Lower bound for size: C(k,2) >= 30 => k >= 9
    # Upper bound: 32
    for k in range(9, 16): # Try up to 15, likely enough
        # We fix the size to k.
        # S starts with [0]. We need to pick k-1 more.
        # max_depth is k-1.
        res = backtrack([0], set(), set(), set(range(1, 31)), 1, k - 1)
        if res is not None:
            # Verify
            if _check_sidon_and_cover(res):
                return res
    return None

def construct():
    start = time.time()
    deadline = start + _DEADLINE
    
    # We want to minimize the largest element.
    # We know a solution exists. 
    # Let's estimate a good upper bound.
    # Random Sidon sets of size k have diameter roughly k^2.
    # For k=10, k^2=100. 
    # Let's try bounds from 100 down to 30.
    
    best_sol = None
    best_max = 10**6
    
    # First, get a valid solution to establish a baseline.
    # Try a loose bound first to ensure we have *something*.
    initial_bound = 200
    sol = _solve_csp(initial_bound, deadline)
    if sol:
        best_sol = sol
        best_max = max(sol)
        
    # Now, try to improve by lowering the bound.
    # We can binary search or linear search.
    # Linear search from best_max - 1 down to 30.
    
    # To save time, we can jump.
