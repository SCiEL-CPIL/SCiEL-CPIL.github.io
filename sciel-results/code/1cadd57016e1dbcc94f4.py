"""Spectral graph lifts: minimize spectral radius of signed prism graph."""
import time
import numpy as np

def sign_edges(graph, budget):
    """
    Assign signs (+1/-1) to edges of a prism graph to minimize the spectral radius
    of the signed adjacency matrix, while keeping the 2-lift connected and 3-regular.
    """
    start_time = time.time()
    DEADLINE = 80  # safety margin before 90s kill
    
    m = graph['n'] // 2
    edges = graph['edges']
    n_edges = len(edges)
    
    # Build edge index map: (u,v) -> index, with u < v
    edge_map = {}
    for i, (u, v) in enumerate(edges):
        edge_map[(min(u,v), max(u,v))] = i
    
    def get_edge_idx(u, v):
        return edge_map[(min(u,v), max(u,v))]
    
    # Identify the three types of edges:
    # 1. Bottom cycle: (i, i+1) for i in 0..m-1 (with wrap)
    # 2. Top cycle: (m+i, m+i+1) for i in 0..m-1 (with wrap)
    # 3. Matching: (i, m+i) for i in 0..m-1
    
    bottom_cycle_edges = []
    top_cycle_edges = []
    matching_edges = []
    
    for i in range(m):
        u, v = i, (i+1) % m
        bottom_cycle_edges.append(get_edge_idx(u, v))
        
        u, v = m+i, m+(i+1) % m
        top_cycle_edges.append(get_edge_idx(u, v))
        
        u, v = i, m+i
        matching_edges.append(get_edge_idx(u, v))
    
    def build_signed_adjacency(signs):
        """Build the signed adjacency matrix for the base graph."""
        A = np.zeros((2*m, 2*m))
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            A[u, v] = s
            A[v, u] = s
        return A
    
    def spectral_radius(signs):
        """Compute spectral radius of signed adjacency matrix."""
        A = build_signed_adjacency(signs)
        eigvals = np.linalg.eigvalsh(A)
        return np.max(np.abs(eigvals))
    
    def is_connected_lift(signs):
        """
        Check if the 2-lift is connected.
        The lift has 2*(2m) = 4m vertices.
        For a 2-lift defined by signs on a connected base graph,
        the lift is connected iff the product of signs around some cycle
        is -1 (i.e., the sign vector is not a "coboundary" / not all +1
        on every cycle). More precisely, the lift is disconnected iff all
        cycle products are +1.
        
        For a prism graph (two cycles + matching), the fundamental cycles are:
        - The bottom m-cycle
        - The top m-cycle  
        - Each "ladder" 4-cycle formed by matching edges and cycle edges
        - Actually, the cycle space has dimension E - V + 1 = (3m) - (2m) + 1 = m+1
        
        The lift is connected iff at least one cycle has product -1.
        More precisely: the 2-lift of a connected graph is connected iff
        the sign vector is not in the image of the boundary map (i.e., not
        a coboundary). For a graph with cycle space, the lift is disconnected
        iff all cycle products are +1.
        """
        # Compute product of signs around the bottom cycle
        prod_bottom = 1
        for idx in bottom_cycle_edges:
            prod_bottom *= signs[idx]
        
        prod_top = 1
        for idx in top_cycle_edges:
            prod_top *= signs[idx]
        
        # The lift is connected iff at least one of these products is -1
        # (or more generally, the sign vector is not a coboundary)
        # For the prism graph, the cycle space is generated by:
        # - bottom cycle, top cycle, and the m-1 independent "rungs"
        # Actually, let's just check: the 2-lift is connected iff there exists
        # a cycle with odd number of -1 edges (product = -1).
        
        # Simple check: if all cycle products are +1, lift is disconnected.
        # The fundamental cycles for the prism:
        # 1. Bottom cycle: product = prod_bottom
        # 2. Top cycle: product = prod_top
        # 3. For each i, the 4-cycle: (i, i+1, m+i+1, m+i) 
        #    This uses edges: bottom[i], top[i], matching[i+1], matching[i]
        
        if prod_bottom == -1 or prod_top == -1:
            return True
        
        # Check the "ladder" cycles
        for i in range(m):
            # Cycle: i -> (i+1)%m -> m+(i+1)%m -> m+i -> i
            prod = 1
            prod *= signs[bottom_cycle_edges[i]]
            prod *= signs[top_cycle_edges[(i+1) % m]]
            prod *= signs[matching_edges[(i+1) % m]]
            prod *= signs[matching_edges[i]]
            if prod == -1:
                return True
        
        return False
    
    # Strategy: 
    # 1. Try analytic solutions that enforce cycle product constraints
    # 2. Use local search / simulated annealing to minimize spectral radius
    
    best_signs = None
    best_radius = float('inf')
    
    # Phase 1: Try structured solutions
    # For even m: set all signs to +1 except one edge in each cycle to get product -1
    # Actually, for minimizing spectral radius of signed adjacency:
    # - All +1 gives spectral radius = 3 (for 3-regular)
    # - We want to make the spectrum as "flat" as possible, i.e., minimize max |eig|
    
    # Let's try: alternating signs on cycles
    # For the bottom cycle, alternate +1, -1, +1, -1, ...
    # This makes the bottom cycle contribute eigenvalues that are "spread out"
    
    # Try several initial patterns:
    patterns = []
    
    # Pattern 1: All +1
    patterns.append(np.ones(n_edges, dtype=int))
    
    # Pattern 2: Bottom cycle alternating, top +1, matching +1
    for m_val in [m]:
        p = np.ones(n_edges, dtype=int)
        for i, idx in enumerate(bottom_cycle_edges):
            p[idx] = 1 if i % 2 == 0 else -1
        patterns.append(p)
        
        # Pattern 3: Top cycle alternating
        p = np.ones(n_edges, dtype=int)
        for i, idx in enumerate(top_cycle_edges):
            p[idx] = 1 if i % 2 == 0 else -1
        patterns.append(p)
        
        # Pattern 4: Both cycles alternating
        p = np.ones(n_edges, dtype=int)
        for i, idx in enumerate(bottom_cycle_edges):
            p[idx] = 1 if i % 2 == 0 else -1
        for i, idx in enumerate(top_cycle_edges):
            p[idx] = 1 if i % 2 == 0 else -1
        patterns.append(p)
        
        # Pattern 5: Matching alternating
        p = np.ones(n_edges, dtype=int)
        for i, idx in enumerate(matching_edges):
            p[idx] = 1 if i % 2 == 0 else -1
        patterns.append(p)
        
        # Pattern 6: All -1
        patterns.append(-np.ones(n_edges, dtype=int))
    
    # Evaluate all patterns
    for p in patterns:
        if not is_connected_lift(p):
            continue
        r = spectral_radius(p)
        if r < best_radius:
            best_radius = r
            best_signs = p.copy()
    
    # Phase 2: Local search / hill climbing
    if best_signs is not None:
        current = best_signs.copy()
        current_r = best_radius
        no_improve_count = 0
        max_no_improve = 200
        
        while time.time() - start_time < DEADLINE and no_improve_count < max_no_improve:
            improved = False
            # Try flipping each edge
            for i in range(n_edges):
                trial = current.copy()
                trial[i] *= -1
                if not is_connected_lift(trial):
                    continue
                r = spectral_radius(trial)
                if r < current_r - 1e-10:
                    current = trial
                    current_r = r
                    improved = True
                    no_improve_count = 0
                    break  # restart scanning from beginning after improvement
            
            if not improved:
                no_improve_count += 1
    
    # Phase 3: Random restarts with local search if time permits
    rng = np.random.default_rng(3)
    while time.time() - start_time < DEADLINE:
        # Generate random sign vector
        random_signs = rng.choice([-1, 1], size=n_edges).astype(int)
        
        # Ensure connectivity
        if not is_connected_lift(random_signs):
            # Flip a random edge to try to fix connectivity
            random_signs[rng.integers(n_edges)] *= -1
            if not is_connected_lift(random_signs):
                continue
        
        r = spectral_radius(random_signs)
        if r < current_r - 1e-10:
            current = random_signs
            current_r = r
        
        # Local search from this point
        local_improved = True
        while local_improved and time.time() - start_time < DEADLINE:
            local_improved = False
            for i in range(n_edges):
                trial = current.copy()
                trial[i] *= -1
                if not is_connected_lift(trial):
                    continue
                r = spectral_radius(trial)
                if r < current_r - 1e-10:
                    current = trial
                    current_r = r
                    local_improved = True
                    break
        
        if current_r < best_radius:
            best_radius = current_r
            best_signs = current.copy()
    
    if best_signs is None:
        # Fallback: all +1 (should be valid for connected base)
        best_signs = np.ones(n_edges, dtype=int)
    
    return best_signs
