import numpy as np
import time

DIMENSIONS = [2, 3, 4]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    dim_u = n * m
    dim_v = m * p
    dim_w = p * n
    
    # Target tensor
    T = np.zeros((dim_u, dim_v, dim_w), dtype=int)
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u = i * m + j
                v = j * p + k
                w = k * n + i
                T[u, v, w] = 1

    def get_error(U, V, W):
        r = U.shape[1]
        T_recon = np.zeros((dim_u, dim_v, dim_w), dtype=int)
        for c in range(r):
            T_recon += U[:, c][:, None, None] * V[:, c][None, :, None] * W[:, c][None, None, :]
        return np.sum(np.abs(T_recon - T))

    def optimize(U, V, W, max_iters=50):
        r = U.shape[1]
        current_error = get_error(U, V, W)
        
        for _ in range(max_iters):
            if current_error == 0:
                break
                
            for c in range(r):
                # Update U column c
                # Residual R = T - sum_{c' != c} U_c' V_c' W_c'
                R = T.copy()
                for c_prime in range(r):
                    if c_prime != c:
                        R -= U[:, c_prime][:, None, None] * V[:, c_prime][None, :, None] * W[:, c_prime][None, None, :]
                
                # We want sum_u U_uc * (V_c \otimes W_c) to match R
                # A is (dim_v * dim_w, dim_u)
                # A[:, u] = flatten(V_c * W_c) ? No.
                # Term is U_uc * V_vc * W_wc.
                # For fixed c, V_c and W_c are fixed vectors.
                # The tensor generated by U_c is sum_u U_uc * (e_u \otimes V_c \otimes W_c).
                # Let M_c be the matrix of size dim_v x dim_w where M_c[v, w] = V_c[v] * W_c[w].
                # Then the tensor is sum_u U_uc * (e_u \otimes M_c).
                # Flattened, this is a linear combination of dim_u vectors of length dim_v*dim_w.
                # Vector for u is e_u flattened (length dim_u) outer M_c flattened?
                # Actually, the contribution to index (u, v, w) is U_uc * M_c[v, w].
                # So for a fixed u, the vector added to R is U_uc * M_c_flat.
                # Wait, the sum is over u.
                # R[u, v, w] = sum_u' U_{u' c} * (delta_{u u'} * V_{v c} * W_{w c})
                # R[u, v, w] = U_{u c} * V_{v c} * W_{w c}.
                # This means for each u, the equation is:
                # R[u, :, :] = U_{u c} * (V_c \otimes W_c).
                # This is not a single linear system for all U_uc at once if we treat it as LSQ on the whole tensor?
                # Yes it is.
                # Let b be R flattened (length dim_u * dim_v * dim_w).
                # Let A be a matrix of shape (dim_u * dim_v * dim_w, dim_u).
                # Column u of A is the tensor e_u \otimes (V_c \otimes W_c) flattened.
                # e_u is 1 at index u, 0 elsewhere.
                # So A[:, u] is 0 everywhere except in the block corresponding to index u, where it is (V_c \otimes W_c).flat.
                
                M_c = np.outer(V[:, c], W[:, c]) # dim_v x dim_w
                M_c_flat = M_c.flatten()
                
                A = np.zeros((dim_u * dim_v * dim_w, dim_u))
                for u in range(dim_u):
                    start_idx = u * dim_v * dim_w
                    end_idx = (u + 1) * dim_v * dim_w
                    A[start_idx:end_idx, u] = M_c_flat
                
                b = R.flatten()
                
                # Solve A x = b
                # x is U_c
                try:
                    U_c, _, _, _ = np.linalg.lstsq(A, b, rcond=None)
                    U_c = np.round(U_c).astype(int)
                    U[:, c] = U_c
                except:
                    pass

                # Update V column c
                R = T.copy()
                for c_prime in range(r):
                    if c_prime != c:
                        R -= U[:, c_prime][:, None, None] * V[:, c_prime][None, :, None] * W[:, c_prime][None, None, :]
                
                # Now we want sum_v V_vc * (U_c \otimes W_c) to match R.
                # R[u, v, w] = V_{v c} * U_{u c} * W_{w c}.
                # For fixed v, R[:, v, :] = V_{v c} * (U_c \otimes W_c).
                # A is (dim_u * dim_v * dim_w, dim_v).
                # Column v of A is the tensor (U_c \otimes e_v \otimes W_c) flattened.
                
                M_c_uw = np.outer(U[:, c], W[:, c]) # dim_u x dim_w
                M_c_uw_flat = M_c_uw.flatten()
                
                A = np.zeros((dim_u * dim_v * dim_w, dim_v))
                for v in range(dim_v):
                    # Block for v is at offset v * dim_u * dim_w?
                    # Indexing: T[u, v, w]. Flatten order: u, then v, then w?
                    # np.flatten default is C-order: last index changes fastest.
                    # So index is u * dim_v * dim_w + v * dim_w + w.
                    # The block for a specific v is not contiguous in C-order flatten if we group by v.
                    # We need to be careful with A construction.
                    
                    # Let's construct A differently.
                    # We want A[:, v] such that A @ V_c = R.flatten()
                    # A[i, v] is the coefficient of V_v in R_flat[i].
                    # R_flat[i] corresponds to (u, v', w).
                    # R[u, v', w] = V_{v' c} * U_{u c} * W_{w c}.
                    # So for a fixed target index (u, v', w), the value depends on V_{v' c}.
                    # The coefficient of V_{v c} in R[u, v', w] is:
                    # 1 if v' == v, else 0.
                    # And multiplied by U_{u c} * W_{w c}.
                    
                    # So A[idx(u, v', w), v] = (1 if v' == v else 0) * U_{u c} * W_{w c}.
                    
                    pass # We'll implement this loop directly

                # Let's just use the direct loop for A construction for V and W updates to be safe.
                # For U update, the block structure was contiguous for each u?
                # idx(u, v, w) = u * dim_v * dim_w + v * dim_w + w.
                # For fixed u, the indices are contiguous from u*dim_v*dim_w to (u+1)*dim_v*dim_w.
                # So the U update A construction was correct.
                
                # For V update:
                A = np.zeros((dim_u * dim_v * dim_w, dim_v))
                for v in range(dim_v):
                    for u in range(dim_u):
                        for w in range(dim_w):
                            idx = u * dim_v * dim_w + v * dim_w + w
                            # We are solving for V[:, c].
                            # R[idx] = V[v, c] * U[u, c] * W[w, c]
                            # So A[idx, v] = U[u, c] * W[w, c]
                            A[idx, v] = U[u, c] * W[w, c]
                
                b = R.flatten()
                try:
                    V_c, _, _, _ = np.linalg.lstsq(A, b, rcond=None)
                    V_c = np.round(V_c).astype(int)
                    V[:, c] = V_c
                except:
                    pass

                # Update W column c
                R = T.copy()
                for c_prime in range(r):
                    if c_prime != c:
                        R -= U[:, c_prime][:, None, None] * V[:, c_prime][None, :, None] * W[:, c_prime][None, None, :]
                
                A = np.zeros((dim_u * dim_v * dim_w, dim_w))
                for w in range(dim_w):
                    for u in range(dim_u):
                        for v in range(dim_v):
                            idx = u * dim_v * dim_w + v * dim_w + w
                            # R[idx] = W[w, c] * U[u, c] * V[v, c]
                            A[idx, w] = U[u, c] * V[v, c]
                
                b = R.flatten()
                try:
                    W_c, _, _, _ = np.linalg.lstsq(A, b, rcond=None)
                    W_c = np.round(W_c).astype(int)
                    W[:, c] = W_c
                except:
                    pass

            current_error = get_error(U, V, W)
            
        return U, V, W, current_error

    start_time = time.time()
    max_time = 30
    
    for r in range(18, 25):
        if time.time() - start_time > max_time:
            break
            
        for restart in range(20):
            if time.time() - start_time > max_time:
                break
                
            U = np.zeros((dim_u, r), dtype=int)
            V = np.zeros((dim_v, r), dtype=int)
            W = np.zeros((dim_w, r), dtype=int)
            
            # Initialize with random sparse pattern
            # Ensure some connectivity
            for c in range(r):
                # Pick random non-zeros
                U[np.random.choice(dim_u, size=3, replace=False), c] = np.random.choice([-1, 1], size=3)
                V[np.random.choice(dim_v, size=4, replace=False), c] = np.random.choice([-1, 1], size=4)
                W[np.random.choice(dim_w, size=3, replace=False), c] = np.random.choice([-1, 1], size=3)
            
            U, V, W, err = optimize(U, V, W, max_iters=20)
            
            if err == 0:
                return {
                    "U": U.tolist(),
                    "V": V.tolist(),
                    "W": W.tolist()
                }

    # Fallback
    rank = n * m * p
    U = np.zeros((dim_u, rank), dtype=int)
    V = np.zeros((dim_v, rank), dtype=int)
    W = np.zeros((dim_w, rank), dtype=int)
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u = i * m + j
                v = j * p + k
                w = k * n + i
                U[u, column] = 1
                V[v, column] = 1
                W[w, column] = 1
                column += 1
        
    return {
        "U": U.tolist(),
        "V": V.tolist(),
        "W": W.tolist()
    }
