import time
import random
from itertools import combinations

N = 17
MIN_DISTANCE = 6
DEADLINE_FRACTION = 0.95

def _hamming(a, b):
    return (a ^ b).bit_count()

def _is_compatible(candidate, selected):
    for s in selected:
        if _hamming(candidate, s) < MIN_DISTANCE:
            return False
    return True

def _generate_linear_code():
    """
    Generates the 256-word [17,8,6] linear code.
    Uses a known generator matrix for the shortened quadratic residue code.
    """
    # Generator matrix rows (17 bits each)
    # Based on standard tables for [17,8,6] code
    g_rows = [
        0b11111111111111111,
        0b11111111000000000,
        0b11110000111100000,
        0b11001111001111000,
        0b10110011110011000,
        0b01101100111100110,
        0b10011011011011100,
        0b01010110101101110
    ]
    
    # Verify generator matrix validity
    # Check min distance of the code generated by these rows
    # If invalid, return None
    words = []
    for mask in range(256):
        w = 0
        for i in range(8):
            if (mask >> i) & 1:
                w ^= g_rows[i]
        words.append(w)
        
    # Quick check: min distance
    # Just check a few pairs to ensure it's not garbage
    # Full check is expensive, but 256^2 is ~65k checks, which is fine.
    min_d = N
    for i in range(len(words)):
        for j in range(i+1, len(words)):
            d = _hamming(words[i], words[j])
            if d < min_d:
                min_d = d
            if min_d < MIN_DISTANCE:
                return None # Invalid matrix
    
    if min_d >= MIN_DISTANCE:
        return words
    return None

def _all_weight_words(weight):
    """Generate all N-bit words of given weight."""
    words = []
    for positions in combinations(range(N), weight):
        word = 0
        for p in positions:
            word |= (1 << p)
        words.append(word)
    return words

