    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None

        n = len(pts)
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])

        # Vectorized LP setup
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = np.zeros((12 * n, 3))
        b_ub = np.zeros(12 * n)

        for i in range(6):
            nx, ny = normals[i]
            idx = slice(i * 2 * n, (i + 1) * 2 * n)
            # -nx*x - ny*y - D <= -(px*nx + py*ny)
            A_ub[idx:idx+n, 0] = -nx
            A_ub[idx:idx+n, 1] = -ny
            A_ub[idx:idx+n, 2] = -1.0
            b_ub[idx:idx+n] = -(pts[:n, 0] * nx + pts[:n, 1] * ny)
            # nx*x + ny*y - D <= px*nx + py*ny
            A_ub[idx+n:idx+2*n, 0] = nx
            A_ub[idx+n:idx+2*n, 1] = ny
            A_ub[idx+n:idx+2*n, 2] = -1.0
            b_ub[idx+n:idx+2*n] = pts[:n, 0] * nx + pts[:n, 1] * ny

        bounds = [(None, None), (None, None), (0, None)]

        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def exact_S_vectorized(pts, cx, cy, beta):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        max_proj = np.max(np.abs(projs))
        S = (max_proj + APOTHEM) / APOTHEM
        return S

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None

