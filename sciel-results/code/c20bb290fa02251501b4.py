    # Let's start M from a reasonable lower bound.
    # For N=9, min diameter is roughly 9^2 - 9 = 72? 
    # Actually, known small Sidon sets:
    # Size 9, diameter ~ 100-150.
    # Let's start M from 50 and go up.
    
    def solve(M):
        """
        Returns a valid Sidon set in [0, M] containing 0 and covering 1..30, or None.
        """
        # State: current set, current diffs
        # We use a recursive backtracking function.
        
        # To speed up, we sort candidates.
        # We will try to add elements in increasing order to keep the set compact?
        # Or try elements that cover the most missing diffs?
        
        # Heuristic: Try adding x that covers the most missing diffs.
        # But we must ensure Sidon property.
        
        # Let's use a simple DFS with pruning.
        # To avoid exponential explosion, we limit the depth or use strong pruning.
        
        # Precompute all possible pairs (i, j) with i < j in [0, M]? No, too many.
        
        def backtrack(S, D):
            # S: list of elements
            # D: set of differences
            
            # Check success
            if all(d in D for d in target_diffs):
                return list(S)
            
            # Pruning: Not enough capacity to cover remaining diffs
            missing = [d for d in target_diffs if d not in D]
            if not missing:
                return list(S)
            
            # Max number of elements allowed is 32
            if len(S) >= 32:
                return None
            
            # Max possible new diffs if we add k elements
            # We can add at most 32 - len(S) elements.
            # Each new element x forms |S| diffs with existing, and (k-1) with other new ones.
            # This is an upper bound on new diffs.
            k_max = 32 - len(S)
            # The diffs formed by new elements among themselves: k_max*(k_max-1)/2
            # The diffs formed with existing: k_max * len(S)
            # Total potential new diffs: k_max * len(S) + k_max*(k_max-1)//2
            potential_new = k_max * len(S) + k_max * (k_max - 1) // 2
            
            if len(missing) > potential_new:
                return None
            
