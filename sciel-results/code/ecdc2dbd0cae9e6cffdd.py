"""Photonic crystal unit cell design for large TM band gap between bands 4 and 5."""
import numpy as np
import time
import random

# EVOLVE-BLOCK-START
def design(problem):
    """Design a 32x32 symmetric unit cell maximizing TM band gap between bands 4 and 5."""
    size = problem["pixels"]
    eps_low = problem.get("eps_low", 1)
    eps_high = problem.get("eps_high", 12)
    
    t_start = time.time()
    DEADLINE = 218.0  # safety margin before 230s kill
    
    def time_ok():
        return time.time() - t_start < DEADLINE
        
    # Plane wave setup: 17x17 = 289 plane waves
    n_pw = 17
    half = n_pw // 2
    G_vals = np.arange(-half, half + 1)
    Gx_grid, Gy_grid = np.meshgrid(G_vals, G_vals, indexing='ij')
    Gx = Gx_grid.ravel()
    Gy = Gy_grid.ravel()
    n_pw_total = n_pw * n_pw  # 289
    
    # K-points in irreducible BZ (30 points as specified)
    pi = np.pi
    k_points = []
    for i in range(10):
        t = i / 9.0
        k_points.append((t * pi, 0.0))
    for i in range(10):
        t = i / 9.0
        k_points.append((pi, t * pi))
    for i in range(10):
        t = i / 9.0
        k_points.append((pi * (1 - t), pi * (1 - t)))
    k_points = np.array(k_points)
    
    # Precompute (k+G)^2
    k2_all = np.zeros((len(k_points), n_pw_total))
    for i, (kx, ky) in enumerate(k_points):
        k2_all[i] = (kx + Gx) ** 2 + (ky + Gy) ** 2
        
    # Precompute difference indices for Fourier coupling
    diff_idx = np.zeros((n_pw_total, n_pw_total), dtype=int)
    for i in range(n_pw_total):
        for j in range(n_pw_total):
            dGx = Gx[i] - Gx[j]
            dGy = Gy[i] - Gy[j]
            idx_x = int(dGx) + half
            idx_y = int(dGy) + half
            if 0 <= idx_x < n_pw and 0 <= idx_y < n_pw:
                diff_idx[i, j] = idx_x * n_pw + idx_y
            else:
                diff_idx[i, j] = -1
    valid_mask = diff_idx >= 0
    valid_rows, valid_cols = np.where(valid_mask)
    
    def get_fourier_coeffs(cell):
        """Compute Fourier coefficients of 1/eps using FFT."""
        eps_map = np.where(cell == 1, eps_high, eps_low)
        inv_eps = 1.0 / eps_map
        fft_2d = np.fft.fft2(inv_eps)
        coeffs = np.zeros(n_pw_total, dtype=complex)
        for idx in range(n_pw_total):
            gx = int(Gx[idx])
            gy = int(Gy[idx])
            fft_ix = gx % size
            fft_iy = gy % size
            coeffs[idx] = fft_2d[fft_ix, fft_iy] / (size * size)
        return coeffs
        
    def compute_band_ratio(coeffs):
        """Compute gap-midgap ratio."""
        max_band4 = -np.inf
        min_band5 = np.inf
        
        for k_idx in range(len(k_points)):
            k2 = k2_all[k_idx]
            # Build H matrix efficiently
            H_vals = k2[valid_rows] * coeffs[diff_idx[valid_rows, valid_cols]]
            H = np.zeros((n_pw_total, n_pw_total), dtype=complex)
            H[valid_rows, valid_cols] = H_vals
            H = (H + H.conj().T) / 2.0
            eigvals = np.linalg.eigvalsh(H)
            eigvals = np.sort(eigvals)
            if len(eigvals) >= 5:
                if eigvals[3] > max_band4:
                    max_band4 = eigvals[3]
                if eigvals[4] < min_band5:
                    min_band5 = eigvals[4]
        
        gap = min_band5 - max_band4
        midgap = (min_band5 + max_band4) / 2.0
        if midgap > 1e-10:
            return gap / midgap
        return 0.0

    def enforce_symmetry(cell):
        """Enforce 4-fold rotational + reflection symmetry (D4)."""
        cell = np.array(cell, dtype=int)
        # Generate all 8 D4 transforms
        transforms = [
            cell,
            np.rot90(cell, 1),
            np.rot90(cell, 2),
            np.rot90(cell, 3),
            cell[:, ::-1].copy(),
            cell[::-1, :].copy(),
            cell.T.copy(),
            np.rot90(cell.T.copy(), 1)
        ]
        # Average and threshold
        avg = np.sum(transforms, axis=0)
        result = (avg >= 4).astype(int)
        return result

    def generate_voronoi_cell(seeds, n_cells=4):
        """
        Generate a cell using Voronoi tessellation with symmetry constraints.
        seeds: list of (x, y) coordinates for one fundamental domain quadrant
        The full set of seeds is generated by applying D4 symmetry.
        Dielectric regions are assigned to Voronoi cells with even indices.
        """
        # Generate full seed set from fundamental domain
        all_seeds = []
        for sx, sy in seeds:
            # D4 orbit: (sx, sy), (-sx, sy), (sx, -sy), (-sx, -sy)
            # and reflections/rotations
            orbit = [
                (sx, sy), (-sx, sy), (sx, -sy), (-sx, -sy),
                (sy, sx), (-sy, sx), (sy, -sx), (-sy, -sx)
            ]
            # Remove duplicates
            unique = []
            for pt in orbit:
                # Round to avoid floating point issues
                pt_rounded = (round(pt[0], 10), round(pt[1], 10))
                if pt_rounded not in unique:
                    unique.append(pt_rounded)
            all_seeds.extend(unique)
        
        # Remove duplicates in all_seeds
        unique_seeds = []
        for pt in all_seeds:
            pt_rounded = (round(pt[0], 10), round(pt[1], 10))
            if pt_rounded not in unique_seeds:
                unique_seeds.append(pt_rounded)
        
        if len(unique_seeds) == 0:
            # Fallback: single seed at center
            unique_seeds = [(0.0, 0.0)]
        
        # Create coordinate grid
        coords = (np.arange(size) + 0.5) / size - 0.5
        X, Y = np.meshgrid(coords, coords, indexing='xy')
        
        # Assign each pixel to nearest seed
        cell = np.zeros((size, size), dtype=int)
        for i in range(size):
            for j in range(size):
                min_dist = float('inf')
                nearest_seed_idx = 0
                for idx, (sx, sy) in enumerate(unique_seeds):
                    dist = (X[i, j] - sx) ** 2 + (Y[i, j] - sy) ** 2
                    if dist < min_dist:
                        min_dist = dist
                        nearest_seed_idx = idx
                # Alternate dielectric/air based on seed index
                if nearest_seed_idx % 2 == 0:
                    cell[i, j] = 1
        
        return enforce_symmetry(cell)

    def generate_superellipses(n_exp, a_size, offset):
        """Generate a cell with 4 superellipses at (+/-offset, +/-offset)."""
        cell = np.zeros((size, size), dtype=int)
        coords = (np.arange(size) + 0.5) / size - 0.5
        X, Y = np.meshgrid(coords, coords, indexing='xy')
        
        centers = [(offset, offset), (-offset, offset), (offset, -offset), (-offset, -offset)]
        
        for cx, cy in centers:
            dx = X - cx
            dy = Y - cy
            val = np.abs(dx / a_size) ** n_exp + np.abs(dy / a_size) ** n_exp
            cell[val <= 1.0] = 1
            
        return enforce_symmetry(cell)

    # Phase 1: Global Search over diverse design families
    best_ratio = -np.inf
    best_cell = None
    best_family = None
    
    # Family 1: Superellipses (proven approach)
    n_values = [1.5, 2.0, 2.5, 3.0, 4.0, 6.0, 10.0]
    a_values = [0.08, 0.10, 0.12, 0.14]
    off_values = [0.20, 0.22, 0.25, 0.28]
    
    for n in n_values:
        for a in a_values:
            for off in off_values:
                if not time_ok():
                    break
                cell = generate_superellipses(n, a, off)
                coeffs = get_fourier_coeffs(cell)
                ratio = compute_band_ratio(coeffs)
                if ratio > best_ratio:
                    best_ratio = ratio
                    best_cell = cell.copy()
                    best_family = 'superellipse'
                if not time_ok():
                    break
            if not time_ok():
                break
        if not time_ok():
            break
    
    # Family 2: Voronoi tessellation (new structural approach)
    # Search over different seed configurations
    voronoi_configs = [
        # Single seed at center
        [(0.0, 0.0)],
        # Two seeds on x-axis
        [(0.15, 0.0), (-0.15, 0.0)],
        # Two seeds on y-axis
        [(0.0, 0.15), (0.0, -0.15)],
        # Four seeds at corners of a square
        [(0.15, 0.15), (-0.15, 0.15), (0.15, -0.15), (-0.15, -0.15)],
        # Four seeds at midpoints
        [(0.2, 0.0), (-0.2, 0.0), (0.0, 0.2), (0.0, -0.2)],
        # Six seeds: hexagonal-like
        [(0.18, 0.0), (-0.18, 0.0), (0.0, 0.18), (0.0, -0.18), 
         (0.13, 0.13), (-0.13, -0.13)],
        # Eight seeds: denser
        [(0.2, 0.0), (-0.2, 0.0), (0.0, 0.2), (0.0, -0.2),
         (0.14, 0.14), (-0.14, 0.14), (0.14, -0.14), (-0.14, -0.14)],
    ]
    
    for seeds in voronoi_configs:
        if not time_ok():
            break
        cell = generate_voronoi_cell(seeds)
        coeffs = get_fourier_coeffs(cell)
        ratio = compute_band_ratio(coeffs)
        if ratio > best_ratio:
            best_ratio = ratio
            best_cell = cell.copy()
            best_family = 'voronoi'
    
    if best_cell is None:
        # Fallback
        best_cell = generate_superellipses(2.0, 0.12, 0.25)
        best_ratio = compute_band_ratio(get_fourier_coeffs(best_cell))
        best_family = 'superellipse'

    # Phase 2: Local Optimization using pixel flipping with simulated annealing
    current_cell = best_cell.copy()
    current_ratio = best_ratio
    
    search_start = time.time()
    search_time_limit = 140.0  # Leave time for final refinement
    
    # Simulated annealing parameters
    T_start = 0.05
    T_end = 0.001
    no_improve_count = 0
    max_no_improve = 100
    
    # Independent pixels in fundamental domain (16x16 quadrant)
    indep_pixels = [(i, j) for i in range(16) for j in range(16)]
    
    iteration = 0
    while time.time() - search_start < search_time_limit and no_improve_count < max_no_improve and time_ok():
        iteration += 1
        # Annealing schedule
        progress = min(1.0, iteration / 500.0)
        T = T_start * (T_end / T_start) ** progress
        
        # Pick a random pixel to flip
        i, j = random.choice(indep_pixels)
        
        old_val = current_cell[i, j]
        new_cell = current_cell.copy()
        new_cell[i, j] = 1 - old_val
        new_cell = enforce_symmetry(new_cell)
        
        coeffs = get_fourier_coeffs(new_cell)
        new_ratio = compute_band_ratio(coeffs)
        
        delta = new_ratio - current_ratio
        
        # Accept if better, or with probability exp(delta/T) if worse
        if delta > 0 or (T > 0 and random.random() < np.exp(delta / T)):
            current_cell = new_cell
            current_ratio = new_ratio
            no_improve_count = 0
        else:
            no_improve_count += 1
    
    # Phase 3: Final greedy refinement
    if time_ok() and (DEADLINE - (time.time() - t_start)) > 30:
        # Try flipping each independent pixel and keep if it improves
        improved = True
        while improved and time_ok():
            improved = False
            for (i, j) in indep_pixels:
                if not time_ok():
                    break
                    
                old_val = current_cell[i, j]
                new_cell = current_cell.copy()
                new_cell[i, j] = 1 - old_val
                new_cell = enforce_symmetry(new_cell)
                
                coeffs = get_fourier_coeffs(new_cell)
                new_ratio = compute_band_ratio(coeffs)
                
                if new_ratio > current_ratio + 1e-8:
                    current_cell = new_cell
                    current_ratio = new_ratio
                    improved = True

    # Final verification
    final_coeffs = get_fourier_coeffs(current_cell)
    final_ratio = compute_band_ratio(final_coeffs)
    
    if final_ratio < best_ratio - 0.01:
        current_cell = best_cell
    else:
        best_ratio = final_ratio
        
    return current_cell.tolist()
# EVOLVE-BLOCK-END
