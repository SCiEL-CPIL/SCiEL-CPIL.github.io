"""Structural change: group-theoretic Cayley-graph search.

Instead of voltage lifts over a fixed base graph (Petersen / K3,3 / cube),
we search directly over 3-generator permutation groups on n vertices.  The
Cayley graph of a group generated by three fixed-point-free involutions is
3-regular, and its girth equals the length of the shortest non-trivial word
in the generators that evaluates to the identity.  This removes the
base-graph bottleneck of voltage lifts and lets us sweep n from the Moore
bound upward, including odd n.

Girth is verified two ways:
  1. A breadth-first word search over the generators (fast pre-filter).
  2. A full non-backtracking BFS in the Cayley graph (exact certificate).
"""
import time as _time
import random as _random
from collections import deque


def _moore_bound(k, g):
    if k == 3:
        if g % 2 == 0:
            return 2 * ((2 ** (g // 2)) - 1)
        else:
            return 2 * ((2 ** (g // 2)) - 1) + 2 * (2 ** (g // 2 - 1))
    # generic Moore bound
    h = g // 2
    return 1 + k * sum(k ** i for i in range(h))


def _random_fixedpointfree_involution(rng, n):
    """A random fixed-point-free involution (perfect matching) on n.

    Uses the transposition trick: pick a random permutation p, then
    sigma(i) = p^{-1}(p(i) + 1)  is an involution with no fixed points.
    """
    perm = list(range(n))
    rng.shuffle(perm)
    inv = [0] * n
    for i, v in enumerate(perm):
        inv[v] = i
    sigma = [0] * n
    for i in range(n):
        sigma[i] = inv[(perm[i] + 1) % n]
    return sigma


def _build_cayley(g1, g2, g3, n):
    """Return (adj, edges) for the Cayley graph of <g1,g2,g3> on n vertices.

    adj is a list of length n; adj[v] = (g1[v], g2[v], g3[v]).
    Returns None if any generator is not an involution or has a fixed point.
    """
    gens = (g1, g2, g3)
    for g in gens:
        for i in range(n):
            if g[g[i]] != i:      # not an involution
                return None
            if g[i] == i:         # fixed point -> loop
                return None
    adj = [None] * n
    for i in range(n):
        adj[i] = (g1[i], g2[i], g3[i])
    edges = []
    for i in range(n):
        for j in range(3):
            v = adj[i][j]
            if i < v:
                edges.append((i, v))
    return adj, edges


def _girth_word_search(adj, g, n):
    """BFS over words in the generators from the identity.

    Returns True iff no non-trivial word of length < g evaluates to identity.
    """
    depth = g - 1
    # frontier: set of (vertex, prev_vertex)
    visited = set()
    frontier = [(0, -1)]
    visited.add((0, -1))
    for d in range(depth):
        if not frontier:
            return True
        nxt = []
        for (v, prev) in frontier:
            for j in range(3):
                w = adj[v][j]
                if w == prev:
                    continue
                if w == 0 and d + 1 >= 3:
                    return False
                state = (w, v)
                if state not in visited:
                    visited.add(state)
                    nxt.append(state)
        frontier = nxt
    return True


def _girth_bfs(adj, g, n):
    """Exact non-backtracking BFS from every vertex.  True iff girth >= g."""
    for start in range(n):
        dist = {}
        dq = deque()
        dq.append((start, -1))
        dist[(start, -1)] = 0
        while dq:
            v, prev = dq.popleft()
            d = dist[(v, prev)]
            if d >= g - 1:
                continue
            for w in adj[v]:
                if w == prev:
                    continue
                if w == start and d + 1 >= 3:
                    return False
                state = (w, v)
                if state not in dist:
                    dist[state] = d + 1
                    dq.append(state)
    return True


def _cayley_search(k, g, deadline, n_start=None, n_end=None):
    """Search over 3-generator permutation groups for a girth-g Cayley graph.

    Returns (n, edges) for the smallest valid n found, or None.
    """
    if k != 3:
        return None
    mb = _moore_bound(k, g)
    if n_start is None:
        n_start = mb
    if n_end is None:
        n_end = mb + 60

    best = None
    # Try n in increasing order; for each n, try a number of random generator
    # triples.  Smaller n is preferred, so we stop as soon as we find a valid
    # graph at the current n (it is the minimum for this sweep).
    for n in range(n_start, n_end + 1):
        if _time.time() > deadline - 20:
            break
        # budget per n: more attempts at smaller n
        attempts = 40 if n <= mb + 10 else 20
        for attempt in range(attempts):
            if _time.time() > deadline - 15:
                break
            rng = _random.Random(hash((n, attempt, g)) & 0xFFFFFFFF)
            g1 = _random_fixedpointfree_involution(rng, n)
            g2 = _random_fixedpointfree_involution(rng, n)
            g3 = _random_fixedpointfree_involution(rng, n)
            built = _build_cayley(g1, g2, g3, n)
            if built is None:
                continue
            adj, edges = built
            # fast word-search pre-filter
            if not _girth_word_search(adj, g, n):
                continue
            # exact certificate
            if _girth_bfs(adj, g, n):
                return n, edges
    return best


def _voltage_lift_fallback(k, g, deadline):
    """Deterministic voltage-lift fallback (Petersen / K3,3) in case the
    Cayley search finds nothing before the deadline."""
    if k != 3:
        return None
    from collections import deque as _dq

    def verify(adj, n, g):
        for start in range(n):
            dist = {}
            dq = _dq()
            dq.append((start, -1))
            dist[(start, -1)] = 0
            while dq:
                v, prev = dq.popleft()
                d = dist[(v, prev)]
                if d >= g - 1:
                    continue
                for w in adj[v]:
                    if w == prev:
                        continue
                    if w == start and d + 1 >= 3:
                        return False
                    st = (w, v)
                    if st not in dist:
                        dist[st] = d + 1
                        dq.append(st)
        return True

    def petersen():
        return [(0,1),(1,2),(2,3),(3,4),(4,0),
                (5,7),(7,9),(9,6),(6,8),(8,5),
                (0,5),(1,6),(2,7),(3,8),(4,9)]

    def k33():
        return [(0,3),(0,4),(0,5),(1,3),(1,4),(1,5),(2,3),(2,4),(2,5)]

    def build(base_edges, m, shifts):
        nb = max(max(u for u,v in base_edges), max(v for u,v in base_edges)) + 1
        n = nb * m
        adj = [set() for _ in range(n)]
        edges = []
        for idx, (u, v) in enumerate(base_edges):
            vol = shifts[idx] % m
            for i in range(m):
                a = u * m + i
                b = v * m + (i + vol) % m
                if a == b or b in adj[a]:
                    return None
                adj[a].add(b); adj[b].add(a); edges.append((a, b))
        for i in range(n):
            if len(adj[i]) != 3:
                return None
        return n, edges

    for base, nb in ((petersen(), 10), (k33(), 6)):
        ec = len(base)
        m_min = max(1, (_moore_bound(3, g) + nb - 1) // nb)
        for m in range(m_min, m_min + 120):
            if _time.time() > deadline - 10:
                return None
            for attempt in range(8):
                if _time.time() > deadline - 5:
                    break
                rng = _random.Random(hash((nb, m, attempt)) & 0xFFFFFFFF)
                shifts = [rng.randint(1, m - 1) for _ in range(ec)]
                res = build(base, m, shifts)
                if res is None:
                    continue
                n, edges = res
                adjl = [sorted(s) for s in [set() for _ in range(n)]]
                adjl = [list(set()) for _ in range(n)]
                adjl = [set() for _ in range(n)]
                for u, v in edges:
                    adjl[u].add(v); adjl[v].add(u)
                adjl = [list(s) for s in adjl]
                if verify(adjl, n, g):
                    return n, edges
    return None


def construct(k, g):
    start_time = _time.time()
    deadline = start_time + 130  # safety margin before 150s limit

    if k == 3:
        result = _cayley_search(k, g, deadline)
        if result is not None:
            return result
        result = _voltage_lift_fallback(k, g, deadline)
        if result is not None:
            return result

    # Generic fallback: random configuration-model 3-regular graph.
    if k == 3:
        mb = _moore_bound(3, g)
        for n_try in range(mb, mb + 40, 2):
            if _time.time() > deadline - 10:
                break
            for attempt in range(30):
                if _time.time() > deadline - 5:
                    break
                rng = _random.Random(hash((n_try, attempt)) & 0xFFFFFFFF)
                stubs = []
                for i in range(n_try):
                    stubs.extend([i, i, i])
                rng.shuffle(stubs)
                adj = [set() for _ in range(n_try)]
                valid = True
                for i in range(0, len(stubs), 2):
                    u, v = stubs[i], stubs[i + 1]
                    if u == v or v in adj[u]:
                        valid = False
                        break
                    adj[u].add(v); adj[v].add(u)
                if not valid:
                    continue
                if not all(len(adj[i]) == 3 for i in range(n_try)):
                    continue
                adjl = [list(s) for s in adj]
                if _girth_bfs(adjl, g, n_try):
                    edges = []
                    for u in range(n_try):
                        for v in adj[u]:
                            if u < v:
                                edges.append((u, v))
                    return n_try, edges

    # Last resort: return an empty-ish but degree-0 placeholder is invalid;
    # return a trivial cycle of length g (2-regular) is not 3-regular.
    # As a final safe 3-regular graph, use a disjoint union of K4's if n allows,
    # otherwise a single K4 padded.  This is only reached on total failure.
    n = 4 * max(1, (g // 2) + 1)
    edges = []
    for base in range(0, n, 4):
        for a in range(4):
            for b in range(a + 1, 4):
                edges.append((base + a, base + b))
    return n, edges
