def _verify(U, V, W, n, m, p, tol=1e-9):
    """Check if the decomposition exactly reproduces the matrix multiplication tensor."""
    rank = len(U[0])
    U_np = np.array(U, dtype=np.float64)
    V_np = np.array(V, dtype=np.float64)
    W_np = np.array(W, dtype=np.float64)
    
    # Build the full tensor T
    T = np.zeros((n*m, m*p, p*n), dtype=np.float64)
    for c in range(rank):
        T += np.einsum('i,j,k->ijk', U_np[:, c], V_np[:, c], W_np[:, c])
    
    # Check the non-zero entries
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u = i * m + j
                v = j * p + k
                w = k * n + i
                if abs(T[u, v, w] - 1.0) > tol:
                    return False
    
    # Check that entries that should be zero are actually zero
    T_expected = np.zeros((n*m, m*p, p*n), dtype=np.float64)
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u = i * m + j
                v = j * p + k
                w = k * n + i
                T_expected[u, v, w] = 1.0
    
    if not np.allclose(T, T_expected, atol=tol):
        return False
    
    return True

def _schoolbook(n, m, p):
    """Fallback schoolbook decomposition."""
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i*m+j][col] = 1
                V[j*p+k][col] = 1
                W[k*n+i][col] = 1
                col += 1
    return {"U": U, "V": V, "W": W}

