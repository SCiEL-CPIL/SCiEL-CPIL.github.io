    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        angles = beta + math.pi / 6.0 + np.arange(6) * math.pi / 3.0
        normals = np.column_stack([np.cos(angles), np.sin(angles)])
        
        n_pts = len(pts)
        c_obj = np.array([0.0, 0.0, 1.0])
        
        # Fully vectorized LP constraint construction
        # proj[k, i] = pts[i] . normals[k]
        proj = pts @ normals.T  # (n_pts, 6)
        
        # A_ub rows: for each (k, i): [-nx_k, -ny_k, -1] <= -proj[i,k]  AND  [nx_k, ny_k, -1] <= proj[i,k]
        # Stack: first all constraint-1 rows, then all constraint-2 rows
        # Constraint 1: -nx*cx - ny*cy - D <= -proj  =>  [-nx, -ny, -1] @ x <= -proj
        # Constraint 2:  nx*cx + ny*cy - D <= proj   =>  [nx,  ny,  -1] @ x <= proj
        
        # Build A_ub as (12*n_pts, 3)
        # For constraint 1 (rows 0..6*n_pts-1): A = [-nx_k, -ny_k, -1], b = -proj[i,k]
        # For constraint 2 (rows 6*n_pts..12*n_pts-1): A = [nx_k, ny_k, -1], b = proj[i,k]
        
        # normals shape (6,2), proj shape (n_pts, 6)
        # We need for each (k,i): nx_k, ny_k, proj[i,k]
        # Reshape: for constraint 1, row index = k*n_pts + i
        # nx for row (k,i) = normals[k,0], ny = normals[k,1], b = -proj[i,k]
        
        # Use broadcasting: normals[:, 0:1] is (6,1), pts proj is (n_pts,6)
        # A1 shape: (6*n_pts, 3)
        # Row k*n_pts+i: [-nx_k, -ny_k, -1]
        A1 = np.zeros((6 * n_pts, 3))
        b1 = np.zeros(6 * n_pts)
        for k in range(6):
            A1[k*n_pts:(k+1)*n_pts, 0] = -normals[k, 0]
            A1[k*n_pts:(k+1)*n_pts, 1] = -normals[k, 1]
            A1[k*n_pts:(k+1)*n_pts, 2] = -1.0
            b1[k*n_pts:(k+1)*n_pts] = -proj[:, k]
        
        A2 = np.zeros((6 * n_pts, 3))
        b2 = np.zeros(6 * n_pts)
        for k in range(6):
            A2[k*n_pts:(k+1)*n_pts, 0] = normals[k, 0]
            A2[k*n_pts:(k+1)*n_pts, 1] = normals[k, 1]
            A2[k*n_pts:(k+1)*n_pts, 2] = -1.0
            b2[k*n_pts:(k+1)*n_pts] = proj[:, k]
        
        A_ub = np.vstack([A1, A2])
        b_ub = np.concatenate([b1, b2])
        
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def exact_S(pts, beta, cx, cy):
        """Compute exact S value for given configuration."""
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = np.abs(pts_centered @ normals.T)
        max_proj = float(np.max(projs))
        S = (max_proj + APOTHEM) / APOTHEM
        return S

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])
        
        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf')
        
        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -50, 50)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S

    def smooth_S_with_beta(pts, beta, cx, cy, temperature=0.1):
        """Smooth surrogate that also handles beta periodicity smoothly."""
        beta_eff = ((beta % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
        return smooth_calc_S(pts, beta_eff, cx, cy, temperature)

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None
        
        # Two-phase grid: coarse then fine around best
        # Phase 1: coarse grid (12 points)
        n_coarse = 12
        for i in range(n_coarse + 1):
            beta = i * (math.pi / 6) / n_coarse
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Phase 2: fine grid (40 points) around best ± 2 coarse steps
        step_coarse = (math.pi / 6) / n_coarse
        lo_fine = max(0.0, best_beta - 2 * step_coarse)
        hi_fine = min(math.pi / 6, best_beta + 2 * step_coarse)
        n_fine = 40
        for i in range(n_fine + 1):
            beta = lo_fine + i * (hi_fine - lo_fine) / n_fine
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Refine beta with bounded scalar optimization from multiple starting points
