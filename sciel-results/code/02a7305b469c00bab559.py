"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import random
import time

N = 256

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = start_time + 55  # Safety margin before 60s kill

    range_1_N = range(1, N + 1)
    all_elements = list(range_1_N)

    def get_sums(selected):
        sums = set()
        for i, a in enumerate(selected):
            for b in selected[i:]:
                sums.add(a + b)
        return sums

    def is_valid_sidon(selected):
        sums = set()
        for i, a in enumerate(selected):
            for b in selected[i:]:
                s = a + b
                if s in sums:
                    return False
                sums.add(s)
        return True

    def can_add(x, selected, sums):
        """Check if x can be added to selected without violating Sidon property."""
        if 2 * x in sums:
            return False
        for a in selected:
            if x + a in sums:
                return False
        return True

    def compute_blocked(selected, sums):
        """
        Compute the set of elements in [1, N] that CANNOT be added to selected.
        An element x is blocked if adding it would violate the Sidon property.
        """
        blocked = set(selected)
        for x in range_1_N:
            if x in selected:
                continue
            if not can_add(x, selected, sums):
                blocked.add(x)
        return blocked

    def is_maximal(selected, sums):
        """Check if no element from [1, N] can be added."""
        # If all elements are either in selected or blocked, it is maximal
        blocked = compute_blocked(selected, sums)
        return len(blocked) == N

    def objective(selected):
        """
        Objective function for optimization.
        We want to minimize size, but maximality is a hard constraint.
        Score = size + penalty * (N - number_of_blocked_elements)
        If not maximal, penalty is huge.
        """
        if not is_valid_sidon(selected):
            return float('inf')
        
        sums = get_sums(selected)
        blocked = compute_blocked(selected, sums)
        unblocked_count = N - len(blocked)
        
        # If unblocked_count > 0, it's not maximal.
        # We want to drive unblocked_count to 0 and minimize len(selected).
        # Let's use a weighted sum.
        # If we find a maximal set, we want the smallest one.
        # If we don't, we want to reduce unblocked elements.
        
        if unblocked_count == 0:
            return len(selected)
        else:
            # High penalty for non-maximality
            return 1000 + len(selected) + 10 * unblocked_count

    def random_greedy_initial(seed):
        """Create an initial maximal Sidon set using greedy method."""
        random.seed(seed)
        candidates = list(range_1_N)
        random.shuffle(candidates)
        
        selected = []
        sums = set()
        
        for x in candidates:
            if can_add(x, selected, sums):
                selected.append(x)
                sums.add(2 * x)
                for a in selected[:-1]:
                    sums.add(x + a)
        
        # Ensure maximality by adding any remaining possible elements
        # The greedy process above ensures that if we go through all candidates,
        # the resulting set is maximal with respect to the Sidon property.
        # Proof: If x was not added, it conflicted with some sum generated by elements added before it.
        # Since we only add elements, the set of sums only grows. Thus x will still conflict.
        # So the set is maximal.
        
        return selected

    # Simulated Annealing / Local Search
    best_result = None
    best_score = float('inf')
    
    # Start with a few random greedy initializations
    num_initials = 5
    for i in range(num_initials):
        if time.time() > deadline:
            break
            
        selected = random_greedy_initial(i)
        score = objective(selected)
        
        if score < best_score:
            best_score = score
            best_result = list(selected)
            
        # Run local search from this start
        current = list(selected)
        current_score = score
        T = 100.0
        cooling = 0.95
        
        # We will iterate until time runs out or T is very small
        # Since we have multiple starts, we limit steps per start
        max_steps = 20000 
        
        for step in range(max_steps):
            if time.time() > deadline:
                break
                
            if T < 0.01:
                break
                
            # Generate a neighbor
            # Moves: Add a random element, Remove a random element, Swap
            move_type = random.random()
            
            new_selected = list(current)
            
            if move_type < 0.4:
                # Remove a random element
                if len(new_selected) > 1:
                    idx = random.randint(0, len(new_selected) - 1)
                    new_selected.pop(idx)
                else:
                    continue
            elif move_type < 0.8:
                # Add a random element
                x = random.randint(1, N)
                if x not in new_selected:
                    new_selected.append(x)
                else:
                    continue
            else:
                # Swap: remove one, add one
                if len(new_selected) < 1:
                    continue
                idx = random.randint(0, len(new_selected) - 1)
                removed = new_selected.pop(idx)
                x = random.randint(1, N)
                if x != removed:
                    new_selected.append(x)
                else:
                    new_selected.append(removed)
                    continue

            new_score = objective(new_selected)
            
            # Acceptance probability
            delta = new_score - current_score
            if delta < 0:
                current = new_selected
                current_score = new_score
                if current_score < best_score:
                    best_score = current_score
                    best_result = list(current)
            else:
                # Metropolis criterion
                if random.random() < pow(2.718281828, -delta / T):
                    current = new_selected
                    current_score = new_score
            
            T *= cooling
            
            # Early stop if we found a very small maximal set
            if best_score <= 16:
                return best_result

    if best_result is not None:
        return best_result
    
    # Fallback: Return a valid maximal set (ascending greedy)
    selected_orig = []
    sums_orig = set()
    for x in range_1_N:
        if can_add(x, selected_orig, sums_orig):
            selected_orig.append(x)
            sums_orig.add(2 * x)
            for a in selected_orig[:-1]:
                sums_orig.add(x + a)
    return selected_orig
# EVOLVE-BLOCK-END
