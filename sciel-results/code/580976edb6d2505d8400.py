def construct(n_rows, k):
    start_time = time.time()
    deadline = start_time + 140.0  # 10s safety margin
    
    # 1. Get a quick initial solution using the greedy method to set an upper bound
    used, rows = set(), []
    for _ in range(n_rows):
        row, x = [0], 0
        while len(row) < k + 1:
            x += 1
            new = {x - a for a in row}
            if not new & used:
                row.append(x)
                used |= new
        rows.append(row)
    
    initial_scope = max(max(row) for row in rows)
    best_rows = [r[:] for r in rows]
    best_scope = initial_scope
    
    # 2. Backtracking search to find a better (smaller scope) solution
    # We will try to construct rows such that the max value is < best_scope
    # We use a recursive helper
    
    def search(row_idx, current_rows, used_diffs, current_max):
        nonlocal best_scope, best_rows, deadline
        
        if time.time() > deadline:
            return False  # Timeout
        
        if row_idx == n_rows:
            # Found a valid solution
            if current_max < best_scope:
                best_scope = current_max
                best_rows = [r[:] for r in current_rows]
            return True  # Signal that a solution was found (to allow pruning in parent)
        
        # Heuristic: Try to build the next row
        # We want to keep values small.
        # We will backtrack within the row construction as well.
        
        row = [0]
        used_row_diffs = set()
        
        # Recursive helper for building a single row
        def build_row(pos, row, used_row_diffs, current_max):
            nonlocal used_diffs, deadline, best_scope, best_rows
            
            if time.time() > deadline:
                return False
            
            if pos == k + 1:
                # Row is complete
                # Check if we can proceed to next row
                # We need to merge used_row_diffs into used_diffs
                # But we need to backtrack, so we pass the new set
                new_used_diffs = used_diffs | used_row_diffs
                new_max = max(current_max, row[-1])
                
                # Pruning: if new_max is not better than best_scope, we might still 
                # want to continue if we are in the "first find" phase, but since we 
                # already have an initial solution, we only care about improvements.
                # However, a slightly larger intermediate max might lead to a smaller 
                # final max? No, max is monotonic. If current_max > best_scope, we prune.
                if new_max >= best_scope:
                    return False
                
                if search(row_idx + 1, current_rows + [row], new_used_diffs, new_max):
                    return True
                return False
            
            # Try to find the next element x
            # x must be > row[-1]
            # Differences x - a for a in row must not be in used_diffs or used_row_diffs
            last_val = row[-1]
            # Upper bound for x: we can't exceed best_scope - 1 (since we want strict improvement)
            # Actually, we can try up to best_scope - 1. If no x works, this branch fails.
            # To be safe and allow finding *any* solution if best_scope is inf (not the case here),
            # we set a high limit, but prune if x >= best_scope.
            
            # Optimization: We can estimate the minimum possible max value.
            # For now, just iterate x.
            
            # To speed up, we can jump x.
            # But simple iteration is fine for small k.
            
            # We need to ensure that the differences generated by adding x
            # do not conflict with used_diffs or used_row_diffs.
            
            # Also, we should consider that adding x creates differences with ALL previous elements.
            
            # Let's iterate x from last_val + 1 upwards.
            # We can stop if x >= best_scope.
            
            # Heuristic: Try smaller x first.
            
            # To avoid checking too many x's, we can note that if x is very large,
            # the differences are large.
            
            # Let's just iterate.
            # We can optimize by pre-computing forbidden differences for the row?
            # No, used_row_diffs changes.
            
            # One optimization: If x - a is in used_diffs, skip.
            
            # Let's try a range of x.
            # To prevent infinite loops or very slow searches, we can limit the number of 
            # backtracks or use a smarter heuristic.
            
            # For now, simple iteration.
            # We can speed this up by noticing that if x is too small, it might conflict.
            
            # Let's try x from last_val + 1 to best_scope - 1.
            # If best_scope is large, this is slow.
            # But k=7, so the row has 8 elements. The depth is 8.
            # The branching factor is limited by conflicts.
            
            # To further prune:
            # The smallest possible max value for a row of length k+1 starting at 0
            # with distinct differences is related to the "Golomb ruler" problem.
            # The optimal Golomb ruler for 8 marks has length 62? 
            # Actually, the differences must be distinct *within* the row and *across* rows.
            # The "across rows" constraint is the hard part.
            
            # Let's just run the search.
            
            # To make it faster, we can use a "forward checking" like approach:
            # For each candidate x, check if it's valid.
            
            # We can also try to randomize the order of x if we get stuck, 
            # but deterministic is better for reproducibility and finding the minimum.
            
            # Let's add a simple heuristic: prioritize x that minimizes the max difference in the row?
            # No, we want to minimize the global max value.
            
            # Let's just iterate.
            # To speed up Python, we can use a while loop and local variables.
            
            x = last_val + 1
            while x < best_scope:
                if time.time() > deadline:
                    return False
                
                # Check differences
                valid = True
                new_diffs = []
                for a in row:
                    d = x - a
                    if d in used_diffs or d in used_row_diffs:
                        valid = False
                        break
                    new_diffs.append(d)
                
                if valid:
                    # Try this x
                    row.append(x)
                    used_row_diffs.update(new_diffs)
                    
                    if build_row(pos + 1, row, used_row_diffs, current_max):
                        return True
                    
                    # Backtrack
                    row.pop()
                    for d in new_diffs:
                        used_row_diffs.remove(d)
                
                x += 1
            
            return False
        
        if build_row(1, row, used_row_diffs, current_max):
            return True
        
        return False
    
    # Run the search
    # We start with empty rows, empty used_diffs, max=0
    # But we already have an initial solution.
    # We call search(0, [], set(), 0)
    # This will try to find a solution with scope < initial_scope.
    
    search(0, [], set(), 0)
    
    return best_rows
