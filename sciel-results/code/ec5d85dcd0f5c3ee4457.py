import time
import sys

def construct(n_rows, k):
    start_time = time.time()
    deadline = 115.0  # 5s margin before 120s limit
    
    # Theoretical lower bound for M
    # Total differences = n_rows * k * (k+1) / 2
    total_diffs_needed = n_rows * k * (k + 1) // 2
    
    # We want to find the smallest M such that we can fit n_rows rows
    # The differences must be distinct integers in [1, M]
    # So M >= total_diffs_needed
    
    best_solution = None
    
    # Iterate M from lower bound upwards
    # The known best is 134. We can start from 112.
    # If we find a solution for M, we return it immediately as it's the minimum for this search order.
    # However, we should verify if we can do better than 134? The task says "minimized".
    # So the first M that yields a valid set is the answer (assuming we search M in increasing order).
    
    # We'll search M from 112 to 135.
    # If we don't find one by 135, we return the best we found or a fallback.
    
    def solve_for_m(M):
        # used_diffs: set of differences already used by previous rows
        # We build rows one by one.
        
        def build_row(current_row, used_diffs):
            # current_row: list of ints, starts with [0]
            # Returns: list of full row or None if fail
            # We need to append k elements to current_row (so k+1 total, 0 is already there)
            
            if len(current_row) == k + 1:
                return current_row[:]
            
            last_val = current_row[-1]
            
            # Try next values for the new element
            # Heuristic: try smaller values first to keep max small?
            # But we are fixing M, so we just need to fit within M.
            # Trying smaller values first might lead to dead ends faster?
            # Actually, for difference sets, "greedy small" is often a good heuristic for feasibility.
            
            for x in range(last_val + 1, M + 1):
                # Check if x is valid
                # Differences with all previous elements in current_row
                valid = True
                new_diffs = []
                for a in current_row:
                    d = x - a
                    if d in used_diffs:
                        valid = False
                        break
                    # Check against diffs already in this row (with elements after a? No, just unique diffs in row)
                    # We haven't added them to used_diffs yet, so we check against a local set or the list
                    # Actually, we can just check if d is in the set of diffs generated by current_row so far?
                    # It's easier to maintain a local set `row_diffs`
                    # But passing it around is messy. Let's just check against `current_row` diffs?
                    # No, we can compute the set of diffs in current_row once?
                    # Or just check if d is in the list of diffs we've generated for this row.
                    
                if not valid:
                    continue
                
                # We need to ensure no duplicate differences *within* the row as well.
                # The problem states: "all differences between two entries of the same row are distinct over all rows".
                # This implies:
                # 1. Diffs within row i are distinct from each other.
                # 2. Diffs within row i are distinct from diffs in row j (i != j).
                
                # So we need to check if `d` is already in the set of differences of `current_row`.
                # Let's compute the set of diffs for the current partial row.
                # To avoid O(k^2) every time, we can maintain a set `row_diffs_so_far`.
                
                # For efficiency in this recursive step, let's just compute the intersection.
                # Since k is small (7), computing diffs is fast.
                
                row_diffs_set = set()
                for i in range(len(current_row)):
                    for j in range(i):
                        row_diffs_set.add(current_row[i] - current_row[j])
                        
                # Check new diffs
                for a in current_row:
                    d = x - a
                    if d in row_diffs_set or d in used_diffs:
                        valid = False
                        break
                    new_diffs.append(d)
                    
                if not valid:
                    continue
                
                # Pruning: Check if we have enough remaining differences in [1, M]
                # Total diffs needed for all rows: total_diffs_needed
                # Diffs used so far: len(used_diffs) + len(row_diffs_set)
                # Diffs remaining to place: total_diffs_needed - (len(used_diffs) + len(row_diffs_set))
                # Available diffs in [1, M]: M - (len(used_diffs) + len(row_diffs_set))
                # If Available < Remaining, fail.
                
                used_count = len(used_diffs) + len(row_diffs_set)
                remaining_needed = total_diffs_needed - used_count
                available = M - used_count
                
                if available < remaining_needed:
                    continue
                
                # Recurse
                next_row = current_row + [x]
                # We don't update used_diffs yet, because this row isn't finished.
                # But we pass the new local diffs?
                # Actually, `used_diffs` is global for *completed* rows.
                # The conflicts within the current row are handled by `row_diffs_set` check.
                # So we just recurse with the same `used_diffs` (which only contains diffs from *previous* rows).
                
                result = build_row(next_row, used_diffs)
                if result is not None:
                    return result
            
            return None

        # Main loop for rows
        rows = []
        global_used_diffs = set()
        
        for r_idx in range(n_rows):
            # Try to build row r_idx
            # We start with [0]
            # Note: The first element is 0.
            
            # Optimization: Symmetry breaking?
            # For the first row, we can fix a_1? No, a_1 can be anything.
            # But we can iterate a_1 from 1 to M.
            
            # To speed up, we can try to build the row.
            # The function build_row handles the rest.
            
            # We need to be careful: build_row starts with [0].
            # It picks a_1...a_k.
            
            # We might want to try different starting points or orderings if it fails?
            # For now, let's just call it.
            
            # One issue: build_row is deterministic given the input.
            # If it fails, it fails.
            # We might need to randomize or try different heuristics.
            # However, for a fixed M, if a solution exists, greedy-small often finds it?
            # Not always.
            
            # Let's add a timeout or node limit inside build_row?
            # Since k=7, the depth is 7. Branching factor is up to M.
            # M ~ 130. 130^7 is huge.
            # Pruning is critical.
            
            # Let's add a simple node counter and a limit.
            # If we exceed limit, return None (fail).
            
            node_limit = 100000
            node_count = [0]
            
            def build_row_limited(current_row, used_diffs):
                if time.time() > deadline:
                    return None
                if node_count[0] > node_limit:
                    return None
                node_count[0] += 1
                
                if len(current_row) == k + 1:
                    return current_row[:]
                
                last_val = current_row[-1]
                
                # Pre-compute row_diffs_set for current_row
                row_diffs_set = set()
                for i in range(len(current_row)):
                    for j in range(i):
                        row_diffs_set.add(current_row[i] - current_row[j])
                        
                # Iterate candidates for next element
                for x in range(last_val + 1, M + 1):
                    valid = True
                    new_diffs = []
                    for a in current_row:
                        d = x - a
                        if d in used_diffs or d in row_diffs_set:
                            valid = False
                            break
                        new_diffs.append(d)
                        
                    if not valid:
                        continue
                    
                    # Pruning
                    used_count = len(used_diffs) + len(row_diffs_set)
                    remaining_needed = total_diffs_needed - used_count
                    available = M - used_count
                    if available < remaining_needed:
                        continue
                        
                    next_row = current_row + [x]
                    result = build_row_limited(next_row, used_diffs)
                    if result is not None:
                        return result
                        
                return None
            
            row = build_row_limited([0], global_used_diffs)
            if row is None:
                return None
            
            # Add diffs of this row to global_used_diffs
            for i in range(len(row)):
                for j in range(i):
                    global_used_diffs.add(row[i] - row[j])
                    
            rows.append(row)
            
            # Check time
            if time.time() > deadline:
                return None
                
        return rows

    # Search for M
    for M in range(total_diffs_needed, 140):
        if time.time() > deadline:
            break
            
        # Try to solve for this M
        # We might want to try multiple times or different strategies if it fails?
        # For now, one deterministic try.
        # If it fails, maybe it's not possible, or the heuristic is too weak.
        
        solution = solve_for_m(M)
        if solution:
            # Verify solution
            all_diffs = set()
            valid = True
            for row in solution:
                if row[0] != 0:
                    valid = False
                    break
                for i in range(len(row)):
                    for j in range(i):
                        d = row[i] - row[j]
                        if d in all_diffs:
                            valid = False
                            break
                        all_diffs.add(d)
                if not valid:
                    break
            if valid:
                return solution
            else:
                # Should not happen if solver is correct
                continue
                
    # Fallback: Return a valid set with a larger scope if we timed out or failed
    # Use a simple greedy to ensure we return *something* valid, even if not optimal
    # This guarantees score > 0 (or at least valid)
    
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new = {x - a for a in row}
            if not new & used:
                row.append(x)
                used |= new
        rows.append(row)
    return rows
