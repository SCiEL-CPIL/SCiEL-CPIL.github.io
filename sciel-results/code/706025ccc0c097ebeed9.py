import numpy as np
import time
from scipy.stats import qmc

class Optimizer:
    """Multi-objective optimizer using Latin Hypercube Sampling for WFG9."""

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start = time.time()
        deadline = start + 280.0  # Safety margin before 330s limit
        
        lo = np.array([b[0] for b in bounds], dtype=float)
        hi = np.array([b[1] for b in bounds], dtype=float)
        dim = self.dim
        n_obj = self.n_obj
        budget = self.budget

        if budget <= 0:
            return np.empty((0, dim))

        # Generate Latin Hypercube Sampling points
        # Using a fixed seed for reproducibility within the run, 
        # but the evaluator sets np.random.seed, so we should ideally 
        # use that or a deterministic seed. 
        # The task says "For seeds 0 and 1 the evaluator calls np.random.seed(seed)".
        # If we use qmc.LatinHypercube(seed=42), it is deterministic.
        # If we want to leverage the evaluator's seed, we could use it.
        # But LHS is deterministic given the seed. 
        # Let's use the current np.random state? No, qmc.LatinHypercube takes a seed.
        # If we pass seed=None, it uses the global state? 
        # Documentation: "seed : int, array_like, or np.random.Generator, optional"
        # If we pass an int, it's fixed. 
        # Since the evaluator seeds np.random, maybe we should generate random points 
        # using np.random to respect the seed? 
        # But LHS is the structural change. 
        # Let's use a fixed seed for the LHS structure, but maybe jitter? 
        # No, pure LHS is the point.
        
        # However, if the evaluator runs seed 0 and seed 1, and we use a fixed 
        # internal seed, the results will be identical for both seeds.
        # The score is the mean over seeds. This is fine.
        # But if the problem has stochasticity (it doesn't, WFG9 is deterministic), 
        # it wouldn't matter.
        
        # To be safe and utilize the "seed" aspect if needed for diversity 
        # (though WFG9 is deterministic), we can use the global random state 
        # to shuffle the LHS points or generate the LHS.
        # qmc.LatinHypercube does not directly accept np.random.RandomState easily 
        # in older versions, but we can generate the unit points manually 
        # or use the seed parameter.
        
        # Let's use the global np.random state to generate the LHS 
        # by shuffling the permutations.
        # LHS can be generated by:
        # 1. Create N points in [0,1] for each dimension: i/N
        # 2. Shuffle each dimension independently.
        # 3. Divide by N.
        
        n = budget
        # Generate the base LHS points
        # This ensures exact uniform coverage
        base = np.arange(n) / n
        # Shuffle each dimension using the global RNG (which is seeded by evaluator)
        X_unit = np.zeros((n, dim))
        for d in range(dim):
            X_unit[:, d] = base[np.random.permutation(n)]
        
        # Map to bounds
        X = lo + (hi - lo) * X_unit

        # Evaluate all points
        F = np.empty((n, n_obj))
        for i in range(n):
            if time.time() > deadline:
                # In case of extreme slowness (unlikely)
                break
            F[i] = problem(X[i])
            
        # If we broke early, we need to handle the partial F
        # But 200 evals is fast.
        
        return X
