import numpy as np
import random
import time

def construct():
    N = 17
    MIN_DIST = 6
    start_time = time.time()
    time_limit = 80.0

    # GF(2^8)
    PRIME = 0x11D
    def gf_mul(a, b):
        p = 0
        while b:
            if b & 1: p ^= a
            b >>= 1
            a <<= 1
            if a & 0x100: a ^= PRIME
        return p

    def gf_pow(a, n):
        r = 1
        while n:
            if n & 1: r = gf_mul(r, a)
            a = gf_mul(a, a)
            n >>= 1
        return r

    alpha = 3
    # Verify alpha is primitive
    if gf_pow(alpha, 255) != 1:
        alpha = 5
        
    Q = [1, 2, 4, 8, 9, 13, 15, 16]
    
    # Compute g(x) in GF(2^8)
    g = [1]
    for i in Q:
        root = gf_pow(alpha, i)
        new_g = [0] * (len(g) + 1)
        for j in range(len(g)):
            new_g[j] ^= g[j]
            new_g[j+1] ^= gf_mul(g[j], root)
        g = new_g
        
    # Check if g is over GF(2)
    # Coeffs should be 0 or 1
    binary_g = []
    for coeff in g:
        if coeff == 0:
            binary_g.append(0)
        elif coeff == 1:
            binary_g.append(1)
        else:
            # Fallback to greedy if not binary
            # This shouldn't happen for the minimal polynomial
            break
    else:
        # binary_g is valid
        # Generate codewords
        words = []
        # g is [c8, c7, ..., c0]
        # Codeword for message m (8 bits) is m(x)g(x)
        for m in range(256):
            # m(x) is 8 bits
            # Compute product
            # Since deg(m)<8, deg(g)=8, deg(mg)<16
            # So no mod x^17-1 wrap around
            cw = [0]*17
            for j in range(8):
                if (m >> j) & 1:
                    # Add x^j g(x)
                    for k in range(9):
                        cw[j+k] ^= binary_g[8-k] # g is reversed?
            # binary_g is [c8...c0]. g(x) = c8 x^8 + ... + c0
            # So term x^j g(x) has coeffs at j..j+8
            # cw[idx] ^= binary_g[8 - (idx-j)]?
            # Let's just do polynomial multiplication properly.
            
            # Simpler:
            msg_poly = [ (m >> j) & 1 for j in range(8) ] # [m0, m1, ..., m7]
            gen_poly = [ binary_g[i] for i in range(8, -1, -1) ] # [c0, c1, ..., c8]
            
            prod = [0]*16
            for i in range(8):
                if msg_poly[i]:
                    for j in range(9):
                        prod[i+j] ^= gen_poly[j]
                        
            # Pad to 17
            for i in range(16):
                if prod[i]:
                    # Set bit i
                    pass
            # Convert to int
            w = 0
            for i in range(16):
                if prod[i]:
                    w |= (1 << i)
            # Bit 16 is 0
            words.append(w)
            
        # Extend to 18 bits with parity
        extended_words = []
        for w in words:
            # Parity bit
            parity = bin(w).count('1') % 2
            ew = (w << 1) | parity
            extended_words.append(ew)
            
        # Shorten by fixing coordinate 17 (the parity bit) to 0?
        # No, shorten by fixing any coordinate.
        # If we fix the parity bit to 0, we get the original [17,8,5] code.
        # Distance 5. We need distance 6.
        # So we must shorten the [18,9,6] code.
        # The [18,9,6] code has 512 words.
        # We only generated 256 (the subcode with parity 0).
        # The other 256 have parity 1.
        # To get the full [18,9,6] code, we need to add the other 256.
        # The other 256 are generated by (m(x) + 1)g(x)? No.
        # The extended code is generated by the extended generator matrix.
        # It consists of all (c, p) where c in C, p = weight(c) mod 2.
        # So we have all 512 words.
        
        # Now shorten. Fix coordinate 0 to 0.
        # Remove words where bit 0 is 1.
        shortened = []
        for ew in extended_words:
            if (ew & 1) == 0:
                shortened.append(ew >> 1)
                
        # This gives 256 words of length 17.
        # Distance is 6.
        
        # Now try to add more words
        code_arr = np.array([list(format(w, '017b')) for w in shortened], dtype=int)
        
        def try_add(w):
            nonlocal code_arr
            w_vec = np.array([int(b) for b in format(w, '017b')])
            dists = np.sum(code_arr != w_vec, axis=1)
            if np.min(dists) >= MIN_DIST:
                code_arr = np.vstack([code_arr, w_vec])
                shortened.append(w)
                return True
            return False

        # Local search
        while time.time() - start_time < time_limit:
            w = random.randint(0, 2**17 - 1)
            try_add(w)
            
        return shortened

    # Fallback
    words = [0]
    return words
