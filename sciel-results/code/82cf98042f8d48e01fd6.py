import numpy as np
from scipy.optimize import minimize

def _apply_ry_vectorized(state, theta, i):
    """Apply Ry(theta) to qubit i using vectorized operations."""
    c = np.cos(theta / 2)
    s = np.sin(theta / 2)
    mask = 1 << i
    
    # Create indices where bit i is 0
    indices_0 = np.where((np.arange(len(state)) & mask) == 0)[0]
    indices_1 = indices_0 | mask
    
    v0 = state[indices_0].copy()
    v1 = state[indices_1].copy()
    
    new_state = state.copy()
    new_state[indices_0] = c * v0 - s * v1
    new_state[indices_1] = s * v0 + c * v1
    
    return new_state

def _apply_cz_vectorized(state, i, j):
    """Apply CZ gate between qubits i and j using vectorized operations."""
    mask_i = 1 << i
    mask_j = 1 << j
    
    # Find indices where both bits are 1
    indices = np.where(((np.arange(len(state)) & mask_i) != 0) & ((np.arange(len(state)) & mask_j) != 0))[0]
    
    new_state = state.copy()
    new_state[indices] *= -1.0
    
    return new_state

def _compute_energy_and_grad(n, coupling, field, angles):
    """
    Compute energy and gradient of the state generated by the circuit.
    angles: shape (layers, n)
    Returns: energy, gradient (shape (layers, n))
    """
    # State evolution
    state = np.zeros(2**n, dtype=complex)
    state[0] = 1.0
    
    # We need to store states at each layer to compute gradients efficiently?
    # For BFGS with finite differences, we just need the energy function.
    # But analytic gradient is faster. Let's stick to finite difference for simplicity 
    # and robustness in the "new design" unless we implement backprop.
    # Given n<=6, finite difference is acceptable if we are careful.
    
    # Actually, let's just implement the energy function cleanly.
    # The optimizer will handle gradients.
    
    # Apply layers
    for l in range(angles.shape[0]):
        # Apply Ry to all qubits
        for i in range(n):
            state = _apply_ry_vectorized(state, angles[l, i], i)
        
        # Apply CZ between adjacent pairs if not the last layer
        if l < angles.shape[0] - 1:
            for i in range(n - 1):
                state = _apply_cz_vectorized(state, i, i + 1)
    
    # Compute Energy <H>
    # H = -coupling * sum Z_i Z_{i+1} - field * sum X_i
    
    # Precompute Z and X expectation values efficiently
    # Z_i Z_{i+1}
    # Z_i = 1 if bit i is 0, -1 if bit i is 1.
    # We can compute the probability distribution.
    probs = np.abs(state)**2
    
    energy = 0.0
    
    # ZZ terms
    for i in range(n - 1):
        mask_i = 1 << i
        mask_j = 1 << (i + 1)
        # Expectation of Z_i Z_j
        # Sum_{k} prob_k * z_i(k) * z_j(k)
        # z_i(k) = 1 - 2*(k>>i & 1)
        # Vectorized:
        z_i = np.where((np.arange(len(state)) & mask_i) == 0, 1.0, -1.0)
        z_j = np.where((np.arange(len(state)) & mask_j) == 0, 1.0, -1.0)
        exp_zz = np.sum(probs * z_i * z_j)
        energy += -coupling * exp_zz
        
    # X terms
    # <X_i> = sum_{k: bit i=0} psi_k^* psi_{k|mask_i} + c.c.
    # Since state is real (Ry, CZ preserve reality if start real), <X_i> = 2 * sum psi_k psi_{k|mask_i}
    for i in range(n):
        mask = 1 << i
        indices_0 = np.where((np.arange(len(state)) & mask) == 0)[0]
        indices_1 = indices_0 | mask
        # Sum of products
        exp_x = 2.0 * np.sum(state[indices_0] * state[indices_1])
        energy += -field * exp_x
        
    return energy

def angles(n, coupling, field, layers):
    """
    Optimize parameters using BFGS (Quasi-Newton) with multi-start.
    """
    half_n = (n + 1) // 2
    n_params = layers * half_n
    
    def unpack(params):
        ang = np.zeros((layers, n))
        for l in range(layers):
            for i in range(half_n):
                val = params[l * half_n + i]
                ang[l, i] = val
                ang[l, n - 1 - i] = val
        return ang
    
    def objective(params):
        ang = unpack(params)
        return _compute_energy_and_grad(n, coupling, field, ang)
        
    # Multi-start BFGS
    best_energy = np.inf
    best_params = None
    
    # Initial guesses
    # 1. Zero
    # 2. Pi/2
    # 3. Pi/4
    # 4. Random
    np.random.seed(42)
    guesses = [
        np.zeros(n_params),
        np.full(n_params, np.pi / 2),
        np.full(n_params, np.pi / 4),
        np.random.uniform(-np.pi, np.pi, n_params)
    ]
    
    for guess in guesses:
        try:
            # BFGS is good for smooth functions.
            # maxiter 200 is usually enough for this small dimension.
            res = minimize(objective, guess, method='BFGS', 
                           options={'maxiter': 200, 'gtol': 1e-6})
            if res.fun < best_energy:
                best_energy = res.fun
                best_params = res.x
        except Exception:
            continue
            
    if best_params is None:
        # Fallback
        theta = np.zeros((layers, n))
        theta[-1] = np.pi / 2
        return theta
        
    best_angles = unpack(best_params)
    return best_angles
