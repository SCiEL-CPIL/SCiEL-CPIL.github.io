import collections

def construct():
    # Modular inverses of 1..10 modulo 101
    p = 101
    inv = [0] * 11
    for i in range(1, 11):
        inv[i] = pow(i, -1, p)
    
    # BFS over states (residue, mask)
    # mask is a 10-bit integer where bit i-1 indicates if denominator i is used
    start_res = 0
    start_mask = 0
    
    # Queue stores (residue, mask)
    queue = collections.deque()
    queue.append((start_res, start_mask))
    visited = set()
    visited.add((start_res, start_mask))
    
    # Track the best (minimum depth) mask for each residue
    # Since we want to minimize the max row length, and rows are independent,
    # finding the shortest path to each residue is optimal.
    best_mask_for_res = {r: None for r in range(p)}
    best_depth_for_res = {r: float('inf') for r in range(p)}
    
    # Initialize for start state
    best_mask_for_res[0] = 0
    best_depth_for_res[0] = 0
    
    while queue:
        res, mask = queue.popleft()
        current_depth = bin(mask).count('1')
        
        # Update best for this residue if current depth is better
        if current_depth < best_depth_for_res[res]:
            best_depth_for_res[res] = current_depth
            best_mask_for_res[res] = mask
            
        # Explore neighbors
        for d in range(1, 11):
            bit = 1 << (d - 1)
            if mask & bit:
                continue # Denominator already used
            
            new_mask = mask | bit
            new_res = (res + inv[d]) % p
            
            if (new_res, new_mask) not in visited:
                visited.add((new_res, new_mask))
                queue.append((new_res, new_mask))
                
    # Construct the result
    result = []
    for r in range(p):
        mask = best_mask_for_res[r]
        if mask is None:
            # This should not happen as the group is generated by the inverses
            # but just in case, we might need a fallback, though mathematically 
            # the set of inverses of 1..10 generates the group mod 101?
            # Let's assume it does. If not, the task is impossible or requires larger set.
            # Given the seed program works, it is possible.
            terms = []
        else:
            terms = [i for i in range(1, 11) if mask & (1 << (i - 1))]
        result.append(terms)
        
    return result
