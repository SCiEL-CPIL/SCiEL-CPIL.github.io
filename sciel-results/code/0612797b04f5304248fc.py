def _reed_muller_32():
    """First-order Reed-Muller code on 16 coordinates, extended by two zero bits."""
    words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            words.append(word)
    return words

def _greedy_add(words, candidate):
    """Try to add candidate to words if it maintains minimum distance 6."""
    for w in words:
        if (w ^ candidate).bit_count() < 6:
            return False
    words.append(candidate)
    return True

def _local_search(words, time_limit, rng):
    """
    Local search to try to add more words.
    Optimized to use numpy for vectorized operations where possible.
    """
    start_time = time.time()
    n = len(words)
    words = list(words)
    
    # Convert to numpy array for faster XOR
    arr = np.array(words, dtype=np.uint32)
    
    def can_add(candidate):
        """Check if candidate can be added to the code."""
        if len(arr) == 0:
            return True
        # XOR all words with candidate
        xored = arr ^ candidate
        # Count bits. 
        # np.bit_count is available in NumPy 2.0. 
        # If not available, we fall back to a list comprehension which is slower.
        # To be safe and fast, we can use a lookup table for 16-bit chunks or just the list comp.
        # Given N=18, we can split into two 9-bit parts or just use the list comp.
        # The list comp is ~1ms for 2048 items.
        # Let's try to use a faster method if np.bit_count exists.
        try:
            dists = np.bit_count(xored)
        except AttributeError:
            dists = np.array([x.bit_count() for x in xored], dtype=np.uint8)
        
        return np.min(dists) >= 6
    
    best_words = list(words)
    best_n = n
    
    # Increase the number of candidates per time check to reduce overhead
    # But keep the time check frequent.
    
    while time.time() - start_time < time_limit:
        # Generate random candidates in batches
        # Check time every 10 candidates to balance overhead
        for _ in range(10):
            if time.time() - start_time > time_limit:
                return best_words
            
            candidate = rng.randint(0, (1 << 18) - 1)
            if can_add(candidate):
                arr = np.append(arr, candidate)
                best_words = list(arr)
                best_n = len(arr)
    
    return best_words

