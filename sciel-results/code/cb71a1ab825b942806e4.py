import time
import random

def pack(boxes, container):
    W, H, D = container
    n = len(boxes)
    
    # Sort indices by volume descending (Best Fit Decreasing)
    # Using max dimension as a secondary tie-breaker can sometimes help, but volume is standard
    sorted_indices = sorted(range(n), key=lambda i: boxes[i][0] * boxes[i][1] * boxes[i][2], reverse=True)
    
    # bins: list of lists of (x, y, z, w, h, d, original_index)
    bins = []
    
    # Helper to check if a box fits at (x,y,z) in a bin
    def fits_at(x, y, z, w, h, d, bin_boxes):
        if x + w > W or y + h > H or z + d > D:
            return False
        for (bx, by, bz, bw, bh, bd, _) in bin_boxes:
            # Check overlap
            if (x < bx + bw and bx < x + w and
                y < by + bh and by < y + h and
                z < bz + bd and bz < z + d):
                return False
        return True

    # Helper to find best position in a specific bin
    # Returns (x, y, z) or None
    def find_best_position(w, h, d, bin_boxes, candidates):
        best_pos = None
        best_score = float('inf')
        
        # We maintain a set of candidate positions to check
        # To avoid O(N^2) explosion of candidates, we can just check the current candidate list
        # and maybe add new ones generated by existing boxes if the list is small
        # For 40 boxes, the number of corners is manageable.
        
        # Actually, a safer approach for small N is to generate all potential corners from existing boxes + origin
        # Potential x: 0, box.x + box.w for all boxes
        # Potential y: 0, box.y + box.h for all boxes
        # Potential z: 0, box.z + box.d for all boxes
        
        x_coords = set([0])
        y_coords = set([0])
        z_coords = set([0])
        
        for (bx, by, bz, bw, bh, bd, _) in bin_boxes:
            x_coords.add(bx + bw)
            y_coords.add(by + bh)
            z_coords.add(bz + bd)
            
        # Filter coords that are within bounds
        x_coords = [x for x in x_coords if x + w <= W]
        y_coords = [y for y in y_coords if y + h <= H]
        z_coords = [z for z in z_coords if z + d <= D]
        
        # Sort coords to prioritize smaller coordinates (Bottom-Left-Front)
        x_coords.sort()
        y_coords.sort()
        z_coords.sort()
        
        for x in x_coords:
            for y in y_coords:
                for z in z_coords:
                    if fits_at(x, y, z, w, h, d, bin_boxes):
                        score = x + y + z
                        if score < best_score:
                            best_score = score
                            best_pos = (x, y, z)
                            # Since we iterate in sorted order, the first valid one found
                            # with the lowest sum isn't necessarily the global min sum if we don't break correctly.
                            # But x, y, z are sorted, so the first valid (x,y,z) in this nested loop
                            # is not guaranteed to be the min x+y+z. 
                            # Example: (10,0,0) sum 10 vs (0,5,0) sum 5. 
                            # If x=0 is first, we check y=0, z=0... 
                            # To be strictly optimal on sum, we should check all or break early if we assume 
                            # monotonicity which doesn't hold for sum.
                            # However, for packing, "corner" preference is usually sufficient.
                            # Let's just find the min sum explicitly.
        
        # Re-evaluating: The loop above checks all combinations. 
        # We can break early if we just want "first found" in a specific order, 
        # but for "min sum", we must check all.
        # With 40 boxes, max corners ~ 41^3 = 68921 checks per box per bin.
        # 40 boxes * 40 bins * 70k checks = 112 million checks. This might be too slow in Python.
        
        # Optimization: Limit candidate set.
        # Only check candidates generated by existing boxes + origin.
        # The set size is at most (num_boxes+1)^3.
        
        return best_pos

    # Refined Search:
    # For each box, check all bins.
    # For each bin, generate candidate positions from existing boxes' corners + origin.
    # Check validity and pick min x+y+z.
    
    for idx in sorted_indices:
        w, h, d = boxes[idx]
        best_bin_idx = -1
        best_pos = None
        best_score = float('inf')
        
        for b_idx, bin_boxes in enumerate(bins):
            # Generate candidates
            x_set = {0}
            y_set = {0}
            z_set = {0}
            for (bx, by, bz, bw, bh, bd, _) in bin_boxes:
                if bx + bw <= W: x_set.add(bx + bw)
                if by + bh <= H: y_set.add(by + bh)
                if bz + bd <= D: z_set.add(bz + bd)
            
            # If bin is empty, only (0,0,0)
            for x in x_set:
                if x + w > W: continue
                for y in y_set:
                    if y + h > H: continue
                    for z in z_set:
                        if z + d > D: continue
                        if fits_at(x, y, z, w, h, d, bin_boxes):
                            score = x + y + z
                            if score < best_score:
                                best_score = score
                                best_bin_idx = b_idx
                                best_pos = (x, y, z)
        
        if best_bin_idx == -1:
            # Open new bin
            bins.append([(0, 0, 0, w, h, d, idx)])
        else:
            bins[best_bin_idx].append((best_pos[0], best_pos[1], best_pos[2], w, h, d, idx))
    
    # Construct result in original order
    placements = [None] * n
    for b_idx, bin_boxes in enumerate(bins):
        for (x, y, z, w, h, d, orig_idx) in bin_boxes:
            placements[orig_idx] = (b_idx, x, y, z, w, h, d)
            
    return placements
