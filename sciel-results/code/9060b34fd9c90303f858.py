    # Vertices are indexed 0..49.
    # Row i (0..4), Col j (0..9).
    # Vertex index = i * 10 + j.
    
    # Coloring c(i, j) = (i + j) % 3
    # This is a proper 3-coloring.
    # As analyzed, this specific coloring ensures that for any pair of colors,
    # the induced subgraph is a forest (specifically, a collection of paths/trees).
    
    coloring = [0] * P['n']
    for i in range(5):
        for j in range(10):
            v = i * 10 + j
            coloring[v] = (i + j) % 3
            
    # Verify validity to be safe
    if _check(coloring):
        return [int(x) for x in coloring]
        
    # Fallback if the pattern fails (it shouldn't)
    # Try a different pattern or fall back to higher colors
    # For now, just return distinct colors to ensure validity if check fails
    return [int(i) for i in range(P['n'])]
