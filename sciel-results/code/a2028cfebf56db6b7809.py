import time

def construct():
    # Rank 7 Strassen decomposition
    rank = 7
    U = [[0] * rank for _ in range(4)]
    V = [[0] * rank for _ in range(4)]
    W = [[0] * rank for _ in range(4)]

    # m1 = (a00 + a11)(b00 + b11)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[3][0] = 1
    
    # m2 = (a10 + a11)b00
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    
    # m3 = a00(b01 - b11)
    U[0][2] = 1
    V[1][2] = 1; V[3][2] = -1
    
    # m4 = a11(b10 - b00)
    U[3][3] = 1
    V[2][3] = 1; V[0][3] = -1
    
    # m5 = (a00 + a01)b11
    U[0][4] = 1; U[1][4] = 1
    V[3][4] = 1
    
    # m6 = (a10 - a00)(b00 + b01)
    U[2][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    
    # m7 = (a01 - a11)(b10 + b11)
    U[1][6] = 1; U[3][6] = -1
    V[2][6] = 1; V[3][6] = 1

    # C00 = m1 + m4 - m5 + m7
    W[0][0] = 1
    W[0][3] = 1
    W[0][4] = -1
    W[0][6] = 1

    # C01 = m3 + m5
    W[2][2] = 1
    W[2][4] = 1

    # C10 = m2 + m4
    W[1][1] = 1
    W[1][3] = 1

    # C11 = m1 - m4 + m6 + m7
    W[3][0] = 1
    W[3][3] = -1
    W[3][5] = 1
    W[3][6] = 1

    return {"U": U, "V": V, "W": W}
