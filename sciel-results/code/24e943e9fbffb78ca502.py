"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
D = 11

# EVOLVE-BLOCK-START
import numpy as np
import time
import heapq
from itertools import combinations, product

def construct():
    start_time = time.time()
    deadline = start_time + 145  # 5s safety margin
    
    # 1. Generate Candidates: Weight-4 vectors
    # C(11, 4) * 16 = 330 * 16 = 5280
    candidates = []
    for support in combinations(range(D), 4):
        for signs in product([1, -1], repeat=4):
            v = np.zeros(D, dtype=np.int64)
            for idx, s in zip(support, signs):
                v[idx] = s
            candidates.append(v)

    cand_arr = np.array(candidates, dtype=np.int64)
    n_cands = len(cand_arr)

    # 2. Build Conflict Graph
    # Conflict if dot product > 2
    G = (cand_arr.astype(np.int8) @ cand_arr.T.astype(np.int8))
    
    # Build adjacency lists and degree array
    neighbors = [np.array([], dtype=np.int32) for _ in range(n_cands)]
    degrees = np.zeros(n_cands, dtype=np.int32)
    for i in range(n_cands):
        js = np.where(G[i] > 2)[0]
        js = js[js != i]
        neighbors[i] = js.astype(np.int32)
        degrees[i] = len(js)
        
    rng = np.random.default_rng(42)
    best_set = np.array([], dtype=np.int64)
    best_size = 0

    # Helper: Convert a boolean mask to a list of selected indices
    def mask_to_indices(mask):
        return np.where(mask)[0]

    # Helper: Check if a set of indices is a valid independent set
    # For efficiency, we assume the input mask is valid if generated by our algorithms,
    # but we can do a quick check on the final result.
    
    # Strategy 1: Greedy Min-Degree with Randomization
    def run_greedy_min_deg(seed_offset=0):
        if time.time() > deadline - 5:
            return None
            
        local_rng = np.random.default_rng(42 + seed_offset)
        deg = degrees.copy()
        selected = []
        remaining = set(range(n_cands))
        
        # Pre-compute a list of nodes sorted by initial degree for tie-breaking?
        # Or just pick randomly from min-degree set.
        
        while remaining:
            if time.time() > deadline - 2:
                break
                
            # Find min degree among remaining
            # Optimization: Instead of scanning all remaining, we can use a heap or buckets.
            # Given n=5280, scanning is O(N^2) worst case, which might be slow.
            # Let's try to be smarter.
            # However, for now, let's stick to a slightly optimized scan or bucket.
            
            # Bucket approach:
            # We maintain a list of nodes for each degree.
            # But degrees change.
            
            # Let's just find min degree quickly.
            min_deg = min(deg[i] for i in remaining)
            candidates = [i for i in remaining if deg[i] == min_deg]
            
            # Pick randomly
            u = local_rng.choice(candidates)
            
            selected.append(u)
            remaining.remove(u)
            
            # Remove neighbors
            for v in neighbors[u]:
                if v in remaining:
                    remaining.remove(v)
                    for w in neighbors[v]:
                        if w in remaining:
                            deg[w] -= 1
                            
        return selected

    # Strategy 2: Local Search (Swap-based) to improve a greedy solution
    # Start with a greedy solution, then try to swap one selected node with an unselected one
    # if it increases the size.
    
    def local_search_improve(selected_indices, max_iters=200):
        if time.time() > deadline - 5:
            return selected_indices
            
        selected_set = set(selected_indices)
        # Precompute conflicts for selected nodes?
        # We need to know which unselected nodes can replace which selected nodes.
        
        # For each selected node u, find unselected nodes v such that:
        # 1. v is not in selected_set
        # 2. v is not a neighbor of any other selected node w (w != u)
        # 3. Replacing u with v is valid?
        # Actually, a standard move is:
        # Remove u from selected.
        # Add v to selected if v is not a neighbor of any remaining selected node.
        
        # Let's track the "conflict count" for unselected nodes against the selected set.
        # conflict_count[v] = number of neighbors of v that are in selected_set.
        # If we remove u, conflict_count[v] decreases by 1 if u is a neighbor of v.
        # Then we can add v if conflict_count[v] == 0.
        
        # Initialize conflict counts
        conflict_count = np.zeros(n_cands, dtype=np.int32)
        for u in selected_indices:
            for v in neighbors[u]:
                conflict_count[v] += 1
        
        # Nodes with conflict_count == 0 are candidates for addition.
        # But we need to remove a node first to make space? No, we just want to increase size.
        # Wait, if we add a node, size increases. But we can only add if it doesn't conflict.
        # If there are any unselected nodes with conflict_count == 0, we can add them directly!
        # This means the greedy solution wasn't maximal?
        # A maximal independent set has no unselected node with 0 conflicts with the set.
        # So if we find one, we add it.
        
        improved = True
        while improved and time.time() < deadline - 5:
            improved = False
            # Find unselected nodes with 0 conflicts
            # We need to check nodes NOT in selected_set
            # To speed this up, we can maintain a list of "available" nodes.
            # But let's just scan for now, as N=5280 is small.
            
            # Optimization: Only check nodes that are not in selected_set.
            # We can create a mask.
            in_selected = np.zeros(n_cands, dtype=bool)
            for u in selected_indices:
                in_selected[u] = True
            
            # Candidates are where in_selected is False and conflict_count is 0
            candidates = np.where((~in_selected) & (conflict_count == 0))[0]
            
            if len(candidates) > 0:
                # Pick one randomly
                v = rng.choice(candidates)
                selected_indices.append(v)
                in_selected[v] = True
                # Update conflict counts for neighbors of v
                for w in neighbors[v]:
                    if not in_selected[w]:
                        conflict_count[w] += 1
                improved = True
            else:
                # Try swaps: Remove u, add v
                # This is more complex. Let's try a simple 1-swap.
                # For each u in selected, remove it, update counts, see if any v becomes available.
                # This is O(N^2) per swap, which is too slow.
                # Let's skip swaps for now and rely on multiple restarts.
                pass
                
        return selected_indices

    # Strategy 3: Weighted Greedy
    # Assign weights to nodes (e.g., random or based on degree) and pick the one with highest weight
    # among min-degree nodes? Or just highest weight overall?
    
    def run_greedy_weighted(seed_offset=0):
        if time.time() > deadline - 5:
            return None
            
        local_rng = np.random.default_rng(42 + seed_offset)
        deg = degrees.copy()
        selected = []
        remaining = set(range(n_cands))
        
        # Assign random weights
        weights = local_rng.random(n_cands)
        
        while remaining:
            if time.time() > deadline - 2:
                break
                
            min_deg = min(deg[i] for i in remaining)
            candidates = [i for i in remaining if deg[i] == min_deg]
            
            # Pick the one with the highest weight
            u = max(candidates, key=lambda i: weights[i])
            
            selected.append(u)
            remaining.remove(u)
            
            for v in neighbors[u]:
                if v in remaining:
                    remaining.remove(v)
                    for w in neighbors[v]:
                        if w in remaining:
                            deg[w] -= 1
                            
        return selected

    # Run multiple restarts with different strategies
    n_restarts = 200 # Increase restarts since we have time budget
    
    for r in range(n_restarts):
        if time.time() > deadline - 10:
            break
        
        if r % 3 == 0:
            result = run_greedy_min_deg(r)
        elif r % 3 == 1:
            result = run_greedy_weighted(r)
        else:
            # Alternate between different random seeds for min_deg
            result = run_greedy_min_deg(1000 + r)
            
        if result is not None:
            # Apply local search improvement
            result = local_search_improve(result)
            
            if len(result) > best_size:
                best_size = len(result)
                best_set = cand_arr[result].copy()

    # Fallback
    if best_size == 0:
        best_set = cand_arr[:1]
        best_size = 1

    return best_set

# EVOLVE-BLOCK-END
