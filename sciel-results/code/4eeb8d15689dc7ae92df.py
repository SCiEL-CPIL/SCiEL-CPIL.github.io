import numpy as np

def construct():
    """
    Returns the schoolbook tensor decomposition for matrix multiplication.
    For n x m * m x p, the rank is n*m*p.
    This is the baseline (score 1.0).
    """
    n, m, p = DIMENSIONS
    rank = n * m * p
    
    # Initialize matrices with zeros
    U = np.zeros((n * m, rank), dtype=float)
    V = np.zeros((m * p, rank), dtype=float)
    W = np.zeros((p * n, rank), dtype=float)
    
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                # U index: i*m + j
                # V index: j*p + k
                # W index: k*n + i
                U[i * m + j, col] = 1.0
                V[j * p + k, col] = 1.0
                W[k * n + i, col] = 1.0
                col += 1
                
    # Convert to lists of floats as required by the interface
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
