import random

def construct():
    """
    Construct a binary error-correcting code of length 18 and minimum distance 6.
    
    We aim to maximize the number of codewords. 
    A punctured Reed-Muller code RM(2, 5) can potentially provide 2^16 = 65536 words
    of length 18 with distance at least 6, if we choose the punctured coordinates wisely.
    RM(2, 5) has length 32, dimension 16, and minimum distance 8.
    We need to remove 14 coordinates such that no codeword of weight 8 has more than 2 ones
    in the removed positions (so that 8-2=6 remains).
    """
    N = 18
    MIN_DIST = 6
    
    # Generate RM(2, 5) codewords
    # RM(2, 5) is generated by polynomials of degree <= 2 in 5 variables over F_2.
    # There are 1 (const) + 5 (linear) + 10 (quadratic) = 16 basis polynomials.
    # We represent the 32 points as 5-bit integers 0..31.
    
    # Basis indices:
    # 0: 1
    # 1-5: x_i
    # 6-15: x_i x_j for i < j
    
    def eval_poly(p, point):
        # p is a 16-bit mask indicating which basis functions are present
        # point is a 5-bit integer
        if p & 1:
            val = 1
        else:
            val = 0
        
        # Linear terms
        for i in range(5):
            if p & (1 << (1 + i)):
                if (point >> i) & 1:
                    val ^= 1
        
        # Quadratic terms
        # Map index 6..15 to pairs (i, j)
        pairs = []
        for i in range(5):
            for j in range(i+1, 5):
                pairs.append((i, j))
        for k, (i, j) in enumerate(pairs):
            if p & (1 << (6 + k)):
                if ((point >> i) & 1) and ((point >> j) & 1):
                    val ^= 1
        return val

    # Generate all 65536 codewords
    # codeword[p] is a 32-bit integer
    codewords = [0] * 65536
    for p in range(65536):
        w = 0
        for point in range(32):
            if eval_poly(p, point):
                w |= (1 << point)
        codewords[p] = w

    # Find weight-8 words
    weight8_words = []
    for w in codewords:
        if w.bit_count() == 8:
            weight8_words.append(w)
    
    # We need to choose 14 coordinates to remove.
    # Let R be the set of removed coordinates (size 14).
    # Constraint: For all w in weight8_words, popcount(w & mask_R) <= 2.
    
    # Greedy selection of coordinates to remove
    # We want to pick 14 coordinates.
    # Start with R = empty.
    # Actually, it's easier to pick 18 coordinates to KEEP.
    # Let K be the set of kept coordinates (size 18).
    # Constraint: For all w in weight8_words, popcount(w & ~mask_K) <= 2.
    # This is equivalent to: For all w in weight8_words, popcount(w) - popcount(w & mask_K) <= 2.
    # Since popcount(w) = 8, this means popcount(w & mask_K) >= 6.
    
    # So we need to choose 18 coordinates K such that every weight-8 word has at least 6 ones in K.
    
    # Greedy approach:
    # Start with all 32 coordinates.
    # Iteratively remove a coordinate that is "least used" by weight-8 words?
    # Or: Start with K = all 32.
    # While len(K) > 18:
    #   Find a coordinate c in K such that removing it doesn't violate the constraint for any w.
    #   Constraint violation if there exists w such that popcount(w & K) == 6 and w has 1 at c.
    #   If we remove c, popcount(w & K_new) becomes 5, which is < 6. Violation.
    #   So we can only remove c if no weight-8 word has exactly 6 ones in K and a 1 at c.
    
    K = set(range(32))
    mask_K = 0
    for c in K:
        mask_K |= (1 << c)
        
    # Precompute for each coordinate c, the list of weight-8 words that have 1 at c
    # And for each w, its current count in K.
    
    # This greedy might get stuck.
    # Let's try a random restart approach.
    
    best_code = None
    best_count = 0
    
    for attempt in range(100):
        K = set(range(32))
        # Shuffle order of removal
        coords_to_try = list(K)
        random.shuffle(coords_to_try)
        
        success = True
        for c in coords_to_try:
            if len(K) <= 18:
                break
            # Check if we can remove c
            can_remove = True
            # We need to check all weight-8 words
            # If any w has popcount(w & K) == 6 and (w & (1<<c)), then removing c drops it to 5.
            # Actually, if popcount(w & K) > 6, removing c makes it >= 6, so it's safe.
            # If popcount(w & K) == 6 and w has 1 at c, removing c makes it 5. Unsafe.
            # If popcount(w & K) < 6, it's already unsafe? No, we maintain invariant that all w have >= 6 in K.
            
            # Optimization: Precompute counts?
            # For now, just check.
            for w in weight8_words:
                # Count ones in K
                # Since K is a set, w & mask_K is fast?
                # Let's maintain mask_K
                if len(K) > 18:
                    # Check if removing c is safe
                    # w must have at least 6 ones in K \ {c}
                    # i.e., popcount(w & (mask_K ^ (1<<c))) >= 6
                    # Since w has 8 ones total, and currently popcount(w & mask_K) >= 6.
                    # If w has 1 at c, new count is old count - 1.
                    # If old count == 6 and w has 1 at c, new count == 5. Bad.
                    # If old count > 6, new count >= 6. Good.
                    # If w has 0 at c, new count == old count >= 6. Good.
                    
                    # So we only fail if there exists w such that:
                    # 1. w has 1 at c
                    # 2. popcount(w & mask_K) == 6
                    
                    # We can check this quickly.
                    if (w & (1 << c)) and ((w & mask_K).bit_count() == 6):
                        can_remove = False
                        break
            
            if can_remove:
                K.remove(c)
                mask_K ^= (1 << c)
            else:
                # Try next coordinate
                pass
        
        if len(K) == 18:
            # Verify the code
            # Generate the 18-bit codewords
            # Project all 65536 words to K
            # Check min distance
            # If min dist >= 6, we have a valid code of size 65536
            
            # To be safe, verify a subset or all?
            # 65536^2 is too big.
            # But it's a linear code. We just need to check the weight of non-zero codewords.
            # Min weight of the punctured code is the min of popcount(w & mask_K) for w != 0.
            
            min_w = 32
            for w in codewords:
                if w == 0:
                    continue
                wt = (w & mask_K).bit_count()
                if wt < min_w:
                    min_w = wt
                if min_w < MIN_DIST:
                    break
            
            if min_w >= MIN_DIST:
                # Construct the list of 18-bit integers
                # We need to map the 32-bit words to 18-bit integers based on K.
                # Let's map the kept coordinates to 0..17 in sorted order.
                sorted_K = sorted(K)
                mapping = {old: new for new, old in enumerate(sorted_K)}
                
                final_words = []
                for w in codewords:
                    new_w = 0
                    for old, new in mapping.items():
                        if (w >> old) & 1:
                            new_w |= (1 << new)
                    final_words.append(new_w)
                
                # Check distinctness (should be distinct if linear and full rank)
                if len(set(final_words)) == len(final_words):
                    return final_words
                else:
                    # Should not happen for linear code
                    pass
    
    # Fallback: Greedy search for 512 words
    # Use the 32 RM(1,4) words as seed
    words = [0]
    rm_words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            rm_words.append(word)
            
    for w in rm_words:
        if w == 0:
            continue
        ok = True
        for existing in words:
            if (w ^ existing).bit_count() < MIN_DIST:
                ok = False
                break
        if ok:
            words.append(w)
            
    random.seed(42)
    candidates = list(range(1, 2**18))
    random.shuffle(candidates)
    
    added = True
    while added and len(words) < 512:
        added = False
        for cand in candidates:
            if len(words) >= 512:
                break
            ok = True
            for existing in words:
                if (cand ^ existing).bit_count() < MIN_DIST:
                    ok = False
                    break
            if ok:
                words.append(cand)
                added = True
                
    return words
