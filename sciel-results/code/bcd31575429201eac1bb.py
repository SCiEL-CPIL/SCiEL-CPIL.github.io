import numpy as np
import time

DIMENSIONS = [2, 3, 4]

def construct():
    n, m, p = DIMENSIONS
    
    # Rank 22 decomposition
    rank = 22
    # U shape: (n*m, rank) = (6, 22)
    # V shape: (m*p, rank) = (12, 22)
    # W shape: (p*n, rank) = (8, 22)
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    def add_term(u_indices, v_indices, w_indices, col):
        for idx, val in u_indices:
            U[idx][col] += val
        for idx, val in v_indices:
            V[idx][col] += val
        for idx, val in w_indices:
            W[idx][col] += val
            
    # Indices for A (2x3):
    # 0: A[0,0], 1: A[0,1], 2: A[0,2]
    # 3: A[1,0], 4: A[1,1], 5: A[1,2]
    
    # Indices for B (3x4):
    # 0: B[0,0], 1: B[0,1], 2: B[0,2], 3: B[0,3]
    # 4: B[1,0], 5: B[1,1], 6: B[1,2], 7: B[1,3]
    # 8: B[2,0], 9: B[2,1], 10: B[2,2], 11: B[2,3]
    
    # Indices for C (2x4) in W (p*n = 4*2 = 8, trace convention W[k*n+i]):
    # C[0,0] -> k=0, i=0 -> 0
    # C[0,1] -> k=1, i=0 -> 2
    # C[0,2] -> k=2, i=0 -> 4
    # C[0,3] -> k=3, i=0 -> 6
    # C[1,0] -> k=0, i=1 -> 1
    # C[1,1] -> k=1, i=1 -> 3
    # C[1,2] -> k=2, i=1 -> 5
    # C[1,3] -> k=3, i=1 -> 7
    
    # Block 1: Strassen for A[0:2, 0:2] * B[0:2, 0:2]
    # A: 0,1,3,4. B: 0,1,4,5.
    # C: 0,2,1,3.
    
    # M1: (A00+A11)(B00+B11) -> C00+C11
    add_term([(0, 1), (4, 1)], [(0, 1), (5, 1)], [(0, 1), (3, 1)], 0)
    # M2: (A10+A11)B00 -> C10-C11
    add_term([(3, 1), (4, 1)], [(0, 1)], [(1, 1), (3, -1)], 1)
    # M3: A00(B01-B11) -> C01+C11
    add_term([(0, 1)], [(1, 1), (5, -1)], [(2, 1), (3, 1)], 2)
    # M4: A11(B10-B00) -> C00+C10
    add_term([(4, 1)], [(4, 1), (0, -1)], [(0, 1), (1, 1)], 3)
    # M5: (A00+A01)B11 -> -C00+C01
    add_term([(0, 1), (1, 1)], [(5, 1)], [(0, -1), (2, 1)], 4)
    # M6: (A10-A00)(B00+B01) -> C11
    add_term([(3, 1), (0, -1)], [(0, 1), (1, 1)], [(3, 1)], 5)
    # M7: (A01-A11)(B10+B11) -> C00
    add_term([(1, 1), (4, -1)], [(4, 1), (5, 1)], [(0, 1)], 6)

    # Block 2: Strassen for A[0:2, 0:2] * B[0:2, 2:4]
    # B: 2,3,6,7.
    # C: 4,6,5,7.
    
    # M1': (A00+A11)(B02+B13) -> C02+C13
    add_term([(0, 1), (4, 1)], [(2, 1), (7, 1)], [(4, 1), (7, 1)], 7)
    # M2': (A10+A11)B02 -> C12-C13
    add_term([(3, 1), (4, 1)], [(2, 1)], [(5, 1), (7, -1)], 8)
    # M3': A00(B03-B13) -> C03+C13
    add_term([(0, 1)], [(3, 1), (7, -1)], [(6, 1), (7, 1)], 9)
    # M4': A11(B12-B02) -> C02+C12
    add_term([(4, 1)], [(6, 1), (2, -1)], [(4, 1), (5, 1)], 10)
    # M5': (A00+A01)B13 -> -C02+C03
    add_term([(0, 1), (1, 1)], [(7, 1)], [(4, -1), (6, 1)], 11)
    # M6': (A10-A00)(B02+B03) -> C13
    add_term([(3, 1), (0, -1)], [(2, 1), (3, 1)], [(7, 1)], 12)
    # M7': (A01-A11)(B12+B13) -> C02
    add_term([(1, 1), (4, -1)], [(6, 1), (7, 1)], [(4, 1)], 13)

    # Block 3: Outer Product for A[0:2, 2:3] * B[2:3, 0:4]
    # A: 2, 5. B: 8, 9, 10, 11.
    # C: 
    # i=0 (A[0,2]=2): C[0,0]=0, C[0,1]=2, C[0,2]=4, C[0,3]=6
    # i=1 (A[1,2]=5): C[1,0]=1, C[1,1]=3, C[1,2]=5, C[1,3]=7
    
    add_term([(2, 1)], [(8, 1)], [(0, 1)], 14)
    add_term([(2, 1)], [(9, 1)], [(2, 1)], 15)
    add_term([(2, 1)], [(10, 1)], [(4, 1)], 16)
    add_term([(2, 1)], [(11, 1)], [(6, 1)], 17)
    
    add_term([(5, 1)], [(8, 1)], [(1, 1)], 18)
    add_term([(5, 1)], [(9, 1)], [(3, 1)], 19)
    add_term([(5, 1)], [(10, 1)], [(5, 1)], 20)
    add_term([(5, 1)], [(11, 1)], [(7, 1)], 21)

    return {"U": U, "V": V, "W": W}
