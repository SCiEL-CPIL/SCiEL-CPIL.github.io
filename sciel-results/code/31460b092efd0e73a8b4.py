import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = 120.0
    safety_margin = 5.0
    
    # Fallback 32-vertex coloring (Clebsch graph related or similar)
    def build_32():
        # This is a known valid 32-vertex coloring
        # We can just return a hardcoded list if we don't want to risk bugs in the generator
        # But let's try to generate it or use a simple one.
        # Actually, the 32-vertex one from the seed was:
        # Based on GF(32) or similar? 
        # Let's just use a random local search on 32 vertices as a last resort fallback.
        # Or better, just return n=32 with a valid coloring generated by a simple heuristic.
        
        # For now, we will rely on the 49-vertex construction being correct.
        # If we need a fallback, we can generate a random 32-vertex coloring and fix it.
        n = 32
        matrix = np.zeros((n, n), dtype=np.int8)
        for i in range(n):
            for j in range(i+1, n):
                matrix[i, j] = random.randint(0, 3)
                matrix[j, i] = matrix[i, j]
        
        # Local search to remove triangles
        def count_mono_triangles(matrix, n):
            count = 0
            for c in range(4):
                adj = (matrix == c).astype(np.int8)
                np.fill_diagonal(adj, 0)
                a3 = adj @ adj @ adj
                count += int(np.trace(a3)) // 6
            return count
            
        best_count = count_mono_triangles(matrix, n)
        for _ in range(1000):
            i = random.randint(0, n-1)
            j = random.randint(0, n-1)
            if i == j: continue
            if i > j: i, j = j, i
            old_c = int(matrix[i, j])
            new_c = random.randint(0, 3)
            if old_c == new_c: continue
            
            # Delta calculation
            row_i = matrix[i]
            row_j = matrix[j]
            mask_i_old = (row_i == old_c).astype(np.int8)
            mask_j_old = (row_j == old_c).astype(np.int8)
            mask_i_old[i] = 0; mask_i_old[j] = 0
            mask_j_old[i] = 0; mask_j_old[j] = 0
            old_tri = int(np.sum(mask_i_old * mask_j_old))
            
            mask_i_new = (row_i == new_c).astype(np.int8)
            mask_j_new = (row_j == new_c).astype(np.int8)
            mask_i_new[i] = 0; mask_i_new[j] = 0
            mask_j_new[i] = 0; mask_j_new[j] = 0
            new_tri = int(np.sum(mask_i_new * mask_j_new))
            
            if new_tri < old_tri:
                matrix[i, j] = new_c
                matrix[j, i] = new_c
                best_count += new_tri - old_tri
                if best_count == 0:
                    break
                    
        if best_count == 0:
            colors = []
            for i in range(n):
                for j in range(i+1, n):
                    colors.append(int(matrix[i, j]))
            return {'n': n, 'colors': colors}
        else:
            # If local search fails, return n=1 trivially? No, we need max n.
            # But 32 is easy. Let's assume the 49-vertex path works.
            # For safety, return a small valid one.
            return {'n': 1, 'colors': []}

    # --- Main Construction: 49 vertices using GF(49) ---
    
    # GF(49) = GF(7^2) with x^2 - 3 = 0 (since 3 is not a square mod 7)
    # Elements: (a, b) representing a + b*omega
    # Add: (a1+b1*o, a2+b2*o) -> (a1+a2, b1+b2) mod 7
    # Mul: (a1+b1*o)*(a2+b2*o) = a1a2 + 3b1b2 + (a1b2 + a2b1)o
    
    def gf49_add(p, q):
        return ((p[0] + q[0]) % 7, (p[1] + q[1]) % 7)
        
    def gf49_sub(p, q):
        return ((p[0] - q[0]) % 7, (p[1] - q[1]) % 7)
        
    def gf49_mul(p, q):
        a1, b1 = p
        a2, b2 = q
        return ((a1*a2 + 3*b1*b2) % 7, (a1*b2 + a2*b1) % 7)
        
    # Find primitive element
    # Order of GF(49)* is 48.
    # We need an element of order 48.
    # Try (0, 1) which is omega. omega^2 = 3.
    # Let's just iterate to find one.
    
    elements = [(a, b) for a in range(7) for b in range(7)]
    
    def gf49_order(p):
        if p == (0, 0):
            return 0
        result = (1, 0)
        for i in range(1, 49):
            result = gf49_mul(result, p)
            if result == (1, 0):
                return i
        return -1
        
    primitive = None
    for elem in elements:
        if elem == (0, 0):
            continue
        if gf49_order(elem) == 48:
            primitive = elem
            break
            
    if primitive is None:
        # Should not happen
        return build_32()
        
    # Generate powers of primitive
    powers = []
    current = (1, 0)
    for i in range(48):
        powers.append(current)
        current = gf49_mul(current, primitive)
        
    # Subgroup H of order 12: {g^0, g^4, ..., g^44}
    # Cosets: C_k = { g^(k + 4*m) for m in 0..11 }
    
    coset_id = {}
    for k in range(4):
        for m in range(12):
            idx = (k + 4*m) % 48
            elem = powers[idx]
            coset_id[elem] = k
            
    # Build 49x49 color matrix
    n49 = 49
    color_matrix = np.zeros((n49, n49), dtype=np.int8)
    
    for i in range(n49):
        for j in range(i + 1, n49):
            diff = gf49_sub(elements[i], elements[j])
            if diff == (0, 0):
                color_matrix[i, j] = 0 # Should not happen for i!=j
            else:
                c = coset_id[diff]
                color_matrix[i, j] = c
                color_matrix[j, i] = c
                
    # Verify 49-vertex coloring
    def is_valid(matrix, n):
        for i in range(n):
            for j in range(i + 1, n):
                for k in range(j + 1, n):
                    if matrix[i, j] == matrix[i, k] == matrix[j, k]:
                        return False
        return True
        
    if not is_valid(color_matrix, n49):
        # Fallback if algebraic construction fails
        return build_32()
        
    # Try to add 50th vertex
    n50 = 50
    full_matrix = np.zeros((n50, n50), dtype=np.int8)
    full_matrix[:49, :49] = color_matrix
    
    # Backtracking for vertex 49 (index 49)
    # We need to assign colors to (49, 0) ... (49, 48)
    
    assignment = [-1] * 49
    
    def backtrack(idx):
        if time.time() - start_time > deadline - safety_margin:
            return False
        if idx == 49:
            return True
            
        # Heuristic: Try colors that minimize conflicts
        # For color c, the number of conflicts with vertex idx is:
        # count of j < idx such that assignment[j] == c and color_matrix[idx, j] == c
        
        # We can just try 0, 1, 2, 3
        for c in range(4):
            valid = True
            for j in range(idx):
                if assignment[j] == c and color_matrix[idx, j] == c:
                    valid = False
                    break
            if valid:
                assignment[idx] = c
                if backtrack(idx + 1):
                    return True
                assignment[idx] = -1
        return False
        
    if backtrack(0):
        for i in range(49):
            full_matrix[49, i] = assignment[i]
            full_matrix[i, 49] = assignment[i]
            
        if is_valid(full_matrix, n50):
            colors = []
            for i in range(n50):
                for j in range(i + 1, n50):
                    colors.append(int(full_matrix[i, j]))
            return {'n': n50, 'colors': colors}
            
    # If 50 failed, return 49
    colors = []
    for i in range(n49):
        for j in range(i + 1, n49):
            colors.append(int(color_matrix[i, j]))
    return {'n': n49, 'colors': colors}
