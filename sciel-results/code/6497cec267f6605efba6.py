import numpy as np
import time
from scipy.optimize import minimize

class Optimizer:
    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 280  # Safety margin for 300s limit
        
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        range_vec = hi - lo
        
        ref_point = np.array([1705.0, 12.0, 0.3])
        
        n_sub = 25  # Number of subproblems (weight vectors)
        evals = 0
        
        # Generate weight vectors using Das-Dennis method for 3 objectives
        def generate_weights(n_obj, n_sub):
            weights = []
            if n_obj == 1:
                weights.append([1.0])
            elif n_obj == 2:
                for i in range(n_sub):
                    w1 = i / (n_sub - 1)
                    w2 = 1 - w1
                    weights.append([w1, w2])
            else:
                # For 3 objectives, use a grid
                # Sum of combinations: n1 + n2 + n3 = n_sub - 2 (if we allow 0)
                # Actually, let's just generate points on the simplex.
                # A simple way is to iterate i, j and set k = 1 - i - j
                # But we need exactly n_sub points.
                # Let's use a stratified sampling or just pick specific points.
                # For simplicity and coverage, let's use a deterministic set.
                # If n_sub is not perfect, we can just take the first n_sub from a larger grid.
                pass
            
            # Let's implement a simple Das-Dennis for 3D
            # Number of points in Das-Dennis for M objectives and H divisions is C(H+M-1, M-1)
            # We want ~n_sub points.
            # Let's just generate a grid of size G x G x G that sums to 1? No, that's expensive.
            # Let's use the approach: iterate over i, j in range(H+1) such that i+j <= H.
            # k = H - i - j.
            # Total points = (H+1)(H+2)/2.
            # We want this to be close to n_sub.
            # Solve (H+1)(H+2)/2 ≈ n_sub.
            # For n_sub=25, H=5 gives 21 points. H=6 gives 28 points.
            # Let's pick H such that points >= n_sub, then take the first n_sub or sample.
            # Actually, for MOEA/D, we need a specific number of weight vectors.
            # Let's just generate a fixed set of 25 weight vectors.
            
            # A simple deterministic set for 3D:
            # 1 corner (1,0,0), 1 corner (0,1,0), 1 corner (0,0,1)
            # 3 edge midpoints (0.5, 0.5, 0), etc.
            # This is tedious. Let's use a random but fixed set with good spread.
            
            # Better: Use a simple grid.
            # Let's divide the simplex into triangles.
            # For now, let's just use a set of points generated by:
            # i from 0 to H, j from 0 to H-i
            # w = [i/H, j/H, (H-i-j)/H]
            # We will generate H=6 (28 points) and randomly select 25?
            # Or just use H=5 (21 points) and add 4 more?
            
            # Let's stick to a robust method:
            # Generate all integer combinations of 3 parts summing to H.
            # Then normalize by H.
            # If count > n_sub, we can subsample.
            # If count < n_sub, we can increase H.
            
            H = 5
            while True:
                pts = []
                for i in range(H + 1):
                    for j in range(H - i + 1):
                        k = H - i - j
                        pts.append([i/H, j/H, k/H])
                if len(pts) >= n_sub:
                    # If we have more, we can just take the first n_sub?
                    # Or better, use all if close, or resample.
                    # For now, let's just use the first n_sub.
                    # But we want uniform coverage.
                    # Let's just use the generated list. If len > n_sub, we can't easily reduce without bias.
                    # Let's adjust H to get exactly or closest.
                    # H=5 -> 21. H=6 -> 28.
                    # Let's use H=5 (21 subproblems) for simplicity and speed.
                    # 21 * 5 evals = 105 evals. Plus 15 LHS. Total 120. Leaves 80 for polish.
                    return np.array(pts[:n_sub]) if len(pts) > n_sub else np.array(pts)
                H += 1

        weights = generate_weights(3, n_sub)
        
        # Initialize population with LHS for diversity
        pop_size = 20
        rng = np.random.default_rng(42)
        X = np.zeros((pop_size, self.dim))
        for d in range(self.dim):
            intervals = np.linspace(lo[d], hi[d], pop_size + 1)
            for i in range(pop_size):
                X[i, d] = rng.uniform(intervals[i], intervals[i+1])
        
        F = np.array([problem(x) for x in X])
        evals += pop_size
        
        # Assign each subproblem an initial solution from the population
        # We'll just use the population and try to improve each weight vector's solution.
        
        # MOEA/D Loop
        # For each weight vector, we run a local search.
        # We need to be careful with the budget.
        
        # Let's do 2 rounds of MOEA/D.
        # Round 1: 3 evals per subproblem.
        # Round 2: 3 evals per subproblem.
        
        # Store best solution per weight vector
        best_x = np.copy(X[:n_sub]) # Take first n_sub points
        best_f = np.copy(F[:n_sub])
        
        # If pop_size < n_sub, we need to handle that.
        # pop_size is 20, n_sub is 21. So we can't take first 21.
        # Let's set n_sub = 20 to match pop_size for simplicity.
        n_sub = 20
        weights = generate_weights(3, n_sub)
        best_x = np.copy(X)
        best_f = np.copy(F)
        
        for round_idx in range(2):
            for k in range(n_sub):
                if evals >= self.budget: break
                if time.time() > deadline: break
                
                w = weights[k]
                x0 = best_x[k]
                
                # Define scalarized objective
                def scalarized(x, w=w):
                    nonlocal evals
                    if evals >= self.budget:
                        return 1e10
                    if time.time() > deadline:
                        return 1e10
                    f = problem(x)
                    evals += 1
                    return np.dot(w, f)
                
                try:
                    res = minimize(
                        scalarized, x0,
                        method='L-BFGS-B',
                        bounds=list(zip(lo, hi)),
                        options={'maxiter': 10, 'maxfun': 5}
                    )
                    
                    # Evaluate the result to get the vector
                    if evals < self.budget and time.time() < deadline:
                        new_f = problem(res.x)
                        evals += 1
                        
                        # Update best if it's better in terms of scalarized value
                        # Or if it dominates the current best?
                        # MOEA/D usually updates if the scalarized value is better.
                        if np.dot(w, new_f) < np.dot(w, best_f[k]):
                            best_x[k] = res.x
                            best_f[k] = new_f
                            
                            # Optional: Update neighbors?
                            # For simplicity, we just keep the best per weight.
                            
                except Exception:
                    pass
                    
        # Final Polish
        # Use remaining budget to polish the non-dominated points found.
        # First, identify non-dominated points in best_f
        nd_idx = []
        for i in range(n_sub):
            is_dom = False
            for j in range(n_sub):
                if i == j: continue
                if np.all(best_f[j] <= best_f[i]) and np.any(best_f[j] < best_f[i]):
                    is_dom = True
                    break
            if not is_dom:
                nd_idx.append(i)
        
        # Sort by sum
        nd_idx.sort(key=lambda i: np.sum(best_f[i]))
        
        # Polish top 10
        for idx in nd_idx[:10]:
            if evals >= self.budget: break
            if time.time() > deadline: break
            
            x0 = best_x[idx]
            
            def scalarized_sum(x):
                nonlocal evals
                if evals >= self.budget:
                    return 1e10
                if time.time() > deadline:
                    return 1e10
                f = problem(x)
                evals += 1
                return np.sum(f)
            
            try:
                res = minimize(
                    scalarized_sum, x0,
                    method='L-BFGS-B',
                    bounds=list(zip(lo, hi)),
                    options={'maxiter': 10, 'maxfun': 5}
                )
                
                if evals < self.budget and time.time() < deadline:
                    new_f = problem(res.x)
                    evals += 1
                    if np.all(new_f <= best_f[idx]) or np.sum(new_f) < np.sum(best_f[idx]):
                        best_x[idx] = res.x
                        best_f[idx] = new_f
                        
            except Exception:
                pass
                
        # Return the best_x (or X, doesn't matter, return value is ignored)
        return best_x

