    add_term([(7, 1)], [(20, 1), (8, -1)], [(4, 1), (5, 1)])

    # Term 5: (A11 + A12)B22
    # X0 = A00 + A02 (0, 2)
    # X1 = A01 + A03 (1, 3)
    # Y00 = B23 (15)
    # Y01 = B24 (16)
    # Y02 = B25 (17)
