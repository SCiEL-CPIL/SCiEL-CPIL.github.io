    # 1.5: X0 * Y02 -> P2
    add_term([(0, 1), (6, 1)], [(2, 1), (17, 1)], [(4, 1), (11, 1)])
    # 1.6: X1 * Y12 -> P2
    add_term([(1, 1), (7, 1)], [(8, 1), (23, 1)], [(4, 1), (11, 1)])

    # Term 2: (A21 + A22)B11
    # X0 = A10 + A12 (idx 4, 6)
    # X1 = A11 + A13 (idx 5, 7)
    # Y00 = B00 (0)
    # Y01 = B01 (1)
    # Y02 = B02 (2)
    # Y10 = B10 (6)
    # Y11 = B11 (7)
    # Y12 = B12 (8)
    # P0 -> C10 (1)
    # P1 -> C11 (3)
    # P2 -> C12 (5)
    
    # 2.1: X0 * Y00 -> P0
    add_term([(4, 1), (6, 1)], [(0, 1)], [(1, 1)])
    # 2.2: X1 * Y10 -> P0
    add_term([(5, 1), (7, 1)], [(6, 1)], [(1, 1)])
    # 2.3: X0 * Y01 -> P1
    add_term([(4, 1), (6, 1)], [(1, 1)], [(3, 1)])
    # 2.4: X1 * Y11 -> P1
    add_term([(5, 1), (7, 1)], [(7, 1)], [(3, 1)])
    # 2.5: X0 * Y02 -> P2
    add_term([(4, 1), (6, 1)], [(2, 1)], [(5, 1)])
