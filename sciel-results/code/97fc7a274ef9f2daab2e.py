    # B[2,0]=12, B[2,1]=13, B[2,2]=14, B[2,3]=15, B[2,4]=16, B[2,5]=17
    # B[3,0]=18, B[3,1]=19, B[3,2]=20, B[3,3]=21, B[3,4]=22, B[3,5]=23
    
    # Indices for C (2x6) -> W index k*n + i
    # C[0,0]=0, C[0,1]=2, C[0,2]=4, C[0,3]=6, C[0,4]=8, C[0,5]=10
    # C[1,0]=1, C[1,1]=3, C[1,2]=5, C[1,3]=7, C[1,4]=9, C[1,5]=11

    rank = 42
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    # Helper to add a rank-1 term
    # a_terms: list of (idx, coeff) for U
    # b_terms: list of (idx, coeff) for V
    # c_terms: list of (idx, coeff) for W
    def add_term(a_terms, b_terms, c_terms):
        nonlocal col
        for idx, coeff in a_terms:
            U[idx][col] = coeff
        for idx, coeff in b_terms:
            V[idx][col] = coeff
        for idx, coeff in c_terms:
            W[idx][col] = coeff
        col += 1

    # Define the 7 Strassen terms
    # Each term defines X (1x2), Y (2x3) and how P (1x3) maps to C
    
    # Term 1: (A11 + A22)(B11 + B22)
    # X0 = A00 + A12 (idx 0, 6)
    # X1 = A01 + A13 (idx 1, 7)
    # Y00 = B00 + B23 (idx 0, 15)
    # Y01 = B01 + B24 (idx 1, 16)
    # Y02 = B02 + B25 (idx 2, 17)
    # Y10 = B10 + B33 (idx 6, 21)
    # Y11 = B11 + B34 (idx 7, 22)
    # Y12 = B12 + B35 (idx 8, 23)
    # P0 -> C00 (0), C13 (7)
    # P1 -> C01 (2), C14 (9)
    # P2 -> C02 (4), C15 (11)
    
    # 1.1: X0 * Y00 -> P0
    add_term([(0, 1), (6, 1)], [(0, 1), (15, 1)], [(0, 1), (7, 1)])
    # 1.2: X1 * Y10 -> P0
    add_term([(1, 1), (7, 1)], [(6, 1), (21, 1)], [(0, 1), (7, 1)])
