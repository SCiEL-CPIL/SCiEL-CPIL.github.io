    add_term([(0, 1), (2, 1)], [(15, 1)], [(0, 1), (7, 1)])
    # 5.2: X1 * Y10 -> P0
    add_term([(1, 1), (3, 1)], [(21, 1)], [(0, 1), (7, 1)])
    # 5.3: X0 * Y01 -> P1
    add_term([(0, 1), (2, 1)], [(16, 1)], [(2, 1), (9, 1)])
    # 5.4: X1 * Y11 -> P1
    add_term([(1, 1), (3, 1)], [(22, 1)], [(2, 1), (9, 1)])
    # 5.5: X0 * Y02 -> P2
    add_term([(0, 1), (2, 1)], [(17, 1)], [(4, 1), (11, 1)])
