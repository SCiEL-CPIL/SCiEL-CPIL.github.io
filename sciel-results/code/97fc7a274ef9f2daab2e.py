def construct():
    n, m, p = DIMENSIONS
    # U shape: (n*m, rank)
    # V shape: (m*p, rank)
    # W shape: (p*n, rank)
    
    # Strassen decomposition for 2x4 * 4x6
    # Partition A (2x4) into 2x2 blocks of size 1x2
    # Partition B (4x6) into 2x2 blocks of size 2x3
    # Partition C (2x6) into 2x2 blocks of size 1x3
    
    # Indices for A (2x4) -> flat index i*m + j
    # A[0,0]=0, A[0,1]=1, A[0,2]=2, A[0,3]=3
    # A[1,0]=4, A[1,1]=5, A[1,2]=6, A[1,3]=7
    
    # Indices for B (4x6) -> flat index j*p + k
    # B[0,0]=0, B[0,1]=1, B[0,2]=2, B[0,3]=3, B[0,4]=4, B[0,5]=5
