    add_term([(5, 1), (7, 1)], [(8, 1)], [(5, 1)])

    # Term 3: A11(B12 - B22)
    # X0 = A00 (0)
    # X1 = A01 (1)
    # Y00 = B03 - B23 (3, 15)
    # Y01 = B04 - B24 (4, 16)
    # Y02 = B05 - B25 (5, 17)
    # Y10 = B13 - B33 (9, 21)
    # Y11 = B14 - B34 (10, 22)
    # Y12 = B15 - B35 (11, 23)
    # P0 -> C03 (6)
    # P1 -> C04 (8)
    # P2 -> C05 (10)
    
    # 3.1: X0 * Y00 -> P0
    add_term([(0, 1)], [(3, 1), (15, -1)], [(6, 1)])
    # 3.2: X1 * Y10 -> P0
    add_term([(1, 1)], [(9, 1), (21, -1)], [(6, 1)])
    # 3.3: X0 * Y01 -> P1
    add_term([(0, 1)], [(4, 1), (16, -1)], [(8, 1)])
    # 3.4: X1 * Y11 -> P1
    add_term([(1, 1)], [(10, 1), (22, -1)], [(8, 1)])
    # 3.5: X0 * Y02 -> P2
    add_term([(0, 1)], [(5, 1), (17, -1)], [(10, 1)])
    # 3.6: X1 * Y12 -> P2
    add_term([(1, 1)], [(11, 1), (23, -1)], [(10, 1)])

    # Term 4: A22(B21 - B11)
    # X0 = A12 (6)
    # X1 = A13 (7)
    # Y00 = B20 - B00 (12, 0)
    # Y01 = B21 - B01 (13, 1)
