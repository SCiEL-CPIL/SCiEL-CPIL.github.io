import numpy as np
import time

def construct():
    n, m, p = 2, 3, 4
    
    rank = 22
    U = [[0] * rank for _ in range(n * m)]  # 6 x 22
    V = [[0] * rank for _ in range(m * p)]  # 12 x 22
    W = [[0] * rank for _ in range(p * n)]  # 8 x 22
    
    def add_term(u_indices, v_indices, w_indices, col):
        for idx, val in u_indices:
            U[idx][col] += val
        for idx, val in v_indices:
            V[idx][col] += val
        for idx, val in w_indices:
            W[idx][col] += val
    
    # Block 1: Strassen for A[0:2, 0:2] * B[0:2, 0:2]
    # U indices: 0=A00, 1=A01, 3=A10, 4=A11
    # V indices: 0=B00, 1=B01, 4=B10, 5=B11
    # W indices: 0=C00, 1=C10, 2=C01, 3=C11
    
    # M1 = (A00+A11)(B00+B11) -> C00+1, C11+1
    add_term([(0, 1), (4, 1)], [(0, 1), (5, 1)], [(0, 1), (3, 1)], 0)
    # M2 = (A10+A11)B00 -> C10+1, C11-1
    add_term([(3, 1), (4, 1)], [(0, 1)], [(1, 1), (3, -1)], 1)
    # M3 = A00(B01-B11) -> C01+1, C11+1
    add_term([(0, 1)], [(1, 1), (5, -1)], [(2, 1), (3, 1)], 2)
    # M4 = A11(B10-B00) -> C10+1, C00+1
    add_term([(4, 1)], [(4, 1), (0, -1)], [(1, 1), (0, 1)], 3)
    # M5 = (A00+A01)B11 -> C01+1, C00-1
    add_term([(0, 1), (1, 1)], [(5, 1)], [(2, 1), (0, -1)], 4)
    # M6 = (A10-A00)(B00+B01) -> C11-1
    add_term([(3, 1), (0, -1)], [(0, 1), (1, 1)], [(3, -1)], 5)
    # M7 = (A01-A11)(B10+B11) -> C00+1
    add_term([(1, 1), (4, -1)], [(4, 1), (5, 1)], [(0, 1)], 6)
    
    # Block 2: Strassen for A[0:2, 0:2] * B[0:2, 2:4]
    # V indices: 2=B02, 3=B03, 6=B12, 7=B13
    # W indices: 4=C02, 5=C12, 6=C03, 7=C13
    
    # M1' = (A00+A11)(B02+B13) -> C02+1, C13+1
    add_term([(0, 1), (4, 1)], [(2, 1), (7, 1)], [(4, 1), (7, 1)], 7)
    # M2' = (A10+A11)B02 -> C12+1, C13-1
    add_term([(3, 1), (4, 1)], [(2, 1)], [(5, 1), (7, -1)], 8)
    # M3' = A00(B03-B13) -> C03+1, C13+1
    add_term([(0, 1)], [(3, 1), (7, -1)], [(6, 1), (7, 1)], 9)
    # M4' = A11(B12-B02) -> C12+1, C02+1
    add_term([(4, 1)], [(6, 1), (2, -1)], [(5, 1), (4, 1)], 10)
    # M5' = (A00+A01)B13 -> C03+1, C02-1
    add_term([(0, 1), (1, 1)], [(7, 1)], [(6, 1), (4, -1)], 11)
    # M6' = (A10-A00)(B02+B03) -> C13-1
    add_term([(3, 1), (0, -1)], [(2, 1), (3, 1)], [(7, -1)], 12)
    # M7' = (A01-A11)(B12+B13) -> C02+1
    add_term([(1, 1), (4, -1)], [(6, 1), (7, 1)], [(4, 1)], 13)
    
    # Block 3: Outer product A[0:2, 2:3] * B[2:3, 0:4]
    # U indices: 2=A02, 5=A12
    # V indices: 8=B20, 9=B21, 10=B22, 11=B23
    # W indices: 0=C00, 2=C01, 4=C02, 6=C03 (for row 0)
    #            1=C10, 3=C11, 5=C12, 7=C13 (for row 1)
    
    add_term([(2, 1)], [(8, 1)], [(0, 1)], 14)
    add_term([(2, 1)], [(9, 1)], [(2, 1)], 15)
    add_term([(2, 1)], [(10, 1)], [(4, 1)], 16)
    add_term([(2, 1)], [(11, 1)], [(6, 1)], 17)
    add_term([(5, 1)], [(8, 1)], [(1, 1)], 18)
    add_term([(5, 1)], [(9, 1)], [(3, 1)], 19)
    add_term([(5, 1)], [(10, 1)], [(5, 1)], 20)
    add_term([(5, 1)], [(11, 1)], [(7, 1)], 21)
    
    return {"U": U, "V": V, "W": W}
