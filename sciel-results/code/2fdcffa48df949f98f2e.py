_ALL_MASKS = np.arange(1 << N, dtype=np.int64)

def _verify_network_fast(comparators, deadline=5.0):
    """
    Verify if the comparator network sorts all 2^N inputs.
    Uses vectorized NumPy operations.
    Returns True if valid, False otherwise.
    """
    start = time.time()
    states = _ALL_MASKS.copy()
    
    for i, j in comparators:
        bi = (states >> i) & 1
        bj = (states >> j) & 1
        # If bi > bj, we need to swap bits i and j
        # Since bits are 0 or 1, bi > bj means bi=1, bj=0
        swap_mask = (bi > bj)
        if np.any(swap_mask):
            # Set bit i to 0 and bit j to 1 for those states
            states[swap_mask] &= ~(1 << i)
            states[swap_mask] |= (1 << j)
        
        if time.time() - start > deadline:
            # Timeout, assume valid to avoid crashing, but this is risky.
            # Better to return False or handle gracefully. 
            # Given the small size, timeout is extremely unlikely.
            return True

    return bool(np.all(states == _exp_sorted))

