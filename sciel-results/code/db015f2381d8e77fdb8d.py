"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
DIMENSIONS = [4, 4, 4]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 49
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Laderman's algorithm for 4x4 matrix multiplication
    # It uses 49 scalar multiplications.
    # The algorithm is defined by 49 triples (u, v, w) of 4x4 matrices
    # such that sum_{r=1}^{49} U_r V_r W_r = C.
    # We define the coefficients explicitly.
    
    # The 49 terms are generated by the tensor product of two Strassen decompositions
    # for the 2x2 block structure.
    # Outer Strassen (7 terms) and Inner Strassen (7 terms).
    
    # Strassen 2x2 coefficients for A (input 1)
    # A is 4x4, viewed as 2x2 blocks of 2x2 matrices.
    # Block indices p, q in {0, 1}.
    # Inner indices u, v in {0, 1}.
    # A_{pq} is a 2x2 matrix.
    # We form 7 linear combinations of the 4 blocks A_{00}, A_{01}, A_{10}, A_{11}.
    # Each combination is a 4x4 matrix formed by placing the 2x2 linear combos in the blocks.
    
    # Let's define the 7 outer combinations (coefficients for blocks)
    # and the 7 inner combinations (coefficients for elements within blocks).
    
    # Outer coefficients (for blocks A_pq)
    # k = 0..6
    # alpha[k][p][q]
    alpha = [
        [[1, 0], [0, 1]], # 1: A00 + A11
        [[0, 0], [1, 1]], # 2: A10 + A11
        [[1, 0], [0, 0]], # 3: A00
        [[0, 0], [0, 1]], # 4: A11
        [[1, 1], [0, 0]], # 5: A00 + A01
        [[-1, 0], [1, 0]],# 6: A10 - A00
        [[0, 1], [0, -1]] # 7: A01 - A11
    ]
    
    # Inner coefficients (for elements within a 2x2 block)
    # u, v = 0..1
    # U2[m][u][v]
    U2 = [
        [[1, 0], [0, 1]], # 1: X00 + X11
        [[0, 0], [1, 1]], # 2: X10 + X11
        [[1, 0], [0, 0]], # 3: X00
        [[0, 0], [0, 1]], # 4: X11
        [[1, 1], [0, 0]], # 5: X00 + X01
        [[-1, 0], [1, 0]],# 6: X10 - X00
        [[0, 1], [0, -1]] # 7: X01 - X11
    ]
    
    # Outer coefficients for B
    beta = [
        [[1, 0], [0, 1]], # 1: B00 + B11
        [[1, 0], [0, 0]], # 2: B00
        [[0, 1], [0, -1]],# 3: B01 - B11
        [[-1, 0], [1, 0]],# 4: B10 - B00
        [[0, 0], [0, 1]], # 5: B11
        [[1, 1], [0, 0]], # 6: B00 + B01
        [[0, 0], [1, 1]]  # 7: B10 + B11
    ]
    
    # Inner coefficients for B
    V2 = [
        [[1, 0], [0, 1]], # 1: Y00 + Y11
        [[1, 0], [0, 0]], # 2: Y00
        [[0, 1], [0, -1]],# 3: Y01 - Y11
        [[-1, 0], [1, 0]],# 4: Y10 - Y00
        [[0, 0], [0, 1]], # 5: Y11
        [[1, 1], [0, 0]], # 6: Y00 + Y01
        [[0, 0], [1, 1]]  # 7: Y10 + Y11
    ]
    
    # Outer coefficients for C (reconstruction)
    # W1[k][p][q] where p, q are block indices of C.
    # C_pq = sum_k W1[k][p][q] M_k
    W1 = [
        [1, 0, 0, 1], # k=1: C00+=1, C11+=1
        [0, 0, 1, -1],# k=2: C10+=1, C11-=1
        [0, 1, 0, 1], # k=3: C01+=1, C11+=1
        [1, 0, 1, 0], # k=4: C00+=1, C10+=1
        [-1, 1, 0, 0],# k=5: C00-=1, C01+=1
        [0, 0, 0, 1], # k=6: C11+=1
        [1, 0, 0, 0]  # k=7: C00+=1
    ]
    
    # Inner coefficients for C
    # W2[m][u][v] where u, v are element indices within a block.
    W2 = [
        [1, 0, 0, 1], # m=1: Z00+=1, Z11+=1
        [0, 0, 1, -1],# m=2: Z10+=1, Z11-=1
        [0, 1, 0, 1], # m=3: Z01+=1, Z11+=1
        [1, 0, 1, 0], # m=4: Z00+=1, Z10+=1
        [-1, 1, 0, 0],# m=5: Z00-=1, Z01+=1
        [0, 0, 0, 1], # m=6: Z11+=1
        [1, 0, 0, 0]  # m=7: Z00+=1
    ]
    
    # Construct U, V, W
    for k in range(7):
        for m in range(7):
            r = k * 7 + m
            # U
            for i in range(4):
                for j in range(4):
                    p = i // 2
                    u = i % 2
                    q = j // 2
                    v = j % 2
                    coeff = alpha[k][p][q] * U2[m][u][v]
                    if coeff != 0:
                        U[i * 4 + j][r] += coeff
                        
            # V
            for j in range(4):
                for k_idx in range(4):
                    r_idx = j // 2
                    u = j % 2
                    s = k_idx // 2
                    v = k_idx % 2
                    coeff = beta[k][r_idx][s] * V2[m][u][v]
                    if coeff != 0:
                        V[j * 4 + k_idx][r] += coeff
                        
            # W
            for k_idx in range(4):
                for i in range(4):
                    q = k_idx // 2
                    v = k_idx % 2
                    p = i // 2
                    u = i % 2
                    # W1[k][p*2+q] corresponds to block (p,q) of C
                    # W2[m][u*2+v] corresponds to element (u,v) in that block
                    coeff = W1[k][p * 2 + q] * W2[m][u * 2 + v]
                    if coeff != 0:
                        W[k_idx * 4 + i][r] += coeff
                        
    return {"U": U, "V": V, "W": W}
# EVOLVE-BLOCK-END
