"""
First autocorrelation inequality: minimize normalized max of autoconvolution
for a nonnegative step function with 600 equal intervals on [-1/4, 1/4].

Strategy:
1. Reformulate the problem in the frequency domain.
   The peak of the autoconvolution is related to the L1 norm of the Fourier transform.
   Minimizing the peak autoconvolution is closely related to making the spectrum
   as "concentrated" or "smooth" as possible in a specific way, but more directly,
   we can optimize the spectral magnitude profile.
   
   However, a more direct approach for "minimizing the max of autoconvolution" 
   given a fixed sum (energy) is to find the function whose autoconvolution is 
   as flat as possible. For a step function, this is hard.
   
   Alternative Insight:
   The autoconvolution $c(t) = \int f(\tau)f(t-\tau)d\tau$.
   $c(0) = \int f^2$.
   We want to minimize $\max_t c(t) / (\int f)^2$.
   
   Let's use a parametric family in the frequency domain.
   Let $F(k)$ be the DFT of $f$.
   $c(t)$ is the inverse DFT of $|F(k)|^2$.
   We want to minimize the max of the inverse DFT of $|F(k)|^2$.
   
   This is equivalent to minimizing the peak of the power spectrum's autocorrelation? No.
   It is minimizing the peak of the time-domain autoconvolution.
   
   Let's try optimizing the log-spectrum.
   Let $f$ be generated by $f = \text{IFFT}(\exp(G(k)))$.
   We constrain $f \ge 0$.
   We optimize the parameters of $G(k)$ (e.g., a Gaussian in frequency space)
   to minimize the peak of $\text{IFFT}(|F|^2)$.
   
   Actually, a known result is that the function minimizing the peak of the 
   autoconvolution (for a given $L_2$ norm) is related to the prolate spheroidal 
   wave functions, but for step functions and $L_1$ normalization, it's different.
   
   Let's stick to a robust heuristic:
   1. Start with a Gaussian in time domain.
   2. Convert to frequency domain.
   3. Optimize the frequency domain magnitudes using gradient descent 
      on a low-dimensional parameterization (e.g., a few cosine coefficients 
      or a Gaussian width in frequency).
   4. Enforce non-negativity in time domain at each step.
   
   Specifically, we will optimize the spectral envelope $S(k) = \log |\hat{f}(k)|$.
   We parameterize $S(k)$ as a quadratic function of $k$ (Gaussian in spectrum) 
   plus a small set of harmonic perturbations to allow for non-Gaussian shapes.
   Then $f = \text{IFFT}(\exp(S(k)))$.
   We project $f$ to be non-negative and normalize.
   We compute the peak of the autoconvolution.
   We use Nelder-Mead or simple gradient descent on the parameters of $S(k)$.
"""

import numpy as np
import time

N = 600
TIME_LIMIT = 140  # Safety margin


def autoconvolve_fft(f):
    """Compute autoconvolution using FFT."""
    n = 2 * N
    F = np.fft.rfft(f, n=n)
    conv = np.fft.irfft(F * F, n=n)[:2 * N - 1]
    return conv


def compute_score(f):
    """Compute the normalized maximum of the autoconvolution."""
    f = np.asarray(f, dtype=np.float64)
    if np.any(f < -1e-15):
        return np.inf
    f = np.maximum(f, 0.0)
    s = np.sum(f)
    if s < 1e-15:
        return np.inf
    conv = autoconvolve_fft(f)
    return np.max(conv) / (s * s)


def spectrum_to_time(log_spectrum_params):
    """
    Generate time-domain function from spectral parameters.
    params: [log_A, center, width, c1, c2, c3]
    log |F(k)| = log_A - (k-center)^2/(2*width^2) + c1*cos(2*pi*k/N) + c2*cos(4*pi*k/N) + c3*cos(6*pi*k/N)
    """
    k = np.arange(N // 2 + 1)
    freqs = k / N  # normalized frequency [0, 0.5]
    
    log_A, center, width, c1, c2, c3 = log_spectrum_params
    
    # Gaussian in frequency
    g = -((freqs - center) ** 2) / (2 * width ** 2)
    
    # Harmonic perturbations
    h = c1 * np.cos(2 * np.pi * freqs) + c2 * np.cos(4 * np.pi * freqs) + c3 * np.cos(6 * np.pi * freqs)
    
    log_spec = log_A + g + h
    
    # Ensure numerical stability
    log_spec -= np.max(log_spec)
    
    F_r = np.exp(log_spec)
    
    # Reconstruct full spectrum (symmetric)
    F = np.zeros(N, dtype=np.complex128)
    F[:N//2+1] = F_r
    F[N//2+1:] = F_r[N//2:0:-1]
    
    # Inverse FFT to get time domain
    f = np.fft.ifft(F).real
    
    # Enforce non-negativity
    f = np.maximum(f, 0.0)
    
    # Normalize to sum N (standard for comparison, score is scale-invariant)
    s = np.sum(f)
    if s > 1e-15:
        f = f * (N / s)
    else:
        f = np.ones(N)
        
    return f


def objective(params):
    """
    Objective function: peak of autoconvolution normalized by sum^2.
    """
    f = spectrum_to_time(params)
    return compute_score(f)


def nelder_mead(func, x0, bounds=None, max_iter=200, tol=1e-8, time_limit=None, start_time=None):
    """
    Simple Nelder-Mead implementation with time guard.
    """
    n = len(x0)
    # Initial simplex
    simplex = [x0.copy()]
    for i in range(n):
        xi = x0.copy()
        step = 0.1 if x0[i] != 0 else 0.1
        xi[i] += step
        simplex.append(xi)
    
    fvals = [func(x) for x in simplex]
    best_val = min(fvals)
    best_x = simplex[np.argmin(fvals)].copy()
    
    alpha = 1.0
    gamma = 2.0
    rho = 0.5
    sigma = 0.5
    
    for _ in range(max_iter):
        if time_limit is not None and time.time() - start_time > time_limit:
            break
        
        # Sort simplex
        order = np.argsort(fvals)
        simplex = [simplex[i] for i in order]
        fvals = [fvals[i] for i in order]
        
        # Check convergence
        if max(fvals) - min(fvals) < tol:
            break
            
        if fvals[0] < best_val:
            best_val = fvals[0]
            best_x = simplex[0].copy()
            
        # Centroid of all but worst
        centroid = np.mean(simplex[:-1], axis=0)
        
        # Reflection
        xr = centroid + alpha * (centroid - simplex[-1])
        fr = func(xr)
        
        if fr < fvals[0]:
            # Expansion
            xe = centroid + gamma * (centroid - simplex[-1])
            fe = func(xe)
            if fe < fr:
                simplex[-1] = xe
                fvals[-1] = fe
            else:
                simplex[-1] = xr
                fvals[-1] = fr
        elif fr < fvals[-2]:
            # Accept reflection
            simplex[-1] = xr
            fvals[-1] = fr
        else:
            # Contraction
            if fr < fvals[-1]:
                # Outside contraction
                xc = centroid + rho * (simplex[-1] - centroid)
            else:
                # Inside contraction
                xc = centroid + rho * (centroid - simplex[-1])
            fc = func(xc)
            if fc < fvals[-1]:
                simplex[-1] = xc
                fvals[-1] = fc
            else:
                # Shrink
                for i in range(1, n + 1):
                    simplex[i] = simplex[0] + sigma * (simplex[i] - simplex[0])
                    fvals[i] = func(simplex[i])
                    
    return best_x, best_val


def construct():
    start_time = time.time()
    
    # Initial guess for spectral parameters
    # log_A, center, width, c1, c2, c3
    # Center 0.25 (middle of 0..0.5), width 0.1
    x0 = [0.0, 0.25, 0.1, 0.0, 0.0, 0.0]
    
    # Multi-start optimization
    best_params = x0.copy()
    best_score = objective(x0)
    
    # Define several initial points to explore the parameter space
    starts = [
        [0.0, 0.25, 0.1, 0.0, 0.0, 0.0],  # Base Gaussian
        [0.0, 0.25, 0.2, 0.0, 0.0, 0.0],  # Wider
        [0.0, 0.25, 0.05, 0.0, 0.0, 0.0], # Narrower
        [0.0, 0.1, 0.1, 0.0, 0.0, 0.0],   # Off-center
        [0.0, 0.4, 0.1, 0.0, 0.0, 0.0],   # Off-center
        [0.0, 0.25, 0.1, 0.5, 0.0, 0.0],  # Perturbed
        [0.0, 0.25, 0.1, -0.5, 0.0, 0.0], # Perturbed
        [0.0, 0.25, 0.1, 0.0, 0.5, 0.0],  # Perturbed 2
        [0.0, 0.25, 0.1, 0.0, -0.5, 0.0], # Perturbed 2
    ]
    
    # Allocate time for each start
    # We have ~140s. Let's give 10s per start, max 10 starts.
    time_per_start = 10.0
    
    for i, x_init in enumerate(starts):
        if time.time() - start_time > TIME_LIMIT - 5:
            break
            
        # Run Nelder-Mead
        try:
            p_opt, score_opt = nelder_mead(
                objective, 
                x_init, 
                max_iter=100, 
                tol=1e-6,
                time_limit=TIME_LIMIT - 5,
                start_time=start_time
            )
            if score_opt < best_score:
                best_score = score_opt
                best_params = p_opt
        except Exception:
            continue
            
    # Generate final function from best params
    f = spectrum_to_time(best_params)
    
    # Local refinement in time domain using coordinate descent on peak lags
    # This corrects for any non-negativity projection artifacts or spectral approximation errors
    if time.time() - start_time < TIME_LIMIT - 10:
        f = np.maximum(f, 0.0)
        s = np.sum(f)
        if s > 1e-15:
            f = f * (N / s)
            
        # Simple coordinate descent polish
        best_f = f.copy()
        best_val = compute_score(f)
        
        # Identify peak lags
        conv = autoconvolve_fft(f)
        max_c = np.max(conv)
        threshold = max_c * 0.95
        peak_indices = np.where(conv >= threshold)[0]
        
        # Sensitivity-based update
        alpha = 0.05
        for _ in range(500):
            if time.time() - start_time > TIME_LIMIT - 2:
                break
                
            conv = autoconvolve_fft(f)
            max_c = np.max(conv)
            current_val = max_c / (N * N)
            
            if current_val < best_val:
                best_val = current_val
                best_f = f.copy()
                
            threshold = max_c * 0.95
            peak_indices = np.where(conv >= threshold)[0]
            
            sensitivity = np.zeros(N)
            for m in peak_indices:
                j_min = max(0, m - (N - 1))
                j_max = min(N - 1, m)
                for j in range(j_min, j_max + 1):
                    sensitivity[j] += f[m - j]
                    
            sens_mean = np.mean(sensitivity)
            sens_std = np.std(sensitivity) + 1e-12
            sens_norm = (sensitivity - sens_mean) / sens_std
            
            f_new = f * (1.0 - alpha * sens_norm)
            f_new = np.maximum(f_new, 0.0)
            s_new = np.sum(f_new)
            if s_new > 1e-15:
                f_new = f_new * (N / s_new)
                
            new_val = compute_score(f_new)
            
            if new_val < current_val:
                f = f_new
                alpha = min(alpha * 1.02, 0.2)
            else:
                alpha *= 0.9
                if alpha < 1e-8:
                    break
                    
        if best_val < best_score:
            best_score = best_val
            f = best_f
            
    # Final cleanup
    f = np.maximum(f, 0.0)
    s = np.sum(f)
    if s > 1e-15:
        f = f * (N / s)
    else:
        f = np.ones(N)
        
    return [float(x) for x in f]


if __name__ == "__main__":
    f = construct()
    print(f"Score: {compute_score(f)}")
    print(f"Length: {len(f)}")
    print(f"Min: {min(f)}, Max: {max(f)}")
