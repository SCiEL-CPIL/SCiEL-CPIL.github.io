    norms_sq = np.sum(candidates**2, axis=1)
    max_norm_sq = np.max(norms_sq)
    
    # Condition: dist^2 >= max_norm_sq
    # dist^2 = |u|^2 + |v|^2 - 2 u.v
    # We need |u|^2 + |v|^2 - 2 u.v >= max_norm_sq
    # This is not a simple dot product constraint like u.v <= C
    # because the RHS depends on u and v norms.
    # However, if we assume all vectors have similar norms, we can approximate.
    # Or we can just use the greedy pack with a strict condition.
    
    # For greedy pack, we need a pairwise condition.
    # Let's check if the condition holds for the whole set.
