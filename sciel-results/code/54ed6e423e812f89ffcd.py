    def axial_to_cartesian(axial_list):
        pts = []
        for q, r in axial_list:
            x = math.sqrt(3) * (q + r / 2.0)
            y = 1.5 * r
            pts.append((x, y))
        return np.array(pts)

    def calc_S_for_beta(pts, beta):
        if not _time_ok():
            return float('inf'), None, None
        
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub_list = []
        b_ub_list = []
        
        for nx, ny in normals:
            for px, py in pts:
                A_ub_list.append([-nx, -ny, -1.0])
                b_ub_list.append(-(px * nx + py * ny))
                A_ub_list.append([nx, ny, -1.0])
                b_ub_list.append(px * nx + py * ny)
        
        A_ub = np.array(A_ub_list)
        b_ub = np.array(b_ub_list)
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if not _time_ok():
            return float('inf'), 0.0, None, pts

        # Coarse grid search over beta
        for i in range(13):
            beta = i * (math.pi / 6) / 12
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Refine beta with bounded scalar optimization
        try:
            if _time_ok():
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(0, math.pi / 6), method='bounded',
                                     options={'maxiter': 200, 'xatol': 1e-10})
                if res.fun < best_S:
                    best_S = res.fun
                    best_beta = res.x
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass
        
        # Local position perturbation search
        # We try to move points slightly to reduce the bounding box size.
        # This is a heuristic local search.
        if _time_ok() and best_center is not None:
            current_pts = pts.copy()
            current_S = best_S
            current_beta = best_beta
            current_center = best_center
            
            # Simple gradient-free local search on positions
            # We only allow small moves that don't cause overlap (checked via min distance > 2*APOTHEM)
            # Since we don't know the exact contacts, we assume the lattice is valid and just try to compress.
            # However, compressing a rigid lattice is impossible. We need to break the lattice.
            # So we will try random perturbations and check validity.
            
            def is_valid(pts_test):
                # Check min distance between centers >= 2 * APOTHEM
                # This is a necessary condition for non-overlapping unit hexagons with same orientation.
                # If orientations differ, this is not sufficient, but we assume same orientation for this local search.
                min_d2 = float('inf')
                n = len(pts_test)
                for i in range(n):
                    for j in range(i+1, n):
                        dx = pts_test[i,0] - pts_test[j,0]
                        dy = pts_test[i,1] - pts_test[j,1]
                        d2 = dx*dx + dy*dy
                        if d2 < min_d2:
                            min_d2 = d2
                return min_d2 >= (2*APOTHEM)**2 - 1e-6

            # Try a few random perturbations
            for iter in range(50):
                if not _time_ok():
                    break
                if current_S < 10.0: # Only bother if we are in a good range
                    break
                    
                # Generate small random moves
                moves = np.random.normal(0, 0.1, size=(len(current_pts), 2))
                new_pts = current_pts + moves
                if is_valid(new_pts):
                    S_new, center_new, _ = calc_S_for_beta(new_pts, current_beta)
                    if S_new < current_S:
                        current_S = S_new
                        current_pts = new_pts
                        current_center = center_new
            
            if current_S < best_S:
                best_S = current_S
                best_center = current_center
                pts = current_pts # Update pts for the final result

        return best_S, best_beta, best_center, pts

    best_global_S = float('inf')
