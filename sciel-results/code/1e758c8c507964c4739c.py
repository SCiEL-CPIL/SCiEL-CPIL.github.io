    def calc_S_for_beta(pts, beta):
        """Fast exact computation of optimal center and S for given beta.
        Uses the fact that optimal center minimizes max projection over all
        6 normal directions. This is a 2D LP with 12 constraints (±6 normals).
        We solve it via a simple 2D linear programming approach."""
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None

        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])

        # The optimal center minimizes max_i |n_i · (p - c)|
        # This is equivalent to: min D s.t. n_i·c - D <= n_i·p and -n_i·c - D <= -n_i·p for all i
        # Which is: min D s.t. -D <= n_i·(p - c) <= D for all i
        # Rearranging: D >= |n_i·p - n_i·c| for all i
        # So: minimize D subject to n_i·c + D >= n_i·p and -n_i·c + D >= -n_i·p

        # This is a 2D LP. We can solve it efficiently by noting the structure.
        # For 2D, we can use the fact that the optimum occurs at intersection of 2 constraint lines.
        # But with 12 constraints, let's just use a simple approach:
        # The center that minimizes max |n_i·(p-c)| is the Chebyshev center in the projected space.
        
        # Quick approach: use scipy's linprog but with a smaller problem
        # Variables: cx, cy, D
        # Minimize D
        # Constraints: for each normal n_i and each point p_j:
        #   n_i·(p_j - c) <= D  =>  -n_i·c + D >= n_i·p_j  =>  n_i_x*cx + n_i_y*cy + D >= n_i·p_j
        #   -n_i·(p_j - c) <= D  =>  n_i·c + D >= -n_i·p_j  =>  -n_i_x*cx - n_i_y*cy + D >= -n_i·p_j
        
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []
        
        for nx, ny in normals:
            for px, py in pts:
                # n·(p-c) <= D  =>  n·p - n·c <= D  =>  nx*cx + ny*cy + D >= n·p
                # In standard form: -nx*cx - ny*cy - D <= -n·p
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-(px * nx + py * ny))
                # -n·(p-c) <= D  =>  -n·p + n·c <= D  =>  -nx*cx - ny*cy + D >= -n·p
                # In standard form: nx*cx + ny*cy - D <= n·p
                A_ub.append([nx, ny, -1.0])
                b_ub.append(px * nx + py * ny)

        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]

        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])

        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T

        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])

        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf'), (cx, cy), float('inf')

        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -50, 50)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S, (cx, cy), D

    def exact_S_vectorized(pts, cx, cy, beta):
        """Vectorized exact computation of S for given center and beta."""
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        max_proj = np.max(np.abs(projs))
        S = (max_proj + APOTHEM) / APOTHEM
        return S

