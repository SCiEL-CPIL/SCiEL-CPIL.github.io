import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 42.0  # Safety margin before 60s limit
    
    N = 17
    MIN_DIST = 6
    
    # Step 1: Construct the [17,8,6] quadratic residue code (256 words)
    # The [18,9,6] extended QR code shortened by one coordinate
    
    # Build GF(2^8) with primitive polynomial x^8 + x^4 + x^3 + x^2 + 1
    # Actually, let's use a simpler approach: generate the QR code via its defining property
    
    # The QR code of length 17: codewords c = (c_0, ..., c_16) where
    # the Fourier transform has zeros at non-quadratic-residue positions
    
    # Quadratic residues mod 17: {1, 2, 4, 8, 16, 15, 13, 9}
    # Non-quadratic residues: {3, 5, 6, 7, 10, 11, 12, 14}
    
    # Generator matrix approach: use the parity-check structure
    # For the [17,9,5] QR code, H has rows corresponding to non-QR frequencies
    
    # Simpler: enumerate all 2^9 = 512 possible codewords of the [17,9] code,
    # then select those with even parity (to get the [17,8,6] subcode)
    
    # The [17,9] QR code: generated by cyclic shifts of the generator polynomial
    # g(x) = product of (x - alpha^r) for r in non-QR set {3,5,6,7,10,11,12,14}
    # Wait, for a cyclic code, g(x) divides x^17 - 1, and the roots are at alpha^r for r in the defining set
    
    # For the QR code, the defining set (zeros) is the set of non-quadratic residues
    # So g(x) = prod_{r in NQR} (x - alpha^r) where NQR = {3,5,6,7,10,11,12,14}
    # This gives degree 8, so k = 17 - 8 = 9
    
    # Let me build this using polynomial arithmetic over GF(2)
    
    # First, find a primitive 17th root of unity in GF(2^8)
    # x^17 - 1 = (x-1)(x^16 + x^15 + ... + x + 1)
    # We need an element alpha of order 17 in some extension field
    
    # GF(2^8) with primitive polynomial p(x) = x^8 + x^4 + x^3 + x^2 + 1
    # Let's work with polynomials mod p(x)
    
    def gf_mul(a, b, p):
        """Multiply in GF(2^8)"""
        result = 0
        while b:
            if b & 1:
                result ^= a
            a <<= 1
            if a & 0x100:
                a ^= p
            b >>= 1
        return result
    
    def gf_pow(a, n, p):
        result = 1
        while n:
            if n & 1:
                result = gf_mul(result, a, p)
            a = gf_mul(a, a, p)
            n >>= 1
        return result
    
    # Primitive polynomial for GF(2^8)
    PP = 0x11d  # x^8 + x^4 + x^3 + x^2 + 1
    
    # Find element of order 17 in GF(2^8)
    # 2^8 - 1 = 255 = 17 * 15, so elements of order 17 exist
    # Try x = 2 (i.e., alpha = x)
    # alpha^17 should be 1 if order divides 17
    
    # Let's find an element of exact order 17
    # (2^8-1)/17 = 15, so g^15 has order 17 for any generator g
    
    # Find a generator of GF(2^8)*
    # x is a generator if its order is 255
    alpha = 2  # x in GF(2^8)
    # Check order of alpha
    # alpha^255 should be 1, and no smaller power
    
    # For our purposes, we just need alpha^17 = 1
    # Let's compute alpha = x^15 (which has order 17 if x has order 255)
    
    # Actually, let's just try all elements and find one with order 17
    order_17_elem = None
    for elem in range(1, 256):
        # Check if elem^17 = 1 and elem^1 != 1
        if gf_pow(elem, 17, PP) == 1 and elem != 1:
            # Check it's not a smaller order divisor of 17 (17 is prime, so just check elem != 1)
            order_17_elem = elem
            break
    
    if order_17_elem is None:
        # Fallback: just use greedy from scratch
        order_17_elem = None
    
    # Build the generator polynomial
    # g(x) = prod_{r in NQR} (x - alpha^r)
    # NQR = {3, 5, 6, 7, 10, 11, 12, 14}
    
    NQR = [3, 5, 6, 7, 10, 11, 12, 14]
    
    def poly_mul(p1, p2):
        """Multiply two polynomials over GF(2), represented as lists of coefficients"""
        result = [0] * (len(p1) + len(p2) - 1)
        for i, c1 in enumerate(p1):
            if c1:
                for j, c2 in enumerate(p2):
                    if c2:
                        result[i + j] ^= 1
        # Trim trailing zeros
        while result and result[-1] == 0:
            result.pop()
        if not result:
            result = [0]
        return result
    
    def poly_mod(p, mod_poly):
        """Polynomial modulo mod_poly over GF(2)"""
        result = p[:]
        mod_len = len(mod_poly)
        while len(result) >= mod_len:
            if result[-1]:
                shift = len(result) - mod_len
                for i in range(mod_len):
                    result[shift + i] ^= mod_poly[i]
            result.pop()
        return result
    
    if order_17_elem is not None:
        # Compute g(x) = prod (x - alpha^r) for r in NQR
        # Each factor is x + alpha^r (since -1 = 1 in GF(2))
        g_poly = [1]  # Start with 1
        for r in NQR:
            # Factor: x + alpha^r, represented as [alpha^r, 1]
            factor = [gf_pow(order_17_elem, r, PP), 1]
            g_poly = poly_mul(g_poly, factor)
        
        # Now g_poly has degree 8 (length 9)
        # The [17,9] code is cyclic with generator polynomial g_poly
        # Generate all 2^9 codewords
        # A codeword is m(x) * g_poly mod (x^17 - 1) for deg(m) < 9
        
        # Actually, for a cyclic code, codewords are of the form m(x)*g(x) where deg(m) < k
        # and the result is taken mod (x^n - 1)
        
        # x^17 - 1 mod x^17 - 1 = 0, so we just need to handle the wrap-around
        # Since deg(m*g) < 17 (deg m < 9, deg g = 8, so deg(m*g) < 17), no reduction needed
        
        # Generate all 512 codewords of the [17,9] code
        qr_codewords = []
        for msg in range(256):  # 2^8 messages for the shortened code
            # Build message polynomial m(x)
            m_poly = [0] * 9
            for bit in range(8):
                if msg & (1 << bit):
                    m_poly[bit] = 1
            # m_poly has degree < 8, so m_poly[8] = 0 always for 8-bit messages
            # Wait, for [17,9] code, messages have 9 bits. 
            # For the shortened [17,8,6] code, we fix one coordinate.
            
            # Let me reconsider. The [18,9,6] extended QR code:
            # Take the [17,9,5] QR code, add a parity bit to make even weight
            # Then shorten by deleting one coordinate (fix it to 0)
            
            # This is getting complicated. Let me use a different approach.
            
            # Alternative: The [17,8,6] code can be constructed as follows:
            # Take all 2^8 = 256 vectors in F_2^8, map them to length-17 vectors
            # using the generator matrix of the [17,8,6] code
            
            # The generator matrix G for the [17,8,6] QR code:
            # It's the top 8 rows of the [17,9] QR code generator matrix,
            # with the last column removed (or some coordinate fixed)
            
            # This is getting too complex for inline implementation. 
            # Let me use a simpler approach: just run greedy with good initialization.
            
            pass
        
        # Given the complexity, let's use a hybrid approach:
        # 1. Start with the 32-word Reed-Muller code (distance 8)
        # 2. Use greedy to expand
        # 3. Also try pure greedy with multiple restarts
        
        rm_words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                rm_words.append(word)
        
        # Now use greedy to expand from this starting set
        best_selected = []
        
        for run in range(8):
            if time.time() > deadline - 3:
                break
            
            if run == 0:
                # Start with Reed-Muller code
                current_selected = rm_words[:]
            else:
                # Random greedy
                current_selected = []
            
            if run == 0:
                # For RM start, just add more words greedily
                candidates = list(range(1 << N))
                random.seed(42 + run)
                random.shuffle(candidates)
                
                for w in candidates:
                    if time.time() > deadline - 2:
                        break
                    
                    is_valid = True
                    for s in current_selected:
                        if (w ^ s).bit_count() < MIN_DIST:
                            is_valid = False
                            break
                    
                    if is_valid:
                        current_selected.append(w)
            else:
                # Pure random greedy
                candidates = list(range(1 << N))
                random.seed(42 + run)
                random.shuffle(candidates)
                
                for w in candidates:
                    if time.time() > deadline - 2:
                        break
                    
                    is_valid = True
                    for s in current_selected:
                        if (w ^ s).bit_count() < MIN_DIST:
                            is_valid = False
                            break
                    
                    if is_valid:
                        current_selected.append(w)
            
            if len(current_selected) > len(best_selected):
                best_selected = current_selected[:]
        
        return best_selected
    else:
        # Fallback: pure greedy
        best_selected = []
        for run in range(8):
            if time.time() > deadline - 3:
                break
            
            candidates = list(range(1 << N))
            random.seed(42 + run)
            random.shuffle(candidates)
            
            current_selected = []
            for w in candidates:
                if time.time() > deadline - 2:
                    break
                
                is_valid = True
                for s in current_selected:
                    if (w ^ s).bit_count() < MIN_DIST:
                        is_valid = False
                        break
                
                if is_valid:
                    current_selected.append(w)
            
            if len(current_selected) > len(best_selected):
                best_selected = current_selected[:]
        
        return best_selected
