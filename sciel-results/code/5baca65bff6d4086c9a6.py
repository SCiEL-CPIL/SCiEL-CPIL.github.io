import numpy as np
import time

def construct():
    start_time = time.time()
    deadline = start_time + 85  # Safety margin
    
    # 1. Generate the 256-word linear [17,8,6] QR code
    # Generator polynomial: x^9 + x^7 + x^6 + x^3 + x^2 + 1
    # Corresponding vector indices (0-based): 0, 2, 3, 6, 7, 9
    gen_indices = [0, 2, 3, 6, 7, 9]
    
    # Create the generator matrix G (8x17)
    # The code is cyclic, so G is circulant with the first row being the generator vector
    G = np.zeros((8, 17), dtype=np.uint8)
    for i in range(8):
        for idx in gen_indices:
            # Shift the generator vector by i
            pos = (idx + i) % 17
            G[i, pos] = 1
            
    # Generate all 256 linear combinations
    # We can iterate through 0..255 and compute the sum of rows
    # Or use matrix multiplication mod 2
    # Let's use matrix multiplication for speed
    # A = G @ coeffs.T mod 2
    # But we need the rows of the code, which are the linear combos.
    # Actually, the code is the row space of G.
    # The codewords are the vectors c = m G mod 2 for m in F_2^8.
    
    codewords = []
    codeword_set = set()
    
    # Pre-compute the 256 codewords
    # Using integer representation for the set, and binary for distance checks
    # Let's generate them as integers first for the set
    # Then convert to numpy matrix
    
    # Efficient generation:
    # The codewords are sums of subsets of rows of G.
    # There are 2^8 = 256 subsets.
    
    # Let's just use the property that it's linear.
    # We can generate them by iterating 0-255
    # For each mask, sum the rows of G where mask has 1.
    
    # Even faster: 
    # The code is generated by the polynomial.
    # We can just use the 256 integers.
    
    # Let's compute the 256 words
    # g is the generator vector as an integer
    g_int = 0
    for idx in gen_indices:
        g_int |= (1 << idx)
        
    # The cyclic shifts
    shifts = []
    for i in range(8):
        # Shift g_int left by i, wrap around 17 bits
        # (g_int << i) | (g_int >> (17-i))
        # Mask to 17 bits
        val = (g_int << i) | (g_int >> (17 - i))
        val &= (1 << 17) - 1
        shifts.append(val)
        
    # Generate all 256 sums
    for mask in range(256):
        word = 0
        for i in range(8):
            if (mask >> i) & 1:
                word ^= shifts[i]
        codewords.append(word)
        codeword_set.add(word)
        
    # Convert to numpy matrix for distance checks
    # Shape (256, 17)
    # We need to unpack the integers to bits
    # Use np.unpackbits or similar, but we need 17 bits.
    # Easier: loop or vectorized bit extraction
    
    # Let's create the matrix
    N = len(codewords)
    M = np.zeros((N, 17), dtype=np.uint8)
    for i, w in enumerate(codewords):
        for j in range(17):
            M[i, j] = (w >> j) & 1
            
    # 2. Greedy Search for Nonlinear Extensions
    # Iterate through all possible words
    # To improve quality, we can try multiple passes or random orders
    # But sequential is a good baseline.
    
    # We will try to add words.
    # To make it more robust, we can try a few random orderings if time permits.
    # Let's do one sequential pass first.
    
    candidates = list(range(1 << 17))
    # Shuffle for better greedy performance? 
    # Sequential might bias towards low-weight words.
    # Let's shuffle.
    np.random.shuffle(candidates)
    
    for c in candidates:
        if time.time() > deadline:
            break
            
        if c in codeword_set:
            continue
            
        # Check distance to all current codewords
        # Convert c to vector
        v = np.zeros(17, dtype=np.uint8)
        for j in range(17):
            v[j] = (c >> j) & 1
            
        # Calculate distances
        # M is (K, 17), v is (17,)
        # dists = np.sum(M != v, axis=1)
        # This creates a temporary array. 
        # Alternative: 
        # dists = 17 - np.sum(M & v, axis=1) - np.sum(~M & v, axis=1)? No.
        # Hamming distance = sum(M XOR v)
        # dists = np.sum(M ^ v, axis=1)
        
        dists = np.sum(M ^ v, axis=1)
        
        if np.min(dists) >= 6:
            # Add to set
            codewords.append(c)
            codeword_set.add(c)
            # Append to M
            M = np.vstack([M, v])
            
    return codewords
