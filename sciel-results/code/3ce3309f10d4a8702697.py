        # In a Mackay icosahedron, the atoms lie on shells.
        # The 30 edge atoms are at the midpoints of the edges of the k=1 icosahedron?
        # No, for k=2, the "edge" atoms are not midpoints of the k=1 edges.
        # They form a new icosahedron-like shell.
        
