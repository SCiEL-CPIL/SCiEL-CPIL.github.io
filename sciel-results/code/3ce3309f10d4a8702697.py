def _get_fcc_cluster(n):
    """
    Generate a truncated FCC cluster with approximately n atoms.
    """
    a = 1.0
    points = []
    # Generate points in a cube of size L x L x L
    # Density of FCC is 4 atoms per unit cell of side a.
    # Volume ~ 4/3 pi R^3.
    # n ~ 4 * Volume / a^3 => R ~ (n/4)^(1/3) * a
    R = (n / 4.0) ** (1.0 / 3.0) * 1.0
    
    max_coord = int(R) + 2
    for x in range(-max_coord, max_coord + 1):
        for y in range(-max_coord, max_coord + 1):
            for z in range(-max_coord, max_coord + 1):
                for dx, dy, dz in [(0,0,0), (0.5,0.5,0), (0.5,0,0.5), (0,0.5,0.5)]:
                    px = x + dx
                    py = y + dy
                    pz = z + dz
                    if np.linalg.norm([px, py, pz]) <= R:
                        points.append([px, py, pz])
    
    points = np.array(points)
    
    if len(points) > n:
        dists = np.linalg.norm(points, axis=1)
        idx = np.argsort(dists)[-n:]
        points = points[idx]
    elif len(points) < n:
        # Add random atoms nearby
        while len(points) < n:
            p = points[0] + np.random.uniform(-1, 1, 3)
            if all(np.linalg.norm(p - q) > 0.5 for q in points):
                points = np.vstack([points, [p]])
            else:
                points = np.vstack([points, [p]])
                
    return points

def _valid_check(pos):
    """Check if positions are valid (finite, no overlaps)."""
    if not np.all(np.isfinite(pos)):
        return False
    from scipy.spatial.distance import cdist
    d = cdist(pos, pos)
    np.fill_diagonal(d, np.inf)
    if np.min(d) < 0.35:
        return False
    return True

def _deterministic_growth(n, kind, potential):
    """
    Grow a cluster atom-by-atom by finding the best interstitial site.
    """
    # Start with a small core
    # For SC, a 13-atom icosahedron or 4-atom tetrahedron is a good start.
    # Let's start with 1 atom.
    if n == 1:
        return np.array([[0.0, 0.0, 0.0]])
    
    # Initialize with a small cluster
    if n <= 13:
        # Use icosahedron for n=13, else random
        if n == 13:
            pos = _get_mackay_icosahedron(1)
        else:
            # Random compact
            radius = 0.72 * n ** (1.0/3.0) * 0.8
            rng = np.random.default_rng(42)
            points = []
            while len(points) < n:
                p = rng.uniform(-radius, radius, 3)
                if np.linalg.norm(p) <= radius:
                    if all(np.linalg.norm(p - q) >= 0.6 for q in points):
                        points.append(p)
            pos = np.array(points)
        
        # Relax
        try:
            e, pos = relax(pos, potential, kind)
        except:
            pass
        return pos

    # Start with 13-atom icosahedron
    pos = _get_mackay_icosahedron(1)
    try:
        e, pos = relax(pos, potential, kind)
    except:
        pass
    
    current_n = 13
    
    while current_n < n:
        if _time_left() < 10.0:
            # Not enough time, break
            break
            
        # Generate candidate sites for the new atom
        # Candidates:
        # 1. On the surface of the current cluster (offset from existing atoms)
        # 2. In the interstices (midpoints of pairs of close atoms)
        
        candidates = []
        
        # Interstitial sites: midpoints of pairs of atoms within a certain distance
        # For SC, nearest neighbor is ~1.0. 
        # Midpoints of bonds are good sites.
        d = cdist(pos, pos)
        np.fill_diagonal(d, np.inf)
        
        # Find pairs with distance < 1.5
        pairs = np.argwhere(d < 1.5)
        # Remove duplicates (i,j) and (j,i)
        unique_pairs = set()
        for i, j in pairs:
            if i < j:
                unique_pairs.add((i, j))
        
        for i, j in unique_pairs:
            mid = (pos[i] + pos[j]) / 2.0
            # Perturb slightly to avoid symmetry degeneracy?
            # Or just use the midpoint.
            candidates.append(mid)
            
        # Surface sites: offset from each atom
        for i in range(len(pos)):
            # Direction away from center
            v = pos[i]
            norm = np.linalg.norm(v)
            if norm > 1e-6:
                v = v / norm
            else:
                v = np.array([1.0, 0.0, 0.0])
            
            # Add a few points along this direction
            for dist in [1.0, 1.2, 1.5]:
                candidates.append(pos[i] + v * dist)
                
            # Also add some random directions
            for _ in range(3):
                rand_dir = np.random.normal(0, 1, 3)
                rand_dir = rand_dir / np.linalg.norm(rand_dir)
                candidates.append(pos[i] + rand_dir * 1.2)

        candidates = np.array(candidates)
        
        # Filter valid candidates (min distance to existing atoms > 0.4)
        valid_cands = []
        for c in candidates:
            d_min = np.min(np.linalg.norm(pos - c, axis=1))
            if d_min > 0.4:
                valid_cands.append(c)
                
        if not valid_cands:
            # Fallback: add a random point
            p = pos[0] + np.random.normal(0, 0.5, 3)
            valid_cands = [p]
            
        valid_cands = np.array(valid_cands)
        
        # Evaluate energy for each candidate
        # To speed up, we can just relax the top few candidates.
        # First, calculate energy of (pos + candidate)
        best_energy = np.inf
        best_new_pos = None
        
        # Limit number of candidates to evaluate to avoid timeout
        max_cands = 50
        if len(valid_cands) > max_cands:
            # Randomly sample
            idx = np.random.choice(len(valid_cands), max_cands, replace=False)
            valid_cands = valid_cands[idx]
            
        for c in valid_cands:
            new_pos = np.vstack([pos, [c]])
            try:
                e, _ = sutton_chen_energy_gradient(new_pos, kind)
                if e < best_energy:
                    best_energy = e
                    best_new_pos = new_pos.copy()
            except:
                continue
        
        if best_new_pos is None:
            # Fallback
            best_new_pos = np.vstack([pos, [valid_cands[0]]])
            
        # Relax the best candidate
        try:
            e, pos = relax(best_new_pos, potential, kind)
        except:
            pos = best_new_pos
            
        current_n = len(pos)
        
    # If we didn't reach n, add random atoms and relax
    if len(pos) < n:
        while len(pos) < n:
            p = pos[0] + np.random.uniform(-1, 1, 3)
            pos = np.vstack([pos, [p]])
        try:
            e, pos = relax(pos, potential, kind)
        except:
            pass
            
    return pos

def construct(instance):
    n = instance['n']
    kind = instance['kind']
    potential = instance['potential']
    
    start_time = time.time()
    time_limit = 280.0 # Leave 10s margin for 300s limit? No, 330s kill.
    
    best_energy = np.inf
    best_pos = None
    
    # Strategy 1: Deterministic Growth
    # This is the primary strategy as it leverages structural hierarchy.
    try:
        pos_growth = _deterministic_growth(n, kind, potential)
        if len(pos_growth) == n and _valid_check(pos_growth):
            e, _ = sutton_chen_energy_gradient(pos_growth, kind)
            if e < best_energy:
                best_energy = e
                best_pos = pos_growth.copy()
    except Exception as e:
        print(f"Growth failed: {e}")
        
    if time.time() - start_time > time_limit:
        return best_pos if best_pos is not None else _get_fcc_cluster(n)

    # Strategy 2: Multi-start Relaxation
    # Generate diverse seeds and relax them.
    seeds = []
    
    # Seed 1: FCC
    try:
        seeds.append(_get_fcc_cluster(n))
    except:
        pass
        
    # Seed 2: Random Compact
    try:
        radius = 0.72 * n ** (1.0/3.0) * 0.8
        rng = np.random.default_rng(n)
        points = []
        while len(points) < n:
            p = rng.uniform(-radius, radius, 3)
            if np.linalg.norm(p) <= radius:
                if all(np.linalg.norm(p - q) >= 0.6 for q in points):
                    points.append(p)
        seeds.append(np.array(points))
    except:
        pass
        
    # Seed 3: Perturbed Growth (if growth succeeded)
    if best_pos is not None:
        noise = np.random.normal(0, 0.2, (n, 3))
        seeds.append(best_pos + noise)

    # Relax seeds
    for seed in seeds:
        if time.time() - start_time > time_limit:
            break
        try:
            e, pos = relax(seed, potential, kind)
            if e < best_energy:
                best_energy = e
                best_pos = pos.copy()
        except:
            continue
            
    # Strategy 3: Basin Hopping on the best found so far
    if best_pos is not None:
        current_pos = best_pos.copy()
        current_energy = best_energy
        step_size = 0.5
        max_steps = 20 # Keep small to fit in time
        
        for _ in range(max_steps):
            if time.time() - start_time > time_limit:
                break
                
            noise = np.random.normal(0, step_size, (n, 3))
            new_pos = current_pos + noise
            
            if not _valid_check(new_pos):
                step_size *= 0.8
                continue
                
            try:
                new_energy, new_pos = relax(new_pos, potential, kind)
            except:
                continue
                
            if new_energy < current_energy:
                current_energy = new_energy
                current_pos = new_pos
                if new_energy < best_energy:
                    best_energy = new_energy
                    best_pos = new_pos.copy()
                step_size = min(step_size * 1.1, 2.0)
            else:
                # Metropolis
                T = 0.01
                if np.random.rand() < np.exp(-(new_energy - current_energy) / T):
                    current_energy = new_energy
                    current_pos = new_pos
                    step_size = min(step_size * 1.1, 2.0)
                else:
                    step_size *= 0.8
                    
            if step_size < 0.01:
                break

    if best_pos is None:
        # Fallback
        best_pos = _get_fcc_cluster(n)
        
    return best_pos
