import numpy as np
from scipy.optimize import minimize, differential_evolution
import itertools

def _build_hamiltonian(n, coupling, field):
    """Build the Hamiltonian matrix for the open transverse-field Ising chain."""
    dim = 2**n
    H = np.zeros((dim, dim), dtype=complex)
    
    # ZZ terms: -coupling * sum Z_i Z_{i+1}
    # Z_i Z_{i+1} is diagonal.
    # For basis state |k>, Z_i = 1 if bit i is 0, -1 if bit i is 1.
    # Z_i Z_{i+1} = 1 if bits are same, -1 if different.
    for k in range(dim):
        zz_val = 0.0
        for i in range(n - 1):
            bit_i = (k >> i) & 1
            bit_j = (k >> (i + 1)) & 1
            z_i = 1.0 if bit_i == 0 else -1.0
            z_j = 1.0 if bit_j == 0 else -1.0
            zz_val += z_i * z_j
        H[k, k] += -coupling * zz_val
        
    # X terms: -field * sum X_i
    # X_i flips bit i.
    for i in range(n):
        mask = 1 << i
        for k in range(dim):
            k_prime = k ^ mask
            H[k, k_prime] += -field
            
    return H

def _compute_energy(n, coupling, field, angles, H=None, ground_state=None):
    """
    Compute energy of the state generated by the circuit.
    If H is provided, we can use it, but we need to apply the circuit to a basis state.
    For efficiency in optimization, we should avoid rebuilding H or re-diagonalizing.
    Here we just compute <psi|H|psi> by evolving the state and doing the dot product.
    """
    # Evolve state
    state = np.zeros(2**n, dtype=complex)
    state[0] = 1.0
    
    for l in range(angles.shape[0]):
        for i in range(n):
            theta = angles[l, i]
            c = np.cos(theta / 2)
            s = np.sin(theta / 2)
            mask = 1 << i
            indices_0 = np.where((np.arange(len(state)) & mask) == 0)[0]
            indices_1 = indices_0 | mask
            
            v0 = state[indices_0].copy()
            v1 = state[indices_1].copy()
            
            state[indices_0] = c * v0 - s * v1
            state[indices_1] = s * v0 + c * v1
        
        if l < angles.shape[0] - 1:
            for i in range(n - 1):
                mask_i = 1 << i
                mask_j = 1 << (i + 1)
                indices = np.where(((np.arange(len(state)) & mask_i) != 0) & ((np.arange(len(state)) & mask_j) != 0))[0]
                state[indices] *= -1.0
                
    # Compute energy <psi|H|psi>
    # Instead of full matrix vector product, we can compute terms directly or use H.
    # Using H is O(2^n * 2^n) = O(4^n). For n=6, 4096 ops. Very fast.
    H_psi = H @ state
    energy = np.vdot(state, H_psi).real
    return energy

def angles(n, coupling, field, layers):
    """
    Optimize parameters using Global (Differential Evolution) + Local (L-BFGS-B) hybrid.
    """
    # 1. Build Hamiltonian and find ground state energy for reference (optional for objective, but good for sanity)
    H = _build_hamiltonian(n, coupling, field)
    
    # Objective function for optimizer
    def objective_flat(params_flat):
        ang = params_flat.reshape((layers, n))
        return _compute_energy(n, coupling, field, ang, H=H)
        
    # Bounds for angles: [-pi, pi]
    bounds = [(-np.pi, np.pi)] * (layers * n)
    
    # Global Optimization: Differential Evolution
    # popsize=15 is a good balance for 18 params.
    # maxiter=100 is enough for convergence in this small space.
    try:
        res_de = differential_evolution(
            objective_flat, 
            bounds, 
            seed=42, 
            maxiter=100, 
            popsize=15,
            tol=1e-8,
            polish=False # We will do local polish manually
        )
        best_params = res_de.x
        best_energy = res_de.fun
    except Exception:
        # Fallback to random if DE fails
        best_params = np.random.uniform(-np.pi, np.pi, layers * n)
        best_energy = objective_flat(best_params)
        
    # Local Polish: L-BFGS-B
    try:
        res_lbfgs = minimize(
            objective_flat, 
            best_params, 
            method='L-BFGS-B',
            bounds=bounds,
            options={'maxiter': 200, 'ftol': 1e-12, 'gtol': 1e-8}
        )
        if res_lbfgs.fun < best_energy:
            best_params = res_lbfgs.x
            best_energy = res_lbfgs.fun
    except Exception:
        pass
        
    # Reshape and return
    best_angles = best_params.reshape((layers, n))
    return best_angles
