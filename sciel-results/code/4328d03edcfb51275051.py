"""Heilbronn triangles: place 11 points in a unit equilateral triangle to maximize the minimum triangle area."""
import numpy as np
import math
import time
from scipy.optimize import minimize
from scipy.stats import qmc

N = 11
S3 = math.sqrt(3)

def _project_to_triangle(points):
    """
    Project points onto the equilateral triangle with vertices (0,0), (1,0), (0.5, sqrt(3)/2).
    """
    points = points.copy()
    # y >= 0
    points[points[:, 1] < 0, 1] = 0
    
    # y <= sqrt(3) * x
    d1 = S3 * points[:, 0] - points[:, 1]
    mask1 = d1 < 0
    if np.any(mask1):
        d1_masked = d1[mask1]
        points[mask1, 0] -= d1_masked * S3 / 4.0
        points[mask1, 1] += d1_masked / 4.0
        
    # y <= sqrt(3) * (1 - x)
    d2 = -S3 * points[:, 0] - points[:, 1] + S3
    mask2 = d2 < 0
    if np.any(mask2):
        d2_masked = d2[mask2]
        points[mask2, 0] += d2_masked * S3 / 4.0
        points[mask2, 1] += d2_masked / 4.0
        
    return points

def _min_area(points):
    """
    Compute minimum area of any triangle formed by 3 points.
    """
    n = len(points)
    min_area = float('inf')
    for i in range(n):
        p1 = points[i]
        for j in range(i + 1, n):
            p2 = points[j]
            v1 = p2 - p1
            for k in range(j + 1, n):
                p3 = points[k]
                v2 = p3 - p1
                area = 0.5 * abs(v1[0] * v2[1] - v1[1] * v2[0])
                if area < min_area:
                    min_area = area
    return min_area

def _objective(flat_points):
    """
    Objective function for Nelder-Mead.
    Minimizes -min_area + penalty for being outside the triangle.
    """
    points = flat_points.reshape(N, 2)
    
    # Penalty for points outside the triangle
    # We check the three half-planes
    # 1. y >= 0
    # 2. y <= sqrt(3) * x  =>  sqrt(3)*x - y >= 0
    # 3. y <= sqrt(3) * (1 - x) => -sqrt(3)*x - y + sqrt(3) >= 0
    
    d1 = points[:, 1] # y
    d2 = S3 * points[:, 0] - points[:, 1]
    d3 = -S3 * points[:, 0] - points[:, 1] + S3
    
    # Penalty is sum of squares of negative distances
    penalty = 0.0
    # We use a large multiplier to enforce constraints
    # Note: d1, d2, d3 should be >= 0. If negative, add penalty.
    neg_d1 = np.clip(-d1, 0, None)
    neg_d2 = np.clip(-d2, 0, None)
    neg_d3 = np.clip(-d3, 0, None)
    
    penalty = 100.0 * (np.sum(neg_d1**2) + np.sum(neg_d2**2) + np.sum(neg_d3**2))
    
    # Calculate min area
    # If points are far outside, area might be large, but penalty dominates.
    # We still need to compute area for the valid part.
    min_area = _min_area(points)
    
    # We want to maximize min_area, so we minimize -min_area
    return -min_area + penalty

def _generate_initial_points(n_samples, seed):
    """
    Generate n_samples distinct initial configurations using Latin Hypercube Sampling.
    """
    rng = np.random.default_rng(seed)
    configs = []
    
    # Use LHS for better coverage
    # We need 22 dimensions (11 points * 2 coords)
    # LHS samples each dimension uniformly in [0, 1]
    # Then we map [0, 1]^2 to the triangle? 
    # Actually, LHS on the bounding box [0, 1] x [0, S3/2] is bad because the triangle is only half the box.
    # Better: Sample x in [0, 1], y in [0, S3*min(x, 1-x)] is hard for LHS directly.
    # Alternative: Sample 22 uniform random numbers, group into pairs (u, v).
    # Map (u, v) in [0,1]^2 to triangle?
    # Standard mapping: x = u, y = v * S3 * (1 - u) if u < 0.5? No.
    # Let's use the property that area of triangle is S3/4.
    # A point (x,y) in the triangle can be generated by:
    # x = 1 - sqrt(u1) * (1 - u2) ... this is getting complicated.
    
    # Simpler: Just use random points in the bounding box and project?
    # Or use the barycentric coordinates.
    # Any point in the triangle is a convex combination of vertices A(0,0), B(1,0), C(0.5, S3/2).
    # P = a*A + b*B + c*C, with a+b+c=1, a,b,c >= 0.
    # We can sample a, b, c from Dirichlet(1,1,1) which is uniform on the simplex.
    
    for _ in range(n_samples):
        # Sample 11 sets of barycentric coordinates
        # Each set (a, b, c) sums to 1.
        # We can generate 2 random numbers per point to determine the 3 barycentric coords.
        # Or just use rng.dirichlet([1, 1, 1], size=N)
        bary = rng.dirichlet([1, 1, 1], size=N)
        
        # Convert barycentric to Cartesian
        # A = (0,0), B = (1,0), C = (0.5, S3/2)
        # P = a*A + b*B + c*C
        # x = 0*a + 1*b + 0.5*c = b + 0.5*c
        # y = 0*a + 0*b + (S3/2)*c = (S3/2)*c
        
        x = bary[:, 1] + 0.5 * bary[:, 2]
        y = (S3 / 2.0) * bary[:, 2]
        
        points = np.column_stack((x, y))
        configs.append(points.flatten())
        
    return configs

def construct():
    """
    Place 11 points using Nelder-Mead optimization with multi-start.
    """
    start_time = time.time()
    time_limit = 110.0
    
    best_points = None
    best_score = -float('inf')
    
    # Number of restarts
    # Nelder-Mead is faster than SA per iteration but might need more restarts.
    # Let's try 30-50 restarts.
    n_restarts = 40
    
    initial_configs = _generate_initial_points(n_restarts, seed=42)
    
    for i in range(n_restarts):
        if time.time() - start_time > time_limit:
            break
            
        x0 = initial_configs[i]
        
        # Nelder-Mead parameters
        # xatol and fatol control stopping criteria
        # maxiter limits iterations
        try:
            res = minimize(
                _objective, 
                x0, 
                method='Nelder-Mead', 
                options={
                    'xatol': 1e-5, 
                    'fatol': 1e-7, 
                    'maxiter': 2000, 
                    'maxfev': 2000,
                    'adaptive': True
                }
            )
            
            if res.success or res.fun < best_score:
                # Check if the result is valid (inside triangle)
                # The penalty should have pushed it inside, but let's verify.
                candidate_points = res.x.reshape(N, 2)
                
                # Project to ensure strict validity
                candidate_points = _project_to_triangle(candidate_points)
                
                score = _min_area(candidate_points)
                
                if score > best_score:
                    best_score = score
                    best_points = candidate_points
                    
        except Exception as e:
            continue
            
    if best_points is None:
        # Fallback: Return a regular grid or random
        return np.full((N, 2), [0.5, S3/6])
        
    return best_points
