"""
Rank-15 tensor decomposition for 2x3x3 matrix multiplication.
"""
import numpy as np

def construct():
    n, m, p = 2, 3, 3
    rank = 15
    
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # Strassen 7 terms for (i in {0,1}, j in {0,1}, k in {0,1})
    # M0 = (a00+a11)(b00+b11)
    U[0,0]=1; U[4,0]=1
    V[0,0]=1; V[7,0]=1
    W[0,0]=1; W[3,0]=1; W[4,0]=1; W[7,0]=1
    
    # M1 = (a01+a11)b00
    U[1,1]=1; U[4,1]=1
    V[0,1]=1
    W[0,1]=-1; W[3,1]=1
    
    # M2 = a00(b10-b00)
    U[0,2]=1
    V[3,2]=1; V[0,2]=-1
    W[0,2]=1; W[3,2]=-1
    
    # M3 = a11(b11-b01)
    U[4,3]=1
    V[7,3]=1; V[4,3]=-1
    W[4,3]=1; W[7,3]=1
    
    # M4 = (a00+a10)b11
    U[0,4]=1; U[3,4]=1
    V[7,4]=1
    W[4,4]=-1; W[7,4]=1
    
    # M5 = (a01-a00)(b00+b10)
    U[1,5]=1; U[0,5]=-1
    V[0,5]=1; V[3,5]=1
    W[0,5]=1
    
    # M6 = (a10-a11)(b01+b11)
    U[3,6]=1; U[4,6]=-1
    V[4,6]=1; V[7,6]=1
    W[7,6]=1
    
    # 8 more terms for remaining entries
    # M7 = a00*b02 -> C[0,2]
    U[0,7]=1; V[2,7]=1; W[5,7]=1
    # M8 = a01*b12 -> C[0,2]
    U[1,8]=1; V[5,8]=1; W[5,8]=1
    # M9 = a02*b22 -> C[0,2]
    U[2,9]=1; V[8,9]=1; W[5,9]=1
    # M10 = a10*b02 -> C[1,2]
    U[3,10]=1; V[2,10]=1; W[6,10]=1
    # M11 = a11*b12 -> C[1,2]
    U[4,11]=1; V[5,11]=1; W[6,11]=1
    # M12 = a12*b22 -> C[1,2]
    U[5,12]=1; V[8,12]=1; W[6,12]=1
    # M13 = (a02+a12)*b20 -> C[0,0], C[1,0]
    U[2,13]=1; U[5,13]=1
    V[6,13]=1
    W[0,13]=1; W[3,13]=1
    # M14 = (a02+a12)*b21 -> C[0,1], C[1,1]
    U[2,14]=1; U[5,14]=1
    V[7,14]=1
    W[1,14]=1; W[4,14]=1
    
    return {
        "U": U.tolist(),
        "V": V.tolist(),
        "W": W.tolist()
    }
