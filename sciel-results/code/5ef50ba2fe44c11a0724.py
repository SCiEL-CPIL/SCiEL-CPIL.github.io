def _hamming_distance(a, b):
    return (a ^ b).bit_count()

def _min_distance(words):
    """Compute minimum pairwise Hamming distance in a list of words."""
    if len(words) < 2:
        return 0
    min_d = 10**9
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            d = (wi ^ words[j]).bit_count()
            if d < min_d:
                min_d = d
                if min_d == 0:
                    return 0
    return min_d

def _is_valid(words, min_dist=6):
    """Check if all pairwise distances are at least min_dist."""
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            if (wi ^ words[j]).bit_count() < min_dist:
                return False
    return True

def _greedy_add(words, candidates, min_dist=6):
    """Try to add candidates to words, keeping those that maintain min_dist."""
    added = 0
    for c in candidates:
        if all((c ^ w).bit_count() >= min_dist for w in words):
            words.append(c)
            added += 1
    return added

