import time
import sys
import numpy as np
import itertools

def construct():
    start_time = time.time()
    deadline = start_time + 115  # Safety margin

    # The goal is to find a 4-coloring of K_n without monochromatic C6.
    # We will attempt n=17 first (known to exist), then n=18.
    # We use a backtracking search with vectorized constraint checking.
    
    def solve(n, time_limit):
        """
        Finds a valid 4-coloring of K_n without mono-C6.
        Returns list of colors or None.
        """
        # Precompute all C6 cycles as tuples of edge indices
        # Edge index mapping: (i, j) -> i*n - i*(i+1)//2 + j - i - 1 
        # This is a standard mapping for upper triangle.
        # Let's use a simpler map for clarity in precomputation, 
        # but for speed in checking, we need the edge indices.
        
        edge_map = {}
        edge_list = []
        idx = 0
        for i in range(n):
            for j in range(i + 1, n):
                edge_map[(i, j)] = idx
                edge_list.append((i, j))
                idx += 1
        
        num_edges = len(edge_list)
        
        # Generate all C6 cycles
        # A C6 is defined by 6 distinct vertices v0..v5.
        # The cycle is (v0-v1-v2-v3-v4-v5-v0).
        # To avoid duplicates, we can fix v0=0? No, that misses cycles not containing 0.
        # We can fix the smallest vertex in the cycle to be v0? 
        # Actually, for checking purposes, we just need the set of edges.
        # Two cycles are the same set of edges if they are the same cycle (up to rotation/reflection).
        # The set of 6 edges uniquely identifies the cycle in a simple graph? 
        # Yes, a 6-cycle is a simple cycle. The set of edges forms the cycle.
        
        cycles = []
        seen_cycles = set()
        
        # Optimization: Only generate cycles where the smallest vertex is 0?
        # No, that's wrong. We need ALL cycles.
        # However, the number of C6 in K17 is C(17,6) * 5! / 2 / 6 ? 
        # Number of C6 in K_n is n! / ((n-6)! * 12).
        # For n=17: 17! / (11! * 12) = (17*16*15*14*13*12) / 12 = 17*16*15*14*13 = 742,560.
        # This is manageable.
        
        # For each set of 6 vertices, there are 5 distinct cycles.
        # 5 * C(17,6) = 5 * 12376 = 61880? 
        # Wait. C(17,6) = 12376.
        # For a fixed set of 6 vertices, how many C6s?
        # (6-1)! / 2 = 60 / 2 = 30? No.
        # Number of distinct cycles on 6 labeled vertices is (6-1)!/2 = 30.
        # So total cycles = 30 * C(17,6) = 30 * 12376 = 371,280.
        
        # Let's generate them.
        # To speed up, we can represent a cycle by its sorted edge indices.
        
        for verts in itertools.combinations(range(n), 6):
            # Generate all permutations of the other 5 vertices?
            # Or just iterate through the 30 unique cycles.
            # A unique cycle can be generated by fixing the first vertex and
            # permuting the rest, then dividing by 2 (reversal) and ensuring
            # the second vertex is smaller than the last? 
            # Standard way: Fix v0. Permute v1..v5. 
            # To avoid rotations, fix v0. 
            # To avoid reversal, require v1 < v5.
            
            v0 = verts[0]
            others = list(verts[1:])
            # We need to consider all vertices, not just those > v0.
            # The combination `verts` is sorted. v0 is the min.
            # But a cycle might not have the global min as v0 in the permutation sense?
            # No, the set of vertices is fixed. The cycle structure is on these 6 vertices.
            # We can just generate all 30 cycles for this set.
            
            # To generate 30 unique cycles on 6 vertices v0..v5:
            # Fix v0. Permute v1..v5.
            # Total perms: 120.
            # Reversal symmetry: (v1..v5) is same as (v5..v1). So 60 unique.
            # Wait, the cycle is undirected.
            # So for a fixed set of 6 vertices, there are 30 distinct cycles.
            
            # Let's just iterate permutations and use a set to deduplicate by edge tuple.
            # This is slower but simpler and robust.
            # Given 12376 sets, and 120 perms each = 1.5M iterations.
            # Inside, we build a tuple of 6 edge indices and check a set.
            # This might take 1-2 seconds in Python. Acceptable.
            
            for perm in itertools.permutations(others):
                # Symmetry breaking: perm[0] < perm[-1]
                if perm[0] > perm[-1]:
                    continue
                
                c_verts = [v0] + list(perm)
                c_edges = []
                for k in range(6):
                    u = c_verts[k]
                    v = c_verts[(k + 1) % 6]
                    if u > v:
                        u, v = v, u
                    c_edges.append(edge_map[(u, v)])
                
                # Sort edges to create a canonical key
                key = tuple(sorted(c_edges))
                if key not in seen_cycles:
                    seen_cycles.add(key)
                    # Store the edge indices (unsorted is fine for checking, 
                    # but sorted helps if we want to dedup later, but we already did)
                    cycles.append(c_edges)
        
        num_cycles = len(cycles)
        
        # Convert cycles to a numpy array for faster access?
        # cycles is a list of lists of ints.
        # We need to check: for a given coloring vector C (length num_edges),
        # does any cycle have all 6 edges with the same color?
        
        # Precompute: for each cycle, the 6 edge indices.
        # cycle_edges = np.array(cycles) # Shape (num_cycles, 6)
        # This uses 371k * 6 * 4 bytes ~ 9 MB. Fine.
        
        cycle_edges = np.array(cycles, dtype=np.int32)
        
        # Backtracking Search
        # We assign colors to edges 0, 1, ..., num_edges-1.
        # State: colors array (length num_edges), initialized to -1.
        
        colors = np.full(num_edges, -1, dtype=np.int8)
        
        # Symmetry Breaking:
        # The first 3 edges (0,0)-(0,1), (0,0)-(0,2), (0,0)-(0,3) can be fixed?
        # Actually, the colors are symmetric. We can fix the first edge to 0.
        # The next edge to 0 or 1?
        # Let's fix edge 0 to 0.
        # This reduces the search space by 4.
        
        # Even better: Fix the colors of the edges incident to vertex 0?
        # There are n-1 edges incident to 0.
        # Due to color symmetry, we can fix the first edge (0,1) to 0.
        # This is a safe symmetry breaking.
        
        # Let's try a more aggressive symmetry breaking if possible, 
        # but fixing edge 0 to 0 is standard.
        
        colors[0] = 0
        
        # We need a fast way to check if the current partial assignment 
        # has already created a mono-C6.
        # A mono-C6 is created only when the 6th edge of that cycle is assigned.
        # So we only need to check cycles that contain the newly assigned edge.
        
        # Precompute: for each edge, which cycles contain it?
        edge_to_cycles = [[] for _ in range(num_edges)]
        for c_idx in range(num_cycles):
            for e_idx in cycle_edges[c_idx]:
                edge_to_cycles[e_idx].append(c_idx)
        
        # Convert to numpy arrays for faster indexing?
        # edge_to_cycles_np = [np.array(lst) for lst in edge_to_cycles]
        
        # For each edge, we store the indices of cycles it belongs to.
        # When we assign color to edge e, we check all cycles in edge_to_cycles[e].
        # For each such cycle, we check if all 6 edges are assigned and have the same color.
        
        # To speed up checking:
        # Maintain a count of colors for each cycle?
        # cycle_color_counts[c_idx] = [count_0, count_1, count_2, count_3, count_unassigned]
        # If count_unassigned > 0, it's not a mono-C6 yet.
        # If count_unassigned == 0, check if max(count_0..3) == 6.
        
        # This requires updating counts for all cycles containing the edge.
        # Average cycles per edge: (6 * num_cycles) / num_edges
        # For n=17: 6 * 371280 / 136 = 1637 cycles per edge.
        # This is quite high. Updating 1600 counters per step might be slow in Python.
        
        # Alternative: Just check the specific cycles when the last edge is assigned.
        # How do we know if it's the last edge?
        # We can check if all other 5 edges in the cycle are assigned.
        # This involves indexing into `colors` 5 times.
        
        # Let's try the direct check approach first.
        
        def is_valid_partial(e_idx, new_color):
            """Check if assigning new_color to e_idx creates a mono-C6."""
            c_indices = edge_to_cycles[e_idx]
            for c_idx in c_indices:
                # Get the 6 edges of this cycle
                edges = cycle_edges[c_idx]
                
                # Check if all edges are assigned
                # One of them is e_idx which is about to be assigned new_color.
                # The other 5 are in colors.
                
                # Optimization: If any of the other 5 is unassigned, skip.
                # We can check this quickly.
                
                # Note: edges is a numpy array of int32.
                # We need to check colors[edges]
                
                # Since e_idx is one of edges, let's find the others.
                # It's faster to just loop through the 6 edges.
                
                all_assigned = True
                target_color = -1
                is_mono = True
                
                for e in edges:
                    if e == e_idx:
                        c = new_color
                    else:
                        c = colors[e]
                        if c == -1:
                            all_assigned = False
                            break
                    
                    if target_color == -1:
                        target_color = c
                    elif c != target_color:
                        is_mono = False
                        break
                
                if all_assigned and is_mono:
                    return False # Conflict
            
            return True
        
        # Backtracking
        # We need to manage the recursion stack or use iterative backtracking.
        # Given the depth (136 edges), recursion limit might be an issue if not set.
        # sys.setrecursionlimit(10000)
        
        # Iterative backtracking is safer and allows time checks.
        
        # State: 
        # - current_edge_idx: 0 to num_edges
        # - colors array
        # - next_color_to_try for each edge?
        
        # Let's use a stack.
        # Each stack item: (edge_idx, next_color_to_try)
        
        # Initialize
        stack = [(0, 0)] # Start with edge 0, try color 0 (it's fixed anyway, but let's handle it)
        # Actually, edge 0 is fixed to 0. So we start with edge 1.
        
        # Wait, if we fix edge 0 to 0, we should start the search from edge 1.
        # But what if edge 0 shouldn't be 0? Symmetry says we can WLOG assume it is.
        
        # Let's refine the stack approach.
        # We process edges in order 0, 1, ..., N-1.
        # For edge i, we try colors 0..3.
        
        # Special case: Edge 0 is fixed to 0.
        
        # Stack: list of (edge_idx, color) representing the path taken.
        # We need to know which color to try next for the current edge.
        
        # Let's use a standard DFS with explicit stack.
        # Stack elements: (edge_idx, next_color)
        
        # Initial state:
        # Edge 0 is assigned 0.
        # We move to Edge 1.
        
        if num_edges == 0:
            return []
        
        # Reset colors
        colors = np.full(num_edges, -1, dtype=np.int8)
        colors[0] = 0
        
        # If n=1, no edges? No, n>=2 for edges.
        
        # Start with edge 1
        stack = [(1, 0)]
        
        # To speed up, we can use a "conflict-directed backjumping" or similar,
        # but simple chronological backtracking might be enough with symmetry breaking.
        
        # However, 4^135 is huge. We need strong pruning.
        # The `is_valid_partial` check is O(degree of edge in cycle graph).
        
        # Let's add a time check inside the loop.
        
        while stack:
            if time.time() > time_limit:
                return None
            
            edge_idx, next_color = stack[-1]
            
            # If we have assigned all edges
            if edge_idx == num_edges:
                return colors.tolist()
            
            # Find a valid color for this edge
            found = False
            while next_color < 4:
                # Skip if this edge is fixed (only edge 0 is, and we start at 1)
                
                if is_valid_partial(edge_idx, next_color):
                    # Accept this color
                    colors[edge_idx] = next_color
                    found = True
                    break
                next_color += 1
            
            if found:
                # Move to next edge
                stack.append((edge_idx + 1, 0))
            else:
                # Backtrack
                stack.pop()
                if not stack:
                    return None
                
                # Update the previous edge's next color
                prev_edge_idx, prev_color = stack[-1]
                stack[-1] = (prev_edge_idx, prev_color + 1)
                
                # Reset colors for the popped edge? 
                # Not strictly necessary if we overwrite, but good for debugging.
                # colors[edge_idx] = -1 (implicit if we don't use it)
        
        return None

    # Try n=18 first? 
    # If n=18 exists, it's a new result. 
    # But n=18 is much harder. 
    # The known bound is 17. 
    # It is highly likely n=18 does NOT exist (R_4(C6)=18). 
    # So trying n=18 first is a waste of time if it's infeasible.
    # We should secure n=17 first.
    
    best_n = 0
    best_colors = None
    
    # Try n=17
    # Time budget: 80s for n=17
    t_start = time.time()
    res_17 = solve(17, t_start + 80)
    
    if res_17 is not None:
        best_n = 17
        best_colors = res_17
    
    # If we found n=17, try n=18 with remaining time?
    # Only if we have significant time left.
    if best_n == 17:
        t_rem = deadline - time.time()
        if t_rem > 20: # At least 20s left
            # Try n=18
            res_18 = solve(18, deadline - 5)
            if res_18 is not None:
                best_n = 18
                best_colors = res_18
    
    # If n=17 failed (which would be bad), try n=16?
    # The seed program returns 17. We must match or beat it.
    # If our solver is too slow for 17, we need a fallback.
    
    if best_n == 0:
        # Fallback: Return a known valid n=17 coloring if we can construct it heuristically?
        # Or return n=9 valid coloring?
        # The seed program's fallback was n=9.
        # Let's try a quick local search for n=17 if exact search failed?
        # No, keep it simple. If exact search fails, return n=9 fallback.
        # But wait, the exact search *should* work for n=17 with symmetry breaking.
        # If it times out, it returns None.
        
        # Let's add a simple fallback: Random local search for n=17 with short time.
        # If that fails, n=9.
        
        # Actually, let's just return n=9 fallback to ensure validity.
        n = 9
        # Generate a valid coloring for K9
        # A 3-coloring of K9? 
        # R_3(C6) = 10? If R_3(C6)=10, then K9 3-coloring has no mono C6.
        # Let's use a cyclic coloring for n=9.
        colors = []
        for i in range(n):
            for j in range(i+1, n):
                # Color based on distance
                d = (j - i) % n
                # Map to 0,1,2
                # 0,1,2,3,4,5,6,7,8
                # Distances: 1,2,3,4,5,6,7,8
                # We need to avoid mono C6.
                # A proper 3-coloring of K9 is impossible (chromatic number 9).
                # But we just need no mono C6.
                # Let's use the seed's fallback formula:
                # min(j - i, n - j + i) - 1
                c = min(j - i, n - j + i) - 1
                if c >= 4: c = 3
                colors.append(c)
        return {'n': n, 'colors': colors}
    
    return {'n': best_n, 'colors': best_colors}

