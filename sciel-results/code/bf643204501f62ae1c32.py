import time

def construct():
    start_time = time.time()
    deadline = start_time + 50
    
    n = 12
    
    S = {0}
    D = set()
    seq = []
    
    for i in range(n):
        if time.time() > deadline:
            # Fallback to powers of 2
            return [1 << j for j in range(n)]
            
        if i == 0:
            x = 1
        else:
            x = 1
            while x in D:
                x += 1
        
        seq.append(x)
        
        # Update S
        # S_new = S union (S + x)
        new_S = set(S)
        for s in S:
            new_S.add(s + x)
        S = new_S
        
        # Update D incrementally
        # D_new = D union { |d - x| : d in D union {0}, |d-x| > 0 }
        # We iterate over D and 0
        new_D = set(D)
        # Add differences involving the shift
        # d ranges over D and 0
        # We can just iterate over D and check 0 separately
        # Or add 0 to a temporary list
        
        # Optimization: 
        # The new differences are generated by pairs (s, s'+x) and (s'+x, s)
        # which correspond to |(s-s') - x| where s-s' can be any value in D_full
        # D_full = D union {0}
        
        # Iterate D
        for d in D:
            nd = d - x
            if nd > 0:
                new_D.add(nd)
            nd2 = x - d
            if nd2 > 0:
                new_D.add(nd2)
        
        # Handle d=0
        # |0 - x| = x
        new_D.add(x)
        
        D = new_D
        
    return seq
