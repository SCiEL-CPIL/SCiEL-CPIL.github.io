DIMENSIONS = [2, 2, 3]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 11
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Strassen for 2x2x2 part (k=0,1)
    # r=0: P1 = (a00+a11)(b00+b11)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[4][0] = 1
    W[0][0] = 1; W[3][0] = 1
    
    # r=1: P2 = (a10+a11)b00
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[1][1] = 1
    
    # r=2: P3 = a00(b01-b11)
    U[0][2] = 1
    V[1][2] = 1; V[4][2] = -1
    W[0][2] = 1; W[2][2] = -1
    
    # r=3: P4 = a11(b00-b10)
    U[3][3] = 1
    V[0][3] = 1; V[3][3] = -1
    W[1][3] = 1; W[3][3] = -1
    
    # r=4: P5 = (a00+a01)b11
    U[0][4] = 1; U[1][4] = 1
    V[4][4] = 1
    W[0][4] = 1; W[2][4] = 1
    
    # r=5: P6 = (a10-a00)(b00+b01)
    U[2][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    W[1][5] = 1; W[3][5] = 1
    
    # r=6: P7 = (a01-a11)(b10+b11)
    U[1][6] = 1; U[3][6] = -1
    V[3][6] = 1; V[4][6] = 1
    W[0][6] = 1; W[2][6] = 1
    
    # Schoolbook for 2x2x1 part (k=2)
    # r=7: a00*b02
    U[0][7] = 1
    V[2][7] = 1
    W[4][7] = 1
    
    # r=8: a01*b12
    U[1][8] = 1
    V[5][8] = 1
    W[4][8] = 1
    
    # r=9: a10*b02
    U[2][9] = 1
    V[2][9] = 1
    W[5][9] = 1
    
    # r=10: a11*b12
    U[3][10] = 1
    V[5][10] = 1
    W[5][10] = 1
    
    return {"U": U, "V": V, "W": W}
# EVOLVE-BLOCK-END
