import time
import random

DIMENSIONS = [2, 2, 3]

def construct():
    start_time = time.time()
    
    n, m, p = DIMENSIONS  # 2, 2, 3
    
    # Known optimal-ish rank: 11 (Strassen for 2x2x2 + schoolbook for 2x2x1)
    rank = 11
    
    U = [[0] * rank for _ in range(n * m)]  # 4 x 11
    V = [[0] * rank for _ in range(m * p)]  # 6 x 11
    W = [[0] * rank for _ in range(p * n)]  # 6 x 11
    
    # Strassen decomposition for 2x2x2 (first 2 columns of B)
    # Rank 7
    # A = [[a, b], [c, d]]
    # B = [[e, f], [g, h]] (only first 2 columns matter, so g, h correspond to B[1,0], B[1,1])
    # Wait, B is 2x3. Let's denote B as:
    # [[b00, b01, b02],
    #  [b10, b11, b12]]
    
    # For the 2x2 part (columns 0,1):
    # C00 = a*e + b*g
    # C01 = a*f + b*h
    # C10 = c*e + d*g
    # C11 = c*f + d*h
    
    # Strassen:
    # M1 = (a+d)(e+h)
    # M2 = (c+d)e
    # M3 = a(f-h)
    # M4 = c(g-e)
    # M5 = (a+b)h
    # M6 = (c-d)(g+h)
    # M7 = (b-d)(f+h)
    
    # C00 = M1 - M4 + M5 - M7
    # C01 = M3 + M4 - M5 + M6
    # C10 = M2 + M5 - M3 - M6
    # C11 = M1 - M2 + M3 + M7
    
    # U indices: i*m + j. i in 0..1, j in 0..1
    # U[0] = [u00, u01, u02, u03, u04, u05, u06, 0, 0, 0, 0] (for A[0,0])
    # U[1] = [u10, u11, u12, u13, u14, u15, u16, 0, 0, 0, 0] (for A[0,1])
    # U[2] = [u20, u21, u22, u23, u24, u25, u26, 0, 0, 0, 0] (for A[1,0])
    # U[3] = [u30, u31, u32, u33, u34, u35, u36, 0, 0, 0, 0] (for A[1,1])
    
    # V indices: j*p + k. j in 0..1, k in 0..2
    # V[0] = [v00, v01, v02, v03, v04, v05, v06, 1, 0, 0, 0] (for B[0,0]) -> wait, V[0,0] is B[0,0], V[0,1] is B[0,1], V[0,2] is B[0,2]
    # V[1] = [v10, v11, v12, v13, v14, v15, v16, 0, 1, 0, 0] (for B[0,1])
    # V[2] = [v20, v21, v22, v23, v24, v25, v26, 0, 0, 1, 0] (for B[0,2])
    # V[3] = [v30, v31, v32, v33, v34, v35, v36, 0, 0, 0, 1] (for B[1,0])
    # V[4] = [v40, v41, v42, v43, v44, v45, v46, 0, 0, 0, 0] (for B[1,1])
    # V[5] = [v50, v51, v52, v53, v54, v55, v56, 0, 0, 0, 0] (for B[1,2])
    
    # W indices: k*n + i. k in 0..2, i in 0..1
    # W[0] = [w00, w01, w02, w03, w04, w05, w06, 0, 0, 0, 0] (for C[0,0])
    # W[1] = [w10, w11, w12, w13, w14, w15, w16, 0, 0, 0, 0] (for C[0,1])
    # W[2] = [w20, w21, w22, w23, w24, w25, w26, 0, 0, 0, 0] (for C[0,2])
    # W[3] = [w30, w31, w32, w33, w34, w35, w36, 0, 0, 0, 0] (for C[1,0])
    # W[4] = [w40, w41, w42, w43, w44, w45, w46, 0, 0, 0, 0] (for C[1,1])
    # W[5] = [w50, w51, w52, w53, w54, w55, w56, 0, 0, 0, 0] (for C[1,2])
    
    # Strassen part (r = 0..6)
    # M1 = (a+d)(e+h)
    # U: a=1, d=1 -> U[0][0]=1, U[3][0]=1
    # V: e=1, h=1 -> V[0][0]=1 (B[0,0]), V[4][0]=1 (B[1,1])
    # W: e=1, h=1 -> W[0][0]=1 (C[0,0]), W[1][0]=1 (C[0,1]), W[3][0]=1 (C[1,0]), W[4][0]=1 (C[1,1])
    # Wait, W indices: W[k*n + i].
    # C00 is W[0]. C01 is W[1]. C10 is W[3]. C11 is W[4].
    # M1 contributes to all Cij.
    # W[0][0] = 1, W[1][0] = 1, W[3][0] = 1, W[4][0] = 1.
    
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[4][0] = 1
    W[0][0] = 1; W[1][0] = 1; W[3][0] = 1; W[4][0] = 1
    
    # M2 = (c+d)e
    # U: c=1, d=1 -> U[2][1]=1, U[3][1]=1
    # V: e=1 -> V[0][1]=1
    # W: e=1 -> W[0][1]=1, W[3][1]=1
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[0][1] = 1; W[3][1] = 1
    
    # M3 = a(f-h)
    # U: a=1 -> U[0][2]=1
    # V: f=1, h=-1 -> V[1][2]=1, V[4][2]=-1
    # W: f=1, h=1 -> W[1][2]=1, W[4][2]=1
    U[0][2] = 1
    V[1][2] = 1; V[4][2] = -1
    W[1][2] = 1; W[4][2] = 1
    
    # M4 = c(g-e)
    # U: c=1 -> U[2][3]=1
    # V: g=1, e=-1 -> V[3][3]=1, V[0][3]=-1
    # W: g=1, e=1 -> W[0][3]=1, W[3][3]=1
    U[2][3] = 1
    V[3][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[3][3] = 1
    
    # M5 = (a+b)h
    # U: a=1, b=1 -> U[0][4]=1, U[1][4]=1
    # V: h=1 -> V[4][4]=1
    # W: h=1 -> W[1][4]=1, W[4][4]=1
    U[0][4] = 1; U[1][4] = 1
    V[4][4] = 1
    W[1][4] = 1; W[4][4] = 1
    
    # M6 = (c-d)(g+h)
    # U: c=1, d=-1 -> U[2][5]=1, U[3][5]=-1
    # V: g=1, h=1 -> V[3][5]=1, V[4][5]=1
    # W: g=1, h=1 -> W[0][5]=1, W[3][5]=1
    U[2][5] = 1; U[3][5] = -1
    V[3][5] = 1; V[4][5] = 1
    W[0][5] = 1; W[3][5] = 1
    
    # M7 = (b-d)(f+h)
    # U: b=1, d=-1 -> U[1][6]=1, U[3][6]=-1
    # V: f=1, h=1 -> V[1][6]=1, V[4][6]=1
    # W: f=1, h=1 -> W[1][6]=1, W[4][6]=1
    U[1][6] = 1; U[3][6] = -1
    V[1][6] = 1; V[4][6] = 1
    W[1][6] = 1; W[4][6] = 1
    
    # Schoolbook part for column 2 (k=2) (r = 7..10)
    # C02 = a*b02 + b*b12
    # C12 = c*b02 + d*b12
    # r=7: a*b02. U[0][7]=1, V[2][7]=1, W[2][7]=1
    # r=8: b*b12. U[1][8]=1, V[5][8]=1, W[2][8]=1
    # r=9: c*b02. U[2][9]=1, V[2][9]=1, W[5][9]=1
    # r=10: d*b12. U[3][10]=1, V[5][10]=1, W[5][10]=1
    
    U[0][7] = 1; V[2][7] = 1; W[2][7] = 1
    U[1][8] = 1; V[5][8] = 1; W[2][8] = 1
    U[2][9] = 1; V[2][9] = 1; W[5][9] = 1
    U[3][10] = 1; V[5][10] = 1; W[5][10] = 1
    
    return {"U": U, "V": V, "W": W}
