        # Fast Approximation: 
        # The Gaussian smoothing of a function f(r) is roughly f(r) + sigma^2/2 * f''(r).
        # Let's use this Taylor expansion for the "DFA" step.
        
        # V(r) = u^2 - 2u, u = exp(rho(1-r))
        # V'(r) = -2*rho*u*(u-1)
        # V''(r) = -2*rho * [ u' (u-1) + u u' ] = -2*rho * [ -rho*u (u-1) - rho*u^2 ]
