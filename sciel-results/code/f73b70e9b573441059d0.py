"""
Strategy: Parallel Multi-Island Nelder-Mead with Error-Repair Mutation.
Rationale: The current program uses a sequential multi-start Nelder-Mead approach. 
We switch to a population-based strategy with multiple independent "islands" (simplexes) running in parallel. 
This increases robustness against local minima and allows for better exploration of the search space.
The key structural change is the introduction of "error-repair" mutation: when a child point generated by a Nelder-Mead operation 
is found to be outside the domain [-5, 5]^5 or otherwise "invalid" (though here the function clips, so we focus on domain boundaries), 
we "repair" it by projecting it back into the domain. More importantly, we use this repair mechanism to inject diversity: 
if a simplex stagnates, we mutate its worst point by adding a random perturbation, and if that point is out of bounds, 
we repair it. This "error-repair" operator is designed to test whether repairing invalid candidates increases the chance of improving the island.
"""

import numpy as np
import time

class Optimizer:
    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

    def __call__(self, func):
        start_time = time.time()
        deadline = start_time + 290.0  # Safety margin
        n_calls = 0
        dim = self.dim
        budget = self.budget
        rng = np.random.default_rng(42)

        best_x = np.zeros(dim)
        best_f = float('inf')

        def call_f(x):
            nonlocal n_calls, best_x, best_f
            if n_calls >= budget:
                return None
            n_calls += 1
            f_val = func(x)
            if f_val < best_f:
                best_f = f_val
                best_x = x.copy()
            return f_val

        def repair(x):
            """
            Error-repair operator: project x into the domain [-5, 5]^dim.
            If x is already in the domain, return it unchanged.
            Otherwise, clip it to the domain.
            """
            return np.clip(x, -5.0, 5.0)

        class Island:
            def __init__(self, x0):
                self.simplex = np.zeros((dim + 1, dim))
                self.simplex[0] = x0
                for i in range(1, dim + 1):
                    self.simplex[i] = x0.copy()
                    self.simplex[i][i - 1] += 0.5  # Larger initial step for exploration
                self.fvals = np.zeros(dim + 1)
                for i in range(dim + 1):
                    f = call_f(self.simplex[i])
                    if f is None:
                        self.fvals[i] = float('inf')
                    else:
                        self.fvals[i] = f
                self.sort_simplex()
                self.stagnation_counter = 0
                self.best_f = self.fvals[0]

            def sort_simplex(self):
                idx = np.argsort(self.fvals)
                self.simplex = self.simplex[idx]
                self.fvals = self.fvals[idx]

            def step(self):
                """
                Perform one Nelder-Mead step.
                Returns True if a new point was evaluated, False if budget exhausted.
                """
                if n_calls >= budget:
                    return False

                # Check convergence
                if np.std(self.fvals) < 1e-10:
                    self.stagnation_counter += 1
                    return True

                centroid = np.mean(self.simplex[:-1], axis=0)
                worst = self.simplex[-1]
                f_worst = self.fvals[-1]

                # Reflection
                x_r = centroid + 1.0 * (centroid - worst)
                x_r = repair(x_r)
                f_r = call_f(x_r)
                if f_r is None:
                    return False

                if f_r < self.fvals[0]:
                    # Expansion
                    x_e = centroid + 2.0 * (x_r - centroid)
                    x_e = repair(x_e)
                    f_e = call_f(x_e)
                    if f_e is None:
                        return False
                    if f_e < f_r:
                        self.simplex[-1] = x_e
                        self.fvals[-1] = f_e
                    else:
                        self.simplex[-1] = x_r
                        self.fvals[-1] = f_r
                elif f_r < f_worst:
                    self.simplex[-1] = x_r
                    self.fvals[-1] = f_r
                else:
                    # Contraction
                    x_c = centroid + 0.5 * (worst - centroid)
                    x_c = repair(x_c)
                    f_c = call_f(x_c)
                    if f_c is None:
                        return False
                    if f_c < f_worst:
                        self.simplex[-1] = x_c
                        self.fvals[-1] = f_c
                    else:
                        # Shrink
                        for i in range(1, dim + 1):
                            self.simplex[i] = self.simplex[0] + 0.5 * (self.simplex[i] - self.simplex[0])
                            f = call_f(self.simplex[i])
                            if f is None:
                                return False
                            self.fvals[i] = f

                self.sort_simplex()
                if self.fvals[0] < self.best_f:
                    self.best_f = self.fvals[0]
                    self.stagnation_counter = 0
                else:
                    self.stagnation_counter += 1

                return True

            def mutate(self):
                """
                Error-repair mutation: replace the worst point with a random perturbation of the best point.
                If the new point is out of bounds, repair it.
                """
                if n_calls >= budget:
                    return False

                # Perturb the best point
                x_new = self.simplex[0] + rng.normal(0, 1.0, dim)
                x_new = repair(x_new)
                f_new = call_f(x_new)
                if f_new is None:
                    return False

                # Replace the worst point
                self.simplex[-1] = x_new
                self.fvals[-1] = f_new
                self.sort_simplex()
                return True

        # Initialize islands
        n_islands = 5
        islands = []
        # First island starts at 0
        islands.append(Island(np.zeros(dim)))
        # Other islands start at random points
        for _ in range(n_islands - 1):
            x_start = rng.uniform(-4, 4, dim)
            islands.append(Island(x_start))

        # Main loop
        while n_calls < budget and time.time() < deadline - 5:
            # Rotate through islands
            for island in islands:
                if n_calls >= budget or time.time() > deadline - 5:
                    break

                # If island is stagnating, mutate it
                if island.stagnation_counter > 20:
                    island.mutate()
                    island.stagnation_counter = 0
                else:
                    island.step()

        return best_x, best_f
