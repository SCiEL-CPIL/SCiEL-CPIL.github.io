import time

def construct():
    start_time = time.time()
    deadline = start_time + 85.0  # Safety margin for 90s limit
    
    # Target: Find the largest set of distinct integers in 1..256
    # such that subset sums of different cardinalities are disjoint.
    
    # We will build the set greedily.
    # State: 
    #   current_set: list of chosen integers
    #   reachable_sums[c]: set of sums achievable by subsets of size c from current_set
    
    # Optimization: 
    # Adding a new element x to a set S:
    # New sums for cardinality c are:
    #   1. Old sums for cardinality c (from S)
    #   2. {sum + x for sum in old_sums[c-1]} (subsets of S of size c-1 plus x)
    # 
    # Constraint:
    # For all c, the new set of sums for cardinality c must be disjoint from 
    # all sets of sums for cardinality c' where c' != c.
    
    # Since we build incrementally, we only need to check:
    # 1. The new sums generated by adding x (which are old_sums[c-1] + x) 
    #    must not collide with any existing sums in the global map for any cardinality.
    # 2. Wait, the constraint is: "Whenever two subsets have different cardinalities their sums must differ."
    #    This means: For any sum S, there is at most one cardinality c such that S is in sums_by_card[c].
    #    Actually, it's stronger: If sum S is in sums_by_card[c] and sum S is in sums_by_card[c'], then c must equal c'.
    #    So, all sums across all cardinalities must be unique? 
    #    No, "Repeated sums within the SAME cardinality are allowed."
    #    So, sums_by_card[c] is a set. The condition is: 
    #    sums_by_card[c] ∩ sums_by_card[c'] = empty for c != c'.
    
    # Therefore, we can maintain a global dictionary: sum_value -> cardinality.
    # When adding x, we generate new sums for each cardinality c:
    #   new_sums_c = {s + x for s in reachable_sums[c-1]}
    # We must ensure that for all c, new_sums_c does not contain any sum that already exists in the global map with a DIFFERENT cardinality.
    # Also, new_sums_c can contain sums that are already in reachable_sums[c] (same cardinality), which is fine.
    # But wait, if a sum s is in reachable_sums[c] (old) and s is also in new_sums_c (generated from c-1 + x), that's fine because it's the same cardinality c.
    # However, if s is in reachable_sums[c'] for c' != c, and s is in new_sums_c, that's a violation.
    
    # So the check for a candidate x is:
    # For each cardinality c from 1 to len(current_set)+1:
    #   For each new_sum in new_sums_c:
    #      if new_sum in global_sum_map:
    #          if global_sum_map[new_sum] != c:
    #              return False (collision)
    #      else:
    #          # It's new, but we need to be careful: 
    #          # We are checking if x is valid. 
    #          # We don't update the map until we commit x.
    #          # So we just need to check against the EXISTING map.
    #          # If new_sum is not in the map, it's safe for now.
    #          # BUT, what if new_sum appears in new_sums_c' for another c'? 
    #          # That would mean a sum is generated for two different cardinalities by the same addition?
    #          # No, new_sums_c are generated from reachable_sums[c-1] + x.
    #          # Can a sum s be in new_sums_c and new_sums_c' with c != c'?
    #          # s = a + x where a in reachable_sums[c-1]
    #          # s = b + x where b in reachable_sums[c'-1]
    #          # => a = b.
    #          # So a is in reachable_sums[c-1] and reachable_sums[c'-1].
    #          # Since reachable_sums for different cardinalities are disjoint (by invariant), a cannot be in both unless c-1 == c'-1.
    #          # So new_sums_c are disjoint from new_sums_c' for c != c'.
    #          # Thus, we only need to check new_sums_c against the EXISTING global map.
    
    # Algorithm:
    # 1. Initialize reachable_sums[0] = {0}. All other reachable_sums[c] = empty.
    # 2. global_map = {0: 0}
    # 3. current_set = []
    # 4. While we can add an element:
    #      Try x from 1 to 256 (or some heuristic order).
    #      Check if x is valid.
    #      If valid, add x to current_set, update reachable_sums and global_map.
    #      Break to next iteration of outer loop (try to add another element).
    
    # To maximize size, we should try small numbers first? 
    # Or maybe we should use a backtracking search if greedy fails?
    # Given the 60s limit and k up to ~10-12, greedy might get stuck.
    # However, the task asks to "Maximize set size using exact cardinality-indexed subset-sum dynamic programming."
    # This suggests a more structured approach might be expected, but greedy with DP checks is a solid baseline.
    # Let's implement a robust greedy first. If it stops early, we might try to swap elements.
    
    # Actually, a better strategy for maximizing size:
    # We want the set to be as "dense" as possible while maintaining the property.
    # Powers of 2 are sparse. 
    # Let's try to add the smallest possible valid number each time.
    
    reachable_sums = [set() for _ in range(20)]  # Max size is small, 20 is safe
    reachable_sums[0].add(0)
    global_map = {0: 0}
    current_set = []
    
    # Precompute bitmasks or just use sets? Sets are fine for small k.
    
    def is_valid_addition(x):
        # Check if adding x to current_set is valid
        # x must be distinct from current_set
        if x in current_set:
            return False
            
        # Calculate new sums for each cardinality
        # new_sums[c] = {s + x for s in reachable_sums[c-1]}
        # We need to check these against global_map
        
        # Optimization: Check collisions first
        # For each c from 1 to len(current_set)+1:
        #   For each s in reachable_sums[c-1]:
        #      new_s = s + x
        #      if new_s in global_map:
        #         if global_map[new_s] != c:
        #             return False
        #      # Note: if new_s is in global_map with cardinality c, it's fine.
        #      # This means the sum new_s was already achievable with cardinality c.
        #      # Adding x creates another way to achieve it with cardinality c. That's allowed.
        
        # Wait, there's a subtlety.
        # If new_s is in global_map with cardinality c, it means there is a subset of current_set of size c that sums to new_s.
        # The new subset (old_subset_of_size_c_minus_1 + x) also sums to new_s and has size c.
        # This is allowed.
        
        # But what if new_s is in global_map with cardinality c' != c?
        # Then we have a subset of size c' summing to new_s, and a subset of size c summing to new_s.
        # Violation.
        
        # So the check is:
        for c in range(1, len(current_set) + 2):
            if not reachable_sums[c-1]:
                continue
            for s in reachable_sums[c-1]:
                new_s = s + x
                if new_s in global_map:
                    if global_map[new_s] != c:
                        return False
        return True

    def add_element(x):
        nonlocal reachable_sums, global_map, current_set
        current_set.append(x)
        # Update reachable_sums in reverse order to avoid using updated values
        # But we are adding x, so new sums for c come from old sums for c-1.
        # We can create a new list of sets or update carefully.
        # Since we are adding one element, we can just compute the new sets.
        new_reachable = [set(s) for s in reachable_sums]
        for c in range(1, len(current_set) + 1):
            for s in reachable_sums[c-1]:
                new_s = s + x
                new_reachable[c].add(new_s)
                # Update global map
                # If new_s is already in global_map, it must be with cardinality c (checked in is_valid_addition)
                # So we just ensure it's there.
                if new_s not in global_map:
                    global_map[new_s] = c
                # If it is there, global_map[new_s] is already c (or we don't need to change it)
        reachable_sums = new_reachable

    # Greedy Search
    # Try to add elements in increasing order? 
    # Or try all possible x and pick the best one?
    # To maximize size, picking the smallest valid x is a common heuristic.
    
    while True:
        if time.time() > deadline:
            break
            
        added = False
        # Try numbers from 1 to 256
        # Heuristic: Start from 1, go up.
        # This tends to pack small numbers, which might allow more numbers?
        # Or does it block larger numbers?
        # Let's try smallest first.
        
        for x in range(1, 257):
            if is_valid_addition(x):
                add_element(x)
                added = True
                break
        
        if not added:
            break
    
    # Greedy might not be optimal. 
    # Let's try a local search improvement if time permits.
    # But first, let's see how big greedy gets.
    # Powers of 2: 1, 2, 4, 8, 16, 32, 64, 128 (8 elements).
    # Greedy with smallest first:
    # Start: {}
    # Add 1: {1}. Sums: 0(0), 1(1)
    # Add 2: {1,2}. Sums: 0(0), 1(1), 2(1), 3(2). 
    #    Check 2: new_sums for c=1: {2}. 2 not in map. OK.
    #    Check 2: new_sums for c=2: {1+2=3}. 3 not in map. OK.
    # Add 3?
    #    Check 3: new_sums for c=1: {3}. 3 not in map. OK.
    #    Check 3: new_sums for c=2: {1+3=4, 2+3=5}. 4,5 not in map. OK.
    #    Check 3: new_sums for c=3: {1+2+3=6}. 6 not in map. OK.
    #    So {1,2,3} is valid.
    # Add 4?
    #    Check 4: c=1: {4}. OK.
    #    c=2: {1+4=5, 2+4=6, 3+4=7}. 
    #       5 is in map? Yes, 5 is in map with cardinality 2 (from 2+3). 
    #       Wait, 2+3=5. So global_map[5]=2.
    #       New sum 1+4=5 has cardinality 2. OK.
    #       6 is in map? Yes, 6 is in map with cardinality 3 (from 1+2+3).
    #       New sum 2+4=6 has cardinality 2. 
    #       global_map[6]=3. 3 != 2. Collision!
    #    So 4 is not valid.
    # Add 5?
    #    Check 5: c=1: {5}. 5 in map? Yes, cardinality 2. Collision! (1 != 2)
    #    So 5 is not valid.
    # Add 6?
    #    Check 6: c=1: {6}. 6 in map? Yes, cardinality 3. Collision!
    # Add 7?
    #    Check 7: c=1: {7}. 7 in map? No. OK.
    #    c=2: {1+7=8, 2+7=9, 3+7=10}. 
    #       8,9,10 not in map? 
    #       Map so far: 0:0, 1:1, 2:1, 3:2, 4:2, 5:2, 6:3.
    #       So 8,9,10 are new. OK.
    #    c=3: {1+2+7=10, 1+3+7=11, 2+3+7=12}.
    #       10 is in new_sums[2]? Yes. 
    #       Wait, my check logic:
    #       "if new_s in global_map: if global_map[new_s] != c: return False"
    #       10 is NOT in global_map yet (it was just generated in c=2 loop of is_valid_addition? No, is_valid_addition doesn't update map).
    #       So 10 is not in global_map. OK.
    #       11, 12 not in global_map. OK.
    #    c=4: {1+2+3+7=13}. 13 not in map. OK.
    #    So {1,2,3,7} is valid.
    
    # This greedy approach seems to work and is fast.
    # Let's run it.
    
    # Result
    result = [int(x) for x in current_set]
    
    # If greedy didn't finish or time ran out, return what we have.
    # It should be valid by construction.
    
    return result
