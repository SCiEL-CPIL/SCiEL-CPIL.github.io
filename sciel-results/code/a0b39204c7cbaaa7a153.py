import math
from collections import deque

TARGET = 123457

def linear_sieve(n):
    """Generate all primes up to n using linear sieve."""
    is_prime = [True] * (n + 1)
    is_prime[0] = is_prime[1] = False
    primes = []
    for i in range(2, n + 1):
        if is_prime[i]:
            primes.append(i)
        for p in primes:
            if i * p > n:
                break
            is_prime[i * p] = False
            if i % p == 0:
                break
    return primes

def construct():
    # Precompute all primes up to TARGET
    primes = linear_sieve(TARGET)
    
    # Start with 1 as the only 2-smooth number (before adding prime 2? 
    # Actually, 1 is 1-smooth. We start with smooth_set = {1}.
    # When we add prime p, we generate numbers formed by multiplying existing smooth numbers by powers of p.
    
    smooth_set = {1}
    
    for p in primes:
        # Generate new numbers by multiplying existing smooth numbers by p, p^2, ...
        # We use a queue to process new numbers generated by p
        # We need to be careful not to add numbers that were already in the set from previous primes.
        
        # To avoid re-processing, we can keep track of numbers added in this step or just check membership.
        # Since we check `if v not in smooth_set`, it's safe.
        
        # We iterate over a snapshot of the current smooth_set to generate first level multiples.
        # Then we process those new multiples to generate higher powers.
        
        # Optimization: 
        # The set `smooth_set` contains all numbers composed of primes < p.
        # We want to add numbers of the form s * p^k where s is in smooth_set and k >= 1.
        
        # We can do this by iterating through the current smooth_set.
        # For each s, we compute v = s * p.
        # If v <= TARGET and v not in smooth_set, add it to smooth_set and to a queue.
        # Then pop from queue, multiply by p, etc.
        
        queue = deque()
        
        # We need to iterate over the set as it was BEFORE adding any new p-multiples.
        # Otherwise, we might use a new element to generate another new element in the same step,
        # which is fine, but we must ensure we don't miss any.
        # Actually, if we add v to smooth_set and queue, and later process v from queue,
        # we generate v*p. This is correct.
        # The only issue is if we iterate over smooth_set while modifying it.
        # So we take a snapshot of the keys.
        
        # However, taking a snapshot of a potentially large set is O(N).
        # Is there a way to avoid it?
        # We can store the list of numbers added in the *previous* prime step? No, that's not enough.
        # We need all numbers composed of primes < p.
        
        # Let's stick to the snapshot for correctness and simplicity, as the set size for small primes is not huge.
        # For p=2, size=1.
        # For p=3, size=5 (1,2,4,8,16... wait, 2-smooth up to 123457 is ~17 numbers).
        # The size grows slowly.
        
        current_items = list(smooth_set)
        
        for s in current_items:
            v = s * p
            if v <= TARGET:
                if v not in smooth_set:
                    smooth_set.add(v)
                    queue.append(v)
                # else: v already exists, no need to queue
        
        # Now process the queue to add higher powers
        while queue:
            v = queue.popleft()
            next_v = v * p
            if next_v <= TARGET:
                if next_v not in smooth_set:
                    smooth_set.add(next_v)
                    queue.append(next_v)
        
        # Check for solution
        # We check if there exists a in smooth_set such that TARGET - a is in smooth_set.
        # To avoid duplicates (a, b) and (b, a), we can check a <= TARGET/2, but it's not strictly necessary for correctness, just efficiency.
        # Since we just need *any* pair, we can iterate.
        
        # Optimization: iterate over the smaller of the two sets? They are the same set.
        # Just iterate over smooth_set.
        for a in smooth_set:
            b = TARGET - a
            if b in smooth_set:
                # Ensure a and b are positive
                if a > 0 and b > 0:
                    return [a, b]
    
    # Fallback
    return [1, TARGET - 1]

