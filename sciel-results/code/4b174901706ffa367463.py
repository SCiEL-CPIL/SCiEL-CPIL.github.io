"""3D Container Loading: 2D Skyline Floor-Map with Best-Fit-Decreasing."""
import time
import itertools

def load(boxes, container):
    start = time.time()
    deadline = start + 100.0
    W, H, D = int(container[0]), int(container[1]), int(container[2])
    n = len(boxes)
    
    # Fallback for very large containers
    if W * H * D > 20_000_000:
        placements, x, y, z = [], 0, 0, 0
        for w, h, d in boxes:
            if x + w > W:
                x, y = 0, y + h
            if y + h > H:
                y, z = 0, z + d
            if z + d > D:
                placements.append((-1, 0, 0, 0, w, h, d))
            else:
                placements.append((0, x, y, z, w, h, d))
                x += w
        return placements

    # Occupancy grid for fast overlap checks
    # Using a flat list of booleans or integers
    occ = bytearray(W * H * D)
    
    def idx(x, y, z):
        return x + W * (y + H * z)

    def fits(x, y, z, w, h, d):
        if x + w > W or y + h > H or z + d > D:
            return False
        # Check bounds
        for dz in range(d):
            base_z = z + dz
            for dy in range(h):
                base_y = y + dy
                base = base_y * W * H + base_z * W * H
                for dx in range(w):
                    if occ[base + dx + base_y * W]: # Wait, index calculation
                        return False
        # Let's use a simpler index: (z * H + y) * W + x
        # Redefine idx for clarity in fits/place
        return True

    # Correct index function
    def idx(x, y, z):
        return (z * H + y) * W + x

    def fits(x, y, z, w, h, d):
        if x + w > W or y + h > H or z + d > D:
            return False
        for dz in range(d):
            for dy in range(h):
                base = idx(x, y + dy, z + dz)
                for dx in range(w):
                    if occ[base + dx]:
                        return False
        return True

    def place(x, y, z, w, h, d):
        for dz in range(d):
            for dy in range(h):
                base = idx(x, y + dy, z + dz)
                for dx in range(w):
                    occ[base + dx] = 1

    # Skyline representation: list of (x, y, z) candidates
    # We maintain a set of "corners" where new boxes can start
    # Initially (0,0,0)
    skyline = [(0, 0, 0)]
    
    # To keep skyline small, we can prune dominated points
    # A point (x1, y1, z1) dominates (x2, y2, z2) if x1<=x2, y1<=y2, z1<=z2 and at least one is strict
    # But for packing, we usually want the "lowest" available spot.
    # A simpler skyline approach: For each (x,y) column, keep the minimum z.
    # But that's O(W*H).
    # Let's stick to a set of candidate points generated by box corners.
    
    # Order boxes: Volume descending
    order = sorted(range(n), key=lambda i: boxes[i][0] * boxes[i][1] * boxes[i][2], reverse=True)
    
    placements = [None] * n
    
    # Helper to generate orientations
    def get_orientations(w, h, d):
        seen = set()
        for perm in itertools.permutations((w, h, d)):
            if perm not in seen:
                seen.add(perm)
                yield perm

    for bi in order:
        if time.time() > deadline:
            break
            
        w, h, d = boxes[bi]
        best_pos = None
        best_score = float('inf')
        
        # Deduplicate skyline points
        candidates = list(set(skyline))
        
        for cx, cy, cz in candidates:
            # Check if we can place here
            # Try all orientations
            for ow, oh, od in get_orientations(w, h, d):
                if cx + ow > W or cy + oh > H or cz + od > D:
                    continue
                
                if not fits(cx, cy, cz, ow, oh, od):
                    continue
                
                # Score: Best Fit Decreasing
                # Prefer placements that minimize wasted space or are "tight"
                # Simple score: minimize z, then y, then x (Bottom-Left-Back)
                # But "Best Fit" often means minimizing the gap.
                # Let's use a weighted sum: z * 1000 + y * 100 + x
                # Or better: minimize the "height" of the placement relative to the skyline
                # If we use skyline, the z is usually the height of the stack at (x,y).
                
                score = cz * 10000 + cy * 100 + cx
                
                if score < best_score:
                    best_score = score
                    best_pos = (cx, cy, cz, ow, oh, od)
        
        if best_pos is None:
            # Try to find any valid spot if skyline failed (shouldn't happen if skyline is complete)
            # But skyline might miss spots if we don't add all corners.
            # For robustness, if no spot found in skyline, mark as left out.
            placements[bi] = (-1, 0, 0, 0, w, h, d)
        else:
            px, py, pz, pw, ph, pd = best_pos
            place(px, py, pz, pw, ph, pd)
            placements[bi] = (0, px, py, pz, pw, ph, pd)
            
            # Update skyline
            # Add corners of the placed box
            new_points = [
                (px + pw, py, pz),
                (px, py + ph, pz),
                (px, py, pz + pd),
                (px + pw, py + ph, pz),
                (px + pw, py, pz + pd),
                (px, py + ph, pz + pd),
                (px + pw, py + ph, pz + pd),
            ]
            
            # Add to skyline
            for pt in new_points:
                if pt[0] <= W and pt[1] <= H and pt[2] <= D:
                    skyline.append(pt)
            
            # Prune skyline to keep it manageable
            # Remove points that are "inside" the placed box? No, they are occupied.
            # Remove points that are dominated?
            # For now, just let it grow, but deduplicate.
            # If it gets too big, we might slow down.
            # A simple pruning: keep only unique points.
            if len(skyline) > 5000:
                skyline = list(set(skyline))
                # Optional: sort by z to prioritize lower layers in future iterations?
                # The scoring handles priority, but iterating 5000 points * 6 orientations * 60 boxes
                # 5000 * 6 * 60 = 1.8M checks. Each check is O(w*h*d) in worst case.
                # This might be slow.
                # Let's add a stricter prune: if a point is strictly higher than another point with same x,y, remove it.
                # This is the "skyline" property.
                # Group by (x,y)
                from collections import defaultdict
                col_min_z = defaultdict(int)
                for x, y, z in skyline:
                    if z < col_min_z[(x, y)]:
                        col_min_z[(x, y)] = z
                skyline = [(x, y, z) for (x, y), z in col_min_z.items()]

    # Fill remaining
    for i in range(n):
        if placements[i] is None:
            w, h, d = boxes[i]
            placements[i] = (-1, 0, 0, 0, w, h, d)

    return placements
