    if _GLOBAL_START_TIME is None:
        _GLOBAL_START_TIME = time.time()
        _GLOBAL_DEADLINE = _GLOBAL_START_TIME + 295.0  # Safety margin
    
    _CALL_COUNT += 1
    size = instance["n"]
    start_time = time.time()
    
    # Time budget for this instance
    remaining = _GLOBAL_DEADLINE - start_time
    # Distribute remaining time: give more to earlier calls, less to later ones
    # Simple heuristic: each call gets remaining / (6 - _CALL_COUNT + 1)
    calls_left = 6 - _CALL_COUNT + 1
    instance_budget = min(remaining / calls_left, 50.0)  # Cap at 50s per instance
    instance_deadline = start_time + instance_budget
    
    rng = np.random.default_rng(size * 7919 + 12345)  # Different seed per size
    
