def _objective(flat_pts):
    """Objective function for Nelder-Mead: minimize negative min area."""
    pts = flat_pts.reshape(-1, 2)
    pts = _project_to_triangle(pts)
    min_area = _min_triangle_area(pts)
    return -min_area


def _nelder_mead_optimize(init_pts, max_time=10.0):
    """Run Nelder-Mead optimization starting from init_pts."""
    start_time = time.time()
    flat_init = init_pts.flatten()
    
    # Use Nelder-Mead
    # bounds are not directly supported in Nelder-Mead, so we rely on projection in objective
    res = minimize(
        _objective,
        flat_init,
        method='Nelder-Mead',
        options={'maxiter': 500, 'xatol': 1e-5, 'fatol': 1e-6, 'adaptive': True}
    )
    
    optimized_pts = res.x.reshape(-1, 2)
    optimized_pts = _project_to_triangle(optimized_pts)
    return optimized_pts


def construct():
    start_time = time.time()
    rng = np.random.default_rng(12345)

    best_pts = None
    best_area = 0.0

    def _elapsed_ok(margin):
        return (time.time() - start_time) < (DEADLINE - margin)

    def _update_best(pts):
        nonlocal best_pts, best_area
        pts = _project_to_triangle(pts.copy())
        area = _min_triangle_area(pts)
        if area > best_area:
            best_area = area
            best_pts = pts.copy()

    # ---- Phase 1: Generate diverse initial candidates ----
    candidates = []
    
    # Symmetric initial configuration
    init_sym = np.array([
        [0.0, 0.0],
        [1.0, 0.0],
        [0.5, S3H],
        [0.5, 0.0],
        [0.75, S3H / 2],
        [0.25, S3H / 2],
        [1/3, S3H/3],
        [0.333, 0.0],
        [0.667, 0.0],
        [0.5, S3H/3],
        [0.2, 0.1],
    ], dtype=float)
    candidates.append(init_sym)
    
    # Sobol inits
    for seed in range(5):
        if not _elapsed_ok(100):
            break
        try:
            pts = _sobol_init(N, seed=seed * 1000 + 42)
            candidates.append(pts)
        except Exception:
            pass

    # Perturb symmetric init
    for _ in range(5):
        if not _elapsed_ok(100):
            break
        cand = init_sym + rng.normal(0, 0.1, size=(N, 2))
        cand = _project_to_triangle(cand)
        candidates.append(cand)

    # ---- Phase 2: Optimize each candidate with Nelder-Mead ----
    for cand in candidates:
        if not _elapsed_ok(20):
            break
        try:
            # Allocate remaining time / number of remaining candidates
            remaining_candidates = len(candidates) + 1 # rough estimate
            time_per_opt = min(10.0, max(2.0, (DEADLINE - (time.time() - start_time)) / max(1, remaining_candidates)))
            
            optimized_pts = _nelder_mead_optimize(cand, max_time=time_per_opt)
            _update_best(optimized_pts)
        except Exception as e:
            # If optimization fails, update with the initial candidate
            _update_best(cand)

    # ---- Phase 3: Refine the best solution further ----
    if best_pts is not None and _elapsed_ok(10):
        try:
            # Run another round of Nelder-Mead on the best found
            optimized_pts = _nelder_mead_optimize(best_pts, max_time=10.0)
            _update_best(optimized_pts)
        except Exception:
            pass

    if best_pts is None:
        # Fallback: return projected symmetric init
        best_pts = _project_to_triangle(init_sym)

    # Final safety projection
    best_pts = _project_to_triangle(best_pts)
    return best_pts
