_GLOBAL_START_TIME = time.time()
_TOTAL_TIME_LIMIT = 300.0
_SAFETY_MARGIN = 5.0

def _get_time_left():
    return _TOTAL_TIME_LIMIT - (time.time() - _GLOBAL_START_TIME) - _SAFETY_MARGIN

def _validate_positions(positions):
    if not np.all(np.isfinite(positions)):
        return False
    n = len(positions)
    if n < 2:
        return True
    dists = np.linalg.norm(positions[:, np.newaxis] - positions[np.newaxis, :], axis=2)
    np.fill_diagonal(dists, np.inf)
    min_dist = np.min(dists)
    if min_dist < 0.35:
        return False
    return True

def _generate_icosahedron(n):
    """
    Generate Mackay icosahedral cluster.
    n=1: 1
    n=13: 1+12
    n=55: 1+12+42
    For other n, return None or truncated version.
    """
    if n not in [1, 13, 55]:
        # We can truncate 55 to get smaller, but it's not a standard Mackay number.
        # For now, only return exact matches.
        if n == 1:
            return np.array([[0.0, 0.0, 0.0]])
        return None
        
    phi = (1 + np.sqrt(5)) / 2
    verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [phi, 0, -1], [-phi, 0, 1], [-phi, 0, -1]
    ])
    verts = verts / np.linalg.norm(verts, axis=1, keepdims=True)
    
    points = [np.zeros(3)]
    
    if n == 1:
        return np.array(points)
        
    # Shell 1: 12 vertices
    shell1 = verts * 1.0
    points.extend(shell1.tolist())
    
    if n == 13:
        return np.array(points)
        
    if n == 55:
        # Shell 2: 42 points
        # 12 face centers
        # 30 edge midpoints
        
        # Find faces of icosahedron
        # This is tedious to hardcode. 
        # Alternative: Use the fact that the 2nd shell of a Mackay icosahedron 
        # can be generated by taking the 1st shell vertices and finding their neighbors.
        # Or simpler: The 42 points are the vertices of a truncated icosahedron? No.
        # The 42 points are the centers of the 12 faces and the midpoints of the 30 edges.
        
        # Let's compute face normals and edge midpoints.
        # Icosahedron faces: 20 triangles.
        # We need to identify the faces.
        # Vertices are indexed 0-11.
        # Edges connect vertices with distance sqrt(2/(1+phi)) * 2? 
        # Distance between adjacent verts in unit icosahedron:
        # d = ||v_i - v_j||
        
        v = verts
        d2 = np.sum((v[:, np.newaxis] - v[np.newaxis, :])**2, axis=2)
        np.fill_diagonal(d2, np.inf)
        min_d2 = np.min(d2)
        
        # Build adjacency
        adj = (d2 < min_d2 * 1.1).astype(int)
        
        # Find faces (triangles)
        faces = []
        for i in range(12):
            for j in range(12):
                if i >= j: continue
                if adj[i,j]:
                    for k in range(12):
                        if k <= j: continue
                        if adj[i,k] and adj[j,k]:
                            faces.append((i,j,k))
        
        # 20 faces
        # Face centers
        for f in faces:
            c = (v[f[0]] + v[f[1]] + v[f[2]]) / 3.0
            c = c / np.linalg.norm(c) # Project to unit sphere
            points.append(c)
            
        # Edge midpoints
        for i in range(12):
            for j in range(12):
                if i >= j: continue
                if adj[i,j]:
                    m = (v[i] + v[j]) / 2.0
                    m = m / np.linalg.norm(m) # Project to unit sphere
                    points.append(m)
                    
        return np.array(points)
        
    return None

def _generate_fcc_chunk(n):
    """
    Generate an FCC-like cluster.
    """
    if n <= 0:
        return np.zeros((0, 3))
    
    a = 0.72 
    points = []
    # Simple cubic grid, then filter? No, FCC is better.
    # Let's just use a random close pack for now if icosahedron is not available,
    # or a simple BCC/FCC grid.
    
    # Generate points in a sphere of radius R
    R = a * n ** (1.0/3.0) * 1.5
    
    # Use a grid
    grid_size = int(2 * R / a) + 3
    centers = np.arange(-grid_size//2, grid_size//2 + 1) * a
    
    fcc_offsets = np.array([
        [0, 0, 0],
        [0, a/2, a/2],
        [a/2, 0, a/2],
        [a/2, a/2, 0]
    ])
    
    all_pts = []
    for x in centers:
        for y in centers:
            for z in centers:
                for off in fcc_offsets:
                    p = np.array([x, y, z]) + off
                    if np.linalg.norm(p) <= R:
                        all_pts.append(p)
                        
    all_pts = np.array(all_pts)
    
    if len(all_pts) == 0:
        return np.zeros((n, 3))
        
    # Center
    all_pts -= np.mean(all_pts, axis=0)
    
    # Sort by distance to center and take n
    dists = np.linalg.norm(all_pts, axis=1)
    order = np.argsort(dists)
    all_pts = all_pts[order[:n]]
    
    return all_pts

def _generate_random_close_pack(n, rng, radius=0.72):
    """
    Generate a random cluster with a minimum distance constraint.
    """
    if n <= 0:
        return np.zeros((0, 3))
    
    R = radius * n ** (1.0/3.0) * 1.5
    points = [np.zeros(3)]
    min_dist = 0.4 * radius
    
    attempts = 0
    max_attempts = n * 500
    
    while len(points) < n and attempts < max_attempts:
        u = rng.uniform(0, 1)
        v = rng.uniform(0, 1)
        theta = 2 * np.pi * u
        phi = np.arccos(2 * v - 1)
        r = R * np.cbrt(rng.uniform(0, 1))
        
        x = r * np.sin(phi) * np.cos(theta)
        y = r * np.sin(phi) * np.sin(theta)
        z = r * np.cos(phi)
        p = np.array([x, y, z])
        
        if all(np.linalg.norm(p - q) >= min_dist for q in points):
            points.append(p)
        attempts += 1
        
    while len(points) < n:
        points.append(rng.uniform(-R, R, 3))
        
    return np.array(points)

def construct(instance):
    n = instance["n"]
    kind = instance.get("kind", "12-6")
    
    seed = n * 100 + (0 if kind == '12-6' else 1 if kind == '9-6' else 2)
    rng = np.random.default_rng(seed)
    
    best_energy = np.inf
    best_positions = None
    
    # Generate diverse starts
    starts = []
    
    # 1. Icosahedron
    ico = _generate_icosahedron(n)
    if ico is not None and _validate_positions(ico):
        starts.append(ico)
        
    # 2. FCC Chunk
    fcc = _generate_fcc_chunk(n)
    if _validate_positions(fcc):
        starts.append(fcc)
        
    # 3. Random Close Packs
    for i in range(3):
        rcp = _generate_random_close_pack(n, rng)
        if _validate_positions(rcp):
            starts.append(rcp)
            
    if not starts:
        # Fallback
        pts = np.zeros((n, 3))
        pts[:, 0] = np.arange(n) * 0.8
        starts.append(pts)

    # Relax each start
    for start in starts:
        try:
            energy, positions = relax(start, 'sutton_chen', kind)
            if _validate_positions(positions):
                if energy < best_energy:
                    best_energy = energy
                    best_positions = positions.copy()
        except Exception:
            continue

    if best_positions is None:
        best_positions = starts[0]
        best_energy, _ = sutton_chen_energy_gradient(best_positions, kind)

    # Basin Hopping
    time_left = _get_time_left()
    if time_left > 10.0:
        current_energy = best_energy
        current_pos = best_positions.copy()
        kick_sigma = 0.2
        T = 0.5
        
        bh_start = time.time()
        while time.time() - bh_start < time_left - 5.0:
            kick = rng.normal(0, kick_sigma, current_pos.shape)
            new_pos = current_pos + kick
            
            try:
                new_energy, new_pos = relax(new_pos, 'sutton_chen', kind)
            except Exception:
                continue
                
            if not _validate_positions(new_pos):
                continue
                
            delta_e = new_energy - current_energy
            # Metropolis acceptance
            if delta_e < 0 or rng.random() < np.exp(-delta_e / T):
                current_energy = new_energy
                current_pos = new_pos
                
                if current_energy < best_energy:
                    best_energy = current_energy
                    best_positions = current_pos.copy()
                    
            # Optional: Slowly reduce kick_sigma or T
            # kick_sigma *= 0.999
            # T *= 0.999

    return best_positions
