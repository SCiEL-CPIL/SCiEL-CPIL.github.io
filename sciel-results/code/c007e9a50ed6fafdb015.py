    def axial_to_cartesian(axial_list):
        pts = []
        for q, r in axial_list:
            x = math.sqrt(3) * (q + r / 2.0)
            y = 1.5 * r
            pts.append((x, y))
        return np.array(pts)

    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append((math.cos(ang), math.sin(ang)))
        
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []
        
        for nx, ny in normals:
            for px, py in pts:
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-(px * nx + py * ny))
                A_ub.append([nx, ny, -1.0])
                b_ub.append(px * nx + py * ny)
        
        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        angles = beta + math.pi / 6.0 + np.arange(6) * math.pi / 3.0
        normals = np.column_stack([np.cos(angles), np.sin(angles)])
        offset = pts - np.array([cx, cy])
        projs = offset @ normals.T
        all_projs = np.concatenate([projs.ravel(), -projs.ravel()])
        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf'), (cx, cy), float('inf')
        shifted = (all_projs - max_val) / temperature
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S, (cx, cy), D

    def fast_screen(pts):
        """Quick LP-based screening: find best S over beta grid."""
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        for i in range(37):
            beta = i * (math.pi / 6) / 36
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        return best_S, best_beta, best_center

    def exact_S(pts, beta, cx, cy):
        angles = beta + math.pi / 6.0 + np.arange(6) * math.pi / 3.0
        normals = np.column_stack([np.cos(angles), np.sin(angles)])
        offset = pts - np.array([cx, cy])
        projs = offset @ normals.T
        max_proj = max(np.max(projs), -np.min(projs))
        return (max_proj + APOTHEM) / APOTHEM

    def coordinate_descent_polish(pts, cx, cy, beta, max_rounds=50):
        """Tighten via coordinate descent with line search on each variable."""
        best = exact_S(pts, beta, cx, cy)
        for _ in range(max_rounds):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
            improved = False
            # Optimize cx
            for _ls in range(30):
                t = 0.001 * (0.7 ** _ls)
                s1 = exact_S(pts, beta, cx + t, cy)
                s2 = exact_S(pts, beta, cx - t, cy)
                if s1 < best - 1e-14:
                    cx, best = cx + t, s1
                    improved = True
                elif s2 < best - 1e-14:
                    cx, best = cx - t, s2
                    improved = True
                else:
                    break
            # Optimize cy
            for _ls in range(30):
                t = 0.001 * (0.7 ** _ls)
                s1 = exact_S(pts, beta, cx, cy + t)
                s2 = exact_S(pts, beta, cx, cy - t)
                if s1 < best - 1e-14:
                    cy, best = cy + t, s1
                    improved = True
                elif s2 < best - 1e-14:
                    cy, best = cy - t, s2
                    improved = True
                else:
                    break
            # Optimize beta
            for _ls in range(30):
                t = 1e-4 * (0.7 ** _ls)
                b1 = min(max(beta + t, 0.0), math.pi / 6)
                b2 = min(max(beta - t, 0.0), math.pi / 6)
                s1 = exact_S(pts, b1, cx, cy)
                s2 = exact_S(pts, b2, cx, cy)
                if s1 < best - 1e-14:
                    beta, best = b1, s1
                    improved = True
                elif s2 < best - 1e-14:
                    beta, best = b2, s2
                    improved = True
                else:
                    break
            if not improved:
                break
        return best, (cx, cy), beta

    def optimize_shape(pts, do_polish=True):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None
        
        # Fast LP grid search
        for i in range(37):
            beta = i * (math.pi / 6) / 36
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        if not do_polish:
            return best_S, best_beta, best_center
        
        # Bounded scalar refinement on beta
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(0, math.pi / 6), method='bounded',
                                     options={'maxiter': 300, 'xatol': 1e-12})
                if res.fun < best_S:
                    best_S = res.fun
                    best_beta = res.x
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass
        
        # Smooth surrogate optimization (reduced set)
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                temperatures = [0.3, 0.1, 0.05]
                start_betas = [0.0, math.pi/12, best_beta]
                
                for temp in temperatures:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    for sb in start_betas:
                        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                            break
                        
                        def smooth_obj(params, t=temp):
                            cx, cy, beta = params
                            beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S, _, _ = smooth_calc_S(pts, beta, cx, cy, temperature=t)
                            return S
                        
                        init = [best_center[0], best_center[1], sb]
                        res = minimize(smooth_obj, init, method='Nelder-Mead',
                                     options={'maxiter': 500, 'xatol': 1e-10, 'fatol': 1e-10})
                        
                        if res.fun < 1e10:
                            cx_r, cy_r, beta_r = res.x
                            beta_r = ((beta_r % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S_exact, c_exact, _ = calc_S_for_beta(pts, beta_r)
                            if S_exact < best_S:
                                best_S = S_exact
                                best_beta = beta_r
                                best_center = c_exact
        except Exception:
            pass
        
        # Final high-precision Nelder-Mead polish
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                def objective(params):
                    cx, cy, beta = params
                    if beta < 0 or beta > math.pi / 6:
                        return 1e10
                    return exact_S(pts, beta, cx, cy)
                
                initial = [best_center[0], best_center[1], best_beta]
                res = minimize(objective, initial, method='Nelder-Mead',
                             options={'maxiter': 5000, 'xatol': 1e-14, 'fatol': 1e-14})
                if res.fun < best_S:
                    best_S = res.fun
                    best_center = (res.x[0], res.x[1])
                    best_beta = res.x[2]
        except Exception:
            pass
        
        # Coordinate descent polish for final tightening
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                S_cd, center_cd, beta_cd = coordinate_descent_polish(pts, best_center[0], best_center[1], best_beta)
                if S_cd < best_S:
                    best_S = S_cd
                    best_center = center_cd
                    best_beta = beta_cd
        except Exception:
            pass
            
        return best_S, best_beta, best_center

    best_global_S = float('inf')
    best_global_pts = None
    best_global_beta = 0.0
    best_global_center = None

    # Phase 1: Fast screen all candidates
    screened = []
    for axial in candidates:
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            break
        pts = axial_to_cartesian(axial)
        S, beta, center = fast_screen(pts)
        screened.append((S, pts, beta, center))
    
    # Sort by S and keep top 8 for expensive optimization
    screened.sort(key=lambda x: x[0])
    top_k = screened[:8]
    
    for S, pts, beta, center in top_k:
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            break
        S_opt, beta_opt, center_opt = optimize_shape(pts, do_polish=True)
        if S_opt < best_global_S:
            best_global_S = S_opt
            best_global_pts = pts
            best_global_beta = beta_opt
            best_global_center = center_opt

    if best_global_center is None or best_global_S == float('inf'):
        best_global_pts = axial_to_cartesian(candidates[0])
        best_global_center = (float(np.mean(best_global_pts[:, 0])), float(np.mean(best_global_pts[:, 1])))
        best_global_beta = 0.0
        max_proj = 0
        for k in range(6):
            ang = math.pi / 6.0 + k * math.pi / 3.0
            nx, ny = math.cos(ang), math.sin(ang)
            projs = best_global_pts[:, 0] * nx + best_global_pts[:, 1] * ny
            max_proj = max(max_proj, np.max(projs), -np.min(projs))
        best_global_S = (max_proj + APOTHEM) / APOTHEM

    cx, cy = best_global_center
    angle_deg = math.degrees(best_global_beta)
    
    SCALE = 1.0 + 1e-10
    pts_scaled = []
    for x, y in best_global_pts:
        sx = cx + (x - cx) * SCALE
        sy = cy + (y - cy) * SCALE
        pts_scaled.append((sx, sy))
    
    pts_scaled = np.array(pts_scaled)
    
    max_proj = 0
    for k in range(6):
        ang = best_global_beta + math.pi / 6.0 + k * math.pi / 3.0
        nx, ny = math.cos(ang), math.sin(ang)
        projs = (pts_scaled[:, 0] - cx) * nx + (pts_scaled[:, 1] - cy) * ny
        max_proj = max(max_proj, np.max(projs), -np.min(projs))
    
    D_scaled = max_proj
    S_scaled = (D_scaled + APOTHEM) / APOTHEM
    
    inner = []
    for x, y in pts_scaled:
        inner.append([float(x), float(y), float(angle_deg)])
        
    center = [float(cx), float(cy)]
    side = float(S_scaled)
    rotation = float(angle_deg)
    
    return inner, center, side, rotation
