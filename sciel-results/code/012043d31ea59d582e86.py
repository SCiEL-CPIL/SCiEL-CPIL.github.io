import time
import random
import sys
from collections import defaultdict

def construct(n_rows, k):
    """
    Construct n_rows rows of k+1 increasing integers starting at 0 such that
    all pairwise differences are distinct across all rows.
    Minimizes the largest entry.
    """
    deadline = time.time() + 140.0  # 10s safety margin for 150s limit
    
    # Problem parameters
    diffs_per_row = k * (k + 1) // 2
    total_diffs_needed = n_rows * diffs_per_row
    
    # Lower bound on M:
    # 1. We need total_diffs_needed distinct differences, all in [1, M]. So M >= total_diffs_needed.
    # 2. The largest entry is M. The differences are generated by pairs.
    #    For a fixed M, the set of available differences is {1, ..., M}.
    #    We need to pack n_rows sets of diffs_per_row differences into {1, ..., M}
    #    such that each set is "realizable" by a row of k+1 integers starting at 0 and ending <= M.
    
    # A stronger lower bound comes from the fact that the largest difference in a row
    # is the largest element (since it starts at 0).
    # So the largest element must be at least the largest difference in that row.
    # Actually, the largest element IS the largest difference (with 0).
    
    # Let's use a heuristic lower bound.
    # M must be at least total_diffs_needed.
    # Also, consider the "density". 
    # For (7,5), total_diffs = 7 * 15 = 105.
    # The counting bound is 105. The known best is 112.
    
    M_lower = max(total_diffs_needed, 50)
    
    # Get an initial upper bound using a greedy method
    best_rows = _greedy_construct(n_rows, k)
    best_M = _max_entry(best_rows)
    
    # If greedy is already very good, we might just return it if we don't have time.
    # But we want to try to beat it.
    
    # Strategy:
    # Iterate M from M_lower to best_M - 1.
    # For each M, try to find a valid packing using a CP-style backtracking solver.
    # The solver will try to assign rows one by one.
    # To make it efficient, we don't sample random rows. Instead, we build rows
    # by selecting differences that are still available and "compatible".
    
    # A row is defined by its elements a_0=0 < a_1 < ... < a_k <= M.
    # The differences are a_j - a_i.
    # Note that a_j = a_{j-1} + (a_j - a_{j-1}).
    # So a row can be represented by its consecutive differences d_1, ..., d_k.
    # a_i = d_1 + ... + d_i.
    # The set of all differences is { sum of subsets of consecutive diffs? No.
    # The differences are a_j - a_i = d_{i+1} + ... + d_j.
    # So the set of differences is the set of all sums of consecutive segments of the sequence d_1...d_k.
    # There are k(k+1)/2 such sums.
    
    # This representation is key.
    # We need to choose k positive integers d_1...d_k such that:
    # 1. Sum(d) <= M
    # 2. All k(k+1)/2 consecutive sums are distinct.
    # 3. All consecutive sums across all rows are distinct.
    
    # This is a "Consecutive Sum Packing" problem.
    
    # Solver for a fixed M:
    # We want to find n_rows sequences of length k.
    
    def solve_for_M(M):
        used_diffs = set()
        rows = []
        
        # We will backtrack on the rows.
        # To improve speed, we can use a heuristic:
        # When constructing a row, we pick d_1...d_k.
        # The generated differences are the consecutive sums.
        # We need to ensure none of these are in used_diffs and they are distinct among themselves.
        
        # Heuristic for order of d_i?
        # Or just random search with strong pruning?
        
        # Let's try a recursive search for a single row that fits, then backtrack.
        # To avoid getting stuck, we use randomized restarts.
        
        def find_row():
            # Returns a tuple of d's or None
            # We need to pick k positive ints such that:
            # - Sum <= M
            # - Consecutive sums are unique and not in used_diffs
            
            # To make this efficient, we can use backtracking on d_1...d_k.
            # However, the space of d's is large.
            
            # Alternative: Generate random d's and check.
            # Since M is small (around 100-110), and k is small (5),
            # the number of valid rows is likely large enough that random sampling works well,
            # BUT we need to be smarter about which differences to pick.
            
            # Let's try a "guided" random search.
            # Pick d_k (the largest step) first? Or d_1?
            
            # Actually, let's stick to the previous "sample row" approach but with
            # better pruning:
            # 1. Precompute all valid rows for this M?
            #    Number of rows with max entry <= M is C(M, k).
            #    For M=110, k=5, C(110, 5) ~ 40 million. Too many to precompute.
            
            # So we must generate on the fly.
            
            # Improvement:
            # Instead of sampling elements a_i, sample the differences d_i.
            # d_i >= 1.
            # Sum(d_i) <= M.
            # This constrains the search space better than sampling a_i directly?
            # Not necessarily.
            
            # Let's try a hybrid:
            # 1. Try to find a row using a local search / hill climbing on the d-vector.
            # 2. If stuck, restart.
            
            # For simplicity and robustness within time limits, let's use a
            # "Randomized Greedy with Backtracking" on the rows, but with a
            # smarter row generation.
            
            # We will generate candidate rows by picking random d_1..d_k
            # such that sum(d) <= M.
            
            # To ensure distinct consecutive sums:
            # This is a strong constraint.
            
            # Let's try up to N candidates.
            max_attempts = 500
            for _ in range(max_attempts):
                # Generate random d's
                # To keep sum <= M, we can generate k-1 random values and set the last to fill?
                # No, that biases towards large last element.
                
                # Better: Generate k random integers in [1, M//k + 1]?
                # Or just generate k random integers in [1, M] and reject if sum > M.
                # For M=110, k=5, average d is 22. Sum ~ 110.
                # Probability sum <= 110 is reasonable.
                
                d = [random.randint(1, M) for _ in range(k)]
                if sum(d) > M:
                    continue
                
                # Compute consecutive sums
                a = [0]
                curr = 0
                for val in d:
                    curr += val
                    a.append(curr)
                
                # Check differences
                diffs = set()
                valid = True
                for i in range(k + 1):
                    for j in range(i + 1, k + 1):
                        diff = a[j] - a[i]
                        if diff in diffs or diff in used_diffs:
                            valid = False
                            break
                        diffs.add(diff)
                    if not valid:
                        break
                
                if valid:
                    return a, diffs
            
            return None, None

        def backtrack(idx):
            if idx == n_rows:
                return True
            
            row, diffs = find_row()
            if row is None:
                return False
            
            rows.append(row)
            used_diffs.update(diffs)
            
            if backtrack(idx + 1):
                return True
            
            rows.pop()
            used_diffs.difference_update(diffs)
            return False

        # Use multiple restarts to escape local minima
        for restart in range(200):
            if time.time() > deadline - 2:
                return None
            random.seed(restart * 1000 + M)
            used_diffs.clear()
            rows.clear()
            if backtrack(0):
                return rows
        
        return None

    # Try to find a solution for M in increasing order
    # Start from M_lower
    # If we find one, it's the best for that M.
    # Since we iterate up, the first one found is the global minimum M we can find.
    
    # Optimization: If best_M - M_lower is large, we might skip some.
    # But for (7,5), range is small (105 to 112).
    
    # We should also consider that the greedy solution might be optimal or near-optimal.
    # If we don't find a better M, we return the greedy one.
    
    # To be safe, let's also try a few values below the greedy bound if we have time.
    # But the loop below does exactly that.
    
    for M in range(M_lower, best_M):
        if time.time() > deadline - 5:
            break
        
        # Try to solve for M
        # We might want to order the M values? No, increasing is correct for minimization.
        
        sol = solve_for_M(M)
        if sol is not None:
            best_rows = sol
            best_M = M
            break
            
    return best_rows

def _greedy_construct(n_rows, k):
    """
    Greedy construction: pick the smallest possible next value that doesn't conflict.
    This provides a valid upper bound.
    """
    used = set()
    rows = []
    for _ in range(n_rows):
        row, x = [0], 0
        while len(row) < k + 1:
            x += 1
            new = {x - a for a in row}
            if not new & used and len(new) == len(row):
                row.append(x)
                used |= new
        rows.append(row)
    return rows

def _max_entry(rows):
    return max(max(row) for row in rows)

def _is_valid(rows, k):
    """
    Check if rows are valid.
    """
    used = set()
    for row in rows:
        if len(row) != k + 1:
            return False
        if row[0] != 0:
            return False
        if not all(row[i] < row[i+1] for i in range(k)):
            return False
            
        d_set = set()
        for i in range(len(row)):
            for j in range(i + 1, len(row)):
                d = row[j] - row[i]
                if d in d_set:
                    return False
                if d in used:
                    return False
                d_set.add(d)
        used |= d_set
    return True
