import random
import time
import math

_DEADLINE = time.time() + 325  # safety margin before 330s kill


def _neighbours(point):
    for axis in range(len(point)):
        for step in (-1, 1):
            q = list(point)
            q[axis] += step
            yield tuple(q)

def _dist(p1, p2):
    return sum(abs(a-b) for a, b in zip(p1, p2))

def _energy(sequence, chain):
    where = {p: i for i, p in enumerate(chain)}
    contacts = 0
    for i, p in enumerate(chain):
        if sequence[i] == "H":
            for q in _neighbours(p):
                j = where.get(q)
                if j is not None and j > i + 1 and sequence[j] == "H":
                    contacts += 1
    return -contacts

def _grow(sequence, dimension, rng):
    """One randomized greedy chain growth: prefer sites with new H-H contacts, then free space."""
    start = (0,) * dimension
    chain, occupied = [start], {start: 0}
    for i in range(1, len(sequence)):
        options = []
        for site in _neighbours(chain[-1]):
            if site in occupied:
                continue
            gain = 0
            if sequence[i] == "H":
                gain = sum(1 for q in _neighbours(site)
                           if q in occupied and occupied[q] < i - 1 and sequence[occupied[q]] == "H")
            free = sum(1 for q in _neighbours(site) if q not in occupied)
            options.append((gain + 0.1 * free + rng.random(), site))
        if not options:
            return None
        site = max(options)[1]
        occupied[site] = i
        chain.append(site)
    return chain

def _pivot_refine(sequence, chain, rng, max_steps=2000):
    """Local refinement using pivot moves which preserve self-avoidance and connectivity."""
    n = len(chain)
    if n < 4:
        return chain, _energy(sequence, chain)
        
    current_energy = _energy(sequence, chain)
    best_chain = list(chain)
    best_energy = current_energy
    occupied = {tuple(p): i for i, p in enumerate(chain)}
    
    step = 0
    while step < max_steps and time.time() < _DEADLINE:
        step += 1
        # Pick a random pivot point
        k = rng.randint(1, n - 2)
        
        # The tail starts at k+1. The vector from k to k+1 is v.
        # We want to rotate the tail around k.
        # The new first step of the tail must be a neighbor of k, different from the step from k-1 to k.
        # Actually, the tail is attached at k. The step from k to k+1 is the "head" of the tail.
        # We can try all 6 neighbors of k for the new position of k+1.
        # One of them is the old position of k+1 (do nothing).
        # The one opposite to the incoming vector (k-1 to k) might be valid or invalid depending on geometry.
        
        old_pos_k_plus_1 = tuple(chain[k+1])
        old_pos_k = tuple(chain[k])
        
        valid_moves = []
        for new_first in _neighbours(old_pos_k):
            if new_first == old_pos_k_plus_1:
                continue
            # Check if new_first is occupied by the head part (0..k-1)
            if new_first in occupied and occupied[new_first] <= k - 1:
                continue
            valid_moves.append(new_first)
            
        if not valid_moves:
            continue
            
        new_first = rng.choice(valid_moves)
        
        # Now we need to "walk" the rest of the tail from new_first.
        # This is essentially regrowing the tail from new_first.
        # To make it a local move, we can try to map the old tail geometry.
        # Simplest valid move: Just regrow the tail greedily? No, that changes the whole tail.
        # A true pivot move rotates the entire tail rigidly.
        # Rigid rotation is hard to implement correctly for arbitrary SAWs in 3D without quaternion math or careful vector arithmetic.
        
        # Alternative: "Slither" or "Snake" move?
        # Let's stick to a simpler, known correct local search: 
        # Try to swap adjacent segments? No.
        
        # Let's use a "Random Restart" strategy inside the refine loop? No.
        
        # Let's implement a simple "2-opt" like move? No, that breaks connectivity.
        
        # Okay, let's use a **Monte Carlo** approach with **valid moves** generated by **reversing a segment**.
        # Reversing a segment (i..j) preserves connectivity and self-avoidance IF the new segment doesn't collide with the rest.
        # This is a very effective and easy to implement move for SAWs.
        
        i = rng.randint(0, n - 2)
        j = rng.randint(i + 1, n - 1)
        
        # Try reversing chain[i..j]
        orig_segment = chain[i:j+1]
        new_segment = list(reversed(orig_segment))
        
        # Check if new_segment is self-avoiding (it is, since orig was)
        # Check if new_segment collides with chain[0..i-1] and chain[j+1..n-1]
        # Note: The endpoints i and j are fixed in space? No, reversing changes positions.
        # chain[i] becomes old chain[j], chain[j] becomes old chain[i].
        # The neighbors of i (i-1) and j (j+1) must remain connected.
        # dist(chain[i-1], new_chain[i]) must be 1.
        # dist(new_chain[j], chain[j+1]) must be 1.
        
        new_chain = chain.copy()
        new_chain[i:j+1] = new_segment
        
        # Check connectivity at boundaries
        if i > 0 and _dist(chain[i-1], new_chain[i]) != 1:
            continue
        if j < n - 1 and _dist(new_chain[j], chain[j+1]) != 1:
            continue
            
        # Check self-avoidance of the new segment against the rest
        # The rest is chain[0..i-1] and chain[j+1..n-1]
        # The new segment occupies positions new_chain[i..j]
        # We must ensure no position in new_segment is in the rest.
        
        rest_positions = set()
        for idx in range(0, i):
            rest_positions.add(tuple(chain[idx]))
        for idx in range(j+1, n):
            rest_positions.add(tuple(chain[idx]))
            
        collision = False
        for p in new_segment:
            if tuple(p) in rest_positions:
                collision = True
                break
        
        if collision:
            continue
            
        # Valid move!
        new_energy = _energy(sequence, new_chain)
        
        if new_energy < best_energy:
            best_energy = new_energy
            best_chain = new_chain
            chain = new_chain # Accept the move to continue from here (Hill Climbing)
            # Rebuild occupied set for next iterations? 
            # _energy uses a dict internally, so we don't need to maintain it for energy calc.
            # But we used 'occupied' in pivot logic which we are skipping.
            # We are using reversal logic now.
            
    return best_chain, best_energy

def fold(sequence, dimension):
    """Best conformation using multiple restarts with local refinement."""
    n = len(sequence)
    rng = random.Random(12345 + len(sequence))
    best_chain = None
    best_energy = 0  # 0 means no H-H contacts (unfolded)
    
    # Phase 1: Greedy growth with multiple restarts
    num_restarts = 100
    if n > 100:
        num_restarts = 30
    elif n > 60:
        num_restarts = 50
    
    for r in range(num_restarts):
        if time.time() > _DEADLINE - 30:
            break
        chain = _grow(sequence, dimension, rng)
        if chain is None:
            continue
        value = _energy(sequence, chain)
        if best_chain is None or value < best_energy:
            best_chain = chain
            best_energy = value
    
    if best_chain is None:
        # Fallback: straight line
        best_chain = [tuple([i] + [0] * (dimension - 1)) for i in range(n)]
        best_energy = 0
    
    # Phase 2: Local refinement on the best chain
    if time.time() < _DEADLINE - 10:
        refined_chain, refined_energy = _pivot_refine(sequence, best_chain, rng, max_steps=5000)
        if refined_energy < best_energy:
            best_chain = refined_chain
            best_energy = refined_energy
    
    # Phase 3: Try a few more refined restarts if time permits
    if time.time() < _DEADLINE - 20:
        for r in range(10):
            if time.time() > _DEADLINE - 15:
                break
            chain = _grow(sequence, dimension, rng)
            if chain is None:
                continue
            refined_chain, refined_energy = _pivot_refine(sequence, chain, rng, max_steps=2000)
            if refined_energy < best_energy:
                best_chain = refined_chain
                best_energy = refined_energy
    
    return [list(p) for p in best_chain]
