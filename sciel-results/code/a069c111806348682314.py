"""Difference triangle set (4,7): construct rows with distinct global differences."""
import time
import random
import sys

# EVOLVE-BLOCK-START
def construct(n_rows, k):
    """
    Construct n_rows rows of k+1 increasing integers starting at 0 such that
    all positive differences within each row are distinct across all rows.
    Minimize the largest entry (scope).
    """
    deadline = time.time() + 115.0  # safety margin before 120s kill
    
    # Total differences required
    total_diffs = n_rows * (k + 1) * k // 2
    
    # Lower bound on scope
    lb = total_diffs
    
    # 1. Get a quick greedy solution to establish an upper bound and fallback
    def greedy_construct():
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            x = 0
            while len(row) < k + 1:
                x += 1
                new_diffs = {x - a for a in row}
                if not new_diffs & used:
                    row.append(x)
                    used |= new_diffs
            rows.append(row)
        return rows

    initial_rows = greedy_construct()
    best_scope = max(max(r) for r in initial_rows)
    best_rows = initial_rows
    
    # 2. Backtracking search for better scope
    # We try to find a solution with scope = lb, lb+1, ... up to best_scope
    # Using symmetry breaking: R_0[1] < R_1[1] < R_2[1] < R_3[1]
    
    def dfs_solve(limit):
        """
        Attempts to find a solution with max entry <= limit.
        Returns list of rows or None.
        """
        used_diffs = set()
        rows = []
        
        # Symmetry breaking constraints for the first element of each row
        # R_0[1] < R_1[1] < R_2[1] < R_3[1]
        prev_first = 0
        
        # Pre-calculate remaining diffs needed for pruning
        # Total diffs = n_rows * (k+1)*k//2
        # Diffs used so far = len(used_diffs)
        
        def backtrack(row_idx, col_idx, current_row):
            nonlocal used_diffs, rows, best_scope, best_rows, deadline
            
            if time.time() > deadline:
                return False
            
            if row_idx == n_rows:
                # All rows filled
                rows.append(list(current_row))
                # Since we fill row by row, we need to store previous rows
                # Actually, 'rows' is being built up.
                # Let's restructure: rows is a list of lists.
                # We pass current_row as the one being built.
                # When row_idx increments, we append the completed row.
                
                # Check if this is a valid complete solution
                # The 'used_diffs' set ensures validity.
                # We found a solution with scope <= limit.
                return True
            
            # If starting a new row
            if col_idx == 0:
                current_row = [0]
                # The first element is 0.
                # We need to choose the next element (index 1)
                # But wait, the loop structure handles col_idx.
                # If col_idx == 0, we are at the start of the row.
                # We don't choose a value for index 0 (it's 0).
                # We immediately proceed to choose index 1.
                # So we can just call backtrack(row_idx, 1, [0])
                # But we need to handle the symmetry breaking for R_i[1].
                
                # Let's adjust the logic:
                # If col_idx == 0, we set current_row = [0] and move to col_idx 1.
                return backtrack(row_idx, 1, [0])
            
            # If col_idx > 0, we are choosing current_row[col_idx]
            
            # Pruning: Check if enough differences are available
            # Diffs needed for current row from col_idx onwards:
            # If we have placed elements up to index col_idx-1 (count = col_idx),
            # Next element is at index col_idx.
            # Number of elements in row so far = col_idx (indices 0 to col_idx-1).
            # Remaining elements to place in this row = k + 1 - col_idx.
            # Diffs generated by placing element at index j (where j goes from col_idx to k)
            # Element at j generates j diffs (with 0..j-1).
            # So remaining diffs for this row = sum_{j=col_idx}^{k} j
            # Sum of 1..k is k(k+1)/2. Sum of 1..(col_idx-1) is (col_idx-1)col_idx/2.
            # Remaining = k(k+1)/2 - (col_idx-1)col_idx/2
            
            rem_diffs_current_row = (k * (k + 1) // 2) - ((col_idx - 1) * col_idx // 2)
            
            # Diffs needed for future rows (row_idx+1 to n_rows-1)
            # Each full row has k(k+1)/2 diffs.
            rem_diffs_future_rows = (n_rows - 1 - row_idx) * (k * (k + 1) // 2)
            
            total_needed = rem_diffs_current_row + rem_diffs_future_rows
            
            # Available diffs in [1, limit]
            # We don't want to count all, just check if len(used_diffs) + total_needed <= limit
            # This is a necessary condition: we need 'total_needed' distinct integers from [1, limit]
            # that are not in used_diffs.
            # Max possible available is limit - len(used_diffs).
            if limit - len(used_diffs) < total_needed:
                return False
            
            # Determine range for current_row[col_idx]
            # Must be > current_row[col_idx-1]
            # Must be <= limit
            start_val = current_row[-1] + 1
            end_val = limit
            
            # Symmetry breaking for the first element of the row (col_idx == 1)
            if col_idx == 1:
                # R_i[1] must be > R_{i-1}[1]
                # prev_first holds R_{i-1}[1]
                if row_idx > 0:
                    start_val = max(start_val, prev_first + 1)
            
            # Try values
            # Heuristic: try smaller values first to keep scope low, 
            # but we are bounded by 'limit'.
            
            # Optimization: If col_idx == 1 and row_idx > 0, we can restrict range further?
            # No, just start_val.
            
            # To speed up, we can randomize the order slightly if we are stuck, 
            # but deterministic is better for finding the *first* solution.
            
            for val in range(start_val, end_val + 1):
                # Check if val is within limit
                if val > limit:
                    break
                
                # Calculate new differences
                new_diffs = set()
                valid = True
                for i in range(col_idx):
                    d = val - current_row[i]
                    if d in used_diffs:
                        valid = False
                        break
                    new_diffs.add(d)
                
                if not valid:
                    continue
                
                # Forward checking:
                # If we place val, do we have enough room for the rest?
                # This is implicitly handled by the recursive call's pruning check.
                
                # Commit
                current_row.append(val)
                used_diffs.update(new_diffs)
                
                if col_idx == k:
                    # Row complete
                    # Save this row
                    completed_row = list(current_row)
                    rows.append(completed_row)
                    
                    # Update prev_first for next row's symmetry breaking
                    if col_idx == 1: # This check is wrong, col_idx is k here.
                        pass
                    # We need to pass the first element of this row to the next row call
                    # The first element is completed_row[1]
                    # We handle this by passing it as an argument or using nonlocal
                    # Let's use a nonlocal variable 'last_row_first'
                    last_row_first = completed_row[1]
                    
                    if backtrack(row_idx + 1, 0, []):
                        return True
                    
                    # Backtrack
                    rows.pop()
                    used_diffs.difference_update(new_diffs)
                    current_row.pop()
                else:
                    if backtrack(row_idx, col_idx + 1, current_row):
                        return True
                    
                    # Backtrack
                    used_diffs.difference_update(new_diffs)
                    current_row.pop()
            
            return False
        
        # Wrapper to handle the 'last_row_first' state
        # Since Python closures don't easily pass state for the next row's start,
        # I will modify the backtrack signature or use a class-like structure.
        # For simplicity in this snippet, I'll use a mutable container or nonlocal.
        
        last_row_first = 0
        
        def backtrack_with_state(row_idx, col_idx, current_row):
            nonlocal used_diffs, rows, last_row_first, deadline
            
            if time.time() > deadline:
                return False
            
            if row_idx == n_rows:
                return True
            
            if col_idx == 0:
                # Start new row
                # Symmetry breaking: first element of this row (index 1)
                # must be > last_row_first
                # But we don't know index 1 yet.
                # We enforce it when we choose index 1.
                return backtrack_with_state(row_idx, 1, [0])
            
            # Choosing current_row[col_idx]
            
            # Pruning check
            rem_diffs_current_row = (k * (k + 1) // 2) - ((col_idx - 1) * col_idx // 2)
            rem_diffs_future_rows = (n_rows - 1 - row_idx) * (k * (k + 1) // 2)
            total_needed = rem_diffs_current_row + rem_diffs_future_rows
            
            if limit - len(used_diffs) < total_needed:
                return False
            
            start_val = current_row[-1] + 1
            end_val = limit
            
            if col_idx == 1 and row_idx > 0:
                start_val = max(start_val, last_row_first + 1)
            
            for val in range(start_val, end_val + 1):
                if val > limit:
                    break
                
                new_diffs = set()
                valid = True
                for i in range(col_idx):
                    d = val - current_row[i]
                    if d in used_diffs:
                        valid = False
                        break
                    new_diffs.add(d)
                
                if not valid:
                    continue
                
                current_row.append(val)
                used_diffs.update(new_diffs)
                
                if col_idx == k:
                    # Row complete
                    completed_row = list(current_row)
                    rows.append(completed_row)
                    last_row_first = completed_row[1]
                    
                    if backtrack_with_state(row_idx + 1, 0, []):
                        return True
                    
                    rows.pop()
                    used_diffs.difference_update(new_diffs)
                    current_row.pop()
                else:
                    if backtrack_with_state(row_idx, col_idx + 1, current_row):
                        return True
                    
                    used_diffs.difference_update(new_diffs)
                    current_row.pop()
            
            return False
        
        # Initialize state
        rows = []
        used_diffs = set()
        last_row_first = 0
        
        if backtrack_with_state(0, 0, []):
            return rows
        else:
            return None

    # Try scopes from lower bound up to the greedy solution's scope
    for scope in range(lb, best_scope + 1):
        if time.time() > deadline:
            break
        
        # Add a small timeout per scope attempt to avoid getting stuck on one
        # If it takes too long, we assume this scope is hard and try next?
        # Or we just let it run until global deadline.
        # Given the structure, if 112 is the answer, it should find it quickly.
        
        solution = dfs_solve(scope)
        if solution:
            best_rows = solution
            best_scope = scope
            break

    return best_rows
