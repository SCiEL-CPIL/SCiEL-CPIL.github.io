def _generate_icosahedral_fragment(n, spacing=1.0):
    """Generate a cluster by truncating or expanding a Mackay icosahedron."""
    # Find the closest Mackay size
    mackay_sizes = [1, 13, 55, 147]
    closest_size = min(mackay_sizes, key=lambda x: abs(x - n))
    
    base = _generate_mackay_icosahedron(closest_size, spacing)
    if base is None:
        return None
    
    if len(base) == n:
        return base
    
    if len(base) > n:
        # Randomly remove atoms
        indices = np.random.choice(len(base), n, replace=False)
        return base[indices]
    else:
        # Randomly add atoms near the surface
        # Find average radius
        r_avg = np.mean(np.linalg.norm(base, axis=1))
        rng = np.random.default_rng(n)
        new_atoms = []
        for _ in range(n - len(base)):
            # Place new atom near an existing atom
            i = rng.integers(0, len(base))
            offset = rng.normal(0, 0.5 * spacing, 3)
            p = base[i] + offset
            new_atoms.append(p)
        return np.vstack([base, np.array(new_atoms)])

def _generate_fcc_fragment(n, spacing=1.0):
    """Generate an FCC-like cluster."""
    # FCC lattice vectors
    # Generate points in a cube and filter
    L = int(np.ceil((2 * n) ** (1.0/3.0))) + 2
    points = []
    rng = np.random.default_rng(n)
    
    # Simple FCC generation:
    # (0,0,0), (0, 0.5, 0.5), (0.5, 0, 0.5), (0.5, 0.5, 0) on a cubic grid
    for i in range(-L, L+1):
        for j in range(-L, L+1):
            for k in range(-L, L+1):
                for dx, dy, dz in [(0,0,0), (0,0.5,0.5), (0.5,0,0.5), (0.5,0.5,0)]:
                    p = np.array([i, j, k]) + np.array([dx, dy, dz])
                    points.append(p)
    
    points = np.array(points)
    # Center and scale
    points -= np.mean(points, axis=0)
    
    # Sort by radius and take n closest
    radii = np.linalg.norm(points, axis=1)
    indices = np.argsort(radii)[:n]
    return points[indices] * spacing

def _random_compact(n, spacing=1.0):
    """Generate a random compact cluster."""
    rng = np.random.default_rng(n)
    radius = spacing * n ** (1.0 / 3.0) * 0.8
    points = []
    while len(points) < n:
        p = rng.uniform(-radius, radius, 3)
        if np.linalg.norm(p) <= radius:
            # Check minimum distance
            if all(np.linalg.norm(p - q) >= 0.5 * spacing for q in points):
                points.append(p)
    return np.array(points)

def construct(instance):
    """Construct the cluster configuration."""
    size = instance["n"]
    potential = instance["potential"]
    kind = instance.get("kind")
    
    # Time limit guard
    start_time = time.time()
    timeout = 290.0  # Leave 10s margin
    
    # Generate diverse initial guesses
    inits = []
    
    # 1. Icosahedral fragment
    ico = _generate_icosahedral_fragment(size)
    if ico is not None:
        inits.append(ico)
        
    # 2. FCC fragment
    fcc = _generate_fcc_fragment(size)
    if fcc is not None:
        inits.append(fcc)
        
    # 3. Random compact
    rand = _random_compact(size)
    inits.append(rand)
    
    # Add a few more random variants
    for i in range(2):
        inits.append(_random_compact(size, 1.0 + 0.1*i))
        
    best_energy = np.inf
    best_positions = None
    
    # Relax each initial guess
    for init in inits:
        if time.time() - start_time > timeout:
            break
        try:
            energy, positions = relax(init, potential, kind)
            if np.isfinite(energy) and energy < best_energy:
                # Check validity
                min_dist = np.min(np.linalg.norm(positions[:, np.newaxis, :] - positions[np.newaxis, :, :], axis=2))
                if min_dist > 0.35:
                    best_energy = energy
                    best_positions = positions
        except Exception:
            continue
            
    if best_positions is None:
        # Fallback: return a simple random valid configuration
        return _random_compact(size)
        
    # Basin Hopping on the best structure
    # Simple implementation: perturb, relax, accept if better
    current_energy = best_energy
    current_positions = best_positions
    
    # Number of basin hopping steps depends on time
    # Estimate cost per step: relax is ~0.1-1s. 
    # We have ~250s left. Let's allow up to 50 steps.
    max_bh_steps = 50
    
    for step in range(max_bh_steps):
        if time.time() - start_time > timeout:
            break
        
        # Perturb
        # Scale perturbation by 1/sqrt(n) or fixed
        noise_scale = 0.2
        perturbed = current_positions + np.random.normal(0, noise_scale, (size, 3))
        
        try:
            energy, positions = relax(perturbed, potential, kind)
            if np.isfinite(energy):
                # Check validity
                min_dist = np.min(np.linalg.norm(positions[:, np.newaxis, :] - positions[np.newaxis, :, :], axis=2))
                if min_dist > 0.35:
                    if energy < current_energy:
                        current_energy = energy
                        current_positions = positions
                    # Metropolis acceptance? 
                    # For global min search, simple descent (accept only if better) is safer 
                    # to avoid getting stuck in a bad basin if we don't have a good temperature schedule.
                    # However, standard basin hopping uses Metropolis. 
                    # Given the time constraint and lack of temperature info, 
                    # let's stick to "accept if better" to ensure we don't lose the best solution.
        except Exception:
            continue
            
    return current_positions
