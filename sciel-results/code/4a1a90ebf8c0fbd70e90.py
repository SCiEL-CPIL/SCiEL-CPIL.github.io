def _local_refine(x, max_passes=5):
    """
    Perform a few passes of coordinate descent to refine the sequence.
    """
    A = _autoconv(x)
    S = np.sum(x)
    current_score = _score(x)
    
    for _ in range(max_passes):
        improved = False
        for i in range(N):
            # Try flipping x[i]
            x[i] *= -1
            new_S = S - 2 * x[i] # x[i] is now -old_x[i], so new_S = old_S - 2*(-old_x[i])? 
            # Wait, if x[i] was v, it becomes -v.
            # S_new = S - v - (-v) = S - 2v? No.
            # S = sum(x). x_new = x - 2*v*e_i.
            # S_new = S - 2*v.
            # But we already flipped x[i]. So x[i] is now -v.
            # The change is -2v.
            # So S_new = S - 2*(x[i] * -1) ? No.
            # Let's just recompute S_new = np.sum(x). It's O(N) and N=400.
            
            new_S = np.sum(x)
            if abs(new_S) < 1e-12:
                x[i] *= -1 # Revert
                continue
            
            # Update A efficiently? Or just recompute?
            # Recomputing A is O(N log N). 400 * 400 * 9 ~ 1.4M ops per pass.
            # 5 passes ~ 7M ops. Very fast.
            new_A = _autoconv(x)
            new_m = np.max(np.abs(new_A))
            new_score = new_m / (new_S * new_S)
            
            if new_score < current_score:
                current_score = new_score
                S = new_S
                A = new_A
                improved = True
            else:
                x[i] *= -1 # Revert
        
        if not improved:
            break
            
    return x, current_score

def construct():
    start_time = time.time()
    deadline = start_time + 145.0
    
    best_x = None
    best_score = np.inf
    
    # Generate several candidate sequences
    # 1. Random
    # 2. M-sequence like (using a simple LFSR with a primitive poly)
    # 3. Chirp (for diversity, as it worked in other islands)
    
    candidates = []
    
    # Candidate 1: Random
    candidates.append(np.random.choice([-1, 1], size=N).astype(float))
    
    # Candidate 2: LFSR-based
    # Let's implement a simple LFSR for m=9 (length 511)
    # Primitive polynomial for GF(2^9): x^9 + x^4 + 1
    # Taps at 9 and 4. 
    # We'll generate 511 bits and take the first 400.
    def lfsr_sequence(degree, taps, length):
        # taps are the exponents in the polynomial (excluding degree)
        # e.g., x^9 + x^4 + 1 -> taps = [4, 0]
        reg = [1] * degree
        seq = []
        for _ in range(length):
            seq.append(reg[0])
            # Calculate feedback
            fb = 0
            for t in taps:
                if t == 0:
                    fb ^= 1
                else:
                    # reg[0] is x^{degree-1}, reg[degree-1] is x^0
                    # Tap t corresponds to x^t.
                    # Index in reg: degree - 1 - t
                    idx = degree - 1 - t
                    if 0 <= idx < degree:
                        fb ^= reg[idx]
            # Shift left
            reg = reg[1:] + [fb]
        return np.array([1 if b else -1 for b in seq])
    
    # Try a few primitive polynomials
    # m=9: x^9 + x^4 + 1
    candidates.append(lfsr_sequence(9, [4, 0], N))
    
    # m=9: x^9 + x^5 + x^2 + x + 1
    candidates.append(lfsr_sequence(9, [5, 2, 1, 0], N))
    
    # m=10: x^10 + x^3 + 1
    candidates.append(lfsr_sequence(10, [3, 0], N))
    
    # Candidate 3: Chirp-like
    # x[i] = (-1)^{i^2 mod 4} or similar
    i = np.arange(N)
    candidates.append(np.where((i * i) % 4 < 2, 1, -1).astype(float))
    
    # Evaluate and refine each candidate
    for x in candidates:
        if time.time() > deadline - 20:
            break
            
        # Initial score
        sc = _score(x)
        
        # Refine
        x_refined, sc_refined = _local_refine(x, max_passes=10)
        
        if sc_refined < best_score:
            best_score = sc_refined
            best_x = x_refined
    
    # If no candidate was processed (should not happen), return random
    if best_x is None:
        best_x = np.random.choice([-1, 1], size=N).astype(float)
        
    return best_x

