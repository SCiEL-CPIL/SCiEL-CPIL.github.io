"""
Strategy: Algebraic Construction via m-sequences (LFSR) with Local Refinement
The task seeks signed step functions minimizing max(|autoconv|) / (sum)^2.
M-sequences (Maximum Length Sequences) generated by Linear Feedback Shift Registers (LFSR)
over GF(2) have ideal periodic autocorrelation: the periodic autocorrelation function is
N at lag 0 and -1 at all other lags.
For a linear autoconvolution of a finite segment of an m-sequence, the peaks are much
lower than for random or structured chirp sequences, especially relative to the sum.
We generate m-sequences of length close to N (or N if N is of form 2^m-1, otherwise we
take a segment or use a different primitive polynomial length and truncate/pad, but 
since N=400 is fixed, we will use the closest m-sequence length L where L=2^m-1.
Actually, N=400 is not of the form 2^m-1. The closest are 255 (2^8-1) and 511 (2^9-1).
We can generate a sequence of length 511 and take the first 400, or better, 
we can generate multiple m-sequences of different lengths and pick the one that 
gives the best score after truncation/padding or just use a length that divides or 
is close.
However, the problem specifies N=400. We must return a sequence of length 400.
Strategy:
1. Generate m-sequences for various primitive polynomial degrees m such that 2^m-1 is 
   reasonably close to N or larger.
2. For each, generate the sequence, map bits to {-1, 1}.
3. If length > N, take the first N elements.
4. If length < N, we might need to repeat or pad, but repeating breaks the autocorrelation 
   property significantly. It's better to use a length L >= N.
   Smallest m such that 2^m - 1 >= 400 is m=9 (511).
   We can also try m=10 (1023), etc.
5. For each candidate, perform a few steps of local sign-flip optimization to 
   further reduce the max absolute autoconvolution.
6. Return the best sequence found.

Why this is different:
- Uses deterministic algebraic structure (LFSR) rather than random initialization.
- Leverages known optimal periodic autocorrelation properties.
- Local search is used only for fine-tuning the linear (non-periodic) boundary effects 
  and to optimize the specific linear autoconvolution metric, not to explore the 
  entire space from scratch.
"""

import numpy as np
from numpy.fft import fft, ifft
import time

N = 400

def _autoconv(x):
    """Compute linear autoconvolution via FFT."""
    n = len(x)
    size = 2 * n - 1
    size2 = 1
    while size2 < size:
        size2 *= 2
    F = fft(x, size2)
    A = ifft(F * np.conj(F)).real
    return A[:size]

def _score(x):
    """Compute max(|autoconv|) / (sum(x))^2. Lower is better."""
    s = np.sum(x)
    if abs(s) < 1e-12:
        return np.inf
    A = _autoconv(x)
    m = np.max(np.abs(A))
    return m / (s * s)

