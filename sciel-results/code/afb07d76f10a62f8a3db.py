import numpy as np
import time
import math

def design(problem):
    """
    Optimizes a C4v-symmetric dielectric field generated by thresholding a 
    multi-scale Perlin-like noise field to maximize the TM band gap.
    """
    start_time = time.time()
    deadline = start_time + 180.0  # Safety margin
    
    size = problem["pixels"]
    eps_low = problem.get("eps_low", 1.0)
    eps_high = problem.get("eps_high", 12.0)
    
    # Precompute grid coordinates centered at 0
    # We define the field on [0, 1] x [0, 1]
    x = np.linspace(0.5/size, 1 - 0.5/size, size)
    X, Y = np.meshgrid(x, x, indexing='ij')
    Xc = X - 0.5
    Yc = Y - 0.5

    # Precompute G vectors for plane wave method
    # Evaluator uses 289 PWs (17x17). We use 15x15 (225) for speed, 
    # but 17x17 is safer for accuracy. Let's stick to 17x17 to match evaluator closely 
    # but use a smaller set of k-points.
    N_pw = 17
    G_vals = np.arange(-N_pw//2, N_pw//2 + 1) # -8 to 8
    Gx, Gy = np.meshgrid(G_vals, G_vals, indexing='ij')
    G_vectors = np.column_stack((Gx.ravel(), Gy.ravel()))
    num_pw = len(G_vectors)
    
    # Precompute G_diff for coefficient lookup
    # We need coeff[G_i - G_j]
    # G_diff[i, j] = G_vectors[i] - G_vectors[j]
    G_diff = G_vectors[:, np.newaxis, :] - G_vectors[np.newaxis, :, :]  # (num_pw, num_pw, 2)
    
    # Precompute indices for FFT lookup
    # coeff_matrix[i, j] = fft_inv_eps[dx % size, dy % size]
    # We can precompute the (dx, dy) pairs, but dx, dy depend on G_vectors which are fixed.
    # So we can precompute the indices (ix, iy) for each (i, j).
    ix_idx = (G_diff[:, :, 0]) % size
    iy_idx = (G_diff[:, :, 1]) % size
    
    # K points: 15 points in irreducible BZ
    # Gamma (0,0) to M (0.5, 0)
    # M (0.5, 0) to X (0.5, 0.5)
    # Gamma (0,0) to X (0.5, 0.5)
    k_points = []
    # Gamma-M: (t, 0) for t in [0, 0.5]
    for t in np.linspace(0, 0.5, 5):
        k_points.append((t, 0))
    # M-X: (0.5, t) for t in [0, 0.5]
    for t in np.linspace(0, 0.5, 5):
        k_points.append((0.5, t))
    # Gamma-X: (t, t) for t in [0, 0.5]
    for t in np.linspace(0, 0.5, 5):
        k_points.append((t, t))
        
    # Remove duplicates
    seen = set()
    unique_k = []
    for k in k_points:
        key = (round(k[0], 10), round(k[1], 10))
        if key not in seen:
            seen.add(key)
            unique_k.append(k)
            
    # Precompute k+G squared for each k-point?
    # (k+G)^2 = (kx+Gx)^2 + (ky+Gy)^2
    # This depends on k. We can precompute Gx^2+Gy^2 and 2*kx*Gx + 2*ky*Gy + kx^2+ky^2
    G_sq = np.sum(G_vectors ** 2, axis=1) # (num_pw,)
    
    def evaluate_cell(eps_grid):
        """
        Computes the band gap using a simplified plane-wave method.
        """
        inv_eps_grid = 1.0 / eps_grid
        fft_inv_eps = np.fft.fft2(inv_eps_grid)
        fft_inv_eps /= (size * size)
        
        # Extract coefficients
        # coeff_matrix[i, j] = fft_inv_eps[ix_idx[i,j], iy_idx[i,j]]
        coeff_matrix = fft_inv_eps[ix_idx, iy_idx]
        
        min_omega_5 = np.inf
        max_omega_4 = -np.inf
        
        for kx, ky in unique_k:
            kx2_ky2 = kx*kx + ky*ky
            # 2 * (k dot G)
            k_dot_G = 2.0 * (kx * G_vectors[:, 0] + ky * G_vectors[:, 1])
            omega_sq = G_sq + k_dot_G + kx2_ky2
            
            # M[i,j] = coeff_matrix[i,j] * omega_sq[i]
            # Note: The matrix for TM is M_ij = (k+G_i)^2 * (1/eps)_{G_i-G_j}
            M = coeff_matrix * omega_sq[:, np.newaxis]
            
            # Solve eigenvalue problem
            # M is Hermitian? 
            # (1/eps) is real and symmetric under G -> -G? 
            # eps_grid is real, so 1/eps is real.
            # fft_inv_eps[-G] = conj(fft_inv_eps[G])? 
            # Since eps is real, 1/eps is real. Its FFT has conjugate symmetry.
            # M_ji = coeff_ji * omega_sq_j = coeff_ij^* * omega_sq_j
            # M_ij^* = coeff_ij^* * omega_sq_i
            # For M to be Hermitian, we need M_ji = M_ij^*.
            # coeff_ji = (1/eps)_{G_j-G_i} = (1/eps)_{-(G_i-G_j)}.
            # Since 1/eps is real, (1/eps)_{-G} = (1/eps)_{G}.
            # So coeff_ji = coeff_ij.
            # Then M_ji = coeff_ij * omega_sq_j.
            # M_ij^* = coeff_ij^* * omega_sq_i.
            # These are not equal unless omega_sq_i = omega_sq_j.
            # Wait, the standard PW matrix is:
            # Sum_j [(k+G_i)^2 delta_ij + (1/eps)_{G_i-G_j} (k+G_j)^2] a_j = omega^2 a_i ? No.
            # The equation is: (k+G)^2 a_G + 1/(2pi)^2 Sum_{G'} (1/eps)_{G-G'} (k+G')^2 a_{G'} = omega^2 a_G ?
            # Actually, the matrix is H_ij = (k+G_i)^2 delta_ij + (1/eps)_{G_i-G_j} (k+G_j)^2 ? No.
            # Let's check the standard form.
            # TM: 1/eps(r) * (-nabla^2) E_z = omega^2 E_z
            # In PW: Sum_j (1/eps)_{G_i-G_j} (k+G_j)^2 a_j = omega^2 a_i
            # So M_ij = (1/eps)_{G_i-G_j} (k+G_j)^2
            # This matrix is NOT Hermitian in general.
            # However, we can transform it.
            # Let S_ij = (1/eps)_{G_i-G_j} (k+G_i) (k+G_j) ? No.
            # Actually, the matrix M_ij = (1/eps)_{G_i-G_j} (k+G_j)^2 is similar to a Hermitian matrix.
            # Or we can just use eigvals.
            # But eigvals of non-Hermitian matrices can be complex.
            # The eigenvalues should be real.
            
            eigvals = np.linalg.eigvals(M)
            real_eigvals = np.sort(np.real(eigvals))
            
            if len(real_eigvals) >= 5:
                # Filter out negative values if any (numerical noise)
                pos_eigvals = real_eigvals[real_eigvals > 0]
                if len(pos_eigvals) >= 5:
                    omega_4 = np.sqrt(pos_eigvals[3])
                    omega_5 = np.sqrt(pos_eigvals[4])
                    
                    max_omega_4 = max(max_omega_4, omega_4)
                    min_omega_5 = min(min_omega_5, omega_5)
        
        if min_omega_5 == np.inf or max_omega_4 == -np.inf:
            return -1.0
            
        gap = min_omega_5 - max_omega_4
        midgap = 0.5 * (min_omega_5 + max_omega_4)
        if midgap == 0:
            return -1.0
        ratio = 2 * gap / midgap
        return ratio

    # Perlin Noise Generator (Simplified)
    # We use a set of random gradients and interpolate.
    # To ensure C4v symmetry, we generate noise on the fundamental domain [0, 0.5]x[0, 0.5]
    # and reflect it.
    
    def generate_noise_field(params, size):
        """
        params: [freq1, amp1, freq2, amp2, freq3, amp3, offset]
        Returns a 32x32 field.
        """
        freq1, amp1, freq2, amp2, freq3, amp3, offset = params
        
        # Generate random permutation for Perlin
        # Use fixed seed for reproducibility of the noise structure, 
        # but vary the sampling position?
        # No, we want different shapes.
        # Let's use the params to shift the sampling or change the lattice.
        
        # Simple approach: Sum of sinusoidal patterns with random phases?
        # Perlin is better for "texture".
        
        # Let's implement a simple 2D Perlin-like function using value noise with smoothstep.
        # Grid of random values
        # To make it C4v symmetric, we define it on [0, 0.5] x [0, 0.5]
        
        # We will use 3 octaves of value noise.
        # Octave 1: freq1
        # Octave 2: freq2
        # Octave 3: freq3
        
        def value_noise(x, y, freq, seed):
            # Scale coordinates
            x_scaled = x * freq
            y_scaled = y * freq
            
            # Integer grid points
            x0 = np.floor(x_scaled).astype(int)
            y0 = np.floor(y_scaled).astype(int)
            x1 = x0 + 1
            y1 = y0 + 1
            
            # Fractional parts
            fx = x_scaled - x0
            fy = y_scaled - y0
            
            # Smoothstep
            fx = fx * fx * (3 - 2 * fx)
            fy = fy * fy * (3 - 2 * fy)
            
            # Get random values at grid points
            # Use a hash function based on coordinates and seed
            # hash(x, y, seed)
            
            def hash_val(ix, iy, s):
                # Simple hash
                h = np.sin(ix * 12.9898 + iy * 78.233 + s * 43.123) * 43758.5453
                return h - np.floor(h)
            
            v00 = hash_val(x0, y0, seed)
            v10 = hash_val(x1, y0, seed)
            v01 = hash_val(x0, y1, seed)
            v11 = hash_val(x1, y1, seed)
            
            # Interpolate
            v0 = v00 * (1 - fx) + v10 * fx
            v1 = v01 * (1 - fx) + v11 * fx
            v = v0 * (1 - fy) + v1 * fy
            
            return v
        
        # We need to generate the field on the full 32x32 grid, but using the symmetry.
        # Actually, it's easier to generate on the full grid and then symmetrize.
        # But the noise must be periodic? No, the unit cell is periodic.
        # Perlin noise is not periodic by default.
        # We can make it periodic by wrapping the grid indices.
        
        # Let's stick to the Fourier series but with more harmonics and random phases?
        # The prompt suggests Perlin noise.
        # Let's implement periodic value noise.
        
        def periodic_value_noise(x, y, freq, seed, period):
            x_scaled = (x * freq) / period
            y_scaled = (y * freq) / period
            
            x0 = np.floor(x_scaled).astype(int)
            y0 = np.floor(y_scaled).astype(int)
            x1 = (x0 + 1) % int(freq) # Wrap around
            y1 = (y0 + 1) % int(freq)
            
            fx = x_scaled - x0
            fy = y_scaled - y0
            
            fx = fx * fx * (3 - 2 * fx)
            fy = fy * fy * (3 - 2 * fy)
            
            def hash_val(ix, iy, s):
                h = np.sin(ix * 12.9898 + iy * 78.233 + s * 43.123) * 43758.5453
                return h - np.floor(h)
            
            v00 = hash_val(x0, y0, seed)
            v10 = hash_val(x1, y0, seed)
            v01 = hash_val(x0, y1, seed)
            v11 = hash_val(x1, y1, seed)
            
            v0 = v00 * (1 - fx) + v10 * fx
            v1 = v01 * (1 - fx) + v11 * fx
            v = v0 * (1 - fy) + v1 * fy
            return v

        # Generate field
        # We use 3 octaves
        # Freqs should be integers for periodicity on the unit cell [0,1]
        # If freq is integer, the noise is periodic with period 1.
        
        f1 = int(np.clip(freq1, 1, 20))
        f2 = int(np.clip(freq2, 1, 40))
        f3 = int(np.clip(freq3, 1, 80))
        
        n1 = periodic_value_noise(Xc, Yc, f1, 1.0, 1.0)
        n2 = periodic_value_noise(Xc, Yc, f2, 2.0, 1.0)
        n3 = periodic_value_noise(Xc, Yc, f3, 3.0, 1.0)
        
        field = amp1 * n1 + amp2 * n2 + amp3 * n3 + offset
        
        # Symmetrize the field to enforce C4v
        # Average with all 8 symmetric counterparts
        sym_field = np.zeros((size, size))
        counts = np.zeros((size, size))
        
        for i in range(size):
            for j in range(size):
                val = field[i, j]
                positions = [
                    (i, j),
                    (size-1-i, j),
                    (i, size-1-j),
                    (size-1-i, size-1-j),
                    (j, i),
                    (size-1-j, i),
                    (j, size-1-i),
                    (size-1-j, size-1-i)
                ]
                for (pi, pj) in positions:
                    sym_field[pi, pj] += val
                    counts[pi, pj] += 1
        
        sym_field /= counts
        return sym_field

    def get_eps_grid(field):
        # Binarize or smooth?
        # The task asks for 0/1 pixels.
        # But we can optimize a continuous field and binarize at the end.
        # However, binarization is a discrete jump.
        # It's better to optimize the continuous field to be close to 0 or 1,
        # then binarize.
        
        # Map field to [0, 1]
        # field range is roughly [-1, 1] * amp_sum
        # Let's normalize
        min_f = np.min(field)
        max_f = np.max(field)
        if max_f - min_f < 1e-6:
            return np.ones((size, size)) * 0.5 * (eps_low + eps_high)
            
        norm_field = (field - min_f) / (max_f - min_f)
        
        # Apply a sigmoid to make it sharp
        # Or just linear map to [eps_low, eps_high]
        eps_grid = eps_low + (eps_high - eps_low) * norm_field
        return eps_grid

    # Optimization Strategy
    # Parameters: [freq1, amp1, freq2, amp2, freq3, amp3, offset]
    # freqs: 1-20, 1-40, 1-80
    # amps: 0-1
    # offset: -1 to 1
    
    best_params = None
    best_score = -np.inf
    
    # Initial guesses
    # 1. Low freq blob
    # 2. High freq texture
    # 3. Random
    
    num_params = 7
    
    # Precompute Xc, Yc already done
    
    def score_params(params):
        field = generate_noise_field(params, size)
        eps_grid = get_eps_grid(field)
        return evaluate_cell(eps_grid)
    
    # Run optimization
    num_restarts = 30
    
    for restart in range(num_restarts):
        if time.time() > deadline - 20:
            break
            
        # Generate initial params
        if restart == 0:
            # Try a simple blob
            p = np.array([4.0, 1.0, 8.0, 0.5, 16.0, 0.2, 0.0])
        elif restart == 1:
            # Try high freq
            p = np.array([10.0, 0.5, 20.0, 0.5, 40.0, 0.5, 0.0])
        else:
            p = np.array([
                np.random.uniform(2, 20),
                np.random.uniform(0.2, 1.0),
                np.random.uniform(4, 40),
                np.random.uniform(0.2, 1.0),
                np.random.uniform(8, 80),
                np.random.uniform(0.2, 1.0),
                np.random.uniform(-0.5, 0.5)
            ])
            
        score = score_params(p)
        
        if score > best_score:
            best_score = score
            best_params = p.copy()
            
        # Local refinement
        # Coordinate ascent
        for step in range(50):
            if time.time() > deadline - 20:
                break
                
            improved = False
            for i in range(num_params):
                # Try perturbing param i
                step_size = 0.1
                if i in [0, 2, 4]: # freqs
                    step_size = 1.0
                elif i in [1, 3, 5]: # amps
                    step_size = 0.05
                else: # offset
                    step_size = 0.05
                    
                p_plus = p.copy()
                p_minus = p.copy()
                
                # Adjust step size based on parameter range
                if i in [0, 2, 4]:
                    p_plus[i] = min(p[i] + step_size, [20, 40, 80][i//2])
                    p_minus[i] = max(p[i] - step_size, 1)
                elif i in [1, 3, 5]:
                    p_plus[i] = min(p[i] + step_size, 1.5)
                    p_minus[i] = max(p[i] - step_size, 0.0)
                else:
                    p_plus[i] = min(p[i] + step_size, 1.0)
                    p_minus[i] = max(p[i] - step_size, -1.0)
                    
                score_plus = score_params(p_plus)
                score_minus = score_params(p_minus)
                
                if score_plus > score and score_plus > score_minus:
                    p = p_plus
                    score = score_plus
                    improved = True
                elif score_minus > score and score_minus > score_plus:
                    p = p_minus
                    score = score_minus
                    improved = True
                    
                if score > best_score:
                    best_score = score
                    best_params = p.copy()
                    
            if not improved:
                # Try a random jump if stuck
                if np.random.random() < 0.2:
                    p = p + np.random.normal(0, 0.1, num_params)
                    # Clip
                    p[0] = np.clip(p[0], 1, 20)
                    p[1] = np.clip(p[1], 0, 1.5)
                    p[2] = np.clip(p[2], 1, 40)
                    p[3] = np.clip(p[3], 0, 1.5)
                    p[4] = np.clip(p[4], 1, 80)
                    p[5] = np.clip(p[5], 0, 1.5)
                    p[6] = np.clip(p[6], -1, 1)
                    score = score_params(p)
                    if score > best_score:
                        best_score = score
                        best_params = p.copy()
                else:
                    break
    
    if best_params is None:
        # Fallback
        cell = []
        for i in range(size):
            row = []
            for j in range(size):
                row.append(0)
            cell.append(row)
        return cell
        
    final_field = generate_noise_field(best_params, size)
    final_eps = get_eps_grid(final_field)
    
    # Binarize
    threshold = 0.5 * (eps_low + eps_high)
    binary_cell = (final_eps > threshold).astype(int)
    
    # Enforce strict symmetry on the binary cell
    sym_cell = np.zeros((size, size), dtype=int)
    counts = np.zeros((size, size), dtype=int)
    
    for i in range(size):
        for j in range(size):
            val = binary_cell[i, j]
            positions = [
                (i, j),
                (size-1-i, j),
                (i, size-1-j),
                (size-1-i, size-1-j),
                (j, i),
                (size-1-j, i),
                (j, size-1-i),
                (size-1-j, size-1-i)
            ]
            for (pi, pj) in positions:
                sym_cell[pi, pj] += val
                counts[pi, pj] += 1
                
    final_cell = []
    for i in range(size):
        row = []
        for j in range(size):
            if counts[i, j] > 0:
                avg_val = sym_cell[i, j] / counts[i, j]
                row.append(1 if avg_val >= 0.5 else 0)
            else:
                row.append(0)
        final_cell.append(row)
        
    return final_cell

