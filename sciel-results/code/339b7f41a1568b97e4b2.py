import numpy as np
import time
import random
import math
from collections import defaultdict

def _normalize_line(A, B, C):
    """
    Normalize line coefficients (A, B, C) for Ax + By + C = 0.
    Divides by gcd and ensures the first non-zero entry is positive.
    """
    # Find GCD of absolute values
    g = math.gcd(math.gcd(abs(A), abs(B)), abs(C))
    if g == 0:
        return (0, 0, 0) # Should not happen for valid lines from 2 distinct points
    A //= g
    B //= g
    C //= g
    
    # Ensure first non-zero is positive
    if A < 0 or (A == 0 and B < 0):
        A = -A
        B = -B
        C = -C
    return (A, B, C)

def _get_line_from_points(p1, p2):
    """
    Get normalized line tuple from two points.
    """
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and y1 == y2:
        return None
    A = y2 - y1
    B = x1 - x2
    C = x2 * y1 - x1 * y2
    return _normalize_line(A, B, C)

def _count_incidences(points, line):
    """
    Count how many points lie on the given line.
    """
    A, B, C = line
    count = 0
    for p in points:
        x, y = p
        if A * x + B * y + C == 0:
            count += 1
    return count

def _generate_candidate_lines(points):
    """
    Generate all unique lines passing through at least 2 points.
    Returns a list of (line_tuple, incidence_count).
    """
    lines_dict = {}
    n = len(points)
    for i in range(n):
        for j in range(i + 1, n):
            line = _get_line_from_points(points[i], points[j])
            if line is None:
                continue
            if line not in lines_dict:
                lines_dict[line] = 0
    
    # Now count incidences for each unique line
    # Optimization: We can count during generation if we were clever, 
    # but 54 points is small. 
    # Better: For each line, count points.
    # Actually, we can just iterate points for each line.
    # Number of lines is at most 1431.
    # 1431 * 54 = 77k ops. Very fast.
    
    candidates = []
    for line in lines_dict.keys():
        count = _count_incidences(points, line)
        # Only consider lines with at least 2 points? 
        # The problem doesn't forbid lines with 1 point, but they add 1 to incidence.
        # However, lines are defined by the set of points. 
        # If a line has only 1 point, it's not generated by pairs.
        # Should we consider lines with only 1 point?
        # "lines a (27, 3) array... A*x + B*y + C = 0"
        # It doesn't say lines must pass through >= 2 points.
        # But a line passing through only 1 point is "worse" than a line passing through 2.
        # Given we have 1431 lines with >= 2 points, and we only need 27,
        # it is highly unlikely that a line with 1 point would be in the top 27
        # unless the grid is extremely sparse and no 2-point lines exist (impossible for 54 points).
        # So we can ignore lines with count < 2 for the top 27 selection, 
        # unless we run out of candidates.
        candidates.append((line, count))
        
    return candidates

def _select_best_lines(candidates, m):
    """
    Select top m lines from candidates to maximize sum of incidences.
    Returns (selected_lines, total_incidence).
    """
    # Sort by incidence count descending
    candidates_sorted = sorted(candidates, key=lambda x: x[1], reverse=True)
    selected = []
    total_inc = 0
    for line, count in candidates_sorted:
        if len(selected) == m:
            break
        selected.append(line)
        total_inc += count
    return selected, total_inc

def _evaluate_configuration(points, m=27):
    """
    Evaluate a point configuration.
    Returns (total_incidence, selected_lines).
    """
    candidates = _generate_candidate_lines(points)
    if len(candidates) < m:
        # If we don't have enough lines with >= 2 points, we might need to add arbitrary lines?
        # But with 54 points, we always have >= 1431 pairs, so we have enough lines.
        pass
    selected_lines, total_inc = _select_best_lines(candidates, m)
    return total_inc, selected_lines

def _initial_grid(w, h):
    """
    Create a grid of w x h points.
    """
    points = []
    for i in range(w):
        for j in range(h):
            points.append((i, j))
    return points

def _valid_points(points):
    """
    Check if points are valid (distinct, integer).
    """
    if len(points) != 54:
        return False
    seen = set()
    for p in points:
        if p in seen:
            return False
        seen.add(p)
        if not (isinstance(p[0], int) and isinstance(p[1], int)):
            return False
    return True

def szemeredi_trotter_incidences():
    start_time = time.time()
    timeout = 590  # Safety margin
    
    # 1. Try several initial configurations
    initial_configs = [
        _initial_grid(3, 18),
        _initial_grid(2, 27),
        _initial_grid(6, 9),
        _initial_grid(1, 54),
        _initial_grid(9, 6),
        _initial_grid(18, 3),
    ]
    
    best_inc = -1
    best_points = None
    best_lines = None
    
    # Evaluate initial configs
    for config in initial_configs:
        if not _valid_points(config):
            continue
        inc, lines = _evaluate_configuration(config)
        if inc > best_inc:
            best_inc = inc
            best_points = [p[:] for p in config]
            best_lines = lines[:]
            
    # 2. Simulated Annealing on the best initial config
    current_points = [p[:] for p in best_points]
    current_inc = best_inc
    current_lines = best_lines[:]
    
    T = 10.0
    T_min = 0.1
    cooling = 0.99
    
    # Pre-compute bounds for random moves
    # Keep points within a reasonable box, e.g., [-100, 100]
    MIN_COORD = -100
    MAX_COORD = 100
    
    step = 0
    while time.time() - start_time < timeout:
        step += 1
        
        # Move a random point
        idx = random.randint(0, 53)
        old_point = current_points[idx][:]
        
        # Random move: delta in [-3, 3]
        dx = random.randint(-3, 3)
        dy = random.randint(-3, 3)
        new_point = (old_point[0] + dx, old_point[1] + dy)
        
        # Check bounds and duplicates
        if new_point[0] < MIN_COORD or new_point[0] > MAX_COORD or new_point[1] < MIN_COORD or new_point[1] > MAX_COORD:
            continue
            
        # Check duplicate
        is_dup = False
        for i, p in enumerate(current_points):
            if i != idx and p == new_point:
                is_dup = True
                break
        if is_dup:
            continue
            
        # Apply move
        current_points[idx] = new_point
        
        # Evaluate
        new_inc, new_lines = _evaluate_configuration(current_points)
        
        # Acceptance
        delta = new_inc - current_inc
        if delta >= 0 or random.random() < math.exp(delta / T):
            current_inc = new_inc
            current_lines = new_lines
            if current_inc > best_inc:
                best_inc = current_inc
                best_points = [p[:] for p in current_points]
                best_lines = current_lines[:]
        else:
            # Revert
            current_points[idx] = old_point
        
        T *= cooling
        if T < T_min:
            T = T_min
            # Reheat occasionally?
            if step % 1000 == 0:
                T = 5.0

    # Final Output Preparation
    # Ensure best_points and best_lines are numpy arrays of correct type
    points_arr = np.array(best_points, dtype=np.int64)
    lines_arr = np.array(best_lines, dtype=np.int64)
    
    # Validation check (just in case)
    if points_arr.shape != (54, 2) or lines_arr.shape != (27, 3):
        # Fallback to seed
        k = 3
        xs = np.arange(1, k + 1)
        ys = np.arange(1, 2 * k * k + 1)
        px, py = np.meshgrid(xs, ys, indexing="ij")
        points_arr = np.stack([px.ravel(), py.ravel()], axis=1).astype(np.int64)
        
        rows = []
        for a in range(1, k + 1):
            for b in range(1, k * k + 1):
                rows.append((a, -1, b))
        lines_arr = np.array(rows, dtype=np.int64)

    return points_arr, lines_arr
