    n, m, p = 3, 4, 4
    total_rank = 39
    U = np.zeros((n * m, total_rank))
    V = np.zeros((m * p, total_rank))
    W = np.zeros((p * n, total_rank))
    
    # Part 1: Laderman for top 2 rows (Rank 23)
    U_l, V_l, W_l = _laderman_4x4x4()
    
    # U_l is 16x23. We need first 8 rows (i=0,1)
    U[:8, :23] = U_l[:8, :]
    V[:, :23] = V_l
