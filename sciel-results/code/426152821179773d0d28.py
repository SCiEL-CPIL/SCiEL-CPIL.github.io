    deadline = time.time() + 140.0
    n, m, p = DIMENSIONS  # 3, 5, 6
    
    # Bini et al. (1978) rank-23 decomposition for 3x3 @ 3x3
    # Each term: (u, v, w) where u,v,w are 9-element lists (row-major 3x3)
