    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None

        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])

        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []

        for nx, ny in normals:
            for px, py in pts:
                proj = px * nx + py * ny
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-proj)
                A_ub.append([nx, ny, -1.0])
                b_ub.append(proj)

        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]

        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])

        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T

        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])

        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf'), (cx, cy), float('inf')

        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -50, 50)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S, (cx, cy), D

    def exact_max_proj(pts, beta, cx, cy):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        max_proj = np.max(np.abs(projs))
        return max_proj

    def newton_polish_center(pts, beta, cx, cy, max_iter=200, tol=1e-14):
        """High-precision Newton-Raphson polish for the center at fixed beta.
        
        The center optimization is a convex piecewise-linear problem.
        We use subgradient Newton with line search for high precision.
        """
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        
        for _ in range(max_iter):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
                
            pts_centered = pts - np.array([cx, cy])
            projs = pts_centered @ normals.T  # shape (N, 6)
            
            # For each normal direction, find the max and min projection
            max_idx = np.argmax(projs, axis=0)  # (6,)
            min_idx = np.argmin(projs, axis=0)  # (6,)
            
            # Subgradient: sum of normals weighted by active constraints
            # The objective is max over all (±n_k · (p_i - c))
            # Gradient w.r.t. c: -sum of active normals
            # For min: +sum of active normals (since -min = max of -)
            
            subgrad_x = 0.0
            subgrad_y = 0.0
            
            for k in range(6):
                px, py = pts[max_idx[k]]
                nx, ny = normals[k]
                # Constraint: n_k · (p - c) <= D  =>  -n_k · c <= D - n_k · p
                # Active if n_k · (p - c) = D (max)
                val = (px - cx) * nx + (py - cy) * ny
                if val > -tol:  # active
                    subgrad_x += -nx
                    subgrad_y += -ny
                
                px2, py2 = pts[min_idx[k]]
                val2 = (px2 - cx) * nx + (py2 - cy) * ny
                if val2 < tol:  # active (min constraint)
                    subgrad_x += nx
                    subgrad_y += ny
            
            if abs(subgrad_x) < tol and abs(subgrad_y) < tol:
                break
            
            # Hessian approximation: sum of outer products of active normals
            Hxx = 0.0
            Hxy = 0.0
            Hyy = 0.0
            
            for k in range(6):
                nx, ny = normals[k]
                # Check if active
                max_val = np.max(projs[:, k])
                min_val = np.min(projs[:, k])
                D_k = max(max_val, -min_val)
                
                if max_val > -tol:
                    Hxx += nx * nx
                    Hxy += nx * ny
                    Hyy += ny * ny
                if min_val < tol:
                    Hxx += nx * nx
                    Hxy += nx * ny
                    Hyy += ny * ny
            
            det = Hxx * Hyy - Hxy * Hxy
            if abs(det) < 1e-20:
                # Regularize
                Hxx += 1e-10
                Hyy += 1e-10
                det = Hxx * Hyy - Hxy * Hxy
            
            if abs(det) < 1e-20:
                break
            
            # Newton step: H * delta = -subgrad
            inv_det = 1.0 / det
            dx = (-Hyy * subgrad_x + Hxy * subgrad_y) * inv_det
            dy = (-Hxx * subgrad_y + Hxy * subgrad_x) * inv_det
            
            # Line search
            best_step = 1.0
            current_obj = exact_max_proj(pts, beta, cx, cy)
            
            for t in [1.0, 0.5, 0.25, 0.125, 0.0625, 0.03125]:
                new_cx = cx + t * dx
                new_cy = cy + t * dy
                new_obj = exact_max_proj(pts, beta, new_cx, new_cy)
                if new_obj < current_obj - 1e-15:
                    best_step = t
                    break
            
            cx += best_step * dx
            cy += best_step * dy
            
            if abs(dx) < tol and abs(dy) < tol:
                break
        
        return cx, cy

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None

        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None

        # Initial center from LP at beta=0
        S_init, c_init, _ = calc_S_for_beta(pts, 0.0)
        if c_init is not None:
            cx0, cy0 = c_init
        else:
            cx0 = float(np.mean(pts[:, 0]))
            cy0 = float(np.mean(pts[:, 1]))

        # Grid over beta
        best_smooth_S = float('inf')
        best_smooth_beta = 0.0
        for i in range(121):
            beta = i * (math.pi / 6) / 120
            S_s, _, _ = smooth_calc_S(pts, beta, cx0, cy0, temperature=0.1)
            if S_s < best_smooth_S:
                best_smooth_S = S_s
                best_smooth_beta = beta

        # Smooth optimization
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                temperatures = [0.3, 0.1, 0.05, 0.02, 0.01]
                start_betas = [best_smooth_beta, 0.0, math.pi/12, math.pi/6,
                              best_smooth_beta + 0.02, best_smooth_beta - 0.02,
                              best_smooth_beta + 0.04, best_smooth_beta - 0.04,
                              math.pi/24, 5*math.pi/24]

                for temp in temperatures:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    for sb in start_betas:
                        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                            break

                        def smooth_obj(params, t=temp):
                            cx, cy, beta = params
                            beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S, _, _ = smooth_calc_S(pts, beta, cx, cy, temperature=t)
                            return S

                        init = [cx0, cy0, sb]
                        res = minimize(smooth_obj, init, method='Nelder-Mead',
                                     options={'maxiter': 3000, 'xatol': 1e-14, 'fatol': 1e-14})

                        if res.fun < 1e10:
                            cx_r, cy_r, beta_r = res.x
                            beta_r = ((beta_r % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S_exact, c_exact, _ = calc_S_for_beta(pts, beta_r)
                            if S_exact < best_S:
                                best_S = S_exact
                                best_beta = beta_r
                                best_center = c_exact
        except Exception:
            pass

        if best_center is None:
            beta_r = best_smooth_beta
            S_exact, c_exact, _ = calc_S_for_beta(pts, beta_r)
            if S_exact < best_S:
                best_S = S_exact
                best_beta = beta_r
                best_center = c_exact

        # Final polish with exact objective
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN and best_center is not None:
                def objective(params):
                    cx, cy, beta = params
                    beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                    max_proj = exact_max_proj(pts, beta, cx, cy)
                    return (max_proj + APOTHEM) / APOTHEM

                d = 0.005
                d2 = 0.01
                polish_starts = [
                    [best_center[0], best_center[1], best_beta],
                    [best_center[0], best_center[1], best_beta + d],
                    [best_center[0], best_center[1], best_beta - d],
                    [best_center[0], best_center[1], best_beta + d2],
                    [best_center[0], best_center[1], best_beta - d2],
                    [best_center[0] + d, best_center[1], best_beta],
                    [best_center[0] - d, best_center[1], best_beta],
                    [best_center[0], best_center[1] + d, best_beta],
                    [best_center[0], best_center[1] - d, best_beta],
                ]

                for init in polish_starts:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    res = minimize(objective, init, method='Nelder-Mead',
                                 options={'maxiter': 50000, 'xatol': 1e-16, 'fatol': 1e-16})
                    if res.fun < best_S:
                        best_S = res.fun
                        best_center = (res.x[0], res.x[1])
                        best_beta = ((res.x[2] % (math.pi/6)) + math.pi/6) % (math.pi/6)

                    # Newton polish for center at this beta
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    try:
                        ncx, ncy = newton_polish_center(pts, best_beta, best_center[0], best_center[1])
                        new_S = (exact_max_proj(pts, best_beta, ncx, ncy) + APOTHEM) / APOTHEM
                        if new_S < best_S:
                            best_S = new_S
                            best_center = (ncx, ncy)
                    except Exception:
                        pass

                    # SLSQP polish
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    try:
                        res2 = minimize(objective, [best_center[0], best_center[1], best_beta],
                                       method='SLSQP', options={'maxiter': 10000, 'ftol': 1e-18})
                        if res2.fun < best_S:
                            best_S = res2.fun
                            best_center = (res2.x[0], res2.x[1])
                            best_beta = ((res2.x[2] % (math.pi/6)) + math.pi/6) % (math.pi/6)
                    except Exception:
                        pass
        except Exception:
            pass

        return best_S, best_beta, best_center

