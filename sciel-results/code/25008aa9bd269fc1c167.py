import time
import random
from math import isqrt

P = {'n': 40, 'maximum_size': 18}

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    # 1. Generate the set of primes up to 40. This is a known valid solution of size 12.
    # Primes are "safe" because their prime factorization is unique and disjoint in a strong sense,
    # though composite sets can also be valid if they avoid multiplicative relations.
    primes = [a for a in range(2, P['n'] + 1) if all(a % d for d in range(2, isqrt(a) + 1))]
    
    # 2. Define a fast validity checker.
    # A set S has distinct subset products iff no non-empty subset of S has product 1 (impossible for ints > 1)
    # AND no two distinct subsets have the same product.
    # This is equivalent to: for any two distinct subsets A, B, prod(A) != prod(B).
    # A faster check: The set of all subset products must have size 2^k.
    # We can generate them iteratively.
    
    def is_valid(S):
        k = len(S)
        if k == 0:
            return True
        # Use a set of products. 
        # Optimization: If the number of distinct products is less than 2^k, it's invalid.
        # We can short-circuit if we find a collision.
        # However, for k up to 18, 2^18 = 262,144. This is fast enough in Python if done carefully.
        # Even better: check if the multiplicative group generated is free? 
        # No, just checking distinctness of subset products is the definition.
        
        # Efficient subset product generation:
        # Start with {1}. For each x in S, double the set of products by multiplying by x.
        # If at any point the size of the set of products is less than 2^i (where i is current count), collision occurred.
        products = {1}
        for x in S:
            # New products are old_products * x
            # If any new product is already in 'products', there's a collision.
            # Actually, we just need to check if len(products) doubles.
            # If len(products) before adding x is M, after adding x it should be 2*M.
            # If it's less, there was a collision.
            new_products = set()
            for p in products:
                new_products.add(p * x)
            # Check for intersection
            if products & new_products:
                return False
            products |= new_products
            # Optional: if len(products) < 2**len(current_S): return False (redundant if intersection check works)
        return True

    # 3. Local Search Strategy
    # Start with the prime set.
    current_set = set(primes)
    best_set = set(primes)
    best_size = len(best_set)
    
    # Candidate pool: all integers 2..40
    all_candidates = list(range(2, P['n'] + 1))
    
    # We want to maximize size. 
    # Strategy: 
    # 1. Try to add elements one by one (greedy improvement).
    # 2. If stuck, try swapping one element for another to potentially allow more additions later.
    
    def try_add(S, x):
        if x in S:
            return False
        new_S = S | {x}
        if is_valid(new_S):
            return True
        return False

    # Phase 1: Greedy Addition
    # Sort candidates by some heuristic? Maybe numbers with large prime factors are "safer"?
    # Or just iterate through all candidates.
    # Since we start with primes, we can try to add composites.
    # Let's shuffle candidates to avoid bias.
    random.shuffle(all_candidates)
    
    # We will run multiple random restarts or perturbations if time allows.
    # But first, let's see how far we can get from the prime seed.
    
    # To be more effective, we should try to add elements that are "independent".
    # A number x is independent from S if x is not in the multiplicative group generated by S?
    # Not exactly. It just needs to not create a product collision.
    
    # Let's do a simple local search:
    # While we can add an element, add it.
    # If we can't add any, try a swap: remove one element, try to add two? Or just add one different one?
    
    # Let's try a hill-climbing approach with restarts.
    
    for restart in range(50):
        if time.time() > deadline:
            break
            
        # Start from a random valid subset? 
        # No, starting from primes is strong. Let's perturb the current best.
        # Or just restart from primes with a different random order of attempts.
        
        S = set(primes)
        
        # Greedy add
        added = True
        while added and time.time() < deadline:
            added = False
            # Shuffle candidates to randomize which one gets picked first
            candidates = [c for c in all_candidates if c not in S]
            random.shuffle(candidates)
            for x in candidates:
                if try_add(S, x):
                    S.add(x)
                    added = True
                    break # Restart the candidate loop to pick the next best? 
                         # Or just continue? Restarting is safer for greedy.
        
        if len(S) > best_size:
            best_set = S
            best_size = len(S)
            if best_size == P['maximum_size']:
                break # Can't do better
        
        # If we are stuck at a local optimum, try a swap move.
        # Remove a random element from S, try to add a random element not in S.
        # If valid, keep it. Then try to add more.
        # This is simulated annealing lite.
        
        if len(S) < P['maximum_size'] and time.time() < deadline - 5:
            for _ in range(100): # 100 swap attempts per restart
                if time.time() > deadline:
                    break
                if len(S) == 0:
                    break
                # Pick a random element to remove
                to_remove = random.choice(list(S))
                S.remove(to_remove)
                
                # Try to add a random element
                candidates = [c for c in all_candidates if c not in S]
                if not candidates:
                    S.add(to_remove) # Restore
                    break
                to_add = random.choice(candidates)
                
                if try_add(S, to_add):
                    S.add(to_add)
                    # Now try to add more
                    added = True
                    while added and time.time() < deadline:
                        added = False
                        candidates = [c for c in all_candidates if c not in S]
                        random.shuffle(candidates)
                        for x in candidates:
                            if try_add(S, x):
                                S.add(x)
                                added = True
                                break
                    if len(S) > best_size:
                        best_set = S
                        best_size = len(S)
                        if best_size == P['maximum_size']:
                            return list(best_set)
                else:
                    S.add(to_remove) # Restore if swap failed

    # Return the best set found
    return list(best_set)
