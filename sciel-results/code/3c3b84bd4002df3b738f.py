"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 256

# EVOLVE-BLOCK-START
import time

def _is_valid_sidon(S):
    sums = set()
    for i in range(len(S)):
        for j in range(i, len(S)):
            s = S[i] + S[j]
            if s in sums:
                return False
            sums.add(s)
    return True

def _seed_construct():
    selected, sums = [], set()
    for x in range(1, N + 1):
        added = [x + a for a in selected] + [2 * x]
        if len(set(added)) == len(added) and not sums.intersection(added):
            selected.append(x)
            sums.update(added)
    return selected

def construct():
    start_time = time.time()
    deadline = start_time + 25.0
    
    available = set(range(1, N + 1))
    S = []
    sums = set()
    
    while available:
        if time.time() > deadline:
            break
            
        candidates = list(available)
        best_x = None
        max_blocked = -1
        
        for x in candidates:
            # Calculate sums generated by x with current S
            x_sums = set()
            for s in S:
                x_sums.add(x + s)
            x_sums.add(2 * x)
            
            blocked_count = 0
            for y in candidates:
                if y == x:
                    continue
                
                blocked = False
                # Check if y is blocked by adding x to S
                # y is blocked if sums(y, S ∪ {x}) intersects sums(S ∪ {x})
                # sums(S ∪ {x}) = sums ∪ x_sums
                # sums(y, S ∪ {x}) = {y+s for s in S} ∪ {y+x} ∪ {2y}
                
                # Since y is in available, sums(y, S) does not intersect sums.
                # So we only need to check:
                # 1. y+x in sums
                # 2. y+x in x_sums (impossible for y!=x, y not in S)
                # 3. any y+s in x_sums
                # 4. 2y in x_sums
                # 5. any y+s in sums (impossible)
                # 6. 2y in sums (impossible)
                
                if (y + x) in sums:
                    blocked = True
                else:
                    # Check y+s in x_sums
                    for s in S:
                        if (y + s) in x_sums:
                            blocked = True
                            break
                    if not blocked and (2 * y) in x_sums:
                        blocked = True
                
                if blocked:
                    blocked_count += 1
            
            if blocked_count > max_blocked:
                max_blocked = blocked_count
                best_x = x
                
        if best_x is None:
            # Should not happen if available is not empty
            break
            
        # Add best_x to S
        S.append(best_x)
        for s in S[:-1]:
            sums.add(best_x + s)
        sums.add(2 * best_x)
        
        # Update available
        new_available = set()
        for y in available:
            if y == best_x:
                continue
            # Check if y is compatible with new S
            # y is compatible if sums(y, S) does not intersect sums
            compatible = True
            for s in S:
                if (y + s) in sums:
                    compatible = False
                    break
            if compatible and (2 * y) in sums:
                compatible = False
                
            if compatible:
                new_available.add(y)
                
        available = new_available
        
    if not S:
        return _seed_construct()
        
    if not _is_valid_sidon(S):
        return _seed_construct()
        
    return S
# EVOLVE-BLOCK-END
