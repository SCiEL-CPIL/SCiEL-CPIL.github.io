# Dzugutov potential parameters
A_POT = 5.82
B_POT = 1.28
a_POT = 1.87
b_POT = 1.94
c_POT = 1.10
d_POT = 0.27
m_POT = 16


def _compute_energy(positions):
    """Compute Dzugutov potential energy for a set of positions."""
    n = len(positions)
    energy = 0.0
    for i in range(n):
        for j in range(i + 1, n):
            r = np.linalg.norm(positions[i] - positions[j])
            if r < 1e-12:
                continue
            if r < a_POT:
                energy += A_POT * (r ** (-m_POT) - B_POT) * np.exp(c_POT / (r - a_POT))
            elif r < b_POT:
                energy += B_POT * np.exp(d_POT / (r - b_POT))
            else:
                energy += 0.0
    return energy


def _generate_mackay_icosahedron(n):
    """Generate a Mackay icosahedral cluster structure for n atoms using proper shell growth."""
    phi = (1 + np.sqrt(5)) / 2
    
    # Icosahedron vertices (12)
    verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [-phi, 0, 1], [phi, 0, -1], [-phi, 0, -1]
    ])
    
    norm = np.linalg.norm(verts[0])
    verts = verts / norm
    
    points = [np.zeros(3)]
    points.extend(verts.tolist())
    
    if n <= 13:
        return np.array(points[:n])
    
    # Generate second shell using proper icosahedral symmetry
    # The icosahedral group has 60 rotational symmetries
    # We'll generate orbits of representative points
    
    # For Mackay icosahedron, second shell has 30 atoms
    # These correspond to the vertices of a truncated icosahedron or similar
    
    # Generate the icosahedral rotation matrices
    def _icosahedral_rotations():
        """Generate the 60 rotational symmetries of the icosahedron."""
        phi = (1 + np.sqrt(5)) / 2
        phi2 = phi * phi
        
        # Generate rotations by applying basic rotations to the vertex set
        # and tracking the transformation matrices
        rotations = []
        
        # Identity
        rotations.append(np.eye(3))
        
        # 12 C5 rotations (about 5-fold axes through opposite vertices)
        # 20 C3 rotations (about 3-fold axes through opposite face centers)
        # 30 C2 rotations (about 2-fold axes through opposite edge midpoints)
        
        # For simplicity, generate by finding all orthogonal matrices that map
        # the vertex set to itself
        verts_set = set([tuple(v) for v in verts])
        
        # Try all possible rotation matrices
        # This is expensive, so let's use a known set of icosahedral rotations
        
        # The icosahedral group can be generated by:
        # - 72-degree rotation about z-axis (C5)
        # - 180-degree rotation about x-axis (C2)
        
        angle_c5 = 2 * np.pi / 5
        R_z_c5 = np.array([
            [np.cos(angle_c5), -np.sin(angle_c5), 0],
            [np.sin(angle_c5), np.cos(angle_c5), 0],
            [0, 0, 1]
        ])
        
        R_x_c2 = np.array([
            [1, 0, 0],
            [0, -1, 0],
            [0, 0, -1]
        ])
        
        # Generate group by repeated application
        group = [np.eye(3)]
        changed = True
        while changed:
            changed = False
            for g in list(group):
                for gen in [R_z_c5, R_x_c2]:
                    new_g = gen @ g
                    # Check if already in group
                    is_dup = False
                    for existing in group:
                        if np.allclose(new_g, existing, atol=1e-10):
                            is_dup = True
                            break
                    if not is_dup:
                        group.append(new_g)
                        changed = True
        
        return group
    
    icos_rotations = _icosahedral_rotations()
    
    # Representative points for second shell (30 atoms total)
    # We need to find 3 orbits under the icosahedral group that sum to 30
    
    # Orbit sizes: 12 (vertices), 20 (face centers), 30 (edge midpoints)
    # For second shell, we want 30 atoms
    
    # Try edge midpoints: 30 edges -> orbit of size 30
    edge_length = np.inf
    for i in range(12):
        for j in range(i + 1, 12):
            d = np.linalg.norm(verts[i] - verts[j])
            if d < edge_length - 1e-10:
                edge_length = d
    
    # Find all edges
    edges = []
    for i in range(12):
        for j in range(i + 1, 12):
            d = np.linalg.norm(verts[i] - verts[j])
            if abs(d - edge_length) < 1e-10:
                edges.append((i, j))
    
    # Take one edge midpoint as representative
    if edges:
        rep_point = (verts[edges[0][0]] + verts[edges[0][1]]) / 2
        rep_norm = np.linalg.norm(rep_point)
        if rep_norm > 1e-10:
            rep_point = rep_point / rep_norm * np.sqrt(2)
            
            # Generate orbit
            orbit = []
            for R in icos_rotations:
                p = R @ rep_point
                p = p / np.linalg.norm(p) * np.sqrt(2)
                # Check if already in orbit
                is_dup = False
                for q in orbit:
                    if np.linalg.norm(p - q) < 0.05:
                        is_dup = True
                        break
                if not is_dup:
                    orbit.append(p)
            
            for p in orbit:
                if len(points) >= n:
                    break
                points.append(p)
    
    # If we still need more atoms, add face centers
    if len(points) < n:
        edge_set = set(edges)
        faces = []
        for i in range(12):
            for j in range(i + 1, 12):
                for k in range(j + 1, 12):
                    if (i, j) in edge_set and (i, k) in edge_set and (j, k) in edge_set:
                        faces.append((i, j, k))
        
        if faces:
            rep_point = (verts[faces[0][0]] + verts[faces[0][1]] + verts[faces[0][2]]) / 3
            rep_norm = np.linalg.norm(rep_point)
            if rep_norm > 1e-10:
                rep_point = rep_point / rep_norm * np.sqrt(2)
                
                orbit = []
                for R in icos_rotations:
                    p = R @ rep_point
                    p = p / np.linalg.norm(p) * np.sqrt(2)
                    is_dup = False
                    for q in orbit:
                        if np.linalg.norm(p - q) < 0.05:
                            is_dup = True
                            break
                    if not is_dup:
                        orbit.append(p)
                
                for p in orbit:
                    if len(points) >= n:
                        break
                    # Check if too close to existing points
                    is_close = False
                    for existing in points:
                        if np.linalg.norm(p - existing) < 0.8:
                            is_close = True
                            break
                    if not is_close:
                        points.append(p)
    
    # If we still need more atoms, add random points
    rng = np.random.default_rng(42 + n)
    R2 = np.sqrt(2)
    while len(points) < n:
        v = rng.normal(size=3)
        v /= np.linalg.norm(v)
        r = R2 * rng.uniform(0.9, 1.3)
        p = v * r
        # Check minimum distance
        is_close = False
        for existing in points:
            if np.linalg.norm(p - existing) < 0.7:
                is_close = True
                break
        if not is_close:
            points.append(p)
    
    return np.array(points[:n])


def _generate_icosahedral_growth(n):
    """Generate an icosahedral cluster using geometric insertion at interstitial sites."""
    phi = (1 + np.sqrt(5)) / 2
    
    # Start with 13-atom icosahedron
    verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [-phi, 0, 1], [phi, 0, -1], [-phi, 0, -1]
    ])
    norm = np.linalg.norm(verts[0])
    verts = verts / norm
    
    points = [np.zeros(3)]
    points.extend(verts.tolist())
    
    if n <= 13:
        return np.array(points[:n])
    
    # For each additional atom, find the best interstitial site
    # by maximizing the minimum distance to existing atoms
    rng = np.random.default_rng(777 + n)
    
    for _ in range(n - len(points)):
        # Generate candidate positions in a shell around the cluster
        best_pos = None
        best_min_dist = -np.inf
        
        # Try positions at various radii and directions
        for trial in range(200):
            v = rng.normal(size=3)
            v /= np.linalg.norm(v)
            r = rng.uniform(1.2, 2.0)
            p = v * r
            
            # Compute minimum distance to existing atoms
            dists = [np.linalg.norm(p - q) for q in points]
            min_dist = np.min(dists)
            
            if min_dist > best_min_dist:
                best_min_dist = min_dist
                best_pos = p
        
        if best_min_dist >= 0.7:
            points.append(best_pos)
        else:
            # If no good position found, add at a slightly larger radius
            v = rng.normal(size=3)
            v /= np.linalg.norm(v)
            p = v * 2.2
            points.append(p)
    
    return np.array(points[:n])


def _generate_fcc(n):
    """Generate a truncated FCC cluster."""
    points = []
    basis = [
        [0, 0, 0],
        [0, 0.5, 0.5],
        [0.5, 0, 0.5],
        [0.5, 0.5, 0]
    ]
    
    N = int(np.ceil(n ** (1/3))) + 3
    candidates = []
    for i in range(-N, N+1):
        for j in range(-N, N+1):
            for k in range(-N, N+1):
                for b in basis:
                    p = np.array([i, j, k]) + np.array(b)
                    candidates.append(p)
    
    candidates = np.array(candidates)
    dists = np.linalg.norm(candidates, axis=1)
    indices = np.argsort(dists)
    candidates = candidates[indices]
    
    points = candidates[:n]
    centroid = np.mean(points, axis=0)
    points -= centroid
    
    return points


def _generate_random_packing(n, seed):
    """Generate a random compact packing."""
    rng = np.random.default_rng(seed)
    points = []
    radius = 1.2 * n ** (1.0 / 3.0)
    min_dist = 0.85
    attempts = 0
    max_attempts = n * 100
    
    while len(points) < n and attempts < max_attempts:
        p = rng.uniform(-radius, radius, 3)
        if np.linalg.norm(p) <= radius:
            if all(np.linalg.norm(p - q) >= min_dist for q in points):
                points.append(p)
        attempts += 1
        
    while len(points) < n:
        p = rng.uniform(-radius, radius, 3)
        points.append(p)
        
    return np.array(points)


def _relax_and_evaluate(pos, potential, parameter, timeout_per_relax=30.0):
    """Relax a structure using gradient-based optimization and return (energy, positions)."""
    try:
        start = time.time()
        
        # First try the built-in relax
        energy, relaxed_pos = relax(pos, potential, parameter)
        elapsed = time.time() - start
        
        # If time allows, try gradient-based refinement
        if time.time() - start < timeout_per_relax - 5:
            try:
                # Use L-BFGS-B for further refinement
                def energy_func(x):
                    positions_reshaped = x.reshape(-1, 3)
                    return _compute_energy(positions_reshaped)
                
                def gradient_func(x):
                    positions_reshaped = x.reshape(-1, 3)
                    grad, _ = dzugutov_energy_gradient(positions_reshaped)
                    return grad.flatten()
                
                x0 = relaxed_pos.flatten()
                result = minimize(
                    energy_func, x0,
                    jac=gradient_func,
                    method='L-BFGS-B',
                    options={'maxiter': 200, 'ftol': 1e-10}
                )
                
                if result.fun < energy:
                    energy = result.fun
                    relaxed_pos = result.x.reshape(-1, 3)
            except Exception:
                pass
        
        return energy, relaxed_pos, time.time() - start
    except Exception as e:
        return np.inf, pos, 0.0


def _parallel_relax(candidates, potential, parameter, max_workers=4):
    """Relax multiple candidates in parallel."""
    results = []
    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        futures = {
            executor.submit(_relax_and_evaluate, pos, potential, parameter): i
            for i, pos in enumerate(candidates)
        }
        for future in as_completed(futures):
            energy, pos, elapsed = future.result()
            results.append((energy, pos, elapsed))
    
    # Sort by energy
    results.sort(key=lambda x: x[0])
    return results


def _basin_hopping(pos, energy, potential, parameter, max_steps=10, timeout=60.0):
    """Perform basin hopping refinement with gradient-based local minimization."""
    rng = np.random.default_rng(int(time.time() * 1000) % 10000)
    current_energy = energy
    current_pos = pos.copy()
    start_time = time.time()
    
    for step in range(max_steps):
        if time.time() - start_time > timeout:
            break
        
        sigma = 0.3 * np.exp(-step * 0.1)
        noise = rng.normal(0, sigma, size=current_pos.shape)
        perturbed_pos = current_pos + noise
        
        try:
            # Use gradient-based relaxation for the perturbed structure
            def energy_func(x):
                positions_reshaped = x.reshape(-1, 3)
                return _compute_energy(positions_reshaped)
            
            def gradient_func(x):
                positions_reshaped = x.reshape(-1, 3)
                grad, _ = dzugutov_energy_gradient(positions_reshaped)
                return grad.flatten()
            
            x0 = perturbed_pos.flatten()
            result = minimize(
                energy_func, x0,
                jac=gradient_func,
                method='L-BFGS-B',
                options={'maxiter': 100, 'ftol': 1e-9}
            )
            
            if result.fun < current_energy:
                current_energy = result.fun
                current_pos = result.x.reshape(-1, 3)
        except Exception:
            continue
    
    return current_energy, current_pos


def construct(instance):
    """
    Find low-energy structures of Dzugutov clusters using hierarchical icosahedral seeding
    and multi-start gradient-based local minimization.
    """
    size = instance["n"]
    potential = instance["potential"]
    parameter = instance.get("rho", instance.get("kind"))
    
    start_time = time.time()
    deadline = start_time + 280.0  # Safety margin before 330s kill
    
    # Generate diverse initial candidates with emphasis on icosahedral structures
    candidates = []
    
    # 1. Mackay icosahedron (primary seed)
    try:
        p_mackay = _generate_mackay_icosahedron(size)
        candidates.append(p_mackay)
    except Exception:
        pass
    
    # 2. Icosahedral growth with interstitial insertion
    try:
        p_ico_grow = _generate_icosahedral_growth(size)
        candidates.append(p_ico_grow)
    except Exception:
        pass
    
    # 3. FCC (for comparison)
    try:
        p_fcc = _generate_fcc(size)
        candidates.append(p_fcc)
    except Exception:
        pass
    
    # 4. Multiple random packings with different seeds
    for seed in [1, 7, 42, 99, 123, 200, 300]:
        try:
            p_rand = _generate_random_packing(size, seed)
            candidates.append(p_rand)
        except Exception:
            pass
    
    # 5. Scaled icosahedron variants
    for scale in [0.85, 0.95, 1.05, 1.15]:
        try:
            p_base = _generate_mackay_icosahedron(size)
            p_scaled = p_base * scale
            candidates.append(p_scaled)
        except Exception:
            pass
    
    # Remove duplicates (structures that are very similar)
    unique_candidates = []
    for c in candidates:
        is_dup = False
        for uc in unique_candidates:
            if len(c) == len(uc):
                # Compute average distance after alignment (simple: just compare)
                diff = np.linalg.norm(c - uc, axis=1)
                if np.mean(diff) < 0.4:
                    is_dup = True
                    break
        if not is_dup:
            unique_candidates.append(c)
    
    # Parallel relaxation with gradient-based refinement
    results = _parallel_relax(unique_candidates, potential, parameter, max_workers=4)
    
    best_energy = np.inf
    best_pos = None
    
    for energy, pos, elapsed in results:
        if energy < best_energy:
            best_energy = energy
            best_pos = pos
    
    # Basin hopping refinement on the best structure
    if best_pos is not None and time.time() < deadline - 40:
        remaining_time = deadline - time.time()
        max_bh_steps = max(8, int(remaining_time / 8))
        best_energy, best_pos = _basin_hopping(
            best_pos, best_energy, potential, parameter,
            max_steps=max_bh_steps, timeout=min(80, remaining_time)
        )
    
    # If we still have time, try basin hopping on the second and third best
    for idx in [1, 2]:
        if idx < len(results) and time.time() < deadline - 20:
            second_energy, second_pos, _ = results[idx]
            if second_energy < np.inf:
                remaining = deadline - time.time()
                e2, p2 = _basin_hopping(
                    second_pos, second_energy, potential, parameter,
                    max_steps=6, timeout=min(40, remaining)
                )
                if e2 < best_energy:
                    best_energy = e2
                    best_pos = p2
    
    # Final check: ensure minimum distance constraint
    if best_pos is not None:
        # Verify all pairs are at least 0.5 apart
        for i in range(len(best_pos)):
            for j in range(i + 1, len(best_pos)):
                d = np.linalg.norm(best_pos[i] - best_pos[j])
                if d < 0.5:
                    # Nudge apart
                    diff = best_pos[i] - best_pos[j]
                    if np.linalg.norm(diff) > 1e-10:
                        diff = diff / np.linalg.norm(diff) * 0.02
                    else:
                        diff = np.array([0.02, 0, 0])
                    best_pos[i] += diff
                    best_pos[j] -= diff
    
    if best_pos is None:
        # Fallback
        return np.array([np.array([i, 0, 0]) for i in range(size)])
    
    return best_pos
