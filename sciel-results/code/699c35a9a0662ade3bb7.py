"""
Rank-minimal tensor decomposition for 2x3 * 3x10 matrix multiplication.

Strategy: Partition middle dim 3 = 2 + 1.
  Part 1: (2x2) * (2x10) via 5 Strassen 2x2x2 blocks -> rank 35
  Part 2: (2x1) * (1x10) schoolbook -> rank 20
  Total: rank 55

Refinements:
  - Vectorized verification using random integer trials
  - Fallback to schoolbook rank 60 if verification fails
  - Deadline guard to stay within 120s limit
"""
import time
import numpy as np

DIMENSIONS = [2, 3, 10]
DEADLINE = 120.0


def _verify_decomposition(U, V, W, n, m, p, num_trials=10, seed=42):
    """Verify decomposition with random integer inputs using vectorized ops."""
    rng = np.random.RandomState(seed)
    rank = U.shape[1]
    for _ in range(num_trials):
        A = rng.randint(-10, 11, size=(n, m)).astype(float)
        B = rng.randint(-10, 11, size=(m, p)).astype(float)
        C_direct = A @ B

        # Vectorized decomposition evaluation
        A_flat = A.flatten()  # shape (n*m,)
        B_flat = B.flatten()  # shape (m*p,)
        u_sums = U.T @ A_flat  # (rank,)
        v_sums = V.T @ B_flat  # (rank,)
        scalars = u_sums * v_sums  # (rank,)
        C_flat = W @ scalars  # (p*n,)
        C_decomp = C_flat.reshape(p, n).T  # (n, p)

        err = np.max(np.abs(C_decomp - C_direct))
        if err > 1e-9:
            return False, err
    return True, 0.0


def construct():
    start_time = time.time()
    n, m, p = DIMENSIONS  # n=2, m=3, p=10

    # Partition middle dim: 3 = 2 + 1
    # Part 1: rows 0,1 of A (2x2) times rows 0,1 of B (2x10) -> 5 Strassen blocks of 2x2x2
    # Part 2: row 2 of A (2x1) times row 2 of B (1x10) -> schoolbook rank 20

    rank = 35 + 20  # 55

    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))

    idx = 0

    # Part 1: Strassen for 2x2 x 2x10 (5 blocks of 2x2x2)
    for block in range(5):
        k0 = 2 * block
        k1 = 2 * block + 1

        # M1 = (A[0,0] + A[1,1]) * (B[0,k0] + B[1,k1])
        # Contributes to C[0,k0] and C[1,k1]
        U[0 * 3 + 0, idx] = 1.0
        U[1 * 3 + 1, idx] = 1.0
        V[0 * 10 + k0, idx] = 1.0
        V[1 * 10 + k1, idx] = 1.0
        W[k0 * 2 + 0, idx] = 1.0
        W[k1 * 2 + 1, idx] = 1.0
        idx += 1

        # M2 = (A[1,0] + A[1,1]) * B[0,k0]
        # Contributes to C[1,k0] and C[1,k1]
        U[1 * 3 + 0, idx] = 1.0
        U[1 * 3 + 1, idx] = 1.0
        V[0 * 10 + k0, idx] = 1.0
        W[k0 * 2 + 1, idx] = 1.0
        W[k1 * 2 + 1, idx] = -1.0
        idx += 1

        # M3 = A[0,0] * (B[0,k1] - B[1,k1])
        # Contributes to C[0,k1] and C[1,k1]
        U[0 * 3 + 0, idx] = 1.0
        V[0 * 10 + k1, idx] = 1.0
        V[1 * 10 + k1, idx] = -1.0
        W[k1 * 2 + 0, idx] = 1.0
        W[k1 * 2 + 1, idx] = 1.0
        idx += 1

        # M4 = A[1,1] * (B[1,k0] - B[0,k0])
        # Contributes to C[0,k0] and C[1,k0]
        U[1 * 3 + 1, idx] = 1.0
        V[1 * 10 + k0, idx] = 1.0
        V[0 * 10 + k0, idx] = -1.0
        W[k0 * 2 + 0, idx] = 1.0
        W[k0 * 2 + 1, idx] = 1.0
        idx += 1

        # M5 = (A[0,0] + A[0,1]) * B[1,k1]
        # Contributes to C[0,k0] and C[0,k1]
        U[0 * 3 + 0, idx] = 1.0
        U[0 * 3 + 1, idx] = 1.0
        V[1 * 10 + k1, idx] = 1.0
        W[k0 * 2 + 0, idx] = -1.0
        W[k1 * 2 + 0, idx] = 1.0
        idx += 1

        # M6 = (A[1,0] - A[0,0]) * (B[0,k0] + B[0,k1])
        # Contributes to C[1,k1]
        U[1 * 3 + 0, idx] = 1.0
        U[0 * 3 + 0, idx] = -1.0
        V[0 * 10 + k0, idx] = 1.0
        V[0 * 10 + k1, idx] = 1.0
        W[k1 * 2 + 1, idx] = 1.0
        idx += 1

        # M7 = (A[0,1] - A[1,1]) * (B[1,k0] + B[1,k1])
        # Contributes to C[0,k0]
        U[0 * 3 + 1, idx] = 1.0
        U[1 * 3 + 1, idx] = -1.0
        V[1 * 10 + k0, idx] = 1.0
        V[1 * 10 + k1, idx] = 1.0
        W[k0 * 2 + 0, idx] = 1.0
        idx += 1

    # Part 2: Schoolbook for 2x1 x 1x10
    for i in range(2):
        for k in range(10):
            U[i * 3 + 2, idx] = 1.0
            V[2 * 10 + k, idx] = 1.0
            W[k * 2 + i, idx] = 1.0
            idx += 1

    assert idx == rank, f"Expected rank {rank}, got {idx}"

    # Check deadline before verification
    elapsed = time.time() - start_time
    if elapsed > DEADLINE - 5.0:
        # Return without verification if we're close to deadline
        return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}

    # Verify decomposition
    valid, err = _verify_decomposition(U, V, W, n, m, p, num_trials=10, seed=42)
    if not valid:
        # Fallback to schoolbook
        rank_fb = n * m * p
        U_fb = np.zeros((n * m, rank_fb))
        V_fb = np.zeros((m * p, rank_fb))
        W_fb = np.zeros((p * n, rank_fb))
        for c in range(rank_fb):
            ii = c // (m * p)
            rem = c % (m * p)
            jj = rem // p
            kk = rem % p
            U_fb[ii * m + jj, c] = 1.0
            V_fb[jj * p + kk, c] = 1.0
            W_fb[kk * n + ii, c] = 1.0
        return {"U": U_fb.tolist(), "V": V_fb.tolist(), "W": W_fb.tolist()}

    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}


if __name__ == "__main__":
    result = construct()
    print(f"Rank: {len(result['U'][0])}")

    n, m, p = DIMENSIONS
    U = np.array(result['U'])
    V = np.array(result['V'])
    W = np.array(result['W'])
    rank = U.shape[1]

    np.random.seed(42)
    A = np.random.randint(-5, 6, size=(n, m)).astype(float)
    B = np.random.randint(-5, 6, size=(m, p)).astype(float)

    C_decomp = np.zeros((n, p))
    for r in range(rank):
        A_w = np.zeros((n, m))
        for i in range(n):
            for j in range(m):
                A_w[i, j] = U[i * m + j, r]
        B_w = np.zeros((m, p))
        for j in range(m):
            for k in range(p):
                B_w[j, k] = V[j * p + k, r]
        prod_r = np.sum(A_w * A) * np.sum(B_w * B)
        for i in range(n):
            for k in range(p):
                C_decomp[i, k] += prod_r * W[k * n + i, r]

    C_direct = A @ B
    error = np.max(np.abs(C_decomp - C_direct))
    print(f"Max error: {error}")
    if error > 1e-10:
        print("WARNING: Decomposition is incorrect!")
