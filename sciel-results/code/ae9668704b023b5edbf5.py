   def get_strassen_2x2():
       # U, V, W for 2x2x2
       # Rank 7
       U = [[0]*7 for _ in range(4)]
       V = [[0]*7 for _ in range(4)]
       W = [[0]*7 for _ in range(4)]
       
       # Standard Strassen
       # M1 = (A11+A22)(B11+B22)
       # U: A11, A22
       U[0][0] = 1 # A11
       U[3][0] = 1 # A22
       # V: B11, B22
       V[0][0] = 1 # B11
       V[3][0] = 1 # B22
       # W: C11, C22
       W[0][0] = 1 # C11
       W[3][0] = 1 # C22
       
       # M2 = (A21+A22)B11
       U[2][1] = 1 # A21
       U[3][1] = 1 # A22
       V[0][1] = 1 # B11
       W[2][1] = 1 # C21
       
       # M3 = A11(B12-B22)
       U[0][2] = 1 # A11
       V[1][2] = 1 # B12
       V[3][2] = -1 # B22
       W[1][2] = 1 # C12
       
       # M4 = A22(B21-B11)
       U[3][3] = 1 # A22
       V[2][3] = 1 # B21
       V[0][3] = -1 # B11
       W[2][3] = 1 # C21
       
       # M5 = (A11+A12)B22
       U[0][4] = 1 # A11
       U[1][4] = 1 # A12
       V[3][4] = 1 # B22
       W[1][4] = 1 # C12
       W[3][4] = 1 # C22
       
       # M6 = (A21-A11)(B11+B12)
       U[2][5] = 1 # A21
       U[0][5] = -1 # A11
       V[0][5] = 1 # B11
       V[1][5] = 1 # B12
       W[0][5] = 1 # C11
       W[2][5] = 1 # C21
       
       # M7 = (A12-A22)(B21+B22)
       U[1][6] = 1 # A12
       U[3][6] = -1 # A22
       V[2][6] = 1 # B21
       V[3][6] = 1 # B22
       W[0][6] = 1 # C11
       W[3][6] = 1 # C22
       
       return U, V, W
   