"""
Signed autocorrelation maximum absolute-value variant.

Strategy:
- Represent the sequence as a sum of K shifted, scaled, signed block pulses (Dirichlet-like kernels).
- Optimize geometric parameters (positions, widths, signs, amplitudes) via differential evolution.
- After DE, perform a local refinement (L-BFGS-B) on the 400-dimensional signal using the
  smooth epigraph objective: minimize t subject to |autoconv[k]| - t <= 0 for all k.
- Use a soft-max surrogate for the max to enable gradient-based local optimization.
- Deadline guard: return best result found before 150s wall-clock.

The objective is: max_k |autoconv[k]| / (sum(x))^2
where autoconv[k] = sum_i x[i] * x[i+k] (full autoconvolution, centered).

We minimize this quantity.
"""

import numpy as np
import time
from scipy.optimize import differential_evolution, minimize

N = 400
DEADLINE = 135.0  # seconds, safety margin before 150s limit
_start_time = time.time()


def _elapsed():
    return time.time() - _start_time


def _autoconv(x):
    """Compute full autoconvolution of x, centered."""
    n = len(x)
    # Use FFT for speed
    f = np.fft.rfft(x, n=2 * n)
    ac_full = np.fft.irfft(f * np.conj(f), n=2 * n)
    # Center: lags from -(n-1) to (n-1)
    ac = np.concatenate([ac_full[n:], ac_full[:n]])
    return ac


def _score(x):
    """Compute the C3' score: max|autoconv| / (sum(x))^2."""
    s = np.sum(x)
    if abs(s) < 1e-12:
        return 1e10
    ac = _autoconv(x)
    return np.max(np.abs(ac)) / (s * s)


def _param_to_signal(params, K):
    """Convert geometric parameters to a signal of length N.
    
    params layout for each block k:
      [center (0..N-1), width (1..N), sign (-1..1), amplitude (-2..2)]
    Total params: 4*K
    """
    x = np.zeros(N)
    for k in range(K):
        base = 4 * k
        center = params[base]
        width = max(1.0, params[base + 1])
        sign = params[base + 2]
        amp = params[base + 3]
        
        # Block pulse: ones in [center - width/2, center + width/2]
        lo = int(np.floor(center - width / 2.0))
        hi = int(np.ceil(center + width / 2.0))
        lo = max(0, lo)
        hi = min(N, hi)
        if hi > lo:
            x[lo:hi] += sign * amp
    return x


def _objective(params, K):
    """Objective for DE: the C3' score of the signal generated by params."""
    x = _param_to_signal(params, K)
    return _score(x)


def _soft_max_abs_ac(x, tau=1.0):
    """Soft-max of |autoconv| using log-sum-exp for smoothness."""
    ac = _autoconv(x)
    a = np.abs(ac)
    # Soft max: tau * log(sum(exp(a/tau)))
    a_max = np.max(a)
    if a_max < 1e-12:
        return 0.0
    sm = tau * (a_max / tau + np.log(np.sum(np.exp((a - a_max) / tau))))
    s = np.sum(x)
    if abs(s) < 1e-12:
        return 1e10
    return sm / (s * s)


def _local_refine(x0, max_iter=200):
    """Local refinement using L-BFGS-B on the 400-dim signal with soft-max objective."""
    def obj(x):
        if _elapsed() > DEADLINE:
            return _score(x0)
        return _soft_max_abs_ac(x, tau=0.5)
    
    try:
        res = minimize(obj, x0, method='L-BFGS-B', maxiter=max_iter,
                       options={'maxls': 20, 'ftol': 1e-10, 'gtol': 1e-8})
        if res.success or res.fun < _score(x0):
            return res.x
        return x0
    except Exception:
        return x0


def construct():
    global _start_time
    _start_time = time.time()
    
    # Try multiple K values for block pulses
    best_x = np.ones(N)
    best_score = _score(best_x)
    
    K_candidates = [3, 4, 5, 6, 8]
    
    for K in K_candidates:
        if _elapsed() > DEADLINE - 30:
            break
        
        np.random.seed(42 + K)
        
        # Bounds for each param
        bounds = []
        for k in range(K):
            bounds.append((1.0, N - 1.0))       # center
            bounds.append((1.0, float(N)))       # width
            bounds.append((-1.0, 1.0))           # sign
            bounds.append((-2.0, 2.0))           # amplitude
        
        # Differential evolution
        try:
            de_res = differential_evolution(
                _objective, bounds, args=(K,),
                maxiter=50, popsize=15, tol=1e-4,
                seed=42 + K, init='sobol',
                polish=False,  # We'll do our own polish
                updating='deferred'
            )
        except Exception:
            continue
        
        x_de = _param_to_signal(de_res.x, K)
        sc_de = _score(x_de)
        
        if sc_de < best_score:
            best_score = sc_de
            best_x = x_de
        
        # Local refinement
        if _elapsed() > DEADLINE - 20:
            break
        
        x_ref = _local_refine(x_de, max_iter=150)
        sc_ref = _score(x_ref)
        
        if sc_ref < best_score:
            best_score = sc_ref
            best_x = x_ref
    
    # Also try a few random initializations with local refinement
    if _elapsed() < DEADLINE - 20:
        for trial in range(5):
            if _elapsed() > DEADLINE - 15:
                break
            np.random.seed(1000 + trial)
            x_rand = np.random.randn(N)
            # Normalize
            x_rand = x_rand / (np.max(np.abs(x_rand)) + 1e-12)
            x_ref = _local_refine(x_rand, max_iter=100)
            sc = _score(x_ref)
            if sc < best_score:
                best_score = sc
                best_x = x_ref
    
    # Final high-precision polish
    if _elapsed() < DEADLINE - 10:
        x_final = _local_refine(best_x, max_iter=300)
        sc_final = _score(x_final)
        if sc_final < best_score:
            best_x = x_final
            best_score = sc_final
    
    return best_x
