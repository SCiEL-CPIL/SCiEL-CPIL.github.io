import random
import math
import time

def construct(n_rows, k):
    # Helper to generate a row given the set of used differences
    # mode: 'greedy' (always smallest), 'random' (random from valid set)
    def generate_row(used, mode='greedy'):
        row = [0]
        # We need to pick k more numbers
        # To speed up, we can estimate a bound. Let's just iterate x upwards.
        # But if we want to be random, we need a range.
        # Let's stick to a simple loop but allow random choice among valid candidates in a small window.
        
        # Optimization: Pre-compute valid candidates? No, just check as we go.
        # We'll iterate x from 1 upwards.
        # To avoid infinite loops if no solution, we need a bound.
        # The max value in a valid DTS(n, k) is bounded. 
        # For n=4, k=7, max is ~134. Let's set a hard limit of 200 for generation attempts.
        
        for _ in range(k):
            found = False
            # Determine search range. 
            # If greedy, just find first valid.
            # If random, find a few valids and pick one.
            
            # We need to know which x are valid.
            # An x is valid if {x - a for a in row} is disjoint from 'used'.
            
            # Let's collect valid candidates in a window.
            # Start x from last_val + 1.
            start_x = row[-1] + 1
            # We don't know the end, but we can look ahead.
            # For 'greedy', we stop at first valid.
            # For 'random', we look at the next 20 valid candidates and pick one randomly?
            # Or pick from a range [start_x, start_x + 50]?
            
            # Let's try a simpler random strategy:
            # Pick a random x in [start_x, start_x + 100] and check if valid.
            # If not, try next.
            # This might be slow.
            
            # Better: Iterate x from start_x. Keep a list of valid candidates up to a limit.
            valid_candidates = []
            limit = 50  # Look ahead 50 values
            
            for x in range(start_x, start_x + limit):
                new_diffs = {x - a for a in row}
                if not new_diffs & used:
                    valid_candidates.append(x)
                    if mode == 'greedy':
                        break
                    if len(valid_candidates) >= 10:
                        break
            
            if not valid_candidates:
                return None # Failed to generate row
            
            if mode == 'greedy':
                x = valid_candidates[0]
            else:
                # Bias towards smaller values
                # Weighted random choice
                # Probability proportional to 1/(x - start_x + 1)
                weights = [1.0 / (c - start_x + 1) for c in valid_candidates]
                total_w = sum(weights)
                r = random.random() * total_w
                cumulative = 0
                x = valid_candidates[-1]
                for c, w in zip(valid_candidates, weights):
                    cumulative += w
                    if r <= cumulative:
                        x = c
                        break
            
            row.append(x)
            # Update used locally? No, we return the row and the caller updates used.
            # But for the next step in the loop, we need to consider the diffs of the current row.
            # The function `generate_row` should probably take `used` as the *external* used set,
            # and internally manage the row's own diffs.
            
            # Wait, the check `if not new_diffs & used` is correct for external conflicts.
            # But we also need to ensure internal uniqueness.
            # Since we are building the row sequentially, and we pick strictly increasing x,
            # are the internal diffs unique?
            # No! Example: 0, 1, 2. Diffs: 1, 2, 1. Duplicate 1.
            # The set `new_diffs` contains diffs with *all* previous elements in `row`.
            # So `new_diffs` is the set of diffs between x and all a in row.
            # If any of these diffs are already in `used` (external) OR in the set of diffs 
            # generated by previous steps of this row, it's a conflict.
            
            # My current `generate_row` does NOT track internal diffs of the row being built.
            # It only checks against `used` (which is external).
            # I need to maintain a `local_used` set for the current row's internal diffs.
            
            # Let's rewrite generate_row to handle internal diffs.
            
        return row # Placeholder

    # Corrected generate_row
    def gen_row(used_external, mode='greedy'):
        row = [0]
        local_used = set() # Diffs within this row
        for _ in range(k):
            start_x = row[-1] + 1
            valid_candidates = []
            # Look ahead window
            # If mode is greedy, we just want the first one.
            # If random, we want a few.
            # Let's scan up to start_x + 100
            for x in range(start_x, start_x + 100):
                new_diffs = {x - a for a in row}
                # Check external conflicts
                if new_diffs & used_external:
                    continue
                # Check internal conflicts
                # new_diffs are diffs with existing elements in row.
                # If any diff in new_diffs is in local_used, it's a conflict.
                if new_diffs & local_used:
                    continue
                
                valid_candidates.append(x)
                
                if mode == 'greedy':
                    break
                if len(valid_candidates) >= 10:
                    break
            
            if not valid_candidates:
                return None
            
            if mode == 'greedy':
                x = valid_candidates[0]
            else:
                # Weighted random
                weights = [1.0 / (c - start_x + 1) for c in valid_candidates]
                total_w = sum(weights)
                r = random.random() * total_w
                cumulative = 0
                x = valid_candidates[-1]
                for c, w in zip(valid_candidates, weights):
                    cumulative += w
                    if r <= cumulative:
                        x = c
                        break
            
            row.append(x)
            # Update local_used with the diffs just added
            local_used.update({x - a for a in row[:-1]})
            
        return row

    def get_max_val(rws):
        return max(max(r) for r in rws)

    start_time = time.time()
    timeout = 110.0
    
    best_rows = None
    best_max = float('inf')
    
    # Initial greedy solution
    # We need an initial valid set.
    # Let's use a simple greedy that builds rows one by one, minimizing max.
    def initial_greedy():
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            local_used = set()
            for _ in range(k):
                found = False
                x = row[-1] + 1
                while True:
                    new_diffs = {x - a for a in row}
                    if not (new_diffs & used) and not (new_diffs & local_used):
                        row.append(x)
                        local_used.update(new_diffs)
                        found = True
                        break
                    x += 1
                    if x > 500: # Safety break
                        break
                if not found:
                    return None, None
            rows.append(row)
            used.update(local_used)
        return rows, used

    init_rows, init_used = initial_greedy()
    if init_rows:
        best_max = get_max_val(init_rows)
        best_rows = [r[:] for r in init_rows]
    else:
        # Fallback
        return [[0] + list(range(1, k+1)) for _ in range(n_rows)]

    current_rows = [r[:] for r in init_rows]
    current_used = set(init_used)
    current_max = best_max
    
    T = 10.0
    cooling = 0.999
    
    while time.time() - start_time < timeout:
        if T < 0.1:
            break
            
        # Pick a row to reconstruct
        # Bias towards rows with large max values
        # Or just random
        r = random.randint(0, n_rows - 1)
        
        old_row = current_rows[r]
        old_max_global = current_max
        
        # Remove old row's diffs from used
        old_diffs = set()
        for i in range(len(old_row)):
            for j in range(i+1, len(old_row)):
                old_diffs.add(old_row[j] - old_row[i])
        current_used -= old_diffs
        
        # Generate new row
        # Use randomized greedy to allow exploration
        # Mode 'random' allows for non-greedy choices
        new_row = gen_row(current_used, mode='random')
        
        if new_row is None:
            # Revert
            current_used |= old_diffs
            # T *= cooling
            # continue
            # If we can't find a row, maybe try greedy?
            new_row = gen_row(current_used, mode='greedy')
            if new_row is None:
                current_used |= old_diffs
                T *= cooling
                continue
        
        # Calculate new max
        new_row_max = max(new_row)
        
        # Estimate new global max
        # We need to know if new_row_max is the new global max
        # Or if the old global max was in this row and is now gone.
        
        # Simple check: 
        # If old_row had the global max, and new_row_max < old_row_max, global max might drop.
        # If old_row didn't have global max, global max stays same unless new_row_max > current_max.
        
        # Let's just compute the new global max properly.
        # This is O(n_rows * k). n_rows=4, k=7. Very fast.
        temp_rows = current_rows[:]
        temp_rows[r] = new_row
        new_global_max = get_max_val(temp_rows)
        
        # Calculate new diffs for acceptance check (if accepted)
        new_diffs = set()
        for i in range(len(new_row)):
            for j in range(i+1, len(new_row)):
                new_diffs.add(new_row[j] - new_row[i])
        
        delta = new_global_max - old_max_global
        
        if delta < 0:
            # Accept
            current_rows[r] = new_row
            current_used |= new_diffs
            current_max = new_global_max
            if current_max < best_max:
                best_max = current_max
                best_rows = [row[:] for row in current_rows]
        else:
            # Accept with prob exp(-delta / T)
            if random.random() < math.exp(-delta / T):
                current_rows[r] = new_row
                current_used |= new_diffs
                current_max = new_global_max
            else:
                # Revert
                current_used |= old_diffs
        
        T *= cooling

    if best_rows is None:
        return init_rows
        
    return best_rows
