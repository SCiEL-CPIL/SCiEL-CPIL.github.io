import random
import time

N = 256

def construct():
    start_time = time.time()
    # Safety margin: Evaluator kills at 60s, but task says 30s. 
    # We aim to finish well before 30s to be safe.
    deadline = start_time + 25.0
    
    best_set = None
    best_size = float('inf')
    
    def greedy_blocking_restart(seed):
        random.seed(seed)
        S = []
        sums = set()
        active = list(range(1, N + 1))
        
        while True:
            # Find compatible candidates
            compatible = []
            for x in active:
                if 2 * x in sums:
                    continue
                ok = True
                for a in S:
                    if x + a in sums:
                        ok = False
                        break
                if ok:
                    compatible.append(x)
            
            if not compatible:
                break
            
            # Score each compatible candidate
            best_x = -1
            best_score = -1
            tied_candidates = []
            
            for x in compatible:
                # Calculate score: how many other compatible candidates y does x block?
                # New sums generated by x: 2x and x+a for a in S
                new_sums = {2 * x}
                for a in S:
                    new_sums.add(x + a)
                
                score = 0
                for y in compatible:
                    if y == x:
                        continue
                    
                    # Check if y is blocked by x
                    # y is blocked if 2y in new_sums OR (y+a in new_sums for a in S) OR (y+x in sums)
                    
                    # 1. 2y in new_sums
                    if 2 * y in new_sums:
                        score += 1
                        continue
                    
                    # 2. y+a in new_sums for a in S
                    blocked = False
                    for a in S:
                        if (y + a) in new_sums:
                            blocked = True
                            break
                            
                    # 3. y+x in sums (old sums)
                    # If y+x is in sums, then adding x creates a collision?
                    # S_new sums = sums U new_sums.
                    # Pair (y, x) is in S_new. Sum is y+x.
                    # If y+x is already in sums, collision.
                    if not blocked and (y + x) in sums:
                        blocked = True
                        
                    if blocked:
                        score += 1

                if score > best_score:
                    best_score = score
                    best_x = x
                    tied_candidates = [x]
                elif score == best_score:
                    tied_candidates.append(x)
            
            x_star = random.choice(tied_candidates)
            S.append(x_star)
            sums.add(2 * x_star)
            for a in S[:-1]:
                sums.add(x_star + a)
            
            # Update active list? 
            # We can just leave it, the filter loop is O(N*|S|) which is small.
            # Or we can remove x_star from active.
            active.remove(x_star)
            
            # Time check
            if time.time() > deadline:
                break
        
        return S

    # Run multiple restarts
    num_restarts = 1000
    for i in range(num_restarts):
        if time.time() > deadline:
            break
        S = greedy_blocking_restart(i)
        if len(S) < best_size:
            best_size = len(S)
            best_set = S
            
    if best_set is None:
        # Fallback: simple ascending
        S = []
        sums = set()
        for x in range(1, N + 1):
            if 2 * x in sums: continue
            ok = True
            for a in S:
                if x + a in sums:
                    ok = False
                    break
            if ok:
                S.append(x)
                sums.add(2 * x)
                for a in S[:-1]:
                    sums.add(x + a)
        best_set = S

    return best_set
