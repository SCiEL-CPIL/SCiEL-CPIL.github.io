def _validate(U, V, W, n, m, p):
    """Exact check using numpy for speed."""
    r = len(U[0])
    U_np = np.array(U)
    V_np = np.array(V)
    W_np = np.array(W)
    
    # Reshape to (n, m, r), (m, p, r), (p, n, r)
    U_t = U_np.reshape(n, m, r)
    V_t = V_np.reshape(m, p, r)
    W_t = W_np.reshape(p, n, r)
    
    # Compute tensor: sum_c U[i,j,c] * V[j,k,c] * W[k,i,c]
    # np.einsum('ijc,jkc,kic->ijk', U_t, V_t, W_t)
    try:
        result = np.einsum('ijc,jkc,kic->ijk', U_t, V_t, W_t)
        # Check if all entries are 1
        if np.all(result == 1):
            return True
    except Exception:
        pass
    return False


def _schoolbook(n, m, p):
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
    return {"U": U, "V": V, "W": W}


