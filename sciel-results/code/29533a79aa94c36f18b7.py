DIMENSIONS = [3, 3, 5]

def construct():
    n, m, p = DIMENSIONS
    # Rank 7 for 3x3x3, Rank 18 for 3x3x2 (schoolbook)
    # Total Rank 25
    rank = 25
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Block 1: 3x3x3 Strassen
    # Indices i,j for A (0-2), j,k for B (0-2), i,k for C (0-2)
    # U index: i*m + j
    # V index: j*p + k
    # W index: k*n + i
    
    # Strassen Terms
    # 1
    U[0*3+0][0] = 1; U[2*3+2][0] = 1
    V[0*5+0][0] = 1; V[2*5+2][0] = 1
    W[0*3+0][0] = 1; W[2*3+2][0] = 1; W[0*3+2][0] = 1; W[2*3+0][0] = 1
    
    # 2
    U[0*3+1][1] = 1; U[2*3+1][1] = 1
    V[0*5+0][1] = 1; V[2*5+0][1] = 1
    W[0*3+0][1] = 1; W[0*3+2][1] = 1; W[2*3+0][1] = 1; W[2*3+2][1] = 1
    
    # 3
    U[1*3+0][2] = 1; U[1*3+2][2] = 1
    V[2*5+2][2] = 1; V[0*5+2][2] = 1
    W[2*3+0][2] = 1; W[2*3+2][2] = 1; W[0*3+0][2] = 1; W[0*3+2][2] = 1
    
    # 4
    U[1*3+1][3] = 1; U[1*3+2][3] = 1
    V[0*5+2][3] = 1; V[2*5+2][3] = 1
    W[0*3+1][3] = 1; W[0*3+2][3] = 1; W[2*3+1][3] = 1; W[2*3+2][3] = 1
    
    # 5
    U[0*3+0][4] = 1; U[1*3+0][4] = 1
    V[1*5+1][4] = 1; V[1*5+2][4] = 1
    W[1*3+0][4] = 1; W[1*3+2][4] = 1; W[0*3+1][4] = 1; W[0*3+2][4] = 1
    
    # 6
    U[0*3+1][5] = 1; U[1*3+1][5] = 1
    V[1*5+0][5] = 1; V[1*5+1][5] = 1
    W[0*3+1][5] = 1; W[1*3+1][5] = 1; W[0*3+0][5] = 1; W[1*3+0][5] = 1
    
    # 7
    U[2*3+0][6] = 1; U[2*3+1][6] = 1
    V[0*5+1][6] = 1; V[1*5+1][6] = 1
    W[1*3+2][6] = 1; W[1*3+1][6] = 1; W[0*3+2][6] = 1; W[0*3+1][6] = 1
    
    # Block 2: 3x3x2 Schoolbook
    # k in 3,4
    col = 7
    for i in range(3):
        for j in range(3):
            for k in range(3, 5):
                U[i*m+j][col] = 1
                V[j*p+k][col] = 1
                W[k*n+i][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
