def _validate(U, V, W, n, m, p):
    """Correct validation: check tensor decomposition constraint.
    For all i, j, jp, k: sum_c U[i*m+j,c] * V[jp*p+k,c] * W[k*n+i,c] == delta_{j,jp}
    """
    r = len(U[0])
    for i in range(n):
        for k in range(p):
            for j in range(m):
                for jp in range(m):
                    val = 0
                    for c in range(r):
                        val += U[i * m + j][c] * V[jp * p + k][c] * W[k * n + i][c]
                    expected = 1 if j == jp else 0
                    if val != expected:
                        return False
    return True


def _schoolbook(n, m, p):
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
    return {"U": U, "V": V, "W": W}


