"""
Strategy: Gradient-Based Optimization on Spectral Parametrization.

Rationale:
1. The current program uses Simulated Annealing (SA), which is a stochastic local search method. 
   While effective, it can be inefficient in high dimensions and does not exploit the 
   differentiability of the objective function (except for the max term).
2. The objective function involves `norm_inf = max(abs(g))`, which is non-differentiable. 
   We use a log-sum-exp approximation to make the objective smooth and differentiable.
3. Instead of optimizing the 50 heights directly (with non-negativity constraints handled 
   by clipping, which creates non-smooth boundaries), we parametrize the heights as 
   squared magnitudes of a signal generated by a small number of complex sinusoids.
   h_i = | sum_{k=1}^K A_k * exp(1j * (phi_k + omega_k * i)) |^2
   This guarantees h_i >= 0 by construction.
4. The optimization problem is now over the parameters (A_k, phi_k, omega_k), which are 
   unconstrained (except A_k >= 0, which can be handled by exp() or just allowing negative 
   amplitudes since they are squared). This creates a smooth landscape for gradient-based 
   optimizers like L-BFGS-B.
5. We use multiple random initializations in the parameter space to explore different 
   spectral structures and avoid local minima.
6. FFT-based convolution is used to compute g = h*h efficiently.
"""

import numpy as np
import time
import sys
from scipy.optimize import minimize

N = 50

def compute_value_smooth(h, beta=50.0):
    """
    Compute a smoothed version of the objective function.
    Uses log-sum-exp for norm_inf to ensure differentiability.
    Uses FFT for fast convolution.
    """
    h = np.asarray(h, dtype=np.float64)
    if not np.all(np.isfinite(h)):
        return -np.inf
    h = np.clip(h, 0, None)
    
    # FFT-based convolution
    n_fft = 1 << (2 * N - 1).bit_length()
    H = np.fft.rfft(h, n=n_fft)
    G = np.fft.irfft(H * H, n=n_fft)[:2*N-1]
    
    # Clean up numerical noise
    G[G < 0] = 0.0
    
    m = len(G)
    
    # Construct y vector as per task:
    # y = [0, g[0], ..., g[m-1], 0]
    # y has length m+2
    y = np.zeros(m + 2)
    y[1:m+1] = G
    
    # Spacing w
    w = 1.0 / (m + 1)
    
    # l2 term: sum over i in 0..m of (w/3) * (y[i]^2 + y[i]*y[i+1] + y[i+1]^2)
    terms = y[:m+1]**2 + y[:m+1]*y[1:m+2] + y[1:m+2]**2
    l2 = (w / 3.0) * np.sum(terms)
    
    # norm_1 = sum(abs(g)) / (m + 1)
    norm_1 = np.sum(G) / (m + 1)
    
    # norm_inf = max(abs(g)) approximated by log-sum-exp
    # max(x) ~ (1/beta) * log(sum(exp(beta * x)))
    # To avoid overflow, subtract max
    max_g = np.max(G)
    if max_g == 0:
        return -np.inf
    
    # Use a stable log-sum-exp
    shifted_G = G - max_g
    # beta * shifted_G is <= 0, so exp is safe
    log_sum_exp = np.log(np.sum(np.exp(beta * shifted_G))) + beta * max_g
    norm_inf_smooth = log_sum_exp / beta
    
    if norm_1 * norm_inf_smooth == 0:
        return -np.inf
        
    return l2 / (norm_1 * norm_inf_smooth)

def compute_value_exact(h):
    """
    Compute the exact objective function as defined in the task.
    """
    h = np.asarray(h, dtype=np.float64)
    if not np.all(np.isfinite(h)):
        return -np.inf
    h = np.clip(h, 0, None)
    
    g = np.convolve(h, h)
    m = len(g)
    
    y = np.zeros(m + 2)
    y[1:m+1] = g
    
    w = 1.0 / (m + 1)
    terms = y[:m+1]**2 + y[:m+1]*y[1:m+2] + y[1:m+2]**2
    l2 = (w / 3.0) * np.sum(terms)
    
    norm_1 = np.sum(np.abs(g)) / (m + 1)
    norm_inf = np.max(np.abs(g))
    
    if norm_1 * norm_inf == 0:
        return -np.inf
        
    return l2 / (norm_1 * norm_inf)

def spectral_to_heights(params, K):
    """
    Convert spectral parameters to heights.
    params: [A_1, phi_1, omega_1, A_2, phi_2, omega_2, ...]
    A_k: amplitude (can be negative, will be squared)
    phi_k: phase
    omega_k: frequency
    
    h_i = | sum_{k=1}^K A_k * exp(1j * (phi_k + omega_k * i)) |^2
    """
    i = np.arange(N)
    signal = np.zeros(N, dtype=np.complex128)
    
    for k in range(K):
        A = params[3*k]
        phi = params[3*k+1]
        omega = params[3*k+2]
        signal += A * np.exp(1j * (phi + omega * i))
        
    heights = np.abs(signal)**2
    # Normalize to have a reasonable scale
    # The objective is scale-invariant? 
    # l2 scales with h^2, norm_1 with h, norm_inf with h.
    # value = (h^2) / (h * h) = constant. 
    # So the scale of h does not affect the value. 
    # We can fix the scale by normalizing the sum of heights to 1.
    total = np.sum(heights)
    if total > 0:
        heights = heights / total
    return heights

def neg_smooth_objective(params, K):
    """
    Objective function for the optimizer.
    """
    h = spectral_to_heights(params, K)
    val = compute_value_smooth(h, beta=50.0)
    if np.isnan(val) or val == -np.inf:
        return 1e10
    return -val

def construct():
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin
    
    # Number of sinusoids to use in the spectral representation
    # More sinusoids allow more complex shapes but increase dimensionality
    K = 5
    
    # Total number of parameters: 3 * K
    n_params = 3 * K
    
    best_h = None
    best_val = -np.inf
    
    # Run multiple random restarts
    n_restarts = 20
    
    for restart in range(n_restarts):
        if time.time() > deadline:
            break
            
        # Initialize parameters randomly
        # Amplitudes: log-normal distribution to cover a wide range
        A = np.exp(np.random.randn(K) * 0.5)
        # Phases: uniform in [0, 2*pi]
        phi = np.random.uniform(0, 2*np.pi, K)
        # Frequencies: uniform in [0, pi] (Nyquist limit for discrete signal)
        # We want frequencies that are "incommensurate" to create aperiodic-like structures
        omega = np.random.uniform(0.1, np.pi, K)
        
        params = np.concatenate([A, phi, omega])
        
        # Optimize using L-BFGS-B
        try:
            res = minimize(neg_smooth_objective, params, args=(K,), method='L-BFGS-B',
                           options={'maxiter': 100, 'ftol': 1e-10, 'gtol': 1e-8})
            
            if res.success:
                h_opt = spectral_to_heights(res.x, K)
                val_opt = compute_value_exact(h_opt)
                
                if val_opt > best_val:
                    best_val = val_opt
                    best_h = h_opt.copy()
                    
        except Exception as e:
            pass # Continue to next restart if optimization fails
    
    # If no valid solution was found, fallback to a simple shape
    if best_h is None:
        # Use a cosine bump as a fallback
        x = np.linspace(0, 1, N)
        best_h = 0.5 * (1 + np.cos(2 * np.pi * x))
        best_h = np.clip(best_h, 0, None)
        best_val = compute_value_exact(best_h)
    
    # Final polish: Try to improve the best solution found by a short SA run
    # or just return the best one. Given the time constraints, returning the best 
    # gradient-based result is likely sufficient.
    
    # Ensure the result is a list of floats
    return list(best_h)

