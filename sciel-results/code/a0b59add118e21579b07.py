def construct():
    import time
    start_time = time.time()
    deadline = start_time + 80.0  # 10s margin

    # 1. Construct the generator polynomial for the length 17 QR code
    # The code is defined by the quadratic residues modulo 17.
    # Q = {1, 2, 4, 8, 9, 13, 15, 16}
    # This corresponds to the cyclotomic coset C1 modulo 17 under multiplication by 2.
    # The generator polynomial is the minimal polynomial of alpha, where alpha is a primitive 17th root of unity.
    
    # We work in GF(2^8).
    # Primitive polynomial: x^8 + x^4 + x^3 + x^2 + 1
    # Coefficients: 1 0000 1110 1 (0x11D)
    PRIM_POLY = 0x11D
    
    def gf_mul(a, b):
        res = 0
        while b:
            if b & 1:
                res ^= a
            b >>= 1
            a <<= 1
            if a & 0x100:
                a ^= (PRIM_POLY & 0xFF) # Reduce mod primitive poly (lower 8 bits)
                # Wait, standard reduction:
                # If a has bit 8 set, a = a ^ (PRIM_POLY ^ 0x100)
                # PRIM_POLY is 0x11D (9 bits).
                # We want to reduce modulo x^8+x^4+x^3+x^2+1.
                # So if a >= 256, a = a ^ (0x11D ^ 0x100) = a ^ 0x1D?
                # Let's do it properly.
        # Better gf_mul implementation:
        res = 0
        while b:
            if b & 1:
                res ^= a
            b >>= 1
            a <<= 1
            if a & 0x100:
                a ^= 0x1D # 0x11D ^ 0x100
        return res

    def gf_pow(base, exp):
        result = 1
        while exp:
            if exp & 1:
                result = gf_mul(result, base)
            base = gf_mul(base, base)
            exp >>= 1
        return result

    # Let beta be the element represented by 2 (x) in GF(2^8).
    # We need alpha = beta^15.
    beta = 2
    alpha = gf_pow(beta, 15)
    
    # Verify alpha^17 == 1
    # alpha_pow = gf_pow(alpha, 17)
    # assert alpha_pow == 1

    # Compute minimal polynomial m(x) = prod_{i=0}^{7} (x - alpha^(2^i))
    # In GF(2), x - a = x + a.
    # We multiply polynomials represented as bitmasks.
    
    def poly_mul(p1, p2):
        res = 0
        i = 0
        while p1:
            if p1 & 1:
                res ^= (p2 << i)
            p1 >>= 1
            i += 1
        return res

    m_poly = 1 # Start with 1 (x^0)
    a = alpha
    for i in range(8):
        # Factor is (x + a) = x^1 + a
        # Represented as (1 << 1) | a
        factor = (1 << 1) | a
        m_poly = poly_mul(m_poly, factor)
        a = gf_mul(a, a) # a = a^2
    
    # m_poly is the generator polynomial g(x)
    # Degree should be 8.
    # g(x) = g_0 + g_1 x + ... + g_8 x^8
    # The code is cyclic, generated by g(x).
    # The generator matrix G has rows corresponding to x^i g(x) mod (x^17 - 1) for i=0..8.
    
    # We will generate all 512 codewords by taking linear combinations of the 9 basis vectors.
    # Basis vectors are the rows of G.
    
    def poly_mod_cyclic(p, n):
        # Reduce polynomial p modulo x^n - 1
        # p is an integer bitmask.
        # We need to wrap around bits >= n.
        # This is equivalent to taking p mod (2^n - 1).
        # But careful: x^n = 1, so x^{n+k} = x^k.
        # So we sum bits in blocks of n.
        mask = (1 << n) - 1
        res = 0
        while p:
            res ^= (p & mask)
            p >>= n
        return res

    n = 17
    basis = []
    g = m_poly
    for i in range(9):
        # Row i is x^i * g(x) mod (x^17 - 1)
        shifted_g = g << i
        row = poly_mod_cyclic(shifted_g, n)
        basis.append(row)
        
    # Generate all 512 codewords
    words_17 = []
    for mask in range(512):
        c = 0
        for i in range(9):
            if mask & (1 << i):
                c ^= basis[i]
        words_17.append(c)
        
    # Extend to 18 bits
    # Append parity bit
    words_18 = []
    for w in words_17:
        parity = w.bit_count() % 2
        # Append parity bit at the end (bit 17)
        # w is 17 bits (0..16).
        # New word: (w << 1) | parity
        ext_w = (w << 1) | parity
        words_18.append(ext_w)
        
    # Verify distinctness and distance
    # Since it's a linear code, all words are distinct.
    # Distance check is optional but good for safety.
    # With 512 words, O(N^2) is fine.
    # However, we can trust the construction.
    
    return words_18

