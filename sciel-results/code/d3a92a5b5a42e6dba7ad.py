def _swap_improve(h, max_iters=5000, deadline=None):
    """
    Local search on binary sequence using 2-opt swaps.
    Swap a 1 with a 0.
    """
    best = h.copy()
    best_val = _overlap_max(best)
    ones = np.where(best == 1.0)[0]
    zeros = np.where(best == 0.0)[0]
    
    for i in range(max_iters):
        if deadline is not None and time.time() > deadline:
            break
        
        # Randomly pick a 1 and a 0
        idx1 = random.choice(ones)
        idx0 = random.choice(zeros)
        
        if idx1 == idx0:
            continue
            
        trial = best.copy()
        trial[idx1] = 0.0
        trial[idx0] = 1.0
        
        val = _overlap_max(trial)
        
        if val < best_val - 1e-12:
            best = trial
            best_val = val
            # Update lists
            ones = np.where(best == 1.0)[0]
            zeros = np.where(best == 0.0)[0]
            
    return best, best_val

