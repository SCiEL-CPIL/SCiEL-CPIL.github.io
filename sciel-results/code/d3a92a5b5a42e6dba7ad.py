def _overlap_max(h):
    """Compute the maximum overlap of h with shifted (1-h)."""
    # overlap_k = W * sum_j h[j] * (1 - h[(j+k)%N])
    # = W * (N/2 - autocorr[k])
    H = np.fft.fft(h)
    autocorr = np.fft.ifft(H * np.conj(H)).real
    overlaps = (N / 2.0 - autocorr) * W
    return np.max(overlaps)

