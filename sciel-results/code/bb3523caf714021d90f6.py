def _generate_icosahedral_shell(count, radius, rng, order=1):
    """
    Generate points on a sphere with approximate icosahedral symmetry.
    Uses Fibonacci sphere for good distribution, then relaxes locally.
    """
    # Fibonacci sphere for even distribution
    n = count
    golden_angle = np.pi * (3 - np.sqrt(5))
    points = []
    for i in range(n):
        z = 1 - (i + 0.5) / n * 2
        r = np.sqrt(1 - z**2)
        theta = golden_angle * i
        x = r * np.cos(theta)
        y = r * np.sin(theta)
        points.append([x, y, z])
    
    points = np.array(points) * radius
    # Center
    points -= np.mean(points, axis=0)
    return points

def _generate_mackay_shells(n, rng):
    """
    Generate Mackay icosahedral shells.
    """
    return _generate_icosahedron_points(n, rng, scale=2.0)

def _generate_random_compact(n, rng):
    """Generate a random cluster with density similar to equilibrium."""
    # Use rejection sampling with spatial hashing for speed
    R = (n * 8.0) ** (1.0/3.0) * 0.9
    points = []
    attempts = 0
    max_attempts = 5000 * n
    
    while len(points) < n and attempts < max_attempts:
        p = rng.uniform(-R, R, 3)
        if np.linalg.norm(p) <= R:
            if len(points) == 0:
                points.append(p)
            else:
                # Quick check using numpy
                arr = np.array(points)
                d = np.linalg.norm(arr - p, axis=1)
                if np.min(d) >= 0.5:
                    points.append(p)
        attempts += 1
    
    if len(points) < n:
        # Fill with random points
        while len(points) < n:
            p = rng.uniform(-R, R, 3)
            points.append(p)
    
    points = np.array(points)
    points -= np.mean(points, axis=0)
    return points

def _relax_worker(args):
    """Worker function for parallel relaxation."""
    positions, potential = args
    try:
        energy, relaxed_positions = relax(positions, potential)
        return energy, relaxed_positions
    except Exception:
        return float('inf'), positions

def _basin_hopping_step(positions, rng, potential, step_size=0.3, num_move=None):
    """Perform one basin hopping step."""
    n = len(positions)
    if num_move is None:
        num_move = max(1, n // 4)
    
    idx = rng.choice(n, size=num_move, replace=False)
    perturbed = positions.copy()
    perturbed[idx] += rng.normal(0, step_size, (num_move, 3))
    
    try:
        energy, relaxed = relax(perturbed, potential)
        return energy, relaxed
    except Exception:
        return float('inf'), positions

def construct(instance):
    global _START_TIME
    if _START_TIME is None:
        _START_TIME = time.time()
    
    size = instance["n"]
    potential = instance["potential"]
    
    # Check deadline
    if _get_elapsed() > 300 - _DEADLINE_MARGIN:
        rng = np.random.default_rng(size)
        R = (size * 8.0) ** (1.0/3.0) * 0.8
        points = rng.uniform(-R, R, (size, 3))
        return points
    
    rng = np.random.default_rng(size)
    
    # Generate diverse initial candidates
    candidates = []
    
    # 1. Icosahedral model
    mackay = _generate_mackay_shells(size, rng)
    candidates.append(mackay)
    
    # 2. Perturbed icosahedral (multiple scales)
    for sigma in [0.1, 0.2, 0.3]:
        perturbed = mackay + rng.normal(0, sigma, (size, 3))
        candidates.append(perturbed)
    
    # 3. Random compact structures
    for i in range(4):
        rand = _generate_random_compact(size, rng)
        candidates.append(rand)
    
    # 4. Scaled icosahedral (different equilibrium guesses)
    for scale in [1.8, 2.1, 2.2]:
        scaled = _generate_icosahedron_points(size, rng, scale=scale)
        candidates.append(scaled)
    
    # Relax all candidates in parallel
    args_list = [(c, potential) for c in candidates]
    
    best_energy = float('inf')
    best_positions = candidates[0]
    
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as executor:
        futures = [executor.submit(_relax_worker, args) for args in args_list]
        
        for future in concurrent.futures.as_completed(futures):
            try:
                energy, positions = future.result()
                if energy < best_energy:
                    best_energy = energy
                    best_positions = positions
            except Exception:
                pass
            
            if _get_elapsed() > 300 - _DEADLINE_MARGIN:
                break
    
    # Basin hopping with adaptive perturbation
    bh_rng = np.random.default_rng(size + 98765)
    max_bh_iterations = 30
    bh_iter = 0
    
    while bh_iter < max_bh_iterations and _remaining_time() > 10:
        # Adaptive step size: start larger, decrease
        progress = bh_iter / max_bh_iterations
        step_size = 0.4 * (1 - 0.5 * progress)
        
        energy, positions = _basin_hopping_step(
            best_positions, bh_rng, potential, 
            step_size=step_size, num_move=max(1, size // 5)
        )
        
        if energy < best_energy:
            best_energy = energy
            best_positions = positions
        
        bh_iter += 1
    
    # Final polish: small perturbations
    if _remaining_time() > 5:
        for _ in range(3):
            if _get_elapsed() > 300 - _DEADLINE_MARGIN:
                break
            energy, positions = _basin_hopping_step(
                best_positions, bh_rng, potential,
                step_size=0.1, num_move=max(1, size // 8)
            )
            if energy < best_energy:
                best_energy = energy
                best_positions = positions
    
    return best_positions
