    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        normals = np.array([
            [math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0)]
            for k in range(6)
        ])
        
        # LP Formulation
        # Variables: cx, cy, D
        # Minimize D
        c_obj = np.array([0.0, 0.0, 1.0])
        
        A_ub = []
        b_ub = []
        
        for k in range(6):
            nx, ny = normals[k]
            projs = pts @ normals[k]
            min_proj = np.min(projs)
            max_proj = np.max(projs)
            
            # Constraint 1: nx*cx + ny*cy - D <= min_proj
            # nx*cx + ny*cy - D - min_proj <= 0
            A_ub.append([nx, ny, -1.0])
            b_ub.append(min_proj)
            
            # Constraint 2: -nx*cx - ny*cy - D <= -max_proj
            # -nx*cx - ny*cy - D + max_proj <= 0
            A_ub.append([-nx, -ny, -1.0])
            b_ub.append(-max_proj)
            
        # D >= 0
        A_ub.append([0.0, 0.0, -1.0])
        b_ub.append(0.0)
        
        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=[(None, None), (None, None), (0, None)], method='highs')
            if res.status == 0:
                best_D = res.fun
                best_c = (res.x[0], res.x[1])
                S = (best_D + APOTHEM) / APOTHEM
                return S, best_c, best_D
        except Exception:
            pass
            
        # Fallback to Nelder-Mead if LP fails (should not happen)
        projs = pts @ normals.T
        a = np.max(projs, axis=0)
        b = np.min(projs, axis=0)
        
        def D_of_center(cx, cy):
            c = np.array([cx, cy])
            nc = normals @ c
            vals = np.maximum(a - nc, nc - b)
            return np.max(vals)
            
        cx_center = (np.max(pts[:, 0]) + np.min(pts[:, 0])) / 2
        cy_center = (np.max(pts[:, 1]) + np.min(pts[:, 1])) / 2
        res = minimize(D_of_center, [cx_center, cy_center], method='Nelder-Mead', options={'maxiter': 200})
        best_D = res.fun
        best_c = (res.x[0], res.x[1])
        S = (best_D + APOTHEM) / APOTHEM
        return S, best_c, best_D

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None
        
        # Coarse grid search over beta (13 points is sufficient)
        for i in range(13):
            beta = i * (math.pi / 6) / 12
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Refine beta with bounded scalar optimization
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(0, math.pi / 6), method='bounded',
                                     options={'maxiter': 200, 'xatol': 1e-10})
                if res.fun < best_S:
                    best_S = res.fun
                    best_beta = res.x
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass
        
        # Final high-precision polish using exact objective
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                def objective(params):
                    cx, cy, beta = params
                    beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                    normals = np.array([
                        [math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
                         math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0)]
                        for k in range(6)
                    ])
                    projs = (pts - np.array([cx, cy])) @ normals.T
                    max_proj = np.max(np.abs(projs))
                    S = (max_proj + APOTHEM) / APOTHEM
                    return S
                
                # Tighter local search around the best candidate
                # We will perform a few iterations of alternating optimization
                # 1. Fix beta, optimize cx, cy
                # 2. Fix cx, cy, optimize beta
                cx, cy = best_center
                beta = best_beta
                
                for _ in range(5):
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    
                    # Optimize cx, cy for fixed beta
                    def obj_c(params):
                        return objective([params[0], params[1], beta])
                    
                    res_c = minimize(obj_c, [cx, cy], method='Nelder-Mead',
                                     options={'maxiter': 500, 'xatol': 1e-10, 'fatol': 1e-10})
                    cx, cy = res_c.x
                    S_c = res_c.fun
                    
                    # Optimize beta for fixed cx, cy
                    def obj_b(params):
                        return objective([cx, cy, params[0]])
                    
                    # Use a small grid + minimize_scalar for beta to avoid local minima in 1D
                    # Beta is periodic with pi/6
                    b_starts = np.linspace(0, math.pi/6, 20)
                    best_b = beta
                    best_S_b = S_c
                    for b0 in b_starts:
                        if abs(b0 - best_b) < 1e-3: continue
                        res_b = minimize_scalar(obj_b, bounds=(0, math.pi/6), method='bounded',
                                                options={'maxiter': 100, 'xatol': 1e-10})
                        if res_b.fun < best_S_b:
                            best_S_b = res_b.fun
                            best_b = res_b.x
                    beta = best_b
                    S_b = best_S_b
                    
                    # Update best if improved
                    if S_b < best_S:
                        best_S = S_b
                        best_center = (cx, cy)
                        best_beta = beta
                        
        except Exception:
            pass
            
        return best_S, best_beta, best_center

    best_global_S = float('inf')
    best_global_pts = None
