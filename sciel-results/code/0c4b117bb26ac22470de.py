"""
Minimum maximal no-isosceles set on [0, N)^2 grid.

Strategy:
- Precompute isosceles-triangle conflicts using bitsets for speed.
- Use a time-bounded simulated annealing / local search to find a small
  maximal no-isosceles set.
- A set is "no-isosceles" if no three points form an isosceles triangle.
- A set is "maximal" if no additional grid point can be added without
  creating an isosceles triangle with two existing points.

We encode the problem as a graph where each grid point is a vertex.
An edge exists between two points if they are "compatible" in the sense
that adding both to a set doesn't immediately create an isosceles triangle
with a third point... actually, the constraint is global (triples), so we
need a different approach.

Better approach: 
- A set S is valid (no-isosceles) if for every triple (a,b,c) in S, the three
  points do not form an isosceles triangle.
- S is maximal if for every point p not in S, there exist two points a, b in S
  such that (p, a, b) forms an isosceles triangle.

We'll use simulated annealing:
- State: a subset of grid points.
- Moves: add a point, remove a point, or swap.
- Objective: minimize |S| while maintaining validity and maximality.
- Penalty for invalidity (isosceles triangles present) and non-maximality.

To make this efficient:
- Precompute for each point p, the set of pairs (a,b) such that (p,a,b) is isosceles.
- Actually, precompute for each pair (a,b), the set of points p such that (p,a,b) is isosceles.
- Then, a point p can be added to S only if for all pairs (a,b) in S, p is not in the
  isosceles-set of (a,b). Equivalently, for each a in S, and for each b in S with b != a,
  p must not form an isosceles triangle with a and b.

Let's define:
- For each point i, precompute iso[i] = set of points j such that there exists a point k
  where (i, j, k) is isosceles. This is too broad.

Better:
- For each ordered pair (i, j), precompute the set of points k such that (i, j, k) is isosceles.
  Let's call this iso_pair[i][j].

Then, a set S is valid if for all distinct i, j, k in S, k is not in iso_pair[i][j].

For maximality: a point p not in S is "blocked" if there exist i, j in S such that p is in iso_pair[i][j].
S is maximal if every point not in S is blocked.

We'll use a heuristic local search:
1. Start with a greedy maximal set.
2. Try to remove points while maintaining validity and maximality.
3. Use simulated annealing to explore.

Given time constraints, we'll implement a practical local search:
- Start with a greedy construction.
- Iteratively try to remove each point; if the resulting set is still valid and maximal, keep the removal.
- Repeat until no more removals are possible.
- Also try adding/removing combinations via random restarts.

But the greedy set might be large. Let's try a different initialization:
- Use a random maximal set generated by random-order greedy.
- Then apply removal heuristics.

We'll implement:
1. Precompute iso_pair as a list of bitsets (using Python integers or numpy arrays).
2. Function to check if a set is valid.
3. Function to check if a set is maximal.
4. Greedy construction with random order.
5. Local search: try to remove points.
6. Time-bounded: run multiple restarts until deadline.
"""

import time
import random
import numpy as np

N = 16
TOTAL_POINTS = N * N

# Precompute squared distances and isosceles conditions
# Point index: p = x * N + y
def point_to_idx(x, y):
    return x * N + y

def idx_to_point(idx):
    return (idx // N, idx % N)

# Precompute squared distance matrix
coords = np.array([(x, y) for x in range(N) for y in range(N)], dtype=np.int32)
dist_sq = np.zeros((TOTAL_POINTS, TOTAL_POINTS), dtype=np.int32)
for i in range(TOTAL_POINTS):
    for j in range(i + 1, TOTAL_POINTS):
        dx = coords[i, 0] - coords[j, 0]
        dy = coords[i, 1] - coords[j, 1]
        d = dx * dx + dy * dy
        dist_sq[i, j] = d
        dist_sq[j, i] = d

# Precompute iso_pair: for each pair (i, j), which points k make (i, j, k) isosceles?
# (i, j, k) is isosceles if dist(i,j) == dist(i,k) or dist(i,j) == dist(j,k) or dist(i,k) == dist(j,k)
# We'll store for each pair (i,j) a bitset of k's.

# Use a list of Python integers as bitsets
iso_pair = [[0] * TOTAL_POINTS for _ in range(TOTAL_POINTS)]

for i in range(TOTAL_POINTS):
    for j in range(i + 1, TOTAL_POINTS):
        dij = dist_sq[i, j]
        mask = 0
        for k in range(TOTAL_POINTS):
            if k == i or k == j:
                continue
            dik = dist_sq[i, k]
            djk = dist_sq[j, k]
            if dij == dik or dij == djk or dik == djk:
                mask |= (1 << k)
        iso_pair[i][j] = mask
        iso_pair[j][i] = mask

def is_valid_no_isosceles(S):
    """Check if set S (list of point indices) has no isosceles triangles."""
    n = len(S)
    for a_idx in range(n):
        for b_idx in range(a_idx + 1, n):
            a = S[a_idx]
            b = S[b_idx]
            # Check if any other point in S is in iso_pair[a][b]
            # We need to check each other point
            for c_idx in range(n):
                if c_idx == a_idx or c_idx == b_idx:
                    continue
                c = S[c_idx]
                if (iso_pair[a][b] >> c) & 1:
                    return False
    return True

def is_maximal(S):
    """Check if S is maximal: no point outside S can be added without creating an isosceles triangle."""
    S_set = set(S)
    for p in range(TOTAL_POINTS):
        if p in S_set:
            continue
        # Check if p is blocked: exists a, b in S such that p is in iso_pair[a][b]
        blocked = False
        S_list = list(S)
        n = len(S_list)
        for a_idx in range(n):
            for b_idx in range(a_idx + 1, n):
                a = S_list[a_idx]
                b = S_list[b_idx]
                if (iso_pair[a][b] >> p) & 1:
                    blocked = True
                    break
            if blocked:
                break
        if not blocked:
            return False
    return True

def greedy_maximal(order):
    """Build a maximal no-isosceles set using the given order of points."""
    chosen = []
    chosen_set = set()
    for p in order:
        if p in chosen_set:
            continue
        # Check if p can be added: for all pairs (a,b) in chosen, p not in iso_pair[a][b]
        can_add = True
        n = len(chosen)
        for a_idx in range(n):
            for b_idx in range(a_idx + 1, n):
                a = chosen[a_idx]
                b = chosen[b_idx]
                if (iso_pair[a][b] >> p) & 1:
                    can_add = False
                    break
            if not can_add:
                break
        if can_add:
            chosen.append(p)
            chosen_set.add(p)
    return chosen

def try_remove_points(S, deadline):
    """Try to remove points from S while maintaining validity and maximality."""
    S = list(S)
    improved = True
    while improved and time.time() < deadline:
        improved = False
        for i in range(len(S)):
            if time.time() > deadline:
                break
            # Try removing S[i]
            new_S = S[:i] + S[i+1:]
            if not is_valid_no_isosceles(new_S):
                continue
            if not is_maximal(new_S):
                continue
            S = new_S
            improved = True
            break  # Restart loop since S changed
    return S

def local_search(S, deadline):
    """Apply local search to minimize |S| while maintaining validity and maximality."""
    S = try_remove_points(S, deadline)
    return S

def construct():
    deadline = time.time() + 280  # Leave 20s safety margin for 300s limit
    
    best_S = None
    best_len = float('inf')
    
    # First, get a baseline greedy set
    order = list(range(TOTAL_POINTS))
    random.seed(42)
    
    # Try multiple random orders
    num_restarts = 50
    for r in range(num_restarts):
        if time.time() > deadline:
            break
        
        random_order = list(range(TOTAL_POINTS))
        random.shuffle(random_order)
        
        S = greedy_maximal(random_order)
        S = local_search(S, deadline)
        
        if len(S) < best_len:
            best_len = len(S)
            best_S = S[:]
    
    if best_S is None:
        # Fallback: simple greedy
        S = greedy_maximal(list(range(TOTAL_POINTS)))
        return [idx_to_point(p) for p in S]
    
    return [idx_to_point(p) for p in best_S]
