"""Adaptive 2D spread-based search for DTLZ4 hypervolume maximization."""
# EVOLVE-BLOCK-START
import numpy as np
import time


class Optimizer:
    """Adaptive 2D spatial search: bisect the (theta1, theta2) square
    by placing points where the local objective spread is largest."""

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 290  # safety margin

        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        n = self.dim
        m = self.n_obj - 1  # 2 shape variables
        k = n - m           # 10 position variables

        # DTLZ4 mapping:
        #   x_pos (k vars) at 0.5 -> g = 0
        #   x_{n-1} = 2/pi * theta1
        #   x_{n-2} = 2/pi * theta2
        #   f1 = cos(theta2)*cos(theta1)
        #   f2 = cos(theta2)*sin(theta1)
        #   f3 = sin(theta2)
        # We search in (theta1, theta2) in [0, pi/2]^2.

        pi_half = np.pi / 2

        def make_x(t1, t2):
            x_pos = np.full(k, 0.5)
            x_shape = np.array([2.0 / np.pi * t1, 2.0 / np.pi * t2])
            x_shape = np.clip(x_shape, 0.0, 1.0)
            x = np.concatenate([x_pos, x_shape])
            x = np.clip(x, lo, hi)
            return x

        def eval_point(t1, t2):
            x = make_x(t1, t2)
            f = problem(x)
            return x, np.asarray(f, dtype=float)

        # --- Phase 1: Seed with a small structured set (corners + midpoints) ---
        seed_points = [
            (0.0, 0.0),       # f=(1,0,0)
            (pi_half, 0.0),   # f=(0,1,0)
            (0.0, pi_half),   # f=(0,0,1)
            (pi_half, pi_half),  # f=(0,0,1) degenerate
            (pi_half / 2, 0.0),
            (0.0, pi_half / 2),
            (pi_half / 2, pi_half / 2),
            (pi_half / 4, pi_half / 4),
            (3 * pi_half / 4, pi_half / 4),
            (pi_half / 4, 3 * pi_half / 4),
        ]

        X = []
        F = []
        theta_pairs = []  # track (t1, t2) for each evaluated point
        used = 0

        for t1, t2 in seed_points:
            if used >= self.budget or time.time() > deadline - 30:
                break
            x, f = eval_point(t1, t2)
            X.append(x)
            F.append(f)
            theta_pairs.append((t1, t2))
            used += 1

        F_arr = np.array(F)

        # --- Phase 2: Adaptive refinement by max-spread bisection ---
        # Maintain a list of "cells" (rectangles in (t1,t2) space).
        # Each cell has 4 corners already evaluated (or we evaluate them).
        # Priority = max pairwise distance among the 4 corner F-vectors.
        # Each step: pick the highest-priority cell, evaluate its center,
        # then split into 4 sub-cells.

        # Build initial cells from the seed points.
        # We'll use a simpler approach: maintain a list of candidate centers
        # generated by recursive bisection, and always pick the one in the
        # region with the largest local spread.

        # Alternative simpler adaptive strategy:
        # Keep a list of "regions" as (t1_lo, t1_hi, t2_lo, t2_hi).
        # For each region, compute the spread of F at its 4 corners (if known)
        # or estimate from nearby points. Pick the region with max spread,
        # evaluate its center, then split the region into 4 quadrants.

        # For efficiency with 200 budget, use a priority queue of regions.
        import heapq

        # Initialize regions: the full square split into a 3x3 grid
        # (9 regions), evaluate centers of each if not already done.
        # Actually, let's just do iterative: at each step, find the pair of
        # already-evaluated points that are closest in (t1,t2) but have
        # large F-difference, and place a point between them.

        # Simpler and effective: use a "max-gap" strategy in (t1,t2) space
        # weighted by F-spread. At each step:
        #   1. For every pair of evaluated points, compute
        #      gap_score = ||f_i - f_j||_inf / (||t_i - t_j||_2 + eps)
        #   2. Place a new point at the midpoint of the pair with max gap_score
        #      (if the midpoint is sufficiently far from all existing points).

        # This is O(N^2) per step, with N up to 200 -> 40k ops per step, 200 steps
        # = 8M ops total. Fine for 290s.

        eps = 1e-6
        min_dist = pi_half / 50  # minimum distance to an existing point

        while used < self.budget and time.time() < deadline - 5:
            n_pts = len(theta_pairs)
            if n_pts < 2:
                break

            tp = np.array(theta_pairs)  # (N, 2)
            fa = F_arr                   # (N, 3)

            # Compute pairwise (t1,t2) distances and F differences
            # For memory efficiency with N up to 200, this is fine.
            # dt = tp[:, None, :] - tp[None, :, :]  # (N,N,2)
            # dist = np.sqrt(np.sum(dt**2, axis=2))
            # df = fa[:, None, :] - fa[None, :, :]  # (N,N,3)
            # fdiff_inf = np.max(np.abs(df), axis=2)  # (N,N)
            # score = fdiff_inf / (dist + eps)
            # np.fill_diagonal(score, 0)

            # More memory-efficient: loop
            best_score = -1
            best_i, best_j = -1, -1
            for i in range(n_pts):
                for j in range(i + 1, n_pts):
                    dt = tp[i] - tp[j]
                    dist = np.sqrt(dt[0] ** 2 + dt[1] ** 2)
                    if dist < eps:
                        continue
                    df = fa[i] - fa[j]
                    fdiff_inf = np.max(np.abs(df))
                    score = fdiff_inf / (dist + eps)
                    if score > best_score:
                        best_score = score
                        best_i, best_j = i, j

            if best_i < 0:
                break

            # Midpoint
            t1_new = 0.5 * (tp[best_i, 0] + tp[best_j, 0])
            t2_new = 0.5 * (tp[best_i, 1] + tp[best_j, 1])

            # Check minimum distance to all existing points
            dt_all = tp - np.array([t1_new, t2_new])
            dists = np.sqrt(np.sum(dt_all ** 2, axis=1))
            if np.min(dists) < min_dist:
                # Try to nudge the point slightly
                # Or just skip this pair and try the next best
                # For simplicity, accept it but with a small random perturbation
                rng = np.random.default_rng(used)
                t1_new += rng.uniform(-min_dist / 2, min_dist / 2)
                t2_new += rng.uniform(-min_dist / 2, min_dist / 2)
                t1_new = np.clip(t1_new, 0.0, pi_half)
                t2_new = np.clip(t2_new, 0.0, pi_half)

            x, f = eval_point(t1_new, t2_new)
            X.append(x)
            F.append(f)
            theta_pairs.append((t1_new, t2_new))
            F_arr = np.vstack([F_arr, f.reshape(1, -1)])
            used += 1

            # Periodic re-sort / cleanup not needed; the O(N^2) loop handles it.

        # --- Phase 3: Fill remaining budget with quasi-random points ---
        if used < self.budget and time.time() < deadline - 5:
            rng = np.random.default_rng(42)
            for _ in range(self.budget - used):
                if time.time() > deadline - 5:
                    break
                t1 = rng.uniform(0.0, pi_half)
                t2 = rng.uniform(0.0, pi_half)
                x, f = eval_point(t1, t2)
                X.append(x)
                F.append(f)
                theta_pairs.append((t1, t2))
                used += 1

        return X
# EVOLVE-BLOCK-END
