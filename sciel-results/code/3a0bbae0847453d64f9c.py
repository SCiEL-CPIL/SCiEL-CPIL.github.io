def integrate(f, t_span, y0):
    t0, t1 = t_span
    y = np.array(y0, dtype=float)
    t = t0
    
    steps = 100
    h = (t1 - t0) / steps
    
    start_time = time.time()
    
    for _ in range(steps):
        if time.time() - start_time > 290:
            break
            
