import sys
import time

def construct():
    """
    Finds a Sidon set containing 0, covering differences 1..30, 
    with the minimum possible largest element.
    """
    required_diffs = set(range(1, 31))
    # A Sidon set of size k has k*(k-1)/2 differences.
    # We need at least 30 distinct differences, so k*(k-1)/2 >= 30 => k >= 9.
    # Also, all differences must be <= D.
    
    def find_set_for_D(D, max_k=12):
        """
        Tries to find a Sidon set in [0, D] covering 1..30.
        Returns the set if found, else None.
        """
        # We try different sizes k
        # k must be at least 9.
        # k cannot be too large because k*(k-1)/2 <= D is not strictly required 
        # (differences can be <= D, but there are only D possible values).
        # So k*(k-1)/2 <= D is a necessary condition for existence in [0, D]?
        # Yes, because all differences are distinct and in [1, D].
        # So max k is approx sqrt(2D).
        
        min_k = 9
        max_k_possible = int((1 + (1 + 8 * D) ** 0.5) / 2)
        
        if min_k > max_k_possible:
            return None
            
        for k in range(min_k, min(max_k_possible, max_k) + 1):
            result = backtrack(D, k, required_diffs)
            if result is not None:
                return result
        return None

    def backtrack(D, k, req_diffs):
        """
        Backtracking search for a Sidon set of size k in [0, D].
        req_diffs: set of differences that must be covered.
        """
        # State:
        # A: list of selected elements, sorted
        # diffs: set of all differences generated so far
        # covered: set of req_diffs covered so far
        
        # Initial state: A=[0]
        A = [0]
        diffs = set()
        covered = set()
        
        # Symmetry breaking: a_0 = 0 is fixed.
        # We need to choose k-1 more elements from [1, D].
        
        # To speed up, we can fix the last element to be D?
        # Not necessarily, but if we don't use D, we could potentially have a smaller max element?
        # The problem asks to minimize the largest element. 
        # If we find a set with max element < D, that would be a better solution for a smaller D.
        # Since we iterate D upwards, if we are checking for a specific D, 
        # we just need *some* set with max element <= D.
        # However, if we find a set with max element < D, it would have been found in a previous iteration of D.
        # So for the current D, we can assume the max element is exactly D to reduce search space?
        # Not strictly. But if a solution exists with max < D, it's a solution for D-1.
        # So if we are at D and haven't found a solution for D-1, any solution for D must have max element D.
        # Wait, if we iterate D=30, 31, ..., and for each D we search for ANY set in [0,D],
        # then if a set with max 35 exists, it will be found when D=35.
        # So we don't need to force max element to be D, but it helps to prune.
        # Actually, forcing max element to be D is valid if we are confident that no solution with max < D exists.
        # Since we iterate D in increasing order, this is true.
        
        def solve(idx, current_max):
            if idx == k:
                if covered == req_diffs:
                    return A[:]
                return None
            
            # Pruning:
            # 1. Can we cover all remaining required diffs?
            remaining_req = req_diffs - covered
            # Max new diffs we can add with (k - idx) elements:
            # Each new element x adds diffs (x - a_i) for all a_i in A.
            # There are idx elements in A.
            # If we add m elements, total new diffs is m*idx + m*(m-1)/2.
            m = k - idx
            max_new_diffs = m * idx + m * (m - 1) // 2
            if len(remaining_req) > max_new_diffs:
                return None
            
            # 2. Can we fit the remaining elements?
            # The smallest possible next element is current_max + 1.
            # The largest possible element is D.
            # We need m elements in [current_max+1, D].
            if D - current_max < m:
                return None

            # Try each possible next element x
            # Start from current_max + 1 to D
            # Optimization: We can start from a lower bound.
            # The smallest new diff we can generate is x - current_max.
            # If there are required diffs smaller than this that are not covered, we might be stuck?
            # Not necessarily, they could be covered by differences with earlier elements?
            # No, diffs with earlier elements are already in `diffs`.
            # So if min(remaining_req) is not in `diffs`, it must be generated by new elements.
            # The smallest diff generated by a new element x is x - max(A) = x - current_max.
            # So if min(remaining_req) < x - current_max, and min(remaining_req) is not in diffs, 
            # then we cannot cover min(remaining_req) with this x or any larger x?
            # Wait, if we pick a smaller x, the diff is smaller.
            # So we should try x such that x - current_max <= min(remaining_req) if min(remaining_req) is not covered?
            # Actually, we just need to ensure that for every r in remaining_req, 
            # there exists some pair (a_i, a_j) with a_j - a_i = r.
            
            start_x = current_max + 1
            # If there is a required diff r that is not covered, and r < start_x - current_max (which is 1), 
            # that's impossible. But start_x - current_max is always 1.
            # So the smallest new diff is 1.
            
            for x in range(start_x, D + 1):
                # Check Sidon property for x
                valid = True
                new_diffs = []
                for a in A:
                    d = x - a
                    if d in diffs:
                        valid = False
                        break
                    new_diffs.append(d)
                
                if not valid:
                    continue
                
                # Update state
                A.append(x)
                diffs.update(new_diffs)
                new_covered = req_diffs.intersection(new_diffs)
                covered.update(new_covered)
                
                res = solve(idx + 1, x)
                if res is not None:
                    return res
                
                # Backtrack
                A.pop()
                diffs.difference_update(new_diffs)
                covered.difference_update(new_covered)
            
            return None
        
        return solve(1, 0)

    # Iterate D upwards
    # Lower bound: 
    # k=9 => 36 diffs => D >= 36
    # k=10 => 45 diffs => D >= 45
    # We start from 30, but it will fail quickly for D < 36.
    
    # To be safe and fast, we can start from a tighter bound.
    # But 30 is fine.
    
    # Timeout protection
    start_time = time.time()
    timeout = 110  # 120s limit, leave buffer
    
    for D in range(30, 1000):
        if time.time() - start_time > timeout:
            # Fallback to a known valid set if we time out?
            # The greedy one produces a valid set. Let's use that as fallback.
            return greedy_construct()
        
        result = find_set_for_D(D)
        if result is not None:
            # Ensure 0 is in result and it's a list of ints
            return sorted(result)
    
    # If loop finishes without finding (should not happen for D < 1000)
    return greedy_construct()

def greedy_construct():
    """Fallback greedy constructor."""
    a = [0]
    def diffs(s):
        return [y - x for i, x in enumerate(s) for y in s[i + 1:]]
    for d in range(1, 31):
        if d in diffs(sorted(a)):
            continue
        for x in sorted(set(v + s for v in a for s in (d, -d) if v + s >= 0) - set(a)):
            trial = sorted(a + [x])
            if len(set(diffs(trial))) == len(diffs(trial)):
                a = trial
                break
        else:
            y = 2 * max(a) + 3 * d + 1
            while True:
                trial = sorted(a + [y, y + d])
                if len(set(diffs(trial))) == len(diffs(trial)):
                    a = trial
                    break
                y += 1
    return a

# Increase recursion limit for backtracking
sys.setrecursionlimit(10000)
