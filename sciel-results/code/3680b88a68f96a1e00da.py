def construct():
    start = time.time()
    n = 16

    def time_ok():
        return (time.time() - start) < DEADLINE

    # Start from STS(15) on points 0..14, point 15 isolated.
    base = _build_sts15_z15()
    # Verify linearity of base (should be a valid STS -> linear)
    if not _is_linear(base):
        # Fallback: just use a safe linear system
        base = [[3*i, 3*i+1, 3*i+2] for i in range(5)]

    best = [list(t) for t in base]
    best_alpha = _independence_number(best, n)

    # Try to add triples involving point 15 to reduce independence number.
    # A triple containing 15 plus two points from 0..14 must not share 2 points
    # with any existing triple. Since STS(15) covers each pair exactly once,
    # adding {15,a,b} is linear iff {a,b} is NOT already a pair in a triple
    # that... actually linearity only cares about pair overlap between triples.
    # {15,a,b} shares {a,b} with the unique triple containing a,b in STS(15) ->
    # that's 2 shared points -> NOT linear. So we cannot add any {15,a,b}
    # where {a,b} is a pair in STS(15). But STS(15) covers ALL pairs of 0..14!
    # So NO triple containing 15 and two points from 0..14 is linear.
    # Hence point 15 must remain isolated, OR we must remove some STS triples.
    # 
    # Strategy: remove a few STS(15) triples to free up pairs, then add triples
    # with 15, then local search.

    def alpha(triples):
        return _independence_number(triples, n)

    random.seed(42)
    current = [list(t) for t in best]
    cur_alpha = best_alpha

    def pair_map(triples):
        pm = {}
        for i, t in enumerate(triples):
            s = sorted(t)
            for a, b in combinations(s, 2):
                pm[(a, b)] = i
        return pm

    def can_add(pm, t):
        s = sorted(t)
        for a, b in combinations(s, 2):
            if (a, b) in pm:
                return False
        return True

    def remove_triple(triples, pm, idx):
        """Remove triple idx, update pm."""
        t = triples.pop(idx)
        s = sorted(t)
        for a, b in combinations(s, 2):
            pm.pop((a, b), None)

    def add_triple(triples, pm, t):
        """Add triple t, update pm."""
        idx = len(triples)
        triples.append(t)
        s = sorted(t)
        for a, b in combinations(s, 2):
            pm[(a, b)] = idx

    # Strategy: Start with STS(15). The key insight is that point 15 is isolated.
    # To reduce alpha, we need to "cover" point 15 with triples. But in STS(15),
    # every pair among 0..14 is already in a triple, so we can't add {15,a,b}
    # without violating linearity.
    #
    # Solution: Remove some triples from STS(15), then add triples involving 15
    # that use the freed pairs. This trades coverage among 0..14 for coverage of 15.
    #
    # Better strategy: Use a different base. Try to find a linear triple system
    # on all 16 points with small alpha via randomized construction.

    # Approach: Randomized greedy construction
    def random_greedy():
        """Build a random linear triple system trying to cover all points."""
        used_pairs = set()
        triples_list = []
        # Shuffle points to break symmetry
        points = list(range(16))
        random.shuffle(points)
        # Try to add triples greedily
        for _ in range(500):
            # Pick 3 random unused points (not sharing 2 with any existing triple)
            candidates = []
            for _ in range(200):
                t = sorted(random.sample(range(16), 3))
                ok = True
                for a, b in combinations(t, 2):
                    if (a, b) in used_pairs:
                        ok = False
                        break
                if ok:
                    candidates.append(t)
            if candidates:
                t = candidates[0]
                triples_list.append(t)
                for a, b in combinations(t, 2):
                    used_pairs.add((a, b))
        return triples_list

    # Approach: Start from STS(15), remove triples, add triples with 15
    def modify_sts15():
        """Modify STS(15) to incorporate point 15."""
        base = [list(t) for t in _build_sts15_z15()]
        pm = pair_map(base)
        cur = list(base)
        cur_alpha = alpha(cur)

        # Find triples to remove and replace with triples involving 15
        # A triple {15, a, b} needs pair (a,b) to be free.
        # Remove triple containing pair (a,b), then add {15, a, b}.
        # But removing one triple frees 3 pairs; we can add up to 3 triples with 15.
        # However, those 3 new triples share point 15, which is fine (1 shared point).
        # But we need the pairs among {a1,b1}, {a2,b2}, {a3,b3} to be distinct and free.

        # Try: remove a triple {a,b,c}, then add {15,a,b} and {15,a,c} and {15,b,c}?
        # No: {15,a,b} and {15,a,c} share {15,a} -> 2 points -> NOT linear!
        # So from one removed triple {a,b,c}, we can add at most one {15, x, y}
        # where {x,y} is one of the freed pairs, AND we must ensure no other conflict.

        # Actually from {a,b,c} removed, freed pairs: (a,b), (a,c), (b,c).
        # We can add {15,a,b} (uses pair a,b). Then pair (a,c) and (b,c) are still free.
        # Can we add {15,a,c}? It shares {15,a} with {15,a,b} -> 2 points -> NO.
        # So from one removed triple, we get at most ONE new triple with 15.

        # Net effect: remove 1 triple, add 1 triple. Point 15 gets covered.
        # But we lose coverage of pair (a,b) among 0..14.
        # Alpha might decrease if 15 was the bottleneck.

        # Try all single swaps
        best_local = cur
        best_local_alpha = cur_alpha

        for trial in range(500):
            if not time_ok():
                break
            # Pick a random triple to remove
            idx = random.randrange(len(cur))
            t_rem = list(cur[idx])
            a, b, c = t_rem

            # Try adding {15, a, b}
            new_t = sorted([15, a, b])
            # Check: after removing t_rem, is (a,b) free? Yes (it was in t_rem).
            # But check no other triple has pair (a,b).
            # Since STS(15) has each pair in exactly one triple, and we removed t_rem,
            # pair (a,b) is now free. But we also need (15,a) and (15,b) to be free.
            # 15 is not in any existing triple (in base), so (15,a) and (15,b) are free.
            # So the swap is always linear!

            # Perform swap
            remove_triple(cur, pm, idx)
            add_triple(cur, pm, new_t)
            new_alpha = alpha(cur)

            if new_alpha <= best_local_alpha:
                best_local_alpha = new_alpha
                best_local = [list(x) for x in cur]
            else:
                # Undo
                remove_triple(cur, pm, len(cur) - 1)
                add_triple(cur, pm, t_rem)

            if best_local_alpha < cur_alpha:
                cur = [list(x) for x in best_local]
                cur_alpha = best_local_alpha
                pm = pair_map(cur)

        return best_local, best_local_alpha

    # Try modification approach
    if time_ok():
        mod_triples, mod_alpha = modify_sts15()
        if mod_alpha < best_alpha:
            best = mod_triples
            best_alpha = mod_alpha

    # Now do local search from best
    current = [list(t) for t in best]
    cur_alpha = best_alpha
    pm = pair_map(current)

    # Local search: try swaps (remove one triple, add another)
    for restart in range(5000):
        if not time_ok():
            break
        if restart > 0 and restart % 500 == 0:
            current = [list(t) for t in best]
            cur_alpha = best_alpha
            pm = pair_map(current)

        improved = False
        for _ in range(30):
            if not time_ok():
                break
            # Try a random swap
            idx = random.randrange(len(current))
            t_rem = list(current[idx])
            # Generate a random new triple
            if random.random() < 0.6:
                a, b = random.sample(range(15), 2)
                t_new = sorted([15, a, b])
            else:
                t_new = sorted(random.sample(range(16), 3))

            # Check if swap is valid: remove t_rem, add t_new
            # Temporarily remove t_rem
            remove_triple(current, pm, idx)
            if can_add(pm, t_new):
                add_triple(current, pm, t_new)
                new_alpha = alpha(current)
                if new_alpha < cur_alpha:
                    cur_alpha = new_alpha
                    improved = True
                    if cur_alpha < best_alpha:
                        best = [list(x) for x in current]
                        best_alpha = cur_alpha
                    break
                elif new_alpha == cur_alpha and random.random() < 0.4:
                    improved = True
                    break
                else:
                    # Undo
                    remove_triple(current, pm, len(current) - 1)
                    add_triple(current, pm, t_rem)
            else:
                # Undo
                add_triple(current, pm, t_rem)

        if cur_alpha < best_alpha:
            best = [list(x) for x in current]
            best_alpha = cur_alpha
            pm = pair_map(best)

    if not time_ok():
        return best

    if not _is_linear(best):
        return [[3*i, 3*i+1, 3*i+2] for i in range(5)]

    return best


if __name__ == "__main__":
    res = construct()
    print("triples:", len(res), "alpha:", _independence_number(res))
