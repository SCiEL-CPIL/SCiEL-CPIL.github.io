"""Linear triple system on 16 points minimizing independence number."""
import time
import random
from itertools import combinations

DEADLINE = 145.0  # wall-clock safety margin (evaluator kills at 150s)


def _independence_number(triples, n=16):
    """Largest subset of points containing no complete triple.

    Independent set = set containing no full triple.
    Equivalently: NOT a hitting set for the family of triple-bitmasks.
    We search for the maximum size subset that is NOT a hitting set.
    """
    if not triples:
        return n
    triples_bits = []
    for t in triples:
        b = 0
        for x in t:
            b |= (1 << x)
        triples_bits.append(b)
    triples_bits = list(set(triples_bits))

    # Check size n down to 1.
    # For a given size, we want to know if there exists a subset of that size
    # that is NOT a hitting set (i.e., contains no full triple).
    # Equivalently: there exists a subset S of size `size` such that for every
    # triple T, S does not contain all of T.
    #
    # Fast approach: iterate over all subsets of size `size` but prune early.
    # For n=16, C(16,8)=12870, C(16,9)=11440, etc. Manageable.
    for size in range(n, 0, -1):
        found = False
        for combo in combinations(range(n), size):
            mask = 0
            for x in combo:
                mask |= (1 << x)
            # Check if mask contains any full triple
            hit = False
            for b in triples_bits:
                if (mask & b) == b:
                    hit = True
                    break
            if not hit:
                found = True
                break
        if found:
            return size
    return 0


def _is_linear(triples):
    """Any two triples share at most one point."""
    for i in range(len(triples)):
        for j in range(i + 1, len(triples)):
            common = set(triples[i]) & set(triples[j])
            if len(common) > 1:
                return False
    return True


