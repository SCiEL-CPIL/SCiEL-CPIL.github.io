def construct(n_rows, k):
    start_time = time.time()
    deadline = start_time + 115  # Safety margin for 120s limit
    
    # Helper to get all differences in a row
    def get_row_diffs(row):
        diffs = set()
        for i in range(len(row)):
            for j in range(i + 1, len(row)):
                diffs.add(row[j] - row[i])
        return diffs

    def is_valid_global(rows):
        all_diffs = set()
        for row in rows:
            if row[0] != 0:
                return False
            for i in range(len(row)):
                for j in range(i + 1, len(row)):
                    d = row[j] - row[i]
                    if d in all_diffs:
                        return False
                    all_diffs.add(d)
        return True

    # 1. Initial Construction: Randomized Greedy
    # The standard greedy (smallest possible next number) often gets stuck in a local minimum
    # where early choices force later rows to be very long.
    # We use a randomized greedy that sometimes skips valid numbers to "reserve" small differences
    # for later, or uses a different ordering.
    
    def generate_random_row(used_diffs, max_val_hint):
        """
        Generates a row of k+1 integers starting at 0.
        Tries to keep values low but avoids conflicts with used_diffs.
        """
        row = [0]
        current_max = 0
        # We want to fill k more spots.
        # Strategy: At each step, look at a window of candidates.
        # If we always pick the smallest, we get the "standard" greedy row.
        # Randomization: Pick a random candidate from a small window of valid options.
        
        for _ in range(k):
            found = False
            # Start from the last value + 1
            # We need to check differences with ALL previous elements in the row
            # AND ensure the new differences don't collide with used_diffs.
            
            # Optimization: 
            # Let's try a range of candidates.
            # To make it "randomized greedy", we can pick a random offset from 1..W 
            # and try to find a valid number in [last + 1, last + W].
            # If none found, expand W.
            
            W = random.randint(1, 10)
            base = row[-1]
            
            while not found:
                # Try candidates in [base + 1, base + W]
                # Shuffle to randomize which one we pick first if multiple are valid?
                # No, let's pick a specific candidate to test.
                # Better: Generate a list of valid candidates in a window and pick one.
                
                candidates = []
                for v in range(base + 1, base + W + 1):
                    # Check order (implicit by v > base)
                    # Check diffs within row
                    valid_row = True
                    for a in row:
                        d = v - a
                        if d in used_diffs:
                            valid_row = False
                            break
                        # Also check if d is already in the current row's diffs?
                        # We are building the row, so we need to ensure d is not in the set of diffs 
                        # generated by pairs in `row` so far? 
                        # Actually, `used_diffs` is global. The row's internal diffs must also be unique 
                        # against each other? 
                        # "all differences between two entries of the same row are distinct over all rows"
                        # This implies:
                        # 1. No diff appears in two different rows.
                        # 2. No diff appears twice in the same row.
                        # So we need to maintain a local set of diffs for the current row being built.
                        pass
                    
                    # Let's re-implement the check properly inside the loop for clarity and correctness
                    # We need to check against:
                    # 1. Global used_diffs
                    # 2. Local row_diffs (diffs already generated in this row)
                    
                    # To do this efficiently, we should pass local_diffs.
                    # Let's refactor generate_random_row to be a generator or accept state.
                    # For now, simple check:
                    local_diffs = set()
                    for i in range(len(row)):
                        for j in range(i+1, len(row)):
                            local_diffs.add(row[j]-row[i])
                    
                    new_diffs = {v - a for a in row}
                    
                    if not (new_diffs & used_diffs) and not (new_diffs & local_diffs):
                        candidates.append(v)
                        
                if candidates:
                    # Pick a random candidate from the window
                    # Bias towards smaller values to keep the row compact
                    # But randomize to explore
                    v = random.choice(candidates)
                    row.append(v)
                    # Update used_diffs? No, we only commit if the whole row is valid.
                    # But for the purpose of building THIS row, we must treat these diffs as "used" 
                    # for subsequent elements in the same row.
                    # So we update a local set.
                    # Wait, the function returns the row. We don't update global used_diffs here.
                    # We need to track local_diffs during construction.
                    
                    # Let's restart the logic inside generate_random_row to be self-contained and correct.
                    break
                else:
                    # No valid candidate in window, expand window
                    W *= 2
                    if W > 500:
                        # Fallback: just find the next valid one greedily
                        v = base + 1
                        while True:
                            local_diffs = set()
                            for i in range(len(row)):
                                for j in range(i+1, len(row)):
                                    local_diffs.add(row[j]-row[i])
                            new_diffs = {v - a for a in row}
                            if not (new_diffs & used_diffs) and not (new_diffs & local_diffs):
                                break
                            v += 1
                        row.append(v)
                        found = True
                        break

        return row

    # Corrected generate_random_row
    def gen_row(used_diffs):
        row = [0]
        local_diffs = set()
        for _ in range(k):
            base = row[-1]
            # Randomized window search
            # Try a few random offsets
            found_val = None
            # Try a random window size
            max_window = random.randint(5, 50)
            # We'll scan from base+1 upwards, but we might skip some to allow "gaps"
            # Actually, to keep it simple and effective:
            # Scan candidates. Collect valid ones in a small buffer. Pick one.
            
            valid_candidates = []
            # We limit the scan to avoid infinite loops if impossible (though it shouldn't be)
            limit = base + 200 
            for v in range(base + 1, limit):
                new_diffs = {v - a for a in row}
                if new_diffs & used_diffs:
                    continue
                if new_diffs & local_diffs:
                    continue
                valid_candidates.append(v)
                if len(valid_candidates) >= 10:
                    break
            if not valid_candidates:
                # Fallback greedy
                v = base + 1
                while True:
                    new_diffs = {v - a for a in row}
                    if not (new_diffs & used_diffs) and not (new_diffs & local_diffs):
                        break
                    v += 1
                valid_candidates = [v]
            
            # Pick a candidate. Bias towards smaller, but allow randomness.
            # Sorting ensures we can pick "smallish"
            valid_candidates.sort()
            # Pick from the first half? Or random?
            # Let's pick randomly from the first few to encourage compactness
            # but not always the smallest.
            pick_idx = random.randint(0, min(4, len(valid_candidates)-1))
            chosen_val = valid_candidates[pick_idx]
            
            row.append(chosen_val)
            # Update local_diffs
            for a in row[:-1]:
                local_diffs.add(chosen_val - a)
                
        return row

    # Initial set of rows
    # Use a mix of greedy and randomized
    used = set()
    rows = []
    for i in range(n_rows):
        # First row: pure greedy (smallest possible)
        if i == 0:
            row = [0]
            local_diffs = set()
            for _ in range(k):
                base = row[-1]
                v = base + 1
                while True:
                    new_diffs = {v - a for a in row}
                    if not (new_diffs & used) and not (new_diffs & local_diffs):
                        break
                    v += 1
                row.append(v)
                for a in row[:-1]:
                    local_diffs.add(v - a)
        else:
            # Subsequent rows: randomized
            row = gen_row(used)
        
        # Update used
        row_diffs = get_row_diffs(row)
        used |= row_diffs
        rows.append(row)
    
    best_rows = [r[:] for r in rows]
    best_score = max(max(r) for r in best_rows)
    best_diffs = set(used)
    
    # 2. Row Replacement Search
    # Strategy: 
    # - Keep a list of rows.
    # - Pick a random row to replace.
    # - Generate a new candidate row that avoids the diffs of ALL OTHER rows.
    # - If the candidate row is valid (internally) and its diffs don't collide with others, 
    #   check if the new global max is lower.
    # - Accept if lower. Also accept equal with some prob (annealing).
    
    current_rows = [r[:] for r in best_rows]
    current_diffs = set(best_diffs)
    current_max = best_score
    
    # Precompute diffs for each row to make removal easy
    current_row_diffs = [get_row_diffs(r) for r in current_rows]
    
    t = 10.0
    cooling = 0.9995
    
    while time.time() < deadline:
        if t < 0.1:
            t = 5.0 # Restart annealing
            
        # Pick a row to replace
        idx = random.randrange(n_rows)
        
        # Calculate the set of "forbidden" diffs: all diffs from other rows
        forbidden = set()
        for i in range(n_rows):
            if i != idx:
                forbidden |= current_row_diffs[i]
        
        # Generate a new row that avoids `forbidden`
        # We want this row to be as compact as possible.
        # Use a greedy-with-randomness generator tailored to `forbidden`.
        
        new_row = [0]
        local_diffs = set()
        success = True
        for _ in range(k):
            base = new_row[-1]
            found_val = None
            # Look for the smallest valid value, but allow some randomness
            # Scan up to a limit
            # If we find a valid value, we might skip it with small prob to explore?
            # No, for replacement, we want a GOOD row. Greedy is usually best for compactness.
            # But pure greedy might get stuck. Randomized greedy is better.
            
            candidates = []
            limit = base + 100 # Look ahead
            for v in range(base + 1, limit):
                new_diffs = {v - a for a in new_row}
                if new_diffs & forbidden:
                    continue
                if new_diffs & local_diffs:
                    continue
                candidates.append(v)
                if len(candidates) >= 5:
                    break
            
            if not candidates:
                # Expand search
                v = base + 1
                while True:
                    new_diffs = {v - a for a in new_row}
                    if not (new_diffs & forbidden) and not (new_diffs & local_diffs):
                        break
                    v += 1
                candidates = [v]
            
            # Pick the smallest? Or random from top 3?
            # Smallest is usually best for minimizing max.
            # Let's pick the smallest 80% of the time, random otherwise.
            if random.random() < 0.8:
                chosen = candidates[0]
            else:
                chosen = random.choice(candidates[:min(3, len(candidates))])
                
            new_row.append(chosen)
            for a in new_row[:-1]:
                local_diffs.add(chosen - a)
                
        new_row_diffs = get_row_diffs(new_row)
        
        # Check if new_row_diffs collide with forbidden (should be 0 by construction)
        # But double check just in case
        if new_row_diffs & forbidden:
            t *= cooling
            continue
            
        # Calculate new global max
        # Remove old row's contribution to max?
        # Simple: just compute max of all rows with the new row inserted.
        # Since n_rows is small (7), this is fast.
        
        temp_rows = current_rows[:]
        temp_rows[idx] = new_row
        new_max = 0
        for r in temp_rows:
            m = max(r)
            if m > new_max:
                new_max = m
        
        # Decide acceptance
        if new_max < current_max:
            # Accept
            current_rows[idx] = new_row
            current_row_diffs[idx] = new_row_diffs
            current_max = new_max
            if current_max < best_score:
                best_score = current_max
                best_rows = [r[:] for r in current_rows]
                best_diffs = set(current_diffs)
                # Update best_diffs
                best_diffs = set()
                for r in best_rows:
                    best_diffs |= get_row_diffs(r)
        elif new_max == current_max:
            if random.random() < 0.1: # Low prob to accept neutral moves
                current_rows[idx] = new_row
                current_row_diffs[idx] = new_row_diffs
        else:
            # Worse
            delta = new_max - current_max
            prob = pow(2.71828, -delta / t)
            if random.random() < prob:
                current_rows[idx] = new_row
                current_row_diffs[idx] = new_row_diffs
                current_max = new_max
        
        t *= cooling
        
    return best_rows
