DEADLINE = TOTAL_BUDGET - SAFETY_MARGIN

def _popcount(x):
    return bin(x).count("1")

def _hamming(a, b):
    return (a ^ b).bit_count()

def _check_min_distance(words, min_dist):
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            if _hamming(wi, words[j]) < min_dist:
                return False
    return True

def _generate_qr_code_18_9_6():
    """
    Construct the [18, 9, 6] extended quadratic residue code.
    p = 17. Quadratic residues Q = {1, 2, 4, 8, 9, 13, 15, 16}.
    Generator polynomial g(x) = (1+x) * prod_{i in Q} (1+x^i).
    """
    p = 17
    Q = [1, 2, 4, 8, 9, 13, 15, 16]
    
    # Build generator polynomial coefficients in GF(2)
    # g(x) = (1+x) * (1+x^1) * (1+x^2) * ... * (1+x^16)
    # We work with bitmasks for polynomials of degree < 18
    g = 1  # 1
    # Multiply by (1+x)
    g = g ^ (g << 1)
    # Multiply by (1+x^i) for each i in Q
    for i in Q:
        g = g ^ (g << i)
    
    # Mask to 18 bits (degrees 0..17)
    g &= (1 << 18) - 1
    
    # Generate all 2^9 codewords
    # The code is generated by the circulant matrix formed by g, xg, ..., x^8 g
    # Actually, since it's a cyclic code, the codewords are multiples of g(x) mod (x^18-1)
    # We can just generate all linear combinations of the 9 generator rows.
    
    # Get the 9 generator vectors (rows of G)
    # Row k is x^k * g(x) mod (x^18-1)
    gen_rows = []
    for k in range(9):
        row = (g << k)
        # Wrap around (cyclic shift)
        # Since g has degree <= 17, and we shift by k<=8, max degree is 17+8=25.
        # We need mod x^18-1.
        # This is equivalent to: (row & ((1<<18)-1)) ^ ((row >> 18) & ((1<<18)-1))
        # But careful: if degree goes higher, we might need multiple wraps.
        # Max degree is 17+8=25. So one wrap is enough?
        # 25 < 18+8. So yes, at most one wrap.
        low = row & ((1 << 18) - 1)
        high = (row >> 18) & ((1 << 18) - 1)
        row = low ^ high
        gen_rows.append(row)
    
    codewords = []
    for mask in range(1 << 9):
        word = 0
        for i in range(9):
            if (mask >> i) & 1:
                word ^= gen_rows[i]
        codewords.append(word)
        
    # Verify min distance
    if _check_min_distance(codewords, 6):
        return codewords
    return None

