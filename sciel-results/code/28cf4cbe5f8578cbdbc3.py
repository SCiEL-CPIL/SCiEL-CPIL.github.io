    def axial_to_cartesian(axial_list):
        pts = []
        for q, r in axial_list:
            x = math.sqrt(3) * (q + r / 2.0)
            y = 1.5 * r
            pts.append((x, y))
        return np.array(pts)

    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None

        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append((math.cos(ang), math.sin(ang)))

        # Compute projections of all points onto each normal
        # For each normal, find max and min projection
        # D = max over all normals of (max_proj - min_proj) / 2
        # Actually, for a centered hexagon, we need the support function
        # The minimal enclosing hexagon has apothem D such that
        # all points satisfy |n . (p - c)| <= D for all 6 normals n
        
        # The optimal center c minimizes the maximum of |n . (p - c)|
        # This is equivalent to finding the Chebyshev center in the hexagonal norm
        
        # For a given beta, the problem reduces to:
        # minimize D subject to:
        #   n_k . (p_i - c) <= D  for all i, k
        #  -n_k . (p_i - c) <= D  for all i, k
        
        # This is a linear program in variables c_x, c_y, D
        
        # But we can solve it more directly:
        # For each normal n_k, the constraint is:
        #   max_i (n_k . p_i) - n_k . c <= D
        #   -(max_i (n_k . p_i) - n_k . c) <= D  =>  n_k . c - min_i (n_k . p_i) <= D
        # So: D >= max_i (n_k . p_i) - n_k . c  and  D >= n_k . c - min_i (n_k . p_i)
        # Thus: n_k . c >= max_i (n_k . p_i) - D  and  n_k . c <= min_i (n_k . p_i) + D
        # So: max_i (n_k . p_i) - D <= n_k . c <= min_i (n_k . p_i) + D
        
        # For feasibility, we need: max_i (n_k . p_i) - D <= min_i (n_k . p_i) + D
        # => 2D >= max_i (n_k . p_i) - min_i (n_k . p_i)
        # => D >= (max_i (n_k . p_i) - min_i (n_k . p_i)) / 2
        
        # And c must satisfy all these constraints simultaneously.
        
        # The minimal D is the smallest D such that there exists c satisfying all constraints.
        # This is a 2D linear programming problem.
        
        # Let's use the fact that the optimal c is determined by the most restrictive constraints.
        # We can solve this by noting that the feasible region for c is an intersection of strips.
        
        # For efficiency, let's compute the max and min projections for each normal
        max_projs = []
        min_projs = []
        for nx, ny in normals:
            projs = pts[:, 0] * nx + pts[:, 1] * ny
            max_projs.append(np.max(projs))
            min_projs.append(np.min(projs))
        
        max_projs = np.array(max_projs)
        min_projs = np.array(min_projs)
        
        # The minimal D must be at least max_k (max_projs[k] - min_projs[k]) / 2
        # But also, the center c must be feasible.
        
        # Let's try to find the optimal c and D using a simple approach:
        # The optimal D is the maximum over all pairs of constraints that are "tight"
        
        # Actually, let's just use the LP approach but with a simpler solver
        # Since we only have 3 variables (cx, cy, D), we can use scipy's linprog
        
        from scipy.optimize import linprog
        
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []
        
        for k in range(6):
            nx, ny = normals[k]
            for px, py in pts:
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-(px * nx + py * ny))
                A_ub.append([nx, ny, -1.0])
                b_ub.append(px * nx + py * ny)
        
        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None

        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None

        # Coarse grid search over beta
        for i in range(37):
            beta = i * (math.pi / 6) / 36
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center

        # Refine beta with bounded scalar optimization
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(0, math.pi / 6), method='bounded',
                                     options={'maxiter': 300, 'xatol': 1e-12})
                if res.fun < best_S:
                    best_S = res.fun
                    best_beta = res.x
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass

        return best_S, best_beta, best_center

    best_global_S = float('inf')
    best_global_pts = None
