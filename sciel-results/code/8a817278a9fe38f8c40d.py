import numpy as np
import time
import sys

DIMENSIONS = [2, 3, 4]

def construct():
    n, m, p = DIMENSIONS
    nm, mp, pn = n * m, m * p, p * n
    
    # Schoolbook fallback
    rank_school = n * m * p
    U_school = np.zeros((nm, rank_school))
    V_school = np.zeros((mp, rank_school))
    W_school = np.zeros((pn, rank_school))
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U_school[i * m + j, col] = 1
                V_school[j * p + k, col] = 1
                W_school[k * n + i, col] = 1
                col += 1
                
    # Precompute tensor T (flattened)
    # T[a, b, c] = 1 if a=i*m+j, b=j'*p+k, c=k'*n+i' and i==i', j==j', k==k'
    # Else 0
    # We need indices a, b, c
    a_idx = []
    b_idx = []
    c_idx = []
    t_vals = []
    for i in range(n):
        for j in range(m):
            for jp in range(m):
                for k in range(p):
                    for kp in range(p):
                        for ip in range(n):
                            a = i * m + j
                            b = jp * p + k
                            c = kp * n + ip
                            val = 1.0 if (i == ip and j == jp and k == kp) else 0.0
                            a_idx.append(a)
                            b_idx.append(b)
                            c_idx.append(c)
                            t_vals.append(val)
                            
    a_idx = np.array(a_idx)
    b_idx = np.array(b_idx)
    c_idx = np.array(c_idx)
    t_vals = np.array(t_vals)
    
    # Precompute row indices for U and V for each equation
    # eq_idx corresponds to (i, j, jp, k, kp, ip)
    # But we grouped by c (kp, ip) for the linear solve
    # So for a fixed c, we need all (a, b) such that the equation is for that c?
    # No, for a fixed c, the equation is for ALL (a, b).
    # So A_c is always the same structure, just different rows of U and V?
    # No, A_c[ab, r] = U[a, r] V[b, r].
    # This depends on a and b.
    # So for each c, we build a 72xR matrix.
    
    # Let's precompute the list of (a, b) pairs for all 72 equations
    ab_pairs = []
    for i in range(n):
        for j in range(m):
            for jp in range(m):
                for k in range(p):
                    a = i * m + j
                    b = jp * p + k
                    ab_pairs.append((a, b))
    ab_pairs = np.array(ab_pairs)
    a_rows = ab_pairs[:, 0]
    b_rows = ab_pairs[:, 1]
    
    # b_c for each c
    # b_c[ab_idx] = T[a, b, c]
    # We can precompute T as a 3D array
    T = np.zeros((nm, mp, pn))
    for i in range(n):
        for j in range(m):
            for k in range(p):
                a = i * m + j
                b = j * p + k
                c = k * n + i
                T[a, b, c] = 1.0
                
    deadline = time.time() + 110
    
    # Try ranks 19 to 23
    for R in range(19, 24):
        if time.time() > deadline - 10:
            break
            
        max_attempts = 2000
        for attempt in range(max_attempts):
            if time.time() > deadline - 5:
                break
                
            # Random U, V with small integers
            # Try different distributions
            if attempt % 3 == 0:
                U_rand = np.random.randint(-1, 2, size=(nm, R))
                V_rand = np.random.randint(-1, 2, size=(mp, R))
            elif attempt % 3 == 1:
                U_rand = np.random.randint(-2, 3, size=(nm, R))
                V_rand = np.random.randint(-2, 3, size=(mp, R))
            else:
                U_rand = np.random.randn(nm, R)
                V_rand = np.random.randn(mp, R)
                # Scale to keep numbers manageable?
                # Actually, if we use random floats, the solution W will be float.
                # We only accept if it's close to half-integer.
                
            valid = True
            W_sol = np.zeros((pn, R))
            
            # Solve for each row of W
            for c in range(pn):
                # Build A_c (72 x R)
                U_sel = U_rand[a_rows, :] # (72, R)
                V_sel = V_rand[b_rows, :] # (72, R)
                A_c = U_sel * V_sel
                
                # Build b_c (72,)
                b_c = T[:, :, c][a_rows, b_rows] # This indexing is wrong.
                # T is (nm, mp, pn).
                # We want T[a, b, c] for all a, b.
                # T[:, :, c] is (nm, mp).
                # We need to flatten it in the same order as ab_pairs.
                # ab_pairs is generated by i, j, jp, k.
                # a = i*m+j, b = jp*p+k.
                # This matches the flattening of T[:, :, c] if we flatten C-order?
                # T[:, :, c].flatten() iterates over last index first?
                # No, C-order flatten iterates over last index fastest.
                # T[a, b, c]. flatten() -> index = a*mp + b.
                # ab_pairs order:
                # for i in range(n):
                #   for j in range(m):
                #     for jp in range(m):
                #       for k in range(p):
                # a = i*m+j
                # b = jp*p+k
                # This is NOT the same as a*mp + b.
                # a*mp + b = (i*m+j)*mp + jp*p+k.
                # My ab_pairs loop:
                # i, j, jp, k.
                # a = i*m+j.
                # b = jp*p+k.
                # So the order is i, j, jp, k.
                # T[:, :, c].flatten() order is a, b.
                # a = i*m+j. b = jp*p+k.
                # So T_flat = T[:, :, c].flatten().
                # b_c = T_flat[ab_pairs_idx]?
                # No, ab_pairs are the indices.
                # b_c[eq_idx] = T[a_rows[eq_idx], b_rows[eq_idx], c]
                
                b_c = np.array([T[a, b, c] for a, b in zip(a_rows, b_rows)])
                
                # Solve A_c x = b_c
                try:
                    x, residuals, rank, sv = np.linalg.lstsq(A_c, b_c, rcond=None)
                except:
                    valid = False
                    break
                    
                # Check if x is close to half-integers
                x_scaled = x * 2
                x_rounded = np.round(x_scaled)
                if np.allclose(x_scaled, x_rounded, atol=1e-5):
                    W_sol[c, :] = x_rounded
                else:
                    valid = False
                    break
                    
            if not valid:
                continue
                
            # Verify exact solution
            # Check sum_r U[a,r] V[b,r] W[c,r] == T[a,b,c] for all a,b,c
            # Use vectorized check
            U_sel = U_rand[a_rows, :]
            V_sel = V_rand[b_rows, :]
            # W_sel for each c?
            # We can compute the full tensor M
            # M[a, b, c] = sum_r U[a,r] V[b,r] W[c,r]
            # Use einsum
            M = np.einsum('ar,br,cr->abc', U_rand, V_rand, W_sol)
            
            if np.allclose(M, T, atol=1e-9):
                # Found solution
                # Convert to list
                U_list = U_rand.tolist()
                V_list = V_rand.tolist()
                W_list = (W_sol / 2.0).tolist()
                return {"U": U_list, "V": V_list, "W": W_list}
                
    # Fallback
    return {"U": U_school.tolist(), "V": V_school.tolist(), "W": W_school.tolist()}
