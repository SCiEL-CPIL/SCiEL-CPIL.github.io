import numpy as np
import scipy.optimize
import time

N = 14

def construct():
    start_time = time.time()
    time_limit = 110.0
    
    def score_from_angles(angles):
        # Sort angles to ensure convex ordering
        angles = np.sort(angles)
        # Make cyclic: add 2pi to the first angle to handle wrap-around for differences?
        # Actually, just compute points.
        points = np.vstack([np.cos(angles), np.sin(angles)]).T
        
        # Calculate all triangle areas
        areas = []
        n = len(points)
        for i in range(n):
            for j in range(i+1, n):
                for k in range(j+1, n):
                    v1 = points[j] - points[i]
                    v2 = points[k] - points[i]
                    area = 0.5 * abs(v1[0]*v2[1] - v1[1]*v2[0])
                    areas.append(area)
        min_area = np.min(areas)
        
        # Calculate Hull Area
        # Since points are on a circle and sorted, the hull is the polygon defined by them.
        # We can calculate hull area using the shoelace formula on the sorted points.
        # This is faster and avoids scipy.spatial overhead.
        # Shoelace formula:
        # Sum over i of (x_i y_{i+1} - x_{i+1} y_i)
        # Note: points are in angular order, which is the hull order for points on a circle.
        x = points[:, 0]
        y = points[:, 1]
        # Shift y by 1
        x_shifted = np.roll(x, -1)
        y_shifted = np.roll(y, -1)
        hull_area = 0.5 * abs(np.sum(x * y_shifted - x_shifted * y))
        
        if hull_area == 0:
            return 0.0
            
        return min_area / hull_area

    def negative_score(angles):
        return -score_from_angles(angles)

    # Initial guess: Regular polygon
    initial_angles = np.linspace(0, 2*np.pi, N, endpoint=False)
    
    best_score = score_from_angles(initial_angles)
    best_angles = initial_angles.copy()
    
    # Local Optimization with Nelder-Mead
    # We need to handle the periodicity. Nelder-Mead on [0, 2pi] might struggle with boundaries.
    # But since we sort inside, the function is continuous with respect to the *set* of angles,
    # but the mapping from input vector to sorted vector has discontinuities.
    # To mitigate this, we can optimize the *differences* (deltas) which are positive and sum to 2pi.
    
    def score_from_deltas(deltas):
        # deltas are the angular gaps between consecutive points
        # Sum of deltas must be 2pi.
        # We pass 13 deltas, the 14th is determined.
        # Actually, let's pass 14 deltas and normalize them to sum to 2pi inside.
        # This ensures we stay in the valid space.
        d = np.array(deltas)
        d = np.abs(d)
        total = np.sum(d)
        if total == 0:
            return 0.0
        d = d / total * 2 * np.pi
        
        # Reconstruct angles
        angles = np.cumsum(d)
        # angles[0] is the first gap. The points are at angles:
        # theta_0 = 0 (wlog, rotation invariance)
        # theta_1 = d_0
        # theta_2 = d_0 + d_1
        # ...
        # But this fixes the rotation. We can ignore rotation as the score is rotation invariant.
        points = np.vstack([np.cos(angles[:-1]), np.sin(angles[:-1])]).T
        # Wait, angles has length 14. points should be 14.
        # angles[0] is the gap to the next point?
        # Let's define points at cumulative sums of deltas, starting from 0.
        # p_0 at 0
        # p_1 at d_0
        # p_2 at d_0 + d_1
        # ...
        # p_13 at d_0 + ... + d_12
        # The last gap d_13 closes the circle.
        # So we use the first 13 cumulative sums for the 13 points, and 0 for the first?
        # No, let's just use the 14 angles generated by cumsum of the 14 deltas,
        # but since sum is 2pi, the last angle is 2pi which is same as 0.
        # So we take the first 13 angles from cumsum(d) and append 0?
        # Or just take cumsum(d)[:-1] and it gives 13 points. We need 14.
        # The points are at 0, d_0, d_0+d_1, ..., sum(d_0..d_12).
        # This is 14 points.
        
        pts = np.vstack([np.cos(angles[:-1]), np.sin(angles[:-1])]).T
        
        # Calculate score
        areas = []
        n = len(pts)
        for i in range(n):
            for j in range(i+1, n):
                for k in range(j+1, n):
                    v1 = pts[j] - pts[i]
                    v2 = pts[k] - pts[i]
                    area = 0.5 * abs(v1[0]*v2[1] - v1[1]*v2[0])
                    areas.append(area)
        min_area = np.min(areas)
        
        x = pts[:, 0]
        y = pts[:, 1]
        x_shifted = np.roll(x, -1)
        y_shifted = np.roll(y, -1)
        hull_area = 0.5 * abs(np.sum(x * y_shifted - x_shifted * y))
        
        if hull_area == 0:
            return 0.0
        return min_area / hull_area

    def negative_score_deltas(deltas):
        return -score_from_deltas(deltas)

    # Initial deltas: uniform
    initial_deltas = np.full(N, 2*np.pi / N)
    
    # Optimize
    try:
        result = scipy.optimize.minimize(negative_score_deltas, initial_deltas, method='Nelder-Mead', 
                                          options={'maxiter': 5000, 'xatol': 1e-8, 'fatol': 1e-8})
        if result.fun < -best_score:
            best_score = -result.fun
            best_deltas = result.x
    except Exception:
        pass

    # Convert best deltas to points
    d = np.abs(best_deltas)
    total = np.sum(d)
    d = d / total * 2 * np.pi
    angles = np.cumsum(d)[:-1]
    points = np.vstack([np.cos(angles), np.sin(angles)]).T
    
    # Check time and try a few random restarts if time permits
    if time.time() - start_time < time_limit - 10:
        for _ in range(10):
            if time.time() - start_time > time_limit:
                break
            # Random perturbation of uniform deltas
            noise = np.random.normal(0, 0.1, N)
            init_d = np.full(N, 2*np.pi / N) + noise
            init_d = np.abs(init_d)
            try:
                res = scipy.optimize.minimize(negative_score_deltas, init_d, method='Nelder-Mead', 
                                              options={'maxiter': 2000, 'xatol': 1e-6, 'fatol': 1e-6})
                if -res.fun > best_score:
                    best_score = -res.fun
                    best_deltas = res.x
            except Exception:
                pass

    # Final conversion
    d = np.abs(best_deltas)
    total = np.sum(d)
    d = d / total * 2 * np.pi
    angles = np.cumsum(d)[:-1]
    points = np.vstack([np.cos(angles), np.sin(angles)]).T
    
    return points
