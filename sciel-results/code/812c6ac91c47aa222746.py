"""Covering-code constructor: Direct-sum baseline + Bitset-based ILS.

Design:
  * A direct-sum baseline provides a guaranteed valid upper bound (81 for q=3, n=6, R=1).
  * For small spaces (q^n <= 10000), we use a specialized solver based on Python
    integers as bitsets. This allows very fast set operations (intersection, count)
    compared to NumPy or list-based approaches.
  * The solver uses an Iterated Local Search (ILS) strategy:
      1. Greedy construction to get a valid cover.
      2. Reduction to remove redundant codewords.
      3. Perturbation (removing random codewords to break local minima).
      4. Repair (greedily filling uncovered gaps).
      5. Reduction again.
  * The loop continues until the time budget is exhausted, returning the best
    (smallest) valid covering found.
"""

import time
import itertools
import random
import sys

# The evaluator kills the process at 150 s; keep a generous buffer.
_DEADLINE = 140.0


def _direct_sum(q, n, radius):
    """Always-valid baseline: a radius-1 perfect code of length 4 over the alphabet,
    tensored with every word on the remaining n-4 coordinates.  Valid for R>=1, n>=4.
    Size = q^2 * q^(n-4) = q^(n-2)."""
    if n < 4:
        return [list(w) for w in itertools.product(range(q), repeat=n)]
    
    # For q=3, n=4, R=1, the perfect code is the [4,2,2]_3 code (size 9).
    # General construction for radius 1:
    # We use the simple sum-check code if possible, or just a generic small code.
    # For q=3, n=4, the code { (a,b,a+b, a+2b) } works? 
    # Distance between (a,b,a+b,a+2b) and (a',b',a'+b',a'+2b')
    # If a!=a' and b!=b', differences are non-zero in all 4 positions?
    # Actually, for q=3, n=4, R=1, K_3(4,1) = 9.
    # The code generated by (a, b, a+b, a+2b) for a,b in {0,1,2} has size 9.
    # Let's verify it's a covering code.
    # It is a known perfect code for q=3, n=4, R=1.
    
    base = [[a, b, (a + b) % q, (a + 2 * b) % q] for a in range(q) for b in range(q)]
    
    # For n > 4, we tensor with all possibilities for the remaining coordinates.
    # This is valid because if c1 is within R of w1 and c2 is any word, 
    # then c1 || c2 is within R of w1 || w2? 
    # No, this only works if the radius is distributed. 
    # Actually, the direct sum construction for covering codes:
    # If C1 is a (n1, M1, R1) code and C2 is a (n2, M2, R2) code,
    # then C1 x C2 is a (n1+n2, M1*M2, R1+R2) code.
    # Here we want R=1. If we use a perfect code of length 4 with R=1,
    # and "perfect" codes of length n-4 with R=0 (i.e., all words),
    # then the product is a code of length n with R=1.
    # The size is M1 * q^(n-4).
    # For q=3, n=4, M1=9. So size is 9 * 3^(n-4).
    # For n=6, size is 9 * 3^2 = 81.
    
    return [h + list(tail) for h in base
            for tail in itertools.product(range(q), repeat=n - 4)]


def _word_to_idx(w, q):
    idx = 0
    for x in w:
        idx = idx * q + x
    return idx


def _covers_all(cw, q, n, radius):
    """Exact coverage check over the whole space (small spaces only)."""
    total = q ** n
    covered = [False] * total
    for c in cw:
        ci = _word_to_idx(c, q)
        # Mark self
        covered[ci] = True
        # Mark neighbors
        for d in range(1, radius + 1):
            for pos in itertools.combinations(range(n), d):
                for vals in itertools.product(range(1, q), repeat=d):
                    w = list(c)
                    for p, v in zip(pos, vals):
                        w[p] = v
                    wi = _word_to_idx(w, q)
                    covered[wi] = True
    return all(covered)


def _solve_small(q, n, radius, deadline):
    """
    Specialized solver for small spaces using bitsets.
    """
    total_words = q ** n
    if total_words > 10000:
        return None

    start_time = time.time()
    
    # Precompute all words and their indices
    all_words = list(itertools.product(range(q), repeat=n))
    idx_map = {w: i for i, w in enumerate(all_words)}
    
    # Precompute neighbors as bitsets
    # neighbors[i] is a bitmask where bit j is set if word j is within distance 'radius' of word i
    neighbors = [0] * total_words
    for i, w in enumerate(all_words):
        mask = 0
        # Generate all words within radius
        # For efficiency, we iterate over combinations of positions to change
        # For radius=1, it's just n*(q-1) neighbors + self
        if radius == 1:
            mask |= (1 << i)
            for pos in range(n):
                orig_val = w[pos]
                for new_val in range(q):
                    if new_val == orig_val:
                        continue
                    new_w_list = list(w)
                    new_w_list[pos] = new_val
                    new_w = tuple(new_w_list)
                    j = idx_map[new_w]
                    mask |= (1 << j)
        else:
            # Generic radius handling (slower, but correct)
            for d in range(radius + 1):
                for pos in itertools.combinations(range(n), d):
                    for vals in itertools.product(range(1, q), repeat=d):
                        if d == 0:
                            mask |= (1 << i)
                        else:
                            new_w_list = list(w)
                            for p, v in zip(pos, vals):
                                new_w_list[p] = v
                            new_w = tuple(new_w_list)
                            j = idx_map[new_w]
                            mask |= (1 << j)
        neighbors[i] = mask
        
    full_mask = (1 << total_words) - 1
    
    # State variables
    # code_set: set of indices of chosen codewords
    # cover_count: list of ints, cover_count[i] is how many codewords cover word i
    
    def greedy_start():
        code_set = set()
        cover_count = [0] * total_words
        uncovered_mask = full_mask
        
        while uncovered_mask:
            best_idx = -1
            best_cnt = -1
            # Find the word that covers the most uncovered words
            for i in range(total_words):
                if i in code_set:
                    continue
                # Count how many bits in neighbors[i] are in uncovered_mask
                # bit_count is fast for Python ints
                cnt = (neighbors[i] & uncovered_mask).bit_count()
                if cnt > best_cnt:
                    best_cnt = cnt
                    best_idx = i
            
            if best_idx == -1 or best_cnt == 0:
                break
                
            code_set.add(best_idx)
            m = neighbors[best_idx]
            # Update cover_count
            # Iterate through set bits in m
            mm = m
            while mm:
                lsb = mm & -mm
                idx = lsb.bit_length() - 1
                cover_count[idx] += 1
                mm ^= lsb
            uncovered_mask &= ~m
            
        return code_set, cover_count

    def reduce_code(code_set, cover_count):
        """Remove redundant codewords."""
        changed = True
        while changed:
            changed = False
            # Iterate over a copy
            for c in list(code_set):
                # Check if c is redundant: all words in neighbors[c] have cover_count > 1
                redundant = True
                m = neighbors[c]
                mm = m
                while mm:
                    lsb = mm & -mm
                    idx = lsb.bit_length() - 1
                    if cover_count[idx] <= 1:
                        redundant = False
                        break
                    mm ^= lsb
                
                if redundant:
                    code_set.remove(c)
                    m = neighbors[c]
                    mm = m
                    while mm:
                        lsb = mm & -mm
                        idx = lsb.bit_length() - 1
                        cover_count[idx] -= 1
                        mm ^= lsb
                    changed = True
                    break # Restart loop to check new state
        return code_set, cover_count

    def repair(code_set, cover_count):
        """Add codewords until valid cover."""
        # Recalculate uncovered mask
        uncovered_mask = 0
        for i in range(total_words):
            if cover_count[i] == 0:
                uncovered_mask |= (1 << i)
                
        while uncovered_mask:
            best_idx = -1
            best_cnt = -1
            for i in range(total_words):
                if i in code_set:
                    continue
                cnt = (neighbors[i] & uncovered_mask).bit_count()
                if cnt > best_cnt:
                    best_cnt = cnt
                    best_idx = i
            
            if best_idx == -1 or best_cnt == 0:
                break
                
            code_set.add(best_idx)
            m = neighbors[best_idx]
            mm = m
            while mm:
                lsb = mm & -mm
                idx = lsb.bit_length() - 1
                cover_count[idx] += 1
                mm ^= lsb
            uncovered_mask &= ~m
            
        return code_set, cover_count

    # Main ILS Loop
    rng = random.Random(42)
    
    # Initial solution
    code_set, cover_count = greedy_start()
    code_set, cover_count = reduce_code(code_set, cover_count)
    
    best_size = len(code_set)
    best_code = list(code_set)
    
    # ILS
    while time.time() < deadline - 2:
        # Perturb
        # Remove k random codewords
        k = rng.randint(2, 5)
        if len(code_set) <= k:
            k = max(1, len(code_set) // 2)
            
        current_code = list(code_set)
        rng.shuffle(current_code)
        to_remove = current_code[:k]
        
        # Apply perturbation
        for c in to_remove:
            if c in code_set:
                code_set.remove(c)
                m = neighbors[c]
                mm = m
                while mm:
                    lsb = mm & -mm
                    idx = lsb.bit_length() - 1
                    cover_count[idx] -= 1
                    mm ^= lsb
        
        # Repair
        code_set, cover_count = repair(code_set, cover_count)
        
        # Reduce
        code_set, cover_count = reduce_code(code_set, cover_count)
        
        # Update best
        if len(code_set) < best_size:
            best_size = len(code_set)
            best_code = list(code_set)
            # If we reached the theoretical lower bound or a known optimum, we could stop,
            # but we don't always know the optimum. We continue to be safe.
            if best_size == 73 and q == 3 and n == 6 and radius == 1:
                break # Found the known optimum for this case

    # Convert best_code (list of indices) back to list of words
    return [list(all_words[i]) for i in best_code]


def construct(q, n, radius):
    start = time.time()

    # Always-valid baseline (guaranteed fallback).
    if n >= 4 and radius >= 1:
        baseline = _direct_sum(q, n, radius)
    else:
        baseline = [list(w) for w in itertools.product(range(q), repeat=n)]

    best = baseline
    best_len = len(baseline)

    def _maybe_update(cand):
        nonlocal best, best_len
        if cand is not None and len(cand) < best_len:
            # Verify before updating to be absolutely safe, though the solver should be robust
            if _covers_all(cand, q, n, radius):
                best = cand
                best_len = len(cand)

    if q ** n <= 10000 and best_len > 1:
        # Try the specialized ILS solver
        t_ils = max(1.0, _DEADLINE - (time.time() - start) - 5.0)
        try:
            cand = _solve_small(q, n, radius, start + t_ils)
            if cand is not None:
                _maybe_update(cand)
        except Exception as e:
            # Fallback to standard greedy if ILS fails
            pass

    # If ILS didn't improve or wasn't run, try standard greedy + reduce as a fallback
    # This is mostly for cases where q^n > 10000 or if ILS failed
    if q ** n <= 3 * 10**6 and best_len > 1 and time.time() - start < _DEADLINE - 10:
         # We could implement the numpy-based greedy here, but for the target case (729 words),
         # the bitset ILS is superior. For larger cases, the baseline is likely already good
         # or the problem is too hard for this time limit.
         pass

    # Final safety: if we are running out of time, return the valid baseline.
    if time.time() - start > _DEADLINE - 5.0:
        return baseline

    return best

