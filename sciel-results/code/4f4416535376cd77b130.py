import time
import random
import collections

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 110.0

    # Moore bound for k=3, g=16 is 510.
    # n must be even.
    min_n = 510
    if min_n % 2 != 0:
        min_n += 1

    def generate_random_involutions(n):
        """
        Generates 3 distinct random involutions on n elements.
        """
        for _ in range(50):
            gens = []
            for _ in range(3):
                # Generate a random involution
                perm = list(range(n))
                available = list(range(n))
                random.shuffle(available)
                i = 0
                while i < n:
                    # 50% chance to form a transposition with the next available
                    if random.random() < 0.5 and i + 1 < n:
                        u, v = available[i], available[i+1]
                        perm[u] = v
                        perm[v] = u
                        i += 2
                    else:
                        u = available[i]
                        perm[u] = u
                        i += 1
                gens.append(tuple(perm))
            
            # Check if they are distinct
            if len(set(gens)) == 3:
                # Check transitivity
                # Group generated by gens
                visited = {0}
                queue = [0]
                while queue:
                    u = queue.pop()
                    for gen in gens:
                        v = gen[u]
                        if v not in visited:
                            visited.add(v)
                            queue.append(v)
                if len(visited) == n:
                    return [list(g) for g in gens]
        return None

    def check_girth(gens, n, g):
        """
        Returns True if girth >= g.
        """
        dist = [-1] * n
        dist[0] = 0
        queue = collections.deque([0])
        
        while queue:
            u = queue.popleft()
            if dist[u] >= g - 1:
                continue
            for gen in gens:
                v = gen[u]
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    queue.append(v)
                elif v == 0 and dist[u] + 1 < g:
                    # Found a cycle of length dist[u] + 1
                    # which is < g
                    return False
        return True

    # Search loop
    n = min_n
    while time.time() < deadline:
        if n % 2 != 0:
            n += 1
            continue
            
        # Try to find a valid graph of size n
        # Limit attempts to avoid getting stuck
        max_attempts = 10
        for _ in range(max_attempts):
            if time.time() > deadline - 5.0:
                break
                
            gens = generate_random_involutions(n)
            if gens is None:
                continue
                
            if check_girth(gens, n, g):
                # Construct edges
                edges = []
                for i in range(n):
                    for gen in gens:
                        j = gen[i]
                        if i < j:
                            edges.append((i, j))
                return n, edges
        
        # If failed, try larger n
        n += 2
        if n > 1000:
            break
            
    # Fallback: Try known good size 936 if time permits
    if time.time() < deadline - 2.0:
        n = 936
        for _ in range(5):
            if time.time() > deadline - 1.0:
                break
            gens = generate_random_involutions(n)
            if gens is None:
                continue
            if check_girth(gens, n, g):
                edges = []
                for i in range(n):
                    for gen in gens:
                        j = gen[i]
                        if i < j:
                            edges.append((i, j))
                return n, edges
                break
    return None
