"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import time
import numpy as np

N = 11

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin before 150s limit
    
    # 1. Generate positions for N unit hexagons in a hexagonal lattice.
    # Unit hexagons in a lattice have centers separated by sqrt(3) in axial coordinates.
    # Axial coordinates (q, r) map to Cartesian:
    # x = sqrt(3) * (q + r/2)
    # y = 1.5 * r
    # This creates a packing where hexagons touch each other.
    
    # We need to select N=11 positions from the infinite lattice that form a compact cluster.
    # The "hexagonal number" arrangement is optimal for minimizing the convex hull area.
    # For N=11, the closest to a perfect hexagon (1, 7, 19...) is not an integer layer.
    # Layer 0: 1 hex
    # Layer 1: 6 hex (total 7)
    # Layer 2: 12 hex (total 19)
    # So N=11 is 7 + 4 hexagons from the next layer.
    
    positions = []
    # Center
    positions.append((0, 0))
    
    # Layer 1 (6 neighbors)
    # Directions in axial coords: (1,0), (0,1), (-1,1), (-1,0), (0,-1), (1,-1)
    dirs = [(1, 0), (0, 1), (-1, 1), (-1, 0), (0, -1), (1, -1)]
    for q, r in dirs:
        positions.append((q, r))
        
    # We have 7. Need 4 more.
    # Layer 2 has 12 positions. We pick 4 that are "closest" to the center or maintain symmetry.
    # Let's just generate the next layer and pick the first 4 to ensure compactness.
    # Actually, for minimal bounding box, symmetry is key.
    # Let's pick positions that extend the shape radially.
    # (2,0), (1,1), (0,2), (-1,2) ... wait, let's just take the next 4 in a specific order.
    # To be safe and symmetric, let's try to form a shape that is as close to a hexagon as possible.
    # Adding (2,0), (1,1), (0,2), (-1,2) creates an asymmetry.
    # Let's add (2,0), (1,1), (0,2) and (-1,2)? No, let's just pick the 4 closest to origin in Layer 2.
    # All Layer 2 points have distance from origin roughly the same.
    # Let's just pick the first 4 generated by expanding the radius.
    
    # Generate Layer 2
    layer2 = []
    for q in range(-2, 3):
        for r in range(-2, 3):
            # Check if it's in Layer 2 (distance 2 in hex grid)
            # Hex distance: (|q| + |r| + |q+r|) / 2
            dist = (abs(q) + abs(r) + abs(q+r)) / 2
            if dist == 2:
                layer2.append((q, r))
                
    # Sort by angle to pick symmetric ones? Or just take the first 4?
    # Let's take the ones with smallest x+y or similar to keep them tight.
    # Actually, for N=11, the optimal packing is known to be a specific shape.
    # Let's just pick 4 from Layer 2.
    # To minimize the bounding hexagon, we want to avoid "spikes".
    # Let's pick (2,0), (1,1), (0,2), (-1,2) ? 
    # Let's try to keep it balanced.
    # Pick (2,0), (1,1), (0,2), (-1,1) ? No (-1,1) is Layer 1.
    # Layer 2 points:
    # (2,0), (2,-1), (1,1), (1,2), (0,2), (-1,2), (-2,2), (-2,1), (-2,0), (-1,-1), (0,-2), (1,-2)
    
    # Let's pick 4 that are evenly distributed.
    # (2,0), (0,2), (-2,2), (-2,0) ?
    # Let's just append the first 4 from the sorted list by angle.
    def hex_angle(q, r):
        x = np.sqrt(3) * (q + r/2)
        y = 1.5 * r
        return np.arctan2(y, x)
        
    layer2_sorted = sorted(layer2, key=hex_angle)
    # Pick 4 evenly spaced?
    # Indices 0, 3, 6, 9
    for idx in [0, 3, 6, 9]:
        if idx < len(layer2_sorted):
            positions.append(layer2_sorted[idx])
            
    # Ensure we have exactly N positions
    while len(positions) < N:
        # Add next available from layer 2
        added = False
        for p in layer2_sorted:
            if p not in positions:
                positions.append(p)
                added = True
                break
        if not added:
            # Fallback: just add arbitrary
            positions.append((3, 0))
            
    positions = positions[:N]
    
    # Convert to Cartesian coordinates
    # Side length of unit hex is 1.
    # Distance between centers of touching hexes is 2 * apothem = 2 * (sqrt(3)/2) = sqrt(3).
    # My axial mapping:
    # x = sqrt(3) * (q + r/2)
    # y = 1.5 * r
    # Let's verify distance between (0,0) and (1,0):
    # (0,0) -> (0,0)
    # (1,0) -> (sqrt(3), 0). Distance = sqrt(3). Correct.
    # Distance between (0,0) and (0,1):
    # (0,1) -> (sqrt(3)/2, 1.5). Distance = sqrt(3/4 + 2.25) = sqrt(3). Correct.
    
    cart_positions = []
    for q, r in positions:
        x = np.sqrt(3) * (q + r/2)
        y = 1.5 * r
        cart_positions.append((x, y))
        
    # Center of mass to center the cluster
    cx = np.mean([p[0] for p in cart_positions])
    cy = np.mean([p[1] for p in cart_positions])
    centered_positions = [(x - cx, y - cy) for x, y in cart_positions]
    
    # 2. Calculate the minimal enclosing regular hexagon side length.
    # The outer hexagon has side length S and is rotated by angle theta.
    # A point (x, y) is inside the hexagon if:
    # |x' cos(theta) + y' sin(theta)| <= S * sqrt(3) / 2  (projection on x-axis) -- Wait, apothem is S*sqrt(3)/2
    # Actually, the condition for a regular hexagon with side S centered at origin, rotated by theta:
    # The apothem (distance from center to side) is a = S * sqrt(3) / 2.
    # The hexagon is the intersection of 6 half-planes.
    # For a hexagon aligned with axes (theta=0), the sides are at:
    # x = +/- a
    # y = +/- a * (1/sqrt(3)) ? No.
    # Vertices at (S, 0), (S/2, S*sqrt(3)/2), ...
    # Apothem is S*sqrt(3)/2.
    # The 6 normal vectors are at angles 0, 60, 120, 180, 240, 300.
    # Condition: |dot(p, n_i)| <= a for all i.
    # Where n_i are unit vectors.
    
    # We need to find S and theta such that for all points p in centered_positions:
    # max_i |dot(p, n_i(theta))| <= S * sqrt(3) / 2
    # This implies S >= (2 / sqrt(3)) * max_i |dot(p, n_i(theta))|
    
    # We want to minimize S, so we minimize max_i |dot(p, n_i(theta))| over theta.
    # Let f(theta) = max_{p in P} max_{k=0..5} |dot(p, n_k(theta))|
    # Then S_min = (2 / sqrt(3)) * min_theta f(theta)
    
    # n_k(theta) = (cos(theta + k*pi/3), sin(theta + k*pi/3))
    
    def calc_required_s(theta):
        max_proj = 0.0
        for px, py in centered_positions:
            for k in range(6):
                angle = theta + k * np.pi / 3
                # Dot product with unit normal
                proj = abs(px * np.cos(angle) + py * np.sin(angle))
                if proj > max_proj:
                    max_proj = proj
        return (2.0 / np.sqrt(3.0)) * max_proj
    
    # Search for optimal theta
    # The function is periodic with period pi/3 (60 degrees) due to hexagonal symmetry.
    # We can sample theta in [0, pi/3).
    
    best_s = float('inf')
    best_theta = 0.0
    
    # Coarse search
    num_samples = 360
    for i in range(num_samples):
        theta = (i / num_samples) * (np.pi / 3)
        s = calc_required_s(theta)
        if s < best_s:
            best_s = s
            best_theta = theta
            
    # Fine search around best_theta
    if time.time() < deadline:
        range_step = 0.05 # radians
        for i in range(-50, 51):
            theta = best_theta + i * range_step / 50.0
            s = calc_required_s(theta)
            if s < best_s:
                best_s = s
                best_theta = theta

    # The outer hexagon center is (0,0) in our local frame, which is (cx, cy) in global?
    # The problem asks for:
    # inner: (x, y, angle_degrees) for each inner hex.
    # outer: (x, y), side, angle.
    
    # We centered the inner hexes around (0,0).
    # So outer center is (0,0).
    # Inner hexes are at centered_positions.
    # Inner hexes are rotated by 0 degrees (aligned with lattice).
    # Outer hexagon is rotated by best_theta.
    
    inner = []
    for x, y in centered_positions:
        inner.append([x, y, 0.0])
        
    outer_center = (0.0, 0.0)
    outer_side = best_s
    outer_angle = np.degrees(best_theta)
    
    return inner, outer_center, outer_side, outer_angle
# EVOLVE-BLOCK-END
