import time
import random
import sys

def construct(n_rows, k):
    """
    Constructs a difference triangle set with n_rows rows and k+1 elements per row.
    Minimizes the largest entry.
    """
    start_time = time.time()
    deadline = 115.0  # Safety margin for 120s limit
    
    # Helper to check if a row is valid given a set of used differences
    def is_valid_row(row, used_diffs):
        row_diffs = set()
        for i in range(len(row)):
            for j in range(i+1, len(row)):
                d = row[j] - row[i]
                if d in used_diffs:
                    return False, None
                if d in row_diffs:
                    return False, None
                row_diffs.add(d)
        return True, row_diffs

    # Randomized greedy construction of a single row
    # Returns the row and its differences
    def greedy_row(used_diffs, k, max_val, randomize=False):
        row = [0]
        current_max = 0
        # We need k more elements
        for _ in range(k):
            candidates = []
            # Try values from current_max + 1 up to max_val
            # Optimization: only check a window if randomize is false, or all if true but with limit
            start = current_max + 1
            end = max_val + 1
            for x in range(start, end):
                # Check differences with existing row elements
                valid = True
                for a in row:
                    d = x - a
                    if d in used_diffs:
                        valid = False
                        break
                if not valid:
                    continue
                # Check differences within the new row (implicitly handled by used_diffs if we update it, 
                # but here we just check against global used_diffs. 
                # Wait, we must also ensure differences between x and previous elements of THIS row are distinct 
                # from each other and from global used_diffs.
                # Since row elements are increasing, x-a is positive.
                # We need to ensure {x-a for a in row} are distinct and not in used_diffs.
                # The loop above checks 'in used_diffs'. 
                # We also need to check if x-a collides with another x-a' for a' in row.
                # Since a < a', x-a > x-a'. So they are distinct automatically.
                # So we just need to check against global used_diffs.
                
                # However, we also need to ensure that the differences generated by this step 
                # don't conflict with each other? No, x-a is unique for each a.
                # So the check is simply: is x-a in used_diffs for any a in row?
                
                # If valid, add to candidates
                candidates.append(x)
            
            if not candidates:
                return None, None
            
            if randomize and len(candidates) > 1:
                # Pick a random candidate from the first few to allow diversity
                # Or pick randomly from all? Picking from all might jump too far.
                # Let's pick from a small prefix of candidates to keep it "greedy-like" but randomized
                prefix_size = min(5, len(candidates))
                x = random.choice(candidates[:prefix_size])
            else:
                x = candidates[0]
            
            row.append(x)
            current_max = x
            
        # Final check and compute diffs
        row_diffs = set()
        for i in range(len(row)):
            for j in range(i+1, len(row)):
                d = row[j] - row[i]
                if d in used_diffs:
                    return None, None
                if d in row_diffs:
                    return None, None
                row_diffs.add(d)
        
        return row, row_diffs

    # Full set construction
    def construct_set(randomize=False):
        used_diffs = set()
        rows = []
        # Determine a reasonable max_val bound for greedy
        # Counting bound: n_rows * k*(k+1)/2 differences.
        # Max diff is roughly sqrt(2 * total_diffs) ? No, max entry M.
        # Number of diffs is n_rows * k*(k+1)/2.
        # These must be distinct integers from 1..M.
        # So M >= n_rows * k*(k+1)/2.
        # For n_rows=4, k=8: 4 * 36 = 144.
        # Seed greedy usually finds something close to this.
        # Let's set a generous bound for the greedy step, say 200 or 3 * counting_bound.
        counting_bound = n_rows * k * (k + 1) // 2
        max_val_bound = max(200, counting_bound * 2)
        
        for _ in range(n_rows):
            row, row_diffs = greedy_row(used_diffs, k, max_val_bound, randomize)
            if row is None:
                return None
            rows.append(row)
            used_diffs.update(row_diffs)
        
        # Calculate scope
        scope = max(max(row) for row in rows)
        return rows, scope

    # Local search: try to improve a specific row
    def improve_row(rows, row_idx, used_diffs_global, current_scope):
        # Remove current row's diffs from global set
        current_row = rows[row_idx]
        current_diffs = set()
        for i in range(len(current_row)):
            for j in range(i+1, len(current_row)):
                current_diffs.add(current_row[j] - current_row[i])
        
        remaining_diffs = used_diffs_global - current_diffs
        
        # Try to find a new row with max value < current_scope
        # We can try to reduce the max value of this row specifically
        current_max = max(current_row)
        
        # We want to find a row with max_val < current_scope (or even < current_max)
        # Let's try to find any valid row with max_val < current_scope
        # If we find one with max_val < current_max, we definitely improve local max.
        # If we find one with current_max <= max_val < current_scope, we might improve global max if this was the bottleneck.
        
        # Iterate possible max values downwards from current_scope - 1
        # But we must ensure the row fits.
        # A smarter way: just try to construct a row with max_val = current_scope - 1
        # If it fails, try smaller?
        # Actually, let's just try to find a valid row with max_val < current_scope.
        # We can use a randomized greedy with a strict max_val limit.
        
        # To be efficient, we can try a few random restarts of greedy_row with max_val = current_scope - 1
        # If we find one, we have a valid row that fits in the new scope.
        
        # However, if current_scope is determined by another row, reducing this row's max 
        # doesn't change the global scope unless this row WAS the one with the max.
        # So, we should only attempt to reduce the scope if this row contains the global max.
        if current_max < current_scope:
            return None # No need to change this row to reduce global scope
        
        # This row has the global max. Try to find a replacement with max < current_scope
        new_max_target = current_scope - 1
        
        # Try a few times with randomization
        for _ in range(20):
            new_row, new_diffs = greedy_row(remaining_diffs, k, new_max_target, randomize=True)
            if new_row is not None:
                return new_row, new_diffs
        
        return None

    # Initial solution
    best_rows, best_scope = construct_set(randomize=False)
    if best_rows is None:
        # Fallback to pure greedy if randomized failed (shouldn't happen)
        used = set()
        rows = []
        for _ in range(n_rows):
            row, x = [0], 0
            while len(row) < k + 1:
                x += 1
                new = {x - a for a in row}
                if not new & used:
                    row.append(x)
                    used |= new
            rows.append(row)
        best_rows = rows
        best_scope = max(max(r) for r in rows)
    
    # Calculate global diffs for best_rows
    best_diffs = set()
    for r in best_rows:
        for i in range(len(r)):
            for j in range(i+1, len(r)):
                best_diffs.add(r[j] - r[i])

    # Main loop
    while time.time() - start_time < deadline:
        # 1. Try to generate a better set from scratch with randomization
        new_rows, new_scope = construct_set(randomize=True)
        if new_rows is not None and new_scope < best_scope:
            best_rows = new_rows
            best_scope = new_scope
            # Recalculate diffs
            best_diffs = set()
            for r in best_rows:
                for i in range(len(r)):
                    for j in range(i+1, len(r)):
                        best_diffs.add(r[j] - r[i])
        
        # 2. Local search on best_rows
        # Identify rows that have the current max
        rows_to_improve = []
        for i, r in enumerate(best_rows):
            if max(r) == best_scope:
                rows_to_improve.append(i)
        
        # Try to improve these rows
        for idx in rows_to_improve:
            if time.time() - start_time > deadline:
                break
            result = improve_row(best_rows, idx, best_diffs, best_scope)
            if result is not None:
                new_row, new_diffs = result
                # Update best_rows and best_diffs
                old_row = best_rows[idx]
                old_diffs = set()
                for i in range(len(old_row)):
                    for j in range(i+1, len(old_row)):
                        old_diffs.add(old_row[j] - old_row[i])
                
                best_diffs -= old_diffs
                best_diffs |= new_diffs
                best_rows[idx] = new_row
                
                # Update best_scope
                new_global_max = max(max(r) for r in best_rows)
                if new_global_max < best_scope:
                    best_scope = new_global_max
        
        # Occasionally, try a full local search pass on all rows?
        # The above only targets rows with the max. 
        # If we reduce the max of one, another might become the new max.
        # The loop structure handles this by re-evaluating.
        
        # Add a small sleep to avoid CPU spinning if it's too fast? No, we want max iterations.
        
    return best_rows
