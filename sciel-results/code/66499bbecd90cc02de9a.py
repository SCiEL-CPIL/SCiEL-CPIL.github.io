import time
import random

def _can_add(S, x, S_sums, D_other):
    """
    Check if x can be added to Sidon set S.
    S: list of elements
    S_sums: set of sums i+j for i<=j in S
    D_other: set of diffs from the other set
    Returns (new_S, new_S_sums, new_D_contrib) or (None, None, None)
    Note: We don't return new_D_contrib as a set of all diffs, just the new ones created by x.
    Actually, we need to update the set of diffs for S.
    """
    # Check Sidon sums
    # New sums: x+x and x+s for s in S
    # Must not be in S_sums
    # Also x+x must not be in S_sums (unless x is already in S, but x is new)
    if 2*x in S_sums:
        return None, None, None
    
    new_diffs = set()
    for s in S:
        s_sum = x + s
        if s_sum in S_sums:
            return None, None, None
        d = abs(x - s)
        if d > 0:
            if d in D_other:
                return None, None, None
            new_diffs.add(d)
            
    # Also check if 2*x conflicts with existing sums? 
    # S_sums contains sums of pairs (i,j) with i<=j.
    # If x is new, x+x is a new sum.
    # x+s are new sums.
    # Are there any other conflicts?
    # The sums generated by x are {2x, x+s1, x+s2, ...}.
    # These must not be in S_sums.
    # And they must be unique among themselves?
    # x+s1 == x+s2 implies s1==s2, so unique.
    # 2x == x+s implies x==s, impossible since x not in S.
    # So internal uniqueness is guaranteed.
    
    return S + [x], S_sums | {2*x} | {x+s for s in S}, new_diffs

def construct():
    start_time = time.time()
    deadline = start_time + 55  # 5s buffer
    
    best_total = 0
    best_A = []
    best_B = []
    
    # Helper to update best
    def update_best(A, B):
        nonlocal best_total, best_A, best_B
        total = len(A) + len(B)
        if total > best_total:
            best_total = total
            best_A = list(A)
            best_B = list(B)

    # Greedy Construction
    def greedy_build(order):
        A = []
        B = []
        sums_A = set()
        sums_B = set()
        diffs_A = set()
        diffs_B = set()
        
        for x in order:
            # Try A
            new_A, new_sums_A, new_diffs = _can_add(A, x, sums_A, diffs_B)
            if new_A is not None:
                A = new_A
                sums_A = new_sums_A
                diffs_A.update(new_diffs)
                continue
            
            # Try B
            new_B, new_sums_B, new_diffs = _can_add(B, x, sums_B, diffs_A)
            if new_B is not None:
                B = new_B
                sums_B = new_sums_B
                diffs_B.update(new_diffs)
                continue
            
            # If neither, skip x
        
        return A, B, sums_A, sums_B, diffs_A, diffs_B

    # Local Search
    def local_search(A, B, sums_A, sums_B, diffs_A, diffs_B, limit_time):
        # We work with copies
        A = list(A)
        B = list(B)
        sums_A = set(sums_A)
        sums_B = set(sums_B)
        diffs_A = set(diffs_A)
        diffs_B = set(diffs_B)
        
        universe = set(range(1, 257))
        
        while time.time() < limit_time:
            improved = False
            
            # 1. Try to add elements
            # Randomize order to escape local optima
            candidates = list(universe - set(A) - set(B))
            random.shuffle(candidates)
            
            for x in candidates:
                # Try add to A
                new_A, new_sums_A, new_diffs = _can_add(A, x, sums_A, diffs_B)
                if new_A is not None:
                    A = new_A
                    sums_A = new_sums_A
                    diffs_A.update(new_diffs)
                    improved = True
                    continue # Restart candidate loop? Or just continue? 
                    # Usually, adding one element might block others. 
                    # Let's just continue to next candidate.
                
                # Try add to B
                new_B, new_sums_B, new_diffs = _can_add(B, x, sums_B, diffs_A)
                if new_B is not None:
                    B = new_B
                    sums_B = new_sums_B
                    diffs_B.update(new_diffs)
                    improved = True
                    continue
            
            # 2. Try swaps (replace) if no additions were made
            if not improved:
                # Try to replace an element in A with a new one
                # This is expensive: O(|A| * |Universe|)
                # We can limit this.
                
                # Randomly pick an element from A to try removing
                if A:
                    idx = random.randint(0, len(A)-1)
                    a_to_remove = A[idx]
                    
                    # Reconstruct state without a_to_remove? 
                    # This is hard with incremental sets.
                    # We need to recompute sums_A and diffs_A without a_to_remove.
                    # Or we can just do a full re-validation of the new set.
                    
                    # Let's try a simpler swap: 
                    # Pick a candidate x not in A U B.
                    # Try to form A' = (A - {a_to_remove}) U {x}.
                    # Check if A' is Sidon and D(A') disjoint from D(B).
                    
                    # To make this fast, we only try a few swaps per iteration.
                    for _ in range(10): # Limit swaps per pass
                        if not A: break
                        idx = random.randint(0, len(A)-1)
                        a_to_remove = A[idx]
                        
                        # Generate candidate x
                        # Prefer x that is "close" or random
                        x = random.choice(list(universe - set(A) - set(B)))
                        
                        # Construct new A
                        new_A = [y for y in A if y != a_to_remove]
                        new_A.append(x)
                        new_A.sort()
                        
                        # Check Sidon
                        valid_sidon = True
                        s_set = set()
                        n = len(new_A)
                        for i in range(n):
                            for j in range(i, n):
                                s = new_A[i] + new_A[j]
                                if s in s_set:
                                    valid_sidon = False
                                    break
                                s_set.add(s)
                            if not valid_sidon: break
                        
                        if valid_sidon:
                            # Check Diffs
                            new_diffs = set()
                            for i in range(n):
                                for j in range(i+1, n):
                                    d = abs(new_A[i] - new_A[j])
                                    if d > 0:
                                        if d in diffs_B:
                                            valid_sidon = False
                                            break
                                        new_diffs.add(d)
                            
                            if valid_sidon:
                                # Perform swap
                                A = new_A
                                sums_A = s_set
                                diffs_A = new_diffs
                                improved = True
                                break # Break out of swap loop, restart main loop?
                
                if not improved and B:
                    for _ in range(10):
                        if not B: break
                        idx = random.randint(0, len(B)-1)
                        b_to_remove = B[idx]
                        
                        x = random.choice(list(universe - set(A) - set(B)))
                        
                        new_B = [y for y in B if y != b_to_remove]
                        new_B.append(x)
                        new_B.sort()
                        
                        valid_sidon = True
                        s_set = set()
                        n = len(new_B)
                        for i in range(n):
                            for j in range(i, n):
                                s = new_B[i] + new_B[j]
                                if s in s_set:
                                    valid_sidon = False
                                    break
                                s_set.add(s)
                            if not valid_sidon: break
                        
                        if valid_sidon:
                            new_diffs = set()
                            for i in range(n):
                                for j in range(i+1, n):
                                    d = abs(new_B[i] - new_B[j])
                                    if d > 0:
                                        if d in diffs_A:
                                            valid_sidon = False
                                            break
                                        new_diffs.add(d)
                            
                            if valid_sidon:
                                B = new_B
                                sums_B = s_set
                                diffs_B = new_diffs
                                improved = True
                                break
                                
            if not improved:
                break
                
        return A, B, sums_A, sums_B, diffs_A, diffs_B

    # Main Loop
    for trial in range(100):
        if time.time() > deadline:
            break
            
        # Randomize start order
        order = list(range(1, 257))
        random.shuffle(order)
        
        A, B, sums_A, sums_B, diffs_A, diffs_B = greedy_build(order)
        
        # Local search
        A, B, sums_A, sums_B, diffs_A, diffs_B = local_search(A, B, sums_A, sums_B, diffs_A, diffs_B, deadline)
        
        update_best(A, B)
        
        # If we hit the theoretical max (unlikely), break
        if best_total >= 60: 
             break

    # Ensure non-empty
    if not best_A:
        best_A = [1]
    if not best_B:
        best_B = [2]
        
    return [best_A, best_B]
