import time
import math
import numpy as np

def construct():
    start = time.time()
    deadline = start + 85  # 85 second budget, 5s margin
    
    denominators = list(range(2, 49))
    n = len(denominators)
    
    # Calculate LCM of denominators
    L = 1
    for d in denominators:
        L = math.lcm(L, d)
        
    # Calculate weights w_i = L / d_i
    # Using float64 for speed. 
    # L is approx 5.3e17. float64 has 52 bits mantissa.
    # Precision loss is acceptable for finding the *best* subset 
    # given that the current best deficit is large enough 
    # (score 4e6 implies deficit ~ 1e11, which is >> float spacing ~ 20).
    weights = np.array([L // d for d in denominators], dtype=np.float64)
    
    # Split into two halves
    mid = n // 2
    weights_A = weights[:mid]
    weights_B = weights[mid:]
    
    def gen_sums(weights_subset):
        # Generate all subset sums using vectorized numpy operations
        sums = np.array([0.0], dtype=np.float64)
        for w in weights_subset:
            # Concatenate current sums with current sums + w
            sums = np.concatenate((sums, sums + w))
        return sums
    
    # Generate sums for both halves
    # Size of A: 2^23 = 8,388,608
    # Size of B: 2^24 = 16,777,216
    sums_A = gen_sums(weights_A)
    sums_B = gen_sums(weights_B)
    
    # Sort sums_B for binary search
    sums_B.sort()
    
    # We want to find pairs (a, b) such that a + b < L
    # Maximize a + b
    # For each a, we need the largest b such that b < L - a
    # np.searchsorted finds the index where (L - a) would be inserted to keep order
    # We want the element at idx - 1
    
    # Vectorize the search
    # targets = L - sums_A
    # indices = np.searchsorted(sums_B, targets, side='left')
