    # However, doing this for 8M elements in a loop is slow.
    # But np.searchsorted is vectorized? 
    # Actually, np.searchsorted accepts arrays.
    
    targets = L - sums_A
    # searchsorted with side='left' gives first index >= target
    # We want the last index < target, which is idx - 1
    idxs = np.searchsorted(sums_B, targets, side='left')
    
    # The candidate index in sums_B is idxs - 1
    cand_idxs = idxs - 1
    
    # Check validity: cand_idxs must be >= 0
    # Also, we should ensure sums_A[i] + sums_B[cand_idxs[i]] < L
    # Due to floating point, it's safer to check
    
    valid_mask = cand_idxs >= 0
    # Filter to valid candidates
    valid_idxs_A = np.where(valid_mask)[0]
    
    if len(valid_idxs_A) == 0:
        # Fallback: should not happen
        return [0]
    
    # Get the corresponding B indices
    valid_idxs_B = cand_idxs[valid_mask]
    
    # Calculate the total sums for these candidates
    total_sums = sums_A[valid_idxs_A] + sums_B[valid_idxs_B]
    
    # Find the maximum total sum
    best_local_idx = np.argmax(total_sums)
    best_sum_val = total_sums[best_local_idx]
    
    best_idx_A = valid_idxs_A[best_local_idx]
    best_idx_B = valid_idxs_B[best_local_idx]
    
    # Reconstruct the masks/indices from the flat array indices
    # The index in the sums array corresponds to the bitmask of the subset
    # sums_A was generated by doubling: 
    # 0: 0
    # 1: w0
    # 2: w1
    # 3: w0+w1
    # ...
    # So index `k` corresponds to the bitmask `k` in binary representation of length `len(weights_subset)`
    
    mask_A = best_idx_A
    mask_B = best_idx_B
    
    selected_indices = []
    
    # Check mask A
    for i in range(len(weights_A)):
        if mask_A & (1 << i):
            selected_indices.append(i)
            
    # Check mask B
    for i in range(len(weights_B)):
        if mask_B & (1 << i):
            selected_indices.append(mid + i)
            
    # Ensure non-empty
    if not selected_indices:
        return [0]
        
    # Verification with exact integer arithmetic to be safe
    # This is fast for a single subset
