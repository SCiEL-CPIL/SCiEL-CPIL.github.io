import time
import random
import sys

# EVOLVE-BLOCK-START

def construct():
    start_time = time.time()
    DEADLINE = 140.0  # Safety margin before 150s limit
    
    # Prescribed elements
    prescribed = [1, 2, 5, 11]
    prescribed_set = set(prescribed)
    
    # Max value in range
    MAX_VAL = 284
    ALL_CANDIDATES = list(range(1, MAX_VAL + 1))
    
    # Bitmask for sums. Max sum is 284 + 284 = 568.
    # We need bits 0..568. Python ints handle this easily.
    
    def init_mask(s):
        """Initialize bitmask for a set of elements."""
        mask = 0
        for i, a in enumerate(s):
            for b in s[i:]:
                mask |= (1 << (a + b))
        return mask

    def can_add_mask(s, mask, x):
        """Check if x can be added using bitmask. O(n) but with fast bit ops."""
        # Check 2*x
        if (mask >> (2 * x)) & 1:
            return False
        # Check x + y for all y in s
        for y in s:
            if (mask >> (x + y)) & 1:
                return False
        return True

    def add_element(s, mask, x):
        """Add element x to set s and update mask."""
        s.append(x)
        for y in s[:-1]:
            mask |= (1 << (x + y))
        mask |= (1 << (2 * x))
        return s, mask

    def remove_element(s, mask, x):
        """Remove element x from set s and update mask. 
        Note: This is tricky with bitmasks because if two pairs produce the same sum, 
        removing one doesn't clear the bit if the other remains. 
        However, in a valid Sidon set, all sums are unique. 
        So, removing x should clear exactly the sums involving x.
        Wait, if the set is valid, all sums a+b are distinct.
        So sums involving x are: 2x, x+y for y!=x.
        These sums are NOT generated by any other pair (a,b) with a,b != x.
        So we can safely clear these bits.
        """
        # Find index
        try:
            idx = s.index(x)
        except ValueError:
            return s, mask
        
        # Clear sums involving x
        mask &= ~(1 << (2 * x))
        for i, y in enumerate(s):
            if i != idx:
                mask &= ~(1 << (x + y))
        
        # Remove from list
        s.pop(idx)
        return s, mask

    # Strategy: Iterative Local Search with Bitsets
    
    best_set = []
    best_size = 0
    best_mask = 0
    
    # Initial Greedy to get a baseline
    s_init = sorted(prescribed)
    mask_init = init_mask(s_init)
    
    # Try a few greedy orders to find a good starting point
    for _ in range(5):
        s = s_init[:]
        mask = mask_init
        remaining = [x for x in ALL_CANDIDATES if x not in s]
        random.shuffle(remaining)
        
        for x in remaining:
            if can_add_mask(s, mask, x):
                s, mask = add_element(s, mask, x)
        
        if len(s) > best_size:
            best_size = len(s)
            best_set = s[:]
            best_mask = mask
            
        if time.time() > DEADLINE - 10:
            break

    # Main Local Search Loop
    # We will run multiple restarts of local search on the best solution found so far, 
    # but also occasionally restart from scratch with different random seeds.
    
    random.seed(42)
    
    while time.time() < DEADLINE - 5.0:
        
        # Occasionally restart from a fresh greedy solution to escape deep local minima
        if random.random() < 0.1:
            s = s_init[:]
            mask = mask_init
            remaining = [x for x in ALL_CANDIDATES if x not in s]
            random.shuffle(remaining)
            for x in remaining:
                if can_add_mask(s, mask, x):
                    s, mask = add_element(s, mask, x)
            
            if len(s) > best_size:
                best_size = len(s)
                best_set = s[:]
                best_mask = mask
        else:
            # Continue from current best
            s = best_set[:]
            mask = best_mask
            
        # Local Search Phase
        # We try to improve s by swapping elements.
        # We use a "no-improvement" counter to decide when to break.
        no_improve_count = 0
        max_no_improve = 2000  # Limit per local search phase
        
        while no_improve_count < max_no_improve and time.time() < DEADLINE - 5.0:
            
            improved = False
            
            # 1. Try to Add
            # Find candidates that can be added
            # To make this fast, we don't check all 284 every time, but it's O(284 * n) which is ~5000 ops.
            # With bitsets, can_add is fast.
            candidates_to_add = []
            for x in ALL_CANDIDATES:
                if x not in s:
                    if can_add_mask(s, mask, x):
                        candidates_to_add.append(x)
                        
            if candidates_to_add:
                # Pick a random one to add
                x_add = random.choice(candidates_to_add)
                s, mask = add_element(s, mask, x_add)
                improved = True
                no_improve_count = 0
                if len(s) > best_size:
                    best_size = len(s)
                    best_set = s[:]
                    best_mask = mask
                continue
            
            # 2. Try to Swap (Remove 1, Add 1)
            # Pick a random element to remove (not prescribed)
            removable = [x for x in s if x not in prescribed_set]
            if not removable:
                break
                
            x_remove = random.choice(removable)
            
            # Temporarily remove
            s_trial = s[:]
            mask_trial = mask
            s_trial, mask_trial = remove_element(s_trial, mask_trial, x_remove)
            
            # Find candidates to add to s_trial
            candidates_to_add = []
            for x in ALL_CANDIDATES:
                if x not in s_trial and x != x_remove:
                    if can_add_mask(s_trial, mask_trial, x):
                        candidates_to_add.append(x)
                        
            if candidates_to_add:
                x_add = random.choice(candidates_to_add)
                s_trial, mask_trial = add_element(s_trial, mask_trial, x_add)
                
                # Since we removed 1 and added 1, size is same. 
                # But maybe it opens up space for future adds? 
                # Actually, if size is same, we only accept if it leads to a better state later?
                # Standard local search: accept if size increases. Here size is same.
                # However, a swap might allow a subsequent add.
                # To avoid cycling, we can accept swaps that change the set, 
                # but we must be careful. 
                # Better: Only accept swap if it allows an immediate add afterwards?
                # Or use Simulated Annealing logic? 
                # For simplicity and speed, let's try to add *after* the swap.
                
                # Try to add one more element after the swap
                candidates_after_swap = []
                for x in ALL_CANDIDATES:
                    if x not in s_trial:
                        if can_add_mask(s_trial, mask_trial, x):
                            candidates_after_swap.append(x)
                            
                if candidates_after_swap:
                    x_add2 = random.choice(candidates_after_swap)
                    s_trial, mask_trial = add_element(s_trial, mask_trial, x_add2)
                    
                    if len(s_trial) > len(s):
                        s = s_trial
                        mask = mask_trial
                        improved = True
                        no_improve_count = 0
                        if len(s) > best_size:
                            best_size = len(s)
                            best_set = s[:]
                            best_mask = mask
                        continue
                    else:
                        # If no immediate gain, reject swap to avoid drift
                        pass
                else:
                    # No immediate gain, reject swap
                    pass
            else:
                # No candidate to add after removal, reject swap
                pass
            
            # 3. Try Double Swap (Remove 2, Add 2)
            if len(removable) >= 2:
                r1, r2 = random.sample(removable, 2)
                s_trial = s[:]
                mask_trial = mask
                s_trial, mask_trial = remove_element(s_trial, mask_trial, r1)
                s_trial, mask_trial = remove_element(s_trial, mask_trial, r2)
                
                # Try to add 2 elements
                added_count = 0
                added_elems = []
                # We need to find 2 elements that can be added sequentially
                # To be fast, just iterate and try to add up to 2
                # This is O(N^2) worst case for the inner loop, but N=284 is small.
                
                # Optimization: Only try to add if we can find at least 2 compatible additions.
                # Simple approach: Shuffle candidates, try to add.
                candidates = [x for x in ALL_CANDIDATES if x not in s_trial and x not in (r1, r2)]
                random.shuffle(candidates)
                
                for x in candidates:
                    if added_count >= 2:
                        break
                    if can_add_mask(s_trial, mask_trial, x):
                        s_trial, mask_trial = add_element(s_trial, mask_trial, x)
                        added_count += 1
                        added_elems.append(x)
                        
                if added_count == 2:
                    # Size is same. Do we accept?
                    # Again, check if we can add a 3rd?
                    candidates_after = [x for x in ALL_CANDIDATES if x not in s_trial]
                    random.shuffle(candidates_after)
                    for x in candidates_after:
                        if can_add_mask(s_trial, mask_trial, x):
                            s_trial, mask_trial = add_element(s_trial, mask_trial, x)
                            if len(s_trial) > len(s):
                                s = s_trial
                                mask = mask_trial
                                improved = True
                                no_improve_count = 0
                                if len(s) > best_size:
                                    best_size = len(s)
                                    best_set = s[:]
                                    best_mask = mask
                                break
                            else:
                                # No gain, reject
                                break
                    else:
                        # No gain, reject
                        pass
                else:
                    # Failed to add 2, reject
                    pass

            if not improved:
                no_improve_count += 1
                
        # End of local search phase
        # If we haven't improved in a long time, force a restart from scratch in the next iteration
        # (This is handled by the 10% restart chance at the top of the loop)

    # Final Validation
    s_final = sorted(set(best_set))
    
    # Ensure prescribed elements are present (they should be, but just in case)
    for p in prescribed:
        if p not in s_final:
            s_final.append(p)
            s_final = sorted(set(s_final))
            
    # Validate Sidon property
    mask_final = 0
    valid = True
    for i, a in enumerate(s_final):
        for b in s_final[i:]:
            if (mask_final >> (a + b)) & 1:
                valid = False
                break
            mask_final |= (1 << (a + b))
        if not valid:
            break

    if not valid:
        # Fallback to a simple valid greedy set
        s_final = sorted(prescribed)
        mask_final = init_mask(s_final)
        for x in range(12, 285):
            if can_add_mask(s_final, mask_final, x):
                s_final, mask_final = add_element(s_final, mask_final, x)
        s_final = sorted(set(s_final))

    return s_final

