def construct():
    start = time.time()
    deadline = start + 90.0 - DEADLINE_MARGIN

    best_words = None
    best_len = 0

    try:
        # Start with RM seed
        words = _seed_words()
        
        # Build initial forbidden mask
        forbidden = _build_forbidden_mask(words)
        
        # Run local search (which includes greedy insertion)
        # The local search will iterate until no more words can be added.
        w = _local_search(words, forbidden, deadline)
        
        if len(w) > best_len:
            best_len = len(w)
            best_words = w
            
    except Exception:
        pass

    if best_words is None:
        best_words = _seed_words()

    # Deduplicate and validate
    seen = set()
    out = []
    for w in best_words:
        if w not in seen and 0 <= w < TOTAL:
            seen.add(w)
            out.append(w)
    if not out:
        out = _seed_words()

    return out
