import time

def construct(k, g):
    """
    Constructs a k-regular graph with girth at least g.
    Uses the LW graph construction for the (4,10)-cage (n=320).
    """
    # Direct construction of the (4,10)-cage using the algebraic rule
    # This is the smallest known graph for k=4, g=10.
    
    q = k
    if q != 4:
        # Fallback for other parameters, though task is specific to (4,10)
        # Using a simple random regular graph generator with validation
        # But for this task, we assume k=4, g=10.
        raise NotImplementedError("Only k=4, g=10 is optimized")

    d = 5 # g=10 -> d=5
    
    table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
    add = lambda x, y: x ^ y
    sub = lambda x, y: x ^ y
    mul = lambda x, y: table[x][y]
    
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    
    return len(order), edges
