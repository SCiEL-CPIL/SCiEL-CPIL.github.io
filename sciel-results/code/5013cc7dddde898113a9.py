import math
import numpy as np
import time
from scipy.optimize import minimize

N = 11
START_TIME = time.time()
TIME_LIMIT = 150.0
SAFETY_MARGIN = 5.0
EPS = 1e-9

# Pre-compute hexagon vertices for a unit hexagon centered at origin
# Flat-top orientation: vertices at 0, 60, 120, 180, 240, 300 degrees
HEX_VERTS = np.array([
    [1.0, 0.0],
    [0.5, math.sqrt(3)/2],
    [-0.5, math.sqrt(3)/2],
    [-1.0, 0.0],
    [-0.5, -math.sqrt(3)/2],
    [0.5, -math.sqrt(3)/2]
])

def get_outer_side_length(positions, center, rotation_deg):
    """
    Calculate the minimum side length S of an outer hexagon with given center and rotation
    that contains all inner hexagons.
    """
    rot = math.radians(rotation_deg)
    # Outward normals for the outer hexagon
    # For a flat-top hexagon, normals are at 30, 90, 150, 210, 270, 330 degrees
    normals = []
    for i in range(6):
        angle = rot + math.pi/6 + i * math.pi / 3
        normals.append(np.array([math.cos(angle), math.sin(angle)]))
    normals = np.array(normals)
    
    c = np.array(center)
    max_proj = 0.0
    
    # Vectorized projection calculation
    # positions: (N, 2)
    # verts: (6, 2)
    # We need max over all i, v of | n . (p_i + v - c) |
    
    # Compute vectors from center to all vertices of all inner hexagons
    # p_i + v - c = (p_i - c) + v
    # Let D = positions - c (N, 2)
    # We want max | n . (D_i + v_j) |
    
    # To be safe and fast, we can just iterate over the 6 normals
    # and compute projections for all vertices.
    
    # Total vertices = N * 6
    # Let's construct the full array of vertex positions relative to center
    # This might be memory heavy if N is large, but N=11 is small.
    
    # Alternative: Loop over normals, compute dot products.
    for n in normals:
        # proj = n . (p_i + v_j - c)
        # = n . (p_i - c) + n . v_j
        # n . (p_i - c) is (N,)
        # n . v_j is (6,)
        # We need max of (n . (p_i - c))_i + (n . v_j)_j
        
        # Actually, max_{i,j} (A_i + B_j) = max(A) + max(B)
        # But we need absolute value: max_{i,j} | A_i + B_j |
        # This is max( max(A+B), -min(A+B) )
        # max(A+B) = max(A) + max(B)
        # min(A+B) = min(A) + min(B)
        
        a = positions @ n # (N,)
        b = HEX_VERTS @ n # (6,)
        
        max_sum = np.max(a) + np.max(b)
        min_sum = np.min(a) + np.min(b)
        
        curr_max_proj = max(abs(max_sum), abs(min_sum))
        if curr_max_proj > max_proj:
            max_proj = curr_max_proj
            
    apothem_factor = math.sqrt(3) / 2.0
    return max_proj / apothem_factor

def construct():
    best_score = float('inf')
    best_params = None
    
    # Generate initial candidates based on honeycomb lattice structures
    # We want to pack 11 hexagons.
    # A central hexagon + 6 neighbors = 7.
    # Remaining 4 can be placed in the next ring.
    
    candidates = []
    
    # Candidate 1: Central + 6 neighbors + 4 from next ring (symmetric)
    # Positions in triangular lattice with spacing 2
    # Center: (0,0)
    # Ring 1: (2,0), (1, sqrt3), (-1, sqrt3), (-2,0), (-1, -sqrt3), (1, -sqrt3)
    # Ring 2: (4,0), (3, sqrt3), (0, 2*sqrt3), (-3, sqrt3), (-4,0), (-3, -sqrt3), (0, -2*sqrt3), (3, -sqrt3)
    
    base = [[0.0, 0.0]]
    for k in range(6):
        angle = math.pi/3 * k
        base.append([2.0 * math.cos(angle), 2.0 * math.sin(angle)])
        
    # Add 4 more from Ring 2. To keep compact, pick 4 adjacent ones?
    # Or spread them out?
    # Let's try a few variations.
    
    # Variation 1: 4 consecutive in ring 2
    ring2_angles = [0, 60, 120, 180, 240, 300]
    # Actually ring 2 angles are offset?
    # Distance from center is 4? No, distance to ring 2 vertices is 4?
    # Distance between centers in honeycomb is 2.
    # Ring 1 centers are at dist 2.
    # Ring 2 centers are at dist 4?
    # Let's check: (2,0) is ring 1. (4,0) is ring 2. Distance 2. Correct.
    # (1, sqrt3) is ring 1. (3, sqrt3) is ring 2. Distance 2. Correct.
    # (0, 2*sqrt3) is ring 2?
    # Distance from (1, sqrt3) to (0, 2*sqrt3): sqrt(1^2 + (-sqrt3)^2) = 2. Correct.
    
    ring2_pos = []
    for k in range(6):
        angle = math.pi/3 * k
        ring2_pos.append([4.0 * math.cos(angle), 4.0 * math.sin(angle)])
        angle2 = math.pi/3 * k + math.pi/6
        # Wait, the honeycomb lattice points are:
        # (2a, 0), (a, a*sqrt3), ...
        # Let's just use the explicit coordinates.
        # (4,0), (2, 2*sqrt3), (-2, 2*sqrt3), (-4,0), (-2, -2*sqrt3), (2, -2*sqrt3)
        # Also (0, 2*sqrt3*sqrt(3)/2)? No.
        # The lattice is generated by vectors (2,0) and (1, sqrt3).
        # Points: i*(2,0) + j*(1, sqrt3)
        # (0,0)
        # (2,0), (-2,0), (1, sqrt3), (-1, -sqrt3), (-1, sqrt3), (1, -sqrt3)
        # (4,0), (3, sqrt3), (0, 2*sqrt3), (-3, sqrt3), (-4,0), (-3, -sqrt3), (0, -2*sqrt3), (3, -sqrt3)
        
    ring2_coords = [
        [4.0, 0.0],
        [3.0, math.sqrt(3)],
        [0.0, 2.0*math.sqrt(3)],
        [-3.0, math.sqrt(3)],
        [-4.0, 0.0],
        [-3.0, -math.sqrt(3)],
        [0.0, -2.0*math.sqrt(3)],
        [3.0, -math.sqrt(3)]
    ]
    
    # Pick 4 from ring2_coords
    # Try different sets of 4
    import itertools
    for combo in itertools.combinations(range(8), 4):
        pos = base + [ring2_coords[i] for i in combo]
        candidates.append(pos)
        
    # Also try random perturbations of the best few
    # But first, let's just run optimization on the distinct structural candidates.
    # To save time, limit the number of candidates.
    # There are C(8,4) = 70 candidates.
    # We can't optimize all 70 in 150s if each takes 1s.
    # Let's pick a diverse subset.
    
    # Subset:
    # 1. (0, 2, 4, 6) - symmetric top/bottom?
    # 2. (0, 1, 2, 3) - consecutive
    # 3. (0, 2, 4, 5)
    # 4. (0, 1, 2, 5)
    
    selected_indices = [
        (0, 2, 4, 6),
        (0, 1, 2, 3),
        (0, 1, 2, 5),
        (0, 2, 4, 7),
        (1, 3, 5, 7)
    ]
    
    for idxs in selected_indices:
        pos = base + [ring2_coords[i] for i in idxs]
        candidates.append(pos)
        
    # Deduplicate candidates (approximate)
    unique_candidates = []
    for c in candidates:
        is_dup = False
        for uc in unique_candidates:
            # Check if centers are close
            diff = np.array(c) - np.array(uc)
            if np.max(np.abs(diff)) < 0.1:
                is_dup = True
                break
        if not is_dup:
            unique_candidates.append(c)
            
    candidates = unique_candidates
    
    # Optimization Function
    def objective(params):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf')
            
        positions = np.array(params[:2*N]).reshape(N, 2)
        center = params[2*N:2*N+2]
        rot_deg = params[2*N+2]
        
        # Constraint: Non-overlap
        # Distance between any two centers >= 2
        # We use a penalty in the objective for SLSQP, or constraints.
        # SLSQP supports constraints.
        # But defining 55 constraints is heavy.
        # Let's use a penalty term for speed, but ensure it's strong.
        
        penalty = 0.0
        for i in range(N):
            for j in range(i+1, N):
                dist = np.linalg.norm(positions[i] - positions[j])
                if dist < 2.0:
                    penalty += (2.0 - dist) ** 2 * 10.0
                    
        S = get_outer_side_length(positions, center, rot_deg)
        
        return S + penalty
        
    # Constraints for SLSQP: g_i(x) >= 0
    # dist(i,j) - 2 >= 0
    
    def make_constraint(i, j):
        def constraint(params):
            p_i = params[2*i:2*i+2]
            p_j = params[2*j:2*j+2]
            dist = np.linalg.norm(p_i - p_j)
            return dist - 2.0
        return constraint
        
    constraints = []
    for i in range(N):
        for j in range(i+1, N):
            constraints.append({'type': 'ineq', 'fun': make_constraint(i, j)})
            
    # Optimize each candidate
    for c in candidates:
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            break
            
        init_pos = np.array(c).flatten()
        com = np.mean(np.array(c), axis=0)
        init_params = np.append(init_pos, com)
        init_params = np.append(init_params, 0.0)
        
        # Try a few rotations for the outer hexagon
        for rot_init in [0.0, 30.0, 15.0]:
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
                
            init_params[-1] = rot_init
            
            try:
                res = minimize(objective, init_params, method='SLSQP',
                               constraints=constraints,
                               options={'maxiter': 100, 'ftol': 1e-8})
                if res.fun < best_score:
                    # Verify validity
                    positions = np.array(res.x[:2*N]).reshape(N, 2)
                    center = res.x[2*N:2*N+2]
                    rot_deg = res.x[2*N+2]
                    
                    # Check disjointness strictly
                    valid = True
                    for i in range(N):
                        for j in range(i+1, N):
                            dist = np.linalg.norm(positions[i] - positions[j])
                            if dist < 2.0 - 1e-6:
                                valid = False
                                break
                        if not valid: break
                            
                    if valid:
                        S = get_outer_side_length(positions, center, rot_deg)
                        if S < best_score:
                            best_score = S
                            best_params = res.x
            except Exception as e:
                pass

    if best_params is None:
        # Fallback: Return the initial honeycomb configuration
        positions = np.array(candidates[0])
        com = np.mean(positions, axis=0)
        S = get_outer_side_length(positions, com, 0.0)
        inner = []
        for p in positions:
            inner.append([float(p[0]), float(p[1]), 0.0])
        return inner, [float(com[0]), float(com[1])], float(S), 0.0

    positions = np.array(best_params[:2*N]).reshape(N, 2)
    center = best_params[2*N:2*N+2]
    rot_deg = best_params[2*N+2]
    
    inner = []
    for p in positions:
        inner.append([float(p[0]), float(p[1]), 0.0])
        
    return inner, [float(center[0]), float(center[1])], float(best_score), float(rot_deg)

if __name__ == "__main__":
    construct()
