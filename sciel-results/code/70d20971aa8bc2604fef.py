import time

def construct():
    start_time = time.time()
    deadline = start_time + 110
    
    n, m, p = 2, 4, 8
    rank = 56
    
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Define Strassen products
    # Each product: (left, right, c_contrib)
    # left[j] = list of (a_row, a_col, coeff) for the j-th element of the 1x2 left vector
    # right[j*4+k] = list of (b_row, b_col, coeff) for the (j,k)-th element of the 2x4 right matrix
    # c_contrib[k] = list of (c_row, c_col, coeff) for the k-th column of the 1x4 result
    
    products = [
        # M1 = (A00+A11)*(B00+B11)
        {
            'left': [
                [(0,0,1), (1,2,1)],
                [(0,1,1), (1,3,1)],
            ],
            'right': [
                [(0,0,1), (2,4,1)],
                [(0,1,1), (2,5,1)],
                [(0,2,1), (2,6,1)],
                [(0,3,1), (2,7,1)],
                [(1,0,1), (3,4,1)],
                [(1,1,1), (3,5,1)],
                [(1,2,1), (3,6,1)],
                [(1,3,1), (3,7,1)],
            ],
            'c_contrib': [
                [(0,0,1), (1,4,1)],
                [(0,1,1), (1,5,1)],
                [(0,2,1), (1,6,1)],
                [(0,3,1), (1,7,1)],
            ]
        },
        # M2 = (A10+A11)*B00
        {
            'left': [
                [(1,0,1), (1,2,1)],
                [(1,1,1), (1,3,1)],
            ],
            'right': [
                [(0,0,1)],
                [(0,1,1)],
                [(0,2,1)],
                [(0,3,1)],
                [(1,0,1)],
                [(1,1,1)],
                [(1,2,1)],
                [(1,3,1)],
            ],
            'c_contrib': [
                [(1,0,1), (1,4,-1)],
                [(1,1,1), (1,5,-1)],
                [(1,2,1), (1,6,-1)],
                [(1,3,1), (1,7,-1)],
            ]
        },
        # M3 = A00*(B01-B11)
        {
            'left': [
                [(0,0,1)],
                [(0,1,1)],
            ],
            'right': [
                [(0,4,1), (2,4,-1)],
                [(0,5,1), (2,5,-1)],
                [(0,6,1), (2,6,-1)],
                [(0,7,1), (2,7,-1)],
                [(1,4,1), (3,4,-1)],
                [(1,5,1), (3,5,-1)],
                [(1,6,1), (3,6,-1)],
                [(1,7,1), (3,7,-1)],
            ],
            'c_contrib': [
                [(0,4,1), (1,4,1)],
                [(0,5,1), (1,5,1)],
                [(0,6,1), (1,6,1)],
                [(0,7,1), (1,7,1)],
            ]
        },
        # M4 = A11*(B10-B00)
        {
            'left': [
                [(1,2,1)],
                [(1,3,1)],
            ],
            'right': [
                [(2,0,1), (0,0,-1)],
                [(2,1,1), (0,1,-1)],
                [(2,2,1), (0,2,-1)],
                [(2,3,1), (0,3,-1)],
                [(3,0,1), (1,0,-1)],
                [(3,1,1), (1,1,-1)],
                [(3,2,1), (1,2,-1)],
                [(3,3,1), (1,3,-1)],
            ],
            'c_contrib': [
                [(0,0,1), (1,0,1)],
                [(0,1,1), (1,1,1)],
                [(0,2,1), (1,2,1)],
                [(0,3,1), (1,3,1)],
            ]
        },
        # M5 = (A00+A01)*B11
        {
            'left': [
                [(0,0,1), (0,2,1)],
                [(0,1,1), (0,3,1)],
            ],
            'right': [
                [(2,4,1)],
                [(2,5,1)],
                [(2,6,1)],
                [(2,7,1)],
                [(3,4,1)],
                [(3,5,1)],
                [(3,6,1)],
                [(3,7,1)],
            ],
            'c_contrib': [
                [(0,0,-1), (0,4,1)],
                [(0,1,-1), (0,5,1)],
                [(0,2,-1), (0,6,1)],
                [(0,3,-1), (0,7,1)],
            ]
        },
        # M6 = (A10-A00)*(B00+B01)
        {
            'left': [
                [(1,0,1), (0,0,-1)],
                [(1,1,1), (0,1,-1)],
            ],
            'right': [
                [(0,0,1), (0,4,1)],
                [(0,1,1), (0,5,1)],
                [(0,2,1), (0,6,1)],
                [(0,3,1), (0,7,1)],
                [(1,0,1), (1,4,1)],
                [(1,1,1), (1,5,1)],
                [(1,2,1), (1,6,1)],
                [(1,3,1), (1,7,1)],
            ],
            'c_contrib': [
                [(1,4,1)],
                [(1,5,1)],
                [(1,6,1)],
                [(1,7,1)],
            ]
        },
        # M7 = (A01-A11)*(B10+B11)
        {
            'left': [
                [(0,2,1), (1,2,-1)],
                [(0,3,1), (1,3,-1)],
            ],
            'right': [
                [(2,0,1), (2,4,1)],
                [(2,1,1), (2,5,1)],
                [(2,2,1), (2,6,1)],
                [(2,3,1), (2,7,1)],
                [(3,0,1), (3,4,1)],
                [(3,1,1), (3,5,1)],
                [(3,2,1), (3,6,1)],
                [(3,3,1), (3,7,1)],
            ],
            'c_contrib': [
                [(0,0,1)],
                [(0,1,1)],
                [(0,2,1)],
                [(0,3,1)],
            ]
        },
    ]
    
    col = 0
    for prod in products:
        for j in range(2):
            for k in range(4):
                if time.time() > deadline:
                    return {"U": U, "V": V, "W": W}
                for (a_row, a_col, coeff) in prod['left'][j]:
                    U[a_row * m + a_col][col] += coeff
                for (b_row, b_col, coeff) in prod['right'][j * 4 + k]:
                    V[b_row * p + b_col][col] += coeff
                for (c_row, c_col, coeff) in prod['c_contrib'][k]:
                    W[c_col * n + c_row][col] += coeff
                col += 1
    
    return {"U": U, "V": V, "W": W}
