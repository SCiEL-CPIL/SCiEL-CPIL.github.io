import time
import itertools

def load(boxes, container):
    W, H, D = container
    n = len(boxes)
    if n == 0:
        return []
    
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin
    
    # Sort boxes by volume descending to place large items first
    # We need to keep track of original indices to return correct placements
    box_indices = list(range(n))
    box_indices.sort(key=lambda i: boxes[i][0] * boxes[i][1] * boxes[i][2], reverse=True)
    
    placements = [None] * n  # Store results for each original box index
    placed_boxes = []  # List of (x, y, z, w, h, d) for placed boxes
    extreme_points = [(0, 0, 0)]
    
    def get_rotations(w, h, d):
        # Generate unique rotations
        rots = set()
        rots.add((w, h, d))
        rots.add((w, d, h))
        rots.add((h, w, d))
        rots.add((h, d, w))
        rots.add((d, w, h))
        rots.add((d, h, w))
        return list(rots)
    
    def check_overlap(x, y, z, w, h, d):
        for px, py, pz, pw, ph, pd in placed_boxes:
            # Check if intervals overlap in all 3 dimensions
            if not (x + w <= px or px + pw <= x or
                    y + h <= py or py + ph <= y or
                    z + d <= pz or pz + pd <= z):
                return True
        return False
    
    for idx in box_indices:
        if time.time() > deadline:
            break
            
        bw, bh, bd = boxes[idx]
        rotations = get_rotations(bw, bh, bd)
        
        best_pos = None
        best_rot = None
        best_score = float('inf')
        
        # Try all candidate points
        # We iterate over a copy of extreme_points because we might update it later, 
        # but for this box, we pick the best from the current set.
        for px, py, pz in extreme_points:
            for rw, rh, rd in rotations:
                # Check bounds
                if px + rw > W or py + rh > H or pz + rd > D:
                    continue
                
                # Check overlap
                if check_overlap(px, py, pz, rw, rh, rd):
                    continue
                
                # Score: Minimize distance from origin (compactness)
                # Using x+y+z is a common heuristic. 
                # Alternative: minimize (x*H*D + y*W*D + z*W*H) to weight larger dimensions?
                # Let's stick to x+y+z for simplicity and speed.
                score = px + py + pz
                
                if score < best_score:
                    best_score = score
                    best_pos = (px, py, pz)
                    best_rot = (rw, rh, rd)
        
        if best_pos is not None:
            bx, by, bz = best_pos
            bw, bh, bd = best_rot
            placements[idx] = (0, bx, by, bz, bw, bh, bd)
            placed_boxes.append((bx, by, bz, bw, bh, bd))
            
            # Update extreme points
            # Add new potential extreme points generated by this placement
            new_points = [
                (bx + bw, by, bz),
                (bx, by + bh, bz),
                (bx, by, bz + bd),
                (bx + bw, by + bh, bz),
                (bx + bw, by, bz + bd),
                (bx, by + bh, bz + bd),
                (bx + bw, by + bh, bz + bd)
            ]
            
            for np in new_points:
                # Only add if it's within bounds and not already in the set
                # We don't strictly need to check if it's "free" here because 
                # check_overlap will filter it out in future iterations if it's covered.
                # However, to keep the set small, we can check if it's strictly inside another box?
                # That's expensive. Just add and let the overlap check handle it.
                if np not in extreme_points:
                    extreme_points.append(np)
        else:
            placements[idx] = (-1, 0, 0, 0, bw, bh, bd)
            
    # Fill any remaining None slots (if loop broke early due to time)
    for i in range(n):
        if placements[i] is None:
            w, h, d = boxes[i]
            placements[i] = (-1, 0, 0, 0, w, h, d)
            
    return placements
