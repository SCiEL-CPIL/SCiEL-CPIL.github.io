def _local_search_fast(colors, quads, pents, time_budget):
    """Optimized local search."""
    colors = np.array(colors, dtype=np.int8)
    m = len(colors)
    n_quads = len(quads)
    n_pents = len(pents)
    
    # Precompute affected quads/pents for each triple
    # This is expensive to build, so we do it once per n.
    # For speed in this function, we assume quads/pents are lists of indices.
    
    # Incidence matrices
    quad_incidence = np.zeros((n_quads, m), dtype=np.int8)
    for qi, idxs in enumerate(quads):
        for i in idxs:
            quad_incidence[qi, i] = 1
            
    pent_incidence = np.zeros((n_pents, m), dtype=np.int8)
    for pi, idxs in enumerate(pents):
        for i in idxs:
            pent_incidence[pi, i] = 1
            
    quad_red = np.sum(quad_incidence * (colors == 0), axis=1).astype(np.int8)
    pent_blue = np.sum(pent_incidence * (colors == 1), axis=1).astype(np.int8)
    red_k4 = int(np.sum(quad_red == 4))
    blue_k5 = int(np.sum(pent_blue == 10))
    total_v = red_k4 + blue_k5
    
    if total_v == 0:
        return colors.tolist(), 0, 0

    t_end = time.time() + time_budget
    order = list(range(m))
    random.shuffle(order)
    
    while time.time() < t_end:
        improved = False
        for t in order:
            if time.time() >= t_end:
                break
            cur = colors[t]
            new = 1 - cur
            delta_red = 1 if new == 0 else -1
            delta_blue = 1 if new == 1 else -1
            
            # Find affected quads
            # Using precomputed incidence is fast if we use numpy where
            # But loop is okay if n is small
            affected_quads = np.where(quad_incidence[:, t] == 1)[0]
            affected_pents = np.where(pent_incidence[:, t] == 1)[0]
            
            dq = 0
            for qi in affected_quads:
                old = quad_red[qi]
                new_q = old + delta_red
                if old == 4: dq -= 1
                if new_q == 4: dq += 1
                
            dp = 0
            for pi in affected_pents:
                old = pent_blue[pi]
                new_p = old + delta_blue
                if old == 10: dp -= 1
                if new_p == 10: dp += 1
                
            if dq + dp < 0:
                colors[t] = new
                for qi in affected_quads:
                    quad_red[qi] += delta_red
                for pi in affected_pents:
                    pent_blue[pi] += delta_blue
                red_k4 += dq
                blue_k5 += dp
                improved = True
                
        if not improved:
            # Random restart within the current coloring? Or break?
            # If no improvement, shuffle and try again to escape local minima
            random.shuffle(order)
            # Optional: random kick
            if random.random() < 0.1:
                kick_idx = random.choice(order)
                colors[kick_idx] = 1 - colors[kick_idx]
                # Update counts
                delta_red = 1 if colors[kick_idx] == 0 else -1
                delta_blue = 1 if colors[kick_idx] == 1 else -1
                for qi in np.where(quad_incidence[:, kick_idx] == 1)[0]:
                    quad_red[qi] += delta_red
                for pi in np.where(pent_incidence[:, kick_idx] == 1)[0]:
                    pent_blue[pi] += delta_blue
                red_k4 = int(np.sum(quad_red == 4))
                blue_k5 = int(np.sum(pent_blue == 10))

    return colors.tolist(), red_k4, blue_k5

def construct():
    deadline = _START + _DEADLINE - 2.0
    
    # Fallback solution: n=9 from seed logic or just a small valid one
    # Let's generate a small valid one quickly if search fails
    # n=9: (a+b+c)%3==0 -> Red? 
    # Check: 0,1,2 -> 3%3=0 Red. 0,1,3 -> 4%3=1 Blue.
    # This is a known valid coloring for n=9? 
    # Actually, let's just try to find n=17 quickly as a baseline, then push to 32.
    
    best_n = 9
    best_colors = [0 if (a + b + c) % 3 == 0 else 1 for a, b, c in combinations(range(9), 3)]
    
    # Try to improve to n=17 first (quick win if seed fails? Seed gets 17)
    # Then try n=32.
    
    targets = [17, 24, 32, 34]
    
    for n in targets:
        if time.time() >= deadline:
            break
        
        triples, idx, m = _triples_to_idx(n)
        quads = _build_quads(n, triples)
        pents = _build_pents(n, triples)
        
        # Time budget per n
        # n=17: 10s
        # n=24: 20s
        # n=32: 40s
        # n=34: 30s
        if n <= 17:
            budget = 10.0
        elif n <= 24:
            budget = 20.0
        elif n <= 32:
            budget = 40.0
        else:
            budget = 30.0
            
        remaining = deadline - time.time()
        if remaining < budget:
            budget = remaining * 0.9
        if budget < 5.0:
            break
            
        # Try multiple restarts
        found = False
        attempts = 0
        max_attempts = 100
        while time.time() < deadline and not found and attempts < max_attempts:
            attempts += 1
            # Adaptive p_red
            # For larger n, we need fewer reds to avoid K4, but not too few to avoid K5?
            # K5 blue requires 10 blue triples.
            # If p_red is low, p_blue is high.
            # Let's sample p_red from [0.05, 0.15]
            p_red = random.uniform(0.05, 0.15)
            colors = (np.random.rand(m) < p_red).astype(np.int8).tolist()
            
            # Local search
            ls_time = min(2.0, (deadline - time.time()) * 0.5) # Shorter searches per attempt
            colors, r4, b5 = _local_search_fast(colors, quads, pents, ls_time)
            
            if r4 == 0 and b5 == 0:
                best_n = n
                best_colors = colors
                found = True
                break
                
    return {'n': best_n, 'colors': best_colors}
