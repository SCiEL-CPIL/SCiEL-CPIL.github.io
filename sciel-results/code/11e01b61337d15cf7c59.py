import time
import random

N = 256

def construct():
    start_time = time.time()
    deadline = start_time + 25.0
    
    best_size = N + 1
    best_set = None
    
    def run_greedy():
        S = []
        used_sums = set()
        candidates = list(range(1, N + 1))
        
        while True:
            valid_candidates = []
            for x in candidates:
                # Check if x can be added
                is_valid = True
                for s in S:
                    if x + s in used_sums:
                        is_valid = False
                        break
                if is_valid and 2 * x in used_sums:
                    is_valid = False
                if is_valid:
                    valid_candidates.append(x)
            
            if not valid_candidates:
                break
            
            # Find x with max blocking power
            best_x = None
            max_blocks = -1
            best_ties = []
            
            for x in valid_candidates:
                # Calculate sums generated by adding x
                new_sums = set()
                for s in S:
                    new_sums.add(x + s)
                new_sums.add(2 * x)
                
                # Check how many other valid candidates become invalid
                blocks = 0
                for y in valid_candidates:
                    if y == x:
                        continue
                    # Check if y is still valid with x added
                    # y is valid if y+s not in (used_sums U new_sums) for all s in S U {x}
                    # This is slightly more expensive. 
                    # Optimization: y becomes invalid if any y+s' is in new_sums (where s' in S U {x}) 
                    # OR y+s is in used_sums (which was already false since y was valid)
                    # So we just need to check if any sum involving y and (S U {x}) conflicts with (used_sums U new_sums)
                    
                    # Simpler check:
                    # Can y be added to S + [x]?
                    temp_valid = True
                    for s in S:
                        if y + s in new_sums: # Conflict with new sums from x
                            temp_valid = False
                            break
                        # Note: y+s in used_sums is already false
                    if temp_valid:
                        if y + x in used_sums or y + x in new_sums: # y+x is in new_sums
                            # Wait, y+x is in new_sums by definition if x is added? No.
                            # new_sums contains x+s for s in S, and 2x.
                            # It does NOT contain y+x unless y is in S. But y is not in S.
                            # So y+x is a NEW sum that would be created if y were added.
                            # We need to check if y+x conflicts with existing sums (used_sums) or sums created by x (new_sums).
                            # If y+x is in used_sums -> conflict (but y was valid, so y+x not in used_sums? 
                            # Wait. y valid means y+s not in used_sums for s in S.
                            # Does y valid imply y+x not in used_sums? No, x is not in S yet.
                            # So we must check y+x against used_sums.
                            pass
                            
                    # Let's just use the can_add logic for clarity, it's fast enough.
                    if not can_add(y, S + [x], used_sums.union(new_sums)):
                        blocks += 1
                
                if blocks > max_blocks:
                    max_blocks = blocks
                    best_x = x
                    best_ties = [x]
                elif blocks == max_blocks:
                    best_ties.append(x)
            
            chosen_x = random.choice(best_ties)
            
            S.append(chosen_x)
            # Update used_sums
            for s in S[:-1]:
                used_sums.add(chosen_x + s)
            used_sums.add(2 * chosen_x)
            
            candidates.remove(chosen_x)
            
        return S

    # Helper for clarity in the above loop (though inlined above for speed, 
    # let's stick to the inlined version but ensure correctness)
    def can_add(x, S, used_sums):
        for s in S:
            if x + s in used_sums:
                return False
        if 2 * x in used_sums:
            return False
        return True

    while time.time() < deadline:
        S = run_greedy()
        if len(S) < best_size:
            best_size = len(S)
            best_set = S[:]
        
        if best_size <= 16:
            break

    if best_set is None:
        # Fallback
        S = []
        used_sums = set()
        for x in range(1, N + 1):
            if can_add(x, S, used_sums):
                S.append(x)
                for s in S[:-1]:
                    used_sums.add(x + s)
                used_sums.add(2 * x)
        return S

    return best_set
