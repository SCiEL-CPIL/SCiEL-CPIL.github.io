_START = time.time()
_LIMIT = 150.0
_MARGIN = 5.0

def _time_left():
    return _LIMIT - _MARGIN - (time.time() - _START)

def _validate(n, colors):
    """Check that no colour class contains a 4-cycle (C4)."""
    if len(colors) != n * (n - 1) // 2:
        return False
    if any(c < 0 or c > 4 for c in colors):
        return False
    # Build neighbour sets per colour
    nbrs = [[set() for _ in range(n)] for _ in range(5)]
    idx = 0
    for i in range(n):
        for j in range(i + 1, n):
            c = colors[idx]
            nbrs[c][i].add(j)
            nbrs[c][j].add(i)
            idx += 1
    for c in range(5):
        for i in range(n):
            for j in range(i + 1, n):
                if len(nbrs[c][i] & nbrs[c][j]) >= 2:
                    return False
    return True

def _seed_construction():
    """Original K11 seed: split into five Hamiltonian cycles by circular distance 1..5."""
    n = 11
    return {'n': n, 'colors': [min(j - i, n - j + i) - 1 for i in range(n) for j in range(i + 1, n)]}

def _construct_gf25():
    """
    Lazebnik-Woldar style construction for n=26 using GF(25).
    """
    p = 5
    # GF(25) elements as (a, b) = a + b*alpha, alpha^2 = 3
    elements = [(a, b) for a in range(p) for b in range(p)]
    
    def gf_mul(x, y):
        a1, b1 = x
        a2, b2 = y
        a = (a1 * a2 + 3 * b1 * b2) % p
        b = (a1 * b2 + a2 * b1) % p
        return (a, b)
    
    def gf_pow(x, n):
        result = (1, 0)
        base = x
        while n > 0:
            if n % 2 == 1:
                result = gf_mul(result, base)
            base = gf_mul(base, base)
            n //= 2
        return result
    
    # Find primitive element (order 24)
    primitive = None
    for elem in elements:
        if elem == (0, 0):
            continue
        # Check order 24
        if gf_pow(elem, 24) == (1, 0):
            # Check it's not a smaller divisor (1, 2, 3, 4, 6, 8, 12)
            is_primitive = True
            for d in [1, 2, 3, 4, 6, 8, 12]:
                if gf_pow(elem, d) == (1, 0):
                    is_primitive = False
                    break
            if is_primitive:
                primitive = elem
                break
                
    if primitive is None:
        return None

    # Generate powers
    powers = []
    current = (1, 0)
    for _ in range(24):
        powers.append(current)
        current = gf_mul(current, primitive)
        
    log_map = {elem: i for i, elem in enumerate(powers)}
    
    # Subgroup H of order 6: generated by g^4
    # Cosets are determined by log(x) mod 4
    # Coset 0: log(x) % 4 == 0
    # Coset 1: log(x) % 4 == 1
    # Coset 2: log(x) % 4 == 2
    # Coset 3: log(x) % 4 == 3
    
    n = 26
    colors = []
    
    # Vertex mapping: 0..24 are elements, 25 is infinity
    # We need to assign colors to all pairs (i, j) with i < j
    
    for i in range(n):
        for j in range(i + 1, n):
            if i == 25 or j == 25:
                # Edge with infinity
                other = j if i == 25 else i
                if other == 0:
                    colors.append(0)
                else:
                    # Color based on coset of the element
                    c = log_map[elements[other]] % 4
                    colors.append(c + 1) # Colors 1..4
            else:
                # Both in GF(25)
                elem_i = elements[i]
                elem_j = elements[j]
                if elem_i == (0, 0) or elem_j == (0, 0):
                    colors.append(0)
                else:
                    # Ratio elem_i / elem_j
                    # log(elem_i) - log(elem_j) mod 24
                    # Coset determined by (log_i - log_j) mod 4
                    log_i = log_map[elem_i]
                    log_j = log_map[elem_j]
                    c = (log_i - log_j) % 4
                    colors.append(c + 1)
                    
    return {'n': n, 'colors': colors}

