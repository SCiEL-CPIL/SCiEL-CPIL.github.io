"""
Strategy: Simulated Annealing (SA) starting from FCC truncated octahedron.
Rationale: LJ38 is a classic hard case where icosahedral structures trap local searches.
SA allows the system to escape local minima (like the icosahedral funnel) via thermal fluctuations.
We start from the known global minimum topology (FCC) to bias the search, but use SA to
ensure we are in the correct basin before final polishing with L-BFGS.
"""

import numpy as np
import time
import math
from scipy.optimize import minimize

N = 38
DEADLINE = 145.0
START_TIME = time.time()

def lj_energy_vectorized(positions):
    """Compute LJ energy efficiently."""
    # Use full matrix to leverage BLAS
    diff = positions[:, np.newaxis, :] - positions[np.newaxis, :, :]
    r2 = np.sum(diff * diff, axis=-1)
    np.fill_diagonal(r2, 1.0)
    inv_r2 = 1.0 / r2
    inv_r6 = inv_r2 ** 3
    inv_r12 = inv_r6 ** 2
    energy = 4.0 * np.sum(inv_r12 - inv_r6) / 2.0
    return energy

def check_validity(positions, min_dist=0.5):
    """Check minimum distance constraint."""
    diff = positions[:, np.newaxis, :] - positions[np.newaxis, :, :]
    r2 = np.sum(diff * diff, axis=-1)
    # Exclude diagonal
    np.fill_diagonal(r2, 1e10)
    min_r2 = np.min(r2)
    return min_r2 >= (min_dist * min_dist)

def make_fcc_truncated_octahedron():
    """
    Generate the 38-atom FCC truncated octahedron.
    This is the putative global minimum structure.
    """
    # FCC lattice vectors
    # Basis points in conventional cell: (0,0,0), (0,0.5,0.5), (0.5,0,0.5), (0.5,0.5,0)
    # We generate points in a cubic grid and select the 38 closest to the center.
    # The FCC lattice can be generated by points (i, j, k) where i+j+k is even, scaled by 1/sqrt(2).
    
    points = []
    max_coord = 5
    scale = 1.0 / math.sqrt(2.0)
    
    for i in range(-max_coord, max_coord + 1):
        for j in range(-max_coord, max_coord + 1):
            for k in range(-max_coord, max_coord + 1):
                if (i + j + k) % 2 == 0:
                    # Distance squared from origin in lattice units
                    r2 = i*i + j*j + k*k
                    if r2 <= 30: # Large enough buffer
                        points.append((i * scale, j * scale, k * scale, r2))
    
    # Sort by distance from center
    points.sort(key=lambda x: x[3])
    
    # Take the 38 closest
    selected = [p[:3] for p in points[:38]]
    
    # Center the cluster
    coords = np.array(selected, dtype=float)
    coords -= np.mean(coords, axis=0)
    
    return coords

def relax_ljfg(positions):
    """Local relaxation using L-BFGS."""
    try:
        from science_chemistry import relax
        return relax(positions)
    except ImportError:
        def energy_func(pos):
            pos = pos.reshape(N, 3)
            return lj_energy_vectorized(pos)
        
        # Use L-BFGS-B with tight tolerance
        result = minimize(
            energy_func, 
            positions.flatten(), 
            method='L-BFGS-B', 
            options={'maxiter': 200, 'gtol': 1e-8, 'ftol': 1e-12}
        )
        return result.x.reshape(N, 3)

def simulated_annealing(initial_positions, T0=1.0, T_end=0.001, steps=5000, alpha=0.999):
    """
    Perform Simulated Annealing.
    """
    current_pos = initial_positions.copy()
    current_energy = lj_energy_vectorized(current_pos)
    best_pos = current_pos.copy()
    best_energy = current_energy
    
    rng = np.random.default_rng(42)
    
    # Pre-compute cooling schedule
    # T_k = T0 * alpha^k
    # We want T_end at step 'steps'
    # alpha = (T_end / T0)^(1/steps)
    if steps > 0:
        alpha = (T_end / T0) ** (1.0 / steps)
    
    for step in range(steps):
        if time.time() - START_TIME > DEADLINE - 20:
            break
            
        T = T0 * (alpha ** step)
        
        # Generate perturbation
        # Gaussian noise scaled by sqrt(T)
        noise_scale = math.sqrt(T) * 0.1
        delta = rng.normal(0, noise_scale, size=(N, 3))
        
        new_pos = current_pos + delta
        
        # Check validity (min distance)
        if not check_validity(new_pos):
            continue
            
        new_energy = lj_energy_vectorized(new_pos)
        
        # Metropolis criterion
        if new_energy < current_energy:
            current_pos = new_pos
            current_energy = new_energy
            if new_energy < best_energy:
                best_energy = new_energy
                best_pos = new_pos.copy()
        else:
            # Accept with probability exp(-dE / T)
            delta_E = new_energy - current_energy
            if T > 0:
                prob = math.exp(-delta_E / T)
                if rng.uniform() < prob:
                    current_pos = new_pos
                    current_energy = new_energy
                    if new_energy < best_energy:
                        best_energy = new_energy
                        best_pos = new_pos.copy()
                    
    return best_pos, best_energy

def construct():
    global START_TIME
    START_TIME = time.time()
    
    # 1. Generate initial FCC structure
    try:
        initial_pos = make_fcc_truncated_octahedron()
        if not check_validity(initial_pos):
            # Fallback to random if FCC generation fails validity (unlikely)
            rng = np.random.default_rng(0)
            initial_pos = rng.uniform(-2, 2, size=(N, 3))
    except Exception:
        rng = np.random.default_rng(0)
        initial_pos = rng.uniform(-2, 2, size=(N, 3))
    
    # 2. Run Simulated Annealing
    # We run SA for a significant portion of the time budget.
    # SA is stochastic, so we might run it for a fixed number of steps or until time runs out.
    # Given the 120s limit (and 145s internal deadline), let's aim for ~100s of SA.
    
    best_pos_sa = None
    best_energy_sa = float('inf')
    
    # Run multiple SA chains if time permits, but one long chain is often better for deep funnels.
    # Let's run one long chain.
    
    try:
        # Parameters:
        # T0 = 1.0 (high enough to explore)
        # T_end = 0.001 (low enough to settle)
        # Steps: estimate max steps we can do.
        # Energy calc is vectorized, should be fast. ~1000-5000 steps/sec?
        # Let's try 10000 steps.
        best_pos_sa, best_energy_sa = simulated_annealing(initial_pos, T0=1.0, T_end=0.001, steps=10000)
    except Exception:
        best_pos_sa = initial_pos
        best_energy_sa = lj_energy_vectorized(initial_pos)
    
    # 3. Local Relaxation (L-BFGS) on the best SA result
    # This is crucial to get the precise coordinates for the score.
    
    final_pos = best_pos_sa
    try:
        if time.time() - START_TIME < DEADLINE - 10:
            final_pos = relax_ljfg(best_pos_sa)
            if not check_validity(final_pos):
                final_pos = best_pos_sa
    except Exception:
        pass
    
    # 4. One more polish if time remains
    if time.time() - START_TIME < DEADLINE - 5:
        try:
            polished = relax_ljfg(final_pos)
            if check_validity(polished):
                e1 = lj_energy_vectorized(polished)
                e2 = lj_energy_vectorized(final_pos)
                if e1 < e2:
                    final_pos = polished
        except Exception:
            pass
    
    # Final validity check
    if not check_validity(final_pos):
        # Fallback to initial FCC if something went wrong
        final_pos = initial_pos
        if not check_validity(final_pos):
            # Absolute fallback: random valid points
            rng = np.random.default_rng(123)
            pts = []
            for _ in range(N):
                while True:
                    p = rng.uniform(-2, 2, size=3)
                    if all(np.linalg.norm(p - q) > 0.5 for q in pts):
                        pts.append(p)
                        break
            final_pos = np.array(pts)
            
    return final_pos

