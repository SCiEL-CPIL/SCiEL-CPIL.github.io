    def get_strassen_2x2x2():
        # U: 4x7, V: 4x7, W: 4x7
        # Indices: U[i*2+j], V[j*2+k], W[k*2+i]
        U = [[0]*7 for _ in range(4)]
        V = [[0]*7 for _ in range(4)]
        W = [[0]*7 for _ in range(4)]
        
        # m1 = (a+d)(e+h)
        U[0][0] = 1; U[3][0] = 1 # a, d
        V[0][0] = 1; V[3][0] = 1 # e, h
        W[0][0] = 1; W[3][0] = 1 # c00, c11
        
        # m2 = (c+d)e
        U[2][1] = 1; U[3][1] = 1 # c, d
        V[0][1] = 1 # e
        W[0][1] = 1 # c01
        
        # m3 = a(f-h)
        U[0][2] = 1 # a
        V[1][2] = 1; V[3][2] = -1 # f, -h
        W[1][2] = 1 # c10
        
        # m4 = d(g-f)
        U[3][3] = 1 # d
        V[0][3] = 1; V[2][3] = -1 # g, -f
        W[1][3] = 1 # c01
        
        # m5 = (a+b)h
        U[0][4] = 1; U[1][4] = 1 # a, b
        V[3][4] = 1 # h
        W[0][4] = -1; W[1][4] = 1 # -c00, c10
        
        # m6 = (c-b)(e+f)
        U[2][5] = 1; U[1][5] = -1 # c, -b
        V[0][5] = 1; V[1][5] = 1 # e, f
        W[3][5] = 1 # c11
        
        # m7 = (a-d)(g+h)
        U[0][6] = 1; U[3][6] = -1 # a, -d
        V[0][6] = 1; V[2][6] = 1 # g, h
        W[0][6] = -1; W[3][6] = 1 # -c00, c11
        
        return U, V, W
    