import numpy as np
import scipy.optimize as opt
import time
import itertools

def construct():
    start_time = time.time()
    deadline = 195.0  # Safety margin before 210s limit

    # Use exact Gauss-Hermite quadrature.
    # g is degree 12. g^2 is degree 24.
    # x^2 g^2 is degree 26.
    # (g' - xg)^2 involves derivatives, so degree increases.
    # g' is degree 11. xg is degree 13.
    # g' - xg is degree 13.
    # (g' - xg)^2 is degree 26.
    # So all integrands are polynomials of degree <= 26 times e^{-x^2}.
    # Gauss-Hermite with N points integrates polynomials up to degree 2N-1 exactly.
    # We need 2N-1 >= 26 => 2N >= 27 => N >= 13.5.
    # So N=14 is sufficient for exact integration.
    N_points = 14
    x_nodes, w_nodes = np.polynomial.hermite.hermgauss(N_points)
    
    # Pre-compute powers and Hermite polynomials at nodes
    x = x_nodes
    x2 = x**2
    x3 = x2 * x
    x4 = x2**2
    x5 = x4 * x
    x6 = x4 * x2
    x7 = x6 * x
    x8 = x4**2
    x9 = x8 * x
    x10 = x8 * x2
    x11 = x10 * x
    x12 = x6**2
    
    # Hermite polynomials (physicists' convention)
    H0 = np.ones_like(x)
    H4 = x4 - 6*x2 + 3
    H8 = x8 - 28*x6 + 210*x4 - 420*x2 + 105
    H12 = x12 - 66*x10 + 1260*x8 - 9240*x6 + 23100*x4 - 27720*x2 + 10395
    
    # Derivatives
    dH0 = np.zeros_like(x)
    dH4 = 4*x3 - 12*x
    dH8 = 8*x7 - 168*x5 + 840*x3 - 840*x
    dH12 = 12*x11 - 660*x9 + 10080*x7 - 55440*x5 + 92400*x3 - 55440*x

    def compute_metrics(coeffs):
        """
        Computes the individual uncertainty terms.
        coeffs: (c0, c4, c8)
        Returns: (A_f, A_gf, product)
        """
        c0, c4, c8 = coeffs
        c12 = -(c0 + 3*c4 + 105*c8) / 10395.0
        
        g = c0*H0 + c4*H4 + c8*H8 + c12*H12
        gp = c0*dH0 + c4*dH4 + c8*dH8 + c12*dH12
        
        # Integrals
        I0 = np.sum(w_nodes * g**2)
        if I0 <= 1e-30 or not np.isfinite(I0):
            return np.inf, np.inf, np.inf
            
        Ix2 = np.sum(w_nodes * x2 * g**2)
        if not np.isfinite(Ix2) or Ix2 < 0:
            return np.inf, np.inf, np.inf
            
        deriv_term = gp - x * g
        Ideriv = np.sum(w_nodes * deriv_term**2)
        if not np.isfinite(Ideriv) or Ideriv < 0:
            return np.inf, np.inf, np.inf
            
        A_f = Ix2 / I0
        A_gf = (1.0 / (4.0 * np.pi**2)) * Ideriv / I0
        
        return np.sqrt(A_f), np.sqrt(A_gf), np.sqrt(A_f * A_gf)

    def compute_score_fast(coeffs):
        """
        Computes the score (uncertainty product).
        """
        if time.time() > deadline - 2:
            return np.inf
        _, _, prod = compute_metrics(coeffs)
        return prod

    # Initial guess from seed
    x0 = np.array([-1.13, 0.04, 0.0003086])
    
    best_score = compute_score_fast(x0)
    best_coeffs = x0.copy()

    # STRATEGY: Min-Max optimization + Deterministic Grid Search + Local Refinement
    # Instead of minimizing the product P = A_f * A_gf, we minimize M = max(A_f, A_gf) * k 
    # or simply minimize the product but using a global grid search to find the basin,
    # then refine. The "Min-Max" idea is to balance the two uncertainties.
    
    # Let's try a different objective: Minimize the sum of squares of the logs?
    # Or just stick to product but use a robust global search.
    
    # The stagnation suggests the current DE/L-BFGS is converging to the same point.
    # Let's try a **Basin Hopping** approach with a **different initial set of points**
    # generated by a **Latin Hypercube Sampling** (LHS) to ensure coverage.
    
    # Define a robust local minimizer
    def local_minimize(x_init):
        try:
            res = opt.minimize(
                compute_score_fast, 
                x_init, 
                method='L-BFGS-B',
                options={'maxiter': 500, 'ftol': 1e-15, 'gtol': 1e-12}
            )
            if res.success and np.isfinite(res.fun):
                return res.x, res.fun
        except Exception:
            pass
        return x_init, np.inf

    # Generate Latin Hypercube Sample in the bounding box
    # Bounds based on seed: c0 ~ -1, c4 ~ 0.04, c8 ~ 0.0003
    # Expand bounds slightly to explore neighbors
    bounds_lhs = [
        (-2.0, 0.0),   # c0
        (-0.5, 0.5),   # c4
        (-0.01, 0.01)  # c8
    ]
    
    n_samples = 200
    # Simple LHS generation
    np.random.seed(42)
    samples = np.zeros((n_samples, 3))
    for i in range(3):
        # Permute intervals
        perm = np.random.permutation(n_samples)
        # Random offset within interval
        offsets = np.random.rand(n_samples)
        # Map to bounds
        low, high = bounds_lhs[i]
        width = (high - low) / n_samples
        samples[:, i] = low + (perm + offsets) * width
    
    # Evaluate all samples
    scores = []
    for s in samples:
        if time.time() > deadline - 20:
            break
        sc = compute_score_fast(s)
        scores.append((sc, s))
    
    # Sort by score
    scores.sort(key=lambda x: x[0])
    
    # Take top 10 candidates and refine
    for sc, s in scores[:10]:
        if time.time() > deadline - 10:
            break
        refined_x, refined_score = local_minimize(s)
        if refined_score < best_score:
            best_score = refined_score
            best_coeffs = refined_x

    # Also try a "balanced" objective: minimize max(A_f, A_gf)
    # This might find a different point where the product is slightly lower or equal
    # but more robust.
    
    def compute_max_metric(coeffs):
        if time.time() > deadline - 2:
            return np.inf
        af, agf, _ = compute_metrics(coeffs)
        return max(af, agf)

    # Use a small grid search for the max metric
    c0_grid = np.linspace(-1.5, -0.5, 5)
    c4_grid = np.linspace(-0.2, 0.2, 5)
    c8_grid = np.linspace(-0.005, 0.005, 5)
    
    best_max_score = np.inf
    best_max_coeffs = x0.copy()
    
    for c0 in c0_grid:
        for c4 in c4_grid:
            for c8 in c8_grid:
                if time.time() > deadline - 15:
                    break
                c_try = np.array([c0, c4, c8])
                m_sc = compute_max_metric(c_try)
                if m_sc < best_max_score:
                    best_max_score = m_sc
                    best_max_coeffs = c_try
    
    # Refine the best max-metric candidate
    if time.time() < deadline - 5:
        refined_x, refined_score = local_minimize(best_max_coeffs)
        if refined_score < best_score:
            best_score = refined_score
            best_coeffs = refined_x

    # Final polish on the absolute best
    if time.time() < deadline - 2:
        try:
            res_final = opt.minimize(
                compute_score_fast, 
                best_coeffs, 
                method='Powell',
                options={'maxiter': 2000, 'xatol': 1e-12, 'fatol': 1e-12}
            )
            if res_final.fun < best_score and np.isfinite(res_final.fun):
                best_score = res_final.fun
                best_coeffs = res_final.x.copy()
        except Exception:
            pass

    return np.array(best_coeffs)
