def construct():
    n, m, p = 4, 4, 7
    rank = 104
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    def add_term(u_idx, v_idx, w_idx, u_c, v_c, w_c):
        nonlocal col
        U[u_idx][col] += u_c
        V[v_idx][col] += v_c
        W[w_idx][col] += w_c
        col += 1

    # Helper to add a 2x2 * 2x2 schoolbook multiplication
    # x_entries: [[(c, a_idx), ...], ...] for x00, x01, x10, x11
    # y_entries: [[(c, b_idx), ...], ...] for y00, y01, y10, y11
    # c_targets: [[(w_idx, c_coeff), ...], ...] for c00, c01, c10, c11
    
    def add_2x2_schoolbook(x_entries, y_entries, c_targets):
        # 8 terms
        # c00 += x00*y00 + x01*y10
        # c01 += x00*y01 + x01*y11
        # c10 += x10*y00 + x11*y10
        # c11 += x10*y01 + x11*y11
        
        terms = [
            (0, 0, 0), # x00, y00, c00
            (0, 1, 0), # x01, y10, c00
            (0, 2, 1), # x00, y01, c01
            (1, 3, 1), # x01, y11, c01
            (2, 0, 2), # x10, y00, c10
            (3, 1, 2), # x11, y10, c10
            (2, 2, 3), # x10, y01, c11
            (3, 3, 3)  # x11, y11, c11
        ]
        
        for x_i, y_i, c_i in terms:
            x_combo = x_entries[x_i]
            y_combo = y_entries[y_i]
            c_list = c_targets[c_i]
            
            # Expand product of two linear combos
            for c_x, a_idx in x_combo:
                for c_y, b_idx in y_combo:
                    for w_idx, c_coeff in c_list:
                        add_term(a_idx, b_idx, w_idx, c_x, c_y, c_coeff)

    # Define A indices
    # A11: 0,1,4,5
    # A12: 2,3,6,7
    # A21: 8,9,12,13
    # A22: 10,11,14,15
    
    # Define B indices (cols 0-3)
    # B11: 0,1,7,8
    # B12: 2,3,9,10
    # B21: 14,15,21,22
    # B22: 16,17,23,24
    
    # Define C targets (cols 0-3)
    # C11: 0,4,1,5 (w_idx: k*4+i)
    # C[0][0]=0, C[0][1]=4, C[1][0]=1, C[1][1]=5
    # C12: 8,12,9,13
    # C[0][2]=8, C[0][3]=12, C[1][2]=9, C[1][3]=13
    # C21: 2,6,3,7
    # C[2][0]=2, C[2][1]=6, C[3][0]=3, C[3][1]=7
    # C22: 10,14,11,15
    # C[2][2]=10, C[2][3]=14, C[3][2]=11, C[3][3]=15

    # M1 = (A11+A22)*(B11+B22)
    x1 = [
        [(1,0), (1,10)], # A11[0]+A22[0]
        [(1,1), (1,11)], # A11[1]+A22[1]
        [(1,4), (1,14)], # A11[2]+A22[2]
        [(1,5), (1,15)]  # A11[3]+A22[3]
    ]
    y1 = [
        [(1,0), (1,16)], # B11[0]+B22[0]
        [(1,1), (1,17)], # B11[1]+B22[1]
        [(1,7), (1,23)], # B11[2]+B22[2]
        [(1,8), (1,24)]  # B11[3]+B22[3]
    ]
    # C11 += M1, C22 += M1
    c1_targets = [
        [(0, 1), (10, 1)], # C11[0], C22[0]
        [(4, 1), (14, 1)], # C11[1], C22[1]
        [(1, 1), (11, 1)], # C11[2], C22[2]
        [(5, 1), (15, 1)]  # C11[3], C22[3]
    ]
    add_2x2_schoolbook(x1, y1, c1_targets)

    # M2 = (A21+A22)*B11
    x2 = [
        [(1,8), (1,10)],
        [(1,9), (1,11)],
        [(1,12), (1,14)],
        [(1,13), (1,15)]
    ]
    y2 = [
        [(1,0)],
        [(1,1)],
        [(1,7)],
        [(1,8)]
    ]
    # C21 += M2, C22 -= M2
    c2_targets = [
        [(2, 1), (10, -1)],
        [(6, 1), (14, -1)],
        [(3, 1), (11, -1)],
        [(7, 1), (15, -1)]
    ]
    add_2x2_schoolbook(x2, y2, c2_targets)

    # M3 = A11*(B12-B22)
    x3 = [
        [(1,0)],
        [(1,1)],
        [(1,4)],
        [(1,5)]
    ]
    y3 = [
        [(1,2), (-1,16)],
        [(1,3), (-1,17)],
        [(1,9), (-1,23)],
        [(1,10), (-1,24)]
    ]
    # C12 += M3, C22 += M3
    c3_targets = [
        [(8, 1), (10, 1)],
        [(12, 1), (14, 1)],
        [(9, 1), (11, 1)],
        [(13, 1), (15, 1)]
    ]
    add_2x2_schoolbook(x3, y3, c3_targets)

    # M4 = A22*(B21-B11)
    x4 = [
        [(1,10)],
        [(1,11)],
        [(1,14)],
        [(1,15)]
    ]
    y4 = [
        [(-1,0), (1,14)],
        [(-1,1), (1,15)],
        [(-1,7), (1,21)],
        [(-1,8), (1,22)]
    ]
    # C11 += M4, C21 += M4
    c4_targets = [
        [(0, 1), (2, 1)],
        [(4, 1), (6, 1)],
        [(1, 1), (3, 1)],
        [(5, 1), (7, 1)]
    ]
    add_2x2_schoolbook(x4, y4, c4_targets)

    # M5 = (A11+A12)*B22
    x5 = [
        [(1,0), (1,2)],
        [(1,1), (1,3)],
        [(1,4), (1,6)],
        [(1,5), (1,7)]
    ]
    y5 = [
        [(1,16)],
        [(1,17)],
        [(1,23)],
        [(1,24)]
    ]
    # C11 -= M5, C12 += M5
    c5_targets = [
        [(0, -1), (8, 1)],
        [(4, -1), (12, 1)],
        [(1, -1), (9, 1)],
        [(5, -1), (13, 1)]
    ]
    add_2x2_schoolbook(x5, y5, c5_targets)

    # M6 = (A21-A11)*(B11+B12)
    x6 = [
        [(-1,0), (1,8)],
        [(-1,1), (1,9)],
        [(-1,4), (1,12)],
        [(-1,5), (1,13)]
    ]
    y6 = [
        [(1,0), (1,2)],
        [(1,1), (1,3)],
        [(1,7), (1,9)],
        [(1,8), (1,10)]
    ]
    # C22 += M6
    c6_targets = [
        [(10, 1)],
        [(14, 1)],
        [(11, 1)],
        [(15, 1)]
    ]
    add_2x2_schoolbook(x6, y6, c6_targets)

    # M7 = (A12-A22)*(B21+B22)
    x7 = [
        [(-1,10), (1,2)],
        [(-1,11), (1,3)],
        [(-1,14), (1,6)],
        [(-1,15), (1,7)]
    ]
    y7 = [
        [(1,14), (1,16)],
        [(1,15), (1,17)],
        [(1,21), (1,23)],
        [(1,22), (1,24)]
    ]
    # C11 += M7
    c7_targets = [
        [(0, 1)],
        [(4, 1)],
        [(1, 1)],
        [(5, 1)]
    ]
    add_2x2_schoolbook(x7, y7, c7_targets)

    # Part 2: Schoolbook for 4x4 * 4x3 (cols 4-6)
    # B cols 4,5,6
    # B[0][4]=4, B[0][5]=5, B[0][6]=6
    # B[1][4]=11, B[1][5]=12, B[1][6]=13
    # B[2][4]=18, B[2][5]=19, B[2][6]=20
    # B[3][4]=25, B[3][5]=26, B[3][6]=27
    
    # C cols 4,5,6
    # C[0][4]=16, C[0][5]=20, C[0][6]=24
    # C[1][4]=17, C[1][5]=21, C[1][6]=25
    # C[2][4]=18, C[2][5]=22, C[2][6]=26
    # C[3][4]=19, C[3][5]=23, C[3][6]=27

    for i in range(4):
        for j in range(4):
            for k in range(3):
                b_col = 4 + k
                u_idx = i * 4 + j
                v_idx = j * 7 + b_col
                w_idx = b_col * 4 + i
                add_term(u_idx, v_idx, w_idx, 1, 1, 1)

    return {"U": U, "V": V, "W": W}
