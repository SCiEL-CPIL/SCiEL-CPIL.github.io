import numpy as np
import time
import math
from scipy.optimize import minimize
from scipy.ndimage import gaussian_filter

N = 150
DEADLINE = 145.0  # Safety margin for 150s limit

def _generate_sphere_grid(lat_res, lon_res):
    """Generate a high-resolution grid on the sphere."""
    lat = np.linspace(0, np.pi, lat_res)
    lon = np.linspace(0, 2 * np.pi, lon_res)
    LON, LAT = np.meshgrid(lon, lat)
    X = np.sin(LAT) * np.cos(LON)
    Y = np.sin(LAT) * np.sin(LON)
    Z = np.cos(LAT)
    return X, Y, Z, LAT, LON

def _level_set_evolution(X, Y, Z, LAT, LON, init_phi, steps=500, dt=0.005, sigma=0.05):
    """
    Evolve the level set function phi using Allen-Cahn dynamics.
    Velocity is derived from the gradient of the interaction energy.
    """
    phi = init_phi.copy()
    lat_res, lon_res = phi.shape
    
    # Precompute grid properties
    d_lat = np.pi / (lat_res - 1)
    d_lon = 2 * np.pi / lon_res
    
    # For stability, we use a simple gradient calculation
    # and a double-well potential to maintain sharp interfaces.
    
    for step in range(steps):
        # 1. Compute the density rho = sigmoid(phi)
        # Use a soft sigmoid to avoid numerical issues
        rho = 1.0 / (1.0 + np.exp(-phi / sigma))
        
        # 2. Compute the interaction force (gradient of energy)
        # Energy ~ sum log(1/r). Gradient w.r.t position is repulsive.
        # In level set, velocity v = -grad E / |grad phi|
        # Approximate grad E by convolving rho with the kernel gradient.
        
        # We use a simple repulsive force model:
        # Force on a cell is proportional to sum of rho_j * (x_i - x_j) / |x_i - x_j|^2
        # For efficiency, we approximate this with a local gradient of rho.
        # Since log(1/r) is long-range, a simple local gradient isn't enough.
        # However, for level sets on a grid, we can use a "pressure" term.
        
        # Alternative: Compute the "energy density" gradient directly.
        # Let's use a simpler heuristic: 
        # The velocity field drives the interface to reduce energy.
        # High density regions repel.
        
        # Compute divergence of rho to get a proxy for local density gradient
        # This is a simplification. A better approach for log energy is to compute
        # the gradient of the potential field generated by rho.
        
        # Potential U = sum rho_j log(1/r_ij). 
        # grad U_i = sum rho_j (x_i - x_j) / r_ij^2.
        
        # We can compute this via convolution if we had a kernel, but log kernel is tricky.
        # Let's use a "mean field" approximation or simply use the gradient of rho 
        # with a repulsive sign, scaled by a global factor.
        
        # Actually, a robust level-set approach for point repulsion often uses:
        # v = - c * grad(rho) where rho is the density.
        # But rho is a sum of deltas. Here rho is a smoothed field.
        
        # Let's compute the gradient of rho on the sphere.
        # d_rho_d_lat
        drho_dlat = np.zeros_like(rho)
        drho_dlon = np.zeros_like(rho)
        
        # Central differences
        drho_dlat[1:-1, :] = (rho[2:, :] - rho[:-2, :]) / (2 * d_lat)
        drho_dlon[:, 1:-1] = (rho[:, 2:] - rho[:, :-2]) / (2 * d_lon)
        
        # Convert to Cartesian gradient components (approx)
        # grad_rho = (drho_dlat / sin(lat)) * e_lat + (drho_dlon / sin(lat)) * e_lon
        # We want the force to be repulsive: points move away from high density.
        # So velocity should be opposite to gradient of density?
        # If density is high, we want to spread out.
        # Force = - grad (Interaction Energy).
        
        # Let's use a simple heuristic velocity:
        # v = - alpha * laplacian(rho) + beta * grad(rho) ? No.
        
        # Let's try: v = - grad (U) where U is the potential.
        # We approximate U by blurring rho with a kernel that mimics log interaction.
        # A Gaussian blur is a good approximation for short/medium range.
        
        U = gaussian_filter(rho, sigma=5) # 5 grid cells ~ reasonable range
        
        # Gradient of U
        dU_dlat = np.zeros_like(U)
        dU_dlon = np.zeros_like(U)
        dU_dlat[1:-1, :] = (U[2:, :] - U[:-2, :]) / (2 * d_lat)
        dU_dlon[:, 1:-1] = (U[:, 2:] - U[:, :-2]) / (2 * d_lon)
        
        # Velocity field in lat/lon coordinates
        # v_lat = - dU_dlat
        # v_lon = - dU_dlon / sin(lat)
        
        sin_lat = np.sin(LAT)
        # Avoid division by zero at poles
        sin_lat_safe = np.where(sin_lat < 1e-6, 1e-6, sin_lat)
        
        v_lat = -dU_dlat
        v_lon = -dU_dlon / sin_lat_safe
        
        # Advection: phi_t + v . grad(phi) = 0
        # Use upwind scheme for stability
        dphi_dlat = np.zeros_like(phi)
        dphi_dlon = np.zeros_like(phi)
        
        # Upwind for lat
        for i in range(1, lat_res - 1):
            v = v_lat[i, :]
            # Positive v means flow from i-1 to i? 
            # Standard advection: phi_i(t+dt) = phi_i(t) - dt * v * dphi/dx
            # Upwind: if v > 0, use backward diff; if v < 0, forward diff.
            mask_pos = v > 0
            mask_neg = v < 0
            
            dphi_dlat[i, mask_pos] = (phi[i, mask_pos] - phi[i-1, mask_pos]) / d_lat
            dphi_dlat[i, mask_neg] = (phi[i+1, mask_neg] - phi[i, mask_neg]) / d_lat
            
        # Upwind for lon (cyclic)
        for j in range(lon_res):
            v = v_lat[:, j] # Wait, v_lon is for lon direction
            v_lon_j = v_lon[:, j]
            
            # Cyclic upwind
            # If v_lon > 0, flow from j-1 to j. Use phi[j-1]
            # If v_lon < 0, flow from j+1 to j. Use phi[j+1]
            
            # Vectorized cyclic shift
            phi_jm1 = np.roll(phi[:, j], 1, axis=0) # This is wrong, roll is along axis 0 (lat)
            # We need to roll along axis 1 (lon).
            
            # Let's do it element-wise or with proper rolls
            # phi_prev_lat = np.roll(phi, 1, axis=0)
            # phi_next_lat = np.roll(phi, -1, axis=0)
            # phi_prev_lon = np.roll(phi, 1, axis=1)
            # phi_next_lon = np.roll(phi, -1, axis=1)
            
            # We already computed dphi_dlat in a loop. Let's do lon similarly or vectorize.
            # For simplicity and speed, let's vectorize the advection step.
            
            pass # The loop above is slow. Let's rewrite advection vectorized.
            
        # Restart advection calculation vectorized
        phi_prev_lat = np.roll(phi, 1, axis=0)
        phi_next_lat = np.roll(phi, -1, axis=0)
        phi_prev_lon = np.roll(phi, 1, axis=1)
        phi_next_lon = np.roll(phi, -1, axis=1)
        
        # Lat advection
        mask_pos_lat = v_lat > 0
        dphi_dlat = np.where(mask_pos_lat, (phi - phi_prev_lat) / d_lat, 
                             (phi_next_lat - phi) / d_lat)
        
        # Lon advection
        mask_pos_lon = v_lon > 0
        dphi_dlon = np.where(mask_pos_lon, (phi - phi_prev_lon) / d_lon, 
                             (phi_next_lon - phi) / d_lon)
        
        # Update phi
        phi_new = phi - dt * (v_lat * dphi_dlat + v_lon * dphi_dlon)
        
        # Allen-Cahn term: phi_t = epsilon^2 * laplacian(phi) - f'(phi)
        # This keeps the interface sharp.
        # Simple Laplacian
        lap_phi = (np.roll(phi_new, 1, axis=0) + np.roll(phi_new, -1, axis=0) + 
                   np.roll(phi_new, 1, axis=1) + np.roll(phi_new, -1, axis=1) - 4 * phi_new)
        
        # f'(phi) for double well potential (e.g., phi^3 - phi)
        # We want phi to be 0 or 1 (or -1/1). 
        # Let's use a simple relaxation to keep values bounded
        phi_new = phi_new + 0.1 * lap_phi
        
        phi = phi_new
        
    return phi

def _extract_points_from_level_set(phi, N_points):
    """
    Extract N_points from the level set field.
    We find the local maxima of the density (or minima of phi if phi is signed distance).
    Here we assume rho = sigmoid(phi) is the density.
    We want to place points at the peaks of the density.
    """
    rho = 1.0 / (1.0 + np.exp(-phi / 0.05))
    
    # Find local maxima
    # Simple approach: threshold and find connected components, or just pick top N values
    # But points should be well-separated.
    
    # Strategy: 
    # 1. Identify candidate points: local maxima of rho.
    # 2. If too many, merge or select best N.
    # 3. If too few, add random points.
    
    # Flatten
    flat_rho = rho.flatten()
    flat_idx = np.argsort(flat_rho)[::-1]
    
    # Select top candidates, but ensure they are not too close
    # This is a greedy selection.
    selected_indices = []
    min_dist_sq = 0.01 # ~10 degrees
    
    # We need to map flat index to (lat, lon)
    lat_res, lon_res = phi.shape
    
    # To be efficient, we only check against already selected points
    # Since N=150, this is fast.
    
    candidate_indices = flat_idx[:1000] # Check top 1000
    
    for idx in candidate_indices:
        i = idx // lon_res
        j = idx % lon_res
        
        # Get coords
        lat = i * np.pi / (lat_res - 1)
        lon = j * 2 * np.pi / lon_res
        
        x = np.sin(lat) * np.cos(lon)
        y = np.sin(lat) * np.sin(lon)
        z = np.cos(lat)
        
        # Check distance to selected
        is_far = True
        for sel_idx in selected_indices:
            si = sel_idx // lon_res
            sj = sel_idx % lon_res
            slat = si * np.pi / (lat_res - 1)
            slon = sj * 2 * np.pi / lon_res
            
            sx = np.sin(slat) * np.cos(slon)
            sy = np.sin(slat) * np.sin(slon)
            sz = np.cos(slat)
            
            dist_sq = (x-sx)**2 + (y-sy)**2 + (z-sz)**2
            if dist_sq < min_dist_sq:
                is_far = False
                break
        
        if is_far:
            selected_indices.append(idx)
            
        if len(selected_indices) >= N_points:
            break
    
    # If we don't have enough, pad with random points
    while len(selected_indices) < N_points:
        # Random point on sphere
        u = np.random.rand()
        v = np.random.rand()
        lat = np.arccos(2 * u - 1)
        lon = 2 * np.pi * v
        
        # Find nearest grid cell
        i = int(lat / np.pi * (lat_res - 1))
        j = int(lon / (2 * np.pi) * lon_res)
        i = np.clip(i, 0, lat_res - 1)
        j = np.clip(j, 0, lon_res - 1)
        
        idx = i * lon_res + j
        if idx not in selected_indices:
            selected_indices.append(idx)
    
    # Convert selected indices to 3D points
    points = np.zeros((N_points, 3))
    for k, idx in enumerate(selected_indices[:N_points]):
        i = idx // lon_res
        j = idx % lon_res
        
        lat = i * np.pi / (lat_res - 1)
        lon = j * 2 * np.pi / lon_res
        
        points[k, 0] = np.sin(lat) * np.cos(lon)
        points[k, 1] = np.sin(lat) * np.sin(lon)
        points[k, 2] = np.cos(lat)
        
    return points

def _log_energy_and_grad(pts):
    """Compute log energy and gradient for points on the sphere."""
    pts = pts.reshape(-1, 3)
    norms = np.linalg.norm(pts, axis=1, keepdims=True)
    pts = pts / norms
    
    # Compute pairwise distances
    diff = pts[:, None, :] - pts[None, :, :]
    dist = np.linalg.norm(diff, axis=2)
    np.fill_diagonal(dist, 1.0)
    
    # Energy: sum_{i<j} log(1/dist)
    iu = np.triu_indices(N, 1)
    d = dist[iu]
    energy = np.sum(np.log(1.0 / d))
    
    # Gradient
    inv_dist_sq = np.ones_like(dist)
    mask = dist > 1e-12
    inv_dist_sq[mask] = 1.0 / (dist[mask] ** 2)
    
    forces = diff * inv_dist_sq[:, :, None]
    grad = -np.sum(forces, axis=1)
    
    # Project gradient to tangent space
    dot = np.sum(grad * pts, axis=1, keepdims=True)
    grad_tangent = grad - dot * pts
    
    return energy, grad_tangent

def construct():
    start_time = time.time()
    
    # Grid resolution
    # 150 points. We need resolution high enough to resolve them.
    # 150 points ~ sqrt(150) ~ 12 points per side? 
    # Let's use 64x64 or 128x128. 128x128 = 16k points. Manageable.
    lat_res = 64
    lon_res = 64
    
    X, Y, Z, LAT, LON = _generate_sphere_grid(lat_res, lon_res)
    
    # Initialize phi
    # Start with a random field or a structured one
    # Random is good for diversity
    np.random.seed(42)
    phi = np.random.randn(lat_res, lon_res) * 0.1
    
    best_energy = np.inf
    best_points = None
    
    # Phase 1: Level Set Evolution
    # Run evolution for a few steps
    # We will run multiple short evolutions and extract points, then polish
    
    for run in range(5): # 5 different evolutions or restarts
        if time.time() - start_time > DEADLINE - 30:
            break
            
        # Initialize phi for this run
        if run == 0:
            phi = np.random.randn(lat_res, lon_res) * 0.1
        else:
            # Perturb previous phi or start fresh
            phi = np.random.randn(lat_res, lon_res) * 0.1
        
        # Evolve
        # Time budget per run: ~20s
        steps = 200
        phi = _level_set_evolution(X, Y, Z, LAT, LON, phi, steps=steps, dt=0.01, sigma=0.05)
        
        # Extract points
        points = _extract_points_from_level_set(phi, N)
        
        # Check validity
        if np.any(~np.isfinite(points)):
            continue
            
        # Normalize
        points /= np.linalg.norm(points, axis=1, keepdims=True)
        
        # Check min distance
        # Simple check: if any pair is too close, skip or fix
        # We'll rely on the polish to fix it, but if it's invalid, we might fail.
        # Let's do a quick check.
        valid = True
        # O(N^2) check is fine for 150
        for i in range(N):
            for j in range(i+1, N):
                if np.linalg.norm(points[i] - points[j]) < 1e-9:
                    valid = False
                    break
            if not valid:
                break
        
        if not valid:
            # Try to fix by randomizing close points? Or just skip.
            # Skipping is safer.
            continue
        
        # Phase 2: L-BFGS Polish
        # This is crucial. The level set gives a good global structure, 
        # but L-BFGS refines it to a local minimum.
        
        def objective_and_grad(x):
            pts = x.reshape(-N, 3)
            e, g = _log_energy_and_grad(pts)
            return e, g.flatten()
            
        x0 = points.flatten()
        
        try:
            result = minimize(objective_and_grad, x0, method='L-BFGS-B', jac=True, 
                              options={'maxiter': 100, 'ftol': 1e-12, 'gtol': 1e-8})
            
            polished_points = result.x.reshape(-N, 3)
            polished_points /= np.linalg.norm(polished_points, axis=1, keepdims=True)
            
            energy, _ = _log_energy_and_grad(polished_points)
            
            if energy < best_energy:
                best_energy = energy
                best_points = polished_points.copy()
                
        except Exception as e:
            pass # Skip if optimization fails
            
    # If no valid points were found (should not happen), fallback to Fibonacci
    if best_points is None:
        i = np.arange(N) + 0.5
        z = 1.0 - 2.0 * i / N
        phi_fib = np.pi * (1.0 + np.sqrt(5.0)) * i
        r = np.sqrt(1.0 - z * z)
        best_points = np.column_stack([r * np.cos(phi_fib), r * np.sin(phi_fib), z])
        
    # Final tight polish if time permits
    if time.time() - start_time < DEADLINE - 5.0 and best_points is not None:
        def objective_and_grad(x):
            pts = x.reshape(-N, 3)
            e, g = _log_energy_and_grad(pts)
            return e, g.flatten()
            
        x0 = best_points.flatten()
        try:
            result = minimize(objective_and_grad, x0, method='L-BFGS-B', jac=True, 
                              options={'maxiter': 200, 'ftol': 1e-15, 'gtol': 1e-10})
            
            final_points = result.x.reshape(-N, 3)
            final_points /= np.linalg.norm(final_points, axis=1, keepdims=True)
            
            final_energy, _ = _log_energy_and_grad(final_points)
            if final_energy < best_energy:
                best_energy = final_energy
                best_points = final_points
        except:
            pass
            
    return best_points
