import numpy as np
import time

DIMENSIONS = [2, 3, 5]

def _add_strassen_block(U, V, W, col, i_off, j_off, k_off):
    """Add Strassen 2x2x2 block at given offsets. Returns new col."""
    n, m, p = 2, 3, 5
    # M1: (A00+A11)(B00+B11) -> C00, C11
    U[i_off * m + j_off][col] = 1
    U[(i_off+1) * m + (j_off+1)][col] = 1
    V[j_off * p + k_off][col] = 1
    V[(j_off+1) * p + (k_off+1)][col] = 1
    W[k_off * n + i_off][col] = 1
    W[(k_off+1) * n + (i_off+1)][col] = 1
    col += 1
    
    # M2: (A10+A11)B00 -> C10, -C11
    U[(i_off+1) * m + j_off][col] = 1
    U[(i_off+1) * m + (j_off+1)][col] = 1
    V[j_off * p + k_off][col] = 1
    W[k_off * n + (i_off+1)][col] = 1
    W[(k_off+1) * n + (i_off+1)][col] = -1
    col += 1
    
    # M3: A00(B01-B11) -> C01, C11
    U[i_off * m + j_off][col] = 1
    V[j_off * p + (k_off+1)][col] = 1
    V[(j_off+1) * p + (k_off+1)][col] = -1
    W[(k_off+1) * n + i_off][col] = 1
    W[(k_off+1) * n + (i_off+1)][col] = 1
    col += 1
    
    # M4: A11(B10-B00) -> C00, C10
    U[(i_off+1) * m + (j_off+1)][col] = 1
    V[(j_off+1) * p + k_off][col] = 1
    V[j_off * p + k_off][col] = -1
    W[k_off * n + i_off][col] = 1
    W[k_off * n + (i_off+1)][col] = 1
    col += 1
    
    # M5: (A00+A01)B11 -> -C00, C01
    U[i_off * m + j_off][col] = 1
    U[i_off * m + (j_off+1)][col] = 1
    V[(j_off+1) * p + (k_off+1)][col] = 1
    W[k_off * n + i_off][col] = -1
    W[(k_off+1) * n + i_off][col] = 1
    col += 1
    
    # M6: (A10-A00)(B00+B01) -> C11
    U[(i_off+1) * m + j_off][col] = 1
    U[i_off * m + j_off][col] = -1
    V[j_off * p + k_off][col] = 1
    V[j_off * p + (k_off+1)][col] = 1
    W[(k_off+1) * n + (i_off+1)][col] = 1
    col += 1
    
    # M7: (A01-A11)(B10+B11) -> C00
    U[i_off * m + (j_off+1)][col] = 1
    U[(i_off+1) * m + (j_off+1)][col] = -1
    V[(j_off+1) * p + k_off][col] = 1
    V[(j_off+1) * p + (k_off+1)][col] = 1
    W[k_off * n + i_off][col] = 1
    col += 1
    
    return col

def construct():
    n, m, p = 2, 3, 5
    deadline = time.time() + 140
    
    # Rank 28 Solution:
    # Block 1: j=0 (2x1x5) -> 10 terms
    # Block 2: j=1,2 (2x2x5)
    #   Sub-block 2a: k=0,1 (2x2x2) -> 7 terms (Strassen)
    #   Sub-block 2b: k=2 (2x2x1) -> 4 terms (Schoolbook)
    #   Sub-block 2c: k=3,4 (2x2x2) -> 7 terms (Strassen)
    # Total: 10 + 7 + 4 + 7 = 28
    
    rank = 28
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    # Block 1: j=0, k=0..4
    for i in range(n):
        for k in range(p):
            U[i * m + 0][col] = 1
            V[0 * p + k][col] = 1
            W[k * n + i][col] = 1
            col += 1
    
    # Block 2a: j=1,2, k=0,1 (Strassen 2x2x2)
    # i_off=0, j_off=1, k_off=0
    col = _add_strassen_block(U, V, W, col, 0, 1, 0)
    
    # Block 2b: j=1,2, k=2 (Schoolbook 2x2x1)
    for i in range(n):
        for j in range(1, 3):
            U[i * m + j][col] = 1
            V[j * p + 2][col] = 1
            W[2 * n + i][col] = 1
            col += 1
    
    # Block 2c: j=1,2, k=3,4 (Strassen 2x2x2)
    # i_off=0, j_off=1, k_off=3
    col = _add_strassen_block(U, V, W, col, 0, 1, 3)
    
    assert col == rank, f"Column mismatch: {col} != {rank}"
    
    return {"U": U, "V": V, "W": W}
