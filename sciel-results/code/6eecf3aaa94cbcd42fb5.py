import math
import time

def construct():
    start = time.time()
    deadline = start + 85.0
    target = 210
    max_val = 10210

    # Sieve for smallest prime factor
    spf = list(range(max_val + 1))
    for i in range(2, int(max_val ** 0.5) + 1):
        if spf[i] == i:
            for j in range(i * i, max_val + 1, i):
                if spf[j] == j:
                    spf[j] = i

    # Collect primes
    primes = []
    prime_index = {}
    for i in range(2, max_val + 1):
        if spf[i] == i:
            prime_index[i] = len(primes)
            primes.append(i)

    def get_mask(n):
        mask = 0
        temp = n
        while temp > 1:
            p = spf[temp]
            count = 0
            while temp % p == 0:
                temp //= p
                count += 1
            if count % 2 == 1:
                mask |= (1 << prime_index[p])
        return mask

    # Precompute masks
    masks = [0] * (max_val + 1)
    for x in range(2, max_val + 1):
        masks[x] = get_mask(x)

    target_mask = masks[target]

    # For each M from 211 upward, check if target_mask is in span of {masks[211], ..., masks[M]}
    # with at most 100 elements. Use linear basis with min-cardinality tracking.
    
    # basis[bit] = (vector_mask, frozenset_of_indices, count)
    # We maintain the basis incrementally as M increases
    
    # Actually, let's use a different approach: for each M, we want the minimum number of 
    # elements from {211..M} whose XOR equals target_mask.
    
    # This is a minimum weight solution to a linear system. We can use the following:
    # Maintain a basis where each basis vector is associated with the minimum number of 
    # original vectors needed to produce it.
    
    # Better approach: use Dijkstra-like on the state space, but that's too large.
    
    # Alternative: for small M, the number of elements is small, so we can use a 
    # meet-in-the-middle or just check all subsets for very small M.
    
    # Let's use the incremental basis with cardinality tracking.
    # basis[bit] = (mask, indices_set, cardinality)
    # When inserting a new vector, if it reduces the basis, update cardinality.
    
    # Actually, the cleanest approach: for each M, compute the minimum cardinality 
    # solution using a standard technique for minimum weight solutions to linear systems.
    
    # Let me use a different strategy: iterate M, and for each M, do a BFS in the 
    # subspace generated by masks[211..M] to find the minimum cardinality solution.
    
    # But the subspace can be large. Let's use the fact that we only need up to 100 elements.
    
    # Practical approach: for M up to maybe 300, the number of distinct masks is limited,
    # so we can use a dictionary mapping mask -> min cardinality.
    
    best_solution = None
    best_M = None
    
    for M in range(211, min(max_val + 1, 5000)):  # Limit search for speed
        if time.time() > deadline:
            break
            
        # Check if target_mask can be formed by XOR of subset of {masks[211], ..., masks[M]}
        # with at most 100 elements.
        # Use BFS in the state space of masks, tracking min cardinality.
        
        # State: mask -> min cardinality to achieve it
        # Start: 0 -> 0
        # Transitions: XOR with each mask in {masks[211], ..., masks[M]}
        
        # This is too slow for large M. Let's use a smarter approach.
        
        # For small M (say M < 250), the number of elements is small, so we can 
        # enumerate all subsets or use a hash-based approach.
        
        if M - 211 <= 40:
            # Small enough to do meet-in-the-middle or direct search
            # Get all masks for 211..M
            candidate_masks = [masks[x] for x in range(211, M + 1)]
            
            # Use BFS: state is (mask, cardinality), find min cardinality to reach target_mask
            # Since M-211 <= 40, at most 40 elements, we can use a dictionary
            # mapping mask -> min cardinality
            
            dist = {0: 0}
            queue = [0]
            found = False
            min_card = 101
            
            for _ in range(41):  # At most 40 elements + start
                new_queue = []
                for state in queue:
                    for cm in candidate_masks:
                        new_state = state ^ cm
                        if new_state not in dist:
                            dist[new_state] = dist[state] + 1
                            new_queue.append(new_state)
                            if new_state == target_mask:
                                min_card = dist[state] + 1
                                found = True
                                break
                    if found:
                        break
                if found:
                    break
                queue = new_queue
            
            if found and min_card <= 100:
                # Now find the actual subset
                # Backtrack: we need to find which elements were used
                # Re-do the search tracking the actual set
                # For simplicity, just verify and use a greedy approach
                
                # Actually, let's just track the solution directly
                # Redo with tracking
                dist = {0: (0, frozenset())}
                queue = [0]
                found = False
                
                for step in range(1, 41):
                    new_queue = []
                    for state in queue:
                        _, idx_set = dist[state]
                        for i, cm in enumerate(candidate_masks):
                            new_state = state ^ cm
                            if new_state not in dist:
                                new_idx = frozenset(idx_set | {i})
                                dist[new_state] = (step, new_idx)
                                new_queue.append(new_state)
                                if new_state == target_mask:
                                    found = True
                                    break
                        if found:
                            break
                    if found:
                        break
                    queue = new_queue
                
                if found:
                    _, idx_set = dist[target_mask]
                    sol = [211 + i for i in sorted(idx_set)]
                    if len(sol) <= 100 and max(sol) <= M:
                        # Verify
                        prod = target
                        for x in sol:
                            prod *= x
                        if math.isqrt(prod) ** 2 == prod:
                            best_solution = sol
                            best_M = M
                            break  # This is the optimal M, so we're done
        
        if best_solution is not None:
            break
    
    if best_solution is not None:
        return [int(x) for x in best_solution]
    
    # Fallback: use the linear basis approach for larger M
    # Build basis incrementally and find when target becomes reachable with <= 100 elements
    
    basis = {}  # bit -> (mask, frozenset_of_indices)
    
    for M in range(211, max_val + 1):
        if time.time() > deadline:
            break
            
        v = masks[M]
        temp_v = v
        temp_indices = frozenset([M])
        
        while temp_v != 0:
            p = temp_v.bit_length() - 1
            if p in basis:
                b_mask, b_indices = basis[p]
                temp_v ^= b_mask
                temp_indices = frozenset(temp_indices ^ b_indices)
            else:
                basis[p] = (temp_v, temp_indices)
                break
        
        # Check if target is in span
        t_v = target_mask
        t_indices = frozenset()
        
        while t_v != 0:
            p = t_v.bit_length() - 1
            if p in basis:
                b_mask, b_indices = basis[p]
                t_v ^= b_mask
                t_indices = frozenset(t_indices ^ b_indices)
            else:
                t_v = -1
                break
        
        if t_v == 0 and len(t_indices) <= 100:
            sol = list(t_indices)
            prod = target
            for x in sol:
                prod *= x
            if math.isqrt(prod) ** 2 == prod:
                return [int(x) for x in sol]
    
    # Final fallback
    return [840]

