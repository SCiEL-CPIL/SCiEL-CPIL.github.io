    # Restructured DFS:
    # We build rows one by one.
    # rows_acc stores completed rows.
    
    def dfs_improve(row_idx, current_row, used_diffs, current_max, rows_acc):
        nonlocal best_scope, best_solution, found_better
        
        if time.time() > deadline:
            return
            
        if row_idx == n_rows:
            final_max = current_max
            if final_max < best_scope:
                best_scope = final_max
                best_solution = [r[:] for r in rows_acc]
