def _try_low_rank(rank, n, m, p, deadline, max_rounds=2000, seed=42):
    """
    Try to find a decomposition of given rank using iterative refinement.
    """
    rng = np.random.RandomState(seed)
    U = rng.randn(n * m, rank)
    V = rng.randn(m * p, rank)
    W = rng.randn(p * n, rank)
    
    ta_list, tb_list, tc_list = [], [], []
    for i in range(n):
        for j in range(m):
            for k in range(p):
                ta_list.append(i * m + j)
                tb_list.append(j * p + k)
                tc_list.append(k * n + i)
    ta_arr = np.array(ta_list)
    tb_arr = np.array(tb_list)
    tc_arr = np.array(tc_list)
    
    for it in range(max_rounds):
        if time.time() > deadline:
            break
        
        # Update U
        for a in range(n * m):
            mask = (ta_arr == a)
            if not np.any(mask):
                continue
            tb_sub = tb_arr[mask]
            tc_sub = tc_arr[mask]
            V_sub = V[tb_sub, :]
            W_sub = W[tc_sub, :]
            prod = V_sub * W_sub
            # Solve U[a, :] * prod.T = 1
            # prod is (num_entries, rank)
            # We want x such that prod.T @ x = ones
            # This is least squares
            try:
                U[a, :], residuals, rank_u, s = np.linalg.lstsq(prod.T, np.ones(len(mask)), rcond=None)
            except:
                pass
        
        # Update V
        for b in range(m * p):
            mask = (tb_arr == b)
            if not np.any(mask):
                continue
            ta_sub = ta_arr[mask]
            tc_sub = tc_arr[mask]
            U_sub = U[ta_sub, :]
            W_sub = W[tc_sub, :]
            prod = U_sub * W_sub
            try:
                V[b, :], residuals, rank_v, s = np.linalg.lstsq(prod.T, np.ones(len(mask)), rcond=None)
            except:
                pass
        
        # Update W
        for c_idx in range(p * n):
            mask = (tc_arr == c_idx)
            if not np.any(mask):
                continue
            ta_sub = ta_arr[mask]
            tb_sub = tb_arr[mask]
            U_sub = U[ta_sub, :]
            V_sub = V[tb_sub, :]
            prod = U_sub * V_sub
            try:
                W[c_idx, :], residuals, rank_w, s = np.linalg.lstsq(prod.T, np.ones(len(mask)), rcond=None)
            except:
                pass
        
        if it % 50 == 0:
            sums = np.zeros(len(ta_arr))
            for c in range(rank):
                sums += U[ta_arr, c] * V[tb_arr, c] * W[tc_arr, c]
            err = np.sum((sums - 1.0) ** 2)
            if err < 1e-10:
                return U.tolist(), V.tolist(), W.tolist()
    
    return None

