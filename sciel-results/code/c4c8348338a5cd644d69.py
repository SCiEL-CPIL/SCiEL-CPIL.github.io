import numpy as np
import time

def ring_routing() -> np.ndarray:
    n = 10
    D = 15
    demands = [
        (0, 5, 3), (1, 7, 2), (2, 9, 4), (3, 6, 1), (0, 4, 5),
        (2, 8, 2), (5, 9, 3), (1, 4, 2), (6, 0, 4), (3, 8, 1),
        (7, 2, 3), (4, 9, 2), (8, 1, 5), (0, 6, 1), (5, 2, 2),
    ]

    # Precompute edge usage matrices
    # cw_mat[i, e] = 1 if edge e is used by demand i in CW direction
    # ccw_mat[i, e] = 1 if edge e is used by demand i in CCW direction
    cw_mat = np.zeros((D, n), dtype=np.float64)
    ccw_mat = np.zeros((D, n), dtype=np.float64)
    weights = np.zeros(D, dtype=np.float64)
    
    for i, (s, t, w) in enumerate(demands):
        weights[i] = w
        d_cw = (t - s) % n
        if d_cw == 0:
            pass
        else:
            # CW edges: s, s+1, ..., t-1
            for k in range(d_cw):
                e = (s + k) % n
                cw_mat[i, e] = 1.0
            # CCW edges: all other edges
            for e in range(n):
                if cw_mat[i, e] == 0.0:
                    ccw_mat[i, e] = 1.0

    # Base load if all demands go CW
    base_load = weights @ cw_mat # shape (n,)
    
    # Delta vector for flipping demand i from CW to CCW
    # delta[i] = w_i * (ccw_mat[i] - cw_mat[i])
    delta_mat = (ccw_mat - cw_mat) * weights[:, None]
    
    # Exhaustive search over all 2^15 routing combinations
    # Using Gray code to minimize the number of updates per step (only 1 bit changes)
    # This is faster than the naive "sum all set bits" approach which is O(D) per step.
    # With Gray code, it is O(1) vector update per step.
    
    best_max_load = np.inf
    best_mask = 0
    
    start_time = time.time()
    deadline = start_time + 590.0 # Safety margin
    
    # Initialize with mask = 0 (all CW)
    current_load = base_load.copy()
    current_mask = 0
    
    # Check mask 0
    max_load = np.max(current_load)
    best_max_load = max_load
    best_mask = 0
    
    total_masks = 1 << D
    
    # Iterate through Gray codes
    for i in range(1, total_masks):
        # Calculate time check periodically to avoid overhead
        if i % 1000 == 0:
            if time.time() > deadline:
                break
        
        # Gray code: g = i ^ (i >> 1)
        # The bit that changes from previous gray code to current is the position of the least significant set bit of i
        # Let's find the bit that changed.
        # prev_gray = (i-1) ^ ((i-1) >> 1)
        # curr_gray = i ^ (i >> 1)
        # changed_bit = prev_gray ^ curr_gray
        # bit_index = log2(changed_bit)
        
        # Alternatively, the bit that flips in the sequence of Gray codes generated by i is the index of the lowest set bit of i.
        # Let's verify:
        # i=1 (01): gray=01. prev=00. diff=01. bit 0. lowbit(1)=1 (bit 0). Correct.
        # i=2 (10): gray=11. prev=01. diff=10. bit 1. lowbit(2)=2 (bit 1). Correct.
        # i=3 (11): gray=10. prev=11. diff=01. bit 0. lowbit(3)=1 (bit 0). Correct.
        # i=4 (100): gray=110. prev=10. diff=100. bit 2. lowbit(4)=4 (bit 2). Correct.
        
        bit_index = (i & -i).bit_length() - 1
        
        # Update load
        current_load += delta_mat[bit_index]
        
        # Update mask (for tracking, though we can just use the gray code value or reconstruct if needed)
        # Actually, we need the mask corresponding to the Gray code to reconstruct the solution.
        # The routing decision is determined by the Gray code bits.
        # Let's maintain the current mask in standard binary representation?
        # No, it's easier to just keep track of the current state of the bits.
        # Or, since we want the "mask" where bit i is 1 if CCW, and the Gray code bit i tells us the direction?
        # Wait, the problem is that the "mask" in the naive approach was the binary representation of the routing choices.
        # Here, the "state" is the Gray code value?
        # Let's clarify:
        # In the naive approach, `mask` was an integer where bit i indicates if demand i is CCW (1) or CW (0).
        # We iterated `mask` from 0 to 2^D - 1.
        # The load for `mask` is base + sum(delta[i] for i in set_bits(mask)).
        
        # In Gray code iteration, we visit states in a different order.
        # Let `g` be the Gray code value.
        # The state of the bits is `g`.
        # But does `g` represent the routing mask directly?
        # If we define the state of the system as the vector of routing decisions, and we traverse the hypercube using Gray code,
        # then the "coordinate" of the vertex is the Gray code value?
        # No, the Gray code value IS the vertex label in the Gray code sequence.
        # However, the mapping from "Routing Mask" (binary) to "Vertex" is identity.
        # The Gray code sequence visits all binary integers 0..2^D-1, but in a specific order.
        # If we iterate `i` from 0 to 2^D-1, and compute `g = i ^ (i>>1)`, then `g` is the binary integer corresponding to the current routing configuration?
        # NO.
        # If we want to visit all routing configurations (which are binary vectors), we can just iterate the binary vector `x`.
        # The "Gray code trick" is usually used when you want to update a state that depends on the bits, and you want to change only one bit at a time to make the update O(1).
        # If we iterate `i` from 0 to 2^D-1, and we want the state to be the binary representation of `i`, then the bit that changes between `i-1` and `i` is NOT necessarily just one bit (e.g., 7->8 changes 3 bits).
        # So, to use the O(1) update trick, we must iterate through the states in Gray code order.
        # Let `g_k` be the k-th Gray code.
        # `g_k` is a binary number.
        # We want to evaluate the load for the routing configuration defined by the bits of `g_k`.
        # Let `x` be the routing vector. `x[i] = bit_i(g_k)`.
        # The load is `base + sum(delta[i] * x[i])`.
        # When we move from `g_{k-1}` to `g_k`, exactly one bit flips.
        # Let `bit_idx` be the index of the flipped bit.
        # If the bit flipped from 0 to 1, we ADD `delta[bit_idx]`.
        # If the bit flipped from 1 to 0, we SUBTRACT `delta[bit_idx]`.
        
        # How to know if it flipped 0->1 or 1->0?
        # We can look at the bit in `g_k`.
        # If `bit_idx` is 1 in `g_k`, it became 1 (so we added).
        # If `bit_idx` is 0 in `g_k`, it became 0 (so we subtracted).
        
