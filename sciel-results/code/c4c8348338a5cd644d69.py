    for i in range(1, total_masks):
        if i % 1000 == 0:
            if time.time() > deadline:
                break
        
        # Find bit that changed
        bit_index = (i & -i).bit_length() - 1
        
        # Determine if bit became 1 or 0
        # The current Gray code is g = i ^ (i >> 1)
        # We don't actually need to compute the full Gray code to know the bit value.
        # We just need to know if bit `bit_index` is 1 in the current Gray code `g`.
        # g = i ^ (i >> 1)
        # Let's just compute the bit.
        g = i ^ (i >> 1)
        if (g >> bit_index) & 1:
            # Bit is 1, so it flipped 0->1. We ADD delta.
            current_load += delta_mat[bit_index]
