import numpy as np
import time

DIMENSIONS = [4, 4, 8]

def construct():
    n, m, p = DIMENSIONS
    
    # Strassen decomposition for 2x2x2
    # U2, V2, W2 are 4x7
    U2 = np.zeros((4, 7))
    V2 = np.zeros((4, 7))
    W2 = np.zeros((4, 7))
    
    # r=0: M1 = (A00+A11)(B00+B11)
    U2[0, 0] = 1; U2[3, 0] = 1
    V2[0, 0] = 1; V2[3, 0] = 1
    W2[0, 0] = 1; W2[3, 0] = 1 # C00 += M1, C11 += M1
    
    # r=1: M2 = (A10+A11)B00
    U2[2, 1] = 1; U2[3, 1] = 1
    V2[0, 1] = 1
    W2[1, 1] = 1; W2[3, 1] = -1 # C10 += M2, C11 -= M2
    
    # r=2: M3 = A00(B01-B11)
    U2[0, 2] = 1
    V2[1, 2] = 1; V2[3, 2] = -1
    W2[2, 2] = 1; W2[3, 2] = 1 # C01 += M3, C11 += M3
    
    # r=3: M4 = A11(B10-B00)
    U2[3, 3] = 1
    V2[0, 3] = -1; V2[2, 3] = 1
    W2[0, 3] = 1; W2[1, 3] = 1 # C00 += M4, C10 += M4
    
    # r=4: M5 = (A00+A01)B11
    U2[0, 4] = 1; U2[1, 4] = 1
    V2[3, 4] = 1
    W2[0, 4] = -1; W2[2, 4] = 1 # C00 -= M5, C01 += M5
    
    # r=5: M6 = (A10-A00)(B00+B01)
    U2[0, 5] = -1; U2[2, 5] = 1
    V2[0, 5] = 1; V2[1, 5] = 1
    W2[3, 5] = 1 # C11 += M6
    
    # r=6: M7 = (A01-A11)(B10+B11)
    U2[1, 6] = 1; U2[3, 6] = -1
    V2[2, 6] = 1; V2[3, 6] = 1
    W2[0, 6] = 1 # C00 += M7
    
    # Construct 4x4x4 decomposition (Rank 49)
    # U4, V4, W4 are 16x49
    U4 = np.zeros((16, 49))
    V4 = np.zeros((16, 49))
    W4 = np.zeros((16, 49))
    
    for ro in range(7):
        for ri in range(7):
            r = ro * 7 + ri
            # Process U
            for uo in range(4):
                if U2[uo, ro] != 0:
                    I = uo // 2
                    J = uo % 2
                    for ui in range(4):
                        if U2[ui, ri] != 0:
                            ip = ui // 2
                            jp = ui % 2
                            i = 2 * I + ip
                            j = 2 * J + jp
                            idx = i * 4 + j
                            U4[idx, r] = U2[uo, ro] * U2[ui, ri]
            
            # Process V
            for vo in range(4):
                if V2[vo, ro] != 0:
                    J = vo // 2
                    K = vo % 2
                    for vi in range(4):
                        if V2[vi, ri] != 0:
                            jp = vi // 2
                            kp = vi % 2
                            j = 2 * J + jp
                            k = 2 * K + kp
                            idx = j * 4 + k
                            V4[idx, r] = V2[vo, ro] * V2[vi, ri]
                            
            # Process W
            for wo in range(4):
                if W2[wo, ro] != 0:
                    K = wo // 2
                    I = wo % 2
                    for wi in range(4):
                        if W2[wi, ri] != 0:
                            kp = wi // 2
                            ip = wi % 2
                            k = 2 * K + kp
                            i = 2 * I + ip
                            idx = k * 4 + i
                            W4[idx, r] = W2[wo, ro] * W2[wi, ri]

    # Construct 4x4x8 decomposition (Rank 98)
    rank = 98
    U = np.zeros((16, rank))
    V = np.zeros((32, rank))
    W = np.zeros((32, rank))
    
    # Left block (columns 0-3 of output)
    U[:, 0:49] = U4
    for j in range(4):
        for k in range(4):
            V[j * 8 + k, 0:49] = V4[j * 4 + k, :]
            W[k * 4 + j, 0:49] = W4[k * 4 + j, :]
            
    # Right block (columns 4-7 of output)
    U[:, 49:98] = U4
    for j in range(4):
        for k in range(4):
            V[j * 8 + (4 + k), 49:98] = V4[j * 4 + k, :]
            W[(4 + k) * 4 + j, 49:98] = W4[k * 4 + j, :]

    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
