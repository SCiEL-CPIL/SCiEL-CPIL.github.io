def construct():
    """
    Returns a rank-minimal exact tensor decomposition for multiplying 
    a 3x5 matrix by a 5x6 matrix.
    
    Currently implements the schoolbook decomposition of rank n*m*p = 90.
    This is guaranteed to be valid and exact with integer entries.
    """
    n, m, p = DIMENSIONS
    rank = n * m * p
    
    # Initialize matrices with zeros
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Construct schoolbook decomposition
    # For each (i, j, k), we have a term in the sum.
    # U[i*m + j, col] = 1
    # V[j*p + k, col] = 1
    # W[k*n + i, col] = 1
    # This ensures that (AB)[i,k] = sum_j A[i,j]B[j,k]
    
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
