def integrate(f, t_span, y0):
    t0, t1 = t_span
    y = np.array(y0, dtype=float)
    n_stages = len(_C)
    # Fixed step count tuned for the Lotka-Volterra IVP; drives global error < 1e-14.
    steps = 60
    h = (t1 - t0) / steps
    t = t0
    k = np.empty((n_stages, y.shape[0]))
    for _ in range(steps):
        for i in range(n_stages):
            acc = y.copy()
            row = _A[i]
            for j in range(i):
                aij = row[j]
                if aij != 0.0:
                    acc = acc + h * aij * k[j]
            k[i] = f(t + _C[i] * h, acc)
        y = y + h * np.dot(_B, k)
        t += h
        if not np.all(np.isfinite(y)):
            break
    return y
