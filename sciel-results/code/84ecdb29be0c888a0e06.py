"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 100

# EVOLVE-BLOCK-START
import numpy as np
import time
from scipy.optimize import minimize

def construct():
    t0 = time.time()
    deadline = t0 + 110.0  # Safety margin: evaluator kills at 150s, aim to finish by 110s
    
    # 1. Generate a dense FCC lattice candidate pool
    # FCC unit cell vectors:
    # a1 = (0, 1, 1)
    # a2 = (1, 0, 1)
    # a3 = (1, 1, 0)
    # Lattice points are integer combinations of these, or shifted by (0.5, 0.5, 0.5)
    # To cover the cube [-0.5, 0.5]^3, we need a range of indices.
    # Let's generate points in a grid of FCC cells.
    
    # Scaling factor to make the lattice dense enough to pick 100 good points.
    # A 5x5x5 grid of simple cubic cells would have 125 points.
    # FCC has 4 points per cell.
    # Let's try generating points from a 4x4x4 grid of FCC unit cells.
    # That gives 4^3 * 4 = 256 points.
    # We will select the 100 with the best "boundary score".
    
    def generate_fcc_candidates():
        # Basis vectors
        a1 = np.array([0, 1, 1])
        a2 = np.array([1, 0, 1])
        a3 = np.array([1, 1, 0])
        
        # We want to fill the cube [-0.5, 0.5].
        # The FCC lattice is dense. Let's define a range for the integer indices.
        # The extent of the lattice generated by indices i,j,k in [-K, K] is roughly 2K.
        # We want to cover [-0.5, 0.5], so we need a small K, but we need enough points.
        # Actually, let's just generate a grid of points based on the FCC structure
        # scaled to fit the cube.
        
        # Alternative: Generate a simple cubic grid of side L, and for each cell,
        # add the 4 FCC points.
        # Let's use a 5x5x5 grid of cells. Side length of cube is 1.
        # Cell size = 1/5 = 0.2.
        # FCC points in a cell of size s:
        # (0,0,0), (0, s/2, s/2), (s/2, 0, s/2), (s/2, s/2, 0) relative to cell corner.
        
        m = 5
        cell_size = 1.0 / m
        points = []
        
        for i in range(m):
            for j in range(m):
                for k in range(m):
                    x0 = -0.5 + i * cell_size
                    y0 = -0.5 + j * cell_size
                    z0 = -0.5 + k * cell_size
                    
                    # 4 points in FCC cell
                    p1 = np.array([x0, y0, z0])
                    p2 = np.array([x0, y0 + cell_size/2, z0 + cell_size/2])
                    p3 = np.array([x0 + cell_size/2, y0, z0 + cell_size/2])
                    p4 = np.array([x0 + cell_size/2, y0 + cell_size/2, z0])
                    
                    points.extend([p1, p2, p3, p4])
                    
        points = np.array(points)
        # Filter points strictly inside the cube (with small margin to avoid boundary issues in selection)
        mask = np.all(np.abs(points) < 0.49, axis=1)
        points = points[mask]
        
        return points

    candidates = generate_fcc_candidates()
    
    # 2. Select 100 points from candidates
    # We want to maximize the minimum distance to the boundary for the selected set?
    # No, we want to maximize the packing radius.
    # A good heuristic: select points that are well-distributed.
    # Let's just take the 100 points that are furthest from the boundary? 
    # That might cluster them in the center.
    # Better: Greedy selection maximizing minimum distance to already selected points.
    
    def select_points(candidates, n_select):
        selected = []
        remaining = list(range(len(candidates)))
        
        # Start with the point furthest from the boundary (center)
        dists_to_boundary = 0.5 - np.max(np.abs(candidates), axis=1)
        center_idx = np.argmax(dists_to_boundary)
        selected.append(center_idx)
        remaining.remove(center_idx)
        
        while len(selected) < n_select:
            # For each remaining point, calculate min distance to selected points
            # and distance to boundary.
            # We want to maximize the "effective radius" if we add this point.
            # This is complex. Let's just use max-min distance to selected points.
            # This creates a well-spaced set.
            
            best_idx = -1
            best_score = -np.inf
            
            # Subsample if too many candidates to speed up selection?
            # 256 candidates is small, so full check is fine.
            for idx in remaining:
                p = candidates[idx]
                dists_to_selected = np.linalg.norm(p - candidates[selected], axis=1)
                min_dist_to_selected = np.min(dists_to_selected)
                
                # Also consider distance to boundary
                dist_to_boundary = 0.5 - np.max(np.abs(p))
                
                # Score: primarily min dist to neighbors, secondarily boundary
                # We want to maximize the min of these.
                score = min(min_dist_to_selected, dist_to_boundary * 2) # Weight boundary less?
                # Actually, just maximizing min_dist_to_selected usually works well for packing.
                # Let's stick to simple max-min distance for selection.
                if min_dist_to_selected > best_score:
                    best_score = min_dist_to_selected
                    best_idx = idx
            
            if best_idx == -1: break
            selected.append(best_idx)
            remaining.remove(best_idx)
            
        return candidates[selected]

    x0 = select_points(candidates, N)
    
    # 3. Optimization
    # Use a smooth approximation of the radius objective to use L-BFGS-B.
    # Objective: minimize -radius
    # radius = min( min_pairwise_dist/2, min_boundary_dist )
    
    # Soft-min approximation:
    # soft_min(x, y, beta) = -1/beta * log( exp(-beta*x) + exp(-beta*y) )
    # This is differentiable.
    
    def soft_min(x, y, beta=100.0):
        # Avoid overflow
        m = np.minimum(x, y)
        return m - (1.0/beta) * np.log(np.exp(-beta*(x-m)) + np.exp(-beta*(y-m)))
    
    def objective_and_grad(x_flat):
        x = x_flat.reshape(-1, 3)
        
        # Pairwise distances
        # This is O(N^2 * 3) memory and compute. N=100, so 10000 pairs. Fine.
        diff = x[:, np.newaxis, :] - x[np.newaxis, :, :]
        dists = np.linalg.norm(diff, axis=2)
        np.fill_diagonal(dists, np.inf)
        
        # We need the min pairwise distance.
        # To make it differentiable, we can sum exp(-beta * dists)
        # min_d ~ -1/beta * log( sum_{i<j} exp(-beta * d_ij) )
        
        beta = 50.0
        
        # Mask upper triangle
        mask = np.triu(np.ones((N, N), dtype=bool), k=1)
        upper_dists = dists[mask]
        
        # Soft min of pairwise distances
        # Using log-sum-exp for stability
        min_d_upper = np.min(upper_dists)
        log_sum_exp = min_d_upper + np.log(np.sum(np.exp(-(upper_dists - min_d_upper) * beta)))
        soft_min_pair = -log_sum_exp / beta
        
        # Boundary distances
        wall_dists = 0.5 - np.abs(x) # shape (N, 3)
        flat_wall = wall_dists.flatten()
        
        min_wall = np.min(flat_wall)
        log_sum_exp_wall = min_wall + np.log(np.sum(np.exp(-(flat_wall - min_wall) * beta)))
        soft_min_wall = -log_sum_exp_wall / beta
        
        # Total soft min
        # We want min(soft_min_pair, soft_min_wall)
        # Approximate this with another soft min? Or just combine them.
        # Since we want to maximize the minimum, we can just take the soft min of the two.
        final_soft_min = soft_min(soft_min_pair, soft_min_wall, beta)
        
        # Objective is -final_soft_min
        obj = -final_soft_min
        
        # Gradient
        # This is tricky to derive analytically for the log-sum-exp chain.
        # Let's use finite difference or just return objective for L-BFGS-B numerical gradient?
        # L-BFGS-B supports numerical gradients. It's slower per eval but robust.
        # Given N=100, 300 vars. Numerical grad is 300 evals per step.
        # If we do 50 steps, that's 15000 evals.
        # Each eval is O(N^2) = 10000 ops. 15000 * 10000 = 1.5e8 ops.
        # This might be too slow in Python/NumPy if not vectorized perfectly.
        # NumPy vectorization is fast. 1.5e8 float ops is < 0.1s usually.
        # So numerical gradient should be fine.
        
        return obj

    # Initial bounds
    bounds = [(-0.5, 0.5)] * (N * 3)
    
    best_x = x0
    best_score_val = -objective_and_grad(x0.flatten()) # This is the soft min value, proxy for radius
    
    # Perform optimization
    try:
        res = minimize(
            objective_and_grad, 
            x0.flatten(), 
            method='L-BFGS-B', 
            bounds=bounds,
            options={'maxiter': 200, 'ftol': 1e-12, 'gtol': 1e-8, 'maxls': 50}
        )
        
        if res.fun < -best_score_val:
            best_x = res.x.reshape(-1, 3)
            best_score_val = -res.fun
            
    except Exception as e:
        pass
    
    # Local refinement with exact objective (non-differentiable)
    # Use a simple coordinate descent or small perturbations
    # Calculate exact score
    def exact_score(x):
        x = x.reshape(-1, 3)
        diff = x[:, np.newaxis, :] - x[np.newaxis, :, :]
        dists = np.linalg.norm(diff, axis=2)
        np.fill_diagonal(dists, np.inf)
        min_pair = np.min(dists) / 2.0
        wall_dists = 0.5 - np.abs(x)
        min_wall = np.min(wall_dists)
        return min(min_pair, min_wall)
        
    current_score = exact_score(best_x)
    
    # Time check
    if time.time() < deadline - 5:
        # Simple local search
        for iter in range(50):
            if time.time() > deadline - 2: break
            improved = False
            # Random perturbation
            for _ in range(10):
                x_new = best_x + 0.001 * np.random.randn(*best_x.shape)
                x_new = np.clip(x_new, -0.499, 0.499)
                s_new = exact_score(x_new)
                if s_new > current_score + 1e-8:
                    best_x = x_new
                    current_score = s_new
                    improved = True
            if not improved:
                break
                
    # Final clamp
    best_x = np.clip(best_x, -0.4999, 0.4999)
    
    return best_x

# EVOLVE-BLOCK-END
