import numpy as np
from scipy.optimize import minimize, differential_evolution
from scipy.special import eval_hermite
import time

def construct():
    """Find optimal coefficients c0, c4, c8 to minimize the bound."""
    start_time = time.time()
    deadline = start_time + 175.0  # Safety margin before 210s kill
    
    # Hermite polynomial values at 0 for the constraint P(0)=0
    # Using physicists' Hermite polynomials
    # H0(0) = 1
    # H4(0) = 12
    # H8(0) = 1680
    # H12(0) = 1032192 (Note: Inspiration 2 uses 665280, let's verify)
    # H_n(0) = (-1)^(n/2) * n! / (n/2)! for even n
    # H_12(0) = (-1)^6 * 12! / 6! = 479001600 / 720 = 665280.
    # Wait, the current program uses 1032192. Let's check.
    # 12! = 479001600. 6! = 720. 479001600 / 720 = 665280.
    # Why does the current program use 1032192?
    # Let's re-read the current program. It says H12_0 = 1032192.0.
    # Inspiration 1 uses 40320 in the denominator for v0, which is 8! ? No, 8! is 40320.
    # Inspiration 1: c12 = -(c0 + 12c4 + 1680c8) / 40320.
    # This implies H12(0) = 40320? No, that would mean H12(0) is 8!.
    # Let's check H8(0) = 1680. 8! / 4! = 40320 / 24 = 1680. Correct.
    # H4(0) = 12. 4! / 2! = 24 / 2 = 12. Correct.
    # H12(0) should be 12! / 6! = 479001600 / 720 = 665280.
    # The current program has 1032192. This is likely a bug in the seed/current program.
    # Inspiration 2 has 665280.
    # Inspiration 1 has 40320 in the denominator of the constraint logic?
    # v0 = (H0 - H12 / 40320.0) * gauss.
    # If c12 = -(c0*1 + c4*12 + c8*1680) / H12_0.
    # Then g = c0*H0 + c4*H4 + c8*H8 + c12*H12.
    # g = c0(H0 - H12/H12_0) + ...
    # If H12_0 = 665280, then the term is H12/665280.
    # Inspiration 1 uses H12/40320. This suggests they think H12_0 = 40320?
    # Or maybe they are using a different normalization?
    # The task says "Hermite-polynomial". Usually physicists' H_n.
    # Let's stick to the mathematically correct value: 665280.
    # However, if the evaluator uses a specific definition, we must match it.
    # The prompt says "H0,H4,H8".
    # Let's assume standard physicists' Hermite polynomials.
    # H12(0) = 665280.
    
    H0_0 = 1.0
    H4_0 = 12.0
    H8_0 = 1680.0
    H12_0 = 665280.0
    
    # Grid setup
    # Using a larger grid for better FFT accuracy and integration
    N = 8192
    x = np.linspace(-25, 25, N)
    dx = x[1] - x[0]
    
    # Precompute Hermite polynomials on the grid
    H0 = eval_hermite(0, x)
    H4 = eval_hermite(4, x)
    H8 = eval_hermite(8, x)
    H12 = eval_hermite(12, x)
    gauss = np.exp(-x**2 / 2.0)
    
    # Effective basis vectors incorporating the g(0)=0 constraint
    # c12 = -(c0*H0_0 + c4*H4_0 + c8*H8_0) / H12_0
    # g = (c0*H0 + c4*H4 + c8*H8 + c12*H12) * gauss
    # g = c0*(H0 - H0_0/H12_0 * H12)*gauss + c4*(H4 - H4_0/H12_0 * H12)*gauss + c8*(H8 - H8_0/H12_0 * H12)*gauss
    
    v0 = (H0 - (H0_0 / H12_0) * H12) * gauss
    v4 = (H4 - (H4_0 / H12_0) * H12) * gauss
    v8 = (H8 - (H8_0 / H12_0) * H12) * gauss
    
    # Precompute Gram matrices for L2 norm, x^2 moment, and k^2 moment
    # M_ij = <v_i, v_j>
    # Mx_ij = <x^2 v_i, v_j>
    # Mf_ij = <k^2 G_i, G_j> where G is FFT
    
    M = np.zeros((3, 3))
    M[0, 0] = np.trapz(v0**2, x)
    M[1, 1] = np.trapz(v4**2, x)
    M[2, 2] = np.trapz(v8**2, x)
    M[0, 1] = M[1, 0] = np.trapz(v0 * v4, x)
    M[0, 2] = M[2, 0] = np.trapz(v0 * v8, x)
    M[1, 2] = M[2, 1] = np.trapz(v4 * v8, x)
    
    Mx = np.zeros((3, 3))
    Mx[0, 0] = np.trapz(x**2 * v0**2, x)
    Mx[1, 1] = np.trapz(x**2 * v4**2, x)
    Mx[2, 2] = np.trapz(x**2 * v8**2, x)
    Mx[0, 1] = Mx[1, 0] = np.trapz(x**2 * v0 * v4, x)
    Mx[0, 2] = Mx[2, 0] = np.trapz(x**2 * v0 * v8, x)
    Mx[1, 2] = Mx[2, 1] = np.trapz(x**2 * v4 * v8, x)
    
    # Fourier transform components
    # Using FFT. Note: The frequency axis for FFT of x in [-L, L] with N points
    # is k = 2*pi * fftfreq(N, d=dx)
    # We need to be careful with the scaling.
    # F(k) = integral f(x) e^{-ikx} dx ~ sum f(x_n) e^{-ik x_n} dx
    # np.fft.fft computes sum f[n] e^{-2 pi i n k / N}
    # So if we set k such that 2 pi k / N = k_fft * dx ? No.
    # Standard FFT: X[k] = sum_{n=0}^{N-1} x[n] exp(-i 2 pi k n / N)
    # Our integral: I = sum x[n] exp(-i k x_n) dx
    # x_n = x_min + n dx
    # exp(-i k x_n) = exp(-i k x_min) exp(-i k n dx)
    # If we choose k values such that k dx = 2 pi m / N, then m = k N dx / 2 pi
    # The frequencies generated by np.fft.fftfreq(N, d=dx) are f = m / (N dx)
    # Angular frequency omega = 2 pi f = 2 pi m / (N dx)
    # So omega dx = 2 pi m / N. This matches the exponent in FFT.
    # So G = dx * fftshift(fft(ifftshift(v))) gives the integral approximation for omega = 2*pi*fftfreq.
    
    freqs = 2 * np.pi * np.fft.fftshift(np.fft.fftfreq(N, d=dx))
    
    G0 = np.fft.fftshift(np.fft.fft(np.fft.ifftshift(v0))) * dx
    G4 = np.fft.fftshift(np.fft.fft(np.fft.ifftshift(v4))) * dx
    G8 = np.fft.fftshift(np.fft.fft(np.fft.ifftshift(v8))) * dx
    
    Mf = np.zeros((3, 3))
    # Mf_ij = integral k^2 G_i(k) conj(G_j(k)) dk
    # Since G are complex, we take real part of the product.
    Mf[0, 0] = np.trapz(freqs**2 * np.abs(G0)**2, freqs)
    Mf[1, 1] = np.trapz(freqs**2 * np.abs(G4)**2, freqs)
    Mf[2, 2] = np.trapz(freqs**2 * np.abs(G8)**2, freqs)
    Mf[0, 1] = Mf[1, 0] = np.trapz(freqs**2 * np.real(G0 * np.conj(G4)), freqs)
    Mf[0, 2] = Mf[2, 0] = np.trapz(freqs**2 * np.real(G0 * np.conj(G8)), freqs)
    Mf[1, 2] = Mf[2, 1] = np.trapz(freqs**2 * np.real(G4 * np.conj(G8)), freqs)
    
    def compute_bound_from_coeffs(c):
        """Compute bound for a specific coefficient vector c."""
        c = np.array(c)
        norm2 = c @ M @ c
        if norm2 <= 1e-15 or not np.isfinite(norm2):
            return 1e10
        
        x2_norm = c @ Mx @ c
        freq2_norm = c @ Mf @ c
        
        if not np.isfinite(x2_norm) or x2_norm < 0 or not np.isfinite(freq2_norm) or freq2_norm < 0:
            return 1e10
            
        # Variance in x: E[x^2] - (E[x])^2. Since functions are even, E[x]=0.
        # So Var(x) = E[x^2] = x2_norm / norm2
        # Var(k) = E[k^2] = freq2_norm / norm2
        delta_x = np.sqrt(x2_norm / norm2)
        delta_k = np.sqrt(freq2_norm / norm2)
        
        # The "upper bound on A(f)*A(Fourier(f))" is typically the product of standard deviations
        # or related to it. The seed program returned sigma_x * sigma_k.
        return delta_x * delta_k

    def compute_bound_from_spherical(theta, phi):
        """Compute bound for spherical parameters.
        theta in [0, pi], phi in [0, 2*pi]
        c0 = sin(theta) cos(phi)
        c4 = sin(theta) sin(phi)
        c8 = cos(theta)
        """
        c0 = np.sin(theta) * np.cos(phi)
        c4 = np.sin(theta) * np.sin(phi)
        c8 = np.cos(theta)
        return compute_bound_from_coeffs([c0, c4, c8])

    # Initial best guess from seed
    # Seed: c0 = -113/100, c4 = 1/25, c8 = 1/3240
    c_seed = np.array([-113.0 / 100.0, 1.0 / 25.0, 1.0 / 3240.0])
    c_seed_norm = c_seed / np.linalg.norm(c_seed)
    
    c0, c4, c8 = c_seed_norm
    # Convert to spherical
    # c8 = cos(theta) => theta = arccos(c8)
    # c0 = sin(theta) cos(phi), c4 = sin(theta) sin(phi)
    # phi = arctan2(c4, c0)
    theta_init = np.arccos(np.clip(c8, -1.0, 1.0))
    phi_init = np.arctan2(c4, c0)
    if phi_init < 0:
        phi_init += 2 * np.pi

    best_bound = compute_bound_from_spherical(theta_init, phi_init)
    best_theta = theta_init
    best_phi = phi_init
    
    # Strategy:
    # 1. Global optimization using Differential Evolution on the 2D spherical space.
    #    This avoids local minima and handles the non-convexity well.
    # 2. Local refinement with Nelder-Mead or BFGS from the best DE result.
    
    # Check time
    elapsed = time.time() - start_time
    if elapsed < deadline - 60.0:
        try:
            # Use a moderate population size for speed
            # Bounds: theta in (0, pi), phi in (0, 2*pi)
            bounds = [(1e-6, np.pi - 1e-6), (1e-6, 2 * np.pi - 1e-6)]
            
            de_result = differential_evolution(
                compute_bound_from_spherical, 
                bounds, 
                seed=42, 
                maxiter=100, 
                tol=1e-8,
                popsize=15,
                polish=False # We will polish manually to save time/ensure control
            )
            if de_result.fun < best_bound:
                best_bound = de_result.fun
                best_theta, best_phi = de_result.x
        except Exception:
            pass

    # Local refinement
    elapsed = time.time() - start_time
    if elapsed < deadline - 20.0:
        try:
            # Use BFGS if gradient is available? No, we don't have analytic gradient.
            # Nelder-Mead is robust.
            res = minimize(
                compute_bound_from_spherical, 
                x0=[best_theta, best_phi], 
                method='Nelder-Mead',
                options={'xatol': 1e-12, 'fatol': 1e-14, 'maxiter': 5000, 'adaptive': True}
            )
            if res.fun < best_bound:
                best_bound = res.fun
                best_theta, best_phi = res.x
        except Exception:
            pass

    # Convert back to Cartesian coefficients
    c0 = np.sin(best_theta) * np.cos(best_phi)
    c4 = np.sin(best_theta) * np.sin(best_phi)
    c8 = np.cos(best_theta)
    
    # Optional: Verify with a direct check if time permits
    # But the Gram matrix method is exact for the linear combination.
    
    return np.array([c0, c4, c8])

