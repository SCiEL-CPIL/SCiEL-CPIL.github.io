import numpy as np
import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 45.0
    
    N = 17
    MIN_DIST = 6
    
    # 1. Construct the 256-word linear code
    # Quadratic residues mod 17
    Q = {1, 2, 4, 8, 9, 13, 15, 16}
    g = np.zeros(17, dtype=np.uint8)
    for q in Q:
        g[q] = 1
        
    basis = []
    for i in range(9):
        v = np.roll(g, i)
        basis.append(v)
    basis = np.array(basis)
    
    codewords = []
    for mask in range(512):
        w = np.zeros(17, dtype=np.uint8)
        for i in range(9):
            if (mask >> i) & 1:
                w ^= basis[i]
        if np.sum(w) % 2 == 0:
            val = 0
            for j in range(17):
                if w[j]:
                    val |= (1 << j)
            codewords.append(val)
            
    selected = set(codewords)
    # selected has 256 words
    
    # Helper to check validity
    def is_valid(w, code_set):
        for c in code_set:
            if (w ^ c).bit_count() < MIN_DIST:
                return False
        return True

    # Helper to try to repair a conflict
    # If w conflicts with c in code_set, try to move c to c'
    def try_repair(w, c, code_set):
        # Generate neighbors of c with Hamming distance 1 or 2
        # Distance 1: 17 neighbors
        # Distance 2: 17*16/2 = 136 neighbors
        # Total ~153 neighbors
        
        # First try distance 1
        for i in range(N):
            c_prime = c ^ (1 << i)
            if c_prime in code_set:
                continue
            # Check if c_prime is valid with respect to code_set - {c}
            valid = True
            for c_other in code_set:
                if c_other == c:
                    continue
                if (c_prime ^ c_other).bit_count() < MIN_DIST:
                    valid = False
                    break
            if not valid:
                continue
            # Check if c_prime is far enough from w
            if (w ^ c_prime).bit_count() >= MIN_DIST:
                return c_prime
        return None

    # Main loop
    # We will try to add random words.
    # To ensure we explore the space, we can also try to "kick" the code by moving random words.
    
    # Optimization: Pre-compute list of all words? 2^17 = 131072.
    # We can iterate through them in random order.
    
    # Let's use a list of all integers and shuffle?
    # Or just generate random integers.
    
    # A better strategy: 
    # 1. Try to add words from a pool of "promising" candidates.
    #    Candidates can be generated by taking existing words and flipping bits.
    #    This keeps the search local.
    
    # Let's combine:
    # 1. Random global candidates.
    # 2. Local candidates (neighbors of existing words).
    
    # To avoid getting stuck, we can use a "temperature" or just randomization.
    
    # Let's try a simple loop:
    # For each iteration:
    #   Pick a random candidate w.
    #   If w is valid, add it.
    #   Else, find conflicts.
    #   For each conflict c, try to repair c.
    #   If repair successful, replace c and add w.
    
    # We need to be careful with time.
    
    # Let's estimate the number of iterations we can do.
    # Each check is O(|C|) ~ 300 ops.
    # Repair is O(|C| * 150) ~ 45000 ops.
    # Total ~ 50k ops per iteration.
    # 45 seconds / 50k ops = 900 iterations?
    # Python is slow. 50k ops might take 1ms.
    # So ~45,000 iterations.
    
    # Let's run as many as possible.
    
    # To speed up conflict detection, we can break early.
    
    # Let's use a list for the code to iterate faster than set?
    # Set is O(1) for membership, but iteration order is arbitrary.
    # List is faster to iterate in Python? No, list iteration is similar.
    # But we need to check distance to ALL elements.
    
    # Let's stick to the set for membership, but convert to list for iteration if needed?
    # Actually, `for c in selected:` is fine.
    
    # One issue: if we add many words, the set grows.
    
    # Let's implement the loop.
    
    # We will try to add words.
    # We will also try to "move" words to open space, even if we don't add a new one immediately.
    # This is harder. Let's stick to Add + Repair.
    
    # To find good candidates, we can look at the "holes" in the code.
    # A word w is a candidate if it has small distance to some existing words but large to others.
    
    # Let's just use random candidates first.
    
    # Also, we should try to add the word 0? It's already in the linear code.
    
    # Let's run the loop.
    
    # To improve success rate, we can try multiple repair attempts per candidate.
    
    # Also, we can try to repair by moving TWO words?
    # That's complex. Let's start with single word repair.
    
    # If single word repair fails, try distance 2 neighbors for repair.
    
    # Let's update try_repair to include distance 2.
    
    def try_repair_extended(w, c, code_set):
        # Distance 1
        for i in range(N):
            c_prime = c ^ (1 << i)
            if c_prime in code_set:
                continue
            valid = True
            for c_other in code_set:
                if c_other == c:
                    continue
                if (c_prime ^ c_other).bit_count() < MIN_DIST:
                    valid = False
                    break
            if valid and (w ^ c_prime).bit_count() >= MIN_DIST:
                return c_prime
        
        # Distance 2
        # Generate pairs of bits to flip
        for i in range(N):
            for j in range(i + 1, N):
                c_prime = c ^ (1 << i) ^ (1 << j)
                if c_prime in code_set:
                    continue
                valid = True
                for c_other in code_set:
                    if c_other == c:
                        continue
                    if (c_prime ^ c_other).bit_count() < MIN_DIST:
                        valid = False
                        break
                if valid and (w ^ c_prime).bit_count() >= MIN_DIST:
                    return c_prime
        return None

    # Main Loop
    # We will try to add random words.
    # If we add a word, great.
    # If not, we try to repair.
    
    # To ensure we don't just loop on the same failing candidates,
    # we can keep a history of failed candidates?
    # Or just randomize heavily.
    
    # Let's also try to "kick" the code:
    # Pick a random word c in selected.
    # Try to move it to a random neighbor c' (dist 1 or 2) if valid.
    # This might open up space for future additions.
    # This is a "null move".
    
    # Let's alternate between Add attempts and Null moves.
    
    # Or just Add attempts with Repair.
    
    # Let's run until deadline.
    
    # To speed up, we can pre-compute the list of all words?
    # No, random is fine.
    
    # One optimization: If we fail to add a word, we can try to add a word that is "closer" to the existing code?
    # No, we want words that are far.
    
    # Let's just do random candidates.
    
    # We will also try to add candidates that are generated by flipping 1 or 2 bits of existing words.
    # These are more likely to be valid or repairable.
    
    # Strategy:
    # 1. Pick a random existing word c.
    # 2. Generate a neighbor w (dist 1, 2, or 3).
    # 3. Try to add w.
    
    # This keeps the search local and likely to succeed.
    
    # Let's implement this.
    
    # We will maintain a list of "hot" candidates?
    # No, just generate on the fly.
    
    # Loop:
    while time.time() < deadline - 1.0:
        # Pick a random existing word to generate a candidate
        # If set is empty, pick random global word.
        if selected:
            c_base = random.choice(list(selected))
            # Generate a neighbor
            # Flip 1, 2, or 3 bits
            k = random.randint(1, 3)
            bits = random.sample(range(N), k)
            w = c_base
            for b in bits:
                w ^= (1 << b)
        else:
            w = random.randint(0, (1 << N) - 1)
            
        # Check if w is already in selected
        if w in selected:
            continue
            
        # Check validity
        conflicts = []
        for c in selected:
            if (w ^ c).bit_count() < MIN_DIST:
                conflicts.append(c)
                
        if not conflicts:
            selected.add(w)
            continue
            
        # Try to repair
        # We can try to repair any of the conflicting words
        # Shuffle conflicts to randomize
        random.shuffle(conflicts)
        
        repaired = False
        for c in conflicts:
            # Try to move c
            c_prime = try_repair_extended(w, c, selected)
            if c_prime is not None:
                # Replace c with c_prime
                selected.remove(c)
                selected.add(c_prime)
                # Now add w
                selected.add(w)
                repaired = True
                break
                
        # If not repaired, we can try to "kick" a random word to open space?
        # Or just continue.
        
    return list(selected)
