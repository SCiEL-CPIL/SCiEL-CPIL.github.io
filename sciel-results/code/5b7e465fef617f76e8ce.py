"""Rewritten program: Lazebnik-Ustimenko-Woldar CD(d,q) with correct d for girth g."""
import time

# EVOLVE-BLOCK-START
def construct(k, g):
    deadline = time.time() + 140.0
    q = k
    # Minimal d such that the LUW construction has girth >= g.
    # For the CD(d,q) family the girth grows with d; d = ceil((g-5)/2) is the
    # standard minimal choice (d=5 gives girth 16 for q=3).
    d = max(3, (g - 5 + 1) // 2)
    if d % 2 == 0:
        d += 1  # keep d odd for the standard girth guarantee
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add = lambda x, y: x ^ y
        sub = lambda x, y: x ^ y
        mul = lambda x, y: table[x][y]
    else:
        add = lambda x, y: (x + y) % q
        sub = lambda x, y: (x - y) % q
        mul = lambda x, y: (x * y) % q

    # Recurrence rule: for c = 2..d, rule[c] = (a, b)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r = (c - 5) % 4
        c0 = c - r
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                if side == 0:
                    y[c] = add(x[c], mul(y[a], x[b]))
                else:
                    y[c] = sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index = {start: 0}
    order = [start]
    edges = []
    for vertex in order:
        if time.time() > deadline:
            break
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
