"""Structural Change: Face-Count based Simulated Annealing with Swap Moves."""
# EVOLVE-BLOCK-START
import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 135  # Safety margin before 150s limit
    d = 7
    n = 2 ** d
    
    # Precompute all edges
    all_edges = []
    edge_to_idx = {}
    for x in range(n):
        for i in range(d):
            y = x ^ (1 << i)
            if x < y:
                idx = len(all_edges)
                all_edges.append((x, y))
                edge_to_idx[(x, y)] = idx
    
    m = len(all_edges)  # 448 edges
    
    # Precompute faces (4-cycles)
    # A face is defined by 2 distinct dimensions i, j and a starting vertex x
    # such that x has 0 bits in positions i and j (to avoid duplicates)
    # Actually, simpler: iterate all x, i, j where i < j.
    # The face vertices are x, x^i, x^j, x^i^j.
    # The 4 edges are:
    # e1: x - x^i
    # e2: x^j - x^i^j (parallel to e1)
    # e3: x - x^j
    # e4: x^i - x^i^j (parallel to e3)
    
    faces = []
    edge_faces = [[] for _ in range(m)]
    
    for x in range(n):
        for i in range(d):
            for j in range(i + 1, d):
                # Ensure we only count each face once.
                # Standard way: require x has 0 in bits i and j?
                # If x has 1 in bit i, then x^i has 0. The set of vertices is the same.
                # To uniquely identify the face, we can require that the minimum vertex in the face is x?
                # Or just check if we've seen it.
                # Better: iterate x from 0 to n-1. For each pair (i,j),
                # the face is uniquely determined if we fix the "base" x to have 0s in i and j?
                # No, x can be any vertex.
                # Let's just generate all potential faces and deduplicate by sorted tuple of edge indices.
                # There are 127 * 21 = 2667 potential (x, i, j) combos.
                # But each face is generated 4 times (by its 4 vertices) if we don't filter.
                # Actually, for a fixed face (vertices A, B, C, D), it is generated by:
                # (A, i, j), (B, i, j) where B=A^i, (C, i, j) where C=A^j, (D, i, j) where D=A^i^j.
                # So 4 times.
                # Total unique faces = 672.
                
                # To avoid duplicates, we can enforce that x has 0 in bit i AND 0 in bit j?
                # If x has 0 in i, then x^i has 1 in i.
                # If we require x to have 0 in i and j, then x is the unique vertex in the face with 0 in both.
                # Yes, this works.
                if (x & (1 << i)) == 0 and (x & (1 << j)) == 0:
                    v1 = x
                    v2 = x ^ (1 << i)
                    v3 = x ^ (1 << j)
                    v4 = x ^ (1 << i) ^ (1 << j)
                    
                    e1 = (min(v1, v2), max(v1, v2))
                    e2 = (min(v3, v4), max(v3, v4))
                    e3 = (min(v1, v3), max(v1, v3))
                    e4 = (min(v2, v4), max(v2, v4))
                    
                    idx1 = edge_to_idx[e1]
                    idx2 = edge_to_idx[e2]
                    idx3 = edge_to_idx[e3]
                    idx4 = edge_to_idx[e4]
                    
                    face_edges = (idx1, idx2, idx3, idx4)
                    faces.append(face_edges)
                    
                    for e_idx in face_edges:
                        edge_faces[e_idx].append(len(faces) - 1)
    
    num_faces = len(faces)
    
    def greedy_polish(chosen, face_counts):
        """Add all possible edges."""
        improved = True
        count = chosen.sum()
        while improved:
            improved = False
            for idx in range(m):
                if not chosen[idx]:
                    # Check if any face containing idx has count 3
                    can_add = True
                    for f_idx in edge_faces[idx]:
                        if face_counts[f_idx] >= 3:
                            can_add = False
                            break
                    if can_add:
                        chosen[idx] = True
                        count += 1
                        for f_idx in edge_faces[idx]:
                            face_counts[f_idx] += 1
                        improved = True
        return count
    
    def local_search(chosen, face_counts, count, T_init=1.0, T_min=0.001, cooling=0.9999, max_time=None):
        if max_time is None:
            max_time = deadline - time.time() - 5
        
        best_count = count
        best_chosen = chosen.copy()
        best_face_counts = face_counts.copy()
        no_improve = 0
        max_no_improve = 50000
        
        T = T_init
        while time.time() < max_time and T > T_min:
            idx = random.randint(0, m - 1)
            
            if not chosen[idx]:
                # Try to add
                can_add = True
                for f_idx in edge_faces[idx]:
                    if face_counts[f_idx] >= 3:
                        can_add = False
                        break
                
                if can_add:
                    # Accept improvement
                    chosen[idx] = True
                    count += 1
                    for f_idx in edge_faces[idx]:
                        face_counts[f_idx] += 1
                    
                    if count > best_count:
                        best_count = count
                        best_chosen = chosen.copy()
                        best_face_counts = face_counts.copy()
                        no_improve = 0
                    else:
                        no_improve += 1
                else:
                    # Try Swap: Remove a conflicting edge, add idx
                    # Find a face f containing idx with count 3
                    conflict_faces = [f_idx for f_idx in edge_faces[idx] if face_counts[f_idx] == 3]
                    
                    if conflict_faces:
                        f_idx = random.choice(conflict_faces)
                        # Pick a random edge in this face to remove
                        # The face has 4 edges. One is idx (not selected).
                        # The other 3 are selected.
                        face_e = faces[f_idx]
                        # Find the selected ones
                        candidates = [e for e in face_e if e != idx and chosen[e]]
                        if candidates:
                            rem_idx = random.choice(candidates)
                            # Tentative swap: remove rem_idx, add idx
                            # 1. Remove rem_idx
                            for f_idx2 in edge_faces[rem_idx]:
                                face_counts[f_idx2] -= 1
                            chosen[rem_idx] = False
                            count -= 1
                            
                            # 2. Check if idx can be added
                            can_add = True
                            for f_idx3 in edge_faces[idx]:
                                if face_counts[f_idx3] >= 3:
                                    can_add = False
                                    break
                            
                            if can_add:
                                # Accept (count is same, but structure changed)
                                # Actually, count is same. We accept swaps with probability 1?
                                # Or use SA acceptance?
                                # Since count doesn't change, we accept to escape local minima.
                                chosen[idx] = True
                                count += 1
                                for f_idx4 in edge_faces[idx]:
                                    face_counts[f_idx4] += 1
                                
                                # If count > best_count is false, we still accept to explore
                                no_improve += 1
                            else:
                                # Revert
                                chosen[rem_idx] = True
                                count += 1
                                for f_idx2 in edge_faces[rem_idx]:
                                    face_counts[f_idx2] += 1
                                no_improve += 1
                    else:
                        no_improve += 1
            else:
                # Consider removing idx
                # Only remove if it enables adding others?
                # In SA, we might accept removals to escape.
                # But removing decreases count.
                # Accept with prob exp(-1/T)
                if random.random() < np.exp(-1.0 / T):
                    chosen[idx] = False
                    count -= 1
                    for f_idx in edge_faces[idx]:
                        face_counts[f_idx] -= 1
                    no_improve += 1
                else:
                    no_improve += 1
            
            T *= cooling
            
            if no_improve > max_no_improve:
                chosen = best_chosen.copy()
                face_counts = best_face_counts.copy()
                count = best_count
                T = max(T, 1.0)
                no_improve = 0
        
        return best_chosen, best_face_counts, best_count
    
    # Multi-round search
    best_count = 0
    best_chosen = None
    
    random.seed(42)
    
    # Round 1: Greedy Random Construction
    chosen = np.zeros(m, dtype=bool)
    face_counts = np.zeros(num_faces, dtype=np.int32)
    
    # Random order greedy
    edge_order = list(range(m))
    random.shuffle(edge_order)
    
    for idx in edge_order:
        can_add = True
        for f_idx in edge_faces[idx]:
            if face_counts[f_idx] >= 3:
                can_add = False
                break
        if can_add:
            chosen[idx] = True
            for f_idx in edge_faces[idx]:
                face_counts[f_idx] += 1
    
    count = chosen.sum()
    count = greedy_polish(chosen, face_counts)
    
    if count > best_count:
        best_count = count
        best_chosen = chosen.copy()
        best_face_counts = face_counts.copy()
    
    # Local Search
    remaining = deadline - time.time() - 5
    if remaining > 5:
        chosen, face_counts, count = local_search(chosen, face_counts, count, T_init=1.0, T_min=0.001, cooling=0.9999, max_time=remaining)
        count = greedy_polish(chosen, face_counts)
        if count > best_count:
            best_count = count
            best_chosen = chosen.copy()
            best_face_counts = face_counts.copy()
    
    # Restart with different random seeds if time permits
    restarts = 5
    for r in range(restarts):
        if time.time() > deadline - 10:
            break
        
        random.seed(42 + r * 123)
        chosen = np.zeros(m, dtype=bool)
        face_counts = np.zeros(num_faces, dtype=np.int32)
        
        edge_order = list(range(m))
        random.shuffle(edge_order)
        
        for idx in edge_order:
            can_add = True
            for f_idx in edge_faces[idx]:
                if face_counts[f_idx] >= 3:
                    can_add = False
                    break
            if can_add:
                chosen[idx] = True
                for f_idx in edge_faces[idx]:
                    face_counts[f_idx] += 1
        
        count = chosen.sum()
        count = greedy_polish(chosen, face_counts)
        
        if count > best_count:
            best_count = count
            best_chosen = chosen.copy()
            best_face_counts = face_counts.copy()
        
        remaining = deadline - time.time() - 5
        if remaining > 5:
            chosen, face_counts, count = local_search(chosen, face_counts, count, T_init=1.0, T_min=0.001, cooling=0.9999, max_time=remaining)
            count = greedy_polish(chosen, face_counts)
            if count > best_count:
                best_count = count
                best_chosen = chosen.copy()
                best_face_counts = face_counts.copy()
    
    # Final polish
    count = greedy_polish(best_chosen, best_face_counts)
    if count > best_count:
        best_count = count
    
    # Convert to output
    out = []
    for idx in range(m):
        if best_chosen[idx]:
            x, y = all_edges[idx]
            out.append([x, y])
    
    return out
# EVOLVE-BLOCK-END
