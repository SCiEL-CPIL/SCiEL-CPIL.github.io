import numpy as np

DIMENSIONS = [2, 4, 4]

def construct():
    n, m, p = DIMENSIONS
    rank = 28
    U = [[0]*rank for _ in range(n*m)]
    V = [[0]*rank for _ in range(m*p)]
    W = [[0]*rank for _ in range(p*n)]
    
    col = 0
    def add_form(u_coeffs, v_coeffs, w_coeffs):
        nonlocal col
        for (idx, coeff) in u_coeffs:
            U[idx][col] += coeff
        for (idx, coeff) in v_coeffs:
            V[idx][col] += coeff
        for (idx, coeff) in w_coeffs:
            W[idx][col] += coeff
        col += 1
    
    # Strassen 2x2x2: A=[[a,b],[c,d]], B=[[e,f],[g,h]]
    # m1=(a+d)(e+h), m2=(c+d)e, m3=a(f-h), m4=d(g-e), m5=(a+b)h, m6=(c-a)(e+f), m7=(b-d)(g+h)
    # c11=m1-m5+m7, c12=m3+m5, c21=m2+m4, c22=m1-m2+m3+m6
    
    # Block 1: A[0:2,0:2] * B[0:2,0:4]
    # A: a=U[0], b=U[1], c=U[4], d=U[5]
    # B[0:2,0:2]: e=V[0], f=V[1], g=V[4], h=V[5]
    # B[0:2,2:4]: i=V[2], j=V[3], k=V[6], l=V[7]
    # C[0,0]=W[0], C[0,1]=W[2], C[1,0]=W[1], C[1,1]=W[3]
    # C[0,2]=W[4], C[0,3]=W[6], C[1,2]=W[5], C[1,3]=W[7]
    
    add_form([(0,1),(5,1)], [(0,1),(5,1)], [(0,1),(3,1)])  # m1
    add_form([(4,1),(5,1)], [(0,1)], [(1,1)])               # m2
    add_form([(0,1)], [(1,1),(5,-1)], [(2,1),(3,1)])        # m3
    add_form([(5,1)], [(4,1),(0,-1)], [(1,1)])              # m4
    add_form([(0,1),(1,1)], [(5,1)], [(2,1),(3,1)])         # m5
    add_form([(4,1),(0,-1)], [(0,1),(1,1)], [(3,1)])        # m6
    add_form([(1,1),(5,-1)], [(4,1),(5,1)], [(2,1)])        # m7
    
    add_form([(0,1),(5,1)], [(2,1),(7,1)], [(4,1),(7,1)])   # n1
    add_form([(4,1),(5,1)], [(2,1)], [(5,1)])               # n2
    add_form([(0,1)], [(3,1),(7,-1)], [(6,1),(7,1)])        # n3
    add_form([(5,1)], [(6,1),(2,-1)], [(5,1)])              # n4
    add_form([(0,1),(1,1)], [(7,1)], [(6,1),(7,1)])         # n5
    add_form([(4,1),(0,-1)], [(2,1),(3,1)], [(7,1)])        # n6
    add_form([(1,1),(5,-1)], [(6,1),(7,1)], [(6,1)])        # n7
    
    # Block 2: A[0:2,2:4] * B[2:4,0:4]
    # A: a'=U[2], b'=U[3], c'=U[6], d'=U[7]
    # B[2:4,0:2]: e'=V[8], f'=V[9], g'=V[12], h'=V[13]
    # B[2:4,2:4]: i'=V[10], j'=V[11], k'=V[14], l'=V[15]
    
    add_form([(2,1),(7,1)], [(8,1),(13,1)], [(0,1),(3,1)])  # p1
    add_form([(6,1),(7,1)], [(8,1)], [(1,1)])               # p2
    add_form([(2,1)], [(9,1),(13,-1)], [(2,1),(3,1)])       # p3
    add_form([(7,1)], [(12,1),(8,-1)], [(1,1)])             # p4
    add_form([(2,1),(3,1)], [(13,1)], [(2,1),(3,1)])        # p5
    add_form([(6,1),(2,-1)], [(8,1),(9,1)], [(3,1)])        # p6
    add_form([(3,1),(7,-1)], [(12,1),(13,1)], [(2,1)])      # p7
    
    add_form([(2,1),(7,1)], [(10,1),(15,1)], [(4,1),(7,1)]) # q1
    add_form([(6,1),(7,1)], [(10,1)], [(5,1)])              # q2
    add_form([(2,1)], [(11,1),(15,-1)], [(6,1),(7,1)])      # q3
    add_form([(7,1)], [(14,1),(10,-1)], [(5,1)])            # q4
    add_form([(2,1),(3,1)], [(15,1)], [(6,1),(7,1)])        # q5
    add_form([(6,1),(2,-1)], [(10,1),(11,1)], [(7,1)])      # q6
    add_form([(3,1),(7,-1)], [(14,1),(15,1)], [(6,1)])      # q7
    
    return {"U": U, "V": V, "W": W}
