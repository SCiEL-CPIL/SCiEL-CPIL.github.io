                    U = np.zeros(n*m); U[i*m+j] = 1
                    V = np.zeros(m*p); V[j*p+k] = 1; V[j*p+k+1] = 1
                    W = np.zeros(p*n); W[k*n+i] = 1; W[(k+1)*n+i] = 1
                    add_candidate(U, V, W)
                    
                    U = np.zeros(n*m); U[i*m+j] = 1
                    V = np.zeros(m*p); V[j*p+k] = 1; V[j*p+k+1] = -1
                    W = np.zeros(p*n); W[k*n+i] = 1; W[(k+1)*n+i] = -1
                    add_candidate(U, V, W)

