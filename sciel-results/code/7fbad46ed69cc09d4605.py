    for i0 in range(n-1):
        for j0 in range(m-1):
            for k0 in range(p-1):
                # All ones
                U = np.zeros(n*m)
                V = np.zeros(m*p)
                W = np.zeros(p*n)
                for di in range(2):
                    for dj in range(2):
                        U[(i0+di)*m + (j0+dj)] = 1
                        V[(j0+dj)*p + (k0+di)] = 1 # Wait, V index is j*p+k.
                        # My V index logic above was V[j*p+k].
                        # So for V, we need j in j0..j0+1, k in k0..k0+1.
                        pass # Let's do this carefully.
                
                # Correct 2x2x2 All Ones
                U = np.zeros(n*m)
                V = np.zeros(m*p)
                W = np.zeros(p*n)
                for di in range(2):
                    for dj in range(2):
                        for dk in range(2):
                            U[(i0+di)*m + (j0+dj)] = 1
                            V[(j0+dj)*p + (k0+dk)] = 1
                            W[(k0+dk)*n + (i0+di)] = 1
                # This U, V, W defines the tensor T[i,j,k] = U[i,j]V[j,k]W[k,i].
                # If U=1 on 2x2, V=1 on 2x2, W=1 on 2x2, then T is 1 on 2x2x2.
                add_candidate(U, V, W)
                
