"""Construct a Sidon set containing 0 with all differences 1..30, minimizing max element."""
import time
import sys

def _check_sidon_and_cover(a, target_diffs):
    """Check if a is a Sidon set covering target_diffs."""
    n = len(a)
    diffs = set()
    for i in range(n):
        for j in range(i + 1, n):
            d = a[j] - a[i]
            if d in diffs:
                return False
            diffs.add(d)
    return all(d in diffs for d in target_diffs)

def _search(M, target_diffs):
    """
    Depth-first search for a Sidon set in [0, M] covering target_diffs.
    Uses heuristic: must cover the smallest remaining difference.
    """
    initial_set = [0]
    initial_diffs = set()
    remaining = set(target_diffs)
    
    # If M is too small to even fit the smallest required diff from 0? 
    # 0 is in set. So M must be >= min(remaining).
    
    def dfs(current_set, used_diffs, remaining):
        if not remaining:
            return current_set[:]
        
        if len(current_set) >= 32:
            return None
            
        # Heuristic: The smallest difference in 'remaining' MUST be generated by the next element x.
        # Because if it's not generated now, it must be generated by x - a for some future x?
        # No, differences are generated by pairs. 
        # If d_min is in remaining, it means no pair in current_set generates it.
        # The next element x will form pairs (x, a) for all a in current_set.
        # If none of these pairs generate d_min, then d_min must be generated by (x_future, a_future) or (x_future, a_current) later?
        # Actually, if we add x, we generate diffs {x-a | a in current_set}.
        # If d_min is not in this set, it remains in 'remaining'.
        # Can it be generated later? Yes, by x2 - x or x2 - a.
        # So the heuristic "must cover d_min now" is NOT strictly valid.
        # HOWEVER, it is a very good heuristic. If we don't cover it now, we might miss it or make it harder.
        # Let's stick to the candidate generation: x must be such that it generates *at least one* new required difference?
        # Or better: We iterate through all possible x in range(last+1, M+1)? Too slow.
        
        # Let's use the candidate set: x = a + d for a in current_set, d in remaining.
        # This covers all x that generate at least one required difference.
        # If a solution exists where x generates NO required differences, it's "wasting" a slot.
        # Given the tight constraint (minimize max), we probably shouldn't waste slots.
        
        last = current_set[-1]
        candidates = set()
        for a in current_set:
            for d in remaining:
                x = a + d
                if x > last and x <= M:
                    candidates.add(x)
        
        # Also, it's possible that x generates a diff that is NOT in remaining, but allows future coverage?
        # Unlikely to be optimal to add a "dead" element.
        
        # Sort candidates to try smaller ones first (minimize max)
        for x in sorted(candidates):
            # Check Sidon property for new diffs
            new_diffs = set()
            conflict = False
            for a in current_set:
                d = x - a
                if d in used_diffs or d in new_diffs:
                    conflict = True
                    break
                new_diffs.add(d)
            
            if conflict:
                continue
                
            # Update state
            new_used = used_diffs | new_diffs
            new_remaining = remaining - new_used
            
            # Recurse
            res = dfs(current_set + [x], new_used, new_remaining)
            if res is not None:
                return res
                
        return None

    return dfs(initial_set, initial_diffs, remaining)

def construct():
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    target_diffs = set(range(1, 31))
    
    # Lower bound estimate: 
    # Min size k such that k(k-1)/2 >= 30 is k=9.
    # Min diameter for Sidon set of size 9 is approx 9^2 - 9 = 72. 
    # Let's start from 50 to be safe, go up to 200.
    
    for M in range(50, 200):
        if time.time() > deadline:
            break
            
        result = _search(M, target_diffs)
        if result is not None:
            # Verify result
            if _check_sidon_and_cover(result, target_diffs):
                return result
                
    # Fallback: Return a known valid set if search fails or times out
    # A known Sidon set covering 1..30:
    # From literature, optimal diameter for covering 1..n is related to perfect difference sets.
    # For n=30, a set like [0, 1, 4, 10, 12, 17, 21, 25, 30] ?
    # Let's just return the best found or a default.
    # The search should find it quickly.
    # If not, return a greedy result.
    return _greedy_fallback()

def _greedy_fallback():
    a = [0]
    used = set()
    required = set(range(1, 31))
    for d in sorted(required):
        # Try to find x such that x-a=d for some a in a
        # and x-a' not in used for all a' in a
        found = False
        for x in range(1, 1000):
            if x in a: continue
            ok = True
            new_diffs = set()
            for v in a:
                diff = abs(x-v)
                if diff in used or diff in new_diffs:
                    ok = False
                    break
                new_diffs.add(diff)
            if ok:
                # Check if it helps
                a.append(x)
                used.update(new_diffs)
                required -= new_diffs
                found = True
                break
        if not found:
            # Add a large number
            x = 1000 + len(a)
            a.append(x)
            for v in a[:-1]:
                used.add(abs(x-v))
            required -= set(abs(x-v) for v in a[:-1])
    return a
