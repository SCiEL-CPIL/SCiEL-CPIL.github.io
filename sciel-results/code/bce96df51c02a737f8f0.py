def _make_symmetric_cell(size, base):
    """Return a size x size list of lists, symmetric under square group, from a base 0/1 array.
    Symmetries: 180-deg rotation, transpose (reflection about main diagonal).
    We enforce cell == cell[::-1] row-wise, cell == cell[::-1] col-wise, and cell == cell.T.
    The intersection of these is the group generated by 180-rotation and transpose.
    We take the majority vote over the 4 equivalent positions: (i,j), (size-1-i,size-1-j), (j,i), (size-1-j,size-1-i).
    """
    b = np.array(base, dtype=np.int8)
    # 180 rotation
    r180 = b[::-1, ::-1]
    # transpose
    t = b.T
    # 180 of transpose = anti-transpose
    at = t[::-1, ::-1]
    votes = (b + r180 + t + at)
    cell = (votes >= 2).astype(np.int8)
    # Convert to nested list
    return cell.tolist()

def _compute_tm_bands_fast(cell, size, n_pw=15, n_kx=6, n_ky=6, eps_high=12.0, eps_low=1.0):
    """Fast plane-wave TM band calculation.
    For TM polarization in 2D square lattice, the eigenvalue problem is:
    For each k, find eigenvalues of M where M_{G,G'} = (k+G)·(k+G') * eps_inv[G-G']
    where eps_inv = 1/eps(r) averaged in Fourier space.
    Actually for TM: (k+G)·(k+G') / eps(G-G') ... let me use the standard formulation.
    
    Standard PWE for TM (Ez):
    sum_G' (k+G)·(k+G') * (1/eps)(G-G') * c_{G'} = omega^2 c_G
    So matrix A[G,G'] = (k+G)·(k+G') * inv_eps[G-G']
    Eigenvalues are omega^2.
    
    inv_eps in Fourier space: inv_eps(G) = (1/A) sum_r (1/eps(r)) exp(-iG·r)
    For pixelated: inv_eps(G) = (1/N) sum_{i,j} (1/eps_{ij}) exp(-iG·(i,j)/size)
    """
    # Build reciprocal lattice vectors
    # G = (mx, my) in units of 2*pi/a, a=1
    G_range = range(-n_pw, n_pw + 1)
    Gs = np.array([(mx, my) for mx in G_range for my in G_range], dtype=float)
    nG = len(Gs)
    
    # Compute inv_eps Fourier coefficients
    cell_arr = np.array(cell, dtype=float)
    eps_arr = np.where(cell_arr > 0.5, eps_high, eps_low)
    inv_eps_arr = 1.0 / eps_arr
    
    inv_eps_G = np.zeros(nG, dtype=complex)
    for idx, (mx, my) in enumerate(Gs):
        # G = 2*pi*(mx, my), positions r = (i/N, j/N)
        # exp(-i G · r) = exp(-i 2*pi*mx*i/N) * exp(-i 2*pi*my*j/N)
        phase_x = np.exp(-1j * 2.0 * np.pi * mx * np.arange(size) / size)
        phase_y = np.exp(-1j * 2.0 * np.pi * my * np.arange(size) / size)
        # 2D Fourier coefficient
        coeff = np.sum(inv_eps_arr * phase_x[:, None] * phase_y[None, :]) / (size * size)
        inv_eps_G[idx] = coeff
    
    # K-points: irreducible BZ of square lattice: kx in [0, pi], ky in [0, kx]
    # Or use standard: kx from 0 to pi, ky from 0 to kx (triangle)
    # Actually for square lattice with a=1, BZ is [-pi,pi]^2, irreducible is kx>=ky, kx,ky in [0,pi]
    # Let's sample points along X (pi,0), M (pi,pi), Gamma (0,0) and interior
    
    k_points = []
    # Gamma
    k_points.append((0.0, 0.0))
    # X direction
    for t in np.linspace(0.1, 1.0, n_kx):
        k_points.append((t * np.pi, 0.0))
    # M direction
    for t in np.linspace(0.1, 1.0, n_ky):
        k_points.append((t * np.pi, t * np.pi))
    # Interior: kx = 0.5*pi, ky from 0 to 0.5*pi
    for t in np.linspace(0.1, 0.5, 4):
        k_points.append((0.5 * np.pi, t * np.pi))
    
    all_eigenvalues = []
    for kx, ky in k_points:
        k = np.array([kx, ky])
        # Build matrix
        A = np.zeros((nG, nG), dtype=complex)
        for i in range(nG):
            ki = k + Gs[i]
            for j in range(nG):
                kj = k + Gs[j]
                # G - G'
                dG = Gs[i] - Gs[j]
                # Find index of dG in Gs
                # Since Gs is all pairs in range, dG might not be in Gs if out of range
                # But for small n_pw, it should be fine. Let's use a dict.
                # Actually let's precompute a lookup
                pass
        
        # This double loop is too slow. Let's vectorize.
        # A[i,j] = (k+Gs[i])·(k+Gs[j]) * inv_eps_G[i-j]
        # We need inv_eps_G for Gs[i]-Gs[j]. Let's build a 2D array of inv_eps indexed by (mx,my)
        
        break  # placeholder
    
    # Let me redo with a better approach
    # Build inv_eps as a 2D array indexed by (mx - n_pw, my - n_pw)
    inv_eps_2d = np.zeros((2 * n_pw + 1, 2 * n_pw + 1), dtype=complex)
    for idx, (mx, my) in enumerate(Gs):
        inv_eps_2d[mx + n_pw, my + n_pw] = inv_eps_G[idx]
    
    all_eigenvalues = []
    for kx, ky in k_points:
        k = np.array([kx, ky])
        # k+Gs for all G
        kGs = k + Gs  # shape (nG, 2)
        # Compute dot products: (k+Gi)·(k+Gj)
        # This is an outer product-like thing
        # A[i,j] = kGs[i,0]*kGs[j,0] + kGs[i,1]*kGs[j,1]
        dot = np.outer(kGs[:, 0], kGs[:, 0]) + np.outer(kGs[:, 1], kGs[:, 1])
        
        # inv_eps[i,j] = inv_eps_2d[Gs[i,0]-Gs[j,0]+n_pw, Gs[i,1]-Gs[j,1]+n_pw]
        # But Gs[i,0]-Gs[j,0] might be out of range [-n_pw, n_pw]
        # For safety, clip or skip
        dmx = Gs[:, 0][:, None] - Gs[:, 0][None, :]
        dmy = Gs[:, 1][:, None] - Gs[:, 1][None, :]
        imx = dmx + n_pw
        imy = dmy + n_pw
        # Only valid if 0 <= imx < 2*n_pw+1 and 0 <= imy < 2*n_pw+1
        valid = (imx >= 0) & (imx < 2 * n_pw + 1) & (imy >= 0) & (imy < 2 * n_pw + 1)
        inv_eps_mat = np.zeros((nG, nG), dtype=complex)
        inv_eps_mat[valid] = inv_eps_2d[imx[valid], imy[valid]]
        
        A = dot * inv_eps_mat
        # A should be Hermitian
        A = (A + A.conj().T) / 2.0
        
        # Solve eigenvalue problem
        eigvals = np.linalg.eigvalsh(A)
        eigvals = np.real(eigvals)
        # Keep only positive eigenvalues (omega^2)
        eigvals = eigvals[eigvals > 1e-10]
        all_eigenvalues.append(eigvals)
    
    # For each k-point, we have eigenvalues. We want bands 4 and 5 (1-indexed).
    # At each k-point, sort eigenvalues and take the 4th and 5th smallest.
    # Then max of 4th, min of 5th over all k-points.
    max_band4 = 0.0
    min_band5 = np.inf
    
    for eigvals in all_eigenvalues:
        if len(eigvals) >= 5:
            b4 = eigvals[3]  # 4th smallest (0-indexed: 3)
            b5 = eigvals[4]  # 5th smallest
            max_band4 = max(max_band4, b4)
            min_band5 = min(min_band5, b5)
    
    if min_band5 == np.inf or max_band4 == 0:
        return -1.0
    
    gap = min_band5 - max_band4
    midgap = 0.5 * (min_band5 + max_band4)
    if midgap <= 0:
        return -1.0
    return 2.0 * gap / midgap

def design(problem):
    """Time-bounded local search for TM band gap maximization."""
    size = problem["pixels"]
    eps_high = problem.get("eps_high", 12.0)
    eps_low = problem.get("eps_low", 1.0)
    
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin
    
    # Initial candidate: circle of radius 0.2
    best_cell = None
    best_score = -1.0
    
    def make_circle(radius):
        base = np.zeros((size, size), dtype=np.int8)
        for i in range(size):
            for j in range(size):
                x = (i + 0.5) / size - 0.5
                y = (j + 0.5) / size - 0.5
                if x * x + y * y < radius * radius:
                    base[i, j] = 1
        return _make_symmetric_cell(size, base)
    
    def make_rounded_square(half_width, corner_radius):
        base = np.zeros((size, size), dtype=np.int8)
        for i in range(size):
            for j in range(size):
                x = abs((i + 0.5) / size - 0.5)
                y = abs((j + 0.5) / size - 0.5)
                # Rounded square: inside if max(x,y) < half_width and corner condition
                if x < half_width and y < half_width:
                    if x > half_width - corner_radius and y > half_width - corner_radius:
                        dx = x - (half_width - corner_radius)
                        dy = y - (half_width - corner_radius)
                        if dx * dx + dy * dy <= corner_radius * corner_radius:
                            base[i, j] = 1
                    else:
                        base[i, j] = 1
        return _make_symmetric_cell(size, base)
    
    def make_cross(arm_width, length):
        base = np.zeros((size, size), dtype=np.int8)
        center = size // 2
        for i in range(size):
            for j in range(size):
                dx = abs(i - center + 0.5)
                dy = abs(j - center + 0.5)
                if dx < length and dy < arm_width / 2:
                    base[i, j] = 1
                elif dy < length and dx < arm_width / 2:
                    base[i, j] = 1
        return _make_symmetric_cell(size, base)
    
    # Try initial candidates
    candidates = []
    for r in [0.15, 0.2, 0.25, 0.3]:
        candidates.append(make_circle(r))
    for hw in [0.2, 0.25, 0.3]:
        for cr in [0.05, 0.1, 0.15]:
            candidates.append(make_rounded_square(hw, cr))
    for aw in [4, 6, 8]:
        for ln in [8, 12, 16]:
            candidates.append(make_cross(aw, ln))
    
    # Evaluate candidates
    for cell in candidates:
        if time.time() > deadline:
            break
        try:
            score = _compute_tm_bands_fast(cell, size, n_pw=8, n_kx=4, n_ky=4, eps_high=eps_high, eps_low=eps_low)
        except Exception:
            score = -1.0
        if score > best_score:
            best_score = score
            best_cell = cell
    
    # Local search: random mutations
    if best_cell is not None:
        current_cell = best_cell
        current_score = best_score
        rng = np.random.default_rng(42)
        
        for step in range(500):
            if time.time() > deadline:
                break
            # Random mutation: flip some pixels
            mut_cell = np.array(current_cell, dtype=np.int8)
            n_flips = rng.integers(1, 5)
            for _ in range(n_flips):
                i = rng.integers(0, size)
                j = rng.integers(0, size)
                mut_cell[i, j] = 1 - mut_cell[i, j]
            sym_cell = _make_symmetric_cell(size, mut_cell)
            
            try:
                score = _compute_tm_bands_fast(sym_cell, size, n_pw=8, n_kx=4, n_ky=4, eps_high=eps_high, eps_low=eps_low)
            except Exception:
                score = -1.0
            
            if score > current_score:
                current_cell = sym_cell
                current_score = score
                if score > best_score:
                    best_score = score
                    best_cell = sym_cell
    
    if best_cell is None:
        # Fallback to original circle
        best_cell = make_circle(0.2)
    
    return best_cell
