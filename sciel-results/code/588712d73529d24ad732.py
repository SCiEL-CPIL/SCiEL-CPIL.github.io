    # H4: [12, -48, 16] -> k=0:12, k=1:-48, k=2:16
    # H8: [1680, -40320, 24192, -4480, 256] -> k=0:1680, k=1:-40320, k=2:24192, k=3:-4480, k=4:256
    # H12: [665280, -20321280, 20901120, -9067200, 1684608, -147456, 4096] -> k=0..5
    
