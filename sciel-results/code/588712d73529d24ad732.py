def _compute_value(c0, c1, c2):
    """
    Compute the value = r^2 / (2*pi) for the given coefficients.
    Returns a positive float (lower is better), or inf if invalid.
    """
    try:
        coeffs_P = _get_coeffs(c0, c1, c2)
        # coeffs_P are [a2, a4, a6, a8, a10, a12] for P(y) = a2 + a4*y + ... + a12*y^5
        
        # Find real positive roots of P(y)
        # P(y) = 0
        roots = np.roots(coeffs_P[::-1]) # np.roots expects descending powers
        
        real_roots = []
        for root in roots:
            if abs(root.imag) < 1e-10:
                real_root = root.real
                if real_root > 1e-12:
                    real_roots.append(real_root)
        
        if not real_roots:
            return float('inf')
        
        real_roots.sort()
        
        # Check sign change
        best_y = None
        for y in real_roots:
            eps = 1e-8 * max(1.0, abs(y))
            P_minus = np.polyval(coeffs_P[::-1], y - eps)
            P_plus = np.polyval(coeffs_P[::-1], y + eps)
            if P_minus * P_plus < 0:
                if best_y is None or y > best_y:
                    best_y = y
        
        if best_y is None:
            return float('inf')
        
        value = best_y / (2 * math.pi)
        return value
    
    except Exception:
        return float('inf')

def _penalty_objective(x):
    """
    Objective function for the penalty method.
    x = [c0, c1, c2, R]
    We want to minimize R.
    Constraints:
    1. g(R) = 0 (where g is the polynomial defined by c0,c1,c2)
    2. g(x) > 0 for all x > R
    
    We enforce these via penalties.
    """
    c0, c1, c2, R = x
    
    if R <= 0:
        return 1e10
    
    coeffs_P = _get_coeffs(c0, c1, c2)
    
    # Evaluate P(y) at y = R^2
    y_R = R * R
    g_R = np.polyval(coeffs_P[::-1], y_R)
    
    # Penalty 1: g(R) should be 0
    pen_root = g_R ** 2
    
    # Penalty 2: g(x) should be positive for x > R
    # Sample a grid from R to R + Delta
    # Delta should be large enough to capture the tail, but not too large for speed.
    # Since the leading term dominates, and it's positive, it will eventually be positive.
    # The danger is in the region just above R.
    x_grid = np.linspace(R, R + 5.0, 200)
    y_grid = x_grid ** 2
    g_vals = np.polyval(coeffs_P[::-1], y_grid)
    
    # We want min(g_vals) > 0
    min_val = np.min(g_vals)
    if min_val < 0:
        pen_pos = min_val ** 2
    else:
        pen_pos = 0.0
        
    # Also, we need to ensure that R is indeed a root where sign changes.
    # If g(R)=0 and g(x)>0 for x>R, then for x<R (close to R), g(x) must be < 0.
    # So we check g(R - eps) < 0.
    eps = 1e-4 * max(1.0, R)
    y_prev = (R - eps) ** 2
    if y_prev > 0:
        g_prev = np.polyval(coeffs_P[::-1], y_prev)
        if g_prev > 0:
            # It didn't change sign (was positive before, positive after)
            # This means R is not a sign-changing root from neg to pos.
            # It could be a touching root or we are in the wrong region.
            # To minimize R, we want the first exit from negative.
            # If g(R-eps) > 0, then R is not the boundary of a negative region ending at R.
            # We penalize this.
            pen_sign = g_prev ** 2
        else:
            pen_sign = 0.0
    else:
        pen_sign = 0.0
        
    return R + 100.0 * (pen_root + pen_pos + pen_sign)

def construct():
    start_time = time.time()
    
    # Start with the seed
    seed_c = [-113.0/100.0, 1.0/25.0, 1.0/3240.0]
    best_c = np.array(seed_c)
    best_value = _compute_value(best_c[0], best_c[1], best_c[2])
    
    # Initial R estimate from seed
    # value = R^2 / (2*pi) => R = sqrt(value * 2 * pi)
    R_seed = math.sqrt(best_value * 2 * math.pi)
    
    def _time_left():
        return _BUDGET_SECONDS - (time.time() - start_time)
    
    # Strategy: Penalty-based Nelder-Mead on [c0, c1, c2, R]
    # We run multiple starts to avoid local minima.
    
    starts = []
    # Start 1: From seed
    starts.append([seed_c[0], seed_c[1], seed_c[2], R_seed])
    
    # Generate some random starts
    rng = np.random.default_rng(42)
    for _ in range(10):
        c0 = rng.uniform(-2, 2)
        c1 = rng.uniform(-1, 1)
        c2 = rng.uniform(-0.5, 0.5)
        # Estimate R roughly
        # Just pick a random R
        R_rand = rng.uniform(0.5, 5.0)
        starts.append([c0, c1, c2, R_rand])
        
    # Sort starts by initial penalty? Or just iterate.
    
    for x0 in starts:
        if _time_left() < 10:
            break
            
        try:
            res = minimize(
                _penalty_objective,
                x0,
                method='Nelder-Mead',
                options={'maxiter': 2000, 'xatol': 1e-8, 'fatol': 1e-10}
            )
            
            # Extract best c0, c1, c2 from result
            c0, c1, c2, R = res.x
            
            # Verify the value with the exact evaluator
            val = _compute_value(c0, c1, c2)
            
            if val < best_value:
                best_value = val
                best_c = np.array([c0, c1, c2])
                
        except Exception:
            pass
    
    # Final polish on best_c
    if _time_left() > 10:
        try:
            # Refine using the original value function directly?
            # The penalty method might have converged to a point where g(R) is small but not 0.
            # We can try to optimize c0,c1,c2 to minimize the value directly, 
            # starting from the best found.
            res = minimize(
                lambda x: _compute_value(x[0], x[1], x[2]),
                best_c,
                method='Nelder-Mead',
                options={'maxiter': 5000, 'xatol': 1e-12, 'fatol': 1e-14}
            )
            if res.fun < best_value:
                best_value = res.fun
                best_c = res.x
        except Exception:
            pass
            
    return np.array(best_c, dtype=np.float64)

