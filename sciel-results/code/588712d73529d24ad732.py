    c3 = -(c0 * _H0_0 + c1 * _H4_0 + c2 * _H8_0) / _H12_0
    
    # Coefficients for g(x)
    # g(x) = sum ak * x^(2k)
    # ak = c0*H0_k + c1*H4_k + c2*H8_k + c3*H12_k
    
