    deadline = start_time + 110.0  # Safety margin for 120s limit
    
    # Strategy:
    # 1. Try to construct a graph on n=43 using a greedy approach with backtracking or local search.
    # 2. Use a known construction as a seed if possible, or start with a random C4-free graph.
    # 3. Optimize by adding edges that reduce the independence number without creating C4s.
    # 4. Verify constraints: No C4 (no two vertices share >1 common neighbor), alpha < 11.
    
    # Helper: Check if adding edge (u,v) creates a C4
    # A C4 is formed if u and v have more than 1 common neighbor.
    # So, we can only add edge (u,v) if |N(u) ∩ N(v)| <= 1.
    
    def is_c4_free(adj_matrix, u, v):
        # Check if adding edge (u,v) creates a C4
        # This happens if they already have >= 2 common neighbors.
        # adj_matrix is a numpy array of 0s and 1s.
        # Common neighbors are 1s in both row u and row v.
        common = np.sum(adj_matrix[u] * adj_matrix[v])
        return common <= 1

    def greedy_max_independent_set(adj_matrix, n):
        # Greedy heuristic to estimate independence number
        # This is an upper bound estimate or a lower bound? 
        # Actually, we want to check if alpha < 11.
        # A fast way to find a large independent set is greedy coloring of the complement, 
        # or simply greedy picking vertices with lowest degree in the remaining graph.
        
        # Let's use a simple greedy: pick vertex with min degree, remove it and its neighbors.
        # Repeat until empty. The number of picks is the size of the independent set found.
        # If this finds a set of size >= 11, the graph is invalid.
        
        remaining = list(range(n))
        adj = adj_matrix.copy()
        count = 0
        while remaining:
            # Find vertex with minimum degree in the induced subgraph of 'remaining'
            min_deg = float('inf')
            min_v = -1
            for v in remaining:
                deg = np.sum(adj[v, remaining])
                if deg < min_deg:
                    min_deg = deg
                    min_v = v
            
            count += 1
            if count >= 11:
                return 11 # Early exit, invalid
            
            # Remove min_v and its neighbors from 'remaining'
            # Update adj? For speed, we can just filter 'remaining'
            # Neighbors of min_v in 'remaining'
            to_remove = set([min_v])
            for v in remaining:
                if adj[min_v, v] == 1:
                    to_remove.add(v)
            
            remaining = [v for v in remaining if v not in to_remove]
        
        return count

    # We want to maximize n. The seed is n=30.
    # We will try to build a graph on n=43.
    # If we fail, we try n=42, etc., down to 30.
    
    best_n = 30
    best_edges = []
