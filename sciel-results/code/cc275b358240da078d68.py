                    # Actually, more edges means smaller alpha.
                    # But C4 constraint limits density.
                    # Max edges in C4-free graph on n vertices is ~ 0.5 * n^(3/2).
                    # For n=43, 0.5 * 43^1.5 ~ 0.5 * 282 = 141.
