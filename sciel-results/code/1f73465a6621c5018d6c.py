def _log_energy_fast(pts):
    """Vectorized log energy computation for speed."""
    n = len(pts)
    dots = pts @ pts.T
    dists_sq = 2.0 - 2.0 * dots
    dists_sq = np.maximum(dists_sq, 1e-15)
    iu = np.triu_indices(n, k=1)
    d2 = dists_sq[iu]
    return -0.5 * np.sum(np.log(d2))

def _log_energy_grad(pts):
    """Compute gradient of logarithmic energy w.r.t. points on sphere (projected)."""
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dists_sq = np.sum(diff * diff, axis=2)
    np.fill_diagonal(dists_sq, 1.0)
    
    inv_d2 = 1.0 / dists_sq
    np.fill_diagonal(inv_d2, 0.0)
    
    weighted_sum_pts = inv_d2 @ pts
    sum_inv_d2 = np.sum(inv_d2, axis=1)
    grad = -pts * sum_inv_d2[:, np.newaxis] + weighted_sum_pts
    
    # Project gradient to tangent space
    dot_prod = np.sum(grad * pts, axis=1)
    grad -= dot_prod[:, np.newaxis] * pts
    
    return grad

def _energy_and_grad_3d(x):
    """Energy and gradient for L-BFGS-B on 3D coordinates."""
    pts = x.reshape(N, 3)
    norms = np.linalg.norm(pts, axis=1, keepdims=True)
    norms = np.maximum(norms, 1e-15)
    pts = pts / norms
    energy = _log_energy_fast(pts)
    grad = _log_energy_grad(pts)
    return energy, grad.flatten()

def _fibonacci_sphere(n):
    """Generate Fibonacci spiral points on unit sphere."""
    i = np.arange(n) + 0.5
    z = 1.0 - 2.0 * i / n
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(np.maximum(0.0, 1.0 - z * z))
    pts = np.column_stack([r * np.cos(phi), r * np.sin(phi), z])
    pts /= np.linalg.norm(pts, axis=1, keepdims=True)
    return pts

def _icosahedral_init(n):
    """
    Initialize using icosahedral symmetry features.
    12 vertices, 20 face centers, 30 edge midpoints.
    Fill the rest with Fibonacci points.
    """
    phi = (1 + np.sqrt(5)) / 2
    verts = np.array([
        [0, 1, phi], [0, 1, -phi], [0, -1, phi], [0, -1, -phi],
        [1, phi, 0], [1, -phi, 0], [-1, phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [phi, 0, -1], [-phi, 0, 1], [-phi, 0, -1]
    ])
    verts = verts / np.linalg.norm(verts, axis=1, keepdims=True)
    
    # Face centers: normalize sum of 3 vertices of a face.
    # We need the faces.
    # Hardcoding faces is tedious.
    # Approximation: Use the 20 points of the dodecahedron vertices?
    # The dual of the icosahedron is the dodecahedron.
    # The face centers of the icosahedron are the vertices of the dodecahedron.
    
    # Dodecahedron vertices:
    # (±1, ±1, ±1)
    # (0, ±1/phi, ±phi)
    # (±1/phi, ±phi, 0)
    # (±phi, 0, ±1/phi)
    
    dodec = []
    for x in [1, -1]:
        for y in [1, -1]:
            for z in [1, -1]:
                dodec.append([x, y, z])
    for x in [0]:
        for y in [1/phi, -1/phi]:
            for z in [phi, -phi]:
                dodec.append([x, y, z])
    for x in [1/phi, -1/phi]:
        for y in [phi, -phi]:
            for z in [0]:
                dodec.append([x, y, z])
    for x in [phi, -phi]:
        for y in [0]:
            for z in [1/phi, -1/phi]:
                dodec.append([x, y, z])
                
    dodec = np.array(dodec)
    dodec = dodec / np.linalg.norm(dodec, axis=1, keepdims=True)
    
    # Edge midpoints: Midpoint of each edge.
    # Edges connect vertices with distance 2.
    # We can find them by checking distances.
    edge_mids = []
    for i in range(12):
        for j in range(i+1, 12):
            d = np.linalg.norm(verts[i] - verts[j])
            if d < 2.1 and d > 1.9: # Edge length is 2
                mid = (verts[i] + verts[j]) / 2.0
                edge_mids.append(mid)
                
    edge_mids = np.array(edge_mids)
    edge_mids = edge_mids / np.linalg.norm(edge_mids, axis=1, keepdims=True)
    
    # Total so far: 12 + 20 + 30 = 62.
    # Need 150 - 62 = 88 more.
    # Generate 88 Fibonacci points.
    fib_pts = _fibonacci_sphere(88)
    
    # Combine
    pts = np.vstack([verts, dodec, edge_mids, fib_pts])
    
    # Normalize and shuffle to break any accidental alignment
    pts = pts / np.linalg.norm(pts, axis=1, keepdims=True)
    
    return pts

def _normalize(pts):
    norms = np.linalg.norm(pts, axis=1, keepdims=True)
    norms = np.maximum(norms, 1e-15)
    return pts / norms

def _exponential_map(pts, tangent_vecs):
    """Apply exponential map on sphere."""
    norms = np.linalg.norm(tangent_vecs, axis=1, keepdims=True)
    norms = np.maximum(norms, 1e-15)
    cos_norms = np.cos(norms)
    sin_norms_over_norms = np.sin(norms) / norms
    return cos_norms * pts + sin_norms_over_norms * tangent_vecs

def _riemannian_cg(pts, time_limit=15.0, max_iter=200):
    """Riemannian conjugate gradient on the sphere."""
    start = time.time()
    current = pts.copy()
    energy, grad = _log_energy_fast(current), _log_energy_grad(current)
    
    d = -grad.copy()
    prev_grad = grad.copy()
    
    for it in range(max_iter):
        if time.time() - start > time_limit - 0.1:
            break
        
        alpha = 0.5
        best_energy = energy
        best_pts = current.copy()
        best_alpha = 0.0
        best_grad = grad.copy()
        
        for ls in range(40):
            new_pts = _exponential_map(current, alpha * d)
            new_energy = _log_energy_fast(new_pts)
            new_grad = _log_energy_grad(new_pts)
            
            if new_energy < best_energy:
                best_energy = new_energy
                best_pts = new_pts
                best_alpha = alpha
                best_grad = new_grad
            
            if new_energy <= energy + 1e-4 * alpha * np.sum(grad * d):
                break
            
            alpha *= 0.7
        
        if best_alpha == 0.0:
            break
        
        current = best_pts
        energy = best_energy
        grad = best_grad
        
        grad_norm = np.linalg.norm(grad)
        if grad_norm < 1e-14:
            break
        
        d_new = -grad
        beta = 0.0
        if it > 0:
            beta_num = np.sum(grad * (grad - prev_grad))
            beta_den = np.sum(prev_grad * prev_grad)
            if beta_den > 1e-30:
                beta = max(0.0, beta_num / beta_den)
            if beta > 1.0:
                beta = 0.0
        
        d = d_new + beta * d
        prev_grad = grad.copy()
    
    return current, energy

