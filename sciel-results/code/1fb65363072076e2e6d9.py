"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import time
import sys

# Increase recursion limit for backtracking
sys.setrecursionlimit(10000)

P = {'n': 40, 'maximum_size': 18}

def construct():
    start_time = time.time()
    deadline = start_time + 85.0  # Safety margin

    candidates = list(range(2, P['n'] + 1))
    # Sort in descending order to prioritize large numbers which have fewer multiples in range
    candidates.sort(reverse=True)
    
    # We will try to find a valid set of size k, starting from 18 down to 12
    # Backtracking solver
    def solve(target_k):
        # State: index in candidates, current selected list, set of subset products
        # We store products as a set of ints
        # Initial product is 1 (empty set)
        
        # To speed up, we can use a global best result
        # But we just want ANY valid set of size target_k
        
        # Optimization: If we already have enough candidates left to reach target_k, proceed.
        
        def dfs(idx, current_set, products, current_size):
            if time.time() > deadline:
                return None
            
            if current_size == target_k:
                return list(current_set)
            
            if idx == len(candidates):
                return None
            
            # Pruning: if even adding all remaining candidates doesn't reach target_k
            if current_size + (len(candidates) - idx) < target_k:
                return None

            cand = candidates[idx]
            
            # Try to include cand
            # Check if adding cand causes collision
            # New products are {p * cand for p in products}
            # Collision if any new product is in products
            # Note: 1 * cand = cand. If cand is in products, collision.
            # products contains 1. So if cand is in products, collision.
            # But cand is not in current_set, so cand is not in products (unless generated by other elements).
            
            new_products = set()
            collision = False
            for p in products:
                np = p * cand
                if np in products:
                    collision = True
                    break
                new_products.add(np)
            
            if not collision:
                # Add cand and new products
                # We don't need to keep the set of products as a list, just the set
                # But we need to pass it to recursion. Sets are immutable in this context? No, we pass reference.
                # So we must copy or use a persistent data structure.
                # Copying a set of size 2^18 (262k) is expensive.
                # Better: Use a list of products and maintain a set for lookup?
                # Or just pass the set and update it in-place with backtracking?
                # In-place with backtracking:
                # 1. Add new_products to products.
                # 2. Recurse.
                # 3. Remove new_products from products.
                
                # Add
                products.update(new_products)
                current_set.append(cand)
                
                result = dfs(idx + 1, current_set, products, current_size + 1)
                
                # Backtrack
                if result:
                    return result
                
                current_set.pop()
                for np in new_products:
                    products.remove(np)
            
            # Try to exclude cand
            result = dfs(idx + 1, current_set, products, current_size)
            if result:
                return result
            
            return None

        initial_products = {1}
        initial_set = []
        return dfs(0, initial_set, initial_products, 0)

    best_result = None
    for k in range(P['maximum_size'], 11, -1):
        if time.time() > deadline - 5.0:
            break
        result = solve(k)
        if result:
            # Verify result just in case
            products = [1]
            for x in result:
                new_products = [p * x for p in products]
                products.extend(new_products)
            if len(products) == len(set(products)):
                best_result = result
                break
            else:
                # Should not happen if solver is correct
                continue
        
        # If we fail to find k, try k-1
        # Note: solve(k) might take a long time. 
        # If it times out, we break the outer loop too.
        if time.time() > deadline - 5.0:
            break

    if best_result:
        return [int(x) for x in best_result]
    
    # Fallback to greedy if backtracking fails or times out
    # Greedy: pick primes, then try to add others
    current_set = []
    products = {1}
    
    # Sort candidates by "safety": primes first?
    # Actually, let's just use the original greedy logic from the seed as fallback
    def _is_prime(n):
        if n < 2: return False
        if n < 4: return True
        if n % 2 == 0 or n % 3 == 0: return False
        i = 5
        while i * i <= n:
            if n % i == 0 or n % (i + 2) == 0: return False
            i += 6
        return True

    primes = [i for i in range(2, P['n'] + 1) if _is_prime(i)]
    current_set = list(primes)
    products = {1}
    for x in current_set:
        new_products = {p * x for p in products}
        products.update(new_products)
        
    # Try to add composites
    for x in range(2, P['n'] + 1):
        if x in current_set:
            continue
        if time.time() > deadline - 2.0:
            break
        new_products = {p * x for p in products}
        if not products.intersection(new_products):
            current_set.append(x)
            products.update(new_products)
            
    # Verify
    final_products = [1]
    for x in current_set:
        new_products = [p * x for p in final_products]
        final_products.extend(new_products)
    if len(final_products) == len(set(final_products)):
        return [int(x) for x in current_set]
    
    # Ultimate fallback: just primes
    return [int(p) for p in primes]

# EVOLVE-BLOCK-END
