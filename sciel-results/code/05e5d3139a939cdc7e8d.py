import numpy as np
from itertools import combinations
from math import gcd
import time

def _normalize_line(A, B, C):
    """Normalize line so first nonzero of (A,B,C) is positive, divided by gcd."""
    g = gcd(abs(A), gcd(abs(B), abs(C)))
    if g == 0:
        return (0, 0, 0)
    A, B, C = A // g, B // g, C // g
    # Make first nonzero positive
    if A < 0 or (A == 0 and B < 0) or (A == 0 and B == 0 and C < 0):
        A, B, C = -A, -B, -C
    return (A, B, C)

def _line_from_points(p1, p2):
    """Get line through two points (x1,y1) and (x2,y2) as (A,B,C)."""
    x1, y1 = p1
    x2, y2 = p2
    A = y1 - y2
    B = x2 - x1
    C = x1 * y2 - x2 * y1
    return _normalize_line(A, B, C)

def _count_incidences(points, lines):
    """Count exact incidences."""
    count = 0
    for (x, y) in points:
        for (A, B, C) in lines:
            if A * x + B * y + C == 0:
                count += 1
    return count

def _evaluate_grid(nx, ny):
    """Evaluate a rectangular grid of size nx x ny."""
    if nx * ny != 54:
        return 0, None, None
    
    points = [(x, y) for x in range(nx) for y in range(ny)]
    
    # Generate all unique lines passing through pairs of points
    line_counts = {}
    n = len(points)
    for i in range(n):
        for j in range(i + 1, n):
            line = _line_from_points(points[i], points[j])
            if line in line_counts:
                line_counts[line] += 1
            else:
                line_counts[line] = 1
                
    # Note: line_counts currently stores the number of PAIRS, not POINTS.
    # We need the number of POINTS on the line.
    # If a line passes through k points, it is generated by k*(k-1)/2 pairs.
    # We can recover k from the pair count, or just recount.
    # Recounting is safer and fast enough for 54 points.
    
    unique_lines = list(line_counts.keys())
    # Sort by pair count descending to prioritize likely high-point lines
    # But we need exact point count.
    
    line_point_counts = []
    for line in unique_lines:
        A, B, C = line
        cnt = 0
        for (x, y) in points:
            if A * x + B * y + C == 0:
                cnt += 1
        line_point_counts.append((cnt, line))
        
    # Sort by count descending
    line_point_counts.sort(key=lambda x: -x[0])
    
    # Take top 27
    top_lines = [line for cnt, line in line_point_counts[:27]]
    
    total_inc = _count_incidences(points, top_lines)
    
    return total_inc, points, top_lines

def szemeredi_trotter_incidences():
    """
    Szemeredi-Trotter incidence maximization with 54 points and 27 lines.
    """
    start_time = time.time()
    deadline = start_time + 580  # 580s safety margin
    
    best_count = 0
    best_points = None
    best_lines = None
    
    # Factor pairs of 54
    grid_shapes = [
        (1, 54), (2, 27), (3, 18), (6, 9), (9, 6), (18, 3), (27, 2), (54, 1)
    ]
    
    for (nx, ny) in grid_shapes:
        if time.time() > deadline:
            break
        count, points, lines = _evaluate_grid(nx, ny)
        if count > best_count:
            best_count = count
            best_points = points
            best_lines = lines
            
    # If we have time, we could try to improve by local search on lines
    # e.g. swapping a low-count line with a high-count one not in the set
    # But the top-27 selection is already optimal for the fixed point set.
    # The only way to improve is to change the point set.
    # Given the discrete nature, other point sets are unlikely to beat the grid
    # significantly, but we can try a few "perturbed" grids if time permits.
    
    # For now, the grid search is the primary strategy.
    
    if best_points is None:
        # Fallback
        best_points = [(x, y) for x in range(6) for y in range(9)]
        count, best_points, best_lines = _evaluate_grid(6, 9)
        
    return np.array(best_points, dtype=np.int64), np.array(best_lines, dtype=np.int64)
