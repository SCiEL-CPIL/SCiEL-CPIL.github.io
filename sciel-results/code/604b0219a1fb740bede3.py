import time
import random
from math import gcd

def construct():
    start_time = time.time()
    deadline = 85.0  # safety margin before 90s kill
    
    n = 30
    # Compute D = lcm(1, 2, ..., 30)
    def lcm(a, b):
        return a * b // gcd(a, b)
    D = 1
    for i in range(1, n + 1):
        D = lcm(D, i)
    
    # weights[i-1] = D // i, so sum of c[i-1]*weights[i-1] gives numerator
    weights = [D // i for i in range(1, n + 1)]
    
    # Build a lattice where short vectors correspond to small signed harmonic sums.
    # We want to find coefficients c_i in {-1, 0, 1} minimizing |sum c_i / i| != 0.
    # 
    # Lattice approach: Consider the lattice L in Z^(n+1) generated by:
    # - v_i = e_i + (weights[i-1], 0, ..., 0) for i = 1..n
    #   (this encodes choosing coefficient 1 for position i)
    # - w = (0, 0, ..., 0, D)  (this encodes the "zero" constraint)
    #
    # Actually, let me think more carefully. We want to find integer vector c in {-1,0,1}^n
    # such that |sum c_i * weights[i-1]| is minimized and nonzero.
    #
    # A better lattice formulation: Consider vectors in Z^(n+1) of the form:
    #   (c_1, c_2, ..., c_n, k) where k = sum c_i * weights[i-1] / D... 
    # 
    # Let me use a different approach. The key insight is that we want a short vector
    # in the lattice generated by:
    #   b_i = (0, ..., 0, 1, 0, ..., 0, weights[i-1]) for i=1..n  (1 in position i, weight in position n+1)
    #   b_{n+1} = (0, ..., 0, 0, D)
    #
    # A vector in this lattice has the form sum a_i * b_i + a_{n+1} * b_{n+1}
    # = (a_1, a_2, ..., a_n, sum a_i * weights[i-1] + a_{n+1} * D)
    #
    # If we restrict a_i to {-1, 0, 1} and a_{n+1} = 0, we get exactly our problem.
    # But LLL doesn't respect these constraints. However, short vectors in this lattice
    # will tend to have small coefficients in the first n coordinates.
    
    # Build the basis matrix (n+1 rows, n+1 columns)
    # Row i (0-indexed) corresponds to b_{i+1}
    # b_i has 1 in column i-1 and weights[i-1] in column n
    # b_{n+1} has D in column n
    
    dim = n + 1
    basis = [[0] * dim for _ in range(dim)]
    for i in range(n):
        basis[i][i] = 1
        basis[i][n] = weights[i]
    basis[n][n] = D
    
    # Implement LLL reduction
    def lll_reduce(basis, delta=None):
        """LLL lattice basis reduction"""
        if delta is None:
            delta = 0.999999
        b = [row[:] for row in basis]
        n_rows = len(b)
        n_cols = len(b[0]) if b else 0
        if n_rows == 0 or n_cols == 0:
            return b
        
        mu = [[0.0] * n_rows for _ in range(n_rows)]
        bprime = [row[:] for row in b]
        
        # Initialize mu
        for i in range(1, n_rows):
            for j in range(i):
                if abs(b[j][-1]) > 1e-12:
                    mu[i][j] = sum(bprime[i][k] * bprime[j][k] for k in range(n_cols)) / (sum(bprime[j][k] ** 2 for k in range(n_cols)) + 1e-18)
        
        k = 1
        while k < n_rows:
            # Step 1: Size reduction
            for j in range(k - 1, -1, -1):
                m = int(round(mu[k][j]))
                if m != 0:
                    for i in range(n_cols):
                        b[k][i] -= m * b[j][i]
                    # Recompute mu[k][*]
                    for jj in range(k):
                        if abs(b[jj][-1]) > 1e-12:
                            mu[k][jj] = sum(b[k][i] * b[jj][i] for i in range(n_cols)) / (sum(b[jj][i] ** 2 for i in range(n_cols)) + 1e-18)
            
            # Step 2: Lovasz condition
            if abs(b[k][-1]) ** 2 >= (delta - mu[k][k-1]**2) * abs(b[k-1][-1])**2:
                k += 1
            else:
                # Swap b[k] and b[k-1]
                b[k], b[k-1] = b[k-1], b[k]
                # Update mu
                for j in range(k):
                    if abs(b[j][-1]) > 1e-12:
                        mu[k][j] = sum(b[k][i] * b[j][i] for i in range(n_cols)) / (sum(b[j][i] ** 2 for i in range(n_cols)) + 1e-18)
                    if abs(b[k-1][j if j < k-1 else j][-1]) > 1e-12:
                        mu[k-1][j] = sum(b[k-1][i] * b[j][i] for i in range(n_cols)) / (sum(b[j][i] ** 2 for i in range(n_cols)) + 1e-18)
                if k > 1:
                    k -= 1
        
        return b
    
    # Try multiple random perturbations of the basis and run LLL
    best_coefficients = None
    best_abs_value = None
    
    num_trials = 50
    for trial in range(num_trials):
        if time.time() > deadline - 5:
            break
        
        # Create a random perturbation of the basis
        perturbed = [[0] * dim for _ in range(dim)]
        for i in range(dim):
            for j in range(dim):
                perturbed[i][j] = basis[i][j]
        
        # Add small random integer perturbations to make it non-symmetric
        for i in range(dim):
            for j in range(dim):
                if i != j:
                    perturbed[i][j] += random.randint(-100, 100)
        
        # Run LLL
        reduced = lll_reduce(perturbed)
        
        # Look for short vectors in the reduced basis
        for i in range(len(reduced)):
            vec = reduced[i]
            # Extract coefficients from the first n coordinates
            coeffs = vec[:n]
            
            # Check if coefficients are in {-1, 0, 1}
            valid = True
            for c in coeffs:
                if c not in (-1, 0, 1):
                    valid = False
                    break
            
            if not valid:
                # Try to project to {-1, 0, 1}
                projected = [max(-1, min(1, c)) for c in coeffs]
                # Compute the sum
                total = sum(projected[i] * weights[i] for i in range(n))
                if total != 0:
                    abs_total = abs(total)
                    if best_abs_value is None or abs_total < best_abs_value:
                        best_abs_value = abs_total
                        best_coefficients = projected
            else:
                total = sum(coeffs[i] * weights[i] for i in range(n))
                if total != 0:
                    abs_total = abs(total)
                    if best_abs_value is None or abs_total < best_abs_value:
                        best_abs_value = abs_total
                        best_coefficients = coeffs[:]
        
        # Also check the original basis vectors
        for i in range(n):
            coeffs = [0] * n
            coeffs[i] = 1
            total = weights[i]
            if total != 0:
                abs_total = abs(total)
                if best_abs_value is None or abs_total < best_abs_value:
                    best_abs_value = abs_total
                    best_coefficients = coeffs[:]
    
    # If LLL didn't find good results, use meet-in-the-middle as fallback
    if best_coefficients is None or time.time() > deadline - 10:
        # Simple fallback: find a pair that gives small sum
        best_coefficients = [0] * n
        best_coefficients[-1] = 1
        best_coefficients[-2] = -1
        best_abs_value = abs(weights[-1] - weights[-2])
    
    # Local search to improve
    if time.time() < deadline - 5:
        improved = best_coefficients[:]
        improved_abs = best_abs_value
        
        for iteration in range(1000):
            if time.time() > deadline - 5:
                break
            
            made_improvement = False
            for i in range(n):
                # Try changing coefficient i
                for new_c in (-1, 0, 1):
                    if new_c == improved[i]:
                        continue
                    old_c = improved[i]
                    improved[i] = new_c
                    total = sum(improved[j] * weights[j] for j in range(n))
                    if total != 0:
                        abs_total = abs(total)
                        if abs_total < improved_abs:
                            improved_abs = abs_total
                            made_improvement = True
                        else:
                            improved[i] = old_c
                    else:
                        improved[i] = old_c
            
            if not made_improvement:
                break
        
        best_coefficients = improved
        best_abs_value = improved_abs
    
    return best_coefficients
