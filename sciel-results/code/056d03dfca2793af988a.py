def _validate_positions(positions):
    if positions is None or len(positions) == 0:
        return False
    if not np.all(np.isfinite(positions)):
        return False
    n = len(positions)
    # Vectorized distance check
    # For n up to 100, this is fast
    dists = np.linalg.norm(positions[:, np.newaxis] - positions[np.newaxis, :], axis=2)
    np.fill_diagonal(dists, np.inf)
    min_dist = np.min(dists)
    if min_dist < 0.35:
        return False
    return True

def _generate_mackay_icosahedron(n):
    """
    Generate Mackay icosahedral clusters for n=13 and n=55.
    Returns None for other n.
    """
    if n == 13:
        phi = (1 + np.sqrt(5)) / 2
        verts = np.array([
            [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
            [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
            [phi, 0, 1], [phi, 0, -1], [-phi, 0, 1], [-phi, 0, -1]
        ])
        verts = verts / np.linalg.norm(verts, axis=1, keepdims=True)
        # Scale to appropriate size for SC potential (lattice const ~1)
        # The equilibrium distance in SC is around 1.0-1.1
        # Icosahedron edge length in this normalized frame is sqrt(2+2/phi) ~ 1.9?
        # Let's just return the unit sphere version and let relax scale it.
        # Actually, better to scale to edge length ~ 1.0
        # Distance between [0,1,phi] and [1,phi,0] is sqrt(1 + (phi-1)^2 + phi^2) = sqrt(1 + 0.382 + 2.618) = sqrt(4) = 2.
        # So if we want edge length 1.0, we divide by 2.
        verts = verts * 0.5
        center = np.zeros(3)
        return np.vstack([center, verts])
    
    elif n == 55:
        phi = (1 + np.sqrt(5)) / 2
        # 1st shell: 12 vertices (radius R1)
        verts1 = np.array([
            [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
            [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
            [phi, 0, 1], [phi, 0, -1], [-phi, 0, 1], [-phi, 0, -1]
        ])
        verts1 = verts1 / np.linalg.norm(verts1, axis=1, keepdims=True)
        
        # 2nd shell: 42 points
        # 12 face centers (radius R2a)
        # 30 edge midpoints (radius R2b)
        
        # To get face centers, we can average the 3 vertices of each face.
        # Icosahedron faces are triangles.
        # We need the list of faces.
        # Instead of hardcoding faces, we can use the fact that the 2nd shell of Mackay icosahedron
        # is generated by placing atoms at the face centers and edge midpoints of the 1st shell,
        # scaled appropriately.
        
        # A simpler approximation for 55:
        # Use the 12 vertices scaled by R1.
        # Use the 30 edge midpoints scaled by R2_edge.
        # Use the 12 face centers scaled by R2_face.
        
        # Let's construct the 42 points explicitly.
        # Icosahedron edges:
        # This is tedious. Let's use a known coordinate set or a simpler "spherical shell" approximation 
        # if exact Mackay is too complex to code inline reliably.
        
        # Alternative: Use a "deformed" icosahedron or just rely on the fact that 
        # relax() from a good 13-atom icosahedron + random additions might work?
        # No, 55 is a magic number. We need the 42 outer atoms.
        
        # Let's try to generate the 42 points by taking the 12 vertices and 
        # creating the 2nd shell by "inflation".
        
        # Actually, there is a simpler way: 
        # The 55-atom Mackay icosahedron has icosahedral symmetry.
        # We can define the 12 vertices of the outer shell (which are NOT the 2nd shell, 
        # the 2nd shell has 42 atoms).
        
        # Let's use a library-free approach: 
        # 12 vertices (V)
        # 30 edge midpoints (E)
        # 12 face centers (F)
        
        # We need the connectivity.
        # For an icosahedron, each vertex is connected to 5 others.
        # Total edges = 12 * 5 / 2 = 30.
        # Total faces = 20.
        
        # Let's hardcode the faces for the standard icosahedron defined above.
        # This is risky. 
        # Instead, let's use a "Spherical Shell" of 42 points that approximates the 2nd shell.
        # The 2nd shell radius is roughly 1.9 * R1?
        # In Mackay icosahedron, the 2nd shell radius is such that the distance 
        # between adjacent 2nd shell atoms is similar to 1st shell edge.
        
        # Let's just return the 13-atom icosahedron for n=55? No, that's wrong size.
        # Let's return a random compact packing for n=55 if we can't generate Mackay easily.
        # BUT, the prompt says "BCC starting closer...". 
        # Let's try to generate a "FCC-like" chunk for 55.
        
        # Actually, I will implement a simple "Shell" generator for n=55 
        # that places 42 points on a sphere of radius ~1.8 (relative to 1st shell at 1.0)
        # using a Fibonacci sphere distribution, then relax.
        # This is a valid "structured" start.
        
        # Generate 42 points on a sphere
        N_outer = 42
        R_outer = 1.8 # Approximate ratio for Mackay
        # Fibonacci sphere
        z = (2 * np.arange(N_outer) + 1) / N_outer
        r = np.sqrt(1 - z**2)
        phi = np.arange(N_outer) * (np.pi * (3 - np.sqrt(5))) # Golden angle
        
        x = r * np.cos(phi)
        y = r * np.sin(phi)
        
        outer_pts = np.column_stack([x, y, z]) * R_outer
        
        # 1st shell
        verts1_scaled = verts1 * 1.0
        center = np.zeros(3)
        
        all_pts = np.vstack([center, verts1_scaled, outer_pts])
        
        # Scale the whole thing so that the nearest neighbor distance is ~1.0
        # The distance between center and 1st shell is 1.0.
        # The distance between 1st shell and 2nd shell is ~ sqrt(1.8^2 - 1^2 + ...)
        # Let's just normalize the whole cluster to have a specific size.
        # The edge length of the 1st shell icosahedron is 2.0 (in our normalized verts1).
        # We want edge length ~ 1.0 for SC potential?
        # SC potential min is around r=1.0 for pair, but cluster equilibrium is different.
        # Let's scale so that the 1st shell edge is 1.0.
        # Current 1st shell edge is 2.0 (from earlier calc).
        # So scale factor 0.5.
        
        all_pts = all_pts * 0.5
        
        return all_pts

    return None

def _generate_fcc_chunk(n):
    """
    Generate an FCC-like cluster.
    """
    if n <= 0:
        return np.zeros((0, 3))
    
    a = 1.0 # Lattice parameter
    # FCC layers are triangular.
    # We stack triangular layers with offset.
    
    # Triangular numbers: 1, 3, 6, 10, 15, 21, 28, 36, 45, 55
    tri_nums = [1, 3, 6, 10, 15, 21, 28, 36, 45, 55]
    
    def get_tri_layer(k, z=0.0):
        pts = []
        for i in range(k):
            for j in range(k - i):
                x = i * a + j * a * 0.5
                y = j * a * np.sqrt(3) / 2
                pts.append([x, y, z])
        return np.array(pts) if pts else np.array([])
    
    points = []
    z = 0.0
    # Interlayer distance in FCC is a * sqrt(2/3)
    dz = a * np.sqrt(2/3)
    
    # Build up
    current_total = 0
    layer_idx = 0
    
    # We might need to add layers until we have enough atoms
    while current_total < n and layer_idx < len(tri_nums):
        k = layer_idx + 1
        num_atoms = tri_nums[layer_idx]
        
        # Generate layer
        layer_pts = get_tri_layer(k, z)
        
        # Offset alternate layers to form FCC (ABAB stacking)
        if layer_idx % 2 == 1:
            # Shift by (a/3, a/sqrt(3), 0) ? 
            # FCC stacking: A at (0,0), B at (1/3, 1/sqrt(3), 0) in unit of a?
            # Let's just use a simple offset for now.
            offset_x = a / 3
            offset_y = a / np.sqrt(3)
            layer_pts[:, 0] += offset_x
            layer_pts[:, 1] += offset_y
            
        points.append(layer_pts)
        current_total += num_atoms
        z += dz
        layer_idx += 1
        
    if not points:
        return np.zeros((n, 3))
        
    all_pts = np.vstack(points)
    
    # Center
    center = all_pts.mean(axis=0)
    all_pts -= center
    
    # Trim to n
    if len(all_pts) > n:
        dists = np.linalg.norm(all_pts, axis=1)
        order = np.argsort(dists)
        all_pts = all_pts[order[:n]]
        
    return all_pts

def _generate_bcc_chunk(n):
    """
    Generate a BCC-like cluster.
    """
    if n <= 0:
        return np.zeros((0, 3))
    
    a = 1.0
    # BCC layers are square.
    # Square numbers: 1, 4, 9, 16, 25, 36, 49, 64
    sq_nums = [1, 4, 9, 16, 25, 36, 49, 64]
    
    def get_sq_layer(k, z=0.0):
        pts = []
        for i in range(k):
            for j in range(k):
                x = i * a
                y = j * a
                pts.append([x, y, z])
        return np.array(pts) if pts else np.array([])
    
    points = []
    z = 0.0
    # BCC interlayer distance is a/2? No, BCC is not layered in simple squares like FCC.
    # BCC can be viewed as layers of atoms with a body-center atom in between.
    # Let's just use a simple cubic grid with body centers.
    
    # Simpler: Generate a cubic grid of size LxLxL and add body centers.
    # Or just use a "Random Compact" with BCC bias?
    # Let's stick to a simple cubic packing for "BCC-like" if complex BCC is hard.
    # Actually, let's just use FCC for now if BCC is too complex, 
    # but the prompt says BCC is better.
    
    # Let's generate a cube of side length L such that L^3 ~ n/2 (since 2 atoms per unit cell)
    L = int(np.cbrt(n / 2.0)) + 1
    
    pts = []
    for i in range(L):
        for j in range(L):
            for k in range(L):
                # Corner atom
                pts.append([i*a, j*a, k*a])
                # Body center atom
                if i < L-1 and j < L-1 and k < L-1:
                    pts.append([(i+0.5)*a, (j+0.5)*a, (k+0.5)*a])
    
    all_pts = np.array(pts)
    
    # Center
    center = all_pts.mean(axis=0)
    all_pts -= center
    
    # Trim to n
    if len(all_pts) > n:
        dists = np.linalg.norm(all_pts, axis=1)
        order = np.argsort(dists)
        all_pts = all_pts[order[:n]]
        
    return all_pts

def _generate_random_compact(n, rng, radius=0.8):
    """
    Generate a random compact cluster.
    """
    if n <= 0:
        return np.zeros((0, 3))
    
    R = radius * n ** (1.0/3.0) * 1.5
    
    points = [np.zeros(3)]
    min_dist = 0.4 # Allow some compression
    
    attempts = 0
    max_attempts = n * 2000
    
    while len(points) < n and attempts < max_attempts:
        # Sample from sphere
        u = rng.uniform(0, 1)
        v = rng.uniform(0, 1)
        theta = 2 * np.pi * u
        phi = np.arccos(2 * v - 1)
        r = R * np.cbrt(rng.uniform(0, 1))
        
        x = r * np.sin(phi) * np.cos(theta)
        y = r * np.sin(phi) * np.sin(theta)
        z = r * np.cos(phi)
        p = np.array([x, y, z])
        
        # Check distance to all existing points
        # For efficiency, we can use a simple check
        if all(np.linalg.norm(p - q) >= min_dist for q in points):
            points.append(p)
        attempts += 1
        
    # If we failed to place all, add random points
    while len(points) < n:
        points.append(rng.uniform(-R, R, 3))
        
    return np.array(points)

def construct(instance):
    n = instance["n"]
    kind = instance.get("kind", "12-6")
    
    # Set up RNG
    seed = n * 100 + (0 if kind == '12-6' else 1 if kind == '9-6' else 2)
    rng = np.random.default_rng(seed)
    
    best_energy = np.inf
    best_positions = None
    
    # Generate starts
    starts = []
    
    # 1. Structural Seeds
    ico = _generate_mackay_icosahedron(n)
    if ico is not None and _validate_positions(ico):
        starts.append(ico)
        
    fcc = _generate_fcc_chunk(n)
    if len(fcc) == n and _validate_positions(fcc):
        starts.append(fcc)
        
    bcc = _generate_bcc_chunk(n)
    if len(bcc) == n and _validate_positions(bcc):
        starts.append(bcc)
        
    # 2. Random Compact Starts
    # We will generate a few of these
    num_random = 5
    for i in range(num_random):
        rcp = _generate_random_compact(n, rng)
        if len(rcp) == n and _validate_positions(rcp):
            starts.append(rcp)
            
    # If no starts, use a chain
    if not starts:
        pts = np.zeros((n, 3))
        pts[:, 0] = np.arange(n) * 0.8
        starts.append(pts)

    # Parallel Relaxation
    # Use ThreadPoolExecutor to relax multiple starts in parallel
    # Max 4 threads
    
    def _relax_one(start):
        try:
            energy, positions = relax(start, 'sutton_chen', kind)
            if _validate_positions(positions):
                return energy, positions
            else:
                return np.inf, None
        except Exception:
            return np.inf, None

    with ThreadPoolExecutor(max_workers=4) as executor:
        futures = {executor.submit(_relax_one, start): start for start in starts}
        
        for future in as_completed(futures):
            if _get_time_left() < 5.0:
                break
                
            try:
                energy, positions = future.result()
                if energy < best_energy:
                    best_energy = energy
                    best_positions = positions.copy()
            except Exception:
                pass

    # If we still have time, try more random starts
    attempts = 0
    while _get_time_left() > 10.0 and attempts < 10:
        attempts += 1
        try:
            rcp = _generate_random_compact(n, rng)
            if not _validate_positions(rcp):
                continue
            energy, positions = _relax_one(rcp)
            if energy < best_energy:
                best_energy = energy
                best_positions = positions.copy()
        except Exception:
            continue

    # Fallback
    if best_positions is None:
        best_positions = starts[0]
        
    return best_positions
