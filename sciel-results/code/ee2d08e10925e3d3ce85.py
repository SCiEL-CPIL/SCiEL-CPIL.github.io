import numpy as np

def laderman_4x4(A, B):
    a = A
    b = B
    
    M1 = (a[0,0]+a[1,1]) * (b[0,0]+b[1,1])
    M2 = (a[0,1]+a[1,1]) * (b[1,0]+b[1,1])
    M3 = (a[0,0]+a[2,2]) * (b[0,0]+b[2,2])
    M4 = (a[0,2]+a[2,2]) * (b[2,0]+b[2,2])
    M5 = (a[0,0]+a[3,3]) * (b[0,0]+b[3,3])
    M6 = (a[0,3]+a[3,3]) * (b[3,0]+b[3,3])
    M7 = (a[0,1]+a[1,0]+a[2,3]+a[3,2]) * (b[0,1]+b[1,0]+b[2,3]+b[3,2])
    M8 = (a[0,2]+a[1,0]+a[2,1]+a[3,3]) * (b[0,2]+b[1,3]+b[2,0]+b[3,1])
    M9 = (a[0,3]+a[1,3]+a[2,0]+a[3,1]) * (b[0,3]+b[1,2]+b[2,1]+b[3,0])
    M10 = (a[0,0]+a[1,1]+a[2,2]+a[3,3]) * (b[0,0]+b[1,1]+b[2,2]+b[3,3])
    M11 = (a[0,0]+a[1,1]-a[2,2]-a[3,3]) * (b[0,0]+b[1,1]-b[2,2]-b[3,3])
    M12 = (a[0,0]-a[1,1]+a[2,2]-a[3,3]) * (b[0,0]-b[1,1]+b[2,2]-b[3,3])
    M13 = (a[0,0]-a[1,1]-a[2,2]+a[3,3]) * (b[0,0]-b[1,1]-b[2,2]+b[3,3])
    M14 = (a[0,1]+a[1,0]) * (b[0,1]+b[1,0])
    M15 = (a[0,2]+a[1,3]) * (b[0,2]+b[1,3])
    M16 = (a[0,3]+a[1,2]) * (b[0,3]+b[1,2])
    M17 = (a[2,0]+a[3,1]) * (b[2,0]+b[3,1])
    M18 = (a[2,1]+a[3,0]) * (b[2,1]+b[3,0])
    M19 = (a[2,2]+a[3,3]) * (b[2,2]+b[3,3])
    M20 = (a[2,3]+a[3,2]) * (b[2,3]+b[3,2])
    
    C = np.zeros((4,4))
    C[0,0] = M1 - M2 - M10 + M11
    C[0,1] = M3 - M4 - M10 + M12
    C[0,2] = M5 - M6 - M10 + M13
    C[0,3] = M7 - M8 - M10 + M14
    C[1,0] = M2 + M10 - M11
    C[1,1] = M1 + M10 - M12
    C[1,2] = M7 + M8 - M10 - M15
    C[1,3] = M9 - M16
    C[2,0] = M4 + M10 - M13
    C[2,1] = M8 + M10 - M14
    C[2,2] = M3 + M10 - M12
    C[2,3] = M19
    C[3,0] = M6 + M10 - M11
    C[3,1] = M9 + M10 - M17
    C[3,2] = M16 + M10 - M18
    C[3,3] = M5 + M10 - M13
    
    return C

# Test
A = np.random.randn(4,4)
B = np.random.randn(4,4)
C_expected = A @ B
C_computed = laderman_4x4(A, B)
print(np.max(np.abs(C_expected - C_computed)))
