import itertools
import random
import time

def construct():
    """
    Construct a triple system on 16 points without the complete 3-partite K(2,2,2).
    Uses a structured initialization based on linear algebra over GF(2)^4
    and a local search with swap moves to maximize the number of triples.
    """
    start_time = time.time()
    deadline = start_time + 145  # 5s margin
    
    n = 16
    points = list(range(n))
    
    # 1. Precompute all possible triples (edges)
    all_triples = list(itertools.combinations(range(n), 3))
    num_edges = len(all_triples) # 560
    
    # Map triple to index
    triple_to_idx = {t: i for i, t in enumerate(all_triples)}
    
    # 2. Precompute all K(2,2,2) conflicts
    # A conflict is a set of 8 edges forming a K(2,2,2).
    # K(2,2,2) is defined by 3 disjoint pairs: {a1,a2}, {b1,b2}, {c1,c2}.
    # The 8 edges are all (ai, bj, ck).
    
    conflicts = []
    # Iterate over all ways to pick 6 distinct points
    # Then partition them into 3 pairs
    # There are 15 partitions for 6 points.
    
    # Optimization: We can just iterate over all 6-subsets and all pairings.
    # But 8008 subsets * 15 pairings = 120120 conflicts.
    # Each conflict is a tuple of 8 edge indices.
    
    # To make checking fast, we represent a conflict as a bitmask (int).
    # 560 bits fits in a Python int (arbitrary precision).
    
    conflict_masks = []
    # Also, for each edge, we need to know which conflicts it belongs to.
    edge_to_conflicts = [[] for _ in range(num_edges)]
    
    # Helper to get index of a triple
    def get_idx(a, b, c):
        return triple_to_idx[(a, b, c)] if (a, b, c) in triple_to_idx else -1
        # Note: combinations are sorted, so (a,b,c) must be sorted.
        # My all_triples are sorted.
        # But get_idx(a,b,c) needs to handle unsorted input?
        # Let's just use the tuple from itertools which is sorted.
        
    # Re-implement get_idx to be robust
    def get_idx_safe(a, b, c):
        t = tuple(sorted((a, b, c)))
        return triple_to_idx[t]

    # Generate conflicts
    for six_points in itertools.combinations(range(n), 6):
        # Generate all 15 perfect matchings of 6 points
        # Points: p0, p1, p2, p3, p4, p5
        # Matchings can be generated by pairing p0 with p1..p5, then pairing the rest.
        # Or simply iterate over permutations? No, 15 is small.
        
        # List of 15 matchings (indices in 0..5)
        matchings = [
            [(0,1), (2,3), (4,5)],
            [(0,1), (2,4), (3,5)],
            [(0,1), (2,5), (3,4)],
            [(0,2), (1,3), (4,5)],
            [(0,2), (1,4), (3,5)],
            [(0,2), (1,5), (3,4)],
            [(0,3), (1,2), (4,5)],
            [(0,3), (1,4), (2,5)],
            [(0,3), (1,5), (2,4)],
            [(0,4), (1,2), (3,5)],
            [(0,4), (1,3), (2,5)],
            [(0,4), (1,5), (2,3)],
            [(0,5), (1,2), (3,4)],
            [(0,5), (1,3), (2,4)],
            [(0,5), (1,4), (2,3)]
        ]
        
        for m in matchings:
            pair1 = (six_points[m[0][0]], six_points[m[0][1]])
            pair2 = (six_points[m[1][0]], six_points[m[1][1]])
            pair3 = (six_points[m[2][0]], six_points[m[2][1]])
            
            # Generate the 8 edges
            edge_indices = []
            for a in pair1:
                for b in pair2:
                    for c in pair3:
                        idx = get_idx_safe(a, b, c)
                        edge_indices.append(idx)
                        
            mask = 0
            for idx in edge_indices:
                mask |= (1 << idx)
                edge_to_conflicts[idx].append(len(conflict_masks))
                
            conflict_masks.append(mask)

    # 3. Initialization: Linear Structure over GF(2)^4
    # Points 0..15 correspond to 4-bit vectors.
    # Edge exists if u ^ v ^ w == 0.
    
    current_edges = set()
    current_mask = 0
    
    for u in range(n):
        for v in range(u+1, n):
            w = u ^ v
            if w > v: # Ensure u < v < w to match combinations
                idx = get_idx_safe(u, v, w)
                current_edges.add(idx)
                current_mask |= (1 << idx)
                
    best_mask = current_mask
    best_count = len(current_edges)
    
    # 4. Local Search
    # We maintain current_mask and current_edges.
    # Move: Try to add a random missing edge.
    # If it creates a conflict, try to swap with an edge in that conflict.
    
    # Precompute list of missing edges for faster sampling?
    # Just sample from 0..559.
    
    def is_conflict_present(mask, conflict_idx):
        return (mask & conflict_masks[conflict_idx]) == conflict_masks[conflict_idx]

    def check_validity_after_add(mask, edge_idx):
        # Check conflicts containing edge_idx
        for c_idx in edge_to_conflicts[edge_idx]:
            if is_conflict_present(mask, c_idx):
                return False
        return True

    def check_validity_after_remove(mask, edge_idx):
        # Removing an edge cannot create a new conflict.
        # It can only resolve them.
        return True

    def perform_swap(mask, edges_set, add_idx, rem_idx):
        new_mask = (mask | (1 << add_idx)) & ~(1 << rem_idx)
        # Check validity of new_mask
        # Only need to check conflicts involving add_idx.
        # (Removing rem_idx doesn't create conflicts)
        if not check_validity_after_add(new_mask, add_idx):
            return None, None
        return new_mask, edges_set | {add_idx} - {rem_idx}

    # Main Loop
    steps = 0
    while time.time() < deadline:
        # Try to add a random edge
        add_idx = random.randint(0, num_edges - 1)
        
        if add_idx in current_edges:
            continue
            
        # Check if adding add_idx creates a conflict
        temp_mask = current_mask | (1 << add_idx)
        conflict_found = -1
        for c_idx in edge_to_conflicts[add_idx]:
            if is_conflict_present(temp_mask, c_idx):
                conflict_found = c_idx
                break
                
        if conflict_found == -1:
            # No conflict, add it!
            current_mask = temp_mask
            current_edges.add(add_idx)
            if len(current_edges) > best_count:
                best_count = len(current_edges)
                best_mask = current_mask
        else:
            # Conflict found. Try to swap.
            # Get the edges in this conflict
            c_mask = conflict_masks[conflict_found]
            # The edges present in this conflict are (c_mask & temp_mask)
            # One of them is add_idx.
            # We need to remove one of the OTHER edges.
            
            # Find indices of edges in the conflict
            # c_mask has 8 bits set.
            # We can iterate through the bits of c_mask.
            # But we only care about the ones that are currently present (in current_mask).
            # Actually, the conflict is "full" in temp_mask.
            # So all 8 edges are in temp_mask.
            # 7 of them are in current_mask.
            
            # Get the 7 other edges
            other_edges = []
            m = c_mask
            while m:
                lsb = m & -m
                idx = lsb.bit_length() - 1
                if idx != add_idx:
                    other_edges.append(idx)
                m ^= lsb
                
            # Try each other edge as a removal candidate
            random.shuffle(other_edges)
            for rem_idx in other_edges:
                new_mask, new_edges = perform_swap(current_mask, current_edges, add_idx, rem_idx)
                if new_mask is not None:
                    # Swap accepted
                    current_mask = new_mask
                    current_edges = new_edges
                    # Size is same, so no update to best_count unless we track best_mask
                    # But this swap might enable future additions.
                    break
            # If no swap worked, we just don't add add_idx.
            
        # Occasionally, if stuck, remove a random edge to open up space?
        # This is risky but can help escape local optima.
        # Let's add a "perturbation" step every 1000 steps.
        steps += 1
        if steps % 500 == 0:
            # Try to remove a random edge and see if we can add 2?
            # Or just remove 1 to break a bottleneck.
            if current_edges:
                rem_idx = random.choice(list(current_edges))
                # Tentatively remove
                old_mask = current_mask
                old_edges = current_edges
                current_mask &= ~(1 << rem_idx)
                current_edges.remove(rem_idx)
                
                # Try to add 2 random edges
                added_any = False
                for _ in range(2):
                    add_idx = random.randint(0, num_edges - 1)
                    if add_idx in current_edges:
                        continue
                    temp_mask = current_mask | (1 << add_idx)
                    # Check conflict
                    ok = True
                    for c_idx in edge_to_conflicts[add_idx]:
                        if is_conflict_present(temp_mask, c_idx):
                            ok = False
                            break
                    if ok:
                        current_mask = temp_mask
                        current_edges.add(add_idx)
                        added_any = True
                        if len(current_edges) > best_count:
                            best_count = len(current_edges)
                            best_mask = current_mask
                
                # If we didn't add anything back, we are smaller.
                # Revert if we didn't improve or maintain?
                # Actually, if we removed 1 and added 0, we lost an edge.
                # If we removed 1 and added 1, we are same size (but different structure).
                # If we removed 1 and added 2, we gained 1.
                
                # Simple heuristic: If we didn't add at least 1, revert?
                # Or keep it to change landscape?
                # Let's keep it if we added at least 1, otherwise revert to avoid shrinking.
                if not added_any:
                    current_mask = old_mask
                    current_edges = old_edges

    # Convert best_mask back to list of triples
    result = []
    m = best_mask
    while m:
        lsb = m & -m
        idx = lsb.bit_length() - 1
        result.append(list(all_triples[idx]))
        m ^= lsb
        
    return result

