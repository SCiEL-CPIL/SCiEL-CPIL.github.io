    def axial_to_cartesian(axial_list):
        pts = []
        for q, r in axial_list:
            x = math.sqrt(3) * (q + r / 2.0)
            y = 1.5 * r
            pts.append((x, y))
        return np.array(pts)

    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None

        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append((math.cos(ang), math.sin(ang)))

        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []

        for nx, ny in normals:
            for px, py in pts:
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-(px * nx + py * ny))
                A_ub.append([nx, ny, -1.0])
                b_ub.append(px * nx + py * ny)

        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]

        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def exact_S_vectorized(pts, cx, cy, beta):
        """Vectorized exact computation of S for given center and beta."""
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        max_proj = np.max(np.abs(projs))
        S = (max_proj + APOTHEM) / APOTHEM
        return S

    def optimize_positions(pts_initial, time_budget):
        """
        Optimizes the positions of the inner hexagons (assuming they are aligned with the outer hexagon)
        to minimize the enclosing hexagon size, subject to pairwise distance constraints.
        """
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None, None
        
        n = len(pts_initial)
        # Parameters: x1, y1, ..., xn, yn, cx, cy, beta
        # Total 2*n + 3 parameters
        
        def objective(params):
            positions = params[:2*n].reshape(-1, 2)
            cx, cy, beta = params[2*n], params[2*n+1], params[2*n+2]
            
            # Calculate S
            S = exact_S_vectorized(positions, cx, cy, beta)
            
            # Check constraints: pairwise distances >= MIN_DIST
            # If violated, add a large penalty
            penalty = 0.0
            for i in range(n):
                for j in range(i+1, n):
                    dx = positions[i, 0] - positions[j, 0]
                    dy = positions[i, 1] - positions[j, 1]
                    dist = math.sqrt(dx*dx + dy*dy)
                    if dist < MIN_DIST:
                        # Quadratic penalty for violation
                        violation = MIN_DIST - dist
                        penalty += 100.0 * violation * violation
            
            return S + penalty

        # Initial guess: centered at mean, beta=0
        cx0 = float(np.mean(pts_initial[:, 0]))
        cy0 = float(np.mean(pts_initial[:, 1]))
        x0 = list(pts_initial[:, 0]) + list(pts_initial[:, 1]) + [cx0, cy0, 0.0]
        
        # Try a few random beta starts
