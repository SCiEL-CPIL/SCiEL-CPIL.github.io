        best_params = None
        
        for beta_start in [0.0, math.pi/6, math.pi/3, math.pi/12]:
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
            
            x0[2*n+2] = beta_start
            
            try:
                res = minimize(objective, x0, method='L-BFGS-B', 
                               options={'maxiter': 1000, 'ftol': 1e-12, 'gtol': 1e-12})
                
                if res.fun < best_S:
                    # Verify no significant overlap
                    positions = res.x[:2*n].reshape(-1, 2)
                    valid = True
                    for i in range(n):
                        for j in range(i+1, n):
                            dx = positions[i, 0] - positions[j, 0]
                            dy = positions[i, 1] - positions[j, 1]
                            dist = math.sqrt(dx*dx + dy*dy)
                            if dist < MIN_DIST - 1e-6:
                                valid = False
                                break
                        if not valid:
                            break
                    
                    if valid:
                        best_S = res.fun
                        best_params = res.x
            except Exception:
                pass
        
        if best_params is None:
            return float('inf'), None, None, None
            
        positions = best_params[:2*n].reshape(-1, 2)
        cx = best_params[2*n]
        cy = best_params[2*n+1]
        beta = best_params[2*n+2]
        
        # Final exact S calculation
        S_final = exact_S_vectorized(positions, cx, cy, beta)
        
        return S_final, positions, (cx, cy), beta

