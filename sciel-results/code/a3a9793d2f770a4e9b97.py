N = 18
MIN_DIST = 6

def hamming_distance(a, b):
    return (a ^ b).bit_count()

def reed_muller_construction():
    """First-order Reed-Muller code on 16 coordinates, extended by two zero bits.
    Every affine Boolean function on F_2^4 is a word: 32 words, distance 8."""
    words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            words.append(word)
    return words

def poly_mod(a, b):
    """
    Compute a(x) % b(x) in GF(2).
    a, b are integers representing polynomials.
    """
    while a.bit_length() >= b.bit_length():
        a ^= b << (a.bit_length() - b.bit_length())
    return a

def find_qr_generator():
    """
    Find the generator polynomial for the [17, 9, 5] QR code.
    """
    # x^17 - 1 in GF(2) is x^17 + 1
    x17_plus_1 = (1 << 17) | 1
    
    # Iterate through all monic polynomials of degree 8 with constant term 1
    # g(x) = x^8 + c7*x^7 + ... + c1*x + 1
    # There are 2^7 = 128 candidates
    for mask in range(128):
        # Construct g(x)
        g = (1 << 8) | 1 # Leading term and constant term
        for i in range(7):
            if (mask >> i) & 1:
                g |= (1 << (i + 1))
        
        # Check if g divides x^17 + 1
        if poly_mod(x17_plus_1, g) == 0:
            # Generate the code to check distance
            # The code is the ideal generated by g in GF(2)[x] / (x^17-1)
            # Codewords are multiples of g: c(x) = m(x) * g(x) mod (x^17-1)
            # Since deg(m) < 9, we can just compute m(x) * g(x) and take mod (x^17-1)
            # But for cyclic codes, the generator matrix rows are shifts of g.
            # Let's just generate all 2^9 = 512 codewords by taking all multiples m(x)*g(x)
            # where m(x) has degree < 9.
            
            min_d = 18
            words = []
