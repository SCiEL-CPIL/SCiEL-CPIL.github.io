def _is_valid_fast(n, edges, k, g):
    """Fast validation using non-backtracking walks for girth."""
    if n <= 0:
        return False
    adj = [[] for _ in range(n)]
    seen = set()
    for u, v in edges:
        if u == v or not (0 <= u < n and 0 <= v < n):
            return False
        if (min(u,v), max(u,v)) in seen:
            return False
        seen.add((min(u,v), max(u,v)))
        adj[u].append(v)
        adj[v].append(u)
    for u in range(n):
        if len(adj[u]) != k:
            return False
        if len(set(adj[u])) != len(adj[u]):
            return False

    # Non-backtracking girth check
    # If girth < g, return False
    prev = {}
    q = deque()
    for u in range(n):
        for p in adj[u]:
            key = (p, u)
            prev[key] = (u, 1)
            q.append(key)
            
    while q:
        (v, p), (u, dist) = q.popleft()
        if dist >= g:
            continue
        for w in adj[v]:
            if w == p:
                continue
            key = (w, v)
            if w == u:
                return False # Found cycle of length dist+1 < g
            if key in prev:
                continue
            prev[key] = (v, dist + 1)
            q.append(key)
    return True

