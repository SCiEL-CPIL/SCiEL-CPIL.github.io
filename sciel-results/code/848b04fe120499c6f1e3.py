def construct():
    """
    Returns the schoolbook tensor decomposition for matrix multiplication.
    For dimensions n x m x p, the schoolbook rank is n*m*p.
    For 2 x 4 x 7, the rank is 56.
    Based on the properties of matrix multiplication tensors for n=2,
    the schoolbook rank is minimal for all (m,p) != (2,2).
    """
    n, m, p = DIMENSIONS
    rank = n * m * p
    
    # Initialize matrices with zeros
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                # U index: i*m + j
                # V index: j*p + k
                # W index: k*n + i (Trace convention W[k*n+i, r])
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
                
    return {"U": U, "V": V, "W": W}
