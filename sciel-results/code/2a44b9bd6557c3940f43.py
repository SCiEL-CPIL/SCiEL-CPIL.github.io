import numpy as np
import time

class Optimizer:
    """
    Optimizer for DTLZ7 exploiting the Pareto front structure.
    Uses Sobol-like quasi-random sampling on the 2D Pareto front manifold
    with strategic corner/edge points to maximize hypervolume coverage.
    
    DTLZ7 Pareto front: x[2:] = 0.5 (for g=0)
    f0 = x[0]
    f1 = x[1]
    f2 = 1 - sqrt(x[1])
    """

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def _sobol_2d(self, n, skip=0):
        """
        Generate n points in [0,1]^2 using a proper Sobol sequence from SciPy.
        """
        from scipy.stats import qmc
        sampler = qmc.Sobol(d=2, scramble=True)
        # Generate n points. We ignore 'skip' as Sobol sequences are not typically
        # generated by skipping indices in the same way, and scrambling makes
        # the sequence effectively random in ordering.
        return sampler.random(n=n)

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 280.0  # Safety margin before 300s
        
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        
        results = []
        n_evals = 0
        budget = self.budget

        # DTLZ7 Pareto front parameterization:
        # x[0] = u in [0,1] -> f0 = u
        # x[1] = v in [0,1] -> f1 = v, f2 = 1 - sqrt(v)
        # x[2:] = 0.5 (midpoint of bounds for g=0)
        
        mid = 0.5 * (lo + hi)
        
        # Strategy: Use a proper Sobol sequence for low-discrepancy sampling
        # across the 2D Pareto front manifold (x[0], x[1]).
        
        # Generate all points at once for efficiency
        sobol_points = self._sobol_2d(budget)
        
        # Evaluate all points
        for i in range(budget):
            if time.time() > deadline:
                break
            
            u = sobol_points[i, 0]
            v = sobol_points[i, 1]
            
            x = np.zeros(self.dim)
            x[0] = lo[0] + u * (hi[0] - lo[0])
            x[1] = lo[1] + v * (hi[1] - lo[1])
            # Set x[2:] to midpoint to minimize g
            for j in range(2, self.dim):
                x[j] = mid[j]
            
            # Clip to bounds
            x = np.clip(x, lo, hi)
            
            obj = problem(x)
            results.append(obj)
            n_evals += 1
        
        return results
