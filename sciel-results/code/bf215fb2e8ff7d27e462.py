    # Each C_t is a 2x2 matrix.
    # The final output C is 4x4.
    # C[0:2, 0:2] = C11
    # C[0:2, 2:4] = C12
    # C[2:4, 0:2] = C21
    # C[2:4, 2:4] = C22
    
    # So, for each of the 49 inner terms (7 outer * 7 inner), we have:
    # 1. A linear combination of A's 2x2 blocks (from X_t)
    # 2. A linear combination of B's 2x2 blocks (from Y_t)
    # 3. A contribution to C's 2x2 blocks (from C_t)
    
    # We can construct U, V, W by iterating over the 49 terms.
    
    # Define the 7 outer terms' X and Y coefficients.
    # X_t and Y_t are 2x2 matrices of coefficients for the 2x2 blocks of A and B.
    # Let's represent A's blocks as A[0,0], A[0,1], A[1,0], A[1,1].
    # Same for B.
    
