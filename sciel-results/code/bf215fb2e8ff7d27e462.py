    # Term 3: A11(B12-B22) -> contributes to C12, C22
    # Term 4: A22(B21-B11) -> contributes to C21, C22
    # Term 5: (A11+A12)B22 -> contributes to C12, C22
    # Term 6: (A21-A11)(B11+B12) -> contributes to C21, C12
