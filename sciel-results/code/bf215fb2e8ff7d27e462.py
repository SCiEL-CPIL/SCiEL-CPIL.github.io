    # M1 = (A11 + A22) * (B11 + B22)
    # M2 = (A21 + A22) * B11
    # M3 = A11 * (B12 - B22)
    # M4 = A22 * (B21 - B11)
    # M5 = (A11 + A12) * B22
    # M6 = (A21 - A11) * (B11 + B12)
    # M7 = (A12 - A22) * (B21 + B22)
    
    # The 2x2 blocks of A (4x4) are at indices:
    # A11: i in {0,1}, j in {0,1}
    # A12: i in {0,1}, j in {2,3}
