import numpy as np
import time
from itertools import combinations

def construct():
    N = 17
    MIN_DIST = 6
    start_time = time.time()
    time_limit = 55

    # Precompute masks for blocking (all masks of weight < MIN_DIST)
    masks_by_dist = [[] for _ in range(MIN_DIST)]
    for d in range(MIN_DIST):
        for combo in combinations(range(N), d):
            mask = 0
            for i in combo:
                mask |= (1 << i)
            masks_by_dist[d].append(mask)
    
    all_masks = []
    for d in range(MIN_DIST):
        all_masks.extend(masks_by_dist[d])

    # Construct the [17,8,6] QR code using a known generator matrix
    # The [17,8,6] code is the shortened [18,9,6] extended quadratic residue code
    # We use a known generator matrix in systematic form [I_8 | P]
    
    # Generator matrix for [17,8,6] QR code (systematic form)
    # This is derived from the quadratic residues mod 17: {1, 2, 4, 8, 9, 13, 15, 16}
    # The code is generated by the circulant matrix with first row corresponding to these positions
    # After shortening, we get the following generator matrix:
    
    # Using a known basis for the [17,8,6] code:
    G_rows = [
        0b10000000000000001,  # weight 2
        0b01000000000000010,  # weight 2  
        0b00100000000000100,  # weight 2
        0b00010000000001000,  # weight 2
        0b00001000000010000,  # weight 2
        0b00000100000100000,  # weight 2
        0b00000010001000000,  # weight 2
        0b00000001010000000,  # weight 2
    ]
    
    # Actually, let me use a proper construction via the parity check matrix approach
    # or use a known valid generator matrix
    
    # Let's construct the [17,8,6] code properly using the fact that it's a QR code
    # The quadratic residues mod 17 are: 1, 2, 4, 8, 9, 13, 15, 16
    # The non-residues are: 3, 5, 6, 7, 10, 11, 12, 14
    
    # A generator matrix for the [17,8,6] QR code can be constructed as follows:
    # Use the circulant matrix with first row having 1s at positions corresponding to QRs
    # But this gives a cyclic code, and the [17,8,6] code is not cyclic in general
    
    # Let me use a different approach: construct via the extended [18,9,6] code
    # The [18,9,6] code has a generator matrix that includes the all-ones vector
    # and the [17,8,6] code is obtained by deleting one coordinate
    
    # For now, let's use a greedy approach with better initialization
    # Start with a good seed and expand greedily
    
    blocked = bytearray(1 << N)
    code = []
    
    def add_word(w):
        if blocked[w]:
            return
        code.append(w)
        for mask in all_masks:
            blocked[w ^ mask] = 1
    
    # Add zero word first
    add_word(0)
    
    # Add words in a structured way to get a good initial code
    # Use a greedy approach with ordering by weight
    candidates = list(range(1, 1 << N))
    candidates.sort(key=lambda x: bin(x).count('1'))
    
    for w in candidates:
        if time.time() - start_time > time_limit:
            break
        if not blocked[w]:
            add_word(w)
    
    # Local search to improve
    if time.time() - start_time < time_limit - 10:
        improved = True
        while improved and time.time() - start_time < time_limit - 5:
            improved = False
            for i in range(len(code)):
                if time.time() - start_time > time_limit - 5:
                    break
                removed = code[i]
                code.remove(removed)
                
                for mask in all_masks:
                    blocked[removed ^ mask] = 0
                
                old_len = len(code)
                for w in range(1 << N):
                    if time.time() - start_time > time_limit - 5:
                        break
                    if not blocked[w]:
                        code.append(w)
                        for mask in all_masks:
                            blocked[w ^ mask] = 1
                
                if len(code) > old_len:
                    improved = True
                else:
                    # Undo
                    while len(code) > old_len:
                        w = code.pop()
                        for mask in all_masks:
                            blocked[w ^ mask] = 0
                    for mask in all_masks:
                        blocked[removed ^ mask] = 1
                    code.append(removed)

    return code
