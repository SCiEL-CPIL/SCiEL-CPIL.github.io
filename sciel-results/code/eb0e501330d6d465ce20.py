import numpy as np
import time
from scipy.spatial import Delaunay

class Optimizer:
    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj
        self.start_time = time.time()
        self.deadline = 295.0

    def _elapsed(self):
        return time.time() - self.start_time

    def __call__(self, problem, bounds):
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        
        used = 0
        points = []
        objectives = []
        
        # DTLZ1 Pareto Front Analysis:
        # The Pareto front for DTLZ1 (minimizing) with n_obj=3 is a 2D simplex in objective space.
        # However, we work in the decision space variables x[0] and x[1] which map to the front.
        # Let x[2:] = 0.5 to satisfy g=0 (on the front).
        # f1 = 0.5 * x[0]
        # f2 = 0.5 * (1 - x[0]) * x[1]
        # f3 = 0.5 * (1 - x[1])
        
        # The mapping from (x[0], x[1]) in [0,1]^2 to the Pareto front (f1, f2, f3) is non-linear.
        # To maximize hypervolume in objective space, we should sample uniformly in the *objective* simplex.
        # The Pareto front is defined by f1 + f2 + f3 = 0.5, fi >= 0.
        # Let's parameterize the front using barycentric coordinates (u, v) such that:
        # f1 = 0.5 * u
        # f2 = 0.5 * (1 - u) * v  <-- Wait, this is the decision space mapping.
        
        # Let's reverse engineer the decision variables from desired objective points on the simplex.
        # The simplex in objective space has vertices:
        # A: (0.5, 0, 0)  -> x[0]=1, x[1]=0
        # B: (0, 0.5, 0)  -> x[0]=0, x[1]=1
        # C: (0, 0, 0.5)  -> x[0]=0, x[1]=0
        
        # Any point on the front is a convex combination of these vertices in objective space.
        # Let (f1, f2, f3) be a point on the simplex.
        # We need to find x[0], x[1] such that:
        # f1 = 0.5 * x0
        # f2 = 0.5 * (1 - x0) * x1
        # f3 = 0.5 * (1 - x1)
        
        # From f1: x0 = 2 * f1
        # From f3: x1 = 1 - 2 * f3
        # Check f2: 0.5 * (1 - 2*f1) * (1 - 2*f3)
        # Is this equal to f2?
        # Since f1+f2+f3 = 0.5 => f2 = 0.5 - f1 - f3
        # Let's check if 0.5 * (1 - 2*f1) * (1 - 2*f3) == 0.5 - f1 - f3
        # 0.5 * (1 - 2*f1 - 2*f3 + 4*f1*f3) = 0.5 - f1 - f3 + 2*f1*f3
        # This is NOT equal to 0.5 - f1 - f3 unless f1*f3 = 0.
        
        # Conclusion: The mapping from the linear objective simplex to the (x0, x1) decision space is NOT linear/affine.
        # The Pareto front in (x0, x1) space is actually the entire unit square [0,1]x[0,1] when mapped to the objective space?
        # No. The set of points (f1, f2, f3) generated by x0, x1 in [0,1] is the region under the hyperbolic surface.
        # Wait, DTLZ1's Pareto front is convex.
        # Let's re-read DTLZ1 definition.
        # f1 = 0.5 * x1
        # f2 = 0.5 * (1 - x1) * x2
        # f3 = 0.5 * (1 - x2)
        # If we fix g=0, the front is the image of the unit square under this map.
        # The image is a curved surface? No, it's a 2D manifold in 3D.
        # f1 + f2 + f3 = 0.5 * x1 + 0.5 * (1 - x1) x2 + 0.5 * (1 - x2)
        # = 0.5 * (x1 + x2 - x1 x2 + 1 - x2)
        # = 0.5 * (1 + x1 - x1 x2)
        # This is NOT constant 0.5.
        
        # My previous assumption that the front is a simplex f1+f2+f3=0.5 is INCORRECT for DTLZ1.
        # For DTLZ1, the Pareto front is defined by:
        # f1 = 0.5 * x1
        # f2 = 0.5 * (1 - x1) * x2
        # f3 = 0.5 * (1 - x2)
        # The front is the set of all (f1, f2, f3) achievable with x1, x2 in [0,1].
        
        # Let's check the shape.
        # x1=0 => f1=0, f2=0.5*x2, f3=0.5*(1-x2). Line segment from (0, 0.5, 0) to (0, 0, 0.5).
        # x1=1 => f1=0.5, f2=0, f3=0.5*(1-x2). Line segment from (0.5, 0, 0) to (0.5, 0, 0.5)? No.
        # If x1=1, f2=0. f1=0.5. f3=0.5*(1-x2).
        # So for x1=1, points are (0.5, 0, f3) where f3 in [0, 0.5].
        
        # The Pareto front is actually a curved surface bounded by these lines.
        # However, for hypervolume maximization, we just need to cover the Pareto front densely.
        
        # Strategy:
        # 1. Generate a uniform grid in the (x1, x2) decision space [0,1]^2.
        # 2. Map these to the Pareto front.
        # 3. Use Delaunay triangulation on the (x1, x2) grid to find centroids?
        #    Or simply use a uniform grid in (x1, x2) which maps to a non-uniform distribution on the front.
        #    Is uniform in (x1, x2) optimal for hypervolume?
        #    The Jacobian of the mapping (x1, x2) -> (f1, f2, f3) varies.
        #    To maximize hypervolume, we should sample uniformly in the *objective* space volume.
        #    But we can only control x1, x2.
        
        # Let's stick to the directive: "Use a deterministic 2D Delaunay triangulation of the Pareto simplex vertices".
        # The directive assumes the front is a simplex. Even if it's curved, we can approximate the "simplex" in decision space (which is a square) or try to invert the mapping.
        
        # Given the complexity of the curved front, a robust approach for DTLZ1 is to sample (x1, x2) uniformly.
        # However, the directive specifically asks for Delaunay triangulation of the "Pareto simplex vertices".
        # The vertices of the Pareto front in objective space are:
        # V1: x=(1,0) -> f=(0.5, 0, 0.5)
        # V2: x=(0,1) -> f=(0, 0.5, 0)
        # V3: x=(0,0) -> f=(0, 0, 0.5)
        # Wait, x=(1,1) -> f=(0.5, 0, 0). This is also a vertex?
        # Let's check x=(1,1): f1=0.5, f2=0, f3=0.
        # So the 4 corners of the decision square map to 4 points in objective space:
        # (1,0) -> (0.5, 0, 0.5)
        # (0,1) -> (0, 0.5, 0)
        # (0,0) -> (0, 0, 0.5)
        # (1,1) -> (0.5, 0, 0)
        
        # These 4 points form a tetrahedron? No, they are in 3D.
        # (0.5, 0, 0.5), (0, 0.5, 0), (0, 0, 0.5), (0.5, 0, 0).
        
        # If we treat the decision space [0,1]^2 as the domain, we can create a Delaunay triangulation of a grid in [0,1]^2.
        # Then we evaluate the centroid of each triangle in the decision space.
        
        # Let's generate a grid of points in [0,1]^2.
        # To get ~200 points, we can use a grid of ~14x14 = 196 points.
        # Then we compute the Delaunay triangulation of these grid points.
        # The centroids of the triangles will be slightly shifted from the grid points, providing a jittered, non-lattice set of points.
        
        n_grid = 14
        # Create a grid
        grid_x = np.linspace(0, 1, n_grid)
        grid_y = np.linspace(0, 1, n_grid)
        xx, yy = np.meshgrid(grid_x, grid_y)
        grid_points = np.column_stack((xx.ravel(), yy.ravel()))
        
        # Compute Delaunay triangulation
        try:
            tri = Delaunay(grid_points)
            # Get centroids of triangles
            # tri.simplices contains indices of vertices for each triangle
            centroids = []
            for simplex in tri.simplices:
                p1 = grid_points[simplex[0]]
                p2 = grid_points[simplex[1]]
                p3 = grid_points[simplex[2]]
                centroid = (p1 + p2 + p3) / 3.0
                centroids.append(centroid)
            
            centroids = np.array(centroids)
            
            # We might have more or fewer than budget.
            # If more, subsample. If fewer, add grid points or random.
            if len(centroids) > self.budget:
                # Subsample uniformly
                indices = np.linspace(0, len(centroids)-1, self.budget).astype(int)
                centroids = centroids[indices]
            elif len(centroids) < self.budget:
                # Add remaining grid points that are not centroids? Or just random?
                # Let's add the original grid points first, then random.
                remaining = self.budget - len(centroids)
                # Remove duplicates? Centroids are distinct.
                # Just append random points from the grid
                rng = np.random.default_rng(42)
                extra = rng.random((remaining, 2))
                centroids = np.vstack([centroids, extra])
                
        except Exception:
            # Fallback to pure grid
            centroids = grid_points
            if len(centroids) > self.budget:
                indices = np.linspace(0, len(centroids)-1, self.budget).astype(int)
                centroids = centroids[indices]
            elif len(centroids) < self.budget:
                rng = np.random.default_rng(42)
                extra = rng.random((self.budget - len(centroids), 2))
                centroids = np.vstack([centroids, extra])

        # Evaluate the points
        for i in range(len(centroids)):
            if used >= self.budget or self._elapsed() > self.deadline:
                break
            
            x1, x2 = centroids[i]
            x1 = float(np.clip(x1, 0.0, 1.0))
            x2 = float(np.clip(x2, 0.0, 1.0))
            
            x = np.full(self.dim, 0.5)
            x[0] = x1
            x[1] = x2
            
            f = problem(x)
            points.append(x.copy())
            objectives.append(f)
            used += 1
            
        return points
