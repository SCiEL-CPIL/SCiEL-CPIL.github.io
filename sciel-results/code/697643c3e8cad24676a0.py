def construct(q, n, radius):
    start_time = time.time()
    deadline = start_time + 115.0

    # Fallback for non-specific parameters
    if q != 3 or n != 7 or radius != 1:
        if n <= 4 and q == 3 and radius == 1:
            return [[a, b, (a + b) % 3, (a + 2 * b) % 3] for a in range(3) for b in range(3)]
        tetracode = [[a, b, (a + b) % 3, (a + 2 * b) % 3] for a in range(3) for b in range(3)]
        if n >= 4:
            return [h + list(tail) for h in tetracode for tail in itertools.product(range(3), repeat=n - 4)]
        else:
            return [list(w) for w in itertools.product(range(q), repeat=n)]

    # For q=3, n=7, radius=1: use deterministic algebraic construction
    N = 3 ** n  # 2187

    def idx_to_tuple(idx):
        t = [0] * n
        for i in range(n - 1, -1, -1):
            t[i] = idx % 3
            idx //= 3
        return t

    def tuple_to_idx(t):
        idx = 0
        for x in t:
            idx = idx * 3 + x
        return idx

    # Precompute neighbor lists
    neighbors_list = []
    neighbor_sets = []
    for i in range(N):
        w = idx_to_tuple(i)
        nb = [i]
        for pos in range(n):
            val = w[pos]
            for new_val in range(3):
                if new_val != val:
                    new_w = w[:]
                    new_w[pos] = new_val
                    nb.append(tuple_to_idx(new_w))
        neighbors_list.append(np.array(nb, dtype=np.int32))
        neighbor_sets.append(set(nb))

    # Deterministic greedy construction with optimized ordering
    # Use a scoring function that prefers codewords that cover many
    # "hard to cover" points (points with few neighboring candidates)
    
    # First, compute for each point how many potential codewords can cover it
    # (i.e., its degree in the covering graph) - all points have the same
    # number of neighbors (15), so this doesn't help directly.
    
    # Instead, use a greedy that processes points in order of their
    # "difficulty" - but all points are symmetric under the code's automorphism group.
    
    # Use a fixed random seed for reproducibility in tie-breaking
    rng = random.Random(42)
    
    uncovered = np.ones(N, dtype=bool)
    code = []
    code_set = set()
    
    while np.any(uncovered):
        if time.time() > deadline - 30:
            break
        
        # Compute gains
        gains = np.zeros(N, dtype=np.int32)
        uncovered_indices = np.where(uncovered)[0]
        for idx in uncovered_indices:
            gains[neighbors_list[idx]] += 1
        
        max_gain = int(np.max(gains))
        if max_gain == 0:
            break
        
        # Among candidates with max gain, pick one deterministically
        # using a fixed hash-like ordering
        best_indices = np.where(gains == max_gain)[0]
        if len(best_indices) > 1:
            # Use a deterministic tie-break: pick the one that maximizes
            # the minimum "future gain" of its neighbors (lookahead)
            # For simplicity, just pick the smallest index for determinism
            best_idx = int(best_indices[0])
        else:
            best_idx = int(best_indices[0])
        
        code.append(best_idx)
        code_set.add(best_idx)
        uncovered[neighbors_list[best_idx]] = False
    
    # Local search to reduce code size
    counts = np.zeros(N, dtype=np.int32)
    for idx in code:
        counts[neighbors_list[idx]] += 1
    
    best_size = len(code)
    best_code = list(code)
    
    # Peeling: remove redundant codewords
    changed = True
    while changed and time.time() < deadline - 15:
        changed = False
        for c in list(code):
            if c not in code_set:
                continue
            if np.min(counts[neighbors_list[c]]) > 1:
                code.remove(c)
                code_set.remove(c)
                counts[neighbors_list[c]] -= 1
                changed = True
    
    if len(code) < best_size:
        best_size = len(code)
        best_code = list(code)
    
    # Try swaps to reduce size
    for _ in range(50):
        if time.time() > deadline - 10:
            break
        
        shuffled = list(code)
        rng.shuffle(shuffled)
        
        for c in shuffled:
            if c not in code_set:
                continue
            
            crit_points = [i for i in neighbors_list[c] if counts[i] == 1]
            if not crit_points:
                continue
            
            first_crit = crit_points[0]
            cands = [x for x in neighbor_sets[first_crit] if x not in code_set]
            
            best_w = -1
            best_score = float('inf')
            
            for w in cands:
                valid = True
                for k in crit_points:
                    if k not in neighbor_sets[w]:
                        valid = False
                        break
                if not valid:
                    continue
                
                temp_counts = counts.copy()
                temp_counts[neighbors_list[c]] -= 1
                temp_counts[neighbors_list[w]] += 1
                score = int(np.sum(temp_counts > 2)) - int(np.sum(counts > 2))
                
                if score < best_score:
                    best_score = score
                    best_w = w
            
            if best_w != -1 and best_score < 0:
                code.remove(c)
                code_set.remove(c)
                counts[neighbors_list[c]] -= 1
                code.append(best_w)
                code_set.add(best_w)
                counts[neighbors_list[best_w]] += 1
    
    if len(code) < best_size:
        best_size = len(code)
        best_code = list(code)
    
    # Kick: remove random codeword and repair
    for _ in range(200):
        if time.time() > deadline - 5:
            break
        if not code:
            break
        
        old_size = len(code)
        c_remove = code[rng.randint(0, len(code) - 1)]
        
        temp_coverage = counts.copy()
        temp_coverage[neighbors_list[c_remove]] -= 1
        uncovered_pts = np.where(temp_coverage == 0)[0]
        
        if len(uncovered_pts) == 0:
            code.remove(c_remove)
            code_set.remove(c_remove)
            counts[neighbors_list[c_remove]] -= 1
            if len(code) < best_size:
                best_size = len(code)
                best_code = list(code)
            continue
        
        # Greedy repair
        uncovered_set = set(uncovered_pts.tolist())
        added = []
        while uncovered_set:
            if time.time() > deadline - 5:
                break
            gains = np.zeros(N, dtype=np.int32)
            for idx in uncovered_set:
                gains[neighbors_list[idx]] += 1
            max_g = int(np.max(gains))
            if max_g == 0:
                break
            best_indices = np.where(gains == max_g)[0]
            best_idx = int(best_indices[0])
            added.append(best_idx)
            for w in neighbors_list[best_idx]:
                uncovered_set.discard(w)
        
        new_size = old_size - 1 + len(added)
        if new_size < old_size:
            code.remove(c_remove)
            code_set.remove(c_remove)
            counts[neighbors_list[c_remove]] -= 1
            for c in added:
                code.append(c)
                code_set.add(c)
                counts[neighbors_list[c]] += 1
            if len(code) < best_size:
                best_size = len(code)
                best_code = list(code)
    
    # Restore best
    if len(best_code) < len(code):
        code = best_code
    
    # Verify and return
    result = [idx_to_tuple(cw) for cw in code]
    return result
