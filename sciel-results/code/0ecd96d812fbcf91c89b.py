    def mis_solve(base_set, time_limit):
        """
        Solves the Maximum Independent Set problem on the conflict graph of remaining candidates.
        Returns the list of selected vertices (candidates) that form an independent set.
        """
        s_set = set(base_set)
        base_sums = get_sums(base_set)
        
        # 1. Identify valid candidates that don't conflict with base_set
        valid_candidates = []
        for x in all_candidates:
            if x in s_set:
                continue
            if can_add(base_set, base_sums, x):
                valid_candidates.append(x)
        
        if not valid_candidates:
            return []
        
        # 2. Build conflict graph among valid_candidates
        # A and B conflict if A+B is in base_sums OR if adding A makes B invalid (A+B in base_sums is covered)
        # Actually, if A and B are both valid against base, they conflict if:
        # 1. A + B is in base_sums (impossible since A,B valid means A+b not in base_sums for any b in base, but A+B is a new sum)
        # Wait, Sidon property: all pairwise sums distinct.
        # If we add A and B, we generate sums: A+B, 2A, 2B.
        # Conflicts with base: A+b, B+b, 2A, 2B must not be in base_sums. (Checked by can_add)
        # Conflicts between A and B: A+B must not be in base_sums (already checked? No, can_add checks A+b for b in base. It does NOT check A+B if B is not in base yet).
        # So, A and B conflict if:
        # - A+B is in base_sums (impossible if A,B valid? No. A valid means A+b not in base. B valid means B+b not in base. A+B is a sum of two non-base elements. It doesn't conflict with base sums unless A+B equals some b1+b2 in base. But base sums are fixed. So A+B must not be in base_sums.)
        # - 2A is in base_sums (checked by can_add)
        # - 2B is in base_sums (checked by can_add)
        # - A+B equals 2A? No, distinct.
        # - A+B equals 2B? No.
        # - A+B equals some other sum generated by A or B?
        #   Sums generated by A: A+b for b in base, 2A.
        #   Sums generated by B: B+b for b in base, 2B.
        #   New sum: A+B.
        #   We need A+B not in {A+b, B+b, 2A, 2B} U base_sums.
        #   Since A,B not in base, A+B != A+b (implies B=b, false).
        #   A+B != B+b (implies A=b, false).
        #   A+B != 2A (implies B=A, false).
        #   A+B != 2B (implies A=B, false).
        #   So the only check needed between two valid candidates A and B is:
        #   Is A+B in base_sums?
        
        n_cands = len(valid_candidates)
        # Map index to value
        val_to_idx = {v: i for i, v in enumerate(valid_candidates)}
        
        # Adjacency list for conflict graph
        # Edge (i, j) exists if valid_candidates[i] + valid_candidates[j] is in base_sums
        adj = [set() for _ in range(n_cands)]
        for i in range(n_cands):
            for j in range(i + 1, n_cands):
                s_sum = valid_candidates[i] + valid_candidates[j]
                if s_sum in base_sums:
                    adj[i].add(j)
                    adj[j].add(i)
        
        # 3. Branch and Bound
        best_size = 0
        best_set = []
        
        # Precompute a greedy coloring for upper bound estimation
        # We will compute colors on the fly or precompute a static coloring for the initial graph?
        # Static coloring on the full graph is a valid upper bound for any induced subgraph.
        colors = [0] * n_cands
