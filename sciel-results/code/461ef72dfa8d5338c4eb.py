LJ_MIN = (2.0 ** (1.0 / 6.0))  # 1.122462048...

def _lj_energy(positions):
    """Compute total Lennard-Jones energy for given positions."""
    n = len(positions)
    energy = 0.0
    for i in range(n):
        for j in range(i + 1, n):
            r2 = np.sum((positions[i] - positions[j]) ** 2)
            r = np.sqrt(r2)
            if r < 1e-12:
                continue
            inv_r6 = 1.0 / (r2 ** 3)
            inv_r12 = inv_r6 * inv_r6
            energy += 4.0 * (inv_r12 - inv_r6)
    return energy

def _lj_energy_and_grad(positions):
    """Compute LJ energy and gradient."""
    n = len(positions)
    energy = 0.0
    grad = np.zeros_like(positions)
    for i in range(n):
        for j in range(i + 1, n):
            diff = positions[i] - positions[j]
            r2 = np.sum(diff ** 2)
            if r2 < 1e-12:
                continue
            r = np.sqrt(r2)
            inv_r2 = 1.0 / r2
            inv_r6 = inv_r2 ** 3
            inv_r12 = inv_r6 ** 2
            # dE/dr = 4*(-12*r^-13 + 6*r^-7)
            # dE/dxi = dE/dr * dr/dxi = dE/dr * (xi - xj)/r
            dEdr = 4.0 * (-12.0 * inv_r12 * inv_r2 + 6.0 * inv_r6 * inv_r2)
            dEdx = dEdr * diff / r
            energy += 4.0 * (inv_r12 - inv_r6)
            grad[i] += dEdx
            grad[j] -= dEdx
    return energy, grad

def _relax(positions):
    """Relax positions using L-BFGS-B."""
    def func_and_grad(x):
        pos = x.reshape(-1, 3)
        e, g = _lj_energy_and_grad(pos)
        return e, g.ravel()
    
    result = minimize(func_and_grad, positions.ravel(), method='L-BFGS-B', 
                      jac=True, options={'maxiter': 200, 'ftol': 1e-10, 'gtol': 1e-8})
    return result.x.reshape(-1, 3)

