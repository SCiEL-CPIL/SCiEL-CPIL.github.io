import random
import math

def calc_max_discrepancy(signs):
    n = len(signs)
    max_abs = 0
    # Iterate over all APs
    # Start s (1-indexed), step d, length L
    # 0-indexed: start s0, step d, length L
    # Elements: s0, s0+d, ..., s0+(L-1)d
    # Must be < n
    
    # Efficient way:
    # For each step d
    for d in range(1, n):
        # For each start s0 such that s0 + (L-1)d < n
        # We can iterate by residue classes mod d
        # Or just iterate all starts
        for s0 in range(n):
            # Build AP
            # s0, s0+d, ...
            curr_sum = 0
            idx = s0
            while idx < n:
                curr_sum += signs[idx]
                if abs(curr_sum) > max_abs:
                    max_abs = abs(curr_sum)
                idx += d
            # Note: The AP can be any length. The sums of prefixes of the AP are the sums of APs of shorter length with same start and step.
            # So checking all prefixes covers all lengths for this start and step.
            # Do we need to check sums that are not prefixes?
            # "ANY arithmetic progression contained in [1,256]"
            # An AP is defined by start, step, length.
            # The sum is $\sum_{k=0}^{L-1} s_{start + k \cdot step}$.
            # This is exactly the prefix sum of the sequence of elements in that AP.
            # So iterating start and step, and accumulating sum, checks all possible APs.
            # Wait, does "contained in [1,256]" imply the AP must be a contiguous segment of the AP defined by start and step?
            # Yes, an AP is a set $\{a, a+d, \dots, a+(L-1)d\}$.
            # So yes, prefix sums of the sequence generated by start and step cover all such APs.
    return max_abs

def construct():
    n = 256
    # 1. Thue-Morse
    signs = [1 if bin(i).count('1') % 2 == 0 else -1 for i in range(n)]
    
    # 2. Hill Climbing
    current_max = calc_max_discrepancy(signs)
    
    # Optimization: Precompute APs?
    # Number of APs is ~ N^2. Storing them might be memory heavy but N=256 is small.
    # Total APs: sum_{d=1}^{N} sum_{s=0}^{N-1} (floor((N-1-s)/d) + 1)
    # This is approx N^2.
    # Let's just recompute. 0.05s per eval is fine for ~100 iterations.
    
    improved = True
    iterations = 0
    while improved and iterations < 20: # Cap iterations to avoid timeout
        improved = False
        iterations += 1
        for i in range(n):
            old_sign = signs[i]
            signs[i] = -old_sign
            new_max = calc_max_discrepancy(signs)
            if new_max < current_max:
                current_max = new_max
                improved = True
            else:
                signs[i] = old_sign
                
    return signs
