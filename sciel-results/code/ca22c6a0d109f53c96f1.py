import time

DIMENSIONS = [2, 2, 5]

def construct():
    n, m, p = DIMENSIONS
    rank = 19
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Strassen for first 2 columns (indices 0,1 in B, 0..3 in C)
    # B indices: B00=0, B01=1, B10=5, B11=6
    # C indices: C00=0, C01=1, C10=2, C11=3
    
    # M1 = (A00+A11)(B00+B11) -> C00+=1, C11+=1
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[5][0] = 1
    W[0][0] = 1; W[3][0] = 1
    
    # M2 = (A10+A11)B00 -> C10+=1, C11-=-1 (so C11+=-1)
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[2][1] = 1; W[3][1] = -1
    
    # M3 = A00(B01-B11) -> C01+=1, C11+=1
    U[0][2] = 1
    V[1][2] = 1; V[5][2] = -1
    W[1][2] = 1; W[3][2] = 1
    
    # M4 = A11(B10-B00) -> C00+=1, C10+=1
    U[3][3] = 1
    V[5][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[2][3] = 1
    
    # M5 = (A00+A01)B11 -> C00-=-1 (C00+=-1), C01+=1
    U[0][4] = 1; U[1][4] = 1
    V[5][4] = 1
    W[0][4] = -1; W[1][4] = 1
    
    # M6 = (A10-A00)(B00+B01) -> C11+=1
    U[2][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    W[3][5] = 1
    
    # M7 = (A01-A11)(B10+B11) -> C00+=1, C10-=-1 (C10+=-1)
    U[1][6] = 1; U[3][6] = -1
    V[5][6] = 1; V[6][6] = 1
    W[0][6] = 1; W[2][6] = -1
    
    # Schoolbook for col 2 (B02=2, B12=7, C02=4, C12=5)
    # A00*B02 -> C02
    U[0][7] = 1; V[2][7] = 1; W[4][7] = 1
    # A01*B12 -> C02
    U[1][8] = 1; V[7][8] = 1; W[4][8] = 1
    # A10*B02 -> C12
    U[2][9] = 1; V[2][9] = 1; W[5][9] = 1
    # A11*B12 -> C12
    U[3][10] = 1; V[7][10] = 1; W[5][10] = 1
    
    # Schoolbook for col 3 (B03=3, B13=8, C03=6, C13=7)
    # A00*B03 -> C03
    U[0][11] = 1; V[3][11] = 1; W[6][11] = 1
    # A01*B13 -> C03
    U[1][12] = 1; V[8][12] = 1; W[6][12] = 1
    # A10*B03 -> C13
    U[2][13] = 1; V[3][13] = 1; W[7][13] = 1
    # A11*B13 -> C13
    U[3][14] = 1; V[8][14] = 1; W[7][14] = 1
    
    # Schoolbook for col 4 (B04=4, B14=9, C04=8, C14=9)
    # A00*B04 -> C04
    U[0][15] = 1; V[4][15] = 1; W[8][15] = 1
    # A01*B14 -> C04
    U[1][16] = 1; V[9][16] = 1; W[8][16] = 1
    # A10*B04 -> C14
    U[2][17] = 1; V[4][17] = 1; W[9][17] = 1
    # A11*B14 -> C14
    U[3][18] = 1; V[9][18] = 1; W[9][18] = 1
    
    return {"U": U, "V": V, "W": W}
