import numpy as np

def construct():
    n, m, p = 2, 3, 3
    rank = 12
    
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # Part 1: Strassen 2x2x2 (i in {0,1}, j in {0,1}, k in {0,1})
    # m1
    U[0, 0] = 1; U[3, 0] = 1
    V[0, 0] = 1; V[4, 0] = 1
    W[0, 0] = 1; W[3, 0] = 1
    
    # m2
    U[3, 1] = 1; U[4, 1] = 1
    V[0, 1] = 1
    W[1, 1] = 1
    
    # m3
    U[0, 2] = 1
    V[1, 2] = 1; V[4, 2] = -1
    W[2, 2] = 1
    
    # m4
    U[4, 3] = 1
    V[3, 3] = 1; V[0, 3] = -1
    W[0, 3] = 1; W[1, 3] = 1
    
    # m5
    U[0, 4] = 1; U[1, 4] = 1
    V[4, 4] = 1
    W[0, 4] = -1; W[2, 4] = 1
    
    # m6
    U[3, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[1, 5] = 1
    W[3, 5] = 1
    
    # m7
    U[1, 6] = 1; U[4, 6] = -1
    V[3, 6] = 1; V[4, 6] = 1
    W[0, 6] = 1
    
    # Part 2: Standard 2x2x1 (i in {0,1}, j in {0,1}, k=2)
    # m8
    U[0, 7] = 1
    V[2, 7] = 1
    W[4, 7] = 1
    
    # m9
    U[1, 8] = 1
    V[5, 8] = 1
    W[4, 8] = 1
    
    # m10
    U[3, 9] = 1
    V[2, 9] = 1
    W[5, 9] = 1
    
    # m11
    U[4, 10] = 1
    V[5, 10] = 1
    W[5, 10] = 1
    
    # Part 3: Rank 1 for 2x1x3 (i in {0,1}, j=2, k in {0,1,2})
    # m12
    U[2, 11] = 1; U[5, 11] = 1
    V[6, 11] = 1; V[7, 11] = 1; V[8, 11] = 1
    W[0, 11] = 1; W[1, 11] = 1; W[2, 11] = 1
    W[3, 11] = 1; W[4, 11] = 1; W[5, 11] = 1
    
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
