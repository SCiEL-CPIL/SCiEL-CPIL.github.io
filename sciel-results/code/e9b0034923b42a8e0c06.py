    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append((math.cos(ang), math.sin(ang)))
        
        c_obj = np.array([0.0, 0.0, 1.0])
        A_ub = []
        b_ub = []
        
        for nx, ny in normals:
            for px, py in pts:
                A_ub.append([-nx, -ny, -1.0])
                b_ub.append(-(px * nx + py * ny))
                A_ub.append([nx, ny, -1.0])
                b_ub.append(px * nx + py * ny)
        
        A_ub = np.array(A_ub)
        b_ub = np.array(b_ub)
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        
        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])
        
        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf'), (cx, cy), float('inf')
        
        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -50, 50)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S, (cx, cy), D

    def newton_polish_center(pts, beta, cx, cy, max_iter=100, tol=1e-14):
        """
        High-precision 2D Newton polish for the center given fixed rotation.
        The objective f(cx,cy) = max over all (point, normal) of |proj|.
        We use a subgradient-based approach with line search for robustness.
        """
        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append(np.array([math.cos(ang), math.sin(ang)]))
        
        def compute_max_and_active(cx, cy):
            max_proj = 0.0
            active = []
            for i, (px, py) in enumerate(pts):
                for j, n in enumerate(normals):
                    proj = (px - cx) * n[0] + (py - cy) * n[1]
                    if proj > max_proj:
                        max_proj = proj
                        active = [(i, j, 1.0)]
                    elif proj < -max_proj:
                        max_proj = -proj
                        active = [(i, j, -1.0)]
                    elif abs(proj) > max_proj - 1e-12:
                        if proj > 0:
                            active.append((i, j, 1.0))
                        else:
                            active.append((i, j, -1.0))
            return max_proj, active
        
        for it in range(max_iter):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
            D, active = compute_max_and_active(cx, cy)
            if len(active) == 0:
                break
            
            # Compute subgradient: average of active normals (with sign)
            gx = 0.0
            gy = 0.0
            for (i, j, sign) in active:
                gx += sign * normals[j][0]
                gy += sign * normals[j][1]
            gx /= len(active)
            gy /= len(active)
            
            norm_g = math.sqrt(gx*gx + gy*gy)
            if norm_g < tol:
                break
            
            # Line search
            alpha = 1.0
            for _ in range(50):
                new_cx = cx - alpha * gx
                new_cy = cy - alpha * gy
                new_D, _ = compute_max_and_active(new_cx, new_cy)
                if new_D < D - 1e-15:
                    cx, cy = new_cx, new_cy
                    break
                alpha *= 0.5
            else:
                break
        
        final_D, _ = compute_max_and_active(cx, cy)
        S = (final_D + APOTHEM) / APOTHEM
        return S, (cx, cy), final_D

    def optimize_shape(pts):
        best_S = float('inf')
