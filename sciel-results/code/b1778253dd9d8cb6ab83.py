import time
import random
import sys

def construct(n_rows, k):
    start_time = time.time()
    deadline = start_time + 105.0  # Safety margin
    
    # Lower bound: we need n_rows * k * (k+1) / 2 distinct differences.
    # Differences are in [1, M-1].
    # So M-1 >= n_rows * k * (k+1) / 2
    # M >= n_rows * k * (k+1) / 2 + 1
    total_diffs = n_rows * k * (k + 1) // 2
    lb = total_diffs + 1
    
    # Get a quick greedy solution to set an upper bound
    # This also serves as a fallback
    best_rows = None
    best_scope = float('inf')
    
    def greedy_construct():
        used = 0  # bitmask for used differences
        rows = []
        for _ in range(n_rows):
            row = [0]
            x = 0
            while len(row) < k + 1:
                x += 1
                # Check differences with all existing elements in row
                valid = True
                new_diffs = 0
                for a in row:
                    d = x - a
                    # d is at most M-1, but we don't know M yet in greedy.
                    # We just need to check if d is in used.
                    if (used >> d) & 1:
                        valid = False
                        break
                    new_diffs |= (1 << d)
                if valid:
                    row.append(x)
                    used |= new_diffs
            rows.append(row)
        return rows, max(max(r) for r in rows)
    
    # Run a few randomized greedy variants to get a better initial bound
    for _ in range(20):
        rows, scope = greedy_construct()
        if scope < best_scope:
            best_scope = scope
            best_rows = rows
        
        if time.time() > deadline - 10:
            break
            
    # If we have a very good bound, we might not need deep search
    # But let's try to find a better one via backtracking
    
    # Backtracking search for minimal M
    # We search M from lb to best_scope - 1
    # If we find a solution for M, that's better than best_scope.
    
    def is_valid_solution(rows):
        used = 0
        for row in rows:
            for i in range(len(row)):
                for j in range(i+1, len(row)):
                    d = row[j] - row[i]
                    if (used >> d) & 1:
                        return False
                    used |= (1 << d)
        return True

    # We will search for M in range(lb, best_scope)
    # To avoid spending too much time on infeasible M, we can limit the depth of search or time per M.
    
    # Optimization: Precompute nothing, just use bitmask.
    # The number of differences is small (< 200 usually).
    
    def backtrack_row(row_idx, current_row, used_diffs, M):
        # current_row is a list of ints, starts with [0]
        if len(current_row) == k + 1:
            return True, current_row
        
        # Heuristic: try smaller numbers first? Or larger?
        # Smaller numbers tend to create smaller differences, which are more "valuable" (scarce).
        # So maybe try larger numbers first to save small diffs for later?
        # Or try to fit the row tightly.
        
        last = current_row[-1]
        # Next number must be > last and <= M-1
        # Also, we need to leave enough room for remaining elements?
        # Remaining elements: rem = k + 1 - len(current_row)
        # We need rem-1 more elements.
        # The smallest possible next elements are last+1, last+2...
        # So we need last + (rem-1) <= M-1 => last <= M - rem
        
        # Let's iterate next_val from last+1 to M-1
        # To prune, if we pick a very large next_val, we might waste space.
        # But we must ensure we can complete the row.
        
        # A stronger pruning:
        # The differences generated by adding x to current_row are {x - a for a in current_row}.
        # These must not be in used_diffs.
        
        # Let's try values in a randomized order or specific heuristic.
        # For speed, let's try values from last+1 to M-1.
        
        # To speed up, we can estimate if it's possible to complete.
        # The number of available differences in [1, M-1] is M-1.
        # Used differences count: bin_count(used_diffs).
        # We need (k+1 - len(current_row)) * len(current_row) more differences?
        # No, adding one element x adds len(current_row) new differences.
        
        # Simple loop
        for x in range(last + 1, M):
            # Check if x is valid
            valid = True
            new_diffs = 0
            for a in current_row:
                d = x - a
                if (used_diffs >> d) & 1:
                    valid = False
                    break
                new_diffs |= (1 << d)
            
            if valid:
                # Recurse
                res, next_row = backtrack_row(row_idx, current_row + [x], used_diffs | new_diffs, M)
                if res:
                    return True, next_row
                # If time is up, abort
                if time.time() > deadline - 5:
                    return False, None
                    
        return False, None

    def backtrack_all_rows(row_idx, rows, used_diffs, M):
        if row_idx == n_rows:
            return True, rows
        
        # Try to build row row_idx
        # Symmetry breaking: enforce rows[0][1] < rows[1][1] < ...
        # If row_idx > 0, the first element (index 1) of current row must be > rows[row_idx-1][1]
        min_first = rows[row_idx-1][1] + 1 if row_idx > 0 else 1
        
        # We start the row with [0]. The next element is x1.
        # x1 must be >= min_first.
        
        # We can call a helper that builds the rest of the row given the first element.
        # Or just let backtrack_row handle it, but it starts with [0].
        # We need to constrain the first non-zero element.
        
        # Let's modify backtrack_row to accept a min_start for the first non-zero element?
        # Or just iterate x1 from min_first to M-1, then build the rest.
        
        for x1 in range(min_first, M):
            # Check x1 against used_diffs (only diff with 0 is x1)
            if (used_diffs >> x1) & 1:
                continue
            
            new_diffs = 1 << x1
            current_row = [0, x1]
            
            # Now build the rest of the row (k-1 more elements)
            # We can reuse backtrack_row but it assumes we start with [0].
            # Let's write a specific builder for the rest.
            
            def build_rest(idx, row, u_diffs):
                if len(row) == k + 1:
                    return True, row
                last = row[-1]
                # Pruning: need len(row) to k+1.
                # Max possible last element?
                for x in range(last + 1, M):
                    valid = True
                    nd = 0
                    for a in row:
                        d = x - a
                        if (u_diffs >> d) & 1:
                            valid = False
                            break
                        nd |= (1 << d)
                    if valid:
                        res, nr = build_rest(idx, row + [x], u_diffs | nd)
                        if res:
                            return True, nr
                        if time.time() > deadline - 5:
                            return False, None
                return False, None
            
            res, full_row = build_rest(row_idx, current_row, used_diffs | new_diffs)
            if res:
                new_rows = rows + [full_row]
                res2, final_rows = backtrack_all_rows(row_idx + 1, new_rows, used_diffs | new_diffs, M)
                if res2:
                    return True, final_rows
            if time.time() > deadline - 5:
                return False, None
                
        return False, None

    # Search for minimal M
    # We iterate M from lb to best_scope - 1
    # If we find a solution, we update best_rows and best_scope and continue to see if we can go lower?
    # No, if we find a solution for M, it's better than the current best.
    # We want the MINIMAL M. So we should search from lb upwards.
    # If we find a solution for M, that is the answer (since we are going up from lb).
    # But we must ensure we don't miss a smaller M if we started with a bad heuristic?
    # No, lb is a hard lower bound.
    
    # However, backtracking can be slow.
    # We should limit the time spent on each M.
    
    current_time = time.time()
    for M in range(lb, best_scope):
        if time.time() > deadline - 10:
            break
        
        # Try to find a solution with max element M
        # Note: The elements must be <= M.
        # Our backtracking uses range(1, M), so max element is M-1.
        # We want max element <= M.
        # So we should search for M such that max element is M.
        # Let's adjust: search for scope S. Elements in [0, S].
        # Differences in [1, S-1].
        
        # Let's rephrase: We want to find rows with max element <= S.
        # We iterate S from lb to best_scope - 1.
        
        # In backtrack, we use M as the exclusive upper bound for elements?
        # In `range(last+1, M)`, the max element is M-1.
        # So if we want max element <= S, we should set M = S+1.
        
        S = M
        M_bound = S + 1
        
        # Time limit per S: 1s?
        t_start = time.time()
        
        res, rows = backtrack_all_rows(0, [], 0, M_bound)
        
        if res:
            # Found a solution with scope S
            # Verify
            if is_valid_solution(rows):
                best_scope = S
                best_rows = rows
                # Since we are searching from lb upwards, this is the minimal possible?
                # Not necessarily, if we skipped some S due to timeout?
                # But we are iterating sequentially.
                # So this is the best we found so far.
                # We can break if we want the absolute best, but maybe we can find even smaller?
                # No, we started from lb. So this is the smallest S that worked.
                # We can return immediately?
                # Yes, because we are looking for the minimum.
                # But wait, if the search for a smaller S timed out, we might have missed it.
                # So we should not assume it's the global minimum if we had timeouts.
                # However, for the purpose of the score, returning the first valid one found
                # in an upward search is good, but if we timed out on S=113, and found S=114,
                # S=113 might still be possible.
                # Given the complexity, let's just keep the best found.
                # Actually, if we find a solution for S, we can return it as it's better than the previous best.
                # But can we find a smaller one? Only if we didn't search it properly.
                # To be safe, we continue searching for smaller S? No, we are going up.
                # So we found the first valid S.
                # We can return this.
                return rows
        
        # If not found, continue to next S
        # If time is running out, break
        if time.time() > deadline - 5:
            break
            
    return best_rows
