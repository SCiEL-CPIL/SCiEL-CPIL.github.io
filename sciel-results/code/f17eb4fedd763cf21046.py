def construct():
    """
    Construct a binary code of length 17 with minimum distance at least 6.
    Start with the 32-word first-order Reed-Muller code and use local search
    to add more words.
    """
    start_time = time.time()
    deadline = start_time + 80.0  # 80 second deadline with 10 second safety margin
    
    # Build the 32-word RM(1,4) code extended to 17 bits
    # RM(1,4): all affine Boolean functions on F_2^4
    words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            # Extend with one zero bit at position 16
            words.append(word)
    
    words = list(words)
    word_set = set(words)
    n_words = len(words)
    
    # Precompute popcount table for fast distance calculation
    popcount_table = np.array([bin(i).count('1') for i in range(1 << 17)], dtype=np.uint8)
    
    # Convert words to numpy array for vectorized operations
    words_np = np.array(words, dtype=np.uint32)
    
    # Local search: try to add new words
    # For each candidate word, check if it has distance >= 6 from all existing words
    
    # Generate candidate words in a smart order
    # Start with words that are close to existing words but not too close
    
    added_count = 0
    attempts = 0
    
    while time.time() < deadline and added_count < 300:
        attempts += 1
        
        # Generate a random candidate
        if attempts % 100 == 0:
            # Occasionally try a word near an existing word
            idx = random.randint(0, n_words - 1)
            base = words[idx]
            # Flip 1-3 random bits
            n_flips = random.randint(1, 3)
            candidate = base
            for _ in range(n_flips):
                bit_pos = random.randint(0, 16)
                candidate ^= (1 << bit_pos)
        else:
            candidate = random.randint(0, (1 << 17) - 1)
        
        if candidate in word_set:
            continue
        
        # Check distance to all existing words using vectorized operations
        # Compute XOR of candidate with all words
        diffs = words_np ^ candidate
        # Compute popcount for each diff
        dists = popcount_table[diffs]
        
        if dists.min() >= 6:
            words.append(candidate)
            word_set.add(candidate)
            n_words += 1
            words_np = np.append(words_np, candidate)
            added_count += 1
        
        # Check deadline
        if time.time() > deadline - 5.0:
            break
    
    # Try some more structured additions
    if time.time() < deadline - 10.0:
        # Try all words of weight 3, 4, 5, 6, 7, 8
        for weight in range(3, 9):
            if time.time() > deadline - 5.0:
                break
            # Generate candidates of this weight
            # Use combinations
            from itertools import combinations
            for combo in combinations(range(17), weight):
                if time.time() > deadline - 5.0:
                    break
                candidate = 0
                for bit in combo:
                    candidate |= (1 << bit)
                
                if candidate in word_set:
                    continue
                
                diffs = words_np ^ candidate
                dists = popcount_table[diffs]
                
                if dists.min() >= 6:
                    words.append(candidate)
                    word_set.add(candidate)
                    n_words += 1
                    words_np = np.append(words_np, candidate)
    
    # Final validation
    # Check that all pairs have distance >= 6
    # (This is expensive, so only do a spot check)
    
    return words
