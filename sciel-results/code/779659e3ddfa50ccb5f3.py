def construct():
    import time
    start_time = time.time()
    
    # Deadline guard: 90s limit, keep margin
    deadline = start_time + 85.0

    def poly_mod(a, b):
        """Compute a % b in GF(2)[x]"""
        deg_a = a.bit_length() - 1
        deg_b = b.bit_length() - 1
        while deg_a >= deg_b and a != 0:
            shift = deg_a - deg_b
            a ^= (b << shift)
            deg_a = a.bit_length() - 1
        return a

    # Target polynomial: x^17 - 1 = x^17 + 1 in GF(2)
    target = (1 << 17) | 1
    
    # Find generator polynomials of degree 8 that divide x^17 + 1
    # There should be 2 such polynomials (cyclotomic cosets of size 8)
    candidates = []
    for g in range(128, 256):  # Degree 8 means MSB (bit 8) is 1, range 2^8 to 2^9-1
        if poly_mod(target, g) == 0:
            candidates.append(g)
            
    if not candidates:
        # Fallback to Reed-Muller if something goes wrong (should not happen)
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words

    # Pick the first candidate
    g = candidates[0]
    
    # Generate basis vectors for the [17, 9, 5] cyclic code
    # The code is generated by g(x).
    # A basis is given by x^i * g(x) mod (x^17 - 1) for i = 0 to 8
    basis = []
    for i in range(9):
        # x^i * g
        # Since we are working mod x^17 - 1, we can just compute the product and mod
        # However, x^i * g is just a shift of g's coefficients?
        # In polynomial representation (bit i is coeff of x^i), multiplying by x shifts bits left.
        # Mod x^17-1 means wrapping around bit 16 to bit 0.
        # Let's use poly_mod to be safe, or manual rotation.
        # Manual rotation is faster and easier.
        # g is 17 bits wide (conceptually, though stored in int).
        # We need (g * (1 << i)) % target
        # But note: g is degree 8. g * x^8 is degree 16.
        # All basis vectors will have degree < 17.
        # So we can just do:
        word = (g << i)
        # If word exceeds 17 bits, wrap around
        # Actually, since deg(g)=8 and i<=8, max degree is 16.
        # So no wrap-around needed for i=0..8!
        # Wait, x^8 * g(x) has max degree 8+8=16.
        # So (g << i) is already the correct representation in GF(2)[x] for i=0..8.
        basis.append(word)
        
    # Generate all 512 codewords
    words = set()
    for mask in range(512):
        word = 0
        for i in range(9):
            if (mask >> i) & 1:
                word ^= basis[i]
        # Extend to 18 bits: add parity bit at position 17
        # Parity is XOR of all bits in word (weight mod 2)
        parity = word.bit_count() & 1
        word_18 = word | (parity << 17)
        words.add(word_18)
        
    # Convert to list
    result = list(words)
    
    # Optional: Verify minimum distance to ensure correctness
    # If this fails, we might have picked the wrong generator or made a mistake.
    # But the math says it should be 6.
    # Checking 512 words takes ~130k XORs. Fast enough.
    min_dist = 100
    for i in range(len(result)):
        for j in range(i + 1, len(result)):
            d = (result[i] ^ result[j]).bit_count()
            if d < min_dist:
                min_dist = d
            if min_dist < 6:
                # If distance is less than 6, something is wrong.
                # Fallback to Reed-Muller
                words = []
                for slope in range(16):
                    for intercept in range(2):
                        word = 0
                        for point in range(16):
                            bit = ((slope & point).bit_count() + intercept) % 2
                            word |= bit << point
                        words.append(word)
                return words
                # break inner loop
        if min_dist < 6:
            break

    return result
