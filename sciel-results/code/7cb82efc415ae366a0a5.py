import time
from fractions import Fraction

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # 55 seconds to be safe
    
    target = Fraction(5, 31)
    best_max_denom = float('inf')
    best_solution = None
    
    # Helper to greedily decompose a fraction into distinct unit fractions
    # Returns a list of denominators or None if it fails (e.g., repeats)
    def greedy_decompose(r, used_denoms, max_terms=200):
        if r == 0:
            return []
        if len(used_denoms) + max_terms > 256:
            return None
        
        values = []
        # We must ensure new denominators are not in used_denoms
        # Greedy step: d = ceil(1/r)
        while r > 0:
            if time.time() > deadline:
                return None
            
            d = (r.denominator + r.numerator - 1) // r.numerator
            
            # If d is already used, we need to skip to next valid d?
            # Standard greedy picks the smallest d. If that d is used, 
            # the remainder might not be representable with distinct denominators 
            # using pure greedy. 
            # However, for the remainder of a 2-term prefix, the denominators 
            # generated by greedy are usually large and distinct from the small 
            # prefix denominators.
            # If d is in used_denoms, we can try d+1, d+2... but this breaks 
            # the "greedy" optimality and might not terminate quickly or work.
            # Given the structure, it's highly likely d > max(used_denoms) if 
            # r is small enough.
            
            if d in used_denoms:
                # Try to find next valid d
                # This is a heuristic branch. If greedy fails, return None.
                # Or we can just fail this path.
                return None
                
            values.append(d)
            used_denoms.add(d)
            r -= Fraction(1, d)
            
            if len(values) > 250:
                return None
                
        return values

    # Search for d1, d2
    # 1/d1 + 1/d2 < 5/31
    # d1 must be at least 7 because 1/6 > 5/31
    for d1 in range(7, 30):
        if time.time() > deadline:
            break
            
        # 1/d2 < 5/31 - 1/d1
        # d2 > 1 / (5/31 - 1/d1)
        rem1 = target - Fraction(1, d1)
        if rem1 <= 0:
            continue
            
        min_d2 = (rem1.denominator + rem1.numerator - 1) // rem1.numerator + 1
        if min_d2 <= d1:
            min_d2 = d1 + 1
            
        # We don't want d2 to be too large, otherwise the remainder is tiny 
        # and greedy might blow up, or it's just inefficient.
        # But we want to minimize max denominator.
        # Let's iterate d2 up to a limit.
        # If d2 is very large, 1/d2 is small, remainder is close to rem1.
        # The greedy step for rem1 will pick a d close to 1/rem1.
        
        for d2 in range(min_d2, min_d2 + 10000):
            if time.time() > deadline:
                break
                
            rem2 = rem1 - Fraction(1, d2)
            if rem2 <= 0:
                # We can break here if we want strictly less, 
                # but the problem says summing reciprocally to EXACTLY 5/31.
                # If rem2 == 0, we have a 2-term solution.
                if rem2 == 0:
                    candidate = [d1, d2]
                    max_d = max(candidate)
                    if max_d < best_max_denom:
                        best_max_denom = max_d
                        best_solution = candidate
                    break
                else:
                    continue # rem2 < 0, increasing d2 makes rem2 larger? No.
                    # 1/d2 decreases as d2 increases.
                    # rem2 = rem1 - 1/d2.
                    # As d2 increases, 1/d2 decreases, so rem2 increases.
                    # So if rem2 < 0, increasing d2 will make rem2 less negative, 
                    # potentially crossing 0.
                    # So we cannot break. We must continue until rem2 > 0.
                    # But we started at min_d2 which ensures rem2 > 0?
                    # min_d2 = ceil(1/rem1) + 1.
                    # 1/min_d2 < rem1. So rem2 > 0.
                    # So rem2 should always be > 0 in this loop.
                    pass
            
            # rem2 > 0
            used = {d1, d2}
            decomp = greedy_decompose(rem2, used)
            
            if decomp is not None:
                candidate = [d1, d2] + decomp
                # Check distinctness (greedy should ensure this, but double check)
                if len(set(candidate)) == len(candidate):
                    max_d = max(candidate)
                    if max_d < best_max_denom:
                        best_max_denom = max_d
                        best_solution = candidate
    
    if best_solution is None:
        # Fallback to the seed solution if search fails or times out with no result
        r, values = Fraction(5, 31) - Fraction(1, 8), [8]
        while r:
            d = (r.denominator + r.numerator - 1) // r.numerator
            values.append(d)
            r -= Fraction(1, d)
        return values
        
    return best_solution
