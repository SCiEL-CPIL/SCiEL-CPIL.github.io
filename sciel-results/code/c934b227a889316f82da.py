"""Cayley-graph construction for 4-regular girth-10 graph."""
import math
import time
from collections import deque

def construct(k, g):
    if k != 4:
        return _construct_fallback(k, g)
    
    start_time = time.time()
    deadline = start_time + 110.0  # 10s margin
    
    # Try to find a 4-regular Cayley graph on Z_p x Z_q with girth >= g
    # We search for small orders n >= Moore bound (243)
    
    # Candidate pairs (p, q) with p <= q
    # We want p*q to be small but >= 243
    candidates = [
        (13, 19), # 247
        (3, 83),  # 249
        (11, 23), # 253
        (3, 89),  # 267
        (5, 59),  # 295
        (13, 23), # 299
        (7, 43),  # 301
        (3, 101), # 303
        (5, 61),  # 305
        (3, 103), # 309
        (11, 29), # 319
        (3, 107), # 321
        (17, 19), # 323
        (11, 31), # 341
        (13, 29), # 377
    ]
    
    for p, q in candidates:
        if time.time() > deadline:
            break
            
        n = p * q
        # We can normalize g1 = (1, v1)
        # g2 = (u2, v2)
        # Condition: det = v2 - u2*v1 is coprime to p and q
        
        for v1 in range(q):
            for u2 in range(p):
                for v2 in range(q):
                    if time.time() > deadline:
                        break
                    
                    g1 = (1, v1)
                    g2 = (u2, v2)
                    
                    # Check if g1, g2 generate the group
                    # Matrix M = [[1, u2], [v1, v2]]
                    # det = v2 - u2*v1
                    det = (v2 - u2 * v1)
                    if math.gcd(det, p) != 1 or math.gcd(det, q) != 1:
                        continue
                    
                    # Check distinctness and non-inverses
                    # g1 != g2, g1 != -g2
                    if g1 == g2 or g1 == (-g2[0] % p, -g2[1] % q):
                        continue
                    
                    # Girth check
                    if _check_girth_abelian(p, q, g1, g2, g):
                        # Construct edges
                        edges = []
                        # Map (u, v) to index
                        # index = u * q + v
                        # Neighbors of (u, v):
                        # (u + g1[0], v + g1[1]), (u - g1[0], v - g1[1])
                        # (u + g2[0], v + g2[1]), (u - g2[0], v - g2[1])
                        
                        for u in range(p):
                            for v in range(q):
                                i = u * q + v
                                # Add edges for g1
                                u1 = (u + g1[0]) % p
                                v1n = (v + g1[1]) % q
                                j1 = u1 * q + v1n
                                if i < j1:
                                    edges.append((i, j1))
                                # Add edges for g2
                                u2n = (u + g2[0]) % p
                                v2n = (v + g2[1]) % q
                                j2 = u2n * q + v2n
                                if i < j2:
                                    edges.append((i, j2))
                                
                                # We only add edges for +g1, +g2 from each vertex
                                # The -g edges are covered when we visit the neighbor
                                # Wait, this logic is for undirected graphs.
                                # If we iterate all vertices and add (i, i+g), we get each edge twice if we are not careful with i < j.
                                # But we must ensure we don't miss edges where i > j.
                                # The condition `if i < j` ensures we add it once.
                                # However, we must check if the edge exists in the reverse direction too?
                                # No, (i, j) is the same as (j, i).
                                # Is it possible that i+g1 = j, but j+g1 != i? No, g1 is a fixed vector.
                                # So the edge is undirected.
                                # The loop adds (i, i+g1) if i < i+g1.
                                # It adds (i, i+g2) if i < i+g2.
                                # This covers all edges generated by +g1 and +g2.
                                # Since the graph is generated by {g1, -g1, g2, -g2},
                                # and we treat edges as undirected, the set of edges is
                                # { (x, x+g1) } U { (x, x+g2) } for all x.
                                # This is correct.
                        
                        return n, edges
                        
    # Fallback to LUW if no small Cayley graph found
    return _construct_fallback(4, g)

def _check_girth_abelian(p, q, g1, g2, g):
    """
    Check if the Cayley graph of Z_p x Z_q with generators {g1, -g1, g2, -g2}
    has girth >= g.
    """
    # Steps
    s0 = g1
    s1 = (-g1[0] % p, -g1[1] % q)
    s2 = g2
    s3 = (-g2[0] % p, -g2[1] % q)
    steps = [s0, s1, s2, s3]
    
    # Inverse map: 0<->1, 2<->3
    inv = {0: 1, 1: 0, 2: 3, 3: 2}
    
    # BFS on non-backtracking walks
    # State: (u, v, last_step_idx)
    # Start: (0, 0) is not a state in the walk sense, we start from neighbors.
    # Actually, we want to find if (0,0) is reachable from (0,0) via non-backtracking walk of length L < g.
    # We can just do BFS from all states (u, v, last) that are at distance 1 from (0,0)?
    # No, standard method:
    # Level 0: (0,0)
    # Level 1: (s0[0], s0[1], 0), (s1[0], s1[1], 1), ...
    # Level k: ...
    # Check if (0,0, last) is in Level k for k < g.
    # Note: The "last" step in the state (0,0, last) means the last step taken was `last`.
    # This is a valid closed walk.
    
    visited = set()
    # Level 1
    frontier = []
    for i, s in enumerate(steps):
        state = (s[0], s[1], i)
        visited.add(state)
        frontier.append(state)
        
    for L in range(2, g):
        new_frontier = []
        for (u, v, last) in frontier:
            for i, s in enumerate(steps):
                if i == inv[last]:
                    continue
                nu = (u + s[0]) % p
                nv = (v + s[1]) % q
                state = (nu, nv, i)
                if state not in visited:
                    visited.add(state)
                    if nu == 0 and nv == 0:
                        return False
                    new_frontier.append(state)
        frontier = new_frontier
        if not frontier:
            break
            
    return True

def _construct_fallback(k, g):
    """Fallback: use the Lazebnik-Ustimenko-Woldar construction from the seed."""
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
