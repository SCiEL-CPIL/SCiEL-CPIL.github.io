import time
import random

def construct():
    """
    Build a set of distinct integers in 1..256 maximizing size such that
    no subset sum is achievable by subsets of different cardinalities.
    
    Uses bitmask-based subset sum tracking for speed, enabling larger sets.
    """
    start_time = time.time()
    DEADLINE = 55.0  # safety margin before 90s kill
    
    def elapsed():
        return time.time() - start_time
    
    def is_done():
        return elapsed() > DEADLINE

    def compute_sums_by_k(A):
        """
        Compute sums_by_k for set A.
        sums_by_k[k] is a bitmask where bit s is 1 if sum s is achievable with exactly k elements.
        """
        n = len(A)
        sums_by_k = [0] * (n + 1)
        sums_by_k[0] = 1  # bit 0 is set, sum 0 with 0 elements
        
        for a in A:
            # Iterate backwards to avoid using 'a' multiple times in the same step
            # We update sums_by_k[k+1] based on old sums_by_k[k]
            # Since we go backwards, sums_by_k[k] has not yet been updated by 'a' for this iteration
            for k in range(n - 1, -1, -1):
                if sums_by_k[k]:
                    # Shift left by 'a' adds 'a' to all sums in level k
                    # The result is a set of sums achievable with k+1 elements including 'a'
                    # We OR this into level k+1
                    sums_by_k[k + 1] |= (sums_by_k[k] << a)
        
        return sums_by_k

    def is_valid_sums(sums_by_k):
        """
        Check if no sum appears in two different cardinality classes.
        sums_by_k is a list of bitmasks.
        """
        n = len(sums_by_k)
        for i in range(n):
            for j in range(i + 1, n):
                if sums_by_k[i] & sums_by_k[j]:
                    return False
        return True

    def try_add_element(A, candidate, sums_by_k):
        """
        Try to add candidate to A.
        Returns (success, new_sums_by_k).
        A is a list of ints.
        sums_by_k is a list of bitmasks.
        """
        if candidate in A:
            return False, None
        
        n = len(A)
        # Copy existing sums
        new_sums_by_k = list(sums_by_k)
        # Initialize the new level (n+1) to 0
        new_sums_by_k.append(0)
        
        # Calculate the "forbidden" mask: union of all sums except the target level (n+1)
        # The new sums will go into level n+1. They must not conflict with any other level.
        forbidden_mask = 0
        for k in range(n + 1): # 0 to n
            forbidden_mask |= new_sums_by_k[k]
        
        # The new sums for level n+1 are generated by shifting level n by 'candidate'
        # AND potentially other levels? No.
        # When we add 'candidate', any subset of size k from A can be extended to size k+1 by adding 'candidate'.
        # So new sums for level k+1 include (old_sums[k] << candidate).
        # We need to check if ANY of these new sums conflict with forbidden masks.
        
        # Optimization:
        # The new sums for level k+1 are `new_sums_by_k[k+1] | (new_sums_by_k[k] << candidate)`.
        # We need to check if `(new_sums_by_k[k] << candidate)` has any bits set that are in `forbidden_mask` 
        # BUT NOT in `new_sums_by_k[k+1]` (because collisions within the same level are allowed).
        
        # Actually, simpler:
        # The new state for level k+1 is `old_sums[k+1] | (old_sums[k] << candidate)`.
        # The constraint is that the *newly added* bits must not overlap with other levels.
        # The newly added bits are `(old_sums[k] << candidate) & ~old_sums[k+1]`.
        # These bits must be disjoint from all other levels `j != k+1`.
        
        # Let's compute the union of all "newly added" bits across all k.
        # If any newly added bit conflicts with a "forbidden" bit (from other levels), it's invalid.
        
        # However, we must be careful. The "forbidden" mask for level k+1 is `Union(all levels j != k+1)`.
        # As we iterate k, the "other levels" change? No, the other levels are fixed (they are the old sums, except the target level).
        # Wait, if we update level k+1, does it affect the forbidden mask for level k+2?
        # Yes, but we are adding 'candidate' to the whole set at once.
        # The new sums for level k+1 come from old level k.
        # The new sums for level k+2 come from old level k+1.
        # The "old" levels are the ones before adding 'candidate'.
        
        # Let's verify the logic:
        # New_sums[k+1] = Old_sums[k+1] | (Old_sums[k] << a)
        # Constraint: For all i != j, New_sums[i] & New_sums[j] == 0.
        
        # This is tricky to check incrementally in one pass without storing intermediate states or doing multiple passes.
        # Given n is small (< 60), we can just construct the full `new_sums_by_k` and then check validity.
        # Construction is O(N) shifts. Validity check is O(N^2) bitwise ANDs.
        # This is very fast.
        
        for k in range(n, -1, -1):
            if new_sums_by_k[k]:
                new_sums_by_k[k + 1] |= (new_sums_by_k[k] << candidate)
        
        # Now check validity of the new state
        if not is_valid_sums(new_sums_by_k):
            return False, None
        
        return True, new_sums_by_k

    def greedy_build(order, max_size=60):
        """Build a valid set by greedily adding elements in the given order."""
        A = []
        sums_by_k = [1]  # Level 0 has sum 0
        
        for candidate in order:
            if len(A) >= max_size:
                break
            success, new_sums = try_add_element(A, candidate, sums_by_k)
            if success:
                A.append(candidate)
                sums_by_k = new_sums
            if is_done():
                break
        
        return A, sums_by_k

    def local_search_improve(A, sums_by_k, max_size=60):
        """Try to improve the set by swapping elements or adding new ones."""
        A = list(A)
        sums_by_k = list(sums_by_k)
        improved = True
        
        while improved and not is_done():
            improved = False
            n = len(A)
            
            # Try adding elements not in A
            for candidate in range(1, 257):
                if len(A) >= max_size:
                    break
                if candidate in A:
                    continue
                success, new_sums = try_add_element(A, candidate, sums_by_k)
                if success:
                    A.append(candidate)
                    sums_by_k = new_sums
                    improved = True
                    if is_done():
                        break
            
            if is_done():
                break
            
            # Try swapping: remove one element, add two
            # This is expensive, so we only do it if we are stuck and have time.
            # The bitmask check makes individual steps fast, so we can try more swaps.
            if len(A) < max_size:
                # We need to be careful with the order of A to make removal efficient?
                # Removal requires recomputing sums from scratch O(N^2).
                # With bitmasks, recompute is fast.
                for i in range(len(A)):
                    if is_done():
                        break
                    removed = A[i]
                    A_temp = A[:i] + A[i+1:]
                    sums_temp = compute_sums_by_k(A_temp)
                    
                    # Try adding two elements
                    found_swap = False
                    for c1 in range(1, 257):
                        if is_done():
                            break
                        if c1 in A_temp:
                            continue
                        success1, sums1 = try_add_element(A_temp, c1, sums_temp)
                        if not success1:
                            continue
                        
                        for c2 in range(c1 + 1, 257):
                            if is_done():
                                break
                            if c2 in A_temp or c2 == c1:
                                continue
                            A_temp2 = A_temp + [c1]
                            success2, sums2 = try_add_element(A_temp2, c2, sums1)
                            if success2:
                                A = A_temp2 + [c2]
                                sums_by_k = sums2
                                improved = True
                                found_swap = True
                                break
                        if found_swap:
                            break
                    if found_swap:
                        break
        
        return A, sums_by_k
    
    # Strategy 1: Greedy from small to large
    best_A = []
    best_sums = None
    
    A1, sums1 = greedy_build(range(1, 257))
    if len(A1) > len(best_A):
        best_A = A1
        best_sums = sums1
    
    if is_done():
        return [int(x) for x in best_A] if best_A else [1, 2, 4, 8, 16, 32, 64, 128, 256]
    
    # Strategy 2: Greedy from large to small
    A2, sums2 = greedy_build(range(256, 0, -1))
    if len(A2) > len(best_A):
        best_A = A2
        best_sums = sums2
    
    if is_done():
        return [int(x) for x in best_A] if best_A else [1, 2, 4, 8, 16, 32, 64, 128, 256]
    
    # Strategy 3: Local search improvement on best found so far
    if best_A:
        best_A, best_sums = local_search_improve(best_A, best_sums)
    
    if is_done():
        return [int(x) for x in best_A] if best_A else [1, 2, 4, 8, 16, 32, 64, 128, 256]
    
    # Strategy 4: Random restarts with greedy + local search
    random.seed(12345)
    
    # Increase restarts since each step is faster
    for restart in range(2000):
        if is_done():
            break
        if len(best_A) >= 60:
            break
        
        # Create a random order
        candidates = list(range(1, 257))
        random.shuffle(candidates)
        
        A_rand, sums_rand = greedy_build(candidates)
        
        # Local search on this result
        A_rand, sums_rand = local_search_improve(A_rand, sums_rand)
        
        if len(A_rand) > len(best_A):
            best_A = A_rand
            best_sums = sums_rand
    
    # Strategy 5: Try specific structured sets
    structured_sets = [
        [1, 2, 4, 8, 16, 32, 64, 128, 256],
        [3, 6, 9, 12, 15, 18, 21, 24, 27, 30, 33, 36, 39, 42, 45, 48, 51, 54, 57, 60,
         63, 66, 69, 72, 75, 78, 81, 84, 87, 90, 93, 96, 99, 102, 105, 108, 111, 114,
         117, 120, 123, 126, 129, 132, 135, 138, 141, 144, 147, 150, 153, 156, 159, 162,
         165, 168, 171, 174, 177, 180, 183, 186, 189, 192, 195, 198, 201, 204, 207, 210,
         213, 216, 219, 222, 225, 228, 231, 234, 237, 240, 243, 246, 249, 252, 255],
        [1, 3, 7, 15, 31, 63, 127, 255],
        [1, 3, 9, 27, 81, 243],
    ]
    
    for sset in structured_sets:
        if is_done():
            break
        sset = [x for x in sset if 1 <= x <= 256]
        sset = list(dict.fromkeys(sset))
        
        if sset:
            sums_struct = compute_sums_by_k(sset)
            if is_valid_sums(sums_struct):
                A_struct, sums_struct = local_search_improve(sset, sums_struct)
                if len(A_struct) > len(best_A):
                    best_A = A_struct
                    best_sums = sums_struct
    
    if not best_A:
        best_A = [1, 2, 4, 8, 16, 32, 64, 128, 256]
    
    # Final validation
    sums_final = compute_sums_by_k(best_A)
    if not is_valid_sums(sums_final):
        # Fallback to powers of 2
        best_A = [1, 2, 4, 8, 16, 32, 64, 128, 256]
    
    # Ensure all are Python ints in a list
    return [int(x) for x in best_A]
