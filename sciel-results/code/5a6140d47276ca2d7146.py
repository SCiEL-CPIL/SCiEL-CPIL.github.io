import numpy as np

def get_strassen_2x2():
    # Returns U, V, W for 2x2x2 Strassen
    # U: (4, 7), V: (4, 7), W: (4, 7)
    # Indices: U[i*2+j], V[i*2+j], W[i*2+j] ? 
    # Convention: U[i*m+j], V[j*p+k], W[k*n+i]
    # For 2x2x2: n=2, m=2, p=2.
    # U idx: i*2+j. V idx: j*2+k. W idx: k*2+i.
    
    U = np.zeros((4, 7))
    V = np.zeros((4, 7))
    W = np.zeros((4, 7))
    
    # M1 = (A00+A11)(B00+B11)
    # A00: U[0], A11: U[3]
    # B00: V[0], B11: V[3]
    # C00: W[0], C01: W[1], C10: W[2], C11: W[3]
    
    # Col 0: M1
    U[0, 0] = 1; U[3, 0] = 1
    V[0, 0] = 1; V[3, 0] = 1
    W[0, 0] = 1; W[1, 0] = 0; W[2, 0] = 0; W[3, 0] = 1 # C00 += M1, C11 += M1
    
    # Col 1: M2 = (A10+A11)B00
    U[2, 1] = 1; U[3, 1] = 1
    V[0, 1] = 1
    W[2, 1] = 1; W[3, 1] = 1 # C10 += M2, C11 += M2
    
    # Col 2: M3 = A00(B10-B11)
    U[0, 2] = 1
    V[2, 2] = 1; V[3, 2] = -1
    W[1, 2] = 1; W[3, 2] = 1 # C01 += M3, C11 += M3
    
    # Col 3: M4 = A11(B01-B00)
    U[3, 3] = 1
    V[1, 3] = 1; V[0, 3] = -1
    W[0, 3] = 1; W[2, 3] = 1 # C00 += M4, C10 += M4
    
    # Col 4: M5 = (A00+A01)B11
    U[0, 4] = 1; U[1, 4] = 1
    V[3, 4] = 1
    W[0, 4] = -1; W[1, 4] = 1 # C00 -= M5, C01 += M5
    
    # Col 5: M6 = (A10-A00)(B00+B10)
    U[2, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[2, 5] = 1
    W[3, 5] = 1 # C11 += M6
    
    # Col 6: M7 = (A01-A11)(B11+B01)
    U[1, 6] = 1; U[3, 6] = -1
    V[3, 6] = 1; V[1, 6] = 1
    W[0, 6] = 1; W[3, 6] = -1 # C00 += M7, C11 -= M7
    
    return U, V, W
