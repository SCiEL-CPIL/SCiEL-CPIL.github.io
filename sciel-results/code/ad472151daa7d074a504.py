import random
import time
from itertools import combinations

def construct():
    start_time = time.time()
    time_limit = 55.0
    
    def is_valid_set(S):
        S_list = list(S)
        n = len(S_list)
        # Check all x in S
        for i in range(n):
            x = S_list[i]
            # Check sums of 3 distinct others
            # To speed up, we can just check if any sum is divisible by x
            # Since n is small (~48), O(n^4) is ~ 48^4 = 5M ops. 
            # 5M ops * 100 iterations = 500M ops. Might be too slow in Python.
            # We need a faster check.
            
            # Precompute sums? 
            # Let's use the incremental check from the seed but wrapped in a function.
