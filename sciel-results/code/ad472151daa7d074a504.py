    def greedy_complete(S):
        """
        Takes a valid set S and tries to add elements from 1..192 not in S.
        Returns the maximal valid superset of S found by greedy.
        """
        S_set = set(S)
        candidates = [x for x in range(1, 193) if x not in S_set]
        random.shuffle(candidates)
        
        for x in candidates:
            # Check if x can be added to S_set
            # 1. x does not divide sum of any 3 in S_set
            if len(S_set) >= 3:
                valid = True
                # Optimization: If x is large, sums are less likely to be divisible?
                # Just check all triples.
                S_list = list(S_set)
                for t in combinations(S_list, 3):
                    if sum(t) % x == 0:
                        valid = False
                        break
                if not valid:
                    continue
            
            # 2. No a in S_set divides sum of 3 in S_set U {x} excluding a
            # This means for each a in S_set, x + s1 + s2 must not be divisible by a
            # for any distinct s1, s2 in S_set \ {a}.
            valid = True
            for a in S_set:
                others = [s for s in S_set if s != a]
                if len(others) >= 2:
                    for s1, s2 in combinations(others, 2):
                        if (x + s1 + s2) % a == 0:
                            valid = False
                            break
                if not valid:
                    break
            
            if valid:
                S_set.add(x)
                
        return S_set

    best_set = []
    
    # Initial greedy
    S0 = set()
    for x in range(192, 0, -1):
        # Simple check for initial build
        # Reuse logic from seed for speed
        S_list = list(S0)
        if len(S_list) >= 3:
             ok = True
             for t in combinations(S_list, 3):
                 if sum(t) % x == 0:
                     ok = False
                     break
             if not ok: continue
             
        ok = True
        for a in S_list:
             others = [s for s in S_list if s != a]
             if len(others) >= 2:
                 for s1, s2 in combinations(others, 2):
                     if (x + s1 + s2) % a == 0:
                         ok = False
                         break
             if not ok: break
             
        if ok:
            S0.add(x)
            
    best_set = list(S0)
    
    # ILS Loop
    while time.time() - start_time < time_limit:
        # Perturb
        S_curr = set(best_set)
        # Remove k random elements
        k = random.randint(1, 3)
        to_remove = random.sample(list(S_curr), min(k, len(S_curr)))
        for x in to_remove:
            S_curr.remove(x)
            
        # Re-greedy
        S_new = greedy_complete(S_curr)
        
        if len(S_new) > len(best_set):
            best_set = list(S_new)
            if len(best_set) == 48:
                break

    return best_set
