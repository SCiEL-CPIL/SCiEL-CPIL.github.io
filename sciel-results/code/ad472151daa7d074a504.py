        # For ILS, we need to check validity of a set generated by Greedy.
        # The Greedy itself ensures validity. So we only need to check if a *perturbed* set is valid?
        # No, if we remove elements, the set is still valid (removing elements cannot create a new conflict, it only removes potential summands).
        # So if S is valid, S \ {u} is valid.
        # Then we run Greedy to add more. The Greedy ensures the final set is valid.
        # So we don't need a full `is_valid_set` if we rely on Greedy for reconstruction.
        
