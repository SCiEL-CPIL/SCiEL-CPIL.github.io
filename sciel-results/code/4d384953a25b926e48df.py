import numpy as np
from scipy.optimize import minimize, differential_evolution

N = 12
SQRT3 = np.sqrt(3)

# EVOLVE-BLOCK-START
def _hex_vertices(cx, cy, angle_deg, side=1.0):
    """Return the 6 vertices of a regular hexagon with center (cx,cy), rotation angle_deg, side length 1."""
    angles = np.radians(angle_deg + np.arange(6) * 60.0)
    return np.column_stack([
        cx + side * np.cos(angles),
        cy + side * np.sin(angles)
    ])

def _required_side(vertices, outer_angle_deg):
    """
    Given a set of vertices (Nx2) and the orientation of the outer hexagon (angle_deg),
    compute the minimal side length S of a regular hexagon centered at origin, rotated by outer_angle_deg,
    that contains all vertices.
    """
    # The outer hexagon has 6 sides. Each side is defined by a normal direction.
    # For a regular hexagon with side S and center at origin, rotated by angle theta:
    # The distance from center to each side (inradius) is S * sqrt(3) / 2.
    # The vertices of the outer hexagon are at distance S from center (circumradius).
    # Wait: for a regular hexagon, circumradius = inradius * 2/sqrt(3)? No.
    # Actually: inradius r = S * sqrt(3)/2, circumradius R = S.
    # The hexagon is the intersection of 6 half-planes: n_k . x <= r, where n_k are unit normals to the sides.
    # The normals are at angles theta + 30 + k*60 degrees.
    
    theta = np.radians(outer_angle_deg)
    # Normals to the sides
    normal_angles = theta + np.pi/6 + np.arange(6) * np.pi/3
    normals = np.column_stack([np.cos(normal_angles), np.sin(normal_angles)])
    
    # Project all vertices onto each normal
    # vertices: (N, 2), normals: (6, 2)
    # We need max over vertices for each normal
    projections = vertices @ normals.T  # (N, 6)
    max_proj = np.max(projections, axis=0)  # (6,)
    
    # The required inradius for each side is max_proj[k]
    # inradius r = S * sqrt(3) / 2 => S = 2 * r / sqrt(3)
    max_r = np.max(max_proj)
    S = 2.0 * max_r / SQRT3
    return S

def _cluster_centers():
    """
    Generate the 12 centers for the honeycomb cluster.
    One central hexagon at (0,0).
    Ring 1: 6 hexagons at distance sqrt(3) in directions 0, 60, ..., 300.
    Ring 2: 5 hexagons at distance 2*sqrt(3) in directions 0, 90, 180, 270, 360 (but 360=0 is already there, so we pick 5 distinct ones).
    Actually, let's be more careful. The standard honeycomb has:
    Center: (0,0)
    Ring 1 (6): at (sqrt(3)*cos(60*k), sqrt(3)*sin(60*k)) for k=0..5
    Ring 2 (12): at (2*sqrt(3)*cos(60*k), 2*sqrt(3)*sin(60*k)) and (sqrt(3)*cos(30+60*k), sqrt(3)*sin(30+60*k)) * 2? 
    Let's use a simpler construction: take a 3x3 block of hexagons minus the 5 corners? 
    A 3x3 block has 9 hexagons. Not enough.
    
    Let's use the following set of 12 positions in a honeycomb lattice with spacing sqrt(3):
    Positions in axial coordinates (q, r):
    (0,0)
    (1,0), (1,-1), (0,-1), (-1,0), (-1,1), (0,1)  -> 6 in ring 1
    (2,0), (2,-1), (1,-2), (-1,2), (-2,1), (-2,0) -> 6 in ring 2, but we only need 5 more to make 12.
    
    Let's just take the 12 closest hexagons in the honeycomb lattice to the origin, including the origin.
    The hexagonal lattice can be generated by vectors v1 = (sqrt(3), 0) and v2 = (sqrt(3)/2, 3/2).
    Points are i*v1 + j*v2.
    Let's generate a list of (i,j) and compute distances, sort, and take the first 12.
    """
    v1 = np.array([SQRT3, 0.0])
    v2 = np.array([SQRT3 / 2.0, 1.5])
    
    candidates = []
    for i in range(-3, 4):
        for j in range(-3, 4):
            pos = i * v1 + j * v2
            dist = np.linalg.norm(pos)
            candidates.append((dist, i, j, pos))
    
    candidates.sort(key=lambda x: x[0])
    # Take the first 12
    centers = [c[3] for c in candidates[:12]]
    return np.array(centers)

def _objective(params):
    """
    params: [alpha, beta]
    alpha: rotation of the inner cluster (and each hexagon) in degrees
    beta: rotation of the outer hexagon in degrees
    """
    alpha = params[0]
    beta = params[1]
    
    # Get cluster centers
    centers = _cluster_centers()
    
    # Rotate centers by alpha
    alpha_rad = np.radians(alpha)
    cos_a, sin_a = np.cos(alpha_rad), np.sin(alpha_rad)
    rot = np.array([[cos_a, -sin_a], [sin_a, cos_a]])
    rotated_centers = centers @ rot.T
    
    # For each hexagon, generate vertices
    all_vertices = []
    for cx, cy in rotated_centers:
        verts = _hex_vertices(cx, cy, alpha)
        all_vertices.append(verts)
    
    all_vertices = np.vstack(all_vertices)
    
    # Compute required outer side length
    S = _required_side(all_vertices, beta)
    
    return S

def construct():
    # Pre-compute cluster centers
    _cluster_centers()  # Just to ensure it's computed
    
    # We want to minimize _objective over alpha and beta.
    # Due to symmetry:
    # The inner cluster has 6-fold symmetry? The set of 12 closest hexagons to origin in a honeycomb lattice:
    # Let's check the symmetry. The 12 closest are:
    # (0,0)
    # 6 at distance sqrt(3)
    # 5 at distance 2*sqrt(3)? Or 6 at distance 2*sqrt(3) but one is missing?
    # Actually, the 12 closest are: 1 + 6 + 5 = 12. The 5th ring-2 hexagon breaks the 6-fold symmetry.
    # So the cluster only has 3-fold symmetry (120 degrees).
    # So alpha in [0, 120), beta in [0, 60).
    
    # Use differential evolution for robustness, then refine with Nelder-Mead.
    
    bounds = [(0, 120), (0, 60)]
    
    # First, do a coarse grid search to find a good starting point
    best_alpha = 0
    best_beta = 0
    best_val = float('inf')
    
    for a in np.linspace(0, 120, 25, endpoint=False):
        for b in np.linspace(0, 60, 25, endpoint=False):
            val = _objective([a, b])
            if val < best_val:
                best_val = val
                best_alpha = a
                best_beta = b
    
    # Refine with differential_evolution
    result_de = differential_evolution(
        _objective,
        bounds,
        maxiter=100,
        tol=1e-8,
        seed=42,
        polish=False
    )
    
    # Refine with Nelder-Mead
    result_nm = minimize(
        _objective,
        result_de.x,
        method='Nelder-Mead',
        options={'xatol': 1e-10, 'fatol': 1e-10, 'maxiter': 10000, 'maxfev': 10000}
    )
    
    best_params = result_nm.x
    best_S = result_nm.fun
    
    # Also try starting from grid best
    result_nm2 = minimize(
        _objective,
        [best_alpha, best_beta],
        method='Nelder-Mead',
        options={'xatol': 1e-10, 'fatol': 1e-10, 'maxiter': 10000, 'maxfev': 10000}
    )
    
    if result_nm2.fun < best_S:
        best_params = result_nm2.x
        best_S = result_nm2.fun
    
    alpha, beta = best_params
    
    # Now construct the inner hexagons
    centers = _cluster_centers()
    alpha_rad = np.radians(alpha)
    cos_a, sin_a = np.cos(alpha_rad), np.sin(alpha_rad)
    rot = np.array([[cos_a, -sin_a], [sin_a, cos_a]])
    rotated_centers = centers @ rot.T
    
    inner = []
    for cx, cy in rotated_centers:
        inner.append([float(cx), float(cy), float(alpha)])
    
    return inner, (0.0, 0.0), float(best_S), float(beta)
