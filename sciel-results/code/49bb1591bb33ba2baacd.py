import time
import numpy as np
from scipy.spatial import ConvexHull

N = 130
_EPS = 1e-12

def _initial_fib():
    """Generate initial points using Fibonacci spiral."""
    i = np.arange(N) + 0.5
    z = 1.0 - 2.0 * i / N
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(np.clip(1.0 - z * z, 0.0, None))
    return np.column_stack([r * np.cos(phi), r * np.sin(phi), z])

def _get_hull_data(pts):
    """
    Compute convex hull and extract facet data.
    Returns:
        radii: (F,) array of covering radii for each facet
        normals: (F, 3) array of outward normals for each facet
        faces: (F, 3) array of vertex indices for each facet
    """
    try:
        hull = ConvexHull(pts)
        faces = hull.simplices
        A = pts[faces[:, 0]]
        B = pts[faces[:, 1]]
        C = pts[faces[:, 2]]
        
        AB = B - A
        AC = C - A
        cross = np.cross(AB, AC)
        area = 0.5 * np.linalg.norm(cross, axis=1)
        
        valid = area > _EPS
        if not np.any(valid):
            return np.array([np.pi]), np.array([[0,0,0]]), faces[:1]

        normals = cross[valid]
        norms = np.linalg.norm(normals, axis=1, keepdims=True)
        
        # Ensure normals point outward (away from origin)
        centroids = (A[valid] + B[valid] + C[valid]) / 3.0
        signs = np.sum(normals * centroids, axis=1, keepdims=True)
        normals = normals * np.sign(signs)
        normals = normals / (norms + _EPS)
        
        # Calculate covering radius for each facet
        # The furthest point on the sphere from the facet plane is the pole.
        # Distance from origin to plane is |n . A| = |n . B| = |n . C|
        # The angular radius is arccos(n . A)
        cos_theta = np.sum(normals * A[valid], axis=1)
        cos_theta = np.clip(cos_theta, -1.0, 1.0)
        radii = np.arccos(cos_theta)
        
        return radii, normals, faces[valid]
    except Exception:
        return np.array([np.pi]), np.array([[0,0,0]]), np.array([[-1, -1, -1]])

def _covering_radius(pts):
    """Compute the exact covering radius."""
    radii, _, _ = _get_hull_data(pts)
    return np.max(radii)

def _simulate_annealing(pts, deadline, rng):
    """
    Perform Simulated Annealing to minimize the covering radius.
    Moves are generated by:
    1. Identifying the worst facet (largest radius).
    2. Moving one of its vertices towards the pole of that facet.
    3. Occasionally applying random perturbations to escape local minima.
    """
    best_pts = pts.copy()
    best_r = _covering_radius(pts)
    
    current_r = best_r
    current_pts = pts.copy()
    
    # Initial temperature
    T = 0.05
    T_min = 0.001
    cooling_rate = 0.999
    
    step_size = 0.05
    no_improve_count = 0
    
    while time.time() < deadline:
        if T < T_min:
            break
            
        # Get hull data for current state
        radii, normals, faces = _get_hull_data(current_pts)
        
        if len(radii) == 0:
            break
            
        # Identify worst facet
        worst_idx = np.argmax(radii)
        worst_r = radii[worst_idx]
        
        # Generate candidate moves
        candidates = []
        
        # Move 1: Move a vertex of the worst facet towards the pole
        pole = normals[worst_idx]
        v_indices = faces[worst_idx]
        
        # Pick a random vertex from the worst facet to move
        v_idx = v_indices[rng.integers(0, 3)]
        
        # Direction: towards the pole
        dir_vec = pole - current_pts[v_idx]
        dir_norm = np.linalg.norm(dir_vec)
        if dir_norm > _EPS:
            dir_vec /= dir_norm
        
        # Apply move
        new_pts = current_pts.copy()
        new_pts[v_idx] += step_size * dir_vec
        new_pts[v_idx] /= (np.linalg.norm(new_pts[v_idx]) + _EPS)
        
        candidates.append(new_pts)
        
        # Move 2: Random perturbation (to escape local minima)
        if rng.random() < 0.1:
            new_pts_rand = current_pts.copy()
            perturbation = rng.standard_normal((N, 3)) * 0.1
            new_pts_rand += perturbation
            new_pts_rand /= np.linalg.norm(new_pts_rand, axis=1, keepdims=True)
            candidates.append(new_pts_rand)
        
        # Evaluate candidates
        accepted = False
        for cand in candidates:
            cand_r = _covering_radius(cand)
            
            # Accept if better, or with probability exp(-(delta)/T) if worse
            if cand_r < current_r:
                current_pts = cand
                current_r = cand_r
                accepted = True
                
                if current_r < best_r - 1e-9:
                    best_r = current_r
                    best_pts = current_pts.copy()
                    no_improve_count = 0
                else:
                    no_improve_count += 1
            else:
                delta = cand_r - current_r
                prob = np.exp(-delta / T)
                if rng.random() < prob:
                    current_pts = cand
                    current_r = cand_r
                    accepted = True
        
        if not accepted:
            no_improve_count += 1
            # Reduce step size if stuck
            if no_improve_count % 10 == 0:
                step_size *= 0.95
                if step_size < 0.001:
                    step_size = 0.05 # Reset occasionally to explore larger moves
        
        # Cool down
        T *= cooling_rate
        
        # If we've been stuck for a long time, restart from best with perturbation
        if no_improve_count > 50:
            current_pts = best_pts + rng.standard_normal((N, 3)) * 0.1
            current_pts /= np.linalg.norm(current_pts, axis=1, keepdims=True)
            current_r = _covering_radius(current_pts)
            T = 0.05
            step_size = 0.05
            no_improve_count = 0

    return best_pts, best_r

def construct():
    deadline = time.time() + 140.0  # Safety margin (150s limit)
    rng = np.random.default_rng(42)
    
    # Initial configuration
    pts = _initial_fib()
    best_pts = pts.copy()
    best_r = _covering_radius(pts)
    
    # Multiple restarts with Simulated Annealing
    n_restarts = 3
    time_per_restart = (deadline - 10.0) / n_restarts
    
    for restart in range(n_restarts):
        if time.time() > deadline - 10.0:
            break
        
        if restart == 0:
            current_pts = pts
        else:
            # Perturb best found so far for new restart
            current_pts = best_pts + rng.standard_normal((N, 3)) * 0.2
            current_pts /= np.linalg.norm(current_pts, axis=1, keepdims=True)
        
        # Run Simulated Annealing
        new_pts, new_r = _simulate_annealing(current_pts, deadline - 10.0 - (n_restarts - restart - 1) * time_per_restart, rng)
        
        if new_r < best_r:
            best_r = new_r
            best_pts = new_pts
    
    # Final polish: Local hill climbing with small steps
    if time.time() < deadline - 5.0:
        current_pts = best_pts.copy()
        current_r = best_r
        step_size = 0.01
        
        while time.time() < deadline - 2.0:
            radii, normals, faces = _get_hull_data(current_pts)
            if len(radii) == 0:
                break
            
            worst_idx = np.argmax(radii)
            pole = normals[worst_idx]
            v_indices = faces[worst_idx]
            v_idx = v_indices[0] # Try first vertex
            
            dir_vec = pole - current_pts[v_idx]
            dir_norm = np.linalg.norm(dir_vec)
            if dir_norm > _EPS:
                dir_vec /= dir_norm
            
            new_pts = current_pts.copy()
            new_pts[v_idx] += step_size * dir_vec
            new_pts[v_idx] /= (np.linalg.norm(new_pts[v_idx]) + _EPS)
            
            new_r = _covering_radius(new_pts)
            if new_r < current_r - 1e-9:
                current_pts = new_pts
                current_r = new_r
                if current_r < best_r - 1e-9:
                    best_r = current_r
                    best_pts = current_pts.copy()
            else:
                step_size *= 0.9
                if step_size < 1e-5:
                    break
    
    # Final normalization and validity check
    best_pts = np.array(best_pts, dtype=float)
    norms = np.linalg.norm(best_pts, axis=1, keepdims=True)
    best_pts /= (norms + _EPS)
    
    if not np.all(np.isfinite(best_pts)) or best_pts.shape != (N, 3):
        return _initial_fib()
        
    return best_pts
