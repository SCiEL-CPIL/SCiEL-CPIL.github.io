def _fallback_construct():
    """
    Fallback to the cyclic construction if the hardcoded list fails validation.
    """
    base_blocks_11 = [
        (0, 1, 3, 4, 5),
        (0, 1, 2, 6, 7),
        (0, 2, 3, 7, 8),
        (0, 2, 4, 8, 9),
        (0, 3, 5, 9, 10),
        (0, 4, 6, 10, 1)
    ]
    
    blocks_11 = []
    for b in base_blocks_11:
        for i in range(11):
            shifted = tuple((x + i) % 11 for x in b)
            blocks_11.append(shifted)
            
    full_blocks = []
    all_points = set(range(12))
    
    for b in blocks_11:
        block_with_11 = list(b) + [11]
        full_blocks.append(block_with_11)
        
    for b in full_blocks:
        b_set = set(b)
        comp = tuple(sorted(all_points - b_set))
        full_blocks.append(list(comp))
        
    return full_blocks

