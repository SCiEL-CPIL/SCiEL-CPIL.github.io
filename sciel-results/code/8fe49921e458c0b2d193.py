"""
LJ38 cluster global minimum search.

Approach:
1. Identify the core 19 atoms of the FCC truncated-octahedron (center + 12 nearest + 6 next-nearest).
2. Identify the outer 24 candidate atoms at the next shell distance.
3. The global minimum is a symmetric truncated octahedron, which corresponds to a specific subset of 19 atoms from the 24 outer candidates.
4. Instead of random sampling, we perform an exhaustive search over the discrete topological space of these subsets, reduced by cubic symmetry (Oh group).
5. For each unique topology, we perform a rapid 1D radial scale optimization followed by a strict L-BFGS polish.
6. We also include an icosahedral starting point as a fallback/comparison, though the FCC topology is expected to be superior.
7. The best energy configuration is returned.
"""
import time
import numpy as np
from scipy.optimize import minimize
from itertools import combinations

N = 38

def _lj_energy_and_grad(pos):
    """Total LJ energy and gradient for positions pos (N,3)."""
    n = len(pos)
    diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    r2 = np.sum(diff ** 2, axis=2)
    np.fill_diagonal(r2, 1.0)
    r6 = r2 ** 3
    r12 = r6 ** 2

    pair_energy = 4.0 * (1.0 / r12 - 1.0 / r6)
    np.fill_diagonal(pair_energy, 0.0)
    energy = 0.5 * np.sum(pair_energy)

    r8 = r2 ** 4
    r14 = r2 ** 7
    coeff = 4.0 * (6.0 / r8 - 12.0 / r14)
    np.fill_diagonal(coeff, 0.0)
    row_sum = np.sum(coeff, axis=1, keepdims=True)
    grad = row_sum * pos - coeff @ pos

    return energy, grad

def _generate_fcc_core_and_outer():
    """
    Generate the 19 core FCC atoms and 24 outer candidate FCC atoms.
    Core: 1 (0,0,0) + 12 (110 type) + 6 (200 type).
    Outer: 24 (211 type).
    """
    core = []
    # Center
    core.append([0.0, 0.0, 0.0])
    
    # Simpler: generate all FCC points up to dist^2 = 6
    pts = []
    max_c = 3
    for i in range(-max_c, max_c + 1):
        for j in range(-max_c, max_c + 1):
            for k in range(-max_c, max_c + 1):
                if (i + j + k) % 2 == 0:
                    d2 = i*i + j*j + k*k
                    if d2 <= 6:
                        pts.append([float(i), float(j), float(k), d2])
    
    pts = np.array(pts)
    
    # Separate by distance
    core_pts = pts[pts[:, 3] <= 4]
    outer_pts = pts[pts[:, 3] == 6]
    
    # core_pts should have 1 + 12 + 6 = 19 atoms
    # outer_pts should have 24 atoms
    return core_pts[:, :3], outer_pts[:, :3]

def _get_oh_symmetry_ops():
    """
    Generate the 48 rotation matrices of the Oh point group.
    These are all 3x3 orthogonal matrices with determinant 1 that permute/flip axes.
    """
    ops = []
    # 24 proper rotations (O group)
    # Generated by permutations of axes and sign flips with det=1
    for perm in [(0,1,2), (0,2,1), (1,0,2), (1,2,0), (2,0,1), (2,1,0)]:
        for s1 in [1, -1]:
            for s2 in [1, -1]:
                for s3 in [1, -1]:
                    if s1 * s2 * s3 != 1: # det must be 1
                        continue
                    mat = np.zeros((3,3))
                    mat[0, perm[0]] = s1
                    mat[1, perm[1]] = s2
                    mat[2, perm[2]] = s3
                    ops.append(mat)
    
    # Add 24 improper rotations (inversion * proper)
    for mat in ops:
        ops.append(-mat)
        
    return np.array(ops)

def _canonical_subset(subset_indices, outer_pts, ops):
    """
    Apply all symmetry operations to the subset of outer points and return the canonical index tuple.
    We map the rotated points back to the original outer_pts indices.
    """
    # Create a lookup from rounded coords to original index
    # Since outer_pts are integer coordinates (scaled by 1), we can use rounded tuples
    coord_to_idx = {}
    for i, p in enumerate(outer_pts):
        key = (int(round(p[0])), int(round(p[1])), int(round(p[2])))
        coord_to_idx[key] = i
        
    min_canonical = None
    for op in ops:
        # Rotate the selected points
        rotated_pts = outer_pts[list(subset_indices)] @ op.T
        # Map back to indices
        new_indices = []
        valid = True
        for p in rotated_pts:
            key = (int(round(p[0])), int(round(p[1])), int(round(p[2])))
            if key in coord_to_idx:
                new_indices.append(coord_to_idx[key])
            else:
                valid = False
                break
        if not valid:
            continue
            
        new_indices.sort()
        if min_canonical is None or tuple(new_indices) < min_canonical:
            min_canonical = tuple(new_indices)
            
    return min_canonical

def _make_icosahedral_structure():
    """
    Icosahedral starting geometry.
    """
    phi = (1.0 + np.sqrt(5.0)) / 2.0
    ico = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [phi, 0, -1], [-phi, 0, 1], [-phi, 0, -1],
    ], dtype=np.float64)
    norms = np.linalg.norm(ico, axis=1, keepdims=True)
    ico /= norms

    layers = [1.0, 1.7, 2.4]
    pts = [np.zeros(3)]
    for r in layers:
        pts.extend(ico * r)
    pts.append(np.array([0.25, 0.25, 0.25]))
    pts = np.array(pts[:N], dtype=np.float64)
    pts -= np.mean(pts, axis=0)
    
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    r2 = np.sum(diff ** 2, axis=2)
    np.fill_diagonal(r2, np.inf)
    nn = np.sqrt(np.min(r2, axis=1))
    avg_nn = np.mean(nn)
    if avg_nn > 1e-12:
        scale = (2.0 ** (1.0 / 6.0)) / avg_nn
        pts *= scale
    return pts

def _relax(pos, max_iter=500, gtol=1e-10):
    """L-BFGS-B local relaxation."""
    def obj_grad(x):
        p = x.reshape(-1, 3)
        e, g = _lj_energy_and_grad(p)
        return e, g.ravel()

    res = minimize(
        obj_grad,
        pos.ravel(),
        jac=True,
        method="L-BFGS-B",
        options={"maxiter": max_iter, "gtol": gtol, "ftol": 1e-14},
    )
    p_out = res.x.reshape(-1, 3)
    e_out, _ = _lj_energy_and_grad(p_out)
    return p_out, e_out

def _optimize_scale(pos):
    """
    Perform a 1D optimization of the scale factor for a given topology.
    This is fast and ensures the structure is at the correct bond length before L-BFGS.
    """
    def energy_scaled(s):
        p = pos * s
        e, _ = _lj_energy_and_grad(p)
        return e

    # Initial scale estimate: average nearest neighbor distance should be 2^(1/6)
    diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    r2 = np.sum(diff ** 2, axis=2)
    np.fill_diagonal(r2, np.inf)
    nn = np.sqrt(np.min(r2, axis=1))
    avg_nn = np.mean(nn)
    s0 = (2.0 ** (1.0 / 6.0)) / avg_nn
    
    # Simple golden section or minimize on 1D
    res = minimize(energy_scaled, s0, method='Nelder-Mead', options={'xatol': 1e-8, 'fatol': 1e-10, 'maxiter': 100})
    best_scale = res.x[0]
    best_pos = pos * best_scale
    best_e, _ = _lj_energy_and_grad(best_pos)
    return best_pos, best_e

def _ensure_min_sep(pos, min_sep=0.5):
    diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    r2 = np.sum(diff ** 2, axis=2)
    np.fill_diagonal(r2, np.inf)
    min_d = np.sqrt(np.min(r2))
    if min_d < min_sep:
        scale = min_sep / min_d * 1.01
        pos = pos * scale
    return pos

def construct():
    t0 = time.time()
    deadline = t0 + 140.0  # Safety margin

    core, outer = _generate_fcc_core_and_outer()
    
    # 1. Generate unique topologies
    # We need to choose 19 atoms from the 24 outer sites.
    # This is equivalent to choosing 5 atoms to EXCLUDE from the 24.
    # C(24, 5) = 42504.
    # We will generate all combinations of 5 indices to exclude, then find the canonical representative of the remaining 19.
    
    ops = _get_oh_symmetry_ops()
    
    unique_topologies = set()
    # For speed, we iterate over the 5 excluded indices
    for exclude in combinations(range(24), 5):
        exclude_set = set(exclude)
        # The selected indices are the complement
        selected = tuple(i for i in range(24) if i not in exclude_set)
        
        # Find canonical representative
        canonical = _canonical_subset(selected, outer, ops)
        if canonical:
            unique_topologies.add(canonical)
            
    # 2. Optimize each unique topology
    best_pos = None
    best_energy = np.inf
    
    # Also add icosahedral start
    starts = []
    try:
        ico = _make_icosahedral_structure()
        starts.append(ico)
    except Exception:
        pass
        
    # Process unique FCC topologies
    for topo in unique_topologies:
        if time.time() > deadline - 30.0:
            break
            
        # Construct positions
        pos = np.vstack([core, outer[list(topo)]])
        pos -= np.mean(pos, axis=0)
        
        try:
            # Rapid scale optimization
            pos_scaled, e_scaled = _optimize_scale(pos)
            
            # L-BFGS polish
            p, e = _relax(pos_scaled, max_iter=200, gtol=1e-9)
            
            if e < best_energy:
                best_energy = e
                best_pos = p.copy()
        except Exception:
            continue

    # Process other starts (icosahedral)
    for start in starts:
        if time.time() > deadline - 10.0:
            break
        try:
            p, e = _relax(start, max_iter=200, gtol=1e-9)
            if e < best_energy:
                best_energy = e
                best_pos = p.copy()
        except Exception:
            continue

    # Fallback
    if best_pos is None:
        # Use the first topology or core+first 19 outer
        pos = np.vstack([core, outer[:19]])
        pos -= np.mean(pos, axis=0)
        best_pos, best_energy = _optimize_scale(pos)

    # Final high-precision polish
    if time.time() < deadline - 5.0:
        try:
            p, e = _relax(best_pos, max_iter=1000, gtol=1e-12)
            if e < best_energy:
                best_energy = e
                best_pos = p
        except Exception:
            pass

    best_pos = _ensure_min_sep(best_pos)
    return best_pos

if __name__ == "__main__":
    # Test
    t0 = time.time()
    pos = construct()
    e, _ = _lj_energy_and_grad(pos)
    print(f"Energy: {e:.6f}, Time: {time.time()-t0:.2f}s")
