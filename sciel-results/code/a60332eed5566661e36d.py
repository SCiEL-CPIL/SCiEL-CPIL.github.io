import time
import random
import math

def _calc_score(A):
    """Compute max(|A+A|, |A*A|) for a set of distinct positive integers."""
    n = len(A)
    sumset = set()
    prodset = set()
    for i in range(n):
        ai = A[i]
        for j in range(i, n):
            aj = A[j]
            sumset.add(ai + aj)
            prodset.add(ai * aj)
    return max(len(sumset), len(prodset))

def _generate_smooth_candidates(max_val, primes, count=None):
    """Generate smooth numbers with given prime factors <= max_val."""
    vals = set([1])
    current_vals = [1]
    for p in primes:
        new_vals = []
        for v in current_vals:
            x = v
            while x * p <= max_val:
                x *= p
                new_vals.append(x)
                vals.add(x)
        current_vals.extend(new_vals)
    
    # Also include the base values multiplied by combinations of previous primes
    # The above loop is slightly inefficient for multiple primes if not careful.
    # Let's use a recursive generation or a priority queue approach for correctness and completeness.
    
    # Simpler robust approach for small max_val and small number of primes:
    # BFS / Dijkstra-like expansion
    vals = set([1])
    # We want to generate all numbers of form p1^a * p2^b * ... <= max_val
    # Let's just iterate through the pool generated by the previous method and verify?
    # Actually, the previous method `current_vals` logic was flawed for multiple primes.
    
    # Correct generation:
    vals = set()
    def gen(idx, current_val):
        if current_val > max_val:
            return
        vals.add(current_val)
        if idx < len(primes):
            p = primes[idx]
            v = current_val
            while v * p <= max_val:
                v *= p
                gen(idx, v)
            gen(idx + 1, current_val)
            
    gen(0, 1)
    return sorted(list(vals))

def _local_search_swap(A, pool, timeout=10.0):
    """
    Local search by swapping elements in A with elements in pool.
    A: list of 20 ints.
    pool: list of candidate ints.
    """
    A = sorted(A)
    A_set = set(A)
    current_score = _calc_score(A)
    best_A = list(A)
    best_score = current_score
    start_time = time.time()
    
    # Pre-filter pool to only valid candidates not in A
    # We will update this list as A changes
    
    # To make it faster, we can limit the pool size or prioritize smaller numbers
    # Since smooth numbers are dense, let's just use the provided pool.
    
    while time.time() - start_time < timeout:
        improved = False
        # Iterate through elements in A
        for i in range(len(A)):
            old_val = A[i]
            # Try swapping with candidates in pool
            # Optimization: If pool is large, this is slow. 
            # We can sort pool by some heuristic or just iterate.
            # Given max 10000, and smooth numbers are few, pool is manageable.
            
            # Find best replacement for A[i]
            best_new_val = old_val
            best_new_score = current_score
            
            for new_val in pool:
                if new_val in A_set:
                    continue
                if new_val == old_val:
                    continue
                
                # Construct new A
                # A is sorted. We remove old_val and insert new_val.
                # For score calculation, we just need the set of values.
                temp_A = A[:i] + A[i+1:] + [new_val]
                # No need to sort for _calc_score, it handles any order, 
                # but distinctness is maintained by A_set check.
                
                new_score = _calc_score(temp_A)
                
                if new_score < best_new_score:
                    best_new_score = new_score
                    best_new_val = new_val
            
            if best_new_val != old_val:
                # Perform the swap
                A[i] = best_new_val
                A.sort()
                A_set = set(A)
                current_score = best_new_score
                improved = True
                
                if current_score < best_score:
                    best_score = current_score
                    best_A = list(A)
        
        if not improved:
            break
            
    return best_A, best_score

def _simulated_annealing(A, pool, timeout=10.0):
    """SA with moves restricted to pool or small perturbations."""
    A = sorted(A)
    A_set = set(A)
    current_score = _calc_score(A)
    best_A = list(A)
    best_score = current_score
    start_time = time.time()
    n = len(A)
    
    start_temp = 50.0
    end_temp = 1.0
    max_iters = 5000
    
    for i in range(max_iters):
        if time.time() - start_time > timeout:
            break
            
        T = start_temp * (end_temp / start_temp) ** (i / max_iters)
        
        idx = random.randint(0, n - 1)
        old_val = A[idx]
        
        # Choose move type
        r = random.random()
        if r < 0.6:
            # Swap with pool
            # Pick random from pool not in A
            valid_pool = [x for x in pool if x not in A_set]
            if not valid_pool:
                continue
            new_val = random.choice(valid_pool)
        elif r < 0.8:
            # Small perturbation
            delta = random.randint(-10, 10)
            new_val = old_val + delta
            if new_val < 1 or new_val > 10000:
                continue
            if new_val in A_set:
                continue
        else:
            # Larger perturbation
            delta = random.randint(-100, 100)
            new_val = old_val + delta
            if new_val < 1 or new_val > 10000:
                continue
            if new_val in A_set:
                continue
            
        # Evaluate
        temp_A = A[:idx] + [new_val] + A[idx+1:]
        new_score = _calc_score(temp_A)
        
        delta_e = new_score - current_score
        
        if delta_e < 0 or (T > 0 and random.random() < math.exp(-delta_e / T)):
            A[idx] = new_val
            A.sort()
            A_set = set(A)
            current_score = new_score
            
            if new_score < best_score:
                best_score = new_score
                best_A = list(A)
                
    return best_A, best_score

def construct():
    start_time = time.time()
    deadline = start_time + 85.0 # Safety margin for 90s limit
    
    # 1. Generate Candidate Pools
    # 2-smooth: 2^a * 3^b
    pool_2 = _generate_smooth_candidates(10000, [2, 3])
    # 3-smooth: 2^a * 3^b * 5^c
    pool_3 = _generate_smooth_candidates(10000, [2, 3, 5])
    # 4-smooth: 2^a * 3^b * 5^c * 7^d
    pool_4 = _generate_smooth_candidates(10000, [2, 3, 5, 7])
    
    # Combine pools and add some random small integers for diversity
    # Random integers might help break ties or find better sum sets
    random.seed(42)
    random_ints = random.sample(range(1, 200), 50)
    
    candidate_pool = list(set(pool_2 + pool_3 + pool_4 + random_ints))
    candidate_pool.sort()
    
    # 2. Initial Candidates
    initial_sets = []
    
    # Smallest 20 from each pool
    if len(pool_2) >= 20: initial_sets.append(pool_2[:20])
    if len(pool_3) >= 20: initial_sets.append(pool_3[:20])
    if len(pool_4) >= 20: initial_sets.append(pool_4[:20])
    
    # Consecutive
    initial_sets.append(list(range(1, 21)))
    
    # Powers of 2
    p2 = [2**i for i in range(20)]
    if max(p2) <= 10000: initial_sets.append(p2)
    
    # Geometric 1.5
    geo = [1]
    for i in range(19):
        geo.append(int(round(geo[-1] * 1.5)))
    geo = sorted(set(x for x in geo if x <= 10000))
    if len(geo) >= 20: initial_sets.append(geo[:20])
    
    # Random from pool
    if len(candidate_pool) >= 20:
        initial_sets.append(sorted(random.sample(candidate_pool, 20)))
        
    best_A = None
    best_score = float('inf')
    
    # Evaluate initial sets
    for init_set in initial_sets:
        if time.time() > deadline - 20.0:
            break
        init_set = sorted(set(x for x in init_set if 1 <= x <= 10000))
        if len(init_set) < 20:
            continue
        score = _calc_score(init_set)
        if score < best_score:
            best_score = score
            best_A = list(init_set)
            
    if best_A is None:
        best_A = list(range(1, 21))
        best_score = _calc_score(best_A)
        
    # 3. Optimization Phase 1: Greedy Swap Local Search
    # Use the combined pool. To keep it fast, maybe limit pool size?
    # The pool of 4-smooth numbers <= 10000 is not huge (approx 100-200 numbers).
    # So swap search is feasible.
    
    time_budget_1 = min(15.0, deadline - time.time() - 15.0)
    if time_budget_1 > 1.0:
        best_A, best_score = _local_search_swap(best_A, candidate_pool, timeout=time_budget_1)
        
    # 4. Optimization Phase 2: Simulated Annealing
    # Use SA to escape local minima found by greedy search.
    time_budget_2 = min(15.0, deadline - time.time() - 10.0)
    if time_budget_2 > 1.0:
        best_A, best_score = _simulated_annealing(best_A, candidate_pool, timeout=time_budget_2)
        
    # 5. Optimization Phase 3: Fine Polish
    # Try small integer steps again, as SA might have moved away from optimal integers.
    time_budget_3 = deadline - time.time() - 2.0
    if time_budget_3 > 1.0:
        # Run a lighter version of local search with a restricted pool of neighbors
        # Or just re-run swap search with a tighter timeout?
        # Let's do a quick local search with a pool of numbers close to current A
        local_pool = set()
        for x in best_A:
            for d in range(-5, 6):
                nx = x + d
                if 1 <= nx <= 10000:
                    local_pool.add(nx)
        local_pool = list(local_pool)
        best_A, best_score = _local_search_swap(best_A, local_pool, timeout=time_budget_3)
        
    return best_A

