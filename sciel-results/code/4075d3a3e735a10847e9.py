import random

def construct(n_rows, k):
    # 1. Generate initial solution using Greedy
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new_diffs = {x - a for a in row}
            if not new_diffs & used:
                row.append(x)
                used |= new_diffs
        rows.append(row)
        
    # 2. Local Search to minimize max value
    # We will try to reduce the maximum mark by decrementing marks.
    # We repeat this process many times or until no improvement.
    
    # To be efficient, we can maintain a list of "candidates" for decrementing.
    # Or just iterate randomly.
    
    best_rows = [r[:] for r in rows]
    best_max = max(max(r) for r in rows)
    
    # We can use a time limit or iteration limit.
    # Let's try a few thousand iterations of random decrement attempts.
    
    for _ in range(10000): # Reasonable iteration count
        # Pick a random row
        r_idx = random.randint(0, n_rows - 1)
        row = rows[r_idx]
        
        # Pick a random index to try to decrement
        # We can prioritize indices with larger values
        j_idx = random.randint(1, k)
        
        old_val = row[j_idx]
        # Try to decrement by 1
        new_val = old_val - 1
        
        # Check order constraints
        if j_idx > 0 and new_val <= row[j_idx - 1]:
            continue
        if j_idx < k and new_val >= row[j_idx + 1]:
            continue
            
        # Check difference constraints
        # Remove old differences involving row[j_idx]
        # old_diffs = {old_val - row[i] for i in range(j_idx)} | {row[i] - old_val for i in range(j_idx+1, k+1)}
        # Actually, we just need to check if new differences are in `used`.
        
        # Calculate new differences
        new_diffs = set()
        for i in range(len(row)):
            if i == j_idx:
                continue
            diff = abs(new_val - row[i])
            new_diffs.add(diff)
            
        # The differences that are *removed* are those involving old_val
        # But `used` contains ALL differences from ALL rows.
        # We need to check if any `new_diff` is in `used` AND was not generated by `old_val` in this row.
        # This is tricky because `used` is global.
        
        # Better approach:
        # 1. Remove all diffs involving old_val from `used`? No, we need to check against the rest.
        # Let's compute the set of diffs that are "free" if we change old_val to new_val.
        
        # Diffs to be removed from `used`:
        removed_diffs = set()
        for i in range(len(row)):
            if i == j_idx:
                continue
            removed_diffs.add(abs(old_val - row[i]))
            
        # Diffs to be added to `used`:
        added_diffs = set()
        for i in range(len(row)):
            if i == j_idx:
                continue
            added_diffs.add(abs(new_val - row[i]))
        
        # Check if any added_diff is in `used` but not in `removed_diffs`
        # i.e., added_diff is already used by ANOTHER row or another position in this row.
        # Note: added_diffs might contain values that are in removed_diffs. Those are fine.
        # We need: (added_diffs - removed_diffs).isdisjoint(used)
        
        conflict = False
        for d in added_diffs:
            if d in removed_diffs:
                continue
            if d in used:
                conflict = True
                break
        
        if conflict:
            continue
            
        # Move is valid
        # Update `used`
        used -= removed_diffs
        used |= added_diffs
        
        # Update row
        row[j_idx] = new_val
        
        # Check if we improved the global max
        current_max = max(max(r) for r in rows)
        if current_max < best_max:
            best_max = current_max
            best_rows = [r[:] for r in rows]
            
    return best_rows
