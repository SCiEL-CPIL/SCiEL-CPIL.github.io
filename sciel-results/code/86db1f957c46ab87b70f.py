from fractions import Fraction
import time

def construct():
    start_time = time.time()
    deadline = start_time + 50.0

    # 1. DP Baseline
    target, reached = 2520, {0: []}
    for d in range(5, target + 1):
        if target % d:
            continue
        w = target // d
        for total, values in list(reached.items()):
            if total + w <= target and total + w not in reached:
                reached[total + w] = values + [d]
        if target in reached:
            best_sol = reached[target]
            break
    else:
        # Fallback if DP fails (should not happen)
        # This is a valid solution found by quick search or known identity
        # 1 = 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520 is INVALID.
        # Let's use a guaranteed valid one.
        # 1/5 + 1/6 + 1/7 + 1/42 = 8/15.
        # 1 - 8/15 = 7/15.
        # 7/15 = 1/5 + 2/3. No.
        # Let's just return a long valid solution if DP fails.
        # 1 = 1/5 + 1/6 + 1/30 + 1/31 + 1/930 + ...
        # Actually, the DP should always find a solution.
        # A simple valid solution:
        # 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520
        # Sum = 1383/2520. Not 1.
        
        # Let's use: 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520 + 1/840
        # 1383 + 3 = 1386. No.
        
        # Correct valid solution:
        # 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520
        # Let's re-calculate.
        # 1/5 = 504/2520
        # 1/6 = 420/2520
        # 1/7 = 360/2520
        # 1/42 = 60/2520
        # 1/140 = 18/2520
        # 1/210 = 12/2520
        # 1/420 = 6/2520
        # 1/1260 = 2/2520
        # 1/2520 = 1/2520
        # Sum = 504+420+360+60+18+12+6+2+1 = 1383.
        
        # Okay, I will generate a valid solution using the identity 1/n = 1/(n+1) + 1/(n(n+1))
        # Start with 1/5.
        # 1/5 = 1/6 + 1/30
        # 1/30 = 1/31 + 1/930
        # 1/930 = 1/931 + 1/(930*931)
        # This grows very fast.
        
        # Let's just use a brute force 4-term search as fallback.
        best_sol = None
        for n in range(5, 20):
            for m in range(n+1, 100):
                rem = 1 - Fraction(1, n) - Fraction(1, m)
                if rem <= 0:
                    break
                for p in range(m+1, 1000):
                    rem2 = rem - Fraction(1, p)
                    if rem2 <= 0:
                        break
                    if rem2.numerator == 1:
                        q = rem2.denominator
                        if q > p and q <= 10000000:
                            best_sol = [n, m, p, q]
                            break
                if best_sol:
                    break
            if best_sol:
                break
        if not best_sol:
            # Last resort: return an empty list? No, must be valid.
            # I will hardcode a known valid solution.
            # 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520 is wrong.
            # Let's use: 1/5 + 1/6 + 1/7 + 1/42 + 1/140 + 1/210 + 1/420 + 1/1260 + 1/2520
            # Wait, 1/5+1/6+1/7+1/42 = 8/15.
            # 1/140+1/210+1/420+1/1260+1/2520 = (18+12+6+2+1)/2520 = 39/2520 = 13/840.
            # 8/15 = 224/420 = 448/840.
            # 448/840 + 13/840 = 461/840.
            
            # I will just return a very long solution generated by splitting.
            best_sol = [5, 6, 30, 31, 930, 931, 865830, 865831]
            # Check: 1/5+1/6 = 11/30.
            # 1/30+1/31 = 61/930.
            # 1/930+1/931 = 1861/865830.
            # Sum = 11/30 + 61/930 + 1861/865830 + 1/865831
            # 11/30 = 317583/865830
            # 61/930 = 56639/865830
            # Sum so far = 317583+56639+1861 = 376083/865830.
            # 1 - 376083/865830 = (865830-376083)/865830 = 489747/865830.
            # Is 489747/865830 = 1/865831? No.
            
            # I will just raise an error if DP fails, but it shouldn't.
            best_sol = [5, 6, 7, 42, 140, 210, 420, 1260, 2520] # Invalid, but better than crash? No.
            # Let's just use the brute force result. If that fails, something is very wrong.
            raise RuntimeError("No valid solution found")

    best_count = len(best_sol)

    # 2. DFS for shorter solution
    def dfs(rem, min_d, current):
        nonlocal best_sol, best_count
        if time.time() > deadline:
            return
        if rem == 0:
            if len(current) < best_count:
                best_count = len(current)
                best_sol = current[:]
            return
        if rem < 0:
            return
        if len(current) >= best_count:
            return

        # Pruning: min terms needed
        k_max = best_count - len(current) - 1
        if k_max < 0:
            return
        if Fraction(k_max, min_d) < rem:
            return

        # Determine range for d
        d_start = max(min_d, (rem.denominator // rem.numerator) + (1 if rem.denominator % rem.numerator != 0 else 0))
        
        # Upper bound for d
        M = best_count - len(current) - 1
        if M == 0:
            if rem * d_start == 1:
                d = d_start
                current.append(d)
                dfs(rem - Fraction(1, d), d + 1, current)
                current.pop()
            return

        # M > 0
        # M/(d+1) >= rem - 1/d
        d_end = d_start
        while True:
            if d_end > 10000000: break
            if Fraction(M, d_end + 1) < rem - Fraction(1, d_end):
                break
            d_end += 1

        for d in range(d_start, d_end):
            if d < 5: continue
            current.append(d)
            dfs(rem - Fraction(1, d), d + 1, current)
            current.pop()

    dfs(Fraction(1, 1), 5, [])

    return best_sol
