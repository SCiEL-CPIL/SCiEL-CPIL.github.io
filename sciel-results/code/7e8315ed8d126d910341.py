def _is_valid_packing(blocks):
    """Check if the list of blocks forms a valid packing (no repeated 5-subsets)."""
    covered = set()
    for b in blocks:
        # Check for duplicates in the block itself (shouldn't happen with sets/tuples of distinct ints)
        # Check 5-subsets
        for i in range(6):
            for j in range(i+1, 6):
                for k in range(j+1, 6):
                    for l in range(k+1, 6):
                        for m in range(l+1, 6):
                            subset = (b[i], b[j], b[k], b[l], b[m])
                            if subset in covered:
                                return False
                            covered.add(subset)
    return True

def _generate_orbit(start_block, generators):
    """Generate the orbit of a block under the group generated by the given permutations."""
    blocks = set()
    current_blocks = [tuple(sorted(start_block))]
    blocks.add(current_blocks[0])
    
    while current_blocks:
        new_blocks = []
        for b in current_blocks:
            for g in generators:
                new_b = tuple(sorted(g[p] for p in b))
                if new_b not in blocks:
                    blocks.add(new_b)
                    new_blocks.append(new_b)
        current_blocks = new_blocks
        
    return [list(b) for b in blocks]

