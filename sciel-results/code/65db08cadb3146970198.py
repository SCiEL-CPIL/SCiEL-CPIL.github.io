import time
import sys

def construct(n_rows, k):
    # Deadline: 120s limit, aim to finish by 110s
    start_time = time.time()
    deadline = 110.0
    
    # Total differences required
    diffs_per_row = k * (k + 1) // 2
    total_diffs_needed = n_rows * diffs_per_row
    
    # Lower bound for max value M
    # The differences must be distinct and in [1, M]
    # So M must be at least total_diffs_needed
    M_min = total_diffs_needed
    
    # Run a simple greedy to get a baseline solution
    # This ensures we always have a valid answer
    def greedy_construct():
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            x = 0
            while len(row) < k + 1:
                x += 1
                new_diffs = {x - a for a in row}
                if not new_diffs & used:
                    row.append(x)
                    used |= new_diffs
            rows.append(row)
        return rows

    greedy_rows = greedy_construct()
    best_M = max(max(r) for r in greedy_rows)
    best_rows = greedy_rows
    
    # If M_min is already high, or time is tight, maybe just return greedy?
    # But let's try to improve.
    
    # Backtracking search for a specific M
    # We want to find a set of rows with max value <= M
    # We use a bitset for used differences.
    # Bit i is 1 if difference i is used.
    
    def search_for_M(M):
        # used_diffs is an integer bitset
        used_diffs = 0
        rows = []
        
        # Precompute mask for valid differences 1..M
        # We only care about bits 1 to M
        valid_mask = (1 << (M + 1)) - 2 # Bits 1 to M set
        
        # Helper to check if a new set of diffs can be added
        def can_add_diffs(new_mask):
            return (used_diffs & new_mask) == 0 and (new_mask & ~valid_mask) == 0
        
        # Recursive function to build rows
        # row_idx: index of row being built
        # current_row: list of marks in current row
        # next_min: minimum value for next mark (must be > last mark)
        
        def backtrack(row_idx, current_row, next_min):
            nonlocal used_diffs, rows
            nonlocal deadline, start_time
            
            # Time check
            if time.time() > deadline:
                return False
            
            # If we have completed all rows
            if row_idx == n_rows:
                return True
            
            # If we have completed the current row
            if len(current_row) == k + 1:
                rows.append(current_row)
                # Start next row
                if backtrack(row_idx + 1, [0], 1):
                    return True
                rows.pop()
                return False
            
            # Need to add a mark to current_row
            last_mark = current_row[-1]
            
            # Try possible next marks x
            # x must be > last_mark
            # x <= M
            # The differences x - a for a in current_row must be unused
            
            # Heuristic: try smallest x first to keep values low
            # But we also need to ensure we don't get stuck.
            # A simple "smallest x first" is usually good for minimizing max value.
            
            # Optimization: 
            # The smallest possible next mark is last_mark + 1.
            # The largest possible next mark is M.
            
            # We can prune if the number of available differences is insufficient.
            # Diffs needed for rest of current row:
            # If current_row has L marks, we need k+1-L more.
            # The number of new differences generated by adding one mark is L.
            # Total diffs remaining for this row: sum_{i=L}^{k} i = (k+1-L)*(k+L+1)//2 ? No.
            # If we have L marks, we have generated L*(L-1)/2 diffs.
            # Total diffs for full row is k*(k+1)/2.
            # Remaining diffs for this row = k*(k+1)/2 - L*(L-1)/2.
            # Diffs for all future rows = (n_rows - 1 - row_idx) * diffs_per_row.
            
            L = len(current_row)
            rem_diffs_current = diffs_per_row - (L * (L - 1) // 2)
            rem_diffs_future = (n_rows - 1 - row_idx) * diffs_per_row
            total_rem_diffs = rem_diffs_current + rem_diffs_future
            
            # Count available diffs in [1, M]
            # available = popcount(valid_mask & ~used_diffs)
            available = (valid_mask & ~used_diffs).bit_count()
            
            if available < total_rem_diffs:
                return False
            
            # Try candidates
            # We can limit the search space.
            # x must be such that x - a are all <= M (which is true if x <= M)
            # and x - a > 0 (true if x > a)
            
            # To speed up, we can try x in increasing order.
            # But if M is large, this loop is big.
            # However, M is small (~100-200).
            
            for x in range(last_mark + 1, M + 1):
                # Calculate mask of new differences
                new_mask = 0
                valid = True
                for a in current_row:
                    d = x - a
                    if d > M:
                        valid = False
                        break
                    new_mask |= (1 << d)
                
                if not valid:
                    continue
                
                # Check if these diffs are already used
                if used_diffs & new_mask:
                    continue
                
                # Check if the diffs are within range (already checked d <= M)
                # Also d >= 1 is guaranteed since x > a >= 0 and x > last_mark >= a
                
                # Prune: Check if adding this x makes it impossible to finish
                # This is expensive, so we rely on the available count check at the top of the loop
                # or a lighter check.
                
                # Commit
                used_diffs |= new_mask
                current_row.append(x)
                
                if backtrack(row_idx, current_row, x + 1):
                    return True
                
                # Undo
                current_row.pop()
                used_diffs &= ~new_mask
                
            return False
        
        # Start search
        # First row starts with 0
        # Symmetry breaking: The first mark of the first row is 0.
        # The second mark can be assumed to be 1? 
        # If we swap rows, the set of differences is the same.
        # If we permute marks within a row? No, order is fixed by value.
        # We can assume the smallest difference in the entire set is 1.
        # This implies some row has a difference of 1.
        # This row must contain two consecutive integers.
        # This doesn't force the first row to start with 1, but we can try to enforce that the global set of differences includes 1.
        # A stronger symmetry break: Fix the first row to start with 0, 1?
        # Not necessarily optimal, but often true.
        # Let's just try standard backtracking.
        
        if backtrack(0, [0], 1):
            return rows
        return None

    # Try to find a solution with M < best_M
    # We iterate M from M_min upwards
    # If we find one, we return it immediately (it's the best for that M)
    # We want the smallest M.
    
    # To save time, we can binary search or just linear scan from M_min.
    # Linear scan is safer.
    
    for M in range(M_min, best_M):
        if time.time() > deadline:
            break
        
        # Optional: Check if M is feasible by counting bound
        # If M < total_diffs_needed, skip (already handled by M_min)
        
        result = search_for_M(M)
        if result is not None:
            # Verify result just in case
            # (Search logic should guarantee it, but double check is cheap)
            all_diffs = set()
            valid = True
            max_val = 0
            for r in result:
                if len(r) != k + 1 or r[0] != 0:
                    valid = False
                    break
                for i in range(len(r)):
                    for j in range(i + 1, len(r)):
                        d = r[j] - r[i]
                        if d in all_diffs:
                            valid = False
                            break
                        all_diffs.add(d)
                if not valid:
                    break
                max_val = max(max_val, r[-1])
            
            if valid and max_val <= M:
                return result
            # If invalid, something went wrong in search, ignore and continue?
            # Or return greedy.
            
    # If no better M found, return greedy
    return best_rows
