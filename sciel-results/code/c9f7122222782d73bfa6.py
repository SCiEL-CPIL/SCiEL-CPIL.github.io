import time
import random
import numpy as np
from itertools import combinations

def construct():
    start_time = time.time()
    deadline = start_time + 50.0

    # Pre-compute popcount table for 17-bit integers (2^17 = 131072 entries)
    # 17 bits -> values from 0 to 131071
    popcount = [0] * (1 << 17)
    for i in range(1, 1 << 17):
        popcount[i] = popcount[i >> 1] + (i & 1)

    def popcount_fast(x):
        return popcount[x & 0x1FFFF]

    def is_valid_code(words):
        for i in range(len(words)):
            wi = words[i]
            for j in range(i + 1, len(words)):
                if popcount_fast(wi ^ words[j]) < 6:
                    return False
        return True

    # Step 1: Build the [17,8,6] linear code (256 words)
    # This is the shortened version of the [18,9,6] extended QR(17) code.
    # The full [17,9,5] QR code has 512 words. We extend to [18,9,6] by appending a parity bit,
    # then shorten by picking a coordinate and keeping only words with 0 in that coordinate.
    
    # GF(2^8) with primitive polynomial 0x1d: x^8 + x^4 + x^3 + x^2 + 1
    # Actually the standard QR(17) code is in GF(2) cyclic, but we need the generator polynomial.
    # g(x) = prod_{r in Q} (x - alpha^r) where alpha is a 17th root of unity.
    # In GF(2^8), we find alpha of order 17. 255 = 15*17.
    
    gf_poly = 0x1d  # x^8+x^4+x^3+x^2+1, primitive in GF(2^8)
    
    def gf_mul(a, b):
        res = 0
        for _ in range(8):
            if b & 1:
                res ^= a
            b >>= 1
            if a & 0x80:
                a = ((a << 1) ^ gf_poly) & 0xFF
            else:
                a = (a << 1) & 0xFF
        return res

    def gf_pow(a, n):
        res = 1
        while n:
            if n & 1:
                res = gf_mul(res, a)
            a = gf_mul(a, a)
            n >>= 1
        return res

    # Find element of order 17
    alpha = None
    for candidate in range(1, 256):
        if gf_pow(candidate, 17) == 1 and candidate != 1:
            alpha = candidate
            break

    if alpha is None:
        # Fallback: use a simpler construction if GF field construction fails
        alpha = 3  # Just a placeholder, should not happen

    # Quadratic residues mod 17
    Q = [1, 2, 4, 8, 9, 13, 15, 16]
    
    # Build generator polynomial g(x) of degree 8: g(x) = prod_{i in Q} (x - alpha^i)
    g = [1]  # coefficients from lowest degree
    for i in Q:
        root = gf_pow(alpha, i)
        new_g = [0] * (len(g) + 1)
        for j in range(len(g)):
            new_g[j] ^= gf_mul(g[j], root)
            new_g[j + 1] ^= g[j]
        g = new_g

    # g now has degree 8, so len(g) = 9
    # Cyclic code of length 17 over GF(2), generated by g(x) mod (x^17-1)
    # The code C consists of all c(x) = m(x)*g(x) mod (x^17-1), m(x) degree < 8
    # This gives [17, 17-8, d_min] code. d_min should be 5.
    
    # Generate all 512 words of the [17,9,5] code
    words_17_9_5 = []
    for m in range(512):
        c = [0] * 17
        for j in range(9):  # degree of g
            if (m >> j) & 1:
                # c += x^j * g mod (x^17 - 1)
                for k in range(9):
                    if (g[k] != 0):  # g should have 0/1 coefficients in GF(2) cyclic
                        pos = (j + k) % 17
                        c[pos] ^= 1
        # Convert to integer
        val = 0
        for bit in c:
            val |= bit
            val <<= 1
        val >>= 1  # shift right once to account for last extra shift
        # Actually let me recompute:
        val = 0
        for bit in c:
            val = (val << 1) | bit
        words_17_9_5.append(val)

    # Extend to [18,9,6] by appending overall parity
    words_18_9_6 = []
    for w in words_17_9_5:
        parity = popcount_fast(w) % 2
        # w is a 17-bit number. Bit 16 is MSB, bit 0 is LSB.
        # Parity bit goes at position 17. New value:
        ext_val = w | (parity << 17)
        words_18_9_6.append(ext_val)

    # Shorten: keep words with parity bit = 0, then mask off the 18th coordinate.
    words_17_8_6 = []
    for w in words_18_9_6:
        if (w >> 17) & 1 == 0:
            w_short = w & 0x1FFFF  # keep only 17 bits
            words_17_8_6.append(w_short)

    # Deduplicate (shouldn't be needed but safe)
    words_17_8_6 = list(set(words_17_8_6))
    base_code = words_17_8_6

    # Verify the base code
    if not is_valid_code(base_code):
        # Fallback: just return the words we have as-is, but ensure validity by filtering
        # Actually let's verify and if invalid, reduce it
        # This shouldn't happen, but just in case
        valid_code = [base_code[0]]
        for w in base_code[1:]:
            ok = True
            for v in valid_code:
                if popcount_fast(w ^ v) < 6:
                    ok = False
                    break
            if ok:
                valid_code.append(w)
        base_code = valid_code

    current_code = list(base_code)
    best_code = list(base_code)
    best_size = len(current_code)
    if best_size < 32:
        # Absolute fallback
        return [0]
    
    # Step 2: Greedy + Local search to try to grow beyond 256
    # Random order for trying to add words
    # We'll try iterative improvement: try adding random words, then local search.

    def greedy_add_all(current, candidates):
        """Try to add as many as possible from candidates to current, greedily."""
        for w in candidates:
            if w in current:
                continue
            ok = True
            for v in current:
                if popcount_fast(w ^ v) < 6:
                    ok = False
                    break
            if ok:
                current.append(w)
        return current

    # Local search using simulated annealing to find better packs
    # We represent the code as a sorted list. 
    # Operations: 
    #  - Add a random word w if it's >=6 from all current words
    #  - Swap: remove a word w_i and add a random word w_new that fits with the rest
    
    def local_search(code, max_iters, time_limit):
        """Attempt to grow code via random insertion/swap, with SA-like logic. Simple version:
        Randomly add if possible, occasionally remove a random word to try inserting others.
        Track the best code size."""
        code = list(code)
        best_local = list(code)
        best_size_local = len(code)
        for it in range(max_iters):
            if time.time() > time_limit:
                break
            r = random.random()
            if r < 0.85:
                # Try add
                w_new = random.randint(0, 0x1FFFF)
                if w_new not in code:
                    ok = True
                    for v in code:
                        if popcount_fast(w_new ^ v) < 6:
                            ok = False
                            break
                    if ok:
                        code.append(w_new)
                        if len(code) > best_size_local:
                            best_size_local = len(code)
                            best_local = list(code)
            else:
                # Try swap: remove one, add another
                if len(code) > 30:
                    idx_rm = random.randint(0, len(code) - 1)
                    w_rm = code[idx_rm]
                    code.pop(idx_rm)
                    w_new = random.randint(0, 0x1FFFF)
                    if w_new != w_rm and w_new not in code:
                        ok = True
                        for v in code:
                            if popcount_fast(w_new ^ v) < 6:
                                ok = False
                                break
                        if ok:
                            code.append(w_new)
                        else:
                            code.insert(idx_rm, w_rm)
                    else:
                        code.insert(idx_rm, w_rm)
                    
        if len(best_local) > len(best_code):
            return best_local
        return best_local

    # --- Vectorized Nonlinear Extension Search ---
    # The goal is to add words to the 256-word linear code.
    # Since 0 is in the code, any new word w must have weight >= 6.
    # We focus on words with weight exactly 6, as they are "closest" to the existing code
    # and thus most likely to fit if they exist.
    
    # 1. Generate all candidates of weight exactly 6.
    # Number of such words is C(17, 6) = 12376. This is small enough to handle in memory.
    candidates = []
    for i in range(17):
        for j in range(i+1, 17):
            for k in range(j+1, 17):
                for l in range(k+1, 17):
                    for m in range(l+1, 17):
                        for n in range(m+1, 17):
                            w = (1 << i) | (1 << j) | (1 << k) | (1 << l) | (1 << m) | (1 << n)
                            candidates.append(w)
    
    candidates = np.array(candidates, dtype=np.int64)
    
    # 2. Prepare the current code as a NumPy array for vectorized XOR operations.
    # We will iteratively filter candidates against the current code.
    # To handle the growing code size, we can either:
    # A) Re-check all remaining candidates against the entire code in each iteration (slow if code grows large, but simple)
    # B) Maintain a list of "compatible" candidates and filter it incrementally.
    
    # Strategy: Greedy addition.
    # In each step, find the candidate that has the maximum minimum distance to the current code?
    # No, we just need distance >= 6. Since candidates have weight 6, distance to 0 is 6.
    # We need distance to all other code words >= 6.
    
    # Let's represent the current code as a matrix of bits? No, XOR is easier on integers.
    # But NumPy doesn't have fast bitwise XOR on int64 arrays in older versions or it's not vectorized for popcount.
    # We have a popcount table.
    
    # Alternative approach:
    # For a candidate w, it is valid if min_{c in code} popcount(w ^ c) >= 6.
    # This is equivalent to: for all c in code, popcount(w ^ c) >= 6.
    
    # We can vectorize the "is valid" check against the *current* code using the popcount table?
    # popcount is a Python list, not a NumPy array. Converting it to a NumPy array allows vectorized lookup.
    popcount_np = np.array(popcount, dtype=np.int8)
    
    # Convert current code to NumPy array
    code_np = np.array(current_code, dtype=np.int64)
    
    # We will maintain a mask of which candidates are still valid.
    # Initially, all candidates are "potentially valid" (we haven't checked them against the code yet).
    # But we know they are valid against 0 (distance 6).
    # We need to check them against all other code words.
    
    # Efficient check:
    # For a batch of candidates C (shape N_c) and code words K (shape N_k):
    # We want to know if min_{k in K} popcount(c ^ k) >= 6.
    # This is expensive if done naively (N_c * N_k XORs and popcounts).
    
    # Let's try a greedy approach with incremental filtering.
    # Keep a list `active_candidates` (indices into `candidates`).
    # In each iteration:
    # 1. Pick a candidate from `active_candidates` (e.g., the first one, or random).
    # 2. Check if it is valid against the *current* code.
    #    - If valid, add it to the code.
    #    - Remove it from `active_candidates`.
    #    - Filter `active_candidates` to remove any that are now invalid (distance < 6) against the *new* code word.
    #      This filtering can be vectorized: 
    #      For the new word w_new, compute distances to all active candidates.
    #      Keep only those with distance >= 6.
    
    active_indices = np.arange(len(candidates))
    # Shuffle to avoid bias
    np.random.shuffle(active_indices)
    
    while time.time() < deadline - 3.0 and len(active_indices) > 0:
        # Take the first active candidate
        idx = active_indices[0]
        w_new = candidates[idx]
        
        # Check if w_new is valid against the current code (excluding 0, which we know is OK)
        # Actually, just check against the whole code to be safe, or just the non-zero words.
        # Since w_new has weight 6, dist(w_new, 0) = 6.
        # We need to check against all other code words.
        
        # Vectorized check against current code:
        # dists = popcount_np[w_new ^ code_np]
        # if np.min(dists) < 6: invalid
        
        # Optimization: We don't need to check against 0 again.
        # But code_np includes 0. It's cheap enough.
        
        dists = popcount_np[w_new ^ code_np]
        
        if np.min(dists) >= 6:
            # Valid! Add to code
            current_code.append(int(w_new))
            code_np = np.append(code_np, w_new)
            
            if len(current_code) > best_size:
                best_size = len(current_code)
                best_code = list(current_code)
            
            # Remove this candidate from active list
            active_indices = active_indices[1:]
            
            # Filter active_indices: remove any candidate that is now too close to w_new
            if len(active_indices) > 0:
                # Compute distances from w_new to all remaining active candidates
                # active_candidates = candidates[active_indices]
                # dists_to_new = popcount_np[w_new ^ active_candidates]
                # mask = dists_to_new >= 6
                # active_indices = active_indices[mask]
                
                active_cands = candidates[active_indices]
                dists_to_new = popcount_np[w_new ^ active_cands]
                mask = dists_to_new >= 6
                active_indices = active_indices[mask]
        else:
            # Invalid against current code. Remove from active list.
            active_indices = active_indices[1:]

    # Final verification
    if len(best_code) >= 32:
        if is_valid_code(best_code):
            return best_code
        else:
            # Filter it down
            final = []
            for w in best_code:
                ok = True
                for v in final:
                    if popcount_fast(w ^ v) < 6:
                        ok = False
                        break
                if ok:
                    final.append(w)
            if len(final) >= 32:
                return final
            return base_code
    else:
        return base_code if len(base_code) >= 32 else [0]
