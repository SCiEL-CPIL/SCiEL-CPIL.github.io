import numpy as np
import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 50.0  # Safety margin for 60s limit
    
    n = 128
    
    def evaluate(A):
        # Calculate counts for A
        # A is bool array
        idxs = np.where(A)[0]
        counts = np.zeros(2 * n + 1, dtype=np.int64)
        if len(idxs) > 0:
            # Generate upper triangle indices for unordered pairs (i <= j)
            i_idx, j_idx = np.triu_indices(len(idxs))
            sums = idxs[i_idx] + idxs[j_idx]
            np.add.at(counts, sums, 1)
        return counts

    def get_score(counts):
        target_counts = counts[128:257]
        invalid_count = np.sum(target_counts == 0)
        if invalid_count > 0:
            # Heavy penalty for invalidity
            return 10000 + invalid_count
        else:
            return np.max(target_counts)

    def greedy_repair(A, counts):
        # Attempt to cover all zero counts by adding elements
        # This is a heuristic to reach validity quickly
        max_iter = 50
        for _ in range(max_iter):
            target_counts = counts[128:257]
            zero_sums = np.where(target_counts == 0)[0] + 128
            if len(zero_sums) == 0:
                break
            
            # Find a candidate x in [0, 128] not in A that covers the most zero_sums
            best_x = -1
            best_cover = 0
            # We can sample candidates or iterate all
            # Iterating all 129 is fast
            for x in range(n + 1):
                if A[x]:
                    continue
                # Potential new sums: x + y for y in A
                # Also 2*x
                # We need to check which of these sums are in zero_sums
                # Efficient check:
                # new_sums = x + idxs
                # But we need to count how many of these are in zero_sums.
                # Since zero_sums is small (hopefully), we can check intersection.
                # Or simpler: just check if adding x reduces the number of zeros.
                # Let's estimate coverage.
                # Sums generated by x with existing A: x + idxs
                # Plus 2*x
                # We want to maximize overlap with zero_sums.
                
                # Optimization: only consider x such that x + min(A) <= max(zero_sums) and x + max(A) >= min(zero_sums)
                # For simplicity, just check all x.
                
                # To speed up, we can precompute the set of zero_sums
                # and for each x, check if any x+y is in zero_sums.
                # Since k is small, x+y is small.
                
                # A faster way: 
                # For each z in zero_sums, if (z - x) is in A, then x covers z.
                # Also if z == 2*x, x covers z.
                
                # Let's just count coverage.
                # Use a set for zero_sums for O(1) lookup
                # But creating a set every time is slow.
                # Let's stick to a simple loop over zero_sums.
                cover = 0
                for z in zero_sums:
                    y = z - x
                    if 0 <= y <= n and A[y]:
                        cover += 1
                    if z == 2 * x:
                        cover += 1
                        break # One pair is enough to cover z? No, multiplicity.
                        # Actually, we just need count > 0.
                        # If z was 0, and we add 1, it becomes > 0.
                        # So covering z once is enough to remove it from zero_sums.
                        
                if cover > best_cover:
                    best_cover = cover
                    best_x = x
            
            if best_x == -1 or best_cover == 0:
                break
                
            # Add best_x
            A[best_x] = True
            idxs = np.where(A)[0]
            # Update counts
            # New pairs involving best_x: {best_x, y} for y in A (including best_x)
            # Note: best_x is now in A.
            # The pairs are {best_x, y} for all y in A.
            # This includes {best_x, best_x}.
            # We need to add 1 to counts[best_x + y] for all y in A.
            targets = best_x + idxs
            np.add.at(counts, targets, 1)
            
        return A, counts

    best_A = None
    best_score = float('inf')
    
    # Initial heuristic: A set that is "dense" enough to cover [128, 256]
    # If we take all even numbers, sums are even. We need all integers.
    # A random set of size ~25-30 should cover it.
    # Let's try a few different starting points.
    
    for restart in range(50):
        if time.time() > deadline:
            break
            
        # Strategy: Start with a random set of size k
        # k around 20-30 is a good guess.
        k = random.randint(18, 35)
        A = np.zeros(n + 1, dtype=bool)
        candidates = list(range(n + 1))
        random.shuffle(candidates)
        for i in range(k):
            A[candidates[i]] = True
            
        counts = evaluate(A)
        current_score = get_score(counts)
        
        # If invalid, try greedy repair
        if current_score > 10000:
            A, counts = greedy_repair(A, counts)
            current_score = get_score(counts)
            
        if current_score < best_score:
            best_score = current_score
            best_A = A.copy()
            
        # If we found a valid set with low peak, we can polish it
        # Otherwise, run SA to find a valid one or improve peak.
        
        # SA Phase
        temperature = 5.0
        cooling = 0.995
        # Give more time if we are still invalid
        local_deadline = min(deadline, time.time() + (1.0 if current_score > 10000 else 0.5))
        
        idxs_cache = np.where(A)[0]
        
        while time.time() < local_deadline:
            # Pick random element to toggle
            idx = random.randint(0, n)
            
            if A[idx]:
                # Remove idx
                # Subtract contributions: pairs {idx, y} for y in A
                # idx is in idxs_cache.
                targets = idx + idxs_cache
                np.add.at(counts, targets, -1)
                A[idx] = False
                # Update idxs_cache
                idxs_cache = idxs_cache[idxs_cache != idx]
            else:
                # Add idx
                # Add contributions: pairs {idx, y} for y in A
                # Plus {idx, idx}
                # Pairs are {idx, y} for y in idxs_cache.
                # And {idx, idx}.
                # So we add 1 to counts[idx + y] for y in idxs_cache.
                # And 1 to counts[2*idx].
                if len(idxs_cache) > 0:
                    targets = idx + idxs_cache
                    np.add.at(counts, targets, 1)
                counts[2 * idx] += 1
                A[idx] = True
                # Update idxs_cache
                idxs_cache = np.append(idxs_cache, idx)
                
            new_score = get_score(counts)
            
            delta = new_score - current_score
            
            # Accept if better, or with probability exp(-delta/T)
            # If delta is large positive (worse), prob is low.
            # If delta is negative (better), prob is 1.
            
            if delta < 0 or (temperature > 0.1 and random.random() < np.exp(-delta / temperature)):
                current_score = new_score
                if new_score < best_score:
                    best_score = new_score
                    best_A = A.copy()
            else:
                # Revert
                if A[idx]:
                    # It was added, so remove it
                    targets = idx + idxs_cache
                    np.add.at(counts, targets, -1)
                    A[idx] = False
                    idxs_cache = idxs_cache[idxs_cache != idx]
                else:
                    # It was removed, so add it back
                    if len(idxs_cache) > 0:
                        targets = idx + idxs_cache
                        np.add.at(counts, targets, 1)
                    counts[2 * idx] += 1
                    A[idx] = True
                    idxs_cache = np.append(idxs_cache, idx)
            
            temperature *= cooling

    # Ensure we return a valid set
    if best_A is None:
        # Fallback: A known valid set, e.g., all numbers?
        # All numbers [0, 128] is valid.
        return list(range(n + 1))
        
    # Check validity of best_A
    counts = evaluate(best_A)
    if np.any(counts[128:257] == 0):
        # If best found is invalid, try to fix or return a known valid set
        # We should probably return the best valid set found.
        # My get_score penalizes invalid sets heavily.
        # So best_score should correspond to a valid set if one was found.
        # If no valid set was found, best_A might be invalid.
        # Let's verify.
        if np.any(counts[128:257] == 0):
             # Return a simple valid set
             return list(range(n + 1))

    return [i for i in range(n + 1) if best_A[i]]
