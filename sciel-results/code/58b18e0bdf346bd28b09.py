# EVOLVE-BLOCK-START
def construct(n_rows, k):
    """
    Construct a difference triangle set with n_rows rows, each of length k+1,
    starting at 0, strictly increasing, such that all positive differences
    within each row are distinct across all rows.
    
    Strategy: Simulated Annealing with Row-Level Re-optimization.
    Instead of moving single elements, we pick a row, remove it, and try to 
    reconstruct it greedily/local-search style to minimize the global scope.
    """
    
    def greedy_row(used_diffs, max_val):
        """
        Construct a single row of length k+1 starting at 0, strictly increasing,
        avoiding 'used_diffs'. Returns None if not possible within max_val.
        """
        row = [0]
        for _ in range(k):
            found = False
            last = row[-1]
            # Try smallest possible next value
            for x in range(last + 1, max_val + 1):
                new_diffs = {x - a for a in row}
                if not (new_diffs & used_diffs):
                    row.append(x)
                    # We don't update used_diffs here because we might backtrack,
                    # but for greedy construction of a single row, we can just check against the static set
                    # Wait, differences within the new row must also be distinct?
                    # Yes, "all differences between two entries of the same row are distinct over all rows".
                    # This implies differences within a row are distinct from each other?
                    # "distinct over all rows" usually means the set of ALL differences (from all rows) has size sum of binomial(k+1, 2) * n_rows.
                    # So yes, no duplicates within a row either.
                    # My check `new_diffs & used_diffs` handles conflicts with OTHER rows.
                    # I also need to ensure `new_diffs` don't conflict with each other?
                    # `new_diffs` are {x-a0, x-a1, ...}. Since a_i are distinct, x-a_i are distinct.
                    # So no internal conflict in new_diffs.
                    # But do they conflict with existing diffs in `row`?
                    # `used_diffs` passed in should contain diffs from OTHER rows.
                    # The current row's diffs are not in `used_diffs` yet.
                    # So I must also check against the current row's existing diffs.
                    
                    # Let's refine: pass `row_diffs_so_far` as well or just check.
                    # Actually, if I just use `used_diffs` as "all forbidden diffs", I must update it as I go?
                    # No, if I update it, I can't backtrack easily.
                    # Better: check against `used_diffs` (external) AND `current_row_diffs` (internal).
                    
                    # Let's rewrite greedy_row to be safe.
                    pass
            
            # The simple greedy above is flawed if it doesn't check internal row diffs properly 
            # against the "used" set if the used set doesn't contain the row's own previous diffs.
            
            # Let's use a helper that takes `forbidden` set.
            # In the main loop, `forbidden` will be the diffs of all OTHER rows.
            # Inside greedy_row, we must ensure new diffs don't collide with `forbidden` 
            # AND don't collide with diffs already in `row`.
            
            # Let's restart the logic for greedy_row.
            pass
            
        return row

    def get_row_diffs(row):
        return {row[j] - row[i] for i in range(len(row)) for j in range(i + 1, len(row))}

    def greedy_construct_full():
        """Build all rows greedily."""
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            for _ in range(k):
                found = False
                last = row[-1]
                # We need to find x such that {x-a for a in row} is disjoint from `used` AND disjoint from {a_j-a_i for 0<=i<j<len(row)}
                # Actually, since we build row sequentially, we just need to check against `used` and the diffs of the current row prefix.
                
                # To speed up, we can just iterate x.
                # Max x is unbounded initially, but we can cap it.
                # For initial construction, let's allow large scope.
                max_search = 200 
                for x in range(last + 1, max_search + 1):
                    new_diffs = {x - a for a in row}
                    # Check against global used
                    if new_diffs & used:
                        continue
                    # Check against current row's existing diffs
                    # Current row diffs are generated by pairs in `row`.
                    # Since `row` is small, we can just compute the set of current row diffs?
                    # Or simpler: The new diffs are x - a_i.
                    # Do any of these equal a_j - a_i (where j < len(row))?
                    # If x - a_i == a_j - a_k, then x = a_j - a_k + a_i.
                    # It's easier to just maintain a set of diffs for the current row.
                    
                    # Let's just compute the set of all diffs in the candidate row [row + [x]]
                    # and check if len == sum of binomials.
                    # This is O(k^2) per step. k=8, so 36 checks. Very fast.
                    
                    candidate_row = row + [x]
                    cand_diffs = get_row_diffs(candidate_row)
                    # Check if all diffs in cand_diffs are unique (within row)
                    if len(cand_diffs) != len(candidate_row)*(len(candidate_row)-1)//2:
                        continue
                    # Check if any diff in cand_diffs is in `used`
                    if cand_diffs & used:
                        continue
                    
                    row = candidate_row
                    found = True
                    break
                
                if not found:
                    # Greedy failed, try larger max_search or return None
                    # For initialization, we can just increase max_search
                    return None
            rows.append(row)
            used |= get_row_diffs(row)
        return rows

    def get_scope(rows):
        return max(max(row) for row in rows)

    def is_valid(rows):
        seen = set()
        for row in rows:
            for d in get_row_diffs(row):
                if d in seen:
                    return False
                seen.add(d)
        return True

    # 1. Initial Construction
    rows = greedy_construct_full()
    if rows is None:
        # Fallback to a very simple random start if greedy fails (unlikely)
        rows = [[0] + [i*(i+1)//2 for i in range(1, k+1)] for _ in range(n_rows)]
        # This might not be valid, but we'll fix it with SA
        
    current_rows = [r[:] for r in rows]
    current_scope = get_scope(current_rows)
    best_rows = [r[:] for r in current_rows]
    best_scope = current_scope
    
    # Pre-compute diffs for each row for fast removal/addition
    row_diffs = [get_row_diffs(r) for r in current_rows]
    global_used = set()
    for rd in row_diffs:
        global_used |= rd
        
    # Simulated Annealing
    T = 50.0
    T_min = 0.1
    cooling = 0.99
    max_iters = 5000
    
    for it in range(max_iters):
        if T < T_min:
            break
            
        # Pick a random row to rebuild
        i = random.randint(0, n_rows - 1)
        
        # Remove row i from global_used
        global_used -= row_diffs[i]
        
        # Try to rebuild row i
        # We want to minimize the max value in row i, but also keep global scope low.
        # Let's try to rebuild it to be as "tight" as possible, or just valid within current_scope.
        # Actually, to improve global scope, we should try to rebuild it to have a smaller max value.
        # Let's try to construct a row that is valid and has max value <= current_scope.
        
        new_row = None
        # Try greedy construction with cap = current_scope
        # We might also try to allow slightly larger cap if we are stuck, but SA handles that.
        
        # Heuristic: Try to find a row with max value < current_scope if possible?
        # Or just any valid row within current_scope.
        # If we find a row with smaller max, global scope might drop.
        
        # Let's use a randomized greedy for the rebuild to escape local optima.
        # Shuffle the order of candidates? No, we must pick increasing integers.
        # We can randomize the choice among valid candidates.
        
        row = [0]
        success = True
        for _ in range(k):
            last = row[-1]
            candidates = []
            # Search range: last+1 to current_scope
            for x in range(last + 1, current_scope + 1):
                candidate_row = row + [x]
                cand_diffs = get_row_diffs(candidate_row)
                # Check internal uniqueness
                if len(cand_diffs) != len(candidate_row)*(len(candidate_row)-1)//2:
                    continue
                # Check against global_used (which excludes row i)
                if cand_diffs & global_used:
                    continue
                candidates.append(x)
            
            if not candidates:
                success = False
                break
                
            # Pick a candidate
            # To encourage smaller scope, pick smallest? 
            # To encourage diversity, pick random?
            # Let's pick random from the first few smallest to allow some flexibility.
            # Or just pick the smallest (greedy) to minimize row max.
            # If we always pick smallest, we might get stuck.
            # Let's pick random from candidates, weighted towards smaller values.
            # Simple: pick random.
            x = random.choice(candidates)
            row.append(x)
            
        if success:
            new_row = row
            new_row_diffs = get_row_diffs(new_row)
            
            # Calculate new global scope
            # We need to know if the max of new_row is less than other rows' max.
            # Other rows are unchanged.
            other_max = max(max(r) for j, r in enumerate(current_rows) if j != i)
            new_row_max = max(new_row)
            new_global_scope = max(other_max, new_row_max)
            
            # Decide whether to accept
            # Cost function: Global Scope
            # If new_global_scope < current_scope: Accept
            # Else: Accept with prob exp(-(new_global_scope - current_scope) / T)
            
            if new_global_scope <= current_scope:
                # Accept
                current_rows[i] = new_row
                row_diffs[i] = new_row_diffs
                global_used |= new_row_diffs
                current_scope = new_global_scope
                
                if current_scope < best_scope:
                    best_scope = current_scope
                    best_rows = [r[:] for r in current_rows]
            else:
                # Worse scope, accept with probability
                delta = new_global_scope - current_scope
                prob = math.exp(-delta / T)
                if random.random() < prob:
                    current_rows[i] = new_row
                    row_diffs[i] = new_row_diffs
                    global_used |= new_row_diffs
                    current_scope = new_global_scope
        else:
            # Rebuild failed, keep old row
            global_used |= row_diffs[i]
        
        T *= cooling

    return best_rows
