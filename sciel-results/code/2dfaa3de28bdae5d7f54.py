import numpy as np
import time

DIMENSIONS = [2, 3, 5]

def _strassen_2x2x2(U, V, W, col, i_offset, j_offset, k_offset, n, m, p):
    # Strassen decomposition for 2x2x2 block
    # Local indices: ii in {0,1}, jj in {0,1}, kk in {0,1}
    # Global indices: i = i_offset + ii, j = j_offset + jj, k = k_offset + kk
    # U index: i*m + j
    # V index: j*p + k
    # W index: k*n + i

    # M1: (A[0,0]+A[1,1])(B[0,0]+B[1,1]) -> C[0,0], C[1,1]
    U[i_offset*m + j_offset][col] = 1
    U[(i_offset+1)*m + (j_offset+1)][col] = 1
    V[j_offset*p + k_offset][col] = 1
    V[(j_offset+1)*p + (k_offset+1)][col] = 1
    W[k_offset*n + i_offset][col] = 1
    W[(k_offset+1)*n + (i_offset+1)][col] = 1
    col += 1

    # M2: (A[1,0]+A[1,1])B[0,0] -> C[1,0], -C[1,1]
    U[(i_offset+1)*m + j_offset][col] = 1
    U[(i_offset+1)*m + (j_offset+1)][col] = 1
    V[j_offset*p + k_offset][col] = 1
    W[k_offset*n + (i_offset+1)][col] = 1
    W[(k_offset+1)*n + (i_offset+1)][col] = -1
    col += 1

    # M3: A[0,0](B[0,1]-B[1,1]) -> C[0,1], C[1,1]
    U[i_offset*m + j_offset][col] = 1
    V[j_offset*p + (k_offset+1)][col] = 1
    V[(j_offset+1)*p + (k_offset+1)][col] = -1
    W[(k_offset+1)*n + i_offset][col] = 1
    W[(k_offset+1)*n + (i_offset+1)][col] = 1
    col += 1

    # M4: A[1,1](B[1,0]-B[0,0]) -> C[0,0], C[1,0]
    U[(i_offset+1)*m + (j_offset+1)][col] = 1
    V[(j_offset+1)*p + k_offset][col] = 1
    V[j_offset*p + k_offset][col] = -1
    W[k_offset*n + i_offset][col] = 1
    W[k_offset*n + (i_offset+1)][col] = 1
    col += 1

    # M5: (A[0,0]+A[0,1])B[1,1] -> -C[0,0], C[0,1]
    U[i_offset*m + j_offset][col] = 1
    U[i_offset*m + (j_offset+1)][col] = 1
    V[(j_offset+1)*p + (k_offset+1)][col] = 1
    W[k_offset*n + i_offset][col] = -1
    W[(k_offset+1)*n + i_offset][col] = 1
    col += 1

    # M6: (A[1,0]-A[0,0])(B[0,0]+B[0,1]) -> C[1,1]
    U[(i_offset+1)*m + j_offset][col] = 1
    U[i_offset*m + j_offset][col] = -1
    V[j_offset*p + k_offset][col] = 1
    V[j_offset*p + (k_offset+1)][col] = 1
    W[(k_offset+1)*n + (i_offset+1)][col] = 1
    col += 1

    # M7: (A[0,1]-A[1,1])(B[1,0]+B[1,1]) -> C[0,0]
    U[i_offset*m + (j_offset+1)][col] = 1
    U[(i_offset+1)*m + (j_offset+1)][col] = -1
    V[(j_offset+1)*p + k_offset][col] = 1
    V[(j_offset+1)*p + (k_offset+1)][col] = 1
    W[k_offset*n + i_offset][col] = 1
    col += 1

    return col

def construct():
    n, m, p = DIMENSIONS  # n=2, m=3, p=5

    # Initial Rank 28 decomposition
    rank = 28
    U = np.zeros((n*m, rank))
    V = np.zeros((m*p, rank))
    W = np.zeros((p*n, rank))

    col = 0

    # Block 1: j=0, k=0..4
    for i in range(n):
        for k in range(p):
            U[i*m + 0, col] = 1
            V[0*p + k, col] = 1
            W[k*n + i, col] = 1
            col += 1

    # Block 2: j=1,2, k=0,1 (Strassen)
    col = _strassen_2x2x2(U, V, W, col, 0, 1, 0, n, m, p)

    # Block 3: j=1,2, k=2
    for i in range(n):
        for j in [1, 2]:
            U[i*m + j, col] = 1
            V[j*p + 2, col] = 1
            W[2*n + i, col] = 1
            col += 1

    # Block 4: j=1,2, k=3,4 (Strassen)
    col = _strassen_2x2x2(U, V, W, col, 0, 1, 3, n, m, p)

    # Check for linear dependencies to reduce rank
    # Flatten U, V, W into a single matrix where each column is a term
    # Term r is a vector of length n*m + m*p + p*n
    total_len = n*m + m*p + p*n
    terms = np.zeros((total_len, rank))
    
    # U part
    terms[:n*m, :] = U
    # V part
    terms[n*m:n*m+m*p, :] = V
    # W part
    terms[n*m+m*p:, :] = W

    # Calculate rank of the terms matrix
    # If rank < 28, we can reduce
    # Use SVD to find basis
    U_svd, s, Vt = np.linalg.svd(terms, full_matrices=False)
    
    # Determine effective rank (tolerance for numerical noise)
    tol = 1e-9
    effective_rank = np.sum(s > tol)
    
    if effective_rank < rank:
        # We can use the first effective_rank columns of Vt (which are the right singular vectors)
        # But we need to ensure they correspond to a valid decomposition.
        # The span of the terms is the same.
        # We can just take the basis vectors.
        new_rank = effective_rank
        new_terms = Vt[:new_rank, :].T
        
        # Extract new U, V, W
        new_U = new_terms[:n*m, :].T
        new_V = new_terms[n*m:n*m+m*p, :].T
        new_W = new_terms[n*m+m*p:, :].T
        
        # Verify the decomposition is exact
        # The tensor T_{ijk} = sum_r U_{ir} V_{jr} W_{kr}
        # We just changed the basis of the rank space, so it should be exact.
        
        # Convert to lists
        U_list = new_U.tolist()
        V_list = new_V.tolist()
        W_list = new_W.tolist()
        
        return {"U": U_list, "V": V_list, "W": W_list}

    # If no reduction found, return original
    U_list = U.tolist()
    V_list = V.tolist()
    W_list = W.tolist()

    return {"U": U_list, "V": V_list, "W": W_list}
