import random
import time

def construct():
    # Mandatory elements
    mandatory = {1, 2, 5, 11}
    max_val = 284
    all_candidates = set(range(1, max_val + 1)) - mandatory
    
    def is_valid_set(S):
        """Check if S is a valid Sidon set."""
        sums = set()
        L = list(S)
        for i in range(len(L)):
            for j in range(i, len(L)):
                s = L[i] + L[j]
                if s in sums:
                    return False
                sums.add(s)
        return True

    def try_add(S, sums, x):
        """Try to add x to S. Returns (success, new_S, new_sums)."""
        # Check conflicts
        for y in S:
            s = x + y
            if s in sums:
                return False, S, sums
        if 2 * x in sums:
            return False, S, sums
            
        # If no conflict, add
        new_S = S | {x}
        new_sums = sums | {x + y for y in S} | {2 * x}
        return True, new_S, new_sums

    def try_remove(S, sums, x):
        """Remove x from S. Returns (new_S, new_sums)."""
        new_S = S - {x}
        # Remove sums involving x
        # Sums were {x+y for y in S} U {2x}
        # Note: when x is in S, the sums generated by x are x+y for y in S (including x itself -> 2x)
        # So we remove {x + y for y in S}
        sums_to_remove = {x + y for y in S}
        new_sums = sums - sums_to_remove
        return new_S, new_sums

    def greedy_fill(S, sums, candidates, randomize=True):
        """Greedily add valid elements from candidates."""
        while True:
            valid_candidates = []
            # To speed up, we can just check all remaining candidates
            # But we need to update 'sums' as we add.
            # Let's iterate through candidates
            # For efficiency in a loop, we might want to pre-filter, but S changes.
            
            added = False
            # If randomize, shuffle candidates
            cand_list = list(candidates)
            if randomize:
                random.shuffle(cand_list)
            else:
                cand_list.sort()
                
            for x in cand_list:
                if x in S:
                    continue
                success, new_S, new_sums = try_add(S, sums, x)
                if success:
                    S = new_S
                    sums = new_sums
                    candidates.remove(x)
                    added = True
                    break # Restart scan with new S
            
            if not added:
                break
        return S, sums, candidates

    def local_search(S, sums, candidates, time_limit=10):
        """Perform local search to maximize size."""
        start_time = time.time()
        best_S = S
        best_size = len(S)
        
        while time.time() - start_time < time_limit:
            # 1. Try to add
            added = False
            cand_list = list(candidates)
            random.shuffle(cand_list)
            for x in cand_list:
                if x in S:
                    continue
                success, new_S, new_sums = try_add(S, sums, x)
                if success:
                    S = new_S
                    sums = new_sums
                    candidates.remove(x)
                    added = True
                    if len(S) > best_size:
                        best_S = set(S)
                        best_size = len(S)
                    break
            
            if added:
                continue # Try adding more immediately
            
            # 2. If stuck, try a swap
            # Pick a non-mandatory element to remove
            removable = [x for x in S if x not in mandatory]
            if not removable:
                break # Cannot swap mandatory elements
            
            random.shuffle(removable)
            x_to_remove = removable[0]
            
            # Pick a candidate to add
            cand_list = list(candidates)
            random.shuffle(cand_list)
            
            swap_success = False
            for y in cand_list:
                if y in S:
                    continue
                # Simulate swap: Remove x, Add y
                # 1. Remove x
                temp_S, temp_sums = try_remove(S, sums, x)
                # 2. Add y
                success, new_S, new_sums = try_add(temp_S, temp_sums, y)
                if success:
                    # Accept swap
                    S = new_S
                    sums = new_sums
                    candidates.remove(y)
                    candidates.add(x)
                    swap_success = True
                    break
            
            if not swap_success:
                # Try different x? Or just break if we've tried many swaps
                # To avoid infinite loop on same state, we can just break or try next x
                # For simplicity, we break and rely on restarts
                break

        return best_S, best_size

    best_overall_S = set(mandatory)
    best_overall_size = len(mandatory)
    
    # Multiple restarts
    num_restarts = 20
    for _ in range(num_restarts):
        S = set(mandatory)
        # Initial sums
        sums = set()
        L = list(S)
        for i in range(len(L)):
            for j in range(i, len(L)):
                sums.add(L[i] + L[j])
        
        candidates = set(range(1, max_val + 1)) - S
        
        # Greedy fill
        S, sums, candidates = greedy_fill(S, sums, candidates, randomize=True)
        
        # Local search
        S, size = local_search(S, sums, candidates, time_limit=5)
        
        if size > best_overall_size:
            best_overall_size = size
            best_overall_S = S
            
        # Check time
        if time.time() > 110:
            break

    return sorted(best_overall_S)
