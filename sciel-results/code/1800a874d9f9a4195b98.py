def construct():
    """Construct a large binary code of length 17 with minimum distance >= 6.
    
    Returns a list of distinct integers in [0, 2**17), each encoding a 17-bit codeword.
    """
    deadline = time.time() + 75.0  # Safety margin before 90s kill
    
    # Step 1: Build the [17,8,6] QR code (256 words)
    words = _build_quad_residue_code(17)
    n_words = len(words)
    
    # Step 2: Generate candidate words at distance exactly 6 from the zero word
    # and check which are compatible with the existing code.
    # A word w is compatible if d(w, v) >= 6 for all v in current code.
    
    # Precompute the code as a numpy array for vectorized distance checks
    code_arr = np.array(words, dtype=np.uint32)
    
    # Generate all words with exactly 6 ones (distance 6 from zero)
    # C(17,6) = 12376 candidates
    candidates = []
    from itertools import combinations
    
    positions = list(range(17))
    for combo in combinations(positions, 6):
        w = 0
        for p in combo:
            w |= (1 << p)
        candidates.append(w)
    
    # Vectorized compatibility check
    # For each candidate, compute XOR with all code words, then bit_count
    # We'll process in batches for memory efficiency
    batch_size = 1024
    added = []
    candidates_arr = np.array(candidates, dtype=np.uint32)
    
    for start in range(0, len(candidates_arr), batch_size):
        if time.time() > deadline - 10.0:
            break
        
        batch = candidates_arr[start:start + batch_size]
        # Compute distances: shape (batch_size, n_words)
        # XOR: (batch_size, 1) ^ (1, n_words) -> (batch_size, n_words)
        xor_mat = batch[:, np.newaxis] ^ code_arr[np.newaxis, :]
        # Count bits using lookup or popcount
        # Use numpy: sum of bits
        # For uint32, we can use: (xor_mat & 1) + ((xor_mat >> 1) & 1) + ...
        # More efficiently: use a lookup table or bit manipulation
        
        # Efficient popcount for uint32 array using bitwise operations
        def popcount_uint32(arr):
            """Popcount for a numpy array of uint32 values."""
            arr = arr.copy()
            arr = arr - ((arr >> 1) & 0x55555555)
            arr = (arr & 0x33333333) + ((arr >> 2) & 0x33333333)
            arr = (arr + (arr >> 4)) & 0x0F0F0F0F
            return ((arr * 0x01010101) >> 24) & 0x7F
        
        min_dists = np.min(popcount_uint32(xor_mat), axis=1)
        
        # Find compatible candidates (min distance >= 6)
        compatible_mask = min_dists >= 6
        compatible_indices = np.where(compatible_mask)[0]
        
        for idx in compatible_indices:
            w = int(batch[idx])
            # Check compatibility with already-added words
            is_compatible = True
            for aw in added:
                if (w ^ aw).bit_count() < 6:
                    is_compatible = False
                    break
