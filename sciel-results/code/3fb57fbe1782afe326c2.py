import time
import collections
import math

def construct(k, g):
    """
    Constructs a k-regular graph with girth at least g.
    Strategy: Try GP graphs first (smaller n), fall back to LUW construction.
    """
    start_time = time.monotonic()
    deadline = start_time + 115.0  # 5s safety margin

    def time_left():
        return deadline - time.monotonic()

    # Try GP graphs first
    if k == 3 and g == 16:
        result = _try_gp_graphs(3, 16, time_left)
        if result is not None:
            return result

    # Fallback: LUW construction
    return _luw_construct(k, g, time_left)


def _try_gp_graphs(k, g, time_left):
    """
    Search for GP graphs G(n, a) with 2n vertices, girth >= g.
    GP graph: vertices (0,i), (1,i) for i in Z_n.
    Edges: (0,i)-(0,i+1), (1,i)-(1,i+a mod n), (0,i)-(1,i).
    """
    # For girth g, we need n large enough.
    # The girth of G(n,a) relates to the order of a mod n and related quantities.
    # A cycle of length 2m exists if a^j ≡ 1 or a^j ≡ -1 (mod n) for j < m,
    # or if a^j ≡ ±1 with certain conditions.
    
    # For girth >= g, we need:
    # - No cycle of length < g
    # For GP graphs, cycles come from relations in the group generated by a mod n
    
    # Lower bound on n: need n >= g (roughly), but actually need much more.
    # The girth is at least 2 * (smallest j such that a^j ≡ ±1 mod n)
    # So we need smallest j with a^j ≡ ±1 mod n to be >= g/2
    
    # Also need: for the "vertical" edges, no short cycles.
    # A cycle going up at position i, along top for some steps, down, along bottom, up...
    
    # Let's just search n from a reasonable lower bound upward.
    # Moore bound for (3,16): let's use a practical lower bound.
    # n must be at least g/2 = 8, but realistically much larger.
    
    # For k=3, g=16: try n from 100 upward
    # Total vertices = 2n
    
    min_n = max(g, 50)
    max_n = 600  # 2*600 = 1200 vertices, well below LUW's 13122
    
    for n in range(min_n, max_n + 1):
        if time_left() < 5.0:
            break
        
        for a in range(2, n):
            if time_left() < 3.0:
                break
            
            # Quick filter: check if a has sufficient order mod n
            # We need no short cycles. The key condition is:
            # For all 1 <= j < g/2, a^j mod n != 1 and a^j mod n != n-1
            # This prevents cycles of length 2j and 2j+1 (roughly)
            
            valid = True
            val = a % n
            for j in range(1, g // 2):
                val = (val * a) % n
                if val == 1 or val == n - 1:
                    valid = False
                    break
            
            if not valid:
                continue
            
            # Additional filter: check gcd conditions
            # For the graph to be connected and have good girth,
            # we need gcd(a, n) = 1 (so a generates a proper subgroup)
            if math.gcd(a, n) != 1:
                continue
            
            # Construct the graph and verify girth
            total_v = 2 * n
            edges = []
            # Top cycle: (0, i) - (0, i+1 mod n)
            for i in range(n):
                edges.append((i, (i + 1) % n))
            # Bottom cycle: (1, i) - (1, i+a mod n)
            for i in range(n):
                edges.append((n + i, n + (i + a) % n))
            # Vertical edges: (0, i) - (1, i)
            for i in range(n):
                edges.append((i, n + i))
            
            # Verify girth
            if _check_girth(total_v, edges, g, time_left):
                return total_v, edges
    
    return None


def _check_girth(n, edges, min_girth, time_left):
    """
    Check if graph has girth >= min_girth using BFS from each vertex.
    Returns True if girth >= min_girth.
    """
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    
    # BFS from each vertex, looking for back edges
    # If we find a back edge giving cycle < min_girth, return False
    
    max_depth = min_girth // 2
    
    for start in range(n):
        if time_left() < 2.0:
            return False  # Can't verify, assume fail
        
        dist = [-1] * n
        parent = [-1] * n
        dist[start] = 0
        queue = collections.deque([start])
        
        while queue:
            u = queue.popleft()
            if dist[u] >= max_depth:
                continue
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    parent[v] = u
                    queue.append(v)
                elif v != parent[u]:
                    cycle_len = dist[u] + dist[v] + 1
                    if cycle_len < min_girth:
                        return False
    
    return True


def _luw_construct(k, g, time_left):
    """
    Lazebnik-Ustimenko-Woldar construction CD(d, q) with q=k.
    Girth of CD(d, q) for odd q is 2d + 2.
    """
    q = k
    # Need girth >= g: 2d + 2 >= g => d >= (g-2)/2
    min_d = (g - 2 + 1) // 2  # ceiling
    
    # Try smallest d first
    for d in range(min_d, min_d + 3):
        if time_left() < 10.0:
            break
        
        try:
            n, edges = _luw_build(q, d, time_left)
            return n, edges
        except Exception:
            continue
    
    # Last resort
    n, edges = _luw_build(q, min_d, time_left)
    return n, edges


def _luw_build(q, d, time_left):
    """
    Build LUW graph CD(d, q).
    """
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add = lambda x, y: x ^ y
        sub = lambda x, y: x ^ y
        mul = lambda x, y: table[x][y]
    else:
        add = lambda x, y: (x + y) % q
        sub = lambda x, y: (x - y) % q
        mul = lambda x, y: x * y % q
    
    # LUW rule
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r = (c - 5) % 4
        c0 = c - r
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                if side == 0:
                    y[c] = add(x[c], mul(y[a], x[b]))
                else:
                    y[c] = sub(x[c], mul(x[a], y[b]))
            yield (1 - side, tuple(y))

    start = (0, (None,) + (0,) * d)
    index = {start: 0}
    order = [start]
    edges = []
    
    for vertex in order:
        if time_left() < 5.0:
            break
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    
    return len(order), edges


if __name__ == "__main__":
    n, edges = construct(3, 16)
    print(f"Constructed graph with {n} vertices, {len(edges)} edges.")
