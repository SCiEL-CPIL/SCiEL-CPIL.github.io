import time
import random

N = 256

def construct():
    start_time = time.time()
    time_limit = 28.0  # Leave 2s margin for the 30s limit
    
    best_set = None
    best_size = float('inf')
    
    # Helper to check if adding x to A (with sums S) is valid
    # Returns True if valid, and the new sums if valid
    def check_validity(x, A, S):
        # Sums to check: x + a for a in A, and 2*x
        # If any is in S, invalid.
        # Also, x + a1 == x + a2 implies a1 == a2, so distinctness among new sums is guaranteed if A is Sidon.
        # We just need to check intersection with S.
        for a in A:
            s = x + a
            if s in S:
                return False
        if 2 * x in S:
            return False
        return True

    def get_new_sums(x, A):
        return [x + a for a in A] + [2 * x]

    # Greedy step: Pick candidate that blocks the most others
    def greedy_step(A, S, candidates):
        if not candidates:
            return None, 0
        
        # For each candidate c, count how many other candidates d become invalid
        # d becomes invalid if adding c to A makes A U {c, d} non-Sidon.
        # This happens if:
        # 1. d + a in S for some a in A (d was already invalid, but d is in candidates so this is false)
        # 2. d + c in S (d+c collides with existing sum)
        # 3. d + c == 2*c => d==c (impossible as d!=c)
        # 4. d + c == c + a => d == a (d is in candidates, a in A, so d!=a)
        # 5. d + a1 == d + a2 (impossible)
        # 6. d + a1 == c + a2 => d + a1 - a2 = c.
        #    Basically, we need to check if (A U {c}) U {d} is Sidon.
        #    Since A is Sidon, we just need to check sums involving c and d.
        #    Sums to check for d given A U {c}:
        #    - d + a for a in A
        #    - d + c
        #    - 2*d
        #    These must not be in S, and must not be in {c+a for a in A} U {2c}.
        
        best_c = None
        max_blocks = -1
        
        # Optimization: Precompute something? 
        # For N=256, candidates size is at most 256.
        # Inner loop is O(|A| * |candidates|).
        # Total per step: O(|candidates|^2 * |A|).
        # |A| grows up to ~20. |candidates| shrinks.
        # This might be slow in Python if done naively.
        
        # Let's use a simpler heuristic: Pick randomly from top-k blocking candidates, or just random.
        # Actually, let's try to calculate blocking count efficiently.
        
        # For a fixed c, d is blocked if:
        # (d + c) in S  OR  (2*d) in S  OR  (d + c) in {c+a | a in A}  OR  (2*d) in {c+a | a in A}  OR  (d+a1) in S (already false)
        # Wait, d is in candidates, so d+a not in S and 2d not in S.
        # So d is blocked by c if:
        # (d + c) in S  OR  (d + c) in {c+a | a in A}  OR  (2*d) in {c+a | a in A}
        # (d+c) in {c+a | a in A}  <=>  d in A. But d not in A. So this is never true.
        # So d is blocked by c if:
        # 1. (d + c) in S
        # 2. (2*d) in {c + a | a in A}  <=>  2*d - c = a for some a in A.
        
        # Let's compute the set of sums generated by c: S_c = {c+a for a in A} U {2c}.
        # d is blocked if (d+c) in S OR (2d) in S_c.
        
        # Precompute S as a set for O(1) lookup.
        # For each c, compute S_c.
        # For each d != c, check if (d+c) in S or (2d) in S_c.
        
        # To speed up, we can iterate d and check.
        
        scores = {}
        for c in candidates:
            S_c = set([c + a for a in A] + [2 * c])
            blocks = 0
            for d in candidates:
                if d == c:
                    continue
                # Check if d is blocked by c
                # Condition 1: d + c in S
                # Condition 2: 2*d in S_c
                if (d + c) in S or (2 * d) in S_c:
                    blocks += 1
            scores[c] = blocks
            
        # Find max score
        max_score = max(scores.values())
        # Get all candidates with max score
        top_candidates = [c for c, s in scores.items() if s == max_score]
        
        # Randomly pick one from top candidates to add diversity
        return random.choice(top_candidates), max_score

    # Main loop with restarts
    while time.time() - start_time < time_limit:
        random.seed() # Re-seed each restart? Or just use global random.
        
        A = []
        S = set()
        candidates = list(range(1, N + 1))
        
        # Optional: Shuffle candidates initially?
        # The greedy step handles ordering.
        
        while candidates:
            c, _ = greedy_step(A, S, candidates)
            if c is None:
                break
            
            # Add c to A
            A.append(c)
            # Update S
            for a in A[:-1]: # A[:-1] is A before adding c? No, A has c now.
                # We added c. New sums are c + a for a in old A, and 2c.
                pass
            
            # Let's do it cleanly
            # A currently has c at the end.
            # Old A was A[:-1]
            new_sums = [c + a for a in A[:-1]] + [2 * c]
            S.update(new_sums)
            
            # Update candidates
            # Remove c
            candidates.remove(c)
            
            # Remove any d that is no longer valid
            # d is valid if check_validity(d, A, S) is True
            # We can filter candidates
            new_candidates = []
            for d in candidates:
                if check_validity(d, A, S):
                    new_candidates.append(d)
            candidates = new_candidates
            
        # End of greedy construction
        if len(A) < best_size:
            best_size = len(A)
            best_set = list(A)
            
            # If we found a very small set, we might stop early?
            # Theoretical lower bound for Sidon set in [N] is ~sqrt(N).
            # For N=256, sqrt(256)=16.
            # Maximal Sidon sets can be smaller?
            # Actually, minimal maximal Sidon sets are related to "small maximal sets".
            # If best_size <= 12, it's likely optimal or near optimal.
            if best_size <= 12:
                break

    if best_set is None:
        # Fallback: simple ascending greedy
        A = []
        S = set()
        for x in range(1, N + 1):
            if check_validity(x, A, S):
                A.append(x)
                S.update([x + a for a in A[:-1]] + [2 * x])
        best_set = A

    return best_set
