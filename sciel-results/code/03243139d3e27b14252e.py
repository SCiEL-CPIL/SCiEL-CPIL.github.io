import numpy as np
import time
from scipy.optimize import minimize

def _lj_energy_and_grad(pos):
    """
    Calculate Lennard-Jones energy and gradient.
    pos: (N, 3) array
    Returns: energy, grad (N, 3)
    """
    N = pos.shape[0]
    # Compute all pairwise differences
    # r[i, j] = pos[i] - pos[j]
    r = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    # Distance matrix
    dist = np.linalg.norm(r, axis=2)
    
    # Avoid division by zero (though shouldn't happen if distinct)
    # Set diagonal to 1 to avoid inf, mask later
    np.fill_diagonal(dist, 1.0)
    
    # r^-6 and r^-12
    r2 = dist**2
    r6 = r2**-3
    r12 = r6**2
    
    # Energy: 4 * sum(r^-12 - r^-6) over i < j
    # Sum over all i, j != i is 2 * sum i<j
    # So energy = 0.5 * 4 * sum_{i!=j} (r^-12 - r^-6)
    # Or just sum i<j.
    # Using full matrix:
    energy = 2.0 * np.sum(r12 - r6) # 4 * 0.5 * sum_{i!=j}
    # Wait, sum_{i!=j} counts each pair twice.
    # E = sum_{i<j} 4(r^-12 - r^-6)
    # sum_{i!=j} (r^-12 - r^-6) = 2 * sum_{i<j} (r^-12 - r^-6)
    # So E = 2 * sum_{i!=j} (r^-12 - r^-6)
    
    # Gradient
    # grad_i = sum_{j!=i} 24 * (r^-8 - 2*r^-14) * r_vec_ij
    # r_vec_ij = pos[i] - pos[j]
    # r^-8 = r^-6 * r^-2 = r6 * r2^-1
    # r^-14 = r^-12 * r^-2 = r12 * r2^-1
    
    r8 = r6 / r2
    r14 = r12 / r2
    
    # Coefficient for each pair (i, j)
    # coeff_ij = 24 * (r^-8 - 2*r^-14)
    coeff = 24.0 * (r8 - 2.0 * r14)
    
    # Zero out diagonal
    np.fill_diagonal(coeff, 0.0)
    
    # grad[i] = sum_j coeff[i, j] * r[i, j]
    # r is (N, N, 3)
    # coeff is (N, N)
    # We need to sum over j for each i.
    # coeff[:, :, np.newaxis] * r
    forces = np.sum(coeff[:, :, np.newaxis] * r, axis=1)
    
    # This forces array is the gradient of Energy w.r.t pos
    # Note: The sign.
    # We derived grad_i = sum_j 24(r^-8 - 2r^-14) r_vec_ij
    # This matches forces.
    
    return energy, forces

def _make_fcc_truncated_octahedron():
    """
    Generate the 38 atoms of the FCC truncated octahedron.
    """
    # FCC basis vectors (scaled by 0.5 for simplicity, we will scale later)
    # Standard FCC lattice points can be generated by:
    # (i, j, k) where i, j, k are integers and i+j+k is even.
    # This generates points with min distance sqrt(2) if spacing is 1?
    # Let's use the vector basis method.
    # b1 = (0.5, 0.5, 0)
    # b2 = (0.5, 0, 0.5)
    # b3 = (0, 0.5, 0.5)
    
    points = []
    # Generate a block of FCC points
    # i, j, k from -3 to 3
    for i in range(-3, 4):
        for j in range(-3, 4):
            for k in range(-3, 4):
                p = np.array([
                    0.5 * (i + j),
                    0.5 * (i + k),
                    0.5 * (j + k)
                ])
                points.append(p)
                
    points = np.array(points)
    
    # Sort by distance to origin
    dists = np.linalg.norm(points, axis=1)
    indices = np.argsort(dists)
    
    # Take the 38 closest
    fcc_points = points[indices[:38]]
    
    # Center the cluster
    fcc_points -= np.mean(fcc_points, axis=0)
    
    # Initial scale: The equilibrium distance for LJ is 2^(1/6) ~ 1.1225.
    # In the FCC lattice with basis 0.5, the nearest neighbor distance is sqrt(0.5^2 + 0.5^2) = sqrt(0.5) ~ 0.707.
    # We need to scale this up to 1.1225.
    # Scale factor s such that 0.707 * s = 1.1225 => s = 1.1225 / 0.707 ~ 1.587.
    # Alternatively, just initialize with s=1.5 and let optimizer find the best.
    # Or better, calculate the NN distance of the generated points and scale to 2^(1/6).
    
    # Find NN distance in the generated points (unscaled)
    # It should be sqrt(0.5)
    # Let's just use a scale factor of 1.5874 (which is 2^(1/6) / sqrt(0.5))
    scale = (2.0 ** (1.0/6.0)) / np.sqrt(0.5)
    
    return fcc_points * scale

def construct():
    start_time = time.time()
    deadline = start_time + 110.0 # Safety margin
    
    # 1. Generate initial geometry
    pos = _make_fcc_truncated_octahedron()
    
    # 2. Optimize
    # Use L-BFGS-B with analytic gradient
    # We don't really need bounds if we start close, but it's safe.
    # However, L-BFGS-B is slower than BFGS for unconstrained.
    # Since we are close to the minimum, BFGS or L-BFGS (unconstrained) is fine.
    # Let's use 'L-BFGS-B' just in case, or 'BFGS'.
    # 'BFGS' is good for small N.
    
    res = minimize(
        _lj_energy_and_grad, 
        pos, 
        method='BFGS', 
        jac=True, # Returns (energy, grad)
        options={'gtol': 1e-10, 'maxiter': 1000, 'disp': False}
    )
    
    if time.time() > deadline:
        return pos # Return initial if timeout (unlikely)
        
    if res.success:
        pos = res.x
    else:
        # Try L-BFGS-B if BFGS fails
        res = minimize(
            _lj_energy_and_grad, 
            pos, 
            method='L-BFGS-B', 
            jac=True,
            options={'gtol': 1e-10, 'maxiter': 1000, 'disp': False}
        )
        if res.success:
            pos = res.x

    # Final polish with very tight tolerance
    if time.time() < deadline - 5.0:
        res = minimize(
            _lj_energy_and_grad, 
            pos, 
            method='L-BFGS-B', 
            jac=True,
            options={'gtol': 1e-12, 'maxiter': 100, 'disp': False}
        )
        if res.success:
            pos = res.x

    return pos
