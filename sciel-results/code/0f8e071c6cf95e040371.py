import time
import random
import numpy as np

def _build_gf49():
    """Build GF(49) arithmetic using polynomial x^2 + x + 1 over GF(7)."""
    def gf7_add(a, b):
        return (a + b) % 7
    def gf7_sub(a, b):
        return (a - b) % 7
    def gf7_mul(a, b):
        return (a * b) % 7
    def gf49_add(a, b):
        return (gf7_add(a[0], b[0]), gf7_add(a[1], b[1]))
    def gf49_sub(a, b):
        return (gf7_sub(a[0], b[0]), gf7_sub(a[1], b[1]))
    def gf49_mul(a, b):
        a0, a1 = a
        b0, b1 = b
        # (a0 + a1*x)(b0 + b1*x) = a0b0 + (a0b1 + a1b0)x + a1b1*x^2
        # x^2 = -x - 1 = 6x + 6 in GF(7)
        c0 = gf7_add(gf7_mul(a0, b0), gf7_mul(a1, b1, 6))
        c1 = gf7_add(gf7_mul(a0, b1), gf7_mul(a1, b0))
        return (c0, c1)
    def gf49_inv(a):
        a0, a1 = a
        for b0 in range(7):
            for b1 in range(7):
                if (b0, b1) == (0, 0):
                    continue
                prod = gf49_mul((a0, a1), (b0, b1))
                if prod == (1, 0):
                    return (b0, b1)
        return (0, 0)
    
    # Find primitive element
    elem = (0, 1)
    elements = [(1, 0)]
    cur = (1, 0)
    for _ in range(48):
        cur = gf49_mul(cur, elem)
        elements.append(cur)
    
    if len(set(elements)) != 48:
        for test in [(1, 1), (1, 2), (2, 1), (2, 2), (3, 1), (1, 3)]:
            elements = [(1, 0)]
            cur = (1, 0)
            for _ in range(48):
                cur = gf49_mul(cur, test)
                elements.append(cur)
            if len(set(elements)) == 48:
                elem = test
                break
    
    # elements[0] is 1, elements[1] is elem, ...
    # We need the list of all non-zero elements
    non_zero_elements = elements
    
    return non_zero_elements, gf49_add, gf49_sub, gf49_mul, gf49_inv

def _gf49_construction():
    """Construct a 49-vertex coloring using GF(49) with difference-based coloring."""
    non_zero_elements, gf49_add, gf49_sub, gf49_mul, gf49_inv = _build_gf49()
    
    # Map element to index
    elem_to_idx = {e: i for i, e in enumerate(non_zero_elements)}
    
    # Subgroup H of order 12: generated by elem^4
    gen_H = non_zero_elements[4] # elem^4
    H = set()
    cur = (1, 0)
    for _ in range(12):
        H.add(cur)
        cur = gf49_mul(cur, gen_H)
        
    # Cosets
    cosets = [set() for _ in range(4)]
    # C0 = H
    cosets[0] = H
    # C1 = elem * H
    # C2 = elem^2 * H
    # C3 = elem^3 * H
    elem_pow = (1,0)
    for c in range(1, 4):
        elem_pow = gf49_mul(elem_pow, non_zero_elements[1]) # multiply by elem
        for h in H:
            cosets[c].add(gf49_mul(elem_pow, h))
            
    # Check if cosets are sum-free
    # A set S is sum-free if for all a, b in S, a+b not in S
    # Note: a+b=0 is not in S (since S contains non-zero elements).
    valid = True
    for c in range(4):
        S = cosets[c]
        S_list = list(S)
        # Precompute sums
        sums = set()
        for i in range(len(S_list)):
            for j in range(i, len(S_list)): # a+b = b+a
                s = gf49_add(S_list[i], S_list[j])
                if s != (0,0):
                    sums.add(s)
        # Check intersection
        if S & sums:
            valid = False
            break
            
    if not valid:
        # Fallback: try a different primitive element or different subgroup?
        # For now, return None to trigger fallback
        return None

    # Build coloring
    n = 49
    # Vertex 0 is (0,0)
    # Vertices 1..48 are non_zero_elements
    # Map vertex index to element
    vertex_elem = [(0,0)] + non_zero_elements
    
    colors = []
    for i in range(n):
        for j in range(i + 1, n):
            ui = vertex_elem[i]
            uj = vertex_elem[j]
            diff = gf49_sub(ui, uj)
            if diff == (0,0):
                # Should not happen for i != j
                c = 0
            else:
                # Find which coset diff belongs to
                found = False
                for c in range(4):
                    if diff in cosets[c]:
                        colors.append((i, j, c))
                        found = True
                        break
                if not found:
                    # Should not happen
                    colors.append((i, j, 0))
    return colors

def _build_adj_matrices(colors, n):
    """Build adjacency matrices for fast triangle checking."""
    adj = [np.zeros((n, n), dtype=bool) for _ in range(4)]
    for i, j, c in colors:
        adj[c][i, j] = True
        adj[c][j, i] = True
    return adj

def _is_triangle_free_numpy(adj, n):
    """Check triangle-freeness using numpy matrix operations."""
    for c in range(4):
        A = adj[c]
        # Triangles are triples (i,j,k) where A[i,j], A[j,k], A[k,i] are all 1.
        # This is equivalent to checking if A has any triangle.
        # A @ A.T gives number of common neighbors.
        # If A[i,j] is 1, and (A @ A.T)[i,j] > 0, then there is a common neighbor k.
        # This forms a triangle i-j-k-i.
        common = A @ A.T
        # We need to check if there is any edge (i,j) such that common[i,j] > 0.
        # Since A is symmetric and 0-diagonal, A[i,j] is 1 only for edges.
        # So we just check if any element of common is > 0 where A is 1.
        if np.any(common * A):
            return False
    return True

def _extend_vertex(adj, n, deadline):
    """Try to extend the coloring to n+1 vertices using simulated annealing."""
    new_n = n + 1
    best_cost = float('inf')
    best_assign = None
    
    # Precompute for each vertex u and color c, the number of neighbors in each color
    # nbr_count[u, c] = number of vertices v such that adj[c][u,v] is True
    nbr_count = np.zeros((n, 4), dtype=np.int32)
    for c in range(4):
        nbr_count[:, c] = adj[c].sum(axis=1).astype(np.int32)
    
    max_trials = 80
    for trial in range(max_trials):
        if time.time() > deadline - 5:
            break
        
        # Initialize with a greedy assignment: for each vertex, pick the color with fewest conflicts
        assign = np.zeros(n, dtype=np.int32)
        for u in range(n):
            best_c = 0
            best_conflicts = float('inf')
            for c in range(4):
                # Count conflicts if u is assigned color c
                # A conflict is a vertex v already assigned color c that is adjacent to u in color c
                # But since we're assigning greedily, we just use the precomputed count as a heuristic
                # Actually, let's just use random for simplicity in the first few trials
                pass
            assign[u] = best_c
        
        # Better initialization: use the average neighbor count as a guide
        # For each vertex, prefer the color where it has the fewest neighbors
        for u in range(n):
            counts = nbr_count[u, :]
            assign[u] = np.argmin(counts)
        
        total_cost = 0
        for c in range(4):
            mask = (assign == c)
            if np.sum(mask) > 1:
                sub = adj[c][np.ix_(mask, mask)]
                total_cost += np.sum(sub) // 2
        
        # Simulated annealing
        T = 10.0
        T_min = 0.1
        cooling = 0.995
        stuck = 0
        max_iter = 8000
        
        for it in range(max_iter):
            if time.time() > deadline - 5:
                break
            if total_cost == 0:
                best_cost = 0
                best_assign = assign.copy()
                break
            
            u = random.randint(0, n - 1)
            old_c = assign[u]
            new_c = random.randint(0, 3)
            if new_c == old_c:
                continue
            
            # Compute delta
            nbrs_old = np.sum(adj[old_c][u, :] & (assign == old_c))
            nbrs_new = np.sum(adj[new_c][u, :] & (assign == new_c))
            delta = nbrs_new - nbrs_old
            
            if delta <= 0 or random.random() < np.exp(-delta / T):
                assign[u] = new_c
                total_cost += delta
                stuck = 0
            else:
                stuck += 1
            
            T *= cooling
            if T < T_min:
                T = T_min
            
            if stuck > 200:
                # Restart with a new temperature or break
                if trial % 3 == 0:
                    break
                T = 10.0
                stuck = 0
        
        if total_cost < best_cost:
            best_cost = total_cost
            best_assign = assign.copy()
        if best_cost == 0:
            break
    
    if best_cost == 0 and best_assign is not None:
        new_adj = [np.zeros((new_n, new_n), dtype=bool) for _ in range(4)]
        for c in range(4):
            new_adj[c][:n, :n] = adj[c]
            for i in range(n):
                if best_assign[i] == c:
                    new_adj[c][i, new_n - 1] = True
                    new_adj[c][new_n - 1, i] = True
        return True, new_adj, best_assign
    else:
        return False, None, None

def _base32_colors():
    """Return the 32-vertex base coloring."""
    def _build_mul_table():
        log = {}
        x = 1
        log[1] = 0
        for e in range(15):
            x2 = 0
            for i in range(4):
                if (x >> i) & 1:
                    x2 ^= (1 << (i + 1))
            if x2 & 0b10000:
                x2 ^= 0b10011
            x = x2
            log[x] = e + 1
        return log
    log_table = _build_mul_table()
    colors = []
    for i in range(32):
        for j in range(i + 1, 32):
            if i // 16 == j // 16:
                ui = i % 16
                uj = j % 16
                c = log_table[ui ^ uj] % 3
            else:
                c = 3
            colors.append((i, j, c))
    return colors

def construct():
    deadline = time.time() + 110
    n = 32
    adj = None
    try:
        base_colors = _gf49_construction()
        if base_colors is not None:
            n = 49
            adj = _build_adj_matrices(base_colors, n)
            if not _is_triangle_free_numpy(adj, n):
                raise ValueError("GF49 construction has triangles")
        else:
            raise ValueError("GF49 construction failed")
    except Exception:
        base_colors = _base32_colors()
        n = 32
        adj = _build_adj_matrices(base_colors, n)
    
    while n < 50 and time.time() < deadline - 15:
        success, new_adj, _ = _extend_vertex(adj, n, deadline)
        if success:
            n += 1
            adj = new_adj
        else:
            break
    
    colors = []
    for i in range(n):
        for j in range(i + 1, n):
            for c in range(4):
                if adj[c][i, j]:
                    colors.append((i, j, c))
                    break
    out_colors = [c for _, _, c in colors]
    return {'n': n, 'colors': out_colors}
