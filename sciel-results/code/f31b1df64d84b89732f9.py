"""ODE integrator for the Lorenz system using DOP853 with matched tolerances."""
# EVOLVE-BLOCK-START
import numpy as np
import scipy.integrate

def integrate(f, t_span, y0):
    """
    Integrate the Lorenz system from t_span[0] to t_span[1] with initial condition y0.
    
    Args:
        f: The ODE function f(t, y) returning dy/dt.
        t_span: Tuple (t_start, t_end).
        y0: Initial state vector.
        
    Returns:
        The state vector at t_end.
    """
    t0, t1 = t_span
    y0 = np.asarray(y0, dtype=float)
    
    # Use DOP853 with the same tolerances as the reference solution.
    # This minimizes the relative error while keeping the number of function calls low
    # due to the high order and adaptive stepping of the method.
    # Setting max_step to infinity allows the integrator to take larger steps if accuracy permits.
    
    try:
        sol = scipy.integrate.solve_ivp(
            f, 
            t_span, 
            y0, 
            method='DOP853', 
            rtol=1e-11, 
            atol=1e-13,
            max_step=np.inf
        )
        
        if sol.success:
            y_end = sol.y[:, -1]
            if np.all(np.isfinite(y_end)):
                return y_end
    except Exception:
        pass

    # Fallback: if the above failed, try with default max_step
    try:
        sol = scipy.integrate.solve_ivp(
            f, 
            t_span, 
            y0, 
            method='DOP853', 
            rtol=1e-11, 
            atol=1e-13
        )
        
        if sol.success:
            y_end = sol.y[:, -1]
            if np.all(np.isfinite(y_end)):
                return y_end
    except Exception:
        pass

    # Last resort: Return initial condition
    return np.array(y0, dtype=float)
# EVOLVE-BLOCK-END
