"""Optimized quantum circuit parameters for Ising ground states using Simulated Annealing."""
# EVOLVE-BLOCK-START
import numpy as np
import time

_DEADLINE = 148.0
_START_TIME = time.time()

def _check_deadline(margin=3.0):
    return (time.time() - _START_TIME) < (_DEADLINE - margin)

def _build_hamiltonian(n, coupling, field):
    """
    Build H = -coupling*sum Z_i Z_{i+1} - field*sum X_i.
    Uses bit manipulation for efficiency in building the sparse structure 
    into a dense matrix (small n).
    """
    total_dim = 2 ** n
    H = np.zeros((total_dim, total_dim), dtype=complex)
    
    # ZZ terms: -coupling * Z_i Z_{i+1}
    # Z_i Z_{i+1} is diagonal. Eigenvalue is +1 if bits are same, -1 if different.
    # H_ii += -coupling * (-1)^(b_i + b_{i+1})
    for i in range(n - 1):
        for state in range(total_dim):
            b1 = (state >> i) & 1
            b2 = (state >> (i + 1)) & 1
            # If b1==b2, product is 1. If b1!=b2, product is -1.
            # zz_val = 1 if b1==b2 else -1
            # H[state, state] += -coupling * zz_val
            if b1 == b2:
                H[state, state] += -coupling
            else:
                H[state, state] += coupling

    # X terms: -field * X_i
    # X_i flips bit i. H[state, state^mask] += -field
    for i in range(n):
        mask = 1 << i
        for state in range(total_dim):
            partner = state ^ mask
            H[state, partner] += -field

    return H

def _get_ground_energy(H):
    eigvals = np.linalg.eigvalsh(H)
    return eigvals[0].real

def _circuit_energy(params, n, layers, H):
    """
    Calculate energy of the state generated by the circuit.
    Uses vectorized tensor operations for speed.
    params: shape (layers, n)
    """
    # State vector representation: shape (2, 2, ..., 2) with n dimensions
    # Index order: qubit 0 is the least significant bit (rightmost in standard notation, 
    # but in numpy array indexing, axis 0 corresponds to the first index).
    # We need to map bit i to the correct axis.
    # If we use standard basis |b_{n-1} ... b_0>, then b_0 is the LSB.
    # In a numpy array of shape (2,)*n, index [i_0, i_1, ..., i_{n-1}] corresponds to 
    # binary number sum(i_k * 2^k) if we treat i_0 as LSB? 
    # Actually, numpy flattening is C-order: last index changes fastest.
    # So index [0, 0, ..., 1] (last axis) is 1. This corresponds to bit 0 being 1.
    # So axis k corresponds to qubit k.
    
    state = np.ones((2,) * n, dtype=complex)
    # Start state |0>^n: all indices 0. 
    # np.ones creates a tensor where state[0,0,...,0]=1 and others 0? 
    # No, np.ones creates all 1s. We need a basis vector.
    state = np.zeros((2,) * n, dtype=complex)
    state[(0,) * n] = 1.0

    for layer in range(layers):
        # Apply Ry(theta) to every qubit
        for q in range(n):
            theta = params[layer, q]
            c = np.cos(theta / 2)
            s = np.sin(theta / 2)
            
            # Ry matrix: [[c, -s], [s, c]]
            # We need to apply this along axis q.
            # We can do this by reshaping and using einsum or manual slicing.
            # Manual slicing is often faster for small n.
            
            # Create a new state
            new_state = np.zeros_like(state)
            
            # For axis q, we have two slices: ...0... and ...1...
            # new_state[..., 0, ...] = c * state[..., 0, ...] - s * state[..., 1, ...]
            # new_state[..., 1, ...] = s * state[..., 0, ...] + c * state[..., 1, ...]
            
            # Construct index tuples
            idx0 = [slice(None)] * n
            idx1 = [slice(None)] * n
            idx0[q] = 0
            idx1[q] = 1
            
            # Get the two components
            comp0 = state[tuple(idx0)]
            comp1 = state[tuple(idx1)]
            
            new_state[tuple(idx0)] = c * comp0 - s * comp1
            new_state[tuple(idx1)] = s * comp0 + c * comp1
            
            state = new_state
            
        if layer < layers - 1:
            # Apply CZ on every adjacent pair (q, q+1) in ascending order
            for q in range(n - 1):
                # CZ: |11> -> -|11>
                # Only the component where both q and q+1 are 1 gets a -1.
                # We can just multiply that specific slice by -1.
                
                idx11 = [slice(None)] * n
                idx11[q] = 1
                idx11[q+1] = 1
                
                # In-place modification is safe here as we are just scaling one part
                state[tuple(idx11)] *= -1.0

    # Flatten state to vector for Hamiltonian multiplication
    # Ensure the flattening order matches the Hamiltonian construction.
    # H was built such that H[state, partner] where state is integer index.
    # Numpy C-order flatten: last axis is fastest changing.
    # If axis 0 is qubit 0 (LSB), then index [i_0, i_1, ..., i_{n-1}] 
    # corresponds to integer sum(i_k * 2^k).
    # This matches the bit-shifting logic in _build_hamiltonian where 
    # bit i is (state >> i) & 1.
    state_vec = state.flatten()
    
    # Energy = <psi| H |psi>
    H_state = H @ state_vec
    energy = np.vdot(state_vec, H_state).real
    return energy

def angles(n, coupling, field, layers):
    global _START_TIME
    _START_TIME = time.time()
    
    H = _build_hamiltonian(n, coupling, field)
    ground_energy = _get_ground_energy(H)
    
    # Objective: minimize (E_circuit - E_ground) / n
    # We can ignore /n for optimization as it's a constant scaling factor, 
    # but we must return params. The score is based on the mean gap.
    
    def objective(params):
        # params is flat array
        p = params.reshape(layers, n)
        e = _circuit_energy(p, n, layers, H)
        return (e - ground_energy)
        
    # Initialize parameters
    # Heuristic: Start with angles that might approximate the ground state.
    # For transverse field Ising, ground state is often close to product states 
    # aligned with the effective field.
    # Let's start with small random angles or zero.
    # Using random start for SA is better to avoid getting stuck in trivial local min.
    
    np.random.seed(42)
    current_params = np.random.uniform(-np.pi/4, np.pi/4, size=(layers, n))
    current_energy = objective(current_params.flatten())
    
    best_params = current_params.copy()
    best_energy = current_energy
    
    # Simulated Annealing Parameters
    T = 0.1 # Initial temperature
    cooling_rate = 0.9995 # Slow cooling to explore more
    min_T = 1e-5
    
    # Pre-calculate some things if possible? No, state evolution is stateful.
    
    while _check_deadline(margin=2.0):
        # Generate neighbor
        # Perturb one random parameter
        l = np.random.randint(layers)
        q = np.random.randint(n)
        
        new_params = current_params.copy()
        # Step size proportional to temperature? Or fixed?
        # Fixed step is safer for stability, T controls acceptance.
        step = 0.1 
        new_params[l, q] += np.random.uniform(-step, step)
        
        # Wrap angles to [-pi, pi] to maintain periodicity
        new_params[l, q] = (new_params[l, q] + np.pi) % (2 * np.pi) - np.pi
        
        new_energy = objective(new_params.flatten())
        
        # Acceptance criterion
        delta_e = new_energy - current_energy
        if delta_e < 0 or np.random.rand() < np.exp(-delta_e / T):
            current_params = new_params
            current_energy = new_energy
            
            if current_energy < best_energy:
                best_energy = current_energy
                best_params = current_params.copy()
        
        # Cool down
        T *= cooling_rate
        if T < min_T:
            T = min_T
            # Optional: Restart with slightly higher T if stuck? 
            # For now, just keep going at min T (essentially local search).
            # To avoid infinite loop at min T, we can break if no improvement for long.
            # But deadline guard handles termination.

    # Final polish with L-BFGS-B from the best SA result
    if _check_deadline(margin=5.0):
        from scipy.optimize import minimize
        try:
            result = minimize(
                objective,
                best_params.flatten(),
                method='L-BFGS-B',
                options={'maxiter': 100, 'maxfun': 200, 'ftol': 1e-12, 'gtol': 1e-10}
            )
            if result.fun < best_energy:
                best_energy = result.fun
                best_params = result.x.reshape(layers, n)
        except Exception:
            pass
            
    # Ensure finite values
    best_params = np.nan_to_num(best_params, nan=0.0, posinf=0.0, neginf=0.0)
    
    return best_params
