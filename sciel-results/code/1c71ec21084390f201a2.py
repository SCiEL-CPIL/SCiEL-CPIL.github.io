import numpy as np

DIMENSIONS = [2, 2, 3]

def construct():
    n, m, p = DIMENSIONS
    rank = 11
    
    U = np.zeros((n * m, rank), dtype=int)
    V = np.zeros((m * p, rank), dtype=int)
    W = np.zeros((p * n, rank), dtype=int)
    
    # Strassen terms for k=0,1 (cols 0-6)
    # U indices: 00, 01, 10, 11
    # V indices: 00, 01, 02, 10, 11, 12
    # W indices: 00, 10, 01, 11, 20, 21 (k*n+i)
    
    # Col 0: P0 = (A00+A11)(B00+B11)
    U[:, 0] = [1, 0, 0, 1]
    V[:, 0] = [1, 0, 0, 1, 0, 0]
    W[:, 0] = [1, 1, 1, 1, 0, 0]
    
    # Col 1: P1 = (A10+A11)B00
    U[:, 1] = [0, 0, 1, 1]
    V[:, 1] = [1, 0, 0, 0, 0, 0]
    W[:, 1] = [0, 0, 1, -1, 0, 0]
    
    # Col 2: P2 = A00(B01-B11)
    U[:, 2] = [1, 0, 0, 0]
    V[:, 2] = [0, 1, 0, -1, 0, 0]
    W[:, 2] = [0, 1, 0, 1, 0, 0]
    
    # Col 3: P3 = A11(B10-B00)
    U[:, 3] = [0, 0, 0, 1]
    V[:, 3] = [0, 0, 0, 1, -1, 0]
    W[:, 3] = [1, 0, 1, 0, 0, 0]
    
    # Col 4: P4 = (A00+A01)B11
    U[:, 4] = [1, 1, 0, 0]
    V[:, 4] = [0, 0, 0, 0, 1, 0]
    W[:, 4] = [-1, 1, 0, 0, 0, 0]
    
    # Col 5: P5 = (A10-A00)(B00+B01)
    U[:, 5] = [0, 0, 1, -1]
    V[:, 5] = [1, 1, 0, 0, 0, 0]
    W[:, 5] = [0, 0, 0, 1, 0, 0]
    
    # Col 6: P6 = (A01-A11)(B10+B11)
    U[:, 6] = [0, 1, -1, 0]
    V[:, 6] = [0, 0, 0, 1, 1, 0]
    W[:, 6] = [1, 0, 0, 0, 0, 0]
    
    # Standard terms for k=2 (cols 7-10)
    # Col 7: A00 B02
    U[:, 7] = [1, 0, 0, 0]
    V[:, 7] = [0, 0, 1, 0, 0, 0]
    W[:, 7] = [0, 0, 0, 0, 1, 0]
    
    # Col 8: A01 B12
    U[:, 8] = [0, 1, 0, 0]
    V[:, 8] = [0, 0, 0, 0, 0, 1]
    W[:, 8] = [0, 0, 0, 0, 1, 0]
    
    # Col 9: A10 B02
    U[:, 9] = [0, 0, 1, 0]
    V[:, 9] = [0, 0, 1, 0, 0, 0]
    W[:, 9] = [0, 0, 0, 0, 0, 1]
    
    # Col 10: A11 B12
    U[:, 10] = [0, 0, 0, 1]
    V[:, 10] = [0, 0, 0, 0, 0, 1]
    W[:, 10] = [0, 0, 0, 0, 0, 1]
    
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
