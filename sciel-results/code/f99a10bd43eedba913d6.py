def _is_latin(sq):
    n = len(sq)
    for i in range(n):
        if sorted(sq[i]) != list(range(n)):
            return False
    for j in range(n):
        if sorted(sq[i][j] for i in range(n)) != list(range(n)):
            return False
    return True

def _orthogonal(a, b):
    n = len(a)
    seen = set()
    for i in range(n):
        for j in range(n):
            p = (a[i][j], b[i][j])
            if p in seen:
                return False
            seen.add(p)
    return True

def _pairwise_orthogonal(squares):
    for i in range(len(squares)):
        for j in range(i + 1, len(squares)):
            if not _orthogonal(squares[i], squares[j]):
                return False
    return True

