import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 85.0  # Safety margin before 90s limit
    n = 256
    max_per_set = 64

    def get_initial_diffs(S):
        """Get set of nonzero differences for set S."""
        diffs = set()
        for i in range(len(S)):
            for j in range(len(S)):
                if i != j:
                    diffs.add(S[i] - S[j])
        return diffs

    def get_initial_sums(S):
        """Get set of pair sums (including a+a) for set S."""
        sums = set()
        for i in range(len(S)):
            for j in range(i, len(S)):
                sums.add(S[i] + S[j])
        return sums

    def can_add(x, S, S_sums, S_diffs, other_diffs):
        """
        Check if x can be added to S maintaining Sidon property and disjoint diffs.
        S: list of elements
        S_sums: set of current pair sums in S
        S_diffs: set of current nonzero differences in S
        other_diffs: set of nonzero differences in the other set
        """
        # 1. Check Sidon property: 
        # New sums involving x: x+x and x+a for all a in S.
        # These must not be in S_sums.
        # Also, we don't need to check if x+x == a+b for a,b in S if that sum is already in S_sums? 
        # Yes, if x+x is in S_sums, it means some a+b = x+x. Since a+b is unique for Sidon, 
        # adding x would create a collision for sum x+x (now generated by x+x and a+b).
        
        if 2 * x in S_sums:
            return False
            
        for a in S:
            if (x + a) in S_sums:
                return False

        # 2. Check Disjoint Differences:
        # New differences involving x: x-a and a-x for all a in S.
        # These must not be in other_diffs.
        for a in S:
            if (x - a) in other_diffs:
                return False
            if (a - x) in other_diffs:
                return False
                
        return True

    def greedy_construct(order, max_time):
        """
        Greedy construction given a specific element order.
        Returns [A, B]
        """
        sets = [[], []]
        sets_sums = [set(), set()]
        sets_diffs = [set(), set()]

        for x in order:
            if time.time() > max_time:
                break
            
            best_side = -1
            # Try to add to side 0 first, then side 1
            for side in (0, 1):
                if len(sets[side]) >= max_per_set:
                    continue
                if can_add(x, sets[side], sets_sums[side], sets_diffs[side], sets_diffs[1 - side]):
                    best_side = side
                    break
            
            if best_side >= 0:
                S = sets[best_side]
                S_sums = sets_sums[best_side]
                S_diffs = sets_diffs[best_side]
                
                # Update state
                for a in S:
                    S_sums.add(x + a)
                    S_diffs.add(x - a)
                    S_diffs.add(a - x)
                S_sums.add(2 * x)
                S.append(x)

        return sets

    def local_search(sets, max_time):
        """
        Perform local search to improve the sets.
        Returns [A, B]
        """
        sets = [list(sets[0]), list(sets[1])]
        sets_sums = [get_initial_sums(sets[0]), get_initial_sums(sets[1])]
        sets_diffs = [get_initial_diffs(sets[0]), get_initial_diffs(sets[1])]
        
        improved = True
        while improved and time.time() < max_time:
            improved = False
            
            # 1. Try adding any missing element
            all_elements = set(range(1, n + 1))
            in_sets = set(sets[0]) | set(sets[1])
            candidates = list(all_elements - in_sets)
            random.shuffle(candidates)
            
            for x in candidates:
                if time.time() > max_time:
                    break
                for side in (0, 1):
                    if len(sets[side]) >= max_per_set:
                        continue
                    if can_add(x, sets[side], sets_sums[side], sets_diffs[side], sets_diffs[1 - side]):
                        S = sets[side]
                        S_sums = sets_sums[side]
                        S_diffs = sets_diffs[side]
                        
                        # Add x
                        for a in S:
                            S_sums.add(x + a)
                            S_diffs.add(x - a)
                            S_diffs.add(a - x)
                        S_sums.add(2 * x)
                        S.append(x)
                        improved = True
                        break
                if improved:
                    break
            
            # 2. Try swaps/removals to allow further growth
            # Strategy: Remove an element from side 0, try to add 2 elements. Or remove from side 0, add 1 to side 1 if blocked?
            # Simpler: Try removing an element from side i, then try to add any candidate to side i or 1-i.
            # If we remove x from side i, we free up sums and diffs.
            
            for side in (0, 1):
                if time.time() > max_time:
                    break
                S = sets[side]
                if not S:
                    continue
                
                # Try removing each element
                for i in range(len(S)):
                    if time.time() > max_time:
                        break
                    x_to_remove = S[i]
                    
                    # Create a temporary copy of the set without x_to_remove
                    temp_S = S[:i] + S[i+1:]
                    temp_sums = get_initial_sums(temp_S)
                    temp_diffs = get_initial_diffs(temp_S)
                    
                    # Check if we can add more elements to temp_S
                    # We want to see if removing x_to_remove allows us to add >= 1 new element
                    # that wasn't addable before, or if it allows the other set to grow.
                    
                    # Let's try to add any candidate to temp_S
                    added_any = False
                    all_elements = set(range(1, n + 1))
                    in_temp = set(temp_S) | set(sets[1 - side])
                    candidates = list(all_elements - in_temp)
                    random.shuffle(candidates)
                    
                    for x in candidates:
                        if time.time() > max_time:
                            break
                        # Check if x can be added to temp_S
                        if can_add(x, temp_S, temp_sums, temp_diffs, sets_diffs[1 - side]):
                            # If we can add x, and x != x_to_remove, it's a swap (size stays same)
                            # If we can add x, and x was not in S, it's an improvement (size increases by 1)
                            # Actually, since we removed x_to_remove, size is len(S)-1.
                            # If we add x, size becomes len(S). No net gain unless we add MORE than 1.
                            # But maybe removing x_to_remove unblocks the OTHER set?
                            # Let's just try to add to temp_S. If we add x, we replace x_to_remove with x.
                            # This is a swap. Does it help? Maybe x has "better" properties?
                            # For now, let's focus on pure additions first.
                            # If we can add x to temp_S, we can just do the swap if it helps future additions.
                            # For simplicity, we'll just accept the swap if it leads to a valid state.
                            # But to increase size, we need to add MORE elements.
                            
                            # Let's try to add as many as possible to temp_S
                            new_S = list(temp_S)
                            new_sums = set(temp_sums)
                            new_diffs = set(temp_diffs)
                            
                            # Re-shuffle candidates excluding those in new_S and other set
                            in_new = set(new_S) | set(sets[1 - side])
                            cands2 = list(all_elements - in_new)
                            random.shuffle(cands2)
                            
                            count_added = 0
                            for y in cands2:
                                if time.time() > max_time:
                                    break
                                if can_add(y, new_S, new_sums, new_diffs, sets_diffs[1 - side]):
                                    # Add y
                                    for a in new_S:
                                        new_sums.add(y + a)
                                        new_diffs.add(y - a)
                                        new_diffs.add(a - y)
                                    new_sums.add(2 * y)
                                    new_S.append(y)
                                    count_added += 1
                                    
                            # If we added more elements than we removed (1), it's an improvement
                            if count_added > 1:
                                sets[side] = new_S
                                sets_sums[side] = new_sums
                                sets_diffs[side] = new_diffs
                                improved = True
                                break
                            elif count_added == 1 and new_S[0] != x_to_remove: # Heuristic: maybe swap helps?
                                # We removed 1, added 1. Size is same.
                                # This might not help immediately, but could unblock the other set?
                                # Let's skip pure swaps for now to save time, focus on size increase.
                                pass
                            
                            break # Only try one candidate for this removal? Or break out of candidates loop?
                            # Actually, we should check if ANY candidate allows >1 additions.
                            # The loop above breaks after the first candidate that adds anything?
                            # No, the inner loop `for y in cands2` runs to completion (or time limit).
                            # So `count_added` is the max we can add after removing x_to_remove.
                            # If count_added > 1, we improved.
                            # If count_added == 1, we swapped.
                            # If count_added == 0, we lost an element.
                            
                            # We break the `for x in candidates` loop because we found a potential improvement (or not).
                            # If we didn't improve, we should try the next element to remove.
                            if not improved:
                                continue
                            else:
                                break # Break out of `for x in candidates`
                                
                    if improved:
                        break
                if improved:
                    break

        return sets

    def validate(sets):
        """Validate that both sets are Sidon and their nonzero differences are disjoint."""
        if not sets[0] or not sets[1]:
            return False
        if len(sets[0]) > max_per_set or len(sets[1]) > max_per_set:
            return False

        # Check Sidon property for each set
        for S in sets:
            sums = set()
            for i in range(len(S)):
                for j in range(i, len(S)):
                    s = S[i] + S[j]
                    if s in sums:
                        return False
                    sums.add(s)

        # Check disjoint nonzero differences
        diffs0 = get_initial_diffs(sets[0])
        diffs1 = get_initial_diffs(sets[1])
        if diffs0 & diffs1:
            return False

        return True

    # Strategy: Try multiple orderings and keep the best valid result
    best_sets = [[], []]
    best_size = 0

    random.seed(42)

    # Try several different orderings
    orderings = []
    # Natural order
    orderings.append(list(range(1, n + 1)))
    # Reverse order
    orderings.append(list(range(n, 0, -1)))
    # Random orderings
    for _ in range(10):
        order = list(range(1, n + 1))
        random.shuffle(order)
        orderings.append(order)
    # Weighted orderings
    for _ in range(5):
        order = list(range(1, n + 1))
        order.sort(key=lambda x: x * random.random())
        orderings.append(order)
    for _ in range(5):
        order = list(range(1, n + 1))
        order.sort(key=lambda x: (n + 1 - x) * random.random())
        orderings.append(order)

    for idx, order in enumerate(orderings):
        if time.time() > deadline - 10:
            break
        
        # Allocate time for greedy and local search
        greedy_deadline = deadline - 5 - (len(orderings) - idx) * 0.5 # Rough allocation
        if greedy_deadline < start_time + 5:
            greedy_deadline = start_time + 5
            
        sets = greedy_construct(order, greedy_deadline)
        
        if validate(sets):
            ls_deadline = deadline - 5
            sets = local_search(sets, ls_deadline)
            if validate(sets):
                size = len(sets[0]) + len(sets[1])
                if size > best_size:
                    best_size = size
                    best_sets = [list(sets[0]), list(sets[1])]

    # If we didn't find a good solution, use a simple fallback
    if not best_sets[0] or not best_sets[1]:
        sets = greedy_construct(list(range(1, n + 1)), deadline - 1)
        if validate(sets):
            best_sets = [list(sets[0]), list(sets[1])]
        else:
            best_sets = [[1], [2]]

    return best_sets
