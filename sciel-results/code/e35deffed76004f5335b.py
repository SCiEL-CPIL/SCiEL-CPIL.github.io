"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import time
import random
from math import gcd

_DEADLINE_SECONDS = 85  # safety margin before 90s kill
_N = 128

# Precompute GCD table
_gcd_table = [[0] * (_N + 1) for _ in range(_N + 1)]
for _i in range(1, _N + 1):
    for _j in range(_i, _N + 1):
        _g = gcd(_i, _j)
        _gcd_table[_i][_j] = _g
        _gcd_table[_j][_i] = _g

# Precompute Bad masks
# Bad[a][b] is a bitmask where bit x is 1 if {a, b, x} is a bad triple.
# Note: x can be equal to a or b? The problem says "three distinct elements".
# So when checking validity of set S, we ensure distinctness.
# In the mask, we should probably mask out a and b themselves? 
# If x == a, gcd(a,b)=gcd(a,a)=a, gcd(b,a)=a. If gcd(a,b)=a, then it's a bad triple?
# But a, a, b are not distinct. The constraint is on "three distinct elements".
# So x must be distinct from a and b.
# However, in our greedy construction, we only add x if x is not already in S.
# So x is always distinct from a and b.
# We just need to ensure that if gcd(a,b) == gcd(a,x) == gcd(b,x), we block x.

_bad_masks = [[0] * (_N + 1) for _ in range(_N + 1)]
for a in range(1, _N + 1):
    for b in range(a + 1, _N + 1):
        g_ab = _gcd_table[a][b]
        mask = 0
        for x in range(1, _N + 1):
            if x == a or x == b:
                continue
            g_ax = _gcd_table[a][x]
            g_bx = _gcd_table[b][x]
            if g_ab == g_ax == g_bx:
                mask |= (1 << x)
        _bad_masks[a][b] = mask
        _bad_masks[b][a] = mask

def _factor_count(n):
    """Count total prime factors with multiplicity."""
    cnt = 0
    d = 2
    while d * d <= n:
        while n % d == 0:
            cnt += 1
            n //= d
        d += 1
    if n > 1:
        cnt += 1
    return cnt

_fc = {x: _factor_count(x) for x in range(1, _N + 1)}

def _greedy_pass(order, table, bad_masks):
    """
    Greedy pass using bitmask conflict tracking.
    Returns the selected list.
    """
    selected = []
    # conflict_mask holds bits for all x that would form a bad triple with some pair in 'selected'
    conflict_mask = 0
    
    for x in order:
        # Check if x is already forbidden by existing pairs
        if (conflict_mask >> x) & 1:
            continue
        
        # It is safe to add x.
        # Update conflict_mask for future elements.
        # New conflicts are generated by pairs (a, x) for all a in selected.
        new_conflicts = 0
        for a in selected:
            new_conflicts |= bad_masks[a][x]
        
        # The new conflict mask is the old one OR the new ones
        conflict_mask |= new_conflicts
        selected.append(x)
        
    return selected

def _local_improve_add(selected, candidates, table, bad_masks, deadline):
    """
    Try to add excluded candidates.
    We reconstruct the conflict mask for 'selected' first.
    """
    improved = list(selected)
    in_set = set(improved)
    
    # Reconstruct conflict mask
    conflict_mask = 0
    for i in range(len(improved)):
        a = improved[i]
        for j in range(i + 1, len(improved)):
            b = improved[j]
            conflict_mask |= bad_masks[a][b]
            
    to_try = [c for c in candidates if c not in in_set]
    random.shuffle(to_try)
    
    for x in to_try:
        if time.time() > deadline:
            break
        if not ((conflict_mask >> x) & 1):
            # Safe to add
            # Update conflict mask
            new_conflicts = 0
            for a in improved:
                new_conflicts |= bad_masks[a][x]
            conflict_mask |= new_conflicts
            improved.append(x)
            
    return improved

def _local_improve_swap(selected, candidates, table, bad_masks, deadline, max_swaps=200):
    """
    Swap-based local search.
    """
    improved = list(selected)
    in_set = set(improved)
    excluded = [c for c in candidates if c not in in_set]
    
    # Helper to compute conflict mask for a list
    def get_conflict_mask(lst):
        cm = 0
        for i in range(len(lst)):
            a = lst[i]
            for j in range(i + 1, len(lst)):
                b = lst[j]
                cm |= bad_masks[a][b]
        return cm

    current_mask = get_conflict_mask(improved)
    
    for _ in range(max_swaps):
        if time.time() > deadline:
            break
        if not excluded:
            break
        
        # Pick a random element to remove
        idx = random.randint(0, len(improved) - 1)
        removed = improved[idx]
        
        # Tentatively remove
        improved.pop(idx)
        
        # Calculate new conflict mask after removal
        # This is O(N^2) but N is small.
        new_mask = get_conflict_mask(improved)
        
        # Try to add multiple excluded elements
        added_any = False
        remaining = [e for e in excluded if e not in in_set] # in_set is stale, check improved
        # Actually, let's just iterate through a shuffled list of all non-improved elements
        candidates_to_add = [c for c in candidates if c not in improved]
        random.shuffle(candidates_to_add)
        
        for x in candidates_to_add:
            if time.time() > deadline:
                break
            if not ((new_mask >> x) & 1):
                # Safe to add
                # Update new_mask
                for a in improved:
                    new_mask |= bad_masks[a][x]
                improved.append(x)
                added_any = True
        
        if not added_any or len(improved) < len(selected):
            # Revert
            improved.insert(idx, removed)
            # Restore mask? We can just recalculate if we accept a move, 
            # but if we revert, the mask is back to current_mask.
            # Since we reverted the list, we keep current_mask.
        else:
            # Accept move
            current_mask = new_mask
            in_set = set(improved)
            excluded = [c for c in candidates if c not in in_set]
            
    return improved

def construct():
    start_time = time.time()
    deadline = start_time + _DEADLINE_SECONDS
    
    all_nums = list(range(1, _N + 1))
    
    best_set = []
    best_len = 0
    
    # Strategy 1: Sequential greedy
    if time.time() < deadline:
        s = _greedy_pass(all_nums, _gcd_table, _bad_masks)
        if len(s) > best_len:
            best_set, best_len = s, len(s)
            
    # Strategy 2: Reverse order greedy
    if time.time() < deadline:
        s = _greedy_pass(list(reversed(all_nums)), _gcd_table, _bad_masks)
        if len(s) > best_len:
            best_set, best_len = s, len(s)
            
    # Strategy 3: Prime-factor-rich first greedy
    if time.time() < deadline:
        order = sorted(all_nums, key=lambda x: (-_fc[x], x))
        s = _greedy_pass(order, _gcd_table, _bad_masks)
        if len(s) > best_len:
            best_set, best_len = s, len(s)
            
    # Strategy 4: Prime-factor-poor first greedy
    if time.time() < deadline:
        order = sorted(all_nums, key=lambda x: (_fc[x], x))
        s = _greedy_pass(order, _gcd_table, _bad_masks)
        if len(s) > best_len:
            best_set, best_len = s, len(s)

    # Strategy 5: Many random greedy passes with local improvement
    rng = random.Random(42)
    num_random_passes = 2000 # Increased due to speedup
    
    for i in range(num_random_passes):
        if time.time() > deadline:
            break
        order = all_nums[:]
        rng.shuffle(order)
        s = _greedy_pass(order, _gcd_table, _bad_masks)
        if len(s) > best_len:
            best_set, best_len = s, len(s)
            if time.time() < deadline:
                improved = _local_improve_add(best_set, all_nums, _gcd_table, _bad_masks, deadline)
                if len(improved) > best_len:
                    best_set, best_len = improved, len(improved)
                if time.time() < deadline:
                    improved2 = _local_improve_swap(best_set, all_nums, _gcd_table, _bad_masks, deadline, max_swaps=100)
                    if len(improved2) > best_len:
                        best_set, best_len = improved2, len(improved2)
                        
    # Final local improvement on the best set found
    if time.time() < deadline:
        improved = _local_improve_add(best_set, all_nums, _gcd_table, _bad_masks, deadline)
        if len(improved) > best_len:
            best_set, best_len = improved, len(improved)
        if time.time() < deadline:
            improved2 = _local_improve_swap(best_set, all_nums, _gcd_table, _bad_masks, deadline, max_swaps=200)
            if len(improved2) > best_len:
                best_set, best_len = improved2, len(improved2)
                
    # Ensure nonempty
    if not best_set:
        best_set = [1]
        
    return best_set
