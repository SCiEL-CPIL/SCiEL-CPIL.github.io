import time
import random
import itertools
import numpy as np
import sys
from scipy.optimize import milp, LinearConstraint, Bounds
import scipy.sparse as sp

# Global state
_start_time = None
_DEADLINE = 325.0
_best_set = {}
_vector_cache = {}
_line_cache = {}

def _init_state(vector, n):
    global _start_time
    if _start_time is None:
        _start_time = time.time()

def _elapsed():
    if _start_time is None:
        return 0.0
    return time.time() - _start_time

def _is_deadline_exceeded():
    return _elapsed() > _DEADLINE

def _get_vectors(n):
    if n not in _vector_cache:
        _vector_cache[n] = list(itertools.product([0, 1, 2], repeat=n))
    return _vector_cache[n]

def _generate_lines(n):
    if n in _line_cache:
        return _line_cache[n]
    
    vectors = _get_vectors(n)
    m = len(vectors)
    vec_to_idx = {v: i for i, v in enumerate(vectors)}
    
    lines = []
    # To avoid duplicates, we only consider lines where i < j < k (by index)
    # or more efficiently, generate unique lines.
    # A line is defined by a pair (u, v) with u < v, and w = -u-v.
    # We need to ensure we don't add the same line multiple times.
    # A line {a,b,c} is generated by pairs (a,b), (a,c), (b,c).
    # If we iterate i < j, we get pairs.
    # If we add frozenset, we can dedupe, but storing a set of frozensets is memory heavy.
    # Better: iterate i, j such that i < j, compute w.
    # If min_idx(u,v,w) == i and max_idx(u,v,w) == j, then this is the "canonical" generation?
    # No, w can have any index.
    # Let's just generate all pairs i < j, compute w, and add the frozenset.
    # Then convert to a list of unique frozensets.
    unique_lines = set()
    for i in range(m):
        u = vectors[i]
        for j in range(i + 1, m):
            v = vectors[j]
            w = tuple((-u[k] - v[k]) % 3 for k in range(n))
            line_set = frozenset([u, v, w])
            unique_lines.add(line_set)
    
    lines = list(unique_lines)
    _line_cache[n] = lines
    return lines

def _solve_ilp(n):
    """Solve ILP for max cap set for small n."""
    if n > 6:
        return None
        
    vectors = _get_vectors(n)
    m = len(vectors)
    lines = _generate_lines(n)
    
    num_constraints = len(lines)
    if num_constraints == 0:
        return set(vectors)
        
    row_indices = []
    col_indices = []
    data = []
    
    vec_to_idx = {v: i for i, v in enumerate(vectors)}
    
    for r, line in enumerate(lines):
        for v in line:
            c = vec_to_idx[v]
            row_indices.append(r)
            col_indices.append(c)
            data.append(1.0)
            
    A = sp.csr_matrix((data, (row_indices, col_indices)), shape=(num_constraints, m))
    
    # Objective: maximize sum(x) => minimize -sum(x)
    c = -np.ones(m)
    
    # Bounds: 0 <= x <= 1
    bounds = Bounds(lb=0, ub=1)
    
    # Integrality: all integer
    integrality = np.ones(m)
    
    # Constraints: A x <= 2
    cons = LinearConstraint(A, ub=2)
    
    try:
        res = milp(c, constraints=cons, integrality=integrality, bounds=bounds, options={"time_limit": 60})
        if res.status == 0:
            x_sol = res.x
            cap_set = set()
            for i, val in enumerate(x_sol):
                if val > 0.5:
                    cap_set.add(vectors[i])
            return cap_set
        else:
            return None
    except Exception:
        return None

def _greedy_cap_set(order, n):
    """
    Greedily build cap set from ordered list of vectors.
    Returns the set of vectors in the cap set.
    """
    cap_set = set()
    forbidden = set()
    for v in order:
        if v not in forbidden:
            cap_set.add(v)
            for u in cap_set:
                if u == v: continue
                w = tuple((-v[i] - u[i]) % 3 for i in range(n))
                forbidden.add(w)
    return cap_set

def _local_search_improve(cap_set, n, time_budget):
    """
    Try to improve a cap set via local search: add, remove, or swap vectors.
    Returns an improved cap set.
    """
    cap_set = set(cap_set)
    vectors = _get_vectors(n)
    
    # Precompute forbidden set for current cap_set
    forbidden = set()
    for v in cap_set:
        for u in cap_set:
            if u == v: continue
            w = tuple((-v[i] - u[i]) % 3 for i in range(n))
            forbidden.add(w)
            
    start = time.time()
    improved = True
    
    while improved and (time.time() - start) < time_budget:
        if _is_deadline_exceeded():
            break
        improved = False
        
        # 1. Try adding a vector not in forbidden
        # We can randomize the order of candidates to escape local optima
        candidates = [v for v in vectors if v not in cap_set and v not in forbidden]
        random.shuffle(candidates)
        
        for v in candidates:
            # Check if adding v keeps cap set property (it should, by definition of forbidden)
            # But we need to update forbidden set
            new_forbidden = set(forbidden)
            can_add = True
            for u in cap_set:
                w = tuple((-v[i] - u[i]) % 3 for i in range(n))
                new_forbidden.add(w)
                # If w is in cap_set, we can't add v
                if w in cap_set and w != v: 
                    can_add = False
                    break
            
            if can_add:
                cap_set.add(v)
                forbidden = new_forbidden
                improved = True
                break # Restart search with new set
                
        if improved:
            continue
            
        # 2. Try swapping a vector in cap_set with one outside
        # This is more complex. We pick a vector u in cap_set to remove,
        # and a vector v outside to add.
        # Remove u: un-forbid vectors that were forbidden only by u.
        # This is hard to track exactly without recounting.
        # Simple heuristic: try swapping random pairs.
        
        if len(cap_set) > 0:
            u_candidates = list(cap_set)
            random.shuffle(u_candidates)
            
            for u in u_candidates:
                # Try removing u
                # Reconstruct forbidden without u
                # This is O(N^2) per swap attempt, which might be slow.
                # Let's limit swap attempts.
                # For now, let's just try adding. If no add, try a random swap.
                break # Only try one swap per iteration to keep it fast?
                
                # Actually, let's implement a simple swap:
                # Pick random u in cap_set, random v not in cap_set/forbidden.
                # Remove u, add v.
                # Check validity.
                
                pass # Skipping complex swap for now to avoid bugs and slowness.
                # The "add" step is the most powerful local move.
                
    return cap_set

def _heuristic_greedy_restart(n, time_budget):
    """
    Run multiple greedy iterations with random linear orderings.
    Returns the largest cap set found.
    """
    vectors = _get_vectors(n)
    best_set = set()
    best_size = 0
    
    start = time.time()
    
    while time.time() - start < time_budget:
        if _is_deadline_exceeded():
            break
        
        # Strategy 1: Random Linear Ordering
        w = tuple(random.randint(0, 2) for _ in range(n))
        
        items = []
        for v in vectors:
            score = sum(v[i] * w[i] for i in range(n)) % 3
            noise = random.uniform(0, 0.001)
            items.append((score + noise, v))
            
        items.sort(key=lambda x: x[0])
        order = [v for _, v in items]
        
        cap_set = _greedy_cap_set(order, n)
        
        # Local Search Improvement
        # Allocate a small budget for local search per restart
        # Or just do a few steps.
        # Let's do local search with a short budget (e.g., 0.1s)
        cap_set = _local_search_improve(cap_set, n, 0.1)
        
        if len(cap_set) > best_size:
            best_size = len(cap_set)
            best_set = cap_set
            
        # Strategy 2: Balance-based
        if random.random() < 0.5:
             def score(v):
                 c0 = sum(1 for x in v if x == 0)
                 c1 = sum(1 for x in v if x == 1)
                 c2 = sum(1 for x in v if x == 2)
                 badness = abs(c0 - c2)**2 + 0.5 * abs(c1 - n/3.0)**2
                 noise = random.gauss(0, 0.01)
                 return badness + noise
             
             items = []
             for v in vectors:
                 items.append((score(v), v))
             items.sort(key=lambda x: x[0])
             order = [v for _, v in items]
             
             cap_set = _greedy_cap_set(order, n)
             cap_set = _local_search_improve(cap_set, n, 0.1)
             
             if len(cap_set) > best_size:
                 best_size = len(cap_set)
                 best_set = cap_set

    return best_set

def priority(vector, n):
    global _start_time
    _init_state(vector, n)
    
    if _is_deadline_exceeded():
        # Fallback heuristic
        c0 = sum(1 for x in vector if x == 0)
        c2 = sum(1 for x in vector if x == 2)
        c1 = sum(1 for x in vector if x == 1)
        return -(abs(c0 - c2)**2 + 0.5*abs(c1 - n/3.0)**2)
    
    if n not in _best_set:
        # Determine strategy based on n
        cap_set = None
        
        if n <= 6:
            # Try ILP
            cap_set = _solve_ilp(n)
            
        if cap_set is None or len(cap_set) == 0:
            # Use heuristic
            # Allocate time for search
            # Reserve 25s for safety
            remaining = _DEADLINE - _elapsed() - 25.0
            if remaining < 10.0:
                remaining = 10.0
            cap_set = _heuristic_greedy_restart(n, remaining)
            
        _best_set[n] = cap_set
    
    # Assign priority
    if vector in _best_set[n]:
        return 1.0
    else:
        return 0.0
