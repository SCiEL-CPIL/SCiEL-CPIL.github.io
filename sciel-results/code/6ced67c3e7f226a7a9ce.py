    def compute_D(pts, center, normals):
        """Exact: D = max over points and normals of |(p - c) . n|."""
        centered = pts - np.array(center)
        projs = centered @ normals.T  # (n_pts, 6)
        return float(np.max(np.abs(projs)))

    def calc_S_for_beta(pts, beta, center=None):
        """
        Calculate minimal side length S for a fixed rotation beta.
        Uses Minkowski Sum Merging principle:
        Support function of Minkowski sum = Sum of support functions.
        h_K(u) = h_P(u) + h_H(u)
        Width in direction u = h_K(u) + h_K(-u)
        For a regular hexagon of side S, width in normal direction is S * sqrt(3).
        So D = max_u (h_K(u) + h_K(-u)) / 2.
        S = (D + APOTHEM) / APOTHEM.
        
        This avoids LP entirely.
        """
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, float('inf')

        normals = get_normals(beta)
        
        # Support function of point set P: h_P(u) = max_i (p_i . u)
        # Support function of unit hexagon H: h_H(u) = APOTHEM * max_k (u . n_k) where n_k are normals of H?
        # No, H is the unit hexagon. Its support function in direction u is APOTHEM if u is normal to a side,
        # but generally it's the projection of the hexagon onto u.
        # Actually, for a regular hexagon of side 1, the support function in direction u is:
        # h_H(u) = APOTHEM * max(1, |cos(theta)|, |cos(theta - pi/3)|, ...) ?
        # Simpler: The width of a unit hexagon in direction u is W_H(u).
        # The width of the Minkowski sum K = P + H in direction u is W_K(u) = W_P(u) + W_H(u).
        # W_P(u) = max_i (p_i . u) - min_i (p_i . u).
        # W_H(u) is the width of a unit hexagon in direction u.
        # The minimal enclosing hexagon of side S has width S * sqrt(3) in the 6 normal directions.
        # We need S * sqrt(3) >= max_k W_K(n_k) for the 6 normals n_k of the container.
        # So S = max_k W_K(n_k) / sqrt(3).
        # W_K(n_k) = W_P(n_k) + W_H(n_k).
        
        # W_H(n_k) for a unit hexagon in direction n_k (which is a normal to a side of the container)
        # is constant? No, the container rotates. The unit hexagons are fixed shape but the container rotates.
        # Wait, the inner hexagons are unit side length. Their orientation is fixed relative to each other?
        # No, "each inner hexagon may translate and rotate".
        # However, in this candidate generation, we assume all inner hexagons are aligned with the container?
        # No, the candidate points are centers. The hexagons themselves have a fixed orientation relative to the global frame?
        # The problem says "each inner hexagon may translate and rotate".
        # The current code assumes the inner hexagons are all rotated by `angle_deg` which is the same as the container?
        # Looking at `return inner, center, side, rotation`:
        # `inner` rows are (x, y, angle_degrees).
        # The code sets `angle_deg = math.degrees(best_global_beta)`.
        # So all inner hexagons are rotated by the same angle as the container.
        # This means the relative orientation between inner hexagons and container is fixed (0).
        # So the Minkowski sum is P + H_rot(beta).
        # But if we rotate the whole system by beta, it's equivalent to P + H (fixed) and checking widths in rotated normals.
        # Let's stick to the previous logic which was working:
        # D = max |(p_i - c) . n_k|. This is the support function of the set of centers relative to center c.
        # The unit hexagons add APOTHEM to the support function in the normal directions of the container?
        # Yes, if the inner hexagons are aligned with the container, the support function of the union (Minkowski sum)
        # in direction n_k is h_P(n_k) + h_H(n_k).
        # h_H(n_k) = APOTHEM because n_k is normal to a side of the unit hexagon (since they are aligned).
        # So D_total = h_P(n_k) + APOTHEM.
        # And D_total = max_k h_P(n_k) + APOTHEM? No, D is the max over k.
        # D = max_k (h_P(n_k) + APOTHEM) = max_k h_P(n_k) + APOTHEM.
        # Then S = (D - APOTHEM) / APOTHEM? No.
        # The container side S must satisfy S * APOTHEM >= h_K(n_k) for all k.
        # h_K(n_k) = h_P(n_k) + APOTHEM.
        # So S * APOTHEM >= h_P(n_k) + APOTHEM.
        # S >= h_P(n_k)/APOTHEM + 1.
        # So S = max_k (h_P(n_k) / APOTHEM + 1).
        
        # Let's re-verify the previous formula: S = (D + APOTHEM) / APOTHEM.
        # Previous D was max |(p_i - c) . n_k|. This is max_k h_P(n_k) - min_k h_P(-n_k)?
        # No, centered = pts - c.
        # h_P_c(n_k) = max_i (p_i - c) . n_k.
        # The width in direction n_k is h_P_c(n_k) - h_P_c(-n_k).
        # If we center the container optimally, the max projection is D.
        # The previous LP solved for c to minimize D = max_k max_i |(p_i - c) . n_k|.
        # This D is the "radius" in the hexagonal norm.
        # The condition for containment is D + APOTHEM <= S * APOTHEM.
        # So S >= (D + APOTHEM) / APOTHEM.
        
        # So the logic holds. We just need to compute D efficiently.
        # D = min_c max_k max_i |(p_i - c) . n_k|.
        # This is still an optimization over c.
        # However, for fixed beta, the optimal c is the midpoint of the min and max projections?
        # No, it's the center of the minimal enclosing hexagon.
        # But we can compute the width W_k = max_i (p_i . n_k) - min_i (p_i . n_k).
        # The minimal D for a given set of widths W_k is not simply max(W_k)/2.
        # It depends on the geometry.
        # However, the LP was fast enough? Maybe not.
        
        # Let's try a simpler approximation first:
        # Assume the optimal center is the centroid.
        # Compute D_centroid.
        # Then refine c using a few iterations of gradient descent or coordinate descent on D(c).
        
        # Actually, the previous code used LP. Let's see if we can vectorize the LP or replace it.
        # The LP had 12*N constraints.
        
        # Let's try a different approach for speed:
        # 1. Compute centroid c0.
        # 2. Compute D0.
        # 3. Use Nelder-Mead to minimize D(c) for fixed beta.
        # This might be faster than LP for small N.
        
        c0 = np.mean(pts, axis=0)
        
        def D_of_c(c):
            centered = pts - c
            projs = centered @ normals.T
            return float(np.max(np.abs(projs)))
            
        # Quick local optimization of center
        from scipy.optimize import minimize
        try:
            res = minimize(D_of_c, c0, method='Nelder-Mead', options={'maxiter': 200, 'xatol': 1e-10})
            c_opt = res.x
            D_opt = res.fun
        except:
            c_opt = c0
            D_opt = D_of_c(c0)
            
        S = (D_opt + APOTHEM) / APOTHEM
        return S, (float(c_opt[0]), float(c_opt[1])), D_opt

    def smooth_D(pts, center, normals, temperature):
        """Smooth surrogate for D via log-sum-exp soft-max over |projections|."""
        centered = pts - np.array(center)
        projs = centered @ normals.T  # (n_pts, 6)
        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])
        max_val = float(np.max(all_projs))
        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -60.0, 60.0)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        return temperature * log_sum

    def smooth_calc_S(pts, beta, center, temperature):
        normals = get_normals(beta)
        D = smooth_D(pts, center, normals, temperature)
        S = (D + APOTHEM) / APOTHEM
        return S

    def exact_objective_3d(pts, params):
        """Exact objective over (cx, cy, beta) — for final polish."""
        cx, cy, beta = params
        beta = ((beta % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
        normals = get_normals(beta)
        D = compute_D(pts, (cx, cy), normals)
        return (D + APOTHEM) / APOTHEM

    def optimize_shape(pts):
        """Optimize (center, rotation) for a fixed point set.
        Strategy:
          1. Coarse + fine grid search over beta (with fast center solve).
          2. Bounded scalar refine around best beta.
          3. Smooth-surrogate Nelder-Mead in (cx, cy, beta) with annealing.
          4. Exact high-precision polish from multiple starts.
        """
        best_S = float('inf')
        best_beta = 0.0
        best_center = (float(np.mean(pts[:, 0])), float(np.mean(pts[:, 1])))

        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, best_center

        # --- Phase 1: Coarse grid over beta ---
        # Increased resolution due to speedup
        n_coarse = 121
        for i in range(n_coarse):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
            beta = i * (math.pi / 6) / (n_coarse - 1)
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                if center is not None:
                    best_center = center

        # --- Phase 2: Bounded scalar refine around best beta ---
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                lo = max(0.0, best_beta - math.pi / 60)
                hi = min(math.pi / 6, best_beta + math.pi / 60)
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0],
                                      bounds=(lo, hi), method='bounded',
                                      options={'maxiter': 300, 'xatol': 1e-13})
                if res.fun < best_S:
                    best_S = float(res.fun)
                    best_beta = float(res.x)
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass

        # --- Phase 3: Smooth-surrogate Nelder-Mead with annealing ---
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                temperatures = [0.3, 0.1, 0.05, 0.02, 0.01]
                start_betas = [best_beta, best_beta + 0.05, best_beta - 0.05,
                               0.0, math.pi / 12, math.pi / 6]

                for temp in temperatures:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    for sb in start_betas:
                        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                            break

                        def smooth_obj(params, t=temp):
                            cx, cy, beta = params
                            beta = ((beta % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
                            return smooth_calc_S(pts, beta, (cx, cy), t)

                        init = [best_center[0], best_center[1], sb]
                        try:
                            res = minimize(smooth_obj, init, method='Nelder-Mead',
                                           options={'maxiter': 500, 'xatol': 1e-11, 'fatol': 1e-11})
                            if res.fun < 1e10:
                                cx_r, cy_r, beta_r = res.x
                                beta_r = ((beta_r % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
                                S_exact, c_exact, _ = calc_S_for_beta(pts, beta_r)
                                if S_exact < best_S:
                                    best_S = S_exact
                                    best_beta = beta_r
                                    if c_exact is not None:
                                        best_center = c_exact
                        except Exception:
                            pass
        except Exception:
            pass

        # --- Phase 4: Exact high-precision polish ---
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                cx0, cy0 = best_center
                polish_starts = [
                    [cx0, cy0, best_beta],
                    [cx0, cy0, best_beta + 0.02],
                    [cx0, cy0, best_beta - 0.02],
                    [cx0 + 0.02, cy0, best_beta],
                    [cx0, cy0 + 0.02, best_beta],
                    [cx0 - 0.02, cy0, best_beta],
                    [cx0, cy0 - 0.02, best_beta],
                ]

                for init in polish_starts:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    # Nelder-Mead polish
                    try:
                        res = minimize(exact_objective_3d, init, method='Nelder-Mead',
                                       options={'maxiter': 5000, 'xatol': 1e-13, 'fatol': 1e-13})
                        if res.fun < best_S:
                            best_S = float(res.fun)
                            best_center = (float(res.x[0]), float(res.x[1]))
                            best_beta = ((float(res.x[2]) % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
                    except Exception:
                        pass

                    # SLSQP polish from current best
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        continue
                    try:
                        res2 = minimize(exact_objective_3d,
                                        [best_center[0], best_center[1], best_beta],
                                        method='SLSQP',
                                        options={'maxiter': 500, 'ftol': 1e-14})
                        if res2.fun < best_S:
                            best_S = float(res2.fun)
                            best_center = (float(res2.x[0]), float(res2.x[1]))
                            best_beta = ((float(res2.x[2]) % (math.pi / 6)) + math.pi / 6) % (math.pi / 6)
                    except Exception:
                        pass
        except Exception:
            pass

        return best_S, best_beta, best_center

    # --- Main loop over candidates ---
    best_global_S = float('inf')
    best_global_pts = None
    best_global_beta = 0.0
    best_global_center = None

    # Sort candidates by a quick heuristic: prefer more compact ones
    # We'll just iterate through all of them with time management
    for idx, axial in enumerate(candidates):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            break
        pts = axial_to_cartesian(axial)
        S, beta, center = optimize_shape(pts)
        if S < best_global_S:
            best_global_S = S
            best_global_pts = pts
            best_global_beta = beta
            best_global_center = center

    # --- Fallback ---
    if best_global_center is None or best_global_S == float('inf'):
        best_global_pts = axial_to_cartesian(candidates[0])
        best_global_center = (float(np.mean(best_global_pts[:, 0])),
                              float(np.mean(best_global_pts[:, 1])))
        best_global_beta = 0.0
        normals = get_normals(best_global_beta)
        max_proj = 0.0
        for nx, ny in normals:
            projs = best_global_pts[:, 0] * nx + best_global_pts[:, 1] * ny
            max_proj = max(max_proj, float(np.max(projs)), float(-np.min(projs)))
        best_global_S = (max_proj + APOTHEM) / APOTHEM

    cx, cy = best_global_center
    angle_deg = math.degrees(best_global_beta)

    # --- Final: recompute exact S with the chosen (center, beta), add tiny scale for safety ---
    SCALE = 1.0 + 1e-12
    pts_scaled = []
    for x, y in best_global_pts:
        sx = cx + (x - cx) * SCALE
        sy = cy + (y - cy) * SCALE
        pts_scaled.append((sx, sy))
    pts_scaled = np.array(pts_scaled)

    normals = get_normals(best_global_beta)
    max_proj = 0.0
    for nx, ny in normals:
        projs = (pts_scaled[:, 0] - cx) * nx + (pts_scaled[:, 1] - cy) * ny
        max_proj = max(max_proj, float(np.max(projs)), float(-np.min(projs)))

    D_scaled = max_proj
    S_scaled = (D_scaled + APOTHEM) / APOTHEM

    inner = []
    for x, y in pts_scaled:
        inner.append([float(x), float(y), float(angle_deg)])

    center = [float(cx), float(cy)]
    side = float(S_scaled)
    rotation = float(angle_deg)

    return inner, center, side, rotation
