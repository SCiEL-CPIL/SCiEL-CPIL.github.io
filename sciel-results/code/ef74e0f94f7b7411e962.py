import time
import sys
import random
from collections import defaultdict
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 55  # Safety margin before 90s kill
    
    N = 17
    MIN_D = 6
    max_val = 1 << N
    
    # Precompute weights for all 2^N words using bit_count
    weights = np.array([i.bit_count() for i in range(max_val)], dtype=np.uint8)
    
    # Precompute offsets with weight < MIN_D (these cause conflicts)
    offsets_lt_d = [i for i in range(max_val) if weights[i] < MIN_D]
    offsets_set = set(offsets_lt_d)
    
    def build_shortened_qr_code():
        """
        Construct the [17,9,6] shortened quadratic residue code.
        The [18,9,6] QR code has generator matrix with rows corresponding to
        quadratic residues mod 19. We shorten by removing one coordinate.
        
        The quadratic residues mod 19 are: 1,4,5,6,7,9,11,16,17
        The [18,9,6] code can be generated by a 9x18 generator matrix.
        We'll use the standard construction and shorten.
        """
        # The [18,9,6] extended QR(19) code generator matrix
        # Using the standard form: G = [I_9 | P] where P is 9x9
        # Actually, let's use a known systematic generator.
        
        # For QR(19), the parity check matrix has columns corresponding to
        # the 18 non-zero elements of GF(19). The generator matrix can be
        # derived from the dual code.
        
        # Alternative: use the fact that the [17,9,6] code is well-known.
        # Let's construct it via the MacWilliams identity or known generator.
        
        # Known: The [17,9,6] code has 2^9 = 512 codewords... wait, that's too many.
        # Actually [17,9,6] means length 17, dimension 9, min distance 6.
        # So it has 2^9 = 512 codewords. But we need pairwise distance >= 6.
        # Wait, the task says "seed has 32 words" and "256-word linear reference".
        # So the reference is a [17,8,6] code with 2^8 = 256 codewords.
        
        # Let me reconsider. The [18,9,6] code shortened by one coordinate gives [17,8,6] or [17,9,6]?
        # Shortening a [n,k,d] code gives [n-1,k-1,d] or [n-1,k,d-1].
        # For [18,9,6], shortening gives [17,8,6] (if we fix one coordinate to 0).
        # So 2^8 = 256 codewords. That matches!
        
        # Let's construct the [18,9,6] QR code generator matrix.
        # The QR(19) code: the generator matrix G is 9x18 where row i has
        # 1s in positions corresponding to quadratic residues shifted by i.
        
        # Actually, let me use a simpler approach: greedy basis construction
        # with a good ordering.
        
        # Greedy construction of a [17,8,6] linear code
        basis = []
        code = [0]
        
        # Try candidates in order of increasing weight, then lexicographic
        # This tends to find good bases
        candidates = sorted(range(1, max_val), key=lambda x: (weights[x], x))
        
        for g in candidates:
            if time.time() > deadline - 30:
                break
            if len(basis) >= 8:
                break
            if g == 0:
                continue
            valid = True
            for c in code:
                if weights[g ^ c] < MIN_D:
                    valid = False
                    break
            if valid:
                basis.append(g)
                new_code = []
                for c in code:
                    new_code.append(c)
                    new_code.append(c ^ g)
                code = new_code
        
        if len(code) >= 256:
            return code
        return None
    
    def fast_greedy_expand(base_code, time_budget):
        """
        Fast greedy expansion using efficient neighbor checking.
        """
        base_set = set(base_code)
        code = list(base_code)
        
        # Find all valid candidates: x such that dist(x, c) >= MIN_D for all c in base
        # Use vectorized approach in chunks
        base_arr = np.array(base_code, dtype=np.int32)
        
        valid_candidates = []
        chunk_size = 8192
        
        for start in range(0, max_val, chunk_size):
            if time.time() > deadline - 5:
                break
            end = min(start + chunk_size, max_val)
            chunk = np.arange(start, end, dtype=np.int32)
            
            # Compute min distance to base code
            min_dists = np.full(len(chunk), max_val, dtype=np.int32)
            for bs in range(0, len(base_arr), 512):
                be = min(bs + 512, len(base_arr))
                base_sub = base_arr[bs:be]
                xor_mat = chunk[:, None] ^ base_sub[None, :]
                dist_mat = weights[xor_mat]
                min_dists = np.minimum(min_dists, dist_mat.min(axis=1))
            
            valid_mask = min_dists >= MIN_D
            valid_chunk = chunk[valid_mask]
            for x in valid_chunk:
                x_int = int(x)
                if x_int not in base_set:
                    valid_candidates.append(x_int)
        
        valid_set = set(valid_candidates)
        
        # Greedy loop with min-degree heuristic
        # Precompute neighbor sets for efficiency
        while valid_set and time.time() < deadline - 5:
            # Find candidate with minimum degree in conflict graph
            best_v = None
            min_deg = float('inf')
            
            # Sample if too many candidates
            if len(valid_set) > 5000:
                sample = random.sample(list(valid_set), min(2000, len(valid_set)))
            else:
                sample = list(valid_set)
            
            for v in sample:
                deg = 0
                for e in offsets_lt_d:
                    u = v ^ e
                    if u in valid_set:
                        deg += 1
                        if deg >= min_deg:
                            break
                
                if deg < min_deg:
                    min_deg = deg
                    best_v = v
            
            if best_v is None:
                break
                
            code.append(best_v)
            valid_set.discard(best_v)
            
            # Remove neighbors
            neighbors = {best_v ^ e for e in offsets_lt_d}
            valid_set.difference_update(neighbors)
        
        return code
    
    # Phase 1: Build base linear code
    base_code = build_shortened_qr_code()
    if not base_code or len(base_code) < 256:
        return [0]
    
    # Phase 2: Greedy expansion
    result = fast_greedy_expand(base_code, deadline - 10)
    
    # Phase 3: Try a few more expansions from different starting points
    # or restart with different random seeds
    for trial in range(3):
        if time.time() > deadline - 8:
            break
        
        # Try expanding from a slightly different base
        # Remove a random word from base and re-expand
        if len(base_code) > 256:
            idx = random.randint(0, len(base_code) - 1)
            alt_base = base_code[:idx] + base_code[idx+1:]
            alt_result = fast_greedy_expand(alt_base, deadline - 8)
            if len(alt_result) > len(result):
                result = alt_result
    
    return result
