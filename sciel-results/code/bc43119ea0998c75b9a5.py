import numpy as np
import time

class Optimizer:
    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

    def __call__(self, func):
        start_time = time.time()
        deadline = start_time + 280.0  # Safety margin for 330s kill
        
        calls_used = 0
        max_calls = self.budget
        best_f = float('inf')
        best_x = None
        rng = np.random.default_rng(42)
        
        def update_best(x, f):
            nonlocal best_f, best_x
            if f < best_f:
                best_f = f
                best_x = x.copy()

        def get_best():
            return best_x, best_f

        # Phase 1: Wide Exploration with Population
        # Use a population of size 50 to cover the space broadly
        pop_size = 50
        # Initial step size: roughly 1/10th of the box width (10/10 = 1)
        # But for 5D, maybe slightly smaller to ensure some overlap
        step_size = 1.5 
        
        # Initialize population: mix of random and some centered
        population = []
        for i in range(pop_size):
            if i == 0:
                x = np.zeros(self.dim)
            else:
                x = rng.uniform(-5, 5, size=self.dim)
            population.append(x)
        
        # Evaluate initial population
        for x in population:
            if time.time() > deadline or calls_used >= max_calls:
                break
            f_val = func(x)
            calls_used += 1
            update_best(x, f_val)

        # Phase 2: (1+lambda) ES Loop
        # We will use a (1+1) or (1+lambda) strategy.
        # Given the multimodal nature, a (1+lambda) with lambda=5-10 is good.
        # But we must manage the budget carefully.
        # Let's use a (1+5) strategy: 1 parent, 5 offspring.
        # Or better, since we have a population, let's use a (mu+lambda) or just
        # restart (1+1) from the best few if we stagnate?
        
        # Actually, a robust strategy for BBOB f22 is to use a CMA-ES like
        # adaptation or a simple adaptive step size (1+1)-ES with restarts.
        
        # Let's stick to a simple, robust (1+lambda) ES with adaptive step size.
        # Parent is always the current best.
        # Offspring are generated by adding noise to the parent.
        # Step size adapts based on success rate (1/5 rule or similar).
        
        lambda_ = 5  # 5 offspring per generation
        success_rate = 0.0
        step_size = 1.5
        min_step = 1e-4
        max_step = 5.0
        
        # To handle multimodality, we should occasionally restart from random
        # points if we stagnate.
        
        stagnant_generations = 0
        best_f_prev = best_f
        
        while time.time() < deadline and calls_used < max_calls:
            # Generate lambda_ offspring from the current best
            offspring = []
            for i in range(lambda_):
                if calls_used >= max_calls or time.time() > deadline:
                    break
                noise = rng.normal(0, 1, size=self.dim) * step_size
                x_off = best_x + noise
                # Clip to box
                x_off = np.clip(x_off, -5, 5)
                offspring.append(x_off)
            
            if not offspring:
                break

            # Evaluate offspring
            best_offspring_x = None
            best_offspring_f = float('inf')
            improved = False
            
            for x_off in offspring:
                if calls_used >= max_calls or time.time() > deadline:
                    break
                f_off = func(x_off)
                calls_used += 1
                if f_off < best_offspring_f:
                    best_offspring_f = f_off
                    best_offspring_x = x_off
                # Update global best
                if f_off < best_f:
                    best_f = f_off
                    best_x = x_off.copy()
                    improved = True
            
            # Adapt step size
            # If we improved, increase step size slightly (or keep)
            # If we didn't, decrease step size
            if improved:
                step_size = min(max_step, step_size * 1.1)
                stagnant_generations = 0
            else:
                step_size = max(min_step, step_size * 0.8)
                stagnant_generations += 1

            # Restart logic: If we've been stagnant for a while, 
            # try a random restart to escape local minima.
            if stagnant_generations > 20:
                # Random restart
                x_restart = rng.uniform(-5, 5, size=self.dim)
                if calls_used < max_calls and time.time() < deadline:
                    f_restart = func(x_restart)
                    calls_used += 1
                    if f_restart < best_f:
                        best_f = f_restart
                        best_x = x_restart.copy()
                    # Reset step size for new basin
                    step_size = 1.5
                    stagnant_generations = 0

        # Final check: if we have budget left and time, do a few more random checks
        # to ensure we didn't miss a better spot due to step size collapse
        while calls_used < max_calls and time.time() < deadline:
            x_rand = rng.uniform(-5, 5, size=self.dim)
            f_rand = func(x_rand)
            calls_used += 1
            if f_rand < best_f:
                best_f = f_rand
                best_x = x_rand.copy()
            # Stop if we've done a lot of randoms
            if calls_used > max_calls - 10:
                break

        return best_x, best_f
