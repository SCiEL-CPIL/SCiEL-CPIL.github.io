import numpy as np
import time
import random

def priority(instance):
    """
    Returns a priority score for each activity to be used in a Serial SGS.
    
    Strategy: 
    The task requires returning a static priority list. However, the score is based on the 
    makespan of the schedule generated by the evaluator using this list. 
    The current approach uses static heuristics. 
    This new strategy computes a "composite" static priority that better approximates 
    the benefit of dynamic scheduling by weighting activities based on their position 
    in the critical path AND their resource intensity.
    
    Specifically, we use a "Weighted Critical Path" heuristic:
    P(i) = CPL(i) * (1 + Sum(demand(i, r) / capacity(r) for all r))
    
    This prioritizes activities that are on the critical path AND consume significant 
    resources, which helps resolve resource conflicts earlier for bottleneck resources.
    
    To improve upon simple static heuristics, we will also perform a lightweight 
    local search (hill climbing) on the priority vector to minimize the makespan 
    simulated by the SGS. We will use a faster, vectorized SGS simulation if possible, 
    or an optimized Python loop.
    """
    start_time = time.time()
    # Safety margin: 145s out of 150s limit
    deadline = start_time + 145.0

    # 1. Extract and process instance data
    N = len(instance["durations"])
    durations = np.array(instance["durations"], dtype=float)
    demands = np.array(instance["demands"], dtype=float)  # Shape (N, R)
    capacities = np.array(instance["capacities"], dtype=float) # Shape (R,)
    R = len(capacities)
    
    # Handle predecessors
    preds = instance.get("predecessors", [[] for _ in range(N)])
    if isinstance(preds, np.ndarray):
        if preds.ndim == 2:
             preds = [np.where(preds[i] > 0)[0].tolist() for i in range(N)]
        else:
             preds = [[] for _ in range(N)]
    elif isinstance(preds, list):
         normalized_preds = []
         for p in preds:
             if isinstance(p, (list, tuple, np.ndarray)):
                 normalized_preds.append(list(map(int, p)))
             else:
                 normalized_preds.append([])
         preds = normalized_preds
    else:
         preds = [[] for _ in range(N)]

    # Build successors
    succs = [[] for _ in range(N)]
    for i in range(N):
        for p in preds[i]:
            succs[p].append(i)
            
    # 2. Compute Static Heuristics
    # Topological Sort
    in_degree = [len(p) for p in preds]
    queue = [i for i in range(N) if in_degree[i] == 0]
    topo_order = []
    indeg_temp = in_degree[:]
    q = queue[:]
    while q:
        u = q.pop(0)
        topo_order.append(u)
        for v in succs[u]:
            indeg_temp[v] -= 1
            if indeg_temp[v] == 0:
                q.append(v)
                
    # Compute Critical Path Length (CPL) backwards
    cpl = np.zeros(N)
    for i in range(len(topo_order) - 1, -1, -1):
        u = topo_order[i]
        max_succ_cpl = 0
        for v in succs[u]:
            if cpl[v] > max_succ_cpl:
                max_succ_cpl = cpl[v]
        cpl[u] = durations[u] + max_succ_cpl
        
    # Compute Resource Intensity (RI): sum of demand/capacity ratios
    # High RI means the activity consumes a large fraction of available resources
    # Avoid division by zero if capacity is 0 (though unlikely in valid instances)
    cap_safe = np.where(capacities > 0, capacities, 1.0)
    ratios = demands / cap_safe  # Shape (N, R)
    ri = np.sum(ratios, axis=1)  # Shape (N,)
    
    # 3. Define Fast SGS Simulation
    # We need a very fast simulator to allow many iterations.
    # Optimization: Pre-compute eligible sets? No, eligibility changes dynamically.
    # Optimization: Use lists and simple loops. N=30 is small.
    
    def simulate_sgs(priorities):
        """
        Serial SGS simulation.
        Returns makespan.
        """
        scheduled = [False] * N
        # active: list of (finish_time, idx)
        active = []
        remaining_res = capacities.copy()
        time_current = 0.0
        makespan = 0.0
        
        # Pre-compute predecessor lists for faster access? 
        # preds is already list of lists.
        
        while True:
            # Check if all done
            # Optimization: count scheduled? Or just break when active is empty and no eligible?
            # Standard check: if all(scheduled): break
            # Faster: if len(scheduled_true) == N: break. But 'scheduled' is a list of bools.
            # Let's use a counter.
            
            # Actually, let's just run the loop. N=30, max steps ~ N + resource waits.
            # It's fast enough.
            
            # Find eligible
            eligible = []
            # Optimization: Instead of checking all N, we could maintain a set of eligible.
            # But N=30 is small.
            for i in range(N):
                if not scheduled[i]:
                    # Check preds
                    is_eligible = True
                    for p in preds[i]:
                        if not scheduled[p]:
                            is_eligible = False
                            break
                    if is_eligible:
                        eligible.append(i)
                        
            if not eligible:
                # Wait for next event
                if not active:
                    break # Should not happen if valid
                min_finish = min(f for f, _ in active)
                time_current = min_finish
                # Process completions
                new_active = []
                for f, idx in active:
                    if f > time_current:
                        new_active.append((f, idx))
                    else:
                        remaining_res += demands[idx]
                        makespan = max(makespan, f)
                active = new_active
                continue
                
            # Sort eligible by priority (descending)
            # Optimization: Use sorted() with key.
            eligible.sort(key=lambda x: priorities[x], reverse=True)
            
            # Attempt to schedule
            any_scheduled = False
            for i in eligible:
                # Check resources
                # Vectorized check: np.all(remaining_res >= demands[i])
                if np.all(remaining_res >= demands[i]):
                    scheduled[i] = True
                    remaining_res -= demands[i]
                    finish_t = time_current + durations[i]
                    active.append((finish_t, i))
                    makespan = max(makespan, finish_t)
                    any_scheduled = True
                    
            if not any_scheduled:
                # Wait
                if not active:
                    break
                min_finish = min(f for f, _ in active)
                time_current = min_finish
                new_active = []
                for f, idx in active:
                    if f > time_current:
                        new_active.append((f, idx))
                    else:
                        remaining_res += demands[idx]
                        makespan = max(makespan, f)
                active = new_active
                
        return makespan

    # 4. Generate Initial Candidates
    candidates = []
    
    # Heuristic 1: CPL
    candidates.append(cpl.copy())
    
    # Heuristic 2: CPL * (1 + RI)
    candidates.append(cpl * (1.0 + ri))
    
    # Heuristic 3: CPL * (1 + 2*RI)
    candidates.append(cpl * (1.0 + 2.0 * ri))
    
    # Heuristic 4: LPT (Duration)
    candidates.append(durations.copy())
    
    # Heuristic 5: LPT * (1 + RI)
    candidates.append(durations * (1.0 + ri))
    
    # Heuristic 6: Successor Count weighted
    succ_count = np.zeros(N, dtype=int)
    for i in range(N):
        visited = set()
        stack = [i]
        while stack:
            node = stack.pop()
            for s in succs[node]:
                if s not in visited:
                    visited.add(s)
                    stack.append(s)
        succ_count[i] = len(visited)
    
    candidates.append(cpl * (1.0 + succ_count.astype(float)))
    
    # 5. Local Search (Hill Climbing)
    # We will pick the best initial candidate and try to improve it by swapping priorities 
    # of pairs of activities.
    
    best_score = float('inf')
    best_priorities = candidates[0]
    
    # Evaluate initial candidates
    for cand in candidates:
        if time.time() > deadline:
            break
        score = simulate_sgs(cand)
        if score < best_score:
            best_score = score
            best_priorities = cand.copy()
            
    # Hill Climbing
    # We will perform random swaps.
    # To make it more effective, we can try "2-opt" style moves: swap priorities of i and j.
    # Since priorities are continuous, swapping values is a valid move in the search space.
    # Alternatively, we can perturb the values.
    # Swapping is discrete and easy to reverse.
    
    current_priorities = best_priorities.copy()
    current_score = best_score
    
    # Use a random seed for reproducibility in the search, but different from the instance?
    # The task implies deterministic behavior per instance is preferred for stability, 
    # but random search is okay if it converges.
    # However, if the evaluator runs this multiple times, non-determinism might cause variance.
    # Let's use a fixed seed based on N or something simple, or just standard random.
    # The prompt says "five generated single-mode instances". 
    # If I use random.seed(42), it's deterministic.
    
    random.seed(42)
    
    improved = True
    max_iterations = 0
    # Estimate budget: 
    # Simulate is ~ O(N^2) or less. N=30. 
    # Let's say 1000 sims/sec. 140s -> 140,000 sims.
    # We can do a lot of swaps.
    
    while improved and time.time() < deadline:
        improved = False
        # Try a batch of swaps
        for _ in range(100):
            if time.time() > deadline:
                break
            i, j = random.sample(range(N), 2)
            
            # Swap priorities
            temp = current_priorities[i]
            current_priorities[i] = current_priorities[j]
            current_priorities[j] = temp
            
            new_score = simulate_sgs(current_priorities)
            
            if new_score < current_score:
                current_score = new_score
                best_score = new_score
                best_priorities = current_priorities.copy()
                improved = True
            else:
                # Swap back
                current_priorities[j] = current_priorities[i]
                current_priorities[i] = temp
                
    return best_priorities
