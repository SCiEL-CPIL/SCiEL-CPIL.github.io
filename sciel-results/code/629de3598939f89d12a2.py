import numpy as np
from scipy.optimize import minimize
import time

N = 400

def _eval_value(h):
    s = np.sum(h)
    if abs(s) < 1e-12:
        return 1e10
    conv = np.convolve(h, h)
    m = np.max(conv)
    return abs(2.0 * N * m / (s * s))

def _convolve_fft(h):
    n = 2 * N - 1
    f = np.fft.rfft(h, n)
    conv = np.fft.irfft(f * f, n)
    return conv

def _soft_max(x, beta=100.0):
    m = np.max(x)
    return m + np.log(np.sum(np.exp(beta * (x - m)))) / beta

def _soft_max_grad(x, beta=100.0):
    m = np.max(x)
    exps = np.exp(beta * (x - m))
    softmax = exps / np.sum(exps)
    return softmax

def _objective_soft(x, beta=100.0):
    h = x
    s = np.sum(h)
    if abs(s) < 1e-12:
        return 1e10
    conv = _convolve_fft(h)
    sm = _soft_max(conv, beta)
    return abs(2.0 * N * sm / (s * s))

def _objective_exact(x):
    return _eval_value(x)

def _spectral_flatness_obj(x):
    h = x
    s = np.sum(h)
    if abs(s) < 1e-12:
        return 1e10
    # We want to minimize the peak of the autoconvolution relative to the mean
    # Using FFT, the autoconvolution peak is related to the time-domain peak
    # But a better proxy for "flatness" that correlates with low peak-to-avg
    # is minimizing the L2 norm of the autoconvolution, which equals L2 norm of h squared (Parseval)
    # Wait, sum(conv^2) = sum(h^4) if conv is full? No.
    # sum(conv[k]^2) = sum_i sum_j h[i]h[j] h[i+k]h[j+k] ... this is complicated.
    # Let's stick to minimizing the max directly via soft-max or just use the exact value.
    # The strategy mentioned: "Represent the step heights as the real part of a complex vector generated by a random unitary transformation..."
    # This is essentially random rotation in a high-dimensional space.
    # Let's try a different structural approach:
    # Minimize the maximum of the autoconvolution directly using gradient descent with FFT.
    # Gradient of max(conv) is the one-hot vector at the argmax position, mapped back to h.
    # d(conv)/d(h) is the convolution operator.
    # If max is at index k, grad_conv[k] = 1, others 0.
    # grad_h = convolve(grad_conv, h) (with appropriate shifts)
    # This is a "peak shaving" approach.
    
    # Let's implement a simple gradient descent on the soft-max objective.
    return _objective_soft(x, beta=50.0)

def construct():
    t0 = time.time()
    deadline = t0 + 145.0  # safety margin for 150s limit
    
    best_h = np.ones(N)
    best_val = 2.0
    
    # Strategy 1: Random Unitary Transform (Spectral Flattening)
    # Generate random unitary matrices (or just random rotations) and apply to a base vector.
    # The base vector should have a non-zero mean to keep sum(h) != 0.
    # Let h = U @ v, where U is unitary and v is sparse/impulse-like.
    # But we need real h. So use real orthogonal matrices.
    # Random orthogonal matrix Q. h = Q @ v.
    # If v is constant, h is constant (value 2).
    # If v is sparse, h has flat spectrum.
    
    # Let's try: h = Q @ (c * ones(N) + epsilon * random_sparse)
    # Or simpler: just optimize directly.
    
    # Initialize with a few diverse points
    inits = []
    inits.append(np.ones(N))
    inits.append(np.random.randn(N) + 1.0) # Shifted to be positive-ish
    inits.append(np.sin(2 * np.pi * np.arange(N) / N) + 1.0)
    inits.append(np.cos(2 * np.pi * np.arange(N) / N) + 1.0)
    
    # Random orthogonal projections
    for _ in range(5):
        # Generate random orthogonal matrix via QR decomposition of random Gaussian
        A = np.random.randn(N, N)
        Q, R = np.linalg.qr(A)
        # Ensure determinant is 1 (proper rotation)
        d = np.sign(np.linalg.det(Q))
        Q[:, 0] *= d
        v = np.ones(N) + 0.1 * np.random.randn(N)
        h_init = Q @ v
        # Normalize to have positive sum
        if np.sum(h_init) < 0:
            h_init = -h_init
        inits.append(h_init)
    
    for h0 in inits:
        if time.time() > deadline - 10:
            break
        try:
            # Use L-BFGS-B with the soft-max objective for differentiability
            # Scale beta to be large enough to approximate max
            res = minimize(_objective_soft, h0, method='L-BFGS-B', 
                          args=(50.0,),
                          options={'maxiter': 100, 'ftol': 1e-10})
            h_new = res.x
            val = _eval_value(h_new)
            if val < best_val and np.all(np.isfinite(h_new)) and abs(np.sum(h_new)) > 1e-12:
                best_h = h_new
                best_val = val
        except Exception:
            pass
    
    # Refine with higher beta (sharper max approximation)
    if time.time() < deadline - 5:
        try:
            res = minimize(_objective_soft, best_h, method='L-BFGS-B', 
                          args=(200.0,),
                          options={'maxiter': 50, 'ftol': 1e-12})
            h_new = res.x
            val = _eval_value(h_new)
            if val < best_val and np.all(np.isfinite(h_new)) and abs(np.sum(h_new)) > 1e-12:
                best_h = h_new
                best_val = val
        except Exception:
            pass
    
    # Final check
    s = np.sum(best_h)
    if abs(s) < 1e-12:
        return np.ones(N)
    
    return best_h
