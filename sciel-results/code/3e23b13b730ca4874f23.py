def hexagon_vertices(cx, cy, side, rotation_deg):
    """Get the 6 vertices of a regular hexagon."""
    rot = math.radians(rotation_deg)
    verts = []
    for i in range(6):
        angle = rot + i * math.pi / 3
        x = cx + side * math.cos(angle)
        y = cy + side * math.sin(angle)
        verts.append((x, y))
    return verts

def point_in_hexagon(px, py, cx, cy, side, rotation_deg):
    """Check if point (px, py) is inside hexagon with center (cx,cy), side length, rotation."""
    rot = math.radians(rotation_deg)
    # Transform point to hexagon's local coordinate system
    dx = px - cx
    dy = py - cy
    # Rotate back
    cos_r = math.cos(-rot)
    sin_r = math.sin(-rot)
    lx = dx * cos_r - dy * sin_r
    ly = dx * sin_r + dy * cos_r
    
    # In local coords, hexagon has vertices at angles 0, 60, 120, 180, 240, 300
    # The hexagon is defined by |x| <= side, |x/2 + y*sqrt(3)/2| <= side, |y| <= side*sqrt(3)/2
    # Actually for a regular hexagon with side length s centered at origin:
    # The six sides are at distance apothem = s*sqrt(3)/2 from center
    # Let's use the half-plane method
    apothem = side * math.sqrt(3) / 2
    for i in range(6):
        angle = i * math.pi / 3
        nx = math.cos(angle)
        ny = math.sin(angle)
        if lx * nx + ly * ny > apothem + 1e-10:
            return False
    return True

def hexagons_disjoint(v1, v2, v3, v4, v5, v6, w1, w2, w3, w4, w5, w6):
    """Check if two hexagons (given by their 6 vertices each) are disjoint."""
    # Two convex polygons are disjoint if no edge of one intersects any edge of the other
    # and neither contains the other
    def segments_intersect(p1, p2, p3, p4):
        def cross(o, a, b):
            return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
        
        d1 = cross(p3, p4, p1)
        d2 = cross(p3, p4, p2)
        d3 = cross(p1, p2, p3)
        d4 = cross(p1, p2, p4)
        
        if ((d1 > 0 and d2 < 0) or (d1 < 0 and d2 > 0)) and \
           ((d3 > 0 and d4 < 0) or (d3 < 0 and d4 > 0)):
            return True
        return False
    
    # Check all edge pairs
    for i in range(6):
        for j in range(6):
            if segments_intersect(v1[i], v1[(i+1)%6], v2[j], v2[(j+1)%6]):
                return False
    
    # Check if one contains the other
    if point_in_hexagon(v1[0][0], v1[0][1], *get_hex_center(v2), *get_hex_params(v2)):
        return False
    if point_in_hexagon(v2[0][0], v2[0][1], *get_hex_center(v1), *get_hex_params(v1)):
        return False
    
    return True

def get_hex_center(verts):
    """Get center from hexagon vertices."""
    cx = sum(v[0] for v in verts) / 6
    cy = sum(v[1] for v in verts) / 6
    return cx, cy

def get_hex_params(verts):
    """Get side length and rotation from hexagon vertices."""
    cx, cy = get_hex_center(verts)
    # Side length is distance from center to vertex
    side = math.sqrt((verts[0][0] - cx)**2 + (verts[0][1] - cy)**2)
    # Rotation is angle of first vertex from center
    rot = math.atan2(verts[0][1] - cy, verts[0][0] - cx)
    return side, math.degrees(rot)

