import time
import numpy as np
from scipy.optimize import differential_evolution, minimize
from scipy.spatial import ConvexHull

N = 14
M = N // 2  # 7 independent edge vectors for centrally symmetric polygon

def _min_triangle_area(pts):
    """Compute minimum triangle area for N points."""
    n = len(pts)
    min_area = float('inf')
    x = pts[:, 0]
    y = pts[:, 1]
    for i in range(n - 2):
        for j in range(i + 1, n - 1):
            dx_ji = x[j] - x[i]
            dy_ji = y[j] - y[i]
            dx_ki = x[j+1:] - x[i]
            dy_ki = y[j+1:] - y[i]
            cross = dx_ji * dy_ki - dy_ji * dx_ki
            areas = 0.5 * np.abs(cross)
            local_min = np.min(areas)
            if local_min < min_area:
                min_area = local_min
    return min_area

def _hull_area(pts):
    try:
        hull = ConvexHull(pts)
        return hull.volume
    except Exception:
        return 0.0

def _decode_symmetric(params):
    """
    Decode 14 parameters (7 edge vectors, 2D each) into 14 points
    forming a centrally symmetric convex polygon.
    
    params: array of shape (14,) = [e1x, e1y, e2x, e2y, ..., e7x, e7y]
    
    The polygon vertices are generated by:
    - Start at origin
    - Add edge vectors e1, e2, ..., e7 to get 7 vertices
    - The other 7 vertices are negatives of the first 7 (central symmetry)
    - For convexity, we need the edge vectors to be in counterclockwise order
      with each turning angle < pi
    
    Returns: array of shape (14, 2)
    """
    edges = params.reshape(M, 2)
    
    # Build first half of polygon vertices
    # Start at origin, add edges
    first_half = np.zeros((M + 1, 2))
    for i in range(1, M + 1):
        first_half[i] = first_half[i-1] + edges[i-1]
    
    # The first M vertices are first_half[1:M+1]
    # The last M vertices are their negatives (central symmetry)
    # But we need to order them properly around the polygon
    
    # Vertices in order: v1, v2, ..., v7, -v7, -v6, ..., -v1
    # where vi = sum of first i edges
    vertices = np.zeros((N, 2))
    for i in range(M):
        vertices[i] = first_half[i+1]
    for i in range(M):
        vertices[M + i] = -first_half[M - i]
    
    return vertices

def _check_convexity(pts):
    """Check if points form a convex polygon (in order)."""
    n = len(pts)
    for i in range(n):
        p0 = pts[i]
        p1 = pts[(i+1) % n]
        p2 = pts[(i+2) % n]
        cross = (p1[0] - p0[0]) * (p2[1] - p1[1]) - (p1[1] - p0[1]) * (p2[0] - p1[0])
        if cross < -1e-10:
            return False
    return True

def _score_symmetric(params):
    """Compute score for symmetric polygon parameters."""
    if not np.all(np.isfinite(params)):
        return 0.0
    
    pts = _decode_symmetric(params)
    
    # Check convexity
    if not _check_convexity(pts):
        return 0.0
    
    hull_area = _hull_area(pts)
    if hull_area < 1e-10:
        return 0.0
    
    min_area = _min_triangle_area(pts)
    return min_area / hull_area

def _objective_symmetric(params):
    """Objective: minimize negative score."""
    score = _score_symmetric(params)
    if score < 1e-10:
        return 1e10
    return -score

def construct():
    start_time = time.time()
    deadline = start_time + 115.0  # Safety margin
    
    best_score = 0.0
    best_params = None
    best_obj = float('inf')
    
    def update_best(params):
        nonlocal best_score, best_params, best_obj
        if params is None:
            return
        obj = _objective_symmetric(params)
        if obj < best_obj:
            best_obj = obj
            best_params = params.copy()
            best_score = -obj

    # Initial guess: Regular 14-gon as centrally symmetric polygon
    # Regular 14-gon has 7 unique edge vectors (by central symmetry)
    # Each edge vector for regular 14-gon with circumradius 1:
    # Edge length = 2*sin(pi/14)
    # Direction of edge i: angle = -pi/2 + (i-0.5)*2*pi/14 for i=0,...,13
    # By symmetry, edges 0-6 are the independent ones
    
    edge_len = 2 * np.sin(np.pi / 14)
    angles = np.array([(-np.pi/2 + (i + 0.5) * 2 * np.pi / 14) for i in range(M)])
    
    x0 = np.zeros(M * 2)
    for i in range(M):
        x0[2*i] = edge_len * np.cos(angles[i])
        x0[2*i+1] = edge_len * np.sin(angles[i])
    
    update_best(x0)
    
    # Phase 1: Differential Evolution on 14-dim space
    # Bounds: edge components in [-2, 2]
    bounds = [(-2.0, 2.0)] * (M * 2)
    
    if time.time() < deadline - 30:
        try:
            de_res = differential_evolution(
                _objective_symmetric, bounds,
                seed=42, maxiter=100, tol=1e-8,
                popsize=20, mutation=(0.5, 1.0), recombination=0.7,
                polish=False, update_interval=1,
                init='sobol'
            )
            if de_res.fun < best_obj:
                update_best(de_res.x)
        except Exception:
            pass
    
    # Phase 2: Powell refinement
    if best_params is not None and time.time() < deadline - 10:
        try:
            res_powell = minimize(
                _objective_symmetric, best_params, method='Powell',
                options={'maxiter': 3000, 'xtol': 1e-12, 'ftol': 1e-14, 'disp': False}
            )
            if res_powell.fun < best_obj:
                update_best(res_powell.x)
        except Exception:
            pass
    
    # Phase 3: Nelder-Mead polish
    if best_params is not None and time.time() < deadline - 3:
        try:
            res_nm = minimize(
                _objective_symmetric, best_params, method='Nelder-Mead',
                options={'maxiter': 5000, 'xatol': 1e-10, 'fatol': 1e-12, 'adaptive': True, 'disp': False}
            )
            if res_nm.fun < best_obj:
                update_best(res_nm.x)
        except Exception:
            pass
    
    # Fallback
    if best_params is None:
        best_params = x0
    
    # Convert to Cartesian points
    pts = _decode_symmetric(best_params)
    
    # Normalize to unit area
    try:
        hull = ConvexHull(pts)
        area = hull.volume
        if area > 1e-10:
            scale = np.sqrt(1.0 / area)
            pts = pts * scale
    except Exception:
        pass
    
    return pts
