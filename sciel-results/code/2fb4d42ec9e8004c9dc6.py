import time
import random
import numpy as np

TOTAL_BUDGET = 60.0
SAFETY_MARGIN = 5.0
DEADLINE = TOTAL_BUDGET - SAFETY_MARGIN

def _hamming(a, b):
    return (a ^ b).bit_count()

def _check_min_distance(words, min_dist):
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            if _hamming(wi, words[j]) < min_dist:
                return False
    return True

def _reed_muller_extended():
    """
    Generate the [16, 5, 6] extended Reed-Muller code.
    This serves as a high-quality seed for the local search.
    """
    words = []
    # The RM(1,4) code has 32 codewords.
    # It is generated by all affine functions f(x) = a.x + b over GF(2)^4.
    for a in range(16):
        for b in range(2):
            word = 0
            for x in range(16):
                # Dot product a.x over GF(2) is parity of (a & x)
                bit = ((a & x).bit_count() + b) % 2
                if bit:
                    word |= (1 << x)
            words.append(word)
    return words

def _try_add_word(code, N, min_dist, rng, max_attempts=1000):
    """
    Try to add a random word to the code.
    Returns True if a word was added.
    """
    for _ in range(max_attempts):
        cand = rng.randint(0, (1 << N) - 1)
        # Check if cand is already in code (optional optimization, but set logic handles it)
        # Check distance to all existing words
        ok = True
        for w in code:
            if _hamming(cand, w) < min_dist:
                ok = False
                break
        if ok:
            code.append(cand)
            return True
    return False

def _local_search_improve(code, N, min_dist, time_limit, rng):
    """
    Iteratively improve the code size by trying to add new words.
    If stuck, try to 'shake' the code by replacing a word with a random one
    to potentially open up space for more words later (heuristic).
    """
    start_time = time.time()
    best_code = list(code)
    current_size = len(best_code)
    
    while time.time() - start_time < time_limit:
        # 1. Try to add a new word
        added = _try_add_word(best_code, N, min_dist, rng, max_attempts=50)
        
        if added:
            current_size = len(best_code)
            # Reset attempts counter implicitly by continuing loop
            continue
        
        # 2. If we couldn't add a word, try a local mutation (swap)
        # This is a heuristic to escape local optima.
        # Pick a random index and replace it with a random word.
        # Only accept if the code remains valid (it will, since we replace one word)
        # AND if we can subsequently add at least one word? 
        # Actually, simple swap doesn't guarantee size increase. 
        # A better heuristic: Random Restart or Simulated Annealing.
        
        # Let's use a simpler "Random Restart" strategy if stuck for too long.
        # But since we want to maximize size, let's try "Greedy with Backtracking" lite.
        
        # Alternative: Try to find a word that is 'close' to the existing code
        # but allows adding more words.
        
        # For simplicity and robustness within time limits, let's just do multiple random restarts
        # if the current trajectory stalls.
        
        # Check if we've been stuck for a while
        # We don't track 'stuck' time explicitly here, so let's just try a few swaps.
        
        # Let's try a swap: pick a random word w_i, remove it, pick random w_new.
        # If the new code is valid, keep it. (Size stays same, but structure changes).
        # This might allow future additions.
        
        if len(best_code) > 0:
            idx = rng.randint(0, len(best_code) - 1)
            old_word = best_code[idx]
            new_word = rng.randint(0, (1 << N) - 1)
            
            # Check if new_word is valid with respect to all OTHER words
            ok = True
            for j, w in enumerate(best_code):
                if j == idx:
                    continue
                if _hamming(new_word, w) < min_dist:
                    ok = False
                    break
            
            if ok:
                best_code[idx] = new_word
                # After swap, try to add again immediately
                # (Loop continues, so _try_add_word will be called)
                
    return best_code

def construct():
    N = 18
    MIN_DIST = 6
    start = time.time()
    
    # 1. Initialize with Reed-Muller code (32 words)
    # This is a valid code with d=6.
    initial_code = _reed_muller_extended()
    
    # Verify initial code
    if not _check_min_distance(initial_code, MIN_DIST):
        # Fallback to empty if RM fails (should not happen)
        initial_code = [0]
        
    best_code = list(initial_code)
    best_size = len(best_code)
    
    # 2. Local Search with Multiple Restarts
    # We will run several independent search trajectories.
    # Each trajectory starts from the RM code and tries to grow it.
    
    # Estimate time per trajectory
    # We have ~55 seconds.
    # Let's allow up to 10 trajectories, each getting ~5 seconds.
    num_restarts = 10
    time_per_restart = (DEADLINE - (time.time() - start)) / num_restarts
    
    for i in range(num_restarts):
        if time.time() > DEADLINE:
            break
            
        # Use a different seed for each restart to explore different regions
        rng = random.Random(42 + i)
        
        # Start from the same base (RM code)
        current_code = list(initial_code)
        
        # Run local search
        improved_code = _local_search_improve(current_code, N, MIN_DIST, time_per_restart, rng)
        
        if len(improved_code) > best_size:
            best_code = improved_code
            best_size = len(best_code)
            
            # If we found a significantly larger code, we might want to
            # use it as the new base for subsequent restarts?
            # For now, we stick to independent restarts from RM to ensure diversity.
            # However, if we find a huge code, extending it is faster.
            # Let's add a "polish" phase on the best code found so far.
            
    # 3. Final Polish on the best code found
    # Use remaining time to try to add more words to the best code.
    elapsed = time.time() - start
    time_remaining = DEADLINE - elapsed
    
    if time_remaining > 1.0:
        rng = random.Random(999)
        # Try to add more words to the best code
        # We use a dedicated function for this final push
        final_code = list(best_code)
        
        # Simple greedy addition loop
        while time.time() - elapsed < time_remaining - 0.5:
            added = _try_add_word(final_code, N, MIN_DIST, rng, max_attempts=100)
            if not added:
                # If we can't add, break to avoid wasting time
                break
        
        if len(final_code) > best_size:
            best_code = final_code
            best_size = len(best_code)

    # Final verification
    if not _check_min_distance(best_code, MIN_DIST):
        # This should not happen if logic is correct, but safe guard
        # Fallback to RM code
        best_code = initial_code
        
    return best_code
