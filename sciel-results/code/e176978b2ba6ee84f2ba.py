"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
DIMENSIONS = [2, 2, 3]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 11
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Strassen part (r=0..6) for k=0,1
    # U indices: 00(0), 01(1), 10(2), 11(3)
    # V indices: 00(0), 01(1), 02(2), 10(3), 11(4), 12(5)
    # W indices: 00(0), 10(1), 01(2), 11(3), 02(4), 12(5)
    
    # r=0: M1 = (a+d)(e+h)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[4][0] = 1
    W[0][0] = 1; W[1][0] = -1; W[2][0] = 1; W[3][0] = 0
    
    # r=1: M2 = (c+d)(e+f)
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1; V[1][1] = 1
    W[0][1] = 0; W[1][1] = 1; W[2][1] = 0; W[3][1] = 1
    
    # r=2: M3 = (a-b)(g+h)
    U[0][2] = 1; U[1][2] = -1
    V[3][2] = 1; V[4][2] = 1
    W[0][2] = 0; W[1][2] = 0; W[2][2] = 0; W[3][2] = -1
    
    # r=3: M4 = d(f-h)
    U[3][3] = 1
    V[1][3] = 1; V[4][3] = -1
    W[0][3] = -1; W[1][3] = 0; W[2][3] = 1; W[3][3] = 1
    
    # r=4: M5 = a(e-g)
    U[0][4] = 1
    V[0][4] = 1; V[3][4] = -1
    W[0][4] = 1; W[1][4] = 0; W[2][4] = -1; W[3][4] = 0
    
    # r=5: M6 = (b+c)(f+g)
    U[1][5] = 1; U[2][5] = 1
    V[1][5] = 1; V[3][5] = 1
    W[0][5] = 0; W[1][5] = 1; W[2][5] = -1; W[3][5] = 0
    
    # r=6: M7 = (a+c)(e-f)
    U[0][6] = 1; U[2][6] = 1
    V[0][6] = 1; V[1][6] = -1
    W[0][6] = -1; W[1][6] = 1; W[2][6] = 0; W[3][6] = -1
    
    # Schoolbook part (r=7..10) for k=2
    # r=7: a * x3
    U[0][7] = 1
    V[2][7] = 1
    W[4][7] = 1
    
    # r=8: b * y3
    U[1][8] = 1
    V[5][8] = 1
    W[4][8] = 1
    
    # r=9: c * x3
    U[2][9] = 1
    V[2][9] = 1
    W[5][9] = 1
    
    # r=10: d * y3
    U[3][10] = 1
    V[5][10] = 1
    W[5][10] = 1
    
    return {"U": U, "V": V, "W": W}
# EVOLVE-BLOCK-END
