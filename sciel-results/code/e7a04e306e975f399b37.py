# This is getting complex. Let me use a simpler but still high-order approach.
# I'll use RK45 (Dormand-Prince 5(4,3)) with very tight tolerances and many steps.

def integrate(f, t_span, y0):
    """
    Integrate the Lorenz system from t_span[0] to t_span[1] starting at y0.
    Uses adaptive RK45 with very tight tolerances for high accuracy.
    """
    start_time = time.time()
    deadline = start_time + 280  # Safety margin before 330s limit
    
    t0, t1 = t_span
    y = np.array(y0, dtype=float)
    n = len(y)
    
    # Adaptive RK45 (Dormand-Prince 5(4,3))
    # Coefficients
    a2 = 1/5
    a3 = 3/10
    a4 = 4/5
    a5 = 8/9
    a6 = 1.0
    a7 = 1.0
    
    b2_1 = 1/5
    b3_1 = 3/40
    b3_2 = 9/40
    b4_1 = 44/45
    b4_2 = -56/15
    b4_3 = 32/9
    b5_1 = 19372/6561
    b5_2 = -25360/2187
    b5_3 = 64448/6561
    b5_4 = -212/729
    b6_1 = 9017/3168
    b6_2 = -355/33
    b6_3 = 46732/5247
    b6_4 = 49/176
    b6_5 = -5103/18656
    b7_1 = 35/384
    b7_2 = 0
    b7_3 = 500/1113
    b7_4 = 125/192
    b7_5 = -2187/6784
    b7_6 = 11/84
    
    # Error coefficients (5th order - 4th order)
    e1 = 71/57600
    e2 = 0
    e3 = -71/16695
    e4 = 71/1920
    e5 = -17253/339200
    e6 = 22/525
    e7 = -1/40
    
    # Adaptive stepping
    rtol = 1e-12
    atol = 1e-14
    
    h = 0.01  # Initial step size
    t = t0
    max_steps = 100000
    step_count = 0
    
    for _ in range(max_steps):
        if time.time() > deadline:
            break
        
        if t >= t1:
            break
        
        # Don't overshoot t1
        if t + h > t1:
            h = t1 - t
        if h <= 0:
            break
        
        # RK45 step
        k1 = f(t, y)
        k2 = f(t + a2*h, y + h*b2_1*k1)
        k3 = f(t + a3*h, y + h*(b3_1*k1 + b3_2*k2))
        k4 = f(t + a4*h, y + h*(b4_1*k1 + b4_2*k2 + b4_3*k3))
        k5 = f(t + a5*h, y + h*(b5_1*k1 + b5_2*k2 + b5_3*k3 + b5_4*k4))
        k6 = f(t + h, y + h*(b6_1*k1 + b6_2*k2 + b6_3*k3 + b6_4*k4 + b6_5*k5))
        k7 = f(t + h, y + h*(b7_1*k1 + b7_3*k3 + b7_4*k4 + b7_5*k5 + b7_6*k6))
        
        # 5th order solution
        y_new = y + h*(b7_1*k1 + b7_3*k3 + b7_4*k4 + b7_5*k5 + b7_6*k6)
        
        # Error estimate
        err = h*(e1*k1 + e3*k3 + e4*k4 + e5*k5 + e6*k6 + e7*k7)
        
        # Error norm
        scale = atol + rtol * np.maximum(np.abs(y), np.abs(y_new))
        err_norm = np.sqrt(np.sum((err/scale)**2))
        
        if err_norm <= 1.0:
            # Accept step
            y = y_new
            t += h
            step_count += 1
            
            # Adjust step size
            if err_norm > 0:
                h *= min(5.0, max(0.1, 0.9 * err_norm**(-0.2)))
            else:
                h *= 2.0
        else:
            # Reject step, reduce h
            h *= max(0.1, 0.9 * err_norm**(-0.25))
            if h < 1e-10:
                h = 1e-10
        
        if not np.all(np.isfinite(y)):
            break
    
    return y
