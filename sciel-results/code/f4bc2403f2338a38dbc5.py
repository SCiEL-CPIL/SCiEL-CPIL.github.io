import time

def construct():
    _t0 = time.time()
    deadline = _t0 + 138.0  # safety margin under the 150s kill

    n, m, p = 3, 4, 6  # C(n x p) = A(n x m) * B(m x p)

    def _u(i, k):
        return i * m + k
    def _v(k, j):
        return k * p + j
    def _w(j, i):
        return j * n + i  # trace convention W[k*n+i, r]

    # Each term: (list of U rows, list of V rows, list of W rows); entries are +/-1.
    # M1..M7 = Strassen 2x2; S1..S4 = 1x2*2x2 schoolbook (rank 4).
    terms = [
        # block (j=0, B cols 0,1)
        ([_u(0,0)],  [_v(0,0)], [_w(0,0)]),  # S1
        ([_u(0,1)],  [_v(1,0)], [_w(0,0)]),  # S2
        ([_u(0,0)],  [_v(0,1)], [_w(1,0)]),  # S3
        ([_u(0,1)],  [_v(1,1)], [_w(1,0)]),  # S4
        ([_u(1,0),_u(2,1)], [_v(0,0),_v(1,1)], [_w(0,1),_w(1,2)]),   # M1
        ([_u(2,0),_u(2,1)], [_v(0,0)],          [_w(0,2),_w(1,1)]),   # M2 (C11 -1)
        ([_u(1,0)],          [_v(0,1),_v(1,1)], [_w(1,1),_w(1,2)]),   # M3
        ([_u(2,1)],          [_v(1,0),_v(0,0)], [_w(0,1),_w(0,2)]),   # M4
        ([_u(1,0),_u(1,1)], [_v(1,1)],          [_w(0,0),_w(1,1)]),   # M5 (C00 -1)
        ([_u(2,0),_u(1,0)], [_v(0,0),_v(0,1)], [_w(1,2)]),            # M6 (A00 -1)
        ([_u(1,1),_u(2,1)], [_v(1,0),_v(1,1)], [_w(0,0)]),            # M7 (A11 -1)
        # block (j=1, B cols 2,3)
        ([_u(0,0)],  [_v(0,2)], [_w(2,0)]),  # S1
        ([_u(0,1)],  [_v(1,2)], [_w(2,0)]),  # S2
        ([_u(0,0)],  [_v(0,3)], [_w(3,0)]),  # S3
        ([_u(0,1)],  [_v(1,3)], [_w(3,0)]),  # S4
        ([_u(1,0),_u(2,1)], [_v(0,2),_v(1,3)], [_w(2,1),_w(3,2)]),   # M1
        ([_u(2,0),_u(2,1)], [_v(0,2)],          [_w(2,2),_w(3,1)]),   # M2 (C11 -1)
        ([_u(1,0)],          [_v(0,3),_v(1,3)], [_w(3,1),_w(3,2)]),   # M3
        ([_u(2,1)],          [_v(1,2),_v(0,2)], [_w(2,1),_w(2,2)]),   # M4
        ([_u(1,0),_u(1,1)], [_v(1,3)],          [_w(2,0),_w(3,1)]),   # M5 (C00 -1)
        ([_u(2,0),_u(1,0)], [_v(0,2),_v(0,3)], [_w(3,2)]),            # M6 (A00 -1)
        ([_u(1,1),_u(2,1)], [_v(1,2),_v(1,3)], [_w(2,0)]),            # M7 (A11 -1)
        # block (j=2, B cols 4,5)
        ([_u(0,0)],  [_v(0,4)], [_w(4,0)]),  # S1
        ([_u(0,1)],  [_v(1,4)], [_w(4,0)]),  # S2
        ([_u(0,0)],  [_v(0,5)], [_w(5,0)]),  # S3
        ([_u(0,1)],  [_v(1,5)], [_w(5,0)]),  # S4
        ([_u(1,0),_u(2,1)], [_v(0,4),_v(1,5)], [_w(4,1),_w(5,2)]),   # M1
        ([_u(2,0),_u(2,1)], [_v(0,4)],          [_w(4,2),_w(5,1)]),   # M2 (C11 -1)
        ([_u(1,0)],          [_v(0,5),_v(1,5)], [_w(5,1),_w(5,2)]),   # M3
        ([_u(2,1)],          [_v(1,4),_v(0,4)], [_w(4,1),_w(4,2)]),   # M4
        ([_u(1,0),_u(1,1)], [_v(1,5)],          [_w(4,0),_w(5,1)]),   # M5 (C00 -1)
        ([_u(2,0),_u(1,0)], [_v(0,4),_v(0,5)], [_w(5,2)]),            # M6 (A00 -1)
        ([_u(1,1),_u(2,1)], [_v(1,4),_v(1,5)], [_w(4,0)]),            # M7 (A11 -1)
        # rows 1-2, A cols 2,3 (second A column pair per block)
        # block (j=0)
        ([_u(0,2)],  [_v(2,0)], [_w(0,0)]),  # S1
        ([_u(0,3)],  [_v(3,0)], [_w(0,0)]),  # S2
        ([_u(0,2)],  [_v(2,1)], [_w(1,0)]),  # S3
        ([_u(0,3)],  [_v(3,1)], [_w(1,0)]),  # S4
        ([_u(1,2),_u(2,3)], [_v(2,0),_v(3,1)], [_w(0,1),_w(1,2)]),   # M1
        ([_u(2,2),_u(2,3)], [_v(2,0)],          [_w(0,2),_w(1,1)]),   # M2 (C11 -1)
        ([_u(1,2)],          [_v(2,1),_v(3,1)], [_w(1,1),_w(1,2)]),   # M3
        ([_u(2,3)],          [_v(3,0),_v(2,0)], [_w(0,1),_w(0,2)]),   # M4
        ([_u(1,2),_u(1,3)], [_v(3,1)],          [_w(0,0),_w(1,1)]),   # M5 (C00 -1)
        ([_u(2,2),_u(1,2)], [_v(2,0),_v(2,1)], [_w(1,2)]),            # M6 (A00 -1)
        ([_u(1,3),_u(2,3)], [_v(3,0),_v(3,1)], [_w(0,0)]),            # M7 (A11 -1)
        # block (j=1)
        ([_u(0,2)],  [_v(2,2)], [_w(2,0)]),  # S1
        ([_u(0,3)],  [_v(3,2)], [_w(2,0)]),  # S2
        ([_u(0,2)],  [_v(2,3)], [_w(3,0)]),  # S3
        ([_u(0,3)],  [_v(3,3)], [_w(3,0)]),  # S4
        ([_u(1,2),_u(2,3)], [_v(2,2),_v(3,3)], [_w(2,1),_w(3,2)]),   # M1
        ([_u(2,2),_u(2,3)], [_v(2,2)],          [_w(2,2),_w(3,1)]),   # M2 (C11 -1)
        ([_u(1,2)],          [_v(2,3),_v(3,3)], [_w(3,1),_w(3,2)]),   # M3
        ([_u(2,3)],          [_v(3,2),_v(2,2)], [_w(2,1),_w(2,2)]),   # M4
        ([_u(1,2),_u(1,3)], [_v(3,3)],          [_w(2,0),_w(3,1)]),   # M5 (C00 -1)
        ([_u(2,2),_u(1,2)], [_v(2,2),_v(2,3)], [_w(3,2)]),            # M6 (A00 -1)
        ([_u(1,3),_u(2,3)], [_v(3,2),_v(3,3)], [_w(2,0)]),            # M7 (A11 -1)
        # block (j=2)
        ([_u(0,2)],  [_v(2,4)], [_w(4,0)]),  # S1
        ([_u(0,3)],  [_v(3,4)], [_w(4,0)]),  # S2
        ([_u(0,2)],  [_v(2,5)], [_w(5,0)]),  # S3
        ([_u(0,3)],  [_v(3,5)], [_w(5,0)]),  # S4
        ([_u(1,2),_u(2,3)], [_v(2,4),_v(3,5)], [_w(4,1),_w(5,2)]),   # M1
        ([_u(2,2),_u(2,3)], [_v(2,4)],          [_w(4,2),_w(5,1)]),   # M2 (C11 -1)
        ([_u(1,2)],          [_v(2,5),_v(3,5)], [_w(5,1),_w(5,2)]),   # M3
        ([_u(2,3)],          [_v(3,4),_v(2,4)], [_w(4,1),_w(4,2)]),   # M4
        ([_u(1,2),_u(1,3)], [_v(3,5)],          [_w(4,0),_w(5,1)]),   # M5 (C00 -1)
        ([_u(2,2),_u(1,2)], [_v(2,4),_v(2,5)], [_w(5,2)]),            # M6 (A00 -1)
        ([_u(1,3),_u(2,3)], [_v(3,4),_v(3,5)], [_w(4,0)]),            # M7 (A11 -1)
    ]

    RANK = len(terms)  # 66

    U = [[0] * RANK for _ in range(n * m)]
    V = [[0] * RANK for _ in range(m * p)]
    W = [[0] * RANK for _ in range(p * n)]

    for r, (uu, vv, ww) in enumerate(terms):
        for a in uu:
            U[a][r] = 1
        for b in vv:
            V[b][r] = 1
        for c in ww:
            W[c][r] = 1

    # Exact verification against the multiplication tensor:
    # sum_r U[i*m+k][r] * V[k*p+j][r] * W[j*n+i][r] == 1 iff (i,k,j) is a
    # multiplication triple (always, here since k is shared), else 0.
    for i in range(n):
        for k in range(m):
            for j in range(p):
                s = 0
                for r in range(RANK):
                    s += U[i*m+k][r] * V[k*p+j][r] * W[j*n+i][r]
                if s != 1:
                    raise RuntimeError("decomposition failed at (i,k,j)=%s" % ((i,k,j),))
        if time.time() > deadline:
            break

    return {"U": U, "V": V, "W": W}
