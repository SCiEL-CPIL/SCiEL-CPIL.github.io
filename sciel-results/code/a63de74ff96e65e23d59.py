"""Parametric Block-Pulse Strategy: Differential Evolution on geometric parameters."""
import numpy as np
import time
from scipy.optimize import differential_evolution

N = 400
# Number of blocks to use in the parametric model
K = 20 

# EVOLVE-BLOCK-START

def _autoconv(x):
    """Compute full linear autoconvolution of x (length N) -> length 2N-1."""
    n = 2 * N
    X = np.fft.fft(x, n=n)
    C = np.fft.ifft(X * X).real[:2*N-1]
    return C

def _eval_ratio(x):
    """Compute the raw value: max|c_k| / (sum x)^2 for k != 0."""
    c = _autoconv(x)
    s = np.sum(x)
    if abs(s) < 1e-12:
        return np.inf
    if len(c) > 1:
        max_sidelobe = np.max(np.abs(c[1:]))
    else:
        max_sidelobe = 0.0
    return max_sidelobe / (s * s)

def _blocks_to_signal(params):
    """
    Convert parametric representation to a signal of length N.
    params: array of shape (K, 3) where each row is [start, width, amplitude]
    start: float in [0, N)
    width: float in [1, N]
    amplitude: float in [-1, 1]
    Returns: array of shape (N,)
    """
    signal = np.zeros(N, dtype=float)
    for i in range(K):
        start, width, amp = params[i]
        # Ensure valid range
        s_idx = int(np.floor(start))
        w_int = int(np.floor(width))
        if w_int < 1:
            w_int = 1
        # Clip to N
        end_idx = min(N, s_idx + w_int)
        if s_idx >= N or end_idx <= s_idx:
            continue
        signal[s_idx:end_idx] += amp
    return signal

def _objective(params):
    """
    Objective function for Differential Evolution.
    Minimizes the autoconvolution ratio of the signal generated by the blocks.
    """
    signal = _blocks_to_signal(params)
    # If the signal is zero, return a large penalty
    s_sum = np.sum(signal)
    if abs(s_sum) < 1e-6:
        return 1e6
    
    c = _autoconv(signal)
    max_sidelobe = np.max(np.abs(c[1:]))
    ratio = max_sidelobe / (s_sum * s_sum)
    
    # Add a small penalty for non-binary signals to encourage sharp transitions?
    # Actually, we just want the geometry to be good. The final step will round.
    # But rounding can change the ratio. 
    # To guide DE better, we can evaluate the rounded version occasionally or just trust the continuous relaxation.
    # Let's evaluate the continuous ratio, but also check the rounded one to see if it's significantly worse.
    # For speed in DE, we stick to continuous. The local search will fix rounding issues.
    
    return ratio

def _local_search(x, max_time=10.0):
    """
    Local search: flip single elements to reduce the peak ratio.
    x: binary array (+1/-1)
    """
    start_time = time.time()
    s = x.copy().astype(np.int8)
    v = _eval_ratio(s)
    best_local = s.copy()
    best_local_v = v
    
    # Pre-compute autoconv
    ac = _autoconv(s)
    peak = np.max(np.abs(ac[1:]))
    s_sum = s.sum()
    denom = s_sum * s_sum
    
    # Simple hill climbing with a few restarts or just one pass
    # Since N=400, one pass is 400 FFTs. ~400 * 0.001s = 0.4s.
    # We can do multiple passes.
    
    for _round in range(50):
        if time.time() > start_time + max_time:
            break
        improved = False
        for i in range(N):
            if time.time() > start_time + max_time:
                break
            
            old_val = s[i]
            new_val = -old_val
            
            # Quick estimate? No, just recompute.
            s[i] = new_val
            ac2 = _autoconv(s)
            peak2 = np.max(np.abs(ac2[1:]))
            s_sum2 = s.sum()
            denom2 = s_sum2 * s_sum2
            v2 = peak2 / denom2 if denom2 != 0 else peak2
            
            if v2 < best_local_v - 1e-12:
                best_local_v = v2
                best_local = s.copy()
                improved = True
            else:
                s[i] = old_val # revert
        
        if not improved:
            break
        s = best_local.copy()
    
    return best_local, best_local_v

def construct():
    start_time = time.time()
    deadline = start_time + 140  # 10s safety margin
    
    # 1. Parametric Optimization via Differential Evolution
    # Bounds: start [0, N), width [1, N], amp [-1, 1]
    bounds = [(0, N - 1), (1, N), (-1, 1)] * K
    
    # Use a fixed seed for reproducibility in the evaluator if needed, but DE is stochastic.
    # The task allows randomness.
    
    best_params = None
    best_obj = np.inf
    
    # Run DE with limited maxiter to stay within time budget
    # K=20 -> 60 params. DE population size is typically 15*dim = 900.
    # 900 evaluations per generation. 
    # If we run 50 generations, that's 45,000 evaluations.
    # Each eval: 20 blocks -> signal (400) -> FFT (400) -> ifft -> max. ~0.1ms?
    # 45,000 * 0.1ms = 4.5s. This is fast enough.
    
    try:
        res = differential_evolution(
            _objective, 
            bounds, 
            maxiter=100, 
            popsize=15, 
            tol=1e-4, 
            seed=42,
            polish=False, # We do our own polish
            callback=lambda xk, convergence: None
        )
        
        if time.time() < deadline - 20: # Check time
            if res.fun < best_obj:
                best_obj = res.fun
                best_params = res.x
                
    except Exception as e:
        pass # Fallback to random if DE fails

    # 2. Convert best params to signal and round
    if best_params is not None:
        signal = _blocks_to_signal(best_params)
        # Round to nearest +1/-1
        # If sum is 0, we might have a problem. 
        # Ensure non-zero sum by biasing if necessary?
        # Simple rounding: sign(x)
        x_binary = np.sign(signal)
        x_binary[x_binary == 0] = 1 # Default to 1 if exactly 0
        
        # Check if sum is 0
        if np.sum(x_binary) == 0:
            # Flip the largest magnitude element? Or just add a constant bias?
            # Better: try flipping a few elements to make sum non-zero
            # Actually, if sum is 0, ratio is inf. 
            # Let's force a bias.
            x_binary = np.ones(N, dtype=np.int8)
    else:
        # Fallback: Random initialization
        x_binary = np.random.choice([1, -1], size=N, p=[0.8, 0.2]).astype(np.int8)

    # 3. Local Search Polish
    # Use remaining time for local search
    remaining_time = max(1.0, deadline - time.time())
    x_polished, v_polished = _local_search(x_binary, max_time=remaining_time)
    
    # 4. Compare with a few random restarts just in case DE got stuck in a bad local min
    # (Though DE is global, the parametric space might have bad minima)
    best_x = x_polished
    best_val = v_polished
    
    # Try 5 random binary initializations with local search
    for _ in range(5):
        if time.time() > deadline - 5:
            break
        x_rand = np.random.choice([1, -1], size=N, p=[0.8, 0.2]).astype(np.int8)
        x_rand_pol, v_rand_pol = _local_search(x_rand, max_time=2.0)
        if v_rand_pol < best_val:
            best_val = v_rand_pol
            best_x = x_rand_pol

    return best_x

