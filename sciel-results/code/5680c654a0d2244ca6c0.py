# EVOLVE-BLOCK-START
import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 145  # Safety margin before 150s limit
    
    n = 20
    
    def popcount(x):
        """Fast popcount for Python integers."""
        return bin(x).count('1')
    
    def can_add(adj_bits, u, v):
        """
        Check if adding edge (u,v) to graph with adjacency bitmasks adj_bits
        maintains K2,3-freeness.
        """
        # Condition 1: common neighbors of u and v
        common_uv = popcount(adj_bits[u] & adj_bits[v])
        if common_uv > 2:
            return False
        
        # Condition 2: for each w in N(v), w != u
        nv = adj_bits[v]
        w = nv
        while w:
            low = w & (-w)
            wi = low.bit_length() - 1
            w ^= low
            if wi == u:
                continue
            # N(u) gains v, and v~w, so v becomes common neighbor of u and w
            common_uw = popcount(adj_bits[u] & adj_bits[wi])
            if common_uw > 1:
                return False
        
        # Condition 3: for each w in N(u), w != v
        nu = adj_bits[u]
        w = nu
        while w:
            low = w & (-w)
            wi = low.bit_length() - 1
            w ^= low
            if wi == v:
                continue
            common_vw = popcount(adj_bits[v] & adj_bits[wi])
            if common_vw > 1:
                return False
        
        return True

    def get_polarity_graph_21():
        """
        Construct the polarity graph of PG(2,4) (21 vertices).
        Vertices are non-zero vectors in GF(4)^3.
        Two vertices are adjacent if their dot product is 0.
        """
        # GF(4) elements: 0, 1, alpha, alpha+1
        # Let alpha be a root of x^2 + x + 1 = 0 in GF(2)[x]
        # So alpha^2 = alpha + 1, alpha^3 = 1
        # We represent elements as integers 0..3
        # 0: 0
        # 1: 1
        # 2: alpha
        # 3: alpha+1
        
        # Addition table (XOR)
        # Multiplication table
        # 0*x = 0
        # 1*x = x
        # alpha * 1 = alpha (2)
        # alpha * alpha = alpha^2 = alpha+1 (3)
        # alpha * (alpha+1) = alpha^2 + alpha = (alpha+1) + alpha = 1
        # (alpha+1) * (alpha+1) = alpha^2 + 2alpha + 1 = (alpha+1) + 0 + 1 = alpha (2)
        
        mult_table = [
            [0, 0, 0, 0],
            [0, 1, 2, 3],
            [0, 2, 3, 1],
            [0, 3, 1, 2]
        ]
        
        # Dot product in GF(4)
        def dot(v1, v2):
            return mult_table[v1[0]][v2[0]] ^ mult_table[v1[1]][v2[1]] ^ mult_table[v1[2]][v2[2]]
        
        # Generate all non-zero vectors in GF(4)^3
        vectors = []
        for a in range(4):
            for b in range(4):
                for c in range(4):
                    if a != 0 or b != 0 or c != 0:
                        vectors.append((a, b, c))
        
        # There are 4^3 - 1 = 63 vectors.
        # However, in PG(2,4), points are 1-dimensional subspaces.
        # Each subspace has 4-1=3 non-zero vectors.
        # So there are 63/3 = 21 points.
        
        # We need to map each point (subspace) to a representative.
        # We can just pick the first non-zero vector in each subspace.
        # A subspace is generated by v if w = c*v for some c != 0.
        
        points = []
        visited = set()
        
        for v in vectors:
            if v in visited:
                continue
            
            # Find all non-zero vectors in this subspace
            subspace = [v]
            # Multiply by 2 and 3
            v2 = (mult_table[2][v[0]], mult_table[2][v[1]], mult_table[2][v[2]])
            v3 = (mult_table[3][v[0]], mult_table[3][v[1]], mult_table[3][v[2]])
            subspace.append(v2)
            subspace.append(v3)
            
            # Mark all as visited
            for s in subspace:
                visited.add(s)
            
            # Add representative v to points
            points.append(v)
        
        # Now construct the graph on these 21 points.
        # Two points (represented by vectors v, w) are adjacent if dot(v, w) == 0.
        # Note: In a polarity graph, self-adjacency is possible (absolute points).
        # The problem asks for a simple graph, so we ignore self-loops.
        # Also, the polarity graph of PG(2,4) is known to be K2,3-free.
        
        adj_21 = [0] * 21
        for i in range(21):
            for j in range(21):
                if i == j:
                    continue
                if dot(points[i], points[j]) == 0:
                    adj_21[i] |= (1 << j)
                    adj_21[j] |= (1 << i)
        
        return adj_21

    def construct_20_from_21(adj_21):
        """
        Delete one vertex from the 21-vertex polarity graph to get a 20-vertex graph.
        To maximize edges, we should delete a vertex with minimum degree.
        In the polarity graph of PG(2,4), the degree of a vertex is the number of absolute points
        on its polar line.
        Actually, let's just compute degrees and pick the min.
        """
        degrees = [popcount(adj_21[i]) for i in range(21)]
        min_deg_idx = min(range(21), key=lambda i: degrees[i])
        
        # Remove min_deg_idx
        # Map old indices to new indices
        # New indices are 0..19
        # Old indices are 0..20, excluding min_deg_idx
        
        adj_20 = [0] * 20
        edges = []
        
        mapping = {}
        new_idx = 0
        for i in range(21):
            if i == min_deg_idx:
                continue
            mapping[i] = new_idx
            new_idx += 1
        
        for i in range(21):
            if i == min_deg_idx:
                continue
            ni = mapping[i]
            for j in range(21):
                if j == min_deg_idx or j == i:
                    continue
                if adj_21[i] & (1 << j):
                    nj = mapping[j]
                    adj_20[ni] |= (1 << nj)
                    edges.append([ni, nj])
        
        return edges, adj_20

    def local_search_add_only(adj_bits, edges, rng, max_iters=100):
        """
        Try to add missing edges using a random greedy approach.
        """
        improved = True
        while improved:
            improved = False
            all_missing = [(i, j) for i in range(n) for j in range(i+1, n) 
                           if not (adj_bits[i] & (1 << j))]
            if not all_missing:
                break
            rng.shuffle(all_missing)
            for u, v in all_missing:
                if can_add(adj_bits, u, v):
                    adj_bits[u] |= (1 << v)
                    adj_bits[v] |= (1 << u)
                    edges.append([u, v])
                    improved = True
        return edges, adj_bits

    def local_search_swap(adj_bits, edges, rng, max_iters=200):
        """
        Local search: try removing one edge and adding two different edges?
        No, 1-for-1 swap is safer.
        Remove (u,v), add (x,y) if possible.
        """
        best_edges = list(edges)
        best_adj = list(adj_bits)
        best_count = len(best_edges)
        
        for _ in range(max_iters):
            if time.time() > deadline - 5:
                break
            
            cur_adj = list(adj_bits)
            cur_edges = list(edges)
            
            # Remove a random edge
            if not cur_edges:
                break
            rem_idx = rng.randint(0, len(cur_edges) - 1)
            u, v = cur_edges[rem_idx]
            cur_adj[u] &= ~(1 << v)
            cur_adj[v] &= ~(1 << u)
            cur_edges.pop(rem_idx)
            
            # Try to add a random missing edge
            all_missing = [(i, j) for i in range(n) for j in range(i+1, n) 
                           if not (cur_adj[i] & (1 << j))]
            if not all_missing:
                continue
            
            # Try a few random candidates
            rng.shuffle(all_missing)
            found = False
            for x, y in all_missing[:20]: # Try up to 20
                if can_add(cur_adj, x, y):
                    cur_adj[x] |= (1 << y)
                    cur_adj[y] |= (1 << x)
                    cur_edges.append([x, y])
                    found = True
                    break
            
            if found and len(cur_edges) > best_count:
                best_count = len(cur_edges)
                best_edges = cur_edges
                best_adj = cur_adj
                adj_bits = cur_adj
                edges = cur_edges
            else:
                # Revert
                adj_bits = list(best_adj)
                edges = list(best_edges)
        
        return edges, adj_bits, best_count

    # Main Strategy
    best_edges_overall = []
    best_count_overall = 0
    
    # 1. Polarity Graph Construction
    if time.time() < deadline - 10:
        adj_21 = get_polarity_graph_21()
        edges, adj_bits = construct_20_from_21(adj_21)
        
        # Verify K2,3-freeness (just in case)
        # The polarity graph is known to be K2,3-free.
        # Let's assume it is.
        
        # Improve with local search
        rng = random.Random(42)
        
        # First, fill in any missing edges greedily
        edges, adj_bits = local_search_add_only(adj_bits, edges, rng)
        
        # Then, try swaps to improve
        edges, adj_bits, count = local_search_swap(adj_bits, edges, rng, max_iters=100)
        
        if len(edges) > best_count_overall:
            best_count_overall = len(edges)
            best_edges_overall = edges
    
    # 2. Random Restart with Greedy Fill (Backup)
    # If polarity graph isn't optimal, maybe a random start + fill is better?
    # But polarity graph is a very strong seed.
    
    # Let's try a few random restarts to see if we can beat the polarity graph seed.
    # The polarity graph seed has ~115 edges.
    # ex(20, K2,3) is likely higher.
    
    for r in range(10):
        if time.time() > deadline - 5:
            break
        
        adj_bits = [0] * n
        edges = []
        
        # Random seed
        all_edges = [(i, j) for i in range(n) for j in range(i+1, n)]
        rng.shuffle(all_edges)
        
        # Add a random subset
        num_seed = rng.randint(20, 40)
        for u, v in all_edges[:num_seed]:
            if can_add(adj_bits, u, v):
                adj_bits[u] |= (1 << v)
                adj_bits[v] |= (1 << u)
                edges.append([u, v])
        
        # Greedy fill
        edges, adj_bits = local_search_add_only(adj_bits, edges, rng)
        
        # Local search
        edges, adj_bits, count = local_search_swap(adj_bits, edges, rng, max_iters=50)
        
        if len(edges) > best_count_overall:
            best_count_overall = len(edges)
            best_edges_overall = edges
    
    # 3. Final polish on the best solution
    if best_edges_overall and time.time() < deadline - 2:
        adj_bits = [0] * n
        for u, v in best_edges_overall:
            adj_bits[u] |= (1 << v)
            adj_bits[v] |= (1 << u)
        
        # Try to add any remaining edges
        edges, adj_bits = local_search_add_only(adj_bits, best_edges_overall, rng)
        
        if len(edges) > best_count_overall:
            best_count_overall = len(edges)
            best_edges_overall = edges
    
    return best_edges_overall
