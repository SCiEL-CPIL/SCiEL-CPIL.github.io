import numpy as np
import time
import itertools

def sign_edges(graph, budget):
    start_time = time.time()
    deadline = start_time + 50  # Safety margin for 60s limit
    
    n = graph['n']
    edges = graph['edges']
    m = n // 2
    
    # Build adjacency list and edge index map
    adj = [[] for _ in range(n)]
    for i, (u, v) in enumerate(edges):
        adj[u].append((v, i))
        adj[v].append((u, i))
        
    # Identify edge types:
    # 0..m-1 are cycle edges in top layer
    # m..2m-1 are cycle edges in bottom layer
    # 2m..3m-1 are matching edges (i, i+m)
    
    # For a prism graph, the edges are usually ordered:
    # Top cycle: (0,1), (1,2), ..., (m-1, 0)
    # Bottom cycle: (m, m+1), ..., (2m-1, m)
    # Matching: (0, m), (1, m+1), ..., (m-1, 2m-1)
    
    # Let's verify this structure and assign types
    edge_type = []
    for u, v in edges:
        if u < m and v < m:
            edge_type.append(0) # Top cycle
        elif u >= m and v >= m:
            edge_type.append(1) # Bottom cycle
        else:
            edge_type.append(2) # Matching
            
    # Strategy:
    # The signed adjacency matrix A has eigenvalues related to the lift.
    # To minimize the spectral radius of the base signed graph (which determines the lift's spectrum),
    # we want the product of signs around every cycle to be -1 if possible?
    # Actually, for a 2-lift, the eigenvalues of the lift are the eigenvalues of the base graph
    # "split" by the signs.
    
    # A known heuristic for minimizing the spectral radius of a signed graph is to make it "balanced" 
    # or "antibalanced". 
    # However, for a 2-lift to be connected, the signs must define a connected bipartite double cover.
    # The lift is disconnected iff the signs allow a bipartition of the base graph such that 
    # all edges go between same sides? No, that's for the base being bipartite.
    
    # Let's think about the structure.
    # The lift has 2n vertices.
    # If we assign +1 to all edges, the lift is two disjoint copies of the base graph (disconnected).
    # If we assign -1 to all edges, the lift is the bipartite double cover. For a bipartite base graph,
    # the bipartite double cover is two disjoint copies of the base graph (disconnected).
    # Prism graphs are bipartite only if m is even?
    # m=4: C4 x K2. C4 is bipartite. Prism is bipartite.
    # m=5: C5 x K2. C5 is not bipartite. Prism is not bipartite.
    # m=7: C7 x K2. Not bipartite.
    # m=9: C9 x K2. Not bipartite.
    
    # For non-bipartite graphs, the bipartite double cover (all -1) is connected?
    # The bipartite double cover of a connected non-bipartite graph is connected.
    # So for m=5,7,9, all -1 signs should yield a connected lift.
    # What is the spectral radius of the signed adjacency matrix for all -1?
    # The eigenvalues of the signed adjacency matrix of a graph with all -1 signs are the same as 
    # the eigenvalues of the unsigned adjacency matrix? No.
    # If A is the adjacency matrix, and we put -1 on every edge, the signed matrix is -A.
    # The eigenvalues of -A are -lambda_i.
    # The spectral radius is max |lambda_i|, which is the same as the unsigned spectral radius.
    
    # Can we do better?
    # The spectral radius of the signed adjacency matrix is the largest absolute eigenvalue.
    # We want to minimize this.
    # For a regular graph, the largest eigenvalue is the degree (if all +1).
    # By flipping signs, we can reduce the largest eigenvalue.
    
    # Heuristic: Random search with spectral radius evaluation is fast for small graphs.
    # m=9 -> n=18, edges=27. 2^27 is too big.
    # But we can use local search.
    
    best_radius = float('inf')
    best_signs = np.ones(len(edges))
    
    # Initialize with all -1 (connected for m=5,7,9)
    # For m=4, all -1 is disconnected. We need at least one +1 to connect?
    # Actually, if the base is bipartite, the bipartite double cover is two copies.
    # To connect them, we need an odd cycle in the sign pattern?
    # The lift is connected iff the subgroup of Z_2 generated by the cycle products is Z_2.
    # i.e., not all cycle products are +1.
    # If all signs are +1, all cycle products are +1 -> Disconnected.
    # If all signs are -1, cycle products are (-1)^length.
    # For m=4, cycles are length 4 (even) and 4 (even) and 4 (matching+2 cycle edges).
    # All cycles in C4xK2 have even length.
    # So all -1 gives +1 product for all cycles -> Disconnected.
    # So for m=4, we need a mix of signs such that some cycle product is -1.
    
    # Let's use a simple local search / simulated annealing approach.
    # Objective: Minimize spectral radius of signed adjacency matrix.
    # Constraint: Lift must be connected.
    
    def get_signed_adj(signs):
        A = np.zeros((n, n))
        for i, (u, v) in enumerate(edges):
            A[u, v] = signs[i]
            A[v, u] = signs[i]
        return A

    def spectral_radius(signs):
        A = get_signed_adj(signs)
        # Use eigvalsh for symmetric matrices
        eigvals = np.linalg.eigvalsh(A)
        return np.max(np.abs(eigvals))

    def is_connected_lift(signs):
        # Build graph of the lift
        # Vertices 0..2n-1. (v,0) is v, (v,1) is v+n.
        # Edge (u,v) with sign s:
        # if s=1: (u,0)-(v,0) and (u,1)-(v,1)
        # if s=-1: (u,0)-(v,1) and (u,1)-(v,0)
        
        adj_lift = [[] for _ in range(2*n)]
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            if s == 1:
                adj_lift[u].append(v)
                adj_lift[v].append(u)
                adj_lift[u+n].append(v+n)
                adj_lift[v+n].append(u+n)
            else:
                adj_lift[u].append(v+n)
                adj_lift[v+n].append(u)
                adj_lift[u+n].append(v)
                adj_lift[v].append(u+n)
                
        # BFS from 0
        visited = [False] * (2*n)
        queue = [0]
        visited[0] = True
        count = 1
        while queue:
            node = queue.pop(0)
            for nei in adj_lift[node]:
                if not visited[nei]:
                    visited[nei] = True
                    count += 1
                    queue.append(nei)
        return count == 2*n

    # Local Search
    current_signs = np.ones(len(edges), dtype=int)
    # Start with random signs? Or all -1?
    # Let's try a few random starts.
    
    rng = np.random.default_rng(3)
    
    for start_iter in range(20):
        if time.time() > deadline:
            break
            
        if start_iter == 0:
            curr = np.ones(len(edges), dtype=int)
        else:
            curr = rng.choice([-1, 1], size=len(edges))
            
        # Check connectivity
        if not is_connected_lift(curr):
            # Try to fix connectivity by flipping random edges
            # Or just skip? Better to find a valid one first.
            # For m=4, we need an odd number of -1s on a cycle?
            # Let's just randomize until connected.
            connected = False
            for _ in range(100):
                if is_connected_lift(curr):
                    connected = True
                    break
                idx = rng.integers(0, len(edges))
                curr[idx] *= -1
            if not connected:
                continue
                
        curr_rad = spectral_radius(curr)
        
        # Local search: flip one edge at a time
        for step in range(500):
            if time.time() > deadline:
                break
                
            if curr_rad < best_radius:
                best_radius = curr_rad
                best_signs = curr.copy()
                
            # Pick a random edge to flip
            idx = rng.integers(0, len(edges))
            new_signs = curr.copy()
            new_signs[idx] *= -1
            
            # Check connectivity of new signs
            if not is_connected_lift(new_signs):
                continue
                
            new_rad = spectral_radius(new_signs)
            
            # Accept if better, or with some probability if worse (simulated annealing)
            # Simple hill climbing for now, maybe add restarts
            if new_rad < curr_rad:
                curr = new_signs
                curr_rad = new_rad
            else:
                # Occasionally accept worse to escape local minima
                if rng.random() < 0.1:
                    curr = new_signs
                    curr_rad = new_rad
                    
    # Ensure best_signs is valid
    if not is_connected_lift(best_signs):
        # Fallback: find any valid signs
        # Try all -1 with one +1
        for i in range(len(edges)):
            signs = np.full(len(edges), -1)
            signs[i] = 1
            if is_connected_lift(signs):
                best_signs = signs
                break
    else:
        # Verify best_signs is valid
        pass
        
    return best_signs
