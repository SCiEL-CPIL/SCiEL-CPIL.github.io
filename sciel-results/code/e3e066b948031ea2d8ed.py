import time
import itertools

def construct():
    # Deadline guard
    start_time = time.time()
    deadline = start_time + 110.0  # 10 second margin
    
    def has_c6_in_cayley(n, diff_set):
        """
        Check if the Cayley graph of Z_n generated by diff_set contains a cycle of length 6.
        diff_set is a set of integers in 1..n-1.
        """
        if len(diff_set) < 3:
            return False
        
        # Build adjacency list
        adj = [[] for _ in range(n)]
        for d in diff_set:
            for i in range(n):
                j = (i + d) % n
                adj[i].append(j)
                # Note: since we add both i->j and j->i in the loop over all i, 
                # and d and n-d are both in diff_set (symmetric), 
                # we might add duplicates. 
                # To be safe, we can use a set for neighbors or just allow duplicates in DFS with visited set.
        
        # To optimize, we can unique the neighbors
        for i in range(n):
            adj[i] = list(set(adj[i]))
        
        # Check for C6
        # A C6 is a sequence v0, v1, v2, v3, v4, v5, v0 with all distinct.
        # We can fix v0 = 0 to break symmetry.
        # Then find a path of length 5 from 0 back to 0, visiting 5 distinct intermediate nodes.
        
        def dfs(current, target, path, visited):
            if len(path) == 6:
                # Check if we are back at start and all distinct
                if current == target and len(set(path)) == 6:
                    return True
                return False
            
            for neighbor in adj[current]:
                if neighbor not in visited:
                    visited.add(neighbor)
                    path.append(neighbor)
                    if dfs(neighbor, target, path, visited):
                        return True
                    path.pop()
                    visited.remove(neighbor)
            return False
        
        # We only need to check cycles starting at 0?
        # In a vertex-transitive graph, if a C6 exists, it exists starting at any vertex.
        # So checking from 0 is sufficient.
        
        # However, the path must be simple.
        # Start at 0.
        # We need a path of length 5 ending at a neighbor of 0?
        # No, a cycle of length 6 is v0-v1-v2-v3-v4-v5-v0.
        # So we look for a path of length 5 from 0 to some node v5, such that v5 is adjacent to 0,
        # and v1..v5 are distinct and not 0.
        
        # Let's modify DFS:
        # State: current node, path length so far.
        # If length == 5, check if current is adjacent to 0.
        
        def dfs_cycle(current, path_len, visited):
            if path_len == 5:
                # Check if current is connected to 0
                if 0 in adj[current]:
                    return True
                return False
            
            for neighbor in adj[current]:
                if neighbor not in visited:
                    visited.add(neighbor)
                    if dfs_cycle(neighbor, path_len + 1, visited):
                        return True
                    visited.remove(neighbor)
            return False
        
        visited = {0}
        # Start from neighbors of 0
        for neighbor in adj[0]:
            if neighbor not in visited:
                visited.add(neighbor)
                if dfs_cycle(neighbor, 1, visited):
                    return True
                visited.remove(neighbor)
        
        return False

    def find_circulant_coloring(n):
        # Pairs of differences: d and n-d
        # We assign colors to representatives 1..n//2
        num_pairs = n // 2
        # For n=17, pairs are 1..8
        # For n=16, pairs are 1..8 (8 is self-pair? No, 16-8=8. So 8 is a single difference, but in Cayley graph context, 
        # if d=8, then -d=8. So it's its own inverse. 
        # In Z_16, 8 is the only self-inverse non-zero element.
        # So for n=16, pairs are {1,15}, {2,14}, {3,13}, {4,12}, {5,11}, {6,10}, {7,9}, {8}.
        # 8 items.
        
        # Pre-compute has_c6 for all subsets of pairs
        # Subset is a bitmask of length num_pairs
        # diff_set for a subset is union of the pairs
        
        # Map pair index to the actual differences
        pair_diffs = []
        for d in range(1, num_pairs + 1):
            if n % (2*d) == 0 and d == n//2:
                # Self-inverse
                pair_diffs.append([d])
            else:
                pair_diffs.append([d, n-d])
        
        # Pre-compute validity for all 2^num_pairs subsets
        valid_subset = [True] * (1 << num_pairs)
        for mask in range(1 << num_pairs):
            diffs = set()
            for i in range(num_pairs):
                if mask & (1 << i):
                    diffs.update(pair_diffs[i])
            if has_c6_in_cayley(n, diffs):
                valid_subset[mask] = False
        
        # Now search for an assignment of the num_pairs items to 4 colors
        # such that the union of items for each color forms a valid subset (no C6)
        
        # Iterate through all 4^num_pairs assignments
        # For n=17, num_pairs=8, 4^8 = 65536
        # For n=20, num_pairs=10, 4^10 = 1,048,576 (might be slow if precomp is heavy, but precomp is 2^10=1024)
        
        for k in range(4 ** num_pairs):
            # Decode k to get color for each pair
            temp = k
            masks = [0] * 4
            for i in range(num_pairs):
                color = temp % 4
                temp //= 4
                masks[color] |= (1 << i)
            
            # Check if all 4 color classes are valid
            if all(valid_subset[masks[c]] for c in range(4)):
                # Found a valid assignment
                # Construct the coloring
                # color_of_pair[i] is the color assigned to pair i
                color_of_pair = [0] * num_pairs
                for i in range(num_pairs):
                    for c in range(4):
                        if masks[c] & (1 << i):
                            color_of_pair[i] = c
                            break
                
                # Generate the list of colors for all edges
                colors = []
                for i in range(n):
                    for j in range(i + 1, n):
                        d = (j - i) % n
                        if d > n // 2:
                            d = n - d
                        # d is in 1..n//2
                        # Pair index is d-1
                        colors.append(color_of_pair[d-1])
                
                return {'n': n, 'colors': colors}
        
        return None

    # Try n from 17 down to 10
    for n in range(17, 9, -1):
        if time.time() > deadline:
            break
        result = find_circulant_coloring(n)
        if result:
            return result
        
    # Fallback to seed if no better found
    n = 9
    return {'n': n, 'colors': [min(j - i, n - j + i) - 1 for i in range(n) for j in range(i + 1, n)]}
