import time
import random

DEADLINE = 145.0  # Safety margin before 150s kill

def _greedy_build(order=None):
    """
    Build a B2[2] set using a greedy approach.
    If order is None, uses 1..1000.
    If order is a list, uses that order.
    Returns (set_list, counts_dict)
    """
    if order is None:
        order = range(1, 1001)
    
    chosen = []
    counts = {}
    chosen_set = set() # For O(1) membership check if needed, but we iterate order
    
    for x in order:
        if x in chosen_set:
            continue
            
        # Check if x can be added
        # New sums: x + y for y in chosen, and 2*x
        valid = True
        for y in chosen:
            s = x + y
            if counts.get(s, 0) + 1 > 2:
                valid = False
                break
        if valid:
            s2 = 2 * x
            if counts.get(s2, 0) + 1 > 2:
                valid = False
        
        if valid:
            # Add x
            chosen.append(x)
            chosen_set.add(x)
            for y in chosen:
                s = x + y
                counts[s] = counts.get(s, 0) + 1
            s2 = 2 * x
            counts[s2] = counts.get(s2, 0) + 1
            
    return chosen, counts

def _local_search(S, counts, time_limit, rng):
    """
    Improve the set S via local search.
    Returns (best_S, best_counts)
    """
    S = list(S)
    counts = dict(counts)
    S_set = set(S)
    
    best_S = list(S)
    best_counts = dict(counts)
    best_size = len(S)
    
    end_time = time.time() + time_limit
    all_elems = set(range(1, 1001))
    
    while time.time() < end_time:
        # Choose a move type
        # Bias towards add/swap if we have space, remove if we want to explore
        move_type = rng.choice(['add', 'swap', 'remove'])
        
        if move_type == 'add':
            comp = all_elems - S_set
            if not comp:
                continue
            x = rng.choice(list(comp))
            
            # Check validity
            valid = True
            for y in S:
                s = x + y
                if counts.get(s, 0) + 1 > 2:
                    valid = False
                    break
            if valid:
                s2 = 2 * x
                if counts.get(s2, 0) + 1 > 2:
                    valid = False
            
            if valid:
                # Apply add
                S.append(x)
                S_set.add(x)
                for y in S:
                    # Note: S now contains x, so x+y covers x+x and x+old_y
                    # But we need to be careful. The previous loop checked against old S.
                    # Let's just update counts based on old S + x
                    pass 
                
                # Efficient update:
                # We already checked validity against old counts.
                # Now update counts.
                for y in S:
                    # This loop includes x itself. 
                    # The sums generated by adding x are {x+y | y in S_old} U {2x}.
                    # Since x is now in S, iterating S gives x+x and x+y for y in S_old.
                    # This is correct.
                    s = x + y
                    counts[s] = counts.get(s, 0) + 1
                
                # Wait, the loop above iterates over the NEW S.
                # So it does x+x and x+y for all y in S_old.
                # This is exactly the new sums.
                # However, we must ensure we don't double count or miss.
                # Old sums remain. New sums are added.
                # The code above adds 1 to counts[s] for each s in {x+y | y in S_new}.
                # This is correct.
                
                if len(S) > best_size:
                    best_size = len(S)
                    best_S = list(S)
                    best_counts = dict(counts)

        elif move_type == 'remove':
            if not S:
                continue
            x = rng.choice(S)
            
            # Remove x
            S.remove(x)
            S_set.discard(x)
            
            # Update counts
            for y in S:
                s = x + y
                counts[s] -= 1
                if counts[s] == 0:
                    del counts[s]
            s2 = 2 * x
            counts[s2] -= 1
            if counts[s2] == 0:
                del counts[s2]
                
            # Note: Removing reduces size, so we don't update best here.
            # But it might enable better future adds/swaps.

        else: # swap
            if not S:
                continue
            u = rng.choice(S)
            comp = all_elems - S_set
            if not comp:
                continue
            v = rng.choice(list(comp))
            
            # Try swap: remove u, add v
            # 1. Remove u
            S.remove(u)
            S_set.discard(u)
            
            old_counts = dict(counts) # Save for revert if needed? 
            # Actually, we can just check validity of adding v to S (without u)
            
            valid = True
            for y in S:
                s = v + y
                if counts.get(s, 0) + 1 > 2:
                    valid = False
                    break
            if valid:
                s2 = 2 * v
                if counts.get(s2, 0) + 1 > 2:
                    valid = False
            
            if valid:
                # Apply add v
                S.append(v)
                S_set.add(v)
                for y in S:
                    s = v + y
                    counts[s] = counts.get(s, 0) + 1
                
                # Update best if size increased (size is same as before swap, so no size gain, but maybe better structure?)
                # Actually, swap keeps size same. We only care about size for "best".
                # But a swap might allow a subsequent add to succeed.
                # We don't update best_size here.
            else:
                # Revert remove of u
                S.append(u)
                S_set.add(u)
                for y in S:
                    s = u + y
                    counts[s] = counts.get(s, 0) + 1
                # Wait, if we revert, we need to restore counts.
                # The counts were modified by removing u.
                # We need to add back the sums involving u.
                # But we didn't modify counts for the "add v" part because valid was False.
                # So we just need to restore the "remove u" part.
                # The loop above does that.
                
    return best_S, best_counts

def construct():
    start = time.time()
    rng = random.Random(42)
    
    # 1. Deterministic Greedy
    S, counts = _greedy_build()
    best_S = list(S)
    best_counts = dict(counts)
    best_size = len(S)
    
    # 2. Local Search on Deterministic Greedy
    # Allocate some time, e.g., 10s
    time_left = DEADLINE - time.time()
    ls_time = min(10.0, time_left * 0.2)
    if ls_time > 1:
        S, counts = _local_search(S, counts, ls_time, rng)
        if len(S) > best_size:
            best_S = list(S)
            best_counts = dict(counts)
            best_size = len(S)
    
    # 3. Randomized Restarts
    # Use remaining time for randomized greedy + local search
    while time.time() < DEADLINE - 5.0:
        # Generate randomized order
        order = list(range(1, 1001))
        rng.shuffle(order)
        
        S_r, counts_r = _greedy_build(order)
        
        # Check if this seed is already better
        if len(S_r) > best_size:
            best_S = list(S_r)
            best_counts = dict(counts_r)
            best_size = len(S_r)
            
        # Apply local search
        # Estimate time for this iteration
        # We want to finish within deadline.
        # Let's allow 5s per restart on average, but check deadline dynamically.
        iter_start = time.time()
        time_limit_ls = min(5.0, DEADLINE - 5.0 - time.time())
        
        if time_limit_ls > 1.0:
            S_l, counts_l = _local_search(S_r, counts_r, time_limit_ls, rng)
            if len(S_l) > best_size:
                best_S = list(S_l)
                best_counts = dict(counts_l)
                best_size = len(S_l)
        
        # If we are running out of time, break
        if time.time() > DEADLINE - 10.0:
            break
            
    return best_S
