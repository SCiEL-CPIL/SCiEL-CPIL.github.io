# EVOLVE-BLOCK-START
import random
import time

def construct():
    def get_subset_sums(elements):
        sums = {0}
        for e in elements:
            new_sums = set()
            for s in sums:
                new_sums.add(s + e)
            sums = sums | new_sums
        sums.discard(0)
        return sums

    def is_valid_divisibility(sums):
        # Check if no two distinct sums in the set divide each other
        # sums is a set of ints
        sum_list = sorted(sums)
        # Optimization: If we know the previous set was valid, we only need to check new elements
        # But for simplicity and robustness in the check function, we do a full check if called on the whole set
        # However, in the greedy loop, we will use a specialized check.
        for i in range(len(sum_list)):
            for j in range(i+1, len(sum_list)):
                if sum_list[j] % sum_list[i] == 0:
                    return False
        return True

    def check_addition(old_sums, new_sums, e):
        # old_sums: set of valid sums before adding e
        # new_sums: set of sums generated by adding e (including e itself and old_sums + e)
        # We need to check if the union old_sums | new_sums is valid.
        # We know old_sums is valid.
        # We need to check:
        # 1. Internal validity of new_sums
        # 2. Cross validity between old_sums and new_sums
        
        # 1. Internal validity of new_sums
        new_list = sorted(new_sums)
        for i in range(len(new_list)):
            for j in range(i+1, len(new_list)):
                if new_list[j] % new_list[i] == 0:
                    return False
        
        # 2. Cross validity
        # For each u in new_sums, check if any v in old_sums divides u or u divides v
        # Note: u and v are distinct because new_sums contains e and old_sums+e, 
        # while old_sums does not contain e (assuming e not in old_sums, which is true if e > max(old_sums) or e is new).
        # Actually, e could be in old_sums? No, elements are distinct. 
        # But a sum in old_sums could equal e? No, e is an element, not a sum of others (unless e is 0, but e>=1).
        # Wait, if old_sums contains a sum equal to e, that would mean a subset of old elements sums to e.
        # If e is distinct from old elements, this is possible. E.g., old={1,2}, e=3. Sum 1+2=3 is in old_sums.
        # If e=3 is added, new_sums contains 3 (the element) and 1+3=4, 2+3=5, 1+2+3=6.
        # old_sums = {1, 2, 3}.
        # Wait, if old_sums contains 3, and we add e=3, the element 3 is not distinct from the sum 3?
        # The condition is "distinct integers in 1..256". So e must not be in the set of elements.
        # But e can be equal to a subset sum of previous elements.
        # If e is equal to a subset sum s_old, then the subset {e} has sum e, and the subset forming s_old has sum e.
        # This violates "no two distinct resulting values may divide one another"? 
        # No, it violates "Equal sum values are counted once. Two different subsets with the same sum still make the set invalid".
        # So we MUST ensure that e is not in old_sums, and no s_old + e is in old_sums, and no two s_old+e collide.
        # The check `len(new_sums) == 2 * len(old_sums) + 1` ensures all sums are distinct.
        # So if we pass that check, we are guaranteed that no sum in new_sums is in old_sums, and all new_sums are distinct.
        # Thus, we only need to check divisibility between elements in new_sums and elements in old_sums.
        
        old_set = set(old_sums)
        for u in new_sums:
            # Check if any divisor of u is in old_set
            # Or if u divides any element in old_set
            
            # Check divisors of u
            # u <= 256 * 15 approx 3840. sqrt(3840) ~ 62.
            # Iterate d from 1 to sqrt(u)
            limit = int(u**0.5)
            for d in range(1, limit + 1):
                if u % d == 0:
                    d1 = d
                    d2 = u // d
                    if d1 in old_set and d1 != u:
                        return False
                    if d2 in old_set and d2 != u:
                        return False
            
            # Check if u divides any element in old_set
            # This is harder. We can iterate old_set and check if v % u == 0.
            # old_set size is 2^k - 1.
            # If k is small (<= 10), this is fast.
            for v in old_set:
                if v > u and v % u == 0:
                    return False
                # If v < u, it was covered by divisor check? 
                # If v < u and u % v == 0, then v is a divisor of u. 
                # My divisor loop checks if d is in old_set. So if v is a divisor of u, it is caught.
                # So we only need to check if u divides v where v > u.
                
        return True

    best_set = []
    best_size = 0
    
    # Try multiple random restarts
    start_time = time.time()
    num_restarts = 20
    
    for _ in range(num_restarts):
        if time.time() - start_time > 50:
            break
            
        # Randomize the order of candidates
        candidates = list(range(1, 257))
        random.shuffle(candidates)
        
        selected = []
        current_sums = set()
        
        for e in candidates:
            # Quick check: if e is in current_sums, skip? 
            # No, e is an element. current_sums are sums of subsets.
            # If e is in current_sums, then {e} and the subset summing to e collide.
            # So e must not be in current_sums.
            if e in current_sums:
                continue
            
            # Generate new sums
            new_sums = set()
            for s in current_sums:
                new_sums.add(s + e)
            new_sums.add(e)
            
            # Check uniqueness (sum-distinctness)
            # Total sums should be len(current_sums) + len(new_sums)
            # And they should be disjoint.
            # len(current_sums | new_sums) should be len(current_sums) + len(new_sums)
            if len(current_sums | new_sums) != len(current_sums) + len(new_sums):
                continue
            
            # Check divisibility
            if check_addition(current_sums, new_sums, e):
                selected.append(e)
                current_sums = current_sums | new_sums
                
        if len(selected) > best_size:
            best_size = len(selected)
            best_set = selected[:]
            
    # Verify the best set one last time
    if best_set:
        sums = get_subset_sums(best_set)
        if not is_valid_divisibility(sums):
            # Fallback to a known valid set if the random search produced an invalid one (shouldn't happen)
            # Or if we didn't find anything
            best_set = [31, 32, 34] # Size 3
            
    return [int(x) for x in best_set]

