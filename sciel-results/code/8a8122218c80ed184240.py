import time
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 120.0
    
    n, m, p = 3, 3, 3
    
    # Try Rank 23 (Laderman)
    rank = 23
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # A indices: 0:a, 1:b, 2:c, 3:d, 4:e, 5:f, 6:g, 7:h, 8:i
    # B indices: 0:x, 1:y, 2:z, 3:u, 4:v, 5:w, 6:s, 7:t, 8:r
    
    # M1
    U[0,0]=1; U[4,0]=1; U[8,0]=1
    V[0,0]=1; V[4,0]=1; V[8,0]=1
    # M2
    U[0,1]=1; U[4,1]=1; U[8,1]=-1
    V[0,1]=1; V[4,1]=1; V[8,1]=-1
    # M3
    U[3,2]=1; U[6,2]=1; U[2,2]=1
    V[3,2]=1; V[6,2]=1; V[2,2]=1
    # M4
    U[3,3]=1; U[6,3]=1; U[2,3]=-1
    V[3,3]=1; V[6,3]=1; V[2,3]=-1
    # M5
    U[1,4]=1; U[5,4]=1; U[7,4]=1
    V[1,4]=1; V[5,4]=1; V[7,4]=1
    # M6
    U[1,5]=1; U[5,5]=1; U[7,5]=-1
    V[1,5]=1; V[5,5]=1; V[7,5]=-1
    # M7
    U[0,6]=1; U[4,6]=1; U[1,6]=-1; U[3,6]=-1
    V[0,6]=1; V[4,6]=1; V[1,6]=1; V[3,6]=1
    # M8
    U[0,7]=1; U[4,7]=-1; U[1,7]=1; U[3,7]=1
    V[0,7]=1; V[4,7]=-1; V[1,7]=1; V[3,7]=1
    # M9
    U[3,8]=1; U[6,8]=1; U[4,8]=-1; U[5,8]=-1
    V[3,8]=1; V[6,8]=1; V[4,8]=1; V[5,8]=1
    # M10
    U[3,9]=1; U[6,9]=-1; U[4,9]=1; U[5,9]=1
    V[3,9]=1; V[6,9]=-1; V[4,9]=1; V[5,9]=1
    # M11
    U[1,10]=1; U[5,10]=1; U[0,10]=-1; U[7,10]=-1
    V[1,10]=1; V[5,10]=1; V[0,10]=1; V[6,10]=1
    # M12
    U[1,11]=1; U[5,11]=-1; U[0,11]=1; U[7,11]=1
    V[1,11]=1; V[5,11]=-1; V[0,11]=1; V[6,11]=1
    # M13
    U[0,12]=1; U[8,12]=1; U[2,12]=-1; U[6,12]=-1
    V[0,12]=1; V[8,12]=1; V[2,12]=1; V[6,12]=1
    # M14
    U[0,13]=1; U[8,13]=-1; U[2,13]=1; U[6,13]=1
    V[0,13]=1; V[8,13]=-1; V[2,13]=1; V[6,13]=1
    # M15
    U[0,14]=1
    V[4,14]=1
    # M16
    U[4,15]=1
    V[3,15]=1
    # M17
    U[8,16]=1
    V[0,16]=1
    # M18
    U[1,17]=1
    V[6,17]=1
    # M19
    U[5,18]=1
    V[2,18]=1
    # M20
    U[7,19]=1
    V[5,19]=1
    # M21
    U[2,20]=1
    V[7,20]=1
    # M22
    U[3,21]=1
    V[8,21]=1
    # M23
    U[6,22]=1
    V[1,22]=1
    
    # W coefficients
    # C[i,k] = sum_r W[k*3+i, r] M_r
    # C00 (0): 0.5(M1+M2-M7-M8) + M15+M16+M21+M22 ? No.
    # Let's use the verified Laderman W matrix.
    # W[0,0]=0.5, W[0,1]=0.5, W[0,6]=-0.5, W[0,7]=-0.5
    # W[0,14]=1, W[0,15]=1, W[0,20]=1, W[0,21]=1
    # This matches the previous attempt's W for C00.
    
    W[0,0] = 0.5; W[0,1] = 0.5; W[0,6] = -0.5; W[0,7] = -0.5
    W[0,14] = 1; W[0,15] = 1; W[0,20] = 1; W[0,21] = 1
    
    W[1,2] = 0.5; W[1,3] = -0.5; W[1,8] = -0.5; W[1,9] = -0.5
    W[1,14] = 1; W[1,15] = 1; W[1,17] = 1; W[1,22] = 1
    
    W[2,4] = 0.5; W[2,5] = -0.5; W[2,10] = -0.5; W[2,11] = -0.5
    W[2,14] = 1; W[2,18] = 1; W[2,19] = 1; W[2,20] = 1
    
    W[3,2] = 0.5; W[3,3] = 0.5; W[3,8] = -0.5; W[3,9] = -0.5
    W[3,15] = 1; W[3,16] = 1; W[3,17] = 1; W[3,21] = 1
    
    W[4,0] = 0.5; W[4,1] = -0.5; W[4,6] = -0.5; W[4,7] = 0.5
    W[4,15] = 1; W[4,18] = 1; W[4,19] = 1; W[4,22] = 1
    
    W[5,4] = 0.5; W[5,5] = 0.5; W[5,10] = -0.5; W[5,11] = 0.5
    W[5,16] = 1; W[5,18] = 1; W[5,19] = 1; W[5,21] = 1
    
    W[6,2] = 0.5; W[6,3] = 0.5; W[6,8] = 0.5; W[6,9] = 0.5
    W[6,15] = 1; W[6,16] = 1; W[6,17] = 1; W[6,20] = 1
    
    W[7,2] = 0.5; W[7,3] = -0.5; W[7,8] = 0.5; W[7,9] = 0.5
    W[7,14] = 1; W[7,15] = 1; W[7,17] = 1; W[7,21] = 1
    
    W[8,0] = 0.5; W[8,1] = 0.5; W[8,6] = 0.5; W[8,7] = 0.5
    W[8,14] = 1; W[8,18] = 1; W[8,19] = 1; W[8,22] = 1
    
    # Verify
    np.random.seed(123)
    for _ in range(5):
        A_t = np.random.randint(-5, 6, size=(3,3)).astype(float)
        B_t = np.random.randint(-5, 6, size=(3,3)).astype(float)
        C_exp = A_t @ B_t
        C_comp = np.zeros((3,3))
        for r in range(23):
            u_val = np.dot(U[:,r], A_t.flatten())
            v_val = np.dot(V[:,r], B_t.flatten())
            prod = u_val * v_val
            for i in range(3):
                for k in range(3):
                    C_comp[i,k] += prod * W[k*3+i, r]
        if not np.allclose(C_comp, C_exp, atol=1e-9):
            # Fallback to Rank 27
            rank_fb = 27
            U_fb = np.zeros((9, rank_fb))
            V_fb = np.zeros((9, rank_fb))
            W_fb = np.zeros((9, rank_fb))
            idx = 0
            for i in range(3):
                for j in range(3):
                    for k in range(3):
                        U_fb[i*3+j, idx] = 1
                        V_fb[j*3+k, idx] = 1
                        W_fb[k*3+i, idx] = 1
                        idx += 1
            return {"U": U_fb.tolist(), "V": V_fb.tolist(), "W": W_fb.tolist()}
            
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
