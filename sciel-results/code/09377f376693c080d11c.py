DIMENSIONS = [2, 3, 5]

def _to_fraction(x):
    if isinstance(x, Fraction):
        return x
    if isinstance(x, (int, float)):
        return Fraction(x)
    return Fraction(x)

def _is_half_integer(frac):
    # Check if frac is a half-integer (i.e., frac * 2 is an integer)
    return (frac * 2).denominator == 1

def _verify_decomposition(U, V, W, n, m, p):
    """
    Verify that sum_r U[:,r] * V[:,r] * W[:,r] == tensor T where T[i,j,k] = 1 if A[i,j]*B[j,k] contributes to C[i,k]
    For matrix mult: T[i, j, k] = 1 means A[i,j]*B[j,k] appears in C[i,k].
    Actually the tensor is T[i, j, k] = delta(i,k from j) ... 
    For matrix multiplication: C[i,k] = sum_j A[i,j] B[j,k]
    The tensor is T[i,j,k] = 1 for all i,j,k? No.
    T[i,j,k] = 1 if the (i,j) element of A and (j,k) element of B contribute to (i,k) of C.
    Actually, the multiplication tensor M_{n,m,p} has entries M_{i,j,k} = 1 for all valid i,j,k.
    Wait, the standard tensor is T[i,j,k] = 1 if we're computing C[i,k] from A[i,j]B[j,k].
    Yes, T[i,j,k] = 1 for all i in [0,n), j in [0,m), k in [0,p).
    So we need sum_r U[i*m+j, r] * V[j*p+k, r] * W[k*n+i, r] = 1 for all i,j,k.
    """
    rank = len(U[0])
    # Convert to numpy arrays for speed
    U_arr = np.array([[float(x) for x in row] for row in U], dtype=float)
    V_arr = np.array([[float(x) for x in row] for row in V], dtype=float)
    W_arr = np.array([[float(x) for x in row] for row in W], dtype=float)
    
    # T_expected[i*m+j, k*n+i] ... no
    # The tensor is T[i, j, k] = 1
    # We check: for each i,j,k: sum_r U[i*m+j, r] * V[j*p+k, r] * W[k*n+i, r] == 1
    
    for i in range(n):
        for j in range(m):
            for k in range(p):
                idx_u = i * m + j
                idx_v = j * p + k
                idx_w = k * n + i
                s = 0.0
                for r in range(rank):
                    s += U_arr[idx_u, r] * V_arr[idx_v, r] * W_arr[idx_w, r]
                if abs(s - 1.0) > 1e-9:
                    return False
    return True

