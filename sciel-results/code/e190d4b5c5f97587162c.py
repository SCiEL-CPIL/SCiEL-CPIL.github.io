def synthesize(matrix, depth_limit):
    import numpy as np
    import random
    from collections import defaultdict

    m, n = matrix.shape
    
    def run_cse(matrix, seed):
        random.seed(seed)
        m, n = matrix.shape
        
        # Use bitmasks for supports to speed up XOR and comparison
        # Input i is 1 << i
        # Zero is 0
        wire_masks = [1 << i for i in range(n)]
        wire_masks.append(0)
        
        # Map mask to wire ID for quick lookup
        mask_to_wire = {0: n}
        for i in range(n):
            mask_to_wire[1 << i] = i
            
        # Expressions: list of sets of wire IDs
        expressions = []
        for i in range(m):
            expr = set()
            for j in range(n):
                if matrix[i, j]:
                    expr.add(j)
            expressions.append(expr)
            
        gates = []
        next_wire = n + 1
        
        while True:
            pair_count = defaultdict(int)
            
            for expr in expressions:
                if len(expr) < 2:
                    continue
                lst = list(expr)
                for i in range(len(lst)):
                    for j in range(i + 1, len(lst)):
                        u, v = lst[i], lst[j]
                        if u > v:
                            u, v = v, u
                        pair_count[(u, v)] += 1
                        
            if not pair_count:
                break
                
            max_count = max(pair_count.values())
            if max_count < 2:
                break
                
            candidates = [(pair, count) for pair, count in pair_count.items() if count == max_count]
            pair, _ = random.choice(candidates)
            u, v = pair
            
            new_mask = wire_masks[u] ^ wire_masks[v]
            
            # Check if this wire already exists
            if new_mask in mask_to_wire:
                # We can replace u and v with the existing wire directly without adding a new gate?
                # No, the gate u^v might not be the same as the existing wire's gate structure,
                # but logically it is the same value.
                # If we use the existing wire, we save a gate.
                existing_id = mask_to_wire[new_mask]
                
                # Update expressions
                for i in range(m):
                    expr = expressions[i]
                    if u in expr and v in expr:
                        expr.remove(u)
                        expr.remove(v)
                        expr.add(existing_id)
                        
                # We did not add a new gate, so we continue the loop to see if more pairs can be formed
                # However, we must be careful: if u and v are not inputs, they were generated by gates.
                # Replacing them with an existing wire is valid.
                continue
            
            # Create new wire
            wire_masks.append(new_mask)
            mask_to_wire[new_mask] = next_wire
            new_id = next_wire
            next_wire += 1
            
            gates.append([u, v])
            
            for i in range(m):
                expr = expressions[i]
                if u in expr and v in expr:
                    expr.remove(u)
                    expr.remove(v)
                    expr.add(new_id)
                    
        outputs = []
        for expr in expressions:
            if not expr:
                outputs.append(n)
            elif len(expr) == 1:
                outputs.append(list(expr)[0])
            else:
                target_mask = 0
                for w in expr:
                    target_mask ^= wire_masks[w]
                
                if target_mask in mask_to_wire:
                    outputs.append(mask_to_wire[target_mask])
                else:
                    lst = list(expr)
                    current = lst[0]
                    for w in lst[1:]:
                        gates.append([current, w])
                        new_mask = wire_masks[current] ^ wire_masks[w]
                        wire_masks.append(new_mask)
                        mask_to_wire[new_mask] = len(wire_masks) - 1
                        current = len(wire_masks) - 1
                    outputs.append(current)
                    
        return {'gates': gates, 'outputs': outputs}

    best_result = None
    best_score = float('inf')
    
    # Run multiple seeds to escape local optima
    # Limit seeds to ensure speed
    num_seeds = 10 
    for seed in range(num_seeds):
        res = run_cse(matrix, seed)
        score = len(res['gates'])
        if score < best_score:
            best_score = score
            best_result = res
            
    return best_result
