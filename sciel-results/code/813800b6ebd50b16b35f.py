import numpy as np
import time

def sign_edges(graph, budget):
    start_time = time.time()
    deadline = start_time + 55  # Safety margin for 60s limit

    m = graph['n'] // 2
    edges = graph['edges']
    n_edges = len(edges)
    n_vertices = 2 * m

    def build_signed_adj(signs):
        A = np.zeros((n_vertices, n_vertices), dtype=float)
        for idx, (u, v) in enumerate(edges):
            s = float(signs[idx])
            A[u, v] = s
            A[v, u] = s
        return A

    def spectral_radius(signs):
        A = build_signed_adj(signs)
        eigvals = np.linalg.eigvalsh(A)
        return float(np.max(np.abs(eigvals)))

    def is_connected_lift(signs):
        # Check if the 2-lift is connected using BFS
        lift_adj = [[] for _ in range(2 * n_vertices)]
        for idx, (u, v) in enumerate(edges):
            s = signs[idx]
            if s == 1:
                lift_adj[u * 2].append(v * 2)
                lift_adj[v * 2].append(u * 2)
                lift_adj[u * 2 + 1].append(v * 2 + 1)
                lift_adj[v * 2 + 1].append(u * 2 + 1)
            else:
                lift_adj[u * 2].append(v * 2 + 1)
                lift_adj[v * 2 + 1].append(u * 2)
                lift_adj[u * 2 + 1].append(v * 2)
                lift_adj[v * 2].append(u * 2 + 1)

        visited = [False] * (2 * n_vertices)
        stack = [0]
        visited[0] = True
        count = 1
        while stack:
            node = stack.pop()
            for neighbor in lift_adj[node]:
                if not visited[neighbor]:
                    visited[neighbor] = True
                    count += 1
                    stack.append(neighbor)
        return count == 2 * n_vertices

    # Identify edge types and build cycle structure
    # Prism graph: top cycle (0..m-1), bottom cycle (m..2m-1), matching edges
    top_edges = []    # edges within top cycle
    bottom_edges = [] # edges within bottom cycle
    match_edges = []  # matching edges (i, i+m)

    for idx, (u, v) in enumerate(edges):
        if u < m and v < m:
            top_edges.append(idx)
        elif u >= m and v >= m:
            bottom_edges.append(idx)
        else:
            match_edges.append(idx)

    # The base graph has n_edges edges.
    # Switching classes: the sign vector can be written as s = s0 + delta where delta is a cut.
    # A cut is determined by a subset S of vertices: delta(e) = 1 if exactly one endpoint in S.
    # Two sign vectors are in the same switching class iff their XOR is a cut.
    # 
    # For connectivity of the 2-lift: the lift is connected iff there is no nonempty proper
    # subset of vertices in the base graph such that all edges crossing the cut have sign +1
    # (which would disconnect the lift into two components). Actually, the lift is disconnected
    # iff there exists a partition of the base vertices into two nonempty sets A, B such that
    # all edges between A and B have sign +1. This is equivalent to: the signed graph has a
    # "balanced" cut.
    #
    # Alternative characterization: The 2-lift is connected iff the cycle space of the base
    # graph has at least one cycle with an odd number of -1 edges. For a prism graph, the
    # cycle space is generated by: the top cycle, the bottom cycle, and m-1 "ladder" cycles
    # (using two matching edges and two path segments).
    #
    # Actually, a cleaner approach: The 2-lift is connected iff the sign assignment is not
    # "balanced" on the entire graph. A signed graph is balanced iff every cycle has an even
    # number of -1 edges. The 2-lift is connected iff the signed graph is NOT balanced.
    #
    # Wait, let me reconsider. The 2-lift of a signed graph: vertices are (v,0) and (v,1).
    # Edge (u,v) with sign +1: connects (u,0)-(v,0) and (u,1)-(v,1).
    # Edge (u,v) with sign -1: connects (u,0)-(v,1) and (u,1)-(v,0).
    #
    # The 2-lift is disconnected iff there exists a function f: V -> {0,1} such that for every
    # edge (u,v) with sign s, we have f(u) + f(v) = 1 - s (mod 2). This is equivalent to the
    # signed graph being balanced (all cycles have even number of -1 edges).
    #
    # So: lift is connected iff signed graph is NOT balanced iff there exists a cycle with
    # odd number of -1 edges.
    #
    # For switching classes: two sign vectors s and s' are in the same switching class iff
    # s XOR s' is a cut. The balance property is invariant under switching. So either all
    # sign vectors in a switching class give a connected lift, or none do.
    #
    # Strategy: Enumerate switching classes. For each class, check if it's connected (i.e.,
    # not balanced). Among connected classes, find the one with minimum spectral radius.
    #
    # Number of switching classes = 2^(n_vertices - c) where c is the number of connected
    # components of the base graph. For a prism graph, c=1, so 2^(2m-1) switching classes.
    # For m=4: 2^7=128, m=5: 2^9=512, m=7: 2^13=8192, m=9: 2^17=131072.
    #
    # To enumerate: fix vertex 0's "gauge" to 0. Then each switching class is determined by
    # the signs on a spanning tree. We can use a BFS/DFS spanning tree.

    # Build a spanning tree of the base graph
    # Use BFS from vertex 0
    adj = {i: [] for i in range(n_vertices)}
    for idx, (u, v) in enumerate(edges):
        adj[u].append((v, idx))
        adj[v].append((u, idx))

    # BFS to find spanning tree
    visited = [False] * n_vertices
    visited[0] = True
    queue = [0]
    tree_edges = []  # list of (parent, child, edge_idx)
    parent = [-1] * n_vertices
    parent[0] = -1

    while queue:
        node = queue.pop(0)
        for neighbor, eidx in adj[node]:
            if not visited[neighbor]:
                visited[neighbor] = True
                parent[neighbor] = node
                tree_edges.append((node, neighbor, eidx))
                queue.append(neighbor)

    n_tree_edges = len(tree_edges)  # = n_vertices - 1 = 2m - 1
    n_non_tree_edges = n_edges - n_tree_edges

    # For each switching class, the signs on tree edges determine the class (given gauge at vertex 0 = 0).
    # The signs on non-tree edges are then determined by the cycle constraints.
    #
    # Actually, let me think differently. A switching class is determined by the signs on the
    # non-tree edges (or equivalently, the "flips" on tree edges relative to a reference).
    #
    # Let's use this approach: 
    # - Pick a reference sign assignment (e.g., all +1).
    # - A switching is determined by a vector of 0/1 on the tree edges (with gauge fixing).
    # - The switched signs are: s'(e) = s(e) * (-1)^(number of tree edges in the path from root to u XOR path from root to v that are flipped)
    #
    # Simpler: enumerate all 2^(2m-1) assignments of signs to the tree edges. For each, compute
    # the implied signs on non-tree edges using cycle constraints. Check balance. Compute spectral radius.

    # Map edge indices
    tree_edge_set = set(eidx for _, _, eidx in tree_edges)
    non_tree_edge_indices = [i for i in range(n_edges) if i not in tree_edge_set]

    # For each non-tree edge, find the cycle it forms with the tree
    # The cycle is: the edge itself + the path in the tree between its endpoints
    non_tree_cycles = []
    for eidx in non_tree_edge_indices:
        u, v = edges[eidx]
        # Find path from u to v in the tree
        # Get path from u to root and v to root, find LCA
        path_u = []
        cur = u
        while cur != -1:
            path_u.append(cur)
            cur = parent[cur]
        path_v = []
        cur = v
        while cur != -1:
            path_v.append(cur)
            cur = parent[cur]
        
        # Find LCA
        set_v = set(path_v)
        lca = None
        for node in path_u:
            if node in set_v:
                lca = node
                break
        
        # Path from u to v in tree: u -> ... -> lca -> ... -> v
        # Edges on path from u to lca
        edges_u_to_lca = []
        cur = u
        while cur != lca:
            p = parent[cur]
            # Find edge index between cur and p
            for p2, c2, e2 in tree_edges:
                if (p2 == cur and c2 == p) or (p2 == p and c2 == cur):
                    edges_u_to_lca.append(e2)
                    break
            cur = p
        
        # Edges on path from lca to v
        edges_lca_to_v = []
        cur = v
        while cur != lca:
            p = parent[cur]
            for p2, c2, e2 in tree_edges:
                if (p2 == cur and c2 == p) or (p2 == p and c2 == cur):
                    edges_lca_to_v.append(e2)
                    break
            cur = p
        
        cycle_edges = edges_u_to_lca + [eidx] + edges_lca_to_v
        non_tree_cycles.append(cycle_edges)

    # Now enumerate switching classes
    # A switching class is determined by signs on tree edges.
    # For a given sign assignment on tree edges, the sign on each non-tree edge is determined
    # by the cycle constraint: the product of signs around the cycle must be +1 for balance,
    # or -1 for imbalance. Actually, the sign on the non-tree edge is free within the class;
    # what's fixed is the parity constraint.
    #
    # Let me reconsider. In a switching class, the product of signs around any cycle is invariant.
    # So for each non-tree edge e forming a cycle C with the tree, the sign s(e) is determined
    # by: s(e) = product_{f in C, f != e} s(f) * (cycle_product)
    # where cycle_product is the invariant for that cycle.
    #
    # Actually, the invariant is: for a cycle C, the product of signs is either +1 or -1,
    # and this is the same for all sign vectors in the switching class.
    #
    # So: given signs on tree edges, and given the cycle invariants (one per non-tree edge),
    # we can compute the sign on each non-tree edge.
    #
    # The cycle invariants are determined by the switching class. There are 2^(n_non_tree) possible
    # combinations of cycle invariants, but they're not all independent... actually for a connected
    # graph, the cycle space has dimension n_edges - n_vertices + 1 = n_non_tree_edges. So all
    # 2^(n_non_tree) combinations are achievable.
    #
    # Total switching classes = 2^(n_non_tree) = 2^(n_edges - n_vertices + 1)
    # For prism: n_edges = 3m, n_vertices = 2m, so n_non_tree = 3m - 2m + 1 = m + 1.
    # m=4: 2^5=32, m=5: 2^6=64, m=7: 2^8=256, m=9: 2^10=1024.
    #
    # This is very manageable!

    n_non_tree = len(non_tree_edge_indices)

    best_signs = None
    best_radius = float('inf')

    # For each combination of cycle invariants (2^n_non_tree possibilities):
    for mask in range(1 << n_non_tree):
        if time.time() > deadline:
            break

        # Determine signs on all edges
        # Start with all +1 on tree edges (this is a gauge choice; we'll fix it later)
        # Actually, we need to also vary the tree edge signs. 
        # 
        # Wait, I think I'm overcomplicating. Let me use a different approach:
        # 
        # The switching class is determined by the signs on a spanning tree (with one gauge
        # vertex fixed). The number of degrees of freedom is n_vertices - 1 = 2m - 1.
        # But the cycle invariants give n_non_tree = m+1 constraints that relate the signs.
        # 
        # Actually, for a connected graph, the number of switching classes is 2^(n_vertices - 1).
        # Each switching class contains 2^(n_non_tree) sign vectors (differing by cuts on non-tree edges... no).
        #
        # Let me just enumerate directly: for each of the 2^(2m-1) assignments of "vertex potentials"
        # (with vertex 0 fixed to 0), compute the resulting signs.
        #
        # A switching is: s'(u,v) = s(u,v) * (-1)^(f(u) + f(v)) where f: V -> {0,1} is the
        # switching function. With f(0) = 0 fixed, there are 2^(2m-1) switchings.
        #
        # The resulting sign on edge (u,v) is: s(u,v) * (-1)^(f(u) + f(v))
        # where s is a reference sign (e.g., all +1).

        # Enumerate f(1), f(2), ..., f(2m-1)
        # There are 2^(2m-1) possibilities
        # For m=9, that's 2^17 = 131072. Each requires computing spectral radius.
        # 131072 * (eigvalsh on 18x18 matrix) might be too slow.
        #
        # Let me estimate: eigvalsh on 18x18 is maybe 50 microseconds. 131072 * 50us = 6.5 seconds.
        # That's fine!

        pass  # We'll do the actual enumeration below

    # Actually, let me do the enumeration more carefully
    # Reference signs: all +1
    # For each switching f (with f[0]=0), compute signs and check validity + spectral radius

    n_switchings = 1 << (n_vertices - 1)  # 2^(2m-1)

    for mask in range(n_switchings):
        if time.time() > deadline:
            break

        # Decode f: f[0] = 0, f[i] = bit (i-1) of mask for i = 1, ..., 2m-1
        f = np.zeros(n_vertices, dtype=np.int8)
        for i in range(1, n_vertices):
            f[i] = (mask >> (i - 1)) & 1

        # Compute signs: s(u,v) = (-1)^(f(u) + f(v)) since reference is all +1
        signs = np.ones(n_edges, dtype=np.int8)
        for idx, (u, v) in enumerate(edges):
            if f[u] + f[v] == 1:
                signs[idx] = -1

        # Check if lift is connected (equivalently, signed graph is not balanced)
        # A signed graph is balanced iff every cycle has even number of -1 edges.
        # Check: compute the product of signs around each fundamental cycle.
        # If all are +1, it's balanced (lift disconnected). Otherwise, not balanced (lift connected).

        balanced = True
        for cycle_edges in non_tree_cycles:
            prod = 1
            for eidx in cycle_edges:
                prod *= signs[eidx]
            if prod == -1:
                balanced = False
                break

        if balanced:
            continue  # Lift is disconnected

        # Compute spectral radius
        r = spectral_radius(signs)
        if r < best_radius:
            best_radius = r
            best_signs = signs.copy()

    if best_signs is None:
        # Fallback: random search for a valid assignment
        rng = np.random.default_rng(42)
        for _ in range(1000):
            if time.time() > deadline:
                break
            signs = rng.choice([-1, 1], size=n_edges).astype(np.int8)
            if is_connected_lift(signs):
                best_signs = signs.copy()
                best_radius = spectral_radius(signs)
                break

    if best_signs is None:
        return np.ones(n_edges, dtype=np.int8)

    return best_signs
