import random
import time
import math

# EVOLVE-BLOCK-START
def construct(n_rows, k):
    start_time = time.time()
    # The evaluator kills after 150s, but the task contract says 120s.
    # We use a safety margin to ensure we return before the hard kill.
    deadline = start_time + 115.0
    
    # Total number of differences that must be distinct
    diffs_per_row = k * (k + 1) // 2
    total_diffs = n_rows * diffs_per_row
    
    # We want to minimize the largest entry M.
    # The counting bound is total_diffs.
    # We will try to find a solution with M starting from the lower bound upwards.
    
    # Bitset representation for used differences.
    # We need to track differences up to M.
    # Python integers can be arbitrarily large, so we can use them as bitsets.
    # Bit d is set if difference d is used.
    
    def solve_csp(M, seed):
        """
        Attempt to find a valid set of rows with max entry <= M.
        Uses DFS with backtracking and bitset pruning.
        """
        rng = random.Random(seed)
        
        # State:
        # rows: list of n_rows lists, each of length k+1 (first is 0)
        # used_diffs: bitset of used differences
        # 
        # We fill rows one by one. Within a row, we fill elements one by one.
        # To make it harder to satisfy, we can order the rows? 
        # Actually, the rows are symmetric. But the "tightness" might vary.
        # A common heuristic is to solve the most constrained subproblem first.
        # Here, all rows have the same structure.
        
        # However, we can randomize the order of rows to escape local minima if we were doing SA,
        # but in DFS, the order of rows doesn't change the search space size, just the path.
        # What matters more is the order of values we try for each position.
        
        # We will represent the partial solution as a list of current rows.
        # rows[i] is a list of integers.
        
        # To speed up, we can pre-compute or dynamically generate candidate values.
        
        # Heuristic: 
        # When placing the j-th element of row i (j from 1 to k),
        # we need a value x > rows[i][j-1] and x <= M.
        # Also, for all previous elements a in rows[i][0:j], x - a must not be in used_diffs.
        # And for all future rows, we just need to ensure we don't use diffs already taken.
        
        # We will use recursion.
        # Depth: row_index * k + col_index
        # But recursion depth can be high. For n_rows=4, k=7, depth is 28. This is fine.
        
        rows = [[0] for _ in range(n_rows)]
        used_diffs = 0  # Bit 0 is 0, which is not a positive difference, so we can ignore bit 0 or set it.
        
        # We need to check if a difference d is used.
        # (used_diffs >> d) & 1
        
        # We need to check if a set of differences is disjoint from used_diffs.
        # We can precompute the bitset of differences generated by adding x to the current row prefix.
        
        def backtrack(row_idx, col_idx):
            # Check time
            if time.time() > deadline:
                return False
            
            if row_idx == n_rows:
                return True
            
            if col_idx == k + 1:
                # Finished this row, move to next
                return backtrack(row_idx + 1, 1)
            
            # We are placing rows[row_idx][col_idx]
            # Previous element:
            prev_val = rows[row_idx][col_idx - 1]
            # Next element (if exists):
            # We don't strictly need to check against next yet, just ensure increasing.
            
            # Candidate range: prev_val + 1 to M
            # But we also need to ensure that the differences formed are not used.
            
            # To prune effectively, we should try values that are "safe".
            # Let's generate candidates.
            # Randomizing the order of candidates can help avoid getting stuck in a specific bad pattern,
            # but DFS is deterministic if we fix the order. 
            # We can shuffle the candidates or use a heuristic order.
            
            # Heuristic: Try values that minimize the "cost" of future placements?
            # Or just randomize to allow multiple attempts with different seeds.
            
            # Let's collect valid candidates for this position.
            candidates = []
            # Optimization: Instead of checking all x in [prev_val+1, M], 
            # we can iterate and check bitset.
            # M is at most ~134 for the known solution. Range is small.
            
            for x in range(prev_val + 1, M + 1):
                # Check if x - a is already used for any a in rows[row_idx][0:col_idx]
                # Also check if x - a is 0? No, x > a so diff > 0.
                
                # We need to check if any of these diffs are in used_diffs.
                # We can build a temporary bitset for this row's new diffs?
                # Or just check one by one.
                
                valid = True
                for i in range(col_idx):
                    d = x - rows[row_idx][i]
                    if (used_diffs >> d) & 1:
                        valid = False
                        break
                
                if valid:
                    candidates.append(x)
            
            # Shuffle candidates to add randomness (if we want to explore different paths)
            # But for a single DFS run, a fixed order is deterministic.
            # The seed allows us to shuffle the candidates differently in each call.
            rng.shuffle(candidates)
            
            for x in candidates:
                # Place x
                rows[row_idx].append(x)
                
                # Update used_diffs
                new_diffs_bitset = 0
                for i in range(col_idx):
                    d = x - rows[row_idx][i]
                    new_diffs_bitset |= (1 << d)
                
                # Also, we need to check if these new diffs conflict with each other?
                # No, within the same row, differences are distinct if the row is strictly increasing?
                # Wait. If row is [0, 2, 4], diffs are 2, 4, 2. Conflict!
                # So we MUST check that the new diffs are distinct among themselves too.
                # The check above `(used_diffs >> d) & 1` only checks against GLOBAL used diffs.
                # It does NOT check against diffs generated by OTHER elements in the SAME row that were already placed?
                # Actually, `used_diffs` contains ALL diffs from all previous rows AND previous columns of current row.
                # So if we placed [0, 2], used_diffs has bit 2.
                # Now we try x=4. d1 = 4-0=4, d2 = 4-2=2.
                # d2=2 is in used_diffs. So it would be rejected.
                # So the logic holds.
                
                # Apply change
                old_used = used_diffs
                used_diffs = old_used | new_diffs_bitset
                
                # Recurse
                if backtrack(row_idx, col_idx + 1):
                    return True
                
                # Backtrack
                rows[row_idx].pop()
                used_diffs = old_used
            
            return False
        
        # Start backtracking
        # We start at row 0, col 1 (since col 0 is 0)
        if backtrack(0, 1):
            return rows
        return None

    # Strategy:
    # 1. Estimate a good lower bound for M.
    # 2. Try to solve for M = lower_bound, then lower_bound + 1, etc.
    # 3. Use multiple random seeds for the candidate shuffling to explore different search paths.
    
    # Lower bound:
    # We need total_diffs distinct positive integers.
    # The largest difference in a row with max M is M.
    # The set of all differences is a subset of {1, ..., M}.
    # So we need M >= total_diffs.
    # Actually, the differences are not necessarily contiguous.
    # But M must be at least the total number of differences.
    
    lb = total_diffs
    
    # We can also use a better lower bound if we know the structure, but lb is a good start.
    # The known solution is 134 for (4,7). total_diffs = 4 * 28 = 112.
    # So we will search from 112 upwards.
    
    best_rows = None
    
    # We will try a few values of M, and for each M, a few seeds.
    # To maximize the chance of finding a solution quickly, we should prioritize smaller M.
    
    # Let's allocate time.
    # We have ~115 seconds.
    # We'll try M from lb to lb + 50.
    # For each M, we'll run DFS with a few seeds.
    
    # Actually, DFS can be very fast if it finds a solution, or very slow if it doesn't.
    # We should limit the time per (M, seed) combination.
    
    # Let's try a "budgeted" DFS.
    # We'll modify backtrack to check time and return False if exceeded.
    # The current backtrack already checks time at the top of the function.
    # This might be too frequent. Let's check every 1000 calls? 
    # Or just rely on the fact that for small M, the search tree is small.
    
    # For M=112, the branching factor is small.
    # For M=134, it's larger.
    
    # Let's try M values in increasing order.
    # For each M, try seeds 0, 1, 2...
    
    # We need to be careful not to spend all time on M=112 if it's impossible.
    # But if it's impossible, DFS should fail relatively quickly if the constraints are tight?
    # Not necessarily. It might explore a huge tree.
    
    # Better strategy:
    # Run DFS for M=lb. If it fails, try M=lb+1, etc.
    # But add a timeout per M.
    
    # Let's set a timeout per M value, say 5 seconds.
    # If we don't find a solution in 5s for M, move to M+1.
    
    # Actually, the problem is hard. The known solution is 134.
    # If we start at 112, we might waste time.
    # But we don't know the exact lower bound for this specific instance (though 112 is the counting bound).
    
    # Let's try a range of M values, interleaved with seeds.
    
    # We'll create a list of (M, seed) tasks.
    # Sort by M, then seed.
    
    # But we don't know how many seeds to try per M.
    # Let's just loop M from lb to lb + 100.
    # For each M, loop seed from 0 to 10.
    # Check time.
    
    # To make it more robust, we can also try a "greedy" initialization to get a valid solution first,
    # then use local search to reduce M.
    # But the directive asks for a CSP/DFS approach.
    
    # Let's stick to DFS but make it efficient.
    
    # One optimization: 
    # If we fail to place an element, we backtrack.
    # We can add a "forward checking" heuristic: 
    # After placing x, check if the NEXT position has any valid candidates.
    # If not, backtrack immediately.
    
    # Let's implement forward checking in the backtrack function.
    
    def solve_csp_with_fc(M, seed):
        rng = random.Random(seed)
        rows = [[0] for _ in range(n_rows)]
        used_diffs = 0
        
        def get_candidates(row_idx, col_idx, current_used):
            """
            Get valid candidates for rows[row_idx][col_idx].
            """
            if col_idx > k:
                return []
            
            prev_val = rows[row_idx][col_idx - 1]
            candidates = []
            
            for x in range(prev_val + 1, M + 1):
                valid = True
                for i in range(col_idx):
                    d = x - rows[row_idx][i]
                    if (current_used >> d) & 1:
                        valid = False
                        break
                if valid:
                    candidates.append(x)
            
            return candidates
        
        def backtrack(row_idx, col_idx):
            if time.time() > deadline:
                return False
            
            if row_idx == n_rows:
                return True
            
            if col_idx == k + 1:
                return backtrack(row_idx + 1, 1)
            
            candidates = get_candidates(row_idx, col_idx, used_diffs)
            
            if not candidates:
                return False
            
            rng.shuffle(candidates)
            
            for x in candidates:
                rows[row_idx].append(x)
                
                new_diffs_bitset = 0
                for i in range(col_idx):
                    d = x - rows[row_idx][i]
                    new_diffs_bitset |= (1 << d)
                
                new_used = used_diffs | new_diffs_bitset
                
                # Forward checking:
                # Check if the next position has candidates.
                # If col_idx + 1 <= k, check next col in same row.
                # Else, check col 1 of next row.
                
                next_row_idx = row_idx
                next_col_idx = col_idx + 1
                if next_col_idx == k + 1:
                    next_row_idx = row_idx + 1
                    next_col_idx = 1
                
                # Only check if there is a next position
                if next_row_idx < n_rows:
                    next_candidates = get_candidates(next_row_idx, next_col_idx, new_used)
                    if not next_candidates:
                        rows[row_idx].pop()
                        continue # Try next candidate for current position
                
                if backtrack(row_idx, col_idx + 1):
                    return True
                
                rows[row_idx].pop()
            
            return False
        
        if backtrack(0, 1):
            return rows
        return None

    # Main loop
    # We'll try M values starting from lb.
    # We'll give each M a few seconds.
    
    # To be safe, let's try a few M values with multiple seeds.
    
    # If we find a solution, we can try to improve it?
    # No, the task is to minimize M. The first valid M we find is not necessarily the minimum.
    # But finding ANY valid solution with small M is good.
    # If we find one with M=134, we can return it.
    # If we find one with M=130, that's better.
    
    # So we should search for the SMALLEST M.
    
    # We'll iterate M from lb upwards.
    # For each M, we'll try a few seeds.
    # If we find a solution, we return it.
    
    # But what if M=lb is impossible? We need to move to M=lb+1.
    # How do we know it's impossible? We don't, unless DFS exhausts the tree.
    # DFS with forward checking should prune a lot.
    
    # Let's set a time limit per M.
    time_per_M = 5.0
    
    M = lb
    max_M_tried = lb + 100 # Don't go too far
    
    while M <= max_M_tried and time.time() < deadline:
        M_start_time = time.time()
        
        # Try a few seeds for this M
        seed = 0
        while seed < 20 and time.time() < M_start_time + time_per_M:
            rows = solve_csp_with_fc(M, seed)
            if rows:
                # Found a valid solution with max entry <= M
                # Actually, the max entry might be less than M.
                # We should return the rows.
                # The score is the largest entry.
                return rows
            seed += 1
        
        M += 1
    
    # If we didn't find a solution in the loop, we need a fallback.
    # This should not happen if M is large enough.
    # But just in case, use a simple greedy that might not be optimal but is valid.
    # Greedy:
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new_diffs = {x - a for a in row}
            if not (new_diffs & used):
                row.append(x)
                used |= new_diffs
        rows.append(row)
    
    return rows

