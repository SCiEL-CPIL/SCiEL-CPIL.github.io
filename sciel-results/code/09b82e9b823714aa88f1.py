"""
Strategy: Deterministic FCC Lattice Initialization + Gradient-Based Optimization.
This approach leverages the known optimal packing structure (FCC) to initialize
spheres, avoiding the "messy" start of random or simple cubic grids. 
It then uses a smooth surrogate objective function (sum of repulsive potentials)
and a gradient-based optimizer (L-BFGS-B) to refine the packing, specifically
addressing boundary constraints and local density fluctuations.
"""
import numpy as np
import time
from scipy.optimize import minimize

N = 100

def _compute_score(centres):
    """Compute the largest common radius for the given centres."""
    if centres.shape != (N, 3):
        return -np.inf
    if not np.all(np.isfinite(centres)):
        return -np.inf
    if np.any(centres < -0.5) or np.any(centres > 0.5):
        return -np.inf
    
    # Min distance from boundary
    dist_boundary = 0.5 - np.max(np.abs(centres), axis=1)
    min_boundary = np.min(dist_boundary)
    if min_boundary < -1e-15:
        return -np.inf
        
    # Pairwise distances
    min_pair = np.inf
    # Efficient pairwise distance calculation for min
    # For N=100, O(N^2) is fine, but we can vectorize slightly
    for i in range(N):
        diffs = centres[i+1:] - centres[i]
        dists = np.sqrt(np.sum(diffs**2, axis=1))
        if len(dists) > 0:
            min_pair = min(min_pair, np.min(dists))
            
    if not np.isfinite(min_pair):
        return -np.inf
    return min(min_pair / 2.0, min_boundary)

def _fcc_lattice_init():
    """
    Generate an FCC lattice of points within [-0.5, 0.5]^3.
    FCC lattice points are at (i, j, k) where i+j+k is even, scaled by a/2.
    Actually, standard FCC basis in cubic cell of side 'a' is:
    (0,0,0), (0, a/2, a/2), (a/2, 0, a/2), (a/2, a/2, 0) + integer translations.
    
    We want to pack N=100 spheres. 
    Volume of cube = 1. Volume per sphere = 1/100 = 0.01.
    Radius r ~ (0.01/4/3*pi)^(1/3) ~ 0.062 (if dense). 
    Specht's r is 0.111, which implies denser packing or different geometry.
    Wait, r=0.111 means diameter 0.222. 
    Simple cubic with side 1 fits 5x5x5=125 spheres of r=0.1.
    So 100 spheres of r=0.111 is very dense.
    
    Let's generate a dense FCC-like grid and pick the best 100.
    """
    # Generate a fine grid of FCC points
    # FCC primitive vectors: (0.5, 0.5, 0), (0.5, 0, 0.5), (0, 0.5, 0.5)
    # Let's just generate a cubic grid of FCC unit cells.
    # Each unit cell of side 's' contains 4 FCC points.
    # We need 100 points. 25 unit cells * 4 = 100 points.
    # So a 3x3x3 block of unit cells? No, 3^3=27 cells * 4 = 108 points.
    # Let's generate points for a 3x3x3 array of FCC unit cells.
    
    points = []
    # FCC basis in a unit cube of side 1:
    # (0,0,0), (0, 0.5, 0.5), (0.5, 0, 0.5), (0.5, 0.5, 0)
    # Plus corner sharing? No, let's use the standard lattice points.
    # Lattice points are at (x,y,z) where x,y,z are integers or half-integers such that x+y+z is integer?
    # Simpler: 
    # The FCC lattice can be generated by taking a cubic lattice of spacing 'a' 
    # and adding points at face centers.
    
    # Let's try a 4x4x4 simple cubic grid of "sites" and map them to FCC?
    # Actually, let's just generate a dense set of candidate points from an FCC lattice
    # scaled to fit the cube, and select the 100 that maximize the minimum distance.
    
    # Generate FCC points in a slightly larger box to ensure coverage, then clip/select.
    # FCC basis vectors for lattice constant a:
    # v1 = (a/2, a/2, 0)
    # v2 = (a/2, 0, a/2)
    # v3 = (0, a/2, a/2)
    
    # We want ~100 points in volume 1.
    # Density of FCC is pi / (3 * sqrt(2)) * 1/a^3.
    # 100 = density * 1 => a^3 = 1 / (100 * pi / (3*sqrt(2))) = 3*sqrt(2)/(100*pi) ~ 0.0135.
    # a ~ 0.238.
    
    a = 0.238
    # Generate points in range [-0.5, 0.5]
    # n_max = int(1.0 / a) + 2
    n_max = 10
    coords = []
    for i in range(-n_max, n_max+1):
        for j in range(-n_max, n_max+1):
            for k in range(-n_max, n_max+1):
                # Generate the 4 FCC points in the unit cell defined by i,j,k
                # Cell corner: (i*a, j*a, k*a)
                cx = i * a
                cy = j * a
                cz = k * a
                # Points in this cell:
                p1 = np.array([cx, cy, cz])
                p2 = np.array([cx + a/2, cy + a/2, cz])
                p3 = np.array([cx + a/2, cy, cz + a/2])
                p4 = np.array([cx, cy + a/2, cz + a/2])
                
                for p in [p1, p2, p3, p4]:
                    # Check if inside or near the cube
                    if np.all(p >= -0.6) and np.all(p <= 0.6):
                        coords.append(p)
                        
    coords = np.array(coords)
    
    # We have many more than 100 points.
    # We want to select 100 points that form the best packing.
    # Strategy: 
    # 1. Filter points strictly inside [-0.5, 0.5].
    # 2. If we have > 100, we need to choose which ones to keep.
    #    We can use a greedy algorithm: pick the point with the largest distance to existing picked points.
    #    This is a "MaxMin" selection.
    
    inside = np.all((coords >= -0.5) & (coords <= 0.5), axis=1)
    coords = coords[inside]
    
    if len(coords) < N:
        # Fallback to random if FCC generation failed (unlikely)
        return np.random.rand(N, 3) - 0.5
        
    # Greedy MaxMin selection
    selected = []
    # Start with a point near the center to maintain symmetry? Or just random?
    # Let's start with the point closest to (0,0,0) to anchor the lattice.
    dists_to_origin = np.sum(coords**2, axis=1)
    first_idx = np.argmin(dists_to_origin)
    selected.append(coords[first_idx])
    remaining = np.delete(coords, first_idx, axis=0)
    
    while len(selected) < N and len(remaining) > 0:
        # Compute min distance from each remaining point to all selected points
        # This is O(N_remaining * N_selected * 3)
        # N_remaining ~ 1000, N_selected ~ 100. 1000*100 = 100k ops. Fast.
        min_dists = np.inf * np.ones(len(remaining))
        for sel in selected:
            dists = np.sqrt(np.sum((remaining - sel)**2, axis=1))
            min_dists = np.minimum(min_dists, dists)
            
        # Pick the point with the maximum min_dist
        best_idx = np.argmax(min_dists)
        selected.append(remaining[best_idx])
        remaining = np.delete(remaining, best_idx, axis=0)
        
    return np.array(selected)

def _smooth_potential(centres, r_target=0.11, sigma=0.01):
    """
    Smooth surrogate objective.
    We want to maximize the minimum distance.
    Equivalent to minimizing the maximum overlap.
    Let d_ij be distance. We want d_ij >= 2r.
    Penalty = sum_{i<j} max(0, 2r - d_ij)^2 + sum_i max(0, r - (0.5 - |c_i|_inf))^2
    
    However, gradients of max are discontinuous.
    Use a soft plus function: softplus(x) = log(1+exp(x/sigma))*sigma.
    Or simply: sum exp((2r - d_ij)/sigma) for d_ij < 2r.
    
    Let's use a simpler energy:
    E = sum_{i<j} (1/ (d_ij^2 + epsilon)) for d_ij < 2r_target
    This pushes them apart.
    Plus boundary penalty: sum_i (1 / (dist_boundary_i^2 + epsilon)) for dist < r_target.
    
    To make it differentiable everywhere, we use:
    E_pair = sum_{i<j} exp((2*r_target - d_ij) / sigma)
    E_bound = sum_i exp((r_target - dist_b_i) / sigma)
    
    Minimizing this E drives d_ij > 2r_target and dist_b > r_target.
    """
    if not np.all(np.isfinite(centres)):
        return 1e10
        
    # Boundary
    dist_b = 0.5 - np.max(np.abs(centres), axis=1)
    # Penalty if dist_b < r_target
    # Use softplus-like: log(1 + exp((r_target - dist_b)/sigma))
    # To avoid overflow, clip argument
    arg_b = (r_target - dist_b) / sigma
    arg_b = np.clip(arg_b, -50, 50)
    E_bound = np.sum(np.log1p(np.exp(arg_b)))
    
    # Pairwise
    E_pair = 0.0
    # Vectorized pairwise
    for i in range(N):
        diffs = centres[i+1:] - centres[i]
        dists = np.sqrt(np.sum(diffs**2, axis=1))
        arg_p = (2*r_target - dists) / sigma
        arg_p = np.clip(arg_p, -50, 50)
        E_pair += np.sum(np.log1p(np.exp(arg_p)))
        
    return E_pair + E_bound

def _gradient_potential(centres, r_target=0.11, sigma=0.01):
    """Compute gradient of the smooth potential."""
    grad = np.zeros_like(centres)
    
    # Boundary gradient
    # E_bound = sum log(1 + exp((r - d_b)/sigma))
    # d/dx log(1+exp(u)) = exp(u)/(1+exp(u)) * du/dx = sigmoid(u) * du/dx
    # u = (r - d_b)/sigma. du/dx = -1/sigma * d(d_b)/dx.
    # d_b = 0.5 - max(|x|,|y|,|z|).
    # d(d_b)/dx = -sign(x) if |x| is max, else 0.
    
    abs_c = np.abs(centres)
    max_idx = np.argmax(abs_c, axis=1)
    signs = np.sign(centres)
    
    dist_b = 0.5 - np.max(abs_c, axis=1)
    arg_b = (r_target - dist_b) / sigma
    arg_b = np.clip(arg_b, -50, 50)
    sig_b = 1 / (1 + np.exp(-arg_b))
    
    # Gradient contribution from boundary
    # dE/dx_i = sig_b_i * (-1/sigma) * (-sign(x_i) if i is max coord)
    # Wait, d_b = 0.5 - max. d(max)/dx = sign(x) if x is max.
    # d(d_b)/dx = -sign(x).
    # So dE/dx = sig_b * (1/sigma) * sign(x) * indicator(i==max_idx)
    
    for i in range(N):
        idx = max_idx[i]
        if sig_b[i] > 1e-6:
            grad[i, idx] += (sig_b[i] / sigma) * signs[i, idx]
            
    # Pairwise gradient
    # E_pair = sum_{i<j} log(1 + exp((2r - d_ij)/sigma))
    # dE/dd_ij = (1/sigma) * sigmoid((2r-d)/sigma)
    # dE/dx_i = sum_{j!=i} (dE/dd_ij) * (d_ij/dx_i)
    # d_ij/dx_i = (x_i - x_j) / d_ij
    
    for i in range(N):
        for j in range(i+1, N):
            diff = centres[i] - centres[j]
            d = np.linalg.norm(diff)
            if d < 1e-8:
                # Perturb slightly to avoid division by zero
                diff = np.array([1e-8, 0, 0])
                d = 1e-8
                
            arg_p = (2*r_target - d) / sigma
            arg_p = np.clip(arg_p, -50, 50)
            sig_p = 1 / (1 + np.exp(-arg_p))
            
            factor = (sig_p / sigma) / d
            grad[i] += factor * diff
            grad[j] -= factor * diff
            
    return grad

def _optimize(centres, time_limit=10.0):
    """
    Use L-BFGS-B to minimize the smooth potential.
    """
    start_time = time.time()
    
    def objective(x):
        if time.time() - start_time > time_limit:
            raise ValueError("Timeout")
        return _smooth_potential(x.reshape(N, 3))
        
    def jac(x):
        if time.time() - start_time > time_limit:
            raise ValueError("Timeout")
        return _gradient_potential(x.reshape(N, 3)).flatten()
        
    # Bounds: [-0.5, 0.5]
    bounds = [(-0.5, 0.5)] * (N * 3)
    
    try:
        res = minimize(
            objective, 
            centres.flatten(), 
            method='L-BFGS-B', 
            jac=jac, 
            bounds=bounds,
            options={'maxiter': 1000, 'ftol': 1e-12, 'gtol': 1e-8}
        )
        if res.success or res.status in [1, 2, 3, 4, 5, 6]: # Some warnings are ok
             return res.x.reshape(N, 3)
        else:
             return centres
    except Exception:
        return centres

def construct():
    deadline = time.time() + 145.0 # Safety margin
    
    # 1. Initialize with FCC lattice selection
    centres = _fcc_lattice_init()
    best_centres = centres.copy()
    best_score = _compute_score(centres)
    
    # 2. Optimize with gradient descent
    # We might need to try different r_targets to guide the optimization.
    # Start with a slightly smaller r to allow movement, then increase.
    
    if time.time() < deadline - 20:
        # Coarse optimization
        c_opt = _optimize(centres, time_limit=15.0)
        s_opt = _compute_score(c_opt)
        if s_opt > best_score:
            best_score = s_opt
            best_centres = c_opt.copy()
            
    # 3. Fine optimization with a tighter potential (smaller sigma)
    # The previous optimization might have settled in a local minimum of the smooth potential
    # that doesn't correspond to the global max-min distance.
    # We can try restarting with a smaller sigma to sharpen the potential.
    
    if time.time() < deadline - 10:
        # Modify the potential parameters for finer search
        # We can't easily change the closure parameters in the previous call without refactoring.
        # Let's just run another optimization on the current best.
        # To make it "finer", we rely on the fact that we are already close.
        # L-BFGS-B will take smaller steps as it converges.
        
        c_opt2 = _optimize(best_centres, time_limit=10.0)
        s_opt2 = _compute_score(c_opt2)
        if s_opt2 > best_score:
            best_score = s_opt2
            best_centres = c_opt2.copy()
            
    # 4. Local refinement (Hill Climbing) to polish the result
    # Gradient descent might stop at a point where the smooth potential is flat 
    # but the hard constraint (min distance) could be improved by a tiny move.
    if time.time() < deadline - 5:
        # Simple local search
        step = 0.001
        stagnant = 0
        curr = best_centres.copy()
        curr_score = best_score
        
        while time.time() < deadline - 1 and stagnant < 100:
            # Find bottleneck
            min_boundary = np.inf
            min_boundary_idx = -1
            dists_boundary = 0.5 - np.max(np.abs(curr), axis=1)
            min_boundary = np.min(dists_boundary)
            min_boundary_idx = np.argmin(dists_boundary)
            
            min_pair_dist = np.inf
            min_pair_i = -1
            min_pair_j = -1
            i_idx, j_idx = np.triu_indices(N, k=1)
            diffs = curr[i_idx] - curr[j_idx]
            dists = np.sqrt(np.sum(diffs**2, axis=1))
            min_pair_idx = np.argmin(dists)
            min_pair_dist = dists[min_pair_idx]
            min_pair_i = i_idx[min_pair_idx]
            min_pair_j = j_idx[min_pair_idx]
            
            improved = False
            
            if min_pair_dist / 2.0 < min_boundary:
                i, j = min_pair_i, min_pair_j
                diff = curr[i] - curr[j]
                norm = np.linalg.norm(diff)
                if norm > 1e-10:
                    dir_vec = diff / norm
                    new_i = curr[i] + dir_vec * step
                    new_j = curr[j] - dir_vec * step
                    new_i = np.clip(new_i, -0.5, 0.5)
                    new_j = np.clip(new_j, -0.5, 0.5)
                    
                    old_i = curr[i].copy()
                    old_j = curr[j].copy()
                    curr[i] = new_i
                    curr[j] = new_j
                    
                    new_score = _compute_score(curr)
                    if new_score > curr_score:
                        curr_score = new_score
                        improved = True
                        if new_score > best_score:
                            best_score = new_score
                            best_centres = curr.copy()
                    else:
                        curr[i] = old_i
                        curr[j] = old_j
            else:
                idx = min_boundary_idx
                pos = curr[idx]
                # Move towards center
                dir_vec = -pos / (np.linalg.norm(pos) + 1e-10)
                new_pos = pos + dir_vec * step
                new_pos = np.clip(new_pos, -0.5, 0.5)
                
                old_pos = pos.copy()
                curr[idx] = new_pos
                new_score = _compute_score(curr)
                if new_score > curr_score:
                    curr_score = new_score
                    improved = True
                    if new_score > best_score:
                        best_score = new_score
                        best_centres = curr.copy()
                else:
                    curr[idx] = old_pos
                    
            if not improved:
                stagnant += 1
                step *= 0.95
                if step < 1e-7:
                    break
            else:
                stagnant = 0
                step *= 1.01 # Slightly increase step if improving
        
    # Ensure validity
    final_score = _compute_score(best_centres)
    if final_score <= 0 or not np.isfinite(final_score):
        best_centres = _fcc_lattice_init()
        
    return best_centres

if __name__ == "__main__":
    # Simple test
    t0 = time.time()
    c = construct()
    t1 = time.time()
    print(f"Time: {t1-t0:.2f}s")
    print(f"Score: {_compute_score(c)}")
