"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import time
import random
from math import isqrt

P = {'n': 40, 'maximum_size': 18}

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin before 60s limit
    
    # Primes up to 40 - known valid set of size 12
    primes = [a for a in range(2, P['n'] + 1) if all(a % d for d in range(2, isqrt(a) + 1))]
    
    # Direct product-based validity check
    def is_valid(S):
        if not S:
            return True
        products = {1}
        for x in S:
            new_products = {p * x for p in products}
            if products & new_products:
                return False
            products |= new_products
        return True
    
    # Try to add x to set S, return True if valid
    def try_add(S, x):
        if x in S:
            return False
        # Quick check: x must not create a collision
        # This is equivalent to checking that x is not in the multiplicative 
        # subgroup generated by S in a way that causes collision
        # Fastest: just check the full set
        new_S = S | {x}
        return is_valid(new_S)
    
    all_candidates = list(range(2, P['n'] + 1))
    best_set = set(primes)
    best_size = len(best_set)
    
    def greedy_add(S, deadline):
        """Keep adding elements until stuck."""
        added = True
        while added and time.time() < deadline:
            added = False
            candidates = [c for c in all_candidates if c not in S]
            random.shuffle(candidates)
            for x in candidates:
                if try_add(S, x):
                    S.add(x)
                    added = True
                    break
    
    for restart in range(80):
        if time.time() > deadline:
            break
        
        # Vary starting point: sometimes start from primes, sometimes from a random valid subset
        if restart % 3 == 0:
            S = set(primes)
        elif restart % 3 == 1:
            # Start from a random subset of primes + some composites
            S = set(random.sample(primes, max(1, len(primes) - 2)))
            # Try to add a few composites
            for _ in range(3):
                candidates = [c for c in all_candidates if c not in S and c not in primes]
                if not candidates:
                    break
                x = random.choice(candidates)
                if try_add(S, x):
                    S.add(x)
        else:
            # Start from best_set with some perturbation
            S = set(best_set)
            # Remove 1-2 random elements
            for _ in range(random.randint(1, 2)):
                if S:
                    S.discard(random.choice(list(S)))
        
        # Greedy add
        greedy_add(S, deadline)
        
        if len(S) > best_size:
            best_set = set(S)
            best_size = len(S)
            if best_size == P['maximum_size']:
                break
        
        # If not at max, try swap moves
        if len(S) < P['maximum_size'] and time.time() < deadline - 3:
            swap_attempts = 0
            max_swaps = 40
            while swap_attempts < max_swaps and time.time() < deadline - 1:
                swap_attempts += 1
                
                # 1-for-1 swap
                if len(S) >= 1:
                    to_remove = random.choice(list(S))
                    S.discard(to_remove)
                    candidates = [c for c in all_candidates if c not in S]
                    if candidates:
                        to_add = random.choice(candidates)
                        if try_add(S, to_add):
                            S.add(to_add)
                            greedy_add(S, deadline)
                            if len(S) > best_size:
                                best_set = set(S)
                                best_size = len(S)
                                if best_size == P['maximum_size']:
                                    break
                        else:
                            S.add(to_remove)
                
                # 2-for-1 swap: remove 2, add 1
                if len(S) >= 2 and time.time() < deadline - 1:
                    remove_pair = random.sample(list(S), 2)
                    for r in remove_pair:
                        S.discard(r)
                    candidates = [c for c in all_candidates if c not in S]
                    if candidates:
                        to_add = random.choice(candidates)
                        if try_add(S, to_add):
                            S.add(to_add)
                            greedy_add(S, deadline)
                            if len(S) > best_size:
                                best_set = set(S)
                                best_size = len(S)
                                if best_size == P['maximum_size']:
                                    break
                        else:
                            for r in remove_pair:
                                S.add(r)
                
                if best_size == P['maximum_size']:
                    break
        
        if best_size == P['maximum_size']:
            break
    
    # Final verification
    if not is_valid(best_set):
        # Fallback to primes if somehow invalid
        return primes
    
    return list(best_set)

# EVOLVE-BLOCK-END
