    # Then iteratively tighten.
    
    # To make it robust, we can do a binary search or linear decrease.
    # Linear decrease from 150 to 112 is 38 steps.
    # Each step might take some time.
    
    # Let's try to find the best possible within the time limit.
    # We'll iterate M from upper_bound down to 100.
    # If we find a solution, we update best.
    # We stop if we run out of time.
    
    # Optimization: If we find a solution at M, we can stop trying larger M.
    # We want the smallest M. So we go down.
    
    # However, finding a solution at M=134 might be hard if we start at 150.
    # Actually, if we start at 150, we find a solution. Then we try 149.
    # If 149 fails, we try 148.
    # This is efficient if the "gap" in solvability is small.
    
    # Let's add a randomization factor to the backtracking to help it find solutions faster.
    # The _backtrack_row function already shuffles candidates.
    
    # To ensure we don't get stuck in one bad random seed, we can allow multiple attempts per M.
    
    for M in range(upper_bound, 100, -1):
        if time.time() - start_total > 110: # Leave 10s buffer
            break
            
