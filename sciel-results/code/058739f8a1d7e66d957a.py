def _backtrack_row(row, k, used_diffs, max_val, internal_diffs):
    """
    Recursively build a row of length k+1 starting with [0].
    row: current list, e.g., [0, 5, ...]
    k: target length is k+1
    used_diffs: set of all diffs from previous rows
    max_val: upper bound for the last element
    internal_diffs: set of diffs already present in 'row'
    """
    if len(row) == k + 1:
        return True
    
    last = row[-1]
    # Try candidates from last+1 to max_val
    # Heuristic: Try smaller values first to keep the row tight? 
    # Or randomize? Randomization helps in finding diverse solutions.
    # Let's try a range.
    
    # To avoid trying too many, we can limit the search space.
    # If we are at position i, the remaining elements must fit in [last+1, max_val].
    # We need (k+1 - len(row)) more elements.
    # The minimum possible next element is last+1.
    # The maximum possible next element is such that we can still fit the rest.
    # But since we just need *a* valid row, we can just iterate.
    
    # Optimization: If the gap is too small to fit the remaining elements, prune.
    # But they just need to be distinct integers, so min gap is 1.
    # So we need max_val - last >= (k + 1 - len(row)).
    if max_val - last < (k + 1 - len(row)):
        return False
        
    # Candidate range
    # We can randomize the order of candidates to escape local traps.
    # However, for finding the *minimum* max_val, we should be careful.
    # Actually, the outer loop controls max_val. Inside, we just need *any* valid row.
    # So randomizing candidates is good for diversity.
    
    candidates = list(range(last + 1, max_val + 1))
    random.shuffle(candidates)
    
    for new_val in candidates:
        # Check constraints
        valid = True
        # Check against used_diffs (from other rows)
        for a in row:
            d = new_val - a
            if d in used_diffs:
                valid = False
                break
            # Check against internal_diffs (from current row so far)
            if d in internal_diffs:
                valid = False
                break
        
        if not valid:
            continue
            
        # If valid, recurse
        new_row = row + [new_val]
        new_internal_diffs = set(internal_diffs)
        for a in row:
            new_internal_diffs.add(new_val - a)
            
        if _backtrack_row(new_row, k, used_diffs, max_val, new_internal_diffs):
            row[:] = new_row # Modify in place
            return True
            
    return False

def _find_solution(n_rows, k, max_val, timeout=10):
    """
    Try to find a valid set of n_rows with all entries <= max_val.
    Returns list of rows or None.
    """
    start_time = time.time()
    used_diffs = set()
    rows = []
    
    # We construct rows one by one.
    # The order of rows doesn't matter for validity, but it affects the search.
    # We can randomize the order of row construction if we allow swapping, 
    # but here we fix the order 0..n_rows-1.
    # To improve success rate, we can try multiple random shuffles of the "candidate selection" inside backtrack.
    
    for r in range(n_rows):
        if time.time() - start_time > timeout:
            return None
            
        row = [0]
        # internal_diffs is initially empty
        internal_diffs = set()
        
        # Backtracking might fail if max_val is too tight.
        # We try a few random restarts for this specific row if it fails?
        # Or just rely on the outer loop reducing max_val.
        
        success = _backtrack_row(row, k, used_diffs, max_val, internal_diffs)
        
        if not success:
            return None
            
        rows.append(row)
        # Update used_diffs with all diffs from this row
        for i in range(len(row)):
            for j in range(i+1, len(row)):
                used_diffs.add(row[j] - row[i])
                
    return rows

def construct(n_rows, k):
    """
    Construct n_rows rows of k+1 increasing integers starting at 0
    such that all pairwise differences are distinct across all rows.
    Minimize the largest entry.
    """
    # Known best for (4,7) is 134. Counting bound is 112.
    # We will search downwards from a safe upper bound.
    # Start with a bound that is likely to work, then tighten.
    
    # Estimate a safe upper bound. 
    # For n_rows=4, k=7, 134 works. Let's start at 140.
    # If we find a solution at 140, we try 139, 138...
    
    upper_bound = 150
    best_rows = None
    best_score = float('inf')
    
