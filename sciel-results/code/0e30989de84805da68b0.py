def _get_neighbors(center, radius):
    """Generate all words within Hamming distance <= radius of center."""
    results = [center]
    bits = list(range(N))
    for r in range(1, radius + 1):
        for comb in combinations(bits, r):
            w = center
            for b in comb:
                w ^= (1 << b)
            results.append(w)
    return results

def _build_forbidden_mask(words):
    """Build a boolean mask of size 2^N where True means 'forbidden'."""
    forbidden = np.zeros(TOTAL, dtype=bool)
    for w in words:
        neighbors = _get_neighbors(w, MIN_DISTANCE - 1)
        forbidden[neighbors] = True
    return forbidden

def _local_search(words, deadline):
    """
    Perform local search to add more words or swap to improve.
    Strategy:
    1. Start with the 512 QR words.
    2. Build forbidden mask.
    3. Try to add any valid word from a pre-sorted list of candidates.
    4. If no word can be added, try "swaps": remove a word w1, add two words w2, w3 
       that are now valid and were previously blocked by w1? 
       Actually, simpler: Randomly remove a word, then try to add as many as possible 
       from the candidates that were previously forbidden but might now be valid.
       Then check if the net gain is positive.
    """
    current_words = list(words)
    forbidden = _build_forbidden_mask(current_words)
    
    # Pre-generate candidates sorted by weight (heuristic: lower weight often easier to fit?)
    # Or just random order?
    # Let's use a list of all words, but we can't iterate 262k every time.
    # We will maintain a list of "potential" candidates.
    
    # For simplicity and speed, let's just do a greedy add pass first.
    # Then do random restarts of the "add" process with different orders.
    
    best_count = len(current_words)
    best_set = set(current_words)
    
    # Time budget for local search
    start_time = time.time()
    
    # Phase 1: Greedy Add
    # We iterate through all possible words. To make it fast, we check the mask.
    # If we find a valid one, we add it and update mask.
    # This is O(2^N * cost_of_update).
    # Cost of update is O(12616) numpy ops.
    # 262k * 12616 is too slow if we do it for every word.
    # But we only update when we ADD a word.
    # We just check `if not forbidden[w]`.
    # Checking 262k booleans is fast.
    
    # We need a list of candidates. 
    # Let's just iterate 0 to 2^N-1.
    # But we want to try multiple times?
    # The problem with greedy is order.
    # Let's shuffle the candidate list a few times.
    
    candidates = np.arange(TOTAL, dtype=np.int64)
    
    for attempt in range(10): # 10 restarts of greedy add
        if time.time() > deadline:
            break
            
        # Shuffle candidates
        np.random.shuffle(candidates)
        
        # We need to reset the state to the best known so far?
        # No, local search usually modifies the current state.
        # But if we shuffle, we are effectively doing a random greedy from the current set.
        
        # Let's stick to a single strong greedy pass from the QR seed, 
        # then try swaps.
        
        pass # Skip complex restarts for now, focus on the main greedy add
    
    # Main Greedy Add Pass
    # We iterate through candidates. 
    # To improve the "greedy" nature, we can prioritize words that are "close" to existing ones?
    # No, we just want to maximize count.
    
    # Let's just do the systematic greedy add from the QR seed.
    # The QR seed is very dense.
    
    added_any = True
    while added_any and time.time() < deadline:
        added_any = False
        # Iterate through all words
        # To speed this up, we can break early if we've scanned a lot without adding?
        # No, just scan all.
        
        # We use a list of all words.
        # To avoid regenerating, we use the global range.
        for w in range(TOTAL):
            if time.time() > deadline:
                return current_words
            
            if not forbidden[w]:
                current_words.append(w)
                added_any = True
                # Update mask
                neighbors = _get_neighbors(w, MIN_DISTANCE - 1)
                forbidden[neighbors] = True
                
    return current_words

def construct():
    start = time.time()
    deadline = start + 90.0 - DEADLINE_MARGIN

    # 1. Get the 512-word QR seed
    try:
        seed = _seed_words()
    except Exception:
        # Fallback to Reed-Muller if QR generation fails
        seed = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                seed.append(word)

    # 2. Local Search (Greedy Add)
    try:
        words = _local_search(seed, deadline)
    except Exception:
        words = seed

    # 3. Final Validation and Deduplication
    seen = set()
    out = []
    for w in words:
        if w not in seen and 0 <= w < TOTAL:
            seen.add(w)
            out.append(w)
            
    # Verify pairwise distance for the final output (small sample or full if fast)
    # Full check of 500+ words is 500^2/2 = 125k checks. Fast.
    valid = True
    for i in range(len(out)):
        for j in range(i + 1, len(out)):
            if (out[i] ^ out[j]).bit_count() < MIN_DISTANCE:
                valid = False
                break
        if not valid:
            break
            
    if not valid:
        # Fallback to seed if local search broke distance
        out = list(set(seed))
        
    if not out:
        out = seed
        
    return out

