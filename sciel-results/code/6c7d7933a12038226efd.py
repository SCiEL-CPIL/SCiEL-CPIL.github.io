    deadline = start_time + 85  # 5 second safety margin
    
    # Candidate numbers: 2 to 40
    candidates = list(range(2, 41))
    
    # Precompute factorizations and vectors
    vecs = {}
    for n in candidates:
        f = _factorize(n)
        vecs[n] = frozenset(f.items())
    
