    # Start with a good initial solution (the known 16-element set)
    initial = [2, 4, 16, 3, 27, 5, 25, 7, 11, 13, 17, 19, 23, 29, 31, 37]
    
    best_set = list(initial)
    best_size = len(best_set)
    
    # Try to add more elements via backtracking
    # Sort candidates by some heuristic (primes first, then by number of prime factors)
    def complexity(n):
        f = _factorize(n)
        return (len(f), n)
    
    sorted_candidates = sorted(candidates, key=complexity)
    
    # Backtracking search
    def backtrack(current_set, start_idx):
        nonlocal best_set, best_size, deadline
        
        if time.time() > deadline:
            return
        
        if len(current_set) > best_size:
            best_set = list(current_set)
            best_size = len(current_set)
        
        # Upper bound: can we possibly beat best_size?
        remaining = len(sorted_candidates) - start_idx
        if len(current_set) + remaining <= best_size:
            return
        
        for i in range(start_idx, len(sorted_candidates)):
            if time.time() > deadline:
                return
            
            n = sorted_candidates[i]
            if n in current_set:
                continue
            
            # Check if we can add n
            existing_vecs = [vecs[x] for x in current_set]
            if _can_add_vec(existing_vecs, vecs[n]):
                current_set.append(n)
                backtrack(current_set, i + 1)
                current_set.pop()
            
            # Pruning: if we've tried enough, stop
            if len(current_set) + (len(sorted_candidates) - i - 1) <= best_size:
                return
    
    # Start backtracking from empty set
    backtrack([], 0)
    
    # Also try starting from the initial solution and adding
    current_set = list(initial)
    existing_set = set(initial)
    for n in sorted_candidates:
        if time.time() > deadline:
            break
        if n in existing_set:
            continue
        existing_vecs = [vecs[x] for x in current_set]
        if _can_add_vec(existing_vecs, vecs[n]):
            current_set.append(n)
            existing_set.add(n)
            if len(current_set) > best_size:
                best_set = list(current_set)
                best_size = len(current_set)
    
    # Try local search: swap elements to increase size
    # Not directly helpful for size, but might find better configurations
    # For now, return the best found
    
    # Ensure all elements are Python ints
    result = [int(x) for x in best_set]
    result = sorted(result)
    
    return result
