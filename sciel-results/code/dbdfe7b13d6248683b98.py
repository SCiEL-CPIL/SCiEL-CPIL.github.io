"""
Combined approach:
1. Robust Randomized Greedy Initialization (from Inspiration)
2. Efficient Simulated Annealing with optimized difference tracking (from Inspiration)
3. Aggressive Deterministic Compaction (from Current, integrated as a post-SA step)
4. Multi-start strategy with strict time management.
"""
import time
import random
import math
import sys

def construct(n_rows, k):
    start_time = time.time()
    # Safety margin: 140s out of 150s limit
    deadline = start_time + 140.0
    
    L = k + 1
    # Total unique differences required
    total_diffs = n_rows * k * (k + 1) // 2
    # Simple counting lower bound for scope
    # If max entry is M, max diff is M. 
    # We need total_diffs distinct values in [1, M]. So M >= total_diffs.
    # Actually, diffs are from 1 to M. So M must be at least total_diffs.
    lb = total_diffs

    best_rows = None
    best_scope = float('inf')

    # --- Helper Functions ---

    def get_scope(rows):
        return max(max(r) for r in rows)

    def build_used(rows):
        used = set()
        for row in rows:
            for i in range(L):
                ri = row[i]
                for j in range(i + 1, L):
                    used.add(row[j] - ri)
        return used

    def diffs_for_pos(row, pos):
        """Calculate the set of differences involving element at 'pos' in 'row'."""
        v = row[pos]
        s = set()
        for i in range(L):
            if i < pos:
                s.add(v - row[i])
            elif i > pos:
                s.add(row[i] - v)
        return s

    def can_place(row, pos, new_val, used_set):
        """
        Check if we can place new_val at row[pos] without creating duplicate differences.
        used_set contains all differences from all rows, EXCLUDING those currently 
        generated by row[pos] (which will be removed before adding new ones).
        """
        if pos > 0 and new_val <= row[pos - 1]:
            return False
        if pos < L - 1 and new_val >= row[pos + 1]:
            return False
        
        v = new_val
        # Check new differences against used_set
        for i in range(L):
            if i == pos:
                continue
            if i < pos:
                d = v - row[i]
                if d in used_set:
                    return False
            else:
                d = row[i] - v
                if d in used_set:
                    return False
        return True

    def apply_move(row, pos, new_val, used_set):
        """
        Update row[pos] to new_val and update used_set.
        Assumes can_place has been verified.
        """
        old_val = row[pos]
        # Remove old diffs
        for i in range(L):
            if i == pos:
                continue
            if i < pos:
                used_set.discard(old_val - row[i])
            else:
                used_set.discard(row[i] - old_val)
        
        # Add new diffs
        v = new_val
        row[pos] = v
        for i in range(L):
            if i == pos:
                continue
            if i < pos:
                used_set.add(v - row[i])
            else:
                used_set.add(row[i] - v)

    def revert_move(row, pos, old_val, used_set):
        """
        Revert row[pos] to old_val and update used_set.
        """
        current_val = row[pos]
        # Remove current diffs
        for i in range(L):
            if i == pos:
                continue
            if i < pos:
                used_set.discard(current_val - row[i])
            else:
                used_set.discard(row[i] - current_val)
        
        # Add old diffs
        v = old_val
        row[pos] = v
        for i in range(L):
            if i == pos:
                continue
            if i < pos:
                used_set.add(v - row[i])
            else:
                used_set.add(row[i] - v)

    # --- Construction Phases ---

    def greedy_build(seed):
        """
        Randomized greedy construction.
        """
        rng = random.Random(seed)
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            while len(row) < L:
                last = row[-1]
                # Adaptive window: start small, expand if stuck
                # We want to keep numbers small, so we search from last+1 upwards
                found = False
                # Try a random window size
                window_size = rng.randint(10, 50)
                start_val = last + 1
                end_val = start_val + window_size
                
                # Shuffle candidates to break ties and explore
                candidates = list(range(start_val, end_val))
                rng.shuffle(candidates)
                
                for x in candidates:
                    # Check if x creates conflicts
                    conflict = False
                    for a in row:
                        d = x - a
                        if d in used:
                            conflict = True
                            break
                    if not conflict:
                        row.append(x)
                        used.update([x - a for a in row[:-1]])
                        found = True
                        break
                
                if not found:
                    # Expand search if window failed
                    for x in range(start_val, lb + 1000):
                        conflict = False
                        for a in row:
                            d = x - a
                            if d in used:
                                conflict = True
                                break
                        if not conflict:
                            row.append(x)
                            used.update([x - a for a in row[:-1]])
                            found = True
                            break
                    if not found:
                        return None
            rows.append(row)
        return rows

    def simulated_annealing(rows_init, time_limit):
        """
        Simulated Annealing to minimize scope.
        """
        rows = [list(r) for r in rows_init]
        used = build_used(rows)
        current_scope = get_scope(rows)
        best_local_scope = current_scope
        best_local_rows = [list(r) for r in rows]
        
        # SA Parameters
        T = max(5.0, current_scope * 0.1)
        T_min = 0.5
        cooling = 0.995
        rng = random.Random(int(time.time() * 10000))
        
        last_improve_time = time.time()
        
        while time.time() < time_limit:
            # Pick a random row and position to move
            r_idx = rng.randint(0, n_rows - 1)
            # Focus more on the last element (pos L-1) as it contributes most to scope
            # But allow movement of other elements to unblock
            if rng.random() < 0.4:
                pos = L - 1
            else:
                pos = rng.randint(1, L - 2)
            
            row = rows[r_idx]
            old_val = row[pos]
            
            # Determine valid range for new value
            lower = row[pos - 1] + 1
            upper = row[pos + 1] - 1 if pos < L - 1 else old_val + 20
            
            if lower >= upper:
                continue
            
            # Bias towards lower values to reduce scope
            # If moving the last element, strongly bias down
            if pos == L - 1:
                # Sample from [lower, min(upper, old_val + 5)] with bias to lower
                max_sample = min(upper, old_val + 10)
                if lower < max_sample:
                    # Geometric-like distribution favoring lower values
                    new_val = lower + int((max_sample - lower) * rng.random() * rng.random())
                else:
                    new_val = lower
            else:
                new_val = rng.randint(lower, upper)
            
            if new_val == old_val:
                continue
            
            # Check validity
            # Temporarily remove old diffs from 'used' to check new ones
            # Optimization: Instead of modifying 'used' every time, we can pass
            # a 'blocked' set or just check against 'used' minus current diffs.
            # Given the small size, let's use the efficient apply/revert pattern
            # but we need to check first.
            
            # Quick check: does new_val create a diff already in 'used'?
            # We must ignore diffs that are currently in 'used' but generated by row[pos].
            # Let's compute the set of diffs generated by row[pos] currently.
            current_diffs = diffs_for_pos(row, pos)
            
            valid = True
            v = new_val
            for i in range(L):
                if i == pos:
                    continue
                if i < pos:
                    d = v - row[i]
                    # d is valid if it's not in 'used' OR if it IS in 'used' 
                    # but it was one of the 'current_diffs' (which we are replacing)
                    # Actually, if d is in current_diffs, it's being removed.
                    # If d is in used AND d not in current_diffs, it's a conflict.
                    if d in used and d not in current_diffs:
                        valid = False
                        break
                else:
                    d = row[i] - v
                    if d in used and d not in current_diffs:
                        valid = False
                        break
            
            if not valid:
                continue
            
            # Apply move
            apply_move(row, pos, new_val, used)
            new_scope = get_scope(rows)
            
            # Acceptance
            delta = new_scope - current_scope
            if delta < 0 or rng.random() < math.exp(-delta / max(T, 0.01)):
                current_scope = new_scope
                if current_scope < best_local_scope:
                    best_local_scope = current_scope
                    best_local_rows = [list(r) for r in rows]
                    last_improve_time = time.time()
            else:
                # Revert
                revert_move(row, pos, old_val, used)
            
            T *= cooling
            if T < T_min:
                # Reheat slightly or break
                T = T_min
                if time.time() - last_improve_time > 5.0:
                    # Stagnant, restart SA with current best
                    break

        return best_local_rows, best_local_scope

    def compact_rows(rows):
        """
        Deterministic local search to compact rows.
        Tries to shift each element to the left as much as possible.
        """
        work = [list(r) for r in rows]
        used = build_used(work)
        
        # Iterate until no improvement
        improved = True
        # Limit iterations to prevent infinite loops in worst cases
        max_iters = 100
        iter_count = 0
        
        while improved and iter_count < max_iters:
            improved = False
            iter_count += 1
            
            # Randomize order to break symmetries
            positions = [(r, p) for r in range(n_rows) for p in range(L - 1, 0, -1)]
            random.shuffle(positions)
            
            for r_idx, pos in positions:
                row = work[r_idx]
                old_val = row[pos]
                lower = row[pos - 1] + 1
                # We only try to move LEFT (reduce value)
                if lower >= old_val:
                    continue
                
                # Try values from lower to old_val - 1
                for new_val in range(lower, old_val):
                    # Check validity
                    current_diffs = diffs_for_pos(row, pos)
                    valid = True
                    v = new_val
                    for i in range(L):
                        if i == pos:
                            continue
                        if i < pos:
                            d = v - row[i]
                            if d in used and d not in current_diffs:
                                valid = False
                                break
                        else:
                            d = row[i] - v
                            if d in used and d not in current_diffs:
                                valid = False
                                break
                    
                    if valid:
                        apply_move(row, pos, new_val, used)
                        improved = True
                        break

        return work

    # --- Main Loop ---

    # Phase 1: Generate initial solutions and run SA
    # We will run multiple iterations of: Greedy -> SA -> Compact
    # Budget: 130s for search, 10s for final compaction/verification
    
    attempts = 0
    last_best_update = start_time
    
    while time.time() < deadline - 10.0:
        attempts += 1
        seed = attempts * 12345 + 67890
        rows = greedy_build(seed)
        
        if rows is None:
            continue
        
        current_scope = get_scope(rows)
        
        if current_scope < best_scope:
            best_scope = current_scope
            best_rows = [list(r) for r in rows]
            last_best_update = time.time()
        
        # Run SA on this solution
        # Time limit for SA: proportional to remaining time, but capped
        sa_time_limit = min(5.0, max(0.5, (deadline - 15.0 - time.time()) / 10.0))
        
        if time.time() < deadline - 15.0:
            sa_rows, sa_scope = simulated_annealing(rows, time.time() + sa_time_limit)
            
            if sa_scope < best_scope:
                best_scope = sa_scope
                best_rows = [list(r) for r in sa_rows]
                last_best_update = time.time()
            
            # Compact the SA result
            if time.time() < deadline - 10.0:
                comp_rows = compact_rows(sa_rows)
                comp_scope = get_scope(comp_rows)
                if comp_scope < best_scope:
                    best_scope = comp_scope
                    best_rows = [list(r) for r in comp_rows]
                    last_best_update = time.time()
        
        # If we've been stuck for a while, we might want to increase randomness
        # But greedy_build already uses different seeds.
        
        # Early exit if we hit the lower bound (unlikely but good to check)
        if best_scope <= lb:
            break

    # Phase 2: Final Compaction on the best solution found
    if best_rows is not None and time.time() < deadline - 2.0:
        final_rows = compact_rows(best_rows)
        final_scope = get_scope(final_rows)
        if final_scope < best_scope:
            best_rows = final_rows
            best_scope = final_scope

    if best_rows is None:
        # Fallback: Return a valid greedy solution if no SA/Compact improved it
        # This shouldn't happen if greedy_build works, but just in case
        used = set()
        rows = []
        for _ in range(n_rows):
            row = [0]
            x = 0
            while len(row) < L:
                x += 1
                conflict = False
                for a in row:
                    d = x - a
                    if d in used:
                        conflict = True
                        break
                if not conflict:
                    row.append(x)
                    used.update([x - a for a in row[:-1]])
            rows.append(row)
        return rows

    return best_rows

