"""
Strategy: Repulsive Potential Maximization (Greedy Construction + Riemannian Polish).
Instead of moving all 100 points simultaneously from a random or Fibonacci start,
we construct the point set sequentially. We start with an initial point and then
iteratively add new points at the location on the sphere that maximizes the
repulsive potential generated by the existing points. 

The potential used is U(x) = sum_{i in S} log(1 / ||x - x_i||) = - sum log(||x - x_i||).
Maximizing this is equivalent to minimizing the sum of log distances to existing points,
which pushes new points into "empty" regions. This greedy approach often finds
configurations with good global spacing properties quickly, avoiding the "swirling"
or slow convergence issues of direct energy minimization from dense starts.

After placing all N points, we perform a final Riemannian L-BFGS optimization to
minimize the total pairwise logarithmic energy, which corrects for any suboptimal
local choices made during the greedy phase.
"""
import time
import math
import numpy as np
from scipy.optimize import minimize

N = 100

# EVOLVE-BLOCK-START

def _energy(pts):
    """Compute logarithmic energy."""
    n = len(pts)
    if n < 2:
        return 0.0
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    np.fill_diagonal(dist_sq, 1.0)
    dist = np.sqrt(dist_sq)
    mask = np.triu(np.ones((n, n), dtype=bool), k=1)
    valid_dists = dist[mask]
    # Avoid log(0) if points are too close, though we check validity later
    valid_dists = np.maximum(valid_dists, 1e-15)
    energy = -np.sum(np.log(valid_dists))
    return energy

def _energy_grad(pts):
    """Compute gradient of logarithmic energy."""
    n = len(pts)
    diff = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    np.fill_diagonal(dist_sq, 1.0)
    # grad E = sum_{j != i} (x_i - x_j) / ||x_i - x_j||^2
    # Note: E = - sum log(d_ij) = sum log(1/d_ij)
    # dE/dx_i = sum_{j != i} -1/d_ij * (x_i - x_j)/d_ij = - sum (x_i - x_j)/d_ij^2
    # Wait. Let E = sum_{i<j} log(1/||x_i-x_j||) = - sum_{i<j} log(||x_i-x_j||).
    # dE/dx_i = - sum_{j != i} (1/||x_i-x_j||) * (x_i-x_j)/||x_i-x_j|| = - sum (x_i-x_j)/||x_i-x_j||^2
    # This is the attractive force direction? 
    # Let's check: if x_i moves away from x_j, distance increases, log(1/d) decreases (becomes more negative).
    # We want to MINIMIZE energy. So we want to move in direction of -grad E.
    # -grad E = sum (x_i-x_j)/||x_i-x_j||^2. This is the repulsive force.
    # So _energy_grad returns the gradient of E.
    
    grad_terms = diff / dist_sq[..., np.newaxis]
    # diff is x_i - x_j. 
    # Term is (x_i - x_j) / d^2.
    # Summing over j for fixed i gives sum (x_i - x_j)/d^2.
    # This is -grad E. 
    # So if we return this, we are returning -grad E.
    # Standard minimize expects grad E.
    # Let's re-verify.
    # f(x) = log(1/|x-y|) = -log|x-y|.
    # df/dx = - (1/|x-y|) * (x-y)/|x-y| = -(x-y)/|x-y|^2.
    # So grad E = sum_{j} -(x_i-x_j)/|x_i-x_j|^2.
    # My code: diff = x_i - x_j. grad_terms = diff / dist_sq.
    # Sum is sum (x_i-x_j)/dist_sq.
    # This is - grad E.
    # So I should return -np.sum(grad_terms, axis=1) to get the actual gradient.
    
    return -np.sum(grad_terms, axis=1)

def _project_tangent(pts, vec):
    """Project vector onto tangent space."""
    dot = np.sum(pts * vec, axis=1, keepdims=True)
    return vec - dot * pts

def _fibonacci_sphere(n):
    i = np.arange(n) + 0.5
    z = 1.0 - 2.0 * i / n
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(1.0 - z * z)
    return np.column_stack([r * np.cos(phi), r * np.sin(phi), z])

def _random_sphere(n):
    vecs = np.random.randn(n, 3)
    norms = np.linalg.norm(vecs, axis=1, keepdims=True)
    norms[norms == 0] = 1.0
    return vecs / norms

def _repulsive_potential(x, existing_pts):
    """
    Calculate the repulsive potential at x given existing points.
    U(x) = sum_{i in S} log(1 / ||x - x_i||) = - sum log(||x - x_i||)
    We want to maximize this.
    """
    diff = x - existing_pts
    dist_sq = np.sum(diff * diff, axis=1)
    # Avoid log(0)
    dist_sq = np.maximum(dist_sq, 1e-15)
    dist = np.sqrt(dist_sq)
    return -np.sum(np.log(dist))

def _find_max_repulsive(existing_pts, grid_size=20000):
    """
    Find the point on the sphere that maximizes the repulsive potential
    generated by existing_pts.
    Uses a dense grid search on the sphere.
    """
    # Generate a dense grid on the sphere using Fibonacci spiral
    # 20,000 points is dense enough for N=100 to find a good local max
    # and is fast to evaluate vectorized.
    candidates = _fibonacci_sphere(grid_size)
    
    # Compute potential for all candidates
    # existing_pts shape (M, 3), candidates shape (K, 3)
    # We need ||candidate_k - existing_m|| for all k, m
    # diff = candidates[:, np.newaxis, :] - existing_pts[np.newaxis, :, :]
    # This is K x M x 3. For K=20000, M=100, this is 20000*100*3 = 6M floats. 
    # Memory: 6M * 8 bytes = 48 MB. Acceptable.
    
    diff = candidates[:, np.newaxis, :] - existing_pts[np.newaxis, :, :]
    dist_sq = np.sum(diff * diff, axis=-1)
    dist_sq = np.maximum(dist_sq, 1e-15)
    dist = np.sqrt(dist_sq)
    
    # Potential for each candidate k is -sum_m log(dist_km)
    potentials = -np.sum(np.log(dist), axis=1)
    
    max_idx = np.argmax(potentials)
    return candidates[max_idx]

def construct():
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin

    # 1. Greedy Construction
    # Start with a random point or North Pole
    current_pts = np.array([[0.0, 0.0, 1.0]])
    
    for i in range(1, N):
        if time.time() > deadline - 20.0:
            # If running out of time, fill rest with Fibonacci points
            break
        
        # Find point that maximizes repulsion from existing
        new_pt = _find_max_repulsive(current_pts)
        current_pts = np.vstack([current_pts, new_pt])
        
        # Optional: Small local refinement of the new point to ensure it's a true local max
        # This helps avoid grid artifacts
        # We can do a few steps of gradient ascent on the potential for the new point
        # But for speed, the grid search is usually sufficient for N=100.
        
    # If we broke out early, fill the rest
    if len(current_pts) < N:
        remaining = N - len(current_pts)
        fib_rest = _fibonacci_sphere(remaining)
        # Project fib_rest away from existing? No, just append for now, polish will fix.
        current_pts = np.vstack([current_pts, fib_rest])

    # Ensure unique points (grid search might return same point if potential is flat? Unlikely)
    # Check for duplicates
    # For N=100, duplicates are unlikely with 20k grid.
    
    current_energy = _energy(current_pts)
    best_pts = current_pts.copy()
    best_energy = current_energy

    # 2. Riemannian L-BFGS Polish
    # This step is crucial to minimize the total energy, as the greedy method
    # minimizes incremental energy, not total.
    
    x0 = best_pts.flatten()
    
    def fun_and_grad(x):
        p = x.reshape(-1, 3)
        norms = np.linalg.norm(p, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        p = p / norms
        e = _energy(p)
        g = _energy_grad(p)
        g_tan = _project_tangent(p, g)
        return e, g_tan.flatten()
    
    try:
        res = minimize(
            fun_and_grad, 
            x0, 
            method='L-BFGS-B', 
            jac=True, 
            options={'maxiter': 100, 'ftol': 1e-12, 'gtol': 1e-8, 'disp': False}
        )
        
        final_pts = res.x.reshape(-1, 3)
        norms = np.linalg.norm(final_pts, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        final_pts = final_pts / norms
        
        final_energy = _energy(final_pts)
        
        # Validity check
        if np.all(np.isfinite(final_pts)):
            diff = final_pts[:, np.newaxis, :] - final_pts[np.newaxis, :, :]
            dists = np.linalg.norm(diff, axis=-1)
            np.fill_diagonal(dists, 1.0)
            if np.min(dists) > 1e-9 and final_energy < best_energy:
                best_energy = final_energy
                best_pts = final_pts
    except Exception:
        pass # Keep greedy result if optimization fails

    # Fallback
    if not np.all(np.isfinite(best_pts)):
        best_pts = _fibonacci_sphere(N)
        
    return best_pts

