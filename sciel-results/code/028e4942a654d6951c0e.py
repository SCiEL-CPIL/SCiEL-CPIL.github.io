import numpy as np

def get_strassen_2x2():
    # Returns U, V, W for 2x2x2
    # Rank 7
    U = np.zeros((4, 7))
    V = np.zeros((4, 7))
    W = np.zeros((4, 7))
    
    # M1 = (A11+A22)(B11+B22)
    # A11=0, A22=1 (indices in 2x2: 00, 01, 10, 11)
    # U indices: 00, 01, 10, 11
    U[0, 0] = 1; U[3, 0] = 1
    V[0, 0] = 1; V[3, 0] = 1
    W[0, 0] = 1; W[3, 0] = 1 # C11, C22? 
    # Wait, W index is k*n + i.
    # C11: k=0, i=0 -> 0
    # C22: k=1, i=1 -> 1*2+1=3
    # C12: k=1, i=0 -> 1
    # C21: k=0, i=1 -> 2
    
    # Let's map carefully.
    # M1 contributes to C11 (+1), C22 (+1)
    # C11: W[0, 0] += 1
    # C22: W[3, 0] += 1
    
    # M2 = (A21+A22)B11
    # A21=1 (idx 2), A22=1 (idx 3)
    # B11=0 (idx 0)
    U[2, 1] = 1; U[3, 1] = 1
    V[0, 1] = 1
    # C21: W[2, 1] += 1
    
    # M3 = A11(B12-B22)
    # A11=0
    # B12=1 (idx 1), B22=3 (idx 3)
    U[0, 2] = 1
    V[1, 2] = 1; V[3, 2] = -1
    # C12: W[1, 2] += 1
    
    # M4 = A22(B21-B11)
    # A22=3
    # B21=2 (idx 2), B11=0
    U[3, 3] = 1
    V[2, 3] = 1; V[0, 3] = -1
    # C11: W[0, 3] += 1
    # C21: W[2, 3] += 1
    
    # M5 = (A11+A12)B22
    # A11=0, A12=1
    # B22=3
    U[0, 4] = 1; U[1, 4] = 1
    V[3, 4] = 1
    # C11: W[0, 4] -= 1
    # C22: W[3, 4] += 1
    
    # M6 = (A21-A11)(B11+B12)
    # A21=2, A11=0
    # B11=0, B12=1
    U[2, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[1, 5] = 1
    # C22: W[3, 5] += 1
    
    # M7 = (A12-A22)(B21+B22)
    # A12=1, A22=3
    # B21=2, B22=3
    U[1, 6] = 1; U[3, 6] = -1
    V[2, 6] = 1; V[3, 6] = 1
    # C11: W[0, 6] += 1
    # C22: W[3, 6] += 1
    
    # Fill W
    W[0, 0] = 1
    W[3, 0] = 1
    W[2, 1] = 1
    W[1, 2] = 1
    W[0, 3] = 1
    W[2, 3] = 1
    W[0, 4] = -1
    W[3, 4] = 1
    W[3, 5] = 1
    W[0, 6] = 1
    W[3, 6] = 1
    
    return U, V, W
