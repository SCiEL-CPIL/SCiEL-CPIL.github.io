def _is_valid_triples(S):
    """Check if all unordered triple sums (with replacement) are unique."""
    n = len(S)
    seen = set()
    # (i, j, k) with i <= j <= k
    for i in range(n):
        for j in range(i, n):
            for k in range(j, n):
                s = S[i] + S[j] + S[k]
                if s in seen:
                    return False
                seen.add(s)
    return True

def _triple_sums_involving_x(x, S):
    """
    Efficiently compute the set of triple sums that would be formed if x were added to S.
    Assumes x is not in S.
    Returns a set of sums.
    """
    sums = set()
    n = len(S)
    
    # (x, x, x)
    sums.add(3 * x)
    
    # (x, x, y) for y in S
    for y in S:
        sums.add(2 * x + y)
        
    # (x, y, y) for y in S
    for y in S:
        sums.add(x + 2 * y)
        
    # (x, y, z) for y < z in S
    for i in range(n):
        for j in range(i + 1, n):
            sums.add(x + S[i] + S[j])
            
    return sums

def _greedy_build(randomized=False, seed=0, deadline=None):
    """
    Build a valid set using greedy insertion.
    If randomized, shuffle the candidate order.
    """
    rng = random.Random(seed)
    
    # Candidates are 1..4096
    candidates = list(range(1, 4097))
    if randomized:
        rng.shuffle(candidates)
    
    S = []
    # Pre-compute existing sums is expensive if we do it from scratch each time.
    # Instead, we check conflicts incrementally.
    # But for simplicity and correctness first, let's use the incremental check.
    
    # To speed up, we can maintain the set of all existing triple sums.
    existing_sums = set()
    
    for x in candidates:
        if deadline and time.time() > deadline:
            break
            
        # Check if x can be added
        # We need to ensure no new sum conflicts with existing_sums
        # And no new sum conflicts with other new sums (within the set of sums involving x)
        
        new_sums = _triple_sums_involving_x(x, S)
        
        # Check intersection with existing_sums
        if new_sums & existing_sums:
            continue
            
        # Check for duplicates within new_sums
        if len(new_sums) != len(list(new_sums)): # This is always true for a set, so this check is redundant unless we used a list.
            # Wait, _triple_sums_involving_x returns a set, so duplicates are already merged.
            # We need to check if any sum in new_sums appears more than once in the *generation* process?
            # No, if the set has size k, and we generated k distinct sums, it's fine.
            # However, if two different triples involving x produce the same sum, that's a conflict.
            # Since we used a set, we lost the count.
            # We need to check if any sum in new_sums is generated by multiple triples.
            # Let's re-evaluate.
            
            # Actually, if we just add x, the new triples are:
            # (x,x,x), (x,x,y), (x,y,y), (x,y,z)
            # If any of these sums equal each other, it's a conflict.
            # If any of these sums equal an existing sum, it's a conflict.
            
            # Let's count occurrences in the generation loop to be safe.
            pass
        
        # Re-do the check properly to catch internal conflicts
        counts = {}
        # (x,x,x)
        s = 3*x
        counts[s] = counts.get(s, 0) + 1
        # (x,x,y)
        for y in S:
            s = 2*x + y
            counts[s] = counts.get(s, 0) + 1
        # (x,y,y)
        for y in S:
            s = x + 2*y
            counts[s] = counts.get(s, 0) + 1
        # (x,y,z)
        n = len(S)
        for i in range(n):
            for j in range(i+1, n):
                s = x + S[i] + S[j]
                counts[s] = counts.get(s, 0) + 1
        
        valid = True
        for s, c in counts.items():
            if c > 1:
                valid = False
                break
            if s in existing_sums:
                valid = False
                break
        
        if valid:
            S.append(x)
            # Update existing_sums
            existing_sums.update(counts.keys())
            
            # Optional: If we reach a good size, we can stop or continue?
            # Greedy usually continues.
            
    return S

