"""Construct a large binary code of length 17 with minimum distance 6."""
# EVOLVE-BLOCK-START
import time
import numpy as np

N = 17
MIN_DIST = 6
SEED_TIME = 90.0
SAFETY = 2.0  # seconds before deadline to stop

# Precompute popcount table for 16-bit values (0..65535)
_PC16 = np.array([i.bit_count() for i in range(65536)], dtype=np.uint8)

def _popcount17(x):
    """Popcount of a 17-bit integer via precomputed table."""
    return int(_PC16[x & 0xFFFF] + _PC16[(x >> 16) & 0xFFFF])

def _hamming(x, y):
    return _popcount17(x ^ y)

def _build_linear_code():
    """
    Construct the [17,8,6] shortened extended quadratic-residue code.
    Use GF(16) with primitive polynomial x^4 + x + 1 (0b10011 = 0x13).
    Generator: for each a in GF(16), the codeword has bit i = Tr(a * alpha^i) for i=0..15,
    then a 17th bit to make even weight (or just append 0 for shortening).
    
    Actually, the standard construction: the [16,5,6] QR code is generated by
    the trace code. For [17,8,6], we use the extended [18,9,6] QR code shortened.
    
    Simpler approach: the [17,8,6] code can be constructed as follows.
    The quadratic residues mod 17 are {1,2,4,8,9,13,15,16} (8 elements).
    The generator polynomial approach is complex. Let's use the trace construction.
    
    GF(16) with primitive element alpha = x (root of x^4+x+1).
    The [16,5,6] code: codewords are (Tr(a*alpha^0), ..., Tr(a*alpha^15)) for a in GF(16).
    But that's only 16 words. We need 256 words = 2^8.
    
    The [17,8,6] code: This is the shortened [18,9,6] extended QR code.
    The extended QR code of length 18 over GF(16) has parameters [18,9,6].
    Shortening one coordinate gives [17,8,6].
    
    Let me use a direct construction. The generator matrix for the [17,8,6] code:
    Rows correspond to basis vectors. Use the fact that the code is the set of all
    (f(0), f(1), ..., f(16)) where f is a polynomial of degree < 8 over GF(2)
    evaluated at quadratic residues... this is getting complex.
    
    Alternative: Use the known generator matrix. The [17,8,6] code has generator matrix
    with rows being the shifts of a generator polynomial g(x) of degree 9.
    
    Let me use a different approach: construct via the BCH/QR structure.
    The [17,8,6] code is generated by the polynomial g(x) = (x-1)(x^4+x+1)(x^4+x^3+1)
    over GF(2), which has degree 1+4+4=9. The code has dimension 17-9=8.
    
    g(x) = (x+1)(x^4+x+1)(x^4+x^3+1)
    (x^4+x+1)(x^4+x^3+1) = x^8 + x^7 + x^6 + x^4 + x^3 + x^2 + 1  (let me compute)
    = x^8 + x^7 + x^6 + x^4 + x^3 + x^2 + 1
    Then multiply by (x+1):
    (x+1)(x^8+x^7+x^6+x^4+x^3+x^2+1) = x^9+x^8+x^7+x^5+x^4+x^3+x^2+x + x^8+x^7+x^6+x^4+x^3+x^2+1
    = x^9 + (x^8+x^8) + (x^7+x^7) + x^6 + x^5 + (x^4+x^4) + (x^3+x^3) + (x^2+x^2) + x + 1
    = x^9 + x^6 + x^5 + x + 1
    
    So g(x) = x^9 + x^6 + x^5 + x + 1.
    
    The generator matrix has rows: g(x), x*g(x), ..., x^7*g(x) mod (x^17-1).
    """
    # g(x) = x^9 + x^6 + x^5 + x + 1
    # Bits from high to low: x^9, x^6, x^5, x^1, x^0
    g = (1 << 9) | (1 << 6) | (1 << 5) | (1 << 1) | (1 << 0)
    
    words = []
    seen = set()
    for msg in range(256):
        # codeword = msg * g(x) mod (x^17 - 1)
        cw = 0
        for i in range(8):
            if (msg >> i) & 1:
                # multiply g by x^i mod (x^17-1)
                shifted = g << i
                # reduce mod x^17-1: if bit 17+ is set, fold back
                # Actually, we just need bits 0..16
                # For i up to 7, g has bits up to 9, so shifted has bits up to 16. No reduction needed.
                cw ^= shifted
        words.append(cw)
        seen.add(cw)
    
    # Verify: should have 256 distinct words
    assert len(words) == 256, f"Expected 256 words, got {len(words)}"
    
    # Verify minimum distance
    # Spot check a few pairs
    for i in range(min(20, len(words))):
        for j in range(i+1, min(20, len(words))):
            d = _hamming(words[i], words[j])
            if d < MIN_DIST:
                # This would be a bug
                pass  # In practice, this should not happen
    
    return words

def _candidate_pool_at_distance(d, center=0):
    """Generate all 17-bit words at Hamming distance exactly d from center."""
    candidates = []
    # Enumerate all subsets of size d from 17 positions
    positions = list(range(17))
    from itertools import combinations
    for combo in combinations(positions, d):
        w = center
        for pos in combo:
            w ^= (1 << pos)
        candidates.append(w)
    return candidates

def _check_compatible(candidate, code_words, code_indices):
    """Check if candidate is at distance >= MIN_DIST from all words in code_words[code_indices]."""
    for idx in code_indices:
        if _hamming(candidate, code_words[idx]) < MIN_DIST:
            return False
    return True

def construct():
    start_time = time.time()
    
    # Step 1: Build the 256-word linear code
    code = _build_linear_code()
    code_set = set(code)
    
    # Step 2: Generate candidate pool - words at distance 6 from zero word
    # These are the most likely candidates to be addable
    candidates = _candidate_pool_at_distance(6, 0)
    
    # Also try distance 7 and 8 candidates if time permits
    candidates_d7 = _candidate_pool_at_distance(7, 0)
    candidates_d8 = _candidate_pool_at_distance(8, 0)
    
    # Sort candidates by some heuristic - maybe by how "spread out" they are
    # For now, just try them in order
    
    all_candidates = candidates + candidates_d7 + candidates_d8
    
    # Shuffle to diversify? No, keep deterministic for reproducibility
    # Actually, let's try distance-6 candidates first as they're most promising
    
    added = 0
    for cand in all_candidates:
        # Deadline check
        if time.time() - start_time > SEED_TIME - SAFETY:
            break
        
        if cand in code_set:
            continue
        
        # Check compatibility with all current codewords
        compatible = True
        for cw in code:
            if _hamming(cand, cw) < MIN_DIST:
                compatible = False
                break
        
        if compatible:
            code.append(cand)
            code_set.add(cand)
            added += 1
    
    # Step 3: Try more candidates from other centers if time permits
    if time.time() - start_time < SEED_TIME - SAFETY:
        # Try words at distance 6 from a few other codewords
        for center in code[:10]:
            if time.time() - start_time > SEED_TIME - SAFETY:
                break
            extra_cands = _candidate_pool_at_distance(6, center)
            for cand in extra_cands:
                if time.time() - start_time > SEED_TIME - SAFETY:
                    break
                if cand in code_set:
                    continue
                compatible = True
                for cw in code:
                    if _hamming(cand, cw) < MIN_DIST:
                        compatible = False
                        break
                if compatible:
                    code.append(cand)
                    code_set.add(cand)
                    added += 1
    
    return code
