import numpy as np

DIMENSIONS = [2, 3, 3]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 17
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Indices for A (2x3):
    # A[0,0]=0, A[0,1]=1, A[0,2]=2
    # A[1,0]=3, A[1,1]=4, A[1,2]=5
    
    # Indices for B (3x3):
    # B[0,0]=0, B[0,1]=1, B[0,2]=2
    # B[1,0]=3, B[1,1]=4, B[1,2]=5
    # B[2,0]=6, B[2,1]=7, B[2,2]=8
    
    # Indices for C (2x3) via W[k*n+i]:
    # C[0,0] -> k=0, i=0 -> 0
    # C[0,1] -> k=1, i=0 -> 2
    # C[0,2] -> k=2, i=0 -> 4
    # C[1,0] -> k=0, i=1 -> 1
    # C[1,1] -> k=1, i=1 -> 3
    # C[1,2] -> k=2, i=1 -> 5
    
    # 1. A_1 (col 0) * B_0 (row 0)
    # m0 = A00 * B00 -> C00
    U[0][0] = 1; V[0][0] = 1; W[0][0] = 1
    # m1 = A10 * B00 -> C10
    U[3][1] = 1; V[0][1] = 1; W[1][1] = 1
    # m2 = A00 * B01 -> C01
    U[0][2] = 1; V[1][2] = 1; W[2][2] = 1
    # m3 = A10 * B01 -> C11
    U[3][3] = 1; V[1][3] = 1; W[3][3] = 1
    # m4 = A00 * B02 -> C02
    U[0][4] = 1; V[2][4] = 1; W[4][4] = 1
    # m5 = A10 * B02 -> C12
    U[3][5] = 1; V[2][5] = 1; W[5][5] = 1
    
    # 2. A_2 (cols 1,2) * B_0 (col 0, rows 1,2)
    # m6 = A01 * B10 -> C00
    U[1][6] = 1; V[3][6] = 1; W[0][6] = 1
    # m7 = A02 * B20 -> C00
    U[2][7] = 1; V[6][7] = 1; W[0][7] = 1
    # m8 = A11 * B10 -> C10
    U[4][8] = 1; V[3][8] = 1; W[1][8] = 1
    # m9 = A12 * B20 -> C10
    U[5][9] = 1; V[6][9] = 1; W[1][9] = 1
    
    # 3. A_2 (2x2) * B_22 (2x2) using Strassen
    # A_2 entries: a01(A[1]), a02(A[2]), a11(A[4]), a12(A[5])
    # B_22 entries: b11(B[4]), b12(B[5]), b21(B[7]), b22(B[8])
    
    # M1 = (a01+a11)(b11+b22)
    U[1][10] = 1; U[4][10] = 1
    V[4][10] = 1; V[8][10] = 1
    W[2][10] = 1  # C01
    W[3][10] = -1 # C11
    W[5][10] = 1  # C12
    
    # M2 = (a11+a12)b11
    U[4][11] = 1; U[5][11] = 1
    V[4][11] = 1
    W[3][11] = 1  # C11
    W[5][11] = 1  # C12
    
    # M3 = a01(b12-b22)
    U[1][12] = 1
    V[5][12] = 1; V[8][12] = -1
    W[4][12] = 1  # C02
    W[5][12] = -1 # C12
    
    # M4 = a12(b21-b11)
    U[5][13] = 1
    V[7][13] = 1; V[4][13] = -1
    W[2][13] = -1 # C01
    W[3][13] = 1  # C11
    
    # M5 = (a01+a02)b22
    U[1][14] = 1; U[2][14] = 1
    V[8][14] = 1
    W[2][14] = 1  # C01
    
    # M6 = (a11-a01)(b11+b12)
    U[4][15] = 1; U[1][15] = -1
    V[4][15] = 1; V[5][15] = 1
    W[3][15] = 1  # C11
    
    # M7 = (a02-a11)(b21+b22)
    U[2][16] = 1; U[4][16] = -1
    V[7][16] = 1; V[8][16] = 1
    W[2][16] = -1 # C01
    W[4][16] = 1  # C02
    
    return {"U": U, "V": V, "W": W}
