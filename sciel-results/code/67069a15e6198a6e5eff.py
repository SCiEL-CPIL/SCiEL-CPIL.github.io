"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 50

# EVOLVE-BLOCK-START
import numpy as np
import time
from scipy.spatial import ConvexHull
import random

def construct():
    start_time = time.time()
    deadline = start_time + 115.0  # Safety margin for 120s limit
    
    # 1. Initialize with Fibonacci spiral (good starting point)
    i = np.arange(N) + 0.5
    z = 1.0 - 2.0 * i / N
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(1.0 - z * z)
    x0 = np.column_stack([r * np.cos(phi), r * np.sin(phi), z])
    
    def compute_covering_radius(pts):
        """
        Computes the covering radius (in radians) and identifies the worst facet.
        Returns: (radius, worst_simplex, worst_point_on_sphere)
        """
        try:
            hull = ConvexHull(pts)
        except Exception:
            return np.pi, None, None
        
        max_r = 0.0
        worst_simplex = None
        worst_y = None
        
        for simplex in hull.simplices:
            i, j, k = simplex
            p1, p2, p3 = pts[i], pts[j], pts[k]
            
            # Compute circumcenter of the planar triangle p1, p2, p3
            u = p2 - p1
            v = p3 - p1
            uu = np.dot(u, u)
            vv = np.dot(v, v)
            uv = np.dot(u, v)
            
            det = uu * vv - uv * uv
            if abs(det) < 1e-12:
                continue
                
            # Solve for circumcenter in the plane
            # c = p1 + a*u + b*v
            # (c-p1).u = 0.5|u|^2 => a*uu + b*uv = 0.5*uu
            # (c-p1).v = 0.5|v|^2 => a*uv + b*vv = 0.5*vv
            a = (0.5 * uu * vv - 0.5 * uv * vv) / det
            b = (0.5 * vv * uu - 0.5 * uu * uv) / det
            
            c_planar = p1 + a * u + b * v
            c_norm = np.linalg.norm(c_planar)
            if c_norm < 1e-12:
                continue
                
            c_sph = c_planar / c_norm
            
            # Check if c_sph is inside the spherical triangle (cone generated by p1, p2, p3)
            # c_sph = alpha*p1 + beta*p2 + gamma*p3 with alpha, beta, gamma > 0
            P = np.column_stack([p1, p2, p3])
            try:
                coeffs = np.linalg.solve(P, c_sph)
                if np.all(coeffs > -1e-6):
                    # Circumcenter is inside the spherical triangle
                    d = np.arccos(np.clip(np.dot(c_sph, p1), -1.0, 1.0))
                    if d > max_r:
                        max_r = d
                        worst_simplex = simplex
                        worst_y = c_sph
                else:
                    # Circumcenter is outside. The farthest point is the midpoint of the longest edge.
                    # We need to check the 3 edges.
                    # Edge (i,j): midpoint m12 = normalize(p1+p2)
                    # Distance is arccos(dot(m12, p1))
                    # Note: for a spherical triangle, if the circumcenter is outside, 
                    # the max distance to the triangle is at the midpoint of the longest edge 
                    # (in terms of angular length).
                    
                    # Calculate angular lengths of edges
                    d12 = np.arccos(np.clip(np.dot(p1, p2), -1.0, 1.0))
                    d23 = np.arccos(np.clip(np.dot(p2, p3), -1.0, 1.0))
                    d31 = np.arccos(np.clip(np.dot(p3, p1), -1.0, 1.0))
                    
                    # Find longest edge
                    if d12 >= d23 and d12 >= d31:
                        m = (p1 + p2) / np.linalg.norm(p1 + p2)
                        d = d12 / 2.0
                    elif d23 >= d12 and d23 >= d31:
                        m = (p2 + p3) / np.linalg.norm(p2 + p3)
                        d = d23 / 2.0
                    else:
                        m = (p3 + p1) / np.linalg.norm(p3 + p1)
                        d = d31 / 2.0
                        
                    if d > max_r:
                        max_r = d
                        worst_simplex = simplex
                        worst_y = m
            except np.linalg.LinAlgError:
                pass
                
        return max_r, worst_simplex, worst_y

    def move_point_towards_sphere(pt, target, strength):
        """
        Moves pt towards target on the sphere.
        Uses exponential map approximation: new_pt = normalize(pt + strength * (target - pt))
        This is a simple spherical interpolation step.
        """
        # Vector from pt to target
        v = target - pt
        # Normalize v to get a direction tangent-ish? No, just use the chord direction.
        # A more robust move: rotate pt towards target by angle * strength.
        # But simple additive update followed by normalization works well for small steps.
        new_pt = pt + strength * v
        norm = np.linalg.norm(new_pt)
        if norm < 1e-10:
            return pt
        return new_pt / norm

    # 2. Simulated Annealing
    best_pts = x0.copy()
    current_pts = x0.copy()
    current_val, cur_simplex, cur_y = compute_covering_radius(current_pts)
    best_val = current_val
    
    # Temperature schedule
    T0 = 0.05  # Initial temperature (radians)
    T_end = 0.001
    cooling_rate = 0.9995
    
    T = T0
    iteration = 0
    
    while time.time() < deadline:
        # If we have a worst facet, try to move one of its vertices towards the worst point
        if cur_simplex is not None and cur_y is not None:
            # Pick a random vertex from the worst facet
            idx = random.choice(cur_simplex)
            # Move it towards the worst point
            # Step size proportional to temperature
            step = T * (1.0 + random.random())
            
            new_pt = move_point_towards_sphere(current_pts[idx], cur_y, step)
            
            # Create a copy of current points with the moved point
            trial_pts = current_pts.copy()
            trial_pts[idx] = new_pt
            
            # Evaluate
            trial_val, new_simplex, new_y = compute_covering_radius(trial_pts)
            
            # Acceptance criterion
            delta = trial_val - current_val
            if delta < 0 or random.random() < np.exp(-delta / T):
                current_pts = trial_pts
                current_val = trial_val
                cur_simplex = new_simplex
                cur_y = new_y
                
                if current_val < best_val:
                    best_val = current_val
                    best_pts = current_pts.copy()
            else:
                # Reject, but keep current state
                pass
        else:
            # If hull failed or no worst facet found, random restart or jitter
            # Randomly perturb a random point
            idx = random.randint(0, N-1)
            noise = np.random.normal(0, T, 3)
            new_pt = current_pts[idx] + noise
            new_pt = new_pt / np.linalg.norm(new_pt)
            trial_pts = current_pts.copy()
            trial_pts[idx] = new_pt
            trial_val, new_simplex, new_y = compute_covering_radius(trial_pts)
            
            delta = trial_val - current_val
            if delta < 0 or random.random() < np.exp(-delta / T):
                current_pts = trial_pts
                current_val = trial_val
                cur_simplex = new_simplex
                cur_y = new_y
                if current_val < best_val:
                    best_val = current_val
                    best_pts = current_pts.copy()

        T *= cooling_rate
        iteration += 1
        
        # Check for time more frequently in tight loops
        if iteration % 10 == 0 and time.time() > deadline - 5.0:
            break

    # 3. Local Polish (Gradient Descent style) to refine the best solution found
    # This ensures we squeeze out the last bits of improvement
    pts = best_pts.copy()
    val, simplex, y = compute_covering_radius(pts)
    
    step_size = 0.01
    for _ in range(200):
        if time.time() > deadline - 2.0:
            break
        if simplex is None or y is None:
            break
            
        # Move vertices of the worst facet towards y
        for idx in simplex:
            old_pt = pts[idx]
            new_pt = move_point_towards_sphere(old_pt, y, step_size)
            pts[idx] = new_pt
            
        new_val, new_simplex, new_y = compute_covering_radius(pts)
        
        if new_val < val:
            val = new_val
            simplex = new_simplex
            y = new_y
            step_size *= 0.95
        else:
            # Revert
            for idx in simplex:
                # We need to revert. Since we modified pts in place, we should have kept a copy.
                # Let's redo the polish loop with copies.
                pass
            
            # Simpler polish:
            # Actually, let's just break if we can't improve easily, or do a proper revert.
            # For robustness, let's just stop if step_size is small.
            step_size *= 0.8
            if step_size < 1e-6:
                break
            # Revert by recomputing from best_pts? No, that's slow.
            # Let's implement the polish properly with a trial copy.
            break # To keep it simple and safe, we stop the simple polish if it fails.

    # A more robust final polish:
    pts = best_pts.copy()
    val, simplex, y = compute_covering_radius(pts)
    step_size = 0.05
    for _ in range(100):
        if time.time() > deadline - 1.0:
            break
        if simplex is None or y is None:
            break
            
        trial_pts = pts.copy()
        for idx in simplex:
            trial_pts[idx] = move_point_towards_sphere(trial_pts[idx], y, step_size)
            
        trial_val, new_simplex, new_y = compute_covering_radius(trial_pts)
        
        if trial_val < val:
            pts = trial_pts
            val = trial_val
            simplex = new_simplex
            y = new_y
            step_size *= 0.9
        else:
            step_size *= 0.8
            if step_size < 1e-6:
                break

    # Final normalization
    pts = pts / np.linalg.norm(pts, axis=1, keepdims=True)
    
    return pts
# EVOLVE-BLOCK-END
