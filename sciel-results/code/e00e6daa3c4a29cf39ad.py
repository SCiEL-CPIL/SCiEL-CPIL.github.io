def _soft_max(x, beta=200.0):
    """Log-sum-exp based soft max for differentiability."""
    x = np.asarray(x, dtype=float)
    m = np.max(x)
    if not np.isfinite(m):
        return m
    return m + math.log(np.sum(np.exp(x - m))) / beta

def _smooth_S(pts, cx, cy, beta_outer, beta_ls=200.0):
    """Smooth surrogate for enclosing-hexagon side length.
    Returns S = (D_soft + APOTHEM)/APOTHEM where D_soft is a soft-max
    of the 12 half-space projections."""
    pts = np.asarray(pts, dtype=float)
    D_terms = []
    for k in range(6):
        ang = beta_outer + math.pi / 6.0 + k * math.pi / 3.0
        nx, ny = math.cos(ang), math.sin(ang)
        projs = (pts[:, 0] - cx) * nx + (pts[:, 1] - cy) * ny
        D_terms.append(_soft_max(projs, beta_ls))
        D_terms.append(_soft_max(-projs, beta_ls))
    D = max(D_terms)
    return (D + APOTHEM) / APOTHEM

def _smooth_grad_S(pts, cx, cy, beta_outer, beta_ls=200.0):
    """Numerical gradient of smooth_S w.r.t. (cx, cy, beta_outer)."""
    h = 1e-5
    f0 = _smooth_S(pts, cx, cy, beta_outer, beta_ls)
    g = np.zeros(3)
    g[0] = (_smooth_S(pts, cx + h, cy, beta_outer, beta_ls) - f0) / h
    g[1] = (_smooth_S(pts, cx, cy + h, beta_outer, beta_ls) - f0) / h
    g[2] = (_smooth_S(pts, cx, cy, beta_outer + h, beta_ls) - f0) / h
    return g

