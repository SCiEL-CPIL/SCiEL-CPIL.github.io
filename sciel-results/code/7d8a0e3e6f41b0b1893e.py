import numpy as np
import time
import math
import random
from collections import defaultdict

def plan(instance):
    start_time = time.time()
    # Safety margin: 150s limit, use 145s
    deadline = start_time + 145.0

    # Extract instance data
    coords = np.array(instance["coords"], dtype=np.float64)
    n_customers = instance["n_customers"]
    demands = np.array(instance["demands"], dtype=np.float64)
    ready = np.array(instance["ready"], dtype=np.float64)
    due = np.array(instance["due"], dtype=np.float64)
    service = np.array(instance["service"], dtype=np.float64)
    stations_set = set(instance["stations"])
    capacity = instance["capacity"]
    battery = instance["battery"]
    speed = instance["speed"]
    recharge_rate = instance["recharge_rate"]
    horizon = instance["horizon"]

    customers = list(range(1, n_customers + 1))
    n_nodes = len(coords)
    
    # Pre-compute distance matrix
    diff = coords[:, np.newaxis, :] - coords[np.newaxis, :, :]
    dist = np.sqrt((diff ** 2).sum(axis=2))

    # Helper to check feasibility and get distance.
    def route_distance_and_feasibility(route):
        if not route:
            return True, 0.0
        
        cur_node = 0
        cur_time = 0.0
        cur_bat = battery
        total_dist = 0.0
        load = 0.0
        
        for node in route:
            d = dist[cur_node, node]
            cur_time += d / speed
            cur_bat -= d
            total_dist += d
            
            if cur_bat < -1e-9:
                return False, total_dist
            
            if node in stations_set:
                energy = battery - cur_bat
                cur_time += energy * recharge_rate
                cur_bat = battery
            else:
                load += demands[node]
                if load > capacity + 1e-9:
                    return False, total_dist
                cur_time = max(cur_time, ready[node])
                if cur_time > due[node] + 1e-9:
                    return False, total_dist
                cur_time += service[node]
                
            cur_node = node

        d = dist[cur_node, 0]
        cur_time += d / speed
        cur_bat -= d
        total_dist += d

        if cur_bat < -1e-9:
            return False, total_dist
        if cur_time > horizon + 1e-9:
            return False, total_dist
            
        return True, total_dist

    def compute_total_distance(routes):
        total = 0.0
        for route in routes:
            if not route:
                continue
            cur_node = 0
            for node in route:
                total += dist[cur_node, node]
                cur_node = node
            total += dist[cur_node, 0]
        return total

    # --- COLUMN GENERATION STRATEGY ---
    
    # We will generate candidate routes (columns).
    # A "column" is a feasible route.
    # We start with a set of columns generated by a "Price-Out" heuristic:
    # For each unvisited customer, find the cheapest feasible route containing it.
    
    # To find the cheapest feasible route containing a specific customer 'c',
    # we can use a Dijkstra-like search on an expanded state space.
    # State: (current_node, current_time_bucket, current_battery_bucket)
    # However, time is continuous. We can discretize time or use a label-setting algorithm.
    # Given small N (25 customers), a simpler "Shortest Path with Constraints" approach 
    # using A* or Dijkstra on (node, battery) with time as cost might work, 
    # but time windows make it complex.
    
    # Alternative: Generate many random feasible routes using a robust Nearest Neighbor 
    # with randomization, and keep the best ones. Then use Set Cover to select the minimal 
    # cost subset of these routes that covers all customers.
    
    # Let's generate a pool of candidate routes.
    candidate_routes = []
    
    def generate_random_route(seed_offset):
        rng = random.Random(42 + seed_offset)
        unvisited = set(customers)
        route = []
        cur_node = 0
        cur_time = 0.0
        cur_bat = battery
        load = 0.0
        
        while unvisited:
            best_next = None
            best_score = float('inf')
            
            # Candidates: all unvisited customers + depot (to end)
            # We only add customers if feasible.
            feasible_nexts = []
            for c in unvisited:
                d = dist[cur_node, c]
                new_time = cur_time + d / speed
                new_bat = cur_bat - d
                if new_bat < -1e-9:
                    continue
                if c in stations_set:
                    # Stations are not in 'customers' list usually, but let's check.
                    # The problem says customers 1..25, stations are separate node ids.
                    # So c is never a station.
                    pass
                else:
                    if load + demands[c] > capacity:
                        continue
                    new_time = max(new_time, ready[c])
                    if new_time > due[c]:
                        continue
                    new_time += service[c]
                    feasible_nexts.append((c, new_time, new_bat, d))
            
            if not feasible_nexts:
                break
            
            # Choose best next: minimize distance + random noise
            # Or minimize distance to nearest unvisited?
            # Let's use a weighted score: distance + penalty for time window tightness
            for c, nt, nb, d in feasible_nexts:
                # Simple heuristic: prefer closer, but add randomness
                score = d + rng.random() * 10
                if score < best_score:
                    best_score = score
                    best_next = c
                    best_nt = nt
                    best_nb = nb
                    best_d = d
            
            if best_next is None:
                break
                
            # Commit to best_next
            route.append(best_next)
            cur_node = best_next
            cur_time = best_nt
            cur_bat = best_nb
            load += demands[best_next]
            unvisited.remove(best_next)
            
            # Check if we should return to depot? 
            # If battery is low or time is getting tight, maybe.
            # For now, just keep going until no more feasible customers.
            
        # Check if route is feasible including return
        if route:
            d_back = dist[cur_node, 0]
            if cur_bat - d_back >= -1e-9:
                t_back = cur_time + d_back / speed
                if t_back <= horizon:
                    # Valid route
                    candidate_routes.append(route)
        return route

    # Generate a pool of candidate routes
    # We want diverse routes.
    for i in range(200):
        if time.time() > deadline - 10:
            break
        generate_random_route(i)
    
    # If no routes generated, fallback to simple construction
    if not candidate_routes:
        # Fallback: simple greedy
        routes = []
        unvisited = set(customers)
        while unvisited:
            # Pick customer with earliest due date
            c = min(unvisited, key=lambda x: due[x])
            # Try to insert into existing routes or start new
            inserted = False
            for r in routes:
                # Try all positions
                for pos in range(len(r) + 1):
                    new_r = r[:pos] + [c] + r[pos:]
                    if route_distance_and_feasibility(new_r)[0]:
                        routes[routes.index(r)] = new_r
                        unvisited.remove(c)
                        inserted = True
                        break
                if inserted:
                    break
            if not inserted:
                # Start new route
                # Check if single customer is feasible
                if route_distance_and_feasibility([c])[0]:
                    routes.append([c])
                    unvisited.remove(c)
                else:
                    # Should not happen
                    break
        return routes

    # --- SET COVER / GREEDY SELECTION ---
    # We have a pool of candidate_routes.
    # We want to select a subset of these routes such that every customer is covered exactly once,
    # minimizing total distance.
    # This is a Set Partitioning Problem.
    # Greedy approach:
    # 1. Sort candidate routes by distance (ascending).
    # 2. Maintain a set of "covered" customers.
    # 3. Iterate through sorted routes. If a route contains no already-covered customers, 
    #    select it and mark its customers as covered.
    # 4. If we cannot cover all customers with disjoint routes from the pool, we need to generate more 
    #    or use a different selection.
    
    # However, simple greedy might miss optimal combinations.
    # Let's use a more robust selection:
    # 1. Calculate distance for each candidate route.
    # 2. Sort by distance.
    # 3. Use a backtracking search to find the best combination? 
    #    With 200 candidates and 25 customers, backtracking might be too slow if not pruned.
    #    
    # Let's try a simpler "Greedy with Conflict Resolution":
    # 1. Sort candidates by distance.
    # 2. Select first route. Mark customers.
    # 3. Remove any other candidate routes that conflict (share customers) with selected ones? 
    #    No, we want to pick the best set.
    
    # Better: 
    # 1. Sort candidates by distance.
    # 2. Initialize selected = [], covered = set().
    # 3. For each route in sorted candidates:
    #    - If route intersects with covered, skip.
    #    - Else, tentatively add to selected, update covered.
    #    - If covered == all customers, stop.
    # 4. If not all covered, we have a problem. The pool might not contain a feasible partition.
    #    In that case, we need to generate more specific routes for the remaining customers.
    
    # Let's implement a more flexible selection:
    # We will maintain a list of "active" candidates.
    
    # First, compute distances for all candidates
    route_data = []
    for r in candidate_routes:
        is_valid, d = route_distance_and_feasibility(r)
        if is_valid:
            custs = set(r)
            route_data.append((d, r, custs))
            
    if not route_data:
        # Fallback
        return [[c] for c in customers]

    # Sort by distance
    route_data.sort(key=lambda x: x[0])
    
    # Greedy Set Partition
    selected_routes = []
    covered = set()
    remaining_candidates = route_data[:]
    
    # We need to cover all customers.
    # If greedy fails to cover all, we'll have to generate more routes or relax.
    # Let's try a simple greedy first.
    for d, r, custs in remaining_candidates:
        if custs & covered:
            continue
        # Check if this route covers any uncovered customers
        if custs - covered:
            selected_routes.append(r)
            covered.update(custs)
            if covered == set(customers):
                break
    
    if len(covered) < n_customers:
        # Greedy failed to cover all. 
        # This can happen if the pool is limited.
        # Fallback: Use the current selected routes, and for remaining customers, 
        # create individual routes or insert them into existing ones if possible.
        
        # Let's try to insert remaining customers into selected routes or create new ones.
        unvisited = set(customers) - covered
        
        # For each unvisited, try to insert into existing selected routes
        for c in list(unvisited):
            best_r_idx = -1
            best_pos = -1
            best_d = float('inf')
            
            for idx, r in enumerate(selected_routes):
                for pos in range(len(r) + 1):
                    new_r = r[:pos] + [c] + r[pos:]
                    if route_distance_and_feasibility(new_r)[0]:
                        # Calculate new total distance
                        # We don't have exact new distance easily without re-calc, 
                        # but we can approximate or just accept if feasible.
                        # To be safe, let's just pick the first feasible one or the one with min length increase.
                        # Since we don't have incremental distance, let's just pick the first feasible.
                        best_r_idx = idx
                        best_pos = pos
                        break
                if best_r_idx != -1:
                    break
            
            if best_r_idx != -1:
                r = selected_routes[best_r_idx]
                selected_routes[best_r_idx] = r[:best_pos] + [c] + r[best_pos:]
                unvisited.remove(c)
            else:
                # Create new route
                if route_distance_and_feasibility([c])[0]:
                    selected_routes.append([c])
                    unvisited.remove(c)
    
    # Now we have a valid set of routes (hopefully).
    current_routes = [list(r) for r in selected_routes]
    
    # --- LOCAL SEARCH ---
    # Improve the solution using 2-opt and Or-opt.
    
    def local_search(routes, time_limit):
        current_routes = [list(r) for r in routes]
        current_dist = compute_total_distance(current_routes)
        best_routes = [list(r) for r in current_routes]
        best_dist = current_dist
        
        start_ls = time.time()
        rng = random.Random(42)
        
        while time.time() - start_ls < time_limit:
            improved = False
            
            # 1. Intra-route 2-opt
            for r_idx in range(len(current_routes)):
                route = current_routes[r_idx]
                n = len(route)
                if n < 2:
                    continue
                
                for i in range(n - 1):
                    for j in range(i + 1, n):
                        # Reverse segment i..j
                        new_route = route[:i] + route[i:j+1][::-1] + route[j+1:]
                        if route_distance_and_feasibility(new_route)[0]:
                            new_routes = [list(r) for r in current_routes]
                            new_routes[r_idx] = new_route
                            new_dist = compute_total_distance(new_routes)
                            if new_dist < current_dist - 1e-9:
                                current_routes = new_routes
                                current_dist = new_dist
                                if current_dist < best_dist:
                                    best_dist = current_dist
                                    best_routes = [list(r) for r in current_routes]
                                improved = True
                                break
                    if improved:
                        break
                if improved:
                    break
            
            # 2. Inter-route Relocate
            if not improved and len(current_routes) > 1:
                for r1_idx in range(len(current_routes)):
                    route1 = current_routes[r1_idx]
                    if not route1:
                        continue
                    for idx in range(len(route1)):
                        node = route1[idx]
                        # Remove
                        new_route1 = route1[:idx] + route1[idx+1:]
                        
                        for r2_idx in range(len(current_routes)):
                            if r2_idx == r1_idx:
                                continue
                            route2 = current_routes[r2_idx]
                            for pos in range(len(route2) + 1):
                                new_route2 = route2[:pos] + [node] + route2[pos:]
                                
                                # Check feasibility
                                if route_distance_and_feasibility(new_route1)[0] and route_distance_and_feasibility(new_route2)[0]:
                                    new_routes = [list(r) for r in current_routes]
                                    new_routes[r1_idx] = new_route1
                                    new_routes[r2_idx] = new_route2
                                    new_dist = compute_total_distance(new_routes)
                                    if new_dist < current_dist - 1e-9:
                                        current_routes = new_routes
                                        current_dist = new_dist
                                        if current_dist < best_dist:
                                            best_dist = current_dist
                                            best_routes = [list(r) for r in current_routes]
                                        improved = True
                                        break
                            if improved:
                                break
                        if improved:
                            break
                    if improved:
                        break
            
            if not improved:
                # No improvement found in this pass, break or continue?
                # If we do a full pass without improvement, we can stop.
                break
                
        return best_routes

    # Run local search
    elapsed = time.time() - start_time
    remaining = deadline - elapsed - 2.0
    if remaining > 1.0:
        current_routes = local_search(current_routes, remaining)
        
    # Final validation
    valid = True
    served = set()
    for route in current_routes:
        if not route_distance_and_feasibility(route)[0]:
            valid = False
            break
        for node in route:
            if node not in stations_set:
                if node in served:
                    valid = False
                    break
                served.add(node)
    
    if not valid or served != set(customers):
        # Fallback to the initial greedy selection if LS broke it
        current_routes = [list(r) for r in selected_routes]
        # Re-validate
        valid = True
        served = set()
        for route in current_routes:
            if not route_distance_and_feasibility(route)[0]:
                valid = False
                break
            for node in route:
                if node not in stations_set:
                    if node in served:
                        valid = False
                        break
                    served.add(node)
        
        if not valid or served != set(customers):
            # Absolute fallback: individual routes
            current_routes = [[c] for c in customers]
            
    return current_routes
