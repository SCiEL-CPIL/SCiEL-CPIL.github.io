def _build_conflict_graph(words, n, min_dist):
    """
    Build the conflict graph where edges connect words with distance < min_dist.
    Returns adjacency list.
    """
    m = len(words)
    adj = [set() for _ in range(m)]
    for i in range(m):
        for j in range(i + 1, m):
            if _hamming(words[i], words[j]) < min_dist:
                adj[i].add(j)
                adj[j].add(i)
    return adj

def _greedy_color(adj, order):
    """
    Greedy coloring of the graph in the given order.
    Returns list of colors.
    """
    n = len(order)
    colors = [0] * n
    color_map = {}
    for i, v in enumerate(order):
        # Find smallest available color
        used = set()
        for u in adj[v]:
            if u in color_map:
                used.add(color_map[u])
        c = 0
        while c in used:
            c += 1
        colors[i] = c
        color_map[v] = c
    return colors

def _branch_and_bound(words, n, min_dist, time_limit, initial_size=0):
    """
    Tomita's branch and bound algorithm for maximum independent set.
    """
    m = len(words)
    if m == 0:
        return []
    
    # Build conflict graph
    adj = [set() for _ in range(m)]
    for i in range(m):
        for j in range(i + 1, m):
            if _hamming(words[i], words[j]) < min_dist:
                adj[i].add(j)
                adj[j].add(i)
    
    # Convert to bitsets for efficiency
    adj_bits = [0] * m
    for i in range(m):
        for j in adj[i]:
            adj_bits[i] |= (1 << j)
    
    best_set = set()
    best_size = initial_size
    
    # Order vertices by degree (descending) for better pruning
    degrees = [len(adj[i]) for i in range(m)]
    order = sorted(range(m), key=lambda x: -degrees[x])
    
    # Map old index to new index
    old_to_new = {v: i for i, v in enumerate(order)}
    new_to_old = order
    
    # Rebuild adj in new order
    new_adj_bits = [0] * m
    for i in range(m):
        old_i = order[i]
        for j in adj[old_i]:
            new_j = old_to_new[j]
            new_adj_bits[i] |= (1 << new_j)
    
    # Recursive search
    def search(P, X, depth):
        nonlocal best_set, best_size
        if len(P) + len(best_set) <= best_size:
            return
        
        if not P:
            if len(best_set) < best_size:
                best_set = set(best_set)
                best_size = len(best_set)
            return
        
        # Greedy coloring
        # Order P by degree in P
        p_list = list(P)
        p_list.sort(key=lambda v: -bin(new_adj_bits[v] & (1 << len(P)) - 1).count('1'))
        
        colors = _greedy_color(new_adj_bits, p_list)
        
        # Process vertices in reverse color order
        for c in range(max(colors) + 1, -1, -1):
            # Get vertices with color c
            P_c = [v for v, col in zip(p_list, colors) if col == c]
            if not P_c:
                continue
            
            # Bound: if current best + remaining vertices <= best_size, prune
            remaining = sum(1 for col in colors if col <= c)
            if len(best_set) + remaining <= best_size:
                return
            
            # Try adding each vertex in P_c
            for v in P_c:
                if v in X:
                    continue
                
                # Add v to independent set
                new_P = P - {v} - set(new_adj_bits[v] & ((1 << m) - 1))
                new_X = X | {v}
                
                # Update best
                current_set = best_set | {v}
                if len(current_set) > best_size:
                    best_set = current_set
                    best_size = len(best_set)
                
                # Recurse
                search(new_P, new_X, depth + 1)
                
                P = new_P | {v}
                X = new_X - {v}
    
    # Initial call
    search(set(range(m)), set(), 0)
    
    return [new_to_old[i] for i in best_set]

def _expand_forbidden_set(center, n, max_dist):
    forbidden = set()
    forbidden.add(center)
    for w in range(1, max_dist + 1):
        for positions in itertools.combinations(range(n), w):
            diff = 0
            for p in positions:
                diff |= (1 << p)
            forbidden.add(center ^ diff)
    return forbidden

def _greedy_pack_with_forbidden_set(base_words, n, min_dist, time_limit, seed=42):
    rng = random.Random(seed)
    words = list(base_words)
    
    forbidden = set()
    for w in words:
        forbidden |= _expand_forbidden_set(w, n, min_dist - 1)
    
    word_set = set(words)
    
    start = time.time()
    best_size = len(words)
    
    # Try low-weight vectors
    low_weight_vectors = []
    for w in range(1, 5):
        for positions in itertools.combinations(range(n), w):
            v = 0
            for p in positions:
                v |= (1 << p)
            low_weight_vectors.append(v)
    
    for v in low_weight_vectors:
        if time.time() - start > time_limit:
            break
        if v not in word_set and v not in forbidden:
            words.append(v)
            word_set.add(v)
            forbidden |= _expand_forbidden_set(v, n, min_dist - 1)
            best_size = len(words)
    
    # Random search
    while time.time() - start < time_limit:
        batch_size = 100
        for _ in range(batch_size):
            if time.time() - start > time_limit:
                break
            cand = rng.randint(0, (1 << n) - 1)
            if cand not in word_set and cand not in forbidden:
                words.append(cand)
                word_set.add(cand)
                forbidden |= _expand_forbidden_set(cand, n, min_dist - 1)
                best_size = len(words)
    
    return words

def construct():
    N = 18
    MIN_DIST = 6
    start = time.time()
    
    # 1. Start with Reed-Muller code (32 words)
    rm_words = _reed_muller_extended()
    if not _check_min_distance(rm_words, MIN_DIST):
        raise ValueError("RM code failed distance check")
    
    # 2. Greedy packing to get a good initial solution
    elapsed = time.time() - start
    time_remaining = DEADLINE - elapsed
    
    best = rm_words
    if time_remaining > 10.0:
        greedy_time = time_remaining * 0.4
        best = _greedy_pack_with_forbidden_set(rm_words, N, MIN_DIST, time_limit=greedy_time, seed=42)
        
        if _check_min_distance(best, MIN_DIST):
            elapsed2 = time.time() - start
            time_remaining2 = DEADLINE - elapsed2
            
            # 3. Branch and bound on the remaining candidates
            if time_remaining2 > 5.0:
                # Generate a pool of candidates
                rng = random.Random(123)
                candidates = set(best)
                for _ in range(5000):
                    cand = rng.randint(0, (1 << N) - 1)
                    candidates.add(cand)
                
                candidates = list(candidates)
                
                # Run branch and bound
                bnb_time = min(time_remaining2 - 2.0, 20.0)
                result_indices = _branch_and_bound(candidates, N, MIN_DIST, time_limit=bnb_time, initial_size=len(best))
                
                if result_indices:
                    bnb_words = [candidates[i] for i in result_indices]
                    if _check_min_distance(bnb_words, MIN_DIST) and len(bnb_words) > len(best):
                        best = bnb_words
    
    return best
