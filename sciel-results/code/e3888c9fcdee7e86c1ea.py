        # Start with S_1 = [1]
        # To get S_n from S_{n-1}:
        # S_{n-1} contains all perms of 1..n-1.
        # We want to insert n.
        # The standard construction is:
        # S_n = S_{n-1}
        # For each permutation p of 1..n-1:
        #    append n
        #    append p (but wait, this is not the standard way)
        
        # Correct Standard Construction:
        # S_1 = "1"
        # S_2 = "121"
        # S_3 = "123121321"
        # S_n is built by taking S_{n-1}, and for each permutation of 1..n-1,
        # we insert n.
        # Specifically, S_n is the concatenation of:
        # For each perm p of 1..n-1:
        #   p + n + p ? No.
        
