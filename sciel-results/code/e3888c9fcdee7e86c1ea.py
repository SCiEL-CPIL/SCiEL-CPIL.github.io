        # The standard superpermutation can be generated by:
        # def gen_superperm(n):
        #     if n == 1: yield [1]
        #     else:
        #         for p in permutations(1..n-1):
        #             ...
        
        # A simpler way:
        # S_n length is sum(i! for i in 1..n)
        # We can construct it recursively.
        
        def build_superperm(m):
            if m == 1:
                return [1]
            prev = build_superperm(m - 1)
            # The standard construction inserts m into the previous superpermutation.
            # It visits all permutations of 1..m-1, and for each, it "swaps" m in.
