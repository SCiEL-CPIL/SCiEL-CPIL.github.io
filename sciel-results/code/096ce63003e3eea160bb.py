import time
import numpy as np

def construct():
    n, m, p = DIMENSIONS
    start_time = time.time()
    deadline = start_time + 140  # Safety margin before 150s limit
    
    # Try to find a lower rank decomposition
    # For 3x4x7 matrix multiplication, the schoolbook rank is 84
    # We can try to reduce this by exploiting structure
    
    # First, let's try a rank-84 schoolbook solution as baseline
    rank = n * m * p
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j, column] = 1
                V[j * p + k, column] = 1
                W[k * n + i, column] = 1
                column += 1
    
    # Convert to lists as required
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
