def _lj_energy_and_grad(pos):
    """Compute LJ energy and gradient for N atoms.
    pos: (N, 3) array
    Returns (energy, gradient)
    """
    n = pos.shape[0]
    # Pairwise differences
    diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]  # (N, N, 3)
    r2 = np.sum(diff ** 2, axis=2)  # (N, N)
    # Avoid division by zero on diagonal
    np.fill_diagonal(r2, 1.0)
    r = np.sqrt(r2)
    # Only compute for i < j to avoid double counting
    # But for gradient, we can compute full matrix and take upper triangle
    # Let's compute energy properly
    inv_r6 = r2 ** (-3)  # r^-6
    inv_r12 = inv_r6 ** 2  # r^-12
    
    # Energy: 4 * sum over i<j of (r^-12 - r^-6)
    # Using full matrix, diagonal is 0 contribution if we set it to 0
    np.fill_diagonal(inv_r6, 0.0)
    np.fill_diagonal(inv_r12, 0.0)
    energy = 2.0 * 4.0 * np.sum(inv_r12 - inv_r6)  # factor 2 because we count each pair twice in NxN matrix
    
    # Gradient: dE/dr_i = 4 * sum_{j != i} (12 r_i^-13 - 6 r_i^-7) * (r_i - r_j)/r_i
    # More carefully:
    # E = 4 * sum_{i<j} (r_ij^-12 - r_ij^-6)
    # dE/dr_i = 4 * sum_{j != i} (-12 r_ij^-14 + 6 r_ij^-8) * (r_i - r_j)
    #         = 4 * sum_{j != i} (6 r_ij^-8 - 12 r_ij^-14) * (r_i - r_j)
    # Let's compute:
    # r_ij^-8 = r2^-4, r_ij^-14 = r2^-7
    inv_r8 = r2 ** (-4)
    inv_r14 = r2 ** (-7)
    np.fill_diagonal(inv_r8, 0.0)
    np.fill_diagonal(inv_r14, 0.0)
    
    # coeff[i,j] = 4 * (6 * r_ij^-8 - 12 * r_ij^-14)
    coeff = 4.0 * (6.0 * inv_r8 - 12.0 * inv_r14)  # (N, N)
    # grad[i] = sum_j coeff[i,j] * (pos[i] - pos[j])
    # Using matrix operations:
    # diff[i,j] = pos[i] - pos[j]
    # grad[i] = sum_j coeff[i,j] * diff[i,j]
    grad = np.sum(coeff[:, :, np.newaxis] * diff, axis=1)
    
    return energy, grad

def _construct_mackay_icosahedron():
    """Construct the 55-atom Mackay icosahedron.
    
    The Mackay icosahedron has:
    - 1 atom at center
    - 12 atoms on first shell (vertices of regular icosahedron) at radius r1
    - 42 atoms on second shell at radius r2
    
    The icosahedron vertices (for unit circumradius) are:
    (0, ±1, ±φ), (±1, ±φ, 0), (±φ, 0, ±1) where φ = (1+√5)/2
    
    For the Mackay icosahedron, the optimal shell radii are approximately:
    r1 ≈ 1.05 (inner shell)
    r2 ≈ 2.10 (outer shell)
    
    But we need to be more precise. The standard Mackay icosahedron for LJ has:
    - Inner shell: 12 atoms at radius ~1.05
    - Outer shell: 42 atoms at radius ~2.10
    
    Let's use known coordinates. The 55-atom Mackay icosahedron can be constructed as:
    Center: 1 atom at origin
    First shell: 12 vertices of icosahedron
    Second shell: 42 atoms - these are the vertices of a larger icosahedron plus additional positions
    
    Actually, the second shell of the Mackay icosahedron consists of:
    - 12 atoms at the vertices of a larger icosahedron
    - 30 atoms at the midpoints of edges (or similar)
    
    Let me use a cleaner approach. The Mackay icosahedron M(2,2) has:
    - 1 center
    - 12 first-shell atoms (icosahedron vertices)
    - 42 second-shell atoms
    
    The 42 second-shell atoms can be described as all points of the form:
    For the icosahedral symmetry, the second shell positions are generated by applying
    icosahedral rotations to a set of generating positions.
    
    Let me use explicit coordinates. The regular icosahedron has 12 vertices.
    For the Mackay icosahedron, I'll use the following construction:
    
    φ = (1 + sqrt(5)) / 2
    
    Icosahedron vertices (12):
    (0, ±1, ±φ)
    (±1, ±φ, 0)
    (±φ, 0, ±1)
    
    Normalize these to have norm 1, then scale by r1 for inner shell.
    
    For the outer shell (42 atoms), the Mackay icosahedron second shell consists of:
    - 12 atoms at positions that are icosahedron vertices scaled to r2
    - 30 atoms at edge-midpoint-like positions
    
    Actually, let me look at this more carefully. The 42 atoms on the second shell of a
    Mackay icosahedron are arranged as:
    - 6 squares (each with 4 atoms) + 2 triangles (each with... ) 
    
    Let me just use the fact that we can generate all 55 positions and then relax.
    
    A simpler approach: use the known fact that the optimal geometry is close to the
    Mackay icosahedron, and construct it as follows:
    
    Inner shell (12 atoms): icosahedron vertices at radius r1
    Outer shell (42 atoms): 
      - 12 atoms at icosahedron vertices at radius r2
      - 30 atoms at positions corresponding to the 30 edges of the icosahedron,
        but offset outward
    
    The 30 edge positions: for each edge of the icosahedron, place an atom at the
    midpoint of the edge, then project radially outward to radius r2.
    
    Let me implement this.
    """
    phi = (1.0 + np.sqrt(5.0)) / 2.0
    
    # Icosahedron vertices (12)
    verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [-phi, 0, 1], [phi, 0, -1], [-phi, 0, -1]
    ], dtype=float)
    
    # Normalize to unit length
    norms = np.linalg.norm(verts, axis=1, keepdims=True)
    verts_unit = verts / norms  # unit vectors
    
    # Edges of the icosahedron: pairs of vertices that are adjacent
    # Two vertices are adjacent if their dot product is -1/phi ≈ -0.618
    # Actually, for unit icosahedron, adjacent vertices have dot product = -1/phi
    # Let's find all edges
    edges = []
    for i in range(12):
        for j in range(i + 1, 12):
            dot = np.dot(verts_unit[i], verts_unit[j])
            # Adjacent vertices in icosahedron have dot product ≈ -1/phi ≈ -0.618
            if abs(dot - (-1.0 / phi)) < 1e-6:
                edges.append((i, j))
    
    # Should have 30 edges
    # For each edge, the midpoint direction is the normalized sum of the two unit vectors
    edge_mids = []
    for i, j in edges:
        mid = verts_unit[i] + verts_unit[j]
        mid_norm = np.linalg.norm(mid)
        if mid_norm > 1e-10:
            edge_mids.append(mid / mid_norm)
    edge_mids = np.array(edge_mids)  # 30 unit vectors
    
    # Now construct the 55-atom cluster
    # Use initial radii close to known optimal values
    r1 = 1.05  # inner shell radius
    r2 = 2.10  # outer shell radius
    
    positions = []
    
    # Center atom
    positions.append([0.0, 0.0, 0.0])
    
    # Inner shell: 12 icosahedron vertices at radius r1
    for v in verts_unit:
        positions.append(r1 * v)
    
    # Outer shell: 12 icosahedron vertices at radius r2
    for v in verts_unit:
        positions.append(r2 * v)
    
    # Outer shell: 30 edge-midpoint directions at radius r2
    for v in edge_mids:
        positions.append(r2 * v)
    
    positions = np.array(positions, dtype=float)
    
    # Verify we have 55 atoms
    assert positions.shape[0] == 55, f"Expected 55 atoms, got {positions.shape[0]}"
    
    return positions

