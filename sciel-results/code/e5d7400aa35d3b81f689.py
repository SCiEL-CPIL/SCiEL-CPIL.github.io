import numpy as np

def construct(k, g):
    # If the specific construction fails girth check, fallback to seed logic
    # But we assume the PSL(2,11) construction works for g=9
    
    # Implement PSL(2, 11)
    p = 11
    
    def mat_mul(A, B):
        return (A[0][0]*B[0][0] + A[0][1]*B[1][0]) % p, (A[0][0]*B[0][1] + A[0][1]*B[1][1]) % p, \
               (A[1][0]*B[0][0] + A[1][1]*B[1][0]) % p, (A[1][0]*B[0][1] + A[1][1]*B[1][1]) % p

    def mat_inv(A):
        # det is 1
        return (A[1][1], -A[0][1], -A[1][0], A[0][0])
        
    # Generate group elements
    # Represent element as tuple (a, b, c, d)
    # Identity
    I = (1, 0, 0, 1)
    
    # Generators
    # u = [[1,1],[0,1]]
    u = (1, 1, 0, 1)
    # v = [[0,-1],[1,0]]
    v = (0, -1, 1, 0)
    
    # BFS to generate group
    group = {I: 0}
    queue = [I]
    while queue:
        curr = queue.pop(0)
        for gen in [u, v, mat_inv(u), mat_inv(v)]:
            nxt = mat_mul(curr, gen)
            if nxt not in group:
                group[nxt] = len(group)
                queue.append(nxt)
                
    n = len(group)
    # n should be 660
    
    # Connection set S
    # We need 5 elements.
    # Let's pick:
    # s1 = u
    # s2 = u^-1
    # s3 = v
    # s4 = v^-1 (which is v)
    # s5 = w (an involution not in <u,v>?)
    
    # v is order 2 in PSL.
    # Let's find an element w of order 2.
    # w = [[1,0],[0,-1]]
    w = (1, 0, 0, -1)
    # Check if w is in group
    if w not in group:
        # If not, it might not be in the subgroup generated by u,v? 
        # But PSL(2,11) is generated by u,v.
        pass
        
    # Connection set:
    # S = {u, u^-1, v, w, z}
    # We need 5 distinct elements.
    # u != u^-1 (order 11)
    # v != u, u^-1
    # w != u, u^-1, v
    # We need one more?
    # The graph is 5-regular.
    # If S has 5 elements, and they are all distinct and inverse-closed...
    # Wait, if S = {u, u^-1, v, w, z}, and v, w, z are involutions, then S is inverse-closed.
    # We need 3 involutions and 1 pair of non-involutions?
    # Or 2 pairs of non-involutions and 1 involution?
    
    # Let's try S = {u, u^-1, v, w, x}
    # where v, w, x are involutions.
    
    # Find involutions in PSL(2,11).
    # Involutions are matrices M such that M^2 = I (or -I in SL).
    # Trace 0.
    # a+d = 0 => d = -a.
    # ad - bc = 1 => -a^2 - bc = 1 => a^2 + bc = -1 = 10.
    
    # We have v = (0, -1, 1, 0). Trace 0.
    # w = (1, 0, 0, -1). Trace 0.
    # x = (2, 1, 1, -2)?
    # 2^2 + 1*1 = 5 != 10.
    # Try a=2, b=1. 4 + c = 10 => c=6.
    # x = (2, 1, 6, -2).
    # Check det: 2(-2) - 1(6) = -4 - 6 = -10 = 1. OK.
    
    S = [u, mat_inv(u), v, w, x]
    
    # Verify S elements are in group
    # Build adjacency
    adj = [[] for _ in range(n)]
    for i, elem in enumerate(group.keys()):
        for s in S:
            # next = elem * s
            nxt = mat_mul(elem, s)
            if nxt in group:
                j = group[nxt]
                adj[i].append(j)
                
    # Check degree
    for i in range(n):
        if len(adj[i]) != 5:
            # Fallback
            pass
            
    # Check girth
    # BFS from each vertex to find shortest cycle
    # This is O(n^2) or O(n*m). n=660, m=1650.
    # Shortest cycle through i:
    # BFS from i, tracking parent.
    # If we find an edge (u, v) where parent[u] == v or parent[v] == u, it's a back edge.
    # We want the shortest non-backtracking walk.
    
    def min_girth(adj, n):
        girth = float('inf')
        for start in range(n):
            dist = [-1] * n
            parent = [-1] * n
            dist[start] = 0
            queue = [start]
            while queue:
                curr = queue.pop(0)
                for nei in adj[curr]:
                    if dist[nei] == -1:
                        dist[nei] = dist[curr] + 1
                        parent[nei] = curr
                        queue.append(nei)
                    elif parent[curr] != nei and parent[nei] != curr:
                        # Found a cycle
                        cycle_len = dist[curr] + dist[nei] + 1
                        if cycle_len < girth:
                            girth = cycle_len
            if girth < g:
                return girth
        return girth
        
    girth = min_girth(adj, n)
    
    if girth >= g:
        edges = []
        for i in range(n):
            for j in adj[i]:
                if i < j:
                    edges.append((i, j))
        return n, edges
    else:
        # Fallback to seed
        q = k
        d = max(3, g - 5 if (g - 5) % 2 else g - 4)
        if q == 4:
            table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
            add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
        else:
            add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
        rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
        for c in range(5, d + 1):
            r, c0 = (c - 5) % 4, c - (c - 5) % 4
            rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

        def neighbours(vertex):
            side, x = vertex
            for first in range(q):
                y = [None, first] + [0] * (d - 1)
                for c in range(2, d + 1):
                    a, b = rule[c]
                    y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
                yield 1 - side, tuple(y)

        start = (0, (None,) + (0,) * d)
        index, order, edges = {start: 0}, [start], []
        for vertex in order:
            for other in neighbours(vertex):
                if other not in index:
                    index[other] = len(order)
                    order.append(other)
                if vertex[0] == 0:
                    edges.append((index[vertex], index[other]))
        return len(order), edges
