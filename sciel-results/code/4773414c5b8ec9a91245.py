def _pair_sums_unique(elements):
    sums = set()
    for i, a in enumerate(elements):
        for j in range(i, len(elements)):
            s = a + elements[j]
            if s in sums:
                return False
            sums.add(s)
    return True

def _diffs(elements):
    d = set()
    for i in range(len(elements)):
        for j in range(i + 1, len(elements)):
            diff = elements[j] - elements[i]
            d.add(diff)
            d.add(-diff)
    return d

def _can_add_to_set(x, elements, sum_set, diff_set, other_diff_set):
    for a in elements:
        s = x + a
        if s in sum_set:
            return False
    s2 = x + x
    if s2 in sum_set:
        return False
    new_diffs = set()
    for a in elements:
        d = x - a
        new_diffs.add(d)
        new_diffs.add(-d)
    if new_diffs & diff_set:
        return False
    if new_diffs & other_diff_set:
        return False
    return True

def _greedy_build():
    A = []
    B = []
    sumA = set()
    sumB = set()
    diffA = set()
    diffB = set()
    
    for x in range(1, N + 1):
        if len(A) < MAX_EACH and _can_add_to_set(x, A, sumA, diffA, diffB):
            for a in A:
                sumA.add(x + a)
            sumA.add(x + x)
            for a in A:
                d = x - a
                diffA.add(d)
                diffA.add(-d)
            A.append(x)
        
        if len(B) < MAX_EACH and _can_add_to_set(x, B, sumB, diffB, diffA):
            for b in B:
                sumB.add(x + b)
            sumB.add(x + x)
            for b in B:
                d = x - b
                diffB.add(d)
                diffB.add(-d)
            B.append(x)
            
    return A, B, sumA, sumB, diffA, diffB

