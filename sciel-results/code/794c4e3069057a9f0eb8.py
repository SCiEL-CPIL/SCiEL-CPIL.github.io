import time
import numpy as np

def construct():
    n, m, p = 2, 2, 5
    rank = 18
    
    U = np.zeros((n*m, rank))
    V = np.zeros((m*p, rank))
    W = np.zeros((p*n, rank))
    
    # Strassen for 2x2x2
    # A: 2x2, B: 2x2, C: 2x2
    # M1 = (A00 + A11) * (B00 + B11)
    # M2 = (A10 + A11) * B00
    # M3 = A00 * (B01 - B11)
    # M4 = A11 * (B10 - B00)
    # M5 = (A00 + A01) * B11
    # M6 = (A10 - A00) * (B00 + B01)
    # M7 = (A01 - A11) * (B10 + B11)
    # C00 = M1 + M4 - M5 + M7
    # C01 = M3 + M5
    # C10 = M2 + M4
    # C11 = M1 - M2 + M3 + M6
    
    # We need to map this to the global U, V, W.
    # Global indices:
    # A: 0..3 (2x2)
    # B: 0..9 (2x5)
    # C: 0..9 (5x2)
    
    # B1 (cols 0,1): indices 0,1,5,6
    # B2 (cols 2,3): indices 2,3,7,8
    # B3 (col 4): indices 4,9
    
    # C1 (cols 0,1): indices 0,1,2,3 (C is 5x2, so C[k*n+i])
    # C[k, i] = k*2 + i
    # C1: k=0,1 -> c=0,1,2,3
    # C2: k=2,3 -> c=4,5,6,7
    # C3: k=4 -> c=8,9
    
    # Strassen 1 (for B1, C1)
    # M1
    U[0, 0] = 1; U[3, 0] = 1
    V[0, 0] = 1; V[1, 0] = 1; V[5, 0] = 1; V[6, 0] = 1
    W[0, 0] = 1; W[1, 0] = 1; W[2, 0] = 1; W[3, 0] = 1
    # M2
    U[2, 1] = 1; U[3, 1] = 1
    V[0, 1] = 1
    W[2, 1] = 1; W[3, 1] = 1
    # M3
    U[0, 2] = 1
    V[1, 2] = 1; V[6, 2] = -1
    W[1, 2] = 1; W[3, 2] = 1
    # M4
    U[3, 3] = 1
    V[5, 3] = 1; V[0, 3] = -1
    W[0, 3] = 1; W[2, 3] = 1
    # M5
    U[0, 4] = 1; U[1, 4] = 1
    V[6, 4] = 1
    W[0, 4] = -1; W[1, 4] = -1; W[2, 4] = -1; W[3, 4] = -1
    # M6
    U[2, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[1, 5] = 1
    W[3, 5] = 1
    # M7
    U[1, 6] = 1; U[3, 6] = -1
    V[5, 6] = 1; V[6, 6] = 1
    W[1, 6] = 1
    
    # Strassen 2 (for B2, C2)
    # B2 indices: 2,3,7,8
    # C2 indices: 4,5,6,7
    # M1
    U[0, 7] = 1; U[3, 7] = 1
    V[2, 7] = 1; V[3, 7] = 1; V[7, 7] = 1; V[8, 7] = 1
    W[4, 7] = 1; W[5, 7] = 1; W[6, 7] = 1; W[7, 7] = 1
    # M2
    U[2, 8] = 1; U[3, 8] = 1
    V[2, 8] = 1
    W[6, 8] = 1; W[7, 8] = 1
    # M3
    U[0, 9] = 1
    V[3, 9] = 1; V[8, 9] = -1
    W[5, 9] = 1; W[7, 9] = 1
    # M4
    U[3, 10] = 1
    V[7, 10] = 1; V[2, 10] = -1
    W[4, 10] = 1; W[6, 10] = 1
    # M5
    U[0, 11] = 1; U[1, 11] = 1
    V[8, 11] = 1
    W[4, 11] = -1; W[5, 11] = -1; W[6, 11] = -1; W[7, 11] = -1
    # M6
    U[2, 12] = 1; U[0, 12] = -1
    V[2, 12] = 1; V[3, 12] = 1
    W[7, 12] = 1
    # M7
    U[1, 13] = 1; U[3, 13] = -1
    V[7, 13] = 1; V[8, 13] = 1
    W[5, 13] = 1
    
    # Schoolbook for B3 (col 4), C3 (col 4)
    # B3 indices: 4,9
    # C3 indices: 8,9
    # C8 = A00 B4 + A01 B9
    # C9 = A10 B4 + A11 B9
    U[0, 14] = 1
    V[4, 14] = 1
    W[8, 14] = 1
    
    U[1, 15] = 1
    V[9, 15] = 1
    W[8, 15] = 1
    
    U[2, 16] = 1
    V[4, 16] = 1
    W[9, 16] = 1
    
    U[3, 17] = 1
    V[9, 17] = 1
    W[9, 17] = 1
    
    return {
        "U": U.tolist(),
        "V": V.tolist(),
        "W": W.tolist()
    }
