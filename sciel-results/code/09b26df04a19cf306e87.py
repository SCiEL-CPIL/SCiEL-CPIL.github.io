def _greedy_sidon_search(deadline):
    """
    Greedy search for a Sidon-like set (minimizing additive collisions).
    We maintain the set of active indices and the set of active sums.
    """
    best_h = np.zeros(N)
    best_score = 0.0
    
    np.random.seed(42)
    
    # Try multiple random starting orders or random subsets
    # Strategy: 
    # 1. Randomly shuffle indices.
    # 2. Greedily add index if it doesn't create a collision.
    # 3. Optimize weights on the resulting set.
    
    num_trials = 20
    
    for trial in range(num_trials):
        if time.time() > deadline - 10:
            break
            
        # Shuffle indices to randomize the greedy choice
        indices = np.random.permutation(N)
        
        active_indices = []
        active_sums = set()
        
        for idx in indices:
            # Check if adding idx creates a collision
            # New sums: idx + s for s in active_indices, and idx + idx
            # Existing sums: active_sums
            # Collision if (idx + s) in active_sums OR (idx + idx) in active_sums
            # Note: idx + s is the same as s + idx.
            # We must check against all existing sums.
            
            new_sums = set()
            for s in active_indices:
                new_sums.add(idx + s)
            new_sums.add(idx + idx)
            
            # Check for intersection
            if not new_sums.intersection(active_sums):
                # Safe to add
                active_indices.append(idx)
                active_sums.update(new_sums)
                
        if not active_indices:
            continue
            
        # We have a set of indices with unique pairwise sums (Sidon set property)
        # This guarantees that the autoconvolution of the indicator vector has peaks of height 1 (for distinct pairs) 
        # and potentially higher for self-sums if we count (i,i) and (j,j) separately?
        # Conv of indicator: 
        # C[k] = sum_i h[i] h[k-i].
        # If h is indicator of S:
        # C[i+j] gets contribution 1 from (i,j) if i!=j, and 1 from (j,i) if i!=j? 
        # No, conv is sum over all i. 
        # If h is binary:
        # C[k] = number of pairs (i, j) in S x S such that i+j=k.
        # If S is Sidon (unique sums for i<=j), then:
        # For i<j, sum i+j is unique. So C[i+j] gets 2 contributions: (i,j) and (j,i).
        # For i=j, sum 2i is unique. So C[2i] gets 1 contribution: (i,i).
        # So max_conv will be 2 (if there are distinct pairs) or 1 (if only one element).
        # This is the minimum possible peak for a set of size > 1!
        # (Uniform distribution of mass would spread it out, but here we are constrained to discrete indices).
        
        # Now, optimize weights on this set.
        # Since the support is "perfect" (min peak), we should just maximize ||h||_2^2 / ||h||_1.
        # For a fixed support, max ||h||_2^2 / ||h||_1 is achieved by concentrating mass.
        # But wait, the peak is fixed at 2 (for |S|>1) regardless of weights?
        # Let's check.
        # If h[i] = w_i.
        # C[k] = sum_{i+j=k} w_i w_j.
        # If sums are unique, each C[k] has only one term (or two symmetric terms).
        # Max C[k] is max( max_{i<j} 2 w_i w_j, max_i w_i^2 ).
        # We want to maximize (sum w_i^2) / (sum w_i * max_peak).
        # To minimize max_peak relative to sum w_i^2, we should balance weights?
        # If we set all w_i = 1, max_peak = 2 (from 2*1*1) or 1 (from 1^2). Max is 2.
        # Ratio = k / (k * 2) = 1/2.
        # If we set one w_i = 1, others 0. Max_peak = 1. Ratio = 1 / (1*1) = 1.
        # So sparsity helps!
        # But we found a large Sidon set. If we use only 1 element, score is 1.
        # If we use 2 elements i, j. Sums: 2i, i+j, 2j. All unique.
        # Weights w1, w2.
        # Conv peaks: w1^2, 2w1w2, w2^2.
        # Max peak M = max(w1^2, 2w1w2, w2^2).
        # Ratio = (w1^2 + w2^2) / ((w1+w2) * M).
        # Let w1=w2=1. M=2. Ratio = 2/(2*2) = 0.5.
        # Let w1=1, w2=epsilon. M ~ 1. Ratio ~ 1/(1) = 1.
        # So for small sets, we want to be sparse.
        # However, the current best score is 1.15. How is that possible?
        # The ratio is ||h||_2^2 / (||h||_1 ||h*h||_inf).
        # If h is dense and smooth, ||h*h||_inf is small relative to ||h||_1^2?
        # No, ||h*h||_inf <= ||h||_1^2.
        # So ratio >= ||h||_2^2 / ||h||_1^2.
        # For uniform h, ||h||_2^2 / ||h||_1^2 = 1/N.
        # But ||h*h||_inf is roughly ||h||_1^2 / N (if spread out).
        # So ratio ~ (1/N) / (1/N) = 1?
        # Actually, for a box function of width W, conv is triangle of width 2W.
        # L2^2 ~ W. L1 ~ W. Max Conv ~ W^2.
        # Ratio ~ W / (W * W^2) = 1/W^2. Small.
        
        # Wait, the task says "maximize the ratio".
        # Seed score is 1.0.
        # My sparse single point gives 1.0.
        # How did the seed get 1.0? Probably uniform or similar.
        # How did the current program get 1.15?
        # It uses "greedy_sidon_search" and optimizes weights.
        # Maybe the Sidon set logic in the current program is flawed or I am misinterpreting the gain.
        
        # Let's re-evaluate the ratio for a Sidon set with optimized weights.
        # If we pick a large Sidon set S, and set weights to be 1 for all, ratio is ~ 0.5.
        # If we set weights to be 1 for a subset, ratio increases towards 1.
        # So why would we want a large Sidon set?
        # Maybe to allow for a specific weight distribution that beats 1?
        
        # Let's look at the formula again.
        # R = ||h||_2^2 / (||h||_1 ||h*h||_inf).
        # By Cauchy-Schwarz, ||h||_1^2 <= N ||h||_2^2. So ||h||_2^2 / ||h||_1^2 >= 1/N.
        # Also ||h*h||_inf <= ||h||_1^2.
        # So R >= (1/N) / ||h||_1^2 * ||h||_1^2 ? No.
        # R = (||h||_2^2 / ||h||_1^2) * (||h||_1 / ||h*h||_inf).
        # Let A = ||h||_2^2 / ||h||_1^2 (between 1/N and 1).
        # Let B = ||h||_1 / ||h*h||_inf.
        # Since ||h*h||_inf >= ||h||_1^2 / N (by pigeonhole on sums? No, sums range is 2N).
        # Actually, sum of all conv values is ||h||_1^2.
        # There are 2N-1 values. So max >= ||h||_1^2 / (2N-1).
        # So B <= (2N-1).
        # So R <= A * (2N-1).
        # If A=1 (delta function), R <= 2N-1?
        # For delta, ||h||_2^2=1, ||h||_1=1, ||h*h||_inf=1. R=1.
        # Why the bound is loose?
        # Because for delta, ||h*h||_inf = 1, not ||h||_1^2/(2N-1).
        
        # To get R > 1, we need A * B > 1.
        # Since A <= 1, we need B > 1.
        # B = ||h||_1 / ||h*h||_inf.
        # This requires ||h*h||_inf < ||h||_1.
        # This means the peak of the autoconvolution must be smaller than the total mass.
        # This is possible if the mass is spread out enough that no single sum dominates.
        # For a uniform vector h=1/N, ||h||_1=1.
        # Conv is triangle. Max is 1/N.
        # So B = 1 / (1/N) = N.
        # A = (N*(1/N^2)) / 1^2 = 1/N.
        # R = (1/N) * N = 1.
        
        # So uniform gives 1.
        # To get > 1, we need to increase A (make spikier) while keeping B high (keeping conv peak low).
        # This is a trade-off.
        # Sidon sets minimize the number of collisions, which helps keep conv peaks low for a given support size.
        # But they also force the support to be sparse?
        
        # Let's try to optimize weights on the Sidon set found.
        h_curr = np.zeros(N)
        h_curr[active_indices] = 1.0
        
        # Optimize weights
        # Minimize -log(R)
        # R = sum(w^2) / (sum(w) * max(conv))
        
        def _neg_ratio_smooth(params, beta=50.0):
            w_local = np.exp(params)
            # Normalize to sum=1 to fix scale invariance
            w_local = w_local / np.sum(w_local)
            
            h_local = np.zeros(N)
            h_local[active_indices] = w_local
            
            l2_sq = np.sum(h_local**2)
            conv = np.convolve(h_local, h_local, mode='full')
            
            m = np.max(conv)
            if m < 0: m = 0
            smooth_max = m + np.log(np.sum(np.exp(beta * (conv - m)))) / beta
            
            if smooth_max < 1e-15:
                return 0.0
            return -l2_sq / smooth_max

        # Initial guess: uniform
        w_init = np.ones(len(active_indices))
        x0 = np.log(w_init)
        
        try:
            res = minimize(
                _neg_ratio_smooth,
                x0,
                args=(50.0,),
                method='L-BFGS-B',
                options={'maxiter': 200, 'ftol': 1e-10}
            )
            w_res = np.exp(res.x)
            w_res = w_res / np.sum(w_res)
            
            h_res = np.zeros(N)
            h_res[active_indices] = w_res
            
            score = _exact_ratio(h_res)
            if score > best_score:
                best_score = score
                best_h = h_res.copy()
                
        except Exception:
            pass

    return best_h, best_score

def construct():
    start_time = time.time()
    deadline = start_time + 140 # Safety margin
    
    best_h, best_score = _greedy_sidon_search(deadline)
    
    # Fallback
    if best_score < 1.0:
        h_fallback = np.ones(N) / N
        score_fallback = _exact_ratio(h_fallback)
        if score_fallback > best_score:
            best_h = h_fallback
            best_score = score_fallback
            
    best_h = np.maximum(best_h, 0)
    return best_h.tolist()
