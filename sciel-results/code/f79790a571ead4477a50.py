"""Matrix multiplication 3x3x4 tensor decomposition, rank 34."""
DIMENSIONS = [3, 3, 4]

def construct():
    n, m, p = DIMENSIONS  # n=3, m=3, p=4
    rank = 34
    U = [[0] * rank for _ in range(n * m)]  # 9 x 34
    V = [[0] * rank for _ in range(m * p)]  # 12 x 34
    W = [[0] * rank for _ in range(p * n)]  # 12 x 34

    col = 0

    def add_term(u_entries, v_entries, w_entries):
        nonlocal col
        for idx, val in u_entries:
            U[idx][col] += val
        for idx, val in v_entries:
            V[idx][col] += val
        for idx, val in w_entries:
            W[idx][col] += val
        col += 1

    # A (3x3): U index = i*m + j = i*3 + j
    #   i=0,j=0 -> 0; i=0,j=1 -> 1; i=0,j=2 -> 2
    #   i=1,j=0 -> 3; i=1,j=1 -> 4; i=1,j=2 -> 5
    #   i=2,j=0 -> 6; i=2,j=1 -> 7; i=2,j=2 -> 8
    #
    # B (3x4): V index = j*p + k = j*4 + k
    #   j=0: k=0->0, k=1->1, k=2->2, k=3->3
    #   j=1: k=0->4, k=1->5, k=2->6, k=3->7
    #   j=2: k=0->8, k=1->9, k=2->10, k=3->11
    #
    # C (3x4): W index = k*n + i = k*3 + i
    #   k=0: i=0->0, i=1->1, i=2->2
    #   k=1: i=0->3, i=1->4, i=2->5
    #   k=2: i=0->6, i=1->7, i=2->8
    #   k=3: i=0->9, i=1->10, i=2->11

    # Partition:
    # A top 2 rows: i in {0,1}, all j in {0,1,2}
    # A bottom 1 row: i=2, all j in {0,1,2}
    # B left 2 cols: k in {0,1}, all j in {0,1,2}
    # B right 2 cols: k in {2,3}, all j in {0,1,2}

    # --- Strassen for A[0:2,:2] * B[0:2,0:2] -> C[0:2,0:2] (7 terms) ---
    # A11 = A[0:2,0:2]: U indices 0,1,3,4
    # B11 = B[0:2,0:2]: V indices 0,1,4,5
    # C11 = C[0:2,0:2]: W indices 0,3,1,4

    # P1 = (A00+A11)*(B00+B11) -> C00 += P1, C11 += P1
    add_term([(0, 1), (4, 1)], [(0, 1), (5, 1)], [(0, 1), (4, 1)])
    # P2 = (A10+A11)*B00 -> C10 += P2, C11 -= P2
    add_term([(3, 1), (4, 1)], [(0, 1)], [(1, 1), (4, -1)])
    # P3 = A00*(B10-B00) -> C01 += P3, C11 += P3
    add_term([(0, 1)], [(4, 1), (0, -1)], [(3, 1), (4, 1)])
    # P4 = A11*(B11-B01) -> C00 += P4, C01 += P4
    add_term([(4, 1)], [(5, 1), (1, -1)], [(0, 1), (3, 1)])
    # P5 = (A00+A01)*B11 -> C00 -= P5, C01 += P5
    add_term([(0, 1), (1, 1)], [(5, 1)], [(0, -1), (3, 1)])
    # P6 = (A10-A00)*(B00+B01) -> C10 += P6
    add_term([(3, 1), (0, -1)], [(0, 1), (1, 1)], [(1, 1)])
    # P7 = (A01-A11)*(B01+B11) -> C00 += P7
    add_term([(1, 1), (4, -1)], [(1, 1), (5, 1)], [(0, 1)])

    # --- A[0:2,2] * B[2,0:2] -> C[0:2,0:2] (4 terms) ---
    # A[0,2]=U[2], A[1,2]=U[5]
    # B[2,0]=V[8], B[2,1]=V[9]
    # C[0,0]=W[0], C[0,1]=W[3], C[1,0]=W[1], C[1,1]=W[4]
    add_term([(2, 1)], [(8, 1)], [(0, 1)])   # A02*B20 -> C00
    add_term([(2, 1)], [(9, 1)], [(3, 1)])   # A02*B21 -> C01
    add_term([(5, 1)], [(8, 1)], [(1, 1)])   # A12*B20 -> C10
    add_term([(5, 1)], [(9, 1)], [(4, 1)])   # A12*B21 -> C11

    # --- A[2,0:2] * B[0:2,0:2] -> C[2,0:2] (4 terms) ---
    # A[2,0]=U[6], A[2,1]=U[7]
    # B[0,0]=V[0], B[0,1]=V[1], B[1,0]=V[4], B[1,1]=V[5]
    # C[2,0]=W[2], C[2,1]=W[5]
    add_term([(6, 1)], [(0, 1)], [(2, 1)])   # A20*B00 -> C20
    add_term([(6, 1)], [(1, 1)], [(5, 1)])   # A20*B01 -> C21
    add_term([(7, 1)], [(4, 1)], [(2, 1)])   # A21*B10 -> C20
    add_term([(7, 1)], [(5, 1)], [(5, 1)])   # A21*B11 -> C21

    # --- A[2,2] * B[2,0:2] -> C[2,0:2] (2 terms) ---
    add_term([(8, 1)], [(8, 1)], [(2, 1)])   # A22*B20 -> C20
    add_term([(8, 1)], [(9, 1)], [(5, 1)])   # A22*B21 -> C21

    # --- Strassen for A[0:2,:2] * B[0:2,2:4] -> C[0:2,2:4] (7 terms) ---
    # A11 = A[0:2,0:2]: U indices 0,1,3,4
    # B12 = B[0:2,2:4]: V indices 2,3,6,7
    # C12 = C[0:2,2:4]: W indices 6,9,7,10

    # P1 = (A00+A11)*(B02+B13) -> C02 += P1, C13 += P1
    add_term([(0, 1), (4, 1)], [(2, 1), (7, 1)], [(6, 1), (10, 1)])
    # P2 = (A10+A11)*B02 -> C12 += P2, C13 -= P2
    add_term([(3, 1), (4, 1)], [(2, 1)], [(7, 1), (10, -1)])
    # P3 = A00*(B12-B02) -> C03 += P3, C13 += P3
    add_term([(0, 1)], [(6, 1), (2, -1)], [(9, 1), (10, 1)])
    # P4 = A11*(B13-B03) -> C02 += P4, C03 += P4
    add_term([(4, 1)], [(7, 1), (3, -1)], [(6, 1), (9, 1)])
    # P5 = (A00+A01)*B13 -> C02 -= P5, C03 += P5
    add_term([(0, 1), (1, 1)], [(7, 1)], [(6, -1), (9, 1)])
    # P6 = (A10-A00)*(B02+B03) -> C12 += P6
    add_term([(3, 1), (0, -1)], [(2, 1), (3, 1)], [(7, 1)])
    # P7 = (A01-A11)*(B03+B13) -> C02 += P7
    add_term([(1, 1), (4, -1)], [(3, 1), (7, 1)], [(6, 1)])

    # --- A[0:2,2] * B[2,2:4] -> C[0:2,2:4] (4 terms) ---
    add_term([(2, 1)], [(10, 1)], [(6, 1)])  # A02*B22 -> C02
    add_term([(2, 1)], [(11, 1)], [(9, 1)])  # A02*B23 -> C03
    add_term([(5, 1)], [(10, 1)], [(7, 1)])  # A12*B22 -> C12
    add_term([(5, 1)], [(11, 1)], [(10, 1)]) # A12*B23 -> C13

    # --- A[2,0:2] * B[0:2,2:4] -> C[2,2:4] (4 terms) ---
    add_term([(6, 1)], [(2, 1)], [(8, 1)])   # A20*B02 -> C22
    add_term([(6, 1)], [(3, 1)], [(11, 1)])  # A20*B03 -> C23
    add_term([(7, 1)], [(6, 1)], [(8, 1)])   # A21*B12 -> C22
    add_term([(7, 1)], [(7, 1)], [(11, 1)])  # A21*B13 -> C23

    # --- A[2,2] * B[2,2:4] -> C[2,2:4] (2 terms) ---
    add_term([(8, 1)], [(10, 1)], [(8, 1)])  # A22*B22 -> C22
    add_term([(8, 1)], [(11, 1)], [(11, 1)]) # A22*B23 -> C23

    assert col == rank, f"Expected {rank} terms, got {col}"
    return {"U": U, "V": V, "W": W}
