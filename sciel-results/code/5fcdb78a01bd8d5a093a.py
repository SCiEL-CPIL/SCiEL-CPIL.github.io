import time
import numpy as np

DIMENSIONS = [3, 5, 6]

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = start_time + 110

    n, m, p = DIMENSIONS  # 3, 5, 6

    def schoolbook():
        rank = n * m * p
        U = [[0] * rank for _ in range(n * m)]
        V = [[0] * rank for _ in range(m * p)]
        W = [[0] * rank for _ in range(p * n)]
        col = 0
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    U[i * m + j][col] = 1
                    V[j * p + k][col] = 1
                    W[k * n + i][col] = 1
                    col += 1
        return {"U": U, "V": V, "W": W}

    def verify_numpy(U, V, W, rank):
        U_arr = np.array(U, dtype=float)
        V_arr = np.array(V, dtype=float)
        W_arr = np.array(W, dtype=float)
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    val = np.dot(U_arr[i*m+j], V_arr[j*p+k] * W_arr[k*n+i])
                    if abs(val - 1.0) > 1e-9:
                        return False
        return True

    def get_strassen_terms():
        # Same as seed
        terms = []
        u1 = {(0,0): 1, (1,1): 1}
        v1 = {(0,0): 1, (1,1): 1}
        w1 = {(0,0): 1, (1,1): 1}
        terms.append((u1, v1, w1))
        u2 = {(1,0): 1, (1,1): 1}
        v2 = {(0,0): 1}
        w2 = {(0,1): 1, (1,1): -1}
        terms.append((u2, v2, w2))
        u3 = {(0,0): 1}
        v3 = {(0,1): 1, (1,1): -1}
        w3 = {(1,0): 1, (1,1): 1}
        terms.append((u3, v3, w3))
        u4 = {(1,1): 1}
        v4 = {(1,0): 1, (0,0): -1}
        w4 = {(0,0): 1, (0,1): 1}
        terms.append((u4, v4, w4))
        u5 = {(0,0): 1, (0,1): 1}
        v5 = {(1,1): 1}
        w5 = {(0,0): -1, (1,0): 1}
        terms.append((u5, v5, w5))
        u6 = {(1,0): 1, (0,0): -1}
        v6 = {(0,0): 1, (0,1): 1}
        w6 = {(1,1): 1}
        terms.append((u6, v6, w6))
        u7 = {(0,1): 1, (1,1): -1}
        v7 = {(1,0): 1, (1,1): 1}
        w7 = {(0,0): 1}
        terms.append((u7, v7, w7))
        return terms

    def build_decomposition(i_groups, j_groups, k_groups, strassen_terms):
        # Same as seed
        total_rank = 0
        block_info = []
        for ig in i_groups:
            for jg in j_groups:
                for kg in k_groups:
                    si, sj, sk = len(ig), len(jg), len(kg)
                    if si == 2 and sj == 2 and sk == 2:
                        r = 7
                    else:
                        r = si * sj * sk
                    total_rank += r
                    block_info.append((ig, jg, kg, r))
        
        U = [[0] * total_rank for _ in range(n * m)]
        V = [[0] * total_rank for _ in range(m * p)]
        W = [[0] * total_rank for _ in range(p * n)]
        
        col = 0
        for ig, jg, kg, r in block_info:
            si, sj, sk = len(ig), len(jg), len(kg)
            if si == 2 and sj == 2 and sk == 2:
                for (u_pat, v_pat, w_pat) in strassen_terms:
                    for (li, lj), val_u in u_pat.items():
                        gi, gj = ig[li], jg[lj]
                        U[gi * m + gj][col] = val_u
                    for (lj, lk), val_v in v_pat.items():
                        gj, gk = jg[lj], kg[lk]
                        V[gj * p + gk][col] = val_v
                    for (lk, li), val_w in w_pat.items():
                        gk, gi = kg[lk], ig[li]
                        W[gk * n + gi][col] = val_w
                    col += 1
            else:
                for li in range(si):
                    for lj in range(sj):
                        for lk in range(sk):
                            gi, gj, gk = ig[li], jg[lj], kg[lk]
                            U[gi * m + gj][col] = 1
                            V[gj * p + gk][col] = 1
                            W[gk * n + gi][col] = 1
                            col += 1
        if col != total_rank:
            return None, None
        result = {"U": U, "V": V, "W": W}
        return result, total_rank

    def try_rank_reduction():
        if time.time() > deadline:
            return None, None
        strassen_terms = get_strassen_terms()
        strategies = []
        strategies.append({
            'name': 's1',
            'i_groups': [[0, 1], [2]],
            'j_groups': [[0, 1], [2, 3], [4]],
            'k_groups': [[0, 1], [2, 3], [4, 5]]
        })
        best_result = None
        best_rank = float('inf')
        for strat in strategies:
            if time.time() > deadline:
                break
            result, rank = build_decomposition(
                strat['i_groups'], strat['j_groups'], strat['k_groups'], strassen_terms
            )
            if result is None:
                continue
            if verify_numpy(result['U'], result['V'], result['W'], rank):
                if rank < best_rank:
                    best_rank = rank
                    best_result = result
        if best_result is not None:
            return best_result, best_rank
        return None, None

    # New Strategy: Rank 78 using 3x3x3 (23) and 3x2x3 (16)
    def try_rank_78():
        if time.time() > deadline:
            return None, None
        
        # Placeholder for Rank 23 3x3x3 and Rank 16 3x2x3
        # If not available, return None
        return None, None

    best_result = schoolbook()
    best_rank = n * m * p

    improved, improved_rank = try_rank_reduction()
    if improved is not None and improved_rank < best_rank:
        best_result = improved
        best_rank = improved_rank

    improved78, rank78 = try_rank_78()
    if improved78 is not None and rank78 < best_rank:
        best_result = improved78
        best_rank = rank78

    return best_result
# EVOLVE-BLOCK-END
