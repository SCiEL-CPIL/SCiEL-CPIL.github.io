def _check_collision(sumsets, new_sums):
    """
    Check if adding new_sums to sumsets causes any collision between different cardinalities.
    sumsets: list of sets, sumsets[c] contains sums for cardinality c before adding new element.
    new_sums: list of sets, new_sums[c] contains sums for cardinality c added by the new element.
    Returns True if valid (no collisions), False otherwise.
    """
    # We need to check if any sum in new_sums[c] is in sumsets[j] or new_sums[j] for j != c
    # And if any sum in new_sums[c] is in new_sums[d] for d != c? 
    # Actually, new_sums are generated from disjoint cardinalities of the previous state, 
    # but they might collide with each other? 
    # No, new_sums[c] comes from sumsets[c-1]. 
    # If sumsets was valid, sumsets[c-1] and sumsets[d-1] are disjoint for c-1 != d-1.
    # So new_sums[c] and new_sums[d] are disjoint if c != d? 
    # Not necessarily. If s1 in sumsets[c-1] and s2 in sumsets[d-1] are distinct, s1+x and s2+x are distinct.
    # So new_sums[c] and new_sums[d] are disjoint for c != d.
    
    # We only need to check if new_sums[c] intersects with existing sumsets[j] for j != c.
    # And also if new_sums[c] intersects with new_sums[j] for j != c? 
    # As argued, they don't.
    
    # Wait, what about new_sums[c] intersecting with new_sums[c]? No, it's a set.
    
    # So check: for each c, for each s in new_sums[c], is s in any sumsets[j] (j != c)?
    # Note: sumsets[c] itself might contain s? 
    # s is in new_sums[c]. s = old_s + x.
    # If s was already in sumsets[c], that's fine (repeated sums within same cardinality are allowed).
    # But if s is in sumsets[j] for j != c, that's a collision.
    
    for c in range(len(sumsets)):
        if not new_sums[c]:
            continue
        for s in new_sums[c]:
            for j in range(len(sumsets)):
                if j == c:
                    continue
                if s in sumsets[j]:
                    return False
    return True

def _is_valid_set(elements):
    """Check if a set of elements satisfies the cardinality-separated subset sum property."""
    if not elements:
        return True
    n = len(elements)
    sumsets = [set() for _ in range(n + 1)]
    sumsets[0] = {0}
    
    for x in elements:
        new_sums = [set() for _ in range(n + 1)]
        # Calculate new sums generated by x
        for c in range(n, 0, -1):
            if sumsets[c - 1]:
                for s in sumsets[c - 1]:
                    new_sums[c].add(s + x)
        
        # Check collisions
        if not _check_collision(sumsets, new_sums):
            return False
            
        # Update sumsets
        for c in range(n + 1):
            sumsets[c] = sumsets[c] | new_sums[c]
            
    return True

def _greedy_construct():
    """
    Greedily construct a valid set.
    """
    current = []
    for x in range(1, 257):
        candidate = current + [x]
        if _is_valid_set(candidate):
            current = candidate
    return current

def _backtrack_search(target_size, time_limit=50):
    """
    Attempt to find a valid set of size target_size using backtracking.
    Uses randomized restarts and heuristics.
    """
    start_time = time.time()
    
    # Heuristic: Start with a subset of the greedy solution or random small numbers
    # To make it faster, we can fix the first few elements from the greedy solution
    # and backtrack on the rest.
    
    greedy_set = _greedy_construct()
    if len(greedy_set) >= target_size:
        return greedy_set[:target_size]
        
    # If greedy didn't reach target, we need to search.
    # We will try to build a set of size target_size.
    
    # Candidate pool: 1..256
    # To reduce search space, we can prioritize smaller numbers (denser packing) 
    # or numbers that are "safe".
    
    # Strategy: Randomized Hill Climbing / Backtracking hybrid
    # 1. Start with a random valid set of size ~target_size/2
    # 2. Try to add elements
    # 3. If stuck, backtrack or restart
    
    # Given the complexity, a pure backtracking over 256 choose K is too slow.
    # We will use a "Guided" backtracking.
    
    # Let's try to find ANY set of size target_size.
    # We'll use a recursive search with pruning.
    # To avoid deep recursion limits and timeouts, we limit the depth of exploration per branch.
    
    best_set = []
    
    def search(current_set, current_sumsets, candidates, depth):
        nonlocal best_set, start_time
        
        if time.time() - start_time > time_limit:
            return
        
        if len(current_set) == target_size:
            if len(current_set) > len(best_set):
                best_set = current_set[:]
            return
        
        # Pruning: If even with the largest possible remaining sums we can't reach target?
        # Not helpful for validity.
        
        # Heuristic: Try candidates in a specific order.
        # Randomize the candidate list for diversification?
        # Or use a fixed order but skip invalid ones quickly.
        
        for i, x in enumerate(candidates):
            # Forward checking
            new_sums = [set() for _ in range(len(current_sumsets) + 1)]
            # Note: current_sumsets has size len(current_set)+1
            # new element increases max cardinality by 1
            max_c = len(current_set) + 1
            for c in range(max_c, 0, -1):
                if c - 1 < len(current_sumsets) and current_sumsets[c - 1]:
                    for s in current_sumsets[c - 1]:
                        new_sums[c].add(s + x)
            
            # Check collision
            # We need to check new_sums against current_sumsets
            # Note: new_sums[c] for c > len(current_sumsets) is just new_sums[c]
            # current_sumsets is shorter.
            
            valid = True
            for c in range(1, max_c + 1):
                if not new_sums[c]:
                    continue
                for s in new_sums[c]:
                    # Check against all existing cardinalities j != c
                    # j can be from 0 to len(current_sumsets)
                    for j in range(len(current_sumsets)):
                        if j == c:
                            continue
                        if s in current_sumsets[j]:
                            valid = False
                            break
                    if not valid:
                        break
                if not valid:
                    break
            
            if not valid:
                continue
            
            # Also check if new_sums[c] collides with new_sums[d] for d != c?
            # As established, they are disjoint if current_sumsets were disjoint.
            
            # Update sumsets for recursion
            new_sumsets = [set() for _ in range(max_c + 1)]
            for c in range(max_c + 1):
                # Copy existing
                if c < len(current_sumsets):
                    new_sumsets[c] = current_sumsets[c].copy()
                # Add new
                if c < len(new_sums):
                    new_sumsets[c] = new_sumsets[c] | new_sums[c]
            
            # Recursive call
            # To avoid modifying candidates list in place, we pass a slice
            # This is O(N) copy, which is fine for N=256
            remaining_candidates = candidates[i+1:]
            
            search(current_set + [x], new_sumsets, remaining_candidates, depth + 1)
            
            # Early exit if we found a solution
            if best_set:
                return
            
    # Initial state
    init_sumsets = [set() for _ in range(1)]
    init_sumsets[0] = {0}
    
    # To improve success rate, we can try multiple random orderings of candidates
    # or fix a prefix.
    
    # Let's try a few random restarts
    for _ in range(100): # Max restarts
        if time.time() - start_time > time_limit:
            break
            
        # Randomly shuffle candidates? 
        # Or use a heuristic order: smaller numbers first?
        # Smaller numbers are more likely to collide, but allow more elements.
        # Let's try sorting by value.
        candidates = list(range(1, 257))
        random.shuffle(candidates)
        
        search([], init_sumsets, candidates, 0)
        
        if best_set:
            return best_set
    return best_set

def construct():
    """
    Construct a set of distinct integers in 1..256 maximizing size such that
    no two subsets of different cardinalities have the same sum.
    """
    # 1. Get a baseline
    baseline = _greedy_construct()
    best_size = len(baseline)
    best_set = baseline
    
    # 2. Try to improve using backtracking
    # Try target sizes larger than baseline
    # We know max possible is bounded by sum constraints.
    # Max sum 256*255/2 is huge, but cardinality is limited.
    # Let's try up to best_size + 2
    
    for target in range(best_size + 1, best_size + 3):
        # Limit time per target
        start_t = time.time()
        found = _backtrack_search(target, time_limit=20)
        if found and len(found) == target:
            best_set = found
            best_size = target
            # If we found a larger set, we can stop or try to go higher
            # Given time constraints, we might just return this if it's significantly better
            # Or continue to see if we can get even larger.
            # Let's break if we used too much time
            if time.time() - start_t > 40:
                break
    
    # Ensure result is list of ints
    return [int(x) for x in best_set]

