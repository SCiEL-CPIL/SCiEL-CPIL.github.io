"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import scipy
N = 38

# EVOLVE-BLOCK-START
import numpy as np
import time
import sys

def _generate_fcc_fragment(n_atoms):
    """
    Generate an FCC lattice fragment of n_atoms atoms centered at the origin.
    This approximates the known global minimum topology for LJ38.
    """
    # Generate a sufficiently large FCC lattice
    # FCC lattice vectors: (0,0,0), (0,0.5,0.5), (0.5,0,0.5), (0.5,0.5,0) * a
    # For simplicity, generate cubic grid and filter, or use explicit vectors.
    # Let's generate a cubic grid of points and keep those that form FCC.
    # Actually, it's easier to generate all FCC lattice points within a radius.
    
    # FCC lattice points can be generated by:
    # i, j, k integers
    # (i, j, k) where i+j+k is even
    # scaled by 1/sqrt(2) to get nearest neighbor distance 1?
    # Standard FCC: nearest neighbors are at distance a/sqrt(2).
    # Let's work in reduced units where sigma=1.
    # The potential minimum is at r = 2^(1/6) sigma.
    # The FCC lattice constant a is such that a/sqrt(2) = 2^(1/6).
    # So a = sqrt(2) * 2^(1/6) = 2^(1/2 + 1/6) = 2^(2/3).
    
    a = 2.0 ** (2.0 / 3.0)
    
    points = []
    # Search radius: enough to get N atoms.
    # For N=38, radius ~ 2-3 lattice constants is plenty.
    max_range = 5
    for i in range(-max_range, max_range + 1):
        for j in range(-max_range, max_range + 1):
            for k in range(-max_range, max_range + 1):
                # FCC condition: i+j+k is even
                if (i + j + k) % 2 == 0:
                    x = i * a
                    y = j * a
                    z = k * a
                    r2 = x*x + y*y + z*z
                    points.append((r2, np.array([x, y, z])))
    
    # Sort by distance from origin
    points.sort(key=lambda x: x[0])
    
    # Take the first N points
    selected = [p[1] for p in points[:n_atoms]]
    
    # Center the cluster
    coords = np.array(selected)
    center = np.mean(coords, axis=0)
    coords = coords - center
    
    return coords

def _lj_energy(pos):
    """Calculate Lennard-Jones energy for a set of positions."""
    # pos shape (N, 3)
    # Compute pairwise distances
    # To avoid sqrt, we can work with r^2 and r^6
    diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    r2 = np.sum(diff * diff, axis=2)
    
    # Mask diagonal (r=0)
    np.fill_diagonal(r2, 1.0) # Avoid division by zero
    
    r6 = r2 ** 3
    r12 = r6 ** 2
    
    # Energy per pair: 4 * (r^-12 - r^-6)
    # Sum over all i < j
    # The matrix r12/r6 includes both (i,j) and (j,i), so we divide by 2
    energy = 4.0 * np.sum(1.0/r12 - 1.0/r6) / 2.0
    
    return energy

def construct():
    start_time = time.time()
    deadline = start_time + 140.0 # 10s safety margin
    
    # 1. Generate FCC fragment
    pos = _generate_fcc_fragment(N)
    
    # 2. Relax using L-BFGS-B
    # Define objective function for optimizer
    def objective(x):
        return _lj_energy(x.reshape(-1, 3))
    
    # Define gradient (optional but helps L-BFGS)
    def gradient(x):
        pos = x.reshape(-1, 3)
        diff = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
        r2 = np.sum(diff * diff, axis=2)
        np.fill_diagonal(r2, 1.0)
        
        r = np.sqrt(r2)
        # dU/dr = 4 * (-12 r^-13 + 6 r^-7)
        # grad = sum_j dU/dr * (r_i - r_j)/r
        # Vectorized:
        # factor[i,j] = 4 * (-12/r^13 + 6/r^7) = 4 * (-12/r^13 + 6/r^7)
        # Let's compute dE/dr2 for efficiency?
        # E = 4 * (r^-12 - r^-6)
        # dE/dr2 = dE/dr * dr/dr2 = dE/dr * (1/(2r))
        # dE/dr = 4 * (-12 r^-13 + 6 r^-7)
        # dE/dr2 = 4 * (-12 r^-14 + 6 r^-8) / 2 = 2 * (-12 r^-14 + 6 r^-8)
        # = -24 r^-14 + 12 r^-8
        
        # r8 = r2^4, r14 = r2^7
        r8 = r2 ** 4
        r14 = r2 ** 7
        
        # Factor for each pair (i,j)
        # grad_i = sum_j (dE/dr2) * (r_i - r_j)
        # Note: The matrix is symmetric.
        # Let M[i,j] = -24 * r2[i,j]^-7 + 12 * r2[i,j]^-4
        M = -24.0 * (1.0 / r14) + 12.0 * (1.0 / r8)
        
        # grad = M @ diff
        # diff[i,j] = r_i - r_j
        grad_flat = (M @ diff).reshape(-1)
        
        return grad_flat

    try:
        res = scipy.optimize.minimize(
            objective,
            pos.flatten(),
            method='L-BFGS-B',
            jac=gradient,
            options={'maxiter': 100, 'ftol': 1e-12, 'gtol': 1e-12}
        )
        pos = res.x.reshape(-1, 3)
    except Exception:
        # If relaxation fails, return the FCC fragment as is
        pass
    
    # Check deadline
    if time.time() > deadline:
        return pos

    return pos

# EVOLVE-BLOCK-END
