"""
Program to find a rank-minimal exact tensor decomposition for matrix multiplication 2x5 by 5x6.
Returns the schoolbook decomposition which has rank 60.
"""

def construct():
    n, m, p = 2, 5, 6
    rank = n * m * p
    
    # Initialize U, V, W with zeros
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
