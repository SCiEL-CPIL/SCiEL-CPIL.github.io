# EVOLVE-BLOCK-START
def pack(boxes, container):
    """
    3D Bin Packing using Extreme Points heuristic.
    This approach maintains a set of candidate positions (extreme points) for each bin.
    A position is an extreme point if it is a valid location to place a box (no overlap)
    and it is "supported" by the floor or other boxes.
    """
    W, H, D = container
    container_volume = W * H * D
    
    # Sort boxes by volume descending, then by max dimension descending
    # This helps place large blocks early which defines the structure
    sorted_indices = sorted(range(len(boxes)), key=lambda i: (boxes[i][0]*boxes[i][1]*boxes[i][2], max(boxes[i])), reverse=True)
    
    # Each bin stores a list of placed boxes: (x, y, z, w, h, d)
    # And a set of extreme points (x, y, z)
    # Extreme points are candidates for the next box's bottom-left-front corner.
    # Initially, (0,0,0) is the only extreme point.
    # When a box is placed at (x,y,z) with size (w,h,d), we generate new extreme points:
    # - (x+w, y, z) : right face
    # - (x, y+h, z) : front face
    # - (x, y, z+d) : top face
    # We also need to ensure we don't keep points that are "covered" by new boxes.
    
    bins = []
    # bin_data: list of dicts or tuples? Let's use list of (box_list, extreme_points_set)
    # Actually, storing extreme points as a list of tuples and filtering is easier to manage than a set if we want to keep it sorted or unique.
    # A set is better for O(1) lookups, but we need to remove covered points.
    
    def is_valid_pos(bin_boxes, x, y, z, w, h, d):
        if x < 0 or y < 0 or z < 0:
            return False
        if x + w > W or y + h > H or z + d > D:
            return False
        for (bx, by, bz, bw, bh, bd) in bin_boxes:
            # Check overlap
            if not (x + w <= bx or bx + bw <= x or
                    y + h <= by or by + bh <= y or
                    z + d <= bz or bz + bd <= z):
                return False
        return True

    def generate_new_extreme_points(bin_boxes, x, y, z, w, h, d, current_eps):
        """
        Generate new extreme points after placing a box at (x,y,z) with size (w,h,d).
        Returns a new set of extreme points.
        """
        new_candidates = set()
        
        # Points generated by the new box
        new_candidates.add((x + w, y, z))
        new_candidates.add((x, y + h, z))
        new_candidates.add((x, y, z + d))
        
        # We should also consider points that were extreme but might now be "blocked" or "covered"?
        # Actually, the standard algorithm adds these 3 points.
        # However, sometimes we need to add points like (x+w, y+h, z) if there's a gap?
        # The "Extreme Point" definition usually requires that the point is on the boundary of the union of boxes.
        # Let's stick to the 3 face points first. If packing is poor, we might need to add corners.
        # For now, let's add the 3 face points.
        
        # Filter existing extreme points:
        # An extreme point (px, py, pz) is no longer valid if it is strictly inside the new box?
        # No, extreme points are for *placing* boxes. If a point is inside the new box, it's no longer a valid empty spot.
        # Also, if a point is "covered" by the new box in the sense that it's no longer on the "skyline", it might be redundant but not invalid.
        # However, if a point (px, py, pz) is such that the new box covers the space immediately below it?
        # Simplest heuristic: Keep all existing points that are not inside the new box.
        # Add the new candidates.
        
        # Optimization: Remove points that are "dominated"?
        # A point P1 dominates P2 if P1 <= P2 in all coords and P1 != P2? No, that's for minimization.
        # In packing, lower z is better. So if we have (0,0,0) and (0,0,5), (0,0,0) is better if both are valid.
        # But we keep all valid candidates and pick the best one at selection time.
        
        # Let's just union the sets and filter out invalid ones (inside existing boxes).
        
        all_points = set(current_eps)
        all_points.update(new_candidates)
        
        # Filter: Remove any point that is strictly inside any box in bin_boxes (including the new one)
        # Note: A point on the surface is valid.
        # Point (px, py, pz) is inside box (bx, by, bz, bw, bh, bd) if:
        # bx <= px < bx+bw and by <= py < by+bh and bz <= pz < bz+bd
        # If it's on the boundary (e.g., px == bx+bw), it's outside (to the right).
        
        final_eps = set()
        for p in all_points:
            px, py, pz = p
            inside = False
            for (bx, by, bz, bw, bh, bd) in bin_boxes:
                if (bx <= px < bx + bw) and (by <= py < by + bh) and (bz <= pz < bz + bd):
                    inside = True
                    break
            if not inside:
                # Also check bounds
                if 0 <= px <= W and 0 <= py <= H and 0 <= pz <= D:
                    final_eps.add(p)
                    
        return final_eps

    placements = [None] * len(boxes)
    bin_count = 0
    
    for idx in sorted_indices:
        w, h, d = boxes[idx]
        placed = False
        
        best_bin_index = -1
        best_pos = None
        best_score = None
        
        for b_idx in range(bin_count):
            bin_boxes = bins[b_idx][0]
            eps = bins[b_idx][1]
            
            # Find best extreme point in this bin
            bin_best_pos = None
            bin_best_score = None
            
            for (x, y, z) in eps:
                if is_valid_pos(bin_boxes, x, y, z, w, h, d):
                    # Score: We want to fill the bin efficiently.
                    # Priority 1: Lowest Z (keep bin short)
                    # Priority 2: Lowest X (keep bin left)
                    # Priority 3: Lowest Y (keep bin back)
                    # This tends to create a compact "block" of boxes.
                    score = (z, x, y)
                    
                    if bin_best_score is None or score < bin_best_score:
                        bin_best_score = score
                        bin_best_pos = (x, y, z)
                        
            if bin_best_pos is not None:
                # Compare across bins
                # Prefer bins that are already "fuller"? Or just pick the one with the best local score?
                # BFD usually picks the bin where the box fits "tightest".
                # Here, since we minimize (z,x,y), a bin with a lower z is better.
                # This effectively fills the first bin until it's full, then opens a new one?
                # Not necessarily, if a later bin has a lower z (e.g. it was placed flat).
                # Let's use the same score for global comparison.
                if best_score is None or bin_best_score < best_score:
                    best_score = bin_best_score
                    best_bin_index = b_idx
                    best_pos = bin_best_pos
        
        if best_bin_index != -1:
            x, y, z = best_pos
            # Update bin
            old_boxes, old_eps = bins[best_bin_index]
            new_box = (x, y, z, w, h, d)
            new_boxes = old_boxes + [new_box]
            new_eps = generate_new_extreme_points(new_boxes, x, y, z, w, h, d, old_eps)
            bins[best_bin_index] = (new_boxes, new_eps)
            placements[idx] = (best_bin_index, x, y, z, w, h, d)
        else:
            # Open new bin
            new_bin_index = bin_count
            bin_count += 1
            new_box = (0, 0, 0, w, h, d)
            new_boxes = [new_box]
            new_eps = generate_new_extreme_points(new_boxes, 0, 0, 0, w, h, d, {(0,0,0)})
            bins.append((new_boxes, new_eps))
            placements[idx] = (new_bin_index, 0, 0, 0, w, h, d)

    return placements
# EVOLVE-BLOCK-END
