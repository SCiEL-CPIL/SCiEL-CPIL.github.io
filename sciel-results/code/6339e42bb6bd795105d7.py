import time
import numpy as np
from scipy.optimize import milp, LinearConstraint, Bounds

def construct():
    start_time = time.time()
    deadline = start_time + 115.0
    
    # We search for the smallest M such that a valid Sidon set exists in [0, M]
    # covering differences 1..30.
    
    # Lower bound for M
    # We need to cover 30 differences.
    # A set of size k has k(k-1)/2 differences.
    # k=9 -> 36 diffs.
    # Minimal M for k=9 Sidon set?
    # Start from 30.
    
    for M in range(30, 200):
        if time.time() > deadline:
            break
            
        # Variables:
        # x_i for i in 0..M (M+1 vars)
        # z_{i,d} for i in 0..M-d, d in 1..30
        
        n_x = M + 1
        z_counts = []
        for d in range(1, 31):
            z_counts.append(M - d + 1)
        n_z = sum(z_counts)
        
        n_vars = n_x + n_z
        
        # Objective: Minimize 0 (feasibility)
        c = np.zeros(n_vars)
        
        # Bounds
        # x_i in {0, 1}
        # z_{i,d} in {0, 1}
        integrality = np.ones(n_vars)
        lb = np.zeros(n_vars)
        ub = np.ones(n_vars)
        
        # Constraints:
        # 1. x_0 = 1
        # 2. sum(x_i) <= 32
        # 3. Sidon: x_i + x_j + x_k + x_l <= 3 for distinct pairs with same diff
        # 4. Coverage: sum(z_{i,d}) >= 1 for each d
        # 5. Linking: z_{i,d} <= x_i, z_{i,d} <= x_{i+d}, z_{i,d} >= x_i + x_{i+d} - 1
        
        A_rows = []
        b_lower = []
        b_upper = []
        
        # Constraint 1: x_0 = 1
        row = np.zeros(n_vars)
        row[0] = 1.0
        A_rows.append(row)
        b_lower.append(1.0)
        b_upper.append(1.0)
        
        # Constraint 2: sum(x_i) <= 32
        row = np.zeros(n_vars)
        for i in range(n_x):
            row[i] = 1.0
        A_rows.append(row)
        b_lower.append(-np.inf)
        b_upper.append(32.0)
        
        # Constraint 3: Sidon
        # For each difference d, get all pairs (i, i+d)
        # For each pair of distinct pairs, add constraint
        # We need to map x indices
        # x index is i
        
        # To avoid duplicate constraints, we only consider pairs of pairs
        # where the first pair's start index is less than the second pair's start index?
        # No, just ensure the pairs are distinct.
        # Pairs are defined by (start, diff).
        # If (start1, d) and (start2, d) are distinct, and (start1, d) != (start2, d),
        # they are distinct pairs of elements.
        # Elements are {start1, start1+d} and {start2, start2+d}.
        # If these sets are disjoint, we add x[start1] + x[start1+d] + x[start2] + x[start2+d] <= 3.
        # If they are not disjoint, they are the same pair (since diff is same).
        # So for a fixed d, all distinct pairs of starts are disjoint.
        
        for d in range(1, 31):
            starts = list(range(0, M - d + 1))
            n_starts = len(starts)
            for idx1 in range(n_starts):
                s1 = starts[idx1]
                for idx2 in range(idx1 + 1, n_starts):
                    s2 = starts[idx2]
                    # Pairs are (s1, s1+d) and (s2, s2+d)
                    # They are distinct because s1 != s2.
                    # Are the element sets disjoint?
                    # {s1, s1+d} and {s2, s2+d}
                    # If s1 == s2, no.
                    # If s1 == s2+d, then d=0, no.
                    # If s1+d == s2, then s2-s1=d.
                    # If s1+d == s2+d, then s1=s2.
                    # So if s2 = s1 + d, the sets are {s1, s1+d} and {s1+d, s1+2d}.
                    # They share s1+d.
                    # In this case, the pairs are NOT disjoint.
                    # The Sidon condition requires that all DIFFERENCES are distinct.
                    # The difference d is generated by pair 1 and pair 2.
                    # If the pairs share an element, do they generate the same difference?
                    # Yes, both generate difference d.
                    # So this is a violation of the Sidon property (duplicate difference).
                    # So we must forbid this too.
                    # Constraint: x[s1] + x[s1+d] + x[s2] + x[s2+d] <= 3
                    # If they share an element, say x[s1+d] is common.
                    # Then sum is x[s1] + 2*x[s1+d] + x[s2+d] <= 3.
                    # This is still a valid linear constraint to forbid both pairs being fully present.
                    # If both pairs are present, sum >= 4 (if disjoint) or sum >= 3 (if shared, 1+2+1=4? No.
                    # If shared: x[s1]=1, x[s1+d]=1, x[s2]=x[s1+d]=1, x[s2+d]=1.
                    # Sum = 1 + 1 + 1 + 1 = 4?
                    # Wait, the variables are x[s1], x[s1+d], x[s2], x[s2+d].
                    # If s2 = s1+d, then x[s2] is the same variable as x[s1+d].
                    # So the sum is x[s1] + x[s1+d] + x[s1+d] + x[s1+2d] = x[s1] + 2*x[s1+d] + x[s1+2d].
                    # If all are 1, sum = 1+2+1 = 4.
                    # So <= 3 forbids it.
                    
                    row = np.zeros(n_vars)
                    row[s1] += 1.0
                    row[s1 + d] += 1.0
                    row[s2] += 1.0
                    row[s2 + d] += 1.0
                    A_rows.append(row)
                    b_lower.append(-np.inf)
                    b_upper.append(3.0)
                    
        # Constraint 4 & 5: Coverage and Linking
        # We need to map z variables to indices
        # z index offset is n_x
        # z_{i,d} index = n_x + sum_{k=1}^{d-1} (M-k+1) + i
        
        z_offset = n_x
        z_indices = {}
        current_idx = z_offset
        for d in range(1, 31):
            for i in range(0, M - d + 1):
                z_indices[(i, d)] = current_idx
                current_idx += 1
                
        for d in range(1, 31):
            # Coverage: sum z_{i,d} >= 1
            row = np.zeros(n_vars)
            for i in range(0, M - d + 1):
                row[z_indices[(i, d)]] = 1.0
            A_rows.append(row)
            b_lower.append(1.0)
            b_upper.append(np.inf)
            
            # Linking constraints for each i
            for i in range(0, M - d + 1):
                z_idx = z_indices[(i, d)]
                x_i_idx = i
                x_ipd_idx = i + d
                
                # z <= x_i
                row = np.zeros(n_vars)
                row[z_idx] = 1.0
                row[x_i_idx] = -1.0
                A_rows.append(row)
                b_lower.append(-np.inf)
                b_upper.append(0.0)
                
                # z <= x_{i+d}
                row = np.zeros(n_vars)
                row[z_idx] = 1.0
                row[x_ipd_idx] = -1.0
                A_rows.append(row)
                b_lower.append(-np.inf)
                b_upper.append(0.0)
                
                # z >= x_i + x_{i+d} - 1  =>  -z + x_i + x_{i+d} <= 1
                row = np.zeros(n_vars)
                row[z_idx] = -1.0
                row[x_i_idx] = 1.0
                row[x_ipd_idx] = 1.0
                A_rows.append(row)
                b_lower.append(-np.inf)
                b_upper.append(1.0)
                
        A = np.vstack(A_rows)
        b_lower = np.array(b_lower)
        b_upper = np.array(b_upper)
        
        constraints = LinearConstraint(A, b_lower, b_upper)
        bounds = Bounds(lb, ub)
        
        res = milp(c, constraints=constraints, integrality=integrality, bounds=bounds)
        
        if res.status == 0:
            # Feasible solution found
            x = res.x[:n_x]
            # Extract indices where x is 1
            sol = [i for i in range(n_x) if x[i] > 0.5]
            
            # Verify
            diffs = set()
            is_sidon = True
            seen = set()
            for i in range(len(sol)):
                for j in range(i+1, len(sol)):
                    d = sol[j] - sol[i]
                    if d in seen:
                        is_sidon = False
                        break
                    seen.add(d)
                    if 1 <= d <= 30:
                        diffs.add(d)
                if not is_sidon:
                    break
            
            if is_sidon and all(d in diffs for d in range(1, 31)):
                return sol
        
    # Fallback
    return [0, 1, 4, 10, 12, 17, 21, 25, 28, 32, 36, 40, 44, 48, 52, 56, 60, 64, 68, 72, 76, 80, 84, 88, 92, 96, 100, 104, 108, 112, 116, 120]
