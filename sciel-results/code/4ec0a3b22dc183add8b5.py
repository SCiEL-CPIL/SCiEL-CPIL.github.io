def construct(n_rows, k):
    """
    Construct n_rows rows of k+1 increasing integers starting at 0
    such that all positive differences within each row are distinct across all rows.
    Minimizes the largest entry.
    """
    # Total differences per row
    K = k * (k + 1) // 2
    
    # Lower bound for M: We need n_rows * K distinct differences in [1, M]
    # So M must be at least n_rows * K
    min_M = n_rows * K
    
    # We can also use the counting bound from the problem description if it's higher?
    # The problem says "simple counting bound is 112".
    # For n_rows=4, k=7, K=28, n_rows*K = 112. So min_M = 112.
    
    # We will try M from min_M upwards
    # To avoid infinite loops if no solution is found (shouldn't happen for valid inputs),
    # we set a hard limit, e.g., min_M + 1000.
    
    max_M = min_M + 200
    
    for M in range(min_M, max_M + 1):
        result = _solve_csp(n_rows, k, M)
        if result is not None:
            return result
            
    # Fallback: If we didn't find a solution within the bound, 
    # use the greedy approach as a last resort (though it might be suboptimal)
    return _greedy_construct(n_rows, k)

def _solve_csp(n_rows, k, M):
    """
    Backtracking solver with forward checking.
    Returns a list of n_rows rows if a solution is found, else None.
    """
    K = k * (k + 1) // 2
    
    # State:
    # rows: list of completed rows
    # current_row: list of elements in the current row (starts with [0])
    # used_diffs: set of all differences used so far
    
    rows = []
    current_row = [0]
    used_diffs = set()
    
    # To speed up, we can pre-calculate the number of differences generated by a row of length L
    # diffs(L) = L*(L-1)//2
    
    def backtrack(row_idx, current_row, used_diffs):
        # row_idx: index of the row currently being processed (0 to n_rows-1)
        # If row_idx == n_rows, we are done
        if row_idx == n_rows:
            return True
        
        # If current_row is full, move to next row
        if len(current_row) == k + 1:
            rows.append(current_row[:])
            return backtrack(row_idx + 1, [0], used_diffs)
        
        # Pruning: Check if enough differences are available
        # Current row length L
        L = len(current_row)
        # Differences already in current row
        curr_diffs_count = L * (L - 1) // 2
        # Differences needed to complete current row
        needed_curr = K - curr_diffs_count
        # Differences needed for remaining full rows
        rows_left = n_rows - 1 - row_idx
        needed_total = needed_curr + rows_left * K
        
        available_diffs = M - len(used_diffs)
        if available_diffs < needed_total:
            return False
        
        # Determine candidates for the next element
        last_val = current_row[-1]
        # The next element must be > last_val and <= M
        # Also, the new differences (candidate - x for x in current_row) must be in [1, M] and not in used_diffs
        
        # Heuristic: Try candidates in a specific order.
        # Smaller candidates might leave more room for larger differences?
        # Or larger candidates?
        # Usually, filling with smaller numbers first is good for packing,
        # but here we have a fixed upper bound M.
        # Let's try candidates from last_val + 1 to M.
        
        # Optimization: We can restrict the search space.
        # The maximum difference we can create with the last element is M - 0 = M.
        # The new differences are candidate - x_i.
        
        # To improve performance, we can use a "most constrained" heuristic for the value?
        # For now, simple iteration.
        
        # We can also prune candidates that create a difference that is "too large" 
        # such that it prevents fitting the remaining elements?
        # Actually, the pruning above handles the global count.
        
        # Let's iterate candidates
        # To break symmetry or improve search, we might want to try values that 
        # use differences that are "scarce" or "abundant"?
        # Let's stick to increasing order first.
        
        for candidate in range(last_val + 1, M + 1):
            # Check differences
            new_diffs = []
            valid = True
            for x in current_row:
                d = candidate - x
                if d > M: # Should not happen if candidate <= M and x >= 0
                    valid = False
                    break
                if d in used_diffs:
                    valid = False
                    break
                new_diffs.append(d)
            
            if not valid:
                continue
                
            # Forward Checking: 
            # If we add this candidate, does it leave enough room?
            # The pruning at the start of the next call will handle this,
            # but we can do a quick check here to avoid function call overhead.
            
            # New state
            next_row = current_row + [candidate]
            next_used = used_diffs.union(new_diffs)
            
            # Recursive call
            if backtrack(row_idx, next_row, next_used):
                return True
            
        return False

    if backtrack(0, [0], set()):
        return rows
    return None

def _greedy_construct(n_rows, k):
    """Fallback greedy constructor"""
    used_diffs = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        while len(row) < k + 1:
            found = False
            for candidate in range(row[-1] + 1, 1000):
                new_diffs = {candidate - a for a in row}
                if not (new_diffs & used_diffs):
                    row.append(candidate)
                    used_diffs |= new_diffs
                    found = True
                    break
            if not found:
                # Extend search range if necessary, though 1000 should be enough for small n,k
                for candidate in range(1000, 5000):
                    new_diffs = {candidate - a for a in row}
                    if not (new_diffs & used_diffs):
                        row.append(candidate)
                        used_diffs |= new_diffs
                        found = True
                        break
            if not found:
                # Failure, return what we have or raise
                # For safety, just break
                break
        rows.append(row)
    return rows
