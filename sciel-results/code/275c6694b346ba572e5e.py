import time
import random
import numpy as np

def construct():
    """
    Construct a large binary code of length 17 with minimum distance 6.
    Strategy:
    1. Use a fast greedy algorithm with vectorized NumPy distance checks.
    2. Start from a strong seed (e.g., the shortened [18,9,6] QR code if we can construct it,
       or a random linear code, or just start with 0 and greedily add).
    3. The key is to use NumPy to check distances from a candidate to all existing codewords
       in a single vectorized operation.
    4. To speed up, we can maintain a "conflict" count or just re-check distances.
       Since the code size is ~300, checking 300 distances is fast.
       The bottleneck is iterating through 131k candidates.
       We can try to be smarter: instead of checking every candidate against the whole code,
       we can maintain a list of "forbidden" candidates (those too close to existing words).
       But maintaining that list is also expensive.
       
       Alternative:
       Use a bit-parallel approach?
       Or just rely on the fact that NumPy is fast.
       
       Let's try:
       - Start with code = [0]
       - candidates = np.arange(1, 2**17)
       - For each candidate c:
           - Compute distances to all words in code: np.array([popcount(c ^ w) for w in code])
           - If min distance >= 6, add c to code.
       
       This is O(N * |code|) popcounts.
       N=131k, |code|~300. 131k * 300 = 39M popcounts.
       In Python, even with NumPy, this might be slow if we do it in a loop.
       
       Better:
       Pre-compute the popcount of all possible 17-bit words?
       There are 2^17 = 131k words. We can pre-compute popcount for all of them.
       Then distance(c, w) = popcount[c ^ w].
       
       So:
       popcount_table = np.array([i.bit_count() for i in range(2**17)])
       
       Then for a candidate c and code list (as array), distances = popcount_table[c ^ code_array]
       This is a single NumPy fancy indexing operation, which is very fast.
       
       Let's implement this.
    """
    start_time = time.time()
    deadline = start_time + 80.0  # Safety margin of 10s before 90s limit
    
    n = 17
    min_dist = 6
    max_val = 1 << n  # 2^17 = 131072
    
    # Pre-compute popcount for all 17-bit words
    # This is a one-time cost of ~131k bit_count operations.
    # We can do this in a list comprehension and convert to numpy array.
    # Or use a lookup table for bytes and combine.
    # Let's just use a list comprehension, it's fast enough for 131k items.
    popcount_table = np.array([i.bit_count() for i in range(max_val)], dtype=np.uint8)
    
    # Strategy:
    # 1. Try to construct a large linear code first?
    #    The QR code of length 17 is [17,8,5]? No, the problem says [18,9,6] shortened is [17,8,6] size 256.
    #    Let's try to find a [17,8,6] code.
    #    We can do a random linear code search:
    #    - Pick 8 random vectors.
    #    - Check if the minimum distance of the code generated by them is >= 6.
    #    - This is hard to check efficiently.
    
    #    Alternatively, we can just use the greedy algorithm with the popcount table.
    #    The greedy algorithm with a good order can find a large code.
    #    
    #    Let's try multiple random restarts of the greedy algorithm.
    #    Each restart:
    #    - Start with code = [0] (or a small random set)
    #    - Candidates = all other words, shuffled.
    #    - For each candidate, check if it's valid using the popcount table.
    #    - If valid, add to code.
    #    
    #    To speed up, we can stop early if we've checked all candidates or if time is up.
    
    best_code = None
    best_size = 0
    
    # We can also try to start with a linear code seed.
    # Let's try to construct the [17,8,6] QR code.
    # The quadratic residues mod 17 are: 1, 2, 4, 8, 9, 13, 15, 16.
    # The generator matrix of the QR code can be constructed.
    # But this is complex. Let's stick to random greedy for now.
    
    # To improve the greedy result, we can use a "greedy with lookahead" or "local search".
    # But let's first see how good the simple greedy is.
    
    # Let's run a few random restarts.
    for restart in range(20):  # Up to 20 restarts
        if time.time() > deadline - 5.0:
            break
        
        code = [0]
        code_array = np.array(code, dtype=np.uint32)
        
        candidates = np.arange(1, max_val, dtype=np.uint32)
        np.random.shuffle(candidates)
        
        for c in candidates:
            if time.time() > deadline - 5.0:
                break
            
            # Compute distances from c to all words in code
            # c is a scalar, code_array is an array.
            # c ^ code_array gives an array of XORs.
            # popcount_table[XORs] gives an array of popcounts.
            dists = popcount_table[c ^ code_array]
            
            if np.min(dists) >= min_dist:
                code.append(c)
                # Update code_array
                # Instead of recreating the array, we can just keep the list and convert to array when needed.
                # But converting to array every time is expensive.
                # Let's keep code as a list and only convert to array when checking.
                # Actually, the check is the bottleneck.
                # Let's keep code as a list, and for the check, convert to array.
                # But that's O(|code|) per check, which is what we're doing anyway.
                # The NumPy operation is vectorized over the code list.
                # So we need code_array to be up-to-date.
                # Let's just rebuild code_array when we add a new word.
                # But that's O(|code|) per addition, which is fine since |code| is small.
                code_array = np.array(code, dtype=np.uint32)
        
        if len(code) > best_size:
            best_size = len(code)
            best_code = code[:]
            
        # If we found a very large code, we can stop early?
        # The upper bound is 340. If we find 340, we can stop.
        if best_size >= 340:
            break
    
    if best_code is None:
        best_code = [0]
        
    return best_code
