"""
Strategy: Fixed-Weight Neural Network Basis (Linear-in-Parameters).

Rationale:
The previous approach used a hybrid of polynomials and Gaussians. This new approach
uses a small neural network (2 hidden layers, tanh activations) with fixed,
randomly initialized internal weights. The only parameters optimized by BFGS are
the 10 weights of the final output layer.

This makes the problem linear in the parameters (convex optimization), which is
crucial for BFGS to reliably find the global minimum. The fixed internal
non-linearities provide a rich basis of features (universal approximation
capability) that can capture complex, non-polynomial structures better than a
simple polynomial or a few fixed Gaussians, while maintaining the convexity
of the optimization landscape.

Parameters (length 10):
w0..w9: Weights for the 10 basis functions (features) generated by the fixed NN.
"""

# EVOLVE-BLOCK-START
import numpy as np

# Pre-compute the fixed weights of the hidden layers.
# We use a fixed seed to ensure reproducibility and to define a specific,
# non-random basis for the evaluator.
np.random.seed(42)

# Architecture: Input (2) -> Hidden 1 (10) -> Hidden 2 (10) -> Output (10 features)
# We need 10 features to match the 10 parameters.
# So the "output" of the fixed part is a 10-dim vector.

# Hidden Layer 1
W1 = np.random.randn(2, 10) * np.sqrt(2.0 / 2)
b1 = np.zeros(10)

# Hidden Layer 2
W2 = np.random.randn(10, 10) * np.sqrt(2.0 / 10)
b2 = np.zeros(10)

# Note: We do NOT have an output layer weights here because those are the `params`.
# The "features" are the outputs of Hidden Layer 2.

def equation(x: np.ndarray, y: np.ndarray, params: np.ndarray) -> np.ndarray:
    """
    Neural Network Basis Model.
    
    x: (N, 2) array of inputs.
    y: (N,) array of targets (not used in prediction, but part of signature).
    params: (10,) array of output layer weights.
    """
    # Ensure x is a 2D array of shape (N, 2)
    # The evaluator passes x as an array of points.
    # If x is 1D, it might be a single point or flattened. 
    # Standard convention in these tasks: x is (N, 2).
    # Let's be robust.
    x = np.asarray(x)
    if x.ndim == 1:
        # If 1D, it might be a single point (length 2) or flattened points.
        # Given "200 training points", x is likely (200, 2).
        # If it's a single point, x would be (2,).
        # Let's assume standard (N, 2).
        if x.shape[0] == 2:
            x = x.reshape(1, 2)
        else:
            # Fallback, though unlikely
            x = x.reshape(-1, 2)

    # Forward pass through fixed layers
    # Hidden 1
    h1 = x @ W1 + b1
    h1 = np.tanh(h1)
    
    # Hidden 2
    h2 = h1 @ W2 + b2
    h2 = np.tanh(h2)
    
    # Now h2 has shape (N, 10). These are our 10 basis functions.
    # The prediction is the dot product of h2 and the 10 parameters.
    # params has shape (10,).
    
    pred = h2 @ params
    
    return pred
# EVOLVE-BLOCK-END
