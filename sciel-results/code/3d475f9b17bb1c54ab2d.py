import numpy as np

def construct():
    n, m, p = 2, 2, 3
    rank = 11
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Schoolbook for k=0
    # r=0: A[0,0] B[0,0] -> C[0,0]
    U[0*2+0][0] = 1
    V[0*3+0][0] = 1
    W[0*2+0][0] = 1
    
    # r=1: A[0,1] B[1,0] -> C[0,0]
    U[0*2+1][1] = 1
    V[1*3+0][1] = 1
    W[0*2+0][1] = 1
    
    # r=2: A[1,0] B[0,0] -> C[1,0]
    U[1*2+0][2] = 1
    V[0*3+0][2] = 1
    W[0*2+1][2] = 1
    
    # r=3: A[1,1] B[1,0] -> C[1,0]
    U[1*2+1][3] = 1
    V[1*3+0][3] = 1
    W[0*2+1][3] = 1
    
    # Strassen for k=1,2
    # B' = B[:, 1:2]
    # B'_{00} = B[0,1], B'_{01} = B[0,2]
    # B'_{10} = B[1,1], B'_{11} = B[1,2]
    
    # M1 = A[0,0] (B[0,2] - B[1,2])
    U[0*2+0][4] = 1
    V[0*3+2][4] = 1
    V[1*3+2][4] = -1
    W[1*2+0][4] = 1 # C[0,1]
    W[1*2+1][4] = 1 # C[1,1]
    
    # M2 = (A[0,0] + A[1,0]) B[1,2]
    U[0*2+0][5] = 1
    U[1*2+0][5] = 1
    V[1*3+2][5] = 1
    W[1*2+0][5] = -1 # C[0,1]
    W[1*2+1][5] = -1 # C[1,1]
    
    # M3 = (A[1,0] - A[0,0]) B[0,1]
    U[1*2+0][6] = 1
    U[0*2+0][6] = -1
    V[0*3+1][6] = 1
    W[1*2+1][6] = 1 # C[1,1]
    
    # M4 = A[1,1] (B[0,1] + B[1,1])
    U[1*2+1][7] = 1
    V[0*3+1][7] = 1
    V[1*3+1][7] = 1
    W[1*2+0][7] = 1 # C[0,1]
    W[1*2+1][7] = 1 # C[1,1]
    
    # M5 = (A[0,0] + A[1,1]) (B[0,1] + B[1,2])
    U[0*2+0][8] = 1
    U[1*2+1][8] = 1
    V[0*3+1][8] = 1
    V[1*3+2][8] = 1
    W[1*2+0][8] = 1 # C[0,1]
    W[2*2+0][8] = 1 # C[0,2]
    W[2*2+1][8] = 1 # C[1,2]
    
    # M6 = (A[0,1] - A[1,1]) (B[1,1] + B[1,2])
    U[0*2+1][9] = 1
    U[1*2+1][9] = -1
    V[1*3+1][9] = 1
    V[1*3+2][9] = 1
    W[1*2+0][9] = 1 # C[0,1]
    
    # M7 = (A[0,0] + A[0,1]) B[0,1]
    U[0*2+0][10] = 1
    U[0*2+1][10] = 1
    V[0*3+1][10] = 1
    W[2*2+1][10] = 1 # C[1,2]
    
    return {"U": U, "V": V, "W": W}
