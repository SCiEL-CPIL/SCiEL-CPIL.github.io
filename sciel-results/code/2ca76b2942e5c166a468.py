import time
import random

def construct(k, g):
    # Deadline guard
    deadline = time.time() + 110.0
    
    # --- Part 1: Random Cayley Graph Search on A5 x A5 ---
    if k == 5 and g == 9:
        result = _try_cayley_a5x5(k, g, deadline)
        if result is not None:
            return result

    # --- Part 2: Fallback LUW ---
    return _luw_construct(k, g)

def _luw_construct(k, g):
    # Original code
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges

def _try_cayley_a5x5(k, g, deadline):
    # Define A5
    # Permutations of 0..4
    # We need all elements of A5.
    # A5 is the alternating group on 5 elements.
    # Elements are even permutations.
    
    # Generate all 5! = 120 permutations
    import itertools
    all_perms = list(itertools.permutations(range(5)))
    
    # Determine parity
    def parity(p):
        invs = 0
        for i in range(5):
            for j in range(i+1, 5):
                if p[i] > p[j]:
                    invs += 1
        return invs % 2
        
    a5_elements = [p for p in all_perms if parity(p) == 0]
    e = (0, 1, 2, 3, 4)
    
    # Map elements to indices for fast lookup?
    # Or just use tuples as keys in dicts.
    
    # Define multiplication
    def mul(p, q):
        return tuple(p[q[i]] for i in range(5))
        
    # Find involutions in A5
    a5_involutions = [p for p in a5_elements if mul(p, p) == e]
    # Remove identity
    a5_invols_non_id = [p for p in a5_involutions if p != e]
    
    # Group is A5 x A5
    # Elements are (a, b)
    # Identity is (e, e)
    id_elem = (e, e)
    
    # Involutions in A5 x A5
    # (a, b) is involution if mul(a,a)==e and mul(b,b)==e and (a,b) != (e,e)
    # a, b in a5_invols_non_id U {e}
    a5_opts = a5_invols_non_id + [e]
    group_involutions = []
    for a in a5_opts:
        for b in a5_opts:
            if a == e and b == e:
                continue
            group_involutions.append((a, b))
            
    # Shuffle
    random.shuffle(group_involutions)
    
    n_attempts = 0
    while time.time() < deadline:
        n_attempts += 1
        # Pick 5 distinct involutions
        if len(group_involutions) < 5:
            break
        # To avoid bias, we can just take first 5 from a shuffled list, 
        # but reshuffling 255 items every time is fine.
        # Or better, maintain a pool.
        # For simplicity, just sample without replacement.
        try:
            gens = random.sample(group_involutions, k)
        except ValueError:
            break
            
        # Check if gens generate the whole group? 
        # If not, the graph is a disjoint union of Cayley graphs of the subgroup.
        # The girth of the graph is the min girth of the components.
        # The component of identity is the Cayley graph of the subgroup H generated by gens.
        # If H is small, the girth is likely small.
        # We can check the size of H first.
        # If |H| < Moore bound, fail fast.
        # Moore bound for k=5, g=9 is 428.
        # A5 x A5 has 3600.
        # If H is A5 (60) or A5 x A5 (3600) or something in between?
        # Subgroups of A5 x A5:
        # 1, C2, C3, C5, A4, D5, S3, A5, A5xC2?, A5xA5.
        # If H is A5, size 60. Too small.
        # If H is A5 x A5, size 3600. Good.
        # Let's check if gens generate A5 x A5.
        
        # Generate subgroup generated by gens
        H = {id_elem}
        frontier = [id_elem]
        while frontier:
            new_frontier = []
            for h in frontier:
                for g in gens:
                    # h * g
                    hg = (mul(h[0], g[0]), mul(h[1], g[1]))
                    if hg not in H:
                        H.add(hg)
                        new_frontier.append(hg)
                    # g * h? Cayley graph edges are v -> v*g. 
                    # The subgroup generated is the same regardless of left/right if we consider the set.
                    # But for BFS, we only go right.
            frontier = new_frontier
            
        if len(H) < 428: # Moore bound approx
            continue
            
        # Check girth via BFS on H
        # Start at id_elem
        # Visited: {id_elem: 0}
        # Queue: [(id_elem, 0)]
        visited = {id_elem: 0}
        queue = [(id_elem, 0)]
        valid = True
        while queue:
            v, d = queue.pop(0)
            if d >= g - 1:
                continue
            for g in gens:
                u = (mul(v[0], g[0]), mul(v[1], g[1]))
                if u == id_elem:
                    # Cycle found of length d+1
                    if d + 1 < g:
                        valid = False
                        break
                elif u not in visited:
                    visited[u] = d + 1
                    queue.append((u, d + 1))
                else:
                    # u is visited. 
                    # The cycle length is d + 1 + visited[u]?
                    # No, BFS finds shortest path to u.
                    # If we are at v (depth d) and go to u (depth d'), 
                    # the path to u is d+1. The existing path is d'.
                    # This creates a cycle of length (d+1) + d' only if the paths are disjoint?
                    # Actually, in a Cayley graph, if we find a back-edge to a visited node, 
                    # the cycle length is d + 1 + depth[u]? No.
                    # The cycle is path(v, u) via BFS + edge (v, u).
                    # Length = depth[v] + 1 + depth[u]? No.
                    # The edge connects v to u.
                    # Path from id to v is depth[v].
                    # Path from id to u is depth[u].
                    # The cycle formed by path(id->v) + edge(v->u) + path(u->id) is not a simple cycle necessarily.
                    # However, we only care about cycles through identity.
                    # We already check u == id_elem.
                    # What about cycles not through identity?
                    # As established, girth of Cayley graph is min length of word w=1.
                    # So we only need to check u == id_elem.
                    # If we exhaust BFS without hitting id_elem (except start), girth >= g.
                    pass
                    
            if not valid:
                break
                
        if valid:
            # Construct the graph
            # Map H elements to 0..len(H)-1
            # Only need the component of identity?
            # The task asks for "a graph". It doesn't explicitly say connected, 
            # but "cage" implies connected usually. 
            # Also, if H is a proper subgroup, the graph is a disjoint union of copies of the Cayley graph of H.
            # The girth is the same.
            # But we want to minimize n.
            # If H is a proper subgroup, n = |G| / |H| * |H| = |G|? No.
            # The graph is on the whole group G? Or just the subgroup?
            # "Construct a k-regular graph... on as few vertices as possible."
            # If we use the Cayley graph of G with generators S, the graph is on G.
            # If S generates a proper subgroup H, the graph is a disjoint union of Cayley graphs of H.
            # The number of vertices is |G|.
            # We want to minimize n.
            # If we can find a set of generators that generates a small subgroup H with high girth, 
            # we could just return the Cayley graph of H?
            # But the generators must be from the ambient group?
            # The task doesn't specify the group. It just asks for a graph.
            # So we can construct the Cayley graph of H directly.
            # But H is a subgroup of A5 x A5.
            # We can just map H to 0..|H|-1 and return that graph.
            # This would give n = |H|.
            # So we should check if H has girth >= g.
            # If yes, return the Cayley graph of H.
            
            # But wait, if H is small, e.g. 60, and girth 9, n=60.
            # Is there a (5,9)-cage with 60 vertices?
            # Moore bound is 428. So NO.
            # So H must be at least 428.
            # So if we find a valid H, n = |H|.
            # We should minimize |H|.
            # So we should prefer smaller H?
            # But finding a small H with high girth is hard.
            # Usually, larger groups have more room for high girth.
            # Let's just return the first valid one found.
            # Or track the best (smallest |H|) found.
            
            # For now, return the first valid one.
            # Map H to indices
            index = {}
            order = list(H)
            for i, v in enumerate(order):
                index[v] = i
                
            edges = []
            for v in order:
                vi = index[v]
                for g in gens:
                    u = (mul(v[0], g[0]), mul(v[1], g[1]))
                    ui = index[u]
                    if vi < ui:
                        edges.append((vi, ui))
                        
            return len(order), edges

    return None
