def _crossover_c4v(parent1, parent2, size=32):
    """C4v-symmetric crossover: for each orbit, pick from either parent."""
    child = np.zeros((size, size), dtype=np.int8)
    for i in range(size):
        for j in range(size):
            orbit = [(i, j), (size-1-i, size-1-j), (j, i), (size-1-j, size-1-i)]
            # Pick randomly from parent1 or parent2 for this orbit
            if random.random() < 0.5:
                val = parent1[orbit[0]]
            else:
                val = parent2[orbit[0]]
            for oi, oj in orbit:
                child[oi, oj] = val
    return child

def _mutate_c4v(cell, size=32, mutation_rate=0.05):
    """C4v-symmetric mutation: flip random orbits."""
    cell = cell.copy()
    n_orbits = (size * size) // 4  # Approximate number of orbits
    n_mutations = int(mutation_rate * n_orbits)
    
    # Get unique orbit representatives
    visited = set()
    orbits = []
    for i in range(size):
        for j in range(size):
            orbit = [(i, j), (size-1-i, size-1-j), (j, i), (size-1-j, size-1-i)]
            # Use the lexicographically smallest as representative
            rep = min(orbit)
            if rep not in visited:
                visited.add(rep)
                orbits.append(orbit)
    
    # Mutate random orbits
    for _ in range(n_mutations):
        orbit = random.choice(orbits)
        val = 1 - cell[orbit[0]]
        for oi, oj in orbit:
            cell[oi, oj] = val
    
    return cell

def design(problem):
    start_time = time.time()
    deadline = start_time + 215  # 15s margin
    
    size = problem["pixels"]
    random.seed(42)
    
    # Initialize population with the current best design
    base_cell = _make_four_rod_cell(size)
    base_cell = _enforce_c4v(base_cell)
    
    # Create initial population
    pop_size = 60
    population = [base_cell.copy() for _ in range(pop_size)]
    # Add some variation
    for i in range(1, pop_size):
        if i % 3 == 0:
            population[i] = _mutate_c4v(base_cell, size, mutation_rate=0.03)
        elif i % 3 == 1:
            population[i] = _mutate_c4v(base_cell, size, mutation_rate=0.08)
        else:
            population[i] = _mutate_c4v(base_cell, size, mutation_rate=0.15)
    
    # Evaluate initial population
    scores = []
    for cell in population:
        score = _compute_tm_bands_fast(cell, n_pw=5)
        scores.append(score)
    
    best_score = max(scores)
    best_cell = population[scores.index(best_score)]
    
    # Genetic algorithm loop
    gen = 0
    while time.time() < deadline - 30:  # Leave 30s for final refinement
        gen += 1
        
        # Sort by score
        sorted_idx = np.argsort(scores)[::-1]
        population = [population[i] for i in sorted_idx]
        scores = [scores[i] for i in sorted_idx]
        
        # Elitism: keep top 20%
        elite_count = max(1, pop_size // 5)
        new_population = [population[i].copy() for i in range(elite_count)]
        
        # Fill rest with offspring
        while len(new_population) < pop_size:
            # Tournament selection
            def tournament_select():
                candidates = random.sample(range(len(population)), min(3, len(population)))
                best_cand = max(candidates, key=lambda x: scores[x])
                return population[best_cand]
            
            p1 = tournament_select()
            p2 = tournament_select()
            
            child = _crossover_c4v(p1, p2, size)
            
            # Mutation with adaptive rate
            if random.random() < 0.7:
                mut_rate = 0.03 + 0.1 * random.random()
                child = _mutate_c4v(child, size, mutation_rate=mut_rate)
            
            new_population.append(child)
        
        population = new_population
        
        # Evaluate new population
        scores = []
        for cell in population:
            if time.time() > deadline - 30:
                scores.append(-1.0)
                continue
            score = _compute_tm_bands_fast(cell, n_pw=5)
            scores.append(score)
        
        # Track best
        current_best = max(scores)
        if current_best > best_score:
            best_score = current_best
            best_cell = population[scores.index(current_best)]
    
    # Final refinement: try local optimization around best cell
    if time.time() < deadline - 10:
        # Try flipping individual orbits near the best design
        improved_cell = best_cell.copy()
        improved_score = best_score
        
        # Get all orbits
        visited = set()
        orbits = []
        for i in range(size):
            for j in range(size):
                orbit = [(i, j), (size-1-i, size-1-j), (j, i), (size-1-j, size-1-i)]
                rep = min(orbit)
                if rep not in visited:
                    visited.add(rep)
                    orbits.append(orbit)
        
        # Hill climbing: try single-orbit flips
        for orbit in orbits:
            if time.time() > deadline - 10:
                break
            trial = improved_cell.copy()
            val = 1 - trial[orbit[0]]
            for oi, oj in orbit:
                trial[oi, oj] = val
            
            score = _compute_tm_bands_medium(trial, n_pw=9)
            if score > improved_score:
                improved_score = score
                improved_cell = trial
        
        if improved_score > best_score:
            best_cell = improved_cell
            best_score = improved_score
    
    # Convert to nested list
    result = [[int(best_cell[i][j]) for j in range(size)] for i in range(size)]
    
    return result
