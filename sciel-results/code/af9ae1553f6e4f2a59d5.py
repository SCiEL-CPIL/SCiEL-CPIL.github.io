def _make_four_rod_cell(size=32, r=5.5):
    """Create the baseline four-quadrant rod design."""
    cell = np.zeros((size, size), dtype=np.int8)
    centers = [
        (size/4.0, size/4.0),
        (size/4.0, 3.0*size/4.0),
        (3.0*size/4.0, size/4.0),
        (3.0*size/4.0, 3.0*size/4.0)
    ]
    for i in range(size):
        for j in range(size):
            x = i + 0.5
            y = j + 0.5
            for cx, cy in centers:
                if (x - cx)**2 + (y - cy)**2 < r**2:
                    cell[i, j] = 1
                    break
    return cell

def _enforce_c4v(cell):
    """Enforce C4v symmetry: 180° rotation, transpose, and both reflections about center."""
    size = cell.shape[0]
    # Average over the 4 symmetry operations, then threshold
    c_rot180 = cell[::-1, ::-1]
    c_trans = cell.T
    # 90° rotation = transpose + flip rows
    c_rot90 = cell.T[::-1, :]
    # 270° rotation
    c_rot270 = cell[::-1, :][:, ::-1]
    # Reflections: horizontal, vertical, diagonal, anti-diagonal
    c_ref_h = cell[::-1, :]
    c_ref_v = cell[:, ::-1]
    c_ref_d = cell.T
    c_ref_ad = cell[::-1, :].T  # anti-diagonal
    
    # The group D4 has 8 elements: identity, rot90, rot180, rot270, ref_h, ref_v, ref_d, ref_ad
    # But for a square lattice unit cell with the given constraints:
    # cell == cell[::-1] row-wise AND column-wise (180° rotation)
    # cell == cell.T (transpose)
    # These two imply the full D4 symmetry.
    
    # Enforce: average over {identity, rot180, transpose, rot90}
    # Actually, the constraint says: cell == cell[::-1] (row-wise, i.e., flip rows) AND
    # cell == cell[:, ::-1] (flip columns) AND cell == cell.T
    # Flip rows + flip cols = rot180. And transpose.
    # So we need: cell[i][j] == cell[31-i][31-j] (rot180) and cell[i][j] == cell[j][i] (transpose)
    
    # The orbit of (i,j) under {id, rot180, trans, rot90}:
    # id: (i,j), rot180: (31-i, 31-j), trans: (j,i), rot90: (j, 31-i)
    # Wait, let me be careful. rot90 of (i,j) in a 32x32 grid:
    # If we rotate 90° clockwise: (i,j) -> (j, 31-i)
    # rot180: (i,j) -> (31-i, 31-j)
    # trans (reflect about main diagonal): (i,j) -> (j,i)
    # The group generated by rot180 and trans has 4 elements:
    # {id, rot180, trans, trans∘rot180}
    # trans∘rot180: (i,j) -> rot180 gives (31-i,31-j) -> trans gives (31-j, 31-i)
    
    # So orbit of (i,j): {(i,j), (31-i,31-j), (j,i), (31-j,31-i)}
    
    result = cell.copy().astype(np.float64)
    for i in range(size):
        for j in range(size):
            orbit = [(i, j), (size-1-i, size-1-j), (j, i), (size-1-j, size-1-i)]
            avg = sum(result[oi, oj] for oi, oj in orbit) / 4.0
            for oi, oj in orbit:
                result[oi, oj] = avg
    # Threshold
    result[result >= 0.5] = 1
    result[result < 0.5] = 0
    return result.astype(np.int8)

def _compute_fourier_coefficients(cell, n_pw):
    """Compute Fourier coefficients of 1/epsilon for a pixel cell.
    For TM mode, the eigenvalue equation involves 1/epsilon.
    epsilon = eps_low + (eps_high - eps_low) * cell (where cell is 0/1)
    So 1/epsilon varies with the pixel pattern.
    
    We compute the discrete Fourier transform of the 1/epsilon field.
    """
    size = cell.shape[0]
    eps = 1.0 + 11.0 * cell.astype(np.float64)  # eps_low=1, eps_high=12
    inv_eps = 1.0 / eps
    
    # The Fourier coefficient for wavevector G = (2*pi*m/L, 2*pi*n/L) where L=size
    # For a pixelated structure, we approximate the Fourier coefficient as:
    # f_{mn} = (1/L^2) * sum_{i,j} inv_eps[i,j] * exp(-2*pi*i*(m*i + n*j)/L)
    # But more accurately for a pixel map, each pixel is a small square.
    # For simplicity and speed, use the DFT of the pixel values.
    
    # Use numpy FFT for speed
    # The DFT: F[m,n] = sum_{i,j} f[i,j] * exp(-2*pi*i*(m*i/L + n*j/L))
    # numpy.fft.fft2 computes sum_{i,j} f[i,j] * exp(-2*pi*i*(m*i/N + n*j/N))
    # So F = fft2(f) / N^2 gives the normalized coefficient
    
    F = np.fft.fft2(inv_eps) / (size * size)
    
    # Extract the (n_pw x n_pw) block centered at (0,0)
    # n_pw should be odd
    half = n_pw // 2
    coeffs = np.zeros((n_pw, n_pw), dtype=np.complex128)
    for im in range(n_pw):
        for in_ in range(n_pw):
            m = im - half
            n = in_ - half
            # Wrap into [0, size)
            m_mod = m % size
            n_mod = n % size
            coeffs[im, in_] = F[m_mod, n_mod]
    
    return coeffs

def _compute_tm_bands_fast(cell, n_pw=5, n_k=8):
    """Fast approximate TM band computation using a small plane-wave basis.
    Returns (max_omega_4, min_omega_5) for the gap ratio.
    
    For TM polarization in 2D photonic crystal:
    The eigenvalue equation is:
    (1/L) * sum_{G'} (1/epsilon_{G-G'}) * |G+G'|^2 * a_{G'} = omega^2 * a_G
    
    Where 1/epsilon_{G} are the Fourier coefficients of 1/epsilon.
    """
    size = cell.shape[0]
    coeffs = _compute_fourier_coefficients(cell, n_pw)
    half = n_pw // 2
    
    # Plane wave indices
    G_indices = [(im - half, in_ - half) for im in range(n_pw) for in_ in range(n_pw)]
    n_pw_total = len(G_indices)
    
    # Precompute G magnitudes squared
    G_sq = np.array([(m*m + n*n) for m, n in G_indices], dtype=np.float64)
    
    # Build the 1/epsilon matrix in plane-wave space
    # inv_eps_mat[G, G'] = coeffs[G - G']
    inv_eps_mat = np.zeros((n_pw_total, n_pw_total), dtype=np.complex128)
    for i, (mi, ni) in enumerate(G_indices):
        for j, (mj, nj) in enumerate(G_indices):
            dm = mi - mj
            dn = ni - nj
            # Find index of (dm, dn) in coeffs
            di = dm + half
            dj = dn + half
            if 0 <= di < n_pw and 0 <= dj < n_pw:
                inv_eps_mat[i, j] = coeffs[di, dj]
            else:
                inv_eps_mat[i, j] = 0.0  # Neglect high-order terms
    
    # Define k-points in the irreducible BZ
    # Square lattice BZ: [-pi, pi] x [-pi, pi] (in units of 2*pi/a where a=1)
    # Irreducible wedge: 0 <= ky <= kx, 0 <= kx <= pi
    # Key points: Gamma (0,0), X (pi, 0), M (pi, pi), and points along X-M and Gamma-M
    
    k_points = [
        (0.0, 0.0),       # Gamma
        (math.pi, 0.0),   # X
        (math.pi, math.pi), # M
        (math.pi/2, 0.0),
        (math.pi/2, math.pi/2),
        (0.75*math.pi, 0.0),
        (0.75*math.pi, 0.75*math.pi),
        (0.5*math.pi, 0.25*math.pi),
    ]
    
    max_omega_4 = 0.0
    min_omega_5 = float('inf')
    
    for kx, ky in k_points:
        # Build the dynamical matrix
        # D[G, G'] = (1/epsilon_{G-G'}) * |G+G'+K|^2
        # where K is the k-point
        
        K = np.array([kx, ky])
        D = np.zeros((n_pw_total, n_pw_total), dtype=np.complex128)
        
        for i in range(n_pw_total):
            Gi = np.array(G_indices[i], dtype=np.float64)
            for j in range(n_pw_total):
                Gj = np.array(G_indices[j], dtype=np.float64)
                total_k = Gi + Gj + K
                k_sq = total_k[0]**2 + total_k[1]**2
                D[i, j] = inv_eps_mat[i, j] * k_sq
        
        # Solve eigenvalue problem
        try:
            eigvals = np.linalg.eigvalsh(D)
            eigvals = np.real(eigvals)
            eigvals = np.sort(eigvals)
            
            # omega^2 = eigval, so omega = sqrt(eigval)
            # We want bands 4 and 5 (1-indexed), so indices 3 and 4 (0-indexed)
            if len(eigvals) >= 5:
                omega_4_sq = eigvals[3]
                omega_5_sq = eigvals[4]
                if omega_4_sq > 0:
                    omega_4 = math.sqrt(omega_4_sq)
                    max_omega_4 = max(max_omega_4, omega_4)
                if omega_5_sq > 0:
                    omega_5 = math.sqrt(omega_5_sq)
                    min_omega_5 = min(min_omega_5, omega_5)
        except:
            pass
    
    if min_omega_5 == float('inf') or max_omega_4 == 0.0:
        return -1.0  # No valid gap
    
    gap_ratio = 2.0 * (min_omega_5 - max_omega_4) / (min_omega_5 + max_omega_4)
    return gap_ratio

