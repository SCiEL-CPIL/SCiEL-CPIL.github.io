import random
import time

def construct(n):
    if n <= 4:
        # Standard construction is optimal for n <= 4
        word = [1]
        for m in range(2, n + 1):
            perms, seen = [], set()
            for i in range(len(word) - m + 2):
                window = tuple(word[i:i + m - 1])
                if len(set(window)) == m - 1 and window not in seen:
                    seen.add(window)
                    perms.append(window)
            new = []
            for p in perms:
                block = list(p) + [m] + list(p)
                overlap = next(o for o in range(min(len(new), len(block)), -1, -1) if new[len(new) - o:] == block[:o])
                new += block[overlap:]
            word = new
        return "".join(map(str, word))

    # For n > 4, use heuristic optimization
    # 1. Generate standard superpermutation
    def get_standard_superperm(n):
        word = [1]
        for m in range(2, n + 1):
            perms, seen = [], set()
            for i in range(len(word) - m + 2):
                window = tuple(word[i:i + m - 1])
                if len(set(window)) == m - 1 and window not in seen:
                    seen.add(window)
                    perms.append(window)
            new = []
            for p in perms:
                block = list(p) + [m] + list(p)
                overlap = next(o for o in range(min(len(new), len(block)), -1, -1) if new[len(new) - o:] == block[:o])
                new += block[overlap:]
            word = new
        return word

    std_word = get_standard_superperm(n)
    
    # Extract permutations from the standard word
    # The standard word contains all permutations.
    # We can identify the order in which they appear.
    # A permutation appears as a window of length n.
    # In the standard construction, every window is a permutation? No, as seen before, some are not.
    # But the set of valid permutations is covered.
    # Let's just generate the list of all permutations and find a good ordering.
    
    import itertools
    
    perms = list(itertools.permutations(range(1, n + 1)))
    # Shuffle to break symmetry or start from standard order?
    # Standard order is generated by the recursive construction.
    # Let's try to optimize the standard order.
    
    # Get standard order of permutations
    std_order = []
    seen = set()
    for i in range(len(std_word) - n + 1):
        w = tuple(std_word[i:i+n])
        if w not in seen:
            seen.add(w)
            std_order.append(w)
            
    # The standard order should contain all n! permutations.
    # Verify
    if len(std_order) != len(perms):
        # Fallback: just return standard
        return "".join(map(str, std_word))
        
    # Local Search: 2-opt or similar
    # Objective: Minimize sum of (n - overlap(P_i, P_{i+1}))
    
    def overlap(p1, p2):
        # Max k such that p1[-k:] == p2[:k]
        max_k = min(len(p1), len(p2))
        for k in range(max_k, -1, -1):
            if p1[-k:] == p2[:k]:
                return k
        return 0

    def calc_length(order):
        if not order:
            return 0
        length = n
        for i in range(len(order) - 1):
            length += n - overlap(order[i], order[i+1])
        return length

    current_order = std_order
    current_len = calc_length(current_order)
    
    start_time = time.time()
    time_limit = 110.0 # Leave 10s buffer
    
    # Simple hill climbing with random restarts or swaps
    # Given 5040 elements, full 2-opt is O(N^2) per pass. 5040^2 ~ 25M. Too slow for many iterations.
    # Use local swaps (adjacent) and random jumps.
    
    improved = True
    while improved and time.time() - start_time < time_limit:
        improved = False
        # Randomly select a subset of indices to check for swaps to speed up
        # Or just iterate through all adjacent pairs (O(N))
        for i in range(len(current_order) - 1):
            if time.time() - start_time > time_limit:
                break
            # Try swapping i and i+1
            old_len = current_len
            current_order[i], current_order[i+1] = current_order[i+1], current_order[i]
            
            # Calculate new length efficiently
            # Only affected parts: (i-1, i), (i, i+1), (i+1, i+2)
            # We need to recalculate the cost of edges (i-1->i), (i->i+1), (i+1->i+2)
            # Old costs:
            cost_old_1 = n - overlap(current_order[i-1], current_order[i]) if i > 0 else 0
            # Wait, we swapped. Let's just recalc the segment.
            
            # Better: store overlaps in an array?
            # For simplicity, just recalc the 3 affected edges.
            
            def get_cost(idx1, idx2):
                if idx1 == -1 or idx1 >= len(current_order) or idx2 == -1 or idx2 >= len(current_order):
                    return 0
                if idx2 == idx1 + 1:
                    return n - overlap(current_order[idx1], current_order[idx2])
                return 0 # Not adjacent
            
            # This is getting messy. Let's just recalc the whole length if N is small, but N=5040 is large.
            # Recalculating whole length is O(N). 5040 ops.
            # If we do 5040 swaps, that's 25M ops. In Python, this is ~1-2 seconds.
            # So we can do a full pass of adjacent swaps in ~1-2 seconds.
            # We can do multiple passes.
            
            new_len = calc_length(current_order)
            
            if new_len < current_len:
                current_len = new_len
                improved = True
            else:
                # Revert
                current_order[i], current_order[i+1] = current_order[i+1], current_order[i]
                
        # If no improvement in adjacent swaps, try some random 2-opt moves
        if not improved:
            # Pick two random indices i, j and reverse the segment?
            # Or just swap two random elements?
            for _ in range(100):
                if time.time() - start_time > time_limit:
                    break
                i, j = random.sample(range(len(current_order)), 2)
                old_len = current_len
                current_order[i], current_order[j] = current_order[j], current_order[i]
                new_len = calc_length(current_order)
                if new_len < current_len:
                    current_len = new_len
                    improved = True
                else:
                    current_order[i], current_order[j] = current_order[j], current_order[i]

    # Reconstruct word
    word = list(current_order[0])
    for i in range(1, len(current_order)):
        p_prev = current_order[i-1]
        p_curr = current_order[i]
        ov = overlap(p_prev, p_curr)
        word.extend(p_curr[ov:])
        
    return "".join(map(str, word))
