"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import time
import random

# EVOLVE-BLOCK-START
def construct():
    """
    Constructs a binary code of length 18 with minimum Hamming distance at least 6.
    Aims for the 512-word [18, 9, 6] code by extending the Reed-Muller code.
    """
    N = 18
    MIN_DIST = 6
    DEADLINE = time.time() + 55.0  # Safety margin for 60s limit
    
    # 1. Generate Reed-Muller code RM(1, 4) words
    # These are affine functions on F_2^4.
    # Basis for RM(1, 4):
    # Constant 1
    # x_0, x_1, x_2, x_3
    rm_basis = []
    # Constant 1
    rm_basis.append((1 << N) - 1)  # All ones
    # Variables
    for i in range(4):
        word = 0
        for point in range(16):
            if (point >> i) & 1:
                word |= (1 << point)
        # Extend to length 18 by adding 2 zero bits
        # The RM code is on 16 coordinates. We extend by 2 zeros.
        # So the word is just the 16-bit word.
        rm_basis.append(word)
        
    # The RM code has dimension 5 (1 constant + 4 variables).
    # Wait, RM(1, m) has dimension m+1. Here m=4, so dim 5.
    # Size 32.
    
    # We want to extend this to dimension 9 to get 512 words.
    # We need to find 4 more linearly independent vectors to add to the basis.
    # Such that the minimum distance of the resulting code is >= 6.
    
    current_basis = rm_basis[:]
    
    # Helper to check if a new vector can be added to the basis
    # while maintaining min distance >= 6 for the code generated by the basis.
    # Actually, we need to check if the code generated by (current_basis + [new_vec])
    # has min distance >= 6.
    # This is equivalent to checking if the new vector has distance >= 6
    # from all codewords in the current code? No.
    # If C is a code with min dist d, and we add a vector v,
    # the new code is C + <v>.
    # The min distance of the new code is min(d, min_{c in C} wt(c+v)).
    # So we need min_{c in C} wt(c+v) >= 6.
    
    def get_codewords(basis):
        words = [0]
        for v in basis:
            new_words = []
            for w in words:
                new_words.append(w ^ v)
            words.extend(new_words)
        return words

    # Current code words
    current_words = get_codewords(current_basis)
    
    # Candidate vectors to add
    # We can iterate through all 2^18 vectors, but that's 262k.
    # For each candidate, we check distance to all current_words.
    # Current size grows.
    # Initially 32 words. Later 64, 128, 256.
    # Checking 262k candidates * 256 words * 18 bits... might be slow in Python.
    # Optimization:
    # We only need to add 4 vectors.
    # We can pick candidates randomly or systematically.
    
    # Let's try a greedy search for the 4 additional vectors.
    # We will iterate through a shuffled list of all possible vectors.
    
    all_vectors = list(range(1 << N))
    random.shuffle(all_vectors)
    
    added_count = 0
    target_dim = 9
    current_dim = len(current_basis)
    
    for candidate in all_vectors:
        if time.time() > DEADLINE:
            break
        if current_dim >= target_dim:
            break
            
        # Check if candidate is in the span of current_basis
        # Simple check: is candidate in current_words?
        # If yes, skip.
        if candidate in current_words:
            continue
            
        # Check min distance
        # min_dist_new = min(wt(candidate ^ w) for w in current_words)
        # We need this to be >= 6.
        
        min_d = 18
        for w in current_words:
            d = (candidate ^ w).bit_count()
            if d < min_d:
                min_d = d
                if min_d < MIN_DIST:
                    break
                    
        if min_d >= MIN_DIST:
            # Add candidate to basis
            current_basis.append(candidate)
            current_dim += 1
            # Regenerate words
            current_words = get_codewords(current_basis)
            added_count += 1
            
    # If we reached dimension 9, we have 512 words.
    # If not, we return what we have.
    
    final_words = get_codewords(current_basis)
    
    # Verify
    # The task requires distinct integers.
    # The code is linear, so words are distinct.
    
    return final_words

# EVOLVE-BLOCK-END
