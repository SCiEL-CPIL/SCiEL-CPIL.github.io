import time
import random

def construct():
    N = 17
    MIN_DIST = 6
    start_time = time.time()
    # Safety margin: evaluator kills at 90s wall-clock. We'll aim for 50s of work.
    deadline = start_time + 50.0
    
    # 1. Construct the base [18,9,6] extended quadratic residue code shortened to length 17.
    # The [18,9,6] code is the extended QR code.
    # Generator polynomial g(x) = 1 + x^3 + x^5 + x^6 + x^9 (one of the two, actually usually 1+x^3+x^5+x^6+x^9 or similar).
    # Let's use a known generator for the [18,9,6] code.
    # According to literature, the generator polynomial for the [18,9,6] QR code over F2 is g(x) = 1 + x^3 + x^5 + x^6 + x^9.
    # Wait, degree of g must be 9 for a [18,9] code.
    # Let's verify: g(x) = 1 + x^3 + x^5 + x^6 + x^9 has degree 9.
    # We generate 512 cyclic shifts (well, 2^9=512 words, but it's a [18,9] code so 2^9=512 words? No, [18,9] means dimension 9, so 2^9=512 words. Wait.
    # A [n, k, d] code has 2^k words. [18,9,6] has 512 words.
    # The shortened code [17,8,6] has 2^8=256 words.
    
    # Let's generate the [18,9,6] code words.
    # The code is cyclic. Generated by g(x).
    # g = [1, 0, 0, 1, 0, 1, 1, 0, 0, 1] (bits for x^0 to x^9)
    # Actually, let's be careful with bit order.
    # g(x) = 1 + x^3 + x^5 + x^6 + x^9.
    # Bits: b0=1, b1=0, b2=0, b3=1, b4=0, b5=1, b6=1, b7=0, b8=0, b9=1.
    
    g_poly = [1, 0, 0, 1, 0, 1, 1, 0, 0, 1]  # index i is coeff of x^i
    
    def cyclic_shift(bits, shift):
        # bits is a list of 18 ints (0 or 1)
        # shift left by 'shift' positions, wrapping around?
        # Cyclic codes: x^i * g(x) mod (x^18 - 1).
        # So we multiply by x^i mod x^18-1.
        res = [0] * 18
        for j in range(10):
            if bits[j]:
                # Add x^(j+i) mod (x^18-1)
                pos = (j + shift) % 18
                res[pos] ^= 1
        return res
    
    # Generate all 2^9 = 512 codewords of the [18,9,6] code.
    # A codeword is a linear combination of x^i * g(x) for i in 0..8.
    base_18_words = set()
    for mask in range(512):
        word = [0] * 18
        for i in range(9):
            if (mask >> i) & 1:
                shifted_g = cyclic_shift(g_poly, i)
                for j in range(18):
                    word[j] ^= shifted_g[j]
        # Convert to int
        val = 0
        for j in range(18):
            if word[j]:
                val |= (1 << j)
        base_18_words.add(val)
        
    # Shorten by deleting the last coordinate (bit 17, index 17).
    # Wait, standard shortening: fix a coordinate to 0 and delete it.
    # For a cyclic code, shortening at any coordinate is equivalent due to automorphism?
    # Usually we shorten at coordinate 0 or n-1.
    # Let's shorten at coordinate 17 (the highest bit).
    # We keep only words where bit 17 is 0.
    # Then remove bit 17.
    
    base_17_words = []
    for w in base_18_words:
        if (w >> 17) & 1 == 0:
            new_w = w & ((1 << 17) - 1)
            base_17_words.append(new_w)
            
    # There should be 256 such words.
    # Let's verify.
    # assert len(base_17_words) == 256, f"Base code size: {len(base_17_words)}"
    
    # 2. Now, we want to add more words.
    # The "holes" are words not in the base code.
    # We look for words w such that d(w, b) >= 6 for all b in base_17_words.
    # If we find such a w, we can add it.
    # Then we look for another w' such that d(w', b) >= 6 for all b in base AND d(w', w) >= 6.
    # This is a greedy search for a maximum clique in the graph of valid extensions.
    
    # To speed up, let's precompute the "forbidden" regions.
    # Actually, with 256 base words, checking a candidate w against all 256 is O(256 * 17) which is very fast.
    # 131072 total possible words.
    # We can iterate through all 131072 words and check if they are valid.
    
    valid_extensions = []
    base_set = set(base_17_words)
    
    # Optimization: 
    # Instead of checking all 131k words against 256 base words (131k * 256 * 17 ops ~ 567M ops),
    # which might be slow in Python (maybe 10-20s), we can be smarter.
    # Or just do it if it's fast enough. 50s limit. 567M simple ops in Python is likely too slow (Python does ~10-50M ops/s for simple loops).
    # We need a faster way.
    
    # Alternative: 
    # The base code is linear. 
    # d(w, b) = wt(w + b).
    # We need wt(w + b) >= 6 for all b in C.
    # This means w is not in the radius 5 ball around any codeword in C.
    
    # Let's use NumPy to speed up the distance calculation?
    # Or just use the fact that we can generate the balls?
    # The volume of radius 5 ball in F2^17 is sum(i=0 to 5) C(17,i) = 1 + 17 + 136 + 680 + 2380 + 6188 = 9402.
    # 256 * 9402 ~ 2.4M entries. We can create a boolean array of size 131072 and mark all words within distance 5 of any base codeword as forbidden.
    # This is much faster: 2.4M set operations.
    
    import numpy as np
    
    forbidden = np.zeros(1 << 17, dtype=bool)
    
    # Precompute all masks of weight <= 5
    # This is a one-time cost.
    masks = []
    for w in range(1 << 17):
        if w.bit_count() <= 5:
            masks.append(w)
            
    # There are 9402 such masks.
    
    # Mark forbidden regions
    for b in base_17_words:
        for m in masks:
            forbidden[b ^ m] = True
            
    # Now, any word w where forbidden[w] is False is a valid extension.
    valid_extensions = [w for w in range(1 << 17) if not forbidden[w]]
    
    # Let's check how many valid extensions there are.
    # If it's small, we can just greedily pick them.
    # If it's large, we need a clique heuristic.
    
    # 3. Greedy Clique on valid_extensions
    # We want the largest subset of valid_extensions such that pairwise distance >= 6.
    # Note: If w1 and w2 are both valid extensions, they are already distance >= 6 from ALL base words.
    # We just need to ensure d(w1, w2) >= 6.
    
    # Let's build a compatibility graph among valid_extensions?
    # If |valid_extensions| is small (e.g., < 1000), we can do pairwise checks.
    # If it's large, we need a heuristic.
    
    # Let's first count them.
    num_valid = len(valid_extensions)
    # print(f"Valid extensions: {num_valid}")
    
    # Strategy:
    # Greedy selection.
    # Sort valid_extensions? Maybe by weight? Or randomly?
    # Let's try a greedy approach:
    # 1. Start with empty set S.
    # 2. Iterate through valid_extensions (shuffled or sorted by degree in the "compatibility" sense? Hard to compute degree without building graph).
    # 3. For each w in valid_extensions:
    #      if d(w, s) >= 6 for all s in S:
    #          S.append(w)
    
    # This is O(num_valid * |S| * 17).
    # If num_valid is ~1000 and |S| is ~100, that's 1000 * 100 * 17 = 1.7M ops. Very fast.
    
    # Let's implement this.
    # To get a better clique, we can do multiple restarts with different orderings.
    
    def greedy_clique(candidates, max_size_hint=100):
        # candidates is a list of ints
        # Returns a list of ints that are pairwise distance >= 6
        result = []
        for w in candidates:
            ok = True
            for s in result:
                if (w ^ s).bit_count() < MIN_DIST:
                    ok = False
                    break
            if ok:
                result.append(w)
        return result
    
    best_extension_set = []
    
    # Try a few orderings
    # 1. Natural order
    # 2. Shuffled order (a few times)
    # 3. Order by weight (maybe helps?)
    
    # Let's do 50 random restarts if we have time.
    
    num_restarts = 100
    for i in range(num_restarts):
        if time.time() > deadline - 5:
            break
            
        shuffled_candidates = valid_extensions[:]
        random.shuffle(shuffled_candidates)
        
        current_set = greedy_clique(shuffled_candidates)
        
        if len(current_set) > len(best_extension_set):
            best_extension_set = current_set[:]
            
        # If we found a large set, we can stop early?
        # Theoretical max?
        # If we add ~80-100 extensions to 256, we get ~340.
        # Let's see what size we get.
        
    # 4. Combine base and extensions
    final_codewords = base_17_words + best_extension_set
    
    # 5. Final Safety Check
    # Verify all distinct and min distance >= 6.
    # This is O(K^2). K ~ 350. 350^2 = 122,500 checks. Fast.
    
    final_codewords = list(set(final_codewords))
    
    # If any pair is too close, remove the later one?
    # Since we built it carefully, this shouldn't happen, but just in case.
    verified = []
    for w in final_codewords:
        ok = True
        for v in verified:
            if (w ^ v).bit_count() < MIN_DIST:
                ok = False
                break
        if ok:
            verified.append(w)
            
    return verified

