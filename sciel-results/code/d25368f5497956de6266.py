def _greedy_fallback(n_rows, k):
    """Original greedy: always valid, used as safety net."""
    used, rows = set(), []
    for _ in range(n_rows):
        row, x = [0], 0
        while len(row) < k + 1:
            x += 1
            new = {x - a for a in row}
            if not new & used:
                row.append(x)
                used |= new
        rows.append(row)
    return rows


def _scope(rows):
    return max(max(r) for r in rows)


def _backtracking_search(n_rows, k, deadline, rng):
    """
    Backtracking search with forward checking.
    Variables: rows (n_rows of them), each row is a list of k+1 increasing ints starting at 0.
    We build rows one at a time. Within a row we build entries left to right.
    The 'used' set holds all positive differences seen so far (across all completed rows
    and the partially-built current row).
    """
    best = [None]
    best_scope = [float('inf')]

    # Precompute: for a row, the differences generated by adding candidate x to current row
    # We search row by row. To make pruning effective, we try to find rows with small scope.

    def search(row_idx, current_row, used, current_time):
        if current_time > deadline:
            return
        if row_idx == n_rows:
            # All rows complete
            sc = _scope([current_row] + best_rows)
            # Actually we need all rows; let's track them
            return

        # We need to track all rows. Let me restructure: pass a list of completed rows.
        pass

    # Better: iterative deepening on scope bound, with backtracking.
    # But that's expensive. Instead: build rows greedily but with backtracking on the
    # choice of next entry within a row, and try multiple orderings.

    # Simpler effective approach: randomized greedy with restarts + local improvement.
    # Given the time budget, I'll do: many randomized greedy constructions, keep best,
    # then try to improve via local search (swap/shift entries).

    best_rows = _greedy_fallback(n_rows, k)
    best_sc = _scope(best_rows)

    t0 = time.time()
    attempts = 0
    while time.time() < deadline:
        attempts += 1
        # Randomized greedy with a "bias" parameter
        used, rows = set(), []
        success = True
        for r in range(n_rows):
            row = [0]
            x = 0
            while len(row) < k + 1:
                # Try next few candidates, pick one that minimizes future conflict
                # (i.e., introduces the "cheapest" new differences)
                found = False
                # Look ahead a window of candidates
                window = 1 + (attempts % 7)  # vary window size
                candidates = []
                for cand in range(x + 1, x + 1 + window):
                    new = {cand - a for a in row}
                    if not new & used:
                        # Score: sum of new differences (prefer small)
                        candidates.append((sum(new), cand))
                if candidates:
                    candidates.sort()
                    # Pick with some randomness
                    if rng.random() < 0.7:
                        chosen = candidates[0][1]
                    else:
                        chosen = candidates[rng.randrange(len(candidates))][1]
                    row.append(chosen)
                    used |= {chosen - a for a in row[:-1]}
                    x = chosen
                    found = True
                else:
                    # No candidate in window; extend
                    x += 1
                    new = {x - a for a in row}
                    if not new & used:
                        row.append(x)
                        used |= new
                        found = True
                    else:
                        continue
                if not found:
                    # Shouldn't happen since we always advance x
                    pass
            rows.append(row)
        sc = _scope(rows)
        if sc < best_sc:
            best_sc = sc
            best_rows = rows

    return best_rows, best_sc


def _local_search(rows, k, deadline, rng):
    """
    Local search: try to reduce scope by shifting entries down.
    For each row, for each position, try to decrease the entry while maintaining
    strict increase and no difference collisions.
    """
    best_rows = [list(r) for r in rows]
    best_sc = _scope(best_rows)

    def compute_used(rws):
        used = set()
        for r in rws:
            for i in range(len(r)):
                for j in range(i + 1, len(r)):
                    used.add(r[j] - r[i])
        return used

    improved = True
    t0 = time.time()
    while improved and time.time() < deadline:
        improved = False
        for ri in range(len(best_rows)):
            row = best_rows[ri]
            # Try to reduce each entry (from last to first to preserve increase)
            for pos in range(len(row) - 1, 0, -1):
                lower = row[pos - 1] + 1
                upper = row[pos] - 1
                if upper < lower:
                    continue
                # Try candidate values from lower upward, pick the smallest valid
                for cand in range(lower, upper + 1):
                    if cand == row[pos]:
                        break
                    # Check: does setting row[pos]=cand cause any duplicate difference?
                    # Temporarily set and check
                    old = row[pos]
                    row[pos] = cand
                    # Check all pairs in this row
                    valid = True
                    diffs_in_row = set()
                    for i in range(len(row)):
                        for j in range(i + 1, len(row)):
                            d = row[j] - row[i]
                            if d in diffs_in_row:
                                valid = False
                                break
                            diffs_in_row.add(d)
                        if not valid:
                            break
                    if valid:
                        # Check against other rows
                        for rj in range(len(best_rows)):
                            if rj == ri:
                                continue
                            r = best_rows[rj]
                            for i in range(len(r)):
                                for j in range(i + 1, len(r)):
                                    d = r[j] - r[i]
                                    if d in diffs_in_row:
                                        valid = False
                                        break
                                if not valid:
                                    break
                            if not valid:
                                break
                    if valid:
                        new_sc = _scope(best_rows)
                        if new_sc <= best_sc:
                            best_sc = new_sc
                            improved = True
                        else:
                            row[pos] = old
                    else:
                        row[pos] = old
                        break  # no point trying larger cand in this direction
                # After trying, if row[pos] was changed, continue; else keep original
        # Also try to reduce the overall max by checking if the global max entry
        # can be moved down
    return best_rows, best_sc


def construct(n_rows, k):
    deadline = time.time() + 100.0  # safety margin before 150s kill
    rng = random.Random(12345)

    # Phase 1: randomized greedy with restarts
    rows, sc = _backtracking_search(n_rows, k, deadline - 30.0, rng)

    # Phase 2: local search to polish
    if time.time() < deadline - 5.0:
        rows, sc = _local_search(rows, k, deadline - 5.0, rng)

    return rows

