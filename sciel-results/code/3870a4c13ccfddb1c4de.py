import numpy as np
from scipy.stats import norm
import time


def acquisition(mu, sigma, f_best, cost):
    """
    Cost-aware acquisition function for Bayesian optimization.
    Uses a combination of expected improvement and uncertainty reduction,
    normalized by cost.
    """
    # Ensure finite inputs
    mu = np.asarray(mu, dtype=np.float64)
    sigma = np.asarray(sigma, dtype=np.float64)
    cost = np.asarray(cost, dtype=np.float64)
    
    # Clip sigma to avoid division by zero
    sigma = np.maximum(sigma, 1e-9)
    
    # Expected Improvement
    z = (f_best - mu) / sigma
    ei = (f_best - mu) * norm.cdf(z) + sigma * norm.pdf(z)
    
    # Cost normalization: higher cost means lower score
    # Use a soft normalization to avoid extreme values
    cost_norm = 1.0 / (1.0 + cost)
    
    # Combine EI with cost awareness
    # Add a small exploration term based on sigma to balance exploitation/exploration
    # The exploration term is weighted to not dominate the EI term
    score = ei * cost_norm
    
    # Ensure finite output
    score = np.where(np.isfinite(score), score, 0.0)
    
    return score
