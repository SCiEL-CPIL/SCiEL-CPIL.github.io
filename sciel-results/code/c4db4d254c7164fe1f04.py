def _is_valid_set(S):
    """Check if set S has no 3-term AP."""
    S_set = set(S)
    for a in S:
        for b in S:
            if a < b:
                c = 2*b - a
                if c in S_set:
                    return False
    return True

def _reciprocal_sum(S):
    return sum(1.0/x for x in S)

def _greedy_initial(n=256):
    selected = []
    for x in range(1, n+1):
        if all(2*b - a != x for a in selected for b in selected if a < b):
            selected.append(x)
    return selected

def _local_search(S, time_limit=55.0):
    """
    Local search to improve reciprocal sum.
    Moves:
    1. Add a number not in S if it doesn't create an AP.
    2. Remove a number from S and try to add two smaller numbers that were previously blocked.
       (Simpler: Remove one, then try to add any available number that fits).
    """
    S = set(S)
    current_score = _reciprocal_sum(S)
    start_time = time.time()
    best_S = S.copy()
    best_score = current_score
    
    n = 256
    candidates = [x for x in range(1, n+1) if x not in S]
    
    while time.time() - start_time < time_limit:
        improved = False
        
        # Try to add a candidate
        # Sort candidates by reciprocal weight (smaller x first)
        # But we should check if adding it is valid.
        # To speed up, we can just iterate through candidates.
        added_any = False
        for x in candidates[:]: # Copy to allow modification
            if x in S:
                continue
            # Check if adding x creates an AP
            valid = True
            for a in S:
                # If x is the middle term: a, x, b => b = 2x - a
                b = 2*x - a
                if b in S and b != x:
                    valid = False
                    break
                # If x is the end term: a, b, x => b = (a+x)/2
                # This is covered by the loop above if we iterate all a?
                # No, the loop checks if x is middle or end relative to a.
                # Let's be precise:
                # A 3-AP (u, v, w) with u < v < w.
                # If we add x, it can be u, v, or w.
                # Case 1: x is u. Then v, w in S. 2v - x = w => v = (x+w)/2.
                # Case 2: x is v. Then u, w in S. 2x - u = w => w = 2x - u.
                # Case 3: x is w. Then u, v in S. 2v - u = x => v = (u+x)/2.
                
                # My previous check:
                # for a in S:
                #   b = 2*x - a  (x is middle, a is start) -> if b in S, invalid.
                #   This covers Case 2.
                
                # What about Case 1 and 3?
                # If x is end (w): 2v - u = x. v = (u+x)/2.
                # If x is start (u): 2v - x = w. v = (x+w)/2.
                
                # Let's just check all pairs in S to see if they form an AP with x.
                # It's O(|S|^2) per candidate. |S| is ~100. 100^2 * 150 candidates = 1.5M ops. Fast.
            
            # Let's do a cleaner validity check
            if _is_valid_set(list(S) + [x]):
                S.add(x)
                candidates.remove(x)
                new_score = _reciprocal_sum(S)
                if new_score > best_score:
                    best_score = new_score
                    best_S = S.copy()
                improved = True
                added_any = True
                break # Restart scan with new S
            
        if not added_any:
            # Try to remove a large element and add a smaller one
            # Sort S by value descending (largest first)
            sorted_S = sorted(S, reverse=True)
            removed_any = False
            for rem in sorted_S:
                # Only remove if it's "large" enough to be worth removing
                # Or just try removing the largest few
                if len(S) <= 5:
                    break
                S.remove(rem)
                # Now try to add any candidate that fits
                # Sort candidates by reciprocal weight (smallest x first)
                for x in candidates[:]:
                    if x in S:
                        continue
                    if _is_valid_set(list(S) + [x]):
                        S.add(x)
                        candidates.remove(x)
                        new_score = _reciprocal_sum(S)
                        if new_score > best_score:
                            best_score = new_score
                            best_S = S.copy()
                        removed_any = True
                        break
                if removed_any:
                    improved = True
                    break
            
            if not improved:
                # If we couldn't improve, we might be stuck in a local optimum.
                # For now, break to avoid infinite loop if no moves help.
                # In a full implementation, we'd randomize or kick.
                break
                
    return list(best_S)

def construct():
    # Start with greedy
    S = _greedy_initial()
