import time
import random
import heapq

def _set_sizes(A):
    """Compute |A+A| and |A*A| with equal summands/factors allowed."""
    A = list(A)
    n = len(A)
    sums = set()
    prods = set()
    for i in range(n):
        ai = A[i]
        for j in range(i, n):
            sums.add(ai + A[j])
            prods.add(ai * A[j])
    return len(sums), len(prods)

def _objective(A):
    s, p = _set_sizes(A)
    return max(s, p)

def _validate(A):
    if len(A) != 20:
        return False
    if len(set(A)) != 20:
        return False
    if any(x < 1 or x > 10000 for x in A):
        return False
    return True

def _generate_smallest_products(bases, n_target):
    """Generate the n_target smallest numbers in the multiplicative monoid generated by bases."""
    if not bases:
        return [1] * n_target
    visited = set([1])
    heap = [1]
    heapq.heapify(heap)
    result = []
    
    while heap and len(result) < n_target:
        x = heapq.heappop(heap)
        # Check if it's still valid (might have been added multiple times? No, visited check on push handles it)
        if x in visited:
            result.append(x)
            for b in bases:
                nx = x * b
                if nx <= 10000 and nx not in visited:
                    visited.add(nx)
                    heapq.heappush(heap, nx)
    return result

def _local_refine(A, deadline, max_rounds=2000):
    """
    Local refinement: try replacing each element with a better one.
    """
    n = len(A)
    A = sorted(A)
    current_cost = _objective(A)
    best_A = A[:]
    best_cost = current_cost
    
    for _ in range(max_rounds):
        if time.time() > deadline:
            break
        
        improved = False
        indices = list(range(n))
        random.shuffle(indices)
        
        for idx in indices:
            if time.time() > deadline:
                break
            
            old_val = A[idx]
            others = [A[i] for i in range(n) if i != idx]
            used = set(others)
            
            trials = set()
            
            # 1. Local neighborhood
            for d in range(-15, 16):
                v = old_val + d
                if 1 <= v <= 10000 and v not in used:
                    trials.add(v)
                    
            # 2. Small numbers (often help sumsets)
            for v in range(1, 50):
                if v not in used:
                    trials.add(v)
                    
            # 3. Structured: Multiples of smallest other element
            if others:
                min_other = min(others)
                for m in range(1, 20):
                    v = min_other * m
                    if 1 <= v <= 10000 and v not in used:
                        trials.add(v)
                        
            # 4. Structured: Values that create product overlap
            # If we replace old_val with v, v * others should overlap with existing prods
            # Hard to check quickly, so we just add some random multiples of others
            for a in others[:5]: # Limit to first 5
                for m in range(2, 10):
                    v = a * m
                    if 1 <= v <= 10000 and v not in used:
                        trials.add(v)
                        
            # 5. Random
            for _ in range(20):
                v = random.randint(1, 10000)
                if v not in used:
                    trials.add(v)
            
            # Limit trials to avoid slow iteration
            trial_list = list(trials)
            if len(trial_list) > 150:
                random.shuffle(trial_list)
                trial_list = trial_list[:150]
                
            for v in trial_list:
                if v in used or v == old_val:
                    continue
                A[idx] = v
                new_cost = _objective(A)
                if new_cost < current_cost:
                    current_cost = new_cost
                    improved = True
                    if new_cost < best_cost:
                        best_cost = new_cost
                        best_A = A[:]
                    break
                else:
                    A[idx] = old_val
                    
        if not improved:
            break
            
    return best_A, best_cost

def construct():
    start_time = time.time()
    deadline = start_time + 80.0  # 10s safety margin
    n = 20
    max_val = 10000
    
    random.seed(42)
    
    best_A = None
    best_cost = float('inf')
    
    # 1. Generate Diverse Candidates
    candidates = []
    
    # Multiplicative Grids
    base_configs = [
        [2],
        [2, 3],
        [2, 5],
        [3, 5],
        [2, 3, 5],
        [2, 7],
        [3, 4],
        [5, 7],
        [2, 11],
    ]
    
    for bases in base_configs:
        A = _generate_smallest_products(bases, n)
        if len(A) == n and _validate(A):
            candidates.append(A)
            
    # Additive / Small Integers
    candidates.append(list(range(1, n + 1)))
    candidates.append(list(range(1, 41, 2)))  # Odds
    candidates.append(list(range(2, 42, 2)))  # Evens
    candidates.append([i * 3 for i in range(1, n + 1)])
    
    # Random Small
    for _ in range(10):
        A = random.sample(range(1, 101), n)
        candidates.append(sorted(A))
        
    # Random Medium
    for _ in range(5):
        A = random.sample(range(1, 500), n)
        candidates.append(sorted(A))
        
    # 2. Evaluate and Sort Candidates
    scored_candidates = []
    for A in candidates:
        if not _validate(A):
            continue
        cost = _objective(A)
        scored_candidates.append((cost, A))
        
    scored_candidates.sort(key=lambda x: x[0])
    
    # 3. Local Search on Best Candidates
    # Refine the top 10 candidates
    for i, (cost, A) in enumerate(scored_candidates):
        if time.time() > deadline - 5.0:
            break
        # Allocate more time to better candidates
        rounds = 5000 if i < 3 else 2000
        refined_A, refined_cost = _local_refine(A, deadline, max_rounds=rounds)
        if refined_cost < best_cost:
            best_cost = refined_cost
            best_A = refined_A
            
    # 4. Additional Random Restarts if Time Permits
    if best_A is None:
        best_A = list(range(1, n + 1))
        best_cost = _objective(best_A)
        
    while time.time() < deadline - 2.0:
        # Generate a random set, biased towards small numbers
        # Mix of small and medium
        A = []
        while len(A) < n:
            if random.random() < 0.5:
                v = random.randint(1, 50)
            else:
                v = random.randint(1, 1000)
            if v not in A:
                A.append(v)
        A = sorted(A)
        
        # Quick refine
        refined_A, refined_cost = _local_refine(A, deadline, max_rounds=500)
        if refined_cost < best_cost:
            best_cost = refined_cost
            best_A = refined_A
            
    return best_A
