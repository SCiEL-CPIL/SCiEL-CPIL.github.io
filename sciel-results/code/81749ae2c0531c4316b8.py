    # 1. Parity: sum c_i = 0
    # 2. For each non-residue a in {2,3,8,10,12,13,14,15,18}:
    #    sum_{i=0}^{18} c_i * (i^a mod 19) = 0   [mod 2]
    #    (Note: for i=0, 0^a = 0 for a>0, so c_0 doesn't appear in these sums
    #     except through the parity check)
    #
    # Wait, that's not right. Let me reconsider.
    #
    # The standard QR code definition: For prime p, the QR code is the cyclic code
    # of length p with generator polynomial g(x) = lcm of minimal polynomials of
