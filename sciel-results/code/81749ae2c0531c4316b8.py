    #
    # So g(x) has degree 9, and the [19,10,5] code has dimension 10.
    #
    # To construct g(x): I need to work in GF(2^18) or use the fact that
    # x^19 - 1 factors over GF(2) into irreducible polynomials.
    #
    # This is getting complex. Let me use a different strategy:
    # I'll hardcode the 512 codewords of the shortened code, or better,
    # I'll use a known generator matrix.
    #
    # Actually, let me just do the greedy approach more efficiently, but start
    # from a better initial set. Or, I can construct the QR code by brute force
    # over the 2^10 message space if I can find the generator matrix.
    #
    # Let me try to compute g(x) for p=19.
    # x^19 - 1 = (x-1) * (x^18 + x^17 + ... + x + 1) over GF(2)
    # The cyclotomic polynomial Phi_19(x) = (x^19-1)/(x-1) has degree 18.
    # Over GF(2), Phi_19(x) factors into two irreducible polynomials of degree 9
    # (since ord_19(2) = 18, and 18 = 2 * 9, so there are 2 factors of degree 9).
    #
    # One factor corresponds to the residues, the other to the non-residues.
    #
    # Let me compute Phi_19(x) mod 2:
    # Phi_19(x) = x^18 + x^17 + x^16 + ... + x + 1
    #
    # I need to factor this over GF(2). Let me do it by trial.
    # A degree-9 factor f(x) must satisfy f(x) * f(x^2) = Phi_19(x) mod 2
