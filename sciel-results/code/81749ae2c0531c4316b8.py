    # This is tedious by hand. Let me just use a computational approach in the code.

    # Compute the generator polynomial for the QR code of length 19
    # by factoring x^19 - 1 over GF(2)
    
    def gf2_poly_mult(p, q):
        """Multiply two polynomials over GF(2), represented as lists of coefficients."""
        r = [0] * (len(p) + len(q) - 1)
        for i, a in enumerate(p):
            if a:
                for j, b in enumerate(q):
                    if b:
                        r[i + j] ^= 1
        return r
    
    def gf2_poly_divmod(num, den):
        """Divide num by den over GF(2), return (quotient, remainder)."""
        num = list(num)
        den = list(den)
        # Remove leading zeros
        while den and den[0] == 0:
            den = den[1:]
        if not den:
            raise ValueError("Division by zero")
        
        q = [0] * len(num)
        r = list(num)
        den_deg = len(den) - 1
        
        for i in range(len(r) - den_deg):
            if r[i]:
                q[i] = 1
                for j in range(len(den)):
                    r[i + j] ^= den[j]
        
        # Trim
        while q and q[-1] == 0:
            q.pop()
        while r and r[-1] == 0:
            r.pop()
        if not q:
            q = [0]
        if not r:
            r = [0]
        return q, r
    
    def gf2_poly_gcd(a, b):
        """GCD of two polynomials over GF(2)."""
        a = list(a)
        b = list(b)
        while b:
            _, r = gf2_poly_divmod(a, b)
            a, b = b, r
        return a
    
    # x^19 - 1 over GF(2)
    # x^19 - 1 = x^19 + 1 (mod 2)
    x19_1 = [0] * 20  # x^19 + 1
    x19_1[0] = 1
    x19_1[19] = 1
    
    # x - 1 = x + 1
    x_1 = [1, 1]
    
    # Phi_19(x) = (x^19 + 1) / (x + 1)
    _, phi19 = gf2_poly_divmod(x19_1, x_1)
    # phi19 should be x^18 + x^17 + ... + x + 1
    
    # Now factor phi19 into two degree-9 factors.
    # Try all monic degree-9 polynomials and check if they divide phi19.
    # There are 2^8 = 256 such polynomials (leading coeff is 1, 8 free coeffs).
    
    def poly_from_bits(bits, degree):
        """Create polynomial from bits (LSB first) with given degree."""
        p = [0] * (degree + 1)
        for i, b in enumerate(bits):
            if b:
                p[i] = 1
        p[degree] = 1  # monic
        return p
    
    # Find the degree-9 factor corresponding to non-residues
    # The non-residue factor g(x) should be such that the code it generates
