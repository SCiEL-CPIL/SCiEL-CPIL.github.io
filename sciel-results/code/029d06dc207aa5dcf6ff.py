import numpy as np
import itertools
import time
import sys

D = 11

def construct():
    # 1. Generate all vectors
    all_vectors = []
    support_map = {}
    
    idx = 0
    for comb in itertools.combinations(range(D), 4):
        support = comb
        support_map[support] = []
        for signs in itertools.product([1, -1], repeat=4):
            v = [0] * D
            for k, s in zip(support, signs):
                v[k] = s
            all_vectors.append((idx, support, signs, v))
            support_map[support].append(idx)
            idx += 1
            
    N = len(all_vectors)
    
    # 2. Build Conflict Graph using Bitmasks
    # adj[i] is an integer where bit j is 1 if i and j conflict
    adj = [0] * N
    
    # For each vector, find its neighbors
    # Conflict if same support (no, distinct same support don't conflict)
    # or different support with intersection 3 and matching signs on intersection
    
    # Precompute support to indices mapping for fast lookup
    # sup_to_vecs already exists in support_map
    
    for i, (idx_i, sup_i, signs_i, vec_i) in enumerate(all_vectors):
        # Iterate over all other supports? No, only those with intersection 3.
        # There are 28 such supports.
        # For each, 2 conflicting sign patterns.
        
        # Get the 3 elements in sup_i
        # For each subset of 3 elements in sup_i:
        for mask in range(1, 16): # 4 bits
            # Count bits
            bcount = bin(mask).count('1')
            if bcount != 3:
                continue
            
            # Get the 3 elements
            common_elems = []
            for k in range(4):
                if mask & (1 << k):
                    common_elems.append(sup_i[k])
            
            # The 4th element of sup_i NOT in common_elems
            # sup_i has 4 elements. common_elems has 3.
            # Find the one in sup_i not in common_elems
            # Actually, we need to form a new support T such that T \cap S = common_elems.
            # T has 4 elements. 3 are fixed (common_elems).
            # The 4th element must be from the remaining 7 elements (11 - 4 in S).
            
            # To avoid duplicates and ensure we cover all T,
            # we can just iterate all 7 possible 4th elements.
            # But we need to map the sign pattern.
            
            # For a fixed common_elems, the signs on these 3 positions in S are fixed by signs_i.
            # Let's say positions in sup_i are p0, p1, p2, p3.
            # We need to know which positions in signs_i correspond to common_elems.
            
            pos_in_sup_i = []
            for k in range(4):
                if mask & (1 << k):
                    pos_in_sup_i.append(k)
            
            # Signs on these positions in vector i
            signs_on_common = [signs_i[p] for p in pos_in_sup_i]
            
            # Now iterate 7th elements for T
            # Remaining elements in R^11 not in sup_i
            # sup_i is a tuple of 4 ints.
            # We can precompute the list of 7 remaining ints for each support?
            # Or just iterate 0..10 and check not in sup_i.
            
            # To speed up, let's precompute for each support the list of 7 external elements.
            # But doing it inside the loop is also fine if optimized.
            
            # Let's use a set for sup_i for fast check
            sup_i_set = set(sup_i)
            
            for x in range(D):
                if x in sup_i_set:
                    continue
                
                # Construct T = common_elems + [x]
                # T is a set of 4 elements.
                # We need to find the index of this support in support_map.
                # Since support_map keys are tuples, we need to sort T?
                # The supports in support_map are generated by itertools.combinations which are sorted.
                # So we should sort T to look it up.
                
                T_list = sorted(common_elems + [x])
                T_tuple = tuple(T_list)
                
                if T_tuple not in support_map:
                    continue # Should not happen if x is valid
                
                # Now we need to find the conflicting vectors in support T.
                # The conflicting vector v in T must have the same signs as u on the common elements.
                # The common elements are common_elems.
                # We need to map the positions of common_elems in T_tuple.
                
                # Find positions of common_elems in T_tuple
                pos_in_T = []
                for elem in common_elems:
                    pos_in_T.append(T_tuple.index(elem))
                
                # The conflicting vectors in T are those where signs match on pos_in_T.
                # There are 2 such vectors (the 4th sign can be +1 or -1).
                
                # Iterate over the 16 sign patterns of T?
                # Or just construct the 2 conflicting ones directly?
                # It's faster to iterate the 2.
                
                # Let's iterate the 16 to be safe, or just construct.
                # Constructing:
                # We need to assign signs to T_tuple positions.
                # For p in pos_in_T, sign must be signs_on_common[k] where common_elems[k] is the elem at pos p.
                
                # Let's create a mapping from elem in T to required sign if it's in common.
                required_signs = {}
                for elem, s in zip(common_elems, signs_on_common):
                    required_signs[elem] = s
                
                # Now generate the 2 vectors in T that satisfy this.
                # The free element is x (since x is not in common_elems).
                # Wait, is x the only free element?
                # T has 4 elements. 3 are common. 1 is x.
                # So yes, only the sign of x is free.
                
                # So there are exactly 2 vectors in T that conflict with i.
                
                for sign_x in [1, -1]:
                    # Construct the sign tuple for T
                    sign_t = [0] * 4
                    for k, elem in enumerate(T_tuple):
                        if elem == x:
                            sign_t[k] = sign_x
                        else:
                            sign_t[k] = required_signs[elem]
                    
                    # Find the index of this vector in all_vectors
                    # We need a map from (support, signs) to index.
                    # We don't have one directly.
                    # We have support_map[support] = list of indices.
                    # We can search in that list.
                    # Or we can build a global dict (support, signs) -> index.
                    
                    # Let's build the global dict first?
                    # It's 5280 entries. Fast.
                    
                    # I will add a global map at the beginning of the function.
                    pass # Placeholder, will restructure

    # Restructure: Build global map first
    vec_map = {}
    for idx, (i, sup, sig, v) in enumerate(all_vectors):
        vec_map[(sup, sig)] = idx
        
    # Re-do neighbor generation with vec_map
    adj = [0] * N
    
    for i, (idx_i, sup_i, signs_i, vec_i) in enumerate(all_vectors):
        sup_i_set = set(sup_i)
        
        for mask in range(1, 16):
            if bin(mask).count('1') != 3:
                continue
            
            common_elems = []
            pos_in_sup_i = []
            for k in range(4):
                if mask & (1 << k):
                    common_elems.append(sup_i[k])
                    pos_in_sup_i.append(k)
            
            signs_on_common = [signs_i[p] for p in pos_in_sup_i]
            
            for x in range(D):
                if x in sup_i_set:
                    continue
                
                T_list = sorted(common_elems + [x])
                T_tuple = tuple(T_list)
                
                if T_tuple not in support_map:
                    continue
                
                pos_in_T = [T_tuple.index(e) for e in common_elems]
                
                required_signs = dict(zip(common_elems, signs_on_common))
                
                for sign_x in [1, -1]:
                    sign_t = [0] * 4
                    for k, elem in enumerate(T_tuple):
                        if elem == x:
                            sign_t[k] = sign_x
                        else:
                            sign_t[k] = required_signs[elem]
                    
                    j = vec_map[(T_tuple, tuple(sign_t))]
                    adj[i] |= (1 << j)
                    adj[j] |= (1 << i)

    # 3. Greedy Initialization
    def greedy_mis(adj, N):
        # Min-degree greedy
        remaining = (1 << N) - 1
        selected = []
        while remaining:
            # Find vertex with min degree in remaining
            min_deg = N
            best_v = -1
            temp = remaining
            while temp:
                # Get lowest set bit
                lsb = temp & -temp
                v = lsb.bit_length() - 1
                deg = (remaining & adj[v]).bit_count()
                if deg < min_deg:
                    min_deg = deg
                    best_v = v
                temp ^= lsb
            if best_v == -1:
                break
            selected.append(best_v)
            # Remove best_v and its neighbors from remaining
            remaining &= ~(1 << best_v)
            remaining &= ~adj[best_v]
        
        return selected

    # Run a few random restarts of greedy to get a good lower bound
    best_set = set()
    start_time = time.time()
    time_limit = 115.0
    
    # Simple greedy first
    greedy_res = greedy_mis(adj, N)
    best_set = set(greedy_res)
    
    # 4. Branch and Bound with Bitmasks
    # To make it faster, we can use a simple heuristic for vertex selection.
    # Since the graph is regular, we can just pick the first available vertex?
    # Or use a precomputed ordering?
    # Let's try to pick the vertex with the highest degree in the current candidate set.
    
    def popcount(x):
        return x.bit_count()
        
    def solve(candidates, count, selected_set):
        nonlocal best_set, start_time, time_limit
        
        if time.time() - start_time > time_limit:
            return
        
        if candidates == 0:
            if count > len(best_set):
                best_set = set(selected_set)
            return
            
        # Pruning
        if count + popcount(candidates) <= len(best_set):
            return
            
        # Heuristic: Pick vertex with max degree in candidates
        # To avoid O(N) scan every time, we can just pick the first one?
        # Let's try picking the one with max degree.
        max_deg = -1
        v = -1
        temp = candidates
        while temp:
            lsb = temp & -temp
            u = lsb.bit_length() - 1
            deg = (candidates & adj[u]).bit_count()
            if deg > max_deg:
                max_deg = deg
                v = u
            temp ^= lsb
            
        if v == -1:
            return
            
        # Branch 1: Include v
        selected_set.add(v)
        new_candidates = candidates & ~(1 << v) & ~adj[v]
        solve(new_candidates, count + 1, selected_set)
        selected_set.remove(v)
        
        # Branch 2: Exclude v
        new_candidates2 = candidates & ~(1 << v)
        solve(new_candidates2, count, selected_set)

    initial_candidates = (1 << N) - 1
    current_set = set()
    
    try:
        solve(initial_candidates, 0, current_set)
    except RecursionError:
        pass
        
    if not best_set:
        return np.array([], dtype=np.int64).reshape(0, D)
        
    result_vectors = [all_vectors[i][3] for i in best_set]
    return np.array(result_vectors, dtype=np.int64)
