import time
import numpy as np
from itertools import combinations

def construct():
    start_time = time.time()
    deadline = start_time + 140  # Safety margin

    def check_validity(n, colors):
        """
        Check if a coloring of n vertices is valid.
        colors: numpy array of 0s and 1s of length C(n,3)
        Returns True if no red K4 and no blue K5.
        """
        # Map triple to index
        # For speed in checking, we can just iterate.
        # But we need to be fast.
        
        # Red K4 check:
        # For every 4-subset, check if all 4 triples are 0.
        # Blue K5 check:
        # For every 5-subset, check if all 10 triples are 1.
        
        # To make this fast, we can precompute indices?
        # Or just use the structure.
        
        # Let's try a simple loop first, if it's too slow, optimize.
        # C(34,4) ~ 46k. C(34,5) ~ 278k.
        # Total checks ~ 324k.
        # Each check involves indexing.
        
        # We need a fast way to get the index of a triple (a,b,c) in the lexicographic list.
        # The list is generated by combinations(range(n), 3).
        # We can precompute a dictionary for a given n once.
        
        # Since n is fixed during the search for a specific n, we can pass the index map.
        # But check_validity is called multiple times? 
        # In the local search, we update incrementally. 
        # This function is for final verification or initial check.
        
        # Let's assume we have a precomputed map or we compute it.
        # For this helper, let's assume it's used for the final check of the best candidate.
        
        # Actually, the local search maintains the violation count. 
        # We only need a robust check at the end to be sure.
        
        # Precompute triple indices for this n
        # This is expensive if done every time. 
        # But we only call it once or twice at the end.
        
        triple_idx = {}
        idx = 0
        for a in range(n):
            for b in range(a+1, n):
                for c in range(b+1, n):
                    triple_idx[(a,b,c)] = idx
                    idx += 1
        
        # Check Red K4
        for quad in combinations(range(n), 4):
            t1 = triple_idx[(quad[0], quad[1], quad[2])]
            t2 = triple_idx[(quad[0], quad[1], quad[3])]
            t3 = triple_idx[(quad[0], quad[2], quad[3])]
            t4 = triple_idx[(quad[1], quad[2], quad[3])]
            if colors[t1] == 0 and colors[t2] == 0 and colors[t3] == 0 and colors[t4] == 0:
                return False
        
        # Check Blue K5
        for quint in combinations(range(n), 5):
            # 10 triples
            all_blue = True
            for tri in combinations(quint, 3):
                t_idx = triple_idx[tri]
                if colors[t_idx] != 1:
                    all_blue = False
                    break
            if all_blue:
                return False
                
        return True

    def try_solve(n, seed):
        """
        Attempt to find a valid coloring for n vertices.
        Returns colors array if successful, None otherwise.
        """
        rng = np.random.RandomState(seed)
        
        # 1. Generate Initial Coloring
        # Strategy: Algebraic construction
        # Map vertices to GF(2^k) or similar? 
        # Or simpler: Random with bias?
        # Let's try a "structured random" or just random first, 
        # but the prompt suggests algebraic.
        # Let's use a simple modular arithmetic heuristic for init:
        # color(a,b,c) = (a + 2b + 3c) % 2 ?
        # Or just random. Random is often fine for local search if the landscape is not too rugged.
        # Let's use random init for robustness, as algebraic might have specific bad patterns.
        
        m = n*(n-1)*(n-2)//6
        colors = rng.randint(0, 2, size=m)
        
        # Precompute structures for fast updates
        # triple_idx: (a,b,c) -> i
        triple_idx = {}
        idx = 0
        for a in range(n):
            for b in range(a+1, n):
                for c in range(b+1, n):
                    triple_idx[(a,b,c)] = idx
                    idx += 1
        
        # red_k4s: list of lists of 4 triple indices
        red_k4s = []
        for quad in combinations(range(n), 4):
            red_k4s.append([
                triple_idx[(quad[0], quad[1], quad[2])],
                triple_idx[(quad[0], quad[1], quad[3])],
                triple_idx[(quad[0], quad[2], quad[3])],
                triple_idx[(quad[1], quad[2], quad[3])]
            ])
            
        # blue_k5s: list of lists of 10 triple indices
        blue_k5s = []
        for quint in combinations(range(n), 5):
            blue_k5s.append([
                triple_idx[tri] for tri in combinations(quint, 3)
            ])
            
        # Inverse maps: triple index -> list of K4 indices, list of K5 indices
        triple_to_k4s = [[] for _ in range(m)]
        for i, k4 in enumerate(red_k4s):
            for t in k4:
                triple_to_k4s[t].append(i)
                
        triple_to_k5s = [[] for _ in range(m)]
        for i, k5 in enumerate(blue_k5s):
            for t in k5:
                triple_to_k5s[t].append(i)
                
        # State
        is_red_viol = np.zeros(len(red_k4s), dtype=bool)
        is_blue_viol = np.zeros(len(blue_k5s), dtype=bool)
        
        # Initial count
        # Vectorized check for red K4s
        # red_k4s is a list of lists. Convert to numpy array?
        # red_k4_array = np.array(red_k4s) # shape (K4_count, 4)
        # red_viol = np.all(colors[red_k4_array] == 0, axis=1)
        
        # Let's do it with numpy for speed
        red_k4_array = np.array(red_k4s)
        blue_k5_array = np.array(blue_k5s)
        
        # Check initial violations
        is_red_viol[:] = np.all(colors[red_k4_array] == 0, axis=1)
        red_viol_count = np.sum(is_red_viol)
        
        is_blue_viol[:] = np.all(colors[blue_k5_array] == 1, axis=1)
        blue_viol_count = np.sum(is_blue_viol)
        
        best_red = red_viol_count
        best_blue = blue_viol_count
        best_colors = colors.copy()
        
        # Local Search
        max_iters = 50000
        # Precompute random indices for selection?
        # We pick a violation, then a triple in it.
        
        for it in range(max_iters):
            if time.time() > deadline - 10:
                break
                
            if red_viol_count == 0 and blue_viol_count == 0:
                return colors
                
            # Select violation
            # Heuristic: Pick the type with more violations, or random.
            # If one is 0, pick the other.
            if red_viol_count == 0:
                pick_red = False
            elif blue_viol_count == 0:
                pick_red = True
            else:
                pick_red = rng.rand() < 0.5
                
            if pick_red:
                # Pick random red violation
                # Get indices of violations
                viol_indices = np.nonzero(is_red_viol)[0]
                vi = viol_indices[rng.randint(len(viol_indices))]
                k4_idx = vi
                k4_triples = red_k4_array[k4_idx]
                
                # Pick random triple in k4
                flip_t = k4_triples[rng.randint(4)]
                
            else:
                viol_indices = np.nonzero(is_blue_viol)[0]
                vi = viol_indices[rng.randint(len(viol_indices))]
                k5_idx = vi
                k5_triples = blue_k5_array[k5_idx]
                
                # Pick random triple in k5
                flip_t = k5_triples[rng.randint(10)]
                
            # Flip color
            old_c = colors[flip_t]
            new_c = 1 - old_c
            colors[flip_t] = new_c
            
            # Update Red K4s
            # Get all K4s containing flip_t
            affected_k4s = triple_to_k4s[flip_t]
            if len(affected_k4s) > 0:
                # Get their triple indices
                # affected_k4_array = red_k4_array[affected_k4s]
                # Check if all red
                # new_viol = np.all(colors[affected_k4_array] == 0, axis=1)
                
                # We need to update is_red_viol for these indices
                # And red_viol_count
                
                # Optimization: Only check the ones that might have changed state?
                # All of them are affected.
                
                # Vectorized check
                # affected_k4_triples = red_k4_array[affected_k4s]
                # new_states = np.all(colors[affected_k4_triples] == 0, axis=1)
                
                # This creates a temporary array. For n=34, K4s per triple is small (~10-20).
                # So this is fast.
                
                affected_k4_triples = red_k4_array[affected_k4s]
                new_states = np.all(colors[affected_k4_triples] == 0, axis=1)
                
                old_states = is_red_viol[affected_k4s]
                
                # Count changes
                # new_count = sum(new_states)
                # old_count = sum(old_states)
                
                # Update global count
                red_viol_count += np.sum(new_states) - np.sum(old_states)
                
                # Update array
                is_red_viol[affected_k4s] = new_states
                
            # Update Blue K5s
            affected_k5s = triple_to_k5s[flip_t]
            if len(affected_k5s) > 0:
                affected_k5_triples = blue_k5_array[affected_k5s]
                new_states = np.all(colors[affected_k5_triples] == 1, axis=1)
                
                old_states = is_blue_viol[affected_k5s]
                
                blue_viol_count += np.sum(new_states) - np.sum(old_states)
                is_blue_viol[affected_k5s] = new_states
                
            # Track best
            if red_viol_count < best_red or (red_viol_count == best_red and blue_viol_count < best_blue):
                best_red = red_viol_count
                best_blue = blue_viol_count
                best_colors = colors.copy()
                
        if best_red == 0 and best_blue == 0:
            return best_colors
        return None

    # Try n=34, then 33, etc.
    best_n = 0
    best_colors = None
    
    # We know 34 is the target.
    # Try multiple seeds for 34.
    # If 34 fails, try 33.
    
    for n in [34, 33, 32]:
        if time.time() > deadline - 20:
            break
        for seed in range(20):
            if time.time() > deadline - 20:
                break
            res = try_solve(n, seed)
            if res is not None:
                # Verify
                if check_validity(n, res):
                    best_n = n
                    best_colors = res
                    break
        if best_n > 0:
            break
            
    # Fallback
    if best_n == 0:
        # Try a smaller n with more seeds or different init
        # Or just return a small valid one
        # n=9 is usually easy
        n = 9
        # Modular construction
        colors = []
        for a in range(n):
            for b in range(a+1, n):
                for c in range(b+1, n):
                    # Simple pattern
                    colors.append((a + b + c) % 2)
        colors = np.array(colors)
        
        # Verify
        if check_validity(n, colors):
            best_n = n
            best_colors = colors
        else:
            # Absolute fallback: n=1
            best_n = 1
            best_colors = np.array([])
            
    return {'n': best_n, 'colors': best_colors.tolist()}

