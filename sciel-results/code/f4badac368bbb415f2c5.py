"""XOR-circuit synthesis: Simulated Annealing with aggressive CSE."""
# EVOLVE-BLOCK-START
import time
import numpy as np
import random
from collections import defaultdict

def synthesize(matrix, depth_limit):
    start_time = time.time()
    DEADLINE = start_time + 85  # safety margin before 90s kill

    mat = np.array(matrix, dtype=np.int32)
    n_rows, n_cols = mat.shape
    n = n_cols
    zero_wire = n  # constant-zero wire

    # Convert rows to sets of indices for initial representation
    row_sets = []
    for i in range(n_rows):
        cols = np.nonzero(mat[i])[0]
        row_sets.append(set(cols.tolist()))

    # Helper to check if a subset can be formed by XOR of two existing wires
    # We represent the circuit as a list of gates.
    # Each gate is a tuple (w1, w2).
    # Wire n+1+k is the output of gate k.
    # Input wires are 0..n-1.
    # Wire n is 0.
    
    def build_greedy():
        """Builds a baseline circuit using a simple balanced tree strategy per row, 
        with some basic global caching."""
        gates = []
        wire_cache = {}
        # Initialize cache with singletons and zero
        for i in range(n):
            wire_cache[frozenset([i])] = i
        wire_cache[frozenset()] = zero_wire
        
        next_wire = n + 1
        
        def get_wire(subset):
            nonlocal next_wire
            if len(subset) == 0:
                return zero_wire
            if len(subset) == 1:
                return next(iter(subset))
            if subset in wire_cache:
                return wire_cache[subset]
            
            elems = sorted(subset)
            k = len(elems)
            
            # Balanced split
            mid = k // 2
            s1 = frozenset(elems[:mid])
            s2 = frozenset(elems[mid:])
            
            w1 = get_wire(s1)
            w2 = get_wire(s2)
            
            if w1 == w2:
                res = zero_wire
            else:
                gates.append([w1, w2])
                res = next_wire
                next_wire += 1
            
            wire_cache[subset] = res
            return res

        # Process rows
        outputs = []
        for s in row_sets:
            if not s:
                outputs.append(zero_wire)
            elif len(s) == 1:
                outputs.append(next(iter(s)))
            else:
                outputs.append(get_wire(frozenset(s)))
        
        return gates, outputs

    # Initial construction
    gates, outputs = build_greedy()
    
    # Data structures for SA
    # We need to track which wires are used by which gates/outputs to allow removal.
    # used_by[wire] = set of (gate_index, position) and (output_index)
    
    def compute_used_by(gates, outputs):
        used_by = defaultdict(set)
        for i, (w1, w2) in enumerate(gates):
            used_by[w1].add(('g', i, 0))
            used_by[w2].add(('g', i, 1))
        for i, w in enumerate(outputs):
            used_by[w].add(('o', i))
        return used_by

    def get_depth(gates, outputs):
        """Calculate max depth of the circuit."""
        if not gates:
            return 0
        
        # Topological sort / DP for depth
        # depth[wire]
        # Inputs and Zero have depth 0.
        n_gates = len(gates)
        # Wire indices: 0..n-1 (in), n (zero), n+1..n+n_gates (gates)
        max_wire = n + n_gates
        
        depth = [0] * (max_wire + 1)
        
        # We need to process gates in topological order.
        # Since gates are added in a way that inputs are usually defined before, 
        # but SA might break this? 
        # Actually, in this representation, gate i can only use wires < n+1+i? 
        # No, we should enforce that gate i only uses wires that are already available 
        # (inputs, zero, or outputs of gates < i).
        # This ensures a valid DAG and allows simple forward pass for depth.
        
        # Let's verify if our moves preserve this property.
        # Rewire: If we change input to a wire that is generated by a later gate, it's invalid.
        # So valid moves must only use wires < current_gate_index + n + 1.
        
        for i in range(n_gates):
            w1, w2 = gates[i]
            # w1, w2 must be < n + 1 + i
            # If not, the circuit is invalid. We should prevent such moves.
            if w1 >= n + 1 + i or w2 >= n + 1 + i:
                return float('inf')
            
            depth[n + 1 + i] = 1 + max(depth[w1], depth[w2])
        
        max_depth = 0
        for w in outputs:
            if w >= n + 1:
                # Find index of gate
                idx = w - (n + 1)
                if 0 <= idx < n_gates:
                    max_depth = max(max_depth, depth[w])
            # Inputs and zero have depth 0
            
        return max_depth

    def apply_cse(gates, outputs):
        """
        Performs Common Subexpression Elimination.
        Returns new gates, outputs, and a boolean if any change was made.
        Assumes gates are in valid topological order (gate i uses wires < n+1+i).
        """
        # Map from (min(w1,w2), max(w1,w2)) to list of gate indices
        # Note: XOR is commutative.
        wire_map = {}
        
        for i, (w1, w2) in enumerate(gates):
            if w1 > w2:
                w1, w2 = w2, w1
            key = (w1, w2)
            if key not in wire_map:
                wire_map[key] = []
            wire_map[key].append(i)
        
        # Identify duplicates
        # For each key with >1 gate, keep the first one (lowest index, usually best for depth/order)
        # and replace all others.
        
        # If no duplicates, return original
        if all(len(v) <= 1 for v in wire_map.values()):
            return gates, outputs, False
        
        # We need to be careful with topological order.
        # If we remove gate j and replace with gate i (where i < j), 
        # the new gate j (which is actually a gate that used to be j+1) 
        # might now have a "hole" in its index sequence?
        # Actually, it's easier to rebuild the list.
        
        # Let's mark gates to keep.
        keep = [True] * len(gates)
        remap = list(range(len(gates))) # remap[old_idx] = new_idx
        
        # First pass: identify which gates to keep
        # We want to keep the earliest gate for each unique XOR pair.
        # However, if we keep gate 5 and remove gate 2 (where 2 < 5), 
        # gate 5 might depend on gate 2? 
        # No, if gate 5 and gate 2 compute the same XOR, their inputs are the same.
        # Gate 2's inputs are wires < n+1+2.
        # Gate 5's inputs are wires < n+1+5.
        # If they are the same, gate 5's inputs are also < n+1+2.
        # So gate 5 does NOT depend on gate 2.
        # So we can safely remove the later gate.
        
        seen_keys = set()
        for i in range(len(gates)):
            w1, w2 = gates[i]
            if w1 > w2:
                w1, w2 = w2, w1
            key = (w1, w2)
            if key in seen_keys:
                keep[i] = False
            else:
                seen_keys.add(key)
        
        # If nothing to remove, return
        if all(keep):
            return gates, outputs, False
        
        # Rebuild gates
        new_gates = []
        old_to_new = {}
        new_idx = 0
        for i in range(len(gates)):
            if keep[i]:
                old_to_new[i] = new_idx
                new_gates.append(gates[i])
                new_idx += 1
        
        # Now we need to update references in the kept gates and outputs.
        # A kept gate i might have used a removed gate j.
        # If gate i used wire w = n+1+j, and j was removed, we need to replace w with the wire of the kept duplicate.
        
        # Let's build a map: removed_gate_idx -> kept_gate_idx
        # For each removed gate j, find the kept gate i such that gates[j] == gates[i].
        # Since we kept the first one, for any removed j, there is a unique kept i < j with same key.
        
        removed_to_kept = {}
        for i in range(len(gates)):
            if not keep[i]:
                w1, w2 = gates[i]
                if w1 > w2:
                    w1, w2 = w2, w1
                key = (w1, w2)
                # Find the kept gate with this key
                # It must be the first one.
                for k in range(len(gates)):
                    if keep[k]:
                        gw1, gw2 = gates[k]
                        if gw1 > gw2:
                            gw1, gw2 = gw2, gw1
                        if (gw1, gw2) == key:
                            removed_to_kept[i] = k
                            break
        
        # Helper to remap a wire index
        def remap_wire(w):
            if w < n + 1:
                return w
            gate_idx = w - (n + 1)
            if gate_idx in old_to_new:
                return n + 1 + old_to_new[gate_idx]
            elif gate_idx in removed_to_kept:
                kept_idx = removed_to_kept[gate_idx]
                new_kept_idx = old_to_new[kept_idx]
                return n + 1 + new_kept_idx
            else:
                # Should not happen if logic is correct
                return w
        
        # Apply remapping to new_gates
        final_gates = []
        for w1, w2 in new_gates:
            nw1 = remap_wire(w1)
            nw2 = remap_wire(w2)
            final_gates.append([nw1, nw2])
            
        # Apply remapping to outputs
        final_outputs = []
        for w in outputs:
            final_outputs.append(remap_wire(w))
            
        return final_gates, final_outputs, True

    # Verify circuit correctness
    def verify(gates, outputs):
        if len(gates) > 1000: # Safety
            return False
        # Calculate value of each wire
        # Wire values are bitmasks (integers)
        val = [0] * (n + 1 + len(gates))
        for i in range(n):
            val[i] = 1 << i
        val[n] = 0
        
        for i in range(len(gates)):
            w1, w2 = gates[i]
            if w1 >= len(val) or w2 >= len(val):
                return False
            val[n + 1 + i] = val[w1] ^ val[w2]
            
        for i in range(n_rows):
            target = row_sets[i]
            target_val = 0
            for col in target:
                target_val |= (1 << col)
            if val[outputs[i]] != target_val:
                return False
        return True

    # Initial verification
    if not verify(gates, outputs):
        # Fallback to simple tree if greedy failed (should not happen)
        return {'gates': [], 'outputs': [0]*n_rows}

    current_gates, current_outputs = gates, outputs
    current_cost = len(current_gates)
    best_gates, best_outputs = current_gates, current_outputs
    best_cost = current_cost
    
    # SA Parameters
    T = 1.0
    T_min = 0.01
    alpha = 0.995 # Cooling rate
    max_iter = 50000 # Max iterations
    
    # Precompute popcount for potential cost estimation? 
    # Cost is simply len(gates).
    
    def get_depth_fast(gates, outputs):
        # Optimized depth check
        if not gates:
            return 0
        n_gates = len(gates)
        max_wire = n + n_gates
        depth = [0] * (max_wire + 1)
        
        for i in range(n_gates):
            w1, w2 = gates[i]
            # Check validity
            if w1 >= n + 1 + i or w2 >= n + 1 + i:
                return float('inf')
            d1 = depth[w1]
            d2 = depth[w2]
            depth[n + 1 + i] = 1 + (d1 if d1 > d2 else d2)
        
        max_depth = 0
        for w in outputs:
            if w >= n + 1:
                idx = w - (n + 1)
                if 0 <= idx < n_gates:
                    if depth[w] > max_depth:
                        max_depth = depth[w]
        return max_depth

    # Main SA Loop
    for it in range(max_iter):
        if time.time() > DEADLINE - 5:
            break
            
        # Generate neighbor
        new_gates = [g[:] for g in current_gates]
        new_outputs = current_outputs[:]
        
        move_type = random.random()
        n_gates = len(new_gates)
        
        if move_type < 0.5 and n_gates > 0:
            # Rewire
            idx = random.randint(0, n_gates - 1)
            pos = random.randint(0, 1)
            # New wire must be < n + 1 + idx to maintain topological order
            max_allowed = n + idx
            if max_allowed < 0:
                continue
            new_w = random.randint(0, max_allowed)
            new_gates[idx][pos] = new_w
            
        elif move_type < 0.7:
            # Add gate
            # Insert at random position? 
            # Easier: Append at end, then maybe swap?
            # If we append, it's at index n_gates.
            # Inputs must be < n + 1 + n_gates.
            w1 = random.randint(0, n + n_gates)
            w2 = random.randint(0, n + n_gates)
            new_gates.append([w1, w2])
            
            # To make it useful, maybe connect it to an output?
            # Or just let CSE handle it?
            # If it's not connected, it will be removed by "Remove Gate" move or just stay unused.
            # But "Remove Gate" only removes if unused.
            # If we add a gate, it is unused initially.
            # So we should probably connect it to something.
            # Let's connect it to a random output or gate input.
            if random.random() < 0.5 and n_rows > 0:
                out_idx = random.randint(0, n_rows - 1)
                new_outputs[out_idx] = n + 1 + n_gates
            elif n_gates > 0:
                # Connect to a random gate input
                g_idx = random.randint(0, n_gates - 1)
                pos = random.randint(0, 1)
                new_gates[g_idx][pos] = n + 1 + n_gates
            else:
                # No gates to connect to, connect to output
                if n_rows > 0:
                    out_idx = random.randint(0, n_rows - 1)
                    new_outputs[out_idx] = n + 1 + n_gates

        elif move_type < 0.9 and n_gates > 0:
            # Remove gate
            # Find a gate that is not used by any other gate or output
            # This requires a used_by map. Expensive to build every time.
            # Approximation: Just pick a random gate, remove it, and remap.
            # If it was used, the circuit becomes invalid (dangling wire).
            # We check validity in verify().
            # But verify is expensive.
            # Better: Only remove if we can find a duplicate via CSE?
            # CSE is done after every move.
            # So "Remove Gate" is effectively handled by CSE if we create duplicates.
            # So we don't need an explicit "Remove Gate" move if CSE is aggressive.
            # However, CSE only removes duplicates. It doesn't remove unused gates.
            # So we need a move to disconnect a gate.
            
            # Let's try to disconnect a random gate.
            idx = random.randint(0, n_gates - 1)
            wire_to_remove = n + 1 + idx
            
            # Check if used
            used = False
            for i, (w1, w2) in enumerate(new_gates):
                if i != idx:
                    if w1 == wire_to_remove or w2 == wire_to_remove:
                        used = True
                        break
            if not used:
                for w in new_outputs:
                    if w == wire_to_remove:
                        used = True
                        break
            
            if not used:
                # Safe to remove
                new_gates.pop(idx)
                # Remap indices of gates after idx?
                # No, we just pop. The indices of subsequent gates decrease by 1.
                # We must update all references to gates >= idx.
                for i in range(len(new_gates)):
                    if new_gates[i][0] > wire_to_remove:
                        new_gates[i][0] -= 1
                    elif new_gates[i][0] == wire_to_remove:
                        # Should not happen if not used
                        pass
                    if new_gates[i][1] > wire_to_remove:
                        new_gates[i][1] -= 1
                    elif new_gates[i][1] == wire_to_remove:
                        pass
                
                for i in range(n_rows):
                    if new_outputs[i] > wire_to_remove:
                        new_outputs[i] -= 1
                    elif new_outputs[i] == wire_to_remove:
                        pass
            else:
                # Cannot remove, try to rewire it to something else?
                # Or just skip.
                continue

        else:
            # Skip
            continue

        # Apply CSE to the new circuit
        new_gates, new_outputs, changed = apply_cse(new_gates, new_outputs)
        
        # Check validity and cost
        if not verify(new_gates, new_outputs):
            continue
            
        new_cost = len(new_gates)
        new_depth = get_depth_fast(new_gates, new_outputs)
        
        if new_depth > depth_limit:
            continue
            
        delta_cost = new_cost - current_cost
        
        if delta_cost < 0:
            # Improvement
            current_gates, current_outputs = new_gates, new_outputs
            current_cost = new_cost
            
            if new_cost < best_cost:
                best_gates, best_outputs = new_gates, new_outputs
                best_cost = new_cost
        else:
            # Accept with probability
            if random.random() < np.exp(-delta_cost / T):
                current_gates, current_outputs = new_gates, new_outputs
                current_cost = new_cost
                
        T *= alpha
        if T < T_min:
            # Restart or stop? 
            # Simple restart
            T = 0.5

    # Final CSE pass on best
    best_gates, best_outputs, _ = apply_cse(best_gates, best_outputs)
    
    # One last verify
    if not verify(best_gates, best_outputs):
        # Fallback to initial greedy
        return {'gates': gates, 'outputs': outputs}
        
    return {'gates': best_gates, 'outputs': best_outputs}
# EVOLVE-BLOCK-END
