import numpy as np
from scipy.optimize import minimize

def _apply_cz(state, i, j):
    """Apply CZ gate between qubits i and j to a state vector."""
    # State is a vector of length 2^n.
    # CZ flips phase if both qubits are 1.
    # Bit i corresponds to 2^i in the binary representation of the index.
    mask_i = 1 << i
    mask_j = 1 << j
    
    # Indices where both bits are set
    # We can iterate through all basis states or use vectorized operations.
    # For small n (4,6), iterating is fine, but vectorized is better.
    # Let's use a vectorized approach for speed.
    
    # Create a mask of indices where bit i is 1
    # Actually, simpler: 
    # The CZ operator is diagonal with entries 1 except -1 where |i>=1 and |j>=1.
    # We can construct the diagonal vector of the CZ operator and multiply.
    # But building the full 2^n vector for each gate is expensive if done naively in a loop.
    # However, n is small (max 6), so 2^6 = 64. It's very small.
    
    # Let's just loop over the basis states for simplicity and correctness, 
    # as n is tiny.
    n_qubits = int(np.log2(len(state)))
    for idx in range(len(state)):
        if (idx & mask_i) and (idx & mask_j):
            state[idx] *= -1
    return state

def _apply_ry(state, theta, i):
    """Apply Ry(theta) to qubit i."""
    # Ry(theta) = [[cos(theta/2), -sin(theta/2)], [sin(theta/2), cos(theta/2)]]
    # Qubit i is bit i.
    c = np.cos(theta / 2)
    s = np.sin(theta / 2)
    
    mask = 1 << i
    n_qubits = int(np.log2(len(state)))
    
    # We need to swap amplitudes for states differing only in bit i.
    # Iterate over basis states where bit i is 0.
    # For each such state |...0...>, the partner is |...1...> = |...0...> + mask.
    # New |0> = c*|0> - s*|1>
    # New |1> = s*|0> + c*|1>
    
    # To avoid modifying state in place while reading, we can use a copy or careful indexing.
    # Since n is small, let's just create a new state.
    new_state = np.zeros_like(state)
    
    for idx in range(len(state)):
        if not (idx & mask):
            # idx has 0 at bit i
            idx_1 = idx | mask
            v0 = state[idx]
            v1 = state[idx_1]
            new_state[idx] = c * v0 - s * v1
            new_state[idx_1] = s * v0 + c * v1
        # else: idx has 1 at bit i, handled by the partner iteration? 
        # No, if we only iterate where bit is 0, we cover all pairs exactly once.
        
    return new_state

def _compute_energy(n, coupling, field, angles):
    """
    Compute the energy of the state generated by the circuit with given angles.
    angles: shape (layers, n)
    """
    # Initial state |0>^n
    state = np.zeros(2**n, dtype=complex)
    state[0] = 1.0
    
    # Apply layers
    for l in range(angles.shape[0]):
        # Apply Ry to all qubits
        for i in range(n):
            state = _apply_ry(state, angles[l, i], i)
        
        # Apply CZ between adjacent pairs if not the last layer
        if l < angles.shape[0] - 1:
            for i in range(n - 1):
                state = _apply_cz(state, i, i + 1)
    
    # Compute Energy <H>
    # H = -coupling * sum Z_i Z_{i+1} - field * sum X_i
    
    # Z_i Z_{i+1}
    # Z is diagonal: +1 for |0>, -1 for |1>.
    # Z_i Z_{i+1} is +1 if bits are same, -1 if different.
    energy_zz = 0.0
    for i in range(n - 1):
        mask_i = 1 << i
        mask_j = 1 << (i + 1)
        # Expectation value of Z_i Z_{i+1}
        # Sum over all states |psi_k|^2 * (z_i * z_j)
        # z_k is +1 if bit is 0, -1 if bit is 1.
        # We can compute this efficiently.
        # Let's just loop, n is small.
        for k in range(2**n):
            prob = np.abs(state[k])**2
            if prob == 0: continue
            zi = 1 if not (k & mask_i) else -1
            zj = 1 if not (k & mask_j) else -1
            energy_zz += prob * zi * zj
    energy_zz *= -coupling
    
    # X_i
    # X_i = |0><1| + |1><0|
    # <X_i> = sum_{k: bit i=0} psi_k^* psi_{k^mask_i} + c.c.
    # Since state is real (Ry and CZ on real state starting from real |0> keep it real? 
    # Ry has real entries. CZ has real entries. Yes, state remains real).
    energy_x = 0.0
    for i in range(n):
        mask = 1 << i
        for k in range(2**n):
            if not (k & mask):
                # psi_k and psi_{k|mask}
                energy_x += 2 * state[k] * state[k | mask]
    energy_x *= -field
    
    return energy_zz + energy_x

def angles(n, coupling, field, layers):
    """
    Optimize parameters of a fixed three-layer Ry/CZ circuit.
    """
    # We assume layers=3, but the function takes it as an argument.
    # The contract says fixed layers=3.
    
    # Symmetry: The Hamiltonian is symmetric under i -> n-1-i.
    # So angles[l, i] should equal angles[l, n-1-i].
    # We optimize only the first half (ceil(n/2)) angles per layer.
    
    half_n = (n + 1) // 2
    n_params = layers * half_n
    
    def unpack(params):
        # params: flat array of length n_params
        # Return (layers, n) array
        ang = np.zeros((layers, n))
        for l in range(layers):
            for i in range(half_n):
                val = params[l * half_n + i]
                ang[l, i] = val
                # Mirror
                ang[l, n - 1 - i] = val
        return ang
    
    def objective(params):
        ang = unpack(params)
        return _compute_energy(n, coupling, field, ang)
    
    # Initial guesses
    # 1. All zeros (|0> state)
    # 2. All pi/2 (|+> state)
    # 3. Random
    
    best_energy = np.inf
    best_params = None
    
    # Define initial guesses
    guesses = [
        np.zeros(n_params),
        np.full(n_params, np.pi / 2),
        np.random.uniform(-np.pi, np.pi, n_params)
    ]
    
    # Add a guess based on mean-field intuition
    # If field is strong, angles close to pi/2. If coupling strong, angles close to 0 or pi.
    # Let's just stick to the 3 above and maybe one more.
    guesses.append(np.full(n_params, np.pi / 4))
    
    for guess in guesses:
        try:
            res = minimize(objective, guess, method='Nelder-Mead', 
                           options={'maxiter': 500, 'xatol': 1e-5, 'fatol': 1e-6})
            if res.fun < best_energy:
                best_energy = res.fun
                best_params = res.x
        except Exception:
            continue
            
    if best_params is None:
        # Fallback to seed behavior
        theta = np.zeros((layers, n))
        theta[-1] = np.pi / 2
        return theta
        
    best_angles = unpack(best_params)
    return best_angles
