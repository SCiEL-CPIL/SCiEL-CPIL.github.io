import time
import math
import numpy as np
from scipy.optimize import differential_evolution, minimize

def construct():
    start_time = time.time()
    deadline = start_time + 145.0  # Safety margin before 150s kill

    # Parameters: x1, y1, x2, y2
    # Points are symmetric under D4 (symmetry of a square)
    # P1=(x1,y1), P2=(y1,x1), P3=(-x1,y1), P4=(-y1,x1)
    # P5=(x2,y2), P6=(y2,x2), P7=(-x2,y2), P8=(-y2,x2)
    
    def get_points(x):
        x1, y1, x2, y2 = x
        pts = np.array([
            [x1, y1],
            [y1, x1],
            [-x1, y1],
            [-y1, x1],
            [x2, y2],
            [y2, x2],
            [-x2, y2],
            [-y2, x2]
        ])
        return pts

    def compute_score(pts):
        """
        Compute the actual score: Delta / n^n.
        """
        n = 8
        pts = np.asarray(pts)
        if not np.all(np.isfinite(pts)):
            return 0.0
            
        diffs = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
        dists = np.sqrt(np.sum(diffs**2, axis=2))
        iu = np.triu_indices(n, k=1)
        d = dists[iu]
        
        # Check for coincident points
        if np.min(d) < 1e-12:
            return 0.0
            
        D = np.max(d)
        if D < 1e-12:
            return 0.0
            
        # Score = (Prod_{i<j} d'_ij)^2 / n^n where d'_ij = d_ij * (2/D)
        # log Score = 2 * (28 * log(2) - 28 * log(D) + sum(log(d_ij))) - 8 * log(8)
        
        log_d_sum = np.sum(np.log(d))
        log_prod_unordered_scaled = 28.0 * math.log(2.0) - 28.0 * math.log(D) + log_d_sum
        log_score = 2.0 * log_prod_unordered_scaled - 8.0 * math.log(8.0)
        
        return math.exp(log_score)

    def objective(x):
        """
        Minimize negative log score.
        Uses soft-max for diameter to ensure differentiability.
        """
        pts = get_points(x)
        if not np.all(np.isfinite(pts)):
            return 1e100
            
        diffs = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
        dists = np.sqrt(np.sum(diffs**2, axis=2))
        iu = np.triu_indices(8, k=1)
        d = dists[iu]
        
        if np.min(d) < 1e-9:
            return 1e100
            
        # Soft max approximation for max distance
        # beta = 100 is usually sufficient for double precision
        beta = 100.0
        # Clip to avoid overflow in exp
        d_safe = np.clip(d, 1e-9, 1e6)
        log_max_d = np.log(np.sum(np.exp(beta * d_safe)) / beta) / beta
        # Actually, log(sum(exp(beta*d))) / beta is approx log(max(d)) + log(sum(exp(beta*(d-max))))/beta
        # A more stable log-sum-exp:
        d_max_local = np.max(d_safe)
        log_sum_exp = d_max_local + np.log(np.sum(np.exp(beta * (d_safe - d_max_local))))
        log_D_approx = log_sum_exp / beta
        
        if not np.isfinite(log_D_approx):
            return 1e100

        log_d_sum = np.sum(np.log(d_safe))
        
        # log_score = 2 * (28*log(2) - 28*log(D) + log_d_sum) - 8*log(8)
        # We minimize -log_score
        # -log_score = -2*28*log(2) + 56*log(D) - 2*log_d_sum + 8*log(8)
        
        val = 56.0 * log_D_approx - 2.0 * log_d_sum
        return val

    bounds = [(-10, 10)] * 4
    
    best_val = np.inf
    best_x = None
    best_score = 0.0

    def update_best(x, val):
        nonlocal best_val, best_x, best_score
        if val < best_val:
            best_val = val
            best_x = x.copy()
            pts = get_points(best_x)
            s = compute_score(pts)
            if s > best_score:
                best_score = s

    # 1. Initial Guesses
    # Regular Octagon in D4 symmetric coordinates?
    # Regular octagon vertices: (cos(22.5), sin(22.5)), (cos(67.5), sin(67.5))...
    # Due to D4 symmetry, we can pick two representative points from the first quadrant.
    # P1 = (cos(22.5), sin(22.5)) -> x1=cos(22.5), y1=sin(22.5)
    # P2 = (cos(67.5), sin(67.5)) -> x2=cos(67.5), y2=sin(67.5)
    # Note: The set generated by D4 symmetry from (x1,y1) and (x2,y2) will include 8 points.
    # For regular octagon, x1=cos(22.5), y1=sin(22.5) and x2=sin(22.5), y2=cos(22.5).
    # Wait, P2=(y1,x1) is (sin(22.5), cos(22.5)) which is cos(67.5), sin(67.5).
    # So if we set x1=cos(22.5), y1=sin(22.5), the first 4 points cover 4 vertices.
    # The next 4 points from x2,y2 must be the other 4.
    # If we set x2=x1, y2=y1, we get duplicates.
    # The regular octagon has only 2 unique orbits under D4?
    # No, the vertices of a regular octagon are not all in the same orbit under D4 if we consider the standard D4 acting on the plane.
    # Actually, the vertices of a regular octagon form a single orbit under the dihedral group D8, but under D4 (symmetries of a square), they split into two orbits of 4.
    # Orbit 1: (r, 0) rotated? No.
    # Let's just use the coordinates of the regular octagon directly.
    # Angles: 22.5, 67.5, 112.5, ...
    # P1 = (cos(22.5), sin(22.5))
    # P2 = (cos(67.5), sin(67.5)) = (sin(22.5), cos(22.5))
    # So x1 = cos(22.5), y1 = sin(22.5).
    # The points generated by (x1,y1) are:
    # (c, s), (s, c), (-c, s), (-s, c)
    # These are angles 22.5, 67.5, 112.5, 157.5.
    # The other 4 points of the octagon are:
    # 202.5, 247.5, 292.5, 337.5
    # (-c, -s), (-s, -c), (c, -s), (s, -c)
    # Can we generate these from (x2, y2)?
    # If we set x2 = -c, y2 = -s, we get (-c, -s), (-s, -c), (c, -s), (s, -c).
    # So init_x = [cos(22.5), sin(22.5), -cos(22.5), -sin(22.5)]
    
    c = math.cos(math.radians(22.5))
    s = math.sin(math.radians(22.5))
    init_x = np.array([c, s, -c, -s])
    
    val = objective(init_x)
    update_best(init_x, val)

    # 2. Differential Evolution
    try:
        res = differential_evolution(
            objective, 
            bounds, 
            seed=42, 
            maxiter=200, 
            popsize=20,
            tol=1e-8,
            polish=True
        )
        
        if res.fun < best_val:
            update_best(res.x, res.fun)
            
    except Exception:
        pass

    # 3. Local Refinement
    start_points = [best_x]
    
    # Add perturbations
    np.random.seed(42)
    for _ in range(10):
        if time.time() > deadline - 10.0:
            break
        x_perturb = best_x + 0.5 * np.random.randn(4)
        x_perturb = np.clip(x_perturb, [b[0] for b in bounds], [b[1] for b in bounds])
        start_points.append(x_perturb)
        
    # Add specific structured candidates
    # Two concentric squares?
    # If x1=y1=r1 and x2=y2=r2, points are (r1,r1), (r1,r1)... duplicates.
    # We need x != y for distinct points in the pair (x,y),(y,x).
    # If x1=1, y1=0.5, x2=0.8, y2=0.2
    candidates = [
        [1.0, 0.5, 0.8, 0.2],
        [1.0, 0.8, 0.5, 0.2],
        [0.9, 0.4, 0.6, 0.7],
        [1.2, 0.3, 0.7, 0.9]
    ]
    for c in candidates:
        if time.time() > deadline - 10.0:
            break
        start_points.append(np.array(c))

    for x0 in start_points:
        if time.time() > deadline - 5.0:
            break
            
        try:
            res_local = minimize(
                objective, 
                x0, 
                method='L-BFGS-B', 
                bounds=bounds, 
                options={'maxiter': 500, 'ftol': 1e-12, 'gtol': 1e-8}
            )
            
            if np.all(np.isfinite(res_local.x)):
                if res_local.fun < best_val:
                    update_best(res_local.x, res_local.fun)
                    
        except Exception:
            pass

    # 4. Final High-Precision Polish
    if time.time() < deadline - 2.0 and best_x is not None:
        try:
            res_final = minimize(
                objective, 
                best_x, 
                method='L-BFGS-B', 
                bounds=bounds, 
                options={'maxiter': 1000, 'ftol': 1e-15, 'gtol': 1e-10}
            )
            if np.all(np.isfinite(res_final.x)) and res_final.fun < best_val:
                update_best(res_final.x, res_final.fun)
        except Exception:
            pass

    # Construct final points
    if best_x is None:
        # Fallback to regular octagon
        angles = np.linspace(0, 2*np.pi, 8, endpoint=False)
        pts = np.column_stack([np.cos(angles), np.sin(angles)])
        return pts.tolist()
        
    pts = get_points(best_x)
    
    # Verify distinctness
    diffs = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dists = np.sqrt(np.sum(diffs**2, axis=2))
    iu = np.triu_indices(8, k=1)
    d = dists[iu]
    
    if np.min(d) < 1e-6 or not np.all(np.isfinite(pts)):
        # Fallback to regular octagon if invalid
        angles = np.linspace(0, 2*np.pi, 8, endpoint=False)
        pts = np.column_stack([np.cos(angles), np.sin(angles)])
        
    # Scale to ensure coordinates are within bounds
    max_coord = np.max(np.abs(pts))
    if max_coord > 1e6:
        pts = pts / max_coord * 1e5

    return pts.tolist()
