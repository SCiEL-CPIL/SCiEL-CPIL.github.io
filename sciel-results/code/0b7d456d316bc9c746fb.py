import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 85
    
    n = 256
    max_size = 64
    
    def check_valid_add(x, S, sums_S, diffs_S, diffs_other):
        if x + x in sums_S:
            return False
        for y in S:
            if x + y in sums_S:
                return False
            d = abs(x - y)
            if d in diffs_S:
                return False
            if d in diffs_other:
                return False
        return True

    def add_element(x, S, sums_S, diffs_S):
        S.append(x)
        sums_S.add(x + x)
        diffs_S_new = []
        for y in S[:-1]:
            sums_S.add(x + y)
            d = abs(x - y)
            if d > 0:
                diffs_S.add(d)

    def remove_element(x, S, sums_S, diffs_S):
        # Remove x from S
        S.remove(x)
        # Remove sums involving x
        sums_S.discard(x + x)
        for y in S:
            sums_S.discard(x + y)
            d = abs(x - y)
            if d > 0:
                # Careful: d might be generated by another pair?
                # In a Sidon set, differences are unique.
                # So if d is in diffs_S, it must have come from x and y?
                # Yes, because we are removing x. If d was from u,v, it stays.
                # But if d was from x,y, it goes.
                # Since diffs are unique in Sidon sets, we can just discard.
                diffs_S.discard(d)

    def greedy_construct(order):
        A = []
        B = []
        sums_A = set()
        diffs_A = set()
        sums_B = set()
        diffs_B = set()
        
        for x in order:
            if len(A) < max_size and check_valid_add(x, A, sums_A, diffs_A, diffs_B):
                add_element(x, A, sums_A, diffs_A)
            elif len(B) < max_size and check_valid_add(x, B, sums_B, diffs_B, diffs_A):
                add_element(x, B, sums_B, diffs_B)
        return A, B, sums_A, diffs_A, sums_B, diffs_B

    def local_search(A, B, sums_A, diffs_A, sums_B, diffs_B, deadline):
        in_A = set(A)
        in_B = set(B)
        none_set = set(range(1, n+1)) - in_A - in_B
        
        while time.time() < deadline:
            improved = False
            
            # 1. Try Add
            if none_set:
                candidates = list(none_set)
                random.shuffle(candidates)
                for x in candidates:
                    if len(A) < max_size and check_valid_add(x, A, sums_A, diffs_A, diffs_B):
                        add_element(x, A, sums_A, diffs_A)
                        in_A.add(x)
                        none_set.remove(x)
                        improved = True
                        break
                    if len(B) < max_size and check_valid_add(x, B, sums_B, diffs_B, diffs_A):
                        add_element(x, B, sums_B, diffs_B)
                        in_B.add(x)
                        none_set.remove(x)
                        improved = True
                        break
            
            if improved:
                continue

            # 2. Try Swap (Remove 1, Add 1)
            # Only do this if we are stuck
            if A or B:
                # Choose side to remove from
                if A and (not B or random.random() < 0.5):
                    idx = random.randint(0, len(A)-1)
                    x_rem = A[idx]
                    remove_element(x_rem, A, sums_A, diffs_A)
                    in_A.remove(x_rem)
                    none_set.add(x_rem)
                    
                    # Try to add new
                    added = False
                    candidates = list(none_set)
                    random.shuffle(candidates)
                    for x_add in candidates:
                        if len(A) < max_size and check_valid_add(x_add, A, sums_A, diffs_A, diffs_B):
                            add_element(x_add, A, sums_A, diffs_A)
                            in_A.add(x_add)
                            none_set.remove(x_add)
                            added = True
                            break
                        if len(B) < max_size and check_valid_add(x_add, B, sums_B, diffs_B, diffs_A):
                            add_element(x_add, B, sums_B, diffs_B)
                            in_B.add(x_add)
                            none_set.remove(x_add)
                            added = True
                            break
                    
                    if not added:
                        # Revert
                        add_element(x_rem, A, sums_A, diffs_A)
                        in_A.add(x_rem)
                        none_set.remove(x_rem)
                else:
                    if B:
                        idx = random.randint(0, len(B)-1)
                        x_rem = B[idx]
                        remove_element(x_rem, B, sums_B, diffs_B)
                        in_B.remove(x_rem)
                        none_set.add(x_rem)
                        
                        added = False
                        candidates = list(none_set)
                        random.shuffle(candidates)
                        for x_add in candidates:
                            if len(A) < max_size and check_valid_add(x_add, A, sums_A, diffs_A, diffs_B):
                                add_element(x_add, A, sums_A, diffs_A)
                                in_A.add(x_add)
                                none_set.remove(x_add)
                                added = True
                                break
                            if len(B) < max_size and check_valid_add(x_add, B, sums_B, diffs_B, diffs_A):
                                add_element(x_add, B, sums_B, diffs_B)
                                in_B.add(x_add)
                                none_set.remove(x_add)
                                added = True
                                break
                        
                        if not added:
                            add_element(x_rem, B, sums_B, diffs_B)
                            in_B.add(x_rem)
                            none_set.remove(x_rem)

        return A, B

    best_A = []
    best_B = []
    best_score = 0
    
    num_restarts = 100
    for i in range(num_restarts):
        if time.time() > deadline - 5:
            break
            
        order = list(range(1, n+1))
        random.shuffle(order)
        
        A, B, sums_A, diffs_A, sums_B, diffs_B = greedy_construct(order)
        score = len(A) + len(B)
        
        if time.time() < deadline - 2:
            A, B = local_search(A, B, sums_A, diffs_A, sums_B, diffs_B, deadline - 1)
            score = len(A) + len(B)
            
        if score > best_score:
            best_score = score
            best_A = A[:]
            best_B = B[:]
            
        if best_score >= 30:
            break

    if not best_A:
        best_A = [1]
    if not best_B:
        best_B = [2]
        
    return [best_A, best_B]
