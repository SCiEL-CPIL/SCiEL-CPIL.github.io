"""
Radial Basis Function (RBF) approach with optimized center placement.
Uses 10 Gaussian kernels centered at points generated by a Halton sequence 
to ensure good coverage of the [-1, 1]^2 domain. 
This linear-in-parameters basis allows BFGS to efficiently find the optimal 
weights. The Halton sequence provides better space-filling properties than 
random or grid-based centers, potentially improving generalization.
"""
# EVOLVE-BLOCK-START
import numpy as np
import time

_START = time.time()
_LIMIT = 150.0
_MARGIN = 10.0

def _elapsed_ok():
    return (time.time() - _START) < (_LIMIT - _MARGIN)

def _halton_sequence(num, base):
    """Generate the first 'num' elements of the Halton sequence with the given 'base'."""
    seq = []
    f = 1.0
    for i in range(1, num + 1):
        q = i
        while q > 0:
            f /= base
            q = int(q / base)
        seq.append(f)
    return seq

# Pre-compute fixed centers for the RBFs
# Using Halton sequence for better distribution
_N_CENTERS = 10
_hx = np.array(_halton_sequence(_N_CENTERS, 2))
_hy = np.array(_halton_sequence(_N_CENTERS, 3))
# Map from [0, 1) to [-1, 1]
_CENTERS_X = 2.0 * _hx - 1.0
_CENTERS_Y = 2.0 * _hy - 1.0
_CENTERS = np.column_stack((_CENTERS_X, _CENTERS_Y))

# Bandwidth for the Gaussian kernel
# Chosen to balance locality and global coverage
_SIGMA = 0.4
_SIGMA_SQ = 2.0 * _SIGMA * _SIGMA

def equation(x: np.ndarray, y: np.ndarray, params: np.ndarray) -> np.ndarray:
    # Ensure 1-D arrays
    x = np.asarray(x, dtype=np.float64).ravel()
    y = np.asarray(y, dtype=np.float64).ravel()
    p = np.asarray(params, dtype=np.float64).ravel()
    n = x.size

    if not _elapsed_ok():
        # Safety fallback: return mean-ish constant
        return np.full(n, float(p[0]))

    # Compute distances from each input point to each center
    # x, y are (n,), _CENTERS is (10, 2)
    # dx = x[:, np.newaxis] - _CENTERS_X[np.newaxis, :] -> (n, 10)
    dx = x[:, np.newaxis] - _CENTERS_X[np.newaxis, :]
    dy = y[:, np.newaxis] - _CENTERS_Y[np.newaxis, :]
    
    # Squared distances
    dist_sq = dx**2 + dy**2
    
    # Gaussian kernel: exp(-dist_sq / (2 * sigma^2))
    # Pre-compute the constant factor if possible, but here sigma is fixed
    basis = np.exp(-dist_sq / _SIGMA_SQ)
    
    # Linear combination
    return basis @ p
# EVOLVE-BLOCK-END
