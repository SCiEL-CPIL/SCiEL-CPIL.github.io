import time
import random
import sys

START_TIME = time.time()
TIME_LIMIT = 85.0  # Leave 5s margin for 90s kill

def _subset_sums(nums):
    """Generate the set of all non-empty subset sums."""
    sums = set()
    for mask in range(1, 1 << len(nums)):
        s = 0
        for i in range(len(nums)):
            if mask & (1 << i):
                s += nums[i]
        sums.add(s)
    return sums

def _is_divisibility_free(sums_set):
    """Check if no two distinct sums in the set divide one another."""
    if len(sums_set) < 2:
        return True
    
    sums_list = sorted(sums_set)
    m = len(sums_list)
    
    # Optimization: If a sum is 1, it divides everything.
    if 1 in sums_set:
        return False

    for i in range(m):
        si = sums_list[i]
        # We only need to check if si divides any sj where j > i
        # Since si < sj, si cannot be divided by sj.
        # We check if sj % si == 0.
        # We can break early if si * 2 > sums_list[-1], but si * 2 might not be in the set.
        # However, if si > sums_list[-1] // 2, then no multiple of si can be in the set (except si itself, but we skip i).
        if si * 2 > sums_list[-1]:
            break
        
        for j in range(i + 1, m):
            sj = sums_list[j]
            if sj % si == 0:
                return False
            # Optional: if sj > si * 100, break? No, multiples can be large.
            # But if sj is very large, sj % si is cheap.
            
    return True

def _can_add(A, x):
    """
    Check if adding x to set A keeps the subset sums divisibility-free.
    A is a list of ints.
    """
    if not A:
        return True
        
    # Compute existing sums
    S_old = _subset_sums(A)
    
    # New sums are S_old union {s + x for s in S_old} union {x}
    # We don't need to store them all if we check on the fly?
    # But we need to check pairs within the new sums too.
    
    # Let D be the set of new sums generated by including x
    # D = {x} U {s + x | s in S_old}
    
    # We need to check:
    # 1. Any d in D divides any e in S_old?
    # 2. Any e in S_old divides any d in D?
    # 3. Any d1 in D divides any d2 in D?
    
    D = set()
    D.add(x)
    for s in S_old:
        D.add(s + x)
        
    # Check 1 & 2: Cross check D and S_old
    # To optimize, we can iterate over the smaller set?
    # S_old and D are similar in size.
    
    # We can combine them into a single list and check, but that's O(N^2) again.
    # Let's do the specific checks.
    
    # Check if any d in D divides any e in S_old
    for d in D:
        if d == 0: continue
        for e in S_old:
            if e == d: continue # Distinct sums
            if e % d == 0:
                return False
            # Note: if d > e, d cannot divide e.
            # So we can skip if d > e.
            
    # Check if any e in S_old divides any d in D
    for e in S_old:
        if e == 0: continue
        for d in D:
            if d == e: continue
            if d % e == 0:
                return False
            # If e > d, e cannot divide d.
            
    # Check if any d1 in D divides any d2 in D
    # This is the same as checking if D is divisibility-free internally.
    # But D is derived from S_old.
    # We can just check the set D.
    if not _is_divisibility_free(D):
        return False
        
    return True

def _greedy_construct(pool, rng):
    """
    Greedily construct a valid set from the pool.
    """
    result = []
    remaining = list(pool)
    rng.shuffle(remaining)
    
    for elem in remaining:
        if time.time() - START_TIME > TIME_LIMIT:
            break
            
        if _can_add(result, elem):
            result.append(elem)
            if len(result) >= 30:
                break
            # If the set of sums becomes too large, stop adding to avoid timeout
            # Estimate size: 2^len(result)
            # If len(result) > 20, 2^20 = 1M sums. _can_add will be slow.
            # We might want to stop earlier or use a faster check.
            # For now, let's see how far we get.
            
    return result

def _local_search(nums, pool, seed, max_rounds=10):
    """
    Try to improve the set by swapping elements.
    """
    rng = random.Random(seed)
    current = list(nums)
    current_set = set(current)
    available = [x for x in pool if x not in current_set]
    
    for _ in range(max_rounds):
        if time.time() - START_TIME > TIME_LIMIT:
            break
            
        improved = False
        
        # Try to swap an element in current with an element in available
        # Pick a random index in current
        if not current:
            break
            
        i = rng.randint(0, len(current) - 1)
        old_elem = current[i]
        
        # Pick a random candidate from available
        if not available:
            break
            
        new_elem = rng.choice(available)
        
        # Try the swap
        trial = current.copy()
        trial[i] = new_elem
        
        if _can_add(trial, 0) is not None: # Wait, _can_add takes a set and an element to add.
            # My _can_add is for adding. I need a full validity check for the trial set.
            pass
        
        # Let's use a simpler full check for local search swaps
        # Check if trial is valid
        if _is_valid_set(trial):
            current = trial
            current_set = set(current)
            available = [x for x in pool if x not in current_set]
            improved = True
            
            # After a swap, try to add more elements
            rng.shuffle(available)
            for elem in available:
                if time.time() - START_TIME > TIME_LIMIT:
                    break
                if _can_add(current, elem):
                    current.append(elem)
                    current_set.add(elem)
                    if len(current) >= 30:
                        break
            available = [x for x in pool if x not in current_set]
            
        if not improved:
            # If no swap worked in this round, maybe break or continue
            # To save time, we can break if we've tried several rounds without improvement
            # But for now, just continue
            pass
            
    return current

def _is_valid_set(nums):
    """
    Check if a set of numbers is valid.
    """
    if not nums:
        return True
    sums = _subset_sums(nums)
    return _is_divisibility_free(sums)

def construct():
    """
    Main entry point.
    """
    pool = list(range(1, 257))
    best = []
    best_size = 0
    
    # Try multiple random restarts
    # Bias towards larger numbers might be better?
    # Or just random.
    
    max_attempts = 50
    
    for attempt in range(max_attempts):
        if time.time() - START_TIME > TIME_LIMIT - 5:
            break
            
        rng = random.Random(attempt * 12345 + 6789)
        
        # Strategy 1: Random order
        pool_order = pool[:]
        rng.shuffle(pool_order)
        
        # Strategy 2: Descending order (large numbers first)
        if attempt % 2 == 1:
            pool_order = sorted(pool, reverse=True)
            rng.shuffle(pool_order[:10]) # Shuffle the top 10 to vary slightly
            
        result = _greedy_construct(pool_order, rng)
        
        # Local search
        if len(result) < 30 and time.time() - START_TIME < TIME_LIMIT - 10:
            result = _local_search(result, pool, seed=attempt * 999 + 1, max_rounds=5)
            
        if len(result) > best_size:
            best = result
            best_size = len(result)
            if best_size >= 30:
                break
                
    # Fallback
    if not best:
        best = [31, 32, 34]
        
    return [int(x) for x in best]
