import numpy as np
import time
from autoresearch_suite.chem_clusters import relax

_START_TIME = time.time()
_HARD_DEADLINE = _START_TIME + 290.0  # Safety margin for 300s limit
_INSTANCE_COUNT = 6
_INSTANCE_INDEX = 0

def _generate_lattice(n, lattice_type, spacing=1.0):
    """Generate n points from a lattice structure centered at origin."""
    # Create a large grid of points
    # Estimate radius needed for n points
    # Volume ~ n * spacing^3 / density
    # For FCC, density is higher. Let's just generate a big cube and filter.
    
    # Approximate radius
    r_max = spacing * (n ** (1/3) + 2)
    
    # Generate grid
    # Step size slightly smaller than spacing to ensure enough candidates
    # Actually, for FCC, we can just generate the lattice points directly.
    
    points = []
    if lattice_type == 'fcc':
        # FCC lattice vectors
        # Generate points in a cubic region
        limit = int(r_max / spacing) + 2
        for i in range(-limit, limit + 1):
            for j in range(-limit, limit + 1):
                for k in range(-limit, limit + 1):
                    # FCC points are (0,0,0) and face centers (1,1,0), etc scaled by spacing/2?
                    # Standard FCC primitive cell has points at (0,0,0), (0, 1/2, 1/2), (1/2, 0, 1/2), (1/2, 1/2, 0) * a
                    # Let's use the explicit coordinates for a cubic supercell
                    # Simpler: generate all integer triples and check if they form FCC? No.
                    # Let's generate points on the FCC lattice directly.
                    # FCC points: (i, j, k) where i,j,k are integers and i+j+k is even? No, that's BCC.
                    # FCC: (i, j, k) where i, j, k are integers and i, j, k are all even or all odd? No.
                    # FCC basis: (0,0,0), (0, 1/2, 1/2), (1/2, 0, 1/2), (1/2, 1/2, 0) in units of lattice constant a.
                    # Let a = spacing.
                    # We can generate all points (i*a, j*a, k*a) and keep those where i+j+k is even? 
                    # Wait, the FCC lattice is a subset of the cubic lattice.
                    # Points (x,y,z) in units of a/2. If x,y,z are all integers, and x+y+z is even, it's BCC?
                    # Let's stick to generating a dense random set on the lattice.
                    pass
                    
    # Let's use a simpler robust method: Generate a large set of random points on a grid, 
    # but specifically for FCC, we can use the fact that it's close-packed.
    # Actually, for small n, we can just use a "spherical cut" of the infinite lattice.
    
    # Generate candidate points
    candidates = []
    limit = int(r_max / spacing) + 2
    
    if lattice_type == 'fcc':
        # FCC points in cubic coordinates (x,y,z) where x,y,z are integers
        # Condition: x+y+z is even? No.
        # FCC is generated by vectors (0, 0.5, 0.5), (0.5, 0, 0.5), (0.5, 0.5, 0) * a
        # This is equivalent to points (i, j, k) * a where i, j, k are integers and i+j+k is even?
        # Let's check: (0,0,0) sum=0 (even). (0, 0.5, 0.5) -> (0, 1, 1) in units of a/2. Sum=2 (even).
        # So yes, if we scale by a/2, we want integer coords with even sum.
        for i in range(-2*limit, 2*limit + 1):
            for j in range(-2*limit, 2*limit + 1):
                for k in range(-2*limit, 2*limit + 1):
                    if (i + j + k) % 2 == 0:
                        p = np.array([i, j, k]) * (spacing / 2.0)
                        candidates.append(p)
    elif lattice_type == 'bcc':
        # BCC: (0,0,0) and (0.5, 0.5, 0.5) * a
        # In units of a/2: (i,j,k) with i,j,k all even or all odd?
        # (0,0,0) -> 0,0,0 (even). (0.5,0.5,0.5) -> 1,1,1 (odd).
        # So i,j,k must have same parity.
        for i in range(-2*limit, 2*limit + 1):
            for j in range(-2*limit, 2*limit + 1):
                for k in range(-2*limit, 2*limit + 1):
                    if (i % 2) == (j % 2) and (j % 2) == (k % 2):
                        p = np.array([i, j, k]) * (spacing / 2.0)
                        candidates.append(p)
    elif lattice_type == 'hcp':
        # HCP is trickier to generate as a simple grid. 
        # We can approximate with FCC for initialization, or generate layer by layer.
        # For now, let's use FCC as a proxy or generate random points if HCP is hard.
        # Actually, let's just use FCC and BCC and Random. HCP is often similar energy.
        # We'll skip explicit HCP generation to save time/complexity, FCC is usually better for Morse.
        return _generate_lattice(n, 'fcc', spacing)
    else:
        # Random
        rng = np.random.default_rng(42)
        candidates = rng.uniform(-r_max, r_max, (n*10, 3))

    candidates = np.array(candidates)
    if len(candidates) < n:
        # Fallback to random if lattice generation failed or was too small
        rng = np.random.default_rng(42)
        candidates = rng.uniform(-r_max, r_max, (n*10, 3))
        
    # Sort by distance from origin
    dists = np.linalg.norm(candidates, axis=1)
    sorted_idx = np.argsort(dists)
    selected = candidates[sorted_idx[:n]]
    
    # Center the cluster
    selected = selected - np.mean(selected, axis=0)
    
    return selected

def construct(instance):
    global _INSTANCE_INDEX
    _INSTANCE_INDEX += 1
    
    size = instance["n"]
    potential = instance["potential"]
    parameter = instance.get("rho", instance.get("kind"))
    
    # Time management
    elapsed = time.time() - _START_TIME
    remaining_total = _HARD_DEADLINE - time.time()
    instances_left = _INSTANCE_COUNT - _INSTANCE_INDEX + 1
    # Allocate time proportional to remaining instances, but cap per-instance time
    # Larger N takes longer to relax.
    # Heuristic: time per atom.
    time_budget = max(2.0, min(40.0, remaining_total / instances_left * 1.5)) # 1.5x average to handle variance
    
    start_time = time.time()
    best_energy = np.inf
    best_positions = None
    
    # Strategies: FCC, BCC, Random
    strategies = ['fcc', 'bcc', 'random']
    
    # For small N, we can afford more restarts
    if size < 50:
        strategies += ['fcc', 'random'] # Duplicate to try again? Or just rely on relax convergence.
        
    for strat in strategies:
        if time.time() - start_time > time_budget:
            break
            
        if strat == 'random':
            rng = np.random.default_rng(size + _INSTANCE_INDEX)
            radius = 1.0 * size ** (1.0 / 3.0) * 0.8
            points = rng.uniform(-radius, radius, (size, 3))
        else:
            points = _generate_lattice(size, strat)
            
        # Ensure minimum distance? Relax should handle it, but bad starts can fail.
        # Add a small jitter to avoid symmetry breaking issues
        points += np.random.default_rng(1).normal(0, 0.01, points.shape)
        
        try:
            energy, positions = relax(points, potential, parameter)
            if energy < best_energy:
                best_energy = energy
                best_positions = positions
        except Exception:
            pass
            
    # If we have time, do a few random restarts
    while time.time() - start_time < time_budget * 0.8:
        rng = np.random.default_rng(int(time.time()*1000) % 10000)
        radius = 1.0 * size ** (1.0 / 3.0) * 0.8
        points = rng.uniform(-radius, radius, (size, 3))
        try:
            energy, positions = relax(points, potential, parameter)
            if energy < best_energy:
                best_energy = energy
                best_positions = positions
        except Exception:
            pass

    if best_positions is None:
        # Fallback: just return random points if everything failed
        rng = np.random.default_rng(0)
        best_positions = rng.uniform(-1, 1, (size, 3))
        
    return best_positions

