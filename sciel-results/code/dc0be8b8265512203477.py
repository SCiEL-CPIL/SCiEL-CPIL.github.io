import math

def construct():
    """
    Construct N as a product of k primes congruent to 1 mod 4 and one prime
    congruent to 3 mod 4 (squared).
    
    N = p_1 * p_2 * ... * p_k * q^2
    
    The number of representations of N as a sum of two squares is 2^(k-1) (for unordered pairs a,b).
    Each (a,b) pair where a^2 + b^2 = N gives a powerful pair (a^2, b^2).
    We select the smallest primes to keep N <= 10^18.
    
    Smallest primes 1 mod 4: 5, 13, 17, 29, 37, 41, 53, 61, 73, 89, 97, ...
    Smallest prime 3 mod 4: 3 (so q^2 = 9)
    
    Let's calculate the product of the first k primes 1 mod 4:
    k=1: 5 * 9 = 45
    k=2: 5*13*9 = 585
    k=3: 5*13*17*9 = 9945
    k=4: 5*13*17*29*9 = 288405
    k=5: 5*13*17*29*37*9 = 10670985
    k=6: 5*13*17*29*37*41*9 = 437510385
    k=7: 5*13*17*29*37*41*53*9 = 23188050405
    k=8: 5*13*17*29*37*41*53*61*9 = 1414471074705
    k=9: 5*13*17*29*37*41*53*61*73*9 = 103256388453465
    k=10: 5*13*17*29*37*41*53*61*73*89*9 = 9189818572358385
    k=11: 5*13*17*29*37*41*53*61*73*89*97*9 = 891412401518763345
    
    k=12 would be 891412401518763345 * 101 = 90032652553395097845 > 10^18.
    
    So max k=11.
    Number of pairs = 2^(11-1) = 1024.
    """
    p1 = [5, 13, 17, 29, 37, 41, 53, 61, 73, 89, 97]
    q = 3
    
    N = q * q
    for p in p1:
        N *= p
        
    # Find all pairs (a, b) such that a + b = N, a, b powerful, a <= b.
    # We know that a, b being perfect squares is sufficient.
    # So we look for x^2 + y^2 = N.
    # Since N is large (~10^18), x and y are up to sqrt(N/2) ~ 7 * 10^8.
    # Iterating x from 1 to sqrt(N/2) is too slow (7 * 10^8 iterations).
    
    # Instead, we can use the formula for the number of representations.
    # But we need the actual pairs.
    
    # Alternative: Use the Gaussian integer factorization.
    # Or, simply iterate x but with a smarter approach?
    # No, 7 * 10^8 is too high for Python in 120s.
    
    # Let's check if we can reduce k to make iteration feasible.
    # If k=6, N = 437510385. sqrt(N/2) ~ 14775.
    # Pairs = 2^5 = 32.
    # Score = 32.
    # Previous score was 0.4 (which is 2 pairs? No, the seed program found a few pairs).
    # The task says score is the number of pairs.
    # If I return 1024 pairs, I need to find them.
    
    # Can we find the pairs without iterating up to 7*10^8?
    # The pairs are generated by the factorization of N in Z[i].
    # N = q^2 * p1 * ... * pk.
    # q=3 is inert (3 mod 4). 3 = (1+i)(1-i) * 3? No, 3 is prime in Z[i] (3 mod 4).
    # 3 = 3 * (1/1) in Z[i]. It doesn't split.
    # Each p_i (1 mod 4) splits as p_i = pi_i * conj(pi_i).
    # A representation x + iy corresponds to a choice of pi_i or conj(pi_i) for each i,
    # multiplied by a unit.
    # Total choices: 2^k.
    # Each choice gives a Gaussian integer z.
    # x + iy = unit * prod(choice_i).
    # x^2 + y^2 = N.
    # We can compute all 2^k Gaussian integers.
    
    # Let's implement this.
    
    # First, find pi_i for each p_i.
    # pi_i = a + bi such that a^2 + b^2 = p_i.
    # a^2 + b^2 = p.
    # b^2 = p - a^2.
    # Iterate a from 1 to sqrt(p).
    
    def find_pi(p):
        limit = math.isqrt(p)
        for a in range(1, limit + 1):
            b2 = p - a * a
            b = math.isqrt(b2)
            if b * b == b2:
                return a, b
        return None, None
    
    pis = []
    for p in p1:
        a, b = find_pi(p)
        pis.append((a, b))
        
    # Now generate all 2^k combinations.
    # We multiply the factors.
    # Start with 1 + 0i.
    # For each pi = a + bi, multiply by (a+bi) or (a-bi).
    # Finally, multiply by q (which is 3) and handle units.
    # The real part x and imaginary part y give a=x, b=y (squared).
    # Note: x^2 + y^2 = N.
    # We want a = x^2, b = y^2.
    # a + b = N.
    # We need a <= b.
    
    pairs = set()
    
    # We generate all 2^k Gaussian integers from the pi's.
    # Let Z be the product.
    # Then x + iy is a representation.
    # The full set of representations comes from Z * u * q (since q is real, it just scales).
    # Actually, N = q^2 * prod(p_i).
    # z = prod(choice_i).
    # |z|^2 = prod(p_i).
    # We need w such that |w|^2 = N.
    # w = q * z * u, where u is a unit (1, i, -1, -i).
    # Let's just compute z for all 2^k choices.
    # Then w = q * z.
    # x = Re(w), y = Im(w).
    # Also w' = q * conj(z), etc.
    # The set of all (x,y) is { Re(q*z*u), Im(q*z*u) } for all 2^k z and 4 units.
    # But Re/Im just swap or change signs.
    # The pairs (x^2, y^2) are the same for z, conj(z), i*z, -z, etc.
    # So we just need the 2^k values of z.
    # For each z, we get x = Re(z), y = Im(z).
    # The pair is (x^2, y^2).
    # Since x and y can be swapped, and signs don't matter for squares,
    # we can just collect all (x^2, y^2) from the 2^k z's.
    # Wait, do the 2^k z's cover all distinct pairs?
    # Yes, because each prime factor contributes a choice of which "half" goes to the real/imaginary part.
    
    # Let's generate the 2^k products.
    # k = 11, so 2048 products.
    
    # z[0] = 1
    # z[j] = z[j-1] * (pi_j or conj(pi_j))
    
    # We can do this iteratively.
    # Start with a list containing [1, 0] (representing 1 + 0i).
    # For each (a, b) in pis:
    #   new_list = []
    #   for (x, y) in list:
    #       # multiply (x+iy) by (a+bi)
    #       x1, y1 = x*a - y*b, x*b + y*a
    #       new_list.append((x1, y1))
    #       # multiply (x+iy) by (a-bi)
    #       x2, y2 = x*a + y*b, -x*b + y*a
    #       new_list.append((x2, y2))
    #   list = new_list
    
    # After all, multiply each (x, y) by q.
    # x_final = q * x, y_final = q * y.
    # pair = (x_final^2, y_final^2).
    
    gaussians = [(1, 0)]
    for a, b in pis:
        new_gaussians = []
        for x, y in gaussians:
            # Multiply by (a+bi)
            x1 = x * a - y * b
            y1 = x * b + y * a
            new_gaussians.append((x1, y1))
            # Multiply by (a-bi)
            x2 = x * a + y * b
            y2 = -x * b + y * a
            new_gaussians.append((x2, y2))
        gaussians = new_gaussians
        
    # Now multiply by q and collect pairs
    for x, y in gaussians:
        xf = q * x
        yf = q * y
        a_sq = xf * xf
        b_sq = yf * yf
        if a_sq > b_sq:
            a_sq, b_sq = b_sq, a_sq
        if a_sq + b_sq == N:
            pairs.add((a_sq, b_sq))
            
    # Convert to list of lists
    pairs_list = [[a, b] for a, b in pairs]
    
    return {'N': N, 'pairs': pairs_list}
