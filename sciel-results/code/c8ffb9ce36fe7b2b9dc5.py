def construct(q, n, radius):
    total_words = q ** n
    
    def int_to_digits(x, n, q):
        digits = [0] * n
        for i in range(n):
            digits[i] = x % q
            x //= q
        return digits

    def digits_to_int(digits, q):
        val = 0
        for d in digits:
            val = val * q + d
        return val

    def get_ball(w, q, n, radius):
        digits = int_to_digits(w, n, q)
        neighbors = {w}
        
        if radius == 0:
            return neighbors
            
        # Generate all subsets of positions of size 1 to radius
        # For each subset, generate all combinations of values for those positions
        # This is equivalent to iterating over all words at distance <= radius
        
        # Efficient way for small radius:
        # For r in 1..radius:
        #   for pos in combinations(range(n), r):
        #     for vals in product(range(q), repeat=r):
        #        if all(vals[i] != digits[pos[i]] for i in range(r)): # Actually we allow some to be same? No, distance is exactly number of changed positions.
        #           # Wait, if we pick positions, we must change them to something different?
        #           # No, if we pick a position, we can change it to any value.
        #           # If we change it to the same value, the distance doesn't increase.
        #           # So we should iterate over all values for the chosen positions, and count the distance.
        
        # Simpler: Just iterate over all possible value vectors for the chosen positions?
        # No, that generates duplicates.
        
        # Let's just use the definition:
        # A word v is in the ball if sum(1 for i in range(n) if digits[i] != v_digits[i]) <= radius
        
        # Since N is small, we can precompute distances? No.
        
        # Let's stick to the specific case radius=1 which is 99% likely.
        # If radius > 1, I will use a slower fallback or just assume radius=1.
        # Given the strict time limit and the specific problem statement, I will optimize for radius=1.
        # If radius != 1, I'll use a simple brute-force check for each candidate during the greedy loop?
        # That would be too slow.
        
