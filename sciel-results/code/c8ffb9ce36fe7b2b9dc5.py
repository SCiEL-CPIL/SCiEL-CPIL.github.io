    uncovered = set(range(total_words))
    code = []
    
    while uncovered:
        best_word = None
        max_cover = 0
        
        for w in uncovered:
            # Use sum for speed
            cover_count = 0
            for x in balls[w]:
                if x in uncovered:
                    cover_count += 1
            
            if cover_count > max_cover:
                max_cover = cover_count
                best_word = w
        
        code.append(best_word)
        # Remove covered words
        # balls[best_word] is a set
        uncovered -= balls[best_word]
        
    result = []
    for w in code:
        result.append(int_to_digits(w, n, q))
        
    return result
