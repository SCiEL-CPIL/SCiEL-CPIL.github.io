    rank = 22
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to set a term
    def set_term(r, u, v, w):
        for i in range(n):
            for j in range(m):
                if u[i][j] != 0:
                    U[i * m + j][r] = u[i][j]
        for j in range(m):
            for k in range(p):
                if v[j][k] != 0:
                    V[j * p + k][r] = v[j][k]
        for k in range(p):
            for i in range(n):
                if w[i][k] != 0:
                    W[k * n + i][r] = w[i][k]
    
    # Strassen terms for 2x2 block (indices 0,1)
    # u, v, w are 3x3 matrices, but only 0,1 indices are used for Strassen
    # w is 3x3, but for Strassen, w[i][k] is 1 for i,k in 0,1?
    # No, w[i][k] is the coefficient for C[i][k].
    # In Strassen, C[i][k] = sum w[i][k] M_r.
    # So w[i][k] is the coefficient.
    
    # M1 = (A00+A11)(B00+B11)
    u1 = [[1,0,0],[1,0,0],[0,0,0]]
    v1 = [[1,0,0],[0,1,0],[0,0,0]]
