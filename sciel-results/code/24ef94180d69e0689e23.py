def _autocorr_peak(h):
    """Compute max absolute autocorrelation at non-zero lags."""
    n = len(h)
    if n <= 1:
        return 0.0
    # Use FFT for efficient autocorrelation
    fft_size = 1
    while fft_size < 2 * n:
        fft_size *= 2
    H = np.fft.rfft(h, n=fft_size)
    acf = np.fft.irfft(np.abs(H) ** 2, n=fft_size)
    # acf[k] for k in 1..n-1 gives positive lags
    # For real signals, acf is symmetric, so max over 1..n-1 suffices
    return float(np.max(np.abs(acf[1:n])))

def _score(h):
    """Upper bound on C3: max absolute autocorrelation at non-zero lags."""
    return _autocorr_peak(h)

def _thue_morse_sequence(length):
    """
    Generate the Thue-Morse sequence mapped to {-1, +1}.
    The Thue-Morse sequence is generated by the morphism 0->01, 1->10.
    It is aperiodic and has flat autocorrelation properties.
    We map 0 -> +1 and 1 -> -1.
    """
    # Generate the sequence up to the required length
    # The Thue-Morse sequence can be generated by t(n) = popcount(n) % 2
    # We want a sequence of length 'length'
    # t(n) = 0 for even popcount, 1 for odd popcount
    # Map: 0 -> +1, 1 -> -1
    n = np.arange(length)
    # Compute popcount for each n
    # Efficient way using numpy bit operations
    # popcount can be computed by summing bits
    # Or use a lookup table for small numbers, but here n goes up to 400
    # Let's use a vectorized approach
    # t(n) = sum of binary digits of n mod 2
    # This is equivalent to: t(n) = n & 1 XOR t(n >> 1)
    # But we can just compute it directly for n < 400
    
    # Using a simple loop for clarity, or vectorized:
    # For n in range(length):
    #   pop = 0
    #   x = n
    #   while x:
    #       pop += x & 1
    #       x >>= 1
    #   seq[i] = 1 if pop % 2 == 0 else -1
    
    # Vectorized approach:
    # Create a matrix of bits
    max_bit = int(math.log2(length)) + 1
    bits = (n[:, None] >> np.arange(max_bit)) & 1
    popcounts = bits.sum(axis=1)
    seq = np.where(popcounts % 2 == 0, 1.0, -1.0)
    return seq

def _legendre_sequence(length, p):
    """
    Generate the Legendre symbol sequence modulo a prime p, mapped to {-1, +1, 0}.
    Legendre symbol (a/p) is 1 if a is a quadratic residue mod p, -1 if non-residue, 0 if a=0.
    We use this for a structured low-autocorrelation sequence.
    """
    seq = np.zeros(length)
    for i in range(1, length):
        # Compute Legendre symbol of i mod p
        # Using Euler's criterion: (i/p) = i^((p-1)/2) mod p
        # 1 -> 1, p-1 -> -1, 0 -> 0
        x = pow(i % p, (p - 1) // 2, p)
        if x == 1:
            seq[i] = 1.0
        elif x == p - 1:
            seq[i] = -1.0
        else:
            seq[i] = 0.0
    return seq

def _muller_sequence(length):
    """
    Generate a Muller sequence (a type of low-autocorrelation sequence).
    These are derived from Legendre sequences but with specific modifications.
    For simplicity, we use a variant of the Legendre sequence with a prime near N/2.
    """
    # Find a prime near length/2
    p = 199  # A prime close to 200
    if p < length:
        p = 397  # A prime close to 400
    return _legendre_sequence(length, p)

def _fast_greedy(h, time_limit=5.0):
    """
    Fast greedy local search.
    1. Flip signs of individual bits.
    2. Zero out bits.
    3. Activate zero bits with +/- 1.
    Uses random ordering to escape local minima.
    """
    n = len(h)
    best_h = h.copy()
    best_score = _score(best_h)
    start = time.time()
    
    while time.time() - start < time_limit:
        improved = False
        
        # Identify active indices
        nonzero_idx = np.nonzero(best_h)[0]
        if len(nonzero_idx) == 0:
            break
            
        # 1. Try flipping signs
        order = np.random.permutation(len(nonzero_idx))
        for idx_pos in order:
            i = nonzero_idx[idx_pos]
            trial = best_h.copy()
            trial[i] = -trial[i]
            s = _score(trial)
            if s < best_score - 1e-12:
                best_h = trial
                best_score = s
                improved = True
                break
        
        # 2. Try zeroing out
        if not improved:
            nonzero_idx = np.nonzero(best_h)[0]
            if len(nonzero_idx) > 0:
                order = np.random.permutation(len(nonzero_idx))
                for idx_pos in order:
                    i = nonzero_idx[idx_pos]
                    trial = best_h.copy()
                    trial[i] = 0.0
                    s = _score(trial)
                    if s < best_score - 1e-12:
                        best_h = trial
                        best_score = s
                        improved = True
                        break
        
        # 3. Try activating zeros
        if not improved:
            zero_idx = np.nonzero(best_h == 0)[0]
            if len(zero_idx) > 0:
                # Limit activations per iteration to keep it fast
                k = min(20, len(zero_idx))
                order = np.random.choice(len(zero_idx), size=k, replace=False)
                for idx_pos in order:
                    i = zero_idx[idx_pos]
                    for sign in [1.0, -1.0]:
                        trial = best_h.copy()
                        trial[i] = sign
                        s = _score(trial)
                        if s < best_score - 1e-12:
                            best_h = trial
                            best_score = s
                            improved = True
                            break
                    if improved:
                        break
        
        if not improved:
            break
            
    return best_h, best_score

def _simulated_annealing(h, time_limit=10.0):
    """
    Simulated annealing to escape local minima.
    """
    n = len(h)
    current_h = h.copy()
    current_score = _score(current_h)
    best_h = current_h.copy()
    best_score = current_score
    
    start = time.time()
    T = 5.0
    cooling = 0.995
    min_T = 0.1
    
    while T > min_T and time.time() - start < time_limit:
        # Pick a random move
        i = np.random.randint(n)
        trial = current_h.copy()
        
        # Randomly choose between flip, zero, or activate
        r = np.random.random()
        if r < 0.6:
            # Flip sign (or activate if 0)
            if trial[i] == 0:
                trial[i] = 1.0 if np.random.random() < 0.5 else -1.0
            else:
                trial[i] = -trial[i]
        elif r < 0.8:
            # Zero out
            trial[i] = 0.0
        else:
            # Activate (if zero) or flip (if non-zero)
            if trial[i] == 0:
                trial[i] = 1.0 if np.random.random() < 0.5 else -1.0
            else:
                trial[i] = -trial[i]
        
        new_score = _score(trial)
        delta = new_score - current_score
        
        if delta < 0 or np.random.random() < np.exp(-delta / T):
            current_h = trial
            current_score = new_score
            if new_score < best_score:
                best_score = new_score
                best_h = current_h.copy()
        
        T *= cooling
        
    return best_h, best_score

