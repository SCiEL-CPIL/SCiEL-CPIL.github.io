import numpy as np
import time
from scipy.stats import norm

_EPS = 1e-9

def _ackley_2d(x):
    """Ackley 2D function (standard, minimum at 0,0)."""
    x1 = x[:, 0]
    x2 = x[:, 1]
    sum_sq = x1**2 + x2**2
    sum_cos = np.cos(2.0 * np.pi * x1) + np.cos(2.0 * np.pi * x2)
    return -20.0 * np.exp(-0.2 * np.sqrt(0.5 * sum_sq)) - np.exp(0.5 * sum_cos) + np.e + 20.0


def acquisition(mu, sigma, f_best, cost):
    """
    Cost-aware acquisition function: uses Expected Improvement adjusted for cost,
    with a small exploration bonus based on GP uncertainty.
    
    mu, sigma: (2000,) arrays of GP mean and std in objective units
    f_best: scalar, lowest observed value
    cost: (2000,) array of evaluation costs
    
    Returns: (2000,) finite scores, higher = prefer to evaluate next
    """
    mu = np.asarray(mu, dtype=np.float64)
    sigma = np.asarray(sigma, dtype=np.float64)
    cost = np.asarray(cost, dtype=np.float64)
    
    # Ensure sigma is positive
    sigma = np.maximum(sigma, 1e-12)
    
    # Expected Improvement
    improvement = f_best - mu
    z = improvement / sigma
    ei = improvement * norm.cdf(z) + sigma * norm.pdf(z)
    ei = np.maximum(ei, 0.0)
    
    # Cost-aware EI: divide by cost to prefer low-cost evaluations
    # cost is in [1, 2] for this problem (1 + mean of two coords scaled to [0,1])
    cost_aware_ei = ei / (cost + _EPS)
    
    # Add a small exploration bonus: prefer high-uncertainty regions
    # but scale it down so exploitation dominates
    # Use a small multiplier to avoid excessive exploration
    exploration_bonus = 0.05 * sigma / (cost + _EPS)
    
    # Final score
    score = cost_aware_ei + exploration_bonus
    
    # Ensure finite
    score = np.where(np.isfinite(score), score, 0.0)
    
    return score
