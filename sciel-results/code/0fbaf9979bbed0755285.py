import sys
from itertools import combinations

def construct():
    # The 132 blocks of the Steiner System S(5,6,12) (Witt Design)
    # Points are 0..11
    # This is a hard-coded list of the unique blocks.
    # Generation logic: These are the weight-6 codewords of the related code or derived from the M12 group action.
    # For reliability and speed, we provide the explicit list.
    
    blocks = [
        (0, 1, 2, 3, 4, 5), (0, 1, 2, 6, 7, 8), (0, 1, 2, 9, 10, 11),
        (0, 1, 3, 6, 9, 10), (0, 1, 3, 7, 8, 11), (0, 1, 4, 6, 8, 11),
        (0, 1, 4, 7, 9, 10), (0, 1, 5, 6, 7, 11), (0, 1, 5, 7, 8, 10),
        (0, 1, 5, 8, 9, 11), (0, 2, 3, 6, 8, 11), (0, 2, 3, 7, 9, 10),
        (0, 2, 4, 6, 7, 10), (0, 2, 4, 7, 8, 9), (0, 2, 4, 5, 9, 11),
        (0, 2, 5, 6, 8, 10), (0, 2, 5, 7, 9, 11), (0, 3, 4, 6, 9, 10),
        (0, 3, 4, 7, 8, 11), (0, 3, 5, 6, 7, 9), (0, 3, 5, 8, 10, 11),
        (0, 4, 5, 6, 8, 9), (0, 4, 5, 7, 10, 11), (1, 2, 3, 7, 8, 9),
        (1, 2, 3, 8, 10, 11), (1, 2, 4, 5, 8, 10), (1, 2, 4, 6, 9, 11),
        (1, 2, 5, 6, 8, 9), (1, 2, 5, 7, 10, 11), (1, 3, 4, 6, 8, 9),
        (1, 3, 4, 7, 10, 11), (1, 3, 5, 6, 7, 8), (1, 3, 5, 9, 10, 11),
        (1, 4, 5, 7, 9, 10), (1, 4, 5, 8, 11, 12) # Wait, 12 is out of range. 
    ]
    
    # The hardcoded list above is prone to errors if I type it manually.
    # Let's use a programmatic generation that is fast.
    # We can use the fact that S(5,6,12) is unique.
    # A known fast generation uses the icosahedron symmetry.
    
    # However, to be absolutely safe and fast, I will use a pre-computed list 
    # generated by a trusted source or algorithm in the code itself.
    
    # Let's use a backtracking search but with a very strong heuristic:
    # 1. Use bitsets.
    # 2. Pick the 5-subset with the minimum number of available covering blocks.
    # 3. This "Minimum Remaining Values" (MRV) heuristic often solves these instantly.
    
    n = 12
    points = range(n)
    fives = list(combinations(points, 5))
    five_to_idx = {f: i for i, f in enumerate(fives)}
    num_fives = len(fives)
    
    sixes = list(combinations(points, 6))
    six_masks = []
    six_tuples = []
    
    for s in sixes:
        mask = 0
        for f in combinations(s, 5):
            idx = five_to_idx[f]
            mask |= (1 << idx)
        six_masks.append(mask)
        six_tuples.append(s)
        
    num_sixes = len(sixes)
    
    # covers[idx_5] = list of indices of 6-sets that contain this 5-set
    covers = [[] for _ in range(num_fives)]
    for i, s in enumerate(six_tuples):
        for f in combinations(s, 5):
            idx_f = five_to_idx[f]
            covers[idx_f].append(i)
            
    # We maintain a set of available block indices.
    # We use a recursive function.
    
    solution = []
    
    # Pre-compute conflict masks? 
    # If we pick block i, we remove all j where six_masks[j] & six_masks[i] != 0.
    
    def backtrack(covered_mask, available_set, depth):
        if depth == 132:
            return covered_mask == (1 << num_fives) - 1
            
        # Find the uncovered 5-subset with the fewest available blocks (MRV)
        # This requires iterating through uncovered 5-subsets and counting available blocks.
        # To speed this up, we can just pick the first uncovered one if MRV is too slow to compute.
        # But MRV is crucial.
        
        # Optimization: 
        # Instead of counting for every uncovered 5-subset, we can just pick one.
        # But let's try to be smart.
        
        # For simplicity and speed in Python, picking the first uncovered is O(N).
        # Counting availables for each is O(N * K).
        
        target_idx = -1
        min_count = float('inf')
        
        # Iterate through all 5-subsets to find the most constrained uncovered one
        for i in range(num_fives):
            if not (covered_mask & (1 << i)):
                # Count how many available blocks cover this 5-subset
                count = 0
                for b_idx in covers[i]:
                    if b_idx in available_set:
                        count += 1
                if count < min_count:
                    min_count = count
                    target_idx = i
                    if min_count == 0:
                        return False # Dead end
                    if min_count == 1:
                        break # Can't get better than 1
                
        if target_idx == -1:
            # All covered
            return depth == 132
            
        # Get candidates
        candidates = []
        for b_idx in covers[target_idx]:
            if b_idx in available_set:
                mask = six_masks[b_idx]
                if (mask & covered_mask) == 0:
                    candidates.append(b_idx)
                    
        if not candidates:
            return False
            
        # Try each candidate
        for b_idx in candidates:
            mask = six_masks[b_idx]
            new_covered = covered_mask | mask
            
            # Compute new available set
            # Remove b_idx and all conflicting blocks
            new_available = set()
            for other in available_set:
                if other == b_idx:
                    continue
                if (six_masks[other] & mask) == 0:
                    new_available.add(other)
                    
            solution.append(six_tuples[b_idx])
            
            if backtrack(new_covered, new_available, depth + 1):
                return True
                
            solution.pop()
            
        return False

    initial_available = set(range(num_sixes))
    if backtrack(0, initial_available, 0):
        return solution
    else:
        return []
