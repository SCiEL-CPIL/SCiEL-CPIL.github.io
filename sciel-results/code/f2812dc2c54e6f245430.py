import time
import random

def construct():
    N = 18
    MIN_DIST = 6
    TOTAL_BUDGET = 55.0
    t_start = time.time()
    deadline = t_start + TOTAL_BUDGET

    # Build the extended quadratic-residue code of length 18, dimension 6, distance 6
    # This is a [18, 6, 6] code with 64 words.
    # The quadratic-residue code QR(18) is the [18, 6, 6] code.
    # We construct it using the known generator matrix or by direct construction.
    
    # The QR(18) code can be constructed as follows:
    # It's the extended quadratic residue code for p=18? No, QR codes are for primes.
    # Actually, the [18,6,6] code is the extended quadratic residue code from p=17, 
    # but that would be length 18 (17+1 parity).
    
    # Let me use a known construction: the [18,6,6] code is the extended QR(17) code.
    # QR(17) has parameters [17,6,5], and extending gives [18,6,6].
    
    # The quadratic residues mod 17 are: 1, 2, 4, 8, 9, 13, 15, 16 (8 elements)
    # The QR code is generated by the circulant matrix with first row having 1s at QR positions.
    
    # For QR(17): the generator matrix is 6x17, circulant, with first row:
    # positions 0,1,2,4,8,9,13,16 (0-indexed, where position 0 corresponds to residue 1)
    # Actually, let me use a different approach.
    
    # Let me just use a known [18,6,6] code. The extended QR(17) code has 64 codewords.
    # I'll construct it by building the generator matrix and computing all 2^6 = 64 codewords.
    
    # Generator matrix for QR(17) (length 17, dimension 6, distance 5):
    # The first row of the circulant generator has 1s at the quadratic residue positions mod 17.
    # Quadratic residues mod 17: {1, 2, 4, 8, 9, 13, 15, 16}
    # In 0-indexed positions (shifting by 1): {0, 1, 3, 7, 8, 12, 14, 15}
    # The generator matrix G is 6x17, where row i is the cyclic shift of row 0 by i.
    
    # Row 0: 1s at positions {0, 1, 3, 7, 8, 12, 14, 15} (0-indexed)
    row0 = [0] * 17
    for pos in [0, 1, 3, 7, 8, 12, 14, 15]:
        row0[pos] = 1
    
    # Build generator matrix (6 rows, each a cyclic shift)
    G = []
    for i in range(6):
        row = [row0[(j - i) % 17] for j in range(17)]
        G.append(row)
    
    # Compute all 2^6 = 64 codewords
    qr_words_17 = []
    for mask in range(64):
        word = 0
        for i in range(6):
            if (mask >> i) & 1:
                for j in range(17):
                    if G[i][j]:
                        word ^= (1 << j)
        qr_words_17.append(word)
    
    # Extend to length 18 by adding a parity bit
    qr_words_18 = []
    for w in qr_words_17:
        parity = w.bit_count() % 2
        # Add parity bit at position 17
        extended = w | (parity << 17)
        qr_words_18.append(extended)
    
    # Verify the distance is at least 6
    def min_distance(words):
        min_d = N
        for i in range(len(words)):
            for j in range(i + 1, len(words)):
                d = (words[i] ^ words[j]).bit_count()
                if d < min_d:
                    min_d = d
        return min_d
    
    # Check our construction
    md = min_distance(qr_words_18)
    if md < MIN_DIST:
        # Fallback to Reed-Muller if construction is wrong
        rm_words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                rm_words.append(word)
        best_words = list(rm_words)
    else:
        best_words = list(qr_words_18)
    
    best_size = len(best_words)
    
    # Greedy extension
    def can_add(candidate, current_words):
        for w in current_words:
            if (candidate ^ w).bit_count() < MIN_DIST:
                return False
        return True
    
    current_words = list(best_words)
    current_set = set(current_words)
    
    # Try to add more words greedily
    added_any = True
    while added_any and time.time() < deadline - 5.0:
        added_any = False
        for candidate in range(1 << N):
            if candidate in current_set:
                continue
            if can_add(candidate, current_words):
                current_words.append(candidate)
                current_set.add(candidate)
                added_any = True
                if len(current_words) > best_size:
                    best_words = list(current_words)
                    best_size = len(best_words)
    
    return best_words
