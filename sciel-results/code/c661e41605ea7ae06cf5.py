"""Linear triple system on 16 points minimizing independence number."""
import time
import random
from itertools import combinations

DEADLINE = 145.0  # wall-clock safety margin (evaluator kills at 150s)


def _independence_number(triples, n=16):
    """Largest subset of points containing no complete triple."""
    # Use the complement: a set is independent iff it contains no triple.
    # We want max size. Try sizes from high down; use bitsets.
    triples_bits = []
    for t in triples:
        b = 0
        for x in t:
            b |= (1 << x)
        triples_bits.append(b)
    all_mask = (1 << n) - 1
    # Check from size n down
    for size in range(n, 0, -1):
        for combo in combinations(range(n), size):
            mask = 0
            for x in combo:
                mask |= (1 << x)
            independent = True
            for b in triples_bits:
                if (mask & b) == b:
                    independent = False
                    break
            if independent:
                return size
    return 0


def _is_linear(triples):
    """Any two triples share at most one point."""
    for i in range(len(triples)):
        for j in range(i + 1, len(triples)):
            common = set(triples[i]) & set(triples[j])
            if len(common) > 1:
                return False
    return True


