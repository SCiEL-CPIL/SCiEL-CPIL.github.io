def construct():
    start = time.time()
    n = 16

    def time_ok():
        return (time.time() - start) < DEADLINE

    # Start from STS(15) on points 0..14, point 15 isolated.
    base = _build_sts15_z15()
    # Verify linearity of base (should be a valid STS -> linear)
    if not _is_linear(base):
        # Fallback: just use a safe linear system
        base = [[3*i, 3*i+1, 3*i+2] for i in range(5)]

    best = [list(t) for t in base]
    best_alpha = _independence_number(best, n)

    # Try to add triples involving point 15 to reduce independence number.
    # A triple containing 15 plus two points from 0..14 must not share 2 points
    # with any existing triple. Since STS(15) covers each pair exactly once,
    # adding {15,a,b} is linear iff {a,b} is NOT already a pair in a triple
    # that... actually linearity only cares about pair overlap between triples.
    # {15,a,b} shares {a,b} with the unique triple containing a,b in STS(15) ->
    # that's 2 shared points -> NOT linear. So we cannot add any {15,a,b}
    # where {a,b} is a pair in STS(15). But STS(15) covers ALL pairs of 0..14!
    # So NO triple containing 15 and two points from 0..14 is linear.
    # Hence point 15 must remain isolated, OR we must remove some STS triples.
    # 
    # Strategy: remove a few STS(15) triples to free up pairs, then add triples
    # with 15, then local search.

    # Local search: try to reduce independence number by swapping/adding/removing triples.
    def alpha(triples):
        return _independence_number(triples, n)

    # Greedy add of triples involving 15 after removing conflicting pairs.
    # Try: for each pair (a,b) in 0..14, we could remove the triple containing it
    # (if we want) and add {15,a,b}. Net: -1 triple +1 triple, but we free the pair.
    # This is complex; do a randomized local search instead.

    random.seed(42)
    current = [list(t) for t in best]
    cur_alpha = best_alpha

    # Precompute pair -> triple index for linearity checks
    def pair_map(triples):
        pm = {}
        for i, t in enumerate(triples):
            for a, b in combinations(sorted(t), 2):
                pm[(a, b)] = i
        return pm

    def can_add(triples, pm, t):
        s = sorted(t)
        for a, b in combinations(s, 2):
            if (a, b) in pm:
                return False
        return True

    # Randomized hill-climbing with occasional restarts
    for restart in range(2000):
        if not time_ok():
            break
        if restart > 0 and restart % 200 == 0:
            # restart from base
            current = [list(t) for t in best]
            cur_alpha = best_alpha

        pm = pair_map(current)
        improved = False
        # Try adding a random triple (with 15 or within 0..14) that is linear
        for _ in range(40):
            if not time_ok():
                break
            if random.random() < 0.5:
                a, b = random.sample(range(15), 2)
                t = [15, a, b]
            else:
                t = random.sample(range(15), 3)
            if can_add(current, pm, t):
                new_alpha = alpha(current + [t])
                if new_alpha < cur_alpha:
                    current.append(t)
                    cur_alpha = new_alpha
                    improved = True
                    if cur_alpha < best_alpha:
                        best = [list(x) for x in current]
                        best_alpha = cur_alpha
                    break
                # occasionally accept equal to explore
                elif new_alpha == cur_alpha and random.random() < 0.3:
                    current.append(t)
                    improved = True
                    break
        if cur_alpha < best_alpha:
            best = [list(x) for x in current]
            best_alpha = cur_alpha

    # Final: try removing triples that don't help (a triple that is "redundant"
    # for independence). Removing a triple can only increase or keep alpha, so
    # we only remove if it lets us add more. Skip for simplicity.

    if not time_ok():
        return best

    # Verify best is linear
    if not _is_linear(best):
        return [[3*i, 3*i+1, 3*i+2] for i in range(5)]

    return best


if __name__ == "__main__":
    res = construct()
    print("triples:", len(res), "alpha:", _independence_number(res))
