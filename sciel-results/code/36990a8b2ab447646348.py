import time
import numpy as np
from itertools import product

_START_TIME = time.time()
_TIME_LIMIT = 300.0
_SAFETY_MARGIN = 15.0

def _calc_forbidden(v, b, n):
    """Calculate the forbidden point -v - b mod 3."""
    # Using list comprehension for speed, then tuple
    # v and b are tuples of ints
    return tuple((-v[i] - b[i]) % 3 for i in range(n))

def priority(vector, n):
    """
    Greedy cap set construction with incremental forbidden set maintenance.
    Returns the size of the largest cap set found.
    """
    global _START_TIME
    start_time = _START_TIME
    
    # Generate all vectors in Z_3^n
    all_vecs = list(product(range(3), repeat=n))
    
    # Heuristic: Sort by sum of coordinates descending.
    # Vectors with higher sums (more 1s and 2s) are often added earlier in good cap sets.
    # We can also try sorting by number of 1s.
    # Let's use sum(v) as the primary key, and maybe a hash for tie-breaking to ensure determinism but variety.
    # Actually, simple sum is fast.
    candidates = sorted(all_vecs, key=lambda v: sum(v), reverse=True)
    
    # Greedy construction
    S = set() # Current cap set
    F = set() # Forbidden points (points that would complete a 3-AP with two points in S)
    
    # Pre-compute n for inner loops to avoid global lookup? No, it's local.
    
    for vec in candidates:
        # Time check
        if time.time() - start_time > _TIME_LIMIT - _SAFETY_MARGIN:
            break
        
        # Check if vec is valid
        # It must not be in S (already added)
        # It must not be in F (would form a 3-AP with two existing points)
        if vec in S or vec in F:
            continue
        
        # Add vec to S
        S.add(vec)
        
        # Update F with new forbidden points generated by pairs (vec, b) for b in S_old
        # S currently contains vec. We need to iterate over the other elements.
        # To avoid creating a copy of S (which is O(K)), we can just iterate and skip vec.
        # However, F is a set, so adding duplicates is cheap (no-op).
        # We must ensure we don't use the *new* S to generate forbidden points that involve vec twice?
        # The condition is distinct a, b.
        # If we iterate over S (which includes vec), and pick b=vec, we get -vec - vec = -2vec = vec (mod 3).
        # So we would add vec to F.
        # If vec is in F, it doesn't matter for *future* checks because vec is already in S.
        # But it might prevent adding vec again? No, we check `vec in S` first.
        # However, adding vec to F is "correct" in the sense that you can't have a 3-AP of (vec, vec, vec) if we considered multisets, but we are dealing with sets.
        # The definition of cap set usually requires distinct points for the 3-AP.
        # So (a, a, a) is not a 3-AP in the set context if a appears once.
        # So we should NOT add -2vec to F if we only care about distinct triples.
        # But wait, if a=b, it's not a valid 3-AP in a set.
        # So we should skip b=vec.
        
        for b in S:
            if b == vec:
                continue
            f = _calc_forbidden(vec, b, n)
            F.add(f)
    
    return float(len(S))
