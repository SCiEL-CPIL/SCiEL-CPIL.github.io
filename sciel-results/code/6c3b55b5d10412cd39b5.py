import numpy as np
import time
import random

def construct(q, n, radius):
    # Parameters for K_3(7,1)
    if q != 3 or n != 7 or radius != 1:
        # Fallback for other parameters, though task is specific
        # Simple greedy for others
        pass

    total_words = q ** n
    num_words = total_words
    
    # Map word to index
    def word_to_idx(w):
        idx = 0
        for i in range(n):
            idx = idx * q + w[i]
        return idx

    def idx_to_word(idx):
        w = [0] * n
        for i in range(n - 1, -1, -1):
            w[i] = idx % q
            idx //= q
        return w

    # Precompute neighbors as lists of indices
    # Also precompute a bitset representation for speed in local search?
    # 2187 bits = 35 uint64s.
    # Let's stick to lists for clarity and speed in Python if optimized, 
    # but the directive wants a "new design".
    
    # New Design: 
    # 1. Initialize with a random valid code (generated by greedy covering)
    # 2. Use Iterated Local Search with 2-opt swaps
    # 3. Use NumPy for counting
    
    # Generate neighbors
    neighbors = []
    for i in range(total_words):
        w = idx_to_word(i)
        covered = [i]
        for pos in range(n):
            original = w[pos]
            for val in range(q):
                if val == original:
                    continue
                w[pos] = val
                covered.append(word_to_idx(w))
            w[pos] = original
        neighbors.append(covered)
        
    # Convert neighbors to numpy arrays for potential vectorization?
    # Or just use sets for membership testing in local search?
    # The current program uses lists and `in` which is O(N). 
    # Using sets for neighbors would be O(1).
    neighbor_sets = [set(neb) for neb in neighbors]
    
    # Greedy Construction of Initial Code
    # Start with empty code, add words that cover the most uncovered words
    covered_mask = np.zeros(total_words, dtype=bool)
    code_indices = []
    
    # Precompute coverage counts for greedy
    # This is O(N^2) roughly. 2187 * 15 is small.
    
    uncovered = np.ones(total_words, dtype=bool)
    
    while np.any(uncovered):
        # Find word with max coverage of uncovered words
        best_idx = -1
        best_cov = -1
        # Randomize tie-breaking
        candidates = np.where(uncovered)[0]
        if len(candidates) == 0:
            break
            
        # Sample or check all? 2187 is small enough to check all.
        # But we only need to consider words that are uncovered? 
        # No, a covered word can cover more uncovered words.
        # Actually, if a word is covered, it's in the code or covered by code.
        # We are building the code.
        
        # Optimization: Only consider words that are currently uncovered?
        # No, a word might be covered but cover many others.
        # However, in radius 1, if u is covered by v, and u covers w, v might not cover w.
        
        for i in range(total_words):
            # How many uncovered words does i cover?
            # Sum of uncovered[j] for j in neighbors[i]
            # Using numpy:
            cov_count = np.sum(uncovered[neighbors[i]])
            if cov_count > best_cov:
                best_cov = cov_count
                best_idx = i
                
        if best_idx == -1:
            break
            
        code_indices.append(best_idx)
        # Update uncovered
        uncovered[neighbors[best_idx]] = False
        
    # Current code size
    current_code = set(code_indices)
    in_code = np.zeros(total_words, dtype=bool)
    for i in current_code:
        in_code[i] = True
        
    count = np.zeros(total_words, dtype=np.int32)
    for i in current_code:
        count[neighbors[i]] += 1
        
    # Verify validity
    def is_valid():
        return np.all(count > 0)
        
    # Local Search: 2-Swap
    # Pick i in code, remove it.
    # Find two words j, k not in code that cover the uncovered set U.
    # Or pick i, j in code, remove them, find k, l to replace.
    
    start_time = time.time()
    time_limit = 115.0
    best_size = len(current_code)
    best_code = set(current_code)
    
    # Precompute list of non-code words for random selection?
    # Just use random.randint
    
    while time.time() - start_time < time_limit:
        # Try 1-Swap
        if current_code:
            i = random.choice(list(current_code))
            # Check if i is critical
            U = [j for j in neighbors[i] if count[j] == 1]
            
            if not U:
                # Remove i
                current_code.remove(i)
                in_code[i] = False
                count[neighbors[i]] -= 1
                # Greedy removal
                changed = True
                while changed:
                    changed = False
                    for j in list(current_code):
                        if j not in current_code: continue
                        if all(count[k] > 1 for k in neighbors[j]):
                            current_code.remove(j)
                            in_code[j] = False
                            count[neighbors[j]] -= 1
                            changed = True
                            
                if len(current_code) < best_size:
                    best_size = len(current_code)
                    best_code = set(current_code)
                continue
            
            # Try to find replacement k
            # k must cover all U
            found_k = -1
            # Optimize: k must be in intersection of neighbors of all u in U
            # Since |U| is small, just check candidates
            # Candidates: words not in code
            # We can restrict candidates to words that are "close" to U?
            # Just iterate all
            
            for k in range(total_words):
                if in_code[k]:
                    continue
                if all(u in neighbor_sets[k] for u in U):
                    found_k = k
                    break
                    
            if found_k != -1:
                # Swap i with k
                current_code.remove(i)
                in_code[i] = False
                count[neighbors[i]] -= 1
                
                current_code.add(found_k)
                in_code[found_k] = True
                count[neighbors[found_k]] += 1
                
                # Greedy removal
                changed = True
                while changed:
                    changed = False
                    for j in list(current_code):
                        if j not in current_code: continue
                        if all(count[k] > 1 for k in neighbors[j]):
                            current_code.remove(j)
                            in_code[j] = False
                            count[neighbors[j]] -= 1
                            changed = True

                if len(current_code) < best_size:
                    best_size = len(current_code)
                    best_code = set(current_code)

    final_indices = list(best_code)
    final_words = [idx_to_word(i) for i in final_indices]
    return final_words
