def _order_in_abelian(s, a, b):
    # Order of (x, y) in Z_a x Z_b is lcm(ord_x, ord_y)
    # ord_x in Z_a is a / gcd(x, a)
    # ord_y in Z_b is b / gcd(y, b)
    x, y = s
    if x == 0 and y == 0:
        return 1
    ox = a // math.gcd(x, a) if x != 0 else 1
    oy = b // math.gcd(y, b) if y != 0 else 1
    return math.lcm(ox, oy)

def _neg_abelian(s, a, b):
    x, y = s
    return (-x) % a, (-y) % b

def _generates_group(s1, s2, a, b):
    # Check if subgroup generated by s1, s2 is Z_a x Z_b
    # This is true iff the matrix [[x1, x2], [y1, y2]] has rank 2 over the appropriate rings?
    # Simpler: BFS from (0,0) with steps s1, s2. If we visit all a*b nodes, it generates.
    # But this is O(n). We do this for many pairs.
    # Optimization: The group generated is Z_{d1} x Z_{d2} ...
    # Actually, for Z_a x Z_b, the generated subgroup is a sublattice.
    # The index of the subgroup is the determinant of the matrix formed by the generators and the basis, if they form a basis?
    # Let's just use the gcd condition for the components?
    # The subgroup generated by (x1, y1) and (x2, y2) in Z_a x Z_b is the whole group iff:
    # 1. gcd(x1, x2, a) = 1 ? No.
    # Let's use the property that the projection to Z_a and Z_b must generate them?
    # Not sufficient.
    # Let's just do a quick check:
    # The subgroup H is generated by s1, s2.
    # H = { k1 s1 + k2 s2 }.
    # The order of H divides n.
    # We can compute the order of the subgroup by finding the size of the lattice generated by s1, s2 in Z^2, modulo the lattice of the group.
    # This is complex.
    # Given the small n, let's just do a BFS limited to a few steps? No.
    # Let's assume if the determinant of [[x1, x2], [y1, y2]] is coprime to something?
    # For Z_m x Z_m, det must be coprime to m.
    # For general a, b, it's harder.
    # Let's just skip this check and let the girth check fail if it's not connected?
    # No, girth check assumes connectedness? No, it just checks for cycles.
    # But the task requires the graph to be connected? "Construct a 4-regular graph...". Usually implies connected.
    # If it's not connected, it's invalid.
    # So we MUST check connectedness.
    # We can do a BFS for connectedness. It's O(n).
    # With 30k pairs and n=250, that's 7.5M operations. Acceptable.
    
    visited = set()
    queue = [(0, 0)]
    visited.add((0, 0))
    while queue:
        u, v = queue.pop(0)
        for s in [s1, s2]:
            nu = (u + s[0]) % a
            nv = (v + s[1]) % b
            if (nu, nv) not in visited:
                visited.add((nu, nv))
                queue.append((nu, nv))
    return len(visited) == a * b

def _check_girth_abelian(n, dims, generators, g):
    """
    Check girth >= g for Cayley graph of Z_{dims[0]} x Z_{dims[1]} with generators.
    dims: (a, b)
    generators: list of 2 tuples (x, y)
    """
    a, b = dims
    s1, s2 = generators
    S = [s1, s2, _neg_abelian(s1, a, b), _neg_abelian(s2, a, b)]
    
    # BFS on non-backtracking walks
    # State: (pos, last_gen_idx)
    # pos is (u, v)
    # last_gen_idx is index in S
    
    # Start: from (0,0), take step s. State: (s, idx)
    # If we return to (0,0) with length L < g, and the last step is not backtracking the first?
    # Actually, we just need to find ANY non-backtracking closed walk of length < g.
    
    # visited[L][pos][last_idx] = True
    # We can use a set of visited states for the current length.
    
    # Initial states:
    current_states = set()
    for i, s in enumerate(S):
        # pos = s
        pos = s
        current_states.add((pos, i))
        
    if 0 in [s[0]*b + s[1] for s in S]: # Check if any generator is 0? No, simple graph.
        return False
        
    # Check length 2:
    # Walk s1, s2. Sum = 0. s2 = -s1.
    # Non-backtracking: s2 != -s1. So if sum=0, it must be backtracking.
    # So no length 2 non-backtracking closed walks.
    
    for L in range(3, g):
        next_states = set()
        for (pos, last_idx) in current_states:
            for i, s in enumerate(S):
                if i == (last_idx + 1) % 2 or i == (last_idx + 3) % 2:
                    # Check if s is -S[last_idx]
                    # S = [s1, s2, -s1, -s2]
                    # If last is s1 (idx 0), next cannot be -s1 (idx 2)
                    # If last is s2 (idx 1), next cannot be -s2 (idx 3)
                    # If last is -s1 (idx 2), next cannot be s1 (idx 0)
                    # If last is -s2 (idx 3), next cannot be s2 (idx 1)
                    if (last_idx == 0 and i == 2) or (last_idx == 1 and i == 3) or \
                       (last_idx == 2 and i == 0) or (last_idx == 3 and i == 1):
                        continue
                
                new_pos = ((pos[0] + s[0]) % a, (pos[1] + s[1]) % b)
                
                # Check if we closed the walk
                if new_pos == (0, 0):
                    # We found a closed walk of length L+1
                    # Is it non-backtracking? Yes, by construction.
                    # But we must ensure it's a valid cycle.
                    # If L+1 < g, return False.
                    return False
                
                next_states.add((new_pos, i))
        
        current_states = next_states
        if not current_states:
            break
            
    return True

def _construct_fallback(k, g):
    """Fallback: use the Lazebnik-Ustimenko-Woldar construction from the seed."""
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
