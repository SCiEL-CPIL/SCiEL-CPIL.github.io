def _check_girth_nb(n, a, h, g):
    """
    Check girth >= g of the 3-regular circulant C(n; {a, -a, h}) (h = n//2)
    using a vectorized non-backtracking walk test from vertex 0.

    State at depth d: for each "incoming step type" i in {0:+a, 1:-a, 2:+h},
    the set of vertices reachable by a non-backtracking walk of length d whose
    last step was type i. A shorter cycle exists iff vertex 0 becomes reachable
    at some depth < g. Because the graph is vertex-transitive (circulant),
    checking from vertex 0 suffices to certify the girth.
    """
    S = np.array([a, (-a) % n, h], dtype=np.int64)
    # neg[i] = the step type that is the inverse of step type i (backtracking)
    neg = np.array([1, 0, 2], dtype=np.int64)

    R = np.zeros((3, n), dtype=bool)
    R[0, a % n] = True
    R[1, (n - a) % n] = True
    R[2, h % n] = True

    for d in range(1, g):
        if d + 1 >= g:
            break
        R_new = np.zeros((3, n), dtype=bool)
        for j in range(3):
            # from each previous type i != neg[j], extend by step type j
            R_new[j] = np.roll(R[0], S[j]) | np.roll(R[1], S[j]) | np.roll(R[2], S[j])
            R_new[j][neg[j]] = False  # remove the vertex reached by backtracking
        R = R_new
        if R[0, 0] or R[1, 0] or R[2, 0]:
            return False
    return True


def _check_girth_dihedral(n_rot, a, g):
    """
    Check girth >= g of the Cayley graph of the dihedral group D_{n_rot}
    with generators {s (reflection), r^a, r^{-a}}. Total vertices = 2*n_rot.
    The group is generated by r and s, and the connection set is symmetric,
    so the graph is vertex-transitive -> checking from the identity suffices.
    """
    if n_rot < 3:
        return False
    if math.gcd(n_rot, a) != 1:
        return False
    if 2 * a % n_rot == 0:
        return False

    N = 2 * n_rot
    # step type 0: +a (rotation), 1: -a (rotation), 2: s (reflection)
    neg = np.array([1, 0, 2], dtype=np.int64)

    # position of each step type from the identity (vertex 0)
    R = np.zeros((3, N), dtype=bool)
    R[0, a % n_rot] = True
    R[1, (-a) % n_rot] = True
    R[2, n_rot] = True  # s = (1, 0) -> vertex n_rot + 0

    def apply_step(R_i, j):
        """Apply step type j to the set of vertices in R_i."""
        if j == 2:
            # reflection: (side, i) -> (1-side, -i)
            rot = R_i[:, :n_rot]
            ref = R_i[:, n_rot:]
            out = np.zeros((3, N), dtype=bool)
            out[:, :n_rot] = ref[:, ::-1]
            out[:, n_rot:] = rot[:, ::-1]
            return out
        else:
            # rotation by +a (j==0) or -a (j==1), side preserved
            sh = a if j == 0 else (-a) % n_rot
            out = np.zeros((3, N), dtype=bool)
            out[:, :n_rot] = np.roll(R_i[:, :n_rot], sh, axis=1)
            out[:, n_rot:] = np.roll(R_i[:, n_rot:], sh, axis=1)
            return out

    for d in range(1, g):
        if d + 1 >= g:
            break
        R_new = np.zeros((3, N), dtype=bool)
        for j in range(3):
            R_new[j] = apply_step(R[0], j) | apply_step(R[1], j) | apply_step(R[2], j)
            R_new[j][neg[j]] = False  # remove the vertex reached by backtracking
        R = R_new
        if R[0, 0] or R[1, 0] or R[2, 0]:
            return False
    return True


def _luw_construct(k, g, deadline):
    """Lazebnik-Ustimenko-Woldar graph CD(d, q) with q = k."""
    q = k
    d = g - 5
    if d % 2 == 0:
        d = g - 4
    d = max(3, d)

    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)

    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        if time.time() > deadline:
            break
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges


def construct(k, g):
    deadline = time.time() + 115

    if k == 3:
        # Moore bound for k=3, even g
        r = g // 2
        moore_bound = 2 * sum((k - 1) ** i for i in range(r))
        if moore_bound % 2 != 0:
            moore_bound += 1

        # Search for the smallest valid 3-regular graph.
        max_n_search = 2000

        for N in range(moore_bound, max_n_search + 1, 2):
            if time.time() > deadline - 8:
                break

            # Cyclic C(N; {a, N-a, N/2})
            h = N // 2
            for a in range(1, h):
                if math.gcd(h, a) != 1:
                    continue
                if _check_girth_nb(N, a, h, g):
                    edges = []
                    for u in range(N):
                        for v in ((u + a) % N, (u - a) % N, (u + h) % N):
                            if u < v:
                                edges.append((u, v))
                    return N, edges

            # Dihedral Cay(D_{N/2}, {s, r^a, r^{-a}})
            n_rot = N // 2
            for a in range(1, n_rot):
                if _check_girth_dihedral(n_rot, a, g):
                    edges = []
                    for i in range(n_rot):
                        u1 = i
                        v1 = n_rot + i
                        if u1 < v1:
                            edges.append((u1, v1))
                        v2 = (i + a) % n_rot
                        if u1 < v2:
                            edges.append((u1, v2))
                        v3 = (i - a) % n_rot
                        if u1 < v3:
                            edges.append((u1, v3))
                        u2 = n_rot + i
                        v4 = (-i) % n_rot
                        if u2 < v4:
                            edges.append((u2, v4))
                        v5 = n_rot + (i + a) % n_rot
                        if u2 < v5:
                            edges.append((u2, v5))
                        v6 = n_rot + (i - a) % n_rot
                        if u2 < v6:
                            edges.append((u2, v6))
                    return N, edges

    # Fallback to LUW
    try:
        return _luw_construct(k, g, deadline)
    except Exception:
        return 0, []

