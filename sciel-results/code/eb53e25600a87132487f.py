"""Rank-21 exact tensor decomposition for 2x2 x 2x6 matrix multiplication.

The tensor decomposes as three independent 2x2 multiplications (one per 2-column
block of B). Each 2x2 block uses the Strassen rank-7 decomposition, giving
total rank = 3 * 7 = 21.
"""

import time

_START = time.time()
_DEADLINE = _START + 110.0


def _deadline_exceeded():
    return time.time() > _DEADLINE


def _build_rank21():
    """Construct rank-21 factor matrices U (4x21), V (12x21), W (12x21)."""
    n, m, p = 2, 2, 6
    rank = 21

    # Strassen 7 factors for 2x2 multiplication.
    U_coeffs = [
        {0: 1, 3: 1},       # M1 = a00 + a11
        {2: 1, 3: 1},       # M2 = a10 + a11
        {0: 1},             # M3 = a00
        {3: 1},             # M4 = a11
        {0: 1, 1: 1},       # M5 = a00 + a01
        {2: 1, 0: -1},      # M6 = a10 - a00
        {1: 1, 3: -1},      # M7 = a01 - a11
    ]
    V_coeffs = [
        [(0, 0, 1), (1, 1, 1)],   # b00 + b11
        [(0, 0, 1)],               # b00
        [(0, 1, 1), (1, 1, -1)],  # b01 - b11
        [(1, 0, 1), (0, 0, -1)],  # b10 - b00
        [(1, 1, 1)],               # b11
        [(0, 0, 1), (0, 1, 1)],   # b00 + b01
        [(1, 0, 1), (1, 1, 1)],   # b10 + b11
    ]
    W_map = [
        [(0, 0, 1), (1, 1, 1)],   # c00 += M1, c11 += M1
        [(1, 0, 1), (1, 1, -1)],  # c10 += M2, c11 -= M2
        [(0, 1, 1), (1, 1, 1)],   # c01 += M3, c11 += M3
        [(0, 0, 1), (1, 0, 1)],   # c00 += M4, c10 += M4
        [(0, 0, -1), (0, 1, 1)],  # c00 -= M5, c01 += M5
        [(1, 1, 1)],              # c11 += M6
        [(0, 0, 1)],              # c00 += M7
    ]

    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]

    for r in range(3):
        for k in range(7):
            col = r * 7 + k
            for idx, val in U_coeffs[k].items():
                U[idx][col] = val
            for j_local, k_local, val in V_coeffs[k]:
                global_k = 2 * r + k_local
                V[j_local * p + global_k][col] = val
            for i, k_local, val in W_map[k]:
                global_k = 2 * r + k_local
                W[global_k * n + i][col] = val

    return {"U": U, "V": V, "W": W}


