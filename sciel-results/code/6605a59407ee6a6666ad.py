import numpy as np
import time

def kissing_number11() -> np.ndarray:
    d = 11
    start_time = time.time()
    deadline = 630  # seconds
    
    # Generate all binary vectors of length d
    # There are 2^11 = 2048 vectors
    all_vectors = np.array(list(np.meshgrid(*[np.array([0, 1]) for _ in range(d)]))).T.reshape(-1, d)
    
    # We want to find a subset with min Hamming distance >= 3
    # Start with the known good 128-point Hamming code subset
    # Construct the shortened Hamming code
    # Standard Hamming code (15, 11, 3) parity check matrix H15
    # Columns are 1..15 in binary
    h15_cols = [np.array([i], dtype=int).reshape(-1, 1) for i in range(1, 16)]
    # This is not the standard way to build H.
    # Standard H has columns as binary representations of 1..15.
    h15 = np.zeros((4, 15), dtype=int)
    for i in range(15):
        for j in range(4):
            h15[j, i] = (i + 1) >> j & 1
            
    # Shorten by 4 coordinates (fix first 4 to 0)
    # The code is the null space of H_short where H_short is H15 with first 4 cols removed?
    # No, shortening means we fix coordinates.
    # If we fix coords 0,1,2,3 to 0, we look at codewords c such that c[0:4]=0.
    # This is equivalent to finding the null space of the remaining 11 columns of H15?
    # Let H11 = H15[:, 4:15]
    h11 = h15[:, 4:15]
    
    # Find null space of h11 over GF(2)
    # We can just iterate through all 2^7 possibilities for the free variables?
    # Or simply generate all 2048 vectors and filter?
    # Easier: Generate all 2048 vectors, keep those with first 4 bits 0?
    # No, the shortened code consists of vectors v in {0,1}^15 such that v[0:4]=0 and H15 v^T = 0.
    # This implies H11 v[4:15]^T = 0.
    # So v[4:15] must be in the null space of H11.
    
    # Let's just use the greedy search on all 2048 vectors.
    # To get a good start, we can seed with the Hamming code vectors.
    
    # Generate the 128 Hamming code vectors
    # The null space of H11 has dimension 7.
    # We can find a basis for the null space.
    # Or simpler: 
    # The code is generated by G11.
    # Let's just use the greedy algorithm on all 2048 vectors.
    
    # To maximize k, we should try to pack as many as possible.
    # Greedy with a good ordering is effective.
    
    # Order vectors by weight? Or random?
    # Let's try a few random shuffles and keep the best result.
    
    best_code = []
    
    # Precompute distances? 2048^2 is ~4M operations. Fast enough.
    # d_H(u, v) = popcount(u ^ v)
    
    def popcount(x):
        return np.sum(x)
        
    # We will run a greedy selection
    # To be efficient, we can maintain a list of selected vectors.
    
    # Try multiple random seeds
    for seed in range(5):
        if time.time() > deadline - 10:
            break
            
        np.random.seed(seed)
        indices = np.random.permutation(2048)
        
        current_code = []
        # To speed up distance check, we can use a set or just a list
        # Since k is small (< 200), checking against all is O(k)
        
        for idx in indices:
            v = all_vectors[idx]
            # Check if v is at distance >= 3 from all in current_code
            valid = True
            for u in current_code:
                if np.sum(v ^ u) < 3:
                    valid = False
                    break
            if valid:
                current_code.append(v)
                
        if len(current_code) > len(best_code):
            best_code = current_code.copy()
            
    # Convert best_code (binary) to integer points (-1, 1)
    # p = 1 - 2*v
    if len(best_code) == 0:
        # Fallback to 2 points
        return np.array([np.ones(d), -1 * np.ones(d)]).astype(np.int64)
        
    points = 1 - 2 * np.array(best_code, dtype=np.int64)
    
    # Verify condition
    # min_dist_sq >= max_norm_sq
    norms = np.sum(points * points, axis=1)
    max_norm = np.max(norms)
    
    min_dist = float('inf')
    for i in range(len(points)):
        for j in range(i + 1, len(points)):
            diff = points[i] - points[j]
            dist_sq = np.sum(diff * diff)
            if dist_sq < min_dist:
                min_dist = dist_sq
                
    if min_dist < max_norm:
        # If invalid, fallback
        return np.array([np.ones(d), -1 * np.ones(d)]).astype(np.int64)
        
    return points
