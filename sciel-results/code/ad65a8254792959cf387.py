import numpy as np

DIMENSIONS = [2, 2, 4]

def construct():
    n, m, p = DIMENSIONS
    rank = 14
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to set values
    def set_val(mat, idx, val):
        mat[idx] = val

    # Strassen terms for first 2x2 block of B (cols 0, 1)
    # Term 1
    U[0*2+0][0] = 1; U[1*2+1][0] = 1
    V[0*4+0][0] = 1; V[1*4+1][0] = 1
    W[0*2+0][0] = 1; W[1*2+1][0] = 1
    
    # Term 2
    U[1*2+0][1] = 1; U[1*2+1][1] = 1
    V[0*4+0][1] = 1
    W[1*2+0][1] = 1; W[1*2+1][1] = -1
    
    # Term 3
    U[0*2+0][2] = 1
    V[0*4+1][2] = 1; V[1*4+1][2] = -1
    W[0*2+1][2] = 1; W[1*2+1][2] = 1
    
    # Term 4
    U[1*2+1][3] = 1
    V[1*4+0][3] = 1; V[0*4+0][3] = -1
    W[0*2+0][3] = 1; W[1*2+0][3] = 1
    
    # Term 5
    U[0*2+0][4] = 1; U[0*2+1][4] = 1
    V[1*4+1][4] = 1
    W[0*2+0][4] = -1; W[0*2+1][4] = 1
    
    # Term 6
    U[1*2+0][5] = 1; U[0*2+0][5] = -1
    V[0*4+0][5] = 1; V[0*4+1][5] = 1
    W[1*2+1][5] = 1
    
    # Term 7
    U[0*2+1][6] = 1; U[1*2+1][6] = -1
    V[1*4+0][6] = 1; V[1*4+1][6] = 1
    W[0*2+0][6] = 1

    # Strassen terms for second 2x2 block of B (cols 2, 3)
    # Term 8 (same U as 1)
    U[0*2+0][7] = 1; U[1*2+1][7] = 1
    V[0*4+2][7] = 1; V[1*4+3][7] = 1
    W[2*2+0][7] = 1; W[3*2+1][7] = 1
    
    # Term 9 (same U as 2)
    U[1*2+0][8] = 1; U[1*2+1][8] = 1
    V[0*4+2][8] = 1
    W[2*2+0][8] = 1; W[3*2+1][8] = -1
    
    # Term 10 (same U as 3)
    U[0*2+0][9] = 1
    V[0*4+3][9] = 1; V[1*4+3][9] = -1
    W[3*2+1][9] = 1; W[2*2+1][9] = 1 # Wait, W index is k*n+i. C_{0,3} is k=3, i=0 -> 3*2+0=6. C_{1,3} is k=3, i=1 -> 3*2+1=7.
    # Correction:
    # W[3*2+0][9] = 1; W[3*2+1][9] = 1
    
    # Term 11 (same U as 4)
    U[1*2+1][10] = 1
    V[1*4+2][10] = 1; V[0*4+2][10] = -1
    W[2*2+0][10] = 1; W[2*2+1][10] = 1 # C_{0,2} (k=2, i=0 -> 4), C_{1,2} (k=2, i=1 -> 5)
    # Correction:
    # W[2*2+0][10] = 1; W[2*2+1][10] = 1
    
    # Term 12 (same U as 5)
    U[0*2+0][11] = 1; U[0*2+1][11] = 1
    V[1*4+3][11] = 1
    W[2*2+0][11] = -1; W[3*2+0][11] = 1 # C_{0,2} (4), C_{0,3} (6)
    # Correction:
    # W[2*2+0][11] = -1; W[3*2+0][11] = 1
    
    # Term 13 (same U as 6)
    U[1*2+0][12] = 1; U[0*2+0][12] = -1
    V[0*4+2][12] = 1; V[0*4+3][12] = 1
    W[3*2+1][12] = 1 # C_{1,3} (7)
    
    # Term 14 (same U as 7)
    U[0*2+1][13] = 1; U[1*2+1][13] = -1
    V[1*4+2][13] = 1; V[1*4+3][13] = 1
    W[2*2+0][13] = 1 # C_{0,2} (4)

    return {"U": U, "V": V, "W": W}
