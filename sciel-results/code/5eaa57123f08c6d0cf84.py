import time
import random
from itertools import permutations

def construct(n):
    start_time = time.time()
    deadline = start_time + 110  # 10s safety margin
    
    # 1. Generate classic superpermutation
    word = [1]
    for m in range(2, n + 1):
        perms, seen = [], set()
        for i in range(len(word) - m + 2):
            window = tuple(word[i:i + m - 1])
            if len(set(window)) == m - 1 and window not in seen:
                seen.add(window)
                perms.append(window)
        new = []
        for p in perms:
            block = list(p) + [m] + list(p)
            overlap = next(o for o in range(min(len(new), len(block)), -1, -1) if new[len(new) - o:] == block[:o])
            new += block[overlap:]
        word = new
    
    # Extract permutations in order
    # A permutation is a window of length n that is a valid perm of 1..n
    # In the classic construction, we can just track the blocks added.
    # But easier: scan the word.
    perms_list = []
    seen = set()
    for i in range(len(word) - n + 1):
        w = tuple(word[i:i+n])
        if len(set(w)) == n and w not in seen:
            seen.add(w)
            perms_list.append(w)
            
    # It's possible that some perms are not found if the construction is weird, 
    # but classic construction guarantees all are present.
    # However, the order in perms_list might not correspond to a simple "sequence" 
    # if overlaps are complex. 
    # But the superperm is generated by concatenating these perms with overlaps.
    # If we reorder perms_list, we generate a different superperm.
    
    # Objective function: length of superperm from a list of perms
    def get_length(perm_seq):
        if not perm_seq:
            return 0
        length = n
        for i in range(1, len(perm_seq)):
            p_prev = perm_seq[i-1]
            p_curr = perm_seq[i]
            # Max overlap
            max_overlap = 0
            # Check all possible overlaps from n-1 down to 1
            # p_prev[k:] == p_curr[:n-k]
            for k in range(1, n):
                if p_prev[k:] == p_curr[:n-k]:
                    max_overlap = n - k
                    break
            length += n - max_overlap
        return length

    best_seq = perms_list
    best_len = get_length(best_seq)
    
    # Simulated Annealing
    current_seq = best_seq[:]
    current_len = best_len
    T = 10.0
    T_min = 0.01
    alpha = 0.99
    
    while time.time() < deadline:
        # Random move: swap two random elements
        i, j = random.sample(range(len(current_seq)), 2)
        current_seq[i], current_seq[j] = current_seq[j], current_seq[i]
        
        new_len = get_length(current_seq)
        
        if new_len < current_len:
            current_len = new_len
            if current_len < best_len:
                best_len = current_len
                best_seq = current_seq[:]
        else:
            # Accept with probability exp(-delta/T)
            delta = new_len - current_len
            if random.random() < pow(2.718281828, -delta / T):
                current_len = new_len
        
        T *= alpha
        if T < T_min:
            T = T_min
            
    # Construct final string from best_seq
    # We need to actually build the string to return it
    # But we can just return the string from the classic construction if no improvement
    # Or build from best_seq.
    
    # Building string from sequence:
    # Start with first perm.
    # Append subsequent perms with max overlap.
    if not best_seq:
        return "".join(map(str, word))
        
    result = list(best_seq[0])
    for i in range(1, len(best_seq)):
        p_prev = best_seq[i-1]
        p_curr = best_seq[i]
        max_overlap = 0
        for k in range(1, n):
            if p_prev[k:] == p_curr[:n-k]:
                max_overlap = n - k
                break
        result.extend(p_curr[max_overlap:])
        
    return "".join(map(str, result))
