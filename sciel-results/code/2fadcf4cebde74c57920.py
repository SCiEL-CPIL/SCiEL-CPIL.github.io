def construct():
    start_time = time.time()
    deadline = 145.0  # Safety margin before 150s limit
    
    # We will search up to N. 
    # A sieve of 200 million takes ~5-10s with numpy. 
    # A linear scan of 200 million takes ~5-10s.
    # Total time ~20s, well within budget.
    # We can try to go higher if time permits, but 200M is a solid baseline for finding k > 30.
    # Let's start with 50 million to be safe, and increase if time permits.
    N = 50000000
    
    # 1. Compute Euler's Totient function phi(n) for n in [1, N]
    # Using a numpy-based sieve method
    phi = np.arange(N + 1, dtype=np.int64)
    
    # Iterate through potential primes
    # We only need to iterate up to sqrt(N) for the sieve to work correctly?
    # No, we need to iterate through all i where phi[i] == i (which are primes).
    # But we can optimize by only checking i up to N.
    
    # To speed up, we can use a loop that checks if phi[i] == i.
    # However, iterating through 50M elements in Python is slow.
    # Instead, we can use a list of primes generated by a faster sieve?
    # Or we can use the fact that if i is prime, phi[i] == i.
    
    # Let's use a more efficient approach:
    # 1. Generate primes up to N using a simple sieve (boolean array).
    # 2. Use those primes to update phi.
    
    # Actually, the standard phi sieve is:
    # for i in range(2, N+1):
    #     if phi[i] == i: # i is prime
    #         for j in range(i, N+1, i):
    #             phi[j] -= phi[j] // i
    
    # In numpy, we can vectorize the inner loop.
    # But we still need to identify primes.
    # Let's generate a boolean array of primes first.
    
    is_prime = np.ones(N + 1, dtype=bool)
    is_prime[0] = False
    is_prime[1] = False
    
    # Sieve of Eratosthenes
    for i in range(2, int(math.isqrt(N)) + 1):
        if is_prime[i]:
            is_prime[i*i::i] = False
            
    # Now, for each prime p, update phi
    # We can iterate through the primes
    # To avoid a slow Python loop over 50M elements, we can use np.where to get indices of primes?
    # But that might be memory intensive.
    
    # Alternative: Use the fact that phi[i] == i identifies primes in the phi array.
    # But we need to update phi in-place.
    
    # Let's try a hybrid approach:
    # Use a Python loop to find primes, but use numpy for the inner update.
    
    # First, let's find primes using the is_prime array
    # primes = np.where(is_prime)[0]
    # This creates an array of ~3M primes for N=50M.
    # Then loop over primes.
    
    primes = np.where(is_prime)[0]
    
    for p in primes:
        if p > N:
            break
        # Update phi for multiples of p
        # j = p, 2p, 3p, ...
        # phi[j] -= phi[j] // p
        # This can be vectorized:
        # indices = np.arange(p, N+1, p)
        # phi[indices] -= phi[indices] // p
        
        # But creating indices array for each prime might be slow/memory heavy.
        # Let's try it.
        
        # Optimization: Only update if p is small? No, all primes matter.
        
        # Let's check time periodically.
        if time.time() - start_time > deadline - 20:
            # If we're running out of time, break and use what we have
            # But phi is partially computed, which is invalid.
            # So we should avoid this.
            pass
        
        indices = np.arange(p, N + 1, p)
        phi[indices] -= phi[indices] // p
        
    # Check time after sieve
    if time.time() - start_time > deadline - 10:
        # If sieve took too long, return a small valid result
        return {'start': 1, 'length': 1}

    # 2. Find the longest run of consecutive integers with distinct totients
    # We use a sliding window approach.
    # Window [l, r] contains indices with distinct phi values.
    # We maintain a count array for phi values in the current window.
    # Since phi(n) <= n, we can use an array of size N+1.
    
    counts = np.zeros(N + 1, dtype=np.int32)
    
    best_k = 1
    best_s = 1
    
    l = 1
    
    # We iterate r from 1 to N
    # For each r, we add phi[r] to the window.
    # If phi[r] is already in the window (counts[phi[r]] > 0), we must move l forward
    # until the previous occurrence of phi[r] is removed from the window.
    
    # To speed up the sliding window, we can use a dictionary or array for counts.
    # But moving l one by one is O(N^2) in worst case? No, each element is added/removed at most once.
    # So it's O(N).
    
    # However, Python loop for 50M iterations is slow (~5-10s).
    # Can we vectorize?
    # The sliding window logic is inherently sequential due to the dependency on l.
    # But we can try to optimize the inner loop.
    
    # Let's use a list for phi to avoid numpy overhead in the loop?
    # No, numpy indexing is fast.
    
    # Let's try the loop.
    
    for r in range(1, N + 1):
        val = phi[r]
        
        # If val is already in the window, shrink from the left
        if counts[val] > 0:
            # Move l until we remove the previous occurrence of val
            while l < r:
                left_val = phi[l]
                counts[left_val] -= 1
                l += 1
                if left_val == val:
                    break
        
        # Now val is not in the window (or it was the one we just removed, but counts is 0 now)
        counts[val] += 1
        
        current_k = r - l + 1
        if current_k > best_k:
            best_k = current_k
            best_s = l
            
        # Early termination if we hit the max allowed k
        if best_k >= 200:
            break
            
        # Time check
        if time.time() - start_time > deadline - 5:
            break

    return {'start': best_s, 'length': best_k}
