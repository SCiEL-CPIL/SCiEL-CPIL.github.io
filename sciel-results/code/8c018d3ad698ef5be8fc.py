"""LJ38 global minimum search: construct FCC truncated octahedron, relax with L-BFGS."""
import numpy as np
import time
import sys

N = 38


def _lj_energy_and_force(pos):
    """Compute total LJ energy and forces for positions (N,3)."""
    n = len(pos)
    rij = pos[:, np.newaxis, :] - pos[np.newaxis, :, :]
    r2 = np.sum(rij * rij, axis=-1)
    np.fill_diagonal(r2, 1.0)  # avoid division by zero
    r6 = 1.0 / (r2 ** 3)
    r12 = r6 * r6
    # Energy: 4 * sum_{i<j} (r^-12 - r^-6)
    e_pair = 4.0 * (r12 - r6)
    np.fill_diagonal(e_pair, 0.0)
    energy = 0.5 * np.sum(e_pair)
    # Force on atom i: -dE/dr_i
    # dE/dr_ij = 4*(-12*r^-13 + 6*r^-7) * r_vec / r
    # In terms of r2: force factor = 4*(12*r12 - 6*r6)/r2
    f_factor = 4.0 * (12.0 * r12 - 6.0 * r6) / r2
    np.fill_diagonal(f_factor, 0.0)
    forces = -np.sum(f_factor[:, :, np.newaxis] * rij, axis=1)
    return energy, forces


def _fcc_truncated_octahedron():
    """
    Construct the 38-atom FCC truncated octahedron (global minimum candidate for LJ38).
    
    The structure consists of:
    - 1 central atom at origin
    - 12 atoms at FCC nearest-neighbor positions (first shell)
    - 24 atoms at second-shell positions
    
    In FCC, nearest neighbors are at (±1,±1,0), (±1,0,±1), (0,±1,±1) scaled by a/√2.
    For LJ, optimal nearest-neighbor distance r_min = 2^(1/6) ≈ 1.12246.
    
    Let's use the standard FCC truncated octahedron coordinates:
    Shell 0: (0,0,0) - 1 atom
    Shell 1: 12 atoms at permutations of (±1, ±1, 0) * d1
    Shell 2: 24 atoms at permutations of (±3, ±1, ±1) * d2... 
    
    Actually, let me think more carefully. The 38-atom FCC truncated octahedron:
    In an FCC lattice with lattice constant a, the truncated octahedron of 38 atoms
    consists of atoms within a certain radius from center.
    
    FCC lattice points (in units of a):
    (0,0,0), (0,0.5,0.5), (0.5,0,0.5), (0.5,0.5,0) and translations.
    
    Let me use the known coordinates. The 38-atom cluster has:
    - 1 atom at center
    - 12 atoms at distance r1 (FCC nearest neighbors): these are at 
      (±r1/√2, ±r1/√2, 0) and permutations → 12 atoms
    - 24 atoms at distance r2 (FCC second shell): these are at
      (±r1, 0, 0) and permutations → 6 atoms at distance r1
      plus (±r1/√2, ±r1/√2, ±r1/√2) → 8 atoms at distance r1*√(3/2)
      Hmm, this is getting complicated.
    
    Let me just use a well-known construction. The 38-atom FCC truncated octahedron
    can be generated by taking all FCC lattice points within a certain cutoff.
    
    FCC lattice: points at (i, j, k) where i+j+k is even, scaled by a/√2... 
    No, standard FCC: (i, j, k) with i,j,k all integers, plus face-centered positions.
    
    Let me use a simpler approach: generate FCC points and select 38 closest to origin.
    """
    # FCC lattice generation
    # FCC basis vectors: a*(0.5, 0.5, 0), a*(0.5, 0, 0.5), a*(0, 0.5, 0.5)
    # So lattice points are: n1*(0.5,0.5,0) + n2*(0.5,0,0.5) + n3*(0,0.5,0.5) for integers n1,n2,n3
    # = ((n1+n2)/2, (n1+n3)/2, (n2+n3)/2)
    # For this to be integer or half-integer coordinates...
    
    # Simpler: FCC points are all (x,y,z) where x,y,z are integers and x+y+z is even,
    # OR x,y,z are all half-integers (i.e., 2x, 2y, 2z are odd integers).
    
    # Let's generate FCC points in a box and pick 38 closest to origin.
    # Scale factor: we'll set the nearest-neighbor distance to be ~1.12 (2^(1/6))
    
    # In FCC, nearest neighbor distance = a/√2 where a is cubic lattice constant.
    # So if we want NN distance = r0, then a = r0 * √2.
    
    # Let's generate points and then scale.
    max_coord = 3  # generate in [-3,3]^3 roughly
    
    points = []
    for i in range(-4, 5):
        for j in range(-4, 5):
            for k in range(-4, 5):
                # FCC: i+j+k even
                if (i + j + k) % 2 == 0:
                    points.append((i, j, k))
                # Also face-centered: (i+0.5, j+0.5, k), etc.
                # Actually the standard FCC in integer coords: 
                # Type 1: (i,j,k) with i+j+k even
                # Type 2: (i+0.5, j+0.5, k+0.5) with i+j+k even... 
                # No, let me just use the basis vector approach.
    
    # Use basis vectors approach
    # a1 = (0.5, 0.5, 0), a2 = (0.5, 0, 0.5), a3 = (0, 0.5, 0.5)
    # Point = n1*a1 + n2*a2 + n3*a3
    pts = []
    for n1 in range(-4, 5):
        for n2 in range(-4, 5):
            for n3 in range(-4, 5):
                x = 0.5 * (n1 + n2)
                y = 0.5 * (n1 + n3)
                z = 0.5 * (n2 + n3)
                pts.append((x, y, z))
    
    pts = np.array(pts)
    # Remove duplicates (there shouldn't be any with this parametrization, but just in case)
    pts = np.unique(pts, axis=0)
    
    # Sort by distance from origin
    dists = np.linalg.norm(pts, axis=1)
    order = np.argsort(dists)
    pts = pts[order]
    
    # Take 38 closest
    pts = pts[:38]
    
    # Center the cluster
    pts = pts - np.mean(pts, axis=0)
    
    # Scale: nearest neighbor distance in this FCC should be 1 (in our units).
    # In FCC with these basis vectors, NN distance = sqrt(0.5^2 + 0.5^2) = sqrt(0.5) = 1/√2
    # So to get NN distance = r0, multiply by r0 * √2
    # Let's compute actual NN distance
    if len(pts) > 1:
        min_dist = np.inf
        for i in range(len(pts)):
            for j in range(i+1, len(pts)):
                d = np.linalg.norm(pts[i] - pts[j])
                if d < min_dist:
                    min_dist = d
        if min_dist > 0:
            scale = 1.0 / min_dist  # normalize NN to 1.0
            pts = pts * scale
    
    # Now scale to optimal LJ distance ~ 2^(1/6)
    pts = pts * 2.0 ** (1.0/6.0)
    
    return pts


def construct():
    start_time = time.time()
    deadline = start_time + 110.0  # 10 second safety margin
    
    # Start with FCC truncated octahedron
    pos = _fcc_truncated_octahedron()
    
    # Ensure minimum separation of 0.5
    # Check and fix if needed
    def _ensure_min_separation(positions, min_sep=0.5):
        """Nudge atoms apart if any pair is too close."""
        positions = positions.copy()
        for _ in range(100):
            too_close = False
            for i in range(len(positions)):
                for j in range(i+1, len(positions)):
                    d = np.linalg.norm(positions[i] - positions[j])
                    if d < min_sep:
                        too_close = True
                        if d < 1e-10:
                            # Random nudge
                            positions[i] += np.random.randn(3) * 0.01
                        else:
                            direction = (positions[i] - positions[j]) / d
                            shift = (min_sep - d) / 2.0 + 0.001
                            positions[i] += direction * shift
                            positions[j] -= direction * shift
            if not too_close:
                break
        return positions
    
    pos = _ensure_min_separation(pos)
    
    # Compute initial energy
    e0, _ = _lj_energy_and_force(pos)
    best_pos = pos.copy()
    best_e = e0
    
    # Try to use scipy L-BFGS-B for relaxation
    try:
        from scipy.optimize import minimize
        
        def energy_fn(x):
            p = x.reshape(-1, 3)
            e, _ = _lj_energy_and_force(p)
            return e
        
        def force_fn(x):
            p = x.reshape(-1, 3)
            _, f = _lj_energy_and_force(p)
            return -f.flatten()  # gradient
        
        x0 = pos.flatten()
        
        # L-BFGS-B optimization
        result = minimize(
            energy_fn,
            x0,
            jac=force_fn,
            method='L-BFGS-B',
            options={
                'maxiter': 2000,
                'ftol': 1e-16,
                'gtol': 1e-12,
                'maxls': 50
            }
        )
        
        if result.success or (result.fun < best_e):
            best_pos = result.x.reshape(-1, 3)
            best_e = result.fun
        
        # Check time
        if time.time() > deadline:
            return _ensure_min_separation(best_pos)
        
        # Polish with tighter tolerances
        result2 = minimize(
            energy_fn,
            best_pos.flatten(),
            jac=force_fn,
            method='L-BFGS-B',
            options={
                'maxiter': 5000,
                'ftol': 1e-18,
                'gtol': 1e-14,
                'maxls': 100
            }
        )
        
        if result2.fun < best_e:
            best_pos = result2.x.reshape(-1, 3)
            best_e = result2.fun
        
    except Exception as ex:
        # If scipy fails, try a simple gradient descent
        try:
            lr = 0.01
            for step in range(5000):
                if time.time() > deadline:
                    break
                e, f = _lj_energy_and_force(best_pos)
                if e < best_e:
                    best_e = e
                best_pos = best_pos - lr * f
                # Adaptive learning rate
                if np.max(np.abs(f)) < 1e-8:
                    break
                lr *= 0.999
        except Exception:
            pass
    
    # Final check
    if time.time() > deadline:
        pass
    
    # Ensure valid separation
    best_pos = _ensure_min_separation(best_pos)
    
    return best_pos
