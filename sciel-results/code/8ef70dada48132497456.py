"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import random
import time

def construct():
    N = 256
    # Precompute conflict matrix
    # conflict[i][j] is True if i and j cannot be in the same set
    conflict = [[False] * N for _ in range(N)]
    
    for i in range(1, N + 1):
        for j in range(i + 1, N + 1):
            if (i * j) % (i + j) == 0:
                conflict[i-1][j-1] = True
                conflict[j-1][i-1] = True
                
    def is_compatible(num, current_set):
        idx = num - 1
        for sel in current_set:
            if conflict[idx][sel - 1]:
                return False
        return True

    def local_search(initial_set):
        S = set(initial_set)
        max_iterations = 2000
        for _ in range(max_iterations):
            # 1. Try to add any compatible element
            added = False
            # Iterate through candidates in random order to break ties
            candidates = [v for v in range(1, N + 1) if v not in S]
            random.shuffle(candidates)
            for v in candidates:
                if is_compatible(v, S):
                    S.add(v)
                    added = True
                    break
            
            if added:
                continue
            
            # 2. If no element can be added, try a swap
            # Pick a random u in S and v not in S
            # Check if (S - {u}) U {v} is valid
            swapped = False
            if len(S) > 0:
                u_candidates = list(S)
                random.shuffle(u_candidates)
                v_candidates = [v for v in range(1, N + 1) if v not in S]
                random.shuffle(v_candidates)
                
                # Try a limited number of random swaps
                for _ in range(50):
                    if not u_candidates or not v_candidates:
                        break
                    u = u_candidates.pop()
                    v = v_candidates.pop()
                    
                    # Check if v is compatible with all in S except u
                    compatible = True
                    for sel in S:
                        if sel == u:
                            continue
                        if conflict[v-1][sel-1]:
                            compatible = False
                            break
                    
                    if compatible:
                        S.remove(u)
                        S.add(v)
                        swapped = True
                        break
            
            if not swapped:
                # No add, no valid swap found in this iteration
                # Try a few more random swaps before giving up on this state?
                # Or just break to restart.
                # To avoid getting stuck, we can try to force a swap by picking random pairs more aggressively
                # But if no swap is valid, we are at a local optimum for this neighborhood.
                break
        
        return S

    best_set = set()
    
    # Strategy:
    # 1. Start with all odds (known large independent set)
    # 2. Run local search
    # 3. Restart with slight variations (e.g., random removals from odds)
    
    # Baseline: All odds
    odds = [i for i in range(1, N + 1) if i % 2 == 1]
    evens = [i for i in range(1, N + 1) if i % 2 == 0]
    
    # Run local search starting from all odds
    for _ in range(20): # 20 restarts
        init_set = list(odds)
        # Add some random evens to init? No, start clean.
        # Maybe shuffle the odds? Doesn't matter for set.
        
        s = local_search(init_set)
        if len(s) > len(best_set):
            best_set = s
    
    # Try starting from a random subset of odds + some evens?
    # Or just random restarts from scratch?
    # The "All Odds" is a very strong seed.
    # Let's also try starting with a random maximal independent set generated by greedy, then local search.
    
    for _ in range(10):
        # Generate a random greedy independent set
        order = list(range(1, N + 1))
        random.shuffle(order)
        greedy_set = []
        for num in order:
            if is_compatible(num, greedy_set):
                greedy_set.append(num)
        
        s = local_search(greedy_set)
        if len(s) > len(best_set):
            best_set = s
            
    return list(best_set)
# EVOLVE-BLOCK-END
