def strassen_2x2(A, B):
    A00, A01 = A[0][0], A[0][1]
    A10, A11 = A[1][0], A[1][1]
    B00, B01 = B[0][0], B[0][1]
    B10, B11 = B[1][0], B[1][1]
    
    M1 = (A00 + A11) * (B00 + B11)
    M2 = (A10 + A11) * (B00 + B01)
    M3 = (A00 - A10) * (B10 + B11)
    M4 = A00 * (B00 - B10)
    M5 = A11 * (B01 - B00)
    M6 = (A00 + A01) * (B11 - B10)
    M7 = (A10 + A11) * (B00 - B01)
    
    C00 = M1 + M4 - M5 + M7
    C01 = M6 + M5
    C10 = M3 + M4
    C11 = M1 - M2 + M3 + M7
