"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import time
from itertools import permutations

def load(boxes, container):
    W, H, D = container
    if not boxes:
        return []
    
    # Start a timer to respect the 150s wall-clock limit (with safety margin)
    start_time = time.time()
    time_limit = 140.0  # Safety margin
    
    # 1. Pre-process boxes: compute unique rotations and sort by volume descending
    box_info = []
    for i, (w, h, d) in enumerate(boxes):
        vol = w * h * d
        # Generate unique permutations of dimensions
        perms = list(set(permutations((w, h, d))))
        # Sort rotations to prefer certain orientations if needed, or just keep them
        box_info.append((i, vol, perms))
    
    # Sort by volume descending (largest first)
    box_info.sort(key=lambda x: x[1], reverse=True)
    
    # 2. State variables
    placed = []  # List of tuples: (x, y, z, w, h, d, original_index)
    corners = [(0, 0, 0)]  # List of candidate corner positions (x, y, z)
    
    # Result array to store final placements
    # We need to return a list of tuples (bin, x, y, z, w, h, d) for each box in original order
    # bin: 0 for loaded, -1 for left out
    # x, y, z: position
    # w, h, d: dimensions used in placement
    results = [(-1, 0, 0, 0, 0, 0, 0)] * len(boxes)
    
    # Helper to check if a box fits at a specific corner
    def fits_at(x, y, z, bw, bh, bd):
        if x + bw > W or y + bh > H or z + bd > D:
            return False
        # Check overlap with all placed boxes
        for (px, py, pz, pw, ph, pd, _idx) in placed:
            # Separation condition: boxes do not overlap if they are separated in any axis
            if x + bw <= px or px + pw <= x:
                continue
            if y + bh <= py or py + ph <= y:
                continue
            if z + bd <= pz or pz + pd <= z:
                continue
            # If none of the above, they overlap
            return False
        return True

    # Helper to add new corners generated by placing a box
    def add_corners(x, y, z, bw, bh, bd):
        # Generate 3 new corners based on the placed box
        # 1. Corner to the right: (x + bw, y, z)
        # 2. Corner above: (x, y + bh, z)
        # 3. Corner in front: (x, y, z + bd)
        new_corners = [
            (x + bw, y, z),
            (x, y + bh, z),
            (x, y, z + bd)
        ]
        for nc in new_corners:
            if nc not in corners:
                corners.append(nc)
    
    # 3. Main Loop: Place boxes one by one
    for idx, vol, perms in box_info:
        if time.time() - start_time > time_limit:
            break
        
        placed_box = False
        # Try each rotation
        for bw, bh, bd in perms:
            if placed_box:
                break
            
            # Sort corners to prioritize "lowest" positions
            # A good heuristic is to sort by z, then y, then x (or some combination)
            # Let's sort by (z, y, x) to fill from bottom-up, back-to-front, left-to-right
            sorted_corners = sorted(corners, key=lambda c: (c[2], c[1], c[0]))
            
            for cx, cy, cz in sorted_corners:
                if fits_at(cx, cy, cz, bw, bh, bd):
                    # Place the box
                    placed.append((cx, cy, cz, bw, bh, bd, idx))
                    results[idx] = (0, cx, cy, cz, bw, bh, bd)
                    add_corners(cx, cy, cz, bw, bh, bd)
                    placed_box = True
                    break
            
            if not placed_box:
                # Check if we should continue to next rotation or give up
                # If we couldn't place in this rotation, try the next one
                pass
        
        if not placed_box:
            # Box could not be placed in any rotation/corner
            results[idx] = (-1, 0, 0, 0, 0, 0, 0)
    
    return results

# EVOLVE-BLOCK-END
