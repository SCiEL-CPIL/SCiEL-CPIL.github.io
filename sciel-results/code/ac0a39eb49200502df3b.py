import time

def construct():
    start_time = time.time()
    deadline = start_time + 50.0  # Safety margin
    
    N = 17
    MIN_DIST = 6
    
    # We will construct the [17, 8, 6] code, which is the dual of the [17, 9, 5] QR code.
    # This code has 2^8 = 256 codewords.
    
    # Step 1: Construct GF(2^8) to find the minimal polynomial of alpha^3
    # Primitive polynomial for GF(2^8): x^8 + x^4 + x^3 + x^2 + 1
    # Let beta be a root. beta^255 = 1.
    # alpha = beta^15 has order 17.
    
    # We represent elements of GF(2^8) as integers 0..255.
    # Multiplication in GF(2^8) modulo P(x) = x^8 + x^4 + x^3 + x^2 + 1
    # P(x) corresponds to 0x11d (285)
    
    def gf_mul(a, b):
        res = 0
        while b:
            if b & 1:
                res ^= a
            b >>= 1
            a <<= 1
            if a & 0x100:
                a ^= 0x11d
        return res

    def gf_pow(a, n):
        res = 1
        while n:
            if n & 1:
                res = gf_mul(res, a)
            a = gf_mul(a, a)
            n >>= 1
        return res

    # Find beta (primitive element)
    # We can just pick 3 and check if it's primitive? 
    # Actually, for GF(2^8) with 0x11d, 3 is often primitive.
    # Let's assume beta = 3.
    beta = 3
    # Verify order is 255
    # if gf_pow(beta, 255) != 1: 
    #    # Try another element? For robustness, let's just use the structure.
    #    # But 3 is a known primitive element for this poly.
    
    alpha = gf_pow(beta, 15)
    # Verify alpha^17 = 1
    # assert gf_pow(alpha, 17) == 1
    
    # Step 2: Find minimal polynomial of alpha^3
    # m_3(x) = x^8 + c7 x^7 + ... + c0
    # We need sum_{i=0}^7 c_i (alpha^3)^i + (alpha^3)^8 = 0
    # Let v_i = (alpha^3)^i for i=0..8
    # We need to find c_0..c_7 such that v_8 + c_7 v_7 + ... + c_0 v_0 = 0
    
    a3 = gf_pow(alpha, 3)
    v = [1] * 9
    for i in range(1, 9):
        v[i] = gf_mul(v[i-1], a3)
        
    # Solve for c_0..c_7
    # We can iterate through all 2^8 possibilities? No, that's 256.
    # Actually, we just need to find the unique vector c in GF(2)^8 such that 
    # v_8 = sum c_i v_i.
    # This is a linear system over GF(2).
    # v_i are elements of GF(2^8), which is an 8-dim vector space over GF(2).
    # So we have 8 equations (one for each bit of the GF(2^8) elements) and 8 unknowns.
    
    # Matrix M (8x8) where M[j][i] is the j-th bit of v[i]
    # Vector b (8) is the bits of v[8]
    
    M = [[0]*8 for _ in range(8)]
    for i in range(8):
        for j in range(8):
            M[j][i] = (v[i] >> j) & 1
            
    b = [(v[8] >> j) & 1 for j in range(8)]
    
    # Solve M c = b over GF(2)
    # Gaussian elimination
    c = [0]*8
    # Augmented matrix
    A = [row[:] + [b[i]] for i, row in enumerate(M)]
    
    for col in range(8):
        # Find pivot
        pivot = -1
        for row in range(col, 8):
            if A[row][col] == 1:
                pivot = row
                break
        if pivot == -1:
            # Should not happen for minimal polynomial
            continue
        A[col], A[pivot] = A[pivot], A[col]
        for row in range(8):
            if row != col and A[row][col] == 1:
                for k in range(col, 9):
                    A[row][k] ^= A[col][k]
    
    for i in range(8):
        c[i] = A[i][8]
        
    # Construct m_3(x) as integer
    # m_3(x) = x^8 + c_7 x^7 + ... + c_0
    m3_poly = 0
    for i in range(8):
        if c[i]:
            m3_poly |= (1 << i)
    m3_poly |= (1 << 8) # x^8 term
    
    # Step 3: Compute h(x) = (x+1) m_3(x)
    # h(x) is the generator polynomial for the [17,8,6] code
    # h(x) = x m_3(x) + m_3(x)
    
    def poly_add(a, b):
        return a ^ b
        
    def poly_mul(x, y):
        # Multiply polynomials over GF(2)
        res = 0
        while y:
            if y & 1:
                res ^= x
            y >>= 1
            x <<= 1
        return res
        
    x_plus_1 = 0b11 # x + 1
    h_poly = poly_mul(x_plus_1, m3_poly)
    
    # Step 4: Generate all 256 codewords
    # Code is cyclic, generated by h(x).
    # Codewords are c(x) = a(x) h(x) mod (x^17 - 1)
    # where a(x) has degree < 8.
    
    def poly_mod(x17_minus_1, p):
        # Reduce p modulo x^17 - 1
        # x^17 = 1
        # So we can just wrap around bits
        # If bit i is set, and i >= 17, add bit (i-17)
        res = p
        # We need to handle carries? No, it's XOR.
        # Actually, x^17 - 1 = x^17 + 1.
        # So x^17 = 1.
        # If p has bit i (i>=17), we XOR 1 to bit (i-17).
        # But this might create new bits >= 17? No, i-17 < i.
        # We can iterate from high to low.
        max_bit = p.bit_length()
        for i in range(max_bit - 1, 16, -1):
            if (p >> i) & 1:
                p ^= (1 << (i - 17))
        return p

    words = set()
    for a in range(256):
        # a is the coefficient vector for a(x)
        # c(x) = a(x) * h_poly
        # We can compute this product
        c = poly_mod(0, poly_mul(a, h_poly))
        # Ensure length 17
        c &= (1 << 17) - 1
        words.add(c)
        
    if len(words) > 0:
        return list(words)
    else:
        # Fallback to seed
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words

