import itertools
import numpy as np

D = 11

def construct():
    vectors = []
    for i, j in itertools.combinations(range(D), 2):
        for si in (1, -1):
            for sj in (1, -1):
                v = [0] * D
                v[i] = si
                v[j] = sj
                vectors.append(v)
    return np.array(vectors, dtype=np.int64)
