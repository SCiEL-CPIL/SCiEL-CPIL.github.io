"""Construct the largest binary code of length 18, distance >= 6.

Strategy:
1. Start with a known large linear code (extended quadratic residue code of length 18, size 512).
2. Use greedy search with multiple random restarts to try to find larger nonlinear codes.
3. Each restart: seed with the QR code, then greedily add random words that maintain distance >= 6.
4. Also try different seeding strategies and local improvement passes.
5. Return the best code found within the time budget.
"""
import time
import random
import numpy as np

N = 18
MIN_DIST = 6
TIME_LIMIT = 85  # safety margin before 90s kill

def _hamming_dist(a, b):
    """Hamming distance between two integers (popcount of XOR)."""
    return (a ^ b).bit_count()

def _min_dist_to_set(word, words):
    """Minimum Hamming distance from word to any word in the list."""
    if not words:
        return N
    # Use numpy for speed with many words
    arr = np.array(words, dtype=np.uint32)
    xors = np.array([word] * len(arr), dtype=np.uint32) ^ arr
    # Compute popcount for each
    # For 18-bit numbers, we can use a lookup or bit operations
    # numpy doesn't have native popcount, so we do it manually
    # Actually, let's just use a loop for small sets, numpy for large
    if len(words) <= 1000:
        return min((word ^ w).bit_count() for w in words)
    else:
        # Vectorized popcount using bit tricks
        x = xors
        x = x - ((x >> 1) & 0x55555555)
        x = (x & 0x33333333) + ((x >> 2) & 0x33333333)
        x = (x + (x >> 4)) & 0x0F0F0F0F
        x = x * 0x01010101
        x = (x >> 24) & 0x3F
        return int(np.min(x))

