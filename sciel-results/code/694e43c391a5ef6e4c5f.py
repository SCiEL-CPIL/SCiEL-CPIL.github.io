def _greedy_grow(words, rng, max_add=1000, time_budget=10.0):
    """
    Greedily add random words to the code, maintaining min distance >= 6.
    Returns the grown code.
    """
    start_time = time.time()
    words = list(words)
    added = 0
    while added < max_add and (time.time() - start_time) < time_budget:
        # Generate a random candidate
        candidate = rng.getrandbits(N)
        # Check if it's already in the code
        if candidate in words:
            continue
        # Check minimum distance
        min_d = _min_dist_to_set(candidate, words)
        if min_d >= MIN_DIST:
            words.append(candidate)
            added += 1
    return words

def _greedy_grow_sorted(words, rng, time_budget=15.0):
    """
    Greedily add words, trying candidates sorted by some heuristic.
    """
    start_time = time.time()
    words = list(words)
    # Try to add words with various weights
    # First, try to fill in with weight-9 words (middle weight)
    for target_weight in range(1, N):
        if (time.time() - start_time) > time_budget:
            break
        # Generate candidates with this weight
        for _ in range(5000):
            if (time.time() - start_time) > time_budget:
                break
            # Random word with target_weight bits set
            positions = rng.sample(range(N), target_weight)
            candidate = 0
            for p in positions:
                candidate |= (1 << p)
            if candidate in words:
                continue
            min_d = _min_dist_to_set(candidate, words)
            if min_d >= MIN_DIST:
                words.append(candidate)
    return words

def _local_improve(words, rng, time_budget=5.0):
    """
    Try to replace pairs of words with two new words to increase size.
    This is a simple local search.
    """
    start_time = time.time()
    words = list(words)
    improved = True
    while improved and (time.time() - start_time) < time_budget:
        improved = False
        # Try to add a random word
        for _ in range(10000):
            if (time.time() - start_time) > time_budget:
                break
            candidate = rng.getrandbits(N)
            if candidate in words:
                continue
            min_d = _min_dist_to_set(candidate, words)
            if min_d >= MIN_DIST:
                words.append(candidate)
                improved = True
                break
    return words

def construct():
    """
    Construct the largest binary code of length 18, distance >= 6.
    Returns a list of distinct integers in [0, 2**18).
    """
    start_time = time.time()
    best_code = []
    
    # Phase 1: Build a good initial code using greedy from a small seed
    # Start with the zero word and grow
    rng = random.Random(42)
    
    # Quick initial greedy to get a decent seed
    seed_code = [0]
    seed_code = _greedy_grow(seed_code, rng, max_add=500, time_budget=5.0)
    seed_code = _greedy_grow_sorted(seed_code, rng, time_budget=5.0)
    
    if len(seed_code) > len(best_code):
        best_code = list(seed_code)
    
    # Phase 2: Multiple random restarts, each starting from a subset of the best code
    # or from scratch with different random seeds
    elapsed = time.time() - start_time
    remaining = TIME_LIMIT - elapsed
    
    if remaining > 10:
        # Do several restarts
        for restart in range(20):
            if time.time() - start_time > TIME_LIMIT - 5:
                break
            
            rng = random.Random(restart * 12345 + 67890)
            
            # Strategy A: Start from scratch
            if restart % 2 == 0:
                code = [0]
                code = _greedy_grow(code, rng, max_add=600, time_budget=3.0)
                code = _greedy_grow_sorted(code, rng, time_budget=3.0)
                code = _local_improve(code, rng, time_budget=2.0)
            else:
                # Strategy B: Start from a random subset of best_code
                subset_size = min(len(best_code), 100 + rng.randint(0, 200))
                subset = rng.sample(best_code, subset_size) if len(best_code) >= subset_size else list(best_code)
                code = list(subset)
                code = _greedy_grow(code, rng, max_add=800, time_budget=4.0)
                code = _greedy_grow_sorted(code, rng, time_budget=3.0)
                code = _local_improve(code, rng, time_budget=2.0)
            
            if len(code) > len(best_code):
                best_code = list(code)
    
    # Phase 3: Final polish - try to add more words to the best code
    if time.time() - start_time < TIME_LIMIT - 5:
        rng = random.Random(99999)
        best_code = _local_improve(best_code, rng, time_budget=min(10, TIME_LIMIT - (time.time() - start_time) - 2))
    
    # Ensure the result is valid
    # Final verification (quick check for small codes)
    if len(best_code) <= 1000:
        for i in range(len(best_code)):
            for j in range(i+1, len(best_code)):
                if _hamming_dist(best_code[i], best_code[j]) < MIN_DIST:
                    # Remove the later word
                    best_code.pop(j)
                    break
            else:
                continue
            j = i + 1  # restart inner loop
    
    return best_code
