def construct():
    n, m, p = 4, 4, 4
    rank = 49
    
    # Strassen 2x2 decomposition
    # U2, V2, W2 are 4x7 matrices
    # Indices 0..3 for 2x2 matrices (row*2+col)
    
    U2 = np.zeros((4, 7), dtype=int)
    V2 = np.zeros((4, 7), dtype=int)
    W2 = np.zeros((4, 7), dtype=int)
    
    # c=0 (M1)
    # L1 = a+d -> U2[0,0]=1, U2[3,0]=1
    # M1 = e+h -> V2[0,0]=1, V2[3,0]=1
    # W1: C00+=1, C10+=1 -> W2[0,0]=1, W2[2,0]=1 (k=0,i=0 -> 0*2+0=0; k=1,i=0 -> 1*2+0=2)
    U2[0,0] = 1; U2[3,0] = 1
    V2[0,0] = 1; V2[3,0] = 1
    W2[0,0] = 1; W2[2,0] = 1
    
    # c=1 (M2)
    # L2 = c+d -> U2[2,1]=1, U2[3,1]=1
    # M2 = e -> V2[0,1]=1
    # W2: C10+=-1, C11+=1 -> W2[2,1]=-1, W2[3,1]=1
    U2[2,1] = 1; U2[3,1] = 1
    V2[0,1] = 1
    W2[2,1] = -1; W2[3,1] = 1
    
    # c=2 (M3)
    # L3 = a -> U2[0,2]=1
    # M3 = f-h -> V2[1,2]=1, V2[3,2]=-1
    # W3: C01+=1, C10+=1 -> W2[1,2]=1, W2[2,2]=1
    U2[0,2] = 1
    V2[1,2] = 1; V2[3,2] = -1
    W2[1,2] = 1; W2[2,2] = 1
    
    # c=3 (M4)
    # L4 = d -> U2[3,3]=1
    # M4 = g-f -> V2[2,3]=1, V2[1,3]=-1
    # W4: C00+=1, C10+=1, C11+=-1 -> W2[0,3]=1, W2[2,3]=1, W2[3,3]=-1
    U2[3,3] = 1
    V2[2,3] = 1; V2[1,3] = -1
    W2[0,3] = 1; W2[2,3] = 1; W2[3,3] = -1
    
    # c=4 (M5)
    # L5 = a+b -> U2[0,4]=1, U2[1,4]=1
    # M5 = h-g -> V2[3,4]=1, V2[2,4]=-1
    # W5: C00+=-1, C01+=1 -> W2[0,4]=-1, W2[1,4]=1
    U2[0,4] = 1; U2[1,4] = 1
    V2[3,4] = 1; V2[2,4] = -1
    W2[0,4] = -1; W2[1,4] = 1
    
    # c=5 (M6)
    # L6 = c-a -> U2[2,5]=1, U2[0,5]=-1
    # M6 = e+f -> V2[0,5]=1, V2[1,5]=1
    # W6: C01+=1, C11+=1 -> W2[1,5]=1, W2[3,5]=1
    U2[2,5] = 1; U2[0,5] = -1
    V2[0,5] = 1; V2[1,5] = 1
    W2[1,5] = 1; W2[3,5] = 1
    
    # c=6 (M7)
    # L7 = b-c -> U2[1,6]=1, U2[2,6]=-1
    # M7 = d+g -> V2[3,6]=1, V2[2,6]=1
    # W7: C00+=1, C11+=1 -> W2[0,6]=1, W2[3,6]=1
    U2[1,6] = 1; U2[2,6] = -1
    V2[3,6] = 1; V2[2,6] = 1
    W2[0,6] = 1; W2[3,6] = 1
    
    # Construct 4x4
    U = np.zeros((16, 49), dtype=int)
    V = np.zeros((16, 49), dtype=int)
    W = np.zeros((16, 49), dtype=int)
    
    for i in range(4):
        for j in range(4):
            i1, i2 = divmod(i, 2)
            j1, j2 = divmod(j, 2)
            for k in range(4):
                k1, k2 = divmod(k, 2)
                for c1 in range(7):
                    for c2 in range(7):
                        c = c1 * 7 + c2
                        val_u = U2[i1*2 + j1, c1] * U2[i2*2 + j2, c2]
                        val_v = V2[j1*2 + k1, c1] * V2[j2*2 + k2, c2]
                        val_w = W2[k1*2 + i1, c1] * W2[k2*2 + i2, c2]
                        
                        U[i*4 + j, c] += val_u
                        V[j*4 + k, c] += val_v
                        W[k*4 + i, c] += val_w
                        
    return {
        "U": U.tolist(),
        "V": V.tolist(),
        "W": W.tolist()
    }
