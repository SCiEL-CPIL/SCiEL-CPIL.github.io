"""
Construct a large binary code of length 17 with minimum distance 6.
Strategy: 
1. Deterministically construct the 256-word [17,9,6] linear code (shortened QR code).
2. Use the remaining time budget for local search (1-for-2 swaps) to attempt 
   finding a larger nonlinear code.
"""
import time
import random
import numpy as np

N = 17
MIN_DISTANCE = 6
TIME_LIMIT = 85  # seconds, safety margin before 90s kill

def _hamming_dist(a, b):
    return (a ^ b).bit_count()

def _generate_reed_muller_seed():
    """
    Fallback seed: 32-word RM(1,4) code extended by 0.
    Used only if QR construction fails or as a sanity check.
    """
    words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            words.append(word)
    return words

