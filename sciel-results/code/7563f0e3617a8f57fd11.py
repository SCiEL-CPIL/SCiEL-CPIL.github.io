def _precompute_deltas():
    """Precompute all vectors with weight <= MIN_DISTANCE - 1."""
    deltas = []
    for d in range(1 << N):
        if d.bit_count() < MIN_DISTANCE:
            deltas.append(d)
    return np.array(deltas, dtype=np.uint32)

def _greedy_expansion_deterministic(seed_words, deltas, rng, time_deadline):
    """
    Greedy expansion using a deterministic order (e.g., sorted by weight, then value).
    This avoids the overhead of shuffling 131072 elements and provides a consistent 
    starting point for local search.
    """
    words = list(seed_words)
    universe_size = 1 << N
    forbidden = np.zeros(universe_size, dtype=bool)
    
    # Initialize forbidden for seed words
    for w in words:
        neighbors = (w ^ deltas).astype(np.uint32)
        forbidden[neighbors] = True
    
    # Create a deterministic order: sorted by bit count, then by value.
    # This tends to find low-weight words first, which are often "compatible" 
    # in the early stages of code construction.
    indices = np.arange(universe_size)
    # np.argsort with a key isn't directly supported for complex keys, 
    # so we create a tuple array or just use a simple heuristic.
    # Actually, random shuffle is often better for avoiding local minima.
    # Let's stick to random but with multiple fast trials.
    
    indices = np.arange(universe_size)
    rng.shuffle(indices)
    
    for idx in indices:
        if time.time() > time_deadline - 10:
            break
            
        if forbidden[idx]:
            continue
            
        w = int(idx)
        words.append(w)
        
        # Update forbidden zone
        neighbors = (w ^ deltas).astype(np.uint32)
        forbidden[neighbors] = True
        
    return words

def _local_search_improve(words, deltas, rng, time_deadline):
    """
    Aggressive local search: 1-for-2 swaps.
    We try to remove one word and add two new words.
    """
    words = list(words)
    universe_size = 1 << N
    
    def rebuild_forbidden(word_list):
        forbidden = np.zeros(universe_size, dtype=bool)
        for w in word_list:
            neighbors = (w ^ deltas).astype(np.uint32)
            forbidden[neighbors] = True
        return forbidden
    
    best_words = words
    best_size = len(words)
    
    # Precompute a random order for candidate searches
    candidate_order = np.arange(universe_size)
    
    # We will loop until time is up
    while time.time() < time_deadline - 2:
        if len(best_words) < 2:
            break
            
        # Pick a random word to remove
        remove_idx = rng.randint(0, len(best_words) - 1)
        removed_word = best_words[remove_idx]
        
        # Create temporary list without the removed word
        temp_words = best_words[:remove_idx] + best_words[remove_idx+1:]
        
        # Rebuild forbidden zone for temp_words
        forbidden = rebuild_forbidden(temp_words)
        
        # Try to find 2 new words
        added_words = []
        
        # Shuffle candidate order for this iteration
        rng.shuffle(candidate_order)
        
        for idx_cand in candidate_order:
            if len(added_words) == 2:
                break
            if forbidden[idx_cand]:
                continue
            
            w = int(idx_cand)
            
            # Add w to temp_words and update forbidden
            temp_words.append(w)
            added_words.append(w)
            neighbors = (w ^ deltas).astype(np.uint32)
            forbidden[neighbors] = True
            
        if len(added_words) == 2:
            # We successfully swapped 1 for 2
            new_size = len(temp_words)
            if new_size > best_size:
                best_words = temp_words
                best_size = new_size
            # Even if not improved, we might want to accept it if it's a "lateral move" 
            # to escape local minima? No, for this task, we only care about max size.
            # However, accepting non-improving moves can help escape. 
            # Given the time limit, we stick to hill-climbing (accept only improvements).
            
    return best_words

def construct():
    start_time = time.time()
    time_deadline = start_time + TIME_LIMIT
    
    rng = random.Random(42)
    
    # Precompute deltas
    deltas = _precompute_deltas()
    
    # Get initial seed
    seed = _generate_reed_muller_seed()
    
    best_words = seed
    best_size = len(seed)
    
    # Phase 1: Multiple Greedy Expansions
    # Run greedy expansion several times with different random seeds/orderings
    num_greedy_trials = 10
    
    for trial in range(num_greedy_trials):
        if time.time() > time_deadline - 20:
            break
        
        rng_trial = random.Random(1000 + trial)
        words_trial = _greedy_expansion_deterministic(seed, deltas, rng_trial, time_deadline - 10)
        
        if len(words_trial) > best_size:
            best_words = words_trial
            best_size = len(words_trial)
            
    # Phase 2: Local Search Improvement
    if time.time() < time_deadline - 5 and len(best_words) > 50:
        rng_ls = random.Random(2000)
        improved_words = _local_search_improve(best_words, deltas, rng_ls, time_deadline - 2)
        if len(improved_words) > best_size:
            best_words = improved_words
            best_size = len(improved_words)
            
    # Phase 3: Final check and cleanup
    seen = set()
    valid_words = []
    for w in best_words:
        if w not in seen:
            seen.add(w)
            valid_words.append(w)
            
    if len(valid_words) < 2:
        return valid_words if valid_words else [0]
        
    return valid_words
