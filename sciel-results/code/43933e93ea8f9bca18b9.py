"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
def construct():
    # Polynomial multiplication in F2[x] modulo g
    def poly_mul_mod(a, b, g):
        res = 0
        deg_g = g.bit_length() - 1
        while b:
            if b & 1:
                res ^= a
                # Reduce res
                while res.bit_length() > deg_g:
                    shift = res.bit_length() - 1 - deg_g
                    res ^= (g << shift)
            b >>= 1
            if b:
                a <<= 1
                while a.bit_length() > deg_g:
                    shift = a.bit_length() - 1 - deg_g
                    a ^= (g << shift)
        return res

    def find_qr_generator():
        # Find a monic polynomial g of degree 8 such that x^17 = 1 mod g
        for coeffs in range(256):
            g = (1 << 8) | coeffs
            # Check if x^17 % g == 1
            # x is 2 (binary 10)
            # x^17 is 1 << 17
            val = poly_mul_mod(1, 1 << 17, g)
            if val == 1:
                # Additional check: g should not divide x^k - 1 for k < 17
                # Since 17 is prime, any non-trivial divisor of x^17-1 has roots of order 17.
                # The only divisors are x-1 and the two degree-8 factors.
                # x-1 is degree 1.
                # So any degree 8 divisor works.
                return g
        return None

    g = find_qr_generator()
    
    if g is None:
        # Fallback to Reed-Muller if something goes wrong
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words

    # Construct the 9 basis vectors for the [17, 9, 5] cyclic code
    # g(x) = sum_{i=0}^8 g_i x^i
    # The generator matrix rows are shifts of the coefficient vector of g
    # Note: The cyclic code generated by g(x) has codewords c(x) = m(x)g(x)
    # The basis vectors correspond to m(x) = 1, x, x^2, ..., x^8
    # So the rows are the coefficients of g(x), xg(x), ..., x^8 g(x)
    # Since deg(g)=8, x^i g(x) has degree 8+i.
    # For i=0, deg 8. Coeffs at 0..8.
    # For i=8, deg 16. Coeffs at 8..16.
    
    basis = []
    for i in range(9):
        # Calculate x^i * g(x)
        # This is just g shifted by i
        # But we need to ensure it fits in 17 bits (indices 0..16)
        # g has degree 8. x^8 g has degree 16. Fits perfectly.
        row_int = (g << i)
        # Extract bits 0..16
        row_bits = []
        for j in range(17):
            row_bits.append((row_int >> j) & 1)
        
        # Extend to length 18 with parity bit
        parity = sum(row_bits) % 2
        row_bits.append(parity)
        
        # Convert back to integer
        word = 0
        for j in range(18):
            if row_bits[j]:
                word |= (1 << j)
        basis.append(word)

    # Generate all 512 codewords
    words = []
    for mask in range(512):
        word = 0
        for i in range(9):
            if (mask >> i) & 1:
                word ^= basis[i]
        words.append(word)
    
    # Verify minimum distance
    # To save time, we can check a subset or trust the theory.
    # But verification is cheap for 512 words (130k pairs).
    # 130,000 * bit_count is very fast.
    min_dist = 18
    for i in range(len(words)):
        for j in range(i + 1, len(words)):
            d = (words[i] ^ words[j]).bit_count()
            if d < min_dist:
                min_dist = d
                if min_dist < 6:
                    # Fallback if theory fails
                    words = []
                    for slope in range(16):
                        for intercept in range(2):
                            word = 0
                            for point in range(16):
                                bit = ((slope & point).bit_count() + intercept) % 2
                                word |= bit << point
                            words.append(word)
                    return words

    return words
# EVOLVE-BLOCK-END
