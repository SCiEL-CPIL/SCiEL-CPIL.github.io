import time
import math
from collections import defaultdict

def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin for 150s limit

    # Primes p ≡ 1 mod 4 and their representation a^2 + b^2 = p
    # We need small primes to maximize the count of factors
    primes_1mod4 = []
    def is_prime(n):
        if n < 2: return False
        if n % 2 == 0: return n == 2
        for i in range(3, int(math.isqrt(n)) + 1, 2):
            if n % i == 0:
                return False
        return True
        
    def find_rep(p):
        # Find a, b such that a^2 + b^2 = p
        # Since p is prime ≡ 1 mod 4, solution exists.
        # Simple search for small p
        for a in range(1, int(math.isqrt(p)) + 1):
            b2 = p - a*a
            b = int(math.isqrt(b2))
            if b*b == b2:
                return a, b
        return None

    # Generate first ~30 primes ≡ 1 mod 4
    candidate_p = 5
    while len(primes_1mod4) < 30:
        if candidate_p % 4 == 1 and is_prime(candidate_p):
            rep = find_rep(candidate_p)
            if rep:
                primes_1mod4.append((candidate_p, rep[0], rep[1]))
        candidate_p += 1

    # We want to maximize K = prod (e_i + 1) subject to prod p_i^e_i <= 10^18
    # Let's use a priority queue or greedy approach?
    # Greedy: at each step, add the prime (or increase exponent) that gives the best marginal gain in log(K) per log(cost).
    # Marginal gain for adding p with e=0 -> 1: log(2) / log(p)
    # Marginal gain for increasing p from e to e+1: log(e+2) - log(e+1) = log((e+2)/(e+1))
    # Cost is log(p) in both cases.
    
    # Let's just do a DFS/BFS over the exponents of the first ~15 primes.
    # The product of the first 12 primes is ~ 10^18.
    # So we likely only need the first 12-15 primes.
    
    max_val = 10**18
    best_M = 1
    best_K = 1
    best_exponents = {}
    
    # Primes to consider
    search_primes = [p for p, a, b in primes_1mod4[:15]]
    
    def dfs(idx, current_M, current_K, exponents):
        nonlocal best_M, best_K, best_exponents
        if current_K > best_K:
            best_K = current_K
            best_M = current_M
            best_exponents = dict(exponents)
            
        if idx >= len(search_primes):
            return
            
        p = search_primes[idx]
        # Try exponents 0, 1, ...
        val = current_M
        exp = 0
        while val <= max_val:
            exponents[p] = exp
            next_K = current_K * (exp + 1)
            # Pruning: even if we multiply by max possible factor for remaining primes, can we beat best_K?
            # Max factor for remaining is roughly 2^(remaining)
            # This is a loose bound, but DFS depth is small.
            dfs(idx + 1, val, next_K, exponents)
            exp += 1
            val = val * p
            if val > max_val:
                break
        # Cleanup
        if p in exponents and exponents[p] == 0:
            del exponents[p]

    # Run DFS
    dfs(0, 1, 1, {})
    
    # best_M is the optimal M.
    # Now we need to generate the pairs (u, v) for u^2 + v^2 = best_M.
    # We use the Gaussian integer multiplication method.
    
    # Map prime to (a, b)
    p_to_rep = {p: (a, b) for p, a, b in primes_1mod4}
    
    # Generate all combinations of exponents k_i for 0 <= k_i <= e_i
    # z = prod (a_i + i b_i)^{k_i} (a_i - i b_i)^{e_i - k_i}
    # Note: We must be careful with the sign/phase.
    # The set of all z is generated by choosing for each prime power p^e, one of the e+1 factors from the expansion.
    # Actually, it's easier to just iterate over all tuples (k_1, ..., k_m) where 0 <= k_i <= e_i.
    # For each tuple, compute z.
    
    pairs_set = set()
    
    # Get the list of primes used and their exponents
    used_primes = [p for p in search_primes if p in best_exponents and best_exponents[p] > 0]
    # Note: best_exponents might have keys with 0, but we filtered them out in DFS cleanup?
    # Actually, DFS sets exponents[p] = exp. If exp=0, it deletes it.
    # So best_exponents only contains primes with e > 0.
    
    if not used_primes:
        # M=1, only rep is 1^2+0^2. But we need u,v > 0?
        # Task says "distinct pairs a <= b, a+b=N".
        # If N=1, a=0, b=1? 0 is not powerful? "1 counts as powerful". 0?
        # Usually powerful numbers are positive integers.
        # If M=1, u=1, v=0. a=1, b=0.
        # But N >= 2.
        # So M=1 is not enough.
        # The DFS should find M > 1.
        pass

    # Generate representations
    # We represent complex numbers as tuples (re, im)
    def complex_mul(c1, c2):
        re1, im1 = c1
        re2, im2 = c2
        return (re1*re2 - im1*im2, re1*im2 + im1*re2)
        
    def complex_pow(c, n):
        if n == 0:
            return (1, 0)
        res = (1, 0)
        base = c
        while n > 0:
            if n % 2 == 1:
                res = complex_mul(res, base)
            base = complex_mul(base, base)
            n //= 2
        return res

    # Get exponents
    exps = [best_exponents[p] for p in used_primes]
    
    # Iterate over all combinations of k_i
    # Number of combinations is best_K
    # best_K is at most a few thousands, so this is fine.
    
    import itertools
    
    # Ranges for k_i
    ranges = [range(e + 1) for e in exps]
    
    for ks in itertools.product(*ranges):
        # z = prod (a_i + i b_i)^{k_i} * (a_i - i b_i)^{e_i - k_i}
        z = (1, 0)
        for i, p in enumerate(used_primes):
            a, b = p_to_rep[p]
            pi = (a, b)
            pi_bar = (a, -b)
            k = ks[i]
            e = exps[i]
            if k > 0:
                z = complex_mul(z, complex_pow(pi, k))
            if e - k > 0:
                z = complex_mul(z, complex_pow(pi_bar, e - k))
        
        u, v = z
        # Normalize
        # We want u^2 + v^2 = M
        # u, v can be negative.
        # Take absolute values
        u = abs(u)
        v = abs(v)
        
        # Ensure u <= v
        if u > v:
            u, v = v, u
            
        # Check if u, v > 0
        # If u=0 or v=0, it's a trivial rep (M is a square).
        # We include them?
        # "distinct pairs a <= b".
        # a = u^2, b = v^2.
        # If u=0, a=0. Is 0 powerful?
        # "1 counts as powerful". 0 is usually not considered.
        # However, N >= 2.
        # If M is a square, one rep is (sqrt(M), 0).
        # a=M, b=0.
        # If 0 is not allowed, we skip.
        # But typically "sum of two powerful numbers" implies positive integers?
        # The prompt says "Integers up to 10^18". "1 counts as powerful".
        # It doesn't explicitly say positive. But a+b=N with N>=2.
        # If a=0, b=N.
        # Let's assume positive integers to be safe, or check if 0 is powerful.
        # Usually powerful numbers are in N+.
        # Let's skip u=0 or v=0 to be safe, unless it's the only one.
        
        if u == 0 or v == 0:
            continue
            
        # Add to set
        pairs_set.add((u*u, v*v))
        
        if time.time() > deadline - 5.0:
            break

    # If we didn't find any pairs (e.g. M=1), fallback
    if not pairs_set:
        # Try a simple known powerful sum
        # N = 1 + 1 = 2?
        # Pairs: [1, 1].
        # 1 is powerful.
        return {'N': 2, 'pairs': [[1, 1]]}

    # Convert set to list
    pairs = sorted(list(pairs_set))
    
    # Verify
    N = best_M
    if N > 10**18 or N < 2:
        return {'N': 2, 'pairs': [[1, 1]]}
        
    # Final check on pairs
    valid_pairs = []
    for a, b in pairs:
        if a + b == N and a <= b:
            # Check powerful
            def is_powerful(n):
                if n == 1: return True
                d = 2
                while d * d <= n:
                    if n % d == 0:
                        cnt = 0
                        while n % d == 0:
                            n //= d
                            cnt += 1
                        if cnt == 1:
                            return False
                    d += 1 if d == 2 else 2
                return True
            if is_powerful(a) and is_powerful(b):
                valid_pairs.append([a, b])
                
    if not valid_pairs:
        return {'N': 2, 'pairs': [[1, 1]]}
        
    return {'N': N, 'pairs': valid_pairs}
