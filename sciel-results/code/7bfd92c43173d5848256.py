def _clean(x):
    if x is None:
        return 0
    rx = round(x)
    if abs(x - rx) < 1e-9:
        return int(rx)
    r2 = round(2 * x)
    if abs(x - r2 / 2.0) < 1e-9:
        if r2 % 2 == 0:
            return int(r2 // 2)
        return (r2, 2)
    return float(x)


def construct():
    t0 = time.time()
    n, m, p = DIMENSIONS

    U4, V4, W4 = _cw444()
    r4 = len(U4[0])  # 18

    U = [[0] * r4 for _ in range(n * m)]
    V = [[0] * r4 for _ in range(m * p)]
    W = [[0] * r4 for _ in range(p * n)]

    for i in range(n * m):
        for c in range(r4):
            U[i][c] = U4[i][c]
    for j in range(m):
        for k in range(4):
            for c in range(r4):
                V[j * p + k][c] = V4[j * 4 + k][c]
    for k in range(4):
        for i in range(n):
            for c in range(r4):
                W[k * n + i][c] = W4[k * 4 + i][c]

    # Schoolbook for the remaining p-4 = 5 output columns (independent).
    col = r4
    for i in range(n):
        for j in range(m):
            for k in range(4, p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1

    assert col == r4, "column mismatch"

    U = [[_clean(v) for v in row] for row in U]
    V = [[_clean(v) for v in row] for row in V]
    W = [[_clean(v) for v in row] for row in W]

    if time.time() - t0 > 140:
        # Fallback to a guaranteed-valid (schoolbook) decomposition.
        rs = n * m * p
        Us = [[0] * rs for _ in range(n * m)]
        Vs = [[0] * rs for _ in range(m * p)]
        Ws = [[0] * rs for _ in range(p * n)]
        cc = 0
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    Us[i * m + j][cc] = 1
                    Vs[j * p + k][cc] = 1
                    Ws[k * n + i][cc] = 1
                    cc += 1
        return {"U": Us, "V": Vs, "W": Ws}

    return {"U": U, "V": V, "W": W}


