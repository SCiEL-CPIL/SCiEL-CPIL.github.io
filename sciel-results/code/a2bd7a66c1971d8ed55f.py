import itertools
import time

def construct():
    """
    Constructs 101 lists of distinct denominators from 1..10 such that the sum
    of their modular inverses modulo 101 equals the row index.
    Minimizes the maximum length of the lists.
    """
    start_time = time.time()
    deadline = start_time + 50.0  # Safety margin, though computation is trivial
    
    p = 101
    # Precompute modular inverses of 1..10 mod 101
    inv = [0] * 11
    for i in range(1, 11):
        inv[i] = pow(i, -1, p)
        
    # best_subset[r] will hold the list of denominators (smallest size found so far)
    # that sum to r modulo 101
    best_subset = {}
    
    # We search for the minimum maximum size K
    # Iterate subset size k from 1 to 10
    for k in range(1, 11):
        # Check time
        if time.time() > deadline:
            break
            
        # Generate all combinations of denominators of size k
        # Denominators are 1, 2, ..., 10
        for combo in itertools.combinations(range(1, 11), k):
            # Calculate sum of inverses
            s = sum(inv[x] for x in combo) % p
            
            # If this residue hasn't been covered by a smaller subset, record it
            if s not in best_subset:
                best_subset[s] = list(combo)
                
        # If all residues are covered, we can stop
        if len(best_subset) == p:
            break
            
    # Construct the final result
    result = []
    for r in range(p):
        if r in best_subset:
            result.append(best_subset[r])
        else:
            # Fallback: this should not happen as k=10 covers all subsets
            # But if it does, we need a non-empty list.
            # The sum of all 10 inverses covers one residue.
            # We might have missed some if the loop broke early due to time?
            # Unlikely. But to be safe, if missing, we can't easily fix it.
            # However, mathematically, k=10 includes all 2^10-1 subsets, so all residues
            # that are reachable are reachable. Are all residues reachable?
            # The group generated by the inverses must be the whole group Z_101.
            # Since 101 is prime, any non-zero element generates the group.
            # The inverses are non-zero. So yes, all residues are reachable.
            # So best_subset will be full.
            result.append([1]) # Placeholder, effectively unreachable
            
    return result
