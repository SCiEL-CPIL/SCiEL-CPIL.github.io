import numpy as np
import time
from itertools import combinations

def construct():
    N = 17
    MIN_DIST = 6
    start_time = time.time()
    time_limit = 58  # Safety margin

    # Precompute masks for blocking
    masks_by_dist = [[] for _ in range(MIN_DIST)]
    for d in range(MIN_DIST):
        for combo in combinations(range(N), d):
            mask = 0
            for i in combo:
                mask |= (1 << i)
            masks_by_dist[d].append(mask)

    def is_valid_code(codewords):
        """Check if all pairwise distances are at least MIN_DIST"""
        for i in range(len(codewords)):
            for j in range(i + 1, len(codewords)):
                if bin(codewords[i] ^ codewords[j]).count('1') < MIN_DIST:
                    return False
        return True

    # Strategy: Find a good [17,8,6] linear code, then greedily expand
    
    # The [18,9,6] extended quadratic residue code for p=17
    # Quadratic residues mod 17: {1,4,9,16,8,2,15,13}
    # The [18,9,6] code has generator matrix with rows corresponding to shifts
    # of the residue pattern plus the all-ones row.
    
    # Let's construct the [17,8,6] code by shortening the [18,9,6] code.
    # The [18,9,6] code: take the length-17 QR code and add an overall parity check.
    # Shortening by one coordinate: fix that coordinate to 0.
    
    # Actually, let me use a different approach: try multiple random linear codes
    # but with a better search strategy.
    
    best_code = None
    best_size = 0
    
    # Try to find a [17,8,6] linear code
    # Use a structured approach: start with a known good code structure
    
    # The shortened [18,9,6] QR code:
    # QR(17) = {1,4,9,16,8,2,15,13}
    # The generator matrix of the [17,8,6] code can be constructed as follows:
    # Row i is the cyclic shift of the QR indicator by i positions, for i=0..7
    # But we need to be careful about the exact construction.
    
    # Alternative: Use a greedy approach to build a large code directly
    # Start with a good seed and expand greedily
    
    # Seed: all-0 word and some well-chosen words
    # Let's use a greedy construction with multiple restarts and different orderings
    
    def greedy_expand(initial_code, order=None, deadline=None):
        """Expand a code greedily using a given word order"""
        if deadline is None:
            deadline = time_limit
        
        blocked = bytearray(1 << N)
        code = list(initial_code)
        
        # Block all neighbors of initial code
        for w in code:
            for d in range(MIN_DIST):
                for mask in masks_by_dist[d]:
                    blocked[w ^ mask] = 1
        
        if order is None:
            order = list(range(1 << N))
        
        for w in order:
            if time.time() > deadline:
                break
            if not blocked[w]:
                code.append(w)
                for d in range(MIN_DIST):
                    for mask in masks_by_dist[d]:
                        blocked[w ^ mask] = 1
        
        return code

    # First, try to find a good 256-word linear code
    # Use the known QR code structure
    
    # QR residues mod 17
    qr = [1, 4, 9, 16, 8, 2, 15, 13]
    
    # Construct generator matrix for [17,8,6] code
    # The code is generated by cyclic shifts of the QR indicator vector
    # QR indicator: 1 at positions in QR, 0 elsewhere (length 17)
    # But we need 8 independent rows
    
    # Let me try: row i = cyclic shift of QR indicator by i, for i=0..7
    # Then check if the resulting code has min distance 6
    
    G = np.zeros((8, N), dtype=np.int8)
    for i in range(8):
        for j in range(N):
            if (j + i) % N in qr:
                G[i, j] = 1
    
    # Generate codewords
    G_ints = []
    for i in range(8):
        val = 0
        for j in range(N):
            if G[i, j] == 1:
                val |= (1 << j)
        G_ints.append(val)
    
    codewords = [0]
    for i in range(8):
        new_codewords = [c ^ G_ints[i] for c in codewords]
        codewords.extend(new_codewords)
    
    # Check min distance
    min_d = N + 1
    for c in codewords:
        if c == 0:
            continue
        wt = bin(c).count('1')
        if wt < min_d:
            min_d = wt
    
    if min_d >= MIN_DIST:
        best_code = codewords
        best_size = len(codewords)
    else:
        # Try other constructions
        # Maybe the QR code needs a different generator matrix
        # Let's try: include the all-ones vector and 7 QR shifts
        G = np.zeros((8, N), dtype=np.int8)
        G[0, :] = 1  # All ones
        for i in range(7):
            for j in range(N):
                if (j + i) % N in qr:
                    G[i + 1, j] = 1
        
        G_ints = []
        for i in range(8):
            val = 0
            for j in range(N):
                if G[i, j] == 1:
                    val |= (1 << j)
            G_ints.append(val)
        
        codewords = [0]
        for i in range(8):
            new_codewords = [c ^ G_ints[i] for c in codewords]
            codewords.extend(new_codewords)
        
        min_d = N + 1
        for c in codewords:
            if c == 0:
                continue
            wt = bin(c).count('1')
            if wt < min_d:
                min_d = wt
        
        if min_d >= MIN_DIST:
            best_code = codewords
            best_size = len(codewords)
    
    if best_code is None:
        # Fallback: pure greedy from 0
        initial = [0]
        best_code = greedy_expand(initial)
        best_size = len(best_code)
    
    # Now expand the code greedily with different orderings
    # Try multiple orderings and keep the best result
    
    # Ordering 1: natural order
    code1 = greedy_expand(best_code, order=list(range(1 << N)), deadline=time_limit - 5)
    
    # Ordering 2: reverse order
    if time.time() < time_limit - 5:
        code2 = greedy_expand(best_code, order=list(range((1 << N) - 1, -1, -1)), deadline=time_limit - 2)
    else:
        code2 = code1
    
    # Ordering 3: weight-sorted (lighter words first)
    if time.time() < time_limit - 2:
        order3 = sorted(range(1 << N), key=lambda x: bin(x).count('1'))
        code3 = greedy_expand(best_code, order=order3, deadline=time_limit)
    else:
        code3 = code1
    
    # Pick the best
    candidates = [code1, code2, code3]
    best = max(candidates, key=len)
    
    return best
