"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import numpy as np
import time
from scipy.optimize import minimize

N = 300

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin before 150s limit

    def calculate_score(points):
        """Calculate the maximum common radius for a given set of points."""
        if len(points) < 2:
            return 1.0
        diff = points[:, np.newaxis, :] - points[np.newaxis, :, :]
        dist_sq = np.sum(diff**2, axis=2)
        np.fill_diagonal(dist_sq, np.inf)
        min_pair_dist = np.min(np.sqrt(dist_sq))
        
        r_i = np.linalg.norm(points, axis=1)
        min_bound_dist = np.min(1.0 - r_i)
        
        return min(min_pair_dist / 2.0, min_bound_dist)

    def gen_hex_lattice(spacing):
        """Generate hexagonal lattice points inside the unit circle."""
        k = int(1.0 / spacing) + 2
        pts = []
        for j in range(-k, k + 1):
            for i in range(-k, k + 1):
                x = (i + 0.5 * (j % 2)) * spacing
                y = j * spacing * np.sqrt(3.0) / 2.0
                r = np.hypot(x, y)
                if r <= 1.0 - spacing * 0.5:
                    pts.append((x, y))
        return np.array(pts) if pts else np.empty((0, 2))

    # 1. Initialization
    # Estimate spacing based on area
    spacing = np.sqrt(2.0 * np.pi / (np.sqrt(3.0) * N))
    points = gen_hex_lattice(spacing)
    
    while len(points) < N and spacing > 0.01:
        spacing *= 0.95
        points = gen_hex_lattice(spacing)
        
    if len(points) >= N:
        # Sort by distance from center to prioritize inner points? 
        # Actually, for packing, we just need N points.
        # Taking the first N from the list generated by loops might be biased.
        # Better to take N points that are well-distributed.
        # The hex lattice generation fills the circle.
        # We just take the first N valid ones.
        init_points = points[:N]
    else:
        init_points = points
        while len(init_points) < N:
            init_points = np.vstack([init_points, np.random.uniform(-0.9, 0.9, size=(1, 2))])
        init_points = init_points[:N]
        
    # Add small noise to break symmetry
    init_points = init_points + np.random.normal(0, 0.001, init_points.shape)
    
    best_points = init_points.copy()
    best_score = calculate_score(init_points)

    # 2. Optimization using L-BFGS-B with Annealing Power-Sum Objective
    # Objective: Minimize sum(V_k^-p) where V_k are distances/2 and 1-r
    # This approximates minimizing the inverse of the min distance.
    
    p_schedule = [10, 30, 100]
    current_points = init_points.copy()
    
    for p in p_schedule:
        if time.time() > deadline - 30.0:
            break
            
        def obj_and_grad(flat_x, p_val=p):
            x = flat_x.reshape((N, 2))
            
            # Pairwise distances
            diff = x[:, np.newaxis, :] - x[np.newaxis, :, :]
            dist_sq = np.sum(diff**2, axis=2)
            np.fill_diagonal(dist_sq, 1e-9)
            dist = np.sqrt(dist_sq)
            
            # Values V
            V_pair = dist / 2.0
            r_i = np.linalg.norm(x, axis=1)
            V_bound = 1.0 - r_i
            
            # Safe values to avoid division by zero or negative base
            eps = 1e-7
            V_pair_safe = np.maximum(V_pair, eps)
            V_bound_safe = np.maximum(V_bound, eps)
            
            # Objective: Sum V^-p
            # To prevent overflow/underflow issues with large p, we can normalize
            # but for p<=100, it should be okay with doubles.
            E = np.sum(V_pair_safe ** (-p_val)) + np.sum(V_bound_safe ** (-p_val))
            
            # Gradient
            # d/dx (V^-p) = -p V^(-p-1) dV/dx
            
            # Pairs
            # dV_pair/dx_i = 0.5 * (x_i - x_j) / dist
            # Term = -p * V_pair^(-p-1) * 0.5 * (x_i - x_j) / dist
            # V_pair = dist/2 => V_pair^(-p-1) = (dist/2)^(-p-1) = 2^(p+1) * dist^(-p-1)
            # Term = -p * 2^(p+1) * dist^(-p-1) * 0.5 * (x_i - x_j) / dist
            #      = -p * 2^p * dist^(-p-2) * (x_i - x_j)
            
            # Calculate coefficient for each pair (i,j)
            # coeff_ij = -p * 2^p * dist^(-p-2)
            # dist^(-p-2) = (dist_sq)^(-(p+2)/2)
            
            # 2^p can be large. p=100 -> 2^100 ~ 1e30.
            # dist ~ 0.05. dist^-102 ~ (0.05)^-102 ~ (20)^102 ~ 1e130.
            # Product ~ 1e160. Safe.
            
            coeff_pair = -p_val * (2.0 ** p_val) * (dist_sq ** (-(p_val + 2) / 2.0))
            np.fill_diagonal(coeff_pair, 0.0)
            
            grad_pair = np.sum(coeff_pair[:, :, np.newaxis] * diff, axis=1)
            
            # Boundary
            # dV_bound/dx = -x/r
            # Term = -p * V_bound^(-p-1) * (-x/r) = p * V_bound^(-p-1) * x/r
            
            r_safe = np.maximum(r_i, eps)
            V_bound_safe_col = V_bound_safe[:, np.newaxis]
            coeff_bound = p_val * (V_bound_safe_col ** (-p_val - 1))
            grad_bound = coeff_bound * (x / r_safe[:, np.newaxis])
            
            grad = grad_pair + grad_bound
            return E, grad

        try:
            res = minimize(
                obj_and_grad,
                current_points.flatten(),
                jac=True,
                method='L-BFGS-B',
                bounds=[(-1.0, 1.0)] * (2 * N),
                options={'maxiter': 1000, 'ftol': 1e-15, 'gtol': 1e-12, 'maxls': 50}
            )
            new_points = res.x.reshape((N, 2))
            if np.all(np.isfinite(new_points)):
                new_score = calculate_score(new_points)
                if new_score > best_score:
                    best_score = new_score
                    best_points = new_points.copy()
                    current_points = new_points.copy()
        except Exception:
            pass

    # 3. Local Polish
    # Greedy search on the bottleneck
    if time.time() < deadline - 5.0:
        current_points = best_points.copy()
        current_score = best_score
        step_size = 0.0005
        no_improve_count = 0
        max_no_improve = 30
        
        for _ in range(3000):
            if time.time() > deadline - 2.0:
                break
            if no_improve_count > max_no_improve:
                break
            
            # Find the bottleneck
            diff = current_points[:, np.newaxis, :] - current_points[np.newaxis, :, :]
            dist_sq = np.sum(diff**2, axis=2)
            np.fill_diagonal(dist_sq, np.inf)
            min_pair_dist = np.min(np.sqrt(dist_sq))
            
            r_i = np.linalg.norm(current_points, axis=1)
            min_bound_dist = np.min(1.0 - r_i)
            
            current_r = min(min_pair_dist / 2.0, min_bound_dist)
            
            if min_pair_dist / 2.0 < min_bound_dist:
                # Pair is limiting
                idx = np.unravel_index(np.argmin(dist_sq), dist_sq.shape)
                i, j = idx
                if i == j:
                    continue
                direction = current_points[i] - current_points[j]
                norm = np.linalg.norm(direction)
                if norm > 1e-9:
                    direction /= norm
                    # Push apart
                    old_i = current_points[i].copy()
                    old_j = current_points[j].copy()
                    current_points[i] += direction * step_size
                    current_points[j] -= direction * step_size
                    
                    new_score = calculate_score(current_points)
                    if new_score > current_score:
                        current_score = new_score
                        best_points = current_points.copy()
                        best_score = current_score
                        no_improve_count = 0
                    else:
                        # Revert
                        current_points[i] = old_i
                        current_points[j] = old_j
                        no_improve_count += 1
            else:
                # Boundary is limiting
                idx = np.argmin(1.0 - r_i)
                point = current_points[idx]
                norm = np.linalg.norm(point)
                if norm > 1e-9:
                    direction = -point / norm
                    old_p = current_points[idx].copy()
                    current_points[idx] += direction * step_size
                    
                    new_score = calculate_score(current_points)
                    if new_score > current_score:
                        current_score = new_score
                        best_points = current_points.copy()
                        best_score = current_score
                        no_improve_count = 0
                    else:
                        current_points[idx] = old_p
                        no_improve_count += 1
                        # Try a smaller step size if stuck
                        if no_improve_count % 10 == 0:
                            step_size *= 0.9

    return best_points
# EVOLVE-BLOCK-END
