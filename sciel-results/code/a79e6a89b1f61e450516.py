def hex_vertices(cx, cy, angle_deg, s=1.0):
    """Return 6 vertices of a unit hexagon centered at (cx,cy) with given rotation."""
    a = math.radians(angle_deg)
    verts = []
    for k in range(6):
        ang = a + k * math.pi / 3.0
        verts.append((cx + s * math.cos(ang), cy + s * math.sin(ang)))
    return np.array(verts)

def hexagon_distance(v1, v2):
    """Compute minimum penetration depth between two hexagons.
    Returns negative if overlapping (penetration > 0 means overlap).
    Uses SAT (Separating Axis Theorem) for convex hexagons."""
    def edge_normals(verts):
        normals = []
        for i in range(6):
            d = verts[(i+1)%6] - verts[i]
            n = np.array([-d[1], d[0]])
            norm = np.linalg.norm(n)
            if norm > 1e-15:
                normals.append(n / norm)
        return normals
    
    n1 = edge_normals(v1)
    n2 = edge_normals(v2)
    all_normals = n1 + n2
    
    min_overlap = float('inf')
    for n in all_normals:
        p1 = v1 @ n
        p2 = v2 @ n
        min1, max1 = np.min(p1), np.max(p1)
        min2, max2 = np.min(p2), np.max(p2)
        
        if max1 < min2 or max2 < min1:
            return 0.0
        
        overlap = min(max1, max2) - max(min1, min2)
        min_overlap = min(min_overlap, overlap)
    
    return min_overlap

