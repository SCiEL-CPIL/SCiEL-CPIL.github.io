import time

def _verify_latin(square):
    n = len(square)
    for i in range(n):
        if sorted(square[i]) != list(range(n)):
            return False
        if sorted(square[j][i] for j in range(n)) != list(range(n)):
            return False
    return True

def _verify_orthogonal(s1, s2):
    n = len(s1)
    pairs = set()
    for i in range(n):
        for j in range(n):
            p = (s1[i][j], s2[i][j])
            if p in pairs:
                return False
            pairs.add(p)
    return len(pairs) == n * n

def _verify_all(squares):
    if not squares:
        return False
    n = len(squares[0])
    for sq in squares:
        if not _verify_latin(sq):
            return False
    for i in range(len(squares)):
        for j in range(i + 1, len(squares)):
            if not _verify_orthogonal(squares[i], squares[j]):
                return False
    return True

