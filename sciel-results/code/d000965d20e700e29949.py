def _fcc_like(n):
    """Generate an FCC-like fragment."""
    points = []
    # FCC lattice points
    a = 1.0  # lattice constant
    # Generate FCC points in a cube
    max_coord = int(np.ceil(n ** (1/3))) + 2
    for i in range(-max_coord, max_coord + 1):
        for j in range(-max_coord, max_coord + 1):
            for k in range(-max_coord, max_coord + 1):
                # FCC: (0,0,0), (0.5,0.5,0), (0.5,0,0.5), (0,0.5,0.5)
                for dx, dy, dz in [(0,0,0), (0.5,0.5,0), (0.5,0,0.5), (0,0.5,0.5)]:
                    p = a * np.array([i + dx, j + dy, k + dz])
                    if np.linalg.norm(p) < max_coord * a:
                        points.append(p)
    
    # Sort by distance from center and take n closest
    points = np.array(points)
    points -= points.mean(axis=0)
    dists = np.linalg.norm(points, axis=1)
    idx = np.argsort(dists)[:n]
    result = points[idx]
    return result


def _hcp_like(n):
    """Generate an HCP-like fragment."""
    points = []
    a = 1.0
    c = a * np.sqrt(8/3)
    max_coord = int(np.ceil(n ** (1/3))) + 2
    for i in range(-max_coord, max_coord + 1):
        for j in range(-max_coord, max_coord + 1):
            for k in range(-max_coord, max_coord + 1):
                # HCP: ABAB stacking
                layer = k % 2
                if layer == 0:
                    offset = [0, 0]
                else:
                    offset = [0.5, 1/np.sqrt(3)]
                p = np.array([a * (i + offset[0]), a * (j + offset[1]), c * k])
                if np.linalg.norm(p) < max_coord * a:
                    points.append(p)
    
    points = np.array(points)
    points -= points.mean(axis=0)
    dists = np.linalg.norm(points, axis=1)
    idx = np.argsort(dists)[:n]
    result = points[idx]
    return result


