import sys
import time
import random

def construct(n_rows, k):
    start_time = time.time()
    timeout = 110.0
    
    best_max = float('inf')
    best_solution = None
    
    # Global state for backtracking
    rows = [[0] * (k + 1) for _ in range(n_rows)]
    used_diffs = set()
    
    def get_max(rows):
        return max(max(r) for r in rows)

    def check_conflicts(row_idx, col_idx, val):
        """Check if placing val at row_idx, col_idx creates any conflict."""
        # 1. Check against current row's previous elements
        current_row = rows[row_idx]
        for i in range(col_idx):
            d = val - current_row[i]
            if d in used_diffs:
                return False
            # Also check if d is already in the current row's local diffs? 
            # No, used_diffs contains ALL diffs from all completed rows 
            # and we must add the current row's partial diffs to a temp set or check against them.
            # Wait, the current row's diffs are NOT in used_diffs yet.
            # We need to check if d conflicts with other diffs in the current row.
            pass
        
        # Better approach: 
        # The set of "forbidden" diffs is:
        # 1. All diffs in used_diffs (from previous rows)
        # 2. All diffs between val and current_row[0..col_idx-1] must be unique 
        #    and not in used_diffs.
        
        # Let's collect the new diffs generated by this placement
        new_diffs = []
        for i in range(col_idx):
            d = val - current_row[i]
            if d in used_diffs:
                return False
            new_diffs.append(d)
            
        # Check if new_diffs has duplicates within itself
        if len(new_diffs) != len(set(new_diffs)):
            return False
            
        return True

    def backtrack(row_idx, col_idx, time_limit):
        """
        Recursive backtracking to fill rows.
        Returns True if a solution is found, False if time runs out or dead end.
        """
        if time.time() > time_limit:
            return False
            
        if row_idx == n_rows:
            # All rows filled
            return True
            
        if col_idx == k + 1:
            # Move to next row
            return backtrack(row_idx + 1, 0, time_limit)
            
        if col_idx == 0:
            rows[row_idx][0] = 0
            # No diffs generated for the first element
            return backtrack(row_idx, 1, time_limit)
            
        # Determine candidate range
        min_val = rows[row_idx][col_idx - 1] + 1
        # We don't have a hard upper bound yet, but we can limit it to best_max if we have one
        # Or just a reasonable limit like 200
        max_val = best_max if best_max != float('inf') else 200
        
        # Generate candidates
        # To introduce randomness and avoid getting stuck in the same "greedy" path,
        # we can pick a random subset or shuffle.
        # For now, let's try increasing order, but with a "jump" strategy if we restart.
        
        found = False
        # We will iterate through candidates. 
        # To make it more "search-like" and less "greedy", we can randomize the start point 
        # or pick a random valid candidate from a window.
        
        # Let's try a window of candidates
        candidates = []
        for v in range(min_val, max_val + 1):
            if check_conflicts(row_idx, col_idx, v):
                candidates.append(v)
                if len(candidates) > 10: # Limit branching factor
                    break
        
        if not candidates:
            return False
            
        # Randomize the order of candidates to explore different parts of the space
        random.shuffle(candidates)
        
        for v in candidates:
            rows[row_idx][col_idx] = v
            # Add new diffs to used_diffs
            new_diffs = []
            for i in range(col_idx):
                d = v - rows[row_idx][i]
                new_diffs.append(d)
                used_diffs.add(d)
                
            if backtrack(row_idx, col_idx + 1, time_limit):
                return True
                
            # Backtrack
            for d in new_diffs:
                used_diffs.remove(d)
            rows[row_idx][col_idx] = 0
            
        return False

    # Main Loop: Multiple attempts with increasing time limits or randomized seeds
    attempt = 0
    while time.time() - start_time < timeout:
        # Reset state
        rows = [[0] * (k + 1) for _ in range(n_rows)]
        used_diffs = set()
        
        # Set a time limit for this specific backtracking run
        # Start with small limits, increase them
        # Or just use the remaining time? 
        # If we use all remaining time, we might not get to "restart" with a different random seed.
        # Let's use a fixed chunk of time, e.g., 5 seconds, or remaining/10.
        remaining = timeout - (time.time() - start_time)
        if remaining < 1:
            break
            
        # Use a fraction of remaining time for this search path
        # This allows multiple diverse searches
        search_time_limit = start_time + min(5.0, remaining / 2)
        
        # Run backtracking
        if backtrack(0, 0, search_time_limit):
            # Found a valid solution
            curr_max = get_max(rows)
            if curr_max < best_max:
                best_max = curr_max
                best_solution = [r[:] for r in rows]
                
            # If we found a good solution, we might want to try to improve it
            # But the backtracker finds *a* valid solution, not necessarily the optimal one.
            # To improve, we can restart the backtracking with a tighter upper bound (best_max - 1)
            # This forces the search to find a better solution if one exists.
            
        attempt += 1
        
    return best_solution
