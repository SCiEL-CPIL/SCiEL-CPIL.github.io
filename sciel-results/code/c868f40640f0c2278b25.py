"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import numpy as np
import time

# EVOLVE-BLOCK-START

def design(problem):
    """Design a 32x32 symmetric unit cell to maximize the TM gap between bands 4 and 5."""
    size = problem["pixels"]  # 32
    eps_low = problem["eps_low"]
    eps_high = problem["eps_high"]
    
    # Deadlines
    start_time = time.time()
    max_time = 180.0  # Leave 40s safety margin for evaluator
    search_time_limit = max_time - 2.0
    
    # 1. Generate High-Quality Seed
    # Literature suggests a ring with a central dielectric dot often works well for TM bands.
    # Let's try a few geometric seeds and evaluate them.
    
    def make_ring_hole(r_in, r_out, r_dot):
        cell = np.zeros((size, size), dtype=np.float64)
        cy = cx = (size - 1) / 2.0
        for i in range(size):
            for j in range(size):
                dx = (i - cx) / size
                dy = (j - cy) / size
                r = np.sqrt(dx*dx + dy*dy)
                # Ring: dielectric if r_in < r < r_out
                # Dot: dielectric if r < r_dot
                if (r_in < r < r_out) or (r < r_dot):
                    cell[i, j] = 1.0
        return cell
    
    def make_solid_circle(r):
        cell = np.zeros((size, size), dtype=np.float64)
        cy = cx = (size - 1) / 2.0
        for i in range(size):
            for j in range(size):
                dx = (i - cx) / size
                dy = (j - cy) / size
                r = np.sqrt(dx*dx + dy*dy)
                if r < r:
                    cell[i, j] = 1.0
        return cell
        
    def make_cross(half_w):
        cell = np.zeros((size, size), dtype=np.float64)
        cy = cx = (size - 1) / 2.0
        # Vertical bar
        for i in range(size):
            for j in range(size):
                dx = (j - cx) / size
                if abs(dx) < half_w / size:
                    cell[i, j] = 1.0
                # Horizontal bar
                dy = (i - cx) / size
                if abs(dy) < half_w / size:
                    cell[i, j] = 1.0
        return cell

    seeds = [
        make_ring_hole(0.05, 0.25, 0.0), # Thin ring
        make_ring_hole(0.1, 0.3, 0.0),   # Thicker ring
        make_ring_hole(0.0, 0.3, 0.0),   # Disk (solid)
        make_ring_hole(0.1, 0.3, 0.05),  # Ring with dot
        make_ring_hole(0.08, 0.28, 0.03),# Ring with small dot
        make_solid_circle(0.2),          # Seed's rod
        make_solid_circle(0.25),
        make_solid_circle(0.15),
        make_cross(6),
        make_cross(8),
        make_cross(4),
    ]
    
    # 2. Fast Evaluator (Proxy)
    # Use a reduced number of plane waves for speed during search.
    # The real evaluator uses 289 (N=8). We use N=5 (121 PWs) or N=6 (169 PWs).
    # N=5 is much faster. Let's try N=6 first for accuracy, fallback to N=5 if slow.
    N_PW_PROXY = 6
    G_range = np.arange(-N_PW_PROXY, N_PW_PROXY + 1)
    Gx, Gy = np.meshgrid(G_range, G_range, indexing='ij')
    G_vectors = np.column_stack((Gx.ravel(), Gy.ravel()))
    G2 = np.sum(G_vectors**2, axis=1)
    G_diff = G_vectors[:, None, :] - G_vectors[None, :, :]
    G_diff_sq = np.sum(G_diff**2, axis=2)
    
    # Precompute k-points for proxy.
    # Focus on high symmetry lines: Gamma-X, Gamma-M, X-M.
    # Gamma = (0,0), X = (0.5, 0), M = (0.5, 0.5)
    k_points = []
    # Gamma to X
    for t in np.linspace(0, 0.5, 11):
        k_points.append((t, 0))
    # Gamma to M
    for t in np.linspace(0, 0.5, 11):
        k_points.append((t, t))
    # X to M
    for t in np.linspace(0, 0.5, 11):
        k_points.append((0.5, t))
    # Remove duplicates
    unique_k = list(set([tuple(np.round(k, 5)) for k in k_points]))
    k_points = [np.array(k) for k in unique_k]
    
    def get_mu_fourier_proxy(cell):
        """Compute Fourier coefficients of 1/eps using FFT."""
        # cell is 0/1. eps = 1 + 11 * cell
        eps = eps_low + (eps_high - eps_low) * cell
        mu = 1.0 / eps
        # Zero-padding or direct FFT? Direct FFT is fine for 32x32.
        mu_ft = np.fft.fft2(mu)
        # Reorder to have DC term at index 0, then positive/negative frequencies in a grid matching G_vectors order
        # G_vectors is generated by meshgrid(G_range, G_range, indexing='ij').
        # fft2 output is ordered: (0,0), (1,0), ..., (N-1, 0), (-N, 0), ...
        # We need to map fft2 indices to G_vectors indices.
        # G_vectors indices: (gx, gy) where gx, gy in [-N, N].
        # fft2 index: (ix, iy) where ix, iy in [0, 2N].
        # ix = (gx + N) % (2N+1)
        
        mu_ft_reordered = np.zeros_like(mu_ft, dtype=np.complex128)
        for ix, gx in enumerate(G_range):
            for iy, gy in enumerate(G_range):
                # Find the index in fft2 array corresponding to (gx, gy)
                # fft2 index is (gx + N_PW_PROXY, gy + N_PW_PROXY) mod size?
                # No, fft2 returns standard order.
                # fft2[i, j] corresponds to frequency i, j (with wrap-around for i > size/2)
                # Actually, fft2[i, j] is frequency i if i <= size/2, i - size if i > size/2.
                # Our G_range is [-N, N]. Size is 2N+1.
                # So G_range is centered.
                # fft2 index for frequency g is:
                # if g >= 0: idx = g
                # if g < 0: idx = g + size
                idx_i = gx if gx >= 0 else gx + size
                idx_j = gy if gy >= 0 else gy + size
                mu_ft_reordered[ix, iy] = mu_ft[idx_i, idx_j]
                
        return mu_ft_reordered.ravel()

    def compute_bands_proxy(k, mu_ft):
        """Compute eigenvalues for a given k-point."""
        kx, ky = k
        # H_{GG'} = mu(G-G') * (k+G')^2
        # Note: k is in units of 2*pi/a? Or just dimensionless 0..1?
        # Problem statement: "30 wave vectors covering the boundary and interior...".
        # Usually k is in reciprocal lattice units.
        # Let's assume k = (kx, ky) where x in [0, 1).
        # G vectors are integers (n, m).
        # (k+G)^2 = (kx + gx)^2 + (ky + gy)^2.
        
        k_plus_G = k + G_vectors
        k_plus_G_sq = np.sum(k_plus_G**2, axis=1)
        
        # H is 121x121
        H = np.outer(mu_ft, k_plus_G_sq)
        
        # Symmetrize H to ensure Hermitian (numerical stability)
        H = (H + H.T.conj()) / 2.0
        
        # Solve eigenvalues
        # We only need the 5th smallest eigenvalue.
        # Use eigh for full spectrum as matrices are small.
        try:
            vals = np.linalg.eigvalsh(H)
            return vals
        except:
            return np.zeros(N_PW_PROXY*2+1)

    def evaluate_gap_proxy(cell):
        """Compute gap ratio for a cell using the proxy."""
        mu_ft = get_mu_fourier_proxy(cell)
        
        min_omega_5 = np.inf
        max_omega_4 = -np.inf
        
        for k in k_points:
            vals = compute_bands_proxy(k, mu_ft)
            if len(vals) < 5:
                continue
            # Sort vals (eigvalsh returns sorted)
            # omega is sqrt(lambda). We can work with lambda directly for ratio?
            # Ratio is 2*(sqrt(l5) - sqrt(l4)) / (sqrt(l5) + sqrt(l4))
            # Let's use omegas.
            omegas = np.sqrt(np.real(vals))
            
            # Ensure we are looking at the correct bands.
            # Band indices 4 and 5 (1-based) -> indices 3 and 4 (0-based)
            # However, sometimes degeneracy or band crossing makes "band 4" ambiguous at high symmetry points.
            # The evaluator takes min omega_5 and max omega_4 over the whole BZ.
            
            omega_4 = omegas[3]
            omega_5 = omegas[4]
            
            max_omega_4 = np.max([max_omega_4, omega_4])
            min_omega_5 = np.min([min_omega_5, omega_5])
            
        if min_omega_5 <= 0 or max_omega_4 < 0:
            return -1.0
            
        gap = min_omega_5 - max_omega_4
        mid = min_omega_5 + max_omega_4
        if mid == 0:
            return 0.0
        ratio = 2.0 * gap / mid
        return ratio

    # 3. Search Strategy
    # Start with best seed
    best_cell = None
    best_score = -np.inf
    
    # Evaluate seeds
    for seed in seeds:
        score = evaluate_gap_proxy(seed)
        if score > best_score:
            best_score = score
            best_cell = seed.copy()
            
    print(f"Best seed score: {best_score}")
    
    # Local Search
    # Perturb the best cell.
    # Since the cell must be symmetric (transpose and flip), we only need to define the top-left quadrant + midlines.
    # Actually, the problem says "invariant under square symmetry group... cell == cell[::-1] row-wise and column-wise and cell == its transpose".
    # This means C4 symmetry + reflections?
    # "cell == cell[::-1] row-wise" -> flip top-bottom.
    # "cell == cell[::-1] column-wise" -> flip left-right.
    # "cell == its transpose" -> flip diagonal.
    # This implies D4 symmetry.
    # We can represent the cell by its unique pixels.
    # For 32x32, the unique region is roughly 8x8 plus the midlines.
    # To simplify, let's just perturb the whole cell and then symmetrize.
    
    def symmetrize_cell(cell):
        # Apply all D4 symmetries and average (or majority vote)
        # Since it's binary, majority vote is safer? Or just force one symmetry?
        # If we enforce all, we might lose information if the input wasn't symmetric.
        # Let's enforce:
        # 1. Flip top-bottom
        # 2. Flip left-right
        # 3. Transpose
        # Actually, just forcing transpose and flips is enough if we start from a symmetric seed.
        # Let's do: cell = (cell + cell[::-1] + cell[:, ::-1] + cell.T) / 4 > 0.5
        # This projects onto the symmetric subspace.
        
        # Wait, the evaluator checks strict equality.
        # cell == cell[::-1]
        # cell == cell[:, ::-1]
        # cell == cell.T
        # If we average, we might get 0.5 values which we round to 1 or 0.
        # Rounding 0.5 -> 0 or 1?
        # Let's use: if val > 0.5: 1 else 0.
        
        sym_cell = (cell + 
                    cell[::-1, :] + 
                    cell[:, ::-1] + 
                    cell.T + 
                    cell[::-1, ::-1] + # 180 rot
                    cell.T[::-1, :] + # ?
                    cell[:, ::-1].T +
                    cell[::-1, ::-1].T) / 8.0
        return (sym_cell > 0.5).astype(np.float64)
        
    # Actually, simpler:
    # Just modify the top-left 16x16 quadrant and reflect.
    # Indices 0..15.
    # i in 0..15, j in 0..15.
    # cell[i, j] = cell[31-i, j] = cell[i, 31-j] = cell[31-i, 31-j]
    # And cell[i, j] = cell[j, i] = ...
    # So we only need to define i in 0..15, j in 0..15, with constraint i<=j? No, just define top-left and reflect.
    # Let's define the top-left 16x16 block.
    # Then:
    # cell[i, j] for i<16, j<16 is from block.
    # cell[i, j] for i<16, j>=16: j' = 31-j (0..15). cell[i, 31-j']? No.
    # Reflection about center.
    # Index 0 maps to 31.
    # So cell[i, j] = block[i, j] for i<16, j<16.
    # cell[i, 31-j] = cell[i, j] -> cell[i, j_right] = block[i, 31-j_right]?
    # Let's just use the projection method, it's safer.
    
    def project_to_symmetry(cell):
        # D4 group has 8 elements.
        # E, C4, C2, C2', Mx, My, Mx', My'
        # Transpose is Mx' (diagonal flip).
        # Let's just average all 8 transformations.
        c = cell
        c1 = c
        c2 = c.T
        c3 = c[::-1, :]
        c4 = c[:, ::-1]
        c5 = c[::-1, ::-1]
        c6 = c.T[::-1, :]
        c7 = c.T[:, ::-1]
        c8 = c.T[::-1, ::-1]
        avg = (c1+c2+c3+c4+c5+c6+c7+c8) / 8.0
        return (avg > 0.5).astype(np.float64)
        
    # Search Loop
    current_cell = best_cell
    current_score = best_score
    rng = np.random.default_rng(42)
    
    # Annealing schedule
    # Start with large perturbations, decrease over time.
    
    steps = 0
    while time.time() - start_time < search_time_limit:
        # Generate perturbation
        # Flip some random pixels in the unique region
        # Unique region: top-left 16x16
        # Actually, just flip random pixels in the whole cell and project.
        
        # Number of flips
        # Decrease over time?
        # Let's start with 5 flips, decrease to 1.
        t = (time.time() - start_time) / search_time_limit
        num_flips = np.random.exponential(1.0 + 4.0 * (1.0 - t))
        num_flips = int(np.clip(num_flips, 1, 10))
        
        new_cell = current_cell.copy()
        for _ in range(num_flips):
            i = rng.integers(0, size)
            j = rng.integers(0, size)
            new_cell[i, j] = 1.0 - new_cell[i, j]
            
        # Project to symmetry
        new_cell = project_to_symmetry(new_cell)
        
        # Evaluate
        new_score = evaluate_gap_proxy(new_cell)
        
        if new_score > current_score:
            current_score = new_score
            current_cell = new_cell
            if current_score > best_score:
                best_score = current_score
                best_cell = current_cell.copy()
                
        steps += 1
        
        # Check time
        if time.time() - start_time > search_time_limit:
            break
    print(f"Search finished. Steps: {steps}, Best Score: {best_score}")
    
    # Convert to list of lists of ints
    final_cell = [[int(x) for x in row] for row in best_cell]
    return final_cell

# EVOLVE-BLOCK-END
