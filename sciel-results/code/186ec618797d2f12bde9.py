    def add_strassen(i0, j0, k0):
        # M1
        add_term(
            [(i0*m + j0, 0, 1), ((i0+1)*m + j0+1, 0, 1)],
            [(j0*p + k0, 0, 1), (j0*p + k0+1, 0, 1)],
            [(k0*n + i0, 0, 1), ((k0+1)*n + i0+1, 0, 1)]
        )
        # M2
        add_term(
            [((i0+1)*m + j0, 0, 1), ((i0+1)*m + j0+1, 0, 1)],
            [(j0*p + k0, 0, 1)],
            [(k0*n + i0+1, 0, 1), ((k0+1)*n + i0+1, 0, -1)]
        )
        # M3
        add_term(
            [(i0*m + j0, 0, 1)],
            [(j0*p + k0+1, 0, 1), ((j0+1)*p + k0+1, 0, -1)],
            [((k0+1)*n + i0, 0, 1), ((k0+1)*n + i0+1, 0, 1)]
        )
        # M4
        add_term(
            [((i0+1)*m + j0+1, 0, 1)],
            [((j0+1)*p + k0, 0, 1), (j0*p + k0, 0, -1)],
            [(k0*n + i0, 0, 1), (k0*n + i0+1, 0, 1)]
        )
        # M5
        add_term(
            [(i0*m + j0, 0, 1), (i0*m + j0+1, 0, 1)],
            [((j0+1)*p + k0+1, 0, 1)],
            [(k0*n + i0, 0, -1), ((k0+1)*n + i0, 0, 1)]
        )
        # M6
        add_term(
            [((i0+1)*m + j0, 0, 1), (i0*m + j0, 0, -1)],
            [(j0*p + k0, 0, 1), (j0*p + k0+1, 0, 1)],
            [((k0+1)*n + i0+1, 0, 1)]
        )
        # M7
        add_term(
            [(i0*m + j0+1, 0, 1), ((i0+1)*m + j0+1, 0, -1)],
            [((j0+1)*p + k0, 0, 1), ((j0+1)*p + k0+1, 0, 1)],
            [(k0*n + i0, 0, 1)]
        )

