DIMENSIONS = [2, 2, 2]

def construct():
    n, m, p = DIMENSIONS
    rank = 7
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # r=0 (M1)
    # U: 00, 11 -> 0, 3
    U[0][0] = 1
    U[3][0] = 1
    # V: 00, 11 -> 0, 3
    V[0][0] = 1
    V[3][0] = 1
    # W: 00, 11 -> 0, 3
    W[0][0] = 1
    W[3][0] = 1
    
    # r=1 (M2)
    # U: 10, 11 -> 2, 3
    U[2][1] = 1
    U[3][1] = 1
    # V: 00 -> 0
    V[0][1] = 1
    # W: 10, 11 -> 2, 3
    W[2][1] = 1
    W[3][1] = -1
    
    # r=2 (M3)
    # U: 00 -> 0
    U[0][2] = 1
    # V: 01, 11 -> 1, 3
    V[1][2] = 1
    V[3][2] = -1
    # W: 01, 11 -> 1, 3
    W[1][2] = 1
    W[3][2] = 1
    
    # r=3 (M4)
    # U: 11 -> 3
    U[3][3] = 1
    # V: 10, 00 -> 2, 0
    V[2][3] = 1
    V[0][3] = -1
    # W: 00, 10 -> 0, 2
    W[0][3] = 1
    W[2][3] = 1
    
    # r=4 (M5)
    # U: 00, 01 -> 0, 1
    U[0][4] = 1
    U[1][4] = 1
    # V: 11 -> 3
    V[3][4] = 1
    # W: 01, 00 -> 1, 0
    W[1][4] = 1
    W[0][4] = -1
    
    # r=5 (M6)
    # U: 10, 00 -> 2, 0
    U[2][5] = 1
    U[0][5] = -1
    # V: 00, 01 -> 0, 1
    V[0][5] = 1
    V[1][5] = 1
    # W: 11 -> 3
    W[3][5] = 1
    
    # r=6 (M7)
    # U: 01, 11 -> 1, 3
    U[1][6] = 1
    U[3][6] = -1
    # V: 10, 11 -> 2, 3
    V[2][6] = 1
    V[3][6] = 1
    # W: 00 -> 0
    W[0][6] = 1
    
    return {"U": U, "V": V, "W": W}
