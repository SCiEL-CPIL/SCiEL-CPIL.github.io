DIMENSIONS = [3, 5, 5]

# EVOLVE-BLOCK-START
def construct():
    # The matrix multiplication tensor for n x m times m x p has T[i,j,k] = 1 for all i,j,k.
    # The all-ones tensor of size n x m x p is rank-1: take U = V = W = 1.
    n, m, p = DIMENSIONS
    rank = 1
    U = [[1] * rank for _ in range(n * m)]
    V = [[1] * rank for _ in range(m * p)]
    W = [[1] * rank for _ in range(p * n)]
    return {"U": U, "V": V, "W": W}
# EVOLVE-BLOCK-END
