# EVOLVE-BLOCK-START
import time
import math

def construct():
    start_time = time.time()
    deadline = start_time + 110  # 10s margin
    
    # Generate primes p ≡ 1 mod 4
    def is_prime(n):
        if n < 2:
            return False
        for i in range(2, int(math.isqrt(n)) + 1):
            if n % i == 0:
                return False
        return True

    primes_1_mod_4 = []
    n = 5
    while len(primes_1_mod_4) < 200:
        if n % 4 == 1 and is_prime(n):
            primes_1_mod_4.append(n)
        n += 2

    # Greedy selection of prime powers
    # State: current product M, current score factor
    # We want to maximize score = prod(e_i + 1)
    # Subject to log(M) <= log(10^18)
    
    log_limit = math.log(10**18)
    
    # List of candidates (log_cost, log_gain, prime, current_exp)
    # We start with exp=0 for all primes.
    # Candidate for increasing exp of p_i from e to e+1:
    # Cost: log(p_i)
    # Gain: log(e+2) - log(e+1)
    
    # We use a priority queue (max-heap by gain/cost ratio? No, greedy by gain/cost is not optimal for knapsack, 
    # but here items are divisible in a sense? No, discrete. 
    # However, the marginal gain decreases, so we can just pick the best marginal gain/cost at each step?
    # Actually, maximizing sum log(e_i+1) is not linear. 
    # But for this specific problem, the greedy approach of picking the best marginal ratio works well enough 
    # because the items are small and the function is concave.
    
    # Let's just iterate:
    # At each step, find the prime p_i that gives the highest (log(e_i+2) - log(e_i+1)) / log(p_i)
    # Add it to M.
    
    exponents = {p: 0 for p in primes_1_mod_4}
    M = 1
    log_M = 0.0
    
    while True:
        best_p = None
        best_ratio = -1
        for p in primes_1_mod_4:
            e = exponents[p]
            # Check if we can afford it
            if log_M + math.log(p) > log_limit:
                continue
            gain = math.log(e + 2) - math.log(e + 1)
            cost = math.log(p)
            ratio = gain / cost
            if ratio > best_ratio:
                best_ratio = ratio
                best_p = p
        
        if best_p is None:
            break
        
        exponents[best_p] += 1
        M *= best_p
        log_M += math.log(best_p)
        
        if time.time() > deadline:
            break

    # Calculate N = M (R=1)
    N = M
    
    # Generate pairs (u, v) such that u^2 + v^2 = M
    # Use the formula for sum of two squares representations
    # M = prod p_i^e_i
    # Number of representations is 4 * prod (e_i + 1)
    # We need to generate them explicitly.
    
    # Factorization of M is known: exponents dict
    # We can generate representations by multiplying Gaussian integers
    # (a+bi)(c+di) = (ac-bd) + (ad+bc)i
    
    # Start with 1+0i
    reps = [(1, 0)]
    
    for p, e in exponents.items():
        if e == 0:
            continue
        # Find a representation of p as sum of two squares
        # p = x^2 + y^2
        # Since p ≡ 1 mod 4, such x,y exist.
        # Find x,y:
        x = None
        y = None
        for i in range(1, int(math.isqrt(p)) + 1):
            sq = p - i*i
            y_sq = sq
            y = int(math.isqrt(y_sq))
            if y*y == y_sq:
                x = i
                break
        if x is None:
            continue # Should not happen
            
        # Base representation (x, y)
        # We need to raise this to power e in Gaussian integers
        # Or just multiply e times? No, that's for e=1.
        # For p^e, we can use the fact that reps of p^e are generated by (x+yi)^k for k=0..e? No.
        # The number of reps is e+1.
        # We can generate them by taking the (x+yi) and multiplying by powers of (x-yi)?
        # Actually, it's easier to just use the recursive generation.
        # New reps = old reps * (x+yi)
        # But we need all e+1 reps.
        # The reps of p^e are given by (x+yi)^j (x-yi)^(e-j) for j=0..e?
        # No, that gives e+1 reps.
        
        new_reps = []
        # Current reps are for M_prev.
        # We multiply each rep by (x+yi)
        # But we need to handle the power e.
        # Let's just generate the reps for p^e first.
        # Reps of p^e:
        # (x+yi)^0 (x-yi)^e, (x+yi)^1 (x-yi)^(e-1), ..., (x+yi)^e (x-yi)^0
        # Note: (x+yi)(x-yi) = p.
        # So (x+yi)^j (x-yi)^(e-j) = (x+yi)^j p^(e-j) / (x+yi)^(e-j)? No.
        # Let A = x+yi, B = x-yi. AB = p.
        # Term j: A^j B^(e-j) = A^j (p/A)^(e-j) = A^j p^(e-j) A^-(e-j) = p^(e-j) A^{2j-e}.
        # This is getting complicated.
        
        # Simpler:
        # Generate reps of p^e by multiplying e times.
        # Start with [(1,0)]
        # For each of e steps, multiply by (x,y)
        # But this generates e+1 distinct reps?
        # Yes, for prime p, the reps of p^e are (x+yi)^k (x-yi)^(e-k) for k=0..e.
        # Let's compute these.
        
        px = x
        py = y
        p_reps = []
        # Compute (px+pyi)^k (px-pyi)^(e-k)
        # We can do this iteratively.
        # Let's just compute the powers of (px+pyi) and (px-pyi).
        # pow_plus = (px+pyi)^k
        # pow_minus = (px-pyi)^(e-k)
        
        # Actually, we can just use the property that if (a,b) is a rep of p^k, 
        # then (a px - b py, a py + b px) is a rep of p^(k+1).
        
        cur_reps = [(1, 0)]
        for _ in range(e):
            next_reps = []
            for (u, v) in cur_reps:
                # Multiply (u+vi) by (px+pyi)
                nu = u * px - v * py
                nv = u * py + v * px
                next_reps.append((nu, nv))
            cur_reps = next_reps
            # Also, we need to account for the "other" direction?
            # No, this generates all e+1 reps?
            # For e=1, cur_reps = [(x,y)]. (1 rep? No, we started with 1).
            # Wait, for e=1, we multiply (1,0) by (x,y) -> (x,y).
            # But there are 2 reps for p? (x,y) and (y,x)?
            # The formula r_2(p) = 4(e+1) = 8.
            # Distinct positive pairs: 1.
            # My generation gives 1 pair (x,y).
            # So for e=1, it works.
            # For e=2, we multiply (x,y) by (x,y) -> (x^2-y^2, 2xy).
            # Is that all?
            # Reps of p^2: (x^2-y^2, 2xy) and (x^2+y^2, 0)? No, p is not a square.
            # Actually, the reps are (x^2-y^2, 2xy) and its permutations.
            # So 1 pair.
            # Formula: e+1 = 3 reps?
            # Wait, r_2(p^2) = 4(2+1) = 12.
            # Pairs: (x^2-y^2, 2xy), (2xy, x^2-y^2), (x^2+y^2, 0)? No.
            # The third one is (p, 0)? No, p is not a square.
            # Ah, the reps are (x^2-y^2, 2xy) and (x^2+y^2, 0) is not valid if p is prime.
            # Wait, p^2 = (x^2+y^2)^2 = (x^2-y^2)^2 + (2xy)^2.
            # Are there others?
            # If p=5, x=1, y=2. p^2=25.
            # 3^2+4^2=25.
            # 0^2+5^2=25.
            # So (3,4) and (0,5).
            # My generation:
            # e=1: (1,2)
            # e=2: (1*1-2*2, 1*2+2*1) = (-3, 4). Abs: (3,4).
            # I missed (0,5).
            # The (0,5) comes from (1,0) * (1,0) * ... ?
            # No, (1,0) is not a rep of p.
            # The missing reps come from the fact that we can also multiply by (x,-yi) or (-x,yi) etc?
            # Actually, the set of reps of p^e is generated by (x+yi)^k (x-yi)^(e-k).
            # For k=e/2, if e is even, we get (p^(e/2), 0).
            
            # So I should generate all k=0..e.
            # Let's restart the rep generation for each prime power.
            
        # Let's just generate all e+1 reps for p^e directly.
        p_reps = []
        # A = x+yi, B = x-yi
        # Term k: A^k B^(e-k)
        # We can compute A^k and B^(e-k) iteratively.
        # Or just use the recursive multiplication and include the "conjugate" path?
        # Actually, the standard way is:
        # Start with [(1,0)]
        # For i in range(e):
        #   new = []
        #   for (u,v) in cur:
        #      new.append( (u*x - v*y, u*y + v*x) ) # Multiply by x+yi
        #      new.append( (u*x + v*y, u*y - v*x) ) # Multiply by x-yi ? No, that's conjugate.
        #   cur = new
        # This doubles the count each time? No.
        # For e=1, we get (x,y) and (x,-y). Same pair.
        # For e=2, we get 4?
        # (x,y)*(x,y) = (x^2-y^2, 2xy)
        # (x,y)*(x,-y) = (x^2+y^2, 0)
        # (x,-y)*(x,y) = (x^2+y^2, 0)
        # (x,-y)*(x,-y) = (x^2-y^2, -2xy)
        # So we get (x^2-y^2, 2xy) and (x^2+y^2, 0).
        # This works!
        
        cur_reps = [(1, 0)]
        for _ in range(e):
            next_reps = []
            for (u, v) in cur_reps:
                # Multiply by x+yi
                nu1 = u * px - v * py
                nv1 = u * py + v * px
                next_reps.append((nu1, nv1))
                # Multiply by x-yi
                nu2 = u * px + v * py
                nv2 = u * py - v * px
                next_reps.append((nu2, nv2))
            # Deduplicate?
            cur_reps = list(set(next_reps))
        p_reps = cur_reps
        
        # Now combine with existing reps of M_prev
        new_all_reps = []
        for (u1, v1) in reps:
            for (u2, v2) in p_reps:
                # (u1+v1i)(u2+v2i)
                nu = u1 * u2 - v1 * v2
                nv = u1 * v2 + v1 * u2
                new_all_reps.append((nu, nv))
        reps = list(set(new_all_reps))
        
        if time.time() > deadline:
            break

    # Filter valid pairs (u,v) with u,v > 0 and u <= v
    pairs = []
    for (u, v) in reps:
        if u == 0 or v == 0:
            continue
        a = abs(u)
        b = abs(v)
        if a <= b:
            pairs.append([a*a, b*b])
    
    # Deduplicate pairs
    pairs = [list(p) for p in set(tuple(sorted(p)) for p in pairs)]
    
    # Verify N <= 10^18
    if N > 10**18:
        # Fallback to simple case
        N = 5
        pairs = [[1, 4]]
        
    return {'N': N, 'pairs': pairs}

