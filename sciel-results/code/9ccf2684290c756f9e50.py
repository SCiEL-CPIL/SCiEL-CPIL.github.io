import time

def construct():
    # The task asks for A_2(18, 6), the maximum size of a binary code of length 18
    # with minimum distance 6.
    # It is known that A_2(18, 6) = 512.
    # This bound is achieved by the extended quadratic-residue code of length 18,
    # which is a linear [18, 9, 6] code.
    #
    # Strategy:
    # Instead of searching for codewords (which is hard to scale to 512 efficiently
    # with simple greedy methods in Python within time limits, or might get stuck
    # in local optima if not guided correctly), we directly construct this specific
    # linear code.
    #
    # The [18, 9, 6] code can be constructed from the [17, 8, 5] quadratic residue
    # code over GF(17) by adding a parity check bit (extension).
    #
    # Construction of the [17, 8, 5] QR code:
    # The generator matrix G_17 is 8x17.
    # The columns correspond to elements of GF(17).
    # A standard construction uses the basis vectors of the dual code or direct
    # polynomial representation.
    #
    # Let's use the polynomial definition.
    # The QR code C_17 is generated by polynomials of degree < 8 whose roots are
    # the quadratic non-residues modulo 17? Or is it the dual?
    # The [17, 8, 5] code is the QR code. Its dual is the [17, 9, 5] code.
    # Actually, the [17, 8, 5] code is generated by the cyclic shifts of a specific
    # generator polynomial.
    #
    # Generator polynomial for the [17, 8, 5] QR code:
    # The roots are the quadratic non-residues modulo 17.
    # Quadratic residues mod 17: 1, 2, 4, 8, 16, 15, 13, 9 (squares of 1..8)
    # 1^2=1, 2^2=4, 3^2=9, 4^2=16, 5^2=8, 6^2=2, 7^2=15, 8^2=13.
    # Residues: {1, 2, 4, 8, 9, 13, 15, 16}
    # Non-residues: {3, 5, 6, 7, 10, 11, 12, 14}
    #
    # The generator polynomial g(x) has roots alpha^i for i in Non-Residues.
    # Let alpha be a primitive element in GF(2^4) or similar? No, this is a binary code.
    # The construction is over GF(2). The length 17 is prime.
    #
    # Alternative construction method:
    # The generator matrix rows are the first 8 rows of the parity check matrix of the dual?
    #
    # Let's use a known explicit generator matrix for the [18, 9, 6] extended QR code.
    # The code is linear. We just need a basis of 9 linearly independent vectors of length 18
    # such that all 2^9 = 512 linear combinations have weight >= 6.
    #
    # We can generate the [17, 8, 5] code and extend it.
    # The [17, 8, 5] code is cyclic.
    # Generator polynomial g(x) in GF(2)[x] / (x^17 - 1).
    # g(x) = (x - alpha^3)(x - alpha^5)(x - alpha^6)(x - alpha^7)(x - alpha^10)(x - alpha^11)(x - alpha^12)(x - alpha^14)
    # where alpha is a primitive 17th root of unity in an extension field of GF(2).
    # The order of 2 modulo 17 is 8 (2^4=16=-1, 2^8=1).
    # So we work in GF(2^8).
    #
    # Let's implement the polynomial multiplication to get g(x).
    
    # Field GF(2^8) with primitive polynomial x^8 + x^4 + x^3 + x^2 + 1 (0x11d) is common,
    # but we need a primitive 17th root of unity.
    # Since 17 divides 2^8 - 1 = 255, the roots exist in GF(2^8).
    
    # Let's pick a primitive element beta in GF(2^8).
    # We need beta^17 = 1 and beta != 1.
    # Let's use the polynomial representation.
    # Represent field elements as integers 0-255.
    # Primitive polynomial for GF(2^8): p(x) = x^8 + x^4 + x^3 + x^2 + 1.
    # This is 0x11D.
    
    def gf28_mul(a, b):
        res = 0
        while b:
            if b & 1:
                res ^= a
            b >>= 1
            a <<= 1
            if a & 0x100:
                a ^= 0x11D # x^8 + x^4 + x^3 + x^2 + 1
        return res

    def gf28_pow(a, e):
        res = 1
        while e:
            if e & 1:
                res = gf28_mul(res, a)
            a = gf28_mul(a, a)
            e >>= 1
        return res

    # Find a primitive 17th root of unity.
    # We need an element of order 17.
    # Let's try small integers as base.
    # Order of 2 in GF(2^8) is 255.
    # Let's find an element of order 17.
    # If g is a primitive element (order 255), then g^(255/17) = g^15 has order 17.
    # We need to find a primitive element g for GF(2^8) with 0x11D.
    # 3 is often primitive. Let's check order of 3.
    # 3^1 = 3
    # 3^2 = 9
    # 3^3 = 27
    # 3^4 = 81
    # 3^5 = 3^4*3 = 81*3 = 243 = 0xF3. 0xF3 ^ 0x11D = 0x6E (110)
    # This is tedious. Let's just iterate candidates for alpha such that alpha^17 = 1.
    
    alpha = None
    for candidate in range(2, 256):
        if gf28_pow(candidate, 17) == 1 and candidate != 1:
            # Check if it's not a smaller order (1, 5, etc? 17 is prime, so order is 1 or 17)
            # Since candidate != 1, order must be 17.
            alpha = candidate
            break
    
    if alpha is None:
        # Fallback if something went wrong with field arithmetic
        return [0] * 32 # Should not happen

    # Now construct g(x) = prod_{i in non_residues} (x - alpha^i)
    # Non-residues mod 17: 3, 5, 6, 7, 10, 11, 12, 14
    non_residues = [3, 5, 6, 7, 10, 11, 12, 14]
    
    # g(x) is a polynomial of degree 8 over GF(2).
    # Represent polynomial as list of coefficients [c0, c1, ..., c8] where c0 is constant term.
    # Initially g(x) = 1
    g_coeffs = [1]
    
    for i in non_residues:
        root = gf28_pow(alpha, i)
        # Multiply current g(x) by (x - root) which is (x + root) in GF(2)
        # (x + root) = [root, 1]
        new_g = [0] * (len(g_coeffs) + 1)
        for j in range(len(g_coeffs)):
            # Multiply by root (shift 0)
            new_g[j] ^= gf28_mul(g_coeffs[j], root)
            # Multiply by x (shift 1)
            new_g[j+1] ^= g_coeffs[j]
        g_coeffs = new_g
    
    # g_coeffs should be length 9 (degree 8).
    # The coefficients are in GF(2^8).
    # However, the QR code is a binary code. The generator matrix is formed by taking
    # the real part (or trace) of the coefficients?
    # Actually, the standard construction of the QR code uses the fact that the
    # generator polynomial has coefficients in GF(2) if we choose the roots correctly?
    # No, the roots are in GF(2^8). The coefficients of g(x) will be in GF(2^8).
    # But wait, the QR code is defined over GF(2).
    # The generator polynomial g(x) for the cyclic code over GF(2) must have coefficients in GF(2).
    # This requires that the set of roots is closed under the Frobenius automorphism (squaring).
    # The non-residues {3, 5, 6, 7, 10, 11, 12, 14} are closed under multiplication by 2 mod 17?
    # 3*2=6 (in set)
    # 6*2=12 (in set)
    # 12*2=24=7 (in set)
    # 7*2=14 (in set)
    # 14*2=28=11 (in set)
    # 11*2=22=5 (in set)
    # 5*2=10 (in set)
    # 10*2=20=3 (in set)
    # Yes, it is a cyclotomic coset.
    # Therefore, the product (x - alpha^3)(x - alpha^6)... will have coefficients in GF(2).
    # So g_coeffs should effectively be 0 or 1.
    
    # Let's verify they are 0 or 1.
    # If not, there's an error in my understanding or implementation.
    # Let's force them to be binary by taking the trace? No, they should be exactly 0 or 1.
    # Let's check the coefficients.
    
    # Construct the 8x17 generator matrix G_17 for the [17, 8, 5] code.
    # The rows are the cyclic shifts of the generator vector.
    # The generator vector is the coefficients of g(x) reversed?
    # g(x) = g0 + g1 x + ... + g8 x^8.
    # The code word corresponding to 1 is g(x) mod (x^17-1).
    # Since deg(g) < 17, it's just the coefficients.
    # The vector is [g0, g1, ..., g8, 0, ..., 0].
    # Wait, standard cyclic code representation:
    # If g(x) = g0 + g1 x + ... + g8 x^8, then the codeword for message 1 is g(x).
    # The vector is (g0, g1, ..., g8, 0, ..., 0).
    # The next shift is x*g(x) mod (x^17-1) = g8 x^9 + ... + g0 x.
    # Vector: (0, g0, g1, ..., g8, 0, ..., 0).
    
    # Let's build the 8x17 matrix.
    G_17 = []
    # Extract binary coefficients
    bin_g = [1 if c == 1 else 0 for c in g_coeffs]
    # Ensure length 8? g_coeffs is length 9 (degree 8).
    # The generator polynomial has degree 8. So there are 9 coefficients.
    # But the code dimension is 8.
    # The generator matrix has 8 rows.
    # The rows are generated by the cyclic shifts of the generator polynomial coefficients.
    # The generator polynomial is of degree n-k = 17-8 = 9?
    # Wait. Dimension k=8. Length n=17.
    # Degree of g(x) is n-k = 9.
    # My non-residues count is 8.
    # The roots are 8 elements. So degree is 8.
    # If degree is 8, then n-k=8 => k=9.
    # But the QR code [17, 8, 5] has k=8.
    # The dual QR code is [17, 9, 5].
    # Which one is the QR code?
    # The "Quadratic Residue Code" usually refers to the code with dimension (p-1)/2 = 8.
    # Its generator polynomial has roots the quadratic non-residues.
    # Number of non-residues is (17-1)/2 = 8.
    # So degree is 8.
    # Then k = 17 - 8 = 9.
    # So the code generated by non-residues is [17, 9, 5].
    # The dual code is [17, 8, 5].
    # The extended code of [17, 9, 5] is [18, 9, 6].
    # The extended code of [17, 8, 5] is [18, 8, 6]? No, distance increases by 1 only if all weights are odd.
    # In [17, 9, 5], are all weights odd?
    # For p=17, the QR code has minimum distance 5.
    # The extended code has minimum distance 6.
    # So we want the [17, 9, 5] code extended to [18, 9, 6].
    # This has size 2^9 = 512. This matches the target.
    
    # So we proceed with the generator of the [17, 9, 5] code.
    # The generator vector is the coefficients of g(x) of degree 8.
    # g_coeffs has 9 elements (indices 0..8).
    # Let's create the 9x17 generator matrix for the [17, 9, 5] code.
    # Rows are cyclic shifts of the generator polynomial coefficients.
    # Generator polynomial coeffs: c0...c8.
    # Row 0: c0, c1, ..., c8, 0, ..., 0 (length 17)
    # Row 1: 0, c0, c1, ..., c8, 0, ..., 0
    # ...
    # Row 8: 0, ..., 0, c0, c1, ..., c8
    
    G_17 = []
    base_vec = bin_g + [0] * (17 - len(bin_g))
    for i in range(9):
        row = [0] * 17
        for j in range(9):
            idx = (i + j) % 17
            row[idx] = base_vec[j]
        G_17.append(row)
        
    # Now extend to length 18 by adding a parity bit.
    # The parity bit is the sum of the first 17 bits (mod 2).
    # This ensures the weight is even.
    # Since min weight in [17, 9, 5] is 5 (odd), the extended weight will be 6.
    # If weight was 7, extended is 8. Etc.
    # Min distance becomes 6.
    
    G_18 = []
    for row in G_17:
        parity = sum(row) % 2
        new_row = row + [parity]
        G_18.append(new_row)
        
    # Now generate all 512 codewords.
    # The code is linear. We iterate over all 9-bit messages.
    codewords = []
    for msg in range(512):
        word = [0] * 18
        for i in range(9):
            if (msg >> i) & 1:
                # Add row i
                for j in range(18):
                    word[j] ^= G_18[i][j]
        # Convert to integer
        val = 0
        for j in range(18):
            if word[j]:
                val |= (1 << j)
        codewords.append(val)
        
    return codewords

if __name__ == "__main__":
    words = construct()
    print(f"Generated {len(words)} codewords")
    # Quick check
    valid = True
    for i in range(len(words)):
        for j in range(i+1, len(words)):
            if (words[i] ^ words[j]).bit_count() < 6:
                valid = False
                break
        if not valid:
            break
    print(f"Valid: {valid}")
