"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import math
import time
import random
import numpy as np

def design(problem):
    """
    Design a 32x32 unit cell using stochastic pixel-space search with symmetry enforcement.
    """
    start_time = time.time()
    deadline = start_time + 220.0  # 10s safety margin
    
    size = problem.get("pixels", 32)
    eps_high = problem.get("eps_high", 12.0)
    eps_low = problem.get("eps_low", 1.0)
    
    # Symmetry constraints:
    # cell == cell[::-1] row-wise and column-wise and cell == its transpose
    # This implies the cell is invariant under:
    # 1. Vertical flip: cell[i][j] == cell[size-1-i][j]
    # 2. Horizontal flip: cell[i][j] == cell[i][size-1-j]
    # 3. Transpose: cell[i][j] == cell[j][i]
    
    # To enforce symmetry, we can define a "fundamental domain" of pixels.
    # Due to the symmetries, the entire 32x32 grid is determined by a subset.
    # Let's identify the independent pixels.
    # For i, j in [0, 31]:
    # The orbit of (i, j) under the group generated by (i,j)->(31-i,j), (i,j)->(i,31-j), (i,j)->(j,i)
    # has size up to 8.
    
    # We can just generate a random symmetric cell by choosing values for the independent pixels.
    # Independent pixels are those where i <= 15 and j <= 15? Not exactly.
    # Let's just enforce symmetry after every mutation.
    
    def enforce_symmetry(cell):
        """
        Enforce the symmetry constraints on the cell.
        cell is a 2D list of 0s and 1s.
        """
        # We need to ensure:
        # cell[i][j] == cell[31-i][j]
        # cell[i][j] == cell[i][31-j]
        # cell[i][j] == cell[j][i]
        
        # This can be done by averaging or majority vote, but since it's binary,
        # we can just pick one representative from each orbit and assign it to all.
        # To be safe and fast, we can just iterate and set values.
        # However, modifying in place can be tricky if we overwrite values we haven't processed yet.
        # Better: create a new cell.
        
        new_cell = [[0 for _ in range(size)] for _ in range(size)]
        
        # To ensure consistency, we can iterate over all pixels and if it's part of an orbit,
        # we need to make sure all pixels in the orbit have the same value.
        # Since we are starting from a potentially asymmetric cell (after mutation),
        # we can just pick the value from the "first" pixel in the orbit (e.g., lexicographically smallest)
        # and apply it to all.
        
        # Let's precompute the orbits or just use a visited set.
        visited = [[False for _ in range(size)] for _ in range(size)]
        
        for i in range(size):
            for j in range(size):
                if not visited[i][j]:
                    # Find all pixels in the orbit of (i, j)
                    orbit = set()
                    queue = [(i, j)]
                    while queue:
                        x, y = queue.pop()
                        if not visited[x][y]:
                            visited[x][y] = True
                            orbit.add((x, y))
                            # Add neighbors in the orbit
                            # (31-x, y)
                            if not visited[31-x][y]:
                                queue.append((31-x, y))
                            # (x, 31-y)
                            if not visited[x][31-y]:
                                queue.append((x, 31-y))
                            # (y, x)
                            if not visited[y][x]:
                                queue.append((y, x))
                    
                    # Pick a value for this orbit.
                    # To preserve some information, we can take the majority vote or just the first one.
                    # Let's take the value of the lexicographically smallest pixel in the orbit.
                    min_pixel = min(orbit)
                    val = cell[min_pixel[0]][min_pixel[1]]
                    
                    for (x, y) in orbit:
                        new_cell[x][y] = val
                        
        return new_cell

    def compute_gap_ratio_fast(cell):
        """
        Approximate band structure calculation for fast evaluation.
        Uses a smaller number of plane waves for speed.
        """
        # This is a simplified version of the exact solver.
        # For speed, we use fewer plane waves and fewer k-points.
        
        # Convert cell to numpy array
        eps_map = np.array(cell, dtype=float)
        eps_map = np.where(eps_map == 1, eps_high, eps_low)
        
        # Compute 1/eps
        inv_eps_map = 1.0 / eps_map
        
        # Fourier coefficients of 1/eps
        # We need the coefficients for the plane waves.
        # Let's use a small set of G vectors.
        # For a 32x32 grid, the fundamental frequency is 2*pi/32 = pi/16.
        # Let's use a 5x5 or 7x7 set of G vectors.
        N_g = 3 # 7x7 G vectors
        g_max = N_g * 2 * np.pi / size
        
        G_vectors = []
        for gx in range(-N_g, N_g+1):
            for gy in range(-N_g, N_g+1):
                G_vectors.append((gx * 2 * np.pi / size, gy * 2 * np.pi / size))
        
        num_g = len(G_vectors)
        
        # Compute Fourier coefficients of inv_eps
        # C_G = sum_{x,y} inv_eps(x,y) exp(-i G . r)
        # Using FFT for speed? Or direct sum since N_g is small.
        # Direct sum is O(N_g * N_pixels) which is 49 * 1024 ~ 50k ops. Very fast.
        
        x_coords = (np.arange(size) + 0.5) / size - 0.5
        y_coords = (np.arange(size) + 0.5) / size - 0.5
        X, Y = np.meshgrid(x_coords, y_coords, indexing='ij')
        
        C_G = np.zeros(num_g, dtype=complex)
        for idx, (gx, gy) in enumerate(G_vectors):
            # G . r = gx * x + gy * y
            phase = np.exp(-1j * (gx * X + gy * Y))
            C_G[idx] = np.sum(inv_eps_map * phase) / (size * size)
        
        # Build the matrix for a given k-point
        # H = (k+G) . (k+G') * C_{G-G'}
        # For TM polarization, the matrix elements are:
        # H_{GG'} = (k+G) . (k+G') * C_{G-G'}
        # where C_{G-G'} is the Fourier coefficient of 1/eps.
        
        def get_C(diff_g_idx1, diff_g_idx2):
            # Find index of G1 - G2 in G_vectors
            G1 = G_vectors[diff_g_idx1]
            G2 = G_vectors[diff_g_idx2]
            diff_G = (G1[0] - G2[0], G1[1] - G2[1])
            # Find if diff_G is in G_vectors
            # Since G_vectors is symmetric, it should be there.
            try:
                return C_G[G_vectors.index(diff_G)]
            except ValueError:
                return 0.0
        
        # To speed up, precompute the C_G matrix
        C_mat = np.zeros((num_g, num_g), dtype=complex)
        for i in range(num_g):
            for j in range(num_g):
                C_mat[i, j] = get_C(i, j)
        
        # Evaluate at a few k-points in the irreducible BZ
        # Irreducible BZ of square lattice: 0 <= kx <= ky, kx, ky >= 0, kx + ky <= pi/a
        # Let's sample a few points: (0,0), (pi/2a, 0), (pi/2a, pi/2a), (pi/4a, pi/4a)
        k_points = [
            (0.0, 0.0),
            (np.pi / size, 0.0),
            (np.pi / size, np.pi / size),
            (np.pi / (2*size), np.pi / (2*size))
        ]
        
        max_omega_4 = 0.0
        min_omega_5 = float('inf')
        
        for kx, ky in k_points:
            # Build Hamiltonian matrix
            H = np.zeros((num_g, num_g), dtype=complex)
            for i in range(num_g):
                Gx_i, Gy_i = G_vectors[i]
                kx_i, ky_i = kx + Gx_i, ky + Gy_i
                for j in range(num_g):
                    Gx_j, Gy_j = G_vectors[j]
                    kx_j, ky_j = kx + Gx_j, ky + Gy_j
                    # (k+G_i) . (k+G_j)
                    dot = kx_i * kx_j + ky_i * ky_j
                    H[i, j] = dot * C_mat[i, j]
            
            # Solve eigenvalue problem
            # H is Hermitian
            eigenvalues = np.linalg.eigvalsh(H)
            eigenvalues = np.sort(eigenvalues.real)
            
            # The eigenvalues are proportional to omega^2
            # We need bands 4 and 5 (indices 3 and 4)
            if len(eigenvalues) >= 5:
                omega_4 = np.sqrt(eigenvalues[3])
                omega_5 = np.sqrt(eigenvalues[4])
                
                if omega_4 > max_omega_4:
                    max_omega_4 = omega_4
                if omega_5 < min_omega_5:
                    min_omega_5 = omega_5
        
        if min_omega_5 == float('inf'):
            return 0.0
            
        gap = min_omega_5 - max_omega_4
        midgap = (min_omega_5 + max_omega_4) / 2.0
        
        if midgap == 0:
            return 0.0
            
        return 2 * gap / midgap

    # Initial cell: random symmetric
    cell = [[random.randint(0, 1) for _ in range(size)] for _ in range(size)]
    cell = enforce_symmetry(cell)
    
    best_cell = [row[:] for row in cell]
    best_score = compute_gap_ratio_fast(best_cell)
    
    # Stochastic search
    current_temp = 1.0
    cooling_rate = 0.95
    
    while time.time() < deadline:
        # Generate a new candidate by flipping a few random pixels
        new_cell = [row[:] for row in cell]
        
        # Flip 1-3 random pixels
        num_flips = random.randint(1, 3)
        for _ in range(num_flips):
            i = random.randint(0, size - 1)
            j = random.randint(0, size - 1)
            new_cell[i][j] = 1 - new_cell[i][j]
            
        # Enforce symmetry
        new_cell = enforce_symmetry(new_cell)
        
        # Evaluate
        new_score = compute_gap_ratio_fast(new_cell)
        
        # Acceptance criterion
        if new_score > best_score:
            best_score = new_score
            best_cell = [row[:] for row in new_cell]
            cell = new_cell
        else:
            # Accept with probability exp((new_score - best_score) / temp)
            delta = new_score - best_score
            if random.random() < math.exp(delta / current_temp):
                cell = new_cell
                
        current_temp *= cooling_rate
        
        # Occasionally restart with a new random cell to escape local minima
        if random.random() < 0.01:
            cell = [[random.randint(0, 1) for _ in range(size)] for _ in range(size)]
            cell = enforce_symmetry(cell)
            current_temp = 1.0

    return best_cell
# EVOLVE-BLOCK-END
