import itertools
import random
import time

def construct():
    n = 16
    all_triples = list(itertools.combinations(range(n), 3))
    triple_to_idx = {t: i for i, t in enumerate(all_triples)}
    num_triples = len(all_triples)
    
    # Precompute all K(2,2,2)s
    # A K(2,2,2) is defined by 6 distinct points and a partition into 3 pairs.
    # We generate all 6-subsets, then all 15 partitions.
    k_list = []
    triple_to_ks = [[] for _ in range(num_triples)]
    
    # Generate all 6-subsets
    for subset in itertools.combinations(range(n), 6):
        # Generate all 15 pairings of 6 items
        # Items: 0,1,2,3,4,5
        # Pairings can be generated by fixing pair for 0, then pair for smallest remaining, etc.
        # Or just use a known list of 15 perfect matchings on K6.
        # Matchings on 6 vertices:
        # (0,1)(2,3)(4,5), (0,1)(2,4)(3,5), ...
        # There are 15.
        matchings = [
            ((0,1),(2,3),(4,5)),
            ((0,1),(2,4),(3,5)),
            ((0,1),(2,5),(3,4)),
            ((0,2),(1,3),(4,5)),
            ((0,2),(1,4),(3,5)),
            ((0,2),(1,5),(3,4)),
            ((0,3),(1,2),(4,5)),
            ((0,3),(1,4),(2,5)),
            ((0,3),(1,5),(2,4)),
            ((0,4),(1,2),(3,5)),
            ((0,4),(1,3),(2,5)),
            ((0,4),(1,5),(2,3)),
            ((0,5),(1,2),(3,4)),
            ((0,5),(1,3),(2,4)),
            ((0,5),(1,4),(2,3))
        ]
        
        for m in matchings:
            # Map indices 0..5 to actual points in subset
            p0, p1, p2, p3, p4, p5 = subset
            # The pairs are (subset[m[0][0]], subset[m[0][1]]), etc.
            # We need the 8 transversals.
            # Transversal is (x from P1, y from P2, z from P3).
            P1 = (subset[m[0][0]], subset[m[0][1]])
            P2 = (subset[m[1][0]], subset[m[1][1]])
            P3 = (subset[m[2][0]], subset[m[2][1]])
            
            k_triples = []
            for x in P1:
                for y in P2:
                    for z in P3:
                        t = tuple(sorted((x, y, z)))
                        k_triples.append(t)
            
            # Add this K to the list
            k_idx = len(k_list)
            k_list.append(k_triples)
            
            # Update triple_to_ks
            for t in k_triples:
                triple_to_ks[triple_to_idx[t]].append(k_idx)

    num_ks = len(k_list)
    
    def run_greedy():
        # counts[k] = number of triples from k_list[k] already in result
        counts = [0] * num_ks
        # blocked[t] = number of K's that are "saturated" (count 7) and contain t
        # If blocked[t] > 0, t cannot be added.
        blocked = [0] * num_triples
        available = list(range(num_triples))
        result = []
        
        # To speed up removal, we can just filter available in each step?
        # Or maintain a set of available indices.
        # Since num_triples is small (560), filtering a list is fast.
        
        while available:
            # Find valid candidates
            valid_candidates = [i for i in available if blocked[i] == 0]
            if not valid_candidates:
                break
            
            # Heuristic: Pick random valid candidate
            # Or pick one with min "risk"?
            # Let's stick to random for speed, relying on restarts.
            chosen_idx = random.choice(valid_candidates)
            result.append(all_triples[chosen_idx])
            
            # Remove chosen from available
            # Instead of removing from list (O(N)), we can just leave it and check blocked?
            # No, we need to ensure we don't pick it again.
            # We can mark it as "used" or just remove it.
            # List removal is O(N). 560 * 560 = 313k ops. Fine.
            available.remove(chosen_idx)
            
            # Update counts and blocked
            for k_idx in triple_to_ks[chosen_idx]:
                counts[k_idx] += 1
                if counts[k_idx] == 7:
                    # The remaining triple in this K is now blocked
                    # Find it
                    k_triples = k_list[k_idx]
                    # The remaining triple is the one not in result and not chosen?
                    # Actually, we know 7 are in result. The 8th is the one not in result.
                    # We can precompute the 8th triple for each K?
                    # Or just check which one is not in the set of added triples?
                    # We don't have a set of added triples.
                    # But we can determine the remaining triple by looking at k_triples and checking which one is not "used".
                    # This is expensive.
                    
                    # Better: Precompute for each K, the 8 triples.
                    # When count becomes 7, the remaining triple is the one that is NOT in the set of 7 added.
                    # We can maintain a set `used_triples`?
                    # Or, simpler:
                    # When we add a triple, we know which K's it affects.
                    # If count becomes 7, we need to identify the last triple.
                    # Let's precompute `k_remaining`? No, it changes.
                    
                    # Alternative:
                    # Instead of `blocked` array, we can just check validity on the fly?
                    # No, that's what the old program did (slow).
                    
                    # Let's optimize the "find remaining" step.
                    # We can store the 8 triples of the K.
                    # We can maintain a `used_count` per triple? No.
                    
                    # Idea: Precompute for each K, the 8 triples.
                    # When count[k] becomes 7, we iterate the 8 triples in K.
                    # The one that is not in `result_set` is the remaining one.
                    # We need `result_set`.
                    
                    # Let's use a `used` boolean array for triples.
                    # used[i] = True if triple i is in result.
                    
