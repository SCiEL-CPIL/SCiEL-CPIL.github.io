import random
import math
import time

def construct(n_rows, k):
    # 1. Generate initial solution using Greedy
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new_diffs = {x - a for a in row}
            if not new_diffs & used:
                row.append(x)
                used |= new_diffs
        rows.append(row)
        
    # Calculate initial energy
    current_energy = max(max(r) for r in rows)
    best_rows = [r[:] for r in rows]
    best_energy = current_energy
    
    # Simulated Annealing Parameters
    start_time = time.time()
    timeout = 110.0  # Leave 10s buffer
    T = 100.0
    cooling_rate = 0.999
    min_T = 0.1
    
    # Helper to get energy
    def get_energy(rows):
        return max(max(r) for r in rows)
        
    # Helper to check if a move is valid and return conflict info
    # Returns True if valid, False otherwise
    # Also updates used set if valid? No, better to have a separate check or
    # apply/revert.
    
    # We will store the current `used` set.
    # To speed up conflict checking, we can pre-compute diffs for each row?
    # No, dynamic is fine for small k.
    
    while T > min_T:
        if time.time() - start_time > timeout:
            break
            
        # Pick a random row and index
        r_idx = random.randint(0, n_rows - 1)
        row = rows[r_idx]
        j_idx = random.randint(1, k)
        
        # Pick a random step
        # Bias towards reduction? Or random?
        # Random step in [-3, 3] is good for exploration
        step = random.randint(-3, 3)
        if step == 0:
            continue
            
        new_val = row[j_idx] + step
        
        # Boundary checks
        if new_val < 0:
            continue
        if j_idx > 0 and new_val <= row[j_idx - 1]:
            continue
        if j_idx < k and new_val >= row[j_idx + 1]:
            continue
            
        # Conflict check
        old_val = row[j_idx]
        removed_diffs = set()
        added_diffs = set()
        
        for i in range(len(row)):
            if i == j_idx:
                continue
            removed_diffs.add(abs(old_val - row[i]))
            added_diffs.add(abs(new_val - row[i]))
            
        # Check conflicts
        # A conflict exists if any diff in added_diffs is in used,
        # UNLESS that diff is also in removed_diffs (meaning it was "freed" by this move)
        # BUT we must be careful: if a diff appears multiple times in the row?
        # The problem states "all differences ... are distinct over all rows".
        # This implies each difference value can appear at most once in the entire set of rows.
        # So `used` is a set of unique difference values.
        
        # If d is in added_diffs:
        # 1. If d is in removed_diffs, it's being "reused" from this row's old state.
        #    Is it safe?
        #    If d was in `used` because of old_val, and we remove old_val, d is no longer in `used` (conceptually).
        #    If we add new_val which produces d, is it a conflict?
        #    Only if d is produced by *another* element in the *same* row or *another* row.
        #    
        #    Let's refine:
        #    The set of "active" differences after the move would be:
        #    (used - removed_diffs) U added_diffs
        #    This set must have no duplicates? No, `used` is a set, so it can't have duplicates.
        #    The condition for validity is that `added_diffs` does not contain any value
        #    that is currently in `used` AND is not being removed by this specific move.
        #    
        #    Wait, what if `added_diffs` contains a value `d` that is in `removed_diffs`?
        #    That means `d` was generated by `old_val` and will be generated by `new_val`.
        #    Since `d` is removed from `used` (conceptually) and then added back, it's fine,
        #    UNLESS `d` is also generated by some other element in the row or another row.
        #    
        #    Let's check:
        #    1. Remove `removed_diffs` from a temporary copy of `used`?
        #    2. Check if `added_diffs` intersects with this temporary copy.
        #    
        #    If we do `temp_used = used - removed_diffs`, then `added_diffs` must be disjoint from `temp_used`.
        #    This correctly handles the case where `d` is in both `added` and `removed` (it's not in `temp_used`, so no conflict from that source).
        #    It also correctly handles if `d` is in `added` and in `used` from another row (it IS in `temp_used`, so conflict).
        
        temp_used = used - removed_diffs
        if added_diffs & temp_used:
            continue
            
        # Move is valid
        # Calculate energy change
        old_max = current_energy
        # We need to update the row to calculate new max?
        # Or just estimate?
        # Let's just apply and check.
        
        # Apply move
        row[j_idx] = new_val
        used = (used - removed_diffs) | added_diffs
        
        new_energy = get_energy(rows)
        
        delta_E = new_energy - old_max
        
        # Acceptance criterion
        if delta_E < 0:
            current_energy = new_energy
            if new_energy < best_energy:
                best_energy = new_energy
                best_rows = [r[:] for r in rows]
        else:
            # Accept with probability exp(-delta_E / T)
            if random.random() < math.exp(-delta_E / T):
                current_energy = new_energy
            else:
                # Revert move
                row[j_idx] = old_val
                used = (used - added_diffs) | removed_diffs
        
        # Cool down
        T *= cooling_rate
        
    return best_rows
