def _check_sidon_and_cover(a, target_diffs):
    """Check if a is a Sidon set covering target_diffs."""
    n = len(a)
    if n > 32:
        return False
    if max(a) > 10**6:
        return False
    if 0 not in a:
        return False
    
    diffs = set()
    for i in range(n):
        for j in range(i + 1, n):
            d = a[j] - a[i]
            if d <= 0:
                return False
            if d in diffs:
                return False
            diffs.add(d)
    return all(d in diffs for d in target_diffs)

def _search_for_m(M, target_diffs, deadline):
    """
    DFS with bitmask diff tracking for a specific maximum bound M.
    Returns a valid set if found, else None.
    """
    initial_set = [0]
    initial_diffs_mask = 0
    target_mask = 0
    for d in target_diffs:
        target_mask |= (1 << d)
    remaining_mask = target_mask
    
    # Precompute candidate positions? No, dynamic.
    
    def dfs(current_set, used_diffs_mask, remaining_mask):
        if remaining_mask == 0:
            return current_set[:]
        
        if len(current_set) >= 32:
            return None
            
        if time.time() > deadline:
            return None
        
        last = current_set[-1]
        
        # Generate candidates: x > last, x <= M
        # x must be such that x - a is a needed diff for some a?
        # Or just any x that doesn't conflict.
        # To be efficient, only consider x that cover at least one remaining diff.
        potential_xs = set()
        for a in current_set:
            # Iterate through set bits in remaining_mask
            r = remaining_mask
            while r:
                # Get lowest set bit
                lsb = r & -r
                d = lsb.bit_length() - 1
                x = a + d
                if x > last and x <= M:
                    potential_xs.add(x)
                x = a - d
                if x > last and x <= M: # x-a = -d, so a-x=d. But we need x-a? No, diff is abs.
                    # If we add x, diff is x-a or a-x.
                    # If x > last >= a, then x-a is the diff.
                    # So x = a + d is the only case for x > a.
                    pass
                r ^= lsb
        
        if not potential_xs:
            return None

        candidates = []
        for x in potential_xs:
            conflict = False
            new_covered_mask = 0
            for a in current_set:
                d = x - a
                if d <= 0:
                    conflict = True
                    break
                if used_diffs_mask & (1 << d):
                    conflict = True
                    break
                if remaining_mask & (1 << d):
                    new_covered_mask |= (1 << d)
            
            if conflict:
                continue
            
            new_count = bin(new_covered_mask).count('1')
            if new_count == 0:
                continue # This candidate doesn't help cover remaining diffs
            
            # Heuristic: Prefer smaller x to keep diameter small?
            # Or prefer larger coverage?
            # We are bounding M, so x <= M is fixed.
            # Smaller x might allow more room for future elements?
            # Actually, we just need to fill the set.
            candidates.append((x, -new_count))
        
        if not candidates:
            return None
            
        candidates.sort()
        
        for x, _ in candidates:
            new_diffs_mask = 0
            for a in current_set:
                d = x - a
                new_diffs_mask |= (1 << d)
            
            new_used = used_diffs_mask | new_diffs_mask
            new_remaining = remaining_mask & ~new_diffs_mask
            
            res = dfs(current_set + [x], new_used, new_remaining)
            if res is not None:
                return res
                
        return None

    return dfs(initial_set, initial_diffs_mask, remaining_mask)

