def _construct_fallback():
    """
    Construct a valid Sidon set covering 1..30 using a systematic greedy approach.
    """
    result = [0]
    used_diffs = set()
    remaining = set(range(1, 31))
    
    next_x = 1
    while remaining and len(result) < 32 and next_x <= 10**6:
        valid = True
        new_diffs = set()
        for a in result:
            d = next_x - a
            if d in used_diffs:
                valid = False
                break
            new_diffs.add(d)
        
        if valid:
            covers_any = any(d in remaining for d in new_diffs)
            if covers_any:
                result.append(next_x)
                used_diffs.update(new_diffs)
                remaining -= new_diffs
                next_x += 1
            else:
                next_x += 1
        else:
            next_x += 1
    
    return result

def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # Leave 10s margin
    
    target_diffs = set(range(1, 31))
    
    # Try progressively larger upper bounds M
    # Theoretical lower bound for diameter is 36 (for n=9)
    # We start from 36 and go up.
    for M in range(36, 200):
        if time.time() > deadline - 5:
            break
            
        # Allocate time based on M
        # Smaller M is harder, give it more time?
        # Or smaller M is easier to prove impossible?
        # Usually, solutions exist near the lower bound.
        m_deadline = min(deadline - 5, time.time() + 5.0)
        
        result = _search_for_m(M, target_diffs, m_deadline)
        if result is not None:
            if _check_sidon_and_cover(result, target_diffs):
                return result
    
    # If no solution found in the range, use fallback
    return _construct_fallback()
