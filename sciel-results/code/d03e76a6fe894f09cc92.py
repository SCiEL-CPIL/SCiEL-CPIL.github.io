import math
import time
import random
import numpy as np
from scipy.optimize import minimize

_START_TIME = time.time()
_DEADLINE = _START_TIME + 230.0  # Safety margin before 270s kill

def _time_left():
    return _DEADLINE - time.time()

def _target(problem):
    return np.array(problem["real"], dtype=complex) + 1j * np.array(problem["imaginary"], dtype=complex)

def _u3_mat(theta, phi, lam):
    c = math.cos(theta / 2)
    s = math.sin(theta / 2)
    return np.array([[c, -np.exp(1j * lam) * s],
                     [np.exp(1j * phi) * s, np.exp(1j * (phi + lam)) * c]], dtype=complex)

def _u3_grads(theta, phi, lam):
    """
    Compute derivatives of the u3 matrix with respect to theta, phi, lam.
    Returns a list of 3 matrices: dU/dtheta, dU/dphi, dU/dlam.
    """
    c = math.cos(theta / 2)
    s = math.sin(theta / 2)
    
    # U = [[c, -e^{i lam} s], [e^{i phi} s, e^{i(phi+lam)} c]]
    
    # dU/dtheta:
    # d(c)/dtheta = -0.5 sin(theta/2) = -0.5 s
    # d(s)/dtheta = 0.5 cos(theta/2) = 0.5 c
    d_c = -0.5 * s
    d_s = 0.5 * c
    
    dU_dtheta = np.array([[d_c, -np.exp(1j * lam) * d_s],
                          [np.exp(1j * phi) * d_s, np.exp(1j * (phi + lam)) * d_c]], dtype=complex)
    
    # dU/dphi:
    # Only terms with e^{i phi} change.
    # d(e^{i phi} s)/dphi = i e^{i phi} s
    # d(e^{i(phi+lam)} c)/dphi = i e^{i(phi+lam)} c
    dU_dphi = np.array([[0, 0],
                        [1j * np.exp(1j * phi) * s, 1j * np.exp(1j * (phi + lam)) * c]], dtype=complex)
    
    # dU/dlam:
    # Only terms with e^{i lam} change.
    # d(-e^{i lam} s)/dlam = -i e^{i lam} s
    # d(e^{i(phi+lam)} c)/dlam = i e^{i(phi+lam)} c
    dU_dlam = np.array([[0, -1j * np.exp(1j * lam) * s],
                        [0, 1j * np.exp(1j * (phi + lam)) * c]], dtype=complex)
    
    return [dU_dtheta, dU_dphi, dU_dlam]

def _build_circuit_parts(gates, qubits):
    """
    Pre-compute the fixed CNOT parts and the positions of variable single-qubit gates.
    Returns:
    - cnot_parts: List of matrices representing the CNOT layers (identity if no CNOT).
    - u3_indices: List of indices in the gates list that are u3 gates.
    """
    n = 2 ** qubits
    eye = np.eye(n, dtype=complex)
    
    # We will group gates into layers.
    # A layer is a sequence of u3 gates followed by a sequence of cx gates.
    # Actually, the layout is: u3s, cxs, u3s, cxs, ...
    
    cnot_matrices = []
    u3_positions = []
    
    # We need to identify the structure.
    # The layout is generated by synthesize.
    # Let's just store the CNOTs as they appear and the u3s.
    
    # For efficiency, we can pre-compute the effect of CNOTs on the basis.
    # But since the u3s are variable, we can't pre-compute the whole product.
    # However, we can pre-compute the CNOT matrices.
    
    cnot_mats = []
    for gate in gates:
        if gate[0] == "cx":
            _, control, target = gate
            # Build CNOT matrix
            cx_mat = np.eye(n, dtype=complex)
            # Swap |10> and |11> if control=0, target=1?
            # Control is qubit c, target is qubit t.
            # Bit index: qubit 0 is MSB.
            # Index i: bit c is (i >> (qubits-1-c)) & 1.
            # If bit c is 1, flip bit t.
            for i in range(n):
                if (i >> (qubits - 1 - control)) & 1:
                    j = i ^ (1 << (qubits - 1 - target))
                    cx_mat[i, j] = 1.0
                    cx_mat[j, i] = 0.0 # Wait, CNOT is a permutation.
                    # Actually, CNOT maps |c, t> to |c, t^c>.
                    # So column j (input |j>) goes to row i (output |i>).
                    # If j has bit c = 1, then i = j ^ (1 << (qubits-1-target)).
                    # So cx_mat[i, j] = 1.
                    # And cx_mat[j, i] = 0.
                    # Let's re-verify.
                    # U |j> = |i>. So U_{i,j} = 1.
                    # If j has control bit 1, i = j ^ target_bit.
                    # If j has control bit 0, i = j.
                    
            # Let's rebuild properly.
            cx_mat = np.zeros((n, n), dtype=complex)
            for j in range(n):
                if (j >> (qubits - 1 - control)) & 1:
                    i = j ^ (1 << (qubits - 1 - target))
                else:
                    i = j
                cx_mat[i, j] = 1.0
            cnot_mats.append(cx_mat)
        else:
            u3_positions.append(len(cnot_mats)) # This is not quite right, we need to interleave.
            
    # This pre-computation is tricky because u3s are interleaved.
    # Let's just return the list of CNOT matrices in order, and the indices of u3s in the original list.
    # Actually, it's easier to just pass the gate list and compute on the fly, but that's slow.
    # Let's stick to on-the-fly but optimized.
    
    return gates

def _evaluate_circuit(gates, qubits, target):
    """
    Evaluate the circuit and return the distance and the gradient with respect to u3 parameters.
    """
    n = 2 ** qubits
    eye = np.eye(n, dtype=complex)
    
    # Forward pass: Compute U and store intermediate matrices for backpropagation.
    # U = G_k ... G_1 I
    # We need dU/dtheta for each u3.
    
    # Let's use the chain rule.
    # Let M_k be the matrix after applying gate k.
    # M_0 = I
    # M_k = G_k M_{k-1}
    # U = M_L
    # T^dagger U = S
    # f = 1 - (1/n) |Tr(S)|
    
    # Gradients:
    # dS/dtheta_k = T^dagger (G_1 ... G_{k-1} (dG_k/dtheta_k) G_{k+1} ... G_L)
    # Wait, U = G_L ... G_1.
    # dU = G_L ... G_{k+1} (dG_k) G_{k-1} ... G_1.
    
    # Let's compute the "left" and "right" parts.
    # L_k = G_L ... G_{k+1}
    # R_k = G_{k-1} ... G_1
    # dU_k = L_k dG_k R_k
    
    # We can compute L_k and R_k efficiently.
    
    # 1. Identify u3 gates and their indices.
    u3_indices = []
    for i, gate in enumerate(gates):
        if gate[0] == "u3":
            u3_indices.append(i)
            
    num_u3 = len(u3_indices)
    
    # Pre-compute the gate matrices
    gate_mats = []
    for gate in gates:
        if gate[0] == "u3":
            _, q, theta, phi, lam = gate
            gate_mats.append(_u3_mat(theta, phi, lam))
        else:
            _, control, target = gate
            cx_mat = np.zeros((n, n), dtype=complex)
            for j in range(n):
                if (j >> (qubits - 1 - control)) & 1:
                    i = j ^ (1 << (qubits - 1 - target))
                else:
                    i = j
                cx_mat[i, j] = 1.0
            gate_mats.append(cx_mat)
            
    # Forward pass: Compute R_k (product of gates 0..k-1)
    # R_0 = I
    # R_k = G_{k-1} R_{k-1}
    R = np.eye(n, dtype=complex)
    R_mats = [R]
    for k in range(len(gates)):
        R = gate_mats[k] @ R
        R_mats.append(R)
        
    # Backward pass: Compute L_k (product of gates k+1..L-1)
    # L_L = I
    # L_k = L_{k+1} G_{k+1}
    L = np.eye(n, dtype=complex)
    L_mats = [None] * (len(gates) + 1)
    L_mats[len(gates)] = L
    for k in range(len(gates) - 1, -1, -1):
        L = L @ gate_mats[k]
        L_mats[k] = L
        
    # Compute S = T^dagger U
    U = R_mats[len(gates)]
    S = target.conj().T @ U
    
    tr_S = np.trace(S)
    abs_tr_S = abs(tr_S)
    dist = 1.0 - min(1.0, abs_tr_S / n)
    
    # Compute gradients
    grads = np.zeros(num_u3 * 3)
    
    if abs_tr_S > 1e-12:
        # dS/dtheta_k = T^dagger L_k dG_k R_k
        # df/dtheta_k = -1/n Re( (dTr(S)/dtheta_k) * conj(tr_S) / |tr_S| )
        
        factor = np.conj(tr_S) / (n * abs_tr_S)
        
        for idx, k in enumerate(u3_indices):
            _, q, theta, phi, lam = gates[k]
            dG = _u3_grads(theta, phi, lam)
            
            # dU_k = L_k dG R_k
            # Note: L_k is product of gates k+1..L-1.
            # R_k is product of gates 0..k-1.
            # Wait, my R_mats and L_mats definitions:
            # R_mats[k] = G_{k-1} ... G_0.
            # L_mats[k] = G_{L-1} ... G_k.
            # So dU_k = L_mats[k+1] dG R_mats[k].
            
            L_k = L_mats[k+1]
            R_k = R_mats[k]
            
            for param_idx in range(3):
                dG_p = dG[param_idx]
                dU_p = L_k @ dG_p @ R_k
                dS_p = target.conj().T @ dU_p
                dTr_p = np.trace(dS_p)
                
                # df/dparam = -1/n Re( dTr_p * conj(tr_S) / |tr_S| )
                # = -Re( dTr_p * factor )
                grad_val = -np.real(dTr_p * factor)
                grads[idx * 3 + param_idx] = grad_val
                
    return dist, grads

def synthesize(problem):
    """
    Synthesize a circuit for the given target unitary.
    """
    qubits = problem["qubits"]
    budget = problem["cnot_budget"]
    target = _target(problem)
    
    # Define a fixed layout of CNOTs.
    # For 2 qubits, typical budget is 3 or 4.
    # For 3 qubits, typical budget is 6 or 12.
    # We will use a "brickwork" layout.
    
    pairs = [(c, t) for c in range(qubits) for t in range(qubits) if c != t]
    
    # Layout:
    # u3s, cx, u3s, cx, ...
    # We need exactly 'budget' CNOTs.
    
    layout = []
    for i in range(budget):
        # Add u3s for all qubits
        for q in range(qubits):
            layout.append(["u3", q, 0.0, 0.0, 0.0])
        # Add a CNOT
        # Choose a pair that covers connectivity
        # For 2 qubits: (0,1)
        # For 3 qubits: (0,1), (1,2), (0,1), ...
        if qubits == 2:
            layout.append(["cx", 0, 1])
        else:
            # Alternate between (0,1) and (1,2)
            if i % 2 == 0:
                layout.append(["cx", 0, 1])
            else:
                layout.append(["cx", 1, 2])
                
    # Add final u3s
    for q in range(qubits):
        layout.append(["u3", q, 0.0, 0.0, 0.0])
        
    num_u3 = sum(1 for g in layout if g[0] == "u3")
    num_params = num_u3 * 3
    
    def get_gates(params):
        gates = []
        k = 0
        for gate in layout:
            if gate[0] == "u3":
                gates.append(["u3", gate[1], params[k], params[k+1], params[k+2]])
                k += 3
            else:
                gates.append(list(gate))
        return gates
        
    best_dist = float('inf')
    best_params = np.zeros(num_params)
    
    # Multi-start optimization
    rng = random.Random(4242 + qubits)
    
    # Time limit check
    max_starts = 10
    start_times = []
    
    for start_idx in range(max_starts):
        if _time_left() < 20.0:
            break
            
        # Random initialization
        params = np.array([rng.uniform(-math.pi, math.pi) for _ in range(num_params)])
        
        # Define objective and gradient
        def obj_grad(p):
            gates = get_gates(p)
            dist, grads = _evaluate_circuit(gates, qubits, target)
            return dist, grads
            
        # Use L-BFGS-B
        try:
            res = minimize(
                obj_grad,
                params,
                jac=True,
                method='L-BFGS-B',
                options={'maxiter': 100, 'ftol': 1e-10}
            )
            if res.success:
                dist = res.fun
                if dist < best_dist:
                    best_dist = dist
                    best_params = res.x
        except Exception:
            pass
            
        # Polish with Nelder-Mead if time allows
        if _time_left() > 50.0 and best_dist < 1e-3:
            try:
                res2 = minimize(
                    obj_grad,
                    best_params,
                    jac=True,
                    method='Nelder-Mead',
                    options={'maxiter': 100, 'xatol': 1e-12, 'fatol': 1e-12}
                )
                if res2.success:
                    dist2 = res2.fun
                    if dist2 < best_dist:
                        best_dist = dist2
                        best_params = res2.x
            except Exception:
                pass
                
    return get_gates(best_params)

