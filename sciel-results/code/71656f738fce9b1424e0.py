def construct():
    """
    Return a rank-minimal exact tensor decomposition for 3x3 * 3x8 matrix multiplication.
    """
    n, m, p = DIMENSIONS
    
    # Fallback: schoolbook rank 72
    U_school, V_school, W_school = _schoolbook(n, m, p)
    best_result = {"U": U_school, "V": V_school, "W": W_school}
    best_rank = n * m * p  # 72
    
    if _time_left() > 5:
        # Use 4 disjoint Strassen blocks at k=0,2,4,6 with i0=0, j0=0
        # This gives rank = 4*7 + (72 - 4*8) = 28 + 40 = 68
        blocks = [(0, 0, 0), (0, 0, 2), (0, 0, 4), (0, 0, 6)]
        
        try:
            U, V, W = _build_strassen_embedding(n, m, p, blocks)
            if _verify(U, V, W, n, m, p):
                r = len(U[0])
                if r < best_rank:
                    best_rank = r
                    best_result = {"U": U, "V": V, "W": W}
        except Exception:
            pass
    
    return best_result
