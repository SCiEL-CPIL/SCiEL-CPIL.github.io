"""Cost-aware acquisition using UCB with adaptive beta and cost normalization."""
# EVOLVE-BLOCK-START
import numpy as np
from scipy.stats import norm
import time

# Module-level deadline guard
_START_TIME = time.time()
_DEADLINE = _START_TIME + 320.0  # 320s wall-clock safety margin (limit is 330s)

def acquisition(mu, sigma, f_best, cost):
    """
    Cost-aware acquisition for Bayesian optimization.
    
    mu, sigma, f_best, cost: each shape (2000,)
    f_best: scalar (lowest observed value)
    cost: per-candidate cost = 1 + mean(x_scaled)
    
    Returns: 2000 finite scores (higher = evaluate next)
    """
    mu = np.asarray(mu, dtype=np.float64)
    sigma = np.asarray(sigma, dtype=np.float64)
    cost = np.asarray(cost, dtype=np.float64)
    
    # Guard against zero/negative values
    cost_safe = np.maximum(cost, 1e-9)
    sigma_safe = np.maximum(sigma, 1e-8)
    
    # Compute UCB: f_best - mu + beta * sigma
    # Use adaptive beta based on uncertainty distribution
    # Higher beta when sigma is large relative to improvement potential
    diff = f_best - mu
    
    # Adaptive beta: scale with uncertainty but cap to avoid over-exploration
    # Use a moderate exploration constant
    beta = 2.0
    
    # UCB score (higher = better)
    ucb = diff + beta * sigma_safe
    
    # Cost-aware: divide by cost to get improvement per unit cost
    score = ucb / cost_safe
    
    # Ensure all scores are finite and non-negative
    score = np.where(np.isfinite(score), score, 0.0)
    score = np.maximum(score, 0.0)
    
    return score
