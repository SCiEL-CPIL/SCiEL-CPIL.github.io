"""Erdos minimum overlap: minimize max overlap of h with shifted 1-h.

Structural change: We model the step heights as a piecewise constant function
with a single transition window. The transition profile is generated by a
cumulative binomial distribution (discrete convolution of uniform noise) rather
than a simple linear ramp. We optimize the transition width, position, and
binomial order via a derivative-free global search (Differential Evolution)
to minimize the maximum overlap. We then polish with local search.

This combines the "direct vector optimization" approach (fine-grained control)
with the "analytic structure" insight (piecewise constant with smooth transition).
"""
import time
import math
import numpy as np
from scipy.optimize import minimize, differential_evolution

N = 100
DEADLINE_MARGIN = 15.0  # seconds to spare before 150s kill
TARGET_SUM = N / 2.0


def _score(h):
    """Compute max overlap of h with shifted (1-h), treating h as zero outside [0,2]."""
    n = len(h)
    shifted = np.zeros(n)
    shifted[:-1] = h[1:]
    overlap = h * (1.0 - shifted)
    return float(np.max(overlap))


def _fix_sum(h, target=None):
    """Adjust h so that sum(h) = N/2, keeping values in [0,1]."""
    if target is None:
        target = TARGET_SUM
    h = np.array(h, dtype=np.float64, copy=True)
    diff = target - h.sum()
    if abs(diff) < 1e-14:
        return h
    # Distribute the difference
    n = len(h)
    if diff > 0:
        # Need to increase some entries
        room = 1.0 - h
        total_room = room.sum()
        if total_room > 1e-14:
            h = h + diff * room / total_room
        else:
            h = np.clip(h + diff / n, 0.0, 1.0)
    else:
        # Need to decrease some entries
        room = h
        total_room = room.sum()
        if total_room > 1e-14:
            h = h + diff * room / total_room
        else:
            h = np.clip(h + diff / n, 0.0, 1.0)
    return np.clip(h, 0.0, 1.0)


def _construct_piecewise_binomial(params):
    """
    Construct a piecewise constant function with a binomial transition.
    
    params:
      - pos: position of the transition center (0 to N-1)
      - width: width of the transition window
      - order: order of the binomial distribution (higher = smoother)
      - h_low: value of h before the transition
      - h_high: value of h after the transition
    
    The function is:
      h[i] = h_low for i < pos - width/2
      h[i] = h_high for i > pos + width/2
      h[i] = h_low + (h_high - h_low) * CDF(i) for i in transition window
    
    where CDF is the cumulative distribution of a binomial(order, 0.5)
    shifted and scaled to the transition window.
    """
    pos, width, order, h_low, h_high = params
    pos = int(np.clip(pos, 0, N - 1))
    width = int(np.clip(width, 1, N))
    order = int(np.clip(order, 1, 20))
    h_low = np.clip(h_low, 0.0, 1.0)
    h_high = np.clip(h_high, 0.0, 1.0)
    
    h = np.full(N, h_low)
    
    # Define the transition window
    start = max(0, pos - width // 2)
    end = min(N, pos + width // 2 + 1)
    
    if start >= end:
        return h
    
    # Generate binomial CDF
    # Binomial(order, 0.5) has support 0..order
    # We want to map this to the transition window
    # CDF(k) = P(X <= k) for X ~ Binomial(order, 0.5)
    
    # Use scipy.stats.binom.cdf
    from scipy.stats import binom
    
    # The transition window has (end - start) points
    # We want to map the binomial CDF to [0, 1] over this window
    # The binomial CDF goes from ~0 to ~1 as k goes from 0 to order
    # We scale the binomial support to the transition window
    
    # For each point in the transition window, compute its relative position
    # and map to binomial CDF
    window_len = end - start
    for i in range(start, end):
        # Relative position in window: 0 to 1
        rel_pos = (i - start + 0.5) / window_len  # Center of the bin
        
        # Map to binomial support: 0 to order
        bin_val = rel_pos * order
        
        # Compute CDF at bin_val
        # P(X <= bin_val) for X ~ Binomial(order, 0.5)
        cdf_val = binom.cdf(bin_val, order, 0.5)
        
        # Interpolate between h_low and h_high
        h[i] = h_low + (h_high - h_low) * cdf_val
    
    return h


def _objective_binomial(params):
    """Objective function for differential evolution."""
    h = _construct_piecewise_binomial(params)
    h = _fix_sum(h)
    return _score(h)


def _optimize_binomial(deadline):
    """Optimize the piecewise binomial function using differential evolution."""
    # Bounds for parameters:
    # pos: [0, N-1]
    # width: [1, N]
    # order: [1, 20]
    # h_low: [0, 1]
    # h_high: [0, 1]
    
    bounds = [
        (0, N - 1),      # pos
        (1, N),          # width
        (1, 20),         # order
        (0, 1),          # h_low
        (0, 1),          # h_high
    ]
    
    # Initial population: try some reasonable starting points
    # pos around N/2, width around 10-30, order around 5-15
    # h_low and h_high around 0.3-0.7
    
    try:
        result = differential_evolution(
            _objective_binomial,
            bounds,
            maxiter=100,
            popsize=20,
            tol=1e-6,
            polish=False,  # We'll do our own polish
            seed=42,
            init='sobol'
        )
        
        if result.success or result.fun < float('inf'):
            best_params = result.x
            h = _construct_piecewise_binomial(best_params)
            h = _fix_sum(h)
            return h, _score(h)
        else:
            return None, float('inf')
    except Exception:
        return None, float('inf')


def _local_search(h, max_iters=5000):
    """Direct discrete local search: try small perturbations to individual entries."""
    h = np.clip(h, 0.0, 1.0).copy()
    h = _fix_sum(h)
    best_score = _score(h)
    best_h = h.copy()

    step_sizes = [0.01, 0.005, 0.002, 0.001, 0.05, 0.02]

    for it in range(max_iters):
        improved = False
        for i in range(N):
            for ds in step_sizes:
                for sign in [1, -1]:
                    h_try = h.copy()
                    h_try[i] = np.clip(h_try[i] + sign * ds, 0.0, 1.0)
                    h_try = _fix_sum(h_try)
                    s = _score(h_try)
                    if s < best_score - 1e-12:
                        best_score = s
                        best_h = h_try.copy()
                        h = h_try.copy()
                        improved = True
                        break
                if improved:
                    break
            if improved:
                break
        if not improved:
            # Try larger steps
            for i in range(N):
                for ds in [0.1, 0.2, 0.05]:
                    for sign in [1, -1]:
                        h_try = h.copy()
                        h_try[i] = np.clip(h_try[i] + sign * ds, 0.0, 1.0)
                        h_try = _fix_sum(h_try)
                        s = _score(h_try)
                        if s < best_score - 1e-12:
                            best_score = s
                            best_h = h_try.copy()
                            h = h_try.copy()
                            improved = True
                            break
                    if improved:
                        break
                if improved:
                    break
            if not improved:
                break
    return best_score, best_h


def _optimize_full_vector(h0, beta=200.0, max_iter=5000):
    """Optimize full vector h using L-BFGS-B with smooth objective."""
    def obj(x):
        h = np.clip(x, 0.0, 1.0)
        n = len(h)
        shifted = np.zeros(n)
        shifted[:-1] = h[1:]
        overlap = h * (1.0 - shifted)
        sum_pen = (h.sum() - N / 2.0) ** 2 * 50.0
        m = np.max(overlap)
        if m < -1e-15:
            return 0.0 + sum_pen
        return m + np.log(np.sum(np.exp(beta * (overlap - m)))) / beta + sum_pen

    def jac(x):
        # Numerical gradient
        eps = 1e-8
        g = np.zeros_like(x)
        f0 = obj(x)
        for i in range(N):
            x[i] += eps
            g[i] = (obj(x) - f0) / eps
            x[i] -= eps
        return g

    h0_clipped = np.clip(h0, 0.0, 1.0)
    try:
        res = minimize(obj, h0_clipped, method='L-BFGS-B', jac=jac,
                       options={'maxiter': max_iter, 'ftol': 1e-14, 'gtol': 1e-10})
        h_opt = np.clip(res.x, 0.0, 1.0)
        h_opt = _fix_sum(h_opt)
        return h_opt
    except Exception:
        return _fix_sum(h0_clipped)


def construct():
    start_time = time.time()
    deadline = start_time + 150.0 - DEADLINE_MARGIN

    best_score = 1e10
    best_h = None

    # --- Initial candidates ---

    # 1. Golden-ratio 2-block (from seed)
    A0 = (3.0 - math.sqrt(5.0)) / 2.0
    B0 = 1.0 - A0
    m0 = N // 2
    h_2block = np.zeros(N)
    h_2block[:m0] = A0
    h_2block[m0:] = B0
    h_2block = _fix_sum(h_2block)
    s = _score(h_2block)
    if s < best_score:
        best_score = s
        best_h = h_2block.copy()

    # 2. Uniform
    h_unif = np.full(N, 0.5)
    s = _score(h_unif)
    if s < best_score:
        best_score = s
        best_h = h_unif.copy()

    # 3. Piecewise binomial optimization (structural change)
    if time.time() < deadline - 30:
        h_binom, s_binom = _optimize_binomial(deadline)
        if h_binom is not None and s_binom < best_score:
            best_score = s_binom
            best_h = h_binom.copy()

    # 4. Full-vector L-BFGS-B optimization from multiple starts
    if time.time() < deadline - 60:
        starts = [best_h.copy(), h_2block.copy(), h_unif.copy()]
        # Add a few random starts
        for _ in range(3):
            h_rand = np.random.uniform(0.2, 0.8, N)
            h_rand = _fix_sum(h_rand)
            starts.append(h_rand)

        for h0 in starts:
            if time.time() > deadline - 30:
                break
            h_opt = _optimize_full_vector(h0, beta=300.0, max_iter=3000)
            s = _score(h_opt)
            if s < best_score:
                best_score = s
                best_h = h_opt.copy()

    # 5. Local search polish
    if time.time() < deadline - 10:
        s_ls, h_ls = _local_search(best_h, max_iters=2000)
        if s_ls < best_score:
            best_score = s_ls
            best_h = h_ls.copy()

    # 6. Another round of L-BFGS-B from the locally-searched result
    if time.time() < deadline - 15:
        h_opt2 = _optimize_full_vector(best_h, beta=500.0, max_iter=3000)
        s = _score(h_opt2)
        if s < best_score:
            best_score = s
            best_h = h_opt2.copy()
        # Final local search
        if time.time() < deadline - 5:
            s_ls2, h_ls2 = _local_search(best_h, max_iters=1000)
            if s_ls2 < best_score:
                best_score = s_ls2
                best_h = h_ls2.copy()

    # Final fix
    best_h = np.clip(best_h, 0.0, 1.0)
    best_h = _fix_sum(best_h)

    return best_h
