import time
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    # We want to find M with many k such that k*sigma(k) = M.
    # Constraint: M <= 10^18.
    # If k <= N, M = k*sigma(k) <= k * (k * C) = C * k^2.
    # For N = 2*10^7, M is around 10^15, well within limit.
    # Any other solution k' for this M must satisfy k' <= sqrt(M).
    # sqrt(M) <= sqrt(C) * N.
    # If C is small (e.g. 10), sqrt(M) <= 3.16 * N.
    # So we should sieve up to a bit more than N to catch all solutions for M found in [1, N].
    # Let's sieve up to N=2*10^7. This covers k up to 2*10^7.
    # If best M comes from k in [1, 2*10^7], its other solutions are <= sqrt(M).
    # Max M from k=2*10^7 is approx 2*10^7 * 10 * 2*10^7 = 4*10^15.
    # sqrt(4*10^15) = 2*10^7.
    # So sieving up to 2*10^7 is sufficient to find ALL solutions for any M generated by k <= 2*10^7.
    # Wait, if k1 = 10^7, M = 10^14. sqrt(M) = 10^7.
    # If k1 = 2*10^7, M ~ 4*10^15. sqrt(M) ~ 2*10^7.
    # So N=2*10^7 is self-consistent for finding all k for M generated in that range.
    
    N = 20000000  # 2 * 10^7
    
    # Check if we have enough time
    if time.time() > deadline - 20:
        # Fallback to known solution
        return {'M': 333312, 'k': [336, 372, 434]}
        
    # 1. Compute sigma(k) for k=1..N
    sigma = np.zeros(N + 1, dtype=np.int64)
    for i in range(1, N + 1):
        # Add i to all multiples of i
        sigma[i::i] += i
        
    if time.time() > deadline - 10:
        return {'M': 333312, 'k': [336, 372, 434]}

    # 2. Compute M_k = k * sigma(k)
    ks = np.arange(1, N + 1, dtype=np.int64)
    Ms = ks * sigma[1:]
    
    # 3. Find M with maximum frequency
    # Filter M <= 10^18 (should be all, but just in case)
    max_M_limit = 10**18
    valid_mask = Ms <= max_M_limit
    Ms_valid = Ms[valid_mask]
    ks_valid = ks[valid_mask]
    
    if len(Ms_valid) == 0:
        return {'M': 333312, 'k': [336, 372, 434]}
        
    unique_M, counts, inverse = np.unique(Ms_valid, return_counts=True, return_inverse=True)
    
    if time.time() > deadline - 5:
        return {'M': 333312, 'k': [336, 372, 434]}

    max_idx = np.argmax(counts)
    best_M = int(unique_M[max_idx])
    best_count = int(counts[max_idx])
    
    # 4. Extract k values
    # We need the indices in ks_valid where Ms_valid == best_M
    # Using inverse is tricky if we filtered. 
    # Easier: mask = (Ms_valid == best_M)
    mask = (Ms_valid == best_M)
    best_ks = ks_valid[mask]
    
    # Convert to Python list of ints
    k_list = [int(x) for x in best_ks]
    
    # Ensure distinct (they are by construction of k)
    # Ensure sorted? Not required, but nice.
    k_list.sort()
    
    # Final check
    if len(k_list) == 0:
        return {'M': 333312, 'k': [336, 372, 434]}
        
    return {'M': best_M, 'k': k_list}

