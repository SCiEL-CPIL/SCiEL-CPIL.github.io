        # Given time constraints, L-BFGS-B is good.
        # But we need to import minimize.
        from scipy.optimize import minimize
        
        try:
            res = minimize(
                neg_ratio_w, 
                w0, 
                method='L-BFGS-B', 
                bounds=[(0, None)] * K,
                options={'maxiter': 200, 'maxfun': 500, 'disp': False}
            )
            w_opt = np.maximum(res.x, 0)
            h_opt = np.zeros(N)
            h_opt[support_arr] = w_opt
            score = compute_ratio(h_opt)
            return h_opt, score
        except Exception:
            return None, 0.0

