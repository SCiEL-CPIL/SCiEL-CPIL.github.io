    # 1. 2k is not in Sums(S).
    # 2. For all i in S, i+k is not in Sums(S) \ {i+k} (actually, i+k must not collide with ANY sum in Sums(S) from a DIFFERENT pair).
    # Wait, if i+k = j+l where {i,k} != {j,l}, then it's a collision.
    
    def is_valid_sidon_addition(S, k):
        """
        Check if adding k to set S (list of indices) results in a set where all pairwise sums are distinct.
        S is a list of ints.
        """
        # Existing sums
        existing_sums = set()
        for i in range(len(S)):
            for j in range(i, len(S)):
                existing_sums.add(S[i] + S[j])
        
        # New sums involving k
        # 1. 2*k
        if 2*k in existing_sums:
            return False
        # 2. i + k for i in S
        for i in S:
            s_val = i + k
            if s_val in existing_sums:
                return False
            # Also, we must ensure that the new sums (2k and i+k) don't collide with EACH OTHER?
            # 2k == i+k => k == i. Since k is not in S (we are adding it), this is impossible.
            # So we just need to check against existing_sums.
            
        return True

