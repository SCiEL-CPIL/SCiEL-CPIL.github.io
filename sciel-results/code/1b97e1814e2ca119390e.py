        """
        Given a support (list of indices), optimize the weights h[i] for i in support.
        h[i] = 0 for i not in support.
        Use L-BFGS-B on the weights.
        """
        if not support:
            return None, 0.0
            
        K = len(support)
        support_arr = np.array(support)
        
        # Initial guess: uniform weights
        w0 = np.ones(K)
        
        def neg_ratio_w(w):
            h = np.zeros(N)
            h[support_arr] = w
            val = compute_ratio(h)
            return -val
            
        # We can also try to optimize the support selection locally (swap in/out) later.
        # For now, just optimize weights.
        
