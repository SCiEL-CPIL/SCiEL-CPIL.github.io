    def get_strassen_2x2():
        # Returns U, V, W for 2x2x2, rank 7
        # U: 4x7, V: 4x7, W: 4x7
        # Indices:
        # U[i*2+j], V[j*2+k], W[k*2+i]
        U = [[0]*7 for _ in range(4)]
        V = [[0]*7 for _ in range(4)]
        W = [[0]*7 for _ in range(4)]
        
        # Step 1: (a+d)(e+h)
        # A: a(0,0), d(1,1) -> U[0]=1, U[3]=1
        # B: e(0,0), h(1,1) -> V[0]=1, V[3]=1
        # C: c00(0,0), c11(1,1) -> W[0]=1, W[3]=1
        # C00 += 1, C11 += 1
        # Wait, C = [[c00, c01], [c10, c11]]
        # W index k*2+i.
        # c00: k=0, i=0 -> idx 0
        # c11: k=1, i=1 -> idx 3
        # c01: k=1, i=0 -> idx 2
        # c10: k=0, i=1 -> idx 1
        
        # P1 = (A00+A11)(B00+B11)
        # A: 1,0,0,1
        # B: 1,0,0,1
        # C: c00 += 1, c11 += 1
        U[0][0] = 1; U[3][0] = 1
        V[0][0] = 1; V[3][0] = 1
        W[0][0] = 1; W[3][0] = 1
        
        # P2 = (A10+A11)B00
        # A: 0,0,1,1
        # B: 1,0,0,0
        # C: c10 += 1
        U[2][1] = 1; U[3][1] = 1
        V[0][1] = 1
        W[1][1] = 1
        
        # P3 = A00(B01-B11)
        # A: 1,0,0,0
        # B: 0,1,0,-1
        # C: c01 += 1
        U[0][2] = 1
        V[1][2] = 1; V[3][2] = -1
        W[2][2] = 1
        
        # P4 = A11(B10-B00)
        # A: 0,0,0,1
        # B: -1,0,1,0
        # C: c00 += 1, c10 += 1
        U[3][3] = 1
        V[0][3] = -1; V[2][3] = 1
        W[0][3] = 1; W[1][3] = 1
        
        # P5 = (A00+A01)B11
        # A: 1,1,0,0
        # B: 0,0,0,1
        # C: c00 -= 1, c01 += 1
        U[0][4] = 1; U[1][4] = 1
        V[3][4] = 1
        W[0][4] = -1; W[2][4] = 1
        
        # P6 = (A10-A00)(B00+B01)
        # A: -1,0,1,0
        # B: 1,1,0,0
        # C: c11 += 1
        U[0][5] = -1; U[2][5] = 1
        V[0][5] = 1; V[1][5] = 1
        W[3][5] = 1
        
        # P7 = (A01-A11)(B10+B11)
        # A: 0,1,0,-1
        # B: 0,0,1,1
        # C: c00 += 1
        U[1][6] = 1; U[3][6] = -1
        V[2][6] = 1; V[3][6] = 1
        W[0][6] = 1
        
        return U, V, W
    