def _rk4_fallback(f, t0, t1, y0):
    """Simple RK4 fallback."""
    y = np.array(y0, dtype=float)
    n_steps = 1000
    h = (t1 - t0) / n_steps
    t = t0
    
    for _ in range(n_steps):
        k1 = f(t, y)
        k2 = f(t + h / 2, y + h / 2 * k1)
        k3 = f(t + h / 2, y + h / 2 * k2)
        k4 = f(t + h, y + h * k3)
        y = y + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
        t += h
    
    return y
