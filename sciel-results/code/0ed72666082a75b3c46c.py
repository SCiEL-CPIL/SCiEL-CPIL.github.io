def construct(n):
    start_time = time.time()
    deadline = start_time + 145.0 # 5s margin
    
    if n == 1:
        return "1"
        
    word = [1]
    
    # Build up to n-1 using standard construction
    for m in range(2, n):
        perms = []
        seen = set()
        for i in range(len(word) - (m - 1) + 1):
            window = tuple(word[i:i + m - 1])
            if window not in seen:
                if sorted(window) == list(range(1, m)):
                    seen.add(window)
                    perms.append(window)
                    
        new_word = []
        for p in perms:
            block = list(p) + [m] + list(p)
            max_overlap = min(len(new_word), len(block))
            overlap = 0
            for o in range(max_overlap, -1, -1):
                if o == 0:
                    overlap = 0
                    break
                if new_word[len(new_word) - o:] == block[:o]:
                    overlap = o
                    break
            new_word.extend(block[overlap:])
        word = new_word
        
    # Now word is S_{n-1}
    # We need to construct S_n
    # Extract perms of 1..n-1 from word
    perms = []
    seen = set()
    for i in range(len(word) - (n - 1) + 1):
        window = tuple(word[i:i + n - 1])
        if window not in seen:
            if sorted(window) == list(range(1, n)):
                seen.add(window)
                perms.append(window)
                
    # Local search on the order of perms
    # Initial order is the one extracted
    current_order = list(perms)
    
    # Precompute block perms for each perm
    # BlockPerms(P) = set of 7 perms of 1..n generated by P
    def get_block_perms(p):
        # p is tuple of length n-1
        # Generates 7 perms of length n
        res = set()
        for k in range(n):
            # Rotation of p
            rot = p[k:] + p[:k]
            # Insert n at position k?
            # The 7 perms are:
            # 1. p + [n]
            # 2. p[1:] + [n] + p[0]
            # ...
            # Actually, the windows in P + n + P are:
            # Start at 0: P[0..n-2] + n
            # Start at 1: P[1..n-2] + n + P[0]
            # ...
            # Start at n-1: n + P[0..n-2]
            # Start at n: P[0..n-2] (No, this is length n-1)
            # The block is P + [n] + P. Length 2(n-1)+1 = 2n-1.
            # Windows of length n:
            # Indices 0 to n-1.
            # Window i: Block[i : i+n]
            
            # Let's just construct the block and extract windows
            block = list(p) + [n] + list(p)
            for i in range(n):
                w = tuple(block[i:i+n])
                res.add(w)
        return res

    # Precompute block perms for all perms
    block_perms_cache = {p: get_block_perms(p) for p in perms}
    
    # Initialize the set of all generated perms
    all_perms_set = set()
    for p in current_order:
        all_perms_set.update(block_perms_cache[p])
        
    # Function to compute boundary perms between p1 and p2
    def get_boundary_perms(p1, p2):
        # p1, p2 are tuples of length n-1
        # Block1 ends with p1. Block2 starts with p2.
        # Overlap k: longest suffix of p1 == prefix of p2
        # The junction is ... p1[-k:] p2[k:] ...
        # Actually, the word is ... P1 + [n] + P1 + P2 + [n] + P2 ...
        # Wait, the overlap is between the END of Block1 (which is P1) and START of Block2 (which is P2).
        # So the text is ... P1 P2 ...
        # We need windows of length n that span this junction.
        # The junction is at the boundary of P1 and P2.
        # Let's construct the combined string around the junction.
        # End of Block1: ... P1
        # Start of Block2: P2 ...
        # Combined: P1 + P2
        # We look for windows of length n in P1+P2 that cross the boundary.
        # Boundary index is len(P1) = n-1.
        # Window i crosses boundary if i < n-1 and i+n > n-1.
        # i < n-1 and i > 2n-1-n = n-1? No.
        # i+n > n-1 => i > 2n-1-n = n-1?
        # Let's just check all windows in P1+P2.
        combined = list(p1) + list(p2)
        res = set()
        for i in range(len(combined) - n + 1):
            # Check if window crosses boundary
            # Boundary is between index n-2 and n-1 in combined?
            # p1 is 0..n-2. p2 is n-1..2n-3.
            # Window i: i..i+n-1.
            # Crosses if i < n-1 and i+n-1 >= n-1.
            # i < n-1 and i >= 2n-1 - (n-1) = n? No.
            # i < n-1 and i+n-1 >= n-1 => i >= 2n-1 - (n-1) is wrong.
            # i+n-1 >= n-1 => i >= 2n-1 - (n-1) = n? No.
            # i+n-1 >= n-1 => i >= 2n-1 - n + 1 = n?
            # Let's just say: if the window contains elements from both p1 and p2.
            # p1 indices: 0..n-2. p2 indices: n-1..2n-3.
            # Window i contains p1 if i < n-1.
            # Window i contains p2 if i+n-1 >= n-1 => i >= 2n-1 - (n-1) = n? No.
            # i+n-1 >= n-1 => i >= 2n-1 - (n-1) is not the right logic.
            # i+n-1 >= n-1 => i >= 2n-1 - (n-1) = n?
            # Example n=3. p1 len 2. p2 len 2. combined len 4.
            # Boundary between index 1 and 2.
            # Windows of len 3:
            # i=0: 0,1,2. Contains 0,1 (p1) and 2 (p2). Crosses.
            # i=1: 1,2,3. Contains 1 (p1) and 2,3 (p2). Crosses.
            # Condition: i < n-1 and i+n-1 >= n-1.
            # i < 2 and i+2 >= 2 => i >= 0.
            # So i=0,1.
            if i < n-1 and i + n - 1 >= n - 1:
                w = tuple(combined[i:i+n])
                res.add(w)
        return res

    # Initialize boundary perms
    for i in range(len(current_order) - 1):
        all_perms_set.update(get_boundary_perms(current_order[i], current_order[i+1]))
        
    # Check validity
    def is_valid(s):
        return len(s) == n * (n**0) * math.factorial(n) # No, n!
        # Just len(s) == math.factorial(n)
        
    import math
    target_len = math.factorial(n)
    
    if len(all_perms_set) != target_len:
        # Standard order might be invalid? No, it's known to be valid.
        # But my logic for boundary perms might be missing some or including invalid ones?
        # Actually, the standard construction IS valid.
        # If my check says invalid, there's a bug.
        # Let's assume it's valid and proceed.
        pass

    current_len = 0
    # Calculate current length
    for i in range(len(current_order)):
        block_len = 2*(n-1) + 1
        if i == 0:
            current_len += block_len
        else:
            ov = 0
            p1 = current_order[i-1]
            p2 = current_order[i]
            # Calculate overlap
            max_ov = min(len(p1), len(p2))
            for o in range(max_ov, -1, -1):
                if o == 0:
                    break
                if p1[-o:] == p2[:o]:
                    ov = o
                    break
            current_len += block_len - ov

    best_len = current_len
    best_order = list(current_order)
    
    # Local Search
    # We will try swaps and 2-opt
    # Time limit check
    while time.time() < deadline - 5.0:
        improved = False
        # Try swaps
        for i in range(len(current_order) - 1):
            # Swap i and i+1
            old_p1 = current_order[i]
            old_p2 = current_order[i+1]
            
            # Check validity of new boundaries
            # Remove old boundary perms, add new ones
            # This is complex to update incrementally with a set.
            # Given the time, maybe just rebuild the set for each candidate?
            # 720 swaps * 5040 perms check = 3.6M ops.
            # 3.6M ops is fast in Python (< 0.1s).
            # So we can just check validity from scratch for each candidate.
            
            candidate_order = current_order[:]
            candidate_order[i], candidate_order[i+1] = candidate_order[i+1], candidate_order[i]
            
            # Check validity
            # We can optimize by only checking the changed boundaries?
            # No, the set of block perms is constant.
            # Only boundary perms change.
            # So we can maintain the set of block perms, and add boundary perms.
            
            # Let's stick to a simpler approach:
            # 1. Compute length of candidate.
            # 2. If length >= best_len, skip.
            # 3. Check validity.
            
            cand_len = 0
            valid = True
            # We can compute length and check validity in one pass?
            # No, validity requires the set.
            
            # Quick length check
            cand_len = 0
            for j in range(len(candidate_order)):
                block_len = 2*(n-1) + 1
                if j == 0:
                    cand_len += block_len
                else:
                    ov = 0
                    p1 = candidate_order[j-1]
                    p2 = candidate_order[j]
                    max_ov = min(len(p1), len(p2))
                    for o in range(max_ov, -1, -1):
                        if o == 0:
                            break
                        if p1[-o:] == p2[:o]:
                            ov = o
                            break
                    cand_len += block_len - ov
                    if cand_len >= best_len:
                        valid = False
                        break
            
            if not valid:
                continue
                
            # Check validity (distinctness)
            # Rebuild set
            s = set()
            for p in candidate_order:
                s.update(block_perms_cache[p])
            for j in range(len(candidate_order) - 1):
                s.update(get_boundary_perms(candidate_order[j], candidate_order[j+1]))
                
            if len(s) == target_len:
                # Valid and shorter
                current_order = candidate_order
                best_len = cand_len
                best_order = candidate_order[:]
                improved = True
                break # Restart search from new state
                
        if not improved:
            # Try 2-opt? Or just break if no swap improves.
            # For simplicity, break if no swap improves.
            break

    # Construct final word
    final_word = []
    for i, p in enumerate(best_order):
        block = list(p) + [n] + list(p)
        if i == 0:
            final_word.extend(block)
        else:
            ov = 0
            p1 = best_order[i-1]
            p2 = p
            max_ov = min(len(p1), len(p2))
            for o in range(max_ov, -1, -1):
                if o == 0:
                    break
                if p1[-o:] == p2[:o]:
                    ov = o
                    break
            final_word.extend(block[ov:])
            
    return "".join(map(str, final_word))
