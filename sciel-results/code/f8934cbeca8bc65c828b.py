"""
Strategy: Deterministic Branch-and-Bound search.
The problem is to find the longest strictly increasing sequence in [2, 128]
such that all consecutive block products are distinct.

We model this as a backtracking search where we build the sequence from left to right.
State:
- current sequence (implicitly defined by the set of suffix products)
- set of 'suffix_products': products of all suffixes of the current sequence.
  If current sequence is [a, b, c], suffixes are [c], [b, c], [a, b, c].
  Their products are c, b*c, a*b*c.
- 'used' set of numbers.

Constraint:
- All suffix products must be distinct.
- When adding a new number x to the sequence S:
  New suffixes are:
  1. [x] -> product x
  2. [last, x] -> product last * x
  3. [second_last, last, x] -> product second_last * last * x
  ...
  k. [S[0], ..., S[-1], x] -> product product(S) * x
  
  Let P = set of old suffix products.
  Let Q = set of new suffix products generated by appending x.
  The new set of suffix products is P union Q.
  Condition for validity: P and Q must be disjoint, and Q must be distinct internally.
  (Note: Q elements are distinct if x is not 1, which is true since x >= 2.
   Specifically, if suffix products of S are s_1, ..., s_k, new ones are s_1*x, ..., s_k*x, x.
   Since x >= 2, s_i * x > s_j * x if s_i > s_j. And x < s_k * x. So Q is distinct internally.)
  So we just need P ∩ Q = ∅.

Pruning:
- If len(current_seq) + (max_possible_remaining) <= best_found, prune.
- max_possible_remaining is simply the count of available numbers.
- Stronger pruning: 
  The number of distinct products in the final sequence of length L is L(L+1)/2.
  However, we are tracking suffix products. The number of suffix products for a sequence of length L is L.
  This doesn't directly limit L by the count of numbers, but by the collisions.
  
  A better bound: 
  Let k be the current length.
  Let R be the set of available numbers.
  If k + |R| <= best_len, prune.
  
  Additionally, we can use the "suffix product collision" bound.
  If the set of current suffix products S has size k.
  Any extension will add new suffix products.
  Actually, the standard B&B for this specific "distinct subarray products" problem relies on:
  If we have a prefix with suffix product set S, and we add x, the new set is S ∪ {s*x for s in S} ∪ {x}.
  Wait, the suffix products of the new sequence [S..., x] are:
  x, (last*S)*x, ..., (prod(S))*x.
  Let old suffix products be s_1, s_2, ..., s_k (where s_1 is the last element, s_k is the product of all).
  New suffix products are x, s_1*x, s_2*x, ..., s_k*x.
  So the new set of suffix products is {x} ∪ {s_i * x for i=1..k}.
  The old suffix products s_i are NOT part of the new suffix products set?
  NO. The suffixes of the new sequence are suffixes of the OLD sequence with x appended, AND x itself.
  Wait. Sequence: [a, b]. Suffixes: [b], [a, b]. Products: b, ab.
  Append c. Sequence: [a, b, c]. Suffixes: [c], [b, c], [a, b, c]. Products: c, bc, abc.
  Notice that b and ab are NO LONGER suffixes of the new sequence. They are subarrays, but not suffixes.
  The constraint is that ALL consecutive block products are distinct.
  This includes:
  - Singletons: a, b, c
  - Pairs: ab, bc
  - Triples: abc
  
  My "suffix product" state only tracks the products of suffixes.
  Does tracking suffix products suffice to check the global constraint?
  No. The constraint is global over ALL subarrays.
  
  However, if we build the sequence from left to right, when we add x:
  The new subarrays ending at x are:
  [x], [last, x], [second_last, last, x], ..., [S, x].
  Their products are x, s_1*x, s_2*x, ..., s_k*x.
  We need these to be distinct from ALL previously generated subarray products.
  
  So the state must be the set of ALL products generated so far.
  Let P be the set of all products of all subarrays in the current sequence.
  Size of P is k(k+1)/2.
  When adding x, we generate k+1 new products: x, s_1*x, ..., s_k*x.
  We need to check if any of these are in P.
  If not, we add them to P.
  
  State: (current_seq, P)
  P can get large. For k=30, |P| ~ 465.
  The numbers are up to 128. Products can be huge.
  But we only care about collisions.
  
  Branch and Bound:
  We want to maximize length.
  We try to add numbers in increasing order? Or any order?
  The sequence must be strictly increasing. So we must pick numbers in increasing order.
  So we are selecting a subsequence of [2, 3, ..., 128].
  
  Algorithm:
  best_len = 0
  best_seq = []
  
  def backtrack(start_idx, current_seq, P):
      nonlocal best_len, best_seq
      k = len(current_seq)
      if k > best_len:
          best_len = k
          best_seq = current_seq[:]
      
      # Pruning: 
      # Max possible length is k + (128 - start_idx + 1)
      if k + (128 - start_idx + 1) <= best_len:
          return
      
      # We can also prune if the number of available products is too small?
      # Total products in a sequence of length L is L(L+1)/2.
      # The products are distinct integers.
      # The smallest possible products for a sequence of length L starting with 2,3,... are fixed?
      # No, we can skip numbers.
      
      # Iterate through candidates
      for i in range(start_idx, 129):
          x = i + 1 # candidates are 2..128, so index 0 is 2
          # Generate new products
          new_prods = [x]
          prod = x
          # We need the suffix products of current_seq to compute new products efficiently?
          # Or just recompute?
          # If we store suffix products in state, we can compute new ones fast.
          # State: (start_idx, current_seq, P, suffix_prods)
          
          # Let's optimize state to include suffix_prods
          # suffix_prods: list of products of suffixes of current_seq
          # e.g. seq [2,3] -> suffixes [3], [2,3] -> prods [3, 6]
          
          # Check validity
          valid = True
          for p in new_prods:
              if p in P:
                  valid = False
                  break
          
          if not valid:
              continue
          
          # Update state
          new_P = P | set(new_prods)
          new_suffix = [x]
          prod = x
          for sp in reversed(suffix_prods): # suffix_prods are [last, ...]
              prod *= sp # Wait, suffix_prods are products.
              # If suffix_prods is [s_1, s_2] where s_1 is last elem, s_2 is last 2 elems prod.
              # New suffixes: x, s_1*x, s_2*x...
              # So new_suffix_prods = [x] + [sp * x for sp in suffix_prods]
              pass
          
          # Correct calculation of new_suffix_prods
          # Old suffixes: s_1 (last), s_2 (last 2), ...
          # New suffixes ending in x:
          # 1. x
          # 2. (last elem) * x = s_1 * x
          # 3. (last 2 elems) * x = s_2 * x
          # ...
          new_suffix_prods = [x] + [sp * x for sp in suffix_prods]
          
          # Recurse
          backtrack(i + 1, current_seq + [x], new_P, new_suffix_prods)

  # Initialization
  # candidates = 2..128
  # start_idx = 0 (corresponding to 2)
  # current_seq = []
  # P = set()
  # suffix_prods = []
  
  # This is a standard B&B. The branching factor is high (up to 127).
  # But pruning is strong if we find a good solution early.
  # Greedy gives a good initial bound.
  
  # To speed up, we can use a heuristic order for candidates?
  # No, order is fixed by "strictly increasing". We MUST pick from increasing indices.
  # So we just skip or take. This is a subset selection problem with a complex constraint.
  # The loop `for i in range(start_idx, 129)` is correct.
  
  # Optimization: 
  # The product values can become very large. Python handles big ints, but set lookups might be slow.
  # However, the number of elements in P is at most L(L+1)/2.
  # If L is around 30-40, |P| is ~1000-10000. This is manageable.
  
  # One more pruning:
  # If the number of distinct products required for length L is L(L+1)/2.
  # The minimum possible value of the largest product in a sequence of length L?
  # This is hard to bound tightly.
  
  # Let's implement and see if it finishes in 60s.
  # If not, we might need to restrict the search space or use a different heuristic.
  
  # Actually, the "suffix_prods" list grows with L.
  # And P grows with L^2.
  
  # Let's add a time check.
"""

import time

def construct():
    start_time = time.time()
    DEADLINE = 50.0  # Safety margin
    
    # Greedy baseline
    def greedy_construct():
        values, products = [], set()
        for x in range(2, 129):
            tails, prod = [x], x
            for a in reversed(values):
                prod *= a
                tails.append(prod)
            if not products.intersection(tails):
                values.append(x)
                products.update(tails)
        return values

    best_seq = greedy_construct()
    best_len = len(best_seq)
    
    # B&B Search
    # State: (next_idx, current_seq, P, suffix_prods)
    # next_idx: index in range(2, 129) to start considering
    # We map index i to number i+2.
    
    # To avoid copying lists/sets at every step, we can use backtracking with undo.
    # But Python sets and lists are mutable. 
    # We can pass them and undo changes.
    
    # Let's use a recursive function with explicit stack or recursion.
    # Recursion depth is at most 127.
    
    # We need to be careful with time.
    # If the search space is too large, we might time out.
    # The greedy solution is likely close to optimal.
    # B&B will prove optimality or find a better solution.
    
    # Optimization: 
    # Sort candidates? No, they are fixed.
    # We can try to jump to the next candidate that doesn't immediately conflict?
    # That's just the loop.
    
    # Let's implement the B&B with time checks.
    
    def solve():
        nonlocal best_len, best_seq
        
        # Candidates are 2 to 128
        # We use index 0 to 126 for 2 to 128
        
        # Initial state
        current_seq = []
        P = set()
        suffix_prods = []
        
        # We use a recursive helper
        def backtrack(start_idx):
            nonlocal best_len, best_seq
            
            if time.time() - start_time > DEADLINE:
                return False # Timeout signal
            
            k = len(current_seq)
            if k > best_len:
                best_len = k
                best_seq = current_seq[:]
            
            # Pruning
            # Max possible remaining elements: 128 - (start_idx + 2) + 1 = 127 - start_idx
            # Wait, start_idx is 0-based index for value start_idx+2.
            # Number of values from start_idx+2 to 128 is 128 - (start_idx+2) + 1 = 127 - start_idx.
            if k + (127 - start_idx) <= best_len:
                return True
            
            # Iterate candidates
            for i in range(start_idx, 127):
                x = i + 2
                
                # Generate new products
                # new_prods = [x, suffix_prods[0]*x, suffix_prods[1]*x, ...]
                # Check if any in P
                valid = True
                new_prods_list = []
                for sp in suffix_prods:
                    p = sp * x
                    new_prods_list.append(p)
                    if p in P:
                        valid = False
                        break
                if not valid:
                    continue
                
                # Check x itself
                if x in P:
                    continue
                new_prods_list.append(x)
                
                # All new products are distinct from P and each other?
                # New prods are x, s1*x, s2*x...
                # Since s_i are distinct and x>1, s_i*x are distinct.
                # x is not s_i*x because s_i >= 2 (min suffix product is last elem >= 2).
                # So new_prods_list is distinct internally.
                
                # Add to P
                added_prods = new_prods_list
                for p in added_prods:
                    P.add(p)
                
                # Update suffix_prods
                # New suffix prods: [x, s1*x, s2*x...]
                # Note: suffix_prods was [s1, s2, ...] where s1 is last elem.
                # New suffixes: x, (last)*x, ...
                # So new_suffix = [x] + [sp * x for sp in suffix_prods]
                old_suffix = suffix_prods[:]
                new_suffix = [x] + [sp * x for sp in suffix_prods]
                
                # Update current_seq
                current_seq.append(x)
                
                # Recurse
                if not backtrack(i + 1):
                    # Timeout
                    # Undo and return
                    current_seq.pop()
                    suffix_prods[:] = old_suffix
                    for p in added_prods:
                        P.discard(p)
                    return False
                
                # Undo
                current_seq.pop()
                suffix_prods[:] = old_suffix
                for p in added_prods:
                    P.discard(p)
            
            return True

        solve()

    return best_seq

if __name__ == "__main__":
    res = construct()
    print(f"Length: {len(res)}")
    print(res)
