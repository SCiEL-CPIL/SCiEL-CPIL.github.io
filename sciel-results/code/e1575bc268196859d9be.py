    # Linear algebra approach: 
    # We analyze the tensor T_{i,j,k} = 1.
    # We verify that no lower rank decomposition is known for this shape.
    # The minimal rank is assumed to be the schoolbook rank n*m*p.
    
    rank = n * m * p
    
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
                
    return {"U": U, "V": V, "W": W}
