def _validate(U, V, W, n, m, p):
    """Exact check: for every (i,j,k) triple, the tensor decomposition condition holds.
    
    The matrix multiplication tensor T has entries T[i,j,k] = 1 for all valid i,j,k.
    A rank-r decomposition gives matrices U (n*m x r), V (m*p x r), W (p*n x r) such that:
    For all i in [0,n), j in [0,m), k in [0,p):
        sum_c U[i*m+j][c] * V[j*p+k][c] * W[k*n+i][c] = 1
    """
    # Convert to numpy arrays for efficient tensor contraction
    U_np = np.array(U)
    V_np = np.array(V)
    W_np = np.array(W)
    
    r = U_np.shape[1]
    
    # Indices for the tensor product
    # We want to check T[i,j,k] = sum_c U[i,j,c] V[j,k,c] W[k,i,c]
    # Here indices are flattened: U_idx = i*m+j, V_idx = j*p+k, W_idx = k*n+i
    
    # Construct the full tensor check vectorized
    # Loop is small enough (45 triples) that a python loop is fine, but let's use numpy for clarity
    is_valid = True
    for i in range(n):
        for j in range(m):
            for k in range(p):
                u_idx = i * m + j
                v_idx = j * p + k
                w_idx = k * n + i
                # Element-wise product sum
                val = np.dot(U_np[u_idx], V_np[v_idx] * W_np[w_idx])
                if val != 1:
                    is_valid = False
                    return False
    return is_valid


def _schoolbook(n, m, p):
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
    return {"U": U, "V": V, "W": W}


