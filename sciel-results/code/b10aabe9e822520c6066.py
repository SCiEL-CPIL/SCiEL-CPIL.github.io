    def get_sums_for(x, S_old):
        """Returns list of sums contributed by x given S_old (which does not contain x)."""
        sums = [3 * x]
        for s in S_old:
            sums.append(2 * x + s)
        for i in range(len(S_old)):
            for j in range(i, len(S_old)):
                sums.append(x + S_old[i] + S_old[j])
