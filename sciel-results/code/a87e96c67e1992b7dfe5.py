def construct(k, g):
    # If k or g are not 4 and 10, fallback to standard construction
    if k != 4 or g != 10:
        return _fallback_construct(k, g)
    
    deadline = time.time() + 105  # 105s limit to be safe
    
    # Attempt to construct a smaller graph using LUG with d=4
    # LUG(4, 4) has n=512. If girth >= 10, this is a huge improvement over n=2048.
    try:
        n, edges = _construct_lug(k, g, d=4)
        if n is not None:
            if _verify_girth(n, edges, g):
                return n, edges
    except Exception:
        pass

    # Fallback to original Lazebnik-Ustimenko-Woldar construction (d=5)
    return _fallback_construct(k, g)

def _construct_lug(k, g, d):
    q = k
    # d is the diameter parameter for LUG
    # Standard LUG uses d such that girth is approx 2d+1
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    
    # Rule generation for LUG
    # This part is copied from the original fallback to ensure consistency
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges

def _verify_girth(n, edges, g):
    # Build adjacency list
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
        
    # Check degree
    for i in range(n):
        if len(adj[i]) != 4:
            return False
            
    # Check simple graph
    edge_set = set()
    for u, v in edges:
        if u == v:
            return False
        if (min(u,v), max(u,v)) in edge_set:
            return False
        edge_set.add((min(u,v), max(u,v)))
        
    # Girth check via BFS from each vertex to find shortest cycle
    from collections import deque
    
    def bfs_shortest_cycle(start):
        # BFS from start, track parent to detect cycles
        dist = [-1] * n
        parent = [-1] * n
        dist[start] = 0
        queue = deque([start])
        min_cycle = float('inf')
        
        while queue:
            u = queue.popleft()
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    parent[v] = u
                    queue.append(v)
                elif v != parent[u] and parent[v] != u:
                    # Found a cycle
                    cycle_len = dist[u] + dist[v] + 1
                    min_cycle = min(min_cycle, cycle_len)
        
        return min_cycle
    
    # Check girth from a sample of vertices (or all if small enough)
    # For n=512, checking all is fine
    for start in range(n):
        cycle = bfs_shortest_cycle(start)
        if cycle < g:
            return False
    
    return True

