        # Better: Generate 1 candidate, evaluate it. If it improves HV, add it.
        # But how to choose the candidate?
        # We can use the current archive to guide the search.
        # For each point in the archive, generate a perturbation.
        # To save evaluations, we can use a "best improvement" local search.
        
        # Strategy:
        # While we have budget:
        # 1. Select a base point from the archive (randomly or the one with highest "potential").
        # 2. Generate a candidate by perturbing the base point.
        # 3. Evaluate the candidate.
        # 4. If the candidate is non-dominated and improves HV, add it to the archive.
        
        # To maximize HV improvement, we should focus on gaps.
        # A simple heuristic: Perturb points that are "far" from others in objective space?
