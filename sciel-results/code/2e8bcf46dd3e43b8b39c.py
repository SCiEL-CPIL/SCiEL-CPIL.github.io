        # But perturbing xG is risky if it increases g.
        # Let's stick to x1, x2 perturbation first, as the front shape is the main driver of HV.
        
        step = 0
        while used < self.budget:
            if time.time() > deadline:
                break
            
            # Pick a random base point
            idx = np.random.randint(len(X_archive))
            base = X_archive[idx].copy()
            
            # Perturb x1, x2
            # Use a small step size
            step_size = 0.1
            dx1 = np.random.uniform(-step_size, step_size)
            dx2 = np.random.uniform(-step_size, step_size)
            
            cand = base.copy()
            cand[0] += dx1
            cand[1] += dx2
            cand = np.clip(cand, lo, hi)
            
            # Evaluate
            f_cand = problem(cand)
            used += 1
            
            # Check if it improves HV
            # We need to check if it is non-dominated and adds volume.
            # A quick check: is it dominated by any point in F_archive?
            # If dominated, it doesn't improve HV (unless it replaces a point? No, we keep all).
            # Actually, if it is dominated, it doesn't add to the non-dominated set, so HV doesn't change.
            # We can skip adding it.
            
            # Check dominance
            is_dominated = False
            # Vectorized check:
            # f_cand is dominated if there exists f in F_archive such that f <= f_cand and f < f_cand
            # (f <= f_cand).all(axis=1) & (f < f_cand).any(axis=1)
            
            dom_mask = np.all(F_archive <= f_cand, axis=1) & np.any(F_archive < f_cand, axis=1)
            if np.any(dom_mask):
                is_dominated = True
            
            if not is_dominated:
                # It is non-dominated. Add to archive.
                X_archive = np.vstack([X_archive, cand.reshape(1, -1)])
                F_archive = np.vstack([F_archive, f_cand.reshape(1, -1)])
                
                # Optional: Remove points dominated by the new point to keep archive small?
                # Not strictly necessary for HV calculation if we filter later, but good for memory.
                # With 200 points, it's fine.
            
            step += 1
            
            # If we have enough time, we can also try to optimize xG for the best point found?
            # No, let's keep it simple.
            
        return X_archive
