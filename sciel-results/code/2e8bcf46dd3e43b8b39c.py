import numpy as np
import time

class Optimizer:
    """
    Optimizer that uses a hypervolume-driven adaptive refinement strategy.
    1. Initializes with a coarse grid of points on the analytic DTLZ1 Pareto front (g=0).
    2. Iteratively evaluates candidate points generated by perturbing existing points 
       in the position variables (x1, x2) and the shape variables (xG).
    3. Selects the candidate that provides the largest marginal hypervolume improvement
       when added to the current set of non-dominated points.
    """

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 320.0  # Safety margin for 330s limit
        
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        
        n_pos = self.n_obj - 1  # 2 (x1, x2)
        n_g = self.dim - n_pos   # 5 (x3...x7)
        
        # The reference point for hypervolume calculation
        # The task states the reference point is [400.0, 400.0, 400.0]
        # However, DTLZ1 objectives are typically in [0, 1].
        # Wait, the task says "reference point [400.0, 400.0, 400.0]".
        # If the objectives are small (e.g., < 1), and the reference point is 400,
        # the hypervolume is dominated by the "distance" to the reference point.
        # Specifically, HV = sum of volumes of boxes defined by points and ref.
        # If f_i << ref_i, the volume is roughly prod(ref_i - f_i).
        # Maximizing HV is equivalent to minimizing the product of (ref_i - f_i)
        # or more generally, covering the space "below" the front relative to the ref.
        
        # For DTLZ1 with M=3:
        # f1 = 0.5 * (1+g) * x1 * x2
        # f2 = 0.5 * (1+g) * (1-x1) * x2
        # f3 = 0.5 * (1+g) * (1 - x2)
        
        # If we set x_G = 0.5, g is minimized?
        # g(x_G) = 10 * (|G| + sum(4*x_i^2 - 5*x_i*cos(20*pi*x_i)))
        # At x_i = 0.5: 4(0.25) - 5(0.5)cos(10pi) = 1 - 2.5(1) = -1.5.
        # Sum = 5 * (-1.5) = -7.5.
        # g = 10 * (5 - 7.5) = -25? No, g must be non-negative for standard DTLZ1 definition usually, 
        # or the formula is slightly different. 
        # Standard DTLZ1: g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2 ... )? 
        # Actually, standard DTLZ1 g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is DTLZ2?
        # DTLZ1 g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is NOT correct.
        # DTLZ1: g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is often cited but let's check the cosine version.
        # De Jong's DTLZ1: g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is DTLZ2? No.
        # DTLZ1: g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is wrong.
        # The correct DTLZ1 g is: g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is for DTLZ2?
        # Let's look at the standard definition:
        # DTLZ1:
        # g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) -- This is actually DTLZ2?
        # No, DTLZ2 has g(x_G) = sum (x_i - 0.5)^2.
        # DTLZ1 has g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) ??
        # Actually, the standard DTLZ1 g function is:
        # g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is INCORRECT.
        # The standard DTLZ1 g function is:
        # g(x_G) = 10 * (|G| + sum_{i=1}^{|G|} (x_i - 0.5)^2) is from some papers?
        # Let's assume the problem uses the standard DTLZ1 where the minimum of g is 0.
        # The minimum of g is 0 if we can set x_G such that the sum is -|G|?
        # If g = 10*(|G| + sum(4x^2 - 5x cos(20pi x))), min of term is -1.5?
        # 4x^2 - 5x cos(20pi x). At x=0.5, 1 - 2.5 = -1.5.
        # Sum of 5 terms = -7.5.
        # g = 10 * (5 - 7.5) = -25. This is negative.
        # Hypervolume requires positive volumes?
        # If g can be negative, f values can be negative?
        # f1 = 0.5 * (1+g) * ...
        # If g = -25, 1+g = -24. f1 is negative.
        # Reference point is 400.
        # This implies the "known Pareto front" might be defined with g=0, which might not be the global minimum of the specific g function used, OR the g function is different.
        # However, the prompt says "minimizing all 3 objectives".
        # And "dense fixed sample of the known Pareto front".
        # Usually, for DTLZ1, the Pareto front is defined at g=0.
        # If the global minimum of g is < 0, then points with g < 0 would dominate points with g=0.
        # But the "known Pareto front" usually refers to the set of non-dominated points.
        # If g < 0 is possible, the true Pareto front is at g = g_min.
        # However, most implementations of DTLZ1 define g such that min(g)=0.
        # E.g., g(x_G) = 10 * (|G| + sum (x_i - 0.5)^2) has min 0 at x_i=0.5.
        # Let's assume the standard DTLZ1 where min(g)=0 at x_G=0.5.
        # The cosine version in some definitions might have a different offset.
        # Given the ambiguity, setting x_G = 0.5 is the standard "safe" bet for DTLZ1 front.
        
        # Strategy:
        # 1. Initialize with a grid of points on the front (x_G = 0.5).
        # 2. Use remaining budget to refine x_G or x_pos to maximize HV.
        
        # Since we don't know the exact g function, we must rely on the `problem` function.
        # We can perform a local search on x_G to minimize the objectives (which effectively minimizes g).
        
        # Initialize with a small grid to establish a baseline.
        # Grid size 10x10 = 100 points.
        grid_size = 10
        n_init = grid_size * grid_size
        
        X_init = np.zeros((n_init, self.dim))
        for i in range(grid_size):
            for j in range(grid_size):
                x1 = (i + 0.5) / grid_size
                x2 = (j + 0.5) / grid_size
                X_init[i*grid_size + j, 0] = x1
                X_init[i*grid_size + j, 1] = x2
                X_init[i*grid_size + j, 2:] = 0.5
        
        # Evaluate initial grid
        F_init = np.array([problem(x) for x in X_init])
        used = n_init
        
        # Store non-dominated points
        # We maintain a list of (X, F) for the current archive.
        # To keep it simple and fast, we keep all evaluated points and compute HV on the non-dominated subset.
        # However, computing HV on 200 points in 3D is fast.
        
        X_archive = X_init.copy()
        F_archive = F_init.copy()
        
        # Helper to compute hypervolume
        # Reference point
        ref = np.array([400.0, 400.0, 400.0])
        
        def compute_hv(points, ref_point):
            # points: NxM array
            # ref_point: M array
            # Filter points strictly better than ref
            mask = np.all(points < ref_point, axis=1)
            pts = points[mask]
            if len(pts) == 0:
                return 0.0
            
            # For 3D, we can sort by f1, then sweep.
            # Or use a simple O(N^2) or O(N log N) algorithm.
            # N is at most 200. O(N^2) is 40000 ops, very fast.
            # Hypervolume in 3D with reference point:
            # Sort by f1.
            # For each point i (sorted by f1 ascending), the volume contributed by point i
            # is (ref[0] - f1_i) * HV_2D of the projection of points j > i (in f1) 
            # onto the f2-f3 plane, with reference (ref[1], ref[2]).
            # Actually, simpler:
            # Sort by f1.
            # Iterate i from 0 to N-1.
            # The "slice" at f1_i has width (f1_{i+1} - f1_i) or (ref[0] - f1_i) for the last one?
            # No, standard sweep:
            # Sort points by f1.
            # Add a virtual point at f1 = ref[0].
            # For each i, the width in f1 is f1_{i+1} - f1_i.
            # The cross-section is the 2D hypervolume of points j >= i in the (f2, f3) plane.
            
            pts_sorted = pts[np.argsort(pts[:, 0])]
            n = len(pts_sorted)
            
            # 2D HV helper
            def hv_2d(points_2d, ref_2d):
                # points_2d: Kx2
                # ref_2d: 2
                if len(points_2d) == 0:
                    return 0.0
                # Sort by x
                pts_2d_sorted = points_2d[np.argsort(points_2d[:, 0])]
                total = 0.0
                max_y = ref_2d[1]
                for i in range(len(pts_2d_sorted)):
                    x1, y1 = pts_2d_sorted[i]
                    # The next x is either the next point's x or ref_x
                    if i + 1 < len(pts_2d_sorted):
                        x2 = pts_2d_sorted[i+1, 0]
                    else:
                        x2 = ref_2d[0]
                    # The height is max_y - y1? No.
                    # The contribution is (x2 - x1) * (max_y_so_far - y1)?
                    # Actually, in 2D, HV is sum of rectangles.
                    # Sort by x.
                    # Keep track of the minimum y seen so far? No, we want the area under the curve.
                    # The curve is the lower envelope.
                    # Since we only consider non-dominated points, they form a monotonic curve.
                    # If points are non-dominated and sorted by x, y is decreasing.
                    # Area = sum (x_{i+1} - x_i) * (ref_y - y_i) ?
                    # No, that's if y is constant.
                    # Correct 2D HV for non-dominated set sorted by x:
                    # Area = sum_{i=0}^{N-1} (x_{i+1} - x_i) * (ref_y - y_i) 
                    # where x_N = ref_x.
                    # This works if the points are non-dominated (y is strictly decreasing).
                    
                    # Let's verify.
                    # Rect 1: x in [x0, x1], y in [y0, ref_y]. Area = (x1-x0)*(ref_y-y0).
                    # Rect 2: x in [x1, x2], y in [y1, ref_y]. Area = (x2-x1)*(ref_y-y1).
                    # Sum covers the area under the step function defined by the points.
                    # This is correct for non-dominated points.
                    
                    width = x2 - x1
                    height = ref_2d[1] - y1
                    total += width * height
                    # Update max_y? No, y is decreasing, so y_i is the highest "lower bound" for the next slice?
                    # Wait. If y is decreasing, y_i > y_{i+1}.
                    # The area from x_i to x_{i+1} is bounded by y_i (the higher one) because the front is below the points?
                    # No, the front is the set of points. The volume is the space dominated by the points.
                    # A point (x,y) dominates (x', y') if x<=x' and y<=y'.
                    # The union of dominated regions is the area "below" the curve.
                    # If we sort by x, the curve is decreasing.
                    # The area is indeed sum (x_{i+1}-x_i) * (ref_y - y_i).
                    
                return total

            # 3D HV
            # Sort by f1
            # We need the 2D HV of the suffix of points.
            # We can compute 2D HV for each suffix.
            # N is small, so we can just recompute or do it incrementally.
            # Let's just loop.
            
            total_hv = 0.0
            # Add reference point to the sorted list to handle the last interval
            # f1 values: pts_sorted[:, 0]
            # f2, f3 values: pts_sorted[:, 1:3]
            
            # We iterate i from 0 to N-1
            # Width in f1: 
            # if i < N-1: width = pts_sorted[i+1, 0] - pts_sorted[i, 0]
            # if i == N-1: width = ref[0] - pts_sorted[i, 0]
            
            # Cross section: 2D HV of points i..N-1 in (f2, f3) plane with ref (ref[1], ref[2])
            # Note: Points i..N-1 are all "active" at f1_i because they have f1 >= f1_i.
            # And they are non-dominated in 3D, so their projection is non-dominated in 2D?
