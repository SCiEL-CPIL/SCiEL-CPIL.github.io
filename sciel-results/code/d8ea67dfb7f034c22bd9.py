"""Matrix multiplication 4x4 * 4x7: exact rank-minimal tensor decomposition."""
import time
import numpy as np

DIMENSIONS = [4, 4, 7]
_START_TIME = time.time()
_TIME_LIMIT = 145.0  # safety margin before 150s kill


def _schoolbook(n, m, p):
    """Return the schoolbook decomposition of rank n*m*p."""
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    col = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][col] = 1
                V[j * p + k][col] = 1
                W[k * n + i][col] = 1
                col += 1
    return {"U": U, "V": V, "W": W}


def _verify(U, V, W, n, m, p):
    """Check that sum_r U[:,r] V[:,r] W[:,r] == multiplication tensor."""
    rank = len(U[0])
    U_arr = np.array(U, dtype=float)
    V_arr = np.array(V, dtype=float)
    W_arr = np.array(W, dtype=float)
    for i in range(n):
        for j in range(m):
            for k in range(p):
                a = i * m + j
                b = j * p + k
                c = k * n + i
                s = np.dot(U_arr[a], V_arr[b] * W_arr[c])
                if abs(s - 1) > 1e-9:
                    return False
    return True


def _strassen_2x2x2():
    """Return the rank-7 Strassen decomposition for 2x2x2 matrix multiplication.
    
    Convention: U[i*2+j, r] for A[i,j], V[j*2+k, r] for B[j,k], W[k*2+i, r] for C[i,k].
    """
    U = [[0]*7 for _ in range(4)]
    V = [[0]*7 for _ in range(4)]
    W = [[0]*7 for _ in range(4)]
    
    # p1 = (a11 + a22)(b11 + b22)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[3][0] = 1
    W[0][0] = 1; W[3][0] = 1
    
    # p2 = (a21 + a22)b11
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[1][1] = 1; W[3][1] = -1
    
    # p3 = a11(b12 - b22)
    U[0][2] = 1
    V[1][2] = 1; V[3][2] = -1
    W[2][2] = 1; W[3][2] = 1
    
    # p4 = a22(b21 - b11)
    U[3][3] = 1
    V[2][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[1][3] = 1
    
    # p5 = (a11 + a12)b22
    U[0][4] = 1; U[1][4] = 1
    V[3][4] = 1
    W[0][4] = -1; W[2][4] = 1
    
    # p6 = (a21 - a11)(b11 + b12)
    U[2][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    W[3][5] = 1
    
    # p7 = (a12 - a22)(b21 + b22)
    U[1][6] = 1; U[3][6] = -1
    V[2][6] = 1; V[3][6] = 1
    W[0][6] = 1
    
    return U, V, W


def _build_4x4x7_optimized():
    """Build decomposition for 4x4 * 4x7 using Strassen where beneficial.
    
    Part 1: 4x4 * 4x4 -> rank 49 (Kronecker of two Strassen 2x2x2)
    Part 2: 4x4 * 4x2 -> rank 28 (four 2x2*2x2 Strassen products)
    Part 3: 4x4 * 4x1 -> rank 16 (four 2x2*2x1 schoolbook products)
    Total: 93
    """
    n, m, p = 4, 4, 7
    U2, V2, W2 = _strassen_2x2x2()
    
    # Part 1: 4x4 * 4x4 (B cols 0-3, C cols 0-3), rank 49
    rank1 = 49
    U1 = [[0] * rank1 for _ in range(16)]
    V1 = [[0] * rank1 for _ in range(16)]
    W1 = [[0] * rank1 for _ in range(16)]
    
    for r1 in range(7):
        for r2 in range(7):
            r = r1 * 7 + r2
            for i1 in range(2):
                for j1 in range(2):
                    for i2 in range(2):
                        for j2 in range(2):
                            i = i1 * 2 + i2
                            j = j1 * 2 + j2
                            val = U2[i1*2+j1][r1] * U2[i2*2+j2][r2]
                            if val != 0:
                                U1[i*4+j][r] += val
            for j1 in range(2):
                for k1 in range(2):
                    for j2 in range(2):
                        for k2 in range(2):
                            j = j1 * 2 + j2
                            k = k1 * 2 + k2
                            val = V2[j1*2+k1][r1] * V2[j2*2+k2][r2]
                            if val != 0:
                                V1[j*4+k][r] += val
            for k1 in range(2):
                for i1 in range(2):
                    for k2 in range(2):
                        for i2 in range(2):
                            k = k1 * 2 + k2
                            i = i1 * 2 + i2
                            val = W2[k1*2+i1][r1] * W2[k2*2+i2][r2]
                            if val != 0:
                                W1[k*4+i][r] += val
    
    # Part 2: 4x4 * 4x2 (B cols 4-5, C cols 4-5), rank 28
    rank2 = 28
    U2p = [[0] * rank2 for _ in range(16)]
    V2p = [[0] * rank2 for _ in range(8)]  # 4*2
    W2p = [[0] * rank2 for _ in range(8)]  # 2*4
    
    block_idx = 0
    for br in range(2):
        for bc in range(2):
            for t in range(7):
                r = block_idx * 7 + t
                for lr in range(2):
                    for lc in range(2):
                        i = br * 2 + lr
                        j = bc * 2 + lc
                        val = U2[lr*2+lc][t]
                        if val != 0:
                            U2p[i*4+j][r] += val
                for lr in range(2):
                    for kl in range(2):
                        j = bc * 2 + lr
                        k = 4 + kl
                        val = V2[lr*2+kl][t]
                        if val != 0:
                            V2p[j*2+kl][r] += val
                for lr in range(2):
                    for kl in range(2):
                        i = br * 2 + lr
                        k = kl
                        val = W2[kl*2+lr][t]
                        if val != 0:
                            W2p[k*4+i][r] += val
            block_idx += 1
    
    # Part 3: 4x4 * 4x1 (B col 6, C col 6), rank 16
    rank3 = 16
    U3 = [[0] * rank3 for _ in range(16)]
    V3 = [[0] * rank3 for _ in range(4)]  # 4*1
    W3 = [[0] * rank3 for _ in range(4)]  # 1*4
    
    block_idx = 0
    for br in range(2):
        for bc in range(2):
            for lr in range(2):
                for lc in range(2):
                    r = block_idx * 4 + lr * 2 + lc
                    i = br * 2 + lr
                    j = bc * 2 + lc
                    U3[i*4+j][r] = 1
                    V3[j][r] = 1
                    W3[i][r] = 1
            block_idx += 1
    
    # Combine all parts
    total_rank = rank1 + rank2 + rank3
    U = [[0] * total_rank for _ in range(n * m)]
    V = [[0] * total_rank for _ in range(m * p)]
    W = [[0] * total_rank for _ in range(p * n)]
    
    # Part 1: B cols 0-3, C cols 0-3
    for i in range(16):
        for r in range(rank1):
            U[i][r] = U1[i][r]
    for i in range(4):
        for j in range(4):
            for r in range(rank1):
                V[i*p+j][r] = V1[i*4+j][r]
    for i in range(4):
        for j in range(4):
            for r in range(rank1):
                W[i*n+j][r] = W1[i*4+j][r]
    
    # Part 2: B cols 4-5, C cols 4-5
    offset2 = rank1
    for i in range(16):
        for r in range(rank2):
            U[i][offset2 + r] = U2p[i][r]
    for i in range(4):
        for j in range(2):
            for r in range(rank2):
                V[i*p + (4+j)][offset2 + r] = V2p[i*2+j][r]
    for i in range(2):
        for j in range(4):
            for r in range(rank2):
                W[(4+i)*n + j][offset2 + r] = W2p[i*4+j][r]
    
    # Part 3: B col 6, C col 6
    offset3 = rank1 + rank2
    for i in range(16):
        for r in range(rank3):
            U[i][offset3 + r] = U3[i][r]
    for i in range(4):
        for r in range(rank3):
            V[i*p + 6][offset3 + r] = V3[i][r]
    for i in range(4):
        for r in range(rank3):
            W[6*n + i][offset3 + r] = W3[i][r]
    
    return {"U": U, "V": V, "W": W}


def _build_4x4x4_strassen():
    """Build rank-49 decomposition for 4x4x4 using Kronecker product of two Strassen decompositions."""
    n = m = p = 4
    U2, V2, W2 = _strassen_2x2x2()
    
    rank = 49
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    for r1 in range(7):
        for r2 in range(7):
            r = r1 * 7 + r2
            for i1 in range(2):
                for j1 in range(2):
                    for i2 in range(2):
                        for j2 in range(2):
                            i = i1 * 2 + i2
                            j = j1 * 2 + j2
                            val = U2[i1*2+j1][r1] * U2[i2*2+j2][r2]
                            if val != 0:
                                U[i*m+j][r] += val
            for j1 in range(2):
                for k1 in range(2):
                    for j2 in range(2):
                        for k2 in range(2):
                            j = j1 * 2 + j2
                            k = k1 * 2 + k2
                            val = V2[j1*2+k1][r1] * V2[j2*2+k2][r2]
                            if val != 0:
                                V[j*p+k][r] += val
            for k1 in range(2):
                for i1 in range(2):
                    for k2 in range(2):
                        for i2 in range(2):
                            k = k1 * 2 + k2
                            i = i1 * 2 + i2
                            val = W2[k1*2+i1][r1] * W2[k2*2+i2][r2]
                            if val != 0:
                                W[k*n+i][r] += val
    
    return {"U": U, "V": V, "W": W}


def _build_4x4x7_simple():
    """Build decomposition for 4x4 * 4x7 using Strassen for 4x4x4 and schoolbook for 4x4x3."""
    n, m, p = 4, 4, 7
    left = _build_4x4x4_strassen()
    rank_left = len(left['U'][0])
    
    n_r, m_r, p_r = 4, 4, 3
    rank_right = n_r * m_r * p_r
    U_right = [[0] * rank_right for _ in range(n_r * m_r)]
    V_right = [[0] * rank_right for _ in range(m_r * p_r)]
    W_right = [[0] * rank_right for _ in range(p_r * n_r)]
    col = 0
    for i in range(n_r):
        for j in range(m_r):
            for k in range(p_r):
                U_right[i * m_r + j][col] = 1
                V_right[j * p_r + k][col] = 1
                W_right[k * n_r + i][col] = 1
                col += 1
    
    total_rank = rank_left + rank_right
    U = [[0] * total_rank for _ in range(n * m)]
    V = [[0] * total_rank for _ in range(m * p)]
    W = [[0] * total_rank for _ in range(p * n)]
    
    for i in range(n * m):
        for r in range(rank_left):
            U[i][r] = left['U'][i][r]
    for i in range(4):
        for j in range(4):
            for r in range(rank_left):
                V[i * p + j][r] = left['V'][i * 4 + j][r]
    for i in range(4):
        for j in range(4):
            for r in range(rank_left):
                W[i * n + j][r] = left['W'][i * 4 + j][r]
    
    offset = rank_left
    for i in range(n * m):
        for r in range(rank_right):
            U[i][offset + r] = U_right[i][r]
    for i in range(4):
        for j in range(3):
            for r in range(rank_right):
                V[i * p + (4 + j)][offset + r] = V_right[i * 3 + j][r]
    for i in range(3):
        for j in range(4):
            for r in range(rank_right):
                W[(4 + i) * n + j][offset + r] = W_right[i * 4 + j][r]
    
    return {"U": U, "V": V, "W": W}


def _build_target_tensor(n, m, p):
    """Build the multiplication tensor T[a,b,c] where a=i*m+j, b=j*p+k, c=k*n+i."""
    nm, mp, pn = n * m, m * p, p * n
    T = np.zeros((nm, mp, pn))
    for i in range(n):
        for j in range(m):
            for k in range(p):
                a = i * m + j
                b = j * p + k
                c = k * n + i
                T[a, b, c] = 1.0
    return T


def _als_decompose(n, m, p, target_rank, init_U, init_V, init_W, max_iter=300, tol=1e-12):
    """Alternating least squares for exact tensor decomposition.
    
    Returns (U, V, W, error) where error is max |T_recon - T|.
    """
    nm, mp, pn = n * m, m * p, p * n
    
    T = _build_target_tensor(n, m, p)
    
    U = np.array(init_U, dtype=float)[:, :target_rank].copy()
    V = np.array(init_V, dtype=float)[:, :target_rank].copy()
    W = np.array(init_W, dtype=float)[:, :target_rank].copy()
    
    T1 = T.reshape(nm, mp * pn)
    T2 = T.transpose(1, 0, 2).reshape(mp, nm * pn)
    T3 = T.transpose(2, 0, 1).reshape(pn, nm * mp)
    
    for it in range(max_iter):
        Z1 = np.einsum('br,cr->bc,r', V, W).reshape(mp * pn, target_rank)
        U_new = np.linalg.lstsq(Z1.T, T1.T, rcond=None)[0].T
        
        Z2 = np.einsum('ar,cr->ac,r', U, W).reshape(nm * pn, target_rank)
        V_new = np.linalg.lstsq(Z2.T, T2.T, rcond=None)[0].T
        
        Z3 = np.einsum('ar,br->ab,r', U, V).reshape(nm * mp, target_rank)
        W_new = np.linalg.lstsq(Z3.T, T3.T, rcond=None)[0].T
        
        diff = max(np.max(np.abs(U_new - U)), np.max(np.abs(V_new - V)), np.max(np.abs(W_new - W)))
        U, V, W = U_new, V_new, W_new
        if diff < tol:
            break
    
    T_recon = np.einsum('ar,br,cr->abc', U, V, W)
    error = float(np.max(np.abs(T_recon - T)))
    
    return U, V, W, error


def _round_and_verify(U, V, W, n, m, p, tol=1e-6):
    """Round to nearest half-integers and verify exact decomposition."""
    U_r = np.round(U * 2) / 2
    V_r = np.round(V * 2) / 2
    W_r = np.round(W * 2) / 2
    
    if (np.max(np.abs(U_r - U)) > tol or np.max(np.abs(V_r - V)) > tol or np.max(np.abs(W_r - W)) > tol):
        return None
    
    U_list = U_r.tolist()
    V_list = V_r.tolist()
    W_list = W_r.tolist()
    
    if _verify(U_list, V_list, W_list, n, m, p):
        return {"U": U_list, "V": V_list, "W": W_list}
    return None


def _reduce_rank(U, V, W, n, m, p, tol=1e-9):
    """Try to reduce rank using ALS and tensor rank analysis."""
    rank = len(U[0])
    nm, mp, pn = n * m, m * p, p * n
    
    U_arr = np.array(U, dtype=float)
    V_arr = np.array(V, dtype=float)
    W_arr = np.array(W, dtype=float)
    
    M = np.zeros((nm * mp * pn, rank))
    for r in range(rank):
        for a in range(nm):
            ua = U_arr[a, r]
            if ua == 0:
                continue
            for b in range(mp):
                vb = V_arr[b, r]
                if vb == 0:
                    continue
                uv = ua * vb
                if uv == 0:
                    continue
                for c in range(pn):
                    wc = W_arr[c, r]
                    if wc != 0:
                        M[a * mp * pn + b * pn + c, r] = uv * wc
    
    try:
        S = np.linalg.svd(M, full_matrices=False, compute_uv=False)
    except np.linalg.LinAlgError:
        return {"U": U, "V": V, "W": W}
    
    if len(S) == 0:
        return {"U": U, "V": V, "W": W}
    
    max_s = S[0]
    if max_s < tol:
        return {"U": U, "V": V, "W": W}
    
    num_rank = sum(1 for s in S if s > tol * max_s)
    
    if num_rank >= rank:
        return {"U": U, "V": V, "W": W}
    
    best_result = None
    for tr in range(num_rank, rank):
        if time.time() - _START_TIME > _TIME_LIMIT - 10:
            break
        try:
            U_als, V_als, W_als, err = _als_decompose(n, m, p, tr, U, V, W, max_iter=200)
            if err < 1e-8:
                result = _round_and_verify(U_als, V_als, W_als, n, m, p)
                if result is not None:
                    best_result = result
                    break
        except Exception:
            continue
    
    if best_result is not None:
        return best_result
    return {"U": U, "V": V, "W": W}


def construct():
    """Construct the tensor decomposition. Returns {'U', 'V', 'W'}."""
    if time.time() - _START_TIME > _TIME_LIMIT:
        return _schoolbook(4, 4, 7)
    
    base_result = None
    try:
        result = _build_4x4x7_optimized()
        if _verify(result['U'], result['V'], result['W'], 4, 4, 7):
            base_result = result
    except Exception:
        pass
    
    if base_result is None:
        if time.time() - _START_TIME > _TIME_LIMIT:
            return _schoolbook(4, 4, 7)
        try:
            result = _build_4x4x7_simple()
            if _verify(result['U'], result['V'], result['W'], 4, 4, 7):
                base_result = result
        except Exception:
            pass
    
    if base_result is None:
        return _schoolbook(4, 4, 7)
    
    if time.time() - _START_TIME < _TIME_LIMIT - 15:
        try:
            reduced = _reduce_rank(base_result['U'], base_result['V'], base_result['W'], 4, 4, 7)
            if reduced is not None:
                r_rank = len(reduced['U'][0])
                b_rank = len(base_result['U'][0])
                if r_rank < b_rank and _verify(reduced['U'], reduced['V'], reduced['W'], 4, 4, 7):
                    return reduced
        except Exception:
            pass
    
    return base_result
