import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 85.0  # Safety margin for 90s limit
    n = 256
    max_size = 64
    
    def elapsed():
        return time.time() - start_time

    def is_valid_solution(A, B):
        if not A or not B:
            return False
        if len(A) > 64 or len(B) > 64:
            return False
        
        # Check Sidon for A
        sums_A = set()
        for i in range(len(A)):
            for j in range(i, len(A)):
                s = A[i] + A[j]
                if s in sums_A:
                    return False
                sums_A.add(s)
        
        # Check Sidon for B
        sums_B = set()
        for i in range(len(B)):
            for j in range(i, len(B)):
                s = B[i] + B[j]
                if s in sums_B:
                    return False
                sums_B.add(s)
        
        # Check disjoint differences
        diffs_A = set()
        for i in range(len(A)):
            for j in range(i+1, len(A)):
                diffs_A.add(abs(A[j] - A[i]))
        diffs_B = set()
        for i in range(len(B)):
            for j in range(i+1, len(B)):
                diffs_B.add(abs(B[j] - B[i]))
                
        if diffs_A & diffs_B:
            return False
            
        return True

    def can_add(x, S, sums_mask, diff_mask_self, diff_mask_other):
        """
        Check if x can be added to S.
        S: list of elements
        sums_mask: int bitmask where bit s is set if s is a sum in S
        diff_mask_self: int bitmask where bit d is set if d is a diff in S
        diff_mask_other: int bitmask where bit d is set if d is a diff in the other set
        Returns: (bool, new_diffs_list) or (False, None)
        """
        # Check Sidon condition: x+s not in sums_mask for all s in S, and 2x not in sums_mask
        # sums_mask has bits 0..511 set.
        if (sums_mask >> (2*x)) & 1:
            return False, None
        
        for s in S:
            if (sums_mask >> (x+s)) & 1:
                return False, None
        
        # Check difference condition: |x-s| not in diff_mask_other and |x-s| not in diff_mask_self?
        # Wait, the constraint is that the *sets* of differences are disjoint.
        # So new diffs generated by x with existing elements in S must not be in diff_mask_other.
        # Do they need to be disjoint from existing diffs in S? No, Sidon set differences can repeat?
        # No, Sidon set definition: pairwise sums are unique. This implies pairwise differences are unique?
        # If a-b = c-d, then a+d = c+b. If {a,b,c,d} are distinct, this is a collision of sums.
        # If a-b = a-b, trivial.
        # So yes, in a Sidon set, all non-zero differences are unique.
        # So we must also ensure new diffs are not in diff_mask_self?
        # Actually, if we maintain diff_mask_self correctly, and we check against it, we ensure uniqueness.
        # But the primary constraint for the *task* is disjointness between A and B.
        # The Sidon constraint implies uniqueness within A.
        # So: new_diff must not be in diff_mask_other (task constraint) AND new_diff must not be in diff_mask_self (Sidon constraint).
        
        new_diffs = []
        for s in S:
            d = abs(x - s)
            if d == 0: continue
            if (diff_mask_other >> d) & 1:
                return False, None
            if (diff_mask_self >> d) & 1:
                return False, None
            new_diffs.append(d)
            
        return True, new_diffs

    def greedy_build(candidates, diff_mask_other, target_size=20):
        S = []
        sums_mask = 0
        diff_mask_self = 0
        
        # Sort candidates? Random is better for diversity.
        local_candidates = candidates[:]
        random.shuffle(local_candidates)
        
        for x in local_candidates:
            if len(S) >= target_size:
                break
            ok, new_diffs = can_add(x, S, sums_mask, diff_mask_self, diff_mask_other)
            if ok:
                S.append(x)
                # Update sums_mask
                sums_mask |= (1 << (2*x))
                for s in S[:-1]:
                    sums_mask |= (1 << (x+s))
                # Update diff_mask_self
                for d in new_diffs:
                    diff_mask_self |= (1 << d)
                    
        return S, sums_mask, diff_mask_self

    def local_search(A, B, sums_mask_A, diff_mask_A, sums_mask_B, diff_mask_B):
        """
        Try to insert elements into A or B that were missed.
        """
        # Create a set of used numbers? No, A and B can overlap?
        # "A and B need not themselves be disjoint."
        # So we can try to add any x in [1, 256] to A or B.
        
        # We need to track which sums/diffs are used.
        # We will iterate through all possible x, and try to add to A, then B.
        # If we add to A, diff_mask_A changes, which might block B additions.
        # So we should be careful or do separate passes.
        
        # Pass 1: Try to add to A
        for x in range(1, 257):
            if x in A: continue
            ok, new_diffs = can_add(x, A, sums_mask_A, diff_mask_A, diff_mask_B)
            if ok:
                A.append(x)
                sums_mask_A |= (1 << (2*x))
                for s in A[:-1]:
                    sums_mask_A |= (1 << (x+s))
                for d in new_diffs:
                    diff_mask_A |= (1 << d)
                    
        # Pass 2: Try to add to B
        for x in range(1, 257):
            if x in B: continue
            ok, new_diffs = can_add(x, B, sums_mask_B, diff_mask_B, diff_mask_A)
            if ok:
                B.append(x)
                sums_mask_B |= (1 << (2*x))
                for s in B[:-1]:
                    sums_mask_B |= (1 << (x+s))
                for d in new_diffs:
                    diff_mask_B |= (1 << d)
                    
        return A, B, sums_mask_A, diff_mask_A, sums_mask_B, diff_mask_B

    best_score = 0
    best_sets = ([1], [2])
    
    candidates = list(range(1, n + 1))
    
    # We will run multiple iterations with different random seeds/orders
    # Since we don't pre-partition diffs, the greedy builder will naturally
    # create disjoint diff sets because it checks against the other set's diffs.
    # Wait, if we build A first, it uses some diffs. Then we build B, checking against A's diffs.
    # This ensures disjointness.
    
    for iteration in range(5000):
        if elapsed() > deadline:
            break
            
        # Build A first
        A, sums_A, diffs_A = greedy_build(candidates, 0, target_size=20)
        if not A:
            continue
            
        # Build B, constrained by A's diffs
        B, sums_B, diffs_B = greedy_build(candidates, diffs_A, target_size=20)
        if not B:
            continue
        
        # Local Search to fill in gaps
        A, B, sums_A, diffs_A, sums_B, diffs_B = local_search(A, B, sums_A, diffs_A, sums_B, diffs_B)
        
        score = len(A) + len(B)
        if score > best_score:
            best_score = score
            best_sets = (A[:], B[:])
            
            # Early exit if we hit theoretical max?
            # Max Sidon size in [1,256] is 16. So max total is 32.
            if best_score >= 32:
                break

    if best_score == 0:
        A = [1]
        B = [2]
        best_sets = (A, B)

    return list(best_sets)
