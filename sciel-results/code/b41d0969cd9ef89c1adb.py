"""Alternative decomposition for 3x3x3 matrix multiplication."""

def construct():
    """
    Tensor decomposition for 3x3x3 matrix multiplication.
    Uses a rank-20 construction based on block Strassen + explicit cross terms.
    """
    n = m = p = 3
    rank = 20
    
    U = [[0] * rank for _ in range(n * m)]  # 9 x rank
    V = [[0] * rank for _ in range(m * p)]  # 9 x rank
    W = [[0] * rank for _ in range(p * n)]  # 9 x rank, W[k*n+i, r] for C[i,k]
    
    r = 0
    # 7 products: top-left 2x2 (Strassen)
    # M0=(A00+A11)(B00+B11)
    U[0*3+0][r]=1; U[1*3+1][r]=1; V[0*3+0][r]=1; V[1*3+1][r]=1
    W[0*3+0][r]=1; W[1*3+0][r]=-1; W[0*3+1][r]=-1; W[1*3+1][r]=1; r+=1
    # M1=(A10+A11)B00
    U[1*3+0][r]=1; U[1*3+1][r]=1; V[0*3+0][r]=1
    W[0*3+1][r]=1; r+=1
    # M2=A00(B10-B11)
    U[0*3+0][r]=1; V[1*3+0][r]=1; V[1*3+1][r]=-1
    W[0*3+0][r]=1; W[1*3+0][r]=-1; r+=1
    # M3=A11(B00-B01)
    U[1*3+1][r]=1; V[0*3+0][r]=1; V[0*3+1][r]=-1
    W[0*3+1][r]=1; W[1*3+1][r]=-1; r+=1
    # M4=(A00+A01)B11
    U[0*3+0][r]=1; U[0*3+1][r]=1; V[1*3+1][r]=1
    W[1*3+0][r]=1; r+=1
    # M5=(A10-A00)(B00+B01)
    U[1*3+0][r]=1; U[0*3+0][r]=-1; V[0*3+0][r]=1; V[0*3+1][r]=1
    W[0*3+0][r]=1; W[1*3+0][r]=1; W[0*3+1][r]=-1; W[1*3+1][r]=-1; r+=1
    # M6=(A01-A11)(B10+B11)
    U[0*3+1][r]=1; U[1*3+1][r]=-1; V[1*3+0][r]=1; V[1*3+1][r]=1
    W[1*3+0][r]=1; W[0*3+1][r]=1; W[1*3+1][r]=-1; r+=1
    
    # 7 products: bottom-right 2x2 (Strassen)
    # M7=(A11+A22)(B11+B22)
    U[1*3+1][r]=1; U[2*3+2][r]=1; V[1*3+1][r]=1; V[2*3+2][r]=1
    W[1*3+1][r]=1; W[2*3+1][r]=-1; W[1*3+2][r]=-1; W[2*3+2][r]=1; r+=1
    # M8=(A21+A22)B11
    U[2*3+1][r]=1; U[2*3+2][r]=1; V[1*3+1][r]=1
    W[1*3+2][r]=1; r+=1
    # M9=A22(B11-B12)
    U[2*3+2][r]=1; V[1*3+1][r]=1; V[1*3+2][r]=-1
    W[1*3+2][r]=1; W[2*3+2][r]=-1; r+=1
    # M10=A11(B21-B22)
    U[1*3+1][r]=1; V[2*3+1][r]=1; V[2*3+2][r]=-1
    W[1*3+2][r]=1; W[2*3+2][r]=-1; r+=1
    # M11=(A11+A12)B22
    U[1*3+1][r]=1; U[1*3+2][r]=1; V[2*3+2][r]=1
    W[2*3+2][r]=1; r+=1
    # M12=(A21-A11)(B11+B12)
    U[2*3+1][r]=1; U[1*3+1][r]=-1; V[1*3+1][r]=1; V[1*3+2][r]=1
    W[1*3+2][r]=1; W[2*3+2][r]=1; W[1*3+3][r]=-1; W[2*3+3][r]=-1; r+=1
    # M13=(A12-A22)(B21+B22)
    U[1*3+2][r]=1; U[2*3+2][r]=-1; V[2*3+1][r]=1; V[2*3+2][r]=1
    W[2*3+2][r]=1; W[1*3+3][r]=1; W[2*3+3][r]=-1; r+=1
    
    # 6 cross-term products
    # M14=A01*B10 (for C00)
    U[0*3+1][r]=1; V[1*3+0][r]=1; W[0*3+0][r]=1; r+=1
    # M15=A02*B20 (for C00)
    U[0*3+2][r]=1; V[2*3+0][r]=1; W[0*3+0][r]=1; r+=1
    # M16=A12*B20 (for C10)
    U[1*3+2][r]=1; V[2*3+0][r]=1; W[0*3+1][r]=1; r+=1
    # M17=A20*B00 (for C20)
    U[2*3+0][r]=1; V[0*3+0][r]=1; W[0*3+2][r]=1; r+=1
    # M18=A21*B10 (for C20)
    U[2*3+1][r]=1; V[1*3+0][r]=1; W[0*3+2][r]=1; r+=1
    # M19=A22*B20 (for C20)
    U[2*3+2][r]=1; V[2*3+0][r]=1; W[0*3+2][r]=1; r+=1
    
    assert r == rank, f"Expected {rank} products, got {r}"
    return {"U": U, "V": V, "W": W}
