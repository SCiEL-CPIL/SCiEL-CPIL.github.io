import time
import random
from collections import deque

def _luw_construct(k, g):
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]
    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)
    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges

def _check_girth(n, edges, g):
    """Check if graph with n vertices and given edges has girth >= g."""
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    
    for start in range(n):
        dist = [-1] * n
        parent = [-1] * n
        dist[start] = 0
        queue = deque([start])
        while queue:
            u = queue.popleft()
            if dist[u] >= g - 1:
                continue
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    parent[v] = u
                    queue.append(v)
                elif v != parent[u] and dist[v] <= dist[u]:
                    cycle_len = dist[u] + dist[v] + 1
                    if cycle_len < g:
                        return False
    return True

def _voltage_construct(k, g, deadline):
    """
    Voltage graph construction on K4 base with Z_m group.
    K4 has 6 edges. We assign voltages (a,b,c,d,e,f) to each edge.
    The covering graph has 4*m vertices.
    Edge 0-1: voltage a, 0-2: voltage b, 0-3: voltage c,
    Edge 1-2: voltage d, 1-3: voltage e, 2-3: voltage f.
    """
    if k != 3:
        return None
    
    def build_graph(m, voltages):
        a, b, c, d, e, f = voltages
        n = 4 * m
        edges = []
        for t in range(m):
            edges.append((0 * m + t, 1 * m + (t + a) % m))
        for t in range(m):
            edges.append((0 * m + t, 2 * m + (t + b) % m))
        for t in range(m):
            edges.append((0 * m + t, 3 * m + (t + c) % m))
        for t in range(m):
            edges.append((1 * m + t, 2 * m + (t + d) % m))
        for t in range(m):
            edges.append((1 * m + t, 3 * m + (t + e) % m))
        for t in range(m):
            edges.append((2 * m + t, 3 * m + (t + f) % m))
        return n, edges
    
    # Moore bound for (3,16): 1 + 3 + 3*2 + 3*2^2 + ... + 3*2^7 = 1 + 3*(2^8 - 1) = 1 + 3*255 = 766
    # Actually Moore bound for odd girth: 1 + k * (k-1)^((g-1)/2 - 1) ... let's just use known lower bound 512
    # We want n as small as possible. n = 4*m. So m = n/4.
    # Lower bound on n is 512, so m >= 128.
    
    best_result = None
    
    # Try m from 128 upwards
    for m in range(128, 300):
        if time.time() > deadline - 15:
            break
        
        n = 4 * m
        # Try random voltage assignments
        num_trials = 50
        for trial in range(num_trials):
            if time.time() > deadline - 10:
                break
            
            # Random voltages in 1..m-1 (avoid 0 to ensure connectivity usually)
            voltages = tuple(random.randint(1, m - 1) for _ in range(6))
            
            # Quick check: build graph and check girth
            # But building the full graph and checking girth is expensive for large m.
            # Let's try a faster girth check first?
            # For now, just build and check.
            
            # Optimization: only check girth if the graph is likely connected.
            # A necessary condition for connectivity is that the subgroup generated by the voltages
            # (with appropriate relations from K4) is the whole group Z_m.
            # The relations in K4: 
            # Cycle 0-1-2-0: a + d - b = 0 mod m? No.
            # Let's trace: 0->1 (a), 1->2 (d), 2->0 (-b). So a + d - b = 0?
            # Wait, the voltage is on the directed edge.
            # 0->1: a. 1->2: d. 2->0: -b (since 0->2 is b).
            # So a + d - b = 0 mod m is a relation? No, that's not a relation, that's just the sum around the cycle.
            # The cycle 0-1-2-0 has voltage a + d + (-b) = a + d - b.
            # If this is 0 mod m, it's a short cycle in the voltage graph? No, it's a cycle in the base.
            # The length of the cycle in the covering graph is the length in the base (3) IF the total voltage is 0.
            # But we need girth 16. So any cycle in the base of length < 16 must have non-zero total voltage.
            # K4 has cycles of length 3 (triangles) and 4.
            # There are 4 triangles in K4.
            # Triangle 0-1-2: voltages a, d, -b. Sum: a + d - b. Must not be 0 mod m.
            # Triangle 0-1-3: voltages a, e, -c. Sum: a + e - c. Must not be 0 mod m.
            # Triangle 0-2-3: voltages b, -d, f. Sum: b - d + f. Must not be 0 mod m.
            # Triangle 1-2-3: voltages -d, e, f. Sum: -d + e + f. Must not be 0 mod m.
            # (Note: 1->2 is d, so 2->1 is -d. 1->3 is e, 3->1 is -e. 2->3 is f, 3->2 is -f.)
            # Let's re-verify triangle 1-2-3: 1->2 (d), 2->3 (f), 3->1 (-e). Sum: d + f - e.
            
            # There are 3 quadrilaterals in K4 (e.g., 0-1-3-2-0).
            # 0->1 (a), 1->3 (e), 3->2 (-f), 2->0 (-b). Sum: a + e - f - b. Must not be 0 mod m.
            # 0->1 (a), 1->2 (d), 2->3 (f), 3->0 (-c). Sum: a + d + f - c. Must not be 0 mod m.
            # 0->2 (b), 2->1 (-d), 1->3 (e), 3->0 (-c). Sum: b - d + e - c. Must not be 0 mod m.
            
            # If any of these sums is 0 mod m, we have a cycle of length 3 or 4, which is < 16.
            # So we can quickly filter out invalid voltage assignments.
            
            valid = True
            if (a + d - b) % m == 0: valid = False
            elif (a + e - c) % m == 0: valid = False
            elif (b - d + f) % m == 0: valid = False
            elif (d + f - e) % m == 0: valid = False
            elif (a + e - f - b) % m == 0: valid = False
            elif (a + d + f - c) % m == 0: valid = False
            elif (b - d + e - c) % m == 0: valid = False
            
            if not valid:
                continue
            
            # If it passes the quick check, we still need to check for longer cycles.
            # But for girth 16, we need to ensure no cycle of length < 16.
            # This is hard to do without building the graph.
            # Let's build the graph and check girth.
            # To save time, we can stop early in the girth check if a short cycle is found.
            
            # But building the graph takes O(m) time and memory.
            # Checking girth takes O(n * g) time.
            # For m=128, n=512. This is fast.
            # For m=300, n=1200. Still fast.
            
            # Let's just build and check.
            
            # However, we must also ensure the graph is connected.
            # The graph is connected iff the subgroup generated by the "cycle voltages" is the whole group Z_m.
            # The cycle voltages are the sums around the independent cycles.
            # A basis for the cycle space of K4 can be the 3 triangles.
            # Let v1 = a + d - b, v2 = a + e - c, v3 = b - d + f.
            # The subgroup generated by v1, v2, v3 in Z_m must be Z_m.
            # This is equivalent to gcd(v1, v2, v3, m) == 1.
            
            v1 = (a + d - b) % m
            v2 = (a + e - c) % m
            v3 = (b - d + f) % m
            if __import__('math').gcd(v1, __import__('math').gcd(v2, __import__('math').gcd(v3, m))) != 1:
                continue
            
            # Now build and check girth
            n, edges = build_graph(m, voltages)
            if _check_girth(n, edges, g):
                best_result = (n, edges)
                break # Found a valid one for this m, try smaller m? No, we're going up.
        
        if best_result is not None:
            break
    
    return best_result

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 110
    
    if k != 3 or g != 16:
        return _luw_construct(k, g)
    
    # Try voltage construction first
    result = _voltage_construct(k, g, deadline)
    if result is not None:
        return result
        
    # Fallback to LUW
    return _luw_construct(k, g)

