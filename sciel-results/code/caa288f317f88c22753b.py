    # 2. For m=7,9: Use a fast local search based on the analytical derivative or just fast numerical evaluation?
    #    The current program's bottleneck is `np.linalg.eigvalsh` on a 2m x 2m matrix.
    #    For m=9, N=18. 18x18 eigvalsh is very fast (~microseconds).
    #    The current program does ~10 restarts and local search. It might be running out of time or getting stuck in local minima.
