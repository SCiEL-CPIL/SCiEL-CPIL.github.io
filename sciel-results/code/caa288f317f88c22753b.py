    # [ C1  I_c ]
    # [ I_c C2 ]
    # Where I_c is the diagonal matrix of matching signs? No, matching connects i to i+m.
    # In the base graph adjacency, S[i, i+1] = a_i, S[i, i-1] = a_{i-1}, S[i, i+m] = c_i.
    
