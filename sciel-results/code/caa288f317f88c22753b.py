    # Subject to: The 2-lift defined by S is connected.
    
    # Analytical Spectral Radius for Prism Graphs:
    # The signed adjacency matrix S of a prism graph P_m with signs s1..s3m can be decomposed.
    # Due to symmetry, the eigenvalues can be found by solving a smaller problem.
    # For a prism, the graph is a circulant-like structure.
    # Let C1 be the cycle 1, C2 be cycle 2, M be the matching.
    # Signs: a_i for C1, b_i for C2, c_i for M.
    
