        S = np.zeros((n, n), dtype=np.float64)
        for i, (u, v) in enumerate(edges):
            val = float(signs[i])
            S[u, v] = val
            S[v, u] = val
        eigvals = np.linalg.eigvalsh(S)
        return np.max(np.abs(eigvals))

