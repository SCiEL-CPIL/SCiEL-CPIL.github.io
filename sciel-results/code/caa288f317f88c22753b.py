    # We can use the fact that the prism graph is a "double cover" of a cycle? No.
    # We can use the eigenvectors of the form (v, v) and (v, -v).
    # If we look for eigenvectors of the form (x, y) where x, y are vectors of length m.
    # S [x] = [lambda x]
    #   [y]   [lambda y]
    # C1 x + D y = lambda x
    # D x + C2 y = lambda y
    # Where D is the diagonal matrix of matching signs c.
    
    # If we assume D = I (all matching signs +1), then:
    # (C1 - lambda I) x + y = 0 => y = (lambda I - C1) x
    # x + (C2 - lambda I) y = 0
    # x + (C2 - lambda I)(lambda I - C1) x = 0
    # det( I - (C2 - lambda I)(lambda I - C1) ) = 0
    
    # This is generally hard to solve analytically for arbitrary signs.
    # However, for small m (4, 5, 7, 9), we can precompute the eigenvalues for all possible sign combinations?
    # Number of edges = 3m.
    # m=4: 12 edges -> 2^12 = 4096 combos. Fast.
    # m=5: 15 edges -> 2^15 = 32768 combos. Fast.
