    # To make the analytical formula work, we need to know which sign corresponds to which structural element.
    # Let's assume the standard ordering as described in similar tasks.
    # If the ordering is different, the analytical formula will be wrong.
    # Let's build the signed adjacency matrix A_s for a given sign vector s.
    # A_s is symmetric.
