    def is_lift_connected(signs):
        # Build lift graph
        # Vertices 0..2n-1. (v, 0) is v, (v, 1) is v+n.
        adj = [[] for _ in range(2*n)]
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            # Edge (u,v)
            if s == 1:
                # (u,0) <-> (v,0)
                adj[u].append(v)
                adj[v].append(u)
                # (u,1) <-> (v,1)
                adj[u+n].append(v+n)
                adj[v+n].append(u+n)
            else:
                # (u,0) <-> (v,1)
                adj[u].append(v+n)
                adj[v+n].append(u)
                # (u,1) <-> (v,0)
                adj[u+n].append(v)
                adj[v].append(u+n)
        
        # BFS from 0
        visited = [False] * (2*n)
        queue = [0]
        visited[0] = True
        count = 1
        while queue:
            node = queue.pop(0)
            for nei in adj[node]:
                if not visited[nei]:
                    visited[nei] = True
                    count += 1
                    queue.append(nei)
        return count == 2*n

