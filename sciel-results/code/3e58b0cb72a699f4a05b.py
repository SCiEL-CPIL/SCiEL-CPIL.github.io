def strassen_2x2():
    # Returns U, V, W for 2x2 * 2x2
    # A is 2x2, B is 2x2, C is 2x2
    # Indices:
    # A: 00, 01, 10, 11 -> 0, 1, 2, 3
    # B: 00, 01, 10, 11 -> 0, 1, 2, 3
    # C: 00, 01, 10, 11 -> 0, 1, 2, 3 (row-major? or col-major?)
    # Problem says W[k*n+i].
    # C[i][k].
    # C00 -> 0, C01 -> 2, C10 -> 1, C11 -> 3.
    
    R = 7
    U = [[0]*R for _ in range(4)]
    V = [[0]*R for _ in range(4)]
    W = [[0]*R for _ in range(4)]
    
    # M1
    U[0][0]=1; U[3][0]=1
    V[0][0]=1; V[3][0]=1
    W[0][0]=1; W[3][0]=1
    
    # M2
    U[2][1]=1; U[3][1]=1
    V[0][1]=1
    W[1][1]=1; W[3][1]=-1
    
    # M3
    U[0][2]=1
    V[2][2]=1; V[3][2]=-1
    W[1][2]=1; W[3][2]=1
    
    # M4
    U[3][3]=1
    V[1][3]=1; V[0][3]=-1
    W[0][3]=-1; W[2][3]=1
    
    # M5
    U[0][4]=1; U[1][4]=1
    V[3][4]=1
    W[2][4]=1; W[3][4]=1
    
    # M6
    U[2][5]=1; U[0][5]=-1
    V[0][5]=1; V[1][5]=1
    W[0][5]=-1
    
    # M7
    U[1][6]=1; U[3][6]=-1
    V[2][6]=1; V[3][6]=1
    W[0][6]=1
    
    return U, V, W
