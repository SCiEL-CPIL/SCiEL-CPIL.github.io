"""Cayley-graph construction for 4-regular girth-10 graph."""
import itertools
import math
import numpy as np
from collections import deque

def construct(k, g):
    if k != 4:
        return _construct_fallback(k, g)
    
    best_n = None
    best_edges = None
    
    # Search over abelian groups Z_a x Z_b
    # n = a * b, need n >= Moore bound ~ 243
    # Try a and b such that a*b is minimized but >= 243
    
    # For Z_a x Z_b, generating set S = {(x1,y1), (x2,y2), (-x1,-y1), (-x2,-y2)}
    # Need all 4 distinct, and the graph connected (gcd of all coords with respective moduli = 1)
    
    for n in range(243, 500):
        # Factor n = a * b with a <= b
        for a in range(2, int(math.sqrt(n)) + 1):
            if n % a != 0:
                continue
            b = n // a
            if a > b:
                continue
            # Try generating sets on Z_a x Z_b
            # S = {(x1,y1), (x2,y2), (-x1%a,-y1%b), (-x2%a,-y2%b)}
            # All 4 must be distinct and non-identity
            found = False
            # Enumerate (x1,y1) and (x2,y2) with some restrictions
            # To reduce search: fix (x1,y1) = (1, 0) by symmetry? No, not quite.
            # Let's just enumerate all pairs.
            for x1 in range(1, a):
                for y1 in range(0, b):
                    n1 = (-x1) % a
                    n1y = (-y1) % b
                    if (n1, n1y) == (0, 0):
                        continue  # would be order 2, creating 2-cycles
                    # (x1,y1) and (n1,n1y) are distinct
                    for x2 in range(0, a):
                        for y2 in range(0, b):
                            if (x2, y2) == (0, 0):
                                continue
                            if (x2, y2) == (x1, y1):
                                continue
                            if (x2, y2) == (n1, n1y):
                                continue
                            n2 = (-x2) % a
                            n2y = (-y2) % b
                            if (n2, n2y) == (0, 0):
                                continue
                            if (n2, n2y) == (x1, y1):
                                continue
                            if (n2, n2y) == (x2, y2):
                                continue
                            if (n2, n2y) == (n1, n1y):
                                continue
                            
                            # Check connectedness: the subgroup generated by S should be all of Z_a x Z_b
                            # This means gcd(x1, x2, a) = 1 and gcd(y1, y2, b) = 1
                            # More precisely: the ideal generated by x1,x2 in Z_a is all of Z_a
                            # i.e., gcd(x1, x2, a) = 1, and similarly for y
                            if math.gcd(math.gcd(x1, x2), a) != 1:
                                continue
                            if math.gcd(math.gcd(y1, y2), b) != 1:
                                continue
                            
                            # Check girth >= g
                            if _check_girth_abelian(a, b, x1, y1, x2, y2, g):
                                # Build edges
                                edges = _build_edges_abelian(a, b, x1, y1, x2, y2)
                                if best_n is None or n < best_n:
                                    best_n = n
                                    best_edges = edges
                                found = True
                                break
                        if found:
                            break
                    if found:
                        break
                if found:
                    break
            if found:
                break
        if found:
            break
    
    if best_n is not None:
        return best_n, best_edges
    
    return _construct_fallback(4, g)


def _check_girth_abelian(a, b, x1, y1, x2, y2, g):
    """Check no non-backtracking closed walk of length < g in Z_a x Z_b with S={s1,s2,-s1,-s2}."""
    S = [(x1, y1), (x2, y2), ((-x1) % a, (-y1) % b), ((-x2) % a, (-y2) % b)]
    
    # Non-backtracking: consecutive steps can't be inverses
    # Inverse of (dx, dy) is (-dx % a, -dy % b)
    
    for L in range(2, g):
        # DFS/BFS over non-backtracking walks of length L
        # State: (current_position, last_step_index)
        # Start from (0,0) with each possible first step
        visited = set()
        # For each starting step
        for si in range(4):
            sx, sy = S[si]
            pos = (sx % a, sy % b)
            if L == 1:
                if pos == (0, 0):
                    return False
            else:
                # Continue with non-backtracking
                if _has_nonbacktracking_cycle(pos, si, L - 1, a, b, S):
                    return False
    return True


def _has_nonbacktracking_cycle(pos, prev_idx, remaining, a, b, S):
    """Check if there's a non-backtracking walk of `remaining` more steps from pos
    (having just taken step prev_idx) that returns to (0,0)."""
    if remaining == 0:
        return pos == (0, 0)
    for si in range(4):
        if si == (prev_idx + 2) % 4:  # inverse step (S[i] and S[i+2] are inverses)
            continue
        sx, sy = S[si]
        new_pos = ((pos[0] + sx) % a, (pos[1] + sy) % b)
        if _has_nonbacktracking_cycle(new_pos, si, remaining - 1, a, b, S):
            return True
    return False


def _build_edges_abelian(a, b, x1, y1, x2, y2):
    """Build edge list for Z_a x Z_b with generators (x1,y1) and (x2,y2)."""
    edge_set = set()
    for i in range(a):
        for j in range(b):
            for dx, dy in [(x1, y1), (x2, y2)]:
                ni = (i + dx) % a
                nj = (j + dy) % b
                v1 = i * b + j
                v2 = ni * b + nj
                if v1 < v2:
                    edge_set.add((v1, v2))
                else:
                    edge_set.add((v2, v1))
    return sorted(edge_set)


def _construct_fallback(k, g):
    """Fallback: use the Lazebnik-Ustimenko-Woldar construction."""
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
