    deadline = start_time + 115.0  # Safety margin before 120s limit
    
    diffs_per_row = k * (k + 1) // 2
    
    # Function to generate a valid row with small max entry
    def generate_candidate_row(rng, max_limit, diversity_factor=1.0):
        """
        Generates a row of k+1 integers starting at 0.
        Uses a greedy approach with some randomness to allow diversity.
        Returns (max_entry, frozenset_of_diffs) or None if fails.
        """
        row = [0]
        used_diffs = set()
        
        for _ in range(k):
            last_val = row[-1]
            found = False
