import time
import math
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 140  # 10s safety margin
    
    # Primes congruent to 1 mod 4
    primes_1_4 = [5, 13, 17, 29, 37, 41, 53, 61, 73, 89, 97, 101, 109, 113, 137, 149, 157, 173, 181, 193, 197]
    
    def get_powerful_pairs_from_sum_of_squares(N, Q):
        """
        Given N = Q^3 * S, find pairs (k, m) such that k^2 + m^2 = S.
        Returns list of pairs [a, b] where a = Q^3 k^2, b = Q^3 m^2.
        """
        S = N // (Q ** 3)
        pairs = []
        limit_k = int(math.isqrt(S))
        for k in range(0, limit_k + 1):
            rem = S - k * k
            if rem < 0:
                break
            m = int(math.isqrt(rem))
            if m * m == rem:
                # We have a solution k, m
                a = Q ** 3 * k * k
                b = Q ** 3 * m * m
                # Ensure a <= b
                if a <= b:
                    # Check if they are powerful (they should be by construction)
                    # But we must ensure a,b >= 1. If k=0, a=0, not powerful? 
                    # Task says 1 is powerful. 0 is not. 
                    # So k, m must be >= 1? 
                    # If k=0, a=0. 0 is not powerful. 
                    # So we need k>=1 and m>=1.
                    if k >= 1 and m >= 1:
                        pairs.append([a, b])
        return pairs

    def is_powerful(n):
        if n == 1:
            return True
        if n < 1:
            return False
        temp = n
        d = 2
        while d * d <= temp:
            if temp % (d * d) == 0:
                while temp % (d * d) == 0:
                    temp //= (d * d)
            elif temp % d == 0:
                return False
            d += 1
        if temp > 1:
            return False
        return True

    best_result = {'N': 0, 'pairs': []}
    
    # Strategy: 
    # 1. Choose Q from a subset of the first few primes.
    # 2. For each Q, construct S to maximize representations.
    # 3. S should be composed of primes from primes_1_4.
    # 4. Maximize product of (e_p + 1) subject to Q^3 * S <= 10^18.
    
    max_N = 10 ** 18
    
    # Try different Q values. 
    # Q is product of first k primes.
    # Small Q allows larger S, which can have more prime factors.
    
    for num_q_primes in range(1, 6):
        Q = 1
        for i in range(num_q_primes):
            Q *= primes_1_4[i]
        
        Q_cubed = Q ** 3
        if Q_cubed > max_N:
            break
            
        max_S = max_N // Q_cubed
        
        # Optimize S
        # We want to maximize prod(e_p + 1) for S = prod p^e_p
        # Subject to S <= max_S
        # Greedy approach: start with e_p = 0. 
        # Repeatedly increment the exponent of the prime that gives the best marginal gain per log cost.
        # Gain of e -> e+1 is (e+2)/(e+1). Cost is log(p).
        # We prioritize smaller primes and smaller current exponents.
        
        exponents = {p: 0 for p in primes_1_4}
        current_S = 1
        
        # We can just iterate and pick the best candidate
        # Since primes are sorted, and we want to use small primes, 
        # we can try to distribute exponents.
        
        # A simpler heuristic: 
        # Try to make S a power of 5? No, that gives (e+1) reps.
        # S = 5^a * 13^b * ...
        # We want many factors.
        
        # Let's try a few specific structures for S
        # 1. S = 5^a
        # 2. S = 5^a * 13^b
        # 3. S = 5^a * 13^b * 17^c
        
        # Actually, let's just do a greedy search on exponents.
        # Start with all 0.
        # While we can multiply by some prime p such that S * p <= max_S:
        #   Find p that maximizes (e_p + 2)/(e_p + 1) / log(p) ?
        #   Or just try all p and pick the one that results in the highest final product?
        #   That's expensive.
        
        # Alternative: 
        # The number of representations is determined by the exponents of primes 1 mod 4.
        # Let's just try to maximize the number of prime factors (with multiplicity) in S.
        
        # Let's try a few candidate S values generated by greedy exponent assignment.
        
        candidates_S = []
        
        # Candidate 1: Pure power of 5
        S = 1
        while S * 5 <= max_S:
            S *= 5
            candidates_S.append(S)
        
        # Candidate 2: 5^a * 13^b
        # We can iterate a, and for each a, max b.
        # But we want to maximize (a+1)(b+1).
        
        # Let's do a proper greedy optimization for S.
        # State: current S, current exponents.
        # Move: multiply by p.
        # We want to reach a state where we can't multiply by any p.
        # To maximize the product, we should balance exponents?
        # No, (e+1) grows linearly, so we want many distinct primes with e=1?
        # (1+1)(1+1)... = 2^k.
        # Vs 5^10: (10+1) = 11.
        # 2^10 = 1024.
        # So many distinct small primes are better.
        
        # So, let's pick the smallest primes 1 mod 4 and set e_p = 1 for as many as possible.
        # Then if budget remains, increase exponents of the smallest primes.
        
        S_greedy = 1
        exp_greedy = {p: 0 for p in primes_1_4}
        
        # Phase 1: Set e_p = 1 for smallest primes
        for p in primes_1_4:
            if S_greedy * p <= max_S:
                S_greedy *= p
                exp_greedy[p] += 1
            else:
                break
        
        # Phase 2: Increase exponents of smallest primes
        changed = True
        while changed:
            changed = False
            for p in primes_1_4:
                if S_greedy * p <= max_S:
                    S_greedy *= p
                    exp_greedy[p] += 1
                    changed = True
                    # We only do one pass? No, we should keep increasing the smallest.
                    # Actually, just keep multiplying by 5 as much as possible?
                    # No, that reduces the number of distinct primes.
                    # The gain of increasing e_5 from 1 to 2 is 3/2 = 1.5x.
                    # The gain of adding a new prime p is 2/1 = 2x.
                    # So adding new primes is better IF they fit.
                    # So Phase 1 is correct.
                    # In Phase 2, we should increase the exponent of the smallest prime?
                    # Gain of e->e+1 is (e+2)/(e+1).
                    # For e=1, gain is 1.5.
                    # For e=2, gain is 1.33.
                    # So we should always increase the exponent with the smallest current e?
                    # No, we should increase the one with the largest (e+2)/(e+1).
                    # That is the one with the smallest e.
                    # So yes, increase the smallest exponent first.
                    # But we also need to consider the prime size?
                    # The "cost" is log(p).
                    # But we are constrained by S <= max_S.
                    # So we just check if it fits.
                    # If multiple fit, pick the one with max gain.
                    # Since all e are likely small, and 5 is smallest, 5 is best candidate.
                    # So just multiply by 5?
                    # Let's just multiply by 5 repeatedly.
                    break # Restart loop to re-evaluate? 
        # The above while loop logic is a bit messy. Let's simplify.
        
        # Simple Heuristic for S:
        # 1. Multiply by 5, 13, 17... until next prime doesn't fit.
        # 2. Then multiply by 5 repeatedly.
        
        S_final = S_greedy
        while S_final * 5 <= max_S:
            S_final *= 5
            
        candidates_S.append(S_final)
        
        # Also try pure powers of 5
        S_pow5 = 1
        while S_pow5 * 5 <= max_S:
            S_pow5 *= 5
        candidates_S.append(S_pow5)
        
        # Also try 5^a * 13^b balanced
        # Let's just evaluate the best N from these candidates.
        
        for S in set(candidates_S):
            N = Q_cubed * S
            if N > max_N:
                continue
            
            # Find pairs for this N
            pairs = get_powerful_pairs_from_sum_of_squares(N, Q)
            
            if len(pairs) > len(best_result['pairs']):
                # Verify pairs
                valid_pairs = []
                for p in pairs:
                    a, b = p
                    if a + b == N and is_powerful(a) and is_powerful(b):
                        valid_pairs.append(p)
                if len(valid_pairs) > len(best_result['pairs']):
                    best_result = {'N': N, 'pairs': valid_pairs}
        
        if time.time() > deadline - 20:
            break

    # If no good result, fallback to small N
    if not best_result['pairs']:
        # Try N=1000000, find powerful pairs
        # Or just return a known small one
        # 1+1=2 (1 is powerful)
        best_result = {'N': 2, 'pairs': [[1, 1]]}
        
    return best_result
