import time
import random
from collections import defaultdict

DEADLINE_SECONDS = 55.0  # Safety margin before 60s kill

def _check_add_valid(sums_by_k, sum_to_ks, x, n):
    """
    Check if adding x to the current set is valid.
    sums_by_k[k] contains sums achievable with exactly k elements.
    sum_to_ks[s] contains the set of cardinalities k such that s is in sums_by_k[k].
    """
    # We need to check if any new sum (s+x for s in sums_by_k[k-1])
    # collides with an existing sum in sums_by_k[k'] for k' != k.
    
    # Iterate over all possible cardinalities k that the new sum could belong to.
    # The new sum is formed by taking a subset of size k-1 and adding x.
    # So the new sum belongs to cardinality k.
    # We must ensure this new sum is NOT in sums_by_k[k'] for any k' != k.
    
    for k in range(1, n + 2):
        if not sums_by_k[k-1]:
            continue
        
        for s_prev in sums_by_k[k-1]:
            s_new = s_prev + x
            
            # If s_new is already in the global map, check its cardinalities
            if s_new in sum_to_ks:
                existing_ks = sum_to_ks[s_new]
                # If any existing cardinality is not k, it's a collision
                # Note: It is allowed for s_new to be in sums_by_k[k] already?
                # No, s_new is a *new* sum generated by adding x.
                # Wait, if s_new is already in sums_by_k[k], that means there was another subset of size k with sum s_new.
                # The problem says "Repeated sums within the SAME cardinality are allowed."
                # So if s_new is in sums_by_k[k], it's fine.
                # But if s_new is in sums_by_k[k'] for k' != k, it's invalid.
                
                for k_prime in existing_ks:
                    if k_prime != k:
                        return False
                        
    return True

def _add_to_state(sums_by_k, sum_to_ks, x, n):
    """
    Update sums_by_k and sum_to_ks to reflect the addition of x.
    Must be called after _check_add_valid returns True.
    """
    # Iterate backwards to avoid using x multiple times in the same step
    # We are adding x to all subsets of size k to form subsets of size k+1
    for k in range(n, -1, -1):
        if not sums_by_k[k]:
            continue
        
        new_sums = set()
        for s in sums_by_k[k]:
            s_new = s + x
            new_sums.add(s_new)
            
            # Update sum_to_ks
            if s_new not in sum_to_ks:
                sum_to_ks[s_new] = set()
            sum_to_ks[s_new].add(k + 1)
            
        # Add new sums to sums_by_k[k+1]
        sums_by_k[k+1].update(new_sums)

def _remove_from_state(sums_by_k, sum_to_ks, x, n):
    """
    Revert the state by removing x.
    This is tricky because we don't know which sums were generated by x vs previously existing.
    However, we can rebuild the state from scratch if we store the set of elements.
    Or, we can just not use backtracking on the state, but instead use a copy.
    Given the small size (max 60 elements, values 1..256), copying sets is feasible.
    """
    pass # We will use a different strategy: DFS with state copying or careful reconstruction.
    
    # Actually, for backtracking, it's safer to just copy the state before adding.
    # Since sums_by_k is a list of sets, copying it is O(total_sums).
    # total_sums is bounded by 256 * 60 roughly? No, sum values are <= 256*60 = 15360.
    # But distinct sums per cardinality are limited.
    # Let's just copy the state in the DFS.

def construct():
    t_start = time.time()
    deadline = t_start + DEADLINE_SECONDS
    
    best_set = []
    best_size = 0
    
    # Candidates: 1..256
    # We want to find a large set.
    # Small numbers tend to create more collisions? Or large numbers?
    # Let's try a heuristic: sort candidates.
    
    # Strategy: DFS with pruning.
    # State: current_set, sums_by_k, sum_to_ks
    # We will try to add elements in a specific order.
    
    # To improve performance, we can use a greedy heuristic to order candidates dynamically?
    # Or just fixed order?
    # Let's try multiple random permutations of candidates, but with a time limit.
    
    # Optimization: Pre-filter candidates?
    # If we pick 1, 2, 4, 8... (powers of 2), sums are unique.
    # But we have range 1..256.
    # Powers of 2 up to 128: 1, 2, 4, ..., 128 (8 elements).
    # We can go larger.
    
    # Let's use a recursive DFS.
    
    def dfs(current_set, sums_by_k, sum_to_ks, candidates):
        nonlocal best_set, best_size, deadline, t_start
        
        if time.time() > deadline:
            return
        
        if len(current_set) > best_size:
            best_size = len(current_set)
            best_set = current_set[:]
            
        if not candidates:
            return
            
        n = len(current_set)
        
        # Try each candidate
        for i, x in enumerate(candidates):
            if time.time() > deadline:
                return
            
            # Check validity
            if _check_add_valid(sums_by_k, sum_to_ks, x, n):
                # Copy state
                new_sums_by_k = [s.copy() for s in sums_by_k]
                new_sum_to_ks = defaultdict(set)
                for s, ks in sum_to_ks.items():
                    new_sum_to_ks[s] = ks.copy()
                
                _add_to_state(new_sums_by_k, new_sum_to_ks, x, n)
                
                # Recurse
                dfs(current_set + [x], new_sums_by_k, new_sum_to_ks, candidates[i+1:])
                
                # Backtrack (state is copied, so no need to revert)
            
            # If we have found a set of size 60, we can stop?
            # Max possible is 60.
            if best_size == 60:
                return

    # Initial state
    init_sums_by_k = [set() for _ in range(61)]
    init_sums_by_k[0].add(0)
    init_sum_to_ks = defaultdict(set)
    init_sum_to_ks[0].add(0)
    
    # Candidate ordering strategy:
    # 1. Ascending (1, 2, 3...)
    # 2. Descending (256, 255...)
    # 3. Random
    
    # Let's try ascending first, as it might allow more elements?
    # Actually, large elements create larger sums, potentially avoiding collisions with small sums?
    # But small elements are "dense".
    
    # Let's try a few strategies within the time limit.
    
    strategies = [
        list(range(1, 257)),
        list(range(256, 0, -1)),
    ]
    
    # Add some random shuffles
    for _ in range(5):
        c = list(range(1, 257))
        random.shuffle(c)
        strategies.append(c)
        
    for c in strategies:
        if time.time() > deadline:
            break
        
        dfs([], init_sums_by_k, init_sum_to_ks, c)
        
        if best_size == 60:
            break

    return list(best_set)
