def pack(boxes, container):
    """
    3D Bin Packing using a combination of Next Fit Decreasing (NFD) with 
    First Fit Decreasing (FFD) bin selection and a simple 3D placement heuristic.
    
    Strategy:
    1. Sort boxes by volume descending.
    2. For each box, try to place it in the first bin where it fits (First Fit).
    3. If it doesn't fit in any existing bin, open a new bin.
    4. Placement within a bin: Use a simple "bottom-left-front" (BLF) strategy 
       with a grid-based or list-based check for valid positions.
    """
    W, H, D = container
    container_volume = W * H * D
    
    # Sort boxes by volume descending
    sorted_indices = sorted(range(len(boxes)), key=lambda i: boxes[i][0]*boxes[i][1]*boxes[i][2], reverse=True)
    
    # Each bin stores a list of placed boxes: (x, y, z, w, h, d)
    bins = []
    
    def is_valid_pos(bin_boxes, x, y, z, w, h, d):
        if x < 0 or y < 0 or z < 0:
            return False
        if x + w > W or y + h > H or z + d > D:
            return False
        for (bx, by, bz, bw, bh, bd) in bin_boxes:
            # Check overlap
            if not (x + w <= bx or bx + bw <= x or
                    y + h <= by or by + bh <= y or
                    z + d <= bz or bz + bd <= z):
                return False
        return True

    def find_best_position(bin_boxes, w, h, d):
        """
        Find the best (x, y, z) position for a box of size (w, h, d) in the given bin.
        Uses a heuristic: try to place as low (z), left (x), and back (y) as possible.
        We'll scan candidate positions. To keep it efficient, we'll use a simple 
        grid-like approach or just try a few key positions.
        
        For simplicity and efficiency, we'll use a "skyline" approach:
        Maintain for each (x, y) column the maximum z height. But that's 2D.
        
        Alternative: Since the number of boxes is small (40), we can try all 
        "extreme points" generated by existing boxes.
        
        Let's use the extreme points method but simplified.
        """
        # Collect candidate positions
        candidates = set()
        candidates.add((0, 0, 0))
        
        for (bx, by, bz, bw, bh, bd) in bin_boxes:
            # Generate candidate positions from existing boxes
            candidates.add((bx + bw, by, bz))
            candidates.add((bx, by + bh, bz))
            candidates.add((bx, by, bz + bd))
            # Also add some corner combinations that might be useful
            candidates.add((bx + bw, by + bh, bz))
            candidates.add((bx + bw, by, bz + bd))
            candidates.add((bx, by + bh, bz + bd))
            
        # Filter and score candidates
        best_pos = None
        best_score = None
        
        for (x, y, z) in candidates:
            if is_valid_pos(bin_boxes, x, y, z, w, h, d):
                # Score: minimize z, then x, then y
                score = (z, x, y)
                if best_score is None or score < best_score:
                    best_score = score
                    best_pos = (x, y, z)
        
        return best_pos

    placements = [None] * len(boxes)
    bin_count = 0
    
    for idx in sorted_indices:
        w, h, d = boxes[idx]
        placed = False
        
        # Try to place in existing bins (First Fit)
        for b_idx in range(bin_count):
            bin_boxes = bins[b_idx]
            pos = find_best_position(bin_boxes, w, h, d)
            if pos is not None:
                x, y, z = pos
                new_box = (x, y, z, w, h, d)
                bins[b_idx].append(new_box)
                placements[idx] = (b_idx, x, y, z, w, h, d)
                placed = True
                break
        
        if not placed:
            # Open new bin
            new_bin_index = bin_count
            bin_count += 1
            new_box = (0, 0, 0, w, h, d)
            bins.append([new_box])
            placements[idx] = (new_bin_index, 0, 0, 0, w, h, d)

    return placements
