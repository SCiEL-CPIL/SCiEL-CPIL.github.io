import time
import random
import math

def construct(n):
    if n <= 1:
        return "1"
    
    # Generate all permutations of 1..n-1
    import itertools
    if n == 2:
        # Base case for n=2, blocks are perms of 1..1
        # P = [1]
        # B = [1, 2, 1]
        # Word = 121
        return "121"
        
    symbols = list(range(1, n))
    perms = list(itertools.permutations(symbols))
    K = len(perms)
    
    # Precompute overlaps
    # overlap[i][j] = longest k such that perms[i][-k:] == perms[j][:k]
    overlaps = [[0]*K for _ in range(K)]
    for i in range(K):
        pi = perms[i]
        for j in range(K):
            pj = perms[j]
            max_k = min(len(pi), len(pj))
            for k in range(max_k, 0, -1):
                if pi[-k:] == pj[:k]:
                    overlaps[i][j] = k
                    break
    
    # Initial order: standard recursive order
    # The standard order for n-1 is the order of first appearance in S_{n-1}.
    # We can generate this by running the standard construction for n-1 and extracting blocks.
    # Or, simpler: The standard order for n is related to the order for n-1.
    # For n=3, order is 12, 21.
    # For n=4, order is derived from S_3.
    
    # Let's just generate the standard order recursively.
    def get_standard_order(m):
        if m == 2:
            return [(1,)]
        prev_order = get_standard_order(m-1)
        # The standard construction for m uses blocks from m-1.
        # The order of blocks in S_m is the order of first appearance in S_{m-1}.
        # This is equivalent to the order of permutations in S_{m-1}.
        # So we just need to return the order of perms of 1..m-1 that appears in S_{m-1}.
        # This is recursive.
        # Actually, the list of perms IS the order.
        # For m=3, perms of 1,2 are 12, 21.
        # For m=4, perms of 1,2,3.
        # The standard order is the order generated by the recursion.
        
        # Let's just use the order from the seed's logic:
        # Extract from the word generated by the seed's logic for m-1.
        word = [1]
        for mm in range(2, m):
            p_list, seen = [], set()
            for i in range(len(word) - mm + 2):
                w = tuple(word[i:i + mm - 1])
                if len(set(w)) == mm - 1 and w not in seen:
                    seen.add(w)
                    p_list.append(w)
            new_w = []
            for p in p_list:
                block = list(p) + [mm] + list(p)
                overlap = next(o for o in range(min(len(new_w), len(block)), -1, -1) if new_w[len(new_w) - o:] == block[:o])
                new_w += block[overlap:]
            word = new_w
        
        # Extract order from word
        final_order = []
        seen = set()
        for i in range(len(word) - (m-2)):
            w = tuple(word[i:i + m-1])
            if len(set(w)) == m-1 and w not in seen:
                seen.add(w)
                final_order.append(w)
        return final_order

    # Get standard order for n-1 symbols
    std_order = get_standard_order(n)
    # Map to indices in perms
    perm_to_idx = {p: i for i, p in enumerate(perms)}
    init_order = [perm_to_idx[p] for p in std_order]
    
    def calc_length(order):
        if not order:
            return 0
        total = 2*n - 1 # Length of first block
        for i in range(1, len(order)):
            prev_idx = order[i-1]
            curr_idx = order[i]
            total += (2*n - 1) - overlaps[prev_idx][curr_idx]
        return total

    best_order = init_order[:]
    best_len = calc_length(best_order)
    
    start_time = time.time()
    time_limit = 110
    
    # VNS with 2-opt and Or-opt
    improved = True
    while improved and time.time() - start_time < time_limit:
        improved = False
        
        # 2-opt
        for i in range(K - 1):
            for j in range(i + 1, K):
                # Reverse i..j
                new_order = best_order[:i] + best_order[i:j+1][::-1] + best_order[j+1:]
                new_len = calc_length(new_order)
                if new_len < best_len:
                    best_len = new_len
                    best_order = new_order
                    improved = True
                    if time.time() - start_time > time_limit:
                        break
            if time.time() - start_time > time_limit:
                break
        
        if time.time() - start_time > time_limit:
            break
            
        # Or-opt (move segment of size 1, 2, 3)
        for size in [1, 2, 3]:
            for i in range(K - size):
                for j in range(K - size + 1):
                    if i == j or i == j - 1: continue
                    # Extract segment i..i+size-1
                    segment = best_order[i:i+size]
                    # Remove
                    new_order = best_order[:i] + best_order[i+size:]
                    # Insert at j (adjust j if j > i)
                    if j > i:
                        j -= size
                    # Ensure j is valid
                    if j < 0: j = 0
                    if j > len(new_order): j = len(new_order)
                    
                    new_order = new_order[:j] + segment + new_order[j:]
                    
                    new_len = calc_length(new_order)
                    if new_len < best_len:
                        best_len = new_len
                        best_order = new_order
                        improved = True
                        if time.time() - start_time > time_limit:
                            break
                if time.time() - start_time > time_limit:
                    break
            if time.time() - start_time > time_limit:
                break
        
        if time.time() - start_time > time_limit:
            break

    # Reconstruct word
    word = []
    for i, idx in enumerate(best_order):
        p = perms[idx]
        block = list(p) + [n] + list(p)
        if i == 0:
            word.extend(block)
        else:
            # Find overlap
            max_k = min(len(word), len(block))
            overlap = 0
            for k in range(max_k, 0, -1):
                if word[-k:] == block[:k]:
                    overlap = k
                    break
            word.extend(block[overlap:])
            
    return "".join(map(str, word))
