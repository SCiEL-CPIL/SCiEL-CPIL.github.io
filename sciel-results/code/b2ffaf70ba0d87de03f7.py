def _hex_vertices(cx, cy, side, angle_deg=0):
    angle = np.radians(angle_deg)
    return [(cx + side * np.cos(angle + i * np.pi / 3),
             cy + side * np.sin(angle + i * np.pi / 3)) for i in range(6)]

def _point_in_hexagon(px, py, cx, cy, side, angle_deg=0):
    dx, dy = px - cx, py - cy
    a = -np.radians(angle_deg)
    ca, sa = np.cos(a), np.sin(a)
    lx, ly = dx * ca - dy * sa, dx * sa + dy * ca
    apothem = side * np.sqrt(3) / 2
    for i in range(6):
        na = np.radians(30 + i * 60)
        if lx * np.cos(na) + ly * np.sin(na) > apothem + 1e-9:
            return False
    return True

def _outer_side_for(inner):
    all_v = []
    for cx, cy, ang in inner:
        all_v.extend(_hex_vertices(cx, cy, 1.0, ang))
    lo, hi = 0.5, 60.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if all(_point_in_hexagon(x, y, 0, 0, mid, 0) for x, y in all_v):
            hi = mid
        else:
            lo = mid
    return hi

def _make_positions(counts, col_w=np.sqrt(3), row_h=1.5):
    pos, y = [], 0.0
    for cnt in counts:
        for j in range(cnt):
            x = (j - (cnt - 1) / 2.0) * col_w
            pos.append((x, y, 0.0))
        y += row_h
    xs, ys = [p[0] for p in pos], [p[1] for p in pos]
    cx, cy = (min(xs)+max(xs))/2, (min(ys)+max(ys))/2
    return [(p[0]-cx, p[1]-cy, p[2]) for p in pos]

