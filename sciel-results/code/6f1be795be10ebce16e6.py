def construct(instance):
    n = instance["n"]
    
    # Initial guess: icosahedron
    p0 = _generate_icosahedron(n)
    if not _valid(p0):
        # Fallback: random
        rng = np.random.default_rng(0)
        p0 = rng.uniform(-1, 1, (n, 3))
        p0 -= p0.mean(axis=0, keepdims=True)
        p0 *= 1.1
        # Ensure validity
        for _ in range(100):
            if _valid(p0):
                break
            p0 = rng.uniform(-1, 1, (n, 3))
            p0 -= p0.mean(axis=0, keepdims=True)
            p0 *= 1.1
    
    best_p = p0
    best_e = _energy(p0)
    
    # Basin Hopping
    T = 0.01
    dt = 0.1
    rng = np.random.default_rng(123)
    
    while _time_left() > 5.0:
        # Perturb
        # Use gradient-guided perturbation
        try:
            grad = dzugutov_energy_gradient(p0)
            # Normalize gradient
            grad_norm = np.linalg.norm(grad)
            if grad_norm > 1e-6:
                grad = grad / grad_norm
            else:
                grad = rng.normal(0, 1, (n, 3))
                grad /= np.linalg.norm(grad)
        except Exception:
            grad = rng.normal(0, 1, (n, 3))
            grad /= np.linalg.norm(grad)
        
        # Random kick
        kick = rng.normal(0, 1, (n, 3))
        kick /= np.linalg.norm(kick)
        
        # Mix gradient and random kick
        alpha = 0.5
        delta = dt * (alpha * grad + (1 - alpha) * kick)
        
        p1 = p0 + delta
        
        # Relax
        try:
            e1, p1_relaxed = relax(p1, "dzugutov")
            e1 = _energy(p1_relaxed)
        except Exception:
            continue
        
        # Metropolis acceptance
        delta_e = e1 - best_e
        if delta_e < 0 or rng.random() < np.exp(-delta_e / T):
            p0 = p1_relaxed
            best_e = e1
            if e1 < best_e:
                best_p = p1_relaxed
                best_e = e1
        
        # Cool down
        T *= 0.95
    
    return best_p
