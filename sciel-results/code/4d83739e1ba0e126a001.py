import numpy as np
import time
import random

def construct():
    """
    Rank-minimal exact tensor decomposition for 3x4 * 4x6 matrix multiplication.
    
    The matrix multiplication tensor T satisfies:
    C[i,k] = sum_j A[i,j] * B[j,k]
    
    We seek U (12 x R), V (24 x R), W (18 x R) such that:
    sum_r U[i*4+j, r] * V[j*6+k, r] * W[k*3+i, r] = 1 for all i,j,k
    
    This means the target tensor is the all-ones tensor of shape 3x4x6.
    """
    n, m, p = 3, 4, 6
    start_time = time.time()
    deadline = start_time + 145  # 5s safety margin
    
    def verify(U, V, W):
        """Verify the decomposition exactly reproduces the target tensor."""
        r = len(U[0])
        for a in range(n):
            for b in range(m):
                for c in range(p):
                    actual = 0.0
                    for rr in range(r):
                        actual += U[a * m + b][rr] * V[b * p + c][rr] * W[c * n + a][rr]
                    if abs(actual - 1.0) > 1e-9:
                        return False
        return True
    
    # The all-ones tensor has rank 1!
    # U[i*m+j, 0] = 1 for all i,j
    # V[j*p+k, 0] = 1 for all j,k  
    # W[k*n+i, 0] = 1 for all k,i
    
    # This gives rank 1
    R = 1
    U = [[1] * R for _ in range(n * m)]
    V = [[1] * R for _ in range(m * p)]
    W = [[1] * R for _ in range(p * n)]
    
    if verify(U, V, W):
        return {"U": U, "V": V, "W": W}
    
    # If verification fails (which it shouldn't for all-ones), fall back to baseline
    # Build a Strassen-based baseline
    R = 66
    U = [[0] * R for _ in range(n * m)]
    V = [[0] * R for _ in range(m * p)]
    W = [[0] * R for _ in range(p * n)]
    
    col = 0
    
    def add_strassen_block(a_r, a_c, b_r, b_c, c_r, c_c):
        nonlocal col
        A00 = a_r * m + a_c
        A01 = a_r * m + a_c + 1
        A10 = (a_r + 1) * m + a_c
        A11 = (a_r + 1) * m + a_c + 1
        B00 = b_r * p + b_c
        B01 = b_r * p + b_c + 1
        B10 = (b_r + 1) * p + b_c
        B11 = (b_r + 1) * p + b_c + 1
        C00 = c_c * n + c_r
        C01 = (c_c + 1) * n + c_r
        C10 = c_c * n + (c_r + 1)
        C11 = (c_c + 1) * n + (c_r + 1)
        
        # Strassen's 7 products
        # M1 = (A00 + A11)(B00 + B11)
        U[A00][col] += 1; U[A11][col] += 1
        V[B00][col] += 1; V[B11][col] += 1
        W[C00][col] += 1; W[C11][col] += 1
        col += 1
        
        # M2 = (A10 + A11)B00
        U[A10][col] += 1; U[A11][col] += 1
        V[B00][col] += 1
        W[C10][col] += 1; W[C11][col] -= 1
        col += 1
        
        # M3 = A00(B01 - B11)
        U[A00][col] += 1
        V[B01][col] += 1; V[B11][col] -= 1
        W[C01][col] += 1; W[C11][col] += 1
        col += 1
        
        # M4 = A11(B10 - B00)
        U[A11][col] += 1
        V[B10][col] += 1; V[B00][col] -= 1
        W[C00][col] += 1; W[C10][col] += 1
        col += 1
        
        # M5 = (A00 + A01)B11
        U[A00][col] += 1; U[A01][col] += 1
        V[B11][col] += 1
        W[C00][col] -= 1; W[C01][col] += 1
        col += 1
        
        # M6 = (A10 - A00)(B00 + B01)
        U[A10][col] += 1; U[A00][col] -= 1
        V[B00][col] += 1; V[B01][col] += 1
        W[C11][col] += 1
        col += 1
        
        # M7 = (A01 - A11)(B10 + B11)
        U[A01][col] += 1; U[A11][col] -= 1
        V[B10][col] += 1; V[B11][col] += 1
        W[C00][col] += 1
        col += 1
    
    def add_direct_1x2_2x2(a_r, a_c, b_r, b_c, c_r, c_c):
        nonlocal col
        A0 = a_r * m + a_c
        A1 = a_r * m + a_c + 1
        B00 = b_r * p + b_c
        B01 = b_r * p + b_c + 1
        B10 = (b_r + 1) * p + b_c
        B11 = (b_r + 1) * p + b_c + 1
        C0 = c_c * n + c_r
        C1 = (c_c + 1) * n + c_r
        
        U[A0][col] += 1; V[B00][col] += 1; W[C0][col] += 1
        col += 1
        U[A1][col] += 1; V[B10][col] += 1; W[C0][col] += 1
        col += 1
        U[A0][col] += 1; V[B01][col] += 1; W[C1][col] += 1
        col += 1
        U[A1][col] += 1; V[B11][col] += 1; W[C1][col] += 1
        col += 1
    
    # Row 0 of C: 3 blocks of (1×2)·(2×2) direct = 12 mults
    for j in range(3):
        for i in range(2):
            add_direct_1x2_2x2(0, i * 2, i * 2, j * 2, 0, j * 2)
    
    # Rows 1-2 of C: 3 blocks of (2×2)·(2×2) Strassen = 21 mults
    for j in range(3):
        for i in range(2):
            add_strassen_block(1, i * 2, i * 2, j * 2, 1, j * 2)
    
    assert col == R, f"Expected {R} columns, got {col}"
    
    if verify(U, V, W):
        return {"U": U, "V": V, "W": W}
    
    # Should not reach here
    raise ValueError("No valid decomposition found")
