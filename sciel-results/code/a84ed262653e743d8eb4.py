"""Optimized: Number-theoretic construction using generalized arithmetic progressions (GAPs)
in the plane, exploiting the bilinear structure of the determinant (cross product).

Points are of the form P(i,j) = i*v1 + j*v2 + offset, where v1, v2 are primitive lattice
vectors. The doubled area of triangle (P(a,b), P(c,d), P(e,f)) is:
    |det(P(c,d)-P(a,b), P(e,f)-P(a,b))|
  = |(c-a)*(v1x*v2y - v2x*v1y) * ... |  -- actually let's compute properly.

For points on a 2D lattice generated by v1=(a,b), v2=(c,d):
  P(i,j) = (i*a + j*c, i*b + j*d)
  
  The doubled area of triangle with indices (i1,j1),(i2,j2),(i3,j3) is:
    |det( (i2-i1)*v1 + (j2-j1)*v2, (i3-i1)*v1 + (j3-j1)*v2 )|
  = |(i2-i1)*(j3-j1) - (i3-i1)*(j2-j1)| * |det(v1, v2)|
  
  So all areas are multiples of D = |det(v1,v2)| = |a*d - b*c|.
  The "shape factor" S = |(i2-i1)*(j3-j1) - (i3-i1)*(j2-j1)| depends only on the
  index triples, not on the actual vectors.

Strategy: Choose index sets (i,j) for 30 points, and vectors v1, v2 such that:
1. All 30 points fit in [-30,30]^2
2. D = |det(v1,v2)| is small (to keep areas small and increase multiplicity)
3. The index configuration maximizes the multiplicity of a single shape factor S
"""
import time
import numpy as np
import random
from itertools import combinations, product
from collections import Counter

def construct():
    start = time.time()
    deadline = start + 55.0  # Safety margin

    # Precompute indices for all triples
    indices = list(combinations(range(30), 3))
    idx_arr = np.array(indices, dtype=np.int64)
    I, J, K = idx_arr[:, 0], idx_arr[:, 1], idx_arr[:, 2]

    def evaluate_target_area(points, target_area):
        """Count how many triples have exactly the given doubled area."""
        if len(points) != 30:
            return 0
        if len(set(points)) < 30:
            return 0
        
        pts = np.array(points, dtype=np.int64)
        x, y = pts[:, 0], pts[:, 1]
        
        xi, yi = x[I], y[I]
        xj, yj = x[J], y[J]
        xk, yk = x[K], y[K]
        
        areas = np.abs(xi * (yj - yk) + xj * (yk - yi) + xk * (yi - yj))
        return int(np.sum(areas == target_area))

    def get_best_target_and_score(points):
        """Return (max_multiplicity, best_target_area) in one pass."""
        if len(points) != 30:
            return 0, 0
        if len(set(points)) < 30:
            return 0, 0
        
        pts = np.array(points, dtype=np.int64)
        x, y = pts[:, 0], pts[:, 1]
        
        xi, yi = x[I], y[I]
        xj, yj = x[J], y[J]
        xk, yk = x[K], y[K]
        
        areas = np.abs(xi * (yj - yk) + xj * (yk - yi) + xk * (yi - yj))
        positive_areas = areas[areas > 0]
        
        if len(positive_areas) == 0:
            return 0, 0
            
        max_area = int(positive_areas.max())
        if max_area > 50000:
            unique_areas, counts = np.unique(positive_areas, return_counts=True)
            best_idx = np.argmax(counts)
            return int(counts.max()), int(unique_areas[best_idx])
        counts = np.bincount(positive_areas.astype(np.int64))
        best_idx = int(np.argmax(counts))
        return int(counts.max()), best_idx

    def compute_shape_factors(index_points):
        """Given 30 index points (i,j), compute the shape factor for each triple.
        Shape factor S = |(i2-i1)*(j3-j1) - (i3-i1)*(j2-j1)|
        """
        n = len(index_points)
        if n != 30:
            return None
        arr = np.array(index_points, dtype=np.int64)
        i_vals = arr[:, 0]
        j_vals = arr[:, 1]
        
        i1, j1 = i_vals[I], j_vals[I]
        i2, j2 = i_vals[J], j_vals[J]
        i3, j3 = i_vals[K], j_vals[K]
        
        shape = np.abs((i2 - i1) * (j3 - j1) - (i3 - i1) * (j2 - j1))
        return shape

    def build_gap_points(index_points, v1, v2, offset):
        """Build actual points from index points and lattice vectors."""
        a, b = v1
        c, d = v2
        ox, oy = offset
        pts = []
        for (i, j) in index_points:
            px = i * a + j * c + ox
            py = i * b + j * d + oy
            pts.append((px, py))
        return pts

    def fits_in_bounds(pts):
        return all(-30 <= p[0] <= 30 and -30 <= p[1] <= 30 for p in pts)

    def center_and_check(index_points, v1, v2):
        """Find best offset to center points in [-30,30]^2. Returns (pts, valid)."""
        a, b = v1
        c, d = v2
        # Compute raw points without offset
        raw_x = [i * a + j * c for (i, j) in index_points]
        raw_y = [i * b + j * d for (i, j) in index_points]
        
        min_x, max_x = min(raw_x), max(raw_x)
        min_y, max_y = min(raw_y), max(raw_y)
        
        # Center
        ox = -(min_x + max_x) // 2
        oy = -(min_y + max_y) // 2
        
        pts = []
        for (i, j) in index_points:
            px = i * a + j * c + ox
            py = i * b + j * d + oy
            pts.append((px, py))
        
        if not fits_in_bounds(pts):
            return None, False
        
        if len(set(pts)) < 30:
            return None, False
        
        return pts, True

    random.seed(42)
    
    best_points = None
    best_score = 0
    best_target = 0

    # === Phase 1: Number-theoretic GAP constructions ===
    # Try various lattice vectors (v1, v2) and index configurations
    
    # Lattice vectors to try (primitive vectors with small determinant)
    lattice_vectors = []
    for a in range(-3, 4):
        for b in range(-3, 4):
            if a == 0 and b == 0:
                continue
            for c in range(-3, 4):
                for d in range(-3, 4):
                    if c == 0 and d == 0:
                        continue
                    det = a * d - b * c
                    if det == 0:
                        continue
                    # Check primitive: gcd of 2x2 minors
                    # For 2D, just check that v1 and v2 are not multiples
                    lattice_vectors.append(((a, b), (c, d), abs(det)))
    
    # Sort by determinant (smaller det = smaller areas = potentially higher multiplicity)
    lattice_vectors.sort(key=lambda x: x[2])
    
    # Index configurations: rectangular grids in index space
    index_configs = []
    for w in range(4, 8):
        for h in range(4, 8):
            if w * h >= 30:
                # Full rectangle
                idx_pts = [(i, j) for i in range(w) for j in range(h)]
                if len(idx_pts) >= 30:
                    index_configs.append(('full', idx_pts[:30]))
                # Also try centered sub-rectangles
                if w * h > 30:
                    # Try different 30-point subsets
                    pass
    
    # Add sheared index configurations
    for w in range(4, 8):
        for h in range(4, 8):
            if w * h >= 30:
                for shear in [1, 2, -1, -2]:
                    idx_pts = [(i, j + i * shear) for i in range(w) for j in range(h)]
                    # Deduplicate
                    unique_pts = list(set(idx_pts))
                    if len(unique_pts) >= 30:
                        index_configs.append(('shear', unique_pts[:30]))
    
    # Add diagonal/line configurations
    for spacing in [1, 2, 3]:
        for w in range(4, 8):
            for h in range(4, 8):
                if w * h >= 30:
                    idx_pts = [(i * spacing, j * spacing) for i in range(w) for j in range(h)]
                    if len(idx_pts) >= 30:
                        index_configs.append(('spaced', idx_pts[:30]))
    
    random.shuffle(index_configs)
    random.shuffle(lattice_vectors)
    
    # Try combinations
    configs_tried = 0
    max_configs = 200
    
    for idx_config in index_configs:
        if time.time() > deadline - 20:
            break
        if configs_tried >= max_configs:
            break
        
        _, idx_pts = idx_config
        if len(idx_pts) < 30:
            continue
        
        for v1, v2, det_val in lattice_vectors[:30]:  # Try top 30 by small det
            if time.time() > deadline - 20:
                break
            if configs_tried >= max_configs:
                break
            
            configs_tried += 1
            
            pts, valid = center_and_check(idx_pts, v1, v2)
            if not valid:
                continue
            
            score, target = get_best_target_and_score(pts)
            if score > best_score:
                best_score = score
                best_points = pts
                best_target = target

    # === Phase 1b: Two-line constructions (keep from original) ===
    for line_sep in [2, 3, 4, 5]:
        if time.time() > deadline - 15:
            break
        for x_start in range(-15, 0):
            line1 = [(x_start + i, 0) for i in range(15)]
            line2 = [(x_start + i, line_sep) for i in range(15)]
            all_pts = line1 + line2
            
            if not all(-30 <= p[0] <= 30 and -30 <= p[1] <= 30 for p in all_pts):
                continue
            if len(set(all_pts)) < 30:
                continue
            
            score, target = get_best_target_and_score(all_pts)
            if score > best_score:
                best_score = score
                best_points = all_pts
                best_target = target

    # Fallback
    if best_points is None:
        pts = [(i, j) for i in range(5) for j in range(6)]
        cx, cy = 2, 2
        best_points = [(p[0]-cx, p[1]-cy) for p in pts]
        best_score, best_target = get_best_target_and_score(best_points)
    
    # === Phase 2: Local search optimizing for target area ===
    current_points = list(best_points)
    current_score = best_score
    current_target = best_target
    best_overall_points = list(current_points)
    best_overall_score = current_score
    
    current_target_count = evaluate_target_area(current_points, current_target)
    
    small_moves = [(dx, dy) for dx in range(-1, 2) for dy in range(-1, 2) if (dx, dy) != (0, 0)]
    medium_moves = [(dx, dy) for dx in range(-2, 3) for dy in range(-2, 3) if (dx, dy) != (0, 0)]
    
    no_improve = 0
    max_no_improve = 3000
    eval_counter = 0
    
    while time.time() < deadline - 3:
        if no_improve > max_no_improve:
            break
        
        idx = random.randint(0, 29)
        old_x, old_y = current_points[idx]
        
        if no_improve > 1000:
            moves = medium_moves
        else:
            moves = small_moves
        
        dx, dy = random.choice(moves)
        new_x = old_x + dx
        new_y = old_y + dy
        
        if not (-30 <= new_x <= 30 and -30 <= new_y <= 30):
            no_improve += 1
            continue
        
        new_point = (new_x, new_y)
        new_points = list(current_points)
        new_points[idx] = new_point
        
        if len(set(new_points)) < 30:
            no_improve += 1
            continue
        
        target_count = evaluate_target_area(new_points, current_target)
        
        eval_counter += 1
        do_full_eval = (eval_counter % 10 == 0) or (target_count > current_target_count + 2)
        
        if do_full_eval:
            full_score, new_target = get_best_target_and_score(new_points)
            
            if full_score > current_score:
                current_score = full_score
                current_points = new_points
                current_target = new_target
                current_target_count = target_count
                no_improve = 0
                
                if current_score > best_overall_score:
                    best_overall_score = current_score
                    best_overall_points = list(current_points)
            elif target_count > current_target_count:
                if random.random() < 0.4:
                    current_points = new_points
                    current_target_count = target_count
                    no_improve = 0
            else:
                no_improve += 1
        else:
            if target_count > current_target_count:
                current_points = new_points
                current_target_count = target_count
                no_improve = 0
            else:
                no_improve += 1
    
    return best_overall_points
