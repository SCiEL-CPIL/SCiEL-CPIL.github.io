        init_x.append(beta0)
        
        def objective(x):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                return float('inf')
            
            # Extract points
            pts = np.array(x[:2*n_pts]).reshape(n_pts, 2)
            cx = x[2*n_pts]
            cy = x[2*n_pts+1]
            beta = x[2*n_pts+2]
            
            # Normalize beta to [0, pi/6)
            beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
            
            # Smooth container size
            S_smooth = smooth_calc_S(pts, beta, cx, cy, temperature=0.1)
            
            # Overlap penalty
            pen = overlap_penalty(pts)
            
            # Weighted sum
            return S_smooth + 10.0 * pen
        
        try:
            res = minimize(objective, init_x, method='Nelder-Mead',
                           options={'maxiter': 2000, 'xatol': 1e-6, 'fatol': 1e-6, 'adaptive': True})
            
            if res.fun < float('inf'):
                # Extract optimized points and container
                opt_pts = np.array(res.x[:2*n_pts]).reshape(n_pts, 2)
                opt_cx = res.x[2*n_pts]
                opt_cy = res.x[2*n_pts+1]
                opt_beta = ((res.x[2*n_pts+2] % (math.pi/6)) + math.pi/6) % (math.pi/6)
                
                # Verify with exact Linprog
                S_exact, center_exact, D_exact = calc_S_for_beta(opt_pts, opt_beta)
                
                # Check validity (no overlaps)
                if overlap_penalty(opt_pts) < 1e-6:
                    return S_exact, opt_pts, opt_beta, center_exact
                else:
                    # If overlaps, try to relax by scaling? Or just return inf?
                    # Better to return a valid configuration if possible.
                    # For now, if penalty is high, discard.
                    return float('inf'), None, None, None
        except Exception:
            pass
            
        return float('inf'), None, None, None

