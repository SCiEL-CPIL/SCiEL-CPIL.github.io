    inner = []
    for x, y in best_global_pts:
        inner.append([float(x), float(y), float(angle_deg)])
        
    center = [float(cx), float(cy)]
    
    # Recompute exact S for the final points to be sure
    S_final, _, _ = calc_S_for_beta(best_global_pts, best_global_beta)
    if S_final == float('inf'):
         S_final = best_global_S
    
    # Add a tiny epsilon to side to ensure validity if evaluator is strict
    side = float(S_final + 1e-9)
    rotation = float(angle_deg)
    
    return inner, center, side, rotation
