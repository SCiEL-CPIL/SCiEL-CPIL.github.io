"""Construct the largest known 18-bit binary code with min distance 6.

Uses the extended quadratic-residue code of length 18 (parameters [18, 9, 6]),
which has 2^9 = 512 codewords. This is a known optimal linear code for A_2(18,6).
The generator matrix is constructed from the quadratic residue code over GF(2)
with the standard extension.
"""
import time

N = 18
MIN_D = 6


def _hamming(a, b):
    return (a ^ b).bit_count()


def _valid_pairwise(words, min_d):
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            if _hamming(wi, words[j]) < min_d:
                return False
    return True


def _quadratic_residue_code_18():
    """Construct the extended quadratic-residue code of length 18, [18, 9, 6].
    
    The QR code of length 17 over GF(2) has parameters [17, 9, 5].
    Extending by one parity bit gives [18, 9, 6].
    
    We build the generator matrix using the standard construction:
    - The QR(17) code is generated by the circulant matrix based on the
      quadratic residues modulo 17: {1, 4, 9, 16, 8, 2, 15, 13, 5}
    - The extended code adds a parity-check bit to each codeword.
    """
    # Quadratic residues mod 17 (nonzero squares)
    # 1^2=1, 2^2=4, 3^2=9, 4^2=16, 5^2=8, 6^2=2, 7^2=15, 8^2=13
    # So QR set: {1, 2, 4, 5, 8, 9, 13, 15} plus 0 for the full set of 9 positions
    # Actually, the QR(17) code uses the 9 nonzero quadratic residues mod 17
    # which are: 1, 4, 9, 16, 8, 2, 15, 13, 5
    # Let's use the standard generator matrix approach.
    
    # The QR(17) code is a cyclic code. Its generator polynomial g(x) divides x^17 - 1.
    # For the [17,9,5] QR code, we can construct the generator matrix as follows:
    # Use the 9x17 matrix where row i is the shift of the base row.
    
    # Base row: indicator of quadratic residues mod 17 (positions 0-16)
    # QR mod 17: {1, 4, 9, 16, 8, 2, 15, 13, 5}
    # Position 0 is not a QR (0^2 = 0)
    # Let's define the base vector of length 17
    
    base = [0] * 17
    for r in [1, 4, 9, 16, 8, 2, 15, 13, 5]:
        base[r] = 1
    
    # Generate 9 rows of the generator matrix (cyclic shifts)
    gen_matrix = []
    for i in range(9):
        row = [0] * 17
        for j in range(17):
            row[j] = base[(j + i) % 17]
        gen_matrix.append(row)
    
    # Now generate all 2^9 = 512 codewords
    words = []
    for mask in range(512):
        word = [0] * 17
        for bit in range(9):
            if (mask >> bit) & 1:
                for pos in range(17):
                    word[pos] ^= gen_matrix[bit][pos]
        
        # Add parity bit for extension to length 18
        parity = sum(word) % 2
        full_word = word + [parity]
        
        # Convert to integer
        val = 0
        for i, b in enumerate(full_word):
            if b:
                val |= (1 << i)
        words.append(val)
    
    return words


def construct():
    start = time.time()
    
    # Construct the extended QR code of length 18
    words = _quadratic_residue_code_18()
    
    # Verify the code is valid
    if not _valid_pairwise(words, MIN_D):
        # This should not happen, but fall back to a simpler construction
        # Use Reed-Muller RM(1,4) extended as fallback
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
    
    return words
