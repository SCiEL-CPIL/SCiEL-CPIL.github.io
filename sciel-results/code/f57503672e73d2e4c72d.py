def get_laderman_factors():
    n = 3
    rank = 23
    U = np.zeros((n*n, rank))
    V = np.zeros((n*n, rank))
    W = np.zeros((n*n, rank))
    
    # Helper to set coefficient
    def set_u(i, j, r, val): U[i*n+j, r] = val
    def set_v(j, k, r, val): V[j*n+k, r] = val
    def set_w(k, i, r, val): W[k*n+i, r] = val

    # 1
    set_u(0,0,0,1); set_v(0,0,0,1); set_w(0,0,0,1)
    # 2
    set_u(0,0,1,1); set_v(1,0,1,1); set_v(1,1,1,-1); set_w(0,1,1,1)
    # 3
    set_u(1,0,2,1); set_v(0,1,2,1); set_v(0,0,2,-1); set_w(1,0,2,1)
    # 4
    set_u(0,1,3,1); set_v(1,1,3,1); set_w(0,1,3,1)
    # 5
    set_u(0,1,4,1); set_v(2,0,4,1); set_v(2,2,4,-1); set_w(0,2,4,1)
    # 6
    set_u(2,0,5,1); set_v(0,2,5,1); set_v(0,0,5,-1); set_w(2,0,5,1)
    # 7
    set_u(1,1,6,1); set_v(1,1,6,1); set_w(1,1,6,1)
    # 8
    set_u(1,1,7,1); set_v(2,1,7,1); set_v(2,2,7,-1); set_w(1,2,7,1)
    # 9
    set_u(2,1,8,1); set_v(1,2,8,1); set_v(1,1,8,-1); set_w(2,1,8,1)
    # 10
    set_u(0,2,9,1); set_v(2,2,9,1); set_w(0,2,9,1)
    # 11
    set_u(0,2,10,1); set_v(1,0,10,1); set_v(1,1,10,-1); set_w(0,1,10,1)
    # 12
    set_u(1,2,11,1); set_v(0,1,11,1); set_v(0,0,11,-1); set_w(1,0,11,1)
    # 13
    set_u(1,2,12,1); set_v(1,1,12,1); set_w(1,1,12,1)
    # 14
    set_u(2,2,13,1); set_v(2,2,13,1); set_w(2,2,13,1)
    
    # The "complex" terms 15-23
    # 15: (A00+A11+A22)(B00-B11-B22)
    set_u(0,0,14,1); set_u(1,1,14,1); set_u(2,2,14,1)
    set_v(0,0,14,1); set_v(1,1,14,-1); set_v(2,2,14,-1)
    set_w(0,0,14,1); set_w(1,1,14,-1); set_w(2,2,14,-1)
    
    # 16: (A00+A11+A22)(B11-B01-B22)
    set_u(0,0,15,1); set_u(1,1,15,1); set_u(2,2,15,1)
    set_v(1,1,15,1); set_v(0,1,15,-1); set_v(2,2,15,-1)
    set_w(1,1,15,1); set_w(0,1,15,-1); set_w(2,2,15,-1)
    
    # 17: (A00+A11+A22)(B22-B02-B12)
    set_u(0,0,16,1); set_u(1,1,16,1); set_u(2,2,16,1)
    set_v(2,2,16,1); set_v(0,2,16,-1); set_v(1,2,16,-1)
    set_w(2,2,16,1); set_w(0,2,16,-1); set_w(1,2,16,-1)
    
    # 18: (A10+A21+A02)(B00-B02-B20)
    set_u(1,0,17,1); set_u(2,1,17,1); set_u(0,2,17,1)
    set_v(0,0,17,1); set_v(0,2,17,-1); set_v(2,0,17,-1)
    set_w(0,0,17,1); set_w(0,2,17,-1); set_w(2,0,17,-1)
    
    # 19: (A10+A21+A02)(B11-B01-B21)
    set_u(1,0,18,1); set_u(2,1,18,1); set_u(0,2,18,1)
    set_v(1,1,18,1); set_v(0,1,18,-1); set_v(2,1,18,-1)
    set_w(1,1,18,1); set_w(0,1,18,-1); set_w(2,1,18,-1)
    
    # 20: (A10+A21+A02)(B22-B12-B20)
    set_u(1,0,19,1); set_u(2,1,19,1); set_u(0,2,19,1)
    set_v(2,2,19,1); set_v(1,2,19,-1); set_v(2,0,19,-1)
    set_w(2,2,19,1); set_w(1,2,19,-1); set_w(2,0,19,-1)
    
    # 21: (A02+A10+A21)(B01-B00-B11)
    set_u(0,2,20,1); set_u(1,0,20,1); set_u(2,1,20,1)
    set_v(0,1,20,1); set_v(0,0,20,-1); set_v(1,1,20,-1)
    set_w(0,1,20,1); set_w(0,0,20,-1); set_w(1,1,20,-1)
    
    # 22: (A02+A10+A21)(B12-B02-B11)
    set_u(0,2,21,1); set_u(1,0,21,1); set_u(2,1,21,1)
    set_v(1,2,21,1); set_v(0,2,21,-1); set_v(1,1,21,-1)
    set_w(1,2,21,1); set_w(0,2,21,-1); set_w(1,1,21,-1)
    
    # 23: (A02+A10+A21)(B20-B00-B22)
    set_u(0,2,22,1); set_u(1,0,22,1); set_u(2,1,22,1)
    set_v(2,0,22,1); set_v(0,0,22,-1); set_v(2,2,22,-1)
    set_w(2,0,22,1); set_w(0,0,22,-1); set_w(2,2,22,-1)

    return U, V, W
