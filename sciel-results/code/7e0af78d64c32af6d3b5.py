import time
import random
from math import gcd
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 80.0  # Leave 10s margin for 90s limit
    
    n = 30
    
    # Precompute LCM of 1..30
    L = 1
    for i in range(1, n + 1):
        L = L * i // gcd(L, i)
    
    # W[i] = L // (i+1) for i in 0..29
    W = [L // (i + 1) for i in range(n)]
    
    best_abs_K = float('inf')
    best_coeffs = None
    
    def try_update(coeffs):
        nonlocal best_abs_K, best_coeffs
        K = sum(coeffs[i] * W[i] for i in range(n))
        if K == 0:
            return
        abs_K = abs(K)
        if abs_K < best_abs_K:
            best_abs_K = abs_K
            best_coeffs = list(coeffs)
    
    # === Phase 1: LLL Lattice Basis Reduction ===
    # We want to find c in {-1,0,1}^n minimizing |sum c[i]*W[i]| subject to sum != 0.
    # 
    # LLL approach: Construct a lattice where short vectors correspond to small |K|.
    # 
    # Strategy: Use a 31-dimensional lattice.
    # Basis vectors:
    #   v_0 = (B, 0, 0, ..., 0)       -- "bias" vector to push K away from 0
    #   v_i = (W[i], e_i) for i=1..30 -- weight + unit vector in coefficient space
    #
    # Actually, let me think more carefully.
    #
    # The problem: minimize |sum_{i=1}^{30} c_i * W_i| where c_i in {-1,0,1}, sum != 0.
    #
    # LLL trick: Create a lattice in R^{n+1} with basis:
    #   b_0 = (M, 0, 0, ..., 0)  where M is large
    #   b_i = (W_i, e_i) for i = 1, ..., n
    #
    # A lattice point is: x_0 * b_0 + sum x_i * b_i = (x_0*M + sum x_i*W_i, x_1, x_2, ..., x_n)
    #
    # The squared norm is: (x_0*M + sum x_i*W_i)^2 + sum x_i^2
    #
    # If we set M very large, the dominant term is the first component.
    # But we want sum x_i * W_i to be small (and nonzero).
    #
    # Alternative: Use a different construction.
    #
    # Let's use the standard "closest vector to origin" approach.
    # Consider the lattice generated by:
    #   b_i = (W_i, e_i) for i = 1, ..., n
    #   b_{n+1} = (1, 0, 0, ..., 0)
    #
    # A lattice point: sum_{i=1}^n x_i * b_i + x_{n+1} * b_{n+1}
    #   = (sum x_i * W_i + x_{n+1}, x_1, x_2, ..., x_n)
    #
    # The squared norm: (sum x_i * W_i + x_{n+1})^2 + sum x_i^2
    #
    # If we choose x_{n+1} to cancel sum x_i * W_i (when possible), we get sum x_i^2.
    # But x_{n+1} must be integer, so this only works when sum x_i * W_i is integer (it is).
    #
    # This doesn't directly help. Let me try another approach.
    #
    # Better LLL formulation:
    # We want to find small nonzero values of K = sum c_i * W_i where c_i in {-1,0,1}.
    #
    # Consider the lattice L in Z^{n+1} generated by:
    #   u_i = (W_i, e_i) for i = 1, ..., n
    #   v = (1, 0, ..., 0)
    #
    # Any lattice element: sum c_i * u_i + d * v = (sum c_i * W_i + d, c_1, ..., c_n)
    #
    # The norm squared = (sum c_i * W_i + d)^2 + sum c_i^2
    #
    # Minimizing this over all integer c_i, d:
    # For fixed c, optimal d = -round(sum c_i * W_i), giving norm^2 = sum c_i^2 + (sum c_i * W_i - round(sum c_i * W_i))^2
    #
    # This is minimized when both sum c_i^2 and |sum c_i * W_i - round(...)| are small.
    #
    # Hmm, this is getting complicated. Let me try a simpler approach.
    #
    # Simplest LLL approach:
    # The weights W_i are known. We want sum c_i * W_i ≈ 0 (but not = 0).
    #
    # Consider the 1D "lattice" {sum c_i * W_i : c_i in Z}. The shortest nonzero element
    # in this set (with c_i constrained to {-1,0,1}) is what we want.
    #
    # Without the {-1,0,1} constraint, the GCD of all W_i would give the answer.
    # With the constraint, it's harder.
    #
    # Let me try: LLL on a lattice that encodes the constraint.
    #
    # Construction:
    # Work in R^{n+1}. Basis:
    #   b_i = (W_i, e_i) for i=1..n
    #   b_{n+1} = (C, 0, ..., 0) where C is a large constant
    #
    # Lattice point: (sum c_i W_i + c_{n+1}*C, c_1, ..., c_n)
    #
    # If C is chosen as a multiple of all W_i (e.g., L), then sum c_i W_i + c_{n+1}*L
    # is always a multiple of gcd(W_1,...,W_n).
    #
    # Actually, let's just implement LLL directly and see what short vectors we get.
    
    def lll_reduce(basis, delta=0.75, eta=0.5):
        """LLL lattice basis reduction. basis is a list of numpy arrays."""
        b = [row.astype(float) for row in basis]
        mu = [[0.0] * len(b) for _ in range(len(b))]
        b = [row.copy() for row in b]
        
        for k in range(1, len(b)):
            for j in range(k):
                # size reduction
                mu[k][j] = np.dot(b[k], b[j]) / np.dot(b[j], b[j])
                b[k] = b[k] - mu[k][j] * b[j]
        
        for k in range(1, len(b)):
            # Lovasz condition
            if np.dot(b[k], b[k]) < (delta - mu[k][k-1]**2) * np.dot(b[k-1], b[k-1]):
                b[k-1], b[k] = b[k].copy(), b[k-1].copy()
                mu[k-1], mu[k] = mu[k].copy(), mu[k-1].copy()
                # Recompute mu
                for j in range(k-1):
                    mu[k-1][j] = np.dot(b[k-1], b[j]) / np.dot(b[j], b[j])
                    mu[k][j] = np.dot(b[k], b[j]) / np.dot(b[j], b[j])
                    b[k-1] = b[k-1] - mu[k-1][j] * b[j]
                    b[k] = b[k] - mu[k][j] * b[j]
                if k > 1:
                    k -= 1
                    continue
            # Size reduction for subsequent vectors
            for j in range(k):
                mu[k+1][j] = np.dot(b[k+1], b[j]) / np.dot(b[j], b[j]) if k+1 < len(b) else 0
                if k+1 < len(b):
                    b[k+1] = b[k+1] - mu[k+1][j] * b[j]
        
        return b
    
    # Simpler and more robust LLL implementation
    def lll(basis):
        """Standard LLL algorithm. basis: list of numpy int/float arrays."""
        n = len(basis)
        d = len(basis[0])
        b = [row.astype(np.float64).copy() for row in basis]
        mu = np.zeros((n, n))
        
        # Initialize
        for k in range(1, n):
            for j in range(k):
                denom = np.dot(b[j], b[j])
                if denom > 0:
                    mu[k][j] = np.dot(b[k], b[j]) / denom
                    b[k] = b[k] - mu[k][j] * b[j]
        
        k = 1
        while k < n:
            # Lovasz condition
            denom = np.dot(b[k-1], b[k-1])
            if denom > 0:
                if np.dot(b[k], b[k]) < (0.75 - mu[k][k-1]**2) * denom:
                    # Swap
                    b[k-1], b[k] = b[k].copy(), b[k-1].copy()
                    mu[k-1], mu[k] = mu[k].copy(), mu[k-1].copy()
                    # Recompute
                    for j in range(k-1):
                        denom_j = np.dot(b[j], b[j])
                        if denom_j > 0:
                            mu[k-1][j] = np.dot(b[k-1], b[j]) / denom_j
                            b[k-1] = b[k-1] - mu[k-1][j] * b[j]
                            mu[k][j] = np.dot(b[k], b[j]) / denom_j
                            b[k] = b[k] - mu[k][j] * b[j]
                    if k > 1:
                        k -= 1
                        continue
                # Size reduction
                for j in range(k):
                    denom_j = np.dot(b[j], b[j])
                    if denom_j > 0:
                        mu[k][j] = np.dot(b[k], b[j]) / denom_j
                        b[k] = b[k] - mu[k][j] * b[j]
            k += 1
        
        return b
    
    # LLL-based search:
    # Construct a lattice where short vectors encode good coefficient assignments.
    #
    # Approach: Use the fact that if we can find c_i in {-1,0,1} with small |sum c_i W_i|,
    # then the vector (sum c_i W_i, c_1, ..., c_n) is "short" in a suitable lattice.
    #
    # Lattice construction:
    # Let's work in Z^{n+1}. Define basis vectors:
    #   e_i = (W_i, 0, ..., 0, 1, ..., 0)  (1 in position i+1) for i=0..n-1
    #   f   = (1, 0, 0, ..., 0)
    #
    # A lattice point is: (sum c_i W_i + d, c_0, c_1, ..., c_{n-1})
    # where c_i, d are integers.
    #
    # The squared norm is: (sum c_i W_i + d)^2 + sum c_i^2
    #
    # For a given c, the optimal d makes sum c_i W_i + d as close to 0 as possible.
    # Since sum c_i W_i is an integer, d = -sum c_i W_i gives first component = 0.
    # Then norm^2 = sum c_i^2.
    #
    # This means the shortest vectors have small sum c_i^2, i.e., few nonzero coefficients.
    # But we need sum c_i W_i != 0, so we can't have d cancel it exactly... wait,
    # d is a free integer variable. If sum c_i W_i = K, then d = -K gives first component 0.
    # The constraint is that the ORIGINAL sum (without d) must be nonzero.
    #
    # So: find shortest lattice vectors (K + d, c) where K = sum c_i W_i != 0.
    # The shortest such vectors will have small |c| (few nonzeros) and K != 0.
    #
    # But LLL finds ALL short vectors, including those with K=0. We need to filter.
    #
    # Let me try a different, more direct approach:
    #
    # Direct MITM is actually quite efficient for n=30. 3^15 = 14,348,907 which is manageable.
    # Let me optimize the MITM with numpy and also try LLL as a complementary approach.
    
    # === Phase 1: Optimized MITM with NumPy ===
    mid = n // 2  # 15
    
    # Generate all 3^15 combinations for first half using numpy
    # For each combination, compute the sum
    # Use base-3 representation
    
    def gen_sums_numpy(weights):
        """Generate all possible sums for a set of weights with coefficients in {-1,0,1}."""
        m = len(weights)
        total = 3 ** m
        # Generate all base-3 digits
        # Use numpy for efficiency
        indices = np.arange(total)
        # Convert to base 3
        # For position j, digit = (index // 3^j) % 3
        # We want the sum = sum_j (digit_j - 1) * weight_j
        
        # Precompute powers of 3
        powers = 3 ** np.arange(m)
        
        # Vectorized: for each index, compute digits and sum
        # This might use too much memory for 3^15 = 14.3M
        # Let's do it in chunks
        
        chunk_size = 1000000
        all_sums = []
        all_indices = []
        
        for start in range(0, total, chunk_size):
            end = min(start + chunk_size, total)
            idx_chunk = np.arange(start, end)
            
            # Compute base-3 digits for each index
            # digit_j = (idx // 3^j) % 3
            # sum_j (digit_j - 1) * w_j
            
            s = np.zeros(end - start, dtype=np.int64)
            for j in range(m):
                digits = (idx_chunk // powers[j]) % 3
                s += (digits - 1) * weights[j]
            
            all_sums.append(s)
            all_indices.append(idx_chunk)
        
        all_sums = np.concatenate(all_sums)
        all_indices = np.concatenate(all_indices)
        
        return all_sums, all_indices
    
    # Generate sums for first half (indices 0 to 14)
    W_a = W[:mid]
    W_b = W[mid:]
    
    print(f"Generating sums for half A ({len(W_a)} weights)...", flush=True)
    sums_a, idx_a = gen_sums_numpy(W_a)
    print(f"  Got {len(sums_a)} sums, min={sums_a.min()}, max={sums_a.max()}", flush=True)
    
    print(f"Generating sums for half B ({len(W_b)} weights)...", flush=True)
    sums_b, idx_b = gen_sums_numpy(W_b)
    print(f"  Got {len(sums_b)} sums, min={sums_b.min()}, max={sums_b.max()}", flush=True)
    
    # Sort half B by sum value
    order_b = np.argsort(sums_b)
    sorted_sums_b = sums_b[order_b]
    sorted_idx_b = idx_b[order_b]
    
    # For each sum in A, find closest sum in B to -sum_a
    print("Searching for optimal combination...", flush=True)
    
    # Use searchsorted for efficiency
    targets = -sums_a
    insert_positions = np.searchsorted(sorted_sums_b, targets)
    
    # Check candidates at insert_positions and insert_positions-1
    # Clip to valid range
    pos1 = np.clip(insert_positions, 0, len(sorted_sums_b) - 1)
    pos0 = np.clip(insert_positions - 1, 0, len(sorted_sums_b) - 1)
    
    # Compute totals for both candidates
    total1 = sums_a + sorted_sums_b[pos1]
    total0 = sums_a + sorted_sums_b[pos0]
    
    abs_total1 = np.abs(total1)
    abs_total0 = np.abs(total0)
    
    # Exclude zero
    abs_total1[total1 == 0] = np.inf
    abs_total0[total0 == 0] = np.inf
    
    # Find the best
    best1 = np.argmin(abs_total1)
    best0 = np.argmin(abs_total0)
    
    best_val1 = abs_total1[best1]
    best_val0 = abs_total0[best0]
    
    if best_val1 <= best_val0:
        best_idx_a = best1
        best_idx_b_pos = pos1[best1]
        best_K = total1[best1]
    else:
        best_idx_a = best0
        best_idx_b_pos = pos0[best0]
        best_K = total0[best0]
    
    best_abs_K = abs(best_K)
    
    # Decode the coefficients
    def decode_index(idx, m):
        """Decode a base-3 index into coefficients in {-1,0,1}."""
        coeffs = []
        for j in range(m):
            digit = (idx // (3 ** j)) % 3
            coeffs.append(digit - 1)
        return coeffs
    
    coeffs_a = decode_index(int(idx_a[best_idx_a]), mid)
    coeffs_b = decode_index(int(sorted_idx_b[best_idx_b_pos]), n - mid)
    best_coeffs = coeffs_a + coeffs_b
    
    print(f"MITM found: |K| = {best_abs_K}, K = {best_K}", flush=True)
    print(f"  Coeffs: {best_coeffs}", flush=True)
    
    # Verify
    K_check = sum(best_coeffs[i] * W[i] for i in range(n))
    assert K_check == best_K, f"Mismatch: {K_check} vs {best_K}"
    
    # === Phase 2: Try to improve with local search ===
    random.seed(42)
    current = list(best_coeffs)
    current_K = best_K
    
    improved = True
    while improved and time.time() < deadline:
        improved = False
        indices = list(range(n))
        random.shuffle(indices)
        
        for i in indices:
            if time.time() > deadline:
                break
                
            old_c = current[i]
            
            for new_c in [-1, 0, 1]:
                if new_c == old_c:
                    continue
                
                new_K = current_K + (new_c - old_c) * W[i]
                
                if new_K == 0:
                    continue
                
                new_abs_K = abs(new_K)
                if new_abs_K < best_abs_K:
                    current[i] = new_c
                    current_K = new_K
                    best_abs_K = new_abs_K
                    best_coeffs = list(current)
                    improved = True
                    old_c = new_c
                    break
    
    # === Phase 3: LLL-based search for additional improvement ===
    if time.time() < deadline - 10:
        # Try LLL on a constructed lattice
        # Lattice in R^{n+1}:
        #   b_i = (W_i, e_i) for i=0..n-1
        #   b_n = (1, 0, ..., 0)
        #
        # Short vectors give (K+d, c) where K = sum c_i W_i
        # We want K != 0 and |K| small.
        
        print("Running LLL search...", flush=True)
        
        # Build basis
        dim = n + 1
        basis = []
        for i in range(n):
            v = np.zeros(dim)
            v[0] = W[i]
            v[i + 1] = 1
            basis.append(v)
        # Add (1, 0, ..., 0)
        v = np.zeros(dim)
        v[0] = 1
        basis.append(v)
        
        # Run LLL
        try:
            reduced = lll(basis)
            
            # Check the first few reduced vectors for good candidates
            # A vector (x_0, x_1, ..., x_n) in the reduced basis corresponds to
            # some combination. We need to check if x_1..x_n are in {-1,0,1}
            # and if x_0 (which equals sum x_i W_i + d for some d) gives a valid K.
            
            # Actually, the reduced basis vectors are linear combinations of the original.
            # We need to track the integer coefficients.
            # This is getting complex. Let me try a simpler approach.
            
            # Alternative: just check the first row of the reduced basis
            # and see if it gives a valid coefficient vector.
            
            # For now, skip LLL if it's too complex and rely on MITM + local search.
            print("LLL: skipping complex decode, using MITM result", flush=True)
        except Exception as e:
            print(f"LLL failed: {e}", flush=True)
    
    # === Phase 4: Additional random restarts ===
    if time.time() < deadline - 5:
        for restart in range(50):
            if time.time() > deadline:
                break
            
            current = list(best_coeffs)
            current_K = sum(current[i] * W[i] for i in range(n))
            
            num_perturb = random.randint(1, 3)
            for _ in range(num_perturb):
                idx = random.randint(0, n - 1)
                current[idx] = random.choice([-1, 0, 1])
            
            current_K = sum(current[i] * W[i] for i in range(n))
            if current_K == 0:
                continue
            
            improved_local = True
            while improved_local and time.time() < deadline:
                improved_local = False
                indices = list(range(n))
                random.shuffle(indices)
                
                for i in indices:
                    if time.time() > deadline:
                        break
                        
                    old_c = current[i]
                    
                    for new_c in [-1, 0, 1]:
                        if new_c == old_c:
                            continue
                        
                        new_K = current_K + (new_c - old_c) * W[i]
                        
                        if new_K == 0:
                            continue
                        
                        new_abs_K = abs(new_K)
                        if new_abs_K < best_abs_K:
                            current[i] = new_c
                            current_K = new_K
                            best_abs_K = new_abs_K
                            best_coeffs = list(current)
                            improved_local = True
                            old_c = new_c
                            break
    
    # Final verification
    final_K = sum(best_coeffs[i] * W[i] for i in range(n))
    assert final_K != 0, "Final sum is zero!"
    assert all(c in (-1, 0, 1) for c in best_coeffs), "Invalid coefficient!"
    
    print(f"Final: |K| = {abs(final_K)}, K = {final_K}, value = {abs(final_K)}/{L}", flush=True)
    
    return best_coeffs
