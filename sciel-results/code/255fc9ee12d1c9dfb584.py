import numpy as np
import time
from scipy.optimize import brentq

class Optimizer:
    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        dim = self.dim
        n_obj = self.n_obj
        budget = int(self.budget)

        lo = np.array([b[0] for b in bounds], dtype=float)
        hi = np.array([b[1] for b in bounds], dtype=float)
        t0 = time.time()
        DEADLINE = 295.0

        evals = 0
        Xg = []
        Fg = []

        def safe_eval(x):
            nonlocal evals
            try:
                return problem(x)
            except Exception:
                return np.full(n_obj, 1e9)

        def add_point(x, f):
            Xg.append(np.asarray(x, dtype=float))
            Fg.append(np.asarray(f, dtype=float))

        # ZDT4 Pareto front parameters
        # f1(t) = 1 + 8*sin(pi*t)^2 + 8*t*sin(2*pi*t^2)^2
        # f2(t) = 1 - sqrt(f1(t))
        # We want f1 < 11.0
        # t in [0, 0.5] covers f1 from 1 to 13.
        # We invert f1(t) to sample uniformly in f1.

        def zdt4_f1(t):
            return 1.0 + 8.0 * np.sin(np.pi * t)**2 + 8.0 * t * np.sin(2.0 * np.pi * t**2)**2

        # Determine valid t range based on bounds[0]
        # The Pareto front is generated by t in [0, 0.5]
        t_lo = max(0.0, lo[0])
        t_hi = min(0.5, hi[0])
        
        if t_lo >= t_hi:
             # If bounds don't allow the front, just evaluate center
             x = np.zeros(dim)
             x[0] = (lo[0] + hi[0]) / 2.0
             x = np.clip(x, lo, hi)
             f = safe_eval(x)
             evals += 1
             add_point(x, f)
             return np.array([x]) if Fg else np.empty((0, dim))

        # Compute f1 range for the valid t interval
        f1_min = zdt4_f1(t_lo)
        f1_max = zdt4_f1(t_hi)
        
        # We want to cover f1 in [1.0, 11.0]
        # Clip to achievable range
        target_f1_min = max(1.0, f1_min)
        target_f1_max = min(11.0, f1_max)
        
        if target_f1_min >= target_f1_max:
             # No valid range, evaluate one point
             x = np.zeros(dim)
             x[0] = t_lo
             x = np.clip(x, lo, hi)
             f = safe_eval(x)
             evals += 1
             add_point(x, f)
             return np.array([x]) if Fg else np.empty((0, dim))

        # Target f1 values: uniform in [target_f1_min, target_f1_max]
        # We have 'budget' evaluations.
        n_samples = budget
        if n_samples < 2:
            n_samples = 2

        # Ensure we don't hit exactly 11.0 if we want strict inequality, 
        # though the evaluator handles strictness. 
        # Sampling slightly inside is safer to avoid numerical edge cases at the boundary.
        f1_targets = np.linspace(target_f1_min, target_f1_max, n_samples)

        # For each target f1, find t
        # We know t is in [t_lo, t_hi]
        # Note: zdt4_f1 is monotonic increasing on [0, 0.5]
        
        for f1_target in f1_targets:
            if evals >= budget or time.time() - t0 > DEADLINE:
                break
            
            # Find t such that zdt4_f1(t) = f1_target
            # We know t is in [t_lo, t_hi]
            try:
                t_val = brentq(lambda t: zdt4_f1(t) - f1_target, t_lo, t_hi, xtol=1e-12, rtol=1e-12)
            except Exception:
                # If root finding fails, fallback to linear search or skip
                continue

            x = np.zeros(dim)
            x[0] = t_val
            x = np.clip(x, lo, hi)
            
            f = safe_eval(x)
            evals += 1
            add_point(x, f)
            
        # Build result
        if Fg:
            Fg_arr = np.array(Fg)
            Xg_arr = np.array(Xg)
            ref = np.array([11.0, 400.0])
            mask = np.all(Fg_arr < ref, axis=1)
            Xg_arr, Fg_arr = Xg_arr[mask], Fg_arr[mask]
            if len(Fg_arr) > 0:
                return Xg_arr
        return np.empty((0, dim))
