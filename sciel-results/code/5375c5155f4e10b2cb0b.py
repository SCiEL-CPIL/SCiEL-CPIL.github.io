import time
from itertools import combinations

def construct():
    start_time = time.time()
    deadline = 145.0
    
    # Points: 0..10, 11 (infinity)
    # Permutations of 12 points
    # Group PSL(2,11) generators
    # x -> x+1 (mod 11), inf -> inf
    # x -> 1/x (mod 11), 0 <-> inf
    
    # Map 11 to infinity
    INF = 11
    
    def gen_T():
        # x -> x + 1 mod 11, inf -> inf
        perm = list(range(12))
        for i in range(11):
            perm[i] = (i + 1) % 11
        perm[INF] = INF
        return perm

    def gen_M():
        # x -> 1/x mod 11, 0 <-> inf
        perm = list(range(12))
        perm[0] = INF
        perm[INF] = 0
        for i in range(1, 11):
            # Find j such that i*j = 1 mod 11
            for j in range(1, 11):
                if (i * j) % 11 == 1:
                    perm[i] = j
                    break
        return perm

    T = gen_T()
    M = gen_M()

    # Generate all elements of PSL(2,11)
    # Use BFS/DFS on the group
    identity = list(range(12))
    elements = [identity]
    element_set = {tuple(identity)}
    
    queue = [identity]
    while queue:
        curr = queue.pop(0)
        # Multiply by T and M
        for gen in [T, M]:
            # Compose curr and gen: (curr o gen)(x) = curr(gen(x))
            # Or gen o curr? Group action usually left or right.
            # Let's use right multiplication: new = gen applied after curr?
            # If we represent permutations as lists where perm[i] is the image of i,
            # then (f o g)(x) = f(g(x)).
            # If we apply g first, then f: result[i] = f[g[i]]
            # Let's generate the group closure.
            
            new_perm = [0] * 12
            for i in range(12):
                new_perm[i] = gen[curr[i]]
            
            if tuple(new_perm) not in element_set:
                element_set.add(tuple(new_perm))
                elements.append(new_perm)
                queue.append(new_perm)
            
            # Also try the other order just in case, though group is generated by T, M
            new_perm2 = [0] * 12
            for i in range(12):
                new_perm2[i] = curr[gen[i]]
            if tuple(new_perm2) not in element_set:
                element_set.add(tuple(new_perm2))
                elements.append(new_perm2)
                queue.append(new_perm2)
                
    # PSL(2,11) has 660 elements.
    # If we got more, we might be in PGL(2,11) or similar.
    # But 660 is the expected size.
    
    # Candidate base blocks
    # The base block must be a 6-subset of 0..11.
    # A known base block is {0, 1, 2, 4, 5, 8}
    # Let's try a few candidates.
    candidates = [
        (0, 1, 2, 4, 5, 8),
        (0, 1, 3, 4, 5, 9),
        (0, 1, 2, 3, 4, 5)
    ]
    
    for base in candidates:
        orbit = set()
        for perm in elements:
            # Apply perm to base block
            mapped = tuple(sorted(perm[x] for x in base))
            orbit.add(mapped)
            
        if len(orbit) == 132:
            # Check if it's a valid packing
            blocks = list(orbit)
            covered = set()
            valid = True
            for b in blocks:
                for five in combinations(b, 5):
                    if five in covered:
                        valid = False
                        break
                    covered.add(five)
                if not valid:
                    break
            
            if valid and len(covered) == 132 * 6:
                # Success
                return [list(b) for b in blocks]
                
    # Fallback: Return empty or best effort if construction fails (should not happen)
    return []
