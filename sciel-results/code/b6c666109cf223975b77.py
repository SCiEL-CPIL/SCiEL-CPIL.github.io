import time
import random
import sys

def construct():
    start_time = time.time()
    deadline = start_time + 55  # 5 second safety margin
    
    n = 12
    m = 40
    N = 1 << n  # 4096
    
    # Precompute comparability matrix
    # comp[i][j] is 1 if i and j are comparable (strict subset in either direction)
    # We use a list of bytearrays for memory efficiency and fast access
    comp = [bytearray(N) for _ in range(N)]
    
    # Optimization: Only compute for i < j and mirror, or just compute all
    # Since N is 4096, N^2 is 16M.
    # Python loop for 16M iterations is slow (~1-2 seconds).
    # We can optimize by iterating over i and j where j is a superset of i.
    # But simple nested loop with bit ops might be okay if we are careful.
    # Actually, let's use a faster method.
    # For each i, iterate through supersets of i.
    # Supersets of i can be generated by adding bits not in i.
    
    # Alternative:
    # For i in range(N):
    #   for j in range(N):
    #     if i == j: continue
    #     if (i & j) == i: comp[i][j] = 1
    #     elif (j & i) == j: comp[i][j] = 1
    
    # This is 16M * 2 checks. ~32M ops.
    # In Python, 32M ops can take 2-3 seconds.
    # Let's try to speed it up.
    
    # We can precompute the subset relation more efficiently.
    # Let's just do the double loop but break early if possible? No.
    # Let's use the property: i subset j iff (i | j) == j.
    
    # To speed up precomputation, we can do it in a tighter loop or use numpy if available, 
    # but standard library is safer for compatibility. 
    # However, 16M iterations in pure Python is borderline for 55s total if we also run SA.
    # Let's check: 16M iterations * ~100ns/iter (optimistic) = 1.6s. Realistically 2-3s.
    # This is acceptable.
    
    for i in range(N):
        row = comp[i]
        # i is not comparable with itself
        for j in range(N):
            if i == j:
                continue
            # Check if i subset j or j subset i
            # (i | j) == j implies i subset j
            # (i | j) == i implies j subset i
            # Since i != j, they are comparable if one is subset of the other.
            # This is equivalent to (i & j) == i OR (i & j) == j
            # Or simpler: (i | j) == i OR (i | j) == j
            # Actually, (i | j) == i means j subset i.
            # (i | j) == j means i subset j.
            # So:
            if (i | j) == i or (i | j) == j:
                row[j] = 1
            # Note: comp[j][i] will be set when i=j in outer loop? No, we set comp[i][j].
            # We need comp[j][i] to be 1 as well.
            # We can just set comp[j][i] here too?
            # But comp[j] is not loaded.
            # Let's just compute the full matrix symmetrically or compute upper triangle and mirror.
            # Given the speed constraint, let's just compute the whole thing.
            # It's better to ensure comp[i][j] == comp[j][i].
            # We can just check once and set both?
            # But accessing comp[j][i] inside the inner loop adds overhead.
            # Let's stick to setting row[j] and rely on the fact that we iterate all pairs.
            # Wait, if I only set row[j], then comp[j][i] is 0 unless j's row sets it.
            # Since we iterate all i and all j, comp[j][i] will be set when outer loop is j and inner is i.
            # So we don't need to set it explicitly here.
            
    # Verify time
    if time.time() > deadline - 10:
        # If precomputation took too long, return a trivial solution
        # But it shouldn't.
        pass

    # Greedy Initialization
    # Start with an empty set (mask 0)
    current_masks = [0]
    # We need to add m-1 more masks.
    # To speed up greedy, we can precompute for each mask, the list of masks it is comparable with?
    # Or just iterate through all available masks and pick the best.
    # This is O(m * N * m) = 40 * 4096 * 40 = 6.5M ops.
    # This is fast.
    
    available = set(range(1, N))  # 0 is already taken
    # We can't use a set of 4095 for removal? Yes we can.
    
    for _ in range(m - 1):
        best_mask = -1
        best_score = -1
        # Iterate through all available masks
        # To make this faster, we can sample? No, N=4096 is small.
        for mask in available:
            # Calculate score: number of comparable pairs with current_masks
            score = 0
            # Optimization: break early if score + (remaining) < best_score?
            # Max possible additional score is len(current_masks).
            # If best_score is high, we can prune.
            # But let's just compute it.
            for cm in current_masks:
                if comp[mask][cm]:
                    score += 1
                    # Pruning
                    if score + (len(current_masks) - current_masks.index(cm) - 1) < best_score:
                        # This pruning is expensive due to index(). 
                        # Let's just sum it up.
                        pass
            if score > best_score:
                best_score = score
                best_mask = mask
        
        if best_mask != -1:
            current_masks.append(best_mask)
            available.remove(best_mask)
            
    # Convert current_masks to a list for SA
    masks = current_masks[:]
    
    # Calculate initial score
    score = 0
    for i in range(m):
        for j in range(i + 1, m):
            if comp[masks[i]][masks[j]]:
                score += 1
                
    best_masks = masks[:]
    best_score = score
    
    # Simulated Annealing
    T = 5.0
    T_min = 0.01
    alpha = 0.9995  # Slow cooling
    steps = 0
    max_steps = 2000000  # Cap on steps
    
    # Precompute indices
    indices = list(range(m))
    
    while time.time() < deadline - 2 and steps < max_steps:
        steps += 1
        
        # Pick a random index
        i = random.choice(indices)
        old_m = masks[i]
        
        # Pick a new random mask
        # Bias towards masks that are likely to be comparable?
        # Uniform random is fine, but we can try to pick from a "neighborhood".
        # For now, uniform from all N masks.
        new_m = random.randint(0, N - 1)
        
        # Check if new_m is already in masks
        # O(m) check
        if new_m in masks:
            continue
            
        # Calculate delta
        delta = 0
        # Add comparabilities of new_m with others
        for j in range(m):
            if j == i:
                continue
            if comp[new_m][masks[j]]:
                delta += 1
        # Subtract comparabilities of old_m with others
        for j in range(m):
            if j == i:
                continue
            if comp[old_m][masks[j]]:
                delta -= 1
                
        if delta > 0:
            # Accept
            masks[i] = new_m
            score += delta
            if score > best_score:
                best_score = score
                best_masks = masks[:]
        else:
            # Accept with probability exp(delta / T)
            if random.random() < (delta / T): # Approximation for small delta/T, or use math.exp
                # math.exp is slower. For negative delta, exp(delta/T) is small.
                # If delta is very negative, prob is 0.
                # Let's use math.exp for correctness.
                import math
                prob = math.exp(delta / T)
                if random.random() < prob:
                    masks[i] = new_m
                    score += delta
                    
        # Cool down
        T *= alpha
        if T < T_min:
            T = T_min

    # Return the best found
    result = []
    for mask in best_masks:
        # Ensure distinct integers 0..11
        # mask is int.
        subset = [b for b in range(n) if (mask >> b) & 1]
        result.append(subset)
        
    return result
