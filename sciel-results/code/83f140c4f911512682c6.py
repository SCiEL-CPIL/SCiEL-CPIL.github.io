    def axial_to_cartesian(axial_list):
        pts = []
        for q, r in axial_list:
            x = math.sqrt(3) * (q + r / 2.0)
            y = 1.5 * r
            pts.append((x, y))
        return np.array(pts)

    def calc_S_for_beta(pts, beta):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        angles = beta + math.pi / 6.0 + np.arange(6) * math.pi / 3.0
        normals = np.column_stack([np.cos(angles), np.sin(angles)])
        
        n_pts = len(pts)
        c_obj = np.array([0.0, 0.0, 1.0])
        
        # Vectorized constraint construction
        # For each normal (nx, ny) and point (px, py):
        #   -nx*cx - ny*cy - D <= -(px*nx + py*ny)  =>  nx*cx + ny*cy + D >= px*nx + py*ny
        #   nx*cx + ny*cy - D <= px*nx + py*ny       =>  -nx*cx - ny*cy + D >= -(px*nx + py*ny)
        # Reformulated as A_ub @ [cx, cy, D] <= b_ub:
        #   -nx*cx - ny*cy - D <= -(px*nx + py*ny)
        #   nx*cx + ny*cy - D <= px*nx + py*ny
        
        # Shape: (6 * n_pts, 3)
        nx_col = normals[:, 0:1]  # (6,1)
        ny_col = normals[:, 1:2]  # (6,1)
        px_row = pts[:, 0:1].T    # (1, n_pts)
        py_row = pts[:, 1:1].T    # (1, n_pts)
        
        # Tile to (6, n_pts)
        nx_tiled = np.tile(nx_col, (1, n_pts))
        ny_tiled = np.tile(ny_col, (1, n_pts))
        px_tiled = np.tile(px_row, (6, 1))
        py_tiled = np.tile(py_row, (6, 1))
        
        A_ub = np.zeros((2 * 6 * n_pts, 3))
        b_ub = np.zeros(2 * 6 * n_pts)
        
        idx = 0
        for k in range(6):
            nx = normals[k, 0]
            ny = normals[k, 1]
            proj = pts[:, 0] * nx + pts[:, 1] * ny
            # Constraint 1: -nx*cx - ny*cy - D <= -proj
            A_ub[idx:idx+n_pts, 0] = -nx
            A_ub[idx:idx+n_pts, 1] = -ny
            A_ub[idx:idx+n_pts, 2] = -1.0
            b_ub[idx:idx+n_pts] = -proj
            idx += n_pts
            # Constraint 2: nx*cx + ny*cy - D <= proj
            A_ub[idx:idx+n_pts, 0] = nx
            A_ub[idx:idx+n_pts, 1] = ny
            A_ub[idx:idx+n_pts, 2] = -1.0
            b_ub[idx:idx+n_pts] = proj
            idx += n_pts
        
        bounds = [(None, None), (None, None), (0, None)]
        
        try:
            res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
            if res.status == 0:
                D = res.x[2]
                cx = res.x[0]
                cy = res.x[1]
                S = (D + APOTHEM) / APOTHEM
                return S, (cx, cy), D
            else:
                return float('inf'), None, None
        except Exception:
            return float('inf'), None, None

    def exact_S(pts, beta, cx, cy):
        """Compute exact S value for given configuration."""
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        pts_centered = pts - np.array([cx, cy])
        projs = np.abs(pts_centered @ normals.T)
        max_proj = float(np.max(projs))
        S = (max_proj + APOTHEM) / APOTHEM
        return S

    def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
        normals = np.array([
            (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
            for k in range(6)
        ])
        
        pts_centered = pts - np.array([cx, cy])
        projs = pts_centered @ normals.T
        all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])
        
        max_val = np.max(all_projs)
        if max_val > 100:
            return float('inf')
        
        shifted = (all_projs - max_val) / temperature
        shifted = np.clip(shifted, -50, 50)
        log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
        D = temperature * log_sum
        S = (D + APOTHEM) / APOTHEM
        return S

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None
        
        # Coarse grid search over beta (denser grid since LP is faster)
        n_grid = 40
        for i in range(n_grid + 1):
            beta = i * (math.pi / 6) / n_grid
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Refine beta with bounded scalar optimization from multiple starting points
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                refine_starts = [best_beta, 0.0, math.pi/12, math.pi/6 * 0.25, math.pi/6 * 0.75]
                for rb in refine_starts:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    lo = max(0, rb - 0.15)
                    hi = min(math.pi/6, rb + 0.15)
                    res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(lo, hi), method='bounded',
                                         options={'maxiter': 200, 'xatol': 1e-12})
                    if res.fun < best_S:
                        best_S = res.fun
                        best_beta = res.x
                        _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass
        
        # Smooth surrogate optimization - multi-start with adaptive temperature
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                temperatures = [0.12, 0.06, 0.03]
                start_configs = [
                    (best_center[0], best_center[1], best_beta),
                    (best_center[0], best_center[1], best_beta + 0.04),
                    (best_center[0], best_center[1], best_beta - 0.04),
                    (best_center[0], best_center[1], 0.0),
                ]
                
                for temp in temperatures:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    for sc in start_configs:
                        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                            break
                        
                        def smooth_obj(params, t=temp):
                            cx, cy, beta = params
                            beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            return smooth_calc_S(pts, beta, cx, cy, temperature=t)
                        
                        res = minimize(smooth_obj, list(sc), method='Nelder-Mead',
                                     options={'maxiter': 400, 'xatol': 1e-12, 'fatol': 1e-12,
                                              'adaptive': True})
                        
                        if res.fun < 1e10:
                            cx_r, cy_r, beta_r = res.x
                            beta_r = ((beta_r % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S_exact = exact_S(pts, beta_r, cx_r, cy_r)
                            if S_exact < best_S:
                                best_S = S_exact
                                best_beta = beta_r
                                best_center = (float(cx_r), float(cy_r))
        except Exception:
            pass
        
        # Final high-precision polish using exact objective with perturbed starts
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                def objective(params):
                    cx, cy, beta = params
                    beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                    return exact_S(pts, beta, cx, cy)
                
                bcx, bcy = best_center
                bb = best_beta
                polish_starts = [[bcx, bcy, bb]]
                # Radial perturbations
                for dr in [0.02, -0.02, 0.008, -0.008]:
                    for ang in range(0, 360, 45):
                        dx = dr * math.cos(math.radians(ang))
                        dy = dr * math.sin(math.radians(ang))
                        polish_starts.append([bcx + dx, bcy + dy, bb])
                # Angular perturbations
                for db in [-0.015, -0.005, 0.005, 0.015]:
                    polish_starts.append([bcx, bcy, bb + db])
                
                for init in polish_starts:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    res = minimize(objective, init, method='Nelder-Mead',
                                 options={'maxiter': 5000, 'xatol': 1e-14, 'fatol': 1e-14,
                                          'adaptive': True})
                    if res.fun < best_S:
                        best_S = res.fun
                        best_center = (float(res.x[0]), float(res.x[1]))
                        best_beta = ((float(res.x[2]) % (math.pi/6)) + math.pi/6) % (math.pi/6)
        except Exception:
            pass
            
        return best_S, best_beta, best_center

