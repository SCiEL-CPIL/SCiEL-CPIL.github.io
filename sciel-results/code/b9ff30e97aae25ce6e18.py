"""Cayley-graph construction for 4-regular girth-10 graph with deadline guard."""
import math
import time
from collections import deque

def construct(k, g):
    deadline = time.time() + 125  # 125s safety margin within 150s limit
    
    if k != 4:
        return _construct_fallback(k, g)
    
    # Strategy: search for a 4-regular Cayley graph on Z_m with generating set
    # S = {a, -a, b, -b} that has girth >= g.
    # Key optimizations:
    # 1. Normalize a=1 by scaling (if gcd(1,b,m)=1, we can always scale)
    #    More generally, try small a values first since they're more likely to work
    # 2. Use fast girth checking via BFS on non-backtracking walks
    # 3. Early termination when a valid graph is found
    # 4. Try m values from Moore bound upward
    
    best_n = None
    best_edges = None
    
    # Moore bound for (4,10) is 243
    # Try cyclic groups Z_m
    for m in range(243, 400):
        if time.time() > deadline - 5:
            break
        
        # For efficiency, try a=1 first (most common case)
        # Then try other a values
        a_candidates = [1] + list(range(2, m // 2 + 1))
        
        found_for_m = False
        for a in a_candidates:
            if time.time() > deadline - 5:
                break
            if found_for_m:
                break
            
            # a must be coprime to m for the subgroup generated by a to be large
            if math.gcd(a, m) != 1:
                continue
            
            # Try b values: b > a, b < m/2, gcd(b,m)=1, gcd(a,b,m)=1
            for b in range(a + 1, m // 2 + 1):
                if time.time() > deadline - 3:
                    break
                
                if math.gcd(b, m) != 1:
                    continue
                if math.gcd(math.gcd(a, b), m) != 1:
                    continue
                
                # Quick checks
                if (a + b) % m == 0:
                    continue
                if (2 * a) % m == 0:
                    continue
                if (2 * b) % m == 0:
                    continue
                if a == b or a == m - b or b == m - a:
                    continue
                
                # Full girth check
                if _check_girth_fast(m, a, b, g):
                    # Construct edges
                    edge_set = set()
                    for i in range(m):
                        for s in [a, b]:
                            j = (i + s) % m
                            if i < j:
                                edge_set.add((i, j))
                            else:
                                edge_set.add((j, i))
                    edges = sorted(edge_set)
                    
                    if best_n is None or m < best_n:
                        best_n = m
                        best_edges = edges
                    found_for_m = True
                    break
        
        if found_for_m:
            break
    
    if best_n is not None:
        return best_n, best_edges
    
    # Fallback: use the Lazebnik-Ustimenko-Woldar construction
    return _construct_fallback(4, g)


def _check_girth_fast(m, a, b, g):
    """Check that the Cayley graph of Z_m with S={a,-a,b,-b} has girth >= g.
    
    Uses BFS on the non-backtracking walk graph.
    State: (position, last_step_index) where last_step_index in {0,1,2,3}
    corresponding to steps [a, -a, b, -b].
    
    We check for closed non-backtracking walks of length L for L = 2, ..., g-1.
    A closed walk of length L starting and ending at 0 with no immediate backtracking
    corresponds to a cycle of length L in the original graph (or a multiple, but
    since we check all L < g, any cycle of length < g would be detected).
    
    Actually, more precisely: a non-backtracking closed walk of length L at vertex v
    means there's a walk v -> ... -> v of length L where no two consecutive edges
    are the same (in the undirected sense). For a simple graph, this is equivalent
    to no cycle of length <= L that can be traversed without backtracking.
    
    For our purpose: if there exists ANY non-backtracking closed walk of length L < g,
    then the girth is < g. We need to verify no such walk exists.
    """
    steps = [a, -a, b, -b]
    # Inverse mapping: step index i has inverse index inv[i]
    # a (idx 0) <-> -a (idx 1)
    # b (idx 2) <-> -b (idx 3)
    inv = [1, 0, 3, 2]
    
    # For each length L from 2 to g-1, check if any non-backtracking walk
    # of length L starts and ends at 0.
    
    # We do BFS layer by layer.
    # Layer 0: just position 0, no last step
    # Layer 1: positions {a, -a, b, -b}, with last step being the step taken
    # Layer L: for each state (pos, last_idx) from layer L-1,
    #          new states are (pos + steps[s], s) for s != inv[last_idx]
    
    # We want to know if position 0 appears in layer L for any L in [2, g-1]
    # (with the constraint that the walk is non-backtracking)
    
    # State representation: (position, last_step_index)
    # Use a set of (pos, last_idx) tuples
    
    # Layer 1
    current = set()
    for i, s in enumerate(steps):
        current.add((s % m, i))
    
    # Check layer 1 for position 0 (this would be a 1-cycle, impossible in simple graph
    # since no loops, but let's be safe)
    for (pos, last) in current:
        if pos == 0:
            return False
    
    # Layers 2 through g-1
    for L in range(2, g):
        next_layer = set()
        for (pos, last) in current:
            for s_idx in range(4):
                if s_idx == inv[last]:
                    continue
                new_pos = (pos + steps[s_idx]) % m
                next_layer.add((new_pos, s_idx))
        
        # Check if position 0 is in this layer
        for (pos, last) in next_layer:
            if pos == 0:
                return False
        
        current = next_layer
    
    return True


def _construct_fallback(k, g):
    """Fallback: use the Lazebnik-Ustimenko-Woldar construction from the seed."""
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
