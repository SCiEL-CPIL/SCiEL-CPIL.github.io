"""Optimal: 3 edge-disjoint Hamiltonian cycles in the 6-regular 21-vertex circulant graph (63 edges / 21 per cycle = 3 max)."""
import time

# EVOLVE-BLOCK-START
P = {'n': 21, 'edges': [[0, 1], [0, 2], [0, 5], [0, 16], [0, 19], [0, 20], [1, 2], [1, 3], [1, 6], [1, 17], [1, 20], [2, 3], [2, 4], [2, 7], [2, 18], [3, 4], [3, 5], [3, 8], [3, 19], [4, 5], [4, 6], [4, 9], [4, 20], [5, 6], [5, 7], [5, 10], [6, 7], [6, 8], [6, 11], [7, 8], [7, 9], [7, 12], [8, 9], [8, 10], [8, 13], [9, 10], [9, 11], [9, 14], [10, 11], [10, 12], [10, 15], [11, 12], [11, 13], [11, 16], [12, 13], [12, 14], [12, 17], [13, 14], [13, 15], [13, 18], [14, 15], [14, 16], [14, 19], [15, 16], [15, 17], [15, 20], [16, 17], [16, 18], [17, 18], [17, 19], [18, 19], [18, 20], [19, 20]]}

def construct():
    start_time = time.time()
    deadline = start_time + 50.0  # Safety margin for 60s limit
    
    n = P['n']
    
    # Construct the 3 Hamiltonian cycles using steps 1, 2, 5
    # In a circulant graph C_n(k1, k2, k3), the cycles generated by steps k1, k2, k3 
    # are edge-disjoint if the sets of differences {±ki} are disjoint mod n.
    # For n=21, steps 1, 2, 5 yield differences {1,20}, {2,19}, {5,16} which are disjoint.
    steps = [1, 2, 5]
    cycles = []
    
    for k in steps:
        if time.time() > deadline:
            break
        cyc = [0]
        cur = 0
        for _ in range(n - 1):
            cur = (cur + k) % n
            cyc.append(cur)
        cycles.append(cyc)
        
    # Verification Step: Ensure validity and edge-disjointness
    # This is a "polish" pass to guarantee correctness.
    if len(cycles) != 3:
        # Fallback: return whatever we have, though this should not happen
        pass
    else:
        # Check vertex sets
        target_vertices = set(range(n))
        for cyc in cycles:
            if set(cyc) != target_vertices:
                # Invalid cycle, clear result
                cycles = []
                break
            
        # Check edge disjointness
        if cycles:
            used_edges = set()
            for cyc in cycles:
                for i in range(len(cyc)):
                    u = cyc[i]
                    v = cyc[(i + 1) % len(cyc)]
                    edge = (min(u, v), max(u, v))
                    if edge in used_edges:
                        # Edge collision, invalid
                        cycles = []
                        break
                    used_edges.add(edge)
                if not cycles:
                    break
            
            # Check if all host edges are covered (optional, but confirms optimality)
            # The problem asks to maximize number of cycles, not necessarily cover all edges,
            # but since 3*21=63 (total edges), covering all edges implies max cycles.
            
    # Convert to Python ints and lists
    # The input P['edges'] are already ints, but ensure our output types are strict
    return [[int(v) for v in cyc] for cyc in cycles]
