def _try_improve(edges, n, max_time=30.0):
    """
    Try to remove edges from the hypergraph while maintaining non-2-colorability.
    This is a greedy edge-removal heuristic.
    """
    start = _now()
    current_edges = list(edges)
    current_n = n
    
    # Sort edges by "importance" - edges that appear in many minimal
    # non-2-colorable substructures are harder to remove.
    # For now, try removing edges in random order.
    
    rng = random.Random(123)
    improved = False
    
    # Try each edge for removal
    for i in range(len(current_edges) - 1):
        if _now() - start > max_time:
            break
        
        # Try removing edge i
        trial_edges = current_edges[:i] + current_edges[i+1:]
        
        # Check if still non-2-colorable
        if _is_not_2_colorable(trial_edges, current_n, deadline=_now() + 5.0):
            current_edges = trial_edges
            improved = True
    
    return current_edges, current_n, improved

def construct():
    start_time = _now()
    
    # First, get a baseline construction
    baseline = _known_51_edge_construction()
    best_n = baseline['n']
    best_edges = baseline['edges']
    best_e = len(best_edges)
    
    # If we already have <= 51 edges, great.
    # Now try to improve.
    
    if best_e <= 51:
        # Try to reduce further
        try:
            improved_edges, improved_n, improved = _try_improve(
                best_edges, best_n, max_time=30.0
            )
            if improved and len(improved_edges) < best_e:
                best_edges = improved_edges
                best_n = improved_n
                best_e = len(best_edges)
        except Exception:
            pass
    
    # Try random search for even smaller hypergraphs
    if _now() - start_time < 60:
        rng = random.Random(42)
        for n_try in range(10, 27):
            if _now() - start_time > 90:
                break
            max_e_to_try = min(50, best_e - 1)
            if max_e_to_try < 5:
                break
            for e_try in range(5, max_e_to_try + 1):
                if _now() - start_time > 90:
                    break
                # Try a few random instances
                for trial in range(3):
                    if _now() - start_time > 90:
                        break
                    all_edges = list(itertools.combinations(range(n_try), 5))
                    if len(all_edges) < e_try:
                        break
                    edges_try = rng.sample(all_edges, e_try)
                    edges_try = [list(e) for e in edges_try]
                    if _is_not_2_colorable(edges_try, n_try, deadline=_now() + 3.0):
                        if e_try < best_e:
                            best_edges = edges_try
                            best_n = n_try
                            best_e = e_try
    
    # Final safety check: verify the result is valid
    if len(best_edges) > 0:
        # Verify all edges are valid 5-element subsets
        valid = True
        for e in best_edges:
            if len(e) != 5 or any(v < 0 or v >= best_n for v in e):
                valid = False
                break
            if len(set(e)) != 5:
                valid = False
                break
        if not valid:
            # Fall back to the dense construction
            best_n = 9
            best_edges = [list(e) for e in itertools.combinations(range(9), 5)]
    
    return {'n': best_n, 'edges': best_edges}
