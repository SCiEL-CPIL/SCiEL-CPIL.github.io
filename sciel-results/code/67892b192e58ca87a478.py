def _verify_3x6(U, V, W, iters=12, seed=555):
    n, m, p = 3, 3, 6
    R = U.shape[1]
    rng = np.random.default_rng(seed)
    for _ in range(iters):
        a = rng.integers(-4, 5, size=(n, m))
        b = rng.integers(-4, 5, size=(m, p))
        C = a @ b
        Cc = np.zeros((n, p))
        for c in range(R):
            ua = np.array([[U[i * m + k, c] for k in range(m)] for i in range(n)])
            vb = np.array([[V[k * p + j, c] for j in range(p)] for k in range(m)])
            wa = np.array([[W[j * n + i, c] for i in range(n)] for j in range(p)])
            Cc += float(np.sum(ua * a)) * float(np.sum(vb * b)) * wa
        if not np.allclose(Cc, C, atol=1e-9, rtol=0.0):
            return False
    return True


def _laderman_3x3():
    """
    Returns U, V, W matrices for 3x3 matrix multiplication using Laderman's algorithm.
    U: (9, 19), V: (9, 19), W: (9, 19)
    Indexing: U[i*3+k], V[k*3+j], W[j*3+i]
    """
    n = 3
    m = 3
    p = 3
    rank = 19
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))

    # Define the 19 factors for Laderman
    # Indices: U[i*m+k, t], V[k*p+j, t]
    
    # 0
    U[0, 0] = 1; U[3, 0] = -1; U[6, 0] = 1
    V[0, 0] = 1; V[1, 0] = -1; V[2, 0] = 1
    # 1
    U[0, 1] = 1; U[3, 1] = -1; U[6, 1] = 1
    V[3, 1] = 1; V[4, 1] = -1; V[5, 1] = 1
    # 2
    U[0, 2] = 1; U[3, 2] = -1; U[6, 2] = 1
    V[6, 2] = 1; V[7, 2] = -1; V[8, 2] = 1
    # 3
    U[0, 3] = 1; U[3, 3] = 1; U[6, 3] = 1
    V[0, 3] = 1; V[1, 3] = 1; V[2, 3] = 1
    # 4
    U[0, 4] = 1; U[3, 4] = 1; U[6, 4] = 1
    V[3, 4] = 1; V[4, 4] = 1; V[5, 4] = 1
    # 5
    U[0, 5] = 1; U[3, 5] = 1; U[6, 5] = 1
    V[6, 5] = 1; V[7, 5] = 1; V[8, 5] = 1
    # 6
    U[1, 6] = 1
    V[3, 6] = 1
    # 7
    U[4, 7] = 1
    V[4, 7] = 1
    # 8
    U[7, 8] = 1
    V[5, 8] = 1
    # 9
    U[2, 9] = 1
    V[6, 9] = 1
    # 10
    U[5, 10] = 1
    V[7, 10] = 1
    # 11
    U[8, 11] = 1
    V[8, 11] = 1
    # 12
    U[1, 12] = 1; U[4, 12] = -1; U[7, 12] = 1
    V[3, 12] = 1; V[4, 12] = -1; V[5, 12] = 1
    # 13
    U[1, 13] = 1; U[4, 13] = 1; U[7, 13] = 1
    V[3, 13] = 1; V[4, 13] = 1; V[5, 13] = 1
    # 14
    U[2, 14] = 1; U[5, 14] = -1; U[8, 14] = 1
    V[6, 14] = 1; V[7, 14] = -1; V[8, 14] = 1
    # 15
    U[2, 15] = 1; U[5, 15] = 1; U[8, 15] = 1
    V[6, 15] = 1; V[7, 15] = 1; V[8, 15] = 1
    # 16
    U[0, 16] = 1; U[1, 16] = -1; U[2, 16] = 1
    V[0, 16] = 1; V[3, 16] = -1; V[6, 16] = 1
    # 17
    U[0, 17] = 1; U[1, 17] = 1; U[2, 17] = 1
    V[0, 17] = 1; V[3, 17] = 1; V[6, 17] = 1
    # 18
    U[3, 18] = 1; U[4, 18] = -1; U[5, 18] = 1
    V[1, 18] = 1; V[4, 18] = -1; V[7, 18] = 1

    # Solve for W
    # The condition is:
    # sum_{t=0}^{18} (sum_{k} U[i*3+k, t] A[i,k]) (sum_{k} V[k*3+j, t] B[k,j]) W[j*3+i, t] = C[i,j]
    # We require this to hold for all A, B.
    # This implies that the tensor T_{i,j,k} defined by the decomposition must match the matrix multiplication tensor.
    # Specifically, for the decomposition to be exact, the coefficients must satisfy:
    # sum_{t} U[i*3+k, t] V[k*3+j, t] W[j*3+i, t] = delta_{k,j} ? 
    # No, let's look at the expansion:
    # C_{ij} = sum_t (sum_{i',k'} U_{i'k'}^{(t)} A_{i'k'}) (sum_{k',j'} V_{k'j'}^{(t)} B_{k'j'}) W_{ji}^{(t)}
    # This form is actually NOT the standard tensor decomposition form $C_{ij} = \sum_k A_{ik} B_{kj}$.
    # The standard form is trilinear. The form above is bilinear in A and B, producing a matrix.
    # If we set A and B to basis matrices, we can solve for W.
    
    # Let's use the property that if we choose specific A and B, we can isolate terms.
    # However, the simplest way is to realize that this specific structure (Frobenius inner product scaling)
    # corresponds to the standard tensor decomposition if we interpret the indices correctly.
    # Actually, the code in _verify_3x6 does:
    # Cc += scalar_A * scalar_B * wa
    # This is equivalent to:
    # C = sum_t (U_t^T A U_t?) No, sum(ua*a) is Frobenius inner product <U_t, A>.
    # So C = sum_t <U_t, A> <V_t, B> W_t.
    
    # This is a valid representation of the bilinear map if U, V, W are chosen correctly.
    # We can find W by solving the linear system generated by random A, B, C?
    # No, we need an exact solution.
    # Let's solve for W using the identity:
    # For any A, B, AB = sum_t <U_t, A> <V_t, B> W_t.
    # This implies that the map (A, B) -> AB is represented by this sum.
    # We can determine W by evaluating the sum for basis matrices A and B?
    # There are 9 basis matrices for A and 9 for B.
    # Let A = E_{pq}, B = E_{rs}.
    # Then <U_t, E_{pq}> = U_t[p, q].
    # <V_t, E_{rs}> = V_t[r, s].
    # AB = E_{ps} if q==r else 0.
    # So for each (p,q,r,s) with q==r, we have:
    # E_{ps} = sum_t U_t[p, q] V_t[q, s] W_t.
    # This gives us 27 equations (for p, s, q where q is the matching index) for the 19*9 = 171 unknowns in W?
    # No, W_t is a 3x3 matrix, so 9 unknowns per t. 19*9 = 171 unknowns.
    # We have 27 equations (one for each non-zero entry of the product of basis matrices? No, 3*3*3 = 27 products E_pq E_qs = E_ps).
    # Each equation is a matrix equation: E_{ps} = sum_t U_t[p,q] V_t[q,s] W_t.
    # This is 9 scalar equations per (p,q,s) triplet? No, E_{ps} is a specific matrix.
    # So for each (p,q,s), we have 9 scalar equations (one for each entry of the resulting matrix E_{ps}).
    # Total equations: 27 triplets * 9 entries = 243 equations.
    # Total unknowns: 171.
    # This is an overdetermined system, but it should be consistent if U and V are correct Laderman factors.
    
    # We can solve this using least squares to find W.
    
    # Let's construct the system.
    # Unknowns: W_flat of size 171.
    # For each t (0..18), W_t is 3x3. Flatten to 9.
    # Total W_flat length 171.
    
    A_sys = np.zeros((243, 171))
    b_sys = np.zeros(243)
    
    eq_idx = 0
    for p in range(3):
        for q in range(3):
            for s in range(3):
                # Product E_pq * E_qs = E_ps
                # The result is a 3x3 matrix with 1 at (p, s) and 0 elsewhere.
                for i in range(3):
                    for j in range(3):
                        # Equation for entry (i, j) of the result
                        b_sys[eq_idx] = 1.0 if (i == p and j == s) else 0.0
                        
                        for t in range(19):
                            # Term: U_t[p, q] * V_t[q, s] * W_t[i, j]
                            # W_t[i, j] is at index t*9 + i*3 + j in W_flat
                            coeff = U[p*3 + q, t] * V[q*3 + s, t]
                            w_idx = t*9 + i*3 + j
                            A_sys[eq_idx, w_idx] = coeff
                        eq_idx += 1
    
    W_flat, residuals, rank, sv = np.linalg.lstsq(A_sys, b_sys, rcond=None)
    W = W_flat.reshape(19, 9).T # Reshape to (9, 19)
    
    return {"U": U, "V": V, "W": W}


def construct():
    # Get the 3x3x3 factors
    factors_3x3 = _laderman_3x3()
    U_3x3 = factors_3x3['U']
    V_3x3 = factors_3x3['V']
    W_3x3 = factors_3x3['W']
    
    n, m, p = 3, 3, 6
    rank_3x3 = 19
    rank_total = 2 * rank_3x3
    
    U = np.zeros((n*m, rank_total))
    V = np.zeros((m*p, rank_total))
    W = np.zeros((p*n, rank_total))
    
    # Block 0: Columns 0:3 of B, Columns 0:3 of C
    U[:, 0:rank_3x3] = U_3x3
    V[0:9, 0:rank_3x3] = V_3x3
    W[0:9, 0:rank_3x3] = W_3x3
    
    # Block 1: Columns 3:6 of B, Columns 3:6 of C
    U[:, rank_3x3:rank_total] = U_3x3
    V[9:18, rank_3x3:rank_total] = V_3x3
    W[9:18, rank_3x3:rank_total] = W_3x3
    
    return {"U": U, "V": V, "W": W}
