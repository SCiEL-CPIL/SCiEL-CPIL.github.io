"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import time
from collections import Counter
from itertools import combinations

# EVOLVE-BLOCK-START
def construct():
    start = time.time()
    deadline = start + 85.0  # safety margin under 90s

    def evaluate(points):
        """Compute the maximum multiplicity of any positive doubled area."""
        counts = Counter()
        n = len(points)
        for i in range(n):
            x1, y1 = points[i]
            for j in range(i + 1, n):
                x2, y2 = points[j]
                dx1 = x2 - x1
                dy1 = y2 - y1
                for k in range(j + 1, n):
                    x3, y3 = points[k]
                    dx2 = x3 - x1
                    dy2 = y3 - y1
                    det = abs(dx1 * dy2 - dy1 * dx2)
                    if det > 0:
                        counts[det] += 1
        if not counts:
            return 0
        return max(counts.values())

    def is_valid(points):
        if len(points) != 30:
            return False
        if len(set(points)) != 30:
            return False
        return all(-30 <= px <= 30 and -30 <= py <= 30 for px, py in points)

    best_points = None
    best_score = 0

    def try_points(pts):
        nonlocal best_points, best_score
        if not is_valid(pts):
            return
        score = evaluate(pts)
        if score > best_score:
            best_score = score
            best_points = pts

    # Initial configuration: two horizontal lines at y=0 and y=1, each with 15 points
    try_points([(x, 0) for x in range(15)] + [(x, 1) for x in range(15)])

    # Try grid configurations: w x h grids with exactly 30 points
    grid_configs = [
        (5, 6), (6, 5), (10, 3), (3, 10), (15, 2), (2, 15)
    ]
    for w, h in grid_configs:
        if w * h != 30:
            continue
        pts = [(x, y) for x in range(w) for y in range(h)]
        try_points(pts)
        if time.time() > deadline:
            return best_points

    # Try different line distances for two parallel lines
    for d in range(1, 6):
        pts = [(x, 0) for x in range(15)] + [(x, d) for x in range(15)]
        try_points(pts)
        if time.time() > deadline:
            return best_points

    # Try 3-line configurations with varying distributions
    for d in range(1, 4):
        for a in range(8, 23):
            for b in range(8, 23 - a + 8):
                c = 30 - a - b
                if c < 1 or c > 30:
                    continue
                if b < 1:
                    continue
                if 2 * d > 30:
                    continue
                pts = [(x, 0) for x in range(a)] + [(x, d) for x in range(b)] + [(x, 2 * d) for x in range(c)]
                try_points(pts)
                if time.time() > deadline:
                    return best_points

    # Number-theoretic construction: generalized arithmetic progression
    # Points as (i*a + j*b, i*c + j*d) for i in range(n1), j in range(n2)
    # where n1 * n2 = 30, and the basis vectors (a,c) and (b,d) are chosen
    # to maximize frequency of a specific cross-product value.
    
    # For a 2D lattice generated by basis vectors u=(a,c) and v=(b,d),
    # the area of triangle formed by points at indices (i1,j1), (i2,j2), (i3,j3)
    # is proportional to |det([u*v]) * det of index differences|
    # The doubled area = |a*d - b*c| * |det of index triple|
    
    # So if we fix the basis, the area is a constant times the index-area.
    # We want to maximize the multiplicity of a single area value.
    # This is equivalent to maximizing the multiplicity of a single index-area value,
    # times the constant |a*d - b*c|.
    
    # Let's try various basis vectors and grid shapes.
    for n1, n2 in [(5, 6), (6, 5), (10, 3), (3, 10), (15, 2), (2, 15)]:
        for a in range(-5, 6):
            for c in range(-5, 6):
                for b in range(-5, 6):
                    for d in range(-5, 6):
                        if a == 0 and c == 0:
                            continue
                        if b == 0 and d == 0:
                            continue
                        # Check that basis vectors are not collinear
                        det_basis = a * d - b * c
                        if det_basis == 0:
                            continue
                        
                        # Generate points
                        pts = []
                        for i in range(n1):
                            for j in range(n2):
                                px = i * a + j * b
                                py = i * c + j * d
                                pts.append((px, py))
                        
                        # Check bounds and uniqueness
                        if len(set(pts)) != 30:
                            continue
                        if not all(-30 <= px <= 30 and -30 <= py <= 30 for px, py in pts):
                            continue
                        
                        try_points(pts)
                        if time.time() > deadline:
                            return best_points

    # Local search: try moving individual points to improve score
    import random
    random.seed(42)

    if best_points is None:
        best_points = [(x, 0) for x in range(15)] + [(x, 1) for x in range(15)]
        best_score = evaluate(best_points)

    # First pass: small perturbations (dx, dy in [-2, 2])
    improved = True
    while improved and time.time() < deadline:
        improved = False
        for idx in range(30):
            if time.time() > deadline:
                break
            old_x, old_y = best_points[idx]
            for dx in range(-2, 3):
                for dy in range(-2, 3):
                    if dx == 0 and dy == 0:
                        continue
                    new_x = old_x + dx
                    new_y = old_y + dy
                    if not (-30 <= new_x <= 30 and -30 <= new_y <= 30):
                        continue
                    new_points = list(best_points)
                    new_points[idx] = (new_x, new_y)
                    if len(set(new_points)) != 30:
                        continue
                    score = evaluate(new_points)
                    if score > best_score:
                        best_score = score
                        best_points = new_points
                        improved = True
                        break
                if improved:
                    break
            if improved:
                break

    # Second pass: random perturbations with larger moves
    for iteration in range(500):
        if time.time() > deadline:
            break
        new_points = list(best_points)
        idx = random.randint(0, 29)
        old_x, old_y = new_points[idx]
        new_x = old_x + random.randint(-5, 5)
        new_y = old_y + random.randint(-5, 5)
        if not (-30 <= new_x <= 30 and -30 <= new_y <= 30):
            continue
        new_points[idx] = (new_x, new_y)
        if len(set(new_points)) != 30:
            continue
        score = evaluate(new_points)
        if score > best_score:
            best_score = score
            best_points = new_points

    # Final pass: try swapping pairs of points
    for iteration in range(200):
        if time.time() > deadline:
            break
        new_points = list(best_points)
        i = random.randint(0, 29)
        j = random.randint(0, 29)
        if i == j:
            continue
        new_points[i], new_points[j] = new_points[j], new_points[i]
        if len(set(new_points)) != 30:
            continue
        score = evaluate(new_points)
        if score > best_score:
            best_score = score
            best_points = new_points

    return best_points
# EVOLVE-BLOCK-END
