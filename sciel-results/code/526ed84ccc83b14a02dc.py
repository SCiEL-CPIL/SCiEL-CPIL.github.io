import time
import numpy as np

def fit_exercise_policy(training_paths, contract):
    """
    Fit a Bermudan exercise policy by searching for a parametric smooth exercise boundary.
    
    Instead of approximating the value function via backward induction (which can suffer
    from discretization bias and interpolation errors), this strategy directly parameterizes
    the exercise boundary as a smooth function of log-spot price. The optimal boundary is
    found by grid-searching over a set of candidate boundary parameters, evaluating the
    resulting policy's value via forward Monte Carlo simulation on the training paths.
    
    This decouples the policy representation from the value function discretization,
    allowing the boundary to adapt continuously across the state space.
    """
    start_time = time.time()
    deadline = start_time + 115.0  # Safety margin for 120s limit

    # Extract parameters from contract
    K = contract.get('strike', contract.get('K', 100.0))
    r = contract.get('rate', contract.get('r', 0.05))
    sigma = contract.get('sigma', 0.2)
    T = contract.get('T', 1.0)
    n_dates = contract.get('n_dates', 12)
    
    # Training paths shape: (n_paths, n_cols)
    n_paths, n_cols = training_paths.shape
    
    # Determine exercise data columns
    # Task: "12 monthly exercise dates (no time-0 exercise)"
    # If n_cols > n_dates, assume first col is t0 (S0) and rest are exercise dates.
    # If n_cols == n_dates, assume all cols are exercise dates.
    if n_cols > n_dates:
        exercise_data = training_paths[:, 1:n_dates+1]
    else:
        exercise_data = training_paths[:, :n_dates]
        
    n_paths_eff, n_steps_eff = exercise_data.shape
    if n_steps_eff != n_dates:
        n_dates = n_steps_eff

    dt = T / n_dates
    discount = np.exp(-r * dt)
    
    # Pre-compute log-spots for efficiency
    log_S = np.log(exercise_data)
    
    # Parametric boundary: B_t = exp(a_t + b_t * (log_S - log_K))
    # We search for a_t and b_t for each time step t.
    # To ensure stability and smoothness, we can constrain b_t to a range or share some params.
    # Let's allow independent a_t and b_t for each t, but search on a coarse grid.
    
    # Grid for a_t (intercept in log-space)
    # The boundary should be around K. 
    # a_t roughly determines the level.
    # Let's search a_t in [log(0.5*K), log(1.5*K)] -> [-0.69, 0.40] + log(K)
    # Actually, let's work in normalized log-space: x = log(S/K)
    # Boundary: S_t = K * exp(a_t + b_t * x_t)
    # If b_t = 0, boundary is constant K*exp(a_t).
    # If b_t > 0, boundary increases with S (which is wrong for puts, put boundary usually decreases or is constant? 
    # Wait, for a put, you exercise when S is LOW. So boundary is a max S you'd exercise.
    # If S < Boundary, exercise.
    # Usually, the exercise boundary for a Bermudan put is a decreasing function of time (as maturity approaches, 
    # it's more likely to exercise, so the boundary might shift? No, for American puts, the boundary is 
    # below K and increases as T decreases? Actually, for American puts, the exercise region is S < B(t). 
    # B(t) is typically less than K. As t -> T, B(T) = K. As t -> 0, B(0) < K.
    # So B(t) increases towards K.
    # Let's model B_t(S_t) = K * exp(a_t + b_t * (S_t/K - 1))? No, log-space is better.
    # Let's use B_t = K * exp(a_t + b_t * log(S_t/K)).
    # If b_t is negative, higher S -> lower boundary? No, that's circular.
    # The boundary is a value S*. We compare S_t to S*_t.
    # Let's define the boundary in log-space: log(S*_t) = c_t + d_t * (something)?
    # Actually, the exercise decision is binary. We just need a threshold S*_t for each time step t.
    # Since the boundary is 1D (just a number for each time step, because the state is 1D spot),
    # we don't need a curve in S, just a scalar threshold for each time step t!
    # Wait, the "parametric smooth curve" idea from the prompt implies the boundary might vary with other states?
    # But here the state is just Spot. So the boundary is a scalar B_t for each time t.
    # The "smooth curve" refers to B_t being a smooth function of time t?
    # Or maybe the prompt implies a more complex state? No, "current_state" is spot.
    # So we are searching for a sequence of thresholds B_0, ..., B_{n-1}.
    # To make it "parametric smooth", we can model B_t = K * exp(a + b*t + c*t^2) or similar.
    # Or simply search for B_t independently? Independent search is 12-dimensional.
    # Grid search over 12 dimensions is impossible.
    # We need a low-dimensional parameterization.
    # Let's assume B_t = K * exp(a_t).
    # And a_t is generated by a polynomial in t: a_t = c0 + c1*t + c2*t^2.
    # We search for c0, c1, c2.
    
    # Grid for c0 (level): [-0.5, 0.1] (relative to log K)
    # Grid for c1 (slope): [-0.5, 0.5]
    # Grid for c2 (curvature): [-0.2, 0.2]
    
    c0_grid = np.linspace(-0.5, 0.1, 10)
    c1_grid = np.linspace(-0.5, 0.5, 10)
    c2_grid = np.linspace(-0.2, 0.2, 10)
    
    best_score = -np.inf
    best_params = None
    
    # Pre-compute intrinsic payoffs for all paths and times
    # payoff[t] = max(K - S_t, 0) * discount^(n_dates-1-t)
    # Note: Discounting is done from time t to 0.
    # Value = E[ sum_{t=0}^{n-1} 1_{Exercise} * Payoff_t * exp(-r*(T-t)) ]
    # Payoff_t = max(K - S_t, 0)
    # Discount_t = exp(-r * (T - t*dt))
    
    discounts = np.exp(-r * (T - dt * np.arange(n_dates)))
    payoffs = np.maximum(K - exercise_data, 0.0) * discounts[np.newaxis, :]
    
    # We will evaluate the policy value for each candidate parameter set.
    # To speed up, we can pre-compute the log-spots and use vectorized operations.
    
    t_indices = np.arange(n_dates)
    
    for c0 in c0_grid:
        for c1 in c1_grid:
            for c2 in c2_grid:
                if time.time() > deadline:
                    break
                
                # Generate boundaries B_t
                # a_t = c0 + c1 * t + c2 * t^2
                a_t = c0 + c1 * t_indices + c2 * t_indices**2
                B_t = K * np.exp(a_t)
                
                # Determine exercise decisions: S_t < B_t
                # exercise_data is (n_paths, n_dates)
                # B_t is (n_dates,)
                exercise_mask = exercise_data < B_t[np.newaxis, :]
                
                # Calculate value: sum of payoffs where exercised
                # value = mean( sum_t (payoffs_t * exercise_mask_t) )
                # payoffs already includes discounting.
                path_values = np.sum(payoffs * exercise_mask, axis=1)
                mean_value = np.mean(path_values)
                
                if mean_value > best_score:
                    best_score = mean_value
                    best_params = (c0, c1, c2)
                    
            if time.time() > deadline:
                break
        if time.time() > deadline:
            break

    # If no params found (e.g., timeout before first iter), use a default
    if best_params is None:
        best_params = (0.0, 0.0, 0.0)
        
    c0, c1, c2 = best_params
    t_indices = np.arange(n_dates)
    a_t = c0 + c1 * t_indices + c2 * t_indices**2
    final_boundaries = K * np.exp(a_t)
    
    class ExercisePolicy:
        def __init__(self, boundaries, K):
            self.boundaries = boundaries
            self.K = K
            
        def exercise(self, current_state, time):
            """
            current_state: array of spot prices
            time: index of the exercise date (0 to n_dates-1)
            Returns: boolean vector
            """
            if time >= len(self.boundaries):
                # Fallback: exercise if in the money
                return (self.K - current_state) > 0
                
            boundary = self.boundaries[time]
            return current_state < boundary
            
    return ExercisePolicy(final_boundaries, K)

