    # V[j*p+k, r]
    # W[k*n+i, r]
    
    # Part 1: 2x4x5 (Rows 0,1 of A)
    # A_L: i in {0,1}, j in {0,1}
    # A_R: i in {0,1}, j in {2,3}
    # B_L: j in {0,1}, k in {0..4}
    # B_R: j in {2,3}, k in {0..4}
    
    # Sub-part 1.1: A_L B_L
    # A_L is 2x2. B_L is 2x5.
    # Split B_L into B_L0 (2x2, k=0,1), B_L1 (2x2, k=2,3), B_L2 (2x1, k=4)
    
