import sys

def construct(n_rows, k):
    # Total number of differences needed
    total_diffs = n_rows * k * (k + 1) // 2
    
    # Lower bound for max value
    lower_bound = total_diffs
    
    # Search for the smallest M that allows a valid construction
    # We expand the range slightly to be safe, but the optimal is close to lower_bound
    # For (7,5), lower_bound is 105, optimal is 112.
    
    # We will try M from lower_bound to lower_bound + 50
    for M in range(lower_bound, lower_bound + 50):
        sol = solve_for_m(n_rows, k, M)
        if sol is not None:
            return sol
            
    # Fallback if not found in the expected range (should not happen for this task)
    # Try a larger range
    for M in range(lower_bound + 50, lower_bound + 200):
        sol = solve_for_m(n_rows, k, M)
        if sol is not None:
            return sol
            
    # Last resort: Greedy (may be invalid, but prevents crash)
    return greedy_fallback(n_rows, k)

def solve_for_m(n_rows, k, M):
    rows = []
    
    def backtrack_rows(row_idx, used_diffs):
        if row_idx == n_rows:
            return True
        
        row = [0]
        
        def backtrack_row(pos, row, used_diffs):
            if pos == k + 1:
                return True
            
            last_val = row[-1]
            
            # Heuristic: Try larger values first to space out differences
            # This reduces conflicts with small differences generated by early elements
            for x in range(M, last_val, -1):
                # Optimization: Check if x can be added
                # Differences are x - a for a in row
                # We need to ensure none of these are in used_diffs
                # And they must be distinct among themselves (which they are, since a are distinct)
                
                # Quick check: 
                # If (x - last_val) is in used_diffs, skip? No, x - last_val is just one diff.
                # We need to check all.
                
                valid = True
                new_used = used_diffs
                for a in row:
                    diff = x - a
                    # If diff is 0, it's not a positive difference, but x > a so diff > 0
                    if (new_used >> diff) & 1:
                        valid = False
                        break
                    new_used |= (1 << diff)
                
                if not valid:
                    continue
                
                row.append(x)
                
                if backtrack_row(pos + 1, row, new_used):
                    return True
                
                row.pop()
            
            return False
        
        if backtrack_row(1, row, used_diffs):
            rows.append(row)
            
            # Calculate the final used_diffs to pass to the next row
            # We re-calculate from the row to ensure correctness, as 'used_diffs' 
            # in the closure is the state BEFORE this row was added.
            # Actually, the 'used_diffs' passed to the successful return of backtrack_row
            # is the one with the row's diffs added.
            # But 'used_diffs' in the scope of backtrack_rows is the one from the caller.
            # We need to update it.
            
            # The variable 'used_diffs' inside backtrack_row is local.
            # We need to capture the final used_diffs.
            # Let's modify backtrack_row to return the used_diffs or use a nonlocal variable.
            
            # Simpler: Recalculate
            final_used = used_diffs
            for i in range(len(row)):
                for j in range(i):
                    final_used |= (1 << (row[i] - row[j]))
            
            if backtrack_rows(row_idx + 1, final_used):
                return True
            
            rows.pop()
        
        return False
    
    if backtrack_rows(0, 0):
        return rows
    return None

def greedy_fallback(n_rows, k):
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new = {x - a for a in row}
            if not new & used:
                row.append(x)
                used |= new
        rows.append(row)
    return rows
