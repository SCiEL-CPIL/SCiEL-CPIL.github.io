import sys

def construct():
    """
    Constructs a 4-coloring of K_n without monochromatic triangles.
    Attempts to use GF(49) algebraic structure for n=49.
    Falls back to seed n=32 if validation fails.
    """
    
    def gf49_mul(a, b):
        # GF(49) = GF(7)[x] / (x^2 + x + 3)
        # Element is (a0 + a1 * x)
        # a, b are integers 0..48 representing index in a table?
        # Let's use pair representation for clarity in logic, then map to int.
        # But for speed in verification, we need fast addition/subtraction.
        # Addition is component-wise mod 7.
        # We will map (a0, a1) to a0 + 7*a1.
        
        a0 = a % 7
        a1 = a // 7
        b0 = b % 7
        b1 = b // 7
        
        # (a0 + a1 x) * (b0 + b1 x)
        # = a0b0 + (a0b1 + a1b0)x + a1b1 x^2
        # x^2 = -x - 3
        # = a0b0 - 3a1b1 + (a0b1 + a1b0 - a1b1)x
        # mod 7
        
        c0 = (a0 * b0 - 3 * a1 * b1) % 7
        c1 = (a0 * b1 + a1 * b0 - a1 * b1) % 7
        
        return c0 + 7 * c1

    def gf49_add(a, b):
        a0 = a % 7
        a1 = a // 7
        b0 = b % 7
        b1 = b // 7
        c0 = (a0 + b0) % 7
        c1 = (a1 + b1) % 7
        return c0 + 7 * c1

    def gf49_sub(a, b):
        a0 = a % 7
        a1 = a // 7
        b0 = b % 7
        b1 = b // 7
        c0 = (a0 - b0) % 7
        c1 = (a1 - b1) % 7
        return c0 + 7 * c1

    # Find primitive element
    # We need an element of order 48.
    # Candidates: 1..48
    # g^48 = 1
    # g^24 != 1, g^16 != 1, g^12 != 1, etc.
    
    def pow_gf49(base, exp):
        res = 1 # multiplicative identity is 1 + 0x = 1
        b = base
        e = exp
        while e > 0:
            if e % 2 == 1:
                res = gf49_mul(res, b)
            b = gf49_mul(b, b)
            e //= 2
        return res

    primitive = None
    for g in range(2, 49):
        # Check order 48
        if pow_gf49(g, 48) == 1:
            # Check smaller factors of 48: 2,3,4,6,8,12,16,24
            if pow_gf49(g, 24) != 1 and pow_gf49(g, 16) != 1 and pow_gf49(g, 12) != 1:
                primitive = g
                break
    
    if primitive is None:
        # Fallback to seed
        return _seed_construct()

    g = primitive
    
    # Generate powers of g
    powers = [1]
    for i in range(1, 48):
        powers.append(gf49_mul(powers[-1], g))
        
    # Map value to log
    log_map = {}
    for i, p in enumerate(powers):
        log_map[p] = i
        
    # H is subgroup of order 12 generated by g^4
    # Cosets: S_k = { g^(4j+k) }
    # We need to assign colors based on the difference d = u - v.
    # d != 0.
    # log_d = log_map[d]
    # color = log_d % 4
    
    n = 49
    vertices = list(range(49))
    
    colors = []
    valid = True
    
    # Precompute color for each difference
    diff_color = {}
    for d in range(1, 49):
        if d == 0: continue
        if d in log_map:
            log_d = log_map[d]
            diff_color[d] = log_d % 4
        else:
            valid = False
            break
            
    if not valid:
        return _seed_construct()

    # Construct colors list
    for i in range(n):
        for j in range(i + 1, n):
            d = gf49_sub(j, i)
            # d is in 1..48
            colors.append(diff_color[d])
            
    # Verify
    C = [[-1]*n for _ in range(n)]
    k = 0
    for i in range(n):
        for j in range(i+1, n):
            C[i][j] = colors[k]
            C[j][i] = colors[k]
            k += 1
            
    for i in range(n):
        for j in range(i+1, n):
            for k in range(j+1, n):
                if C[i][j] == C[j][k] == C[i][k]:
                    valid = False
                    break
            if not valid: break
        if not valid: break
        
    if valid:
        return {'n': n, 'colors': colors}
    else:
        return _seed_construct()

def _seed_construct():
    def mul(a, b):
        r = 0
        for i in range(4):
            if b >> i & 1:
                r ^= a << i
        for i in range(7, 3, -1):
            if r >> i & 1:
                r ^= 0b10011 << (i - 4)
        return r
    log, x = {}, 1
    for e in range(15):
        log[x] = e
        x = mul(x, 2)
    colors = []
    for i in range(32):
        for j in range(i + 1, 32):
            colors.append(log[(i % 16) ^ (j % 16)] % 3 if i // 16 == j // 16 else 3)
    return {'n': 32, 'colors': colors}
