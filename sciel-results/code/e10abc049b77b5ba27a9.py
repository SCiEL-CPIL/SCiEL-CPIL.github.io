    # To speed up, we can precompute suffixes and prefixes?
    # Or just loop.
    # 25M loops in Python is ~5-10s.
    
    # Optimization:
    # For each i, for each j:
    #   check k from n-1 down to 1.
    
    # We can vectorize the "check" part?
    # No, easy to just loop.
    
    # Let's try to build it.
    # If it's too slow, we fall back to on-the-fly for boundaries?
    # But on-the-fly for 12M boundary checks is also slow.
    # Matrix is the way.
    
    for i in range(N):
        pi = perm_strs[i]
        for j in range(N):
            pj = perm_strs[j]
            # Find max k
            # pi[n-k:] == pj[:k]
            # k can be 0 to n-1
            # We check from high to low.
            # Since n is small (7), this is fast.
            # pi_suffixes = [pi[n-k:] for k in range(n)]
            # pj_prefixes = [pj[:k] for k in range(n)]
            
            # Precompute for i?
            pass
            
    # This double loop might be too slow in pure Python if not optimized.
    # Let's use a different strategy for the matrix:
    # We only need the overlap for pairs that are "close" in the path?
    # No, 2-Opt checks arbitrary (i-1, j) and (i, j+1).
    
    # Alternative:
    # Don't build the full matrix.
    # Use a cache?
    # Or, compute overlap on the fly but optimize the string comparison.
    # `perm_strs[i][n-k:] == perm_strs[j][:k]`
    
    # Let's estimate time for NN again.
    # NN is O(N^2) overlap checks. 25M checks.
    # If we do NN, we spend 5-10s.
    # Then 2-Opt passes.
    
    # If we don't build the matrix, 2-Opt boundary checks are O(n) each.
    # 12M checks * 7 ops = 84M ops. ~5-10s per pass.
    # We can do 5-10 passes.
    
    # Let's skip the matrix and use on-the-fly with string slicing, but optimize the function.
    
    def get_overlap(i, j):
        pi = perm_strs[i]
        pj = perm_strs[j]
        # Check k from n-1 down to 1
        # We can use endswith/startswith?
        # pi.endswith(pj[:k])? No, pi's suffix must match pj's prefix.
        # So pi[n-k:] == pj[:k].
        for k in range(n - 1, 0, -1):
            if pi[n-k:] == pj[:k]:
                return k
        return 0

    # 4. Initial Path: Nearest Neighbor
    unvisited = set(range(N))
    unvisited.remove(0)
    path = [0]
    current = 0
    
    for _ in range(N - 1):
        best_next = -1
        best_overlap = -1
        for j in unvisited:
            ov = get_overlap(current, j)
            if ov > best_overlap:
                best_overlap = ov
                best_next = j
        path.append(best_next)
        unvisited.remove(best_next)
        current = best_next
        
    # 5. 2-Opt Improvement
    # Precompute edge costs for current path
    # cost_forward[i] = cost(path[i], path[i+1]) = n - overlap(path[i], path[i+1])
    # cost_backward[i] = cost(path[i+1], path[i]) = n - overlap(path[i+1], path[i])
    
    def calc_costs(path):
        cf = [0] * (N - 1)
        cb = [0] * (N - 1)
        for i in range(N - 1):
            ov_f = get_overlap(path[i], path[i+1])
            ov_b = get_overlap(path[i+1], path[i])
            cf[i] = n - ov_f
            cb[i] = n - ov_b
        return cf, cb

    cf, cb = calc_costs(path)
    
    # Prefix sums for O(1) internal cost calculation
    # sum_cf[i] = sum(cf[0..i])
    # sum_cb[i] = sum(cb[0..i])
    
    def make_prefix(arr):
        ps = [0] * len(arr)
        s = 0
        for i in range(len(arr)):
            s += arr[i]
            ps[i] = s
        return ps

    sum_cf = make_prefix(cf)
    sum_cb = make_prefix(cb)
    
    def get_internal_cost_forward(i, j):
        # Sum of cf[i..j-1]
        if i > j - 1: return 0
        if i == 0:
            return sum_cf[j-1]
        else:
            return sum_cf[j-1] - sum_cf[i-1]
            
    def get_internal_cost_backward(i, j):
        # Sum of cb[i..j-1]
        if i > j - 1: return 0
        if i == 0:
            return sum_cb[j-1]
        else:
            return sum_cb[j-1] - sum_cb[i-1]

    improved = True
    passes = 0
    max_passes = 20
    
    while improved and passes < max_passes:
        improved = False
        passes += 1
        if time.time() - start_time > timeout - 10:
            break
            
        # 2-Opt: reverse path[i..j]
        # We iterate i from 0 to N-2
        # And j from i+1 to N-1
        # This is O(N^2).
        
        # To speed up, we can limit j-i distance?
        # Usually long reversals are less likely to help initially, but can help later.
        # Let's do full search but break early if time is tight.
        
        for i in range(N - 1):
            if time.time() - start_time > timeout - 10:
                break
            for j in range(i + 1, N):
                # Check improvement
                # Old Cost:
                # Boundary 1: (i-1, i) if i>0 else 0
                # Boundary 2: (j, j+1) if j<N-1 else 0
                # Internal: sum_cf[i..j-1]
                
                # New Cost:
                # Boundary 1: (i-1, j) if i>0 else 0
                # Boundary 2: (i, j+1) if j<N-1 else 0
                # Internal: sum_cb[i..j-1] (because edges are reversed)
                
                old_cost = 0
                new_cost = 0
                
                if i > 0:
                    old_cost += n - get_overlap(path[i-1], path[i])
                    new_cost += n - get_overlap(path[i-1], path[j])
                else:
                    # No cost for start edge? 
                    # The total length is sum of (n - overlap).
                    # The first permutation contributes n.
                    # Subsequent contribute n - overlap.
                    # So cost of path is n + sum_{k=0}^{N-2} (n - overlap(path[k], path[k+1])).
                    # My cf/cb are exactly (n - overlap).
                    # So total length = n + sum(cf).
                    # If i=0, we are reversing from the start.
                    # The "entry" edge doesn't exist.
                    pass
                    
                if j < N - 1:
                    old_cost += n - get_overlap(path[j], path[j+1])
                    new_cost += n - get_overlap(path[i], path[j+1])
                    
                old_internal = get_internal_cost_forward(i, j)
                new_internal = get_internal_cost_backward(i, j)
                
                total_old = old_cost + old_internal
                total_new = new_cost + new_internal
                
                if total_new < total_old:
                    # Apply reversal
                    path[i:j+1] = reversed(path[i:j+1])
                    # Update cf, cb
                    # The edges inside i..j are reversed.
                    # cf[i..j-1] becomes cb[i..j-1] (reversed order?)
                    # Wait.
                    # Path segment: P_i, P_{i+1}, ..., P_j
                    # Edges: (P_i, P_{i+1}), ..., (P_{j-1}, P_j)
                    # Costs: cf[i], ..., cf[j-1]
                    # Reversed Path: P_j, P_{j-1}, ..., P_i
                    # Edges: (P_j, P_{j-1}), ..., (P_{i+1}, P_i)
                    # Costs: cb[j-1], ..., cb[i]
                    # So the new cf values for indices i..j-1 are the old cb values for j-1..i, reversed.
                    
                    # We need to update cf and cb arrays.
                    # cf_new[i..j-1] = [cb_old[j-1], cb_old[j-2], ..., cb_old[i]]
                    # cb_new[i..j-1] = [cf_old[j-1], cf_old[j-2], ..., cf_old[i]]
                    
                    # And update boundary edges if they exist.
                    # Edge (i-1, i) becomes (i-1, j).
                    # Edge (j, j+1) becomes (i, j+1).
                    
                    # Update cf
                    if i < j:
                        segment_cf = cf[i:j]
                        segment_cb = cb[i:j]
                        cf[i:j] = segment_cb[::-1]
                        cb[i:j] = segment_cf[::-1]
                        
                    if i > 0:
                        cf[i-1] = n - get_overlap(path[i-1], path[i]) # path[i] is now old path[j]
                        cb[i-1] = n - get_overlap(path[i], path[i-1])
                    if j < N - 1:
                        cf[j] = n - get_overlap(path[j], path[j+1]) # path[j] is now old path[i]
                        cb[j] = n - get_overlap(path[j+1], path[j])
                        
                    # Update prefix sums
                    sum_cf = make_prefix(cf)
                    sum_cb = make_prefix(cb)
                    
                    improved = True
                    # Restart j loop? Or continue?
                    # Continuing is fine, but the costs changed.
                    # For simplicity, break and restart pass?
                    # Or just continue, knowing that subsequent checks might be slightly off 
                    # if they depend on the changed region?
                    # Actually, if we change path, the indices for future j might be invalid 
                    # if we don't update the path correctly.
                    # But we updated path.
                    # However, the cost arrays are updated.
                    # The prefix sums are updated.
                    # So the next check (i, j+1) will use the new costs.
                    # This is valid.
                    
