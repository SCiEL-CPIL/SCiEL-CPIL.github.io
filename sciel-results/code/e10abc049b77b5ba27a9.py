    # Let's use the Classic Construction to get the initial path.
    # It is known to be better than random.
    # We simulate the classic construction to get the order of permutations.
    
    # Classic Construction Logic:
    # S_1 = [1]
    # S_k is formed by taking S_{k-1}, and for each permutation p in S_{k-1}:
    #   insert k at the end, then append p?
    # Actually, the standard "classic" superpermutation is:
    # 1
    # 121
    # 1213121
    # ...
    # The recursive step:
    # Let W_{k-1} be the superpermutation for k-1.
    # For each permutation of 1..k-1 appearing in W_{k-1} (in order of first appearance? or just the set?):
    #   The classic algorithm iterates through the permutations of 1..k-1 in the order they appear in the "core" of W_{k-1}.
    
    # Easier: Just use the list of all permutations in lexicographic order?
    # Lexicographic order has low overlaps (adjacent perms differ in last few digits).
    # Johnson-Trotter is better.
    
    # Let's implement a simple JT generator that returns indices.
    # Or, we can just start with the path generated by the Greedy Nearest Neighbor, which is fast.
    # The seed program did NN. Let's do NN to get a good start, then 2-Opt.
    
    # 3. Build Overlap Matrix
    # N=5040. N^2 = 25M.
    # We use numpy uint8 array.
