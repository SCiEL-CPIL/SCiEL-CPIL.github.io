import numpy as np
import itertools
import time

def construct():
    start_time = time.time()
    deadline = start_time + 130.0  # Safety margin
    
    D = 11
    result_vectors = []
    
    # Step 1: Generate the 252 minimal vectors of E8 x A3
    # E8 minimal vectors (norm^2 = 2)
    # E8 can be generated as vectors with coordinates:
    # (1/2, 1/2, ..., 1/2) with even number of minus signs? No, that's norm^2 = 8/4 = 2.
    # Actually, E8 minimal vectors are of two types:
    # 1. (1/2, 1/2, 1/2, 1/2, 1/2, 1/2, 1/2, 1/2) with an even number of minus signs. (128 vectors)
    # 2. (0, 0, 0, 1, 1, 0, 0, 0) permutations. (112 vectors)
    # Total 240.
    # However, these are not integers. The task requires INTEGER vectors.
    # The Leech lattice and E8 lattice often refer to scaled versions or specific integer embeddings.
    # The standard E8 lattice is NOT an integer lattice (it has 1/2 coordinates).
    # BUT, the problem asks for "nonzero integer vectors".
    # So we cannot use the standard E8 minimal vectors if they are non-integer.
    
    # Let's re-read the task carefully.
    # "Construct nonzero integer vectors in R^11"
    # "Kissing number in dimension 11"
    # "Normalizing each vector to norm 2 certifies a kissing configuration"
    
    # If the lattice E8 is not integer, we must use integer vectors.
    # The directive mentioned "E8 x A3 ... via explicit coordinate permutations and sign changes".
    # This implies an integer representation.
    # The lattice $2 \cdot E_8$ has integer coordinates?
    # $2 \cdot E_8$ minimal vectors:
    # Type 1: (1, 1, 1, 1, 1, 1, 1, 1) with even minuses. Norm^2 = 8.
    # Type 2: (0, 0, 0, 2, 2, 0, 0, 0). Norm^2 = 8.
    # These are integers.
    # But we want small norms to pack more.
    
    # Let's look at the integer vectors with small norm squared.
    # Norm^2 = 2:
    # Vectors with two 1s (or -1s) and rest 0.
    # Count: 440.
    # Are there 240 of these that form E8?
    # The subset of 240 vectors among the 440 that form E8 (scaled) is well known.
    # Specifically, the 240 vectors of the form $\pm e_i \pm e_j$ in $\mathbb{Z}^8$ such that... ?
    # Actually, the 240 minimal vectors of $E_8$ (as a root lattice) are the vectors with two $\pm 1$ and rest 0.
    # Wait, the root lattice $E_8$ is generated by simple roots which have norm^2 2.
    # The set of all roots in $E_8$ is exactly the 240 vectors with two non-zero entries $\pm 1$ and rest 0, satisfying a parity condition?
    # No, the 240 roots of $E_8$ are:
    # - 112 vectors with two $\pm 1$ and rest 0? No, there are $8 \times 7 \times 4 = 224$ such vectors in $\mathbb{Z}^8$.
    # - The other 16? No.
    # Let's check the count.
    # Number of vectors in $\mathbb{Z}^8$ with norm^2 2 is $8 \times 7 \times 4 = 224$.
    # Number of vectors in $\mathbb{Z}^8$ with norm^2 2 and half-integer coordinates? No, we need integers.
    # So we only have 224 integer vectors of norm^2 2 in 8D.
    # Plus 12 from A3 (3D) which are $\pm e_i \pm e_j$ in 3D?
    # In 3D, norm^2 2 vectors are $\pm e_i \pm e_j$. Count $3 \times 2 \times 4 = 24$.
    # But A3 has only 12 roots. They are a subset.
    
    # So, total integer vectors of norm^2 2 in 11D is 440.
    # The "E8 x A3" construction likely refers to selecting a specific subset of these 440 vectors that have good separation properties.
    
    # Let's generate all 440 norm^2 2 vectors and all 22 norm^2 4 vectors (one 2).
    # And try to select a large subset.
    
    candidates = []
    
    # Type 1: Norm^2 = 2 (two +-1)
    for i, j in itertools.combinations(range(D), 2):
        for si in (1, -1):
            for sj in (1, -1):
                v = np.zeros(D, dtype=np.int64)
                v[i] = si
                v[j] = sj
                candidates.append(v)
                
    # Type 2: Norm^2 = 4 (one +-2)
    for i in range(D):
        for s in (1, -1):
            v = np.zeros(D, dtype=np.int64)
            v[i] = s * 2
            candidates.append(v)
            
    # Type 3: Norm^2 = 4 (four +-1) - This is many, maybe add later if time permits
    # For now, focus on the 462 vectors above.
    
    candidates = np.array(candidates, dtype=np.int64)
    n = len(candidates)
    norms_sq = np.sum(candidates**2, axis=1)
    
    # Conflict matrix: dist_sq < 4 is conflict (since we want dist >= max_norm, and max_norm will likely be 2 if we include Type 2/3, or sqrt(2) if only Type 1).
    # If we only use Type 1 (norm sqrt(2)), we need dist >= sqrt(2). dist_sq >= 2.
    # If we include Type 2 (norm 2), we need dist >= 2. dist_sq >= 4.
    
    # Strategy:
    # 1. Build the set of all Type 1 vectors (440).
    # 2. Find the maximum independent set in the graph where edges connect vectors with dist_sq < 4.
    #    This ensures dist_sq >= 4 for all pairs.
    #    This set will have max norm sqrt(2) (if no Type 2) or 2 (if Type 2 included).
    #    Actually, if we only pick from Type 1, max norm is sqrt(2). Constraint dist >= sqrt(2) is dist_sq >= 2.
    #    The graph with dist_sq < 4 is stricter than dist_sq < 2.
    #    So an independent set in the dist_sq < 4 graph is a valid set for max_norm = 2.
    #    Is it valid for max_norm = sqrt(2)? Yes, because dist_sq >= 4 implies dist_sq >= 2.
    
    # So, finding a large independent set in the "dist_sq < 4" graph gives a valid set that works even if we were to add norm 2 vectors later (provided they are also dist >= 2 from everyone).
    
    # Let's compute the conflict matrix for dist_sq < 4.
    dots = candidates @ candidates.T
    dist_sq = norms_sq[:, None] + norms_sq[None, :] - 2 * dots
    conflict = (dist_sq < 4)
    np.fill_diagonal(conflict, False)
    
    # Greedy Independent Set with Restart
    # Use a bitset or simple list. n=462 is small.
    best_selected = []
    best_size = 0
    np.random.seed(42)
    
    # Precompute neighbor lists
    neighbors = [np.where(conflict[i])[0] for i in range(n)]
    
    # We will try to find a large independent set.
    # Since n is small, we can use a greedy approach with randomization.
    
    # Heuristic: Prioritize nodes with lower degree.
    
    for attempt in range(50):
        if time.time() > deadline:
            break
            
        remaining = np.ones(n, dtype=bool)
        selected = []
        degrees = np.array([len(neighbors[i]) for i in range(n)], dtype=np.int32)
        
        while remaining.any():
            if time.time() > deadline:
                break
            rem_indices = np.where(remaining)[0]
            if len(rem_indices) == 0: break
            
            rem_degrees = degrees[rem_indices]
            min_deg = np.min(rem_degrees)
            min_indices = rem_indices[rem_degrees == min_deg]
            
            # Random tie-breaking
            chosen = np.random.choice(min_indices)
            selected.append(chosen)
            
            # Remove chosen and its neighbors
            to_remove = np.unique(np.concatenate(([chosen], neighbors[chosen])))
            remaining[to_remove] = False
            # Update degrees
            for idx in to_remove:
                if remaining[idx]: continue
                # We don't actually need to update degrees for removed nodes
                # But for remaining nodes connected to removed nodes, their degree in the *remaining* graph decreases.
                # However, simple greedy usually just picks min degree from current remaining set.
                # Recalculating degrees is O(n^2). n=462 is fine.
            
            # Recalculate degrees for remaining?
            # For small n, we can just recalculate.
            if remaining.sum() < n:
                rem_indices = np.where(remaining)[0]
                new_degrees = np.zeros(len(rem_indices), dtype=np.int32)
                for k, idx in enumerate(rem_indices):
                    # Count neighbors in remaining
                    new_degrees[k] = np.sum(remaining[neighbors[idx]])
                degrees[rem_indices] = new_degrees
                
        if len(selected) > best_size:
            best_size = len(selected)
            best_selected = list(selected)
            
    # Result is the subset of candidates
    if not best_selected:
        # Fallback: take first 100
        best_selected = list(range(min(100, n)))
        
    result = candidates[best_selected]
    return result
