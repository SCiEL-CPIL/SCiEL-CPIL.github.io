import numpy as np
from scipy.optimize import differential_evolution, minimize
from math import log, inf

def construct():
    import time
    start_time = time.time()
    deadline = start_time + 140.0 # Safety margin

    def get_points(params):
        """
        params: [r1, r2, theta1, theta2, h]
        Returns 8 points as an 8x2 numpy array.
        """
        r1, r2, t1, t2, h = params
        
        # Square 1 centered at (0,0)
        p1 = []
        for k in range(4):
            angle = t1 + k * np.pi / 2
            p1.append([r1 * np.cos(angle), r1 * np.sin(angle)])
        
        # Square 2 centered at (0, h)
        p2 = []
        for k in range(4):
            angle = t2 + k * np.pi / 2
            p2.append([r2 * np.cos(angle), r2 * np.sin(angle) + h])
        
        return np.array(p1 + p2)

    def log_score_from_points(points):
        """
        Calculate log of the normalized product of distances.
        Score = (prod(distances) * (2/D)^n_pairs) / n^n ? 
        Task says: Score = Delta / n^n, where Delta is product of distances after scaling to diameter 2.
        Let d_ij be distances in scaled set. Diameter is 2.
        Delta = prod(d_ij).
        Score = Delta / 8^8.
        
        If we have unscaled points P, with diameter D.
        Scaled points P' = P * (2/D).
        Distances d'_ij = d_ij * (2/D).
        Delta = prod(d'_ij) = (prod(d_ij)) * (2/D)^(28).
        Score = (prod(d_ij) * (2/D)^28) / 8^8.
        
        We maximize log(Score) = sum(log(d_ij)) + 28*log(2) - 28*log(D) - 8*log(8).
        Constants: 28*log(2) - 8*log(8) = 28*log(2) - 24*log(2) = 4*log(2).
        So maximize: sum(log(d_ij)) - 28*log(D) + 4*log(2).
        Since 4*log(2) is constant, we maximize: sum(log(d_ij)) - 28*log(D).
        """
        n = len(points)
        # Calculate all pairwise distances
        dists = []
        min_dist = inf
        max_dist = 0
        for i in range(n):
            for j in range(i+1, n):
                d = np.linalg.norm(points[i] - points[j])
                if d < 1e-10:
                    return -inf
                dists.append(d)
                if d < min_dist:
                    min_dist = d
                if d > max_dist:
                    max_dist = d
        
        if max_dist == 0:
            return -inf
            
        D = max_dist
        sum_log_d = sum(log(d) for d in dists)
        
        return sum_log_d - 28 * log(D)

    def objective(params):
        points = get_points(params)
        val = log_score_from_points(points)
        return -val # Minimize negative log score

    # Define bounds for DE
    # r1, r2 should be positive. Let's try [0.1, 5.0]
    # theta1, theta2 in [0, pi/2] due to symmetry of square
    # h in [-2.0, 2.0]
    bounds = [
        (0.1, 5.0),  # r1
        (0.1, 5.0),  # r2
        (0.0, np.pi/2), # t1
        (0.0, np.pi/2), # t2
        (-2.0, 2.0)   # h
    ]
    
    best_params = None
    best_score = -inf
    
    # Run Differential Evolution
    try:
        result = differential_evolution(
            objective, 
            bounds, 
            seed=42, 
            maxiter=50, 
            popsize=15,
            tol=1e-6,
            polish=False # We will polish later
        )
        if time.time() > deadline - 20:
             # If we are running out of time, just use the DE result directly
             best_params = result.x
        else:
             best_params = result.x
    except Exception:
        best_params = np.array([1.0, 1.0, 0.0, np.pi/4, 0.0]) # Fallback to regular octagon approx

    # Refine with local optimization on full 16 coordinates
    # Start from the points generated by best_params
    initial_points = get_points(best_params)
    
    def objective_full(points_flat):
        points = points_flat.reshape(8, 2)
        val = log_score_from_points(points)
        return -val

    try:
        # Use Nelder-Mead or Powell for robustness without gradients
        result_local = minimize(
            objective_full, 
            initial_points.flatten(), 
            method='Nelder-Mead',
            options={'xatol': 1e-8, 'fatol': 1e-8, 'maxiter': 1000}
        )
        
        if time.time() < deadline - 5:
            # If we have time, maybe try another local method or just accept
            best_points = result_local.x.reshape(8, 2)
        else:
            best_points = initial_points
            
    except Exception:
        best_points = initial_points

    # Final check and return
    # Ensure distinct points
    # The problem states points must be distinct.
    # If any points are too close, we might have a degenerate solution.
    # The log function returns -inf for d < 1e-10, so the optimizer should avoid this.
    
    # Scale and return? No, the evaluator scales. We just return the points.
    # The evaluator calculates the score.
    
    return best_points.tolist()
