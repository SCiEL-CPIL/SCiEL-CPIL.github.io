    # Generate candidates from radius-2 hexagon
    # Points in radius 2 hexagon: q+r+s=0, |q|<=2, |r|<=2, |s|<=2
    radius2_points = []
    for q in range(-2, 3):
        for r in range(-2, 3):
            s = -q - r
            if abs(s) <= 2:
                radius2_points.append((q, r))
    
    # radius2_points has 19 elements
    # We want subsets of size 11
    # To speed up, we can restrict to subsets that are "connected"
    
    def is_connected(axial_set):
        if not axial_set: return True
        start = next(iter(axial_set))
        visited = {start}
        queue = [start]
        neighbors = [(1, 0), (-1, 0), (0, 1), (0, -1), (1, -1), (-1, 1)]
        while queue:
            q, r = queue.pop()
            for dq, dr in neighbors:
                nq, nr = q + dq, r + dr
                if (nq, nr) in axial_set and (nq, nr) not in visited:
                    visited.add((nq, nr))
                    queue.append((nq, nr))
        return len(visited) == len(axial_set)

    generated_candidates = []
    # Use a heuristic to filter: calculate bounding box area or max distance
    # But first, let's just generate all connected ones and score them roughly
    
    # To avoid generating 75k combinations and checking connectivity (which is fast but adds up),
    # we can be smarter. But 75k is small.
    
    seen_shapes = set()
    for combo in itertools.combinations(radius2_points, 11):
        combo_set = set(combo)
        if is_connected(combo_set):
            # Canonicalize the shape to avoid duplicates (rotation/reflection)
            # This is complex. Instead, we can just use the tuple of sorted coords as key
            # But rotated versions are distinct in axial coords unless we transform them.
            # Since we optimize over rotation beta, distinct axial shapes that are rotations
            # of each other will yield the same optimal S (just with different beta).
            # So we can skip canonicalization if we are willing to test duplicates.
            # However, testing duplicates wastes time.
            # Simple canonicalization: shift so min q is 0, min r is 0?
            min_q = min(q for q, r in combo_set)
            min_r = min(r for q, r in combo_set)
            shifted = tuple(sorted((q - min_q, r - min_r) for q, r in combo_set))
            
            if shifted not in seen_shapes:
                seen_shapes.add(shifted)
                # Store the original unshifted coords? No, we can store shifted,
                # as the optimization will find the center.
                generated_candidates.append(list(shifted))
                
    # Combine hardcoded and generated
    all_candidates = []
    for c in hardcoded_candidates:
        min_q = min(q for q, r in c)
