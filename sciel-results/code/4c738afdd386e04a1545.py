import time
import random
import sys

def construct():
    start_time = time.time()
    deadline = start_time + 110  # Safety margin: 110s out of 120s allowed, 30s buffer for overhead/kill
    
    prescribed = [1, 2, 5, 11]
    prescribed_set = frozenset(prescribed)
    max_val = 284
    n = max_val
    
    # Pre-compute initial sums for prescribed set
    # Sums: 1+1=2, 1+2=3, 1+5=6, 1+11=12, 2+2=4, 2+5=7, 2+11=13, 5+5=10, 5+11=16, 11+11=22
    initial_sums = {2, 3, 6, 12, 4, 7, 13, 10, 16, 22}
    
    best_set = list(prescribed)
    best_size = len(best_set)
    best_sums = set(initial_sums)
    
    def build_sums(s):
        """Build the set of all pairwise sums a+b for a<=b in s."""
        sl = sorted(s)
        sums = set()
        for i in range(len(sl)):
            for j in range(i, len(sl)):
                sums.add(sl[i] + sl[j])
        return sums

    def can_add(x, current_set, current_sums):
        """Check if x can be added to current_set maintaining Sidon property."""
        # New sums generated by x
        new_sums = {x + y for y in current_set}
        new_sums.add(2 * x)
        
        # Check for conflicts with existing sums
        if new_sums & current_sums:
            return False
        
        # Check for internal conflicts in new_sums
        # Since x is new and distinct from all y in current_set, 
        # x+y1 == x+y2 implies y1==y2.
        # x+y == 2x implies y==x, which is false since x not in current_set.
        # So internal conflicts are impossible if current_set is valid.
        return True

    def get_new_sums(x, current_set):
        return {x + y for y in current_set} | {2 * x}

    # --- Phase 1: Greedy Initialization with Randomization ---
    # We want to find a good starting point for local search.
    # Try several randomized greedy passes.
    
    def greedy_randomized(rng, time_limit=2.0):
        nonlocal best_set, best_size, best_sums
        current_set = set(prescribed)
        current_sums = set(initial_sums)
        start = time.time()
        
        candidates = [x for x in range(1, max_val + 1) if x not in current_set]
        rng.shuffle(candidates)
        
        for x in candidates:
            if time.time() - start > time_limit:
                break
            if can_add(x, current_set, current_sums):
                new_sums = get_new_sums(x, current_set)
                current_set.add(x)
                current_sums.update(new_sums)
        
        if len(current_set) > best_size:
            best_set = list(current_set)
            best_size = len(current_set)
            best_sums = set(current_sums)
        
        return current_set, current_sums

    rng = random.Random(42)
    # Run 50 quick randomized greedy passes
    for _ in range(50):
        if time.time() > deadline - 20:
            break
        greedy_randomized(rng, time_limit=0.5)

    # Also try a deterministic "smallest first" and "largest first" greedy
    if time.time() < deadline - 20:
        current_set = set(prescribed)
        current_sums = set(initial_sums)
        for x in range(1, max_val + 1):
            if x in current_set: continue
            if can_add(x, current_set, current_sums):
                current_set.add(x)
                current_sums.update(get_new_sums(x, current_set))
        if len(current_set) > best_size:
            best_set = list(current_set)
            best_size = len(current_set)
            best_sums = set(current_sums)

    # --- Phase 2: Fast Local Search ---
    # We start from the best set found so far.
    # Key optimization: Incremental sum update for swaps.
    
    def fast_local_search(start_set, start_sums, time_limit=60.0):
        nonlocal best_set, best_size, best_sums
        
        current_set = set(start_set)
        current_sums = set(start_sums)
        start = time.time()
        
        all_candidates = list(range(1, max_val + 1))
        removable_pool = [x for x in current_set if x not in prescribed_set]
        
        no_improve_count = 0
        max_no_improve = 500 # Restart if stuck
        
        while time.time() - start < time_limit and time.time() < deadline - 5:
            
            # 1. Try to add a random element (Expansion)
            # Pick a few random candidates
            added = False
            for _ in range(10):
                x = rng.choice(all_candidates)
                if x in current_set:
                    continue
                if can_add(x, current_set, current_sums):
                    # Valid addition
                    new_sums = get_new_sums(x, current_set)
                    current_set.add(x)
                    current_sums.update(new_sums)
                    added = True
                    no_improve_count = 0
                    if len(current_set) > best_size:
                        best_set = list(current_set)
                        best_size = len(current_set)
                        best_sums = set(current_sums)
                        # Update removable pool
                        removable_pool = [x for x in current_set if x not in prescribed_set]
                    break
            if added:
                continue

            # 2. Try a swap (Move)
            # Remove r, Add a
            if not removable_pool:
                # If we can't remove anything (only prescribed left), we are stuck at prescribed size
                # But we should have more. If we are here, we might have removed all non-prescribed?
                # Actually, if we only have prescribed, we can't swap.
                # Let's break if we can't improve.
                break

            r = rng.choice(removable_pool)
            
            # Compute sums of S \ {r} efficiently
            # Sums to remove: {r + y for y in current_set} U {2r}
            # Note: r+r = 2r. r+y for y!=r.
            sums_to_remove = {r + y for y in current_set}
            sums_to_remove.add(2 * r)
            
            # Since it's a Sidon set, these sums are unique and distinct from sums of other pairs
            # except for the ones involving r.
            # So Sums(S \ {r}) = Sums(S) - sums_to_remove
            
            reduced_sums = current_sums - sums_to_remove
            reduced_set = current_set - {r}
            
            # Try to find a valid addition a to reduced_set
            swapped = False
            for _ in range(20):
                a = rng.choice(all_candidates)
                if a in current_set:
                    continue
                
                # Check if a can be added to reduced_set
                new_sums_for_a = {a + y for y in reduced_set}
                new_sums_for_a.add(2 * a)
                
                if not (new_sums_for_a & reduced_sums):
                    # Valid swap!
                    # Update current state
                    current_set = reduced_set | {a}
                    current_sums = reduced_sums | new_sums_for_a
                    
                    # Update removable pool
                    # Remove r from pool, add a if a is not prescribed
                    # Note: r is removed. a is added.
                    # We need to update the list.
                    # Efficient way: just rebuild if size changes or periodically?
                    # Rebuilding is O(N). N is small (~20).
                    removable_pool = [x for x in current_set if x not in prescribed_set]
                    
                    swapped = True
                    no_improve_count = 0
                    
                    if len(current_set) > best_size:
                        best_set = list(current_set)
                        best_size = len(current_set)
                        best_sums = set(current_sums)
                    break
            
            if not swapped:
                no_improve_count += 1
                if no_improve_count > max_no_improve:
                    # Perturb: random restart from best found? Or just continue?
                    # Let's try to "kick" the search by doing a random 2-swap or just resetting
                    # to best and trying a different random seed for the next iteration?
                    # For now, just reset no_improve_count to prevent infinite loop,
                    # but the random choices should eventually find a move.
                    no_improve_count = 0

        return current_set, current_sums

    # Run local search from the best greedy result
    if best_size > len(prescribed):
        # Run for a significant chunk of time
        time_left = deadline - 5 - time.time()
        if time_left > 10:
            fast_local_search(best_set, best_sums, time_limit=time_left)

    # --- Phase 3: Final Polish / Additional Restarts ---
    # If we have time left, run a few more local searches from slightly perturbed best sets
    if time.time() < deadline - 10:
        # Try to improve by removing a random element from best_set and re-running local search
        # This helps escape local optima where the "best" set is stuck.
        
        for restart in range(5):
            if time.time() > deadline - 10:
                break
            
            # Create a perturbed start
            start_set = set(best_set)
            start_sums = set(best_sums)
            
            # Remove 1-2 random non-prescribed elements
            removable = [x for x in start_set if x not in prescribed_set]
            if removable:
                for _ in range(2):
                    if not removable: break
                    r = rng.choice(removable)
                    start_set.remove(r)
                    # Rebuild sums for correctness after manual removal
                    start_sums = build_sums(start_set)
                    removable = [x for x in start_set if x not in prescribed_set]
            
            # Run a short local search from this perturbed state
            time_left = deadline - 10 - time.time()
            if time_left > 2:
                fast_local_search(start_set, start_sums, time_limit=min(time_left, 10.0))

    # Final verification
    final_set = set(best_set)
    sums = build_sums(final_set)
    expected = len(final_set) * (len(final_set) + 1) // 2
    if len(sums) != expected:
        # Fallback to prescribed if something went wrong
        best_set = list(prescribed)
    else:
        # Ensure prescribed are in
        if not prescribed_set.issubset(final_set):
            best_set = list(prescribed)
        else:
            best_set = sorted(list(final_set))

    return best_set

if __name__ == "__main__":
    start = time.time()
    res = construct()
    end = time.time()
    print(f"Size: {len(res)}, Time: {end-start:.2f}s")
    # Verify
    sums = set()
    valid = True
    r = sorted(res)
    for i in range(len(r)):
        for j in range(i, len(r)):
            s = r[i] + r[j]
            if s in sums:
                valid = False
            sums.add(s)
    if not all(x in res for x in [1, 2, 5, 11]):
        valid = False
    if not all(1 <= x <= 284 for x in res):
        valid = False
    if len(set(res)) != len(res):
        valid = False
    print(f"Valid: {valid}")
