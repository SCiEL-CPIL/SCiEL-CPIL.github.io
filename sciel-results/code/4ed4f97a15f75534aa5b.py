"""Construct the [18,9,6] extended quadratic-residue code (512 codewords)."""
import time

def _poly_mult(a, b):
    """Multiply two polynomials over GF(2), represented as integers."""
    result = 0
    while b:
        if b & 1:
            result ^= a
        a <<= 1
        b >>= 1
    return result

def _poly_divmod(a, b):
    """Divide polynomial a by b over GF(2). Returns (quotient, remainder)."""
    # Normalize: b must have highest bit set
    deg_b = b.bit_length() - 1
    q = 0
    r = a
    while r != 0 and r.bit_length() - 1 >= deg_b:
        shift = r.bit_length() - 1 - deg_b
        q |= 1 << shift
        r ^= b << shift
    return q, r

def _build_generator_matrix():
    """Build the 9x18 generator matrix for the [18,9,6] extended QR code."""
    # The QR code of length 17: generator polynomial g(x) of degree 8
    # such that g(x) divides x^17 + 1 in GF(2)[x].
    # The two QR codes of length 17 have generator polynomials that are
    # factors of x^17+1. Since 17 is prime, x^17+1 = (x+1)(x^16+x^15+...+x+1)
    # in GF(2)[x]. The cyclotomic cosets of 2 mod 17 partition {0,...,16}.
    
    # Coset of 0: {0}
    # Coset of 1: {1, 2, 4, 8, 9, 13, 15, 16}
    # Coset of 3: {3, 6, 12, 7, 14, 11, 5, 10}
    
    # So x^17+1 = (x+1) * f1(x) * f2(x) where f1, f2 are degree-8 irreducibles.
    # The QR code uses one of f1 or f2 as generator.
    
    # Let's find f1 (the minimal polynomial of alpha^1 where alpha is a primitive
    # 17th root of unity in GF(2^8)).
    
    # Actually, let's just try both candidate generator polynomials and verify.
    # The generator polynomial for one QR code is:
    # g1(x) = 1 + x^3 + x^5 + x^6 + x^7 + x^10 + x^12 + x^14 + x^16
    # Let's verify g1 divides x^17+1.
    
    x17_plus_1 = (1 << 17) | 1  # x^17 + 1
    
    g1 = 1
    for e in [3, 5, 6, 7, 10, 12, 14, 16]:
        g1 |= 1 << e
    
    # Check g1 divides x^17+1
    q, r = _poly_divmod(x17_plus_1, g1)
    if r != 0:
        # Try the other candidate
        g1 = 1
        for e in [1, 2, 4, 8, 9, 13, 15, 16]:
            g1 |= 1 << e
        q, r = _poly_divmod(x17_plus_1, g1)
    
    if r != 0:
        # Brute force: find all degree-8 polynomials that divide x^17+1
        # and have constant term 1
        candidates = []
        for mask in range(1, 1 << 8):
            g = 1 | (mask << 1)  # constant term 1, degree 8
            if g.bit_length() != 9:
                continue
            _, rem = _poly_divmod(x17_plus_1, g)
            if rem == 0:
                candidates.append(g)
        if len(candidates) >= 2:
            g1 = candidates[0]
        elif len(candidates) == 1:
            g1 = candidates[0]
        else:
            raise ValueError("Could not find generator polynomial")
    
    # Now build the generator matrix for the [17,9,5] QR code.
    # The code is cyclic, so the generator matrix rows are shifts of g.
    # g has degree 8, so the [17,9,5] code has 9 codewords generated by
    # g, xg, x^2g, ..., x^8g (mod x^17+1).
    
    # Build 9x17 matrix
    basis_17 = []
    for i in range(9):
        # Compute x^i * g mod (x^17+1)
        word = g1
        for _ in range(i):
            # Multiply by x: shift left, wrap around (since mod x^17+1)
            word = (word << 1) & ((1 << 17) - 1)
            if word & (1 << 17):
                word ^= 1  # x^17 = 1 in the quotient
        basis_17.append(word)
    
    # Extend to length 18 by adding a parity bit to make it self-dual.
    # The extended QR code adds a parity-check bit such that the code becomes self-dual.
    # For the [17,9,5] QR code, the extension to [18,9,6] is achieved by adding
    # a parity bit (the 18th coordinate) equal to the sum of the first 17 bits.
    # This makes the code self-dual with minimum distance 6.
    
    basis_18 = []
    for word in basis_17:
        parity = word.bit_count() % 2
        extended = word | (parity << 17)
        basis_18.append(extended)
    
    return basis_18

def construct():
    deadline = time.time() + 55  # Safety margin before 60s limit
    
    try:
        basis = _build_generator_matrix()
    except Exception:
        # Fallback: Reed-Muller code (32 words)
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words
    
    # Generate all 2^9 = 512 codewords as linear combinations of the basis
    codewords = [0]
    for b in basis:
        current_len = len(codewords)
        for i in range(current_len):
            codewords.append(codewords[i] ^ b)
    
    # Verify: all codewords are distinct and in [0, 2^18)
    if len(codewords) != 512:
        # Fallback
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words
    
    # Full verification: check all pairwise distances
    # 512 codewords -> ~130k pairs. This is fast in Python.
    if time.time() < deadline:
        valid = True
        for i in range(len(codewords)):
            for j in range(i + 1, len(codewords)):
                d = (codewords[i] ^ codewords[j]).bit_count()
                if d < 6:
                    valid = False
                    break
            if not valid:
                break
        
        if not valid:
            # Fallback
            words = []
            for slope in range(16):
                for intercept in range(2):
                    word = 0
                    for point in range(16):
                        bit = ((slope & point).bit_count() + intercept) % 2
                        word |= bit << point
                    words.append(word)
            return words
    
    return codewords
