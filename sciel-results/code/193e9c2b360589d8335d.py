import numpy as np

def construct():
    n, m, p = 3, 3, 8
    
    # Target tensor is all ones
    # T[i, j, k] = 1
    
    # We want to find U (n*m, R), V (m*p, R), W (p*n, R)
    # such that sum_r U[i*m+j, r] * V[j*p+k, r] * W[k*n+i, r] = 1
    
    # Try rank 58
    R = 58
    
    # Initialize
    np.random.seed(42)
    U = np.random.randn(n*m, R)
    V = np.random.randn(m*p, R)
    W = np.random.randn(p*n, R)
    
    # ALS
    for it in range(100):
        # Solve for U
        # For each i, j: sum_r U[i*m+j, r] * (V[j*p+..., r] * W[..., r]) = 1
        # This is linear in U.
        # Let M[i*m+j, r] = sum_k V[j*p+k, r] * W[k*n+i, r]
        # Then sum_r U[i*m+j, r] M[i*m+j, r] = 1
        # This is a system U * M^T = 1?
        # U is (n*m, R). M is (n*m, R).
        # We want U * M^T = 1 (vector of ones).
        # This is underdetermined if R > n*m? No, R=58, n*m=9.
        # We can just set U[i*m+j, r] = M[i*m+j, r] / sum_r M[i*m+j, r]^2?
        # No, we want to minimize residual.
        # The optimal U for fixed V, W is given by:
        # U = 1 * M^T (M M^T)^{-1}?
        # Let's derive.
        # Minimize || 1 - U M^T ||^2.
        # Derivative w.r.t U is -2 (1 - U M^T) M = 0.
        # U M^T M = M.
        # U = M (M^T M)^{-1}.
        
        M_U = np.zeros((n*m, R))
        for i in range(n):
            for j in range(m):
                # M_U[i*m+j, r] = sum_k V[j*p+k, r] * W[k*n+i, r]
                # V slice: V[j*p : (j+1)*p, :]
                # W slice: W[:, :] but indexed by k*n+i.
                # W is (p*n, R). Index k*n+i.
                # So for fixed i, we take rows i, n+i, 2n+i, ...
                W_slice = W[i::n, :] # (p, R)
                V_slice = V[j*p:(j+1)*p, :] # (p, R)
                M_U[i*m+j, :] = np.sum(V_slice * W_slice, axis=0)
                
        # Solve U = M_U (M_U^T M_U)^{-1}
        # M_U^T M_U is R x R.
        # Add regularization
        reg = 1e-6
        A = M_U.T @ M_U + reg * np.eye(R)
        b = M_U.T
        U = np.linalg.solve(A, b).T
        
        # Solve for V
        # Similarly
        M_V = np.zeros((m*p, R))
        for j in range(m):
            for k in range(p):
                # M_V[j*p+k, r] = sum_i U[i*m+j, r] * W[k*n+i, r]
                U_slice = U[:, j::m] # (n, R) - wait, U index is i*m+j.
                # U[i*m+j, r] for fixed j.
                # Rows are i*m+j.
                # So U_slice = U[0:m*n:m, :]? No.
                # i=0 -> 0*m+j = j
                # i=1 -> 1*m+j = m+j
                # i=2 -> 2*m+j = 2m+j
                U_slice = U[j::m, :] # (n, R)
                W_slice = W[k*n:(k+1)*n, :] # (n, R)
                M_V[j*p+k, :] = np.sum(U_slice * W_slice, axis=0)
                
        A = M_V.T @ M_V + reg * np.eye(R)
        b = M_V.T
        V = np.linalg.solve(A, b).T
        
        # Solve for W
        M_W = np.zeros((p*n, R))
        for k in range(p):
            for i in range(n):
                # M_W[k*n+i, r] = sum_j U[i*m+j, r] * V[j*p+k, r]
                U_slice = U[:, :] # Need to extract i*m+j for all j
                # U rows for fixed i: i*m, i*m+1, i*m+2
                U_slice = U[i*m:(i+1)*m, :] # (m, R)
                V_slice = V[:, k::p] # (m, R) - V index j*p+k
                # j=0 -> k
                # j=1 -> p+k
                # j=2 -> 2p+k
                V_slice = V[k::p, :]
                M_W[k*n+i, :] = np.sum(U_slice * V_slice, axis=0)
                
        A = M_W.T @ M_W + reg * np.eye(R)
        b = M_W.T
        W = np.linalg.solve(A, b).T
        
        # Check residual
        # Residual = sum_{i,j,k} (1 - sum_r U V W)^2
