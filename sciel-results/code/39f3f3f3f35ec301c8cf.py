import numpy as np

def construct():
    # Define the generator polynomial for the [17, 8, 5] QR code
    # g(x) = x^8 + x^5 + x^3 + x^2 + x + 1
    # Coefficients for x^0 to x^8
    g_coeffs = [1, 1, 1, 1, 0, 1, 0, 0, 1]
    
    # Generate the 8 basis vectors for the cyclic code of length 17
    basis_17 = []
    for shift in range(8):
        vec = [0] * 17
        for i, coeff in enumerate(g_coeffs):
            if coeff:
                vec[(i + shift) % 17] = 1
        basis_17.append(vec)
        
    # Extend to length 18 by appending a parity bit
    # The parity bit is 0 if weight is even, 1 if weight is odd
    # This ensures all codewords in the extended cyclic code have even weight
    basis_18 = []
    for vec in basis_17:
        weight = sum(vec)
        parity = weight % 2
        vec_ext = vec + [parity]
        basis_18.append(vec_ext)
        
    # Convert to numpy array for linear algebra
    A = np.array(basis_18, dtype=int)
    
    # Find the null space of A (vectors v such that A @ v.T = 0)
    # We need v to be orthogonal to all rows of A
    # Use SVD to find null space basis
    U, s, Vt = np.linalg.svd(A)
    # Null space is the rows of Vt corresponding to zero singular values
    # Tolerance for zero
    tol = 1e-10
    null_space_indices = np.where(s < tol)[0]
    if len(null_space_indices) == 0:
        # Should not happen, but fallback
        null_space_basis = []
    else:
        null_space_basis = Vt[null_space_indices, :].astype(int)
        
    # The null space has dimension 18 - 8 = 10
    # We iterate through all non-zero vectors in the null space
    # There are 2^10 = 1024 vectors
    num_basis = len(null_space_basis)
    
    # Generate all codewords in the extended cyclic code (256 codewords)
    # Use integer representation for speed
    codewords_ext = []
    for mask in range(256):
        word = 0
        for i in range(8):
            if (mask >> i) & 1:
                # Add basis vector i
                for j in range(18):
                    if basis_18[i][j]:
                        word ^= (1 << j)
        codewords_ext.append(word)
        
    # Check each candidate v in the null space
    for mask in range(1, 1 << num_basis):
        v = 0
        for i in range(num_basis):
            if (mask >> i) & 1:
                # Add basis vector i of null space
                for j in range(18):
                    if null_space_basis[i][j]:
                        v ^= (1 << j)
                        
        # Check if v is orthogonal to itself (self-orthogonal)
        # v . v = weight(v) % 2 == 0
        if v.bit_count() % 2 != 0:
            continue
            
        # Check distance from v to all codewords in C_ext
        # d(v, c) = (v ^ c).bit_count()
        valid = True
        for c in codewords_ext:
            dist = (v ^ c).bit_count()
            if dist < 6:
                valid = False
                break
                
        if valid:
            # We found a valid v. Construct the full code.
            # The full code is generated by basis_18 and v.
            # Generate all 512 codewords
            full_codewords = []
            for mask_full in range(512):
                word = 0
                # First 8 bits of mask select from basis_18
                for i in range(8):
                    if (mask_full >> i) & 1:
                        for j in range(18):
                            if basis_18[i][j]:
                                word ^= (1 << j)
                # 9th bit selects v
                if (mask_full >> 8) & 1:
                    word ^= v
                full_codewords.append(word)
                
            # Verify min distance of the full code (optional, but good for safety)
            # Just return if we trust the logic
            return full_codewords
            
    # Fallback: return the extended cyclic code (256 words) if no v found
    return codewords_ext
