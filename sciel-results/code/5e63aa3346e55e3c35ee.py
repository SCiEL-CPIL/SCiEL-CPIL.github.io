import numpy as np
from numpy.fft import fft, ifft
import time

N = 400

def _autoconv(x):
    """Compute linear autoconvolution via FFT."""
    n = len(x)
    size = 2 * n - 1
    size2 = 1
    while size2 < size:
        size2 *= 2
    F = fft(x, size2)
    A = ifft(F * np.conj(F)).real
    return A[:size]

def _score(x):
    """Compute max(|autoconv|) / (sum(x))^2. Lower is better."""
    s = np.sum(x)
    if abs(s) < 1e-12:
        return np.inf
    A = _autoconv(x)
    m = np.max(np.abs(A))
    return m / (s * s)

def _generate_m_sequence(taps, length):
    """
    Generate an m-sequence (Maximum Length Sequence) using a Linear Feedback Shift Register (LFSR).
    taps: list of bit positions to XOR (1-indexed, LSB is 1).
    length: desired length of the sequence.
    Returns a numpy array of 0s and 1s.
    """
    # State is a list of bits, LSB first
    # We need a primitive polynomial.
    # Common primitive polynomials for small degrees:
    # deg 7: x^7 + x^3 + 1 -> taps [1, 3, 7]
    # deg 8: x^8 + x^4 + x^3 + x^2 + 1 -> taps [1, 2, 3, 4, 8]
    # deg 9: x^9 + x^4 + 1 -> taps [1, 4, 9]
    # deg 10: x^10 + x^7 + 1 -> taps [1, 7, 10]
    # deg 11: x^11 + x^9 + 1 -> taps [1, 9, 11]
    # deg 12: x^12 + x^6 + x^4 + x + 1 -> taps [1, 2, 4, 6, 12]
    # deg 13: x^13 + x^4 + 1 -> taps [1, 4, 13]
    # deg 14: x^14 + x^10 + x^6 + x + 1 -> taps [1, 2, 6, 10, 14]
    # deg 15: x^15 + x + 1 -> taps [1, 2, 15]
    # deg 16: x^16 + x^14 + x^13 + x^11 + 1 -> taps [1, 11, 13, 14, 16]
    
    # We will try a few known primitive polynomials.
    # The state size determines the period 2^k - 1.
    # We pick k such that 2^k - 1 >= length.
    
    # Let's pick k=10 (period 1023) or k=9 (period 511) or k=8 (period 255).
    # N=400, so k=9 (511) is a good fit.
    
    # Primitive polynomial for k=9: x^9 + x^4 + 1. Taps: 1, 4, 9.
    # Let's implement a generic LFSR generator.
    
    # Find appropriate degree
    k = 9
    # Taps for x^9 + x^4 + 1
    # Feedback bit = s[0] XOR s[3] (if 0-indexed, x^1 is bit 0, x^4 is bit 3, x^9 is bit 8? No, standard LFSR notation varies)
    # Let's use the standard Galois LFSR or Fibonacci LFSR.
    # Fibonacci LFSR:
    # s_{n+k} = s_{n} XOR s_{n+k-4} (for x^k + x^4 + 1)
    # So if state is [s0, s1, ..., s_{k-1}], new bit = s0 XOR s_{k-1-4} = s0 XOR s_{k-5}.
    # Wait, x^k + x^j + 1 means s_{n+k} = s_n + s_{n+k-j}.
    # For x^9 + x^4 + 1: s_{n+9} = s_n + s_{n+5}.
    # In a shift register holding s_n ... s_{n+8}:
    # New bit = s_n XOR s_{n+5}.
    # s_n is the bit being shifted out (index 0).
    # s_{n+5} is index 5.
    
    state = np.ones(k, dtype=np.int8) # Initial state all 1s (non-zero)
    seq = np.zeros(length, dtype=np.int8)
    
    for i in range(length):
        seq[i] = state[0]
        # Calculate feedback
        # x^9 + x^4 + 1 -> taps at 0 and 5 (relative to shift out)
        # Let's verify: Char poly P(x) = x^9 + x^4 + 1.
        # Recurrence: s_{n+9} = s_n + s_{n+5}.
        # Yes.
        fb = state[0] ^ state[5]
        # Shift left (towards higher indices)
        state = np.roll(state, -1)
        state[-1] = fb
        
    return seq

