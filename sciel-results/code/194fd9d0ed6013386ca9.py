import time
import math

def construct():
    start_time = time.time()
    deadline = start_time + 85  # Safety margin before 90s limit
    
    N = 256
    
    # Sieve of Eratosthenes
    is_prime = [True] * (N + 1)
    is_prime[0] = False
    is_prime[1] = False
    for i in range(2, int(N ** 0.5) + 1):
        if is_prime[i]:
            for j in range(i * i, N + 1, i):
                is_prime[j] = False
    
    primes = [i for i in range(2, N + 1) if is_prime[i]]
    total_primes = len(primes)
    
    # Precompute prime factors for all numbers up to N
    pf = [set() for _ in range(N + 1)]
    for i in range(2, N + 1):
        if is_prime[i]:
            for j in range(i, N + 1, i):
                pf[j].add(i)
    
    # Identify small primes for subset enumeration
    # Primes > 50 generate very few composites
    small_primes = [p for p in primes if p <= 50]
    
    best_score = 0
    best_R = set()
    
    # Iterate over subsets of small_primes to find optimal R
    # R is the set of primes we REMOVE from K (and use to generate composites)
    # Score = (total_primes - |R|) + (number of composites c with PF(c) subset of R)
    
    from itertools import combinations
    
    for r_size in range(len(small_primes) + 1):
        if time.time() - start_time > 70:
            break
        for R_subset in combinations(small_primes, r_size):
            R = set(R_subset)
            
            # Count composites generated by R
            comp_count = 0
            for c in range(4, N + 1):
                if not is_prime[c]:
                    if pf[c] and pf[c].issubset(R):
                        comp_count += 1
                        
            k_count = total_primes - len(R)
            score = k_count + comp_count
            
            if score > best_score:
                best_score = score
                best_R = R.copy()
    
    # Refinement: Try adding larger primes to best_R
    current_R = best_R.copy()
    current_score = best_score
    
    for p in primes:
        if p in current_R:
            continue
        if p <= 50:
            continue  # Already considered in enumeration
            
        # Check if adding p to current_R improves score
        # Gain: composites c where PF(c) subset of (current_R U {p}) and p in PF(c)
        gain = 0
        for c in range(4, N + 1):
            if not is_prime[c]:
                if p in pf[c]:
                    # Check if all other factors are in current_R
                    if (pf[c] - {p}).issubset(current_R):
                        gain += 1
                        
        # Cost is 1 (remove p from K)
        if gain - 1 > 0:
            current_R.add(p)
            current_score += gain - 1
    
    # Construct the set S
    # S = (Primes not in current_R) U { c | composite, PF(c) subset of current_R }
    
    S = []
    # Add primes not in R
    for p in primes:
        if p not in current_R:
            S.append(p)
            
    # Add composites whose prime factors are all in current_R
    for c in range(4, N + 1):
        if not is_prime[c]:
            if pf[c] and pf[c].issubset(current_R):
                S.append(c)
                
    # Ensure distinct and in range
    S = list(set(S))
    S = [x for x in S if 2 <= x <= N]
    
    # Validate: Check that for all distinct a, b, c in S, a does not divide b*c
    S.sort()
    valid = True
    n_s = len(S)
    for i in range(n_s):
        a = S[i]
        for j in range(i + 1, n_s):
            b = S[j]
            for k in range(j + 1, n_s):
                c = S[k]
                if (b * c) % a == 0:
                    valid = False
                    break
            if not valid:
                break
        if not valid:
            break
    
    if not valid:
        # Fallback to primes if validation fails
        S = primes
    
    # Final type check: ensure Python int
    S = [int(x) for x in S]
    
    return S
