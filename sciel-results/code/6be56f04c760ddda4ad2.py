import time

def construct():
    start_time = time.time()
    deadline = start_time + 50.0

    # 1. Construct the [18, 9, 6] Extended Quadratic Residue Code
    # p = 17
    # Quadratic residues mod 17: {1, 2, 4, 8, 9, 13, 15, 16}
    # The generator matrix for the [17, 9, 5] QR code is circulant with first row 
    # having 1s at indices {0} U QR.
    # We extend with a parity bit to get length 18.
    
    p = 17
    qr_set = {1, 2, 4, 8, 9, 13, 15, 16}
    # Indices with 1s in the base vector (cyclic shift of this)
    # Base vector indices: 0 and the QRs
    base_indices = {0} | qr_set
    
    # Generate 9 generator rows as 18-bit integers
    # Row i is the cyclic shift of the base vector by i positions?
    # Standard QR code construction:
    # The code is generated by the circulant matrix with first row c0...c16
    # where c_j = 1 if j is in {0} U QR, else 0.
    # The 9 rows are the cyclic shifts of this base vector.
    
    gen_rows = []
    for i in range(9):
        row_mask = 0
        for j in range(p):
            # The entry at column j in row i is base_vector[(j - i) % p]
            if ((j - i) % p) in base_indices:
                row_mask |= (1 << j)
        # Add parity bit at position 17
        # Parity bit is the sum of bits mod 2
        parity = row_mask.bit_count() % 2
        row_mask |= (parity << p)
        gen_rows.append(row_mask)
        
    # Generate all 2^9 = 512 codewords
    codewords = []
    for mask in range(512):
        word = 0
        for i in range(9):
            if (mask >> i) & 1:
                word ^= gen_rows[i]
        codewords.append(word)
        
    # 2. Verify (Quick check)
    # Since it's a linear code, min distance is guaranteed by construction if the generator matrix is correct.
    # But let's do a spot check or full check if time permits.
    # Full check is 512*511/2 ~ 130k pairs. Very fast.
    if len(codewords) > 1:
        # Verify distinctness
        if len(set(codewords)) != len(codewords):
            # Fallback to simple valid code if something went wrong (shouldn't happen)
            return [0]
            
        # Verify min distance
        # For a linear code, it suffices to check the weight of all non-zero codewords.
        # But we are returning the list of all codewords.
        # Let's just verify pairwise for safety, it's fast.
        for i in range(len(codewords)):
            for j in range(i+1, len(codewords)):
                if (codewords[i] ^ codewords[j]).bit_count() < 6:
                    # This should never happen for the QR code
                    # Fallback
                    return [0]
                    
    return codewords

if __name__ == "__main__":
    words = construct()
    print(f"Generated {len(words)} codewords")
