def _is_valid_triples(S):
    """Check if all unordered triple sums (with replacement) are unique."""
    n = len(S)
    seen = set()
    # (i, j, k) with i <= j <= k
    for i in range(n):
        for j in range(i, n):
            for k in range(j, n):
                s = S[i] + S[j] + S[k]
                if s in seen:
                    return False
                seen.add(s)
    return True

def _check_conflict(x, S):
    """
    Check if adding x to S creates any duplicate triple sums.
    Returns True if x can be added (no conflict).
    """
    n = len(S)
    # We need to check:
    # 1. New sums involving x don't collide with existing sums.
    # 2. New sums involving x don't collide with each other.
    
    # To be efficient, we check collisions against existing sums first.
    # Existing sums are all a+b+c where a,b,c in S.
    # New sums are:
    # 3x
    # 2x + y
    # x + 2y
    # x + y + z (y != z)
    
    # A faster way: 
    # Generate all new sums. If any sum appears twice in the new set, or if any new sum is in the existing sum set, it's invalid.
    
    # However, generating all existing sums is O(n^3) which is too slow for large n if done repeatedly.
    # Instead, we can maintain a set of existing sums? 
    # The current program doesn't maintain it globally in a way that's easy to pass around without overhead.
    # Let's use a probabilistic/efficient check or just recompute if n is small enough?
    # For n ~ 50, n^3 is 125k. If we do this 4096 times, that's 500M ops. Too slow in Python.
    
    # Better approach for _check_conflict:
    # We only need to check if the NEW sums collide with EXISTING sums.
    # Existing sums set is not passed. We must compute it or pass it.
    # Let's modify the main loop to maintain `existing_sums`.
    
    # For this function signature, I will assume S is sorted.
    # We will compute the set of new sums.
    new_sums = set()
    
    # (x, x, x)
    new_sums.add(3 * x)
    
    # (x, x, y)
    for y in S:
        new_sums.add(2 * x + y)
        
    # (x, y, y)
    for y in S:
        new_sums.add(x + 2 * y)
        
    # (x, y, z) with y < z
    n = len(S)
    for i in range(n):
        for j in range(i + 1, n):
            new_sums.add(x + S[i] + S[j])
            
    # Check for internal conflicts in new_sums
    # Since we used a set, we lost the count. 
    # We need to know if any sum was generated by multiple distinct triples.
    # Example: 2x+y1 == x+2y2 == x+y3+y4
    # This is hard to check without counting.
    
    # Let's use a dictionary to count occurrences in the generation loop.
    counts = {}
    
    s = 3 * x
    counts[s] = counts.get(s, 0) + 1
    
    for y in S:
        s = 2 * x + y
        counts[s] = counts.get(s, 0) + 1
        
    for y in S:
        s = x + 2 * y
        counts[s] = counts.get(s, 0) + 1
        
    for i in range(n):
        for j in range(i + 1, n):
            s = x + S[i] + S[j]
            counts[s] = counts.get(s, 0) + 1
            
    # If any count > 1, there is an internal conflict.
    for s, c in counts.items():
        if c > 1:
            return False
            
    return counts

