import numpy as np
import time

def sign_edges(graph, budget):
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin before 60s limit
    
    m = graph['n'] // 2
    edges = graph['edges']
    n_edges = len(edges)
    n = 2 * m
    
    # Identify edge roles
    # Roles:
    # 'top_path': (i, i+1) for i in 0..m-2
    # 'bot_path': (i+m, i+1+m) for i in 0..m-2
    # 'match_i': (i, i+m) for i in 0..m-1
    # 'top_close': (m-1, 0)
    # 'bot_close': (2m-1, m)
    
    edge_roles = {}
    non_tree_indices = []
    non_tree_roles = []
    
    for idx, (u, v) in enumerate(edges):
        u, v = int(u), int(v)
        
        # Check if it's a matching edge
        if abs(u - v) == m:
            top_v = min(u, v)
            edge_roles[idx] = f'match_{top_v}'
            if top_v != 0:
                non_tree_indices.append(idx)
                non_tree_roles.append(f'match_{top_v}')
        else:
            # It's a cycle edge
            if u < m and v < m:
                # Top cycle
                if (u == m-1 and v == 0) or (u == 0 and v == m-1):
                    edge_roles[idx] = 'top_close'
                    non_tree_indices.append(idx)
                    non_tree_roles.append('top_close')
                else:
                    edge_roles[idx] = 'top_path'
            elif u >= m and v >= m:
                # Bottom cycle
                if (u == 2*m-1 and v == m) or (u == m and v == 2*m-1):
                    edge_roles[idx] = 'bot_close'
                    non_tree_indices.append(idx)
                    non_tree_roles.append('bot_close')
                else:
                    edge_roles[idx] = 'bot_path'
            else:
                edge_roles[idx] = 'unknown'
                
    # Fallback if roles are not as expected
    if 'unknown' in edge_roles.values() or len(non_tree_indices) != m + 1:
        signs = np.ones(n_edges, dtype=int)
        for i, (u, v) in enumerate(edges):
            if abs(u - v) == m:
                top = u if u < m else v
                if top % 2 == 0:
                    signs[i] = -1
        return signs

    # Precompute base adjacency structure
    # We'll use a fast connectivity check and eigenvalue computation
    
    # For the lift to be connected, the product of signs around the "twisted" cycles must be consistent
    # Actually, for a 2-lift of a graph, the lift is connected iff the signs define a non-trivial homomorphism to Z2
    # i.e., there exists a vertex labeling c: V -> {0,1} such that for every edge (u,v) with sign s,
    # c(v) = c(u) XOR (s == -1)
    # And the lift is connected iff this labeling is not constant (i.e., both 0 and 1 appear)
    # Wait, that's for the bipartite double cover. Let me think again.
    
    # Actually, the 2-lift is connected iff the signed graph is "bipartite" in a certain sense.
    # More precisely: the lift is connected iff the cycle space of the base graph, when mapped by the sign product,
    # generates the whole Z2. Since Z2 is generated by a single non-trivial element, we just need at least one
    # cycle with product -1.
    
    # So: the lift is connected iff there exists at least one cycle in the base graph whose edge signs multiply to -1.
    
    # For the prism graph, the fundamental cycles are:
    # 1. Top cycle: product of top_path signs * top_close sign
    # 2. Bottom cycle: product of bot_path signs * bot_close sign
    # 3. For each i, the "ladder" cycle: (i, i+1) top, (i+1, i+1+m) match, (i, i+m) match reversed, (i, i+1) bottom reversed
    #    Actually, let's use the tree structure.
    
    # Let's use the tree:
    # Tree edges: match_0, all top_path, all bot_path
    # Non-tree edges: match_1..match_{m-1}, top_close, bot_close
    
    # The cycle products for non-tree edges:
    # For match_i (i >= 1): cycle is match_0, top_path(0..i-1), match_i, bot_path(i-1..0)
    #   Product = sign(match_0) * prod(top_path[0..i-1]) * sign(match_i) * prod(bot_path[0..i-1])
    #   Since tree edges are +1, this is just sign(match_i)
    # Wait, no. The tree edges are fixed to +1 in my construction.
    # So the cycle product for match_i is just sign(match_i).
    # For top_close: cycle is top_close * prod(top_path[0..m-1]) reversed
    #   Product = sign(top_close) * prod(top_path signs)
    #   But top_path signs are +1 (tree), so product = sign(top_close)
    # For bot_close: similarly, product = sign(bot_close)
    
    # So the lift is connected iff at least one of:
    # sign(match_1), sign(match_2), ..., sign(match_{m-1}), sign(top_close), sign(bot_close) is -1
    
    # This is a huge simplification!
    
    num_non_tree = len(non_tree_indices)
    total_combinations = 1 << num_non_tree
    
    best_radius = float('inf')
    best_signs = None
    
    # Precompute the base signed matrix for tree edges (all +1)
    A_base_tree = np.zeros((n, n), dtype=float)
    for i, (u, v) in enumerate(edges):
        if i not in non_tree_indices:
            A_base_tree[u, v] = 1.0
            A_base_tree[v, u] = 1.0
            
    # For each combination, we just need to add the non-tree edges with their signs
    # And check connectivity (which is just: at least one non-tree sign is -1)
    
    for mask in range(total_combinations):
        if time.time() > deadline:
            break
            
        # Check connectivity: at least one non-tree edge has sign -1
        # In our mask, bit j corresponds to non_tree_indices[j]
        # If bit j is 1, sign is -1; else +1
        # So we need mask != 0 for connectivity (since if all are +1, the lift is disconnected)
        # Wait, is that right?
        # If all non-tree signs are +1, then all cycle products are +1, so the lift is disconnected.
        # If at least one is -1, then at least one cycle product is -1, so the lift is connected.
        # Yes!
        
        if mask == 0:
            continue
            
        # Construct the full signed adjacency matrix
        A_signed = A_base_tree.copy()
        for j, idx in enumerate(non_tree_indices):
            if (mask >> j) & 1:
                s = -1.0
            else:
                s = 1.0
            u, v = edges[idx]
            A_signed[u, v] = s
            A_signed[v, u] = s
            
        # Compute spectral radius
        try:
            eigenvalues = np.linalg.eigvalsh(A_signed)
            radius = np.max(np.abs(eigenvalues))
        except np.linalg.LinAlgError:
            continue
            
        if radius < best_radius:
            best_radius = radius
            # Reconstruct signs array
            signs = np.ones(n_edges, dtype=int)
            for j, idx in enumerate(non_tree_indices):
                if (mask >> j) & 1:
                    signs[idx] = -1
                else:
                    signs[idx] = 1
            best_signs = signs
            
    if best_signs is None:
        # Fallback
        signs = np.ones(n_edges, dtype=int)
        for i, (u, v) in enumerate(edges):
            if abs(u - v) == m:
                top = u if u < m else v
                if top % 2 == 0:
                    signs[i] = -1
        return signs
        
    return best_signs
