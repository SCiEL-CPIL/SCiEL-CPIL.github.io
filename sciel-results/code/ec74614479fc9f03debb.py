import numpy as np
from scipy.optimize import minimize
import time

N = 50
DEADLINE = 140.0  # Safety margin before 150s kill

def _compute_score(pts):
    """Compute the true packing radius (nonsmooth)."""
    n = len(pts)
    if n == 0:
        return 0.0
    diffs = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dists = np.sqrt(np.sum(diffs ** 2, axis=-1))
    np.fill_diagonal(dists, np.inf)
    min_pair = np.min(dists) / 2.0
    radii = np.sqrt(np.sum(pts ** 2, axis=-1))
    min_margin = np.min(1.0 - radii)
    return min(min_pair, min_margin)

def _violation_and_grad(x, r):
    """
    x: (2N,) array of centers.
    r: candidate radius.
    Returns (V, grad) where V is the sum of squared violations.
    Violations:
    1. Pairwise: max(0, 2r - dist_ij)^2
    2. Boundary: max(0, |c_i| - (1-r))^2
    """
    pts = x.reshape(-1, 2)
    n = len(pts)
    
    # Pairwise distances
    diffs = pts[:, np.newaxis, :] - pts[np.newaxis, :, :]
    dists = np.sqrt(np.sum(diffs ** 2, axis=-1))
    np.fill_diagonal(dists, np.inf)
    
    # Boundary radii
    radii = np.sqrt(np.sum(pts ** 2, axis=-1))
    
    V = 0.0
    grad = np.zeros_like(x)
    
    # 1. Pairwise violations
    # We want dist_ij >= 2r. Violation if dist_ij < 2r.
    # v_ij = max(0, 2r - dist_ij)^2
    # d(v_ij)/d(c_i) = 2 * (2r - dist_ij) * (-1) * (c_i - c_j) / dist_ij
    #                = -2 * (2r - dist_ij) * (c_i - c_j) / dist_ij
    # Note: only if dist_ij < 2r.
    
    # To avoid O(N^2) python loop, we can vectorize the gradient calculation.
    # However, L-BFGS-B calls this many times. N=50 is small enough that O(N^2) is fine.
    # 1225 pairs.
    
    for i in range(n):
        for j in range(i + 1, n):
            d = dists[i, j]
            if d < 2 * r:
                # v = (2r - d)^2
                # dv/dci = 2(2r-d) * d(2r-d)/dci
                # d(2r-d)/dci = - (ci-cj)/d
                # dv/dci = -2(2r-d) (ci-cj)/d
                # dv/dcj = 2(2r-d) (ci-cj)/d
                
                factor = -2.0 * (2.0 * r - d) / d
                diff_vec = pts[i] - pts[j]
                grad[2*i:2*i+2] += factor * diff_vec
                grad[2*j:2*j+2] -= factor * diff_vec
                V += (2.0 * r - d) ** 2
                
    # 2. Boundary violations
    # We want |c_i| <= 1 - r. Violation if |c_i| > 1 - r.
    # v_i = max(0, |c_i| - (1-r))^2
    # dv/dci = 2(|c_i| - (1-r)) * (c_i / |c_i|)
    
    for i in range(n):
        rad = radii[i]
        limit = 1.0 - r
        if rad > limit:
            # v = (rad - limit)^2
            # dv/dci = 2(rad-limit) * (ci/rad)
            factor = 2.0 * (rad - limit) / rad
            grad[2*i:2*i+2] += factor * pts[i]
            V += (rad - limit) ** 2
            
    return V, grad

def _feasibility_search(init_pts, r_target, time_limit):
    """
    Try to find a configuration where all circles of radius r_target fit.
    Minimizes violation function.
    Returns (success, pts).
    """
    t0 = time.time()
    x0 = init_pts.flatten()
    
    # Use L-BFGS-B
    # We don't have bounds strictly, but we can constrain to unit disk roughly?
    # Actually, the violation function penalizes going outside, so no hard bounds needed.
    # But L-BFGS-B works well with bounds. Let's use bounds=[(-1,1)]*2N to keep them in square?
    # The container is a circle. Keeping them in the square [-1,1]^2 is a safe superset.
    bounds = [(-1.0, 1.0)] * (2 * N)
    
    def objective_and_grad(x):
        V, g = _violation_and_grad(x, r_target)
        return V, g
        
    res = minimize(objective_and_grad, x0, method='L-BFGS-B', bounds=bounds,
                   options={'maxiter': 1000, 'ftol': 1e-12, 'gtol': 1e-8, 'disp': False})
    
    final_pts = res.x.reshape(-1, 2)
    final_violation = res.fun
    
    # Check if we actually satisfied the constraints
    # A small tolerance is needed due to numerical precision
    if final_violation < 1e-10:
        return True, final_pts
    return False, final_pts

def _hex_init(spacing):
    """Hexagonal lattice initialization."""
    k = int(1.0 / spacing) + 2
    rows = [((i + 0.5 * (j % 2)) * spacing, j * spacing * np.sqrt(3.0) / 2.0)
            for i in range(-k, k + 1) for j in range(-k, k + 1)]
    points = np.array(rows)
    radius = np.hypot(points[:, 0], points[:, 1])
    points = points[radius <= 1.0 - spacing / 2.0]
    if len(points) >= N:
        # Sort by distance to center to keep the most central ones?
        # Or just take first N?
        # Taking first N from a list generated by loops might be biased.
        # Let's take the N points closest to the center to form a compact core.
        radii = np.hypot(points[:, 0], points[:, 1])
        idx = np.argsort(radii)[:N]
        points = points[idx]
    else:
        # If not enough, pad with random? Or just return what we have?
        # The task requires N points. If we don't have N, we need to generate more.
        # But hex_init with reasonable spacing should have plenty.
        pass
    return points

def _ring_init():
    """
    Initialize with concentric rings.
    Ring 0: 1 point (center)
    Ring 1: 6 points
    Ring 2: 12 points
    Ring 3: 18 points
    Ring 4: 13 points (to reach 50)
    Total: 1+6+12+18+13 = 50
    """
    pts = []
    pts.append(np.array([0.0, 0.0]))
    
    # Ring 1
    for i in range(6):
        angle = 2 * np.pi * i / 6
        pts.append(np.array([0.3 * np.cos(angle), 0.3 * np.sin(angle)]))
        
    # Ring 2
    for i in range(12):
        angle = 2 * np.pi * i / 12 + np.pi/12 # offset
        pts.append(np.array([0.55 * np.cos(angle), 0.55 * np.sin(angle)]))
        
    # Ring 3
    for i in range(18):
        angle = 2 * np.pi * i / 18
        pts.append(np.array([0.75 * np.cos(angle), 0.75 * np.sin(angle)]))
        
    # Ring 4
    for i in range(13):
        angle = 2 * np.pi * i / 13 + np.pi/13
        pts.append(np.array([0.9 * np.cos(angle), 0.9 * np.sin(angle)]))
        
    return np.array(pts[:N])

def _random_init(seed):
    """Random initialization within unit disk."""
    rng = np.random.RandomState(seed)
    pts = []
    while len(pts) < N:
        # Generate points in a square and reject those outside unit circle
        x = rng.uniform(-1, 1, size=(N * 5, 2))
        r = np.hypot(x[:, 0], x[:, 1])
        valid = r <= 0.95
        pts.extend(x[valid].tolist())
    pts = np.array(pts[:N])
    return pts

def construct():
    t_start = time.time()
    
    # List of initializers
    inits = []
    inits.append(_hex_init(0.25))
    inits.append(_hex_init(0.22))
    inits.append(_hex_init(0.28))
    inits.append(_ring_init())
    inits.append(_random_init(42))
    inits.append(_random_init(123))
    inits.append(_random_init(999))
    
    # Filter inits to ensure they have exactly N points and are valid
    valid_inits = []
    for init in inits:
        if len(init) == N and np.all(np.isfinite(init)):
            valid_inits.append(init)
            
    if not valid_inits:
        # Fallback
        return _hex_init(0.25)
        
    best_score = -1.0
    best_pts = None
    
    # Binary search bounds
    # Lower bound: very small
    # Upper bound: theoretical max is 1/sqrt(50) ~ 0.141, but packing efficiency reduces this.
    # Known best is ~0.1258. Let's search between 0.10 and 0.14.
    r_low = 0.10
    r_high = 0.14
    
    # We will perform a few iterations of binary search.
    # Since the feasibility check is expensive (L-BFGS-B), we limit the number of steps.
    # Let's do 5-6 steps of binary search.
    
    num_search_steps = 6
    
    for step in range(num_search_steps):
        if time.time() - t_start > DEADLINE - 10:
            break
            
        r_mid = (r_low + r_high) / 2.0
        
        # Try to find a feasible configuration for r_mid
        # Use multiple initializers to increase chance of finding a solution
        feasible = False
        best_feasible_pts = None
        
        # Sort initializers by their current score for r_mid?
        # Or just try them all?
        # Trying all initializers for every r_mid might be too slow.
        # Let's try the best performing initializers from previous steps?
        # For simplicity, try all, but break early if we find a good one.
        
        for init in valid_inits:
            if time.time() - t_start > DEADLINE - 5:
                break
                
            # Time limit per feasibility check
            time_remaining = DEADLINE - (time.time() - t_start)
            time_for_check = min(time_remaining / 3.0, 10.0) # Allow up to 10s per check
            if time_for_check < 1.0:
                continue
                
            success, pts = _feasibility_search(init, r_mid, time_for_check)
            
            if success:
                feasible = True
                # Score the found points to see how much better they are than r_mid
                score = _compute_score(pts)
                if best_feasible_pts is None or score > _compute_score(best_feasible_pts):
                    best_feasible_pts = pts
                    if score > best_score:
                        best_score = score
                        best_pts = pts.copy()
                        
        if feasible:
            # We found a configuration for r_mid.
            # Update lower bound
            r_low = r_mid
            # We can also update upper bound if the score is significantly higher?
            # No, binary search logic: if r_mid is feasible, try larger.
            # However, we found a specific configuration. Its score might be > r_mid.
            # Let's set r_high to max(r_high, best_score * 1.05) to explore?
            # Actually, standard binary search: if feasible, low = mid. Else high = mid.
            # But we want to maximize.
            # If r_mid is feasible, the optimal is >= r_mid. So low = r_mid.
            # If not feasible, optimal < r_mid. So high = r_mid.
            
            # To be safe and converge, let's stick to standard bisection logic
            # but use the actual score found to potentially jump?
            # If we found a config with score 0.126, we know 0.126 is feasible.
            # So low = max(low, best_score).
            if best_score > r_low:
                r_low = best_score
        else:
            # Not feasible
            r_high = r_mid
            
    # After binary search, we have best_pts.
    # Do a final polish on the best_pts found to squeeze out more.
    # We can run L-BFGS-B again with the current best_score as the target r?
    # Or just run a generic optimization to maximize score?
    # The feasibility search already does this for a fixed r.
    # If we set r = best_score, it will try to minimize violations for that r.
    # This effectively polishes the solution.
    
    if best_pts is not None and time.time() - t_start < DEADLINE - 5:
        # Polish step: try to improve the best found configuration
        # Use the current best score as the target radius for feasibility search
        # This forces the optimizer to try to make all constraints >= best_score
        target_r = best_score
        # Use the best_pts as the initial guess
        success, polished_pts = _feasibility_search(best_pts, target_r, DEADLINE - (time.time() - t_start) - 2)
        
        if success:
            polished_score = _compute_score(polished_pts)
            if polished_score > best_score:
                best_score = polished_score
                best_pts = polished_pts
        else:
            # If it failed to find a feasible solution for the current best score,
            # it might have improved the geometry anyway (reduced violations).
            # Check if the returned points are better.
            polished_score = _compute_score(polished_pts)
            if polished_score > best_score:
                best_score = polished_score
                best_pts = polished_pts

    if best_pts is None:
        # Fallback
        best_pts = valid_inits[0]
        
    return best_pts
