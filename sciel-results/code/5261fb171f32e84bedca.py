import time
import random
import sys

def _popcount(x):
    # Python 3.8+ has int.bit_count()
    return x.bit_count() if hasattr(x, 'bit_count') else bin(x).count('1')

def _has_independent_set_10(adj_mask, n):
    """
    adj_mask: list of ints, adj_mask[i] has bits set for neighbors of i.
    n: number of vertices.
    Returns True if independent set of size 10 exists.
    """
    all_mask = (1 << n) - 1
    # Precompute non-neighbors including self? No, independent set cannot contain self.
    # non_neighbors[i] = all_mask ^ adj_mask[i] ^ (1 << i)
    non_neighbors = [all_mask ^ adj_mask[i] ^ (1 << i) for i in range(n)]
    
    # Order vertices by degree in the graph? 
    # For the search, we will pick from candidates.
    
    # Memoization? State is (cands_mask, size). cands_mask can be large (2^40).
    # But the search tree is pruned heavily.
    
    def dfs(cands, size):
        if size == 10:
            return True
        if _popcount(cands) < 10 - size:
            return False
            
        # Heuristic: Pick vertex with max degree in the subgraph induced by cands
        # This minimizes the "include" branch size.
        # Degree of v in cands is popcount(adj_mask[v] & cands)
        # We want to pick v such that popcount(non_neighbors[v] & cands) is MINIMIZED.
        # Because next_cands_include = cands & non_neighbors[v].
        
        best_v = -1
        min_next_size = _popcount(cands) + 1
        
        # Iterate through set bits in cands
        # Optimization: If cands is small, iterate all. If large, sample?
        # For n=40, iterating all 40 is fast enough.
        temp = cands
        while temp:
            # Get lowest set bit
            lsb = temp & -temp
            v = lsb.bit_length() - 1
            temp ^= lsb
            
            # Calculate size of next candidates if we include v
            next_cands = cands & non_neighbors[v]
            next_size = _popcount(next_cands)
            
            if next_size < min_next_size:
                min_next_size = next_size
                best_v = v
                best_next_cands = next_cands
                if min_next_size == 0:
                    break

        if best_v == -1:
            return False

        # Branch 1: Include best_v
        if dfs(best_next_cands, size + 1):
            return True
            
        # Branch 2: Exclude best_v
        # Remove best_v from cands
        cands_without_v = cands & ~(1 << best_v)
        if dfs(cands_without_v, size):
            return True
            
        return False

    # Start with all vertices
    # Order doesn't matter for the set, but we pass the mask
    return dfs(all_mask, 0)

def construct():
    start_time = time.time()
    deadline = start_time + 140  # 10s margin
    
    # Try n from 40 down to 30
    for n in range(40, 29, -1):
        if time.time() > deadline:
            break
            
        # Try random restarts
        # Maximal triangle-free graphs are generated by random edge ordering
        for restart in range(200):
            if time.time() > deadline:
                break
                
            # Generate random maximal triangle-free graph
            # adj_mask[i] is int
            adj_mask = [0] * n
            
            # Create list of all edges
            edges = []
            for i in range(n):
                for j in range(i+1, n):
                    edges.append((i, j))
            
            random.shuffle(edges)
            
            for i, j in edges:
                # Check if adding (i,j) creates a triangle
                # Triangle exists if there is k such that (i,k) and (j,k) are edges
                # common_neighbors = adj_mask[i] & adj_mask[j]
                # If common_neighbors is not 0, triangle exists
                if (adj_mask[i] & adj_mask[j]) == 0:
                    # Add edge
                    adj_mask[i] |= (1 << j)
                    adj_mask[j] |= (1 << i)
            
            # Verify
            if not _has_independent_set_10(adj_mask, n):
                # Convert to edge list
                edge_list = []
                for i in range(n):
                    # Only add j > i to avoid duplicates
                    mask = adj_mask[i]
                    # Iterate bits
                    temp = mask
                    while temp:
                        lsb = temp & -temp
                        j = lsb.bit_length() - 1
                        if j > i:
                            edge_list.append([i, j])
                        temp ^= lsb
                return {'n': n, 'edges': edge_list}
        
    # Fallback to a known small valid graph
    # The seed fallback was n=26.
    # Let's return a simple valid graph on n=20 (Polarity graph PG(2,4) is n=21, alpha<10)
    # Or just return the seed fallback structure if we can't find better.
    # But we should try to return something valid.
    # A complete bipartite graph K_10,10 is triangle free.
    # Independent set size is 10 (one part).
    # We need NO independent set of size 10. So alpha < 10.
    # K_9,9 has n=18, alpha=9. Valid.
    # Let's construct K_9,9.
    n = 18
    edges = []
    for i in range(9):
        for j in range(9, 18):
            edges.append([i, j])
    return {'n': n, 'edges': edges}
