import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin for 150s limit
    
    N = 1000
    max_sum = 2 * N
    
    # State representation:
    # We work with the "excluded" set E.
    # S (valid set) = {1..N} \ E
    # We want to minimize |E| (maximize |S|).
    # The constraint is on S: every sum a+b (a<=b in S) has count <= 2.
    
    # To make SA efficient, we maintain:
    # 1. `excluded`: a boolean array of size N+1, True if x is in E.
    # 2. `sum_counts`: array of size 2*N+1, counts of representations in S.
    #    sum_counts[s] = number of pairs (a,b) in S with a<=b and a+b=s.
    
    def init_state():
        """
        Initialize with a valid set to start SA from a reasonable place.
        We can start with a random valid set generated by a quick greedy pass,
        or just start with all excluded and add some, but starting valid 
        helps the penalty landscape be smooth initially.
        
        Actually, starting with a random subset of size ~400 and repairing 
        is slow. Let's start with a known valid structure: 
        A Sidon sequence (B2[1]) is a subset of B2[2].
        Greedy Sidon generation is fast.
        """
        S = []
        counts = {}
        # Greedy Sidon (B2[1])
        candidates = list(range(1, N + 1))
        random.shuffle(candidates)
        for x in candidates:
            can_add = True
            for y in S:
                s = x + y
                if counts.get(s, 0) >= 1:
                    can_add = False
                    break
            if can_add:
                s = 2 * x
                if counts.get(s, 0) >= 1:
                    can_add = False
            
            if can_add:
                S.append(x)
                for y in S[:-1]:
                    s = x + y
                    counts[s] = counts.get(s, 0) + 1
                counts[2 * x] = counts.get(s, 0) + 1
        
        # Convert to excluded representation
        excluded = np.zeros(N + 1, dtype=bool)
        for x in range(1, N + 1):
            if x not in set(S):
                excluded[x] = True
        
        # Compute sum_counts for this S
        sum_counts = np.zeros(2 * N + 1, dtype=np.int32)
        S_arr = np.array(S)
        # Efficiently compute counts for initial S
        # Since S is Sidon, counts are 0 or 1.
        for i in range(len(S_arr)):
            for j in range(i, len(S_arr)):
                s = S_arr[i] + S_arr[j]
                sum_counts[s] += 1
        
        return excluded, sum_counts

    def get_violation(sum_counts):
        """
        Calculate the penalty: sum of max(0, count - 2) for all sums.
        """
        excess = sum_counts > 2
        if np.any(excess):
            return np.sum(sum_counts[excess] - 2)
        return 0

    def get_score(excluded, sum_counts):
        """
        Score = -|E| - penalty.
        We want to maximize this (minimize |E| and penalty).
        """
        num_excluded = np.sum(excluded)
        penalty = get_violation(sum_counts)
        return -num_excluded - penalty

    def update_counts_on_add(x, sum_counts, excluded):
        """
        Add x to S (remove from E).
        Updates sum_counts.
        """
        # x was excluded, now included.
        # Pairs (x, y) for all y in S (y != x, y < x to avoid double count if we iterate carefully, 
        # but here we just add contributions of x with all other elements in S)
        # Elements in S are those where excluded[z] is False.
        # We need to add 1 to sum_counts[x+y] for all y in S, y < x.
        # And add 1 to sum_counts[2*x].
        
        # Iterate through all y < x that are in S
        # Optimization: Instead of iterating all y, we can just iterate 1..x-1 and check excluded.
        # But checking excluded is O(1).
        for y in range(1, x):
            if not excluded[y]: # y is in S
                sum_counts[x + y] += 1
        sum_counts[2 * x] += 1

    def update_counts_on_remove(x, sum_counts, excluded):
        """
        Remove x from S (add to E).
        """
        for y in range(1, x):
            if not excluded[y]: # y is in S
                sum_counts[x + y] -= 1
        sum_counts[2 * x] -= 1

    def simulate_annealing(excluded, sum_counts, time_limit):
        current_score = get_score(excluded, sum_counts)
        best_score = current_score
        best_excluded = excluded.copy()
        best_sum_counts = sum_counts.copy()
        
        # Annealing parameters
        # Start T high enough to allow violations, end T low.
        # Penalty can be large. Let's estimate max penalty.
        # Max pairs ~ 400*400/2 = 80k. Max sum count for a specific sum is small, 
        # but total excess could be large if we break many.
        # Let's use a dynamic T or a standard geometric decay.
        T_start = 50.0
        T_end = 0.1
        # Number of steps?
        # Each step is O(x) ~ O(N) for update. N=1000.
        # 1000 steps takes ~1s? No, Python loop 1000 is fast. 
        # 1000 * 10000 steps = 10M ops ~ 5-10s in Python.
        # We have ~100s. Let's do as many as possible.
        
        steps = 0
        # We will run until time limit
        while time.time() < time_limit:
            # Pick a random x to flip
            x = random.randint(1, N)
            
            # Calculate delta score
            # If excluded[x] is True, we are adding x to S.
            # If excluded[x] is False, we are removing x from S.
            
            if excluded[x]:
                # Action: Add x to S
                # Update counts
                update_counts_on_add(x, sum_counts, excluded)
                new_penalty = get_violation(sum_counts)
                new_num_excluded = np.sum(excluded) - 1 # One less excluded
                new_score = -new_num_excluded - new_penalty
                delta = new_score - current_score
                
                # Accept if delta > 0 or with prob exp(delta/T)
                if delta > 0 or random.random() < np.exp(delta / T_start):
                    # Accept
                    excluded[x] = False
                    current_score = new_score
                    if current_score > best_score:
                        best_score = current_score
                        best_excluded = excluded.copy()
                        best_sum_counts = sum_counts.copy()
                else:
                    # Reject, revert counts
                    update_counts_on_remove(x, sum_counts, excluded)
                    # Note: excluded[x] was already False in the trial, 
                    # but we didn't change the actual state variable `excluded` 
                    # until we accepted. 
                    # Wait, in the code above, I didn't flip `excluded[x]` before checking.
                    # Let's fix the logic flow.
                    
            else:
                # Action: Remove x from S
                update_counts_on_remove(x, sum_counts, excluded)
                new_penalty = get_violation(sum_counts)
                new_num_excluded = np.sum(excluded) + 1 # One more excluded
                new_score = -new_num_excluded - new_penalty
                delta = new_score - current_score
                
                if delta > 0 or random.random() < np.exp(delta / T_start):
                    # Accept
                    excluded[x] = True
                    current_score = new_score
                    if current_score > best_score:
                        best_score = current_score
                        best_excluded = excluded.copy()
                        best_sum_counts = sum_counts.copy()
                else:
                    # Reject, revert counts
                    update_counts_on_add(x, sum_counts, excluded)

            steps += 1
            
            # Decay temperature
            # Geometric decay based on steps
            # We want to reach T_end after some reasonable number of steps.
            # Let's say 50000 steps to reach T_end.
            # T = T_start * (T_end/T_start)^(steps/total_steps)
            # Or simpler: T = T_start * 0.9999^steps
            # Let's use a time-based decay to be safe.
            elapsed = time.time() - start_time
            total_time = 110.0
            # Fraction of time elapsed
            frac = elapsed / total_time
            # Exponential decay of T
            T_start_current = T_start
            T_end_current = T_end
            # T = T_end * (T_start/T_end)^(1-frac)
            T = T_end_current * (T_start_current / T_end_current) ** (1 - frac)
            
            # Prevent division by zero or overflow in exp
            if T < 1e-9:
                T = 1e-9
            
            # Re-check time before next loop
            if time.time() > deadline:
                break

        return best_excluded, best_sum_counts, best_score

    # Main Logic
    # We can run multiple SA restarts if time permits, 
    # but SA itself explores well. 
    # Let's do one long SA run, or a few shorter ones.
    # Given the "stagnation" warning, a single long SA run might get stuck.
    # Let's do 5 restarts, each with 1/5 of the time budget.
    
    best_final_score = -float('inf')
    best_final_excluded = None
    
    num_restarts = 5
    time_per_restart = (deadline - start_time) / num_restarts
    
    for i in range(num_restarts):
        if time.time() > deadline:
            break
            
        # Initialize
        excluded, sum_counts = init_state()
        
        # Run SA
        t_end_for_this_run = start_time + (i + 1) * time_per_restart
        # Add a small buffer
        t_end_for_this_run = min(t_end_for_this_run, deadline - 1.0)
        
        best_excl, best_sc, best_sc_val = simulate_annealing(excluded, sum_counts, t_end_for_this_run)
        
        if best_sc_val > best_final_score:
            best_final_score = best_sc_val
            best_final_excluded = best_excl
    
    # Convert best_excluded back to S
    if best_final_excluded is None:
        # Fallback: return empty or a simple valid set
        return list(range(1, N + 1)) # This is invalid, but shouldn't happen. 
        # Better fallback:
        S = []
        return S
        
    S = [x for x in range(1, N + 1) if not best_final_excluded[x]]
    
    # Final verification and cleanup (just in case)
    # The SA might end with a valid set (penalty 0) or invalid (penalty > 0).
    # We need to return a VALID set.
    # If penalty > 0, we must repair it.
    
    # Check if valid
    S_arr = np.array(S, dtype=np.int32)
    if len(S_arr) == 0:
        return []
        
    sums = S_arr[:, None] + S_arr[None, :]
    iu = np.triu_indices(len(S_arr))
    relevant_sums = sums[iu]
    _, counts = np.unique(relevant_sums, return_counts=True)
    
    if np.all(counts <= 2):
        return S
    else:
        # Repair: remove elements causing violations
        # Simple greedy repair
        S_list = list(S)
        S_set = set(S_list)
        
        # Re-compute counts dict for repair
        counts_dict = {}
        for i, x in enumerate(S_list):
            for y in S_list[i:]:
                s = x + y
                counts_dict[s] = counts_dict.get(s, 0) + 1
        
        while True:
            # Find a sum with count > 2
            bad_sum = None
            for s, c in counts_dict.items():
                if c > 2:
                    bad_sum = s
                    break
                    
            if bad_sum is None:
                break
                
            # Find an element to remove
            # We want to remove an element x such that x+y == bad_sum for some y in S
            # And x is involved in the excess.
            # Just pick the first element x in S such that there exists y in S (y>=x) with x+y=bad_sum
            # Actually, if we remove x, we remove all pairs involving x.
            # We need to ensure we don't remove too many.
            
            removed = False
            # Iterate through S to find a candidate
            # To be efficient, we can just pick a random element involved in bad_sum
            candidates_for_removal = []
            for x in S_list:
                y = bad_sum - x
                if y in S_set and y >= x:
                    candidates_for_removal.append(x)
            
            if not candidates_for_removal:
                # Should not happen if bad_sum is from S
                break
            
            x_to_remove = random.choice(candidates_for_removal)
            
            # Remove x_to_remove
            S_list.remove(x_to_remove)
            S_set.remove(x_to_remove)
            
            # Update counts
            for y in S_list:
                s = x_to_remove + y
                counts_dict[s] -= 1
                if counts_dict[s] == 0:
                    del counts_dict[s]
            s = 2 * x_to_remove
            counts_dict[s] -= 1
            if counts_dict[s] == 0:
                del counts_dict[s]
                
        return S_list

if __name__ == "__main__":
    res = construct()
    print(f"Size: {len(res)}")
