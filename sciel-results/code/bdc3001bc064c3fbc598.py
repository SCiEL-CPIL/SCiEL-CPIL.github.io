import numpy as np
import time

DIMENSIONS = [4, 4, 4]

def construct():
    start_time = time.time()
    deadline = start_time + 110  # 10s margin
    
    n, m, p = DIMENSIONS
    # n=4, m=4, p=4
    
    # We will build the rank 49 decomposition.
    # Rank 49 comes from 7 Strassen steps for 4x4 (as 2x2 blocks)
    # and 7 Strassen steps for each 2x2 block multiplication.
    
    # Helper: Get Strassen coefficients for 2x2 matrices
    # A = [[a11, a12], [a21, a22]]
    # B = [[b11, b12], [b21, b22]]
    # M1 = (a11+a22)(b11+b22)
    # M2 = (a21+a22)b11
    # M3 = a11(b12-b22)
    # M4 = a22(b21-b11)
    # M5 = (a11+a12)b22
    # M6 = (a21-a11)(b11+b12)
    # M7 = (a12-a22)(b21+b22)
    # C11 = M1 + M4 - M5 + M7
    # C12 = M3 + M5
    # C21 = M2 + M4
    # C22 = M1 - M2 + M3 + M6
    
    # We need to map these to the 4x4 indices.
    # Block 11 corresponds to i in [0,2), j in [0,2)
    # Block 12 corresponds to i in [0,2), j in [2,4)
    # Block 21 corresponds to i in [2,4), j in [0,2)
    # Block 22 corresponds to i in [2,4), j in [2,4)
    
    # The 49 terms will be generated by iterating s in 0..6 (outer) and t in 0..6 (inner).
    
    # U, V, W will be lists of dicts or sparse representations first.
    # U: dict (i,j) -> coeff
    # V: dict (j,k) -> coeff
    # W: dict (k,i) -> coeff
    
    U_list = []
    V_list = []
    W_list = []
    
    # Strassen inner coefficients (for 2x2)
    # Each term t has coeffs for a11, a12, a21, a22 and b11, b12, b21, b22
    # a_coeffs: [c11, c12, c21, c22]
    # b_coeffs: [d11, d12, d21, d22]
    
    inner_a = [
        [1, 0, 0, 1], # M1: a11+a22
        [0, 0, 1, 1], # M2: a21+a22
        [1, 0, 0, 0], # M3: a11
        [0, 0, 0, 1], # M4: a22
        [1, 1, 0, 0], # M5: a11+a12
        [0, 0, 1, -1], # M6: a21-a11
        [0, 1, 0, -1]  # M7: a12-a22
    ]
    inner_b = [
        [1, 0, 0, 1], # M1: b11+b22
        [1, 0, 0, 0], # M2: b11
        [0, 1, 0, -1], # M3: b12-b22
        [0, 0, 1, -1], # M4: b21-b11
        [0, 0, 0, 1], # M5: b22
        [1, 1, 0, 0], # M6: b11+b12
        [0, 0, 1, 1]  # M7: b21+b22
    ]
    
    # Outer Strassen steps (for 2x2 blocks)
    # Block indices: 0=11, 1=12, 2=21, 3=22
    # A_s is a 2x2 matrix of blocks.
    # We need to express A_s blocks as linear combos of A_ij.
    
    # Outer A coeffs: list of 7 matrices (2x2 of coeffs for blocks)
    # Block 0 (11), 1 (12), 2 (21), 3 (22)
    
    outer_a = [
        [[1, 0], [0, 1]], # M1: A11+A22 -> Blocks 0 and 3
        [[0, 0], [1, 1]], # M2: A21+A22 -> Blocks 2 and 3
        [[1, 0], [0, 0]], # M3: A11 -> Block 0
        [[0, 0], [0, 1]], # M4: A22 -> Block 3
        [[1, 1], [0, 0]], # M5: A11+A12 -> Blocks 0 and 1
        [[0, 0], [1, -1]], # M6: A21-A11 -> Blocks 2 and 0
        [[0, 1], [0, -1]]  # M7: A12-A22 -> Blocks 1 and 3
    ]
    
    outer_b = [
        [[1, 0], [0, 1]], # M1: B11+B22 -> Blocks 0 and 3
        [[1, 0], [0, 0]], # M2: B11 -> Block 0
        [[0, 1], [0, -1]], # M3: B12-B22 -> Blocks 1 and 3
        [[0, 0], [1, -1]], # M4: B21-B11 -> Blocks 2 and 0
        [[0, 0], [0, 1]], # M5: B22 -> Block 3
        [[1, 1], [0, 0]], # M6: B11+B12 -> Blocks 0 and 1
        [[0, 0], [1, 1]]  # M7: B21+B22 -> Blocks 2 and 3
    ]
    
    # C reconstruction
    # C11 = M1 + M4 - M5 + M7
    # C12 = M3 + M5
    # C21 = M2 + M4
    # C22 = M1 - M2 + M3 + M6
    
    # C_block_coeffs: 2x2 matrix of lists of (s, coeff)
    c_recon = [
        [[(0, 1), (3, 1), (4, -1), (6, 1)], [(2, 1), (4, 1)]],
        [[(1, 1), (3, 1)], [(0, 1), (1, -1), (2, 1), (5, 1)]]
    ]
    
    # Mapping block index to i,j ranges
    # Block 0: i 0-1, j 0-1
    # Block 1: i 0-1, j 2-3
    # Block 2: i 2-3, j 0-1
    # Block 3: i 2-3, j 2-3
    
    # We will generate 49 terms.
    # For each outer s, and inner t:
    # The term is P * Q.
    # P is linear combo of A_ij.
    # Q is linear combo of B_jk.
    # The result contributes to C_ki with weight from c_recon.
    
    # Wait, the inner Strassen computes M_st = P_st Q_st.
    # M_st is a 2x2 matrix (block).
    # The entries of M_st are linear combos of A_ij B_jk.
    # We need to add these to U, V, W.
    
    # For a specific s, t:
    # P_st = sum (inner_a[t][block_pos] * outer_a[s][block_pos]) A_ij?
    # No.
    # A_s is a 2x2 matrix of blocks.
    # A_s[block_r][block_c] is a 2x2 matrix of A_ij.
    # The inner Strassen operates on the 2x2 structure of A_s.
    # So inner_a[t][0] multiplies A_s[0][0], etc.
    
    # A_s[0][0] corresponds to Block 0 of A (if outer_a[s][0][0] is 1).
    # Block 0 of A contains A_00, A_01, A_10, A_11.
    
    # So for term (s,t):
    # u_coeffs[i,j] = sum over block_r, block_c of inner_a[t][block_r*2+block_c] * outer_a[s][block_r][block_c] * (coeff of A_ij in that block)
    # Actually, each block is a 2x2 matrix.
    # Let's just expand it.
    
    for s in range(7):
        for t in range(7):
            # Determine U, V, W contributions for this term
            U_dict = {}
            V_dict = {}
            W_dict = {}
            
            # Calculate coefficients for A_ij
            # A_s is 2x2 blocks.
            # Inner Strassen picks linear combos of the 4 blocks of A_s.
            # Let inner_a_t = [c00, c01, c10, c11]
            # A_s = [[B00, B01], [B10, B11]]
            # P = c00*B00 + c01*B01 + c10*B10 + c11*B11
            
            # B00 is outer_a[s][0][0] * Block0(A)
            # Block0(A) has A_00, A_01, A_10, A_11.
            
            for br in range(2):
                for bc in range(2):
                    coeff_block = inner_a[t][br*2+bc]
                    if coeff_block == 0: continue
                    outer_coeff = outer_a[s][br][bc]
                    if outer_coeff == 0: continue
                    total_coeff = coeff_block * outer_coeff
                    if total_coeff == 0: continue
                    
                    # Add to U_dict
                    # Block index = br*2+bc
                    # i range: br*2 to br*2+1
                    # j range: bc*2 to bc*2+1
                    for di in range(2):
                        for dj in range(2):
                            i = br*2 + di
                            j = bc*2 + dj
                            U_dict[(i,j)] = U_dict.get((i,j), 0) + total_coeff
            
            # Similarly for V_dict (B_jk)
            for br in range(2):
                for bc in range(2):
                    coeff_block = inner_b[t][br*2+bc]
                    if coeff_block == 0: continue
                    outer_coeff = outer_b[s][br][bc]
                    if outer_coeff == 0: continue
                    total_coeff = coeff_block * outer_coeff
                    if total_coeff == 0: continue
                    
                    # B_s blocks
                    # Block index = br*2+bc
                    # j range: br*2 to br*2+1 (Row of B block)
                    # k range: bc*2 to bc*2+1 (Col of B block)
                    for dj in range(2):
                        for dk in range(2):
                            j = br*2 + dj
                            k = bc*2 + dk
                            V_dict[(j,k)] = V_dict.get((j,k), 0) + total_coeff
            
            # Now W_dict
            # The result M_st is a 2x2 block matrix.
            # M_st[br][bc] is a 2x2 matrix of C_ki?
            # C is 4x4.
            # The outer Strassen reconstruction tells us how M_s blocks combine to form C blocks.
            # But M_st is the result of the inner Strassen step t for the outer step s.
            # The inner Strassen computes M_st = P_st Q_st.
            # The entries of M_st are linear combos of A_ij B_jk.
            # We need to map these to C_ki.
            
            # Inner Strassen C reconstruction:
            # C11 = M1 + M4 - M5 + M7
            # C12 = M3 + M5
            # C21 = M2 + M4
            # C22 = M1 - M2 + M3 + M6
            
            # This is for the 2x2 matrix M_st.
            # So M_st[0][0] (Block 0 of M_st) contributes to C with weight from inner_c_recon.
            
            inner_c_recon = [
                [[(0, 1), (3, 1), (4, -1), (6, 1)], [(2, 1), (4, 1)]],
                [[(1, 1), (3, 1)], [(0, 1), (1, -1), (2, 1), (5, 1)]]
            ]
            
            # M_st[br][bc] is a 2x2 matrix.
            # Its entries are C_ki for k,i in the block.
            
            for br in range(2):
                for bc in range(2):
                    # M_st[br][bc] is the (br,bc) block of the result of inner Strassen.
                    # We need to sum over the inner Strassen steps?
                    # No, t is fixed.
                    # M_st is just one term.
                    # The inner Strassen formula gives C = sum_t ...
                    # Wait, the inner Strassen is a decomposition.
                    # M_st is the t-th term in the inner decomposition.
                    # So we need to add the contribution of M_st to C.
                    
                    # The contribution of M_st[br][bc] to C_block[br][bc] is 1?
                    # No, the inner Strassen computes the product.
                    # The term M_st is added to the C blocks according to the inner_c_recon?
                    # No, M_st IS the product.
                    # The inner Strassen algorithm computes C_inner = sum_t L_t(M_t).
                    # So M_t contributes to C_inner.
                    # But here M_st is a term in the expansion of A_s B_s.
                    # A_s B_s = sum_t (P_t Q_t).
                    # So M_st = P_t Q_t.
                    # This M_st is the full 2x2 block matrix.
                    # So M_st[br][bc] is the (br,bc) block of the product.
                    # This block is a 2x2 matrix of C_ki.
                    
                    # So we just add 1 to W_dict for the corresponding k,i?
                    # No, we need to check if this term is valid.
                    # The term is P_t Q_t.
                    # P_t is linear in A. Q_t is linear in B.
                    # The product is bilinear.
                    # The coefficient of A_ij B_jk in M_st[br][bc][di][dk] is U[(i,j)] * V[(j,k)].
                    # And it contributes to C[k,i] with weight 1?
                    # Yes, because M_st is the product.
                    
                    # So for each (i,j) in U and (j,k) in V,
                    # the term contributes to C[k,i] with weight U[(i,j)] * V[(j,k)].
                    
                    # We can just set W_dict for the resulting k,i.
                    # But W_dict is for the rank-1 tensor.
                    # The rank-1 tensor is u v w.
                    # u = U_dict values.
                    # v = V_dict values.
                    # w = ?
                    # The product u v w should match the bilinear form.
                    # The bilinear form is sum_{i,j,k} U[i,j] V[j,k] W[k,i] A[i,j] B[j,k].
                    # Our term is sum_{i,j,k} U[i,j] V[j,k] A[i,j] B[j,k].
                    # So W[k,i] should be 1?
                    # But only for the k,i that are in the block br,bc?
                    # Yes, M_st[br][bc] is non-zero only for k,i in that block.
                    
                    for di in range(2):
                        for dk in range(2):
                            k = bc*2 + dk
                            i = br*2 + di
                            W_dict[(k,i)] = W_dict.get((k,i), 0) + 1
                    
            # Now we have U_dict, V_dict, W_dict for this term.
            # We need to add this to the global U, V, W.
            # But we also need to apply the OUTER Strassen reconstruction.
            # The outer Strassen computes C = sum_s L_s(M_s).
            # M_s = sum_t M_st.
            # So M_st contributes to C with weight L_s[br][bc]?
            # No, M_s is a 2x2 block matrix.
            # C_block[br][bc] = sum_s outer_c_recon[br][bc][s] * M_s[br][bc].
            # M_s[br][bc] = sum_t M_st[br][bc].
            # So M_st[br][bc] contributes to C_block[br][bc] with weight outer_c_recon[br][bc][s].
            
            # So we need to multiply W_dict by this weight.
            
            for (k,i), val in W_dict.items():
                # Find which block k,i belongs to
                br = k // 2
                bc = i // 2
                weight = 0
                for (s_idx, c) in c_recon[br][bc]:
                    if s_idx == s:
                        weight += c
                if weight != 0:
                    W_dict[(k,i)] = val * weight
                else:
                    W_dict[(k,i)] = 0
            
            # Convert dicts to lists
            U_list.append(U_dict)
            V_list.append(V_dict)
            W_list.append(W_dict)
            
            if time.time() > deadline:
                break
        if time.time() > deadline:
            break
            
    # Now construct the matrices
    rank = len(U_list)
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    for r in range(rank):
        for (i,j), val in U_list[r].items():
            if val != 0:
                U[i*m + j][r] = val
        for (j,k), val in V_list[r].items():
            if val != 0:
                V[j*p + k][r] = val
        for (k,i), val in W_list[r].items():
            if val != 0:
                W[k*n + i][r] = val
                
    return {"U": U, "V": V, "W": W}
