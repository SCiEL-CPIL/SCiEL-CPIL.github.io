import numpy as np

DIMENSIONS = [2, 3, 7]

def construct():
    n, m, p = DIMENSIONS
    rank = 39
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    col = 0
    
    def add_term(u_vec, v_vec, w_vec):
        nonlocal col
        for i in range(len(u_vec)):
            if u_vec[i] != 0:
                U[i][col] += u_vec[i]
        for j in range(len(v_vec)):
            if v_vec[j] != 0:
                V[j][col] += v_vec[j]
        for k in range(len(w_vec)):
            if w_vec[k] != 0:
                W[k][col] += w_vec[k]
        col += 1

    # Indices
    # A: 0:00, 1:01, 2:02, 3:10, 4:11, 5:12
    # B: 0:00, 1:01, 2:02, 3:03, 4:04, 5:05, 6:06
    #    7:10, 8:11, 9:12, 10:13, 11:14, 12:15, 13:16
    #    14:20, 15:21, 16:22, 17:23, 18:24, 19:25, 20:26
    # C: 0:00, 1:01, 2:02, 3:03, 4:04, 5:05, 6:06
    #    7:10, 8:11, 9:12, 10:13, 11:14, 12:15, 13:16

    # Part 1: A1 B1 (j=0)
    # A1: A[0] (idx 0), A[3] (idx 3)
    # B1: B[k] (idx k)
    # C: C[k] (idx k), C[7+k] (idx 7+k)
    for k in range(7):
        # C[k] += A[0] B[k]
        u = [0]*6; u[0] = 1
        v = [0]*21; v[k] = 1
        w = [0]*14; w[k] = 1
        add_term(u, v, w)
        
        # C[7+k] += A[3] B[k]
        u = [0]*6; u[3] = 1
        v = [0]*21; v[k] = 1
        w = [0]*14; w[7+k] = 1
        add_term(u, v, w)

    # Part 2: A2 B2 (j=1,2)
    # A2: A[1] (1), A[2] (2), A[4] (4), A[5] (5)
    # B2: B[7..13] (1st row), B[14..20] (2nd row)
    
    # Sub-part 2a: k=0,1 (Strassen)
    # A11=1, A12=2, A21=4, A22=5
    # B11=7, B12=8, B21=14, B22=15
    # C11=0, C12=1, C21=7, C22=8
    
    # Strassen Terms
    # M1 = (A11+A22)(B11+B22)
    u = [0]*6; u[1]=1; u[5]=1
    v = [0]*21; v[7]=1; v[15]=1
    w = [0]*14; w[0]=1; w[8]=1
    add_term(u, v, w)
    
    # M2 = (A21+A22)B11
    u = [0]*6; u[4]=1; u[5]=1
    v = [0]*21; v[7]=1
    w = [0]*14; w[7]=1; w[8]=1
    add_term(u, v, w)
    
    # M3 = A11(B12-B22)
    u = [0]*6; u[1]=1
    v = [0]*21; v[8]=1; v[15]=-1
    w = [0]*14; w[1]=1; w[8]=1
    add_term(u, v, w)
    
    # M4 = A22(B21-B11)
    u = [0]*6; u[5]=1
    v = [0]*21; v[14]=1; v[7]=-1
    w = [0]*14; w[0]=-1; w[7]=1
    add_term(u, v, w)
    
    # M5 = (A11+A12)B22
    u = [0]*6; u[1]=1; u[2]=1
    v = [0]*21; v[15]=1
    w = [0]*14; w[0]=1; w[8]=-1
    add_term(u, v, w)
    
    # M6 = (A21-A11)(B11+B12)
    u = [0]*6; u[4]=1; u[1]=-1
    v = [0]*21; v[7]=1; v[8]=1
    w = [0]*14; w[8]=1
    add_term(u, v, w)
    
    # M7 = (A12-A22)(B21+B22)
    u = [0]*6; u[2]=1; u[5]=-1
    v = [0]*21; v[14]=1; v[15]=1
    w = [0]*14; w[1]=1; w[0]=-1
    add_term(u, v, w)

    # Sub-part 2b: k=2 (Schoolbook 2x2x1)
    # C[2] = A[1]B[9] + A[2]B[16]
    # C[9] = A[4]B[9] + A[5]B[16]
    
    u = [0]*6; u[1]=1
    v = [0]*21; v[9]=1
    w = [0]*14; w[2]=1
    add_term(u, v, w)
    
    u = [0]*6; u[2]=1
    v = [0]*21; v[16]=1
    w = [0]*14; w[2]=1
    add_term(u, v, w)
    
    u = [0]*6; u[4]=1
    v = [0]*21; v[9]=1
    w = [0]*14; w[9]=1
    add_term(u, v, w)
    
    u = [0]*6; u[5]=1
    v = [0]*21; v[16]=1
    w = [0]*14; w[9]=1
    add_term(u, v, w)

    # Sub-part 2c: k=3,4 (Strassen)
    # B11=10, B12=11, B21=17, B22=18
    # C11=3, C12=4, C21=10, C22=11
    
    # M1
    u = [0]*6; u[1]=1; u[5]=1
    v = [0]*21; v[10]=1; v[18]=1
    w = [0]*14; w[3]=1; w[11]=1
    add_term(u, v, w)
    # M2
    u = [0]*6; u[4]=1; u[5]=1
    v = [0]*21; v[10]=1
    w = [0]*14; w[10]=1; w[11]=1
    add_term(u, v, w)
    # M3
    u = [0]*6; u[1]=1
    v = [0]*21; v[11]=1; v[18]=-1
    w = [0]*14; w[4]=1; w[11]=1
    add_term(u, v, w)
    # M4
    u = [0]*6; u[5]=1
    v = [0]*21; v[17]=1; v[10]=-1
    w = [0]*14; w[3]=-1; w[10]=1
    add_term(u, v, w)
    # M5
    u = [0]*6; u[1]=1; u[2]=1
    v = [0]*21; v[18]=1
    w = [0]*14; w[3]=1; w[11]=-1
    add_term(u, v, w)
    # M6
    u = [0]*6; u[4]=1; u[1]=-1
    v = [0]*21; v[10]=1; v[11]=1
    w = [0]*14; w[11]=1
    add_term(u, v, w)
    # M7
    u = [0]*6; u[2]=1; u[5]=-1
    v = [0]*21; v[17]=1; v[18]=1
    w = [0]*14; w[4]=1; w[3]=-1
    add_term(u, v, w)

    # Sub-part 2d: k=5,6 (Strassen)
    # B11=12, B12=13, B21=19, B22=20
    # C11=5, C12=6, C21=12, C22=13
    
    # M1
    u = [0]*6; u[1]=1; u[5]=1
    v = [0]*21; v[12]=1; v[20]=1
    w = [0]*14; w[5]=1; w[13]=1
    add_term(u, v, w)
    # M2
    u = [0]*6; u[4]=1; u[5]=1
    v = [0]*21; v[12]=1
    w = [0]*14; w[12]=1; w[13]=1
    add_term(u, v, w)
    # M3
    u = [0]*6; u[1]=1
    v = [0]*21; v[13]=1; v[20]=-1
    w = [0]*14; w[6]=1; w[13]=1
    add_term(u, v, w)
    # M4
    u = [0]*6; u[5]=1
    v = [0]*21; v[19]=1; v[12]=-1
    w = [0]*14; w[5]=-1; w[12]=1
    add_term(u, v, w)
    # M5
    u = [0]*6; u[1]=1; u[2]=1
    v = [0]*21; v[20]=1
    w = [0]*14; w[5]=1; w[13]=-1
    add_term(u, v, w)
    # M6
    u = [0]*6; u[4]=1; u[1]=-1
    v = [0]*21; v[12]=1; v[13]=1
    w = [0]*14; w[13]=1
    add_term(u, v, w)
    # M7
    u = [0]*6; u[2]=1; u[5]=-1
    v = [0]*21; v[19]=1; v[20]=1
    w = [0]*14; w[6]=1; w[5]=-1
    add_term(u, v, w)

    return {"U": U, "V": V, "W": W}
