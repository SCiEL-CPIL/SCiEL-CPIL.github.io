import time
import numpy as np
from math import isqrt
from collections import defaultdict

def construct():
    start_time = time.time()
    deadline = start_time + 140  # 10s buffer for 150s limit

    # Target limit for powerful numbers
    # We want N up to 10^18, so a+b=N.
    # If we generate powerfuls up to L, we can check sums up to 2*L.
    # To maximize chance, we want L as large as possible within time.
    # The number of powerful numbers up to X is approx C * X^(1/3).
    # For L=10^9, N~1.4 million. Pairs ~ 10^12 (too many for naive).
    # For L=10^8, N~46k. Pairs ~ 10^9 (still high).
    # Strategy: Generate powerfuls up to L.
    # Then use a heuristic search for N?
    # No, we need to maximize the count.
    # Let's try L=10^8 first.
    
    L = 10**8
    
    # 1. Generate powerful numbers up to L
    # Powerful numbers are of the form a^2 * b^3 where b is squarefree?
    # No, simply: a number n is powerful if for every prime p|n, p^2|n.
    # This is equivalent to n = x^2 * y^3 where y is squarefree? 
    # Actually, any powerful number can be uniquely written as a^2 * b^3 with b squarefree?
    # Let's just enumerate x^2 * y^3 <= L.
    # y must be squarefree? No, if y has a square factor, it can be absorbed into x.
    # To ensure uniqueness (or at least cover all), we can just iterate y and x.
    # To avoid duplicates, we can enforce that y is squarefree.
    
    # Let's generate all powerfuls <= L.
    # Method:
    # for y in range(1, L^(1/3)+1):
    #   if y is not squarefree, skip? No, simpler:
    #   Just generate a^2 * b^3 <= L.
    #   If we allow any b, we get duplicates.
    #   E.g. 1^2 * 2^3 = 8. 2^2 * 1^3 = 4. 1^2 * 4^3 = 64.
    #   8 is 8. 4 is 4.
    #   64 is 64.
    #   Is 64 generated by another pair?
    #   a=8, b=1 -> 64*1 = 64.
    #   a=2, b=2 -> 4*8 = 32.
    #   Let's just use a set.
    
    powerfuls = set()
    max_b = int(L ** (1/3)) + 1
    for b in range(1, max_b + 1):
        b3 = b ** 3
        if b3 > L:
            break
        max_a = isqrt(L // b3)
        for a in range(1, max_a + 1):
            n = a * a * b3
            if n <= L:
                powerfuls.add(n)
    
    P = np.array(sorted(powerfuls), dtype=np.int64)
    P_len = len(P)
    
    # 2. Find N with max representations
    # We need to count pairs (a, b) from P such that a+b=N.
    # Since P_len is ~50k for L=1e8, O(P^2) is 2.5e9 operations.
    # This is too slow in pure Python, but maybe doable in NumPy?
    # We can do it in chunks to avoid memory explosion.
    
    # Alternative:
    # Since we want to maximize the count, we can sample or use a smarter method?
    # No, we need the maximum.
    # Let's use a dictionary for sums.
    # But building a dict of size 2*L (2e8) might be memory heavy but doable?
    # Keys are ints, values are counts.
    # Number of entries in dict is at most P_len * (avg pairs) ... no, it's the number of distinct sums.
    # Distinct sums <= 2*L.
    
    # Let's try to vectorize the pair counting using a sparse approach or chunks.
    # We can iterate over i in range(P_len):
    #   sums = P[i:] + P[i]
    #   This creates an array of size P_len-i.
    #   Total operations ~ P_len^2 / 2.
    #   With P_len=50k, that's 1.25e9 additions.
    #   NumPy can do ~1e8 to 1e9 additions per second depending on overhead.
    #   This might take 1-10 seconds per full pass if vectorized well?
    #   Actually, creating the array `P[i:] + P[i]` allocates memory.
    #   We can use `np.add(P[i], P[i:])` which returns an array.
    #   Then we need to count unique sums? No, we need to accumulate counts.
    #   `np.bincount` on the sums would be efficient.
    #   `counts = np.bincount(sums, minlength=2*L+1)`
    #   Then `total_counts += counts`
    #   But `total_counts` is an array of size 2*L+1 (2e8 ints).
    #   That's 1.6 GB of memory (int64). This might be too much.
    #   
    #   Let's check memory limits. Usually 2GB is the limit.
    #   If L=1e8, 2*L = 2e8. int64 is 8 bytes. 1.6 GB.
    #   Plus the temporary array for sums (P_len size, 50k * 8 = 400KB).
    #   Plus P itself.
    #   So ~1.7 GB. Risky but possible.
    #   
    #   If L=1e7, 2*L = 2e7. 160 MB. Safe.
    #   Current program used L=1e7 and scored 4.06.
    #   If we increase L to 1e8, we might find a better N.
    #   
    #   Let's try L=1e8 with careful memory management.
    #   If memory fails, we fall back to L=1e7.
    
    # To be safe, let's start with L=10**8.
    # If memory error, we catch it and retry with smaller L?
    # Or just stick to L=10**7?
    # The insight says L=1e8 improved score to 5.93.
    # So L=1e8 is good.
    
    # Let's implement the counting.
    
    max_sum = 2 * L
    # Use int32 if possible? Counts are likely small.
    # Max count for any N is bounded by P_len.
    # P_len ~ 50,000. int32 is fine.
    
    try:
        total_counts = np.zeros(max_sum + 1, dtype=np.int32)
        
        # Iterate over i
        # To speed up, we can skip i where P[i] > max_sum? No, P[i] <= L.
        # We need a+b <= max_sum.
        
        for i in range(P_len):
            a = P[i]
            # b must be >= a
            # Sums = a + P[j] for j >= i
            # We want sums <= max_sum
            # P[j] <= max_sum - a
            # Since P is sorted, we can find the last index j_max
            # But P[j] <= L, and max_sum = 2L.
            # So a + P[j] <= L + L = 2L = max_sum.
            # So all pairs (i, j) with j>=i are valid sums <= max_sum.
            
            # sums = a + P[i:]
            # This allocates an array.
            sums = a + P[i:]
            
            # bincount
            # minlength must be max_sum+1
            # This is the bottleneck: bincount on an array of size P_len-i
            # and accumulating into an array of size max_sum+1.
            
            # Optimization:
            # Instead of bincount every time, can we do better?
            # No, bincount is O(N + K) where N is len(sums), K is minlength.
            # Here K is constant (2L).
            # So total time is O(sum (P_len-i) + P_len * 2L) ?
            # No, bincount is O(N) if we don't zero the array every time?
            # `np.bincount` returns a new array.
            # We do `total_counts += np.bincount(sums, minlength=max_sum+1)`
            # This creates a new array of size max_sum+1 each time?
            # No, `np.bincount` creates the array.
            # So we are creating an array of size 2L (2e8) P_len (5e4) times?
            # That's 10^13 operations just for allocation/zeroing. Too slow.
            
            # We need a different approach.
            
            # Approach:
            # We can't afford to touch the full 2L array P_len times.
            # We should only update the relevant indices.
            # But `total_counts[sums] += 1` is vectorized and only touches len(sums) elements.
            # This is O(N) per iteration.
            # Total O(P_len^2).
            
            # Let's use `np.add.at` or just `total_counts[sums] += 1`.
            # `total_counts[sums] += 1` works with advanced indexing?
            # Yes, but it's not strictly atomic (doesn't matter here, single thread).
            # However, if `sums` has duplicates, `total_counts[sums] += 1` will only add 1 once per index?
            # NO. `arr[idx] += 1` with repeated idx in idx does NOT accumulate.
            # `arr[[1,1]] += 1` results in arr[1] being incremented by 1, not 2.
            # We need `np.add.at(total_counts, sums, 1)`.
            
            np.add.at(total_counts, sums, 1)
            
            if time.time() > deadline - 20:
                break
    
    except MemoryError:
        # Fallback to smaller L
        L = 10**7
        powerfuls = set()
        max_b = int(L ** (1/3)) + 1
        for b in range(1, max_b + 1):
            b3 = b ** 3
            if b3 > L:
                break
            max_a = isqrt(L // b3)
            for a in range(1, max_a + 1):
                n = a * a * b3
                if n <= L:
                    powerfuls.add(n)
        P = np.array(sorted(powerfuls), dtype=np.int64)
        P_len = len(P)
        max_sum = 2 * L
        total_counts = np.zeros(max_sum + 1, dtype=np.int32)
        
        for i in range(P_len):
            a = P[i]
            sums = a + P[i:]
            np.add.at(total_counts, sums, 1)
            if time.time() > deadline - 20:
                break

    # Find best N
    # total_counts is an array of counts for sums 0..max_sum.
    # We want the max count.
    # Note: We only counted pairs a<=b.
    # The problem asks for distinct pairs a<=b.
    # So the count in total_counts is exactly the number of valid pairs.
    
    # Find the index with the max count.
    # We should probably exclude N=0,1?
    # N >= 2.
    # Also, powerfuls include 1.
    # 1 is powerful.
    
    # Get the best sum
    # We want to maximize the score.
    best_count = np.max(total_counts[2:])  # N >= 2
    best_N = np.argmax(total_counts[2:]) + 2
    
    # If best_count is 0, something went wrong.
    if best_count == 0:
        return {'N': 2, 'pairs': [[1, 1]]}
        
    # Generate pairs for best_N
    # We need to list the pairs [a, b] such that a+b=best_N, a<=b, a,b powerful.
    # We can iterate through P and check if best_N - a is in P and >= a.
    
    powerful_set = set(P.tolist())
    pairs = []
    for a in P:
        if a > best_N // 2:
            break
        b = best_N - a
        if b in powerful_set:
            pairs.append([a, b])
            
    # Sort pairs (they are already sorted by a, since P is sorted)
    pairs.sort()
    
    return {'N': int(best_N), 'pairs': pairs}
