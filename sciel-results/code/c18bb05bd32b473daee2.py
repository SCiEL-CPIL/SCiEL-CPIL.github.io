"""
Photonic crystal unit cell design for large TM 4-5 band gap.
Strategy: Parametric Fourier series representation of the dielectric profile.
We represent the continuous dielectric function epsilon(r) as a truncated 2D Fourier series:
epsilon(x, y) = sum_{h,k} C_{h,k} exp(i 2 pi (h x + k y))
Truncated to |h| + |k| <= 3.
We optimize the real and imaginary parts of the coefficients C_{h,k} (subject to symmetry)
to maximize the band gap. The binary pixel map is generated by thresholding this profile.
"""

import time
import math
import random
import numpy as np
from scipy.optimize import minimize

