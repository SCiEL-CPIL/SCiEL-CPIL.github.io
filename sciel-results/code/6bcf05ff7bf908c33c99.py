import time

def construct():
    """
    Constructs the Steiner system S(5,6,12) using the cyclic construction 
    of the S(4,5,11) on points 1..11, extended with point 0.
    
    The S(4,5,11) is generated by 6 base blocks under cyclic shifts mod 11.
    The S(5,6,12) consists of:
    1. Blocks containing 0: {0} U B, where B is a block of S(4,5,11).
    2. Blocks not containing 0: B^c, where B is a block of S(4,5,11) (complement in 1..11).
    """
    
    # Base blocks for S(4,5,11) on Z_11
    # These are standard base blocks for the Witt design W_11
    base_blocks = [
        [0, 1, 3, 4, 5],
        [0, 1, 2, 6, 8],
        [0, 1, 2, 7, 9],
        [0, 1, 3, 7, 10],
        [0, 2, 3, 6, 9],
        [0, 2, 4, 5, 8]
    ]
    
    # Generate all 66 blocks of S(4,5,11) on points 0..10 (which map to 1..11 in final)
    # We will use points 1..11 for the S(4,5,11) part to match the task's 0..11 range
    # where 0 is the special point.
    
    blocks_4511 = []
    for b in base_blocks:
        for shift in range(11):
            # Apply cyclic shift mod 11, then map to 1..11
            # Original points are 0..10. Shifted points are (x+shift)%11.
            # Map to 1..11: y = (x+shift)%11 + 1
            shifted_block = sorted([(x + shift) % 11 + 1 for x in b])
            blocks_4511.append(shifted_block)
    
    # Now construct S(5,6,12) on 0..11
    final_blocks = []
    
    # 1. Blocks containing 0
    for b in blocks_4511:
        final_blocks.append([0] + b)
        
    # 2. Blocks not containing 0 (complements in 1..11)
    for b in blocks_4511:
        b_set = set(b)
        # Points are 1..11
        comp = [p for p in range(1, 12) if p not in b_set]
        # The complement should have size 6
        final_blocks.append(comp)
        
    # Optional: Verify validity and count
    # The task asks for a list of distinct 6-subsets.
    # We should ensure no duplicates (though the construction guarantees distinctness 
    # if the base blocks are distinct and shifts don't overlap in a way that creates duplicates, 
    # which they don't for a Steiner system).
    
    # Convert to lists of ints for return
    return final_blocks
