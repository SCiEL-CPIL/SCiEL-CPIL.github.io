import time
import random
from itertools import permutations

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 110  # 110s safety margin

    # The seed program uses LUW construction which yields very large graphs for k=5, g=9.
    # We attempt to find a smaller 5-regular graph of girth >= 9 (i.e., >= 10 for bipartite)
    # by searching over Cayley graphs of small non-abelian groups.
    
    # Target: 5-regular.
    # We need a group G and a set S of 5 generators such that S = S^-1 and 1 not in S.
    # For 5-regular, S must contain 2 pairs {a, a^-1}, {b, b^-1} and one involution c (c=c^-1).
    
    def get_cayley_graph_generators(group_elements, identity, group_op, group_inv, num_generators=5, trials=100):
        """
        Searches for a set of generators for the Cayley graph.
        Returns (generators, group_elements) or None.
        """
        # This is a simplified search. We assume the group is provided as a list of elements.
        # We need to pick 2 non-involutions (and their inverses) and 1 involution.
        
        involutions = []
        non_involutions = []
        
        for g_elem in group_elements:
            if g_elem == identity:
                continue
            inv_g = group_inv(g_elem)
            if g_elem == inv_g:
                involutions.append(g_elem)
            else:
                non_involutions.append(g_elem)
        
        if len(involutions) < 1 or len(non_involutions) < 2:
            return None

        for _ in range(trials):
            # Pick 1 involution
            c = random.choice(involutions)
            # Pick 2 distinct non-involutions a, b such that a != b, a != b^-1, etc.
            # We need {a, a^-1, b, b^-1, c} to be distinct.
            a = random.choice(non_involutions)
            a_inv = group_inv(a)
            
            # Ensure b is not a, a_inv, c, c_inv (c=c_inv)
            valid_b_candidates = [x for x in non_involutions if x != a and x != a_inv and x != c and group_inv(x) != c]
            if not valid_b_candidates:
                continue
            b = random.choice(valid_b_candidates)
            b_inv = group_inv(b)
            
            S = {a, a_inv, b, b_inv, c}
            if len(S) != 5:
                continue
            
            # Check if this S generates the group? 
            # For girth, we don't strictly need it to generate the whole group, 
            # but we want a connected component. 
            # The task asks for a graph on n vertices. 
            # If the Cayley graph is disconnected, we return the component.
            # We want the component to have girth >= g.
            
            # Build the component from identity
            visited = {identity}
            queue = [identity]
            edges = []
            adj = {identity: []}
            
            while queue:
                u = queue.pop(0)
                for s in S:
                    v = group_op(u, s)
                    if v not in visited:
                        visited.add(v)
                        queue.append(v)
                        adj[v] = []
                    # Add edge u-v
                    edges.append((u, v))
                    adj[u].append(v)
                    adj[v].append(u)
            
            # Check girth
            n = len(visited)
            if n < 10: # Too small to have girth 9?
                continue
                
            if check_girth(adj, n, g):
                # Remap vertices to 0..n-1
                mapping = {v: i for i, v in enumerate(visited)}
                remapped_edges = [(mapping[u], mapping[v]) for u, v in edges]
                # Remove duplicate edges? 
                # The construction adds u->v for each s. 
                # If s1 and s2 lead to same v, we have duplicate edges.
                # Simple graph required.
                unique_edges = set()
                for u, v in remapped_edges:
                    if u == v:
                        continue
                    if (u, v) not in unique_edges and (v, u) not in unique_edges:
                        unique_edges.add((u, v))
                
                # Check degree
                deg = [0] * n
                for u, v in unique_edges:
                    deg[u] += 1
                    deg[v] += 1
                if all(d == k for d in deg):
                    return n, list(unique_edges)
            
        return None

    def check_girth(adj, n, target_girth):
        # BFS from each vertex
        # Since we expect bipartite (if group is bipartite? No, Cayley graph is bipartite iff S contains no odd length cycles? 
        # Actually, Cayley graph is bipartite iff the group is generated by S and there is no odd length cycle.
        # For 5-regular, if S has an involution, there might be 2-cycles? No, simple graph.
        # We just check for cycles < target_girth.
        
        max_depth = (target_girth - 1) // 2
        # For target 9, we check for cycles of length < 9.
        # Bipartite graphs have even girth. So we check for 2, 4, 6, 8.
        # If we find any, girth < 9.
        
        for start_node in range(n):
            # BFS
            visited = {start_node: (None, 0)}
            queue = [(start_node, None, 0)]
            while queue:
                node, parent, depth = queue.pop(0)
                if depth == max_depth:
                    continue
                for neighbor in adj[node]:
                    if neighbor == parent:
                        continue
                    if neighbor in visited:
                        # Cycle found
                        # Length = depth + 1 + visited[neighbor][1]
                        # This is a lower bound? 
                        # Actually, if we find a back edge, the cycle length is depth + 1 + dist(neighbor, start) 
                        # ONLY IF the path to neighbor is disjoint from path to node except start.
                        # In a tree, it is. In a graph, it might merge earlier.
                        # If they merge earlier, the cycle is shorter.
                        # So if depth + 1 + visited[neighbor][1] < target_girth, we definitely have a short cycle.
                        if depth + 1 + visited[neighbor][1] < target_girth:
                            return False
                    else:
                        visited[neighbor] = (node, depth + 1)
                        queue.append((neighbor, node, depth + 1))
        return True

    # Define A7 group
    # Elements are permutations of 0..6
    # Identity
    identity = tuple(range(7))
    
    def perm_mul(p, q):
        return tuple(p[q[i]] for i in range(7))
    
    def perm_inv(p):
        inv = [0] * 7
        for i, pi in enumerate(p):
            inv[pi] = i
        return tuple(inv)
    
    # Generate all elements of A7? 
    # A7 has 2520 elements. 
    # We can generate them by BFS from identity using generators.
    # Generators for A7: 
    # (0 1 2) and (0 1 2 3 4 5 6)? 
    # Actually, A_n is generated by 3-cycles.
    gen_3c = (1, 2, 0, 3, 4, 5, 6) # (0 1 2)
    gen_3c2 = (1, 0, 2, 3, 4, 5, 6) # (0 1) ? No, (0 1) is odd.
    # A7 is generated by (0 1 2) and (0 1 2 3 4 5 6)? No, 7-cycle is even.
    # Let's use (0 1 2) and (0 1 2 3 4 5 6).
    
    # Actually, just use a known generating set for A7.
    # A7 is generated by (0 1 2) and (0 1 2 3 4 5 6).
    g1 = (1, 2, 0, 3, 4, 5, 6)
    g2 = (1, 2, 3, 4, 5, 6, 0)
    
    elements = [identity]
    index = {identity: 0}
    for i in range(len(elements)):
        e = elements[i]
        for g in [g1, g2, perm_inv(g1), perm_inv(g2)]:
            ne = perm_mul(e, g)
            if ne not in index:
                index[ne] = len(elements)
                elements.append(ne)
    
    # Verify size
    if len(elements) != 2520:
        # Fallback to seed if group generation fails or is wrong
        pass
    else:
        # Search for good generators
        result = get_cayley_graph_generators(elements, identity, perm_mul, perm_inv, trials=50)
        if result:
            return result
    
    # Fallback to Seed Logic (LUW)
    q = k
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index_luw, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index_luw:
                index_luw[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index_luw[vertex], index_luw[other]))
    return len(order), edges
