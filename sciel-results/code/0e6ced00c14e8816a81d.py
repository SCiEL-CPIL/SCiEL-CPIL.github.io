import numpy as np
import time

def sign_edges(graph, budget):
    start_time = time.time()
    deadline = start_time + 55  # Safety margin for 60s limit
    
    n = graph['n']
    edges = graph['edges']
    m = n // 2
    num_edges = len(edges)
    
    # Identify edge types: top cycle, bottom cycle, matching
    top_cycle_edges = []
    bottom_cycle_edges = []
    matching_edges = []
    
    for i, (u, v) in enumerate(edges):
        if u < m and v < m:
            top_cycle_edges.append(i)
        elif u >= m and v >= m:
            bottom_cycle_edges.append(i)
        else:
            matching_edges.append(i)
    
    # Build signed adjacency matrix quickly
    def build_signed_adj(signs):
        A = np.zeros((n, n), dtype=float)
        for i, (u, v) in enumerate(edges):
            s = float(signs[i])
            A[u, v] = s
            A[v, u] = s
        return A
    
    def spectral_radius(signs):
        A = build_signed_adj(signs)
        eigvals = np.linalg.eigvalsh(A)
        return np.max(np.abs(eigvals))
    
    # Fast connectivity check using cycle parity
    # The lift is disconnected iff all cycles have even number of -1 edges
    # Fundamental cycles: top cycle, bottom cycle, and for each matching edge, 
    # a cycle going through that matching edge and parts of both cycles
    # Actually, simpler: the lift is connected iff the sign assignment is not 
    # a "coboundary" - i.e., not all cycles are balanced.
    # For a prism graph, the cycle space is generated by: top cycle, bottom cycle,
    # and one "ladder" cycle (going around one side of the prism).
    # The lift is disconnected iff:
    #   product of signs on top cycle = +1
    #   product of signs on bottom cycle = +1  
    #   product of signs on any one "rung" cycle = +1
    # where a rung cycle goes: i -> i+1 (top) -> i+1+m (matching) -> i+m (bottom) -> i (matching)
    
    def is_connected_fast(signs):
        # Check top cycle product
        top_prod = 1
        for idx in top_cycle_edges:
            top_prod *= signs[idx]
        
        # Check bottom cycle product
        bottom_prod = 1
        for idx in bottom_cycle_edges:
            bottom_prod *= signs[idx]
        
        # Check one rung cycle (use first matching edge)
        if not matching_edges:
            return True
        # Rung cycle: matching edge 0, then follow top and bottom
        # Actually, let's just check if top_prod * bottom_prod * (product of all matching) gives info
        # Simpler: the lift is connected iff NOT (top_prod == 1 AND bottom_prod == 1 AND 
        # for some specific cycle the product is 1)
        # Most robust: check if there's any cycle with product -1
        # The cycle space dimension is E - V + 1 = 3m - 2m + 1 = m + 1
        # But we can just check: is the sign vector in the cut space?
        # A sign assignment is balanced (disconnected lift) iff it's a coboundary,
        # i.e., there exist vertex potentials s_v in {+1,-1} such that sign(u,v) = s_u * s_v
        # for all edges. This is equivalent to: for every cycle, product of signs = +1.
        
        # Efficient check: try to assign vertex potentials
        # Start with potential[0] = +1, propagate
        potential = [None] * n
        potential[0] = 1
        stack = [0]
        while stack:
            u = stack.pop()
            for v, _ in adj[u]:
                edge_idx = edge_to_idx[(u, v)]
                expected = potential[u] * signs[edge_idx]
                if potential[v] is None:
                    potential[v] = expected
                    stack.append(v)
                elif potential[v] != expected:
                    return True  # Inconsistent, so not a coboundary, lift is connected
        return False  # Consistent, so it IS a coboundary, lift is disconnected
    
    # Build adjacency list and edge index lookup
    adj = [[] for _ in range(n)]
    edge_to_idx = {}
    for i, (u, v) in enumerate(edges):
        adj[u].append((v, i))
        adj[v].append((u, i))
        edge_to_idx[(u, v)] = i
        edge_to_idx[(v, u)] = i
    
    rng = np.random.default_rng(3)
    
    best_signs = None
    best_radius = float('inf')
    
    # Multiple initializations
    for init in range(50):
        if time.time() > deadline:
            break
        
        # Different initialization strategies
        if init == 0:
            # All +1 except one matching edge
            signs = np.ones(num_edges, dtype=int)
            signs[matching_edges[0]] = -1
        elif init == 1:
            # All +1 except one top edge
            signs = np.ones(num_edges, dtype=int)
            signs[top_cycle_edges[0]] = -1
        elif init == 2:
            # Random with at least one -1
            signs = np.ones(num_edges, dtype=int)
            signs[rng.integers(0, num_edges)] = -1
        else:
            # Random pattern
            signs = rng.choice([-1, 1], size=num_edges)
        
        if not is_connected_fast(signs):
            continue
        
        radius = spectral_radius(signs)
        if radius < best_radius:
            best_radius = radius
            best_signs = signs.copy()
    
    if best_signs is None:
        # Fallback
        best_signs = np.ones(num_edges, dtype=int)
        best_signs[matching_edges[0]] = -1
        best_radius = spectral_radius(best_signs)
    
    current_signs = best_signs.copy()
    current_radius = best_radius
    
    # Simulated annealing with fast connectivity
    temperature = 0.5
    cooling_rate = 0.9995
    min_temperature = 0.01
    
    while time.time() < deadline and temperature > min_temperature:
        edge_idx = rng.integers(0, num_edges)
        
        current_signs[edge_idx] = -current_signs[edge_idx]
        
        if not is_connected_fast(current_signs):
            current_signs[edge_idx] = -current_signs[edge_idx]
            temperature *= cooling_rate
            continue
        
        new_radius = spectral_radius(current_signs)
        
        if new_radius < current_radius:
            current_radius = new_radius
            if new_radius < best_radius:
                best_radius = new_radius
                best_signs = current_signs.copy()
        else:
            delta = new_radius - current_radius
            if delta < 0 or rng.random() < np.exp(-delta / max(temperature, 1e-10)):
                current_radius = new_radius
            else:
                current_signs[edge_idx] = -current_signs[edge_idx]
        
        temperature *= cooling_rate
    
    return best_signs
