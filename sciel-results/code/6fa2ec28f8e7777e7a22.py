def _is_half_integer(x):
    return abs(2.0 * x - round(2.0 * x)) < 1e-9


def _is_valid(U, V, W):
    n, m, p = DIMENSIONS
    r = len(W[0])
    Ua = np.array(U, dtype=float)
    Va = np.array(V, dtype=float)
    Wa = np.array(W, dtype=float)
    if Ua.shape != (n * m, r) or Va.shape != (m * p, r) or Wa.shape != (p * n, r):
        return False
    if not all(_is_half_integer(x) for row in U for x in row):
        return False
    if not all(_is_half_integer(x) for row in V for x in row):
        return False
    if not all(_is_half_integer(x) for row in W for x in row):
        return False
    # Exact decomposition check:
    # C[k, i] = sum_c V[j, c] * W[k*n + i, c] where j is chosen so U[i*m+j, c] = 1
    # i.e. for each (i, j, k): sum_c U[i*m+j, c] * V[j*p+k, c] * W[k*n+i, c] == 1
    # and for all other (i, j, k) combinations the product structure yields 0.
    for i in range(n):
        for j in range(m):
            for k in range(p):
                val = 0.0
                for c in range(r):
                    val += Ua[i * m + j, c] * Va[j * p + k, c] * Wa[k * n + i, c]
                expected = 1.0
                if abs(val - expected) > 1e-9:
                    return False
    # Cross terms must vanish: for any (i, j, k) with the index pattern,
    # the only non-zero contributions are when all three factors align.
    # Verify the full tensor: C[i,k] = sum_j A[i,j]*B[j,k]; each A[i,j]B[j,k]
    # must map to exactly the (i,k) slot and not leak.
    for i in range(n):
        for k in range(p):
            total = 0.0
            for j in range(m):
                for c in range(r):
                    total += Ua[i * m + j, c] * Va[j * p + k, c] * Wa[k * n + i, c]
            # This should equal sum_j 1 = m only if every (i,j,k) contributes;
            # but the tensor requires C[i,k] = sum_j A[i,j] B[j,k], and each
            # (i,j,k) term contributes exactly 1 to (i,k). So total must equal m.
            if abs(total - m) > 1e-9:
                return False
    return True


def _schoolbook():
    n, m, p = DIMENSIONS
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
    return {"U": U, "V": V, "W": W}


