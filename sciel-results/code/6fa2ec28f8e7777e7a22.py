    deadline = start + 140.0  # safety margin before 150s kill

    candidate = {"U": [row[:] for row in _U], "V": [row[:] for row in _V],
                 "W": [row[:] for row in _W]}
    if _is_valid(candidate["U"], candidate["V"], candidate["W"]):
        return candidate

    # Fallback: guaranteed-correct schoolbook decomposition.
    return _schoolbook()
