def construct():
    start_time = time.time()
    deadline = 140.0  # Safety margin before 150s kill
    
    def score_set(U):
        if not U:
            return 0.0
        U_set = set(U)
        max_U = max(U_set)
        if max_U == 0:
            return 0.0
        
        # Compute sumset and difference set sizes
        # For efficiency in the search, we might approximate, 
        # but for final scoring we need exact or very good estimates.
        # Since we are constructing structured sets, we can compute exactly.
        
        # Optimization: If the set is defined by digits D and base B,
        # |U+U| and |U-U| can be computed combinatorially if digits are distinct enough.
        # However, to be safe and general, we compute directly for small N,
        # or use the combinatorial formula if we recognize the structure.
        
        n = len(U_set)
        if n > 2000:
            # Fallback for large sets: random sampling might be too slow/accurate?
            # Actually, for structured sets, we can derive sizes.
            # Let's try to compute directly but with a time check.
            pass
            
        sumset = set()
        diffset = set()
        
        # If n is large, O(n^2) is too slow. 
        # But our constructed sets will likely have n < 1000 for the search phase.
        # If we find a large candidate, we might need a faster estimator.
        
        for a in U_set:
            for b in U_set:
                sumset.add(a + b)
                diffset.add(a - b)
                
        ratio = len(diffset) / len(sumset)
        if ratio <= 0:
            return 0.0
        
        try:
            exponent = 1 + math.log(ratio) / math.log(2 * max_U + 1)
        except:
            return 0.0
        return exponent

    def score_structured(digits, base, num_digits):
        """
        Compute score for a set generated by digits 'digits' at positions base^0, base^1, ... base^(num_digits-1)
        U = { sum d_i * base^i | d_i in digits }
        """
        # Generate the set
        U = [0]
        for i in range(num_digits):
            factor = base ** i
            new_U = []
            for u in U:
                for d in digits:
                    new_U.append(u + d * factor)
            U = new_U
        
        U = sorted(set(U))
        
        # If the set is too big to compute exactly within time, 
        # we can use the combinatorial properties.
        # For a "full" digit set (no carries in sum/diff), 
        # |U+U| = prod |D+D| and |U-U| = prod |D-D|.
        # This holds if max(D) < base and min(D) >= 0 such that no overlaps occur in the radix representation.
        # Specifically, if we view U as a number in base B with digits D,
        # then U+U corresponds to all sums of digit pairs, provided no carry occurs.
        # Carry occurs if d1+d2 >= B.
        # To ensure no carry in sum: max(D) + max(D) < B => 2*max(D) < B.
        # To ensure no carry in diff: min(D) - min(D) >= 0 (always true for non-negative) 
        # and max(D) - min(D) < B (always true if digits are in [0, B-1]).
        # Actually, difference set in base B: 
        # If we allow negative digits in the representation of U-U, 
        # the size is prod |D-D|.
        
        # Let's check if the "no-carry" condition holds for sums.
        max_d = max(digits)
        min_d = min(digits)
        
        # If 2*max_d < base, then |U+U| = prod_{i} |D_i + D_i| = (|D+D|)^num_digits
        # And |U-U| = (|D-D|)^num_digits
        # This is a huge speedup.
        
        if 2 * max_d < base:
            # Compute |D+D| and |D-D| for the single digit set
            D_set = set(digits)
            sum_d = set()
            diff_d = set()
            for a in D_set:
                for b in D_set:
                    sum_d.add(a + b)
                    diff_d.add(a - b)
            
            size_sum_d = len(sum_d)
            size_diff_d = len(diff_d)
            
            # Total sizes
            # Note: The max element is max_d * (base^num_digits - 1) / (base - 1)
            max_U = max_d * (base ** num_digits - 1) // (base - 1) if base > 1 else max_d
            
            # Wait, if base=1, it's just repetition. Base must be > 1 for geometric spacing.
            if base <= 1:
                return 0.0
                
            ratio = (size_diff_d ** num_digits) / (size_sum_d ** num_digits)
            
            if ratio <= 0:
                return 0.0
                
            try:
                exponent = 1 + math.log(ratio) / math.log(2 * max_U + 1)
            except:
                return 0.0
            return exponent
        else:
            # Carries occur. We must compute exactly if feasible.
            if len(U) > 1000:
                # Too big to compute exactly quickly. 
                # We can estimate or just return a lower bound? 
                # Better to avoid such configs in search or use a faster approx.
                # For now, let's just compute if it's not too big.
                # If it is too big, we'll rely on the no-carry constraint in search.
                return 0.0 
            else:
                return score_set(U)

    best_score = 0.0
    best_params = None

    # Search space:
    # Base B: 2 to 10
    # Num digits k: 1 to 15 (max_U grows exponentially)
    # Digits D: subset of {0, ..., B-1} containing 0.
    # To maximize ratio |D-D|/|D+D|, we want D to be "spread out" for differences 
    # but "clustered" for sums.
    # |D-D| is maximized when D is spread (e.g., {0, B-1}).
    # |D+D| is minimized when D is clustered (e.g., {0, 1}).
    # But D is fixed.
    # Let's iterate over small digit sets.
    
    # Pre-compute good digit sets for small bases
    # We want to maximize log(|D-D|/|D+D|) / log(2*max_U+1)
    
    # Let's do a grid search over B and k, and pick the best D for each.
    # Actually, D is small (size <= B). We can iterate all subsets of {0..B-1} containing 0.
    
    for B in range(2, 12):
        # Possible digits are subsets of {0, 1, ..., B-1} containing 0
        # To keep it fast, we limit digit set size to <= 4
        # Or just try specific promising structures:
        # 1. {0, B-1} (Max spread)
        # 2. {0, 1, ..., m} (Clustered)
        # 3. Random subsets
        
        candidate_digit_sets = []
        
        # Add specific patterns
        candidate_digit_sets.append([0, B-1])
        candidate_digit_sets.append([0, 1])
        candidate_digit_sets.append([0, B//2, B-1])
        
        # Try all subsets of size 3 and 4 from {0, ..., B-1}
        # If B is small, this is cheap.
        if B <= 8:
            elems = list(range(B))
            # Subsets of size 2, 3, 4 containing 0
            for size in [2, 3, 4]:
                # Fix 0, choose size-1 from 1..B-1
                others = [i for i in elems if i != 0]
                for combo in itertools.combinations(others, size-1):
                    d_set = sorted([0] + list(combo))
                    candidate_digit_sets.append(d_set)
        
        # Deduplicate
        unique_d_sets = []
        seen = set()
        for d in candidate_digit_sets:
            key = tuple(d)
            if key not in seen:
                seen.add(key)
                unique_d_sets.append(d)
        
        for digits in unique_d_sets:
            # Check no-carry condition for fast scoring
            # 2*max(digits) < B
            if 2 * max(digits) >= B:
                # This might still be good if we compute exactly, 
                # but let's prioritize the fast path.
                # We can still evaluate it if num_digits is small.
                pass
            
            # Determine max num_digits k such that max_U doesn't get too large 
            # (log denominator grows) and we don't timeout.
            # max_U approx max_d * B^k
            # We want to maximize 1 + k * log(ratio_d) / log(2*max_d*B^k + 1)
            # Let R = log(ratio_d). If R > 0, larger k is better up to a point?
            # f(k) = 1 + k*R / (log(2*max_d) + k*log(B))
            # As k -> infinity, f(k) -> 1 + R/log(B).
            # So the limit is 1 + log(|D-D|/|D+U|) / log(B).
            # We should check if this limit is > current best.
            
            # Calculate single-step ratio
            D_set = set(digits)
            sum_d = set()
            diff_d = set()
            for a in D_set:
                for b in D_set:
                    sum_d.add(a + b)
                    diff_d.add(a - b)
            
            size_sum_d = len(sum_d)
            size_diff_d = len(diff_d)
            
            if size_sum_d == 0:
                continue
                
            ratio_d = size_diff_d / size_sum_d
            
            if ratio_d <= 1:
                # Adding more digits will make ratio_d^k <= 1, so exponent <= 1.
                # We want exponent > 1.
                # So we need ratio_d > 1.
                continue
            
            # The asymptotic exponent is 1 + log(ratio_d) / log(B)
            # We can achieve this with large k.
            # Let's pick a k that is large enough to get close to the asymptote,
            # but not so large that max_U causes issues (though log handles it).
            # However, if we can't compute exactly due to carries, we are stuck.
            # If 2*max(digits) < B, we can use any k.
            # Let's pick k=10 or 20.
            
            if 2 * max(digits) < B:
                # Safe to use large k
                k = 20
            else:
                # Carries occur. We can only use small k to compute exactly.
                # Let's try k=2, 3, 4
                # We will evaluate a few k values.
                pass
            
            # Evaluate for a few k values
            max_k_to_try = 20 if (2 * max(digits) < B) else 4
            
            for k in range(1, max_k_to_try + 1):
                s = score_structured(digits, B, k)
                if s > best_score:
                    best_score = s
                    best_params = (digits, B, k)
                
                if time.time() > deadline:
                    return construct_final(best_params)
            
            if time.time() > deadline:
                return construct_final(best_params)

    # If no structured set found, fall back to a simple set
    if best_params is None:
        return [0, 1, 3]
    
    return construct_final(best_params)

def construct_final(params):
    """
    Reconstruct the set from the best parameters found.
    """
    if params is None:
        return [0, 1, 3]
        
    digits, B, k = params
    
    U = [0]
    for i in range(k):
        factor = B ** i
        new_U = []
        for u in U:
            for d in digits:
                new_U.append(u + d * factor)
        U = new_U
    
    return sorted(set(U))

