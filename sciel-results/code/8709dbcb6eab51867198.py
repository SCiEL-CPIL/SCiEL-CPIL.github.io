import random
import time
import sys

N = 256

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = start_time + 55  # safety margin before 60s kill
    
    # 1. Precompute conflict bitmasks
    # For each element x in [1, N], compute a bitmask of all other elements y
    # such that {x, y} cannot be part of a Sidon set together.
    # Specifically, y conflicts with x if adding y to a set containing x
    # creates a sum collision with sums involving x and other potential elements?
    # No, the Sidon property is about the set S itself.
    # Two elements x, y are "compatible" if {x, y} is Sidon.
    # {x, y} is Sidon iff 2x != 2y, 2x != x+y, x+y != 2y.
    # 2x != 2y => x != y
    # 2x != x+y => x != y
    # x+y != 2y => x != y
    # So ANY distinct pair is compatible.
    
    # The constraint arises when we have 3+ elements.
    # A set S is Sidon iff all pairwise sums a+b (a<=b) are distinct.
    
    # Let's define the "blocking" relationship.
    # We want a set S such that for every x not in S, S U {x} is NOT Sidon.
    # S U {x} is not Sidon iff there exist a, b in S U {x} such that a+b = c+d
    # where {a,b} != {c,d}.
    
    # Since S is Sidon, all sums within S are distinct.
    # So the collision must involve x.
    # Possible collisions when adding x to S:
    # 1. 2x = a + b for some a, b in S.
    # 2. x + a = x + b => a = b (trivial, not a collision of distinct pairs)
    # 3. x + a = b + c for some a, b, c in S with a != b, a != c, b != c?
    #    Actually, if x+a = b+c, and x is not in S, then {x,a} and {b,c} are distinct pairs.
    #    So x is blocked if there exist a,b,c in S such that:
    #    - 2x = a+b
    #    - OR x+a = b+c (with a,b,c in S, and pairs {x,a}, {b,c} distinct)
    
    # Let's precompute for each x, which sets S block it?
    # This is hard to precompute for all S.
    
    # Alternative Strategy: Branch and Bound with Bitmask State
    # State:
    # - current_set: list of elements in S
    # - sums_mask: bitmask of all sums a+b in S
    # - blocked_mask: bitmask of elements x in [1, N] that are currently blocked by S.
    #   An element x is blocked if adding it would cause a collision.
    #   Collision 1: 2x is in sums_mask.
    #   Collision 2: There exists a in S such that x+a is in sums_mask.
    #                (Note: if x+a = b+c, then x+a is in sums_mask. Since S is Sidon, 
    #                 the representation is unique unless x is in S. But x is not in S.
    #                 So if x+a is in sums_mask, it means x+a = b+c for some b,c in S.
    #                 This is a valid collision.)
    
    # We want to find a minimal S such that blocked_mask covers all elements not in S.
    # Actually, if x is in S, it doesn't need to be blocked.
    # So we need: for all x not in S, x is blocked.
    # Equivalently: (blocked_mask | set_mask) covers all elements [1, N].
    
    # Let's use a recursive search.
    # To speed up, we can precompute:
    # - sum_bit[x]: 1 << (2x)
    # - For each x, a bitmask of elements y such that 2y = x? No.
    # Let's precompute "potential blockers".
    
    # If we add x to S, which elements does it block?
    # It blocks y if:
    # 1. 2y = 2x => y=x
    # 2. 2y = x + a (for some a in S) => y = (x+a)/2
    # 3. y + a = x + b (for some a,b in S) => y = x + b - a
    # 4. y + a = x + x (for some a in S) => y = 2x - a
    
    # This dynamic calculation is expensive.
    
    # Let's try a different angle: Integer Programming or SAT?
    # No, let's stick to optimized Python with bitmasks.
    
    # Precompute:
    # sum_mask_for_pair[i][j] is not needed.
    # Let's precompute a matrix M where M[x] is a bitmask of all y such that
    # y is "conflicted" with x in the sense that {x, y} cannot be in a Sidon set?
    # No, any pair is fine.
    
    # Let's precompute the "sum index" for each possible sum.
    # Max sum is 512.
    
    # Strategy:
    # 1. Randomly generate a valid Sidon set S (greedy).
    # 2. Use local search to minimize size.
    #    Move: Remove an element x from S if S\{x} is still maximal.
    #    Move: Swap x in S with y not in S if size decreases? No, size stays same.
    #    Move: Remove x and add y?
    
    # The "Remove" strategy is the most direct for minimization.
    # Key optimization: Fast check for maximality.
    
    # Let's represent S as a bitmask of elements (256 bits).
    # Let's represent Sums as a bitmask of sums (513 bits).
    
    # Precompute:
    # For each x, let sum_bits[x] be the bitmask of sums generated by x with itself? No.
    # When we have a set S, the sum mask is OR of (1 << (a+b)) for all a<=b in S.
    
    # To check if S is maximal:
    # For each x not in S:
    #   Check if x is blocked.
    #   x is blocked if:
    #   (1 << (2*x)) & sum_mask != 0  OR
    #   Any (1 << (x+a)) & sum_mask != 0 for a in S.
    
    # We can precompute for each x, a bitmask of elements a such that x+a is a "potential" sum?
    # No, the sum_mask changes.
    
    # Let's optimize the "is_blocked" check.
    # is_blocked(x, S_mask, SumMask):
    #   if (1 << (2*x)) & SumMask: return True
    #   # Check x+a
    #   # We need to know if any x+a is in SumMask.
    #   # This is equivalent to: (SumMask >> x) & S_mask != 0?
    #   # Let's see. SumMask has bit s set if s is a sum in S.
    #   # We want to know if there exists a in S such that x+a is in SumMask.
    #   # i.e., exists a in S such that bit (x+a) in SumMask is 1.
    #   # Let T = SumMask >> x. Bit a in T is 1 iff bit (x+a) in SumMask is 1.
    #   # So we need T & S_mask != 0.
    #   # Yes! This is O(1) per check.
    
    # So, is_blocked(x, S_mask, SumMask):
    #   return ((1 << (2*x)) & SumMask) or (((SumMask >> x) & S_mask) != 0)
    
    # This is extremely fast.
    
    # Now, how to update SumMask when adding/removing x?
    # Adding x:
    #   New sums: 2x, and x+a for all a in S.
    #   SumMask_new = SumMask | (1 << (2*x)) | (OR of (1 << (x+a)) for a in S)
    #   We can precompute for each x, a bitmask SumContribution[x] which is not static.
    #   But we can compute it fast:
    #   contrib = 1 << (2*x)
    #   # For each a in S, set bit (x+a)
    #   # This is still O(|S|).
    
    # Removing x:
    #   This is harder because we can't just OR. We need to know if a sum is still present
    #   via other pairs.
    #   However, if we are doing "Remove" search, we can recompute SumMask from scratch?
    #   O(k^2) where k is size. k ~ 15. 225 ops. Fast.
    
    # So the plan:
    # 1. Generate random maximal Sidon set S.
    # 2. Loop:
    #    For each x in S (random order):
    #      Try removing x.
    #      Compute new S_mask, new SumMask (recompute).
    #      Check if new S is maximal.
    #      If yes, keep removal.
    #    If no removals possible, break or restart.
    
    # To improve, we can also try "Swap":
    #    Remove x, Add y.
    #    But minimization is the primary goal.
    
    # Let's implement this.
    
    def recompute_sum_mask(selected):
        mask = 0
        k = len(selected)
        for i in range(k):
            a = selected[i]
            mask |= (1 << (2*a))
            for j in range(i+1, k):
                b = selected[j]
                mask |= (1 << (a+b))
        return mask

    def is_maximal_fast(selected, S_mask, SumMask):
        # Check all x not in S
        # x is blocked if (1 << (2*x)) & SumMask or ((SumMask >> x) & S_mask)
        # We iterate x from 1 to N.
        # If x is in S, skip.
        # If x is not in S and not blocked, return False.
        
        # Optimization: iterate over bits not in S_mask?
        # S_mask has 256 bits.
        # We can just loop 1..N.
        for x in range(1, N+1):
            if (S_mask >> (x-1)) & 1: # x is in S
                continue
            # Check blocked
            if (1 << (2*x)) & SumMask:
                continue
            if ((SumMask >> x) & S_mask):
                continue
            # Not blocked
            return False
        return True

    def construct_greedy_maximal():
        S = []
        S_mask = 0
        SumMask = 0
        remaining = list(range(1, N+1))
        random.shuffle(remaining)
        
        for x in remaining:
            # Check if x can be added
            # New sums: 2x, x+a for a in S
            # Conflict if any new sum is in SumMask
            # (1 << (2*x)) & SumMask
            # OR: ((SumMask >> x) & S_mask) != 0
            
            if (1 << (2*x)) & SumMask:
                continue
            if ((SumMask >> x) & S_mask):
                continue
            
            # Add x
            S.append(x)
            S_mask |= (1 << (x-1))
            
            # Update SumMask
            SumMask |= (1 << (2*x))
            for a in S[:-1]:
                SumMask |= (1 << (x+a))
                
        return S, S_mask, SumMask

    def minimize_size(S, S_mask, SumMask):
        # Try to remove elements
        changed = True
        while changed:
            changed = False
            # Random order of elements in S
            order = S[:]
            random.shuffle(order)
            
            for x in order:
                if x not in S:
                    continue
                
                # Try removing x
                new_S = [y for y in S if y != x]
                new_S_mask = 0
                for y in new_S:
                    new_S_mask |= (1 << (y-1))
                
                new_SumMask = recompute_sum_mask(new_S)
                
                if is_maximal_fast(new_S, new_S_mask, new_SumMask):
                    S = new_S
                    S_mask = new_S_mask
                    SumMask = new_SumMask
                    changed = True
        
        return S

    best_result = None
    best_size = float('inf')
    
    # Run multiple iterations
    for _ in range(2000):
        if time.time() > deadline:
            break
            
        S, S_mask, SumMask = construct_greedy_maximal()
        
        # Minimize
        minimized_S = minimize_size(S, S_mask, SumMask)
        
        if len(minimized_S) < best_size:
            best_size = len(minimized_S)
            best_result = minimized_S[:]
            
        # Early exit
        if best_size <= 12:
             break

    if best_result is None:
        # Fallback
        S, _, _ = construct_greedy_maximal()
        best_result = S

    return best_result
