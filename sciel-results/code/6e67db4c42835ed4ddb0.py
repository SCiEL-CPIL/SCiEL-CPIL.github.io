def _is_prime(a):
    if a < 2:
        return False
    if a < 4:
        return True
    if a % 2 == 0 or a % 3 == 0:
        return False
    d = 5
    while d * d <= a:
        if a % d == 0 or a % (d + 2) == 0:
            return False
        d += 6
    return True

def _prime_signature(a):
    """Return tuple of prime factors (with multiplicity) for a."""
    factors = []
    d = 2
    n = a
    while d * d <= n:
        while n % d == 0:
            factors.append(d)
            n //= d
        d += 1
    if n > 1:
        factors.append(n)
    return tuple(sorted(factors))

def _check_distinct_subset_products(S):
    """
    Check if all 2^k subset products of S are distinct.
    S is a list of distinct integers >= 2.
    Returns True if all subset products are distinct.
    """
    k = len(S)
    if k == 0:
        return True
    if k == 1:
        return True
    # For k up to ~18, 2^k is up to 262144, which is manageable.
    # We use a set to track seen products.
    seen = set()
    seen.add(1)  # empty product
    # We can use a meet-in-the-middle or just iterate through all subsets.
    # For k <= 20, iterating through 2^k subsets is fine.
    # However, products can be large. Python handles big ints.
    # Let's use a recursive or iterative approach to generate subset products.
    # A more efficient way: 
    # If we have a set S, the subset products are distinct iff 
    # the multiplicative semigroup generated by S is free (no relations).
    # A necessary and sufficient condition for distinct subset products is that
    # no non-empty subset has product 1 (impossible here) and that the map 
    # from subsets to products is injective.
    
    # Efficient check: 
    # Sort S. 
    # Actually, a simpler check for small k: just generate all subset products.
    # 2^18 = 262144. This is fast enough in Python if done carefully.
    
    # Let's use a bit-iterative approach or a set update approach.
    # Start with {1}. For each x in S, update seen = seen U {p*x for p in seen}.
    # If len(seen) != 2^(i+1) after adding the (i+1)-th element, then there's a collision.
    
    current_products = {1}
    for x in S:
        new_products = set()
        for p in current_products:
            new_products.add(p * x)
        # Check for overlap
        if current_products & new_products:
            return False
        current_products |= new_products
    
    return True

def _check_distinct_subset_products_fast(S):
    """
    Faster check using the property that if we sort S, and for each element,
    we check if it can be formed by the product of a subset of previous elements,
    it's not sufficient because the collision can be between two different subsets
    that don't involve the new element directly in a simple way.
    However, the set update method above is O(2^k * k) which is fine for k<=18.
    Let's stick with the set update method but optimize the inner loop.
    """
    current_products = [1]
    for x in S:
        new_products = [p * x for p in current_products]
        # Check if any product in new_products is already in current_products
        # Or if there are duplicates within new_products (impossible if current_products has no dups and x is fixed)
        # So we just need to check intersection.
        # Converting to set for intersection is O(2^i).
        if set(current_products) & set(new_products):
            return False
        current_products = current_products + new_products
    return True

def _check_valid(S):
    """
    Validate that all subset products are distinct.
    Uses the incremental set expansion method.
    """
    current = {1}
    for x in S:
        new_vals = {p * x for p in current}
        if current & new_vals:
            return False
        current |= new_vals
    return True

