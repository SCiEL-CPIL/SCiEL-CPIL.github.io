import time

def construct():
    start = time.time()
    deadline = start + 80  # Safety margin

    # We'll use a bitmask-based DP approach for efficiency
    # dp[c] is a set of achievable sums using exactly c elements
    def compute_sums(s):
        n = len(s)
        dp = [set() for _ in range(n + 1)]
        dp[0].add(0)
        for x in s:
            # Iterate backwards to avoid using x multiple times in the same step
            for c in range(n - 1, -1, -1):
                if dp[c]:
                    dp[c + 1].update(sum_val + x for sum_val in dp[c])
        return dp

    def is_valid(s):
        dp = compute_sums(s)
        all_sums = set()
        for c in range(len(s) + 1):
            if not all_sums.isdisjoint(dp[c]):
                return False
            all_sums.update(dp[c])
        return True

    # Incremental validity check: given a valid set s and a new element x,
    # check if s + [x] is valid by comparing new sums against existing sums
    def can_add(s, x, dp):
        # dp is the current DP for set s
        n = len(s)
        # New sums when adding x:
        # For each cardinality c from 0 to n, new sums at c+1 = old sums at c + x
        # We need to check that these new sums don't collide with existing sums at c+1
        # AND that new sums at c+1 don't collide with sums at other cardinalities
        
        # Build the set of all existing sums
        all_sums = set()
        for c in range(n + 1):
            all_sums.update(dp[c])
        
        # New sums generated by adding x
        new_sums = set()
        for c in range(n, -1, -1):
            for sum_val in dp[c]:
                new_sums.add(sum_val + x)
        
        # Check that new_sums don't intersect with all_sums \ new_sums (i.e., old sums)
        # Actually, we need: new_sums ∩ (all_sums - new_sums) = empty
        # Which is: new_sums ∩ all_sums should only contain elements that are in new_sums
        # Simpler: check new_sums ∩ all_sums. If any element is in both but wasn't in new_sums before...
        # Wait, the issue is: when we add x, the new set of sums for each cardinality changes.
        # Let me think differently.
        
        # After adding x, dp'[c] = dp[c] ∪ {s + x : s in dp[c-1]} for c >= 1
        # And dp'[0] = {0}
        
        # We need all dp'[c] to be pairwise disjoint.
        # Since dp[c] are already pairwise disjoint (s is valid), we only need to check
        # that the new elements {s + x : s in dp[c-1]} don't collide with:
        # 1. dp[c] (same cardinality - but wait, duplicates within same cardinality are allowed)
        #    Actually, the constraint is: sums from different cardinalities must differ.
        #    So within same cardinality, duplicates are fine.
        # 2. dp'[c'] for c' != c, i.e., any other cardinality's sums (old or new)
        
        # Let me just recompute: for each c, the new sums added are dp[c-1] + x.
        # These must not appear in dp'[c'] for any c' != c.
        # dp'[c'] = dp[c'] ∪ (dp[c'-1] + x) for c' >= 1
        # dp'[0] = {0}
        
        # So for new elements at cardinality c (which are dp[c-1] + x), we need:
        # - They don't appear in dp[c'] for any c' != c (old sums at other cardinalities)
        # - They don't appear in dp[c'-1] + x for any c' != c, c' >= 1 (new sums at other cardinalities)
        
        # This is getting complex. Let's just do the full check but efficiently.
        
        # Actually, let's just build the full new DP and check.
        # For small n (<=10 or so), this is fast enough.
        
        new_dp = [set() for _ in range(n + 2)]
        new_dp[0].add(0)
        # Copy old dp
        for c in range(n + 1):
            new_dp[c] = set(dp[c])
        # Add new sums
        for c in range(n, -1, -1):
            if dp[c]:
                new_dp[c + 1].update(sum_val + x for sum_val in dp[c])
        
        # Check disjointness
        all_sums = set()
        for c in range(n + 2):
            if not all_sums.isdisjoint(new_dp[c]):
                return False, None
            all_sums.update(new_dp[c])
        return True, new_dp

    # Greedy construction: try to add the smallest valid element
    def greedy_build():
        s = []
        dp = [set()]
        dp[0].add(0)
        
        while True:
            added = False
            for x in range(1, 257):
                if x in s:
                    continue
                valid, new_dp = can_add(s, x, dp)
                if valid:
                    s.append(x)
                    dp = new_dp
                    added = True
                    break
            if not added:
                break
        return s

    best_set = greedy_build()
    best_size = len(best_set)
    
    # Try to improve with randomized local search
    import random
    rng = random.Random(42)
    
    # Local search: try swapping elements to see if we can add more
    def local_search(s, dp, max_time=5.0):
        s = list(s)
        dp = [set(x) for x in dp]
        n = len(s)
        best_s = list(s)
        best_dp = [set(x) for x in dp]
        
        elapsed = 0
        t0 = time.time()
        
        while time.time() - t0 < max_time:
            improved = False
            # Try removing one element and adding a different one
            for i in range(len(s)):
                if time.time() - t0 > max_time:
                    break
                for x in range(1, 257):
                    if x in s:
                        continue
                    # Remove s[i], add x
                    new_s = s[:i] + s[i+1:] + [x]
                    new_s.sort()
                    # Check validity
                    if is_valid(new_s):
                        new_dp = compute_sums(new_s)
                        if len(new_s) > len(best_s):
                            best_s = new_s
                            best_dp = new_dp
                        # Keep the improved set for further search
                        s = new_s
                        dp = new_dp
                        improved = True
                        break
                if improved:
                    break
            if not improved:
                break
        
        return best_s, best_dp

    # Run local search from the greedy solution
    if time.time() < deadline - 10:
        best_set, best_dp = local_search(best_set, compute_sums(best_set), max_time=min(30, deadline - time.time() - 10))
        best_size = len(best_set)
    
    # Try a few random restarts with different strategies
    for seed in range(20):
        if time.time() > deadline - 15:
            break
        rng = random.Random(seed)
        # Randomized greedy
        s = []
        dp = [set()]
        dp[0].add(0)
        
        while True:
            valid_candidates = []
            for x in range(1, 257):
                if x in s:
                    continue
                valid, _ = can_add(s, x, dp)
                if valid:
                    valid_candidates.append(x)
            
            if not valid_candidates:
                break
            
            # Random choice with bias towards smaller
            if rng.random() < 0.3:
                x = min(valid_candidates)
            else:
                x = rng.choice(valid_candidates)
            
            valid, new_dp = can_add(s, x, dp)
            if valid:
                s.append(x)
                dp = new_dp
        
        if len(s) > best_size:
            best_size = len(s)
            best_set = s
    
    # Final validation
    if not is_valid(best_set):
        # Fallback to powers of 2
        best_set = [1, 2, 4, 8, 16, 32, 64, 128]
    
    # Ensure all are Python ints
    return [int(x) for x in best_set]
