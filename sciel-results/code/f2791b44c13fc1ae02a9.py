# Time management
_START_TIME = time.time()
TIME_LIMIT = 280.0  # Safety margin before 300s limit

def _check_time():
    return time.time() - _START_TIME < TIME_LIMIT

def _get_time_remaining():
    return max(0, TIME_LIMIT - (time.time() - _START_TIME))

def _generate_icosahedral_cluster(n, r1=1.0, r2=1.9, r3=2.8, twist=0.0, seed=42):
    """
    Generate a cluster with icosahedral symmetry:
    - 1 center
    - 12 first shell
    - 42 second shell (20 face centers, 30 edge midpoints)
    - 120 third shell (if needed)
    """
    phi = (1 + np.sqrt(5)) / 2
    
    # Icosahedron vertices (12)
    ico_verts = np.array([
        [0, 1, phi], [0, -1, phi], [0, 1, -phi], [0, -1, -phi],
        [1, phi, 0], [-1, phi, 0], [1, -phi, 0], [-1, -phi, 0],
        [phi, 0, 1], [-phi, 0, 1], [phi, 0, -1], [-phi, 0, -1]
    ], dtype=float)
    norms = np.linalg.norm(ico_verts, axis=1, keepdims=True)
    ico_verts = ico_verts / norms * r1
    
    positions = [np.zeros(3)]  # Center atom
    
    # First shell: 12 atoms
    if n > 1:
        positions.extend(ico_verts.tolist())
    
    if n > 13:
        # Second shell: 42 atoms
        # Face centers (20) and edge midpoints (30)
        # Face centers: normalized cross products of adjacent vertices
        # Edge midpoints: normalized sums of adjacent vertices
        
        # Identify faces and edges of icosahedron
        # This is hardcoded for efficiency
        
        # Face centers (20)
        face_centers = []
        # 12 vertices, 20 faces. Each face is a triangle.
        # We can generate them by finding all triplets of vertices that form a face.
        # A face exists if the angle between each pair is the minimum angle (approx 51.8 deg).
        
        # For efficiency, let's use a simpler construction:
        # The 42 points can be generated by taking the 12 vertices, 20 face centers, and 30 edge midpoints.
        
        # Let's compute face centers and edge midpoints explicitly.
        
        # Edges: pairs of vertices with minimum distance
        edge_midpoints = []
        face_centers = []
        
        min_dist = np.inf
        # Find min distance between vertices
        for i in range(12):
            for j in range(i+1, 12):
                d = np.linalg.norm(ico_verts[i] - ico_verts[j])
                if d < min_dist:
                    min_dist = d
        
        # Now find all edges (distance approx min_dist)
        edges = []
        for i in range(12):
            for j in range(i+1, 12):
                d = np.linalg.norm(ico_verts[i] - ico_verts[j])
                if np.isclose(d, min_dist, rtol=1e-5):
                    edges.append((i, j))
        
        # Edge midpoints (30)
        for i, j in edges:
            mid = (ico_verts[i] + ico_verts[j]) / 2.0
            norm = np.linalg.norm(mid)
            if norm > 1e-10:
                mid = mid / norm * r2
            edge_midpoints.append(mid)
        
        # Face centers (20)
        # A face is a triangle of 3 vertices where all 3 pairs are edges.
        # We can find faces by looking for triangles in the edge list.
        # Or, simpler: for each vertex, find its 5 neighbors. The faces around a vertex are triangles (v, n1, n2) where n1, n2 are adjacent neighbors.
        
        # Let's use a different approach: generate 20 points by rotating one face center.
        # Or, compute cross products of edge vectors.
        
        # Let's find faces by checking all triplets of vertices that are mutually connected.
        faces = []
        for i in range(12):
            for j in range(i+1, 12):
                for k in range(j+1, 12):
                    # Check if (i,j), (j,k), (i,k) are all edges
                    if ((i,j) in edges or (j,i) in edges) and \
                       ((j,k) in edges or (k,j) in edges) and \
                       ((i,k) in edges or (k,i) in edges):
                        # Compute face center
                        center = (ico_verts[i] + ico_verts[j] + ico_verts[k]) / 3.0
                        norm = np.linalg.norm(center)
                        if norm > 1e-10:
                            center = center / norm * r2
                        faces.append(center)
        
        # We should have 20 faces and 30 edges
        # Apply twist to second shell
        # Twist is a rotation around the z-axis for each atom based on its y-coordinate? 
        # Or a global twist? Let's use a global twist for simplicity, or per-atom based on polar angle.
        # A better twist: rotate each atom around the z-axis by an angle proportional to its z-coordinate.
        
        second_shell = edge_midpoints + faces
        
        # Apply twist
        if twist != 0.0:
            for i in range(len(second_shell)):
                p = second_shell[i]
                # Rotate around z-axis by twist * p[2]
                angle = twist * p[2]
                cos_a = np.cos(angle)
                sin_a = np.sin(angle)
                new_x = p[0] * cos_a - p[1] * sin_a
                new_y = p[0] * sin_a + p[1] * cos_a
                second_shell[i] = np.array([new_x, new_y, p[2]])
        
        positions.extend(second_shell[:min(42, n - 13)])
    
    # If we still need more atoms (n > 55), add third shell
    if n > 55:
        r3 = 2.8
        # Generate 120 points for third shell
        # This is complex. Let's use a Fibonacci sphere for the remaining atoms.
        needed = n - len(positions)
        if needed > 0:
            golden_angle = np.pi * (3 - np.sqrt(5))
            third_shell = []
            for i in range(needed):
                z = 1 - 2 * i / max(1, needed - 1)
                r = np.sqrt(1 - z*z)
                theta = golden_angle * i
                p = np.array([r * np.cos(theta), r * np.sin(theta), z]) * r3
                third_shell.append(p)
            positions.extend(third_shell)
    
    pos_array = np.array(positions[:n])
    
    # Ensure minimum distance of 0.5
    # Quick check and adjustment if needed
    for i in range(len(pos_array)):
        for j in range(i+1, len(pos_array)):
            d = np.linalg.norm(pos_array[i] - pos_array[j])
            if d < 0.5 and d > 1e-10:
                # Nudge apart
                direction = (pos_array[i] - pos_array[j]) / d
                pos_array[i] += 0.01 * direction
                pos_array[j] -= 0.01 * direction
    
    return pos_array

def _evaluate_params(params, n, potential, parameter):
    """
    Evaluate the energy for a given set of icosahedral parameters.
    params: [r1, r2, r3, twist]
    """
    r1, r2, r3, twist = params
    try:
        pos = _generate_icosahedral_cluster(n, r1, r2, r3, twist)
        # Relax the structure
        energy, relaxed_pos = relax(pos, potential, parameter)
        return energy
    except Exception:
        return 1e10

def _manifold_optimizer(n, potential, parameter, time_limit, result_holder, lock, seed=42):
    """
    Optimize the icosahedral manifold parameters using Nelder-Mead.
    """
    if not _check_time():
        return
    
    # Initial parameters: [r1, r2, r3, twist]
    # Typical values: r1 ~ 1.0, r2 ~ 1.9, r3 ~ 2.8, twist ~ 0.0
    # We'll try multiple starting points
    
    rng = np.random.default_rng(seed)
    
    # Define multiple starting points
    starts = [
        [1.0, 1.9, 2.8, 0.0],
        [1.0, 1.8, 2.7, 0.1],
        [1.0, 2.0, 2.9, -0.1],
        [0.9, 1.9, 2.8, 0.2],
        [1.1, 1.9, 2.8, -0.2],
    ]
    
    best_energy = 1e10
    best_pos = None
    best_params = None
    
    for start in starts:
        if not _check_time():
            break
        if time.time() > time_limit:
            break
        
        # Perturb the start slightly
        perturbed_start = np.array(start) + rng.normal(0, 0.05, 4)
        
        # Nelder-Mead optimization
        try:
            result = minimize(
                _evaluate_params,
                perturbed_start,
                args=(n, potential, parameter),
                method='Nelder-Mead',
                options={'maxiter': 50, 'xatol': 0.01, 'fatol': 0.01}
            )
            
            if result.success and result.fun < best_energy:
                best_energy = result.fun
                best_params = result.x
                # Get the relaxed position
                pos = _generate_icosahedral_cluster(n, best_params[0], best_params[1], best_params[2], best_params[3])
                energy, relaxed_pos = relax(pos, potential, parameter)
                best_pos = relaxed_pos
        except Exception:
            continue
        
        # Update global best
        with lock:
            if result_holder['energy'] is None or best_energy < result_holder['energy']:
                result_holder['energy'] = best_energy
                result_holder['pos'] = best_pos.copy() if best_pos is not None else None
    
    # Final update
    with lock:
        if result_holder['energy'] is None or best_energy < result_holder['energy']:
            result_holder['energy'] = best_energy
            result_holder['pos'] = best_pos.copy() if best_pos is not None else None

def _generate_random_cluster(n, seed=42, min_dist=0.6):
    """Generate a random compact cluster with minimum distance constraint."""
    rng = np.random.default_rng(seed)
    radius = 0.8 * n ** (1.0/3.0)
    points = [np.zeros(3)]  # Start with center
    
    attempts = 0
    max_attempts = 10000
    
    while len(points) < n and attempts < max_attempts:
        attempts += 1
        # Sample point in sphere
        r = radius * np.cbrt(rng.random())
        theta = rng.uniform(0, 2 * np.pi)
        phi = np.arccos(2 * rng.random() - 1)
        p = np.array([
            r * np.sin(phi) * np.cos(theta),
            r * np.sin(phi) * np.sin(theta),
            r * np.cos(phi)
        ])
        
        # Check minimum distance
        valid = True
        for q in points:
            if np.linalg.norm(p - q) < min_dist:
                valid = False
                break
        
        if valid:
            points.append(p)
    
    # If we couldn't place all, add remaining randomly (relax will fix)
    while len(points) < n:
        p = rng.uniform(-radius, radius, 3)
        points.append(p)
    
    return np.array(points[:n])

def _relax_with_timeout(positions, potential, parameter, timeout=5.0):
    """Relax with a timeout to prevent hanging."""
    result = {'energy': None, 'pos': None, 'done': False}
    
    def _do_relax():
        try:
            e, p = relax(positions, potential, parameter)
            result['energy'] = e
            result['pos'] = p
        except Exception as ex:
            pass
        result['done'] = True
    
    t = threading.Thread(target=_do_relax)
    t.start()
    t.join(timeout=timeout)
    
    if result['done'] and result['pos'] is not None:
        return result['energy'], result['pos']
    return None, None

def _basin_hopping_worker(initial_pos, potential, parameter, max_iter, time_limit, result_holder, lock):
    """
    Perform basin hopping from a given initial position.
    Updates result_holder with best found energy/position.
    """
    if not _check_time():
        return
    
    # Initial relaxation
    energy, pos = _relax_with_timeout(initial_pos, potential, parameter, timeout=10.0)
    if energy is None:
        return
    
    best_energy = energy
    best_pos = pos.copy()
    current_energy = energy
    current_pos = pos.copy()
    
    rng = np.random.default_rng(hash(id(initial_pos)) % 2**32)
    
    # Adaptive step size
    step_size = 0.6
    
    for i in range(max_iter):
        if not _check_time():
            break
        if time.time() > time_limit:
            break
        
        # Multi-atom perturbation: perturb a random subset of atoms
        n_perturb = max(1, min(5, len(current_pos) // 10))
        indices = rng.choice(len(current_pos), size=n_perturb, replace=False)
        perturbed = current_pos.copy()
        perturbed[indices] += rng.normal(0, step_size, (n_perturb, 3))
        
        # Relax
        new_energy, new_pos = _relax_with_timeout(perturbed, potential, parameter, timeout=8.0)
        if new_energy is None:
            continue
        
        # Metropolis acceptance with cooling temperature
        # Temperature decreases over iterations
        T = 0.5 * (1.0 - i / max(1, max_iter))
        if new_energy < current_energy or rng.random() < np.exp(-(new_energy - current_energy) / max(T, 0.01)):
            current_energy = new_energy
            current_pos = new_pos
        
        if new_energy < best_energy:
            best_energy = new_energy
            best_pos = new_pos.copy()
            
            # Update global best
            with lock:
                if result_holder['energy'] is None or best_energy < result_holder['energy']:
                    result_holder['energy'] = best_energy
                    result_holder['pos'] = best_pos.copy()
        
        # Adaptive step size: increase if stuck, decrease if improving
        if new_energy < current_energy:
            step_size = max(0.3, step_size * 0.95)
        else:
            step_size = min(1.5, step_size * 1.05)
    
    # Final update
    with lock:
        if result_holder['energy'] is None or best_energy < result_holder['energy']:
            result_holder['energy'] = best_energy
            result_holder['pos'] = best_pos.copy()

def construct(instance):
    """
    Strategy:
    1. Generate multiple diverse initial guesses (Icosahedral manifold, random).
    2. Run parallel manifold optimization and basin hopping on 4 threads.
    3. Return the best result found.
    """
    size = instance["n"]
    potential = instance["potential"]
    parameter = instance.get("rho", instance.get("kind", "dzugutov"))
    
    # Time budget
    time_limit = _START_TIME + TIME_LIMIT - 10  # Leave 10s safety margin
    
    # Global best result
    result_holder = {'energy': None, 'pos': None}
    lock = threading.Lock()
    
    # Generate initial guesses
    ico_pos = _generate_icosahedral_cluster(size)
    rand_pos = _generate_random_cluster(size, seed=size)
    
    # Define worker functions
    def worker_manifold_1():
        _manifold_optimizer(size, potential, parameter, time_limit, result_holder, lock, seed=1)
    
    def worker_manifold_2():
        _manifold_optimizer(size, potential, parameter, time_limit, result_holder, lock, seed=2)
    
    def worker_bh_ico():
        _basin_hopping_worker(ico_pos, potential, parameter, 80, time_limit, result_holder, lock)
    
    def worker_bh_rand():
        _basin_hopping_worker(rand_pos, potential, parameter, 100, time_limit, result_holder, lock)
    
    # Run 4 workers in parallel
    threads = [
        threading.Thread(target=worker_manifold_1),
        threading.Thread(target=worker_manifold_2),
        threading.Thread(target=worker_bh_ico),
        threading.Thread(target=worker_bh_rand),
    ]
    
    for t in threads:
        t.start()
    
    for t in threads:
        t.join()
    
    # Return best result or fallback
    if result_holder['pos'] is not None:
        return result_holder['pos']
    else:
        # Fallback: return the icosahedral structure
        return ico_pos

