import numpy as np

def construct():
    n, m, p = 2, 3, 3
    rank = 17
    
    U = np.zeros((n * m, rank))
    V = np.zeros((m * p, rank))
    W = np.zeros((p * n, rank))
    
    # Indices:
    # A[i, j] -> i*m + j
    # B[j, k] -> j*p + k
    # C[i, k] -> k*n + i
    
    # 1. Strassen for A[0:2, 0:2] * B[0:2, 0:2]
    # A_L: 0,1,3,4. B_LL: 0,1,3,4. C_L: 0,1,2,3
    
    # M1: (A00+A11)(B00+B11)
    U[0, 0] = 1; U[4, 0] = 1
    V[0, 0] = 1; V[4, 0] = 1
    W[0, 0] = 1; W[3, 0] = 1
    
    # M2: (A10+A11)B00
    U[3, 1] = 1; U[4, 1] = 1
    V[0, 1] = 1
    W[1, 1] = 1; W[3, 1] = -1
    
    # M3: A00(B01-B11)
    U[0, 2] = 1
    V[1, 2] = 1; V[4, 2] = -1
    W[2, 2] = 1; W[3, 2] = 1
    
    # M4: A11(B10-B00)
    U[4, 3] = 1
    V[3, 3] = 1; V[0, 3] = -1
    W[0, 3] = 1; W[1, 3] = 1
    
    # M5: (A00+A01)B11
    U[0, 4] = 1; U[1, 4] = 1
    V[4, 4] = 1
    W[0, 4] = -1; W[2, 4] = 1
    
    # M6: (A10-A00)(B00+B01)
    U[3, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[1, 5] = 1
    W[3, 5] = 1
    
    # M7: (A01-A11)(B10+B11)
    U[1, 6] = 1; U[4, 6] = -1
    V[3, 6] = 1; V[4, 6] = 1
    W[0, 6] = 1
    
    # 2. A_L * B_LR (A[0:2, 0:2] * B[0:2, 2] -> C[0:2, 2])
    # A_L: 0,1,3,4. B_LR: 2,5. C_R: 4,5
    
    # A00 * B02 -> C02
    U[0, 7] = 1
    V[2, 7] = 1
    W[4, 7] = 1
    
    # A01 * B12 -> C02
    U[1, 8] = 1
    V[5, 8] = 1
    W[4, 8] = 1
    
    # A10 * B02 -> C12
    U[3, 9] = 1
    V[2, 9] = 1
    W[5, 9] = 1
    
    # A11 * B12 -> C12
    U[4, 10] = 1
    V[5, 10] = 1
    W[5, 10] = 1
    
    # 3. A_R * B_RL (A[0:2, 2] * B[2, 0:2] -> C[0:2, 0:2])
    # A_R: 2,5. B_RL: 6,7. C_L: 0,1,2,3
    
    # A02 * B20 -> C00
    U[2, 11] = 1
    V[6, 11] = 1
    W[0, 11] = 1
    
    # A02 * B21 -> C01
    U[2, 12] = 1
    V[7, 12] = 1
    W[2, 12] = 1
    
    # A12 * B20 -> C10
    U[5, 13] = 1
    V[6, 13] = 1
    W[1, 13] = 1
    
    # A12 * B21 -> C11
    U[5, 14] = 1
    V[7, 14] = 1
    W[3, 14] = 1
    
    # 4. A_R * B_RR (A[0:2, 2] * B[2, 2] -> C[0:2, 2])
    # A_R: 2,5. B_RR: 8. C_R: 4,5
    
    # A02 * B22 -> C02
    U[2, 15] = 1
    V[8, 15] = 1
    W[4, 15] = 1
    
    # A12 * B22 -> C12
    U[5, 16] = 1
    V[8, 16] = 1
    W[5, 16] = 1
    
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
