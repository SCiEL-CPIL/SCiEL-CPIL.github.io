import numpy as np

DIMENSIONS = [2, 2, 2]

def construct():
    n, m, p = DIMENSIONS
    rank = 7
    
    # Initialize U, V, W as 2D lists
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to set values
    # U indices: i*m + j
    # V indices: j*p + k
    # W indices: k*n + i
    
    # Term 1: M1 = a(e+h)
    U[0*2+0][0] = 1
    V[0*2+0][0] = 1
    V[1*2+1][0] = 1
    W[0*2+0][0] = 1 # C00
    W[0*2+1][0] = 0 # C10
    W[1*2+0][0] = 1 # C01
    W[1*2+1][0] = -1 # C11
    
    # Term 2: M2 = (c+a)e
    U[0*2+0][1] = 1
    U[1*2+0][1] = 1
    V[0*2+0][1] = 1
    W[0*2+0][1] = 0
    W[0*2+1][1] = 0
    W[1*2+0][1] = 1 # C01
    W[1*2+1][1] = 1 # C11
    
    # Term 3: M3 = a(g-e)
    U[0*2+0][2] = 1
    V[1*2+0][2] = 1
    V[0*2+0][2] = -1
    W[0*2+0][2] = -1 # C00
    W[0*2+1][2] = 1 # C10
    W[1*2+0][2] = 0
    W[1*2+1][2] = 0
    
    # Term 4: M4 = d(f-h)
    U[1*2+1][3] = 1
    V[0*2+1][3] = 1
    V[1*2+1][3] = -1
    W[0*2+0][3] = 1 # C00
    W[0*2+1][3] = 1 # C10
    W[1*2+0][3] = -1 # C01
    W[1*2+1][3] = 1 # C11
    
    # Term 5: M5 = (c+d)h
    U[1*2+0][4] = 1
    U[1*2+1][4] = 1
    V[1*2+1][4] = 1
    W[0*2+0][4] = 0
    W[0*2+1][4] = 1 # C10
    W[1*2+0][4] = 0
    W[1*2+1][4] = 1 # C11
    
    # Term 6: M6 = (a-c)(f+h)
    U[0*2+0][5] = 1
    U[1*2+0][5] = -1
    V[0*2+1][5] = 1
    V[1*2+1][5] = 1
    W[0*2+0][5] = 0
    W[0*2+1][5] = 1 # C10
    W[1*2+0][5] = -1 # C01
    W[1*2+1][5] = 0
    
    # Term 7: M7 = (b-d)(g+e)
    U[0*2+1][6] = 1
    U[1*2+1][6] = -1
    V[1*2+0][6] = 1
    V[0*2+0][6] = 1
    W[0*2+0][6] = 1 # C00
    W[0*2+1][6] = -1 # C10
    W[1*2+0][6] = 0
    W[1*2+1][6] = 0
    
    return {"U": U, "V": V, "W": W}
