import time

DIMENSIONS = [2, 2, 7]

def construct():
    n, m, p = DIMENSIONS
    # Rank 25: 3 Strassen blocks (7 each) + 1 Schoolbook block (4)
    rank = 25
    
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to add a term
    def add_term(u_idx, v_idx, w_idx, col):
        U[u_idx][col] += 1
        V[v_idx][col] += 1
        W[w_idx][col] += 1
        
    def add_term_signed(u_idx, v_idx, w_idx, col, sign):
        U[u_idx][col] += sign
        V[v_idx][col] += sign
        W[w_idx][col] += sign

    # Strassen Block 1: B cols 0, 1. Offset k0=0.
    # U indices: 0(00), 1(01), 2(10), 3(11)
    # V indices: 0(0,0), 7(1,0), 1(0,1), 8(1,1)
    # W indices: 0(0,0), 2(0,1), 1(1,0), 3(1,1)
    
    # M1: (A11 - A00)(B00 - B11) -> C11 + C22
    # U: 3:1, 0:-1. V: 0:1, 8:-1. W: 0:1, 3:1.
    U[3][0] += 1; U[0][0] -= 1
    V[0][0] += 1; V[8][0] -= 1
    W[0][0] += 1; W[3][0] += 1
    
