import time
import math
import sys

def construct(n_rows, k):
    start_time = time.time()
    time_limit = 145.0
    
    k_plus_1 = k + 1
    total_diffs_per_row = k * (k + 1) // 2
    total_diffs_needed = n_rows * total_diffs_per_row
    
    # Lower bound based on counting: S(S+1)/2 >= total_diffs_needed
    lb = int(math.ceil((-1 + math.sqrt(1 + 8 * total_diffs_needed)) / 2))
    
    # Helper to check if a row is valid given a used mask
    def row_diff_mask(row):
        mask = 0
        n = len(row)
        for i in range(n):
            for j in range(i + 1, n):
                d = row[j] - row[i]
                mask |= (1 << d)
        return mask

    def is_valid_full(rows):
        used_mask = 0
        for row in rows:
            mask = row_diff_mask(row)
            if used_mask & mask:
                return False
            used_mask |= mask
        return True

    # Backtracking search for a specific scope S
    def search_scope(S):
        # used_mask: bitmask of differences used so far
        # rows: list of completed rows
        # current_row: list of elements in the row being constructed
        # row_idx: index of the current row being constructed
        
        # We will use a recursive function
        # To enforce symmetry breaking: rows are sorted lexicographically.
        # This means row[i] <= row[i+1] lexicographically.
        
        # We can pass the previous row to constrain the current one.
        
        def backtrack(row_idx, used_mask, prev_row, current_row):
            if time.time() > time_limit:
                return None
            
            if row_idx == n_rows:
                return [list(r) for r in [prev_row] + [current_row]] # This logic is messy, let's store rows in a list
            
            # Better: store completed rows in a list 'rows'
            # And 'current_row' is the one being built for index row_idx
            
            # If we are starting a new row (current_row is empty or just [0])
            # Actually, let's structure it as:
            # build_row(row_idx, used_mask, prev_row, partial_row)
            
            # If partial_row is complete (len == k_plus_1)
            if len(partial_row) == k_plus_1:
                # Check symmetry: partial_row must be >= prev_row lexicographically
                if prev_row is not None:
                    if partial_row < prev_row:
                        return None
                
                # Check if this row's diffs conflict with used_mask
                r_mask = row_diff_mask(partial_row)
                if used_mask & r_mask:
                    return None
                
                # If this is the last row, we are done
                if row_idx == n_rows - 1:
                    return [partial_row]
                
                # Recurse to next row
                res = backtrack(row_idx + 1, used_mask | r_mask, partial_row, [0])
                if res is not None:
                    return [partial_row] + res
                return None
            
            # Otherwise, we need to add the next element to partial_row
            last_val = partial_row[-1]
            start_x = last_val + 1
            
            # Optimization: If we have a previous row, we might be able to bound the search?
            # Not easily.
            
            # Heuristic: Try values in increasing order
            for x in range(start_x, S + 1):
                # Quick check: does x - y conflict for any y in partial_row?
                conflict = False
                new_diffs = 0
                for y in partial_row:
                    d = x - y
                    if (used_mask >> d) & 1:
                        conflict = True
                        break
                    new_diffs |= (1 << d)
                
                if conflict:
                    continue
                
                # Additional pruning: 
                # The remaining elements must fit in [x+1, S].
                # The number of remaining elements is k_plus_1 - len(partial_row) - 1.
                # Let rem = k_plus_1 - len(partial_row) - 1.
                # We need to place 'rem' more elements.
                # The minimum span required for a Golomb ruler of size rem+1 (including x as the first mark of the sub-problem? No, x is the last mark of the current partial row, so the new marks will be > x).
                # The differences from the new marks to x, and to all previous marks, must be distinct.
                # A simple bound: The maximum difference from x to the last possible mark S is S - x.
                # The number of differences generated by adding 'rem' marks to a ruler of size 'len(partial_row)+1' is rem * (len(partial_row)+1) + rem*(rem-1)/2.
                # These differences must be distinct and <= S.
                # This is a weak bound.
                
                # Let's just try the recursion.
                res = backtrack(row_idx, used_mask, prev_row, partial_row + [x])
                if res is not None:
                    return res
            
            return None
        
        # Start the search
        # row_idx 0, used_mask 0, prev_row None, current_row [0]
        res = backtrack(0, 0, None, [0])
        return res

    # Iterate scope from LB upwards
    best_rows = None
    for S in range(lb, lb + 50): # Search window
        if time.time() > time_limit:
            break
        res = search_scope(S)
        if res is not None:
            # Verify validity just in case
            if is_valid_full(res):
                best_rows = res
                break
        # If we are running out of time, break
        if time.time() > time_limit - 5:
            break

    # Fallback if no solution found in the window (should not happen for small N)
    if best_rows is None:
        # Use the greedy fallback from the original program
        used_mask = 0
        rows = []
        for _ in range(n_rows):
            row = [0]
            x = 0
            while len(row) < k_plus_1:
                x += 1
                conflict = False
                for a in row:
                    d = x - a
                    if (used_mask >> d) & 1:
                        conflict = True
                        break
                if not conflict:
                    row.append(x)
                    for a in row[:-1]:
                        used_mask |= (1 << (x - a))
            rows.append(row)
        best_rows = rows

    return best_rows
