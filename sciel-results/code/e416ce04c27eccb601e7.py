def pack(boxes, container):
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin

    W, H, D = container
    n = len(boxes)

    if n == 0:
        return []

    box_volumes = [w * h * d for w, h, d in boxes]
    total_volume = sum(box_volumes)
    container_vol = W * H * D

    if container_vol == 0:
        return [(i, 0, 0, 0, w, h, d) for i, (w, h, d) in enumerate(boxes)]

    # Sort indices by volume descending
    vol_sorted = sorted(range(n), key=lambda i: box_volumes[i], reverse=True)
    
    # Other orderings for diversification
    max_dim_sorted = sorted(range(n), key=lambda i: max(boxes[i]), reverse=True)
    sum_dim_sorted = sorted(range(n), key=lambda i: sum(boxes[i]), reverse=True)
    
    orderings = [vol_sorted, max_dim_sorted, sum_dim_sorted]
    # Add a few random perturbations to the sorted list
    for _ in range(3):
        perturbed = vol_sorted[:]
        random.shuffle(perturbed)
        # Swap a few adjacent elements to keep it mostly sorted
        for _ in range(n // 4):
            if len(perturbed) > 1:
                idx = random.randint(0, len(perturbed) - 2)
                perturbed[idx], perturbed[idx+1] = perturbed[idx+1], perturbed[idx]
        orderings.append(perturbed)

    def compute_score(placements):
        if len(placements) != n:
            return float('inf')
        bin_labels = set(p[0] for p in placements)
        B = len(bin_labels)
        max_bin = max(p[0] for p in placements)
        last_bin_vol = sum(p[4] * p[5] * p[6] for p in placements if p[0] == max_bin)
        occupied_frac = last_bin_vol / container_vol if container_vol > 0 else 0.0
        return B + 0.1 * (1 - occupied_frac)

    def validate_placement(placements):
        if len(placements) != n:
            return False
        bins = defaultdict(list)
        for i, (b, x, y, z, w, h, d) in enumerate(placements):
            if x < 0 or y < 0 or z < 0:
                return False
            if x + w > W or y + h > H or z + d > D:
                return False
            bins[b].append((x, y, z, w, h, d))
        for bin_idx, box_list in bins.items():
            for i in range(len(box_list)):
                for j in range(i + 1, len(box_list)):
                    x1, y1, z1, w1, h1, d1 = box_list[i]
                    x2, y2, z2, w2, h2, d2 = box_list[j]
                    if (x1 < x2 + w2 and x2 < x1 + w1 and
                        y1 < y2 + h2 and y2 < y1 + h1 and
                        z1 < z2 + d2 and z2 < z1 + d1):
                        return False
        return True

    class Bin:
        def __init__(self):
            self.boxes = [] # (x, y, z, w, h, d)
            self.eps = [(0, 0, 0)] # Extreme Points
            self.volume = 0

        def is_dominated(self, p1, p2):
            # p1 dominates p2 if p1 <= p2 in all dims and < in at least one
            return (p1[0] <= p2[0] and p1[1] <= p2[1] and p1[2] <= p2[2] and 
                    (p1[0] < p2[0] or p1[1] < p2[1] or p1[2] < p2[2]))

        def add_box(self, x, y, z, w, h, d):
            # Check bounds
            if x + w > W or y + h > H or z + d > D:
                return False
            
            # Check overlap with existing boxes
            for bx, by, bz, bw, bh, bd in self.boxes:
                if (x < bx + bw and bx < x + w and
                    y < by + bh and by < y + h and
                    z < bz + bd and bz < z + d):
                    return False
            
            # Place box
            self.boxes.append((x, y, z, w, h, d))
            self.volume += w * h * d
            
            # Update Extreme Points
            new_eps = []
            # Generate new candidates from the new box's corners
            candidates = [
                (x + w, y, z),
                (x, y + h, z),
                (x, y, z + d),
                (x + w, y + h, z),
                (x + w, y, z + d),
                (x, y + h, z + d),
                (x + w, y + h, z + d)
            ]
            
            # Filter out candidates that are inside or on the boundary of existing boxes?
            # Actually, EPs are points in free space.
            # A point is an EP if it is not dominated by any other EP.
            # When adding a box, we remove EPs that are "covered" by the new box?
            # No, we remove EPs that are no longer "extreme" or are inside the new box.
            # Standard EP update:
            # 1. Remove any existing EPs that are dominated by the new box's "corner" logic?
            #    Actually, if an EP is inside the new box, it's invalid.
            #    If an EP is not inside, it might still be dominated by new points generated by the box.
            
            # Let's refine the EP update logic:
            # An EP is a point (x,y,z) such that no other point in the set is <= (x,y,z) and != (x,y,z).
            # When we add a box, the space it occupies is blocked.
            # Any existing EP that falls inside the new box's volume (x <= px <= x+w, etc) is removed.
            # Also, any existing EP that is dominated by a new point generated by the box's corners should be removed.
            # And the new points generated should only be kept if they are not dominated by existing EPs or other new points.
            
            # Simpler robust approach for small n:
            # Keep all existing EPs that are not inside the new box.
            # Add new candidate points from the box's corners.
            # Then, prune the set to keep only non-dominated points.
            
            new_candidates = list(self.eps)
            # Remove EPs inside the new box
            filtered_eps = []
            for p in self.eps:
                if not (x <= p[0] < x + w and y <= p[1] < y + h and z <= p[2] < z + d):
                    filtered_eps.append(p)
            
            # Add new candidates
            for c in candidates:
                if 0 <= c[0] <= W and 0 <= c[1] <= H and 0 <= c[2] <= D:
                    # Only add if not inside the box (corners are on boundary, so they are valid points for placement *start*)
                    # Wait, if we place at a corner, the box occupies [x, x+w].
                    # If an EP is at (x+w, y, z), it is a valid start point for another box.
                    filtered_eps.append(c)
            
            # Prune dominated points
            # Sort by x, then y, then z to help pruning?
            # Just do O(N^2) pruning since N is small (bounded by number of boxes * 7)
            final_eps = []
            for p in filtered_eps:
                is_dom = False
                for q in filtered_eps:
                    if p == q:
                        continue
                    if self.is_dominated(q, p):
                        is_dom = True
                        break
                if not is_dom:
                    final_eps.append(p)
            
            self.eps = final_eps
            return True

        def try_place(self, w, h, d):
            """Try to place a box in this bin using EPs. Returns (x,y,z) or None."""
            if not self.eps:
                return None
            
            # Sort EPs by "tightness" or just iterate
            # We want to find a valid position.
            # To minimize fragmentation, we prefer positions with smaller coordinates (closer to origin).
            # Let's sort EPs by x+y+z or just lexicographically.
            sorted_eps = sorted(self.eps)
            
            best_pos = None
            for x, y, z in sorted_eps:
                if self.is_valid_pos(x, y, z, w, h, d):
                    # Heuristic: prefer lower z, then y, then x
                    if best_pos is None or (z, y, x) < (best_pos[2], best_pos[1], best_pos[0]):
                        best_pos = (x, y, z)
            
            if best_pos is None:
                return None
            
            # Actually, we should just place it at the first valid one found if we want speed,
            # but "best fit" usually implies checking all.
            # Given the small number of EPs, checking all is fine.
            # However, we need to ensure that placing it here doesn't prevent better placements later?
            # Greedy: Place at the "best" (lowest) valid EP.
            
            # Let's stick to the lowest valid EP found.
            for x, y, z in sorted_eps:
                if self.is_valid_pos(x, y, z, w, h, d):
                    return (x, y, z)
            
            return None

        def is_valid_pos(self, x, y, z, w, h, d):
            if x + w > W or y + h > H or z + d > D:
                return False
            for bx, by, bz, bw, bh, bd in self.boxes:
                if (x < bx + bw and bx < x + w and
                    y < by + bh and by < y + h and
                    z < bz + bd and bz < z + d):
                    return False
            return True

