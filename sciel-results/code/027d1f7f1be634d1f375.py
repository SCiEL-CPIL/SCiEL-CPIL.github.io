"""Skyline / floor-map based 3D container loading."""
import numpy as np
from itertools import product

def load(boxes, container):
    W, H, D = container
    n = len(boxes)
    
    # We will use a discrete grid approach for the floor map.
    # To keep it efficient, we might not need full resolution if boxes are large,
    # but for general correctness with arbitrary integer dimensions, 
    # a grid of size W x D is standard for skyline algorithms.
    # However, if W, D are large (e.g., > 1000), this could be slow/memory heavy.
    # Given 60 boxes, the number of distinct x and z coordinates is at most 60*2+1.
    # A more efficient "skyline" approach uses a list of (x, z, height) segments or a 2D list of heights at specific coordinates.
    
    # Let's use a "2D Skyline" represented as a dictionary or a small grid of critical points.
    # Actually, the classic 3D skyline maintains a 2D map of minimum heights.
    # Since we have only 60 boxes, we can maintain a set of "critical" x and z coordinates.
    
    # Simpler and robust approach for small N:
    # Maintain a list of placed boxes. For each new box, try all permutations of its dimensions.
    # For each permutation, try all possible (x, y, z) positions generated by the boundaries of existing boxes.
    # This is O(N^4) roughly, which for N=60 is 60^4 = 13M, might be too slow in Python if not optimized.
    
    # Better: Use a 2D grid for the "floor" (z=0 plane) is not enough because we stack.
    # Let's use the "Max Height Map" on a grid defined by the unique x and z coordinates of placed boxes.
    
    # Initialize grid
    # We will maintain a 2D array `height_map` where height_map[i][j] is the max height of boxes covering cell (i, j) in the grid.
    # The grid coordinates are derived from the unique x and z boundaries.
    
    # To avoid dynamic grid resizing complexity, we can just use the container dimensions if they are small.
    # If W, H, D are large, this fails.
    # Let's check typical sizes. If they are small (e.g., < 200), a direct grid is best.
    # If they are large, we need coordinate compression.
    
    # Let's assume coordinate compression is needed for robustness.
    
    # Collect all potential x and z coordinates.
    # Initially just 0 and W, 0 and D.
    # As we place boxes, we add their x, x+w, z, z+d.
    
    # This dynamic insertion into a compressed grid is tricky.
    
    # Alternative: Since N=60 is small, we can use a simple "Best Fit" heuristic with explicit overlap checking.
    # For each box, try all 6 rotations.
    # For each rotation, generate candidate positions.
    # Candidate positions: x in {0} U {b.x + b.w for b in placed}, z in {0} U {b.z + b.d for b in placed}.
    # y is determined by the max height of all placed boxes that overlap in x and z with the candidate position.
    # We pick the position with the minimum y (lowest).
    # If min y + box.h <= H, place it.
    
    # This is O(N^2 * 6 * N) = O(N^3 * 6) for checking overlaps?
    # For each candidate (x, z), we check all placed boxes to see if they overlap in x-z plane to determine the required y.
    # Number of candidates: O(N) * O(N) = O(N^2).
    # For each candidate, checking overlap with N placed boxes is O(N).
    # So per box: 6 rotations * N^2 candidates * N overlap checks = 6 * N^3.
    # Total: N * 6 * N^3 = 6 * N^4.
    # N=60 -> 60^4 = 12,960,000. * 6 = 77M operations.
    # In Python, 77M simple operations might take ~5-10 seconds. This is within the 120s limit.
    
    placed = []  # list of (x, y, z, w, h, d)
    results = []
    
    # Sort boxes by volume descending? Or by max dimension?
    # Usually, largest first is better for packing.
    box_indices = list(range(n))
    # Sort by volume descending
    box_indices.sort(key=lambda i: boxes[i][0]*boxes[i][1]*boxes[i][2], reverse=True)
    
    # We need to return results in the original order.
    # So we will store the placement for each original index.
    final_placements = [None] * n
    
    for idx in box_indices:
        w, h, d = boxes[idx]
        
        # Generate 6 rotations
        # Dimensions are (w, h, d). Rotations permute these.
        # The container is W, H, D.
        # We try to fit (w', h', d') into (W, H, D).
        rotations = [
            (w, h, d),
            (w, d, h),
            (h, w, d),
            (h, d, w),
            (d, w, h),
            (d, h, w)
        ]
        
        best_placement = None
        best_y = float('inf')
        
        for rw, rh, rd in rotations:
            if rw > W or rh > H or rd > D:
                continue
            
            # Generate candidate x positions
            # x can be 0 or the right edge of any placed box
            xs = [0]
            for (px, py, pz, pw, ph, pd) in placed:
                xs.append(px + pw)
            # Also, we might want to try x positions that align with the left edge of placed boxes?
            # No, for "skyline" style lowest placement, we usually only need to check positions where the box
            # is "supported" or touches a wall/other box on the left.
            # Actually, the optimal x for a given z and y is often determined by the gaps.
            # The set {0} U {b.x + b.w} is sufficient for finding the "lowest" y for a given z?
            # Not necessarily. We also need to consider x positions that fit into gaps.
            # However, the standard "Best Fit" with these candidates works well.
            # To be more thorough, we can also include {b.x} but that's usually not needed for "lowest y" if we scan all z.
            
            # Generate candidate z positions
            zs = [0]
            for (px, py, pz, pw, ph, pd) in placed:
                zs.append(pz + pd)
            
            # Filter xs and zs to those that fit
            xs = [x for x in xs if x + rw <= W]
            zs = [z for z in zs if z + rd <= D]
            
            # Remove duplicates
            xs = sorted(set(xs))
            zs = sorted(set(zs))
            
            for cx in xs:
                for cz in zs:
                    # Determine the minimum y for this box at (cx, cz)
                    # y must be >= max(py + ph) for all placed boxes that overlap in x and z
                    min_y = 0
                    for (px, py, pz, pw, ph, pd) in placed:
                        # Check overlap in x
                        if cx < px + pw and cx + rw > px:
                            # Check overlap in z
                            if cz < pz + pd and cz + rd > pz:
                                # Overlap exists, so we must be above this box
                                if py + ph > min_y:
                                    min_y = py + ph
                    
                    if min_y + rh <= H:
                        # This is a valid placement
                        if min_y < best_y:
                            best_y = min_y
                            best_placement = (cx, min_y, cz, rw, rh, rd)
        
        if best_placement is not None:
            cx, cy, cz, rw, rh, rd = best_placement
            placed.append((cx, cy, cz, rw, rh, rd))
            final_placements[idx] = (0, cx, cy, cz, rw, rh, rd)
        else:
            final_placements[idx] = (-1, 0, 0, 0, w, h, d)
    
    return final_placements
