import time
import random

N = 256

def construct():
    start_time = time.time()
    deadline = start_time + 25.0  # Safety margin for 60s limit
    
    best_set = None
    best_size = N + 1
    
    # We will run a few variations of the greedy heuristic to find a smaller set
    # Variation 1: Standard Max Blocking
    # Variation 2: Max Blocking with random tie-breaking
    # Variation 3: Min Blocking (sometimes counter-intuitive, but let's stick to Max Blocking primarily)
    
    def greedy_construct(tie_break_random=False):
        selected = []
        used_sums = set()
        candidates = list(range(1, N + 1))
        
        while candidates:
            if time.time() > deadline:
                return None
            
            best_candidate = None
            max_blocks = -1
            best_score = -1
            
            # Precompute sums generated by adding x to current selected
            # We need to check validity of x first
            
            valid_candidates = []
            for x in candidates:
                # Check if x is valid with current 'selected'
                new_sums = [2 * x] + [x + s for s in selected]
                if any(s in used_sums for s in new_sums):
                    continue
                valid_candidates.append(x)
            
            if not valid_candidates:
                break
            
            # Evaluate each valid candidate
            for x in valid_candidates:
                # Calculate how many other valid_candidates would be blocked by adding x
                blocks = 0
                # The sums that would be added by x
                added_sums = set([2 * x] + [x + s for s in selected])
                
                for y in valid_candidates:
                    if y == x:
                        continue
                    # Check if y is still valid if x is added
                    # y's sums relative to new set (selected + {x})
                    # Sums involving y: 2y, y+s for s in selected, y+x
                    # We need to check if any of these collide with:
                    # 1. Existing used_sums
                    # 2. The new sums added by x (added_sums)
                    
                    # Note: y is currently valid, so y's sums don't collide with used_sums.
                    # We only need to check collisions with added_sums.
                    
                    # Sums to check for y:
                    # 2y
                    if 2 * y in added_sums:
                        blocks += 1
                        continue
                    # y + s for s in selected
                    # Since y is currently valid, y+s is not in used_sums.
                    # But y+s might be in added_sums?
                    # added_sums contains 2x and x+s for s in selected.
                    # So we check if y+s == 2x or y+s == x+s' for some s' in selected.
                    # y+s == 2x => y = 2x - s
                    # y+s == x+s' => y = x + s' - s
                    
                    blocked = False
                    if 2 * y in added_sums:
                        blocked = True
                    else:
                        for s in selected:
                            if y + s in added_sums:
                                blocked = True
                                break
                        # Also check y+x against added_sums?
                        # y+x is a new sum formed by the pair (y,x).
                        # Is y+x in added_sums?
                        # added_sums has x+s for s in selected.
                        # y+x == x+s => y==s. But y is not in selected.
                        # y+x == 2x => y==x. But y!=x.
                        # So y+x does not collide with added_sums directly.
                        # However, we must ensure y+x is not in used_sums.
                        # Since y is currently valid, is y+x in used_sums?
                        # used_sums contains sums from selected.
                        # If y+x was in used_sums, y would have been invalid already?
                        # Not necessarily. used_sums has a+b for a,b in selected.
                        # If y+x = a+b, then y+x is in used_sums.
                        # But we established y is currently valid, meaning no sum involving y
                        # (2y, y+s for s in selected) is in used_sums.
                        # Wait, the condition for y being valid is:
                        # 2y not in used_sums AND y+s not in used_sums for all s in selected.
                        # It does NOT check y+x because x is not in selected yet.
                        # So if we add x, we must ensure y+x is not in used_sums 
                        # AND y+x is not in added_sums (which we checked)
                        # AND y+x is not equal to any other new sum?
                        # The new sums are {2x} U {x+s}.
                        # The sums involving y in the new set are {2y} U {y+s for s in selected} U {y+x}.
                        # We know {2y} U {y+s} are disjoint from used_sums (y valid).
                        # We checked {2y} U {y+s} against added_sums.
                        # We need to check {y+x} against used_sums.
                        # And {y+x} against added_sums (already done implicitly? 
                        # y+x in added_sums? 
                        # added_sums = {2x} U {x+s}.
                        # y+x = 2x => y=x (false).
                        # y+x = x+s => y=s (false, y not in selected).
                        # So y+x is not in added_sums.
                        
                        if not blocked:
                            # Check if y+x is in used_sums
                            if y + x in used_sums:
                                blocked = True
                            # Check if y+x creates a collision with other new sums?
                            # The new sums from x are 2x and x+s.
                            # The new sum from y is y+x.
                            # Do any of these collide with each other?
                            # y+x == 2x => y=x (no)
                            # y+x == x+s => y=s (no)
                            # So y+x is unique among the new sums.
                            # But we must also ensure that adding x doesn't make 
                            # some other existing sum collide with y's sums?
                            # No, sums are fixed.
                            
                    if blocked:
                        blocks += 1
                    
                if blocks > max_blocks:
                    max_blocks = blocks
                    if not tie_break_random:
                        best_candidate = x
                    else:
                        # Random tie break among max blocks
                        if random.random() < 0.5 or best_candidate is None:
                            # This logic is slightly flawed for strict random tie break, 
                            # but good enough for variation. 
                            # Better: collect all max, pick random.
                            pass
            
            # Refined selection logic for random tie-breaking
            if tie_break_random:
                max_block_candidates = []
                for x in valid_candidates:
                    blocks = 0
                    added_sums = set([2 * x] + [x + s for s in selected])
                    for y in valid_candidates:
                        if y == x:
                            continue
                        blocked = False
                        if 2 * y in added_sums:
                            blocked = True
                        else:
                            for s in selected:
                                if y + s in added_sums:
                                    blocked = True
                                    break
                        if not blocked:
                            if y + x in used_sums:
                                blocked = True
                        if blocked:
                            blocks += 1
                    if blocks == max_blocks:
                        max_block_candidates.append(x)
                if max_block_candidates:
                    best_candidate = random.choice(max_block_candidates)
            
            if best_candidate is None:
                break
                
            selected.append(best_candidate)
            used_sums.update([2 * best_candidate] + [best_candidate + s for s in selected[:-1]])
            
            # Remove blocked candidates
            new_candidates = []
            added_sums = set([2 * best_candidate] + [best_candidate + s for s in selected[:-1]])
            for y in candidates:
                if y == best_candidate:
                    continue
                # Check if y is still valid
                blocked = False
                if 2 * y in used_sums:
                    blocked = True
                else:
                    for s in selected:
                        if y + s in used_sums:
                            blocked = True
                            break
                if not blocked:
                    new_candidates.append(y)
            candidates = new_candidates
            
        return selected

    # Run a few iterations
    for i in range(10):
        if time.time() > deadline:
            break
        
        if i == 0:
            res = greedy_construct(False)
        else:
            res = greedy_construct(True)
            
        if res is not None and len(res) < best_size:
            best_size = len(res)
            best_set = res
            # If we found a very small set, we might stop early or continue to polish
            # Lower bound for maximal Sidon set in [1, N] is roughly sqrt(N) * constant?
            # For N=256, sqrt(256)=16. Maximal sets are often around 20-30.
            # If we get below 25, it's good.
            
    if best_set is None:
        # Fallback to original greedy if something went wrong or time out
        selected, sums = [], set()
        for x in range(1, N + 1):
            added = [x + a for a in selected] + [2 * x]
            if len(set(added)) == len(added) and not sums.intersection(added):
                selected.append(x)
                sums.update(added)
        return selected
        
    return best_set
