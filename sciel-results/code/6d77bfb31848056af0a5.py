import time
import numpy as np

DIMENSIONS = [4, 4, 7]

# EVOLVE-BLOCK-START
def construct():
    """
    Construct a rank-minimal exact tensor decomposition for multiplying 
    a 4x4 matrix by a 4x7 matrix.
    
    Returns:
        dict: A dictionary with keys 'U', 'V', 'W' containing lists of lists
              representing the factor matrices.
    """
    n, m, p = DIMENSIONS
    
    # The schoolbook rank is n * m * p
    rank = n * m * p
    
    # Initialize U, V, W with zeros
    # U has shape (n*m, rank)
    # V has shape (m*p, rank)
    # W has shape (p*n, rank)
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                # Each term in the sum corresponds to the product A[i,j] * B[j,k]
                # U[i*m + j, column] = 1
                # V[j*p + k, column] = 1
                # W[k*n + i, column] = 1
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
                W[k * n + i][column] = 1
                column += 1
                
    return {"U": U, "V": V, "W": W}
