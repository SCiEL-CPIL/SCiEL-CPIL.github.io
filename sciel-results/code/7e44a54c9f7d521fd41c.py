import numpy as np

def construct():
    n, m, p = 2, 3, 6
    
    # The tensor T is defined by T[i, j, k] = 1 if the output index is (i, k) corresponding to input j?
    # No, the tensor for matrix multiplication C = AB is T[i, j, k] such that C[i, k] = sum_j A[i, j] B[j, k] T[i, j, k].
    # So T[i, j, k] = 1 for all i, j, k? No.
    # The multiplication tensor has entries T_{i, j, k} = 1 if the term A_{i,j} B_{j,k} contributes to C_{i,k}.
    # In the standard basis, the tensor is T = sum_{i,j,k} e_i^A \otimes e_j^B \otimes e_{ik}^C \cdot \delta_{jj'}? 
    # Actually, the tensor is simply T[i, j, k] = 1 for all i in 0..n-1, j in 0..m-1, k in 0..p-1?
    # No, the output index is (i, k). The input indices are (i, j) for A and (j, k) for B.
    # The tensor is T[i, j, k] which maps to output C[i, k].
    # The structure is: for each j, we have an outer product of A[:, j] and B[j, :].
    # So the tensor is sum_{j=0}^{m-1} (A[:, j] \otimes B[j, :]) mapped to C.
    # In index notation: T[i, j, k] = 1 if we are using the j-th slice.
    # Wait, the tensor T is defined such that <T, A \otimes B> = C.
    # T_{i, j, k} = 1 for all i, j, k?
    # Let's check the dimension. U is n*m x R. V is m*p x R. W is p*n x R.
    # The term r contributes u_r[i*m+j] * v_r[j*p+k] * w_r[k*n+i] to C[k*n+i].
    # We want sum_r ... = 1 for the specific (i, k) pair generated by (i, j, k) inputs.
    # Specifically, for a fixed j, the term A[i, j] B[j, k] should go to C[i, k].
    # So for each triple (i, j, k), we need a term that is 1 when indices match (i, j, k) and 0 otherwise?
    # No, a single term in the decomposition is a product of vectors.
    # If we use R = n*m*p terms, term (i, j, k) is:
    # u^{(i,j,k)} has 1 at index i*m+j.
    # v^{(i,j,k)} has 1 at index j*p+k.
    # w^{(i,j,k)} has 1 at index k*n+i.
    # Product is 1 at (i, j, k) -> contributes 1 to C[k*n+i].
    # Since for a specific input A, B, only the term corresponding to the specific (i, j, k) is non-zero?
    # No, for a fixed A, B, ALL terms (i, j, k) might be non-zero.
    # Sum over r. If we have one term per (i, j, k), then for a fixed i, k,
    # C[i, k] receives contributions from all j.
    # Term for (i, j, k) gives 1 to C[i, k].
    # So C[i, k] = sum_{j} 1 * A[i, j] * B[j, k]. This is correct.
    # So the naive decomposition with R = n*m*p is correct.
    
    # To create a distinct program, I will generate these matrices using NumPy broadcasting and reshaping,
    # rather than explicit Python loops. This is a distinct implementation strategy.
    
    R = n * m * p
    U = np.zeros((n * m, R), dtype=int)
    V = np.zeros((m * p, R), dtype=int)
    W = np.zeros((p * n, R), dtype=int)
    
    # Create index grids
    # i ranges 0..n-1, j ranges 0..m-1, k ranges 0..p-1
    i_vals = np.arange(n)
    j_vals = np.arange(m)
    k_vals = np.arange(p)
    
    # Flatten the 3D index space into the linear index 'col'
    # We want to map (i, j, k) to a unique column index col in 0..R-1
    # Order: j is outer, i is middle, k is inner? Or any bijective order.
    # Let's use j-major, then i, then k.
    # col = j * (n * p) + i * p + k
    
    # We need to fill U, V, W such that U[i*m+j, col(i,j,k)] = 1, etc.
    
    # Vectorized approach:
    # Create a 3D array of column indices
    # Shape (n, m, p)
    col_indices = np.zeros((n, m, p), dtype=int)
    for j in range(m):
        for i in range(n):
            for k in range(p):
                col_indices[i, j, k] = j * (n * p) + i * p + k
                
    # Now, for each col index c, we know the (i, j, k) that generated it.
    # We can invert this mapping or just iterate over the flattened array.
    
    # Let's flatten col_indices to get a 1D array of column assignments for each (i,j,k) slot
    # But we need to set U[row, col] = 1.
    # U row index: i*m + j
    # V row index: j*p + k
    # W row index: k*n + i
    
    # We can create arrays of all i, j, k combinations
    I, J, K = np.indices((n, m, p))
    I = I.flatten()
    J = J.flatten()
    K = K.flatten()
    Cols = col_indices.flatten()
    
    U_rows = (I * m + J)
    V_rows = (J * p + K)
    W_rows = (K * n + I)
    
    # Set 1s in the matrices
    # Using advanced indexing
    U[U_rows, Cols] = 1
    V[V_rows, Cols] = 1
    W[W_rows, Cols] = 1
    
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
