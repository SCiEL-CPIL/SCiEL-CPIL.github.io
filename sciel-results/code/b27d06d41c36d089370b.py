def _make_symmetric_cell(size, base):
    """Return a size x size list of lists, symmetric under square group, from a base 0/1 array.
    Symmetries: 180-deg rotation, transpose (reflection about main diagonal).
    We enforce cell == cell[::-1] row-wise, cell == cell[::-1] col-wise, and cell == cell.T.
    The intersection of these is the group generated by 180-rotation and transpose.
    We take the majority vote over the 4 equivalent positions: (i,j), (size-1-i,size-1-j), (j,i), (size-1-j,size-1-i).
    """
    b = np.array(base, dtype=np.int8)
    # 180 rotation
    r180 = b[::-1, ::-1]
    # transpose
    t = b.T
    # 180 of transpose = anti-transpose
    at = t[::-1, ::-1]
    votes = (b + r180 + t + at)
    cell = (votes >= 2).astype(np.int8)
    # Convert to nested list
    return cell.tolist()

def _compute_tm_bands_fast(cell, size, n_pw=15, n_kx=8, n_ky=8, eps_high=12.0, eps_low=1.0):
    """Fast plane-wave TM band calculation using FFT for Fourier coefficients."""
    # Build reciprocal lattice vectors
    G_range = range(-n_pw, n_pw + 1)
    Gs = np.array([(mx, my) for mx in G_range for my in G_range], dtype=float)
    nG = len(Gs)
    
    # Compute inv_eps Fourier coefficients using FFT
    cell_arr = np.array(cell, dtype=float)
    eps_arr = np.where(cell_arr > 0.5, eps_high, eps_low)
    inv_eps_arr = 1.0 / eps_arr
    
    # The DFT coefficient for G=(mx,my) is sum_{i,j} inv_eps[i,j] exp(-i 2pi (mx*i + my*j)/N)
    # This is exactly np.fft.fft2(inv_eps_arr)
    inv_eps_fft = np.fft.fft2(inv_eps_arr)
    
    # Map G indices to FFT bin indices
    # G = (mx, my) where mx, my in [-n_pw, n_pw]
    # FFT bins are 0..N-1.
    # Bin index = (mx % N, my % N)
    G_bins = np.array([(mx % size, my % size) for mx, my in Gs], dtype=int)
    inv_eps_G = inv_eps_fft[G_bins[:, 0], G_bins[:, 1]]
    
    # Build inv_eps matrix: M[i,j] = inv_eps(G_i - G_j)
    # G_i - G_j = (mx_i - mx_j, my_i - my_j)
    dmx = Gs[:, 0][:, None] - Gs[:, 0][None, :]
    dmy = Gs[:, 1][:, None] - Gs[:, 1][None, :]
    # Map difference to bin index
    diff_bins = np.array([(dmx[i,j] % size, dmy[i,j] % size) for i in range(nG) for j in range(nG)]).reshape(nG, nG, 2)
    inv_eps_mat = inv_eps_fft[diff_bins[:, :, 0], diff_bins[:, :, 1]].reshape(nG, nG)
    
    # K-points: irreducible BZ of square lattice
    # Gamma (0,0), X (pi,0), M (pi,pi)
    # Triangle: 0 <= ky <= kx <= pi
    k_points = []
    k_points.append((0.0, 0.0))
    # Line Gamma-X
    for t in np.linspace(0.1, 1.0, n_kx):
        k_points.append((t * np.pi, 0.0))
    # Line Gamma-M
    for t in np.linspace(0.1, 1.0, n_ky):
        k_points.append((t * np.pi, t * np.pi))
    # Line X-M
    for t in np.linspace(0.1, 1.0, n_kx):
        k_points.append((np.pi, t * np.pi))
    # Interior points
    for t1 in np.linspace(0.2, 0.8, 3):
        for t2 in np.linspace(0.1, 0.5, 3):
             if t2 <= t1:
                 k_points.append((t1 * np.pi, t2 * np.pi))

    max_band4 = 0.0
    min_band5 = np.inf
    
    for kx, ky in k_points:
        k = np.array([kx, ky])
        kGs = k + Gs  # shape (nG, 2)
        
        # Compute dot products: (k+Gi)·(k+Gj)
        dot = np.outer(kGs[:, 0], kGs[:, 0]) + np.outer(kGs[:, 1], kGs[:, 1])
        
        A = dot * inv_eps_mat
        # A should be Hermitian
        A = (A + A.conj().T) / 2.0
        
        # Solve eigenvalue problem
        eigvals = np.linalg.eigvalsh(A)
        eigvals = np.real(eigvals)
        # Keep only positive eigenvalues
        eigvals = eigvals[eigvals > 1e-10]
        
        if len(eigvals) >= 5:
            b4 = eigvals[3]
            b5 = eigvals[4]
            max_band4 = max(max_band4, b4)
            min_band5 = min(min_band5, b5)
    
    if min_band5 == np.inf or max_band4 == 0:
        return -1.0
    
    gap = min_band5 - max_band4
    midgap = 0.5 * (min_band5 + max_band4)
    if midgap <= 0:
        return -1.0
    return 2.0 * gap / midgap

def _generate_initial_candidates(size):
    """Generate a diverse set of initial candidates."""
    candidates = []
    center = size // 2
    
    def make_cell_from_blobs(blobs, bg_val):
        """blobs: list of (cx, cy, radius, val)"""
        base = np.full((size, size), bg_val, dtype=np.int8)
        for cx, cy, r, val in blobs:
            # cx, cy are in pixel coordinates, centered at (center, center)
            # Convert to relative coords
            # r is radius in pixels
            for i in range(size):
                for j in range(size):
                    dx = i - (center - cx) # Wait, let's use relative to center
                    # Let's define cx, cy as offset from center
                    dx = i - center - cx
                    dy = j - center - cy
                    if dx*dx + dy*dy <= r*r:
                        base[i, j] = val
        return _make_symmetric_cell(size, base)

    # Case 1: Dielectric background (1), Air holes (0)
    # 1 central hole
    for r in [2, 3, 4, 5, 6]:
        candidates.append(make_cell_from_blobs([(0, 0, r, 0)], 1))
    
    # 4 holes at (d, 0)
    for d in [4, 5, 6, 7, 8]:
        for r in [1, 2, 3]:
            blobs = [(-d, 0, r, 0), (d, 0, r, 0), (0, -d, r, 0), (0, d, r, 0)]
            candidates.append(make_cell_from_blobs(blobs, 1))
            
    # 4 holes at (d, d)
    for d in [4, 5, 6, 7]:
        for r in [1, 2, 3]:
            blobs = [(-d, -d, r, 0), (d, -d, r, 0), (-d, d, r, 0), (d, d, r, 0)]
            candidates.append(make_cell_from_blobs(blobs, 1))
            
    # Central hole + 4 corner holes
    for r1 in [2, 3, 4]:
        for d in [6, 7, 8]:
            for r2 in [1, 2]:
                blobs = [(0, 0, r1, 0), (-d, -d, r2, 0), (d, -d, r2, 0), (-d, d, r2, 0), (d, d, r2, 0)]
                candidates.append(make_cell_from_blobs(blobs, 1))

    # Case 2: Air background (0), Dielectric rods (1)
    # 1 central rod
    for r in [4, 5, 6, 7, 8]:
        candidates.append(make_cell_from_blobs([(0, 0, r, 1)], 0))
        
    # 4 rods at (d, 0)
    for d in [4, 5, 6, 7]:
        for r in [1, 2, 3]:
            blobs = [(-d, 0, r, 1), (d, 0, r, 1), (0, -d, r, 1), (0, d, r, 1)]
            candidates.append(make_cell_from_blobs(blobs, 0))
            
    # 4 rods at (d, d)
    for d in [4, 5, 6]:
        for r in [1, 2, 3]:
            blobs = [(-d, -d, r, 1), (d, -d, r, 1), (-d, d, r, 1), (d, d, r, 1)]
            candidates.append(make_cell_from_blobs(blobs, 0))

    # Crosses
    def make_cross(arm_width, length, bg_val, cross_val):
        base = np.full((size, size), bg_val, dtype=np.int8)
        for i in range(size):
            for j in range(size):
                dx = abs(i - center)
                dy = abs(j - center)
                if dx < length and dy < arm_width / 2:
                    base[i, j] = cross_val
                elif dy < length and dx < arm_width / 2:
                    base[i, j] = cross_val
        return _make_symmetric_cell(size, base)
        
    for aw in [2, 3, 4, 5]:
        for ln in [6, 8, 10, 12]:
            candidates.append(make_cross(aw, ln, 0, 1)) # Air bg, Dielectric cross
            candidates.append(make_cross(aw, ln, 1, 0)) # Dielectric bg, Air cross

    return candidates

def design(problem):
    """Time-bounded local search for TM band gap maximization."""
    size = problem["pixels"]
    eps_high = problem.get("eps_high", 12.0)
    eps_low = problem.get("eps_low", 1.0)
    
    start_time = time.time()
    deadline = start_time + 110.0  # Safety margin
    
    # Generate initial candidates
    candidates = _generate_initial_candidates(size)
    
    best_cell = None
    best_score = -1.0
    
    # Evaluate initial candidates
    for cell in candidates:
        if time.time() > deadline:
            break
        try:
            score = _compute_tm_bands_fast(cell, size, n_pw=12, n_kx=6, n_ky=6, eps_high=eps_high, eps_low=eps_low)
        except Exception:
            score = -1.0
        if score > best_score:
            best_score = score
            best_cell = cell
    
    # Local search: random mutations
    if best_cell is not None:
        current_cell = best_cell
        current_score = best_score
        rng = np.random.default_rng(42)
        
        # We will do a few rounds of local search
        for round_num in range(5):
            if time.time() > deadline:
                break
            improved = False
            for step in range(100):
                if time.time() > deadline:
                    break
                # Random mutation: flip some pixels
                mut_cell = np.array(current_cell, dtype=np.int8)
                n_flips = rng.integers(1, 4)
                for _ in range(n_flips):
                    i = rng.integers(0, size)
                    j = rng.integers(0, size)
                    mut_cell[i, j] = 1 - mut_cell[i, j]
                sym_cell = _make_symmetric_cell(size, mut_cell)
                
                try:
                    score = _compute_tm_bands_fast(sym_cell, size, n_pw=12, n_kx=6, n_ky=6, eps_high=eps_high, eps_low=eps_low)
                except Exception:
                    score = -1.0
                
                if score > current_score:
                    current_cell = sym_cell
                    current_score = score
                    improved = True
                    if score > best_score:
                        best_score = score
                        best_cell = sym_cell
            
            if not improved:
                break # No improvement in this round, try a different starting point? 
                # For simplicity, we just break.
    
    if best_cell is None:
        # Fallback to a simple circle
        base = np.zeros((size, size), dtype=np.int8)
        center = size // 2
        for i in range(size):
            for j in range(size):
                dx = i - center
                dy = j - center
                if dx*dx + dy*dy < 16:
                    base[i, j] = 1
        best_cell = _make_symmetric_cell(size, base)
    
    return best_cell
