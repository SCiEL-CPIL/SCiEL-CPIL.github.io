import time
import random

P = {'n': 12, 'm': 40}

def construct():
    deadline = time.time() + 85
    n = P['n']
    m = P['m']
    N = 1 << n
    
    # Greedy Initialization: Start with a maximal chain
    chain = []
    cur = 0
    for b in range(n):
        chain.append(cur)
        cur |= (1 << b)
    chain.append(cur)
    
    # We need 40 sets. The chain has 13.
    # Fill the rest greedily by adding the set with the highest current "degree" in the comparability graph.
    
    family = []
    fam_set = set()
    
    # Precompute comparability matrix? No, N=4096, matrix is 16M entries. Too big for fast access in Python lists of ints?
    # Actually, 4096*4096 is 16,777,216. A list of lists of booleans or ints might be slow to build but fast to access.
    # Or just calculate on the fly.
    
    # Let's use the sub/sup count approach which is O(N) per update.
    sub_count = [0] * N
    sup_count = [0] * N
    
    def update_counts(mask, delta):
        # For all M, if mask subset M, sub_count[M] changes?
        # Wait, sub_count[M] = number of sets in family that are subsets of M.
        # So if we add `mask`, for every M such that `mask` is a subset of M, sub_count[M] += delta.
        # Similarly for sup_count.
        # This is O(N) per update.
        
        # Iterate over all supersets of mask
        # Supersets of mask can be generated by iterating over all submasks of ~mask
        # But simple loop is O(N) = 4096. 4096 * 40 (initial) + 4096 * 40 * passes.
        # This is fast enough.
        
        for M in range(N):
            if (mask & M) == mask:
                sub_count[M] += delta
            if (mask & M) == M:
                sup_count[M] += delta

    # Initialize with chain
    for mask in chain[:m]:
        family.append(mask)
        fam_set.add(mask)
        update_counts(mask, 1)
        
    # Greedy fill
    while len(family) < m:
        if time.time() > deadline - 5:
            break
            
        best_mask = -1
        best_score = -1
        
        for M in range(N):
            if M in fam_set:
                continue
            
            score = sub_count[M] + sup_count[M]
            if score > best_score:
                best_score = score
                best_mask = M
        
        if best_mask == -1:
            break
            
        family.append(best_mask)
        fam_set.add(best_mask)
        update_counts(best_mask, 1)
        
    # Local Search (Hill Climbing)
    improved = True
    while improved and time.time() < deadline - 2:
        improved = False
        
        for i in range(m):
            if time.time() > deadline - 2:
                break
                
            old_mask = family[i]
            
            # Loss of removing old_mask
            # Number of sets comparable to old_mask (excluding itself)
            loss = (sub_count[old_mask] - 1) + (sup_count[old_mask] - 1)
            
            best_mask = -1
            best_gain = -1
            
            for M in range(N):
                if M in fam_set:
                    continue
                
                # Gain of adding M
                # Number of sets in (family \ {old_mask}) comparable to M
                # sub_count[M] counts sets in family subset M.
                # If old_mask is subset M, it's included.
                # sup_count[M] counts sets in family superset M.
                # If M is subset old_mask, it's included.
                
                gain = sub_count[M] + sup_count[M]
                
                # Check if old_mask is comparable to M
                if (old_mask & M) == old_mask: # old_mask subset M
                    gain -= 1
                elif (old_mask & M) == M: # M subset old_mask
                    gain -= 1
                
                if gain > best_gain:
                    best_gain = gain
                    best_mask = M
            
            if best_mask != -1 and best_gain > loss:
                fam_set.remove(old_mask)
                fam_set.add(best_mask)
                family[i] = best_mask
                
                update_counts(old_mask, -1)
                update_counts(best_mask, 1)
                improved = True
                
    # Convert to lists of integers
    result = []
    for mask in family:
        result.append([b for b in range(n) if (mask >> b) & 1])
    
    return result
