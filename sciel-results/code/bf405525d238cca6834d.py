DIMENSIONS = [2, 3, 3]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 17
    
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Indices for A (2x3):
    # a00=0, a01=1, a02=2
    # a10=3, a11=4, a12=5
    
    # Indices for B (3x3):
    # b00=0, b01=1, b02=2
    # b10=3, b11=4, b12=5
    # b20=6, b21=7, b22=8
    
    # Indices for C (2x3) using W[k*n+i]:
    # C00 -> 0*2+0 = 0
    # C10 -> 0*2+1 = 1
    # C01 -> 1*2+0 = 2
    # C11 -> 1*2+1 = 3
    # C02 -> 2*2+0 = 4
    # C12 -> 2*2+1 = 5
    
    # Strassen for A[0:2, 0:2] * B[0:2, 0:2]
    # m0 = a00 * (b00 + b11)
    U[0][0] = 1
    V[0][0] = 1; V[4][0] = 1
    W[1][0] = 1  # C10 += m0
    
    # m1 = (a00 + a01) * b10
    U[0][1] = 1; U[1][1] = 1
    V[3][1] = 1
    W[0][1] = -1; W[2][1] = 1  # C00 -= m1, C01 += m1
    
    # m2 = (a10 + a11) * b00
    U[3][2] = 1; U[4][2] = 1
    V[0][2] = 1
    W[2][2] = 1; W[3][2] = -1  # C01 += m2, C11 -= m2
    
    # m3 = a11 * (b01 + b10)
    U[4][3] = 1
    V[1][3] = 1; V[3][3] = 1
    W[0][3] = 1  # C00 += m3
    
    # m4 = (a00 + a11) * (b00 + b01)
    U[0][4] = 1; U[4][4] = 1
    V[0][4] = 1; V[1][4] = 1
    W[0][4] = 1; W[3][4] = 1  # C00 += m4, C11 += m4
    
    # m5 = (a01 - a11) * (b10 + b11)
    U[1][5] = 1; U[4][5] = -1
    V[3][5] = 1; V[4][5] = 1
    W[3][5] = -1  # C11 -= m5
    
    # m6 = (a00 - a10) * (b00 + b10)
    U[0][6] = 1; U[3][6] = -1
    V[0][6] = 1; V[3][6] = 1
    W[0][6] = -1; W[1][6] = 1  # C00 -= m6, C10 += m6
    
    # Schoolbook for A[0:2, 0:2] * B[0:2, 2:3] (col 2 of B)
    # m7 = a00 * b02
    U[0][7] = 1
    V[2][7] = 1
    W[4][7] = 1  # C02 += m7
    
    # m8 = a01 * b12
    U[1][8] = 1
    V[5][8] = 1
    W[4][8] = 1  # C02 += m8
    
    # m9 = a10 * b02
    U[3][9] = 1
    V[2][9] = 1
    W[5][9] = 1  # C12 += m9
    
    # m10 = a11 * b12
    U[4][10] = 1
    V[5][10] = 1
    W[5][10] = 1  # C12 += m10
    
    # Schoolbook for A[0:2, 2:3] * B[2:3, 0:3] (row 2 of B)
    # m11 = a02 * b20
    U[2][11] = 1
    V[6][11] = 1
    W[0][11] = 1  # C00 += m11
    
    # m12 = a12 * b20
    U[5][12] = 1
    V[6][12] = 1
    W[1][12] = 1  # C10 += m12
    
