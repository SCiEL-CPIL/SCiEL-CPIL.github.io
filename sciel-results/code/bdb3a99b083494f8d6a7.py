import time
import numpy as np
from math import isqrt

def construct():
    start_time = time.time()
    timeout = 140  # Safety margin for 150s limit
    
    # Target M: 200M allows generating ~1M powerful numbers
    # Sum of two powerful numbers up to 2M is up to 4M
    # Array size 4M is manageable (~32MB for int32)
    M = 200_000_000
    
    # 1. Generate powerful numbers
    # Powerful numbers are of the form x^2 * y^3 where y is square-free
    # Actually, any powerful number can be written as x^2 * y^3 with y square-free.
    # We iterate y from 1 to M^(1/3) and x from 1 to sqrt(M/y^3).
    
    max_y = int(M ** (1/3)) + 2
    powerful = []
    
    # We need to check if y is square-free?
    # If y is not square-free, say y = k^2 * z, then y^3 = k^6 * z^3.
    # x^2 * k^6 * z^3 = (x * k^3)^2 * z^3.
    # So the value is generated by a smaller square-free z.
    # Thus, iterating all y and adding to a set is safe, but we can optimize by only using square-free y.
    # However, for simplicity and correctness, we can just generate and use a set, 
    # or generate with all y and sort+unique.
    # Given M=200M, number of powerful numbers is roughly M / (2 * sqrt(pi^2/6)) ? No, density is ~ 1/sqrt(x).
    # Count is approx sum_{y=1}^{M^{1/3}} sqrt(M/y^3) = sqrt(M) * sum y^{-3/2} ~ sqrt(M) * C.
    # For M=200M, sqrt(M) ~ 14142. Sum converges fast.
    # Let's estimate count: ~ 100,000 to 200,000?
    # Actually, number of powerful numbers <= N is ~ 1.05 * sqrt(N).
    # So for 200M, ~ 1.05 * 14142 ~ 14800.
    # Wait, 1.05 * sqrt(200,000,000) = 1.05 * 14142 = 14849.
    # This is small enough that O(N^2) is 2e8 operations, which might be too slow in pure Python,
    # but numpy vectorization makes it fast.
    
    # Let's refine the generation to be fast.
    # We'll use a set to avoid duplicates if we don't filter square-free y.
    # But filtering square-free y is better for generation efficiency.
    # A number y is square-free if no p^2 divides y.
    
    # Simple generation:
    # for y in range(1, max_y+1):
    #    y3 = y**3
    #    if y3 > M: break
    #    max_x = isqrt(M // y3)
    #    for x in range(1, max_x+1):
    #       powerful.append(x*x*y3)
    
    # This generates duplicates if y is not square-free.
    # Example: y=4, y^3=64. x=1 -> 64.
    # y=2, y^3=8. x=2 -> 4*8=32. x=... 
    # Wait, 64 = 1^2 * 4^3. Also 64 = 4^2 * 2^3? No 16*8=128.
    # 64 = 8^2 * 1^3.
    # So 64 is generated by y=1, x=8 AND y=4, x=1.
    # So we must use a set or unique filter.
    
    # Let's use a set for generation, then convert to sorted list.
    powerful_set = set()
    for y in range(1, max_y + 1):
        y3 = y ** 3
        if y3 > M:
            break
        max_x = isqrt(M // y3)
        for x in range(1, max_x + 1):
            p = x * x * y3
            powerful_set.add(p)
            
    powerful_list = sorted(powerful_set)
    powerful_arr = np.array(powerful_list, dtype=np.int64)
    n_pow = len(powerful_list)
    
    # 2. Count sums using NumPy
    # We want to count pairs (i, j) with i <= j such that powerful[i] + powerful[j] = S.
    # We can do this by iterating i and adding counts for all j >= i.
    # Sum array size: max sum is 2*M.
    sum_arr_size = 2 * M + 1
    counts = np.zeros(sum_arr_size, dtype=np.int32)
    
    # Time check
    if time.time() - start_time > timeout - 10:
        # Fallback if generation took too long (unlikely)
        return {'N': 2, 'pairs': [[1, 1]]}

    # Vectorized accumulation
    # For each i, we add 1 to counts[powerful[i] + powerful[j]] for all j in [i, n_pow)
    # This is equivalent to:
    # for i in range(n_pow):
    #     counts[powerful[i] + powerful_arr[i:]] += 1
    
    # This loop is O(N^2) in the number of elements updated, but each step is vectorized.
    # Total operations ~ N^2 / 2.
    # If N ~ 15000, N^2 ~ 2.25e8.
    # NumPy can do ~1e8-1e9 simple ops/sec.
    # So this should take ~ 0.2 - 2 seconds.
    
    for i in range(n_pow):
        if time.time() - start_time > timeout - 5:
            break
        # Add 1 to the slice of counts corresponding to sums with powerful[i]
        # We only count pairs a <= b, so j >= i
        # The indices are powerful[i] + powerful_arr[i:]
        indices = powerful[i] + powerful_arr[i:]
        # np.add.at is safe for repeated indices, but here indices are unique within a single step?
        # powerful_arr is sorted and unique. So powerful[i] + powerful_arr[i:] is strictly increasing.
        # So simple addition is fine and faster than np.add.at.
        counts[indices] += 1
        
    # 3. Find the best N
    # We need N <= 10^18. Since max N here is 4e7, this is always true.
    # We also need N >= 2.
    
    # Find index of max count
    # Note: counts[0] and counts[1] are 0.
    max_count = np.max(counts)
    if max_count == 0:
        return {'N': 2, 'pairs': [[1, 1]]}
    
    # Find the N with max count
    # If there are multiple, pick the smallest N? Or any?
    # The task says "Maximize. The score is the number of pairs".
    # So any N with max_count is optimal for this M.
    best_N = np.argmax(counts)
    
    # 4. Reconstruct pairs
    pairs = []
    # We need to find all a in powerful_list such that a <= best_N/2 and best_N - a is in powerful_set.
    # Since powerful_list is sorted, we can iterate.
    # To be efficient, we can use a set for O(1) lookup.
    # powerful_set is already created.
    
    for a in powerful_list:
        if a > best_N // 2:
            break
        b = best_N - a
        if b in powerful_set:
            pairs.append([a, b])
            
    # The score is the number of pairs.
    # We should verify that the number of pairs matches the count?
    # The count included pairs (i,j) with i<=j.
    # Our reconstruction finds a <= b.
    # So it should match.
    
    return {'N': int(best_N), 'pairs': pairs}

# Test
if __name__ == "__main__":
    res = construct()
    print(f"N: {res['N']}, Pairs: {len(res['pairs'])}")
