    # The [17,8,6] code can be generated by taking the 8x17 matrix where
    # G[i][j] = 1 if (j+1) * inv(2^i) mod 17 is in Q, for j=0..16
    # Wait, that's not quite right either.
    
    # Let me use a different well-known construction:
    # The [17,8,6] code is the first-order Reed-Muller-like code... no.
    # 
    # Actually, let me just hardcode a generator matrix for the [17,8,6] code.
    # The code is equivalent to the one with generator matrix:
    
    # Let me construct it via the standard QR code method.
    # The [17,8,6] code has a generator matrix G where:
    # G = [I_8 | P] for some 8x9 matrix P
    # The dual code is [17,9,5].
    
    # I'll use the following approach: generate all 256 codewords by
    # computing the QR code properly.
    
    # Quadratic residues mod 17:
    Q = set()
    for x in range(1, 17):
        Q.add((x * x) % 17)
    # Q = {1, 4, 9, 16, 8, 2, 15, 13}
    
    # The [17,8,6] code: codewords are vectors c in F2^17 such that
    # sum_{q in Q} c_q * omega^{q*k} = 0 for appropriate conditions...
    
