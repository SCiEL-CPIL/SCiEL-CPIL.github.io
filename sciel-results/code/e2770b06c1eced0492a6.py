def _verify(res):
    """Symbolic check: sum_c U[a,c]*V[b,c] must equal 1 iff a and b share j."""
    n, m, p = 3, 4, 6
    U, V, W = res["U"], res["V"], res["W"]
    rank = len(U[0])
    for a in range(n * m):
        for b in range(m * p):
            i, j = divmod(a, m)
            j2, k = divmod(b, p)
            s = 0
            for c in range(rank):
                if U[a][c] and V[b][c]:
                    s += U[a][c] * V[b][c]
            if (j == j2 and s != 1) or (j != j2 and s != 0):
                return False
    # W consistency: for each (j,k), the i-row coefficients must match U's i-coeffs.
    for c in range(rank):
        # gather the j,k that this column touches via V
        jks = []
        for b in range(m * p):
            if V[b][c]:
                j2, k = divmod(b, p)
                jks.append((j2, k, V[b][c]))
        # for each (j,k) present, check W[i,k] == U[i,j]
        seen = set()
        for (j2, k, vv) in jks:
            if (j2, k) in seen:
                continue
            seen.add((j2, k))
            for i in range(n):
                wval = W[k * n + i][c]
                uval = U[i * m + j2][c]
                if wval != uval:
                    return False
    return True


