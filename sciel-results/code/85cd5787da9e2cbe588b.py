import numpy as np
import time

class Optimizer:
    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

    def __call__(self, func):
        start_time = time.time()
        time_limit = 280  # 20s buffer before 300s kill
        
        calls_made = 0
        best_x = None
        best_f = float('inf')

        def evaluate(x):
            nonlocal calls_made, best_x, best_f
            if time.time() - start_time > time_limit:
                raise TimeoutError()
            if calls_made >= self.budget:
                raise RuntimeError()
            
            calls_made += 1
            try:
                f_val = func(x)
            except Exception:
                return best_f if best_f != float('inf') else 0.0
            
            if f_val < best_f:
                best_f = f_val
                best_x = np.array(x)
            return f_val

        N = self.dim
        budget = self.budget
        
        # Phase 1: Sparse Grid Search for Global Basin Identification
        # 3^5 = 243 points. This is deterministic and covers the space [-5, 5]
        # with a step size of 5.0.
        # This addresses the "STAGNATION" directive by using a structural change:
        # grid-based multi-start instead of pure stochastic evolution.
        
        # We need to be careful with budget. 243 calls is ~48% of 500.
        # If budget is small, we might skip or reduce grid.
        # For budget=500, we do full grid.
        
        grid_points = []
        if budget >= 250:
            # 3 levels: -5, 0, 5
            levels = [-5.0, 0.0, 5.0]
            # Generate 3^N grid
            import itertools
            for combo in itertools.product(levels, repeat=N):
                grid_points.append(np.array(combo))
        else:
            # Fallback for small budgets: just center and corners?
            # But task says budget=500.
            grid_points = [np.zeros(N)]

        # Evaluate grid
        grid_results = []
        try:
            for x in grid_points:
                f_val = evaluate(x)
                grid_results.append((f_val, x))
        except (TimeoutError, RuntimeError):
            pass

        # Sort grid results by fitness
        grid_results.sort(key=lambda x: x[0])
        
        # Select top K basins
        K = 5
        top_basins = []
        for f_val, x in grid_results[:K]:
            top_basins.append(x)
        
        # If grid search used all budget, we are done.
        if calls_made >= budget:
            return best_x, best_f

        # Phase 2: Local Polish with Nelder-Mead
        # We allocate the remaining budget to local searches.
        # We want to run Nelder-Mead from each of the top K basins.
        # To ensure fair distribution, we split remaining budget among K basins.
        # However, Nelder-Mead is iterative. It's better to run them sequentially
        # and stop if budget runs out, prioritizing the best grid points first.
        
        # We'll use scipy.optimize.minimize with Nelder-Mead.
        # We need a wrapper that tracks calls and respects time/budget.
        
        def nm_wrapper(x):
            nonlocal calls_made, best_x, best_f
            if time.time() - start_time > time_limit:
                raise TimeoutError()
            if calls_made >= self.budget:
                raise RuntimeError()
            
            calls_made += 1
            try:
                f_val = func(x)
            except Exception:
                return best_f if best_f != float('inf') else 0.0
            
            if f_val < best_f:
                best_f = f_val
                best_x = np.array(x)
            return f_val

        # Determine how many iterations we can afford per basin.
        # Nelder-Mead uses N+1 function evaluations per iteration (approx).
        # Let's just let it run until it hits the global budget limit via the wrapper.
        # We will iterate through the top basins.
        
        from scipy.optimize import minimize
        
        for start_x in top_basins:
            if calls_made >= budget or time.time() - start_time > time_limit:
                break
                
            try:
                # Initial simplex
                # Standard Nelder-Mead simplex is generated by scipy if not provided.
                # We can provide one to control step size.
                # Step size of 0.5 is reasonable given the grid spacing was 5.
                initial_simplex = [start_x]
                for i in range(N):
                    x_i = start_x.copy()
                    x_i[i] += 0.5
                    initial_simplex.append(x_i)
                
                # Run Nelder-Mead
                # maxiter is a soft limit; the wrapper will hard-stop on budget.
                # We set a high maxiter to allow it to run as long as it makes progress.
                res = minimize(
                    nm_wrapper, 
                    start_x, 
                    method='Nelder-Mead', 
                    options={
                        'maxiter': 1000, 
                        'xatol': 1e-8, 
                        'fatol': 1e-8,
                        'initial_simplex': initial_simplex,
                        'adaptive': True
                    }
                )
                if res.fun < best_f:
                    best_f = res.fun
                    best_x = np.array(res.x)
                    
            except (TimeoutError, RuntimeError):
                break
            except Exception:
                pass

        return best_x, best_f
