"""Search-based approach to maximize set size under divisibility constraint on subset sums."""
import time
import random

# EVOLVE-BLOCK-START

DEADLINE_SECONDS = 85.0


def _subset_sums_incr(sums_set, x):
    """Given existing subset sums set (nonempty), add x to all and to itself.
    Returns the new set of subset sums for the augmented list."""
    return sums_set | {s + x for s in sums_set} | {x}


def _divisibility_conflict(sums_set):
    """Check if any two distinct values in sums_set divide one another.
    Returns True if conflict exists (invalid), False otherwise."""
    if len(sums_set) < 2:
        return False
    vals = sorted(sums_set)
    n = len(vals)
    max_val = vals[-1]
    for i in range(n):
        vi = vals[i]
        if vi > max_val // 2:
            continue
        multiple = vi * 2
        while multiple <= max_val:
            if multiple in sums_set:
                return True
            multiple += vi
    return False

def _has_conflict_incremental(old_sums, new_sums):
    """
    Check if adding new_sums to old_sums creates a divisibility conflict.
    Assumes old_sums is internally valid.
    new_sums are the sums generated by adding the new element.
    Returns True if conflict exists.
    """
    # 1. Check for duplicate sums
    if new_sums & old_sums:
        return True

    # 2. Check cross conflicts: old vs new
    # We need to check if any a in old, b in new: a|b or b|a.
    max_old = max(old_sums) if old_sums else 0
    
    for b in new_sums:
        # Check if b divides any a in old_sums
        # i.e., is there a in old_sums such that a % b == 0?
        # a must be a multiple of b.
        if b > 0:
            multiple = b * 2
            while multiple <= max_old:
                if multiple in old_sums:
                    return True
                multiple += b
        
        # Check if any a in old_sums divides b
        # i.e., is there a in old_sums such that b % a == 0?
        # a must be a divisor of b.
        # Iterate through divisors of b.
        i = 1
        while i * i <= b:
            if b % i == 0:
                if i in old_sums:
                    return True
                other = b // i
                if other != i and other in old_sums:
                    return True
            i += 1

    # 3. Check conflicts within new_sums
    if _divisibility_conflict(new_sums):
        return True

    return False


def _is_valid_set(elements):
    """Full validation: all nonempty subset sums, no two distinct divide each other."""
    n = len(elements)
    if n == 0:
        return True
    sums_set = set()
    for x in elements:
        sums_set = _subset_sums_incr(sums_set, x)
    return not _divisibility_conflict(sums_set)


def _greedy_randomized(elements_pool, rng, max_size=30, time_limit=None):
    """Randomized greedy: repeatedly pick a random element that keeps validity."""
    current = []
    sums_set = set()
    remaining = list(elements_pool)
    rng.shuffle(remaining)

    if time_limit is not None:
        deadline = time.time() + time_limit
    else:
        deadline = None

    while len(current) < max_size and remaining:
        found = False
        for i in range(len(remaining)):
            x = remaining[i]
            new_sums = _subset_sums_incr(sums_set, x)
            if not _has_conflict_incremental(sums_set, new_sums):
                current.append(x)
                sums_set = new_sums
                remaining.pop(i)
                found = True
                break
            if deadline is not None and time.time() > deadline:
                break
        if not found:
            break
        if deadline is not None and time.time() > deadline:
            break

    return current


def _greedy_order_based(elements_pool, order, max_size=30, time_limit=None):
    """Greedy: try elements in given order, add if valid."""
    current = []
    sums_set = set()

    if time_limit is not None:
        deadline = time.time() + time_limit
    else:
        deadline = None

    for x in order:
        if len(current) >= max_size:
            break
        if deadline is not None and time.time() > deadline:
            break
        new_sums = _subset_sums_incr(sums_set, x)
        if not _has_conflict_incremental(sums_set, new_sums):
            current.append(x)
            sums_set = new_sums

    return current


def _local_search(current, sums_set, pool, rng, max_size=30, time_limit=None):
    """Try to extend current set by swapping elements or adding new ones."""
    if not current:
        return current, sums_set
    
    if time_limit is not None:
        deadline = time.time() + time_limit
    else:
        deadline = None
    
    current = list(current)
    current_set = set(current)
    remaining = [x for x in pool if x not in current_set]
    
    improved = True
    while improved and len(current) < max_size:
        if deadline is not None and time.time() > deadline:
            break
        improved = False
        rng.shuffle(remaining)
        
        # Try adding
        for x in remaining:
            if deadline is not None and time.time() > deadline:
                break
            new_sums = _subset_sums_incr(sums_set, x)
            if not _has_conflict_incremental(sums_set, new_sums):
                current.append(x)
                current_set.add(x)
                sums_set = new_sums
                remaining.remove(x)
                improved = True
                break
        
        # Try swapping
        if not improved:
            for i in range(len(current)):
                if deadline is not None and time.time() > deadline:
                    break
                old = current[i]
                # Remove old
                temp_sums = set()
                for x in current:
                    if x != old:
                        temp_sums = _subset_sums_incr(temp_sums, x)
                
                for x in remaining:
                    if deadline is not None and time.time() > deadline:
                        break
                    new_sums = _subset_sums_incr(temp_sums, x)
                    if not _has_conflict_incremental(temp_sums, new_sums):
                        current[i] = x
                        current_set.discard(old)
                        current_set.add(x)
                        sums_set = new_sums
                        remaining.remove(x)
                        improved = True
                        break
                if improved:
                    break
    
    return current, sums_set


def construct():
    start_time = time.time()
    deadline = start_time + DEADLINE_SECONDS

    # Candidate pool: focus on upper half to reduce divisibility risks
    # Numbers in [129, 256] are less likely to divide sums of other numbers
    pool_upper = list(range(129, 257))
    pool_full = list(range(1, 257))

    best = []
    best_size = 0

    rng = random.Random(42)

    # Strategy 1: Greedy on upper pool, descending (largest first)
    order_desc = sorted(pool_upper, reverse=True)
    t_remaining = deadline - time.time()
    if t_remaining > 0.5:
        result = _greedy_order_based(pool_upper, order_desc, max_size=30, time_limit=min(t_remaining - 0.1, 5.0))
        if len(result) > best_size:
            best = result
            best_size = len(result)

    # Strategy 2: Randomized greedy on upper pool with local search
    num_restarts = 200
    for r in range(num_restarts):
        if time.time() > deadline - 2.0:
            break
        t_remaining = deadline - time.time() - 2.0
        if t_remaining < 0.3:
            break

        # Shuffle upper pool
        pool_shuffled = list(pool_upper)
        rng.shuffle(pool_shuffled)
        
        # Vary the order strategy
        if r % 7 == 0:
            pool_shuffled.sort()
        elif r % 7 == 1:
            pool_shuffled.sort(reverse=True)
        elif r % 7 == 2:
            # Start with middle values
            mid = len(pool_shuffled) // 2
            pool_shuffled = pool_shuffled[mid:] + pool_shuffled[:mid]
        # else keep shuffled

        result = _greedy_randomized(pool_shuffled, rng, max_size=30, time_limit=min(t_remaining - 1.0, 0.5))
        
        # Apply local search to extend
        if result:
            sums_set = set()
            for x in result:
                sums_set = _subset_sums_incr(sums_set, x)
            
            t_ls = deadline - time.time() - 1.0
            if t_ls > 0.2:
                result, sums_set = _local_search(result, sums_set, pool_full, rng, max_size=30, time_limit=min(t_ls, 1.0))
        
        if len(result) > best_size:
            best = result
            best_size = len(result)

    # Strategy 3: Try to extend best set with full pool (including small numbers)
    # Small numbers are risky, but if we have a large set of large numbers,
    # maybe a small number fits? Unlikely, but check.
    if best and time.time() < deadline - 2.0:
        current = list(best)
        sums_set = set()
        for x in current:
            sums_set = _subset_sums_incr(sums_set, x)
        
        # Check full pool in random order
        remaining_pool = [x for x in pool_full if x not in set(best)]
        rng.shuffle(remaining_pool)
        
        for x in remaining_pool:
            if time.time() > deadline - 1.0:
                break
            if len(current) >= 30:
                break
            new_sums = _subset_sums_incr(sums_set, x)
            if not _divisibility_conflict(new_sums):
                current.append(x)
                sums_set = new_sums
        
        if len(current) > best_size:
            best = current
            best_size = len(best)

    # Final local search on best
    if best and time.time() < deadline - 1.0:
        sums_set = set()
        for x in best:
            sums_set = _subset_sums_incr(sums_set, x)
        
        t_final = deadline - time.time() - 0.5
        if t_final > 0.3:
            best, sums_set = _local_search(best, sums_set, pool_full, rng, max_size=30, time_limit=min(t_final, 2.0))

    # Verify best is valid
    if best:
        if not _is_valid_set(best):
            best = [129, 130, 131]

    result = [int(x) for x in best]
    return result

