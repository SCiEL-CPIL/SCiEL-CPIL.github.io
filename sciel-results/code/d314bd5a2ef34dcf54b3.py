import time
import random
import sys

def construct():
    start_time = time.time()
    DEADLINE = 55.0  # Safety margin for 60s limit
    max_val = 4096
    
    # Helper to check if adding x is valid
    def can_add(S, used_sums, x):
        # 1. x + x + x
        s1 = 3 * x
        if s1 in used_sums:
            return False
        
        # 2. x + x + s
        for s in S:
            s2 = 2 * x + s
            if s2 in used_sums:
                return False
            
        # 3. x + s_i + s_j
        # We need to check all pairs (i, j) with i <= j
        # Note: s_i + s_j + x must not be in used_sums
        # Also, we must ensure that the new sums don't collide with EACH OTHER?
        # No, the problem states "Every unordered triple... must have a different sum".
        # This implies all sums generated by the set S must be unique.
        # When adding x, we generate new sums.
        # We must check:
        # a) New sums are not in used_sums (old sums)
        # b) New sums are unique among themselves.
        
        # Let's check uniqueness among new sums.
        new_sums = set()
        new_sums.add(s1)
        
        for s in S:
            s2 = 2 * x + s
            if s2 in used_sums or s2 in new_sums:
                return False
            new_sums.add(s2)
            
        for i in range(len(S)):
            for j in range(i, len(S)):
                s3 = x + S[i] + S[j]
                if s3 in used_sums or s3 in new_sums:
                    return False
                new_sums.add(s3)
                
        return True

    def get_sums_for(x, S):
        """Calculate the sums contributed by x given the rest of the set S (excluding x)."""
        sums = set()
        sums.add(3*x)
        for s in S:
            sums.add(2*x + s)
        for i in range(len(S)):
            for j in range(i, len(S)):
                sums.add(x + S[i] + S[j])
        return sums

    def add_to_state(S, used_sums, x):
        S_k = S[:-1] # Assuming x was just appended
        sums_to_add = get_sums_for(x, S_k)
        for s_val in sums_to_add:
            used_sums.add(s_val)

    def remove_from_state(S, used_sums, x):
        # S contains x. We need to remove sums generated by x with other elements in S\{x}
        S_temp = S[:S.index(x)] + S[S.index(x)+1:]
        sums_to_remove = get_sums_for(x, S_temp)
        for s_val in sums_to_remove:
            used_sums.discard(s_val) # discard is safer if something went wrong

    # Fast Greedy first to get a good initial bound
    S = []
    used_sums = set()
    
    for x in range(1, max_val + 1):
        if can_add(S, used_sums, x):
            S.append(x)
            add_to_state(S, used_sums, x)
            
    best_set = list(S)
    best_len = len(S)
    
    # Local Search
    # We maintain S and used_sums.
    # Moves:
    # 1. Add x (if valid) -> Size +1
    # 2. Remove y, Add x1, Add x2 (if valid) -> Size +1
    # 3. Swap y with x (if valid) -> Size 0, better structure?
    
    no_improvement_count = 0
    max_no_improvement = 500 # Increase restart tolerance
    
    while time.time() - start_time < DEADLINE:
        improved = False
        
        # Phase 1: Try to add a single element
        # To avoid bias, we can shuffle the candidates or just scan.
        # Scanning 1..4096 is ~4096 checks. Each check is O(N^2).
        # If N=16, N^2=256. 4096*256 ~ 1M ops. ~0.1s.
        # We can do this a few times per second.
        
        added = False
        # We scan all candidates to ensure we don't miss a valid one.
        # However, if we just added one, the state changed.
        # We break after one add to allow the loop to re-evaluate the whole space.
        
        # Optimization: If N is large, checking all 4096 is expensive.
        # But N is likely < 30.
        
        for x in range(1, max_val + 1):
            if x in S:
                continue
            if can_add(S, used_sums, x):
                S.append(x)
                add_to_state(S, used_sums, x)
                best_set = list(S)
                best_len = len(S)
                improved = True
                added = True
                break
        
        if not added:
            # Phase 2: Try 2-for-1 move
            # Pick a random element to remove
            if len(S) > 2:
                idx_remove = random.randint(0, len(S) - 1)
                y = S[idx_remove]
                
                # Remove y
                S_temp = S[:idx_remove] + S[idx_remove+1:]
                sums_y = get_sums_for(y, S_temp)
                
                for s_val in sums_y:
                    used_sums.discard(s_val)
                S.pop(idx_remove)
                
                # Now try to add two elements x1, x2
                success = False
                
                # To make this faster, we can try to find x1 that allows x2.
                # Or just random sampling.
                # Random sampling might be slow if valid x1s are rare.
                # Let's try scanning for x1, and for each x1, scan for x2.
                # This is O(4096 * 4096 * N^2) which is too slow.
                
                # Better: Randomly sample x1. If valid, randomly sample x2.
                # If we fail many times, revert.
                
                attempts = 0
                max_attempts = 50 # Limit attempts to save time
                
                while attempts < max_attempts and not success:
                    attempts += 1
                    x1 = random.randint(1, max_val)
                    if x1 in S:
                        continue
                    if can_add(S, used_sums, x1):
                        # Tentatively add x1
                        sums_x1 = get_sums_for(x1, S)
                        S.append(x1)
                        for s_val in sums_x1:
                            used_sums.add(s_val)
                        
                        # Now try to add x2
                        x2_found = False
                        # Try a few random x2s or scan?
                        # Scanning x2 is 4096 * N^2. If we do this for 50 x1s, it's 50 * 1M = 50M ops.
                        # Might be too slow in Python.
                        # Let's just random sample x2 as well.
                        for _ in range(20):
                            x2 = random.randint(1, max_val)
                            if x2 in S or x2 == x1:
                                continue
                            if can_add(S, used_sums, x2):
                                # Success! Add x2
                                sums_x2 = get_sums_for(x2, S)
                                S.append(x2)
                                for s_val in sums_x2:
                                    used_sums.add(s_val)
                                success = True
                                improved = True
                                best_set = list(S)
                                best_len = len(S)
                                x2_found = True
                                break
                            
                        if not x2_found:
                            # Rollback x1
                            S.pop()
                            for s_val in sums_x1:
                                used_sums.discard(s_val)
                
                if not success:
                    # Rollback removal of y
                    S.append(y)
                    for s_val in sums_y:
                        used_sums.add(s_val)
                    
            # Phase 3: Random Swap (to escape local minima)
            # Swap y with x
            if len(S) > 0 and random.random() < 0.2:
                idx_remove = random.randint(0, len(S) - 1)
                y = S[idx_remove]
                S_temp = S[:idx_remove] + S[idx_remove+1:]
                sums_y = get_sums_for(y, S_temp)
                
                for s_val in sums_y:
                    used_sums.discard(s_val)
                S.pop(idx_remove)
                
                swapped = False
                for _ in range(20):
                    x = random.randint(1, max_val)
                    if x in S:
                        continue
                    if can_add(S, used_sums, x):
                        S.append(x)
                        sums_x = get_sums_for(x, S)
                        for s_val in sums_x:
                            used_sums.add(s_val)
                        swapped = True
                        break
                
                if not swapped:
                    # Rollback
                    S.append(y)
                    for s_val in sums_y:
                        used_sums.add(s_val)
                else:
                    # Swapped successfully. 
                    pass
        
        if not improved:
            no_improvement_count += 1
            if no_improvement_count > 1000:
                # Restart with a different random seed or strategy?
                # For now, just continue. The random swaps should help.
                # We could also try a full restart from a random greedy start.
                pass
        else:
            no_improvement_count = 0
            
    return best_set
