    # B: p(6), n(4)
    # C: C12(5), C22(8)
    # W[5,15]=1, W[8,15]=1
    U[3, 15] = 1; U[2, 15] = -1
    V[6, 15] = 1; V[4, 15] = 1
    W[5, 15] = 1; W[8, 15] = 1
    
    # Term 17: (b+c+h+i)(k+l+q+r)
    # A: b(1), c(2), h(7), i(8)
    # B: k(1), l(2), q(7), r(8)
    # C: C01(1), C02(2), C11(4), C12(5), C21(7), C22(8)
    # W[1,16]=1, W[2,16]=1, W[4,16]=1, W[5,16]=1, W[7,16]=1, W[8,16]=1
    U[1, 16] = 1; U[2, 16] = 1; U[7, 16] = 1; U[8, 16] = 1
    V[1, 16] = 1; V[2, 16] = 1; V[7, 16] = 1; V[8, 16] = 1
    W[1, 16] = 1; W[2, 16] = 1; W[4, 16] = 1; W[5, 16] = 1; W[7, 16] = 1; W[8, 16] = 1
    
    # Term 18: (h+i-b-c)(k+l+q+r)
    # A: h(7), i(8), -b(1), -c(2)
    # B: k(1), l(2), q(7), r(8)
    # C: C01(1), C02(2), C11(4), C12(5), C21(7), C22(8)
    # W[1,17]=1, W[2,17]=1, W[4,17]=1, W[5,17]=1, W[7,17]=1, W[8,17]=1
    U[7, 17] = 1; U[8, 17] = 1; U[1, 17] = -1; U[2, 17] = -1
    V[1, 17] = 1; V[2, 17] = 1; V[7, 17] = 1; V[8, 17] = 1
    W[1, 17] = 1; W[2, 17] = 1; W[4, 17] = 1; W[5, 17] = 1; W[7, 17] = 1; W[8, 17] = 1
    
    # Term 19: (b+h-c-i)(k+q-l-r)
    # A: b(1), h(7), -c(2), -i(8)
    # B: k(1), q(7), -l(2), -r(8)
    # C: C01(1), C02(2), C11(4), C12(5), C21(7), C22(8)
    # W[1,18]=1, W[2,18]=1, W[4,18]=1, W[5,18]=1, W[7,18]=1, W[8,18]=1
    U[1, 18] = 1; U[7, 18] = 1; U[2, 18] = -1; U[8, 18] = -1
    V[1, 18] = 1; V[7, 18] = 1; V[2, 18] = -1; V[8, 18] = -1
    W[1, 18] = 1; W[2, 18] = 1; W[4, 18] = 1; W[5, 18] = 1; W[7, 18] = 1; W[8, 18] = 1
    
    # Term 20: (c+i-b-h)(k+r-l-q)
    # A: c(2), i(8), -b(1), -h(7)
    # B: k(1), r(8), -l(2), -q(7)
    # C: C01(1), C02(2), C11(4), C12(5), C21(7), C22(8)
    # W[1,19]=1, W[2,19]=1, W[4,19]=1, W[5,19]=1, W[7,19]=1, W[8,19]=1
    U[2, 19] = 1; U[8, 19] = 1; U[1, 19] = -1; U[7, 19] = -1
    V[1, 19] = 1; V[8, 19] = 1; V[2, 19] = -1; V[7, 19] = -1
    W[1, 19] = 1; W[2, 19] = 1; W[4, 19] = 1; W[5, 19] = 1; W[7, 19] = 1; W[8, 19] = 1
    
