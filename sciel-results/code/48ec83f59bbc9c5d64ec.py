def _make_3x3_laderman():
    """
    Returns U, V, W for 3x3 matrix multiplication using Laderman's algorithm (rank 23).
    U, V, W are 9x23 arrays.
    """
    U = np.zeros((9, 23))
    V = np.zeros((9, 23))
    W = np.zeros((9, 23))
    
    # Indices for 3x3:
    # A: 0,1,2 / 3,4,5 / 6,7,8
    # B: 0,1,2 / 3,4,5 / 6,7,8
    # C: 0,1,2 / 3,4,5 / 6,7,8
    # U[i*m+j, k], V[j*p+k, k], W[k*n+i, k]
    # Here n=m=p=3.
    # U index: i*3+j
    # V index: j*3+k
    # W index: k*3+i
    
    # Term 1: (a+e)(j+n)
    # A: a(0), e(4)
    # B: j(0), n(4)
    # C: C00(0), C01(1), C10(3), C11(4)
    # W indices: C00 -> 0, C01 -> 1, C10 -> 3, C11 -> 4
    # W[0,0]=1, W[1,0]=1, W[3,0]=1, W[4,0]=1
    U[0, 0] = 1; U[4, 0] = 1
    V[0, 0] = 1; V[4, 0] = 1
    W[0, 0] = 1; W[1, 0] = 1; W[3, 0] = 1; W[4, 0] = 1
    
    # Term 2: (e-a)j
    # A: e(4), -a(0)
    # B: j(0)
    # C: C00(0), C10(3)
    # W[0,1]=1, W[3,1]=1
    U[4, 1] = 1; U[0, 1] = -1
    V[0, 1] = 1
    W[0, 1] = 1; W[3, 1] = 1
    
    # Term 3: a(l-o)
    # A: a(0)
    # B: l(2), -o(5)
    # C: C01(1), C02(2)
    # W[1,2]=1, W[2,2]=1
    U[0, 2] = 1
    V[2, 2] = 1; V[5, 2] = -1
    W[1, 2] = 1; W[2, 2] = 1
    
    # Term 4: e(m-j)
    # A: e(4)
    # B: m(3), -j(0)
    # C: C10(3), C11(4)
    # W[3,3]=1, W[4,3]=1
    U[4, 3] = 1
    V[3, 3] = 1; V[0, 3] = -1
    W[3, 3] = 1; W[4, 3] = 1
    
    # Term 5: (a+b)n
    # A: a(0), b(1)
    # B: n(4)
    # C: C01(1), C11(4)
    # W[1,4]=1, W[4,4]=1
    U[0, 4] = 1; U[1, 4] = 1
    V[4, 4] = 1
    W[1, 4] = 1; W[4, 4] = 1
    
    # Term 6: (d+e)j
    # A: d(3), e(4)
    # B: j(0)
    # C: C10(3), C11(4)
    # W[3,5]=1, W[4,5]=1
    U[3, 5] = 1; U[4, 5] = 1
    V[0, 5] = 1
    W[3, 5] = 1; W[4, 5] = 1
    
    # Term 7: (a-b)(j+k)
    # A: a(0), -b(1)
    # B: j(0), k(1)
    # C: C00(0), C01(1)
    # W[0,6]=1, W[1,6]=1
    U[0, 6] = 1; U[1, 6] = -1
    V[0, 6] = 1; V[1, 6] = 1
    W[0, 6] = 1; W[1, 6] = 1
    
    # Term 8: (b-a)(k+n)
    # A: b(1), -a(0)
    # B: k(1), n(4)
    # C: C01(1), C02(2)
    # W[1,7]=1, W[2,7]=1
    U[1, 7] = 1; U[0, 7] = -1
    V[1, 7] = 1; V[4, 7] = 1
    W[1, 7] = 1; W[2, 7] = 1
    
    # Term 9: (c+f)(m+p)
    # A: c(2), f(5)
    # B: m(3), p(6)
    # C: C12(5), C22(8)
    # W[5,8]=1, W[8,8]=1
    U[2, 8] = 1; U[5, 8] = 1
    V[3, 8] = 1; V[6, 8] = 1
    W[5, 8] = 1; W[8, 8] = 1
    
    # Term 10: (f-c)p
    # A: f(5), -c(2)
    # B: p(6)
    # C: C12(5), C22(8)
    # W[5,9]=1, W[8,9]=1
    U[5, 9] = 1; U[2, 9] = -1
    V[6, 9] = 1
    W[5, 9] = 1; W[8, 9] = 1
    
    # Term 11: c(o-n)
    # A: c(2)
    # B: o(5), -n(4)
    # C: C02(2), C12(5)
    # W[2,10]=1, W[5,10]=1
    U[2, 10] = 1
    V[5, 10] = 1; V[4, 10] = -1
    W[2, 10] = 1; W[5, 10] = 1
    
    # Term 12: f(m-p)
    # A: f(5)
    # B: m(3), -p(6)
    # C: C12(5), C22(8)
    # W[5,11]=1, W[8,11]=1
    U[5, 11] = 1
    V[3, 11] = 1; V[6, 11] = -1
    W[5, 11] = 1; W[8, 11] = 1
    
    # Term 13: (c+d)o
    # A: c(2), d(3)
    # B: o(5)
    # C: C02(2), C12(5)
    # W[2,12]=1, W[5,12]=1
    U[2, 12] = 1; U[3, 12] = 1
    V[5, 12] = 1
    W[2, 12] = 1; W[5, 12] = 1
    
    # Term 14: (g+f)p
    # A: g(6), f(5)
    # B: p(6)
    # C: C20(6), C22(8)
    # W[6,13]=1, W[8,13]=1
    U[6, 13] = 1; U[5, 13] = 1
    V[6, 13] = 1
    W[6, 13] = 1; W[8, 13] = 1
    
    # Term 15: (c-d)(m+p)
    # A: c(2), -d(3)
    # B: m(3), p(6)
    # C: C12(5), C22(8)
    # W[5,14]=1, W[8,14]=1
