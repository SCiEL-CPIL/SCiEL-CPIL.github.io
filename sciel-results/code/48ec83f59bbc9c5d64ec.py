    # A: a(0), g(6), -d(3), -h(7)
    # B: j(0), q(7), -m(3), -p(6)
    # C: C00(0), C01(1), C10(3), C11(4), C20(6), C21(7)
    # W[0,22]=1, W[1,22]=1, W[3,22]=1, W[4,22]=1, W[6,22]=1, W[7,22]=1
