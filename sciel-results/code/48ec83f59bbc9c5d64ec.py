    # A: a(0), d(3), g(6), h(7)
    # B: j(0), m(3), p(6), q(7)
    # C: C00(0), C01(1), C10(3), C11(4), C20(6), C21(7)
    # W[0,20]=1, W[1,20]=1, W[3,20]=1, W[4,20]=1, W[6,20]=1, W[7,20]=1
