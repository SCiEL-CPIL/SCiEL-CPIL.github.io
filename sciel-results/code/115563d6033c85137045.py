import time
import numpy as np

DIMENSIONS = [2, 4, 8]

def construct():
    deadline = time.time() + 110
    n, m, p = DIMENSIONS
    
    # The minimal rank for M_{2,4,8} is 56.
    # Constructed via 8 independent M_{2,2,2} Strassen blocks.
    
    rank = 56
    U = np.zeros((n * m, rank), dtype=int)
    V = np.zeros((m * p, rank), dtype=int)
    W = np.zeros((p * n, rank), dtype=int)
    
    col = 0
    # n=2, m=4, p=8
    # Blocks: i in {0,1}, j in {0,1,2,3}, k in {0,..,7}
    # Group into 2x2 blocks for Strassen:
    # i_block: 1 (size 2)
    # j_block: 2 (size 2)
    # k_block: 4 (size 2)
    
    for bi in range(1):
        for bj in range(2):
            for bk in range(4):
                i0 = 2 * bi
                i1 = 2 * bi + 1
                j0 = 2 * bj
                j1 = 2 * bj + 1
                k0 = 2 * bk
                k1 = 2 * bk + 1
                
                # U indices (A matrix, 2x4)
                u_a = i0 * m + j0
                u_b = i0 * m + j1
                u_c = i1 * m + j0
                u_d = i1 * m + j1
                
                # V indices (B matrix, 4x8)
                v_e = j0 * p + k0
                v_f = j0 * p + k1
                v_g = j1 * p + k0
                v_h = j1 * p + k1
                
                # W indices (C matrix, 8x2) -> W[k*n+i, r]
                w_c00 = k0 * n + i0
                w_c01 = k1 * n + i0
                w_c10 = k0 * n + i1
                w_c11 = k1 * n + i1
                
                # Strassen 7 multiplications
                # M1 = (a+d)(e+h)
                U[u_a, col] += 1; U[u_d, col] += 1
                V[v_e, col] += 1; V[v_h, col] += 1
                W[w_c00, col] += 1; W[w_c11, col] += 1
                col += 1
                
                # M2 = (c+d)e
                U[u_c, col] += 1; U[u_d, col] += 1
                V[v_e, col] += 1
                W[w_c10, col] += 1; W[w_c11, col] -= 1
                col += 1
                
                # M3 = a(f-h)
                U[u_a, col] += 1
                V[v_f, col] += 1; V[v_h, col] -= 1
                W[w_c01, col] += 1; W[w_c11, col] += 1
                col += 1
                
                # M4 = d(g-e)
                U[u_d, col] += 1
                V[v_g, col] += 1; V[v_e, col] -= 1
                W[w_c00, col] += 1; W[w_c10, col] += 1
                col += 1
                
                # M5 = (a+b)h
                U[u_a, col] += 1; U[u_b, col] += 1
                V[v_h, col] += 1
                W[w_c00, col] -= 1; W[w_c01, col] += 1
                col += 1
                
                # M6 = (c-a)(e+f)
                U[u_c, col] += 1; U[u_a, col] -= 1
                V[v_e, col] += 1; V[v_f, col] += 1
                W[w_c11, col] += 1
                col += 1
                
                # M7 = (b-d)(g+h)
                U[u_b, col] += 1; U[u_d, col] -= 1
                V[v_g, col] += 1; V[v_h, col] += 1
                W[w_c00, col] += 1
                col += 1

    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
