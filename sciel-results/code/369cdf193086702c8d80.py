"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 300

# EVOLVE-BLOCK-START
import numpy as np
import time
from scipy.optimize import minimize

def construct():
    start_time = time.time()
    deadline = start_time + 145.0  # Safety margin before 150s limit

    def compute_exact_score(pts):
        """Compute the exact packing radius for given centers."""
        if len(pts) != N:
            return -1.0
        if not np.all(np.isfinite(pts)):
            return -1.0
        
        dists = np.linalg.norm(pts, axis=1)
        if np.any(dists > 1.0):
            return -1.0
        
        i_idx, j_idx = np.triu_indices(N, k=1)
        diffs = pts[i_idx] - pts[j_idx]
        pair_dists = np.linalg.norm(diffs, axis=1)
        
        min_pair_dist = np.min(pair_dists)
        min_radial_dist = 1.0 - np.max(dists)
        
        r = min(min_pair_dist / 2.0, min_radial_dist)
        return r

    def expand_12fold(params):
        """Expand 12-fold symmetric parameters to full N=300 points.
        
        params: array of shape (25, 2) for the 25 unique points in one sector
        (sector spans 30 degrees). The remaining 275 points are generated by
        rotating the 25 unique points by multiples of 30 degrees.
        
        Actually, 300/12 = 25 points per sector.
        """
        unique_pts = params.reshape(-1, 2)
        n_unique = len(unique_pts)  # should be 25
        
        # Generate 12-fold symmetric copies
        all_pts = []
        for k in range(12):
            angle = k * 2 * np.pi / 12
            c, s = np.cos(angle), np.sin(angle)
            rot = np.array([[c, -s], [s, c]])
            rotated = unique_pts @ rot.T
            all_pts.append(rotated)
        
        return np.vstack(all_pts)  # shape (300, 2)

    def generate_hexagonal_initialization():
        """Generate a hexagonal lattice clipped to the unit circle."""
        best_pts = None
        best_score = -1.0
        
        for scale in [0.9, 0.95, 1.0, 1.05, 1.1]:
            spacing = 2.0 / (np.sqrt(N) * scale)
            
            nx = int(2.0 / spacing) + 3
            ny = int(2.0 / (spacing * np.sqrt(3.0) / 2.0)) + 3
            
            x_coords = (np.arange(-nx//2, nx//2 + 1) + 0.5) * spacing
            y_coords = (np.arange(-ny//2, ny//2 + 1)) * spacing * np.sqrt(3.0) / 2.0
            
            pts_list = []
            for i, y in enumerate(y_coords):
                offset = 0.0 if i % 2 == 0 else spacing / 2.0
                for x in x_coords:
                    px = x + offset
                    py = y
                    if np.hypot(px, py) <= 1.0 - spacing / 2.0:
                        pts_list.append([px, py])
            
            if len(pts_list) < N:
                continue
                
            pts = np.array(pts_list)
            norms = np.linalg.norm(pts, axis=1)
            idx = np.argsort(norms)
            pts = pts[idx[:N]]
            
            score = compute_exact_score(pts)
            if score > best_score:
                best_score = score
                best_pts = pts
        
        if best_pts is None:
            best_pts = np.random.rand(N, 2) * 2 - 1
            norms = np.linalg.norm(best_pts, axis=1)
            best_pts = best_pts * (0.9 / norms)[:, None]
            best_score = compute_exact_score(best_pts)
            
        return best_pts, best_score

    def extract_sector_params(pts_full):
        """Extract the 25 unique points from a full 300-point configuration
        assuming 12-fold symmetry. We pick the first 25 points as the sector."""
        return pts_full[:25].copy()

    def optimize_symmetric_12fold(pts_init, max_iter=500):
        """Optimize using 12-fold symmetry constraint.
        
        Only optimize the 25 unique points in one sector (50 parameters),
        then expand to 300 points. This reduces dimensionality by 12x.
        """
        if time.time() > deadline - 10:
            return pts_init, compute_exact_score(pts_init)
        
        # Extract sector parameters
        sector_params = extract_sector_params(pts_init)
        
        def objective(params):
            if time.time() > deadline:
                return 1e10
            
            unique_pts = params.reshape(-1, 2)
            
            if not np.all(np.isfinite(unique_pts)):
                return 1e10
            
            # Expand to full 300 points
            all_pts = expand_12fold(params)
            
            # Check radial constraints
            dists = np.linalg.norm(all_pts, axis=1)
            if np.any(dists > 1.0):
                return 1e10 + np.sum(np.maximum(dists - 1.0, 0.0))
            
            # Pairwise distances
            i_idx, j_idx = np.triu_indices(N, k=1)
            diffs = all_pts[i_idx] - all_pts[j_idx]
            pair_dists = np.linalg.norm(diffs, axis=1)
            
            min_pair_dist = np.min(pair_dists)
            min_radial_dist = 1.0 - np.max(dists)
            
            r = min(min_pair_dist / 2.0, min_radial_dist)
            return -r
        
        x0 = sector_params.flatten()
        bounds = [(-0.999, 0.999)] * 50
        
        try:
            result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds,
                             options={'maxiter': max_iter, 'maxfun': max_iter * 5,
                                      'ftol': 1e-12, 'gtol': 1e-10})
            if result.fun < 1e10:
                new_sector = result.x.reshape(-1, 2)
                new_pts = expand_12fold(new_sector.flatten())
                new_score = compute_exact_score(new_pts)
                return new_pts, new_score
        except Exception:
            pass
        
        return pts_init, compute_exact_score(pts_init)

    def optimize_with_auxiliary_t_symmetric(pts_init, max_iter=400):
        """Optimize using auxiliary variable t with 12-fold symmetry."""
        if time.time() > deadline - 10:
            return pts_init, compute_exact_score(pts_init)
        
        sector_params = extract_sector_params(pts_init)
        
        def objective(params):
            if time.time() > deadline:
                return 1e10
            
            t = params[0]
            unique_pts = params[1:].reshape(-1, 2)
            
            if not np.all(np.isfinite(unique_pts)) or not np.isfinite(t):
                return 1e10
            
            if t < 0:
                t = 0
            
            all_pts = expand_12fold(unique_pts.flatten())
            
            dists = np.linalg.norm(all_pts, axis=1)
            radial_violation = np.maximum(0, dists + t - 1.0)
            radial_penalty = np.sum(radial_violation ** 2)
            
            i_idx, j_idx = np.triu_indices(N, k=1)
            diffs = all_pts[i_idx] - all_pts[j_idx]
            pair_dists = np.linalg.norm(diffs, axis=1)
            viol = np.maximum(0, 2*t - pair_dists)
            pair_penalty = np.sum(viol ** 2)
            
            lambda_val = 100.0
            obj = -t + lambda_val * (radial_penalty + pair_penalty)
            
            return obj
        
        pts = pts_init.copy()
        dists = np.linalg.norm(pts, axis=1)
        i_idx, j_idx = np.triu_indices(N, k=1)
        diffs = pts[i_idx] - pts[j_idx]
        pair_dists = np.linalg.norm(diffs, axis=1)
        min_pair_dist = np.min(pair_dists)
        
        t_init = min(min_pair_dist / 2.0, 1.0 - np.max(dists)) * 0.95
        t_init = max(0.01, min(t_init, 0.08))
        
        x0 = np.concatenate([[t_init], sector_params.flatten()])
        bounds = [(0.001, 0.08)] + [(-0.999, 0.999)] * 50
        
        try:
            result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds,
                             options={'maxiter': max_iter, 'maxfun': max_iter * 5,
                                      'ftol': 1e-12, 'gtol': 1e-10})
            if result.fun < 1e10:
                t_opt = result.x[0]
                new_sector = result.x[1:].reshape(-1, 2)
                new_pts = expand_12fold(new_sector.flatten())
                score = compute_exact_score(new_pts)
                return new_pts, score
        except Exception:
            pass
        
        return pts_init, compute_exact_score(pts_init)

    def polish_symmetric(pts, max_iter=300):
        """Final polish with 12-fold symmetry and tight tolerance."""
        if time.time() > deadline - 5:
            return pts, compute_exact_score(pts)
        
        sector_params = extract_sector_params(pts)
        
        def objective(params):
            if time.time() > deadline:
                return 1e10
            
            unique_pts = params.reshape(-1, 2)
            
            if not np.all(np.isfinite(unique_pts)):
                return 1e10
            
            all_pts = expand_12fold(params)
            
            dists = np.linalg.norm(all_pts, axis=1)
            if np.any(dists > 1.0):
                return 1e10
            
            i_idx, j_idx = np.triu_indices(N, k=1)
            diffs = all_pts[i_idx] - all_pts[j_idx]
            pair_dists = np.linalg.norm(diffs, axis=1)
            
            min_dist = np.min(pair_dists)
            r = min(min_dist / 2.0, 1.0 - np.max(dists))
            return -r
        
        x0 = sector_params.flatten()
        bounds = [(-0.999, 0.999)] * 50
        
        try:
            result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds,
                             options={'maxiter': max_iter, 'maxfun': max_iter * 3,
                                      'ftol': 1e-14, 'gtol': 1e-12})
            if result.fun < 1e10:
                new_sector = result.x.reshape(-1, 2)
                new_pts = expand_12fold(new_sector.flatten())
                new_score = compute_exact_score(new_pts)
                if new_score > compute_exact_score(pts):
                    return new_pts, new_score
        except Exception:
            pass
        
        return pts, compute_exact_score(pts)

    def polish_unsymmetric(pts, max_iter=200):
        """Final polish without symmetry constraint for last-mile improvement."""
        if time.time() > deadline - 5:
            return pts, compute_exact_score(pts)
        
        def objective(params):
            if time.time() > deadline:
                return 1e10
            
            pts = params.reshape(-1, 2)
            
            if not np.all(np.isfinite(pts)):
                return 1e10
            
            dists = np.linalg.norm(pts, axis=1)
            if np.any(dists > 1.0):
                return 1e10
            
            i_idx, j_idx = np.triu_indices(N, k=1)
            diffs = pts[i_idx] - pts[j_idx]
            pair_dists = np.linalg.norm(diffs, axis=1)
            
            min_dist = np.min(pair_dists)
            r = min(min_dist / 2.0, 1.0 - np.max(dists))
            return -r
        
        x0 = pts.flatten()
        bounds = [(-0.999, 0.999)] * (2 * N)
        
        try:
            result = minimize(objective, x0, method='L-BFGS-B', bounds=bounds,
                             options={'maxiter': max_iter, 'maxfun': max_iter * 3,
                                      'ftol': 1e-14, 'gtol': 1e-12})
            if result.fun < 1e10:
                new_pts = result.x.reshape(-1, 2)
                new_score = compute_exact_score(new_pts)
                if new_score > compute_exact_score(pts):
                    return new_pts, new_score
        except Exception:
            pass
        
        return pts, compute_exact_score(pts)

    # Step 1: Generate initial hexagonal packing
    hex_pts, hex_score = generate_hexagonal_initialization()
    
    best_pts = hex_pts
    best_score = hex_score
    
    # Step 2: Symmetric optimization (12-fold) - main strategy
    if time.time() < deadline - 40:
        sym_pts, sym_score = optimize_symmetric_12fold(best_pts, max_iter=400)
        if sym_score > best_score:
            best_pts = sym_pts
            best_score = sym_score
    
    # Step 3: Auxiliary t with symmetry
    if time.time() < deadline - 30:
        aux_pts, aux_score = optimize_with_auxiliary_t_symmetric(best_pts, max_iter=300)
        if aux_score > best_score:
            best_pts = aux_pts
            best_score = aux_score
    
    # Step 4: Symmetric polish
    if time.time() < deadline - 15:
        pol_pts, pol_score = polish_symmetric(best_pts, max_iter=250)
        if pol_score > best_score:
            best_pts = pol_pts
            best_score = pol_score
    
    # Step 5: Unsymmetric polish for last-mile improvement
    if time.time() < deadline - 8:
        final_pts, final_score = polish_unsymmetric(best_pts, max_iter=150)
        if final_score > best_score:
            best_pts = final_pts
            best_score = final_score
    
    # Final validation
    final_score = compute_exact_score(best_pts)
    if final_score <= 0 or not np.all(np.isfinite(best_pts)):
        # Return a valid fallback
        best_pts = np.zeros((N, 2))
        n_per_row = int(np.sqrt(N))
        spacing = 0.03
        for i in range(N):
            row = i // n_per_row
            col = i % n_per_row
            best_pts[i, 0] = (col - n_per_row/2) * spacing
            best_pts[i, 1] = (row - n_per_row/2) * spacing
    
    return best_pts
# EVOLVE-BLOCK-END
