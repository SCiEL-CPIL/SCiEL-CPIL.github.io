def _lj_energy(positions):
    """Calculate the total Lennard-Jones energy for the given positions."""
    # positions shape (N, 3)
    # Compute all pair distances
    diff = positions[:, np.newaxis, :] - positions[np.newaxis, :, :]
    dist_sq = np.sum(diff**2, axis=-1)
    
    # Avoid division by zero for i=j
    np.fill_diagonal(dist_sq, 1.0)
    
    # Lennard-Jones potential: 4 * (r^-12 - r^-6)
    # r^-12 = (r^2)^-6, r^-6 = (r^2)^-3
    inv_r6 = 1.0 / (dist_sq**3)
    inv_r12 = inv_r6**2
    
    # Sum over all pairs, divide by 2 to avoid double counting
    energy = 4.0 * np.sum(inv_r12 - inv_r6) / 2.0
    
    return energy

def _foc_38():
    """
    Generate coordinates for the FCC truncated octahedron with 38 atoms.
    We generate an FCC lattice and select the 38 atoms closest to the center.
    """
    # FCC lattice points can be generated by taking integer coordinates (i, j, k)
    # such that i + j + k is even.
    # The nearest neighbor distance in this integer grid is sqrt(2).
    # We want nearest neighbor distance to be 1.0 (sigma=1).
    # So we scale by 1/sqrt(2).
    
    # Generate a sufficiently large range of indices to ensure we have at least 38 points
    # centered around 0.
    # The radius of the 38th atom in FCC is roughly... 
    # 1st: 0
    # Next shell (12 atoms): dist sqrt(2)
    # Next shell (6 atoms): dist 2
    # Next shell (24 atoms): dist sqrt(6) ~ 2.45
    # Total so far: 1 + 12 + 6 + 24 = 43 atoms.
    # So we need points up to distance sqrt(6) in the integer grid.
    # Let's use a range of -4 to 4 to be safe.
    
    points = []
    for i in range(-4, 5):
        for j in range(-4, 5):
            for k in range(-4, 5):
                if (i + j + k) % 2 == 0:
                    points.append((i, j, k))
    
    # Convert to numpy array
    points = np.array(points, dtype=float)
    
    # Calculate distance from origin for each point
    dists = np.sqrt(np.sum(points**2, axis=1))
    
    # Sort by distance
    indices = np.argsort(dists)
    
    # Take the first 38
    selected = points[indices[:38]]
    
    # Scale to have nearest neighbor distance 1.0
    # Nearest neighbor in integer grid is sqrt(2).
    # Scale factor = 1.0 / sqrt(2)
    selected = selected * (1.0 / np.sqrt(2))
    
    return selected

def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # 10s margin
    
    # Initialize with FCC truncated octahedron
    x0 = _foc_38()
    
    best_pos = x0.copy()
    best_energy = _lj_energy(best_pos)
    
    # Define objective function for optimizer
    def objective(x):
        return _lj_energy(x.reshape(-1, 3))
    
    # Use L-BFGS-B for local optimization
    # We don't have explicit bounds, but we can rely on the optimizer's behavior.
    # To be safe and fast, we just minimize.
    try:
        res = minimize(objective, x0.flatten(), method='L-BFGS-B', 
                       options={'maxiter': 1000, 'gtol': 1e-10})
        
        if res.success:
            new_pos = res.x.reshape(-1, 3)
            new_energy = res.fun
            if new_energy < best_energy:
                best_pos = new_pos
                best_energy = new_energy
    except Exception:
        pass
    
    # Check time
    if time.time() > deadline:
        return best_pos
    
    # If we have time, we can try a second pass with tighter tolerance or from a slightly perturbed start
    # But the FCC start is extremely close to the global min, so one pass is usually sufficient.
    # Let's do a second, very tight polish pass if time permits.
    if time.time() < deadline - 10.0:
        try:
            res2 = minimize(objective, best_pos.flatten(), method='L-BFGS-B', 
                           options={'maxiter': 2000, 'gtol': 1e-12})
            if res2.success:
                new_pos2 = res2.x.reshape(-1, 3)
                new_energy2 = res2.fun
                if new_energy2 < best_energy:
                    best_pos = new_pos2
                    best_energy = new_energy2
        except Exception:
            pass
            
    return best_pos
