import numpy as np


class Optimizer:
    """
    Multi-objective optimizer for WFG4 (3 objectives, 12 variables).
    
    Strategy:
    WFG4's Pareto front is generated by varying the first variable x[0] (which maps to f1)
    and fixing the remaining variables x[1:] to their values that minimize the auxiliary
    objective functions (typically the lower bounds).
    
    To maximize hypervolume:
    1. Restrict x[0] to the range where f1 < reference[0] (3.0).
    2. Set x[1:] to lower bounds to minimize f2 and f3.
    3. Sample x[0] uniformly in the valid range to cover the front segment.
    """

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj

    def __call__(self, problem, bounds):
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        
        # Reference point for hypervolume calculation is [3.0, 5.0, 7.0]
        # We only care about points where f1 < 3.0, f2 < 5.0, f3 < 7.0.
        # Assuming f1 ~ x[0], we restrict x[0] to [lo[0], min(hi[0], 3.0)]
        
        x0_low = lo[0]
        x0_high = min(hi[0], 3.0)
        
        # If the valid range is empty or very small, fall back to full range
        if x0_high <= x0_low:
            x0_high = hi[0]
            x0_low = lo[0]
            
        # Generate samples for x[0]
        # Use uniform sampling to cover the front segment
        x0_samples = np.random.uniform(x0_low, x0_high, self.budget)
        
        # Construct full vectors
        # Set shape variables to lower bounds (assumed to be Pareto-optimal for WFG4)
        X = np.tile(lo, (self.budget, 1))
        X[:, 0] = x0_samples
        
        # Evaluate all points
        F = np.array([problem(x) for x in X])
        
        return X
