import time
import numpy as np
from math import isqrt

def construct():
    start_time = time.time()
    deadline = 110.0  # Leave 10s margin
    
    # We want to maximize L.
    # K ~ 0.65 * L^(2/3)
    # Work ~ K^2 / 2 ~ 0.21 * L^(4/3)
    # If L=10^8, Work ~ 0.21 * 10^(32/3) = 0.21 * 10^10.6 ~ 8 * 10^10.
    # This might be too slow for Python+NumPy hybrid.
    # Let's estimate NumPy speed.
    # 10^9 ops/sec is optimistic for add.at.
    # Let's aim for L=10^7 first (K~30k, Work~4*10^8).
    # 4*10^8 ops is < 1s in NumPy.
    # Loop overhead 30k is negligible.
    # So L=10^7 is very safe.
    # Let's try L=2*10^7. K~45k. Work~10^9. ~1-2s.
    # Let's try L=5*10^7. K~70k. Work~2.5*10^9. ~3-5s.
    # Let's try L=10^8. K~140k. Work~10^10. ~10-20s.
    # 20s is safe.
    
    L = 100_000_000  # 10^8
    
    # Generate powerful numbers
    powerful_set = set()
    max_v = int(L ** (1/3)) + 1
    
    for v in range(1, max_v + 1):
        v_cubed = v ** 3
        if v_cubed > L:
            break
        max_u = isqrt(L // v_cubed)
        for u in range(1, max_u + 1):
            p = u * u * v_cubed
            if p <= L:
                powerful_set.add(p)
                
    powerful_list = sorted(powerful_set)
    K = len(powerful_list)
    
    # If generation took too long, we are in trouble, but it's fast.
    
    A = np.array(powerful_list, dtype=np.int64)
    
    max_sum = 2 * L
    # Allocate counts. 2*10^8 integers. 1.6 GB.
    # This is a large allocation.
    # If memory fails, we need a smaller L.
    # Let's check memory. 1.6 GB is usually okay.
    
    counts = np.zeros(max_sum + 1, dtype=np.int64)
    
    # Loop
    for i in range(K):
        if i % 5000 == 0:
            if time.time() - start_time > deadline - 10.0:
                break
        
        sums_row = A[i] + A[i:]
        np.add.at(counts, sums_row, 1)
        
    # Find best N
    # If we broke early, counts are partial, but still valid lower bound.
    # However, we need to return valid pairs.
    # The pairs for the best N found in the partial count might not be complete
    # if the loop broke.
    # But the task asks for a certified lower bound.
    # If we break, the count is a lower bound.
    # But we must ensure the pairs we return are valid.
    # The pairs we return are generated by scanning the full powerful_list.
    # So they are valid.
    # The score is the number of pairs returned.
    # If we break, the `counts` array underestimates the true count.
    # But we return the pairs we find in the final scan.
    # Wait, if we pick best_N based on partial counts, it might not be the global best.
    # But it's a valid N.
    # And we return ALL pairs for that N.
    # So the score is the true number of pairs for that N.
    # This is a valid lower bound for that N.
    # Is it the maximum? Probably not if we broke early.
    # But if we don't break, it is the maximum.
    # Given the time budget, we likely won't break.
    
    best_N = np.argmax(counts)
    
    # Construct pairs
    powerful_set_np = set(powerful_list)
    pairs = []
    for a in powerful_list:
        if a * 2 > best_N:
            break
        b = best_N - a
        if b in powerful_set_np:
            pairs.append([a, b])
            
    return {'N': int(best_N), 'pairs': pairs}
