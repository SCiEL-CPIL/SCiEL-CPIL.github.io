import time

DIMENSIONS = [2, 2, 3]

def construct():
    # Dimensions
    n, m, p = DIMENSIONS
    rank = 11
    
    # Initialize U, V, W
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # --- Part 1: Strassen for 2x2x2 (cols 0,1 of B and C) ---
    # U indices: 0:00, 1:01, 2:10, 3:11
    # V indices: 0:00, 1:01, 2:02, 3:10, 4:11, 5:12
    # W indices: 0:00, 1:10, 2:01, 3:11, 4:02, 5:12
    
    # P1
    U[0][0] += 1; U[3][0] += 1
    V[0][0] += 1; V[4][0] += 1
    W[0][0] += 1; W[3][0] += 1
    
    # P2
    U[2][1] += 1; U[3][1] += 1
    V[0][1] += 1
    W[1][1] += 1; W[3][1] += -1
    
    # P3
    U[0][2] += 1
    V[1][2] += 1; V[4][2] += -1
    W[2][2] += 1; W[3][2] += 1
    
    # P4
    U[3][3] += 1
    V[3][3] += 1; V[0][3] += -1
    W[0][3] += 1; W[1][3] += 1
    
    # P5
    U[0][4] += 1; U[1][4] += 1
    V[4][4] += 1
    W[0][4] += -1; W[2][4] += 1
    
    # P6
    U[2][5] += 1; U[0][5] += -1
    V[0][5] += 1; V[1][5] += 1
    W[3][5] += 1
    
    # P7
    U[1][6] += 1; U[3][6] += -1
    V[3][6] += 1; V[4][6] += 1
    W[0][6] += 1
    
    # --- Part 2: Schoolbook for 2x2x1 (col 2 of B and C) ---
    # Q1: A00 * B02 -> C02
    U[0][7] += 1
    V[2][7] += 1
    W[4][7] += 1
    
    # Q2: A01 * B12 -> C02
    U[1][8] += 1
    V[5][8] += 1
    W[4][8] += 1
    
    # Q3: A10 * B02 -> C12
    U[2][9] += 1
    V[2][9] += 1
    W[5][9] += 1
    
    # Q4: A11 * B12 -> C12
    U[3][10] += 1
    V[5][10] += 1
    W[5][10] += 1
    
    return {"U": U, "V": V, "W": W}
