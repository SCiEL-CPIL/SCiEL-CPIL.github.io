import math

def construct():
    # Primes congruent to 1 mod 4
    primes = [5, 13, 17, 29, 37, 41, 53, 61, 73, 89, 97, 101]
    
    # Verify N <= 10^18
    N = 1
    for p in primes:
        N *= p
        
    if N > 10**18:
        # Remove the largest prime if necessary
        primes.pop()
        N = 1
        for p in primes:
            N *= p
            
    # Function to find a^2 + b^2 = p for p = 1 mod 4
    def sum_two_squares_prime(p):
        # Simple search since p is small
        a = 1
        while a*a < p:
            b2 = p - a*a
            b = math.isqrt(b2)
            if b*b == b2:
                return (a, b)
            a += 1
        return (1, 0) # Should not happen
        
    # Gaussian integer multiplication (a+ib)*(c+id) = (ac-bd) + i(ad+bc)
    def mul_gauss(z1, z2):
        a1, b1 = z1
        a2, b2 = z2
        return (a1*a2 - b1*b2, a1*b2 + b1*a2)
        
    # Generate all representations
    # Start with 1+0i
    reps = [(1, 0)]
    
    for p in primes:
        a, b = sum_two_squares_prime(p)
        # Two factors: a+ib and a-ib
        # Actually, we need to consider all combinations.
        # The number of representations doubles at each step.
        new_reps = []
        for (x, y) in reps:
            # Multiply by a+ib
            z1 = mul_gauss((x, y), (a, b))
            # Multiply by a-ib
            z2 = mul_gauss((x, y), (a, -b))
            # Also consider conjugates of the current product?
            # The set of representations is generated by multiplying by (a+ib) or (a-ib).
            # Since we start with 1, and multiply sequentially, we get 2^k numbers.
            # These correspond to the 2^k solutions in the first quadrant (up to sign).
            new_reps.append(z1)
            new_reps.append(z2)
        reps = new_reps
        
    pairs = set()
    for (x, y) in reps:
        # x^2 + y^2 = N
        # We want pairs of powerful numbers (x^2, y^2)
        # Ensure x, y are positive
        ax = abs(x)
        ay = abs(y)
        if ax == 0 or ay == 0:
            continue
        # Ensure order
        if ax > ay:
            ax, ay = ay, ax
        # Check if ax^2 + ay^2 == N
        # It should be
        pairs.add((ax*ax, ay*ay))
        
    # Convert to list of lists
    pair_list = [[a, b] for a, b in sorted(pairs)]
    
    return {'N': N, 'pairs': pair_list}
