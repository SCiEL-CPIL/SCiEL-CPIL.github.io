import time

DIMENSIONS = [3, 3, 3]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    rank = 26
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Helper to get flattened index
    def idx(i, j, dim):
        return i * dim + j

    # 1. Strassen Core (Top-Left 2x2)
    # A indices: 00, 01, 10, 11
    # B indices: 00, 01, 10, 11
    # C indices: 00, 01, 10, 11
    
    # P1 = (A00 + A11)(B00 + B11)
    U[0][0] = 1; U[4][0] = 1
    V[0][0] = 1; V[4][0] = 1
    W[0][0] = 1; W[4][0] = 1
    
    # P2 = (A10 + A11)B00
    U[3][1] = 1; U[4][1] = 1
    V[0][1] = 1
    W[3][1] = 1; W[4][1] = -1
    
    # P3 = A00(B01 - B11)
    U[0][2] = 1
    V[1][2] = 1; V[4][2] = -1
    W[1][2] = 1; W[4][2] = 1
    
    # P4 = A11(B10 - B00)
    U[4][3] = 1
    V[3][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[3][3] = 1
    
    # P5 = (A00 + A01)B11
    U[0][4] = 1; U[1][4] = 1
    V[4][4] = 1
    W[0][4] = -1; W[1][4] = 1
    
    # P6 = (A10 - A00)(B00 + B01)
    U[3][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    W[4][5] = 1
    
    # P7 = (A01 - A11)(B10 + B11)
    U[1][6] = 1; U[4][6] = -1
    V[3][6] = 1; V[4][6] = 1
    W[0][6] = 1

    # 2. Border Terms
    # T1: A02 B20 -> C00
    U[2][7] = 1; V[6][7] = 1; W[0][7] = 1
    # T2: A02 B21 -> C01
    U[2][8] = 1; V[7][8] = 1; W[1][8] = 1
    # T3: A12 B20 -> C10
    U[5][9] = 1; V[6][9] = 1; W[3][9] = 1
    # T4: A12 B21 -> C11
    U[5][10] = 1; V[7][10] = 1; W[4][10] = 1
    
    # T5: A00 B02 -> C02
    U[0][11] = 1; V[2][11] = 1; W[2][11] = 1
    # T6: A01 B12 -> C02
    U[1][12] = 1; V[5][12] = 1; W[2][12] = 1
    # T7: A02 B22 -> C02
    U[2][13] = 1; V[8][13] = 1; W[2][13] = 1
    
    # T8: A10 B02 -> C12
    U[3][14] = 1; V[2][14] = 1; W[5][14] = 1
    # T9: A11 B12 -> C12
    U[4][15] = 1; V[5][15] = 1; W[5][15] = 1
    # T10: A12 B22 -> C12
    U[5][16] = 1; V[8][16] = 1; W[5][16] = 1
    
    # T11: A20 B00 -> C20
    U[6][17] = 1; V[0][17] = 1; W[6][17] = 1
    # T12: A21 B10 -> C20
    U[7][18] = 1; V[3][18] = 1; W[6][18] = 1
    # T13: A22 B20 -> C20
    U[8][19] = 1; V[6][19] = 1; W[6][19] = 1
    
    # T14: A20 B01 -> C21
    U[6][20] = 1; V[1][20] = 1; W[7][20] = 1
    # T15: A21 B11 -> C21
    U[7][21] = 1; V[4][21] = 1; W[7][21] = 1
    # T16: A22 B21 -> C21
    U[8][22] = 1; V[7][22] = 1; W[7][22] = 1
    
    # T17: A20 B02 -> C22
    U[6][23] = 1; V[2][23] = 1; W[8][23] = 1
    # T18: A21 B12 -> C22
    U[7][24] = 1; V[5][24] = 1; W[8][24] = 1
    # T19: A22 B22 -> C22
    U[8][25] = 1; V[8][25] = 1; W[8][25] = 1

    return {"U": U, "V": V, "W": W}
