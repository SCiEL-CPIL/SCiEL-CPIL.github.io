def get_strassen_2x2_factors():
    u = [[0]*7 for _ in range(4)]
    v = [[0]*7 for _ in range(4)]
    w = [[0]*7 for _ in range(4)]
    
    # M0 = (a00+a11)(b00+b11)
    u[0][0]=1; u[3][0]=1
    v[0][0]=1; v[3][0]=1
    w[0][0]=1; w[3][0]=1
    
    # M1 = (a10+a11)b00
    u[2][1]=1; u[3][1]=1
    v[0][1]=1
    w[2][1]=1; w[3][1]=-1
    
    # M2 = a00(b01-b11)
    u[0][2]=1
    v[1][2]=1; v[3][2]=-1
    w[1][2]=1; w[3][2]=1
    
    # M3 = a11(b10-b00)
    u[3][3]=1
    v[2][3]=1; v[0][3]=-1
    w[0][3]=1; w[2][3]=1
    
    # M4 = (a00+a01)b11
    u[0][4]=1; u[1][4]=1
    v[3][4]=1
    w[0][4]=-1; w[1][4]=1
    
    # M5 = (a10-a00)(b00+b01)
    u[0][5]=-1; u[2][5]=1
    v[0][5]=1; v[1][5]=1
    w[2][5]=1  # FIX: was w[3][5]=1
    
    # M6 = (a01-a11)(b10+b11)
    u[1][6]=1; u[3][6]=-1
    v[2][6]=1; v[3][6]=1
    w[0][6]=-1; w[3][6]=1  # FIX: was w[0][6]=1 only
    
    return u, v, w
