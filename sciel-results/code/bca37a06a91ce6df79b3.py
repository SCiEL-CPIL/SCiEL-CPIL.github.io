import numpy as np
import time
from scipy.optimize import minimize


class Optimizer:
    """Nelder-Mead with multi-start and time guard."""

    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

    def __call__(self, func):
        start_time = time.time()
        deadline = start_time + 290.0  # Safety margin
        rng = np.random.default_rng(42)
        
        # We need to track the best value found so far to return it
        # The return value is ignored, but we must not crash.
        best_val = np.inf
        best_x = np.zeros(self.dim)
        
        # Wrap the function to count calls and handle time
        call_count = 0
        def wrapper(x):
            nonlocal call_count, best_val, best_x
            if time.time() > deadline:
                raise TimeoutError()
            if call_count >= self.budget:
                raise ValueError("Budget exceeded")
            
            # Ensure x is a valid length-5 vector
            x = np.asarray(x, dtype=float).flatten()
            if x.shape[0] != self.dim:
                x = x[:self.dim] if x.shape[0] > self.dim else np.pad(x, (0, self.dim - x.shape[0]))
            
            # Clip to box
            x = np.clip(x, -5, 5)
            
            call_count += 1
            val = func(x)
            
            if val < best_val:
                best_val = val
                best_x = x.copy()
                
            return val

        # Strategy:
        # 1. Try Nelder-Mead from origin (0,0,0,0,0).
        # 2. If that fails or time remains, try random restarts.
        
        # Initial start at 0
        x0 = np.zeros(self.dim)
        
        try:
            # Nelder-Mead parameters
            # initial_simplex is generated by scipy based on x0
            # We can control the initial step size via 'xatol', 'fatol', 'maxiter'
            # Default initial step is 0.05 * (1 - x0[i]) + 0.00025 * x0[i]
            # Since x0=0, step is 0.05. This might be too small if the optimum is shifted.
            # Let's use a slightly larger initial spread if we were to define simplex manually, 
            # but scipy handles it. 
            # To be safer with shifts, we might want to start with a larger simplex.
            
            # However, standard NM is very efficient for Rosenbrock if close.
            # If not close, it might get stuck.
            # Let's try a few random starts as well.
            
            starts = [x0]
            
            # Add a few random starts spread across the box
            for _ in range(4):
                x_start = rng.uniform(-4, 4, self.dim)
                starts.append(x_start)
            
            for x_start in starts:
                if time.time() > deadline - 10: # Stop if close to deadline
                    break
                if call_count >= self.budget - 10: # Stop if close to budget
                    break
                
                try:
                    res = minimize(
                        wrapper, 
                        x_start, 
                        method='Nelder-Mead',
                        options={'xatol': 1e-6, 'fatol': 1e-6, 'maxiter': 200, 'adaptive': True}
                    )
                    # If minimize returns, update best
                    if res.fun < best_val:
                        best_val = res.fun
                        best_x = res.x
                except (TimeoutError, ValueError):
                    break
                except Exception:
                    # If NM fails for some other reason, continue to next start
                    continue
        
        except Exception:
            pass

        return best_x, best_val
# EVOLVE-BLOCK-END
