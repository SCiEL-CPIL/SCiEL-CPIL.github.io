def _greedy_order(masks, forced, order):
    """Greedy: start with forced, add candidates in order if no conflict."""
    chosen = set(forced)
    # sums of chosen
    sums = set()
    for i, x in enumerate(sorted(chosen)):
        for y in sorted(chosen)[i:]:
            sums.add(x + y)
    result = list(sorted(chosen))
    for v in order:
        if v in chosen:
            continue
        # check v against all chosen
        ok = True
        for c in chosen:
            if (v + c) in sums or (2 * v) in sums:
                ok = False
                break
        if ok:
            # add v
            for c in chosen:
                sums.add(v + c)
            sums.add(2 * v)
            chosen.add(v)
            result.append(v)
    return sorted(result)


def _local_search(result, masks, forced, fs, time_limit=10.0):
    """Try to improve by swaps/adds. Return best set found."""
    best = set(result)
    best_sums = set()
    for i, x in enumerate(sorted(best)):
        for y in sorted(best)[i:]:
            best_sums.add(x + y)
    best_size = len(best)
    t0 = time.time()
    # Try adding any candidate not in best
    while time.time() - t0 < time_limit:
        improved = False
        for v in range(1, N + 1):
            if v in best:
                continue
            ok = True
            for c in best:
                if (v + c) in best_sums or (2 * v) in best_sums:
                    ok = False
                    break
            if ok:
                for c in best:
                    best_sums.add(v + c)
                best_sums.add(2 * v)
                best.add(v)
                best_size += 1
                improved = True
        if not improved:
            break
    # Try swaps: remove one, add another
    while time.time() - t0 < time_limit:
        improved = False
        for v in range(1, N + 1):
            if v in best:
                continue
            # try to add v by removing some u
            for u in list(best):
                if u in forced:
                    continue
                # remove u, add v
                new_sums = set()
                new_best = set(best)
                new_best.discard(u)
                new_best.add(v)
                for i, x in enumerate(sorted(new_best)):
                    for y in sorted(new_best)[i:]:
                        new_sums.add(x + y)
                if len(new_sums) == len(new_best) * (len(new_best) + 1) // 2:
                    best = new_best
                    best_sums = new_sums
                    improved = True
                    break
            if improved:
                break
        if not improved:
            break
    return sorted(best)


def _branch_and_bound(masks, forced, order, initial_best, time_limit):
    """B&B over candidates in `order`, with forced pre-included."""
    best = list(initial_best)
    best_set = set(best)
    # Precompute forced mask
    forced_mask = 0
    for f in forced:
        forced_mask |= (1 << f)

    # Upper bound: number of candidates not yet decided that could still be added
    # Simple bound: remaining candidates count
    # We'll do a recursive search with bitsets.

    import sys
    sys.setrecursionlimit(10000)

    def _bound(available_mask, chosen_mask):
        """Upper bound on additional elements we can add from available_mask."""
        # Greedy upper bound: count how many can be greedily picked
        # This is expensive; use a simpler bound: popcount(available_mask)
        # But that's too loose. Use degree-based: each chosen conflicts with
        # some available, so bound = popcount(available) - min_conflicts
        # For speed, just use popcount.
        return bin(available_mask).count('1')

    def _search(chosen_mask, available_mask, depth):
        nonlocal best, best_set
        if time.time() > time_limit:
            return
        if chosen_mask == 0:
            return
        # Current size
        cur_size = bin(chosen_mask).count('1')
        # Bound
        ub = cur_size + _bound(available_mask, chosen_mask)
        if ub <= len(best):
            return
        # If no available, update best
        if available_mask == 0:
            if cur_size > len(best):
                best = [i for i in range(1, N + 1) if chosen_mask & (1 << i)]
                best_set = set(best)
            return
        # Pick next candidate from available in order
        # Find first in order that's in available
        for v in order:
            bit = 1 << v
            if available_mask & bit:
                break
        else:
            return

        # Option 1: exclude v
        _search(chosen_mask, available_mask & ~bit, depth + 1)

        # Option 2: include v
        new_chosen = chosen_mask | bit
        # Remove v and all its conflicts from available
        conflict = masks[v]
        new_avail = (available_mask & ~bit) & ~conflict
        _search(new_chosen, new_avail, depth + 1)

    # Initial: forced are chosen, available = all non-forced
    avail = 0
    for v in range(1, N + 1):
        if v not in forced:
            avail |= (1 << v)
    # Remove conflicts with forced from avail
    for f in forced:
        avail &= ~masks[f]
        avail &= ~(1 << f)

    _search(forced_mask, avail, 0)
    return best


def construct():
    t0 = time.time()
    forced, fs, masks, order = _precompute()

    # Greedy warm start
    greedy = _greedy_order(masks, forced, order)
    # Local search
    ls = _local_search(greedy, masks, forced, fs, time_limit=15.0)
    best = ls

    # B&B with remaining time
    remaining = _DEADLINE - (time.time() - t0) - 5.0  # 5s safety
    if remaining > 10.0:
        bb = _branch_and_bound(masks, forced, order, best, time.time() + remaining)
        if len(bb) > len(best):
            best = bb

    # Final validation
    result = sorted(best)
    sums = set()
    valid = True
    for i, x in enumerate(result):
        for y in result[i:]:
            s = x + y
            if s in sums:
                valid = False
                break
            sums.add(s)
        if not valid:
            break
    if not valid:
        # Fallback to greedy
        result = greedy

    return result
