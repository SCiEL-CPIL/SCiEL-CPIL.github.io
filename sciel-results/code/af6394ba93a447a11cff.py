    # The above loop is O(N^2 * |forced|) which is fine for N=284.
    # Let me redo more carefully: two candidates a,b (a<b) conflict if
    # {a+b, 2a, 2b} ∩ fs != empty.
    # Recompute properly.
    masks = [0] * (N + 1)
    for v in range(1, N + 1):
        m = 0
        for w in range(1, N + 1):
            if w == v:
                continue
            # a+b, 2a, 2b must not be in fs
            if (v + w) in fs or (2 * v) in fs or (2 * w) in fs:
                m |= (1 << w)
        masks[v] = m
