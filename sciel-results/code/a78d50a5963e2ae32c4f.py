def _can_add(x, elems, sum_bits, diff_bits, other_diff_bits):
    # Check Sidon sums
    if (sum_bits >> (2*x)) & 1:
        return False
    for y in elems:
        s = x + y
        if (sum_bits >> s) & 1:
            return False
        d = abs(x - y)
        if (diff_bits >> d) & 1:
            return False
        if (other_diff_bits >> d) & 1:
            return False
    return True

