import numpy as np
import time

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    # 1. Construct the 256-word [17, 9, 6] code
    poly = 0x11D
    
    def gf_mul(a, b):
        res = 0
        while b:
            if b & 1:
                res ^= a
            b >>= 1
            a <<= 1
            if a & 0x100:
                a ^= poly
        return res & 0xFF

    def gf_pow(a, n):
        res = 1
        base = a
        while n:
            if n & 1:
                res = gf_mul(res, base)
            base = gf_mul(base, base)
            n >>= 1
        return res

    def get_primitive_17th_root():
        for candidate in range(2, 256):
            if gf_pow(candidate, 17) == 1 and candidate != 1:
                return candidate
        return None

    beta = get_primitive_17th_root()
    
    if beta is None:
        # Fallback to seed (32 words)
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words

    # Build generator polynomial G(x)
    # The generator of the [17,9,6] code is derived from the [18,9,6] QR code.
    # The [18,9,6] code is generated by the cyclotomic cosets.
    # We can construct it directly using the known generator polynomial coefficients or by encoding.
    # Let's use the standard encoding method for the shortened code.
    
    # The [18,9,6] code is a cyclic code? No, QR codes are not cyclic in the standard sense over GF(2) for length 18?
    # Actually, the quadratic residue code of length 17 (prime) is cyclic.
    # The [17,9,6] code is the QR code itself?
    # Wait, the task says: "The 256-word linear reference is the [18,9,6] extended quadratic-residue code shortened by one coordinate".
    # The [17,9,6] code is the QR code of length 17. It is cyclic.
    # Generator polynomial of length 17 QR code:
    # Roots are quadratic residues mod 17: 1, 2, 4, 8, 16, 15, 13, 9, 5, 10, 3, 6, 12, 7, 14, 11.
    # There are 16 roots? No, 17 is prime. QRs are (17-1)/2 = 8 roots.
    # So the generator has degree 8. Code dimension 17-8=9.
    # We need the generator polynomial g(x) of degree 8.
    
    # Let's find the generator polynomial.
    # We need alpha such that alpha^17 = 1 and alpha is primitive.
    # In GF(2^8), we found beta.
    # The roots of g(x) are beta^r for r in QR(17).
    # QR(17) = {1, 2, 4, 8, 16, 15, 13, 9} ? 
    # Squares mod 17: 1^2=1, 2^2=4, 3^2=9, 4^2=16, 5^2=8, 6^2=2, 7^2=15, 8^2=13.
    # So QRs are {1, 2, 4, 8, 9, 13, 15, 16}.
    
    roots = []
    for r in [1, 2, 4, 8, 9, 13, 15, 16]:
        roots.append(gf_pow(beta, r))
        
    # Construct g(x) = prod (x - root_i)
    g_coeffs = [1]
    for root in roots:
        new_coeffs = [0] * (len(g_coeffs) + 1)
        for i in range(len(g_coeffs)):
            new_coeffs[i+1] = g_coeffs[i]
        for i in range(len(g_coeffs)):
            new_coeffs[i] ^= gf_mul(g_coeffs[i], root)
        g_coeffs = new_coeffs
        
    # g_coeffs is degree 8, so length 9.
    # g(x) = g_coeffs[8] x^8 + ... + g_coeffs[0]
    # For cyclic code encoding, we can use systematic form or just standard encoding.
    # Standard: c(x) = m(x) * g(x).
    # m(x) has degree < 9.
    
    codewords_17 = []
    for u in range(256):
        m_coeffs = [(u >> k) & 1 for k in range(9)]
        c_coeffs = [0] * 17
        for k in range(9):
            if m_coeffs[k]:
                for j in range(9):
                    c_coeffs[k+j] ^= g_coeffs[j]
        c = 0
        for i in range(17):
            if c_coeffs[i]:
                c |= (1 << i)
        codewords_17.append(c)
        
    code_set = set(codewords_17)
    if len(code_set) < 256:
        return list(code_set)
        
    code_list = list(code_set)
    used = set(code_list)
    best_size = len(code_list)
    best_code = list(code_list)
    
    rng = np.random.RandomState(42)
    
    # Local Search
    # Strategy:
    # 1. Try to add a random word.
    # 2. If it conflicts, try to repair by moving one of the conflicting words to a new random position.
    # 3. If repair succeeds, add the word.
    # 4. If repair fails, try a simple swap (replace a word with a random one that fits the others) to explore space.
    
    def try_add_candidate(candidate):
        nonlocal code_list, used, best_size, best_code
        if candidate in used:
            return False
        
        conflicts = []
        for i, w in enumerate(code_list):
            if (candidate ^ w).bit_count() < 6:
                conflicts.append(i)
                
        if not conflicts:
            code_list.append(candidate)
            used.add(candidate)
            if len(code_list) > best_size:
                best_size = len(code_list)
                best_code = list(code_list)
            return True
            
        # Try to repair
        # Pick a random conflict
        target_idx = conflicts[int(rng.randint(len(conflicts)))]
        target_word = code_list[target_idx]
        
        # Try to move target_word to a new location
        for _ in range(20):
            flip_mask = 0
            n_flips = int(rng.randint(1, 4))
            bits = list(range(17))
            rng.shuffle(bits)
            for b in bits[:n_flips]:
                flip_mask |= (1 << b)
            
            new_word = target_word ^ flip_mask
            
            if new_word == candidate or new_word in used:
                continue
                
            if (new_word ^ candidate).bit_count() < 6:
                continue
                
            valid = True
            for j, w in enumerate(code_list):
                if j == target_idx:
                    continue
                if (new_word ^ w).bit_count() < 6:
                    valid = False
                    break
                    
            if valid:
                # Replace
                used.remove(target_word)
                used.add(new_word)
                code_list[target_idx] = new_word
                # Now add candidate
                code_list.append(candidate)
                used.add(candidate)
                if len(code_list) > best_size:
                    best_size = len(code_list)
                    best_code = list(code_list)
                return True
                
        return False

    def try_swap():
        nonlocal code_list, used
        if len(code_list) < 2:
            return False
            
        idx = int(rng.randint(len(code_list)))
        old_word = code_list[idx]
        
        for _ in range(20):
            new_word = int(rng.randint(2**17))
            if new_word == old_word or new_word in used:
                continue
                
            valid = True
            for j, w in enumerate(code_list):
                if j == idx:
                    continue
                if (new_word ^ w).bit_count() < 6:
                    valid = False
                    break
                    
            if valid:
                used.remove(old_word)
                used.add(new_word)
                code_list[idx] = new_word
                return True
        return False

    iterations = 0
    while time.time() < deadline - 5:
        iterations += 1
        if iterations % 1000 == 0:
            # Occasionally restart search parameters or just continue
            pass
            
        candidate = int(rng.randint(2**17))
        if not try_add_candidate(candidate):
            # If we can't add, try to swap to explore
            if rng.random() < 0.5:
                try_swap()
            else:
                # Try to add a different candidate immediately
                candidate2 = int(rng.randint(2**17))
                try_add_candidate(candidate2)

    # Final verification
    n = len(best_code)
    valid = True
    for i in range(n):
        if time.time() > deadline - 1:
            break
        for j in range(i+1, n):
            if (best_code[i] ^ best_code[j]).bit_count() < 6:
                valid = False
                break
        if not valid:
            break
            
    if not valid:
        return list(code_set)
        
    return best_code
