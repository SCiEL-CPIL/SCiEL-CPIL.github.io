"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
import time
import math
import random

# EVOLVE-BLOCK-START
def construct():
    start_time = time.time()
    deadline = 140.0  # Safety margin before 150s kill

    def score_asymptotic(digits, base):
        """
        Estimate the score for a set generated by 'digits' in base 'base' with large k.
        Score -> 1 + log(|D-D|/|D+D|) / log(base)
        This is valid when 2*max(D) < base (no carries).
        """
        if not digits or base <= 1:
            return 0.0
        D_set = set(digits)
        if len(D_set) < 2:
            return 0.0
        max_d = max(D_set)
        min_d = min(D_set)
        
        # No-carry condition for sums
        if 2 * max_d >= base:
            # We could compute exact for small k, but for the GA we want a fast metric.
            # If carries exist, the asymptotic formula is not strictly valid for large k 
            # in the same simple way, but for the purpose of fitness in GA, 
            # we can penalize or just compute exact for small k if we decide to.
            # However, the best sets usually have no carries. 
            # Let's return a slightly penalized score or 0 to steer GA away.
            # Actually, let's just compute exact for k=1 to be safe? No, too slow for GA loop.
            # We will rely on the constraint 2*max(D) < B in the GA or handle it carefully.
            # For now, if carry exists, we can still estimate the ratio for k=1.
            # But the asymptotic limit is different. 
            # Let's just use the k=1 score if carry exists, but it won't scale as well.
            pass

        sum_d = set()
        diff_d = set()
        for a in D_set:
            for b in D_set:
                sum_d.add(a + b)
                diff_d.add(a - b)
        
        ratio = len(diff_d) / len(sum_d)
        if ratio <= 1:
            return 0.0
            
        # Asymptotic exponent
        return 1 + math.log(ratio) / math.log(base)

    def exact_score(U):
        if not U:
            return 0.0
        U_set = set(U)
        max_U = max(U_set)
        if max_U == 0:
            return 0.0
        n = len(U_set)
        sumset = set()
        diffset = set()
        for a in U_set:
            for b in U_set:
                sumset.add(a + b)
                diffset.add(a - b)
        ratio = len(diffset) / len(sumset)
        if ratio <= 0:
            return 0.0
        try:
            exponent = 1 + math.log(ratio) / math.log(2 * max_U + 1)
        except:
            return 0.0
        return exponent

    def construct_set(digits, base, k):
        U = [0]
        for i in range(k):
            factor = base ** i
            new_U = []
            for u in U:
                for d in digits:
                    new_U.append(u + d * factor)
            U = new_U
        return sorted(set(U))

    # Genetic Algorithm Setup
    # Chromosome: (base, digits_list)
    # We search over base B in [2, 20] and digits D subset of {0..B-1} containing 0.
    
    best_score = 0.0
    best_solution = None # (base, digits, k, U)
    
    # Initialize population
    pop_size = 50
    population = []
    
    # Add some heuristic seeds
    for B in [2, 3, 4, 5, 8, 10]:
        # Try {0, B-1}
        d = [0, B-1]
        if 2*max(d) < B:
             population.append((B, d))
        # Try {0, 1, B-1}
        d = [0, 1, B-1]
        if 2*max(d) < B:
             population.append((B, d))
             
    # Fill rest with random
    while len(population) < pop_size:
        B = random.randint(2, 20)
        # Random subset containing 0
        size = random.randint(2, min(6, B))
        others = random.sample(range(1, B), size-1)
        d = sorted([0] + others)
        # Ensure no carry for the fast path preference, or just allow it
        # If 2*max(d) >= B, the asymptotic score is less reliable, 
        # but we can still try.
        population.append((B, d))

    # Ensure unique
    seen = set()
    unique_pop = []
    for ind in population:
        key = (ind[0], tuple(ind[1]))
        if key not in seen:
            seen.add(key)
            unique_pop.append(ind)
    population = unique_pop

    # GA Loop
    while time.time() < deadline - 10: # Leave 10s for final exact evaluation
        # Evaluate fitness
        scored_pop = []
        for B, d in population:
            s = score_asymptotic(d, B)
            scored_pop.append((s, B, d))
        
        scored_pop.sort(key=lambda x: x[0], reverse=True)
        
        # Update best
        if scored_pop[0][0] > best_score:
            # We don't know the best k yet, but we can assume large k is good for asymptotic
            # We will refine k later. For now, store the params.
            best_score = scored_pop[0][0]
            best_B, best_d = scored_pop[0][1], scored_pop[0][2]
            # We'll determine optimal k in the final phase or here.
            # Let's just keep the top candidate.
            
        # Selection: Keep top half
        survivors = scored_pop[:pop_size//2]
        
        # Crossover and Mutation
        new_population = []
        
        # Elitism: Keep top 2
        for i in range(min(2, len(survivors))):
             new_population.append((survivors[i][1], survivors[i][2]))
             
        while len(new_population) < pop_size:
            # Crossover
            if len(survivors) >= 2 and random.random() < 0.7:
                p1 = random.choice(survivors)
                p2 = random.choice(survivors)
                B1, d1 = p1[1], p1[2]
                B2, d2 = p2[1], p2[2]
                
                # Simple crossover: Pick a base from one, digits from other?
                # Or interpolate?
                # Let's try: Randomly choose base from parents, and digits from the one with that base?
                # Or just mutate.
                if random.random() < 0.5:
                    B = B1
                    d = d1[:]
                else:
                    B = B2
                    d = d2[:]
            else:
                # Mutation from random survivor
                p = random.choice(survivors)
                B = p[1]
                d = p[2][:]
                
            # Mutation
            # 1. Change Base
            if random.random() < 0.2:
                B = random.randint(2, 20)
                # Adjust digits if base changed?
                # If new base is smaller, some digits might be invalid.
                # If new base is larger, digits are still valid.
                
            # 2. Mutate Digits
            # Remove a digit
            if len(d) > 2 and random.random() < 0.3:
                idx = random.randint(1, len(d)-1) # Keep 0
                d.pop(idx)
                d = sorted(set(d))
            # Add a digit
            if len(d) < min(8, B) and random.random() < 0.3:
                available = [x for x in range(1, B) if x not in d]
                if available:
                    new_d = random.choice(available)
                    d.append(new_d)
                    d = sorted(set(d))
            # Change a digit
            if len(d) > 1 and random.random() < 0.3:
                idx = random.randint(1, len(d)-1)
                available = [x for x in range(1, B) if x not in d]
                if available:
                    d[idx] = random.choice(available)
                    d = sorted(set(d))
                    
            # Ensure 0 is in d and d is valid for base B
            if 0 not in d:
                d.append(0)
            d = [x for x in d if 0 <= x < B]
            d = sorted(set(d))
            
            if len(d) < 2:
                # Invalid, skip or fix
                d = [0, 1]
                B = 2
                
            new_population.append((B, d))
            
        # Deduplicate new population
        seen = set()
        unique_new_pop = []
        for ind in new_population:
            key = (ind[0], tuple(ind[1]))
            if key not in seen:
                seen.add(key)
                unique_new_pop.append(ind)
        
        # If unique_new_pop is too small, refill
        while len(unique_new_pop) < pop_size:
             B = random.randint(2, 20)
             size = random.randint(2, min(6, B))
             others = random.sample(range(1, B), size-1)
             d = sorted([0] + others)
             unique_new_pop.append((B, d))
             
        population = unique_new_pop[:pop_size]
        
        # Check time
        if time.time() > deadline - 10:
            break

    # Final Phase: Determine best k for the best (B, D) found
    # We might have lost the best (B, D) if the population diverged, 
    # so we should keep track of the absolute best seen so far.
    
    # Let's re-evaluate the top few candidates from the final population 
    # and also the best seen so far (best_B, best_d).
    
    candidates = set()
    if best_B is not None:
        candidates.add((best_B, tuple(best_d)))
    for s, B, d in scored_pop[:5]: # Top 5 from last eval
        candidates.add((B, tuple(d)))
        
    # Also add some known good ones just in case
    candidates.add((3, (0, 1))) # Ratio 2/2=1? No. D={0,1}, D+D={0,1,2}, D-D={-1,0,1}. Ratio 3/3=1.
    # D={0,2} in B=5? 2*2=4<5. D+D={0,2,4}, D-D={-2,0,2}. Ratio 3/3=1.
    # D={0, 1, 3} in B=7? 2*3=6<7. 
    # D={0, 1, 4} in B=9?
    
    final_best_score = 0.0
    final_best_U = [0, 1, 3]
    
    for B, d_tuple in candidates:
        d = list(d_tuple)
        # Check no-carry
        if 2*max(d) >= B:
            # If carries exist, we can only use small k.
            # Let's try k=1, 2
            for k in [1, 2]:
                U = construct_set(d, B, k)
                s = exact_score(U)
                if s > final_best_score:
                    final_best_score = s
                    final_best_U = U
        else:
            # No carries, try large k
            # Optimal k is large. Let's try k=10, 20, 50
            # Score(k) = 1 + k * log(ratio_d) / log(2*max_U(k)+1)
            # max_U(k) = max_d * (B^k - 1)/(B-1)
            # log(max_U) ~ k log B
            # So score approaches 1 + log(ratio_d)/log(B)
            # We just need k large enough.
            for k in [5, 10, 20, 50]:
                if time.time() > deadline - 2:
                    break
                U = construct_set(d, B, k)
                if len(U) > 10000: # Too big to compute exactly in reasonable time?
                    # If no carries, we can compute score combinatorially
                    D_set = set(d)
                    sum_d = set()
                    diff_d = set()
                    for a in D_set:
                        for b in D_set:
                            sum_d.add(a + b)
                            diff_d.add(a - b)
                    ratio = (len(diff_d) ** k) / (len(sum_d) ** k)
                    max_U = max(U)
                    s = 1 + math.log(ratio) / math.log(2 * max_U + 1)
                else:
                    s = exact_score(U)
                
                if s > final_best_score:
                    final_best_score = s
                    final_best_U = U
            # Try even larger k if time permits
            if time.time() < deadline - 5:
                 k = 100
                 U = construct_set(d, B, k)
                 # Use combinatorial score
                 D_set = set(d)
                 sum_d = set()
                 diff_d = set()
                 for a in D_set:
                     for b in D_set:
                         sum_d.add(a + b)
                         diff_d.add(a - b)
                 ratio = (len(diff_d) ** k) / (len(sum_d) ** k)
                 max_U = max(U)
                 s = 1 + math.log(ratio) / math.log(2 * max_U + 1)
                 if s > final_best_score:
                     final_best_score = s
                     final_best_U = U

    # Fallback
    if final_best_U is None or final_best_score <= 0:
        return [0, 1, 3]
        
    return final_best_U

# EVOLVE-BLOCK-END
