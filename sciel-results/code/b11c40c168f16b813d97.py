import numpy as np
import time

DIMENSIONS = [3, 3, 3]

def construct():
    n, m, p = DIMENSIONS
    rank = 22
    
    U = [[0.0] * rank for _ in range(n * m)]
    V = [[0.0] * rank for _ in range(m * p)]
    W = [[0.0] * rank for _ in range(p * n)]
    
    # Strassen terms for top-left 2x2
    # Term 0: M1 = (A00+A11)(B00+B11)
    U[0][0] = 1; U[4][0] = 1
    V[0][0] = 1; V[4][0] = 1
    # C00 += M1, C11 += M1
    W[0][0] = 1 # C00 -> W[0]
    W[4][0] = 1 # C11 -> W[4]
    
    # Term 1: M2 = (A10+A11)B00
    U[3][1] = 1; U[4][1] = 1
    V[0][1] = 1
    # C10 += M2, C11 -= M2
    W[1][1] = 1 # C10 -> W[1]
    W[4][1] = -1 # C11 -> W[4]
    
    # Term 2: M3 = A00(B01-B11)
    U[0][2] = 1
    V[1][2] = 1; V[4][2] = -1
    # C01 += M3, C11 += M3
    W[3][2] = 1 # C01 -> W[3]
    W[4][2] = 1 # C11 -> W[4]
    
    # Term 3: M4 = A11(B10-B00)
    U[4][3] = 1
    V[3][3] = 1; V[0][3] = -1
    # C00 += M4, C10 += M4
    W[0][3] = 1 # C00 -> W[0]
    W[1][3] = 1 # C10 -> W[1]
    
    # Term 4: M5 = (A00+A01)B11
    U[0][4] = 1; U[1][4] = 1
    V[4][4] = 1
    # C00 -= M5, C01 += M5
    W[0][4] = -1 # C00 -> W[0]
    W[3][4] = 1 # C01 -> W[3]
    
    # Term 5: M6 = (A10-A00)(B00+B01)
    U[3][5] = 1; U[0][5] = -1
    V[0][5] = 1; V[1][5] = 1
    # C11 += M6
    W[4][5] = 1 # C11 -> W[4]
    
    # Term 6: M7 = (A01-A11)(B10+B11)
    U[1][6] = 1; U[4][6] = -1
    V[3][6] = 1; V[4][6] = 1
    # C00 += M7
    W[0][6] = 1 # C00 -> W[0]
    
    # Trivial terms for the rest
    # C02 = A00B02 + A01B12 + A02B22
    # Term 7: A00 B02
    U[0][7] = 1
    V[2][7] = 1
    W[6][7] = 1 # C02 -> W[2*3+0]=6
    
    # Term 8: A01 B12
    U[1][8] = 1
    V[5][8] = 1
    W[6][8] = 1 # C02 -> W[6]
    
    # Term 9: A02 B22
    U[2][9] = 1
    V[8][9] = 1
    W[6][9] = 1 # C02 -> W[6]
    
    # C12 = A10B02 + A11B12 + A12B22
    # Term 10: A10 B02
    U[3][10] = 1
    V[2][10] = 1
    W[7][10] = 1 # C12 -> W[2*3+1]=7
    
    # Term 11: A11 B12
    U[4][11] = 1
    V[5][11] = 1
    W[7][11] = 1 # C12 -> W[7]
    
    # Term 12: A12 B22
    U[5][12] = 1
    V[8][12] = 1
    W[7][12] = 1 # C12 -> W[7]
    
    # C20 = A20B00 + A21B10 + A22B20
    # Term 13: A20 B00
    U[6][13] = 1
    V[0][13] = 1
    W[2][13] = 1 # C20 -> W[0*3+2]=2
    
    # Term 14: A21 B10
    U[7][14] = 1
    V[3][14] = 1
    W[2][14] = 1 # C20 -> W[2]
    
    # Term 15: A22 B20
    U[8][15] = 1
    V[6][15] = 1
    W[2][15] = 1 # C20 -> W[2]
    
    # C21 = A20B01 + A21B11 + A22B21
    # Term 16: A20 B01
    U[6][16] = 1
    V[1][16] = 1
    W[5][16] = 1 # C21 -> W[1*3+2]=5
    
    # Term 17: A21 B11
    U[7][17] = 1
    V[4][17] = 1
    W[5][17] = 1 # C21 -> W[5]
    
    # Term 18: A22 B21
    U[8][18] = 1
    V[7][18] = 1
    W[5][18] = 1 # C21 -> W[5]
    
    # C22 = A20B02 + A21B12 + A22B22
    # Term 19: A20 B02
    U[6][19] = 1
    V[2][19] = 1
    W[8][19] = 1 # C22 -> W[2*3+2]=8
    
    # Term 20: A21 B12
    U[7][20] = 1
    V[5][20] = 1
    W[8][20] = 1 # C22 -> W[8]
    
    # Term 21: A22 B22
    U[8][21] = 1
    V[8][21] = 1
    W[8][21] = 1 # C22 -> W[8]
    
    return {"U": U, "V": V, "W": W}
