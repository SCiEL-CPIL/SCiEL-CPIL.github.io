def _validate(positions):
    """Check if positions are valid."""
    if not np.all(np.isfinite(positions)):
        return False
    n = len(positions)
    if n == 0:
        return True
    # Vectorized distance check
    # dists[i, j] is distance between i and j
    # We only need i < j
    diff = positions[:, np.newaxis, :] - positions[np.newaxis, :, :]
    dists = np.linalg.norm(diff, axis=2)
    # Mask upper triangle
    mask = np.triu(np.ones((n, n), dtype=bool), k=1)
    if np.any(dists[mask] < 0.35):
        return False
    return True

def _relax_and_validate(positions, kind):
    """Relax positions and return (energy, positions) if valid, else (inf, None)."""
    try:
        energy, pos = relax(positions, 'sutton_chen', kind)
        if np.all(np.isfinite(pos)) and _validate(pos):
            return energy, pos
    except:
        pass
    return np.inf, None

