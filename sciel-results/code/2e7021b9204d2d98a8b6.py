def _random_compact(n, spacing=0.72, rng=None):
    """Generate a random compact cluster."""
    if rng is None:
        rng = np.random.default_rng()
    
    radius = spacing * n ** (1.0 / 3.0) * 0.9
    points = []
    attempts = 0
    max_attempts = n * 1000
    
    while len(points) < n and attempts < max_attempts:
        p = rng.uniform(-radius, radius, 3)
        if np.linalg.norm(p) <= radius:
            # Check distance to existing points
            if points:
                dists = np.linalg.norm(np.array(points) - p, axis=1)
                if np.min(dists) >= 0.4 * spacing:
                    points.append(p)
            else:
                points.append(p)
        attempts += 1
    
    while len(points) < n:
        points.append(rng.uniform(-radius, radius, 3))
    
    return np.array(points)

def _basin_hop(positions, kind, rng, time_limit):
    """Perform basin hopping to find lower energy minima."""
    best_energy, best_pos = _relax_and_validate(positions, kind)
    if best_pos is None:
        return np.inf, positions
    
    current_energy = best_energy
    current_pos = best_pos
    
    kick_scale = 0.5
    max_iter = 50
    
    while _time_left() > time_limit and max_iter > 0:
        max_iter -= 1
        
        # Kick
        kick = rng.normal(0, kick_scale, positions.shape)
        new_pos = current_pos + kick
        
        # Relax
        new_energy, relaxed_pos = _relax_and_validate(new_pos, kind)
        
        if relaxed_pos is None:
            continue
            
        # Accept if better (greedy) or with some probability (Metropolis)
        # For global min search, greedy hill-climbing on the basin landscape is good.
        if new_energy < current_energy:
            current_energy = new_energy
            current_pos = relaxed_pos
            kick_scale = max(0.1, kick_scale * 0.9) # Anneal kick size
        else:
            # Occasionally accept worse to escape local minima?
            # Given time constraints, we stick to greedy or very conservative.
            pass
            
        if current_energy < best_energy:
            best_energy = current_energy
            best_pos = current_pos
            
    return best_energy, best_pos

def construct(instance):
    """Find near-global minimum for Sutton-Chen transition-metal clusters."""
    global _START_TIME
    _START_TIME = time.time()
    
    n = instance["n"]
    kind = instance.get("kind", "12-6")
    rng = np.random.default_rng(n * 12345 + 67890)
    
    best_energy = np.inf
    best_positions = None
    
    # Strategy:
    # 1. Generate a few diverse random starts.
    # 2. For each, run basin hopping.
    # 3. Keep the best.
    
    n_starts = 5
    time_per_start = (_time_left() - 5.0) / n_starts
    
    for i in range(n_starts):
        if _time_left() < 10.0:
            break
            
        # Generate start
        # Mix of random and "structured" random (e.g. spherical shell)
        if i == 0:
            # Try a spherical shell distribution
            radius = 0.72 * n ** (1/3)
            theta = rng.uniform(0, np.pi, n)
            phi = rng.uniform(0, 2 * np.pi, n)
            r = radius * rng.uniform(0.5, 1.0, n)
            x = r * np.sin(theta) * np.cos(phi)
            y = r * np.sin(theta) * np.sin(phi)
            z = r * np.cos(theta)
            start = np.column_stack((x, y, z))
        else:
            start = _random_compact(n, 0.72, rng)
            
        if not _validate(start):
            continue
            
        # Basin Hop
        energy, positions = _basin_hop(start, kind, rng, time_per_start)
        
        if energy < best_energy:
            best_energy = energy
            best_positions = positions
    
    if best_positions is None:
        # Fallback
        best_positions = _random_compact(n, 0.72, rng)
        # Force valid
