def get_2x2_strassen():
    # Returns U, V, W for 2x2x2, size 4x7
    U = np.zeros((4, 7))
    V = np.zeros((4, 7))
    W = np.zeros((4, 7))
    
    # M1 = (A11+A22)(B11+B22)
    # A11=0, A22=3, B11=0, B22=3
    U[0, 0] = 1; U[3, 0] = 1
    V[0, 0] = 1; V[3, 0] = 1
    W[0, 0] = 1; W[3, 0] = 1 # C11 += M1, C22 += M1
    
    # M2 = (A21+A22)B11
    # A21=2, A22=3, B11=0
    U[2, 1] = 1; U[3, 1] = 1
    V[0, 1] = 1
    W[2, 1] = 1 # C21 += M2
    
    # M3 = A11(B12-B22)
    # A11=0, B12=1, B22=3
    U[0, 2] = 1
    V[1, 2] = 1; V[3, 2] = -1
    W[1, 2] = 1 # C12 += M3
    
    # M4 = A22(B21-B11)
    # A22=3, B21=2, B11=0
    U[3, 3] = 1
    V[2, 3] = 1; V[0, 3] = -1
    W[1, 3] = 1; W[2, 3] = 1 # C11 += M4, C21 += M4
    
    # M5 = (A11+A12)B22
    # A11=0, A12=1, B22=3
    U[0, 4] = 1; U[1, 4] = 1
    V[3, 4] = 1
    W[0, 4] = -1; W[2, 4] = 1 # C11 -= M5, C21 += M5? 
    # Check Strassen formulas:
    # C11 = M1 + M4 - M5 + M7
    # C12 = M3 + M5
    # C21 = M2 + M4
    # C22 = M1 - M2 + M3 + M6
    # So for M5:
    # C11 gets -1. C12 gets +1.
    # W index for C11 is 0. W index for C12 is 1.
    W[0, 4] = -1
    W[1, 4] = 1
    
    # M6 = (A21-A11)(B11+B12)
    # A21=2, A11=0, B11=0, B12=1
    U[2, 5] = 1; U[0, 5] = -1
    V[0, 5] = 1; V[1, 5] = 1
    W[3, 5] = 1 # C22 += M6
    
    # M7 = (A12-A22)(B21+B22)
    # A12=1, A22=3, B21=2, B22=3
    U[1, 6] = 1; U[3, 6] = -1
    V[2, 6] = 1; V[3, 6] = 1
    W[0, 6] = 1; W[3, 6] = 1 # C11 += M7, C22 += M7
    
    return U, V, W
