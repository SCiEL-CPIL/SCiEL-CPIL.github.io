def _validate(xyz):
    """Check if configuration is valid: circles inside unit square and non-overlapping."""
    n = xyz.shape[0]
    x = xyz[:, 0]
    y = xyz[:, 1]
    r = xyz[:, 2]
    # Check bounds
    if np.any(r < -1e-9):
        return False
    if np.any(x - r < -1e-7) or np.any(x + r > 1 + 1e-7):
        return False
    if np.any(y - r < -1e-7) or np.any(y + r > 1 + 1e-7):
        return False
    # Check pairwise non-overlap using Delaunay for efficiency
    try:
        pts = np.column_stack([x, y])
        tri = Delaunay(pts)
        edges = set()
        for simplex in tri.simplices:
            for k in range(3):
                i, j = simplex[k], simplex[(k+1)%3]
                if i > j:
                    i, j = j, i
                edges.add((i, j))
        for i, j in edges:
            dx = x[i] - x[j]
            dy = y[i] - y[j]
            dist = np.sqrt(dx * dx + dy * dy)
            if dist < r[i] + r[j] - 1e-7:
                return False
        # Also check all pairs for safety (Delaunay may miss some close pairs)
        for i in range(n):
            for j in range(i + 1, n):
                dx = x[i] - x[j]
                dy = y[i] - y[j]
                dist = np.sqrt(dx * dx + dy * dy)
                if dist < r[i] + r[j] - 1e-7:
                    return False
    except Exception:
        # Fallback: full O(N^2) check
        for i in range(n):
            for j in range(i + 1, n):
                dx = x[i] - x[j]
                dy = y[i] - y[j]
                dist = np.sqrt(dx * dx + dy * dy)
                if dist < r[i] + r[j] - 1e-7:
                    return False
    return True
