    # We search over k (number of odd primes) and a (exponent of 2).
    
    # Precompute prefix products of odd primes
    odd_primes = _PRIMES[1:] # 3, 5, 7, ...
    prefix_prod = [1]
    for p in odd_primes:
        prefix_prod.append(prefix_prod[-1] * p)
        
    # Max k such that product of first k odd primes <= 10^18
    max_k = 0
    for i, prod in enumerate(prefix_prod):
        if prod <= 10**18:
            max_k = i
        else:
            break
            
    # We iterate over possible k (number of odd primes in m)
    # For each k, we find the optimal a.
    # Note: m = product of first k odd primes.
    # n = 2^a * m.
    # Constraint: n <= 10^18 => 2^a * m <= 10^18 => a <= log2(10^18 / m).
    
    # Optimization:
    # For a fixed m, how does score change with a?
    # Generally, increasing a adds more divisors.
    # The structure of coprime pairs depends on the interleaving of powers of 2 and divisors of m.
    
    # We will scan a for each k.
    # To save time, we can be smart about the range of a.
    
    # Let's also consider that m might not be the *first* k primes?
    # The cell finding suggests "Systematic search over squarefree numbers... single and double swaps".
    # However, the smallest primes yield the most divisors for the smallest size.
    # Swapping a small prime for a large one reduces the number of divisors for the same size,
    # or allows a larger exponent of 2?
    # Usually, keeping the smallest primes is optimal for maximizing tau(n) and likely tau_perp.
    # We will focus on the "canonical" m (first k primes) but allow a quick check of swaps for the top candidates.
    
    for k in range(0, max_k + 1):
        if time.time() > deadline:
            break
            
        m = prefix_prod[k]
        if m > 10**18:
            break
            
        max_a = int(math.log2(10**18 / m))
        
        # If k=0, m=1. n=2^a.
        # Score for 2^a is 1 (if a>=1).
        if k == 0:
            if max_a >= 1:
                n_candidate = 2 ** 1
                s = 1
                if s > best_score:
                    best_score = s
                    best_n = n_candidate
            continue
            
        # For k >= 1
