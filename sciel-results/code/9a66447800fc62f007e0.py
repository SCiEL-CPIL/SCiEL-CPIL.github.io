def _score_n(n, primes_of_m, a):
    """
    Score n = 2^a * prod(p in primes_of_m).
    primes_of_m is a list of primes.
    """
    if n < 2:
        return 0
    
    # Generate divisors of m
    divs_m = [1]
    for p in primes_of_m:
        new_divs = []
        for d in divs_m:
            new_divs.append(d)
            new_divs.append(d * p)
        divs_m = new_divs
    divs_m.sort()
    
    # Generate divisors of n = 2^a * m
    # d = 2^i * d_m
    divs_n = []
    for d_m in divs_m:
        val = d_m
        for i in range(a + 1):
            divs_n.append(val)
            val *= 2
            
    divs_n.sort()
    
    score = 0
    for i in range(1, len(divs_n)):
        if math.gcd(divs_n[i-1], divs_n[i]) == 1:
            score += 1
    return score

