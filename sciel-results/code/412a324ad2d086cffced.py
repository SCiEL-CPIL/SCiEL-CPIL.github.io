def reconstruct(sequences):
    global _DEADLINE
    if _DEADLINE is None:
        _DEADLINE = time.time() + 250

    labels = sorted(sequences, key=lambda name: int(name[1:]))
    n = len(labels)

    if n == 1:
        return labels[0]
    if n == 2:
        return f"({labels[0]},{labels[1]})"
