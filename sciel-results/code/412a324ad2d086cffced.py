def _compute_distance_matrix(sequences, labels):
    """Compute pairwise JC-corrected distances using vectorized operations."""
    n = len(labels)
    seq_arrays = []
    for lab in labels:
        s = sequences[lab]
        arr = np.zeros(len(s), dtype=np.int8)
        for i, c in enumerate(s):
            if c == 'A':
                arr[i] = 0
            elif c == 'C':
                arr[i] = 1
            elif c == 'G':
                arr[i] = 2
            else:
                arr[i] = 3
        seq_arrays.append(arr)

    L = len(sequences[labels[0]])
    mat = np.stack(seq_arrays)
    dist = np.zeros((n, n), dtype=np.float64)
    chunk = 32
    for i in range(0, n, chunk):
        i_end = min(i + chunk, n)
        diff = (mat[i:i_end, None, :] != mat[None, :, :])
        counts = diff.sum(axis=2)
        p = counts.astype(np.float64) / L
        p_safe = np.clip(p, 0, 0.7499)
        jc = -0.75 * np.log(1.0 - 4.0 * p_safe / 3.0)
        jc[p >= 0.7499] = 3.0
        dist[i:i_end, :] = jc

    np.fill_diagonal(dist, 0.0)
    return dist


def _nj_newick_numpy(dist, labels):
    """
    NumPy-optimized Neighbor Joining.
    """
    n = len(labels)
    if n == 1:
        return labels[0]
    if n == 2:
        return f"({labels[0]},{labels[1]})"
    if n == 3:
        return f"({labels[0]},{labels[1]},{labels[2]})"

    # active nodes
    active = list(range(n))
    # tree strings
    tree = {i: labels[i] for i in range(n)}
    
    # We need a distance matrix large enough to hold internal nodes.
    # Max nodes = 2n - 2.
    max_nodes = 2 * n - 2
    D = np.zeros((max_nodes, max_nodes), dtype=np.float64)
    D[:n, :n] = dist
    
    next_id = n

    while len(active) > 3:
        m = len(active)
        # Compute row sums for active nodes
        sub_D = D[np.ix_(active, active)]
        row_sums = sub_D.sum(axis=1)
        
        # NJ criterion: (m-2)*D[i,j] - r[i] - r[j]
        r = row_sums
        C = (m - 2) * sub_D - r[:, None] - r[None, :]
        
        # Set diagonal to inf to avoid self-pairs
        np.fill_diagonal(C, np.inf)
        
        # Find the minimum
        min_idx = np.unravel_index(np.argmin(C), C.shape)
        i_idx, j_idx = min_idx
        i = active[i_idx]
        j = active[j_idx]
        
        # Update tree
        new_id = next_id
        next_id += 1
        tree[new_id] = f"({tree[i]},{tree[j]})"
        
        # Update distances for new_id
        # We only need to update distances to other active nodes
        # But storing them in the full D matrix is fine as long as we don't access uninitialized parts incorrectly.
        # Actually, we can just update D[new_id, active] and D[active, new_id]
        # But the formula D[new_id, k] = 0.5 * (D[i, k] + D[j, k] - D[i, j])
        
        # Vectorized update for all k in active
        # Mask for k != i, k != j
        mask = np.ones(m, dtype=bool)
        mask[i_idx] = False
        mask[j_idx] = False
        
        # active_nodes_to_update = active[mask]
        # D[new_id, active_nodes_to_update] = 0.5 * (D[i, active_nodes_to_update] + D[j, active_nodes_to_update] - D[i, j])
        
        # Let's do it simply with a loop for clarity and safety with indices, or vectorized.
        # Vectorized:
        k_indices = np.array(active)[mask]
        D[new_id, k_indices] = 0.5 * (D[i, k_indices] + D[j, k_indices] - D[i, j])
        D[k_indices, new_id] = D[new_id, k_indices]
        
        # Update active list
        # Remove i and j, add new_id
        # active is a list, removing by value is O(n), which is fine for n<=32
        active.remove(i)
        active.remove(j)
        active.append(new_id)

    a, b, c = active
    return f"({tree[a]},{tree[b]},{tree[c]})"


