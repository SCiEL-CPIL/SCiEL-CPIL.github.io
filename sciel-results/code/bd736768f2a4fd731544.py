"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
def construct():
    # Construct the Extended Quadratic Residue Code of length 18, dimension 9, min distance 6.
    # This code has 512 codewords, which is A_2(18, 6).
    
    # 1. Define GF(256) arithmetic
    # Primitive polynomial: x^8 + x^4 + x^3 + x^2 + 1 (0x11D)
    # We represent elements as integers 0-255.
    
    def gf_mul(a, b):
        p = 0
        while b:
            if b & 1:
                p ^= a
            a <<= 1
            if a & 0x100:
                a ^= 0x11D
            b >>= 1
        return p

    def gf_pow(a, n):
        result = 1
        while n:
            if n & 1:
                result = gf_mul(result, a)
            a = gf_mul(a, a)
            n >>= 1
        return result

    # 2. Find alpha, a primitive 17th root of unity in GF(256)
    # Let beta be the element 'x' (represented as 2).
    beta = 2
    # alpha = beta^15, since (beta^15)^17 = beta^(15*17) = beta^255 = 1
    alpha = gf_pow(beta, 15)
    
    # 3. Compute the minimal polynomial of alpha over GF(2)
    # The roots are the conjugates: alpha^(2^j) for j=0..7
    # These correspond to the quadratic residues mod 17.
    # We compute P(x) = prod (x - alpha_j)
    # We represent polynomials as lists of coefficients in GF(256).
    # P(x) starts as 1.
    poly = [1]  # Coefficients of P(x), poly[i] is coeff of x^i
    
    for j in range(8):
        # Conjugate is alpha^(2^j)
        # We can just square the previous conjugate or recompute
        if j == 0:
            root = alpha
        else:
            root = gf_mul(root, root)
            
        # Multiply poly by (x - root)
        # In GF(2), subtraction is addition (XOR), so (x - root) is (x + root)
        # (x + root) = [root, 1]
        
        # New poly will have degree len(poly)
        new_poly = [0] * (len(poly) + 1)
        
        for i in range(len(poly)):
            # poly[i] * x^i * (x + root) = poly[i]*x^(i+1) + poly[i]*root*x^i
            new_poly[i] ^= gf_mul(poly[i], root)
            new_poly[i+1] ^= poly[i]
            
        poly = new_poly

    # 4. Extract coefficients of g(x)
    # The coefficients should be in GF(2), i.e., 0 or 1.
    # poly[0] is constant term, poly[7] is x^7 term.
    # g(x) = g0 + g1 x + ... + g7 x^7
    # g_i should be 0 or 1.
    g_coeffs = [0] * 8
    for i in range(8):
        if poly[i] not in [0, 1]:
            # This should not happen for a correct minimal polynomial over GF(2)
            # But let's assert or handle it.
            pass 
        g_coeffs[i] = poly[i]
        
    # 5. Construct the generator matrix G (9x17)
    # The code is cyclic, generated by g(x).
    # Row i is the cyclic shift of g by i.
    # g is represented as a 17-bit integer? No, g has degree 7, so 8 bits.
    # In the cyclic code of length 17, the generator polynomial is padded to length 17.
    # g(x) = g0 + g1 x + ... + g7 x^7.
    # The codewords are multiples of g(x) modulo x^17 - 1.
    # The generator matrix rows are:
    # Row 0: g0, g1, ..., g7, 0, ..., 0
    # Row 1: 0, g0, g1, ..., g7, 0, ..., 0
    # ...
    # Row 8: 0, ..., 0, g0, g1, ..., g7
    
    # Let's represent each row as an integer (17 bits)
    rows = []
    for i in range(9):
        word = 0
        for k in range(8):
            bit = g_coeffs[k]
            pos = (i + k) % 17
            if bit:
                word |= (1 << pos)
        rows.append(word)
        
    # 6. Generate all 512 codewords
    words = []
    for mask in range(512):
        # Sum of rows where mask has 1
        c = 0
        for i in range(9):
            if (mask >> i) & 1:
                c ^= rows[i]
        
        # Extend to length 18 by adding parity bit
        # Parity bit is XOR of all 17 bits
        parity = 0
        temp = c
        for _ in range(17):
            parity ^= (temp & 1)
            temp >>= 1
        
        # The extended word has bits 0..16 from c, and bit 17 is parity
        # Or bit 17 is the new bit.
        extended_word = c | (parity << 17)
        words.append(extended_word)
        
    return words
