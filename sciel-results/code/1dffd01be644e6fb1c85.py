import time
import random
from collections import deque

def construct(k, g):
    start_time = time.time()
    deadline = start_time + 115
    
    def luw_construction():
        q = k
        d = max(3, g - 5 if (g - 5) % 2 else g - 4)
        if q == 4:
            table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
            add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
        else:
            add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
        rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
        for c in range(5, d + 1):
            r, c0 = (c - 5) % 4, c - (c - 5) % 4
            rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

        def neighbours(vertex):
            side, x = vertex
            for first in range(q):
                y = [None, first] + [0] * (d - 1)
                for c in range(2, d + 1):
                    a, b = rule[c]
                    y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
                yield 1 - side, tuple(y)

        start = (0, (None,) + (0,) * d)
        index, order, edges = {start: 0}, [start], []
        for vertex in order:
            for other in neighbours(vertex):
                if other not in index:
                    index[other] = len(order)
                    order.append(other)
                if vertex[0] == 0:
                    edges.append((index[vertex], index[other]))
        return len(order), edges

    def verify_girth(n, edges, g):
        """Verify girth >= g using non-backtracking walks from every vertex."""
        # Build adjacency
        adj = [[] for _ in range(n)]
        for u, v in edges:
            adj[u].append(v)
            adj[v].append(u)
        
        # Check degree
        for i in range(n):
            if len(adj[i]) != k:
                return False
        
        # Check for loops and duplicate edges
        edge_set = set()
        for u, v in edges:
            if u == v:
                return False
            key = (min(u, v), max(u, v))
            if key in edge_set:
                return False
            edge_set.add(key)
        
        # Non-backtracking walk check for girth < g
        # A cycle of length L < g exists iff there's a non-backtracking walk of length L that returns to start
        # We check for cycles of length 3 to g-1
        for L in range(3, g):
            # For each start vertex, do DFS of non-backtracking walks of length L
            for start in range(n):
                # State: (current_vertex, previous_vertex, length)
                visited = set()
                stack = [(start, -1, 0)]
                while stack:
                    v, prev, l = stack.pop()
                    if l == L:
                        if v == start:
                            return False
                        continue
                    for w in adj[v]:
                        if w != prev:
                            if (v, prev, l) not in visited:
                                visited.add((v, prev, l))
                                stack.append((w, v, l + 1))
        return True

    n, edges = luw_construction()
    
    # Verify the construction
    if time.time() < deadline - 5:
        if not verify_girth(n, edges, g):
            # Should not happen for LUW construction, but handle gracefully
            pass
    
    return n, edges
