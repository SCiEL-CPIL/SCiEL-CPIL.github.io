                seed_fs = frozenset(seed)
                orbit = set()
                for perm in group:
                    perm_list = list(perm)
                    new_block = frozenset(perm_list[x] for x in seed_fs)
                    orbit.add(new_block)
                if len(orbit) == 132:
                    blocks = [sorted(b) for b in orbit]
                    seen_5 = set()
