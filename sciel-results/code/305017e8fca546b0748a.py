import time
import random
from itertools import permutations

def construct(n):
    start_time = time.time()
    deadline = start_time + 110  # Safety margin
    
    if n == 1:
        return "1"
    
    # Generate all permutations
    perms = list(permutations(range(1, n + 1)))
    num_perms = len(perms)
    
    # Map permutation to index
    perm_to_idx = {p: i for i, p in enumerate(perms)}
    
    # Generate recursive order
    # Build the recursive superpermutation string to extract order
    # This is only needed for the starting point of the search
    def get_recursive_order(n):
        if n == 1:
            return [(1,)]
        
        # Build S_{n-1}
        word = "1"
        for m in range(2, n):
            # Extract perms of size m-1 from word
            perms_prev, seen = [], set()
            for i in range(len(word) - (m - 1) + 1):
                window = tuple(int(c) for c in word[i:i + m - 1])
                if len(set(window)) == m - 1 and all(1 <= x <= m - 1 for x in window):
                    if window not in seen:
                        seen.add(window)
                        perms_prev.append(window)
                        
            new_word = []
            for p in perms_prev:
                block = list(p) + [m] + list(p)
                max_overlap = min(len(new_word), len(block))
                overlap = 0
                for o in range(max_overlap, -1, -1):
                    if o == 0 or new_word[len(new_word) - o:] == block[:o]:
                        overlap = o
                        break
                new_word += block[overlap:]
            word = "".join(map(str, new_word))
            
        # Now word is S_{n-1}
        # Extract order of perms of size n-1
        perms_prev, seen = [], set()
        for i in range(len(word) - (n - 1) + 1):
            window = tuple(int(c) for c in word[i:i + n - 1])
            if len(set(window)) == n - 1 and all(1 <= x <= n - 1 for x in window):
                if window not in seen:
                    seen.add(window)
                    perms_prev.append(window)
                    
        # Construct order for n
        order = []
        for p in perms_prev:
            # The block is p + [n] + p
            # We need to identify which perms of size n appear in this block
            # And in what order
            block = list(p) + [n] + list(p)
            # The perms are:
            # 1. p + [n] (indices 0 to n-1)
            # 2. Shifted by 1?
            # Actually, in the recursive step, we append the block.
            # The new permutations are those that include n.
            # In the block p + [n] + p, the permutations of size n are:
            # p[0..n-2] + [n]
            # p[1..n-1] + [n] + p[0]? No.
            
            # Let's just scan the block for new perms of size n that contain n.
            # But we must ensure we pick them in the order they appear in the final superpermutation.
            # Since we are appending blocks, the order is determined by the blocks.
            # However, overlaps might merge blocks.
            # For the purpose of getting a valid starting order, we can just list the perms
            # in the order they appear in the block, assuming no overlap with previous block 
            # for the sake of the *order list* (the search will fix the order).
            # Actually, the recursive construction's order is well-defined.
            
            # A simpler way: The recursive order for n is derived from n-1.
            # For each p in order_{n-1}, the perms of n are:
            # p + [n]
            # Then, for the next p, we overlap.
            
            # Let's use the property:
            # The set of perms of n generated by p is:
            # p + [n]
            # (p[1:] + [n] + [p[0]])? No.
            
            # Let's just use the string construction to extract the final order.
            pass
        
        # Re-do: Build S_n string and extract order.
        # We already have S_{n-1} in 'word'.
        # We need to build S_n.
        # But we already did the loop above? No, the loop stopped at n-1.
        
        # Let's restart the string building inside this function for clarity.
        word = "1"
        for m in range(2, n + 1):
            perms_curr, seen = [], set()
            for i in range(len(word) - (m - 1) + 1):
                window = tuple(int(c) for c in word[i:i + m - 1])
                if len(set(window)) == m - 1 and all(1 <= x <= m - 1 for x in window):
                    if window not in seen:
                        seen.add(window)
                        perms_curr.append(window)
                        
            new_word = []
            for p in perms_curr:
                block = list(p) + [m] + list(p)
                max_overlap = min(len(new_word), len(block))
                overlap = 0
                for o in range(max_overlap, -1, -1):
                    if o == 0 or new_word[len(new_word) - o:] == block[:o]:
                        overlap = o
                        break
                new_word += block[overlap:]
            word = "".join(map(str, new_word))
            
        # Now word is S_n.
        # Extract order of first occurrences of perms of size n.
        final_order = []
        seen = set()
        for i in range(len(word) - n + 1):
            window = tuple(int(c) for c in word[i:i + n])
            if window not in seen:
                seen.add(window)
                final_order.append(window)
                
        return final_order

    order = get_recursive_order(n)
    
    # Convert to indices
    order_idx = [perm_to_idx[p] for p in order]
    
    # Compute overlap matrix
    # O[i][j] = overlap between perms[i] and perms[j]
    # Overlap is max k such that suffix of i of len k == prefix of j of len k
    # Since perms are of length n, max overlap is n-1.
    
    # Optimization: Only compute if n is small enough or use efficient check.
    # For n=7, 5040^2 = 25M.
    # Check:
    # def overlap(i, j):
    #    p1 = perms[i]
    #    p2 = perms[j]
    #    for k in range(n-1, 0, -1):
    #       if p1[n-k:] == p2[:k]:
    #          return k
    #    return 0
    
    # This is O(n^2) per pair if not optimized.
    # But n=7 is small.
    
    # We can precompute.
    # However, 25M * 7 * 7 ops is ~1.2B ops. Too slow in Python.
    
    # Alternative:
    # Overlap depends on the relative positions.
    # If p1 = (a1...an) and p2 = (b1...bn).
    # Overlap k means a_{n-k+1}..an == b_1..b_k.
    
    # We can compute overlaps on the fly during the search if the search is not too slow.
    # With 110 seconds, how many swaps can we do?
    # If each swap evaluation is O(n) = 7 ops, we can do ~100M swaps?
    # 100M * 7 = 700M ops. Might be too slow in Python (10-20s per 100M simple ops?).
    # Python is slow. 100M loops might take 10-30 seconds.
    # So we can do ~10-30M swaps.
    # This is a reasonable number of iterations.
    
    # Let's implement on-the-fly overlap calculation.
    
    def get_overlap(i, j):
        p1 = perms[i]
        p2 = perms[j]
        # Max possible overlap is n-1
        for k in range(n - 1, 0, -1):
            if p1[n - k:] == p2[:k]:
                return k
        return 0

    # Initial total overlap
    total_overlap = 0
    for i in range(len(order_idx) - 1):
        total_overlap += get_overlap(order_idx[i], order_idx[i + 1])
        
    best_order = order_idx[:]
    best_overlap = total_overlap
    
    # Local Search
    # We want to maximize total_overlap.
    # Length = M*n - total_overlap.
    
    current_order = best_order[:]
    current_overlap = best_overlap
    
    while time.time() < deadline:
        improved = False
        # Try random swaps
        # To be efficient, we can just pick a random index and try swapping with next.
        # If we do many passes, we might converge.
        
        # To avoid getting stuck, we can also try random restarts?
        # No, just iterate.
        
        # Number of steps per "epoch"
        # We don't know how many fit in time, so just run until deadline.
        
        i = random.randint(0, len(current_order) - 2)
        
        # Swap i and i+1
        a = current_order[i]
        b = current_order[i + 1]
        
        # Calculate delta
        # Old overlaps: (i-1, i), (i, i+1), (i+1, i+2)
        # New overlaps: (i-1, i+1), (i+1, i), (i, i+2)
        
        delta = 0
        
        # Left boundary
        if i > 0:
            left = current_order[i - 1]
            old_left = get_overlap(left, a)
            new_left = get_overlap(left, b)
            delta += new_left - old_left
            
        # Middle
        old_mid = get_overlap(a, b)
        new_mid = get_overlap(b, a)
        delta += new_mid - old_mid
        
        # Right boundary
        if i + 2 < len(current_order):
            right = current_order[i + 2]
            old_right = get_overlap(b, right)
            new_right = get_overlap(a, right)
            delta += new_right - old_right
            
        if delta > 0:
            # Apply swap
            current_order[i] = b
            current_order[i + 1] = a
            current_overlap += delta
            improved = True
            
            if current_overlap > best_overlap:
                best_overlap = current_overlap
                best_order = current_order[:]
                
        # If no improvement in a long time, maybe we should do something else?
        # For now, just keep swapping.
        
    # Construct the final word
    # We have the best_order of permutation indices.
    # We need to generate the superpermutation string from this order.
    
    # Start with first permutation
    word = list(perms[best_order[0]])
    
    for i in range(len(best_order) - 1):
        curr = perms[best_order[i]]
        next_p = perms[best_order[i + 1]]
        
        # Find max overlap
        max_ov = 0
        for k in range(n - 1, 0, -1):
            if curr[n - k:] == next_p[:k]:
                max_ov = k
                break
                
        # Append the non-overlapping part of next_p
        word += list(next_p[max_ov:])
        
    return "".join(map(str, word))

