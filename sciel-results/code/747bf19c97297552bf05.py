    def verify(U, V, W, rank):
        """Verify exact decomposition."""
        Ua = np.array(U, dtype=float)
        Va = np.array(V, dtype=float)
        Wa = np.array(W, dtype=float)
        
        target = np.zeros((n*m, m*p, p*n))
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    a_idx = i * m + j
                    b_idx = j * p + k
                    c_idx = k * n + i
                    target[a_idx, b_idx, c_idx] = 1.0
        
        recon = np.einsum('ir,jr,kr->ijk', Ua, Va, Wa)
        max_err = np.max(np.abs(recon - target))
        return max_err < 1e-9
    
    def schoolbook():
        rank = n * m * p
        U = [[0] * rank for _ in range(n * m)]
        V = [[0] * rank for _ in range(m * p)]
        W = [[0] * rank for _ in range(p * n)]
        col = 0
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    U[i * m + j][col] = 1
                    V[j * p + k][col] = 1
                    W[k * n + i][col] = 1
                    col += 1
        return U, V, W, rank
    
    # Try to find a better decomposition using linear algebra
    def try_linear_solve(target_rank):
        """Try to find a rank-target_rank decomposition by fixing U,W and solving for V."""
        if time.time() > _DEADLINE - 20:
            return None
        
        # Fix U and W to structured sparse matrices
        U = np.zeros((n * m, target_rank))
        W = np.zeros((p * n, target_rank))
        
        # Use a simple structured pattern: each row of U has a few 1s
        # This is a heuristic - we need to find patterns that work
        
        # Try: U[i*m+j, t] = 1 if (i*m+j + t) % (n*m) == t % (n*m)
        # This is too complex. Let's try a different approach.
        
        # Actually, let's try: fix U to be the first target_rank columns of a 
        # structured matrix, and similarly for W.
        
        # Simple approach: U[i*m+j, t] = 1 if i*m+j == t % (n*m)
        for t in range(target_rank):
            idx_u = t % (n * m)
            U[idx_u, t] = 1.0
            idx_w = t % (p * n)
            W[idx_w, t] = 1.0
        
        # Build linear system: for each (i,j,k), sum_t U[i*m+j,t]*W[k*n+i,t]*V[j*p+k,t] = 1
        A = np.zeros((n * m * p, m * p * target_rank))
        b = np.ones(n * m * p)
        
        eq_idx = 0
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    for t in range(target_rank):
                        coeff = U[i * m + j, t] * W[k * n + i, t]
                        if coeff != 0:
                            var_idx = (j * p + k) * target_rank + t
                            A[eq_idx, var_idx] += coeff
                    eq_idx += 1
        
        try:
            V_flat, residuals, rank_A, s = np.linalg.lstsq(A, b, rcond=None)
            V = V_flat.reshape(m * p, target_rank)
            
            # Verify
            if verify(U.tolist(), V.tolist(), W.tolist(), target_rank):
                return U.tolist(), V.tolist(), W.tolist(), target_rank
        except:
            pass
        
        return None
    
    # Build the current 93-term solution
    U_cur, V_cur, W_cur, rank_cur = build_current_solution()
    
    if not verify(U_cur, V_cur, W_cur, rank_cur):
        # Fallback to schoolbook
        U_sb, V_sb, W_sb, rank_sb = schoolbook()
