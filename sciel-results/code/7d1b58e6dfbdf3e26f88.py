def construct():
    start_time = time.time()
    deadline = start_time + 90.0 - DEADLINE_MARGIN

    # Construct the QR code (512 words)
    words = _qr_code_words()

    # Verify it's valid
    if not _verify_code(words):
        # Fallback to Reed-Muller if QR construction is wrong
        words = []
        for slope in range(16):
            for intercept in range(2):
                word = 0
                for point in range(16):
                    bit = ((slope & point).bit_count() + intercept) % 2
                    word |= bit << point
                words.append(word)
        return words

    # Try to extend if time permits
    if time.time() < deadline - 5.0:
        words = _greedy_extend(words, deadline)

    return words


