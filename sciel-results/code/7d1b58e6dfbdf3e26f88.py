"""Construct A_2(18,6): largest binary code of length 18, distance >= 6."""
import time
import itertools

N = 18
MIN_DISTANCE = 6
DEADLINE_MARGIN = 8.0  # seconds of safety margin before 90s kill


def _popcount(x):
    return x.bit_count()


def _hamming(x, y):
    return _popcount(x ^ y)


def _qr_code_words():
    """Construct the extended quadratic-residue code of length 18 (512 words).

    The QR code C_17 over F_17 has length 17, size 512, distance 7.
    We extend by one parity bit to length 18, giving distance 8.
    """
    p = 17
    # Quadratic residues mod 17
    residues = set()
    for x in range(1, p):
        residues.add((x * x) % p)
    # residues = {1, 2, 4, 8, 9, 13, 15, 16} (8 residues)
    # Non-residues = {3, 5, 6, 7, 10, 11, 12, 14}

    # The QR code is the [17, 8, 7] code. Its generator matrix has rows:
    # Row 0: all-ones vector (length 17)
    # Rows 1..7: cyclic shifts of the indicator of residues
    # Row 8: parity (for the [17,8,7] code, the all-ones vector is in the code)
    #
    # Actually, the [17,8,7] QR code: generator matrix G is 8x17.
    # G[i][j] = 1 if (j - i) mod 17 is a quadratic residue, for i=0..7, j=0..16.
    # Wait, that's not quite right either. Let me use the standard construction.
    #
    # The QR code C_17: codewords are vectors c = (c_0, ..., c_16) where
    # c_j = 1 if j is a quadratic residue (for the base code)
    # The [17,8,7] code is generated by the 8 cyclic shifts of the residue indicator.
    #
    # Let me define: base vector v has v[j] = 1 if j mod 17 in residues, else 0.
    # The code is spanned by cyclic shifts of v (8 independent shifts).
    #
    # Actually for p=17, the QR code [17,8,7]: the generator matrix rows are
    # cyclic shifts of the indicator of quadratic residues mod 17.
    # There are 17 cyclic shifts but only 8 are independent (since the all-ones
    # vector is a sum of them, and the code has dimension 8).

    # Build the 8 generator rows as cyclic shifts of the residue indicator
    # v[j] = 1 if j in residues (j=0..16), where residues are of 1..16
    # Note: 0 is neither a residue nor non-residue in the usual sense.
    # For QR codes, the generator uses the indicator of residues in positions 1..p-1.
    # Position 0 (or the "infinity" point) is handled separately.

    # Standard construction: G is 8x17 where G[i][j] = 1 iff (j-i) mod 17 in residues
    # for i = 0, ..., 7 (the first 8 cyclic shifts).

    gen_rows = []
    for i in range(8):
        row = 0
        for j in range(17):
            if ((j - i) % p) in residues:
                row |= (1 << j)
        gen_rows.append(row)

    # Verify: the all-ones vector should be in the code (sum of all 17 shifts = 8 * ones? No.)
    # Actually, sum of all 17 cyclic shifts of v: each position j gets hit by
    # exactly 8 shifts (since |residues|=8), so sum = 8 * ones = 0 in F_2.
    # So the 17 shifts sum to zero, meaning at most 16 are independent.
    # The code has dimension 8, so we need to check which 8 shifts are independent.

    # Let me just enumerate all 2^8 combinations of the 8 generator rows
    # and verify the minimum distance.
    words = set()
    for mask in range(256):
        w = 0
        for i in range(8):
            if mask & (1 << i):
                w ^= gen_rows[i]
        # Extend by parity bit (position 17)
        parity = _popcount(w) % 2
        w_extended = w | (parity << 17)
        words.add(w_extended)

    return sorted(words)


def _verify_code(words):
    """Verify all pairs have Hamming distance >= MIN_DISTANCE."""
    n = len(words)
    for i in range(n):
        for j in range(i + 1, n):
            if _hamming(words[i], words[j]) < MIN_DISTANCE:
                return False
    return True


