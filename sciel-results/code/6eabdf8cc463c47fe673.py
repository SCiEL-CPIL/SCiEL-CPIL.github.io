import time
import itertools
import random

N = 18
MIN_DIST = 6
DEADLINE = 85.0

def _hamming(a, b):
    return (a ^ b).bit_count()

def _verify(code):
    if not code:
        return False
    if len(set(code)) != len(code):
        return False
    for i in range(len(code)):
        wi = code[i]
        for j in range(i + 1, len(code)):
            if _hamming(wi, code[j]) < MIN_DIST:
                return False
    return True

