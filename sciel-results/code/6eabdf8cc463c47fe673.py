    # Random search with local optimization
    for iteration in range(500000):
        if time.time() > deadline:
            break
        
        w = random.getrandbits(18)
        if try_add(w):
            continue
        
        # Local search: minimize min distance
        best_w = w
        best_min_dist = min(_hamming(w, c) for c in code)
        
        for _ in range(20):
            if best_min_dist >= MIN_DIST:
                break
            improved = False
            for bit in range(18):
                w2 = best_w ^ (1 << bit)
                min_d = min(_hamming(w2, c) for c in code)
                if min_d > best_min_dist:
                    best_w = w2
                    best_min_dist = min_d
                    improved = True
            if not improved:
                break
        
        if best_min_dist >= MIN_DIST:
            try_add(best_w)
    
    return code
