   def get_strassen_coeffs_2x2():
       # Returns s, t, w for 2x2 Strassen
       # s[j][alpha] for j=1..7, alpha=0..3 (X00, X01, X10, X11)
       # t[j][beta] for j=1..7, beta=0..3 (Y00, Y01, Y10, Y11)
       # w[j][ac] for j=1..7, ac=0..3 (Z00, Z01, Z10, Z11)
       
       s = [[0]*4 for _ in range(7)]
       t = [[0]*4 for _ in range(7)]
       w = [[0]*4 for _ in range(7)]
       
       # S1 = X00 + X11
       s[0][0] = 1; s[0][3] = 1
       # S2 = X10 + X11
       s[1][2] = 1; s[1][3] = 1
       # S3 = X00
       s[2][0] = 1
       # S4 = X11
       s[3][3] = 1
       # S5 = X00 + X01
       s[4][0] = 1; s[4][1] = 1
       # S6 = X10 - X00
       s[5][2] = 1; s[5][0] = -1
       # S7 = X01 - X11
       s[6][1] = 1; s[6][3] = -1
       
       # T1 = Y00 + Y11
       t[0][0] = 1; t[0][3] = 1
       # T2 = Y00
       t[1][0] = 1
       # T3 = Y01 - Y11
       t[2][1] = 1; t[2][3] = -1
       # T4 = Y10 - Y00
       t[3][2] = 1; t[3][0] = -1
       # T5 = Y11
       t[4][3] = 1
       # T6 = Y00 + Y01
       t[5][0] = 1; t[5][1] = 1
       # T7 = Y10 + Y11
       t[6][2] = 1; t[6][3] = 1
       
       # Z00 = M1 + M4 - M5 + M7
       w[0][0] = 1; w[3][0] = 1; w[4][0] = -1; w[6][0] = 1
       # Z01 = M3 + M5
       w[2][1] = 1; w[4][1] = 1
       # Z10 = M2 + M4
       w[1][2] = 1; w[3][2] = 1
       # Z11 = M1 - M2 + M3 + M6
       w[0][3] = 1; w[1][3] = -1; w[2][3] = 1; w[5][3] = 1
       
       return s, t, w
   