def _greedy_improve(words, min_dist=6, time_limit=5.0):
    """Try to add random words to the code."""
    rng = random.Random(42)
    start = time.time()
    words = list(words)
    word_set = set(words)
    while time.time() - start < time_limit:
        c = rng.randint(0, (1 << 18) - 1)
        if c in word_set:
            continue
        valid = True
        for w in words:
            if (c ^ w).bit_count() < min_dist:
                valid = False
                break
        if valid:
            words.append(c)
            word_set.add(c)
    return words

