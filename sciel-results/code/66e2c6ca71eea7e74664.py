import time
import itertools
import random

def construct(n):
    start_time = time.time()
    deadline = start_time + 110  # 110s limit to be safe
    
    # Base cases
    if n <= 1:
        return "1"
    if n == 2:
        return "121"
    if n == 3:
        return "123121321"
        
    # Generate all permutations of 1..n-1
    symbols = list(range(1, n))
    perms = list(itertools.permutations(symbols))
    M = len(perms)
    
    # Precompute overlap matrix
    # overlap[i][j] is the length of the longest suffix of perms[i] that is a prefix of perms[j]
    overlap = [[0] * M for _ in range(M)]
    for i in range(M):
        p_i = perms[i]
        for j in range(M):
            p_j = perms[j]
            max_ov = n - 1  # max possible overlap is length of perm
            # Check from max down to 0
            for k in range(max_ov, -1, -1):
                if k == 0:
                    overlap[i][j] = 0
                    break
                if p_i[n-1-k:] == p_j[:k]:
                    overlap[i][j] = k
                    break
    
    # Initial order: classic recursive order
    # The classic order for n-1 is generated by the recursive step.
    # We can simulate the classic order generation for n-1 to get the initial permutation order.
    def get_classic_perm_order(k):
        if k == 1:
            return [(1,)]
        # Get order for k-1
        prev_order = get_classic_perm_order(k - 1)
        # The classic construction for k uses the order of perms of k-1.
        # Wait, the order of perms in S(k) is determined by the order in S(k-1).
        # Let's just use the order from itertools.permutations for simplicity?
        # Or better, simulate the block stitching order.
        # The code's get_classic_superperm does this.
        # Let's extract the order of perms of 1..k from the classic superperm of k.
        # But we don't want to build the whole string, just the order.
        
        # Actually, the order of permutations in the classic superpermutation S(n)
        # is the same as the order of permutations in S(n-1), but each perm P is replaced by
        # P with n inserted? No.
        
        # Let's just use a random order or the lexicographic order as a start,
        # and rely on local search to improve it.
        # Lexicographic order is a reasonable start.
        return list(itertools.permutations(range(1, k+1)))

    # For n=7, we need order of perms of 1..6.
    # Let's use the lexicographic order as the initial state.
    current_order = list(range(M)) # indices into perms
    
    def calc_score(order):
        score = 0
        for i in range(len(order) - 1):
            u = order[i]
            v = order[i+1]
            score += overlap[u][v]
        return score
    
    current_score = calc_score(current_order)
    best_order = current_order[:]
    best_score = current_score
    
    # Local Search: 2-Opt
    # We want to maximize score.
    # Try reversing a segment [i, j]
    improved = True
    while improved and time.time() < deadline:
        improved = False
        for i in range(M - 1):
            if time.time() > deadline:
                break
            for j in range(i + 1, M):
                # Calculate delta score for reversing order[i..j]
                # Current edges: (i-1, i), (i, i+1), ..., (j-1, j), (j, j+1)
                # New edges: (i-1, j), (j, j-1), ..., (i+1, i), (i, i+1)
                
                # Edges removed:
                # (i-1, i) if i>0
                # (j, j+1) if j<M-1
                # Internal edges (k, k+1) for k in i..j-1 become (k+1, k)
                
                # This is getting complicated to calculate delta efficiently without implementing carefully.
                # Given M=720, M^2 = 518k.
                # If we do a full pass of 2-opt, it's M^2/2 ~ 250k iterations.
                # Each delta calculation is O(1) if we have the overlap matrix.
                # So 250k iterations is very fast.
                
                # Let's just do a simple adjacent swap first (2-opt with j=i+1)
                # Then expand to full 2-opt if time permits.
                
                # Adjacent Swap (i, i+1)
                # Removed: (i-1, i), (i, i+1), (i+1, i+2)
                # Added: (i-1, i+1), (i+1, i), (i, i+2)
                
                delta = 0
                # Remove (i, i+1)
                delta -= overlap[current_order[i]][current_order[i+1]]
                
                # Remove (i-1, i) and add (i-1, i+1)
                if i > 0:
                    delta -= overlap[current_order[i-1]][current_order[i]]
                    delta += overlap[current_order[i-1]][current_order[i+1]]
                else:
                    # No (i-1, i)
                    pass
                    
                # Remove (i+1, i+2) and add (i, i+2)
                if i + 1 < M - 1:
                    delta -= overlap[current_order[i+1]][current_order[i+2]]
                    delta += overlap[current_order[i]][current_order[i+2]]
                else:
                    pass
                    
                # Add (i+1, i)
                delta += overlap[current_order[i+1]][current_order[i]]
                
                if delta > 0:
                    current_order[i], current_order[i+1] = current_order[i+1], current_order[i]
                    current_score += delta
                    if current_score > best_score:
                        best_score = current_score
                        best_order = current_order[:]
                    improved = True

    # Use best_order to construct the word
    def build_string(order):
        if not order:
            return []
        # First block
        word = list(perms[order[0]]) + [n] + list(perms[order[0]])
        for idx in range(1, len(order)):
            p_prev = perms[order[idx-1]]
            p_curr = perms[order[idx]]
            block_curr = list(p_curr) + [n] + list(p_curr)
            
            # Find overlap between end of word and start of block_curr
            # End of word is p_prev (which is perms[order[idx-1]])
            # Start of block_curr is p_curr
            # We already computed overlap[p_prev_idx][p_curr_idx]
            # But we need to be careful: the end of the *current word* is the suffix of the previous block.
            # The previous block ended with p_prev.
            # So the overlap is overlap[order[idx-1]][order[idx]].
            
            ov = overlap[order[idx-1]][order[idx]]
            word += block_curr[ov:]
        return word

    final_word = build_string(best_order)
    
    # Verification
    all_perms = set(itertools.permutations(range(1, n+1)))
    found_perms = set()
    for i in range(len(final_word) - n + 1):
        window = tuple(final_word[i:i+n])
        found_perms.add(window)
        
    if all_perms == found_perms:
        return "".join(map(str, final_word))
    else:
        # Fallback
        def get_classic_superperm(k):
            if k == 1:
                return [1]
            word = [1]
            for m in range(2, k + 1):
                perms, seen = [], set()
                for i in range(len(word) - m + 2):
                    window = tuple(word[i:i + m - 1])
                    if len(set(window)) == m - 1 and window not in seen:
                        seen.add(window)
                        perms.append(window)
                new = []
                for p in perms:
                    block = list(p) + [m] + list(p)
                    overlap = 0
                    max_overlap = min(len(new), len(block))
                    for o in range(max_overlap, -1, -1):
                        if o == 0:
                            break
                        if new[len(new) - o:] == block[:o]:
                            overlap = o
                            break
                    new += block[overlap:]
                word = new
            return word

        classic_word = get_classic_superperm(n)
        return "".join(map(str, classic_word))
