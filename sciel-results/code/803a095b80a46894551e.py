    def calc_S_for_beta(pts, beta, cx=None, cy=None):
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), None, None
        
        normals = []
        for k in range(6):
            ang = beta + math.pi / 6.0 + k * math.pi / 3.0
            normals.append((math.cos(ang), math.sin(ang)))
        
        if cx is None or cy is None:
            # Find optimal center for this beta
            # Minimize max over all points and normals of |dot(p-c, n)|
            # This is equivalent to finding center that minimizes the enclosing hexagon
            # We can use linear programming or just use the centroid as initial
            cx0 = float(np.mean(pts[:, 0]))
            cy0 = float(np.mean(pts[:, 1]))
            
            # Use scipy to find optimal center
            try:
                from scipy.optimize import linprog
                c_obj = np.array([0.0, 0.0, 1.0])
                A_ub = []
                b_ub = []
                
                for nx, ny in normals:
                    for px, py in pts:
                        A_ub.append([-nx, -ny, -1.0])
                        b_ub.append(-(px * nx + py * ny))
                        A_ub.append([nx, ny, -1.0])
                        b_ub.append(px * nx + py * ny)
                
                A_ub = np.array(A_ub)
                b_ub = np.array(b_ub)
                bounds = [(None, None), (None, None), (0, None)]
                
                res = linprog(c_obj, A_ub=A_ub, b_ub=b_ub, bounds=bounds, method='highs')
                if res.status == 0:
                    cx = res.x[0]
                    cy = res.x[1]
                    D = res.x[2]
                else:
                    cx = cx0
                    cy = cy0
                    D = 0
                    for nx, ny in normals:
                        for px, py in pts:
                            proj = abs((px - cx) * nx + (py - cy) * ny)
                            D = max(D, proj)
            except Exception:
                cx = cx0
                cy = cy0
                D = 0
                for nx, ny in normals:
                    for px, py in pts:
                        proj = abs((px - cx) * nx + (py - cy) * ny)
                        D = max(D, proj)
        else:
            D = 0
            for nx, ny in normals:
                for px, py in pts:
                    proj = abs((px - cx) * nx + (py - cy) * ny)
                    D = max(D, proj)
        
        S = (D + APOTHEM) / APOTHEM
        return S, (cx, cy), D

    def newton_polish_center(pts, beta, cx, cy, max_iter=100, tol=1e-14):
        """High-precision 2D Newton polish for center at fixed beta."""
        normals = np.array([
            [math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
             math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0)]
            for k in range(6)
        ])
        
        for _ in range(max_iter):
            if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                break
            
            # Compute projections
            pts_c = pts - np.array([cx, cy])
            projs = pts_c @ normals.T  # shape (n, 6)
            abs_projs = np.abs(projs)
            D = np.max(abs_projs)
            
            # Find active constraints (within tolerance of max)
            tol_act = 1e-10
            active_mask = abs_projs >= (D - tol_act)
            
            # Get active rows: for each active (point, normal) pair
            active_indices = np.argwhere(active_mask)
            if len(active_indices) == 0:
                break
            
            # Build linear system: minimize max |dot(p_i - c, n_j)|
            # At optimum, the active constraints should be balanced
            # Use least squares to find center that equalizes active constraints
            
            A_rows = []
            b_rows = []
            for idx in active_indices:
                i, j = idx
                px, py = pts[i]
                nx, ny = normals[j]
                # Constraint: (px-cx)*nx + (py-cy)*ny = +/- D
                # We want to find cx, cy such that all active constraints are satisfied
                # Use the sign of the projection
                sign = np.sign(projs[i, j])
                if sign == 0:
                    sign = 1
                A_rows.append([nx, ny])
                b_rows.append(sign * D - (px * nx + py * ny))
            
            A = np.array(A_rows)
            b = np.array(b_rows)
            
            # Solve least squares
            try:
                sol, residuals, rank, sv = np.linalg.lstsq(A, b, rcond=None)
                dx, dy = sol
                cx_new = cx + dx
                cy_new = cy + dy
                
                # Check convergence
                if abs(dx) < tol and abs(dy) < tol:
                    cx, cy = cx_new, cy_new
                    break
                cx, cy = cx_new, cy_new
            except Exception:
                break
        
        return cx, cy

    def optimize_shape(pts):
        best_S = float('inf')
        best_beta = 0.0
        best_center = None
        
        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
            return float('inf'), 0.0, None
        
        # Coarse grid search over beta
        for i in range(37):
            beta = i * (math.pi / 6) / 36
            S, center, D = calc_S_for_beta(pts, beta)
            if S < best_S:
                best_S = S
                best_beta = beta
                best_center = center
        
        # Refine beta with bounded scalar optimization
        try:
            from scipy.optimize import minimize_scalar
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                res = minimize_scalar(lambda b: calc_S_for_beta(pts, b)[0], bounds=(0, math.pi / 6), method='bounded',
                                     options={'maxiter': 300, 'xatol': 1e-12})
                if res.fun < best_S:
                    best_S = res.fun
                    best_beta = res.x
                    _, best_center, _ = calc_S_for_beta(pts, best_beta)
        except Exception:
            pass
        
        # Smooth surrogate optimization with adaptive temperature
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                def smooth_calc_S(pts, beta, cx, cy, temperature=0.1):
                    normals = np.array([
                        (math.cos(beta + math.pi / 6.0 + k * math.pi / 3.0),
                         math.sin(beta + math.pi / 6.0 + k * math.pi / 3.0))
                        for k in range(6)
                    ])
                    
                    pts_centered = pts - np.array([cx, cy])
                    projs = pts_centered @ normals.T
                    
                    all_projs = np.concatenate([projs.ravel(), (-projs).ravel()])
                    
                    max_val = np.max(all_projs)
                    if max_val > 100:
                        return float('inf'), (cx, cy), float('inf')
                    
                    shifted = (all_projs - max_val) / temperature
                    shifted = np.clip(shifted, -50, 50)
                    log_sum = np.log(np.sum(np.exp(shifted))) + max_val / temperature
                    D = temperature * log_sum
                    S = (D + APOTHEM) / APOTHEM
                    return S, (cx, cy), D
                
                temperatures = [0.3, 0.1, 0.05, 0.02, 0.01]
                start_betas = [best_beta, best_beta + 0.05, best_beta - 0.05, 0.0, math.pi/12, math.pi/6]
                
                for temp in temperatures:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    for sb in start_betas:
                        if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                            break
                        
                        def smooth_obj(params, t=temp):
                            cx, cy, beta = params
                            beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S, _, _ = smooth_calc_S(pts, beta, cx, cy, temperature=t)
                            return S
                        
                        init = [best_center[0], best_center[1], sb]
                        res = minimize(smooth_obj, init, method='Nelder-Mead',
                                     options={'maxiter': 500, 'xatol': 1e-10, 'fatol': 1e-10})
                        
                        if res.fun < 1e10:
                            cx_r, cy_r, beta_r = res.x
                            beta_r = ((beta_r % (math.pi/6)) + math.pi/6) % (math.pi/6)
                            S_exact, c_exact, _ = calc_S_for_beta(pts, beta_r)
                            if S_exact < best_S:
                                best_S = S_exact
                                best_beta = beta_r
                                best_center = c_exact
        except Exception:
            pass
        
        # High-precision Newton polish for center at optimal beta
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN and best_center is not None:
                cx_np, cy_np = newton_polish_center(pts, best_beta, best_center[0], best_center[1])
                S_np, _, _ = calc_S_for_beta(pts, best_beta, cx_np, cy_np)
                if S_np < best_S:
                    best_S = S_np
                    best_center = (cx_np, cy_np)
        except Exception:
            pass
        
        # Final high-precision polish using exact objective
        try:
            if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                def objective(params):
                    cx, cy, beta = params
                    beta = ((beta % (math.pi/6)) + math.pi/6) % (math.pi/6)
                    normals = []
                    for k in range(6):
                        ang = beta + math.pi / 6.0 + k * math.pi / 3.0
                        normals.append((math.cos(ang), math.sin(ang)))
                    
                    max_proj = 0.0
                    for nx, ny in normals:
                        for px, py in pts:
                            proj = abs((px - cx) * nx + (py - cy) * ny)
                            if proj > max_proj:
                                max_proj = proj
                    
                    S = (max_proj + APOTHEM) / APOTHEM
                    return S
                
                polish_starts = [
                    [best_center[0], best_center[1], best_beta],
                    [best_center[0], best_center[1], best_beta + 0.02],
                    [best_center[0], best_center[1], best_beta - 0.02],
                    [best_center[0] + 0.02, best_center[1], best_beta],
                    [best_center[0], best_center[1] + 0.02, best_beta],
                    [best_center[0] - 0.02, best_center[1], best_beta],
                    [best_center[0], best_center[1] - 0.02, best_beta],
                ]
                
                for init in polish_starts:
                    if time.time() - START_TIME > TIME_LIMIT - SAFETY_MARGIN:
                        break
                    res = minimize(objective, init, method='Nelder-Mead',
                                 options={'maxiter': 5000, 'xatol': 1e-13, 'fatol': 1e-13})
                    if res.fun < best_S:
                        best_S = res.fun
                        best_center = (res.x[0], res.x[1])
                        best_beta = ((res.x[2] % (math.pi/6)) + math.pi/6) % (math.pi/6)
                        
                        # Newton polish after Nelder-Mead
                        if time.time() - START_TIME < TIME_LIMIT - SAFETY_MARGIN:
                            cx_np, cy_np = newton_polish_center(pts, best_beta, best_center[0], best_center[1])
                            S_np, _, _ = calc_S_for_beta(pts, best_beta, cx_np, cy_np)
                            if S_np < best_S:
                                best_S = S_np
                                best_center = (cx_np, cy_np)
        except Exception:
            pass
            
        return best_S, best_beta, best_center

