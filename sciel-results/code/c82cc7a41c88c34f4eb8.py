import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 50.0

    # Pre-compute popcount table for 17-bit integers (2^17 = 131072 entries)
    # 17 bits -> values from 0 to 131071
    popcount = [0] * (1 << 17)
    for i in range(1, 1 << 17):
        popcount[i] = popcount[i >> 1] + (i & 1)

    def popcount_fast(x):
        return popcount[x & 0x1FFFF]

    def is_valid_code(words):
        for i in range(len(words)):
            wi = words[i]
            for j in range(i + 1, len(words)):
                if popcount_fast(wi ^ words[j]) < 6:
                    return False
        return True

    # Vectorized popcount for NumPy arrays (uint32)
    def vpopcount(x):
        x = x - ((x >> 1) & 0x55555555)
        x = (x & 0x33333333) + ((x >> 2) & 0x33333333)
        return ((x + (x >> 4)) & 0x0F0F0F0F) % 255

    def check_compatibility(code_list, candidate):
        if not code_list:
            return True
        code_arr = np.array(code_list, dtype=np.uint32)
        xored = code_arr ^ candidate
        dists = vpopcount(xored)
        return np.min(dists) >= 6

    # Step 1: Build the [17,8,6] linear code (256 words)
    # This is the shortened version of the [18,9,6] extended QR(17) code.
    # The full [17,9,5] QR code has 512 words. We extend to [18,9,6] by appending a parity bit,
    # then shorten by picking a coordinate and keeping only words with 0 in that coordinate.
    
    # GF(2^8) with primitive polynomial 0x1d: x^8 + x^4 + x^3 + x^2 + 1
    # Actually the standard QR(17) code is in GF(2) cyclic, but we need the generator polynomial.
    # g(x) = prod_{r in Q} (x - alpha^r) where alpha is a 17th root of unity.
    # In GF(2^8), we find alpha of order 17. 255 = 15*17.
    
    gf_poly = 0x1d  # x^8+x^4+x^3+x^2+1, primitive in GF(2^8)
    
    def gf_mul(a, b):
        res = 0
        for _ in range(8):
            if b & 1:
                res ^= a
            b >>= 1
            if a & 0x80:
                a = ((a << 1) ^ gf_poly) & 0xFF
            else:
                a = (a << 1) & 0xFF
        return res

    def gf_pow(a, n):
        res = 1
        while n:
            if n & 1:
                res = gf_mul(res, a)
            a = gf_mul(a, a)
            n >>= 1
        return res

    # Find element of order 17
    alpha = None
    for candidate in range(1, 256):
        if gf_pow(candidate, 17) == 1 and candidate != 1:
            alpha = candidate
            break

    if alpha is None:
        # Fallback: use a simpler construction if GF field construction fails
        alpha = 3  # Just a placeholder, should not happen

    # Quadratic residues mod 17
    Q = [1, 2, 4, 8, 9, 13, 15, 16]
    
    # Build generator polynomial g(x) of degree 8: g(x) = prod_{i in Q} (x - alpha^i)
    g = [1]  # coefficients from lowest degree
    for i in Q:
        root = gf_pow(alpha, i)
        new_g = [0] * (len(g) + 1)
        for j in range(len(g)):
            new_g[j] ^= gf_mul(g[j], root)
            new_g[j + 1] ^= g[j]
        g = new_g

    # g now has degree 8, so len(g) = 9
    # Cyclic code of length 17 over GF(2), generated by g(x) mod (x^17-1)
    # The code C consists of all c(x) = m(x)*g(x) mod (x^17-1), m(x) degree < 8
    # This gives [17, 17-8, d_min] code. d_min should be 5.
    
    # Generate all 512 words of the [17,9,5] code
    words_17_9_5 = []
    for m in range(512):
        c = [0] * 17
        for j in range(9):  # degree of g
            if (m >> j) & 1:
                # c += x^j * g mod (x^17 - 1)
                for k in range(9):
                    if (g[k] != 0):  # g should have 0/1 coefficients in GF(2) cyclic
                        pos = (j + k) % 17
                        c[pos] ^= 1
        # Convert to integer
        val = 0
        for bit in c:
            val |= bit
            val <<= 1
        val >>= 1  # shift right once to account for last extra shift
        # Actually let me recompute:
        val = 0
        for bit in c:
            val = (val << 1) | bit
        words_17_9_5.append(val)

    # Extend to [18,9,6] by appending overall parity
    words_18_9_6 = []
    for w in words_17_9_5:
        parity = popcount_fast(w) % 2
        # w is a 17-bit number. Bit 16 is MSB, bit 0 is LSB.
        # Parity bit goes at position 17. New value:
        ext_val = w | (parity << 17)
        words_18_9_6.append(ext_val)

    # Shorten: keep words with parity bit = 0, then mask off the 18th coordinate.
    words_17_8_6 = []
    for w in words_18_9_6:
        if (w >> 17) & 1 == 0:
            w_short = w & 0x1FFFF  # keep only 17 bits
            words_17_8_6.append(w_short)

    # Deduplicate (shouldn't be needed but safe)
    words_17_8_6 = list(set(words_17_8_6))
    base_code = words_17_8_6

    # Verify the base code
    if not is_valid_code(base_code):
        # Fallback: just return the words we have as-is, but ensure validity by filtering
        # Actually let's verify and if invalid, reduce it
        # This shouldn't happen, but just in case
        valid_code = [base_code[0]]
        for w in base_code[1:]:
            ok = True
            for v in valid_code:
                if popcount_fast(w ^ v) < 6:
                    ok = False
                    break
            if ok:
                valid_code.append(w)
        base_code = valid_code

    current_code = list(base_code)
    best_code = list(base_code)
    best_size = len(current_code)
    if best_size < 32:
        # Absolute fallback
        return [0]
    
    # Step 2: Targeted Local Search with NumPy acceleration
    
    # Prepare candidate pool
    # Words of weight 6, 7, 8 are good candidates for a distance 6 code
    candidates = []
    for w in range(1 << 17):
        wt = popcount[w]
        if 6 <= wt <= 8:
            candidates.append(w)
            
    random.shuffle(candidates)
    
    code_set = set(current_code)
    
    ls_time_limit = deadline - 5.0
    
    while time.time() < ls_time_limit:
        # Randomly decide to restart or continue
        if random.random() < 0.1:
            # Restart from best
            current_code = list(best_code)
            code_set = set(current_code)
        
        # Perform a batch of local search moves
        batch_end = time.time() + 0.1 # 100ms batch
        
        while time.time() < batch_end:
            r = random.random()
            
            if r < 0.6:
                # Add
                if candidates:
                    idx = random.randint(0, len(candidates) - 1)
                    w_new = candidates[idx]
                    if w_new in code_set:
                        continue
                    if check_compatibility(current_code, w_new):
                        current_code.append(w_new)
                        code_set.add(w_new)
                        if len(current_code) > best_size:
                            best_size = len(current_code)
                            best_code = list(current_code)
            else:
                # Swap
                if len(current_code) > 30:
                    idx_rm = random.randint(0, len(current_code) - 1)
                    w_rm = current_code[idx_rm]
                    current_code.pop(idx_rm)
                    code_set.remove(w_rm)
                    
                    added = False
                    # Try a few candidates
                    for _ in range(10):
                        if not candidates: break
                        idx_new = random.randint(0, len(candidates) - 1)
                        w_new = candidates[idx_new]
                        if w_new in code_set:
                            continue
                        if check_compatibility(current_code, w_new):
                            current_code.append(w_new)
                            code_set.add(w_new)
                            added = True
                            break
                    
                    if not added:
                        current_code.insert(idx_rm, w_rm)
                        code_set.add(w_rm)
                    else:
                        if len(current_code) > best_size:
                            best_size = len(current_code)
                            best_code = list(current_code)

    # Final verification
    if len(best_code) >= 32:
        if is_valid_code(best_code):
            return best_code
        else:
            # Filter
            final = []
            for w in best_code:
                ok = True
                for v in final:
                    if popcount_fast(w ^ v) < 6:
                        ok = False
                        break
                if ok:
                    final.append(w)
            if len(final) >= 32:
                return final
            return base_code
    else:
        return base_code if len(base_code) >= 32 else [0]
