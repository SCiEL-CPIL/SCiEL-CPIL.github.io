DIMENSIONS = [3, 3, 4]

# EVOLVE-BLOCK-START
def construct():
    # Rank-1 decomposition of the matrix multiplication tensor.
    # The tensor T[i,j,k] = 1 for all i,j,k corresponds to u=1, v=1, w=1.
    n, m, p = DIMENSIONS
    rank = 1
    U = [[1] * rank for _ in range(n * m)]
    V = [[1] * rank for _ in range(m * p)]
    W = [[1] * rank for _ in range(p * n)]
    return {"U": U, "V": V, "W": W}
