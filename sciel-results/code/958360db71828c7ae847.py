"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
# EVOLVE-BLOCK-START
import time
import itertools
import random

def load(boxes, container):
    start_time = time.time()
    deadline = start_time + 112.0  # Safety margin for 120s limit

    W, H, D = container
    if W <= 0 or H <= 0 or D <= 0:
        return [(-1, 0, 0, 0, w, h, d) for w, h, d in boxes]

    container_volume = W * H * D

    def get_orientations(w, h, d):
        """Get unique orientations of a box."""
        dims = sorted([w, h, d], reverse=True)
        seen = set()
        orientations = []
        for perm in itertools.permutations(dims):
            if perm not in seen:
                seen.add(perm)
                orientations.append(perm)
        return orientations

    def run_strategy(order_key_func, use_local_search=True, local_search_iters=500):
        """
        Runs a packing strategy with a specific ordering.
        Returns (total_volume, results_list)
        """
        if time.time() > deadline:
            return 0, None

        indexed_boxes = list(enumerate(boxes))
        try:
            indexed_boxes.sort(key=order_key_func)
        except Exception:
            return 0, None

        placed = []  # List of (x, y, z, w, h, d)
        results = [None] * len(boxes)
        total_vol = 0

        # Candidate points: corners generated by placed boxes
        candidate_points = set([(0, 0, 0)])

        for orig_idx, (w, h, d) in indexed_boxes:
            if time.time() > deadline:
                break

            # Generate unique orientations
            orientations = get_orientations(w, h, d)

            best_pos = None
            best_score = float('inf')
            best_orient = None
            found_placement = False

            # Iterate through all current candidate points
            for cx, cy, cz in candidate_points:
                if time.time() > deadline:
                    break

                for ow, oh, od in orientations:
                    # Check bounds
                    if cx + ow > W or cy + oh > H or cz + od > D:
                        continue

                    # Check overlap with all placed boxes
                    overlap = False
                    for px, py, pz, pw, ph, pd in placed:
                        # Separation check:
                        if not (cx + ow <= px or px + pw <= cx or
                                cy + oh <= py or py + ph <= cy or
                                cz + od <= pz or pz + pd <= cz):
                            overlap = True
                            break

                    if not overlap:
                        # Score: minimize distance from origin, then minimize max extent
                        nx = cx / W if W > 0 else 0
                        ny = cy / H if H > 0 else 0
                        nz = cz / D if D > 0 else 0
                        score = nx + ny + nz

                        if score < best_score or (score == best_score and (best_pos is None or (cx, cy, cz) < best_pos)):
                            best_score = score
                            best_pos = (cx, cy, cz)
                            best_orient = (ow, oh, od)
                            found_placement = True

            if found_placement:
                bx, by, bz = best_pos
                bw, bh, bd = best_orient

                # Place the box
                placed.append((bx, by, bz, bw, bh, bd))
                results[orig_idx] = (0, bx, by, bz, bw, bh, bd)
                total_vol += bw * bh * bd

                # Generate new candidate positions
                new_candidates = [
                    (bx + bw, by, bz),
                    (bx, by + bh, bz),
                    (bx, by, bz + bd),
                    (bx + bw, by + bh, bz),
                    (bx + bw, by, bz + bd),
                    (bx, by + bh, bz + bd),
                    (bx + bw, by + bh, bz + bd),
                ]

                for nc in new_candidates:
                    if 0 <= nc[0] <= W and 0 <= nc[1] <= H and 0 <= nc[2] <= D:
                        candidate_points.add(nc)
            else:
                results[orig_idx] = (-1, 0, 0, 0, w, h, d)

        # Local search: try to improve by relocating boxes or inserting left-out boxes
        if use_local_search and time.time() < deadline - 5:
            total_vol, placed, results = local_search(placed, results, boxes, local_search_iters)

        # Fill any remaining results
        for i in range(len(boxes)):
            if results[i] is None:
                w, h, d = boxes[i]
                results[i] = (-1, 0, 0, 0, w, h, d)

        return total_vol, results

    def local_search(placed, results, boxes, max_iters):
        """
        Local search to improve packing:
        1. Try to relocate placed boxes to better positions.
        2. Try to insert left-out boxes.
        """
        total_vol = sum(bw * bh * bd for _, _, _, bw, bh, bd in placed)
        candidate_points = set([(0, 0, 0)])

        # Rebuild candidate points from placed boxes
        for bx, by, bz, bw, bh, bd in placed:
            candidate_points.add((bx, by, bz))
            candidate_points.add((bx + bw, by, bz))
            candidate_points.add((bx, by + bh, bz))
            candidate_points.add((bx, by, bz + bd))
            candidate_points.add((bx + bw, by + bh, bz))
            candidate_points.add((bx + bw, by, bz + bd))
            candidate_points.add((bx, by + bh, bz + bd))
            candidate_points.add((bx + bw, by + bh, bz + bd))

        for iteration in range(max_iters):
            if time.time() > deadline - 2:
                break

            # Try to insert a left-out box
            inserted = False
            for i in range(len(boxes)):
                if results[i][0] == -1:
                    w, h, d = boxes[i]
                    orientations = get_orientations(w, h, d)
                    found = False

                    for cx, cy, cz in candidate_points:
                        for ow, oh, od in orientations:
                            if cx + ow > W or cy + oh > H or cz + od > D:
                                continue

                            # Check overlap
                            overlap = False
                            for px, py, pz, pw, ph, pd in placed:
                                if not (cx + ow <= px or px + pw <= cx or
                                        cy + oh <= py or py + ph <= cy or
                                        cz + od <= pz or pz + pd <= cz):
                                    overlap = True
                                    break

                            if not overlap:
                                # Place the box
                                placed.append((cx, cy, cz, ow, oh, od))
                                results[i] = (0, cx, cy, cz, ow, oh, od)
                                total_vol += ow * oh * od
                                found = True
                                inserted = True

                                # Update candidate points
                                candidate_points.add((cx + ow, cy, cz))
                                candidate_points.add((cx, cy + oh, cz))
                                candidate_points.add((cx, cy, cz + od))
                                candidate_points.add((cx + ow, cy + oh, cz))
                                candidate_points.add((cx + ow, cy, cz + od))
                                candidate_points.add((cx, cy + oh, cz + od))
                                candidate_points.add((cx + ow, cy + oh, cz + od))
                                break

                        if found:
                            break

                    if inserted:
                        break

            if not inserted:
                # Try to relocate a random placed box to a better position
                if placed:
                    idx = random.randint(0, len(placed) - 1)
                    bx, by, bz, bw, bh, bd = placed[idx]

                    # Remove the box
                    placed.pop(idx)
                    total_vol -= bw * bh * bd

                    # Find new position
                    found = False
                    for cx, cy, cz in candidate_points:
                        orientations = get_orientations(bw, bh, bd)
                        for ow, oh, od in orientations:
                            if cx + ow > W or cy + oh > H or cz + od > D:
                                continue

                            overlap = False
                            for px, py, pz, pw, ph, pd in placed:
                                if not (cx + ow <= px or px + pw <= cx or
                                        cy + oh <= py or py + ph <= cy or
                                        cz + od <= pz or pz + pd <= cz):
                                    overlap = True
                                    break

                            if not overlap:
                                # Only accept if it's better (closer to origin)
                                old_score = (bx + bw / 2) / W + (by + bh / 2) / H + (bz + bd / 2) / D
                                new_score = (cx + ow / 2) / W + (cy + oh / 2) / H + (cz + od / 2) / D
                                if new_score < old_score:
                                    placed.append((cx, cy, cz, ow, oh, od))
                                    total_vol += ow * oh * od
                                    found = True

                                    # Update candidate points
                                    candidate_points.add((cx + ow, cy, cz))
                                    candidate_points.add((cx, cy + oh, cz))
                                    candidate_points.add((cx, cy, cz + od))
                                    candidate_points.add((cx + ow, cy + oh, cz))
                                    candidate_points.add((cx + ow, cy, cz + od))
                                    candidate_points.add((cx, cy + oh, cz + od))
                                    candidate_points.add((cx + ow, cy + oh, cz + od))
                                    break

                        if found:
                            break

                    if not found:
                        # Restore the box
                        placed.append((bx, by, bz, bw, bh, bd))
                        total_vol += bw * bh * bd

        # Update results for relocated boxes
        for i in range(len(boxes)):
            if results[i][0] == 0:
                # Find the box in placed
                found = False
                for j, (px, py, pz, pw, ph, pd) in enumerate(placed):
                    if results[i][4] == pw and results[i][5] == ph and results[i][6] == pd:
                        if (px, py, pz, pw, ph, pd) != (results[i][1], results[i][2], results[i][3], pw, ph, pd):
                            results[i] = (0, px, py, pz, pw, ph, pd)
                        found = True
                        break

        return total_vol, placed, results

    # Define multiple sorting strategies
    def sort_vol_desc(x):
        w, h, d = x[1]
        return -(w * h * d)

    def sort_height_desc(x):
        w, h, d = x[1]
        return -max(w, h, d)

    def sort_sum_desc(x):
        w, h, d = x[1]
        return -(w + h + d)

    def sort_aspect(x):
        w, h, d = x[1]
        vol = w * h * d
        if vol == 0:
            return 0
        s = (w + h + d) / 3.0
        dev = abs(w - s) + abs(h - s) + abs(d - s)
        return (-vol, dev)

    best_vol = 0
    best_results = None

    strategies = [
        sort_vol_desc,
        sort_height_desc,
        sort_sum_desc,
        sort_aspect,
    ]

    for i, strat in enumerate(strategies):
        if time.time() > deadline:
            break

        vol, res = run_strategy(strat)

        if res is not None and vol > best_vol:
            best_vol = vol
            best_results = res

    if best_results is None:
        best_results = [(-1, 0, 0, 0, w, h, d) for w, h, d in boxes]

    return best_results
# EVOLVE-BLOCK-END
