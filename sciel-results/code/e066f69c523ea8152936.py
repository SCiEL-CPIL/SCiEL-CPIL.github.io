import numpy as np

def construct():
    n, m, p = 2, 2, 3
    rank = 11
    
    U = np.zeros((n*m, rank))
    V = np.zeros((m*p, rank))
    W = np.zeros((p*n, rank))
    
    # Strassen for first 2 columns of B
    # U indices: 0:A11, 1:A12, 2:A21, 3:A22
    # V indices: 0:B11, 1:B12, 2:B13, 3:B21, 4:B22, 5:B23
    
    # M1: (A11+A22)(B11+B22)
    U[:, 0] = [1, 0, 0, 1]
    V[:, 0] = [1, 0, 0, 0, 1, 0]
    W[0, 0] = 1 # C11
    W[4, 0] = 1 # C22
    
    # M2: (A21+A22)B11
    U[:, 1] = [0, 0, 1, 1]
    V[:, 1] = [1, 0, 0, 0, 0, 0]
    W[3, 1] = 1 # C21
    W[4, 1] = -1 # C22
    
    # M3: A11(B12-B22)
    U[:, 2] = [1, 0, 0, 0]
    V[:, 2] = [0, 1, 0, 0, -1, 0]
    W[1, 2] = 1 # C12
    W[4, 2] = 1 # C22
    
    # M4: A22(B21-B11)
    U[:, 3] = [0, 0, 0, 1]
    V[:, 3] = [0, 0, 0, 1, 0, 0] # B21 is index 3
    # Wait, B21 is row 2 col 1. Index 1*3+0 = 3.
    # B11 is index 0.
    # M4 = A22 * (B21 - B11).
    V[:, 3] = [0, 0, 0, 1, 0, 0] # B21
    # Need to subtract B11.
    V[:, 3] = [0, 0, 0, 1, 0, 0]
    # Actually V is a vector.
    # M4 term is A22 * (B21 - B11).
    # U part: A22 -> [0,0,0,1]
    # V part: B21 - B11 -> [ -1, 0, 0, 1, 0, 0]
    V[:, 3] = [-1, 0, 0, 1, 0, 0]
    W[0, 3] = 1 # C11
    W[3, 3] = 1 # C21
    
    # M5: (A11+A12)B22
    U[:, 4] = [1, 1, 0, 0]
    V[:, 4] = [0, 0, 0, 0, 1, 0] # B22 is index 4
    W[0, 4] = -1 # C11
    W[1, 4] = 1 # C12
    
    # M6: (A21-A11)(B11+B12)
    U[:, 5] = [0, 0, 1, -1]
    V[:, 5] = [1, 1, 0, 0, 0, 0]
    W[4, 5] = 1 # C22
    
    # M7: (A12-A22)(B21+B22)
    U[:, 6] = [0, 1, 0, -1]
    V[:, 6] = [0, 0, 0, 1, 1, 0] # B21(3) + B22(4)
    W[0, 6] = 1 # C11
    W[4, 6] = -1 # C22
    
    # Schoolbook for 3rd column
    # C13 = A11 B13 + A12 B23
    # C23 = A21 B13 + A22 B23
    
    # T8: A11 B13
    U[:, 7] = [1, 0, 0, 0]
    V[:, 7] = [0, 0, 1, 0, 0, 0] # B13 is index 2
    W[2, 7] = 1 # C13
    
    # T9: A12 B23
    U[:, 8] = [0, 1, 0, 0]
    V[:, 8] = [0, 0, 0, 0, 0, 1] # B23 is index 5
    W[2, 8] = 1 # C13
    
    # T10: A21 B13
    U[:, 9] = [0, 0, 1, 0]
    V[:, 9] = [0, 0, 1, 0, 0, 0] # B13 is index 2
    W[5, 9] = 1 # C23
    
    # T11: A22 B23
    U[:, 10] = [0, 0, 0, 1]
    V[:, 10] = [0, 0, 0, 0, 0, 1] # B23 is index 5
    W[5, 10] = 1 # C23
    
    return {"U": U, "V": V, "W": W}
