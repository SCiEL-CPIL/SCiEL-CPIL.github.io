import numpy as np

DIMENSIONS = [4, 4, 9]

def construct():
    # 1. Construct M_2,2,2 (Strassen)
    # U, V, W are 4x7
    U_222 = np.zeros((4, 7))
    V_222 = np.zeros((4, 7))
    W_222 = np.zeros((4, 7))
    
    # P1: (A00+A11)(B00+B11) -> C00+C11
    U_222[0, 0] = 1; U_222[3, 0] = 1
    V_222[0, 0] = 1; V_222[3, 0] = 1
    W_222[0, 0] = 1; W_222[3, 0] = 1
    
    # P2: (A10+A11)B00 -> C10-C11
    U_222[2, 1] = 1; U_222[3, 1] = 1
    V_222[0, 1] = 1
    W_222[2, 1] = 1; W_222[3, 1] = -1
    
    # P3: A00(B01-B11) -> C01+C11
    U_222[0, 2] = 1
    V_222[1, 2] = 1; V_222[3, 2] = -1
    W_222[1, 2] = 1; W_222[3, 2] = 1
    
    # P4: A11(B10-B00) -> C00+C10
    U_222[3, 3] = 1
    V_222[2, 3] = 1; V_222[0, 3] = -1
    W_222[0, 3] = 1; W_222[2, 3] = 1
    
    # P5: (A00+A01)B11 -> -C00+C01
    U_222[0, 4] = 1; U_222[1, 4] = 1
    V_222[3, 4] = 1
    W_222[0, 4] = -1; W_222[1, 4] = 1
    
    # P6: (A10-A00)(B00+B01) -> C11
    U_222[2, 5] = 1; U_222[0, 5] = -1
    V_222[0, 5] = 1; V_222[1, 5] = 1
    W_222[3, 5] = 1
    
    # P7: (A01-A11)(B10+B11) -> C00
    U_222[1, 6] = 1; U_222[3, 6] = -1
    V_222[2, 6] = 1; V_222[3, 6] = 1
    W_222[0, 6] = 1

    # 2. Kronecker Product for M_4,4,4
    # U_444 = U_222 kron U_222 ? No.
    # The tensor T_444 = T_222 (x) T_222.
    # U_444[i*4+j, r1*7+r2] = U_222[i, r1] * U_222[j, r2]
    U_444 = np.kron(U_222, U_222)
    V_444 = np.kron(V_222, V_222)
    W_444 = np.kron(W_222, W_222)
    
    # Check shapes: 16x49
    # 3. Construct M_4,4,1
    U_441 = np.zeros((16, 16))
    V_441 = np.zeros((4, 16))
    W_441 = np.zeros((4, 16))
    for r in range(16):
        i = r // 4
        j = r % 4
        U_441[i*4+j, r] = 1
        V_441[j, r] = 1
        W_441[i, r] = 1 # k=0, index 0*4+i = i

    # 4. Combine for M_4,4,9
    # Rank = 49 + 49 + 16 = 114
    rank = 114
    U = np.zeros((16, rank))
    V = np.zeros((36, rank))
    W = np.zeros((36, rank))
    
    # Block 1: B1 (4x4)
    U[:, 0:49] = U_444
    V[0:16, 0:49] = V_444
    W[0:16, 0:49] = W_444
    
    # Block 2: B2 (4x4)
    U[:, 49:98] = U_444
    V[16:32, 49:98] = V_444
    W[16:32, 49:98] = W_444
    
    # Block 3: B3 (4x1)
    U[:, 98:114] = U_441
    V[32:36, 98:114] = V_441
    W[32:36, 98:114] = W_441
    
    # Convert to lists
    return {"U": U.tolist(), "V": V.tolist(), "W": W.tolist()}
