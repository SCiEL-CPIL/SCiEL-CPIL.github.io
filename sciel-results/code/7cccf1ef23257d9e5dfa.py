# EVOLVE-BLOCK-START
import time
import itertools
import random

def load(boxes, container):
    start_time = time.time()
    deadline = start_time + 115.0  # Safety margin for 120s limit
    
    W, H, D = container
    if W <= 0 or H <= 0 or D <= 0:
        return [(-1, 0, 0, 0, w, h, d) for w, h, d in boxes]
        
    container_volume = W * H * D
    
    def run_strategy(order_key_func, seed=0):
        """
        Runs a packing strategy with a specific ordering.
        Returns (total_volume, results_list)
        """
        if time.time() > deadline:
            return 0, None
            
        indexed_boxes = list(enumerate(boxes))
        try:
            indexed_boxes.sort(key=order_key_func)
        except Exception:
            return 0, None

        placed = [] # List of (x, y, z, w, h, d)
        results = [None] * len(boxes)
        total_vol = 0
        
        # Candidate points: corners generated by placed boxes
        # We use a set for uniqueness, but need to iterate. 
        # To maintain some order/determinism in tie-breaking, we might sort later or just rely on set iteration if we check all.
        # However, for speed, we just iterate the set.
        candidate_points = set([(0, 0, 0)])
        
        for orig_idx, (w, h, d) in indexed_boxes:
            if time.time() > deadline:
                break
                
            # Generate unique orientations
            box_dims = sorted([w, h, d], reverse=True)
            seen_orientations = set()
            orientations = []
            for perm in itertools.permutations(box_dims):
                if perm not in seen_orientations:
                    seen_orientations.add(perm)
                    orientations.append(perm)
            
            best_pos = None
            best_score = float('inf')
            best_orient = None
            found_placement = False
            
            # Iterate through all current candidate points
            # To ensure determinism in case of ties or floating point issues in set iteration order (though coords are ints/floats),
            # we don't strictly need sorted if we just pick min score.
            for cx, cy, cz in candidate_points:
                if time.time() > deadline:
                    break
                    
                for ow, oh, od in orientations:
                    # Check bounds
                    if cx + ow > W or cy + oh > H or cz + od > D:
                        continue
                    
                    # Check overlap with all placed boxes
                    overlap = False
                    for px, py, pz, pw, ph, pd in placed:
                        # Separation check:
                        # If any of these is true, they do NOT overlap
                        if not (cx + ow <= px or px + pw <= cx or 
                                cy + oh <= py or py + ph <= cy or 
                                cz + od <= pz or pz + pd <= cz):
                            overlap = True
                            break
                    
                    if not overlap:
                        # New Strategy: Volume-aware Best Fit
                        # We want to place boxes as "tightly" as possible to the origin and to each other.
                        # Metric: Sum of normalized distances from origin.
                        # This encourages filling the (0,0,0) corner first, then expanding.
                        # Normalizing by container dims makes it scale-invariant.
                        nx = cx / W if W > 0 else 0
                        ny = cy / H if H > 0 else 0
                        nz = cz / D if D > 0 else 0
                        
                        # Also consider the "tightness" against the box itself?
                        # A common heuristic is minimizing the max coordinate reached.
                        # Let's try a weighted sum of distances.
                        # score = nx + ny + nz
                        # But we also want to prefer orientations that fit better?
                        # Let's stick to position first.
                        
                        score = nx + ny + nz
                        
                        # Tie-breaker: minimize max extent to keep bounding box tight?
                        # Or just lexicographic order of coords for determinism?
                        # Let's add a small penalty for larger extents if scores are very close?
                        # Actually, simple lexicographic tie-break on (cx, cy, cz) is robust.
                        
                        if score < best_score or (score == best_score and (best_pos is None or (cx, cy, cz) < best_pos)):
                            best_score = score
                            best_pos = (cx, cy, cz)
                            best_orient = (ow, oh, od)
                            found_placement = True
            
            if found_placement:
                bx, by, bz = best_pos
                bw, bh, bd = best_orient
                
                # Place the box
                placed.append((bx, by, bz, bw, bh, bd))
                results[orig_idx] = (0, bx, by, bz, bw, bh, bd)
                total_vol += bw * bh * bd
                
                # Generate new candidate positions
                # 1. (bx + bw, by, bz)  -> Next to it in X
                # 2. (bx, by + bh, bz)  -> Next to it in Y
                # 3. (bx, by, bz + bd)  -> On top of it in Z
                # Also consider combinations? No, just the 3 immediate faces is standard for this heuristic.
                
                new_candidates = [
                    (bx + bw, by, bz),
                    (bx, by + bh, bz),
                    (bx, by, bz + bd)
                ]
                
                for nc in new_candidates:
                    if 0 <= nc[0] <= W and 0 <= nc[1] <= H and 0 <= nc[2] <= D:
                        candidate_points.add(nc)
            else:
                results[orig_idx] = (-1, 0, 0, 0, w, h, d)
                
        # Fill any remaining results
        for i in range(len(boxes)):
            if results[i] is None:
                w, h, d = boxes[i]
                results[i] = (-1, 0, 0, 0, w, h, d)
                
        return total_vol, results

    # Define multiple sorting strategies
    # 1. Volume Descending
    def sort_vol_desc(x):
        w, h, d = x[1]
        return -(w * h * d)
        
    # 2. Height Descending (often good for stacking)
    def sort_height_desc(x):
        w, h, d = x[1]
        return -max(w, h, d)
        
    # 3. Sum of dims Descending
    def sort_sum_desc(x):
        w, h, d = x[1]
        return -(w + h + d)
        
    # 4. Aspect Ratio (prefer cubic)
    def sort_aspect(x):
        w, h, d = x[1]
        vol = w * h * d
        if vol == 0: return 0
        # Normalize
        s = (w + h + d) / 3.0
        # Deviation from cube
        dev = abs(w-s) + abs(h-s) + abs(d-s)
        # Prefer larger volume, then lower deviation?
        # Let's just sort by volume desc, but break ties by aspect?
        # Simpler: Sort by -volume, then by aspect deviation
        return (-vol, dev)
        
    # 5. Randomized Volume (with fixed seed for reproducibility within run)
    # We can run a few random perturbations if time permits
    
    best_vol = 0
    best_results = None
    
    strategies = [
        sort_vol_desc,
        sort_height_desc,
        sort_sum_desc,
        sort_aspect,
    ]
    
    # Add a few random strategies if we have time
    # But let's stick to deterministic ones first for reliability
    
    for i, strat in enumerate(strategies):
        if time.time() > deadline:
            break
            
        vol, res = run_strategy(strat)
        
        if res is not None and vol > best_vol:
            best_vol = vol
            best_results = res
            
        # If we have significant time left, try some randomized variants
        if time.time() < deadline - 20:
             # Try a random shuffle of items with similar volumes?
             # Or just a random seed for tie-breaking?
             # Let's try one random strategy: sort by volume but with random tie-breaking
             pass # Keeping it simple for now to avoid bugs. The deterministic diversity is usually enough.
             
    if best_results is None:
        # Fallback: all left out
        best_results = [(-1, 0, 0, 0, w, h, d) for w, h, d in boxes]
        
    return best_results
# EVOLVE-BLOCK-END
