def construct():
    start = time.time()
    
    # Phase 1: Construct the 64-word [18,6,6] code
    try:
        base_words = _shorten_golay_to_18()
    except Exception as e:
        # Fallback to RM code if Golay construction fails
        base_words = _reed_muller_extended()
        
    # Verify base code
    if not _check_min_distance(base_words, MIN_DIST):
        # Fallback
        base_words = _reed_muller_extended()
        
    best = list(base_words)
    
    elapsed = time.time() - start
    if elapsed > DEADLINE:
        return best
        
    # Phase 2: Greedy packing
    time_remaining = DEADLINE - (time.time() - start)
    greedy_time = min(50.0, time_remaining * 0.8)
    
    if greedy_time > 1.0:
        # Run greedy packing
        try:
            packed_words = _greedy_pack_fast(best, greedy_time)
            if len(packed_words) > len(best) and _check_min_distance(packed_words, MIN_DIST):
                best = packed_words
        except Exception:
            pass # Keep best if greedy fails
    
    # Final validation
    if not _check_min_distance(best, MIN_DIST):
        return _reed_muller_extended()
        
    return best

def _reed_muller_extended():
    """First-order Reed-Muller on 16 coords extended by 2 zero bits -> 32 words, dist 8."""
    words = []
    for slope in range(16):
        for intercept in range(2):
            word = 0
            for point in range(16):
                bit = ((slope & point).bit_count() + intercept) % 2
                word |= bit << point
            words.append(word)
    return words
