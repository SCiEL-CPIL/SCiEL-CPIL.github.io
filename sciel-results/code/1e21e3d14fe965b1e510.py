"""
Strategy: Structured Algebraic Construction + Efficient Greedy Packing
1. Construct the [18,6,6] linear code by shortening the [24,12,8] Golay code.
   This yields 64 codewords, which is a much stronger seed than the 32-word RM code.
2. Use a bitmask-based greedy algorithm to add more words.
   For each candidate, we check against a precomputed 'forbidden mask' of all words
   within distance < 6 from existing codewords. This allows $O(1)$ rejection checks
   for most candidates, enabling thousands of attempts per second.
"""
import time
import random
import numpy as np

TOTAL_BUDGET = 60.0
SAFETY_MARGIN = 5.0
DEADLINE = TOTAL_BUDGET - SAFETY_MARGIN

N = 18
MIN_DIST = 6

def _hamming(a, b):
    return (a ^ b).bit_count()

def _check_min_distance(words, min_dist):
    n = len(words)
    for i in range(n):
        wi = words[i]
        for j in range(i + 1, n):
            if _hamming(wi, words[j]) < min_dist:
                return False
    return True

def _generate_golay_code():
    """
    Generate the [24,12,8] binary Golay code.
    Uses the standard construction from the [23,12,7] QR code.
    Returns a list of 4096 integers.
    """
    # Quadratic residues mod 23
    qr_set = set((i * i) % 23 for i in range(1, 23))
    qr_set.discard(0)
    
    # The [23,12,7] QR code is generated by the 12x23 matrix where row i 
    # corresponds to the cyclic shift of the QR set.
    # However, a more direct way is to use the known generator matrix structure.
    # The generator matrix G_23 has rows:
    # Row 0: 1 at positions in QR set
    # Row i: cyclic shift of Row 0 by i positions
    
    # Let's build the 12 basis vectors for the [23,12,7] code.
    # The code is spanned by the 12 vectors v_0, ..., v_11 where v_i is the 
    # indicator of the set { (x + i) mod 23 | x in QR_set }? No, that's not quite right for the standard basis.
    
    # Standard construction:
    # The generator matrix G is 12x23.
    # Let's use the property that the code is cyclic.
    # Actually, the simplest robust way is to use the known parity check matrix or generator matrix.
    
    # Let's construct the [23,12,7] code using the fact that it's the null space of the 
    # 11x23 parity check matrix H, or more simply, use the 12 linearly independent words.
    
    # A known set of 12 basis words for the [23,12,7] QR code:
    # We can generate them by taking the 12 shifts of the "all ones" vector? No.
    
    # Let's use the standard "circulant" construction.
    # The generator polynomial is related to the QR set.
    
    # Alternative: Use the fact that the [24,12,8] code is the set of all vectors (u, v) 
    # where u is in the [23,12,7] code and v is the parity bit.
    
    # To get the [23,12,7] code, we can use the 12 vectors:
    # v_i = sum_{j in QR} e_{(i+j) mod 23} ? No, that gives 23 vectors.
    
    # Let's use a verified generator matrix from literature or construct it via linear algebra.
    # The code is the span of the 12 vectors formed by the rows of the matrix:
    # M[i, j] = 1 if j-i mod 23 is in QR_set, else 0.
    # This matrix is 23x23 and has rank 12. The rows are not independent.
    # We need to extract 12 independent rows.
    
    # Let's form the 23x23 matrix and find a basis for its row space.
    M = np.zeros((23, 23), dtype=int)
    for i in range(23):
        for j in range(23):
            if (j - i) % 23 in qr_set:
                M[i, j] = 1
    
    # Find row echelon form to get 12 independent rows
    # Using numpy for linear algebra over GF(2) is tricky, so let's do Gaussian elimination manually.
    rows = [list(row) for row in M]
    basis = []
    for r in rows:
        pivot = -1
        for j in range(23):
            if r[j] == 1:
                pivot = j
                break
        if pivot == -1:
            continue
        for b in basis:
            if b[pivot] == 1:
                for k in range(23):
                    r[k] ^= b[k]
        # Check if zero
        if any(r):
            # Normalize pivot to 1 (already 1)
            basis.append(r)
            if len(basis) == 12:
                break
    
    # We have 12 basis vectors for the [23,12,7] code.
    # Now generate all 2^12 = 4096 codewords of the [23,12,7] code.
    code_23 = [0]
    for b in basis:
        new_words = []
        for w in code_23:
            # XOR w with the basis vector
            bw = 0
            for k in range(23):
                if b[k]:
                    bw |= (1 << k)
            new_words.append(w ^ bw)
        code_23.extend(new_words)
    
    # Extend to [24,12,8] by adding a parity bit
    code_24 = []
    for w in code_23:
        # Parity bit is sum of bits mod 2
        parity = bin(w).count('1') % 2
        w_24 = (w << 1) | parity
        code_24.append(w_24)
        
    return code_24

def _shorten_golay_to_18():
    """
    Shorten the [24,12,8] Golay code to length 18.
    We fix 6 coordinates to 0 and keep only codewords that have 0s in those positions.
    To maximize the number of surviving codewords, we should choose the 6 coordinates
    such that the restriction has minimal rank loss.
    For a random linear code, fixing k coordinates reduces the dimension by k on average.
    Here, fixing 6 coordinates should reduce dimension from 12 to 6, yielding 2^6 = 64 words.
    The distance remains at least 8 (actually, shortening preserves or increases relative distance, 
    but since we remove coordinates, the min distance of the shortened code is at least the original min distance, 
    wait: if we fix coordinates to 0, we are intersecting the code with a subspace. 
    The minimum distance of the intersection is at least the minimum distance of the original code? 
    Yes, because any two distinct codewords in the intersection are also distinct in the original code, 
    so their distance is >= 8. 
    Wait, the task requires distance >= 6. So a distance of 8 is fine.
    """
    golay_code = _generate_golay_code()
    
    # We need to choose 6 positions to fix to 0.
    # Due to the symmetry of the Golay code, any 6 positions should yield an isomorphic code.
    # Let's fix positions 0, 1, 2, 3, 4, 5.
    fixed_positions = [0, 1, 2, 3, 4, 5]
    mask = 0
    for p in fixed_positions:
        mask |= (1 << p)
        
    shortened_code = []
    for w in golay_code:
        if (w & mask) == 0:
            # Remove the fixed positions from the word
            # We want to map the 24-bit word to an 18-bit word.
            # The remaining 18 bits are at positions not in fixed_positions.
            # Let's just keep the bits as they are in the 24-bit integer, 
            # but the task requires length 18. 
            # So we need to compress the bits.
            # Positions 6..23 are the variable ones.
            # We can just take the lower 18 bits if we shift? 
            # No, the positions are 0..23. If we fix 0..5, the remaining are 6..23.
            # We can shift right by 6 to get an 18-bit integer.
            w_18 = w >> 6
            shortened_code.append(w_18)
            
    # Verify distinctness and distance
    if len(set(shortened_code)) != len(shortened_code):
        raise ValueError("Shortened code has duplicates")
        
    # The minimum distance of the shortened code is at least 8.
    # We return this 64-word code.
    return shortened_code

def _greedy_pack(base_words, time_limit):
    """
    Greedily add words to the base code using a forbidden mask approach.
    """
    words = list(base_words)
    start_time = time.time()
    rng = random.Random(42)
    
    # Precompute forbidden mask: all words within distance < MIN_DIST from any word in `words`
    # This is a boolean array of size 2^18 = 262144.
    forbidden = np.zeros(1 << N, dtype=bool)
    
    def update_forbidden(w):
        # Mark all words within distance < MIN_DIST from w as forbidden
        # Distance < 6 means weight of (w ^ cand) <= 5
        # Iterate over all masks with weight <= 5
        # There are sum_{i=0}^5 C(18, i) = 1 + 18 + 153 + 816 + 3060 + 8568 = 12616 masks.
        # This is fast enough.
        for mask in _masks_up_to_weight(5):
            forbidden[w ^ mask] = True
            
    for w in words:
        update_forbidden(w)
        
    while time.time() - start_time < time_limit:
        # Try to find a candidate not in forbidden
        # Random sampling is fast
        found = False
        for _ in range(1000): # Try 1000 random candidates
            cand = rng.randint(0, (1 << N) - 1)
            if not forbidden[cand]:
                # Add it
                words.append(cand)
                update_forbidden(cand)
                found = True
                break
        if not found:
            # If we can't find one quickly, try a more systematic search or break
            # For efficiency, we might just break or try a different strategy
            # Let's try to scan a portion of the space
            # But scanning 262144 items is fast in Python if we use numpy
            # available = np.where(~forbidden)[0]
            # if len(available) > 0:
            #    cand = rng.choice(available)
            #    ...
            # Let's just break if random fails, as the space is likely saturated or we are stuck in a local optimum
            # But we can try to "shake" by removing a random word and re-adding? 
            # That's complex. Let's stick to simple greedy for now.
            break
            
    return words

def _masks_up_to_weight(k):
    """Generate all masks of weight <= k for N=18."""
    # Precompute once? No, N is fixed.
    # We can generate them on the fly or cache.
    # Since N=18 is small, we can generate the list once.
    masks = []
    for w in range(k + 1):
        # Generate combinations of w positions from 0..17
        from itertools import combinations
        for combo in combinations(range(N), w):
            m = 0
            for p in combo:
                m |= (1 << p)
            masks.append(m)
    return masks

# Precompute masks for efficiency
_MASKS_W5 = _masks_up_to_weight(5)

