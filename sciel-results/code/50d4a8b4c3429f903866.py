def construct():
    start_time = time.time()
    deadline = start_time + 140.0  # Safety margin for 150s limit
    
    # 1. Deterministic Algebraic Construction
    # We construct a linear triple system on Z_16.
    # A base block B is translated by adding i mod 16 for i in 0..15.
    # To ensure linearity, we need that for any two distinct differences in the base block,
    # the number of solutions to x+y = diff is limited, or more simply, we check linearity directly.
    # A known good starting point for small n is to use a "near Steiner" structure.
    
    # Let's try a few candidate base blocks for Z16.
    # For a cyclic STS-like structure, we want the differences to cover each non-zero element roughly equally.
    # In Z16, there are 15 non-zero elements.
    # A triple {a,b,c} has differences b-a, c-a, c-b (and negatives).
    # If we use orbit of {0, 1, 5}:
    # Differences: 1, 5, 4. Negatives: 15, 11, 12.
    # Orbits: {1, 15}, {5, 11}, {4, 12}.
    # This doesn't cover all differences. We might need multiple orbits or a non-cyclic start.
    
    # Alternative: Start with a random greedy packing but use a "structured" random seed 
    # and then heavily optimize.
    # However, the directive asks for a structural change.
    # Let's use a **Greedy + Local Search** approach where the initial state is a 
    # **Maximal Linear Packing** generated by a **Deterministic Priority Queue** 
    # (choosing triples that minimize the "potential" independent set size, approximated by degree).
    
    # Actually, a better structural change is to use **Simulated Annealing** starting from 
    # a **random maximal packing**, but with a **cost function** that directly estimates 
    # the independence number or a lower bound on it, and **move operators** that 
    # preserve linearity (swap points).
    
    # Let's implement a robust Local Search on a random maximal packing.
    # Move: Pick two triples T1, T2. Try to swap a point in T1 with a point in T2 
    # such that linearity is preserved and the independence number decreases.
    
    def calculate_independence_number(system):
        """
        Fast calculation of independence number for n=16.
        Returns the size of the largest independent set.
        """
        if not system:
            return 16
            
        # Pre-compute bitmask for each triple
        triple_masks = []
        for a, b, c in system:
            mask = (1 << a) | (1 << b) | (1 << c)
            triple_masks.append(mask)
        
        # We want to find the max k such that there exists a subset of size k with no triple.
        # Iterate k from 16 down to 1.
        # For each k, check if any combination of k points is independent.
        # To speed up, we can use a recursive backtracking search for the maximum independent set.
        
        points = list(range(16))
        
        # Backtracking search
        # State: current_mask, current_size, start_idx
        # We want to maximize size.
        
        max_size = 0
        
        def backtrack(mask, size, start_idx):
            nonlocal max_size
            if size > max_size:
                max_size = size
                
            # Pruning: if size + (16 - start_idx) <= max_size, return
            if size + (16 - start_idx) <= max_size:
                return
                
            # Try adding points from start_idx to 15
            for i in range(start_idx, 16):
                new_mask = mask | (1 << i)
                
                # Check if new_mask is independent
                # A mask is independent if it does not fully contain any triple mask.
                is_independent = True
                for tm in triple_masks:
                    if (new_mask & tm) == tm:
                        is_independent = False
                        break
                        
                if is_independent:
                    backtrack(new_mask, size + 1, i + 1)
                else:
                    # If adding i makes it dependent, we can't add i or any superset containing i 
                    # that also contains the conflicting triple. 
                    # But we can still try other points.
                    pass
                    
        backtrack(0, 0, 0)
        return max_size

    def is_linear(triples):
        """Check if the set of triples is linear (no pair repeated)."""
        used_pairs = set()
        for a, b, c in triples:
            pairs = [(a, b), (b, c), (a, c)]
            for p in pairs:
                p_sorted = tuple(sorted(p))
                if p_sorted in used_pairs:
                    return False
                used_pairs.add(p_sorted)
        return True

    def greedy_packing(seed):
        random.seed(seed)
        points = list(range(16))
        all_triples = list(combinations(points, 3))
        random.shuffle(all_triples)
        
        triples = []
        used_pairs = set()
        
        for t in all_triples:
            a, b, c = t
            p1 = (a, b) if a < b else (b, a)
            p2 = (b, c) if b < c else (c, b)
            p3 = (a, c) if a < c else (c, a)
            
            if p1 not in used_pairs and p2 not in used_pairs and p3 not in used_pairs:
                triples.append([a, b, c])
                used_pairs.add(p1)
                used_pairs.add(p2)
                used_pairs.add(p3)
                
        return triples

    def local_search(system, max_steps, time_limit):
        """
        Improve the system by swapping points in triples to reduce independence number.
        """
        current_system = [list(t) for t in system]
        current_score = calculate_independence_number(current_system)
        
        # Precompute pair usage for quick linearity check
        def get_used_pairs(sys):
            used = set()
            for a, b, c in sys:
                used.add((a, b) if a < b else (b, a))
                used.add((b, c) if b < c else (c, b))
                used.add((a, c) if a < c else (c, a))
            return used

        used_pairs = get_used_pairs(current_system)
        
        # Move: Pick a triple T_i and a point p in T_i. Remove p from T_i.
        # Pick a point q not in T_i. Add q to T_i.
        # This changes the pairs associated with T_i.
        # We must ensure no pair is duplicated.
        
        # A more complex move: Swap two points between two triples?
        # Let's stick to single point replacement first.
        
        step = 0
        while step < max_steps and time.time() < time_limit:
            step += 1
            if time.time() > time_limit:
                break
                
            improved = False
            # Randomly select a triple to modify
            idx = random.randint(0, len(current_system) - 1)
            t = current_system[idx]
            
            # Try replacing each point in t with a random other point
            for k in range(3):
                old_point = t[k]
                # Candidates: points not in t
                candidates = [p for p in range(16) if p not in t]
                random.shuffle(candidates)
                
                for new_point in candidates:
                    # Construct new triple
                    new_t = t.copy()
                    new_t[k] = new_point
                    # Sort for consistency? No, order doesn't matter for set logic, but for pair check it does.
                    
                    # Check linearity
                    # Remove old pairs from used_pairs
                    old_pairs = []
                    a, b, c = t
                    old_pairs.append((a, b) if a < b else (b, a))
                    old_pairs.append((b, c) if b < c else (c, b))
                    old_pairs.append((a, c) if a < c else (c, a))
                    
                    # Add new pairs
                    new_pairs = []
                    a, b, c = new_t
                    new_pairs.append((a, b) if a < b else (b, a))
                    new_pairs.append((b, c) if b < c else (c, b))
                    new_pairs.append((a, c) if a < c else (c, a))
                    
                    # Check if any new pair is already in used_pairs (excluding the ones we just removed)
                    # Temporarily remove old pairs
                    for p in old_pairs:
                        used_pairs.remove(p)
                        
                    valid = True
                    for p in new_pairs:
                        if p in used_pairs:
                            valid = False
                            break
                            
                    if valid:
                        # Add new pairs
                        for p in new_pairs:
                            used_pairs.add(p)
                        
                        # Update system
                        current_system[idx] = new_t
                        
                        # Evaluate
                        new_score = calculate_independence_number(current_system)
                        
                        if new_score < current_score:
                            current_score = new_score
                            improved = True
                            break
                        else:
                            # Revert
                            for p in new_pairs:
                                used_pairs.remove(p)
                            for p in old_pairs:
                                used_pairs.add(p)
                            current_system[idx] = t
                    else:
                        # Revert removal of old pairs
                        for p in old_pairs:
                            used_pairs.add(p)
                            
                    if improved:
                        break
                if improved:
                    break
            if not improved and step % 100 == 0:
                # Maybe random restart or accept worse moves? 
                # For now, just continue. If stuck, break.
                if step > 5000:
                    break
                    
        return current_system, current_score

    best_system = None
    best_score = 16
    
    # Run multiple instances of: Greedy + Local Search
    num_runs = 50
    for i in range(num_runs):
        if time.time() > deadline - 20.0:
            break
            
        # Generate initial packing
        init_system = greedy_packing(i)
        
        # Local search
        # Time limit per local search: 100ms
        search_start = time.time()
        optimized_system, score = local_search(init_system, max_steps=2000, time_limit=search_start + 0.1)
        
        if score < best_score:
            best_score = score
            best_system = optimized_system
            
            if best_score <= 5:
                break

    if best_system is None:
        # Fallback
        return [[3 * i, 3 * i + 1, 3 * i + 2] for i in range(5)]
        
    return best_system
