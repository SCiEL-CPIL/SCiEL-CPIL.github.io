def construct():
    start_time = time.time()
    deadline = 145.0  # Safety margin before 150s kill

    def score_set(U):
        """
        Compute the score for a set U.
        Score = 1 + log(|U-U| / |U+U|) / log(2*max(U)+1)
        """
        if not U:
            return 0.0
        U_set = set(U)
        max_U = max(U_set)
        if max_U == 0:
            return 0.0
        
        # For small sets, compute exactly
        # For larger sets, we rely on the fact that we are only calling this
        # on sets generated by the structured search which are small enough,
        # or we use the combinatorial shortcut if the structure allows it.
        # However, the directive suggests ternary search over continuous b, m.
        # The set U = { floor(b^k) } is not necessarily "no-carry" in a simple base.
        # So we must compute exactly or estimate.
        # Given the time limit, we should restrict the size of U during search.
        
        n = len(U_set)
        if n > 500:
            # Too slow for O(n^2) in the inner loop of ternary search.
            # We will avoid such sets in the search or use a faster estimator.
            # For now, return a low score to discourage large n in search.
            return 0.0
            
        sumset = set()
        diffset = set()
        
        # Optimization: use numpy if available for speed? 
        # Standard library is safer to avoid import issues in some environments, 
        # but numpy is allowed. Let's stick to sets for correctness and simplicity 
        # for n < 500. n=500 -> 250k ops, which is fast in Python.
        
        for a in U_set:
            for b in U_set:
                sumset.add(a + b)
                diffset.add(a - b)
                
        ratio = len(diffset) / len(sumset)
        if ratio <= 0:
            return 0.0
        
        try:
            exponent = 1 + math.log(ratio) / math.log(2 * max_U + 1)
        except:
            return 0.0
        return exponent

    def generate_set(b, m):
        """
        Generate U = { floor(b^k) | k=0...m }
        b is float, m is int.
        """
        U = []
        for k in range(m + 1):
            # Use pow for precision
            val = int(math.floor(b ** k))
            U.append(val)
        return sorted(set(U))

    def score_params(b, m):
        """
        Wrapper for ternary search.
        Returns negative score for minimization (or just score for maximization).
        We want to maximize score.
        """
        U = generate_set(b, m)
        return score_set(U)

    best_score = 0.0
    best_b = None
    best_m = None

    # Strategy: 
    # 1. Discretize m (integer).
    # 2. For each m, ternary search over b (continuous).
    # 
    # Ranges:
    # m: 2 to 30 (max_U grows as b^m. If b=10, m=30 -> 10^30. log is fine. 
    #      But n=m+1. If m=30, n=31. O(n^2) is tiny. 
    #      Why limit m? If m is huge, n is huge, O(n^2) becomes slow.
    #      Let's cap m at 100? n=101 -> 10k ops. Still fast.
    #      Let's try m up to 200. n=201 -> 40k ops. Still fast.
    #      Let's try m up to 500. n=501 -> 250k ops. Might be slow if done many times.
    #      Ternary search takes ~log_{1.5}(range/eps) iterations.
    #      Range of b: 1.01 to 100.
    #      Iterations: ~50.
    #      50 * 500 (m) * 250k (ops) = 6.25e9 ops. Too slow.
    #      
    #      So we need to be smarter.
    #      1. Limit m in the search phase.
    #      2. Use a coarser search first.
    #      3. Note that score depends on ratio |U-U|/|U+U|.
    #         For geometric progressions, this ratio is roughly constant or grows slowly?
    #         Actually, for b close to 1, U is clustered, |U+U| is small, |U-U| is small?
    #         Let's analyze.
    #         If b=1, U={0,1,...,m}. |U+U|=2m+1, |U-U|=2m+1. Ratio=1. Score=1.
    #         If b is large, U is sparse. 
    #         Let's just search.
    
    # We will iterate over m in a range.
    # For each m, we ternary search b.
    # To speed up, we can first do a coarse grid search over b, then refine.
    
    # Ranges for b:
    # b must be > 1.
    # If b is very close to 1, floor(b^k) might have duplicates or slow growth.
    # If b is very large, max_U is huge, log(2*max_U+1) is large.
    # 
    # Let's define the search space for b: [1.01, 50.0]
    # Let's define the search space for m: [2, 50] initially.
    
    # Time budget per (b, m) evaluation:
    # If m=50, n=51. O(n^2) = 2600 ops. Very fast.
    # So we can afford many evaluations.
    
    # Let's do:
    # For m in range(2, 51):
    #   Ternary search b in [1.01, 50.0]
    #   Iterations: 60
    
    # Total evals: 50 * 60 = 3000.
    # Each eval: generate set (50 ops) + score (2600 ops) ~ 3000 ops.
    # Total ops: 9e6. Should finish in < 1s.
    # We can expand m to 200.
    # m=200, n=201. O(n^2) = 40k ops.
    # Total evals: 200 * 60 = 12000.
    # Total ops: 12000 * 40000 = 4.8e8. Might take a few seconds.
    # Let's try m up to 100.
    
    for m in range(2, 101):
        # Ternary search for b
        lo = 1.01
        hi = 50.0
        
        # Coarse search first? No, ternary is fine.
        # But the function might not be unimodal.
        # Let's do a grid search first to find a good region, then ternary.
        
        # Grid search: 20 points
        best_b_local = None
        best_score_local = -1
        
        # Logarithmic spacing for b? Or linear?
        # b from 1.01 to 50.
        # Let's use linear for simplicity, or log.
        # Log spacing is better for scale invariance.
        log_lo = math.log(1.01)
        log_hi = math.log(50.0)
        
        for i in range(20):
            log_b = log_lo + (log_hi - log_lo) * i / 19.0
            b = math.exp(log_b)
            s = score_params(b, m)
            if s > best_score_local:
                best_score_local = s
                best_b_local = b
        
        if best_b_local is None:
            continue
            
        # Refine around best_b_local using ternary search
        # Window size: 10% of the range? Or just use the whole range if unimodal?
        # Let's assume local unimodality around the grid peak.
        # Or just do ternary search on the whole range, it's robust if unimodal.
        # If not unimodal, grid + local ternary is better.
        
        # Let's refine in a window around best_b_local
        # Window: [best_b_local * 0.9, best_b_local * 1.1]
        # Ensure within [1.01, 50]
        lo_ref = max(1.01, best_b_local * 0.8)
        hi_ref = min(50.0, best_b_local * 1.2)
        
        for _ in range(40):
            if time.time() > deadline:
                break
            m1 = lo_ref + (hi_ref - lo_ref) / 3.0
            m2 = hi_ref - (hi_ref - lo_ref) / 3.0
            
            s1 = score_params(m1, m)
            s2 = score_params(m2, m)
            
            if s1 > s2:
                hi_ref = m2
            else:
                lo_ref = m1
        
        # Evaluate the midpoint of the refined interval
        b_final = (lo_ref + hi_ref) / 2.0
        s_final = score_params(b_final, m)
        
        if s_final > best_score:
            best_score = s_final
            best_b = b_final
            best_m = m
        
        # Also check the grid peak just in case
        if best_score_local > best_score:
            best_score = best_score_local
            best_b = best_b_local
            best_m = m

    # If we still have time, try larger m or finer search
    if time.time() < deadline - 10:
        # Try m up to 200
        for m in range(101, 201):
            # Coarse search
            best_b_local = None
            best_score_local = -1
            log_lo = math.log(1.01)
            log_hi = math.log(50.0)
            
            for i in range(10): # Fewer points for larger m
                log_b = log_lo + (log_hi - log_lo) * i / 9.0
                b = math.exp(log_b)
                s = score_params(b, m)
                if s > best_score_local:
                    best_score_local = s
                    best_b_local = b
            
            if best_b_local is not None and best_score_local > best_score:
                # Refine
                lo_ref = max(1.01, best_b_local * 0.9)
                hi_ref = min(50.0, best_b_local * 1.1)
                
                for _ in range(30):
                    if time.time() > deadline:
                        break
                    m1 = lo_ref + (hi_ref - lo_ref) / 3.0
                    m2 = hi_ref - (hi_ref - lo_ref) / 3.0
                    s1 = score_params(m1, m)
                    s2 = score_params(m2, m)
                    if s1 > s2:
                        hi_ref = m2
                    else:
                        lo_ref = m1
                
                b_final = (lo_ref + hi_ref) / 2.0
                s_final = score_params(b_final, m)
                
                if s_final > best_score:
                    best_score = s_final
                    best_b = b_final
                    best_m = m

    # If no valid set found, fallback
    if best_b is None or best_m is None:
        return [0, 1, 2]

    # Generate the final set
    U = generate_set(best_b, best_m)
    
    # Sanity check: ensure 0 is in U
    if 0 not in U:
        U.insert(0, 0)
        
    return U

