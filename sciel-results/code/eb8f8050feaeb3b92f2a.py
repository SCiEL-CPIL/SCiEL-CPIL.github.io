import time
import random
from math import lcm
import bisect
from fractions import Fraction

def construct():
    start_time = time.time()
    deadline = start_time + 85.0

    denominators = list(range(2, 49))
    n = len(denominators)

    L = 1
    for d in denominators:
        L = lcm(L, d)

    weights = [L // d for d in denominators]

    def check_time():
        return time.time() > deadline

    def validate(indices):
        if not indices:
            return False, 0
        if len(set(indices)) != len(indices):
            return False, 0
        if any(i < 0 or i >= n for i in indices):
            return False, 0
        s = sum(weights[i] for i in indices)
        if s >= L:
            return False, 0
        return True, s

    best_sum = -1
    best_indices = None

    def update_best(indices):
        nonlocal best_sum, best_indices
        valid, s = validate(indices)
        if valid and s > best_sum:
            best_sum = s
            best_indices = list(indices)
            return True
        return False

    # Strategy 0: LLL-based lattice search
    # We want to find subset sums close to L.
    # Consider the lattice generated by vectors:
    #   v0 = [L, 0, 0, ..., 0]
    #   vi = [weights[i-1], 0, ..., 1, ..., 0] for i=1..n
    # A short vector in this lattice corresponds to a combination of weights
    # that sums to something close to a multiple of L.
    # Specifically, if we find a vector [a, b1, b2, ..., bn] with small |a|,
    # then sum(bi * weights[i-1]) is close to a*L.
    # If a = 1 and all bi are in {0,1}, we have a subset summing to L.
    # But we need sum < L, so we want sum = L - 1 (deficit 1) or as close as possible.
    
    # Let's implement LLL reduction on the lattice.
    def lll_reduce(basis):
        """LLL lattice basis reduction. basis is list of lists (integer vectors)."""
        d = len(basis[0])
        n = len(basis)
        
        # Deep copy
        B = [row[:] for row in basis]
        mu = [[0.0] * (n + 1) for _ in range(n + 1)]
        size = [[0] * (n + 1) for _ in range(n + 1)]
        
        # Initialize size
        for i in range(n):
            for j in range(i + 1, n + 1):
                size[i][j] = 1
        
        # Initialize mu
        for i in range(n):
            for j in range(i + 1, n + 1):
                # mu[i][j] = <B[i], B[j-1]> / <B[j-1], B[j-1]>
                dot_ij = sum(B[i][k] * B[j-1][k] for k in range(d))
                dot_jj = sum(B[j-1][k] * B[j-1][k] for k in range(d))
                if dot_jj != 0:
                    mu[i][j] = dot_ij / dot_jj
                else:
                    mu[i][j] = 0.0
        
        # LLL algorithm
        k = 1
        while k < n:
            if check_time():
                break
            # Step 1: Size reduction
            for i in range(k - 1, -1, -1):
                # mu[i][k+1] = mu[i][k] - mu[i][k+1] * mu[k][k+1]
                mu[i][k + 1] = mu[i][k] - mu[i][k + 1] * mu[k][k + 1]
                # B[i] = B[i] - round(mu[i][k+1]) * B[k]
                r = round(mu[i][k + 1])
                if r != 0:
                    for d_idx in range(d):
                        B[i][d_idx] -= r * B[k][d_idx]
                    # Recompute mu[i][j] for j = i+1..k+1
                    for j in range(i + 1, k + 2):
                        dot_ij = sum(B[i][dd] * B[j-1][dd] for dd in range(d))
                        dot_jj = sum(B[j-1][dd] * B[j-1][dd] for dd in range(d))
                        if dot_jj != 0:
                            mu[i][j] = dot_ij / dot_jj
                        else:
                            mu[i][j] = 0.0
            
            # Step 2: Lovasz condition check
            # mu[k][k+1]^2 * size[k][k+2] >= (1 - delta) * size[k][k+1]
            delta = 0.75
            lhs = mu[k][k + 1] ** 2 * size[k][k + 2]
            rhs = (1 - delta) * size[k][k + 1]
            
            if lhs >= rhs:
                k += 1
            else:
                # Swap B[k-1] and B[k]
                B[k - 1], B[k] = B[k], B[k - 1]
                
                # Update mu and size
                for i in range(k - 1):
                    mu[i][k] = mu[i][k + 1]
                    mu[i][k + 1] = mu[i][k]
                
                mu[k - 1][k + 1] = mu[k - 1][k] - mu[k - 1][k + 1] * mu[k][k + 1]
                
                # Recompute mu[k-1][k]
                dot_kk = sum(B[k-1][dd] * B[k-1][dd] for dd in range(d))
                dot_kk1 = sum(B[k][dd] * B[k][dd] for dd in range(d))
                if dot_kk != 0:
                    mu[k - 1][k] = 0.0  # After swap, recompute properly
                    # Actually need to recompute from scratch
                    dot_kk1_k = sum(B[k][dd] * B[k-1][dd] for dd in range(d))
                    if dot_kk1 != 0:
                        mu[k - 1][k] = dot_kk1_k / dot_kk1
                    else:
                        mu[k - 1][k] = 0.0
                
                # Update sizes
                for j in range(k, k + 2):
                    size[k - 1][j + 1] = size[k][j + 1]
                
                if k > 1:
                    k -= 1
        
        return B
    
    # Build lattice basis
    # v0 = [L, 0, 0, ..., 0]
    # vi = [weights[i-1], 0, ..., 1, ..., 0] for i=1..n
    # We'll use a scaled version to keep numbers manageable.
    # Actually, let's work with the deficit directly.
    # We want sum(weights[i] for i in subset) to be as close to L as possible, but < L.
    # Let deficit = L - sum. We want to minimize deficit > 0.
    # So we want to find subset sums that are L-1, L-2, etc.
    
    # Alternative approach: use the lattice to find vectors where the first coordinate
    # is small (close to 0 mod L) and the other coordinates are 0 or 1.
    
    # Let's try a different lattice formulation.
    # Consider vectors in Z^(n+1):
    #   e0 = [1, 0, 0, ..., 0] * L  (this represents L)
    #   ei = [weights[i-1], 0, ..., 1, ..., 0] for i = 1..n
    # A lattice vector [a, b1, ..., bn] represents a*L - sum(bi*weights[i-1]) = 0
    # if all bi are integers. We want bi in {0,1} and a=1, giving sum = L.
    # But we need sum < L, so we want a=1 and sum = L - deficit for small deficit.
    
    # This is getting complex. Let's use a simpler approach:
    # Enumerate subset sums using meet-in-the-middle, but with a twist.
    
    # Strategy 1: Meet-in-the-middle (keep existing)
    mid = n // 2
    w1 = [weights[i] for i in range(mid)]
    w2 = [weights[i] for i in range(mid, n)]

    def gen_subset_sums(weights_list):
        sums = [(0, 0)]
        for i, w in enumerate(weights_list):
            if check_time():
                break
            bit = 1 << i
            current_len = len(sums)
            for j in range(current_len):
                s, m = sums[j]
                ns = s + w
                if ns < L:
                    sums.append((ns, m | bit))
        return sums

    sums1 = gen_subset_sums(w1)

    if not check_time():
        sums2 = gen_subset_sums(w2)
        if not check_time():
            sums2.sort(key=lambda x: x[0])
            sums2_vals = [s[0] for s in sums2]

            for s1, m1 in sums1:
                if check_time():
                    break
                target = L - s1 - 1
                idx = bisect.bisect_right(sums2_vals, target)
                if idx > 0:
                    s2, m2 = sums2[idx - 1]
                    total = s1 + s2
                    if total > best_sum:
                        best_sum = total
                        indices = []
                        for i in range(mid):
                            if m1 & (1 << i):
                                indices.append(i)
                        for i in range(mid, n):
                            if m2 & (1 << (i - mid)):
                                indices.append(i)
                        best_indices = indices

    # Strategy 2: Enhanced local search with 2-swap moves
    if not check_time() and best_indices is not None:
        chosen = set(best_indices)
        s = best_sum
        
        for iteration in range(50000):
            if check_time():
                break
            improved = False
            
            # Try 1-add
            candidates_add = [i for i in range(n) if i not in chosen and s + weights[i] < L]
            if candidates_add:
                best_add = max(candidates_add, key=lambda i: s + weights[i])
                new_s = s + weights[best_add]
                if new_s > best_sum:
                    chosen.add(best_add)
                    best_sum = new_s
                    s = new_s
                    best_indices = list(chosen)
                    improved = True
            
            if not improved:
                # Try 1-remove 1-add (swap)
                found = False
                for rem in list(chosen):
                    if found or check_time():
                        break
                    s_after = s - weights[rem]
                    candidates_add2 = [i for i in range(n)
                                       if i not in chosen and s_after + weights[i] < L]
                    if candidates_add2:
                        best_add2 = max(candidates_add2, key=lambda i: s_after + weights[i])
                        new_s = s_after + weights[best_add2]
                        if new_s > best_sum:
                            chosen.discard(rem)
                            chosen.add(best_add2)
                            best_sum = new_s
                            s = new_s
                            best_indices = list(chosen)
                            found = True
                            improved = True
                            break
            
            if not improved:
                # Try 2-remove 2-add
                if len(chosen) >= 2:
                    found2 = False
                    rem_list = list(chosen)
                    for i_rem in range(len(rem_list)):
                        if found2 or check_time():
                            break
                        for j_rem in range(i_rem + 1, len(rem_list)):
                            if found2 or check_time():
                                break
                            r1, r2 = rem_list[i_rem], rem_list[j_rem]
                            s_after2 = s - weights[r1] - weights[r2]
                            if s_after2 < 0:
                                continue
                            available = [i for i in range(n) if i not in chosen]
                            if len(available) < 2:
                                continue
                            # Find best pair to add
                            best_pair = None
                            best_pair_s = s_after2
                            for a1 in available:
                                if check_time():
                                    break
                                if s_after2 + weights[a1] >= L:
                                    continue
                                for a2 in available:
                                    if a2 <= a1:
                                        continue
                                    ns = s_after2 + weights[a1] + weights[a2]
                                    if ns < L and ns > best_pair_s:
                                        best_pair_s = ns
                                        best_pair = (a1, a2)
                            if best_pair is not None and best_pair_s > best_sum:
                                chosen.discard(r1)
                                chosen.discard(r2)
                                chosen.add(best_pair[0])
                                chosen.add(best_pair[1])
                                best_sum = best_pair_s
                                s = best_pair_s
                                best_indices = list(chosen)
                                found2 = True
                                improved = True
                                break
            
            if not improved:
                break

    # Strategy 3: Targeted search around current best
    if not check_time() and best_indices is not None:
        chosen = set(best_indices)
        s = best_sum
        deficit = L - s
        
        # Try to find combinations that reduce deficit by small amounts
        # Look for items that can replace larger items with smaller ones
        for _ in range(10000):
            if check_time():
                break
            
            # Random perturbation: remove 1-2 items, add 1-2 different items
            n_rem = random.randint(1, min(2, len(chosen)))
            n_add = random.randint(1, 2)
            
            to_remove = random.sample(list(chosen), n_rem)
            available = [i for i in range(n) if i not in chosen]
            if len(available) < n_add:
                continue
            to_add = random.sample(available, n_add)
            
            new_chosen = chosen.copy()
            for r in to_remove:
                new_chosen.discard(r)
            for a in to_add:
                new_chosen.add(a)
            
            new_s = sum(weights[i] for i in new_chosen)
            if new_s < L and new_s > best_sum:
                best_sum = new_s
                best_indices = list(new_chosen)
                chosen = new_chosen
                s = new_s

    # Strategy 4: Systematic refinement
    if not check_time() and best_indices is not None:
        for _ in range(50):
            if check_time():
                break
            changed = False
            chosen = set(best_indices)
            s = best_sum

            # Try adding any single item
            for i in range(n):
                if check_time():
                    break
                if i not in chosen and s + weights[i] < L and s + weights[i] > best_sum:
                    chosen.add(i)
                    best_sum = s + weights[i]
                    best_indices = list(chosen)
                    s = best_sum
                    changed = True

            # Try swapping each item with every other
            if not changed:
                for rem in list(chosen):
                    if check_time():
                        break
                    s_without = s - weights[rem]
                    for add in range(n):
                        if add in chosen:
                            continue
                        new_s = s_without + weights[add]
                        if new_s < L and new_s > best_sum:
                            best_sum = new_s
                            new_chosen = chosen.copy()
                            new_chosen.discard(rem)
                            new_chosen.add(add)
                            best_indices = list(new_chosen)
                            chosen = new_chosen
                            s = new_s
                            changed = True

            if not changed:
                break

    # Final validation
    if best_indices is None or not validate(best_indices)[0]:
        for i in range(n):
            if weights[i] < L:
                best_indices = [i]
                best_sum = weights[i]
                break
        if best_indices is None:
            best_indices = [0]

    return best_indices
