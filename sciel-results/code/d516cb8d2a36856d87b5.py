import numpy as np
import time


class Optimizer:
    """Multi-objective optimizer for DTLZ1 using a deterministic nested lattice grid
    on the 2D Pareto simplex for maximum hypervolume coverage."""

    def __init__(self, budget, dim, n_obj):
        self.budget = budget
        self.dim = dim
        self.n_obj = n_obj
        self.start_time = time.time()
        self.deadline = 290.0  # Safety margin before 300s kill

    def _elapsed(self):
        return time.time() - self.start_time

    def __call__(self, problem, bounds):
        used = 0
        points = []
        objectives = []

        # DTLZ1 Pareto front:
        #   x[2:] = 0.5
        #   f1 = 0.5 * x1
        #   f2 = 0.5 * (1 - x1) * x2
        #   f3 = 0.5 * (1 - x2)
        # Parameterized by (x1, x2) in [0,1]^2.
        # The Pareto front lies on the simplex f1 + f2 + f3 = 0.5 with fi >= 0.

        # Strategy: Use a nested lattice grid to discretize the 2D Pareto simplex.
        # We generate points on a triangular lattice that gives uniform coverage
        # of the simplex {f1, f2, f3 >= 0, f1 + f2 + f3 = 0.5}.
        #
        # A nested lattice of order n has n(n+1)/2 points. We want ~200 points.
        # n=19: 19*20/2 = 190 points
        # n=20: 20*21/2 = 210 points
        # We'll use n=19 (190 points) and add 10 more points to reach 200.
        #
        # Actually, let's use a different approach: generate a uniform grid on the
        # (u, v) parameterization where:
        #   f1 = 0.5 * u
        #   f2 = 0.5 * (1 - u) * v
        #   f3 = 0.5 * (1 - v)
        # with u, v in [0, 1].
        #
        # For maximum hypervolume, we want points spread across the entire simplex.
        # A nested lattice on the simplex can be generated by:
        #   For i = 0..n, j = 0..n-i:
        #     f1 = 0.5 * i/n
        #     f2 = 0.5 * j/n
        #     f3 = 0.5 * (n - i - j)/n
        #   Then map back to (x1, x2):
        #     x1 = f1 / 0.5 = i/n
        #     x2 = f2 / (0.5 * (1 - x1)) = j / (n - i)  if i < n, else 0
        #
        # Let's generate a nested lattice with n=19 giving 190 points,
        # then add 10 additional points to reach 200.

        n = 19
        lattice_points = []
        for i in range(n + 1):
            for j in range(n - i + 1):
                # f1 = 0.5*i/n, f2 = 0.5*j/n, f3 = 0.5*(n-i-j)/n
                x1 = i / n
                if i < n:
                    x2 = j / (n - i)
                else:
                    x2 = 0.0  # When i=n, x1=1, f2=0, x2 is irrelevant
                lattice_points.append((x1, x2))

        # We have n*(n+1)/2 = 19*20/2 = 190 points
        # Add 10 more points to reach 200. Use a slightly different lattice
        # or add points from a finer grid.
        # Let's add points from a nested lattice with offset to fill gaps.
        # Use n=19 but with half-integer offsets for the extra points.
        extra_points = []
        # Add points at half-integer positions that weren't covered
        for i in range(n + 1):
            for j in range(n - i + 1):
                x1 = (i + 0.5) / (n + 1)
                if x1 < 1.0:
                    x2 = (j + 0.5) / (n - i)
                    extra_points.append((x1, x2))
            if len(extra_points) >= 10:
                break
            if len(extra_points) >= 10:
                break

        # Take first 10 extra points
        extra_points = extra_points[:10]
        all_points = lattice_points + extra_points

        # Shuffle deterministically to avoid any ordering bias
        rng = np.random.RandomState(42)
        indices = rng.permutation(len(all_points))
        all_points = [all_points[i] for i in indices]

        # Take exactly self.budget points
        all_points = all_points[:self.budget]

        for x1, x2 in all_points:
            if used >= self.budget or self._elapsed() > self.deadline:
                break

            x1 = float(np.clip(x1, 0.0, 1.0))
            x2 = float(np.clip(x2, 0.0, 1.0))

            x = np.full(self.dim, 0.5)
            x[0] = x1
            x[1] = x2

            f = problem(x)
            points.append(x.copy())
            objectives.append(np.array(f, dtype=float))
            used += 1

        return points
