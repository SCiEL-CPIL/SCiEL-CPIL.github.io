import numpy as np

DIMENSIONS = [4, 4, 8]

def construct():
    n, m, p = DIMENSIONS
    # Rank 98 decomposition
    rank = 98
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Strassen 2x2x2 factors
    U222 = np.zeros((4, 7))
    V222 = np.zeros((4, 7))
    W222 = np.zeros((4, 7))
    
    # M1 = (A11+A22)(B11+B22)
    U222[0, 0] = 1; U222[1, 0] = 1; U222[2, 0] = 1; U222[3, 0] = 1
    V222[0, 0] = 1; V222[1, 0] = 1; V222[2, 0] = 1; V222[3, 0] = 1
    W222[0, 0] = 1; W222[1, 0] = 1; W222[2, 0] = 1; W222[3, 0] = 1
    
    # M2 = (A21+A22)B11
    U222[0, 1] = 0; U222[1, 1] = 0; U222[2, 1] = 1; U222[3, 1] = 1
    V222[0, 1] = 1; V222[1, 1] = 1; V222[2, 1] = 0; V222[3, 1] = 0
    W222[0, 1] = 0; W222[1, 1] = 0; W222[2, 1] = 1; W222[3, 1] = 1
    
    # M3 = A11(B12-B22)
    U222[0, 2] = 1; U222[1, 2] = 1; U222[2, 2] = 0; U222[3, 2] = 0
    V222[0, 2] = 0; V222[1, 2] = 0; V222[2, 2] = -1; V222[3, 2] = 1
    W222[0, 2] = 0; W222[1, 2] = 1; W222[2, 2] = 0; W222[3, 2] = 1
    
    # M4 = A22(B21-B11)
    U222[0, 3] = 0; U222[1, 3] = 0; U222[2, 3] = 1; U222[3, 3] = 1
    V222[0, 3] = -1; V222[1, 3] = 1; V222[2, 3] = 0; V222[3, 3] = 0
    W222[0, 3] = 1; W222[1, 3] = 0; W222[2, 3] = 1; W222[3, 3] = 0
    
    # M5 = (A11+A12)B22
    U222[0, 4] = 1; U222[1, 4] = 1; U222[2, 4] = 1; U222[3, 4] = 1
    V222[0, 4] = 0; V222[1, 4] = 0; V222[2, 4] = 1; V222[3, 4] = 1
    W222[0, 4] = -1; W222[1, 4] = 0; W222[2, 4] = 0; W222[3, 4] = 1
    
    # M6 = (A21-A11)(B11+B12)
    U222[0, 5] = -1; U222[1, 5] = -1; U222[2, 5] = 1; U222[3, 5] = 1
    V222[0, 5] = 1; V222[1, 5] = 1; V222[2, 5] = 1; V222[3, 5] = 1
    W222[0, 5] = 0; W222[1, 5] = 0; W222[2, 5] = 0; W222[3, 5] = 1
    
    # M7 = (A12-A22)(B21+B22)
    U222[0, 6] = 0; U222[1, 6] = 1; U222[2, 6] = -1; U222[3, 6] = 1
    V222[0, 6] = 0; V222[1, 6] = 0; V222[2, 6] = 1; V222[3, 6] = 1
    W222[0, 6] = 1; W222[1, 6] = 0; W222[2, 6] = 1; W222[3, 6] = 0
    
    strassen_terms_444 = [
        {
            'X': {(0,0): 1, (1,1): 1},
            'Y': {(0,0): 1, (1,1): 1},
            'Z': {(0,0): 1, (1,1): 1}
        },
        {
            'X': {(1,0): 1, (1,1): 1},
            'Y': {(0,0): 1},
            'Z': {(1,0): 1, (1,1): -1}
        },
        {
            'X': {(0,0): 1},
            'Y': {(0,1): 1, (1,1): -1},
            'Z': {(0,1): 1, (1,1): 1}
        },
        {
            'X': {(1,1): 1},
            'Y': {(1,0): 1, (0,0): -1},
            'Z': {(0,0): 1, (1,0): 1}
        },
        {
            'X': {(0,0): 1, (0,1): 1},
            'Y': {(1,1): 1},
            'Z': {(0,0): -1, (0,1): 1}
        },
        {
            'X': {(1,0): 1, (0,0): -1},
            'Y': {(0,0): 1, (0,1): 1},
            'Z': {(1,1): 1}
        },
        {
            'X': {(0,1): 1, (1,1): -1},
            'Y': {(1,0): 1, (1,1): 1},
            'Z': {(0,0): 1}
        }
    ]
    
    def add_decomposition(offset, b_offset):
        for k in range(7):
            term = strassen_terms_444[k]
            for s in range(7):
                col = offset + k * 7 + s
                
                for (bi, bj), coeff_x in term['X'].items():
                    for li in range(2):
                        for lj in range(2):
                            i = bi * 2 + li
                            j = bj * 2 + lj
                            U[i * 4 + j][col] += coeff_x * U222[li * 2 + lj, s]
                            
                for (bi, bj), coeff_y in term['Y'].items():
                    for li in range(2):
                        for lj in range(2):
                            j = bi * 2 + li
                            k_local = bj * 2 + lj
                            k_global = k_local + b_offset * 4
                            V[j * 8 + k_global][col] += coeff_y * V222[li * 2 + lj, s]
                            
                for (bi, bj), coeff_z in term['Z'].items():
                    for li in range(2):
                        for lj in range(2):
                            k = bi * 2 + li
                            i = bj * 2 + lj
                            W[k * 4 + i][col] += coeff_z * W222[li * 2 + lj, s]
                            
    add_decomposition(0, 0)
    add_decomposition(49, 1)
    
    return {"U": U, "V": V, "W": W}
