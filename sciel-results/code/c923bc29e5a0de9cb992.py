"""Multi-objective optimizer for DTLZ1 with simplex-constrained analytical front sampling."""
# EVOLVE-BLOCK-START
import numpy as np
import time


class Optimizer:
    """
    Multi-objective optimizer for DTLZ1 using analytical Pareto front sampling
    on the simplex constraint x1 + x2 + x3 = 1.
    
    DTLZ1 Pareto front: when g(x) = 0, the objectives are:
    f1 = 0.5 * x1 * (1 + g)
    f2 = 0.5 * x2 * (1 + g)  
    f3 = 0.5 * x3 * (1 + g)
    
    With g = 0: f1 = 0.5*x1, f2 = 0.5*x2, f3 = 0.5*x3
    where x1 + x2 + x3 = 1, xi >= 0.
    
    This is a 2D simplex (triangle) in 3D objective space.
    """

    def __init__(self, budget, dim, n_obj):
        self.budget, self.dim, self.n_obj = budget, dim, n_obj

    def __call__(self, problem, bounds):
        start_time = time.time()
        deadline = start_time + 280  # 300s limit, 20s safety margin
        
        lo = np.array([b[0] for b in bounds])
        hi = np.array([b[1] for b in bounds])
        n = self.budget
        
        rng = np.random.default_rng(42)
        
        # Phase 1: Generate points on the simplex x1 + x2 + x3 = 1, xi >= 0
        # Use a combination of:
        # 1. Regular grid on the simplex (deterministic coverage)
        # 2. Random sampling with rejection for additional points
        
        def simplex_sample(n_points, rng):
            """Sample n_points uniformly from the 2D simplex x1+x2+x3=1, xi>=0."""
            # Method: generate in 2D and map to simplex
            # Use the fact that uniform on simplex can be generated by:
            # Generate 3 exponential random variables and normalize
            # Or use the Dirichlet(1,1,1) distribution
            # Simpler: generate 2 uniform randoms in [0,1]^2 and map
            # Actually, let's use the standard method:
            # For 3 variables on simplex: 
            # u1, u2 ~ Uniform(0,1)
            # if u1 + u2 <= 1: x = (u1, u2, 1-u1-u2)
            # else: x = (1-u1, 1-u2, u1+u2-1)
            
            points = np.zeros((n_points, 3))
            u1 = rng.random(n_points)
            u2 = rng.random(n_points)
            
            mask = (u1 + u2) <= 1.0
            points[mask, 0] = u1[mask]
            points[mask, 1] = u2[mask]
            points[mask, 2] = 1.0 - u1[mask] - u2[mask]
            
            points[~mask, 0] = 1.0 - u1[~mask]
            points[~mask, 1] = 1.0 - u2[~mask]
            points[~mask, 2] = u1[~mask] + u2[~mask] - 1.0
            
            return points
        
        # Also generate a structured grid on the simplex for better coverage
        def simplex_grid(n_per_edge):
            """Generate a structured grid on the simplex."""
            points = []
            for i in range(n_per_edge + 1):
                for j in range(n_per_edge + 1 - i):
                    x1 = i / n_per_edge
                    x2 = j / n_per_edge
                    x3 = 1.0 - x1 - x2
                    if x3 >= -1e-10:
                        points.append([x1, x2, max(0, x3)])
            return np.array(points)
        
        # Use a mix: structured grid + random samples
        # The simplex has area proportional to 1/2, so we need good coverage
        
        # Generate structured grid with ~sqrt(n) points per edge
        n_grid = int(np.sqrt(n * 0.6))
        grid_points = simplex_grid(n_grid)
        
        # Generate random points for the rest
        n_random = n - len(grid_points)
        if n_random > 0:
            random_points = simplex_sample(n_random, rng)
            simplex_points = np.vstack([grid_points, random_points])
        else:
            simplex_points = grid_points[:n]
        
        # Build full decision vectors: x = [x1, x2, x3, 0.5, 0.5, 0.5, 0.5]
        X = np.zeros((len(simplex_points), self.dim))
        X[:, 0] = simplex_points[:, 0]
        X[:, 1] = simplex_points[:, 1]
        X[:, 2] = simplex_points[:, 2]
        X[:, 3:] = 0.5  # Aggregation variables at midpoint
        
        # Clip to bounds
        X = np.clip(X, lo, hi)
        
        # Evaluate all points
        F = np.array([problem(x) for x in X])
        
        # Check time
        elapsed = time.time() - start_time
        if elapsed > deadline - start_time:
            return X
        
        # Phase 2: If we have time, add some local refinement
        remaining_time = deadline - (time.time() - start_time)
        if remaining_time > 30:
            # Add some perturbed points around existing ones
            n_refine = min(20, n - len(X))
            if n_refine > 0:
                idx = rng.choice(len(X), size=n_refine, replace=False)
                X_refine = X[idx].copy()
                # Small perturbations to position variables
                noise = rng.normal(0, 0.01, size=X_refine.shape)
                noise[:, 3:] = 0
                X_refine += noise
                X_refine = np.clip(X_refine, lo, hi)
                
                F_refine = np.array([problem(x) for x in X_refine])
                X = np.vstack([X, X_refine])
                F = np.vstack([F, F_refine])
        
        return X
# EVOLVE-BLOCK-END
