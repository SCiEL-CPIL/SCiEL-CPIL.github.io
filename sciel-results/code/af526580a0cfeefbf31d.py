import time
import random
import math
import numpy as np

_DEADLINE = 0.0
_BEST = None

def _valid(rows, k):
    seen = set()
    for r in rows:
        if r[0] != 0 or len(r) != k + 1:
            return False
        for i in range(len(r)):
            for j in range(i + 1, len(r)):
                d = r[j] - r[i]
                if d <= 0 or d in seen:
                    return False
                seen.add(d)
    return True

def _scope(rows):
    return max(a for r in rows for a in r[1:])

def _row_to_bitset(row):
    mask = 0
    for i in range(len(row)):
        for j in range(i + 1, len(row)):
            d = row[j] - r[i]
            mask |= (1 << d)
    return mask

def _fast_greedy(k, n_rows, rng, spread=False):
    used = 0
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        while len(row) < k + 1:
            x += 1
            new = 0
            for a in row:
                new |= (1 << (x - a))
            if (used & new) == 0:
                row.append(x)
                used |= new
                if spread:
                    x += max(1, (k - len(row) + 1) * 2 - 2)
        rows.append(row)
    return rows

def _backtrack_row(k, used_mask, rng, max_scope=150):
    """
    Use randomized backtracking to find a valid row.
    This is more robust than pure greedy when the space is tight.
    """
    def backtrack(row, x, row_mask):
        if len(row) == k + 1:
            return row
        
        # Heuristic: try values closer to the end first? Or start?
        # For minimizing scope, we generally want small values, but sometimes
        # we need to jump to avoid future conflicts.
        # Let's try a range of candidates.
        
        # Determine search range. We want to keep scope small, so we bias towards smaller x.
        # But if we are stuck, we might need to go higher.
        # Let's try candidates from x+1 to max_scope.
        
        # To speed up, we can pre-filter candidates.
        # A candidate t is valid if (new_diffs & (used_mask | row_mask)) == 0
        
        # Randomize the order slightly to escape local minima?
        # No, backtracking is deterministic if order is fixed.
        # Let's try increasing order, but if we fail, the caller can retry with different random seeds or higher max_scope.
        
        # Actually, pure backtracking can be slow.
        # Let's use a "greedy with backtracking" approach:
        # 1. Pick the smallest valid t.
        # 2. If no valid t, return None.
        # 3. If we get stuck later, we need to backtrack.
        
        # For efficiency in a tight loop, let's just do a simple recursive search with a depth limit or just return the first solution found in increasing order.
        # Since k is small (5), the search tree is manageable if we prune well.
        
        # Optimization: Pre-compute potential conflicts?
        # For each t, new_diffs = {t - a for a in row}
        
        # Let's iterate t from x+1 upwards.
        for t in range(x + 1, max_scope + 1):
            new_diffs = 0
            conflict = False
            for a in row:
                d = t - a
                if d <= 0:
                    continue
                if (used_mask >> d) & 1:
                    conflict = True
                    break
                if (row_mask >> d) & 1:
                    conflict = True
                    break
                new_diffs |= (1 << d)
            
            if not conflict:
                # Try this path
                res = backtrack(row + [t], t, row_mask | new_diffs)
                if res is not None:
                    return res
        
        return None

    return backtrack([0], 0, 0)

def _sa_optimize(rows, k, deadline, rng):
    """
    Simulated Annealing with bitset-based validity checks.
    Moves:
    1. Replace a row with a new one generated by backtracking (expensive, use sparingly).
    2. Shift a row (cheap check).
    3. Swap elements within a row? (Complex, skip for now).
    4. Perturb a row: change one element and repair.
    
    We will focus on "Replace Row" and "Shift Row".
    To make "Replace Row" fast, we pre-compute masks for all rows except the one being replaced.
    """
    
    n_rows = len(rows)
    current_rows = [list(r) for r in rows]
    current_scope = _scope(current_rows)
    
    # Pre-compute masks for all rows
    masks = [_row_to_bitset(r) for r in current_rows]
    
    best_rows = [list(r) for r in current_rows]
    best_scope = current_scope
    
    T = 10.0
    cooling = 0.9999
    min_T = 0.01
    
    start_time = time.time()
    
    while time.time() < deadline - 2:
        # Pick a random row to modify
        i = rng.randint(0, n_rows - 1)
        
        move_type = rng.random()
        
        if move_type < 0.7:
            # Shift row i
            # Try shifting all elements except the first (which is 0)
            # Or shift a subset? Shifting all is simpler.
            shift = rng.randint(-5, 5)
            if shift == 0:
                continue
            
            new_row = [0] + [x + shift for x in current_rows[i][1:]]
            
            # Check basic validity
            if new_row[1] <= 0 or not all(new_row[j] < new_row[j+1] for j in range(len(new_row)-1)):
                continue
            
            new_mask = _row_to_bitset(new_row)
            
            # Check conflicts with other rows
            # used_mask = XOR of all masks except i
            # But we can just check (new_mask & (total_mask ^ masks[i]))
            # Wait, total_mask is not maintained. Let's maintain total_mask.
            
            # Let's maintain total_mask in the outer scope? No, it changes.
            # Let's compute the mask of all OTHER rows.
            # For efficiency, we can maintain a global mask and subtract?
            # Bitsets don't support subtraction easily if bits overlap.
            # But since all differences are distinct globally, the masks are disjoint!
            # So total_mask = OR of all masks.
            # Mask of others = total_mask ^ masks[i] (since disjoint).
            
            # Let's maintain total_mask.
            # But we are inside the loop. Let's just compute it or maintain it.
            # Maintaining total_mask is O(1) update if we know old and new mask.
            
            # Let's assume we have total_mask.
            # For now, let's just check against all other rows. O(n_rows) checks.
            conflict = False
            for j in range(n_rows):
                if j == i:
                    continue
                if new_mask & masks[j]:
                    conflict = True
                    break
            
            if conflict:
                continue
            
            # Calculate new scope
            new_scope = max(current_scope, new_row[-1])
            # Actually, if we shift down, scope might decrease.
            # But other rows might have larger scope.
            # new_scope = max(max(x for r in current_rows for idx, x in enumerate(r) if not (r is current_rows[i] and idx > 0)), new_row[-1])
            # Simpler: just compute _scope(current_rows) after replacement?
            # That's O(n_rows * k). Acceptable for n=7, k=5.
            
            # Let's do the swap
            old_row = current_rows[i]
            old_mask = masks[i]
            
            current_rows[i] = new_row
            masks[i] = new_mask
            
            actual_new_scope = _scope(current_rows)
            
            delta = actual_new_scope - current_scope
            
            if delta < 0 or rng.random() < math.exp(-delta / T):
                current_scope = actual_new_scope
                if current_scope < best_scope:
                    best_scope = current_scope
                    best_rows = [list(r) for r in current_rows]
            else:
                # Revert
                current_rows[i] = old_row
                masks[i] = old_mask
        
        else:
            # Replace row i with a new one from backtracking
            # This is expensive.
            used_mask = 0
            for j in range(n_rows):
                if j != i:
                    used_mask |= masks[j]
            
            # Try to find a row with scope <= current_scope (or slightly larger)
            # Backtracking finds the "first" valid row in increasing order of elements.
            # This tends to minimize the row's scope given the constraints.
            
            # Limit max_scope to current_scope + some buffer?
            # If we want to improve, we should look for rows with scope <= best_scope.
            # But backtracking doesn't take a target scope, it finds *a* valid row.
            # The first one found is usually the one with smallest elements.
            
            new_row = _backtrack_row(k, used_mask, rng, max_scope=current_scope + 10)
            
            if new_row:
                new_mask = _row_to_bitset(new_row)
                
                # It should be valid by construction
                # Check if it improves scope
                old_row = current_rows[i]
                old_mask = masks[i]
                
                current_rows[i] = new_row
                masks[i] = new_mask
                
                actual_new_scope = _scope(current_rows)
                delta = actual_new_scope - current_scope
                
                if delta < 0 or rng.random() < math.exp(-delta / T):
                    current_scope = actual_new_scope
                    if current_scope < best_scope:
                        best_scope = current_scope
                        best_rows = [list(r) for r in current_rows]
                else:
                    current_rows[i] = old_row
                    masks[i] = old_mask
        
        T *= cooling
        if T < min_T:
            T = min_T
    
    return best_rows

def construct(n_rows, k):
    global _BEST, _DEADLINE
    _BEST = None
    _DEADLINE = time.time() + 140.0  # Safety margin

    def consider(rows):
        global _BEST
        if not _valid(rows, k):
            return
        s = _scope(rows)
        if _BEST is None or s < _BEST[0]:
            _BEST = (s, [list(r) for r in rows])

    rng = random.Random(42)

    # 1. Initial greedy
    greedy_rows = _fast_greedy(k, n_rows, rng, spread=False)
    consider(greedy_rows)
    
    # 2. Try to improve with backtracking-based initialization
    # Sometimes greedy gets stuck in a bad configuration.
    # Let's try to build rows one by one using backtracking.
    for _ in range(5):
        used = 0
        rows = []
        success = True
        for _ in range(n_rows):
            row = _backtrack_row(k, used, rng, max_scope=150)
            if row is None:
                success = False
                break
            rows.append(row)
            used |= _row_to_bitset(row)
        
        if success:
            consider(rows)
        
        if time.time() > _DEADLINE - 20:
            break

    # 3. SA Optimization on the best found so far
    if _BEST is not None and time.time() < _DEADLINE - 10:
        best_rows = [list(r) for r in _BEST[1]]
        sa_rows = _sa_optimize(best_rows, k, _DEADLINE - 2, rng)
        consider(sa_rows)

    # 4. Final Polish
    if _BEST is not None and time.time() < _DEADLINE - 1:
        best_rows = [list(r) for r in _BEST[1]]
        # Try small shifts
        for _ in range(500):
            if time.time() > _DEADLINE - 1:
                break
            i = rng.randint(0, n_rows - 1)
            shift = rng.randint(-2, 2)
            if shift == 0:
                continue
            new_row = [0] + [x + shift for x in best_rows[i][1:]]
            if new_row[1] <= 0 or not all(new_row[j] < new_row[j+1] for j in range(len(new_row)-1)):
                continue
            
            # Quick validity check
            new_mask = _row_to_bitset(new_row)
            valid = True
            for j in range(n_rows):
                if j == i:
                    continue
                if new_mask & _row_to_bitset(best_rows[j]):
                    valid = False
                    break
            
            if valid:
                old_row = best_rows[i]
                best_rows[i] = new_row
                if _valid(best_rows, k):
                    s = _scope(best_rows)
                    if s < _BEST[0]:
                        _BEST = (s, [list(r) for r in best_rows])
                else:
                    best_rows[i] = old_row

    if _BEST is not None:
        return _BEST[1]
    return greedy_rows
