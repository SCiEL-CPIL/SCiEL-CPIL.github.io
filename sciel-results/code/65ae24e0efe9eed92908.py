def construct():
    n, m, p = DIMENSIONS  # 2, 4, 8
    rank = 56
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Indices for A blocks in U (8x1)
    # A11: 0,1 ; A12: 2,3 ; A21: 4,5 ; A22: 6,7
    # Indices for B blocks in V (32x1)
    # B11: 0-3, 8-11
    # B12: 4-7, 12-15
    # B21: 16-19, 24-27
    # B22: 20-23, 28-31
    # Indices for C blocks in W (16x1)
    # C11: 0,2,4,6
    # C12: 8,10,12,14
    # C21: 1,3,5,7
    # C22: 9,11,13,15

    # Define Strassen steps
    # Each step: (X_coeffs, Y_coeffs, W_targets)
    # X_coeffs: list of 2 tuples, each tuple is dict {A_idx: coeff}
    # Y_coeffs: list of 4 tuples (for c=0..3), each tuple is dict {B_idx: coeff}
    # Actually, Y is 2x4. Y[r][c].
    # W_targets: list of 4 tuples (for c=0..3), each tuple is dict {W_idx: coeff}
    
    steps = []
    
    # M1 = (A22 - A11)(B11 + B22)
    # X1 = A22 - A11
    # Y1 = B11 + B22
    # C11 += Z1, C22 += Z1
    steps.append({
        'X': [
            {6: 1, 0: -1},  # X1[0] = A12? No. A22[0] is idx 6. A11[0] is idx 0.
            {7: 1, 1: -1}   # X1[1] = A22[1] (7) - A11[1] (1)
        ],
        'Y': [
            {0: 1, 20: 1},  # Y1[0][0] = B11[0][0] (0) + B22[0][0] (20)
            {1: 1, 21: 1},  # Y1[0][1]
            {2: 1, 22: 1},  # Y1[0][2]
            {3: 1, 23: 1},  # Y1[0][3]
            {8: 1, 28: 1},  # Y1[1][0]
            {9: 1, 29: 1},  # Y1[1][1]
            {10: 1, 30: 1}, # Y1[1][2]
            {11: 1, 31: 1}  # Y1[1][3]
        ],
        'W': [
            {0: 1, 9: 1},   # W[0] (C11[0]), W[9] (C22[0])
            {2: 1, 11: 1},  # W[2] (C11[1]), W[11] (C22[1])
            {4: 1, 13: 1},  # W[4] (C11[2]), W[13] (C22[2])
            {6: 1, 15: 1}   # W[6] (C11[3]), W[15] (C22[3])
        ]
    })
    
    # M2 = (A11 + A12) B22
    # X2 = A11 + A12
    # Y2 = B22
    # C21 += Z2, C22 -= Z2
    steps.append({
        'X': [
            {0: 1, 2: 1},   # X2[0] = A11[0] + A12[0]
            {1: 1, 3: 1}    # X2[1] = A11[1] + A12[1]
        ],
        'Y': [
            {20: 1}, {21: 1}, {22: 1}, {23: 1}, # Y2[0][0..3] = B22[0][0..3]
            {28: 1}, {29: 1}, {30: 1}, {31: 1}  # Y2[1][0..3] = B22[1][0..3]
        ],
        'W': [
            {1: 1, 9: -1},  # W[1] (C21[0]), W[9] (C22[0])
            {3: 1, 11: -1},
            {5: 1, 13: -1},
            {7: 1, 15: -1}
        ]
    })
    
    # M3 = A11 (B22 - B12)
    # X3 = A11
    # Y3 = B22 - B12
    # C12 += Z3, C22 += Z3
    steps.append({
        'X': [
            {0: 1},         # X3[0] = A11[0]
            {1: 1}          # X3[1] = A11[1]
        ],
        'Y': [
            {20: 1, 4: -1}, {21: 1, 5: -1}, {22: 1, 6: -1}, {23: 1, 7: -1}, # Y3[0][0..3]
            {28: 1, 12: -1}, {29: 1, 13: -1}, {30: 1, 14: -1}, {31: 1, 15: -1} # Y3[1][0..3]
        ],
        'W': [
            {8: 1, 9: 1},   # W[8] (C12[0]), W[9] (C22[0])
            {10: 1, 11: 1},
            {12: 1, 13: 1},
            {14: 1, 15: 1}
        ]
    })
    
    # M4 = A22 (B11 - B21)
    # X4 = A22
    # Y4 = B11 - B21
    # C11 += Z4, C21 += Z4
    steps.append({
        'X': [
            {6: 1},         # X4[0] = A22[0]
            {7: 1}          # X4[1] = A22[1]
        ],
        'Y': [
            {0: 1, 16: -1}, {1: 1, 17: -1}, {2: 1, 18: -1}, {3: 1, 19: -1}, # Y4[0][0..3]
            {8: 1, 24: -1}, {9: 1, 25: -1}, {10: 1, 26: -1}, {11: 1, 27: -1} # Y4[1][0..3]
        ],
        'W': [
            {0: 1, 1: 1},   # W[0] (C11[0]), W[1] (C21[0])
            {2: 1, 3: 1},
            {4: 1, 5: 1},
            {6: 1, 7: 1}
        ]
    })
    
    # M5 = (A11 + A22) B11
    # X5 = A11 + A22
    # Y5 = B11
    # C11 -= Z5, C12 += Z5
    steps.append({
        'X': [
            {0: 1, 6: 1},   # X5[0] = A11[0] + A22[0]
            {1: 1, 7: 1}    # X5[1] = A11[1] + A22[1]
        ],
        'Y': [
            {0: 1}, {1: 1}, {2: 1}, {3: 1}, # Y5[0][0..3]
            {8: 1}, {9: 1}, {10: 1}, {11: 1} # Y5[1][0..3]
        ],
        'W': [
            {0: -1, 8: 1},  # W[0] (C11[0]), W[8] (C12[0])
            {2: -1, 10: 1},
            {4: -1, 12: 1},
            {6: -1, 14: 1}
        ]
    })
    
    # M6 = (A21 - A11) (B12 + B22)
    # X6 = A21 - A11
    # Y6 = B12 + B22
    # C22 += Z6
    steps.append({
        'X': [
            {4: 1, 0: -1},  # X6[0] = A21[0] - A11[0]
            {5: 1, 1: -1}   # X6[1] = A21[1] - A11[1]
        ],
        'Y': [
            {4: 1, 20: 1}, {5: 1, 21: 1}, {6: 1, 22: 1}, {7: 1, 23: 1}, # Y6[0][0..3]
            {12: 1, 28: 1}, {13: 1, 29: 1}, {14: 1, 30: 1}, {15: 1, 31: 1} # Y6[1][0..3]
        ],
        'W': [
            {9: 1},         # W[9] (C22[0])
            {11: 1},        # W[11] (C22[1])
            {13: 1},        # W[13] (C22[2])
            {15: 1}         # W[15] (C22[3])
        ]
    })
    
    # M7 = (A12 - A22) (B21 + B11)
    # X7 = A12 - A22
    # Y7 = B21 + B11
    # C11 += Z7
    steps.append({
        'X': [
            {2: 1, 6: -1},  # X7[0] = A12[0] - A22[0]
            {3: 1, 7: -1}   # X7[1] = A12[1] - A22[1]
        ],
        'Y': [
            {16: 1, 0: 1}, {17: 1, 1: 1}, {18: 1, 2: 1}, {19: 1, 3: 1}, # Y7[0][0..3]
            {24: 1, 8: 1}, {25: 1, 9: 1}, {26: 1, 10: 1}, {27: 1, 11: 1} # Y7[1][0..3]
        ],
        'W': [
            {0: 1},         # W[0] (C11[0])
            {2: 1},         # W[2] (C11[1])
            {4: 1},         # W[4] (C11[2])
            {6: 1}          # W[6] (C11[3])
        ]
    })
    
    col = 0
    for step in steps:
        X = step['X']
        Y = step['Y']
        W_targets = step['W']
        
        for r in range(2):
            for c in range(4):
                # U part
                for a_idx, coeff in X[r].items():
                    U[a_idx][col] = coeff
                # V part
                for b_idx, coeff in Y[r*4 + c].items():
                    V[b_idx][col] = coeff
                # W part
                for w_idx, coeff in W_targets[c].items():
                    W[w_idx][col] = coeff
                
                col += 1
                
    return {"U": U, "V": V, "W": W}
