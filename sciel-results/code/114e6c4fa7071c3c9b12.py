import numpy as np
import time
from itertools import combinations

def construct():
    N = 17
    MIN_DIST = 6
    start_time = time.time()
    time_limit = 55

    # Precompute masks for blocking (all masks of weight < MIN_DIST)
    masks_by_dist = [[] for _ in range(MIN_DIST)]
    for d in range(MIN_DIST):
        for combo in combinations(range(N), d):
            mask = 0
            for i in combo:
                mask |= (1 << i)
            masks_by_dist[d].append(mask)
    
    all_masks = []
    for d in range(MIN_DIST):
        all_masks.extend(masks_by_dist[d])

    # Helper to build the [17,8,6] code from the [18,9,6] extended QR code
    # The [18,9,6] code is the extended quadratic residue code over GF(17).
    # We construct it via the generator polynomial approach or by using a known basis.
    # Since deriving the QR code generator polynomial is complex, we use a known
    # parity-check or generator matrix structure.
    
    # Alternative: Use the fact that the [17,8,6] code is a subcode of the [17,9,5] QR code?
    # No, the [17,8,6] code is the *shortened* [18,9,6] code.
    
    # Let's try to construct the [18,9,6] code first.
    # The extended QR code of length 18 is the code generated by the circulant matrix
    # with first row corresponding to the generator polynomial of the [17,8,6] code?
    # Actually, the [17,8,6] code is not cyclic because 17 is prime, but the [18,9,6] code
    # is not cyclic either (18 is not prime).
    
    # However, the [17,8,6] code *is* the code obtained by deleting one coordinate from
    # the [18,9,6] code. The [18,9,6] code is the extended QR code.
    
    # A simpler approach: The [17,8,6] code is a BCH code?
    # BCH code with n=17, d=6.
    # The roots are in GF(2^m). Since 17 = 2^4 + 1, the multiplicative order of 2 mod 17 is 8.
    # So we work in GF(2^8).
    # The primitive narrow-sense BCH code with designed distance 6 has roots 1, 2, 4, 8, 16, 32...
    # Wait, the roots are alpha^1, alpha^2, alpha^3, alpha^4, alpha^5 where alpha is a primitive
    # 17th root of unity in GF(2^8).
    # The degree of the generator polynomial is at least 5.
    # Actually, for n=17, the cyclotomic cosets mod 17 are:
    # C1 = {1, 2, 4, 8, 16, 15, 13, 9} (size 8)
    # C3 = {3, 6, 12, 7, 14, 11, 5, 10} (size 8)
    # C0 = {0} (size 1)
    # So the generator polynomial for roots alpha^1, alpha^2, ..., alpha^5 includes C1 and C3?
    # No, alpha^3 is in C3. So roots 1,2,3,4,5 involve C1 and C3.
    # The degree would be 8+8=16, so k=1. That's too small.
    
    # The [17,8,6] code is NOT a narrow-sense BCH code.
    # It is the quadratic residue code.
    
    # Let's use a known generator matrix for the [17,8,6] code.
    # One such matrix (from standard tables) is:
    # G = [I_8 | P]
    # where P is an 8x9 matrix.
    
    # Actually, let's use the following property:
    # The [17,8,6] code is the dual of the [17,9,5] code? No, 8+9=17.
    # The dual of the [17,8,6] code is a [17,9,5] code.
    
    # Let's try to find the generator matrix by solving a system of equations?
    # Too slow.
    
    # Instead, let's use a **randomized search** for a [17,8,6] linear code, but with a
    # better heuristic. We know such a code exists.
    # We can try to find it by starting with a random 8x17 matrix and checking the min distance.
    # If we find one, we use it as the base.
    
    # Step 1: Find a [17,8,6] linear code
    k = 8
    linear_code = None

    for attempt in range(500):
        if time.time() - start_time > 3.0:
            break
        G = np.random.randint(0, 2, size=(k, N))
        
        G_ints = []
        for i in range(k):
            val = 0
            for j in range(N):
                if G[i, j] == 1:
                    val |= (1 << j)
            G_ints.append(val)
        
        codewords = [0]
        for i in range(k):
            new_codewords = [c ^ G_ints[i] for c in codewords]
            codewords.extend(new_codewords)
        
        min_d = N + 1
        for c in codewords:
            if c == 0:
                continue
            w = bin(c).count('1')
            if w < min_d:
                min_d = w
                if min_d < MIN_DIST:
                    break
        
        if min_d >= MIN_DIST:
            linear_code = codewords
            break

    # Step 2: Fallback to greedy if no linear code found
    if linear_code is None:
        blocked = bytearray(1 << N)
        code = []
        
        def add_word(w):
            if blocked[w]:
                return
            code.append(w)
            for mask in all_masks:
                blocked[w ^ mask] = 1
        
        add_word(0)
        for w in range(1, 1 << N):
            if time.time() - start_time > time_limit:
                break
            if not blocked[w]:
                add_word(w)
        return code

    # Step 3: Expand the linear code greedily
    blocked = bytearray(1 << N)
    code = list(linear_code)
    
    for w in code:
        for mask in all_masks:
            blocked[w ^ mask] = 1

    for w in range(1 << N):
        if time.time() - start_time > time_limit:
            break
        if not blocked[w]:
            code.append(w)
            for mask in all_masks:
                blocked[w ^ mask] = 1

    # Step 4: Local Search to improve the code size
    if time.time() - start_time < time_limit - 10:
        improved = True
        while improved and time.time() - start_time < time_limit - 5:
            improved = False
            for i in range(len(code)):
                if time.time() - start_time > time_limit - 5:
                    break
                removed = code[i]
                code.remove(removed)
                
                for mask in all_masks:
                    blocked[removed ^ mask] = 0
                
                old_len = len(code)
                for w in range(1 << N):
                    if time.time() - start_time > time_limit - 5:
                        break
                    if not blocked[w]:
                        code.append(w)
                        for mask in all_masks:
                            blocked[w ^ mask] = 1
                
                if len(code) > old_len:
                    improved = True
                else:
                    # Undo
                    while len(code) > old_len:
                        w = code.pop()
                        for mask in all_masks:
                            blocked[w ^ mask] = 0
                    for mask in all_masks:
                        blocked[removed ^ mask] = 1
                    code.append(removed)

    return code
