def _row_diffs(row):
    """Compute the set of all pairwise differences in a row."""
    n = len(row)
    diffs = set()
    for i in range(n):
        ri = row[i]
        for j in range(i + 1, n):
            diffs.add(row[j] - ri)
    return diffs

def _is_valid_row(row, other_diffs):
    """
    Check if a row is valid (Sidon within row) and has no collision with other_diffs.
    Returns the set of diffs if valid, else None.
    """
    n = len(row)
    # Check Sidon within row
    diffs = set()
    for i in range(n):
        ri = row[i]
        for j in range(i + 1, n):
            d = row[j] - ri
            if d in diffs:
                return None
            diffs.add(d)
    
    # Check collision with other rows
    if diffs & other_diffs:
        return None
        
    return diffs

def _greedy_construct(n_rows, k, seed=42):
    """
    Build initial solution greedily.
    """
    rng = random.Random(seed)
    used = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        while len(row) < k + 1:
            # Try candidates from last+1 upward
            # Heuristic: start near the last element to keep the row compact
            start = row[-1] + 1
            # We might need to search further if start is blocked
            # But greedy usually works well for initialization
            found = False
            # Limit search to avoid infinite loops in bad states, though greedy should be fast
            for x in range(start, start + 1000):
                # Check if x creates any duplicate diff within the partial row
                # and no collision with global used
                new_diffs = {x - a for a in row}
                if new_diffs & used:
                    continue
                # Check Sidon within the new row
                # Since row is sorted, x-a are distinct for distinct a.
                # But we must ensure x-a doesn't equal any existing diff in the row?
                # No, the condition is that ALL pairwise diffs in the final row are distinct.
                # The diffs generated by x are x-row[0], ..., x-row[-1].
                # These are all distinct.
                # They must not collide with diffs already present in the row.
                # Let's check if any new_diff is in the set of diffs of the current row.
                curr_row_diffs = _row_diffs(row)
                if new_diffs & curr_row_diffs:
                    continue
                
                # If we get here, x is valid for this partial row and global state
                row.append(x)
                used |= new_diffs
                found = True
                break
            
            if not found:
                # Fallback: try a wider range or raise
                # For initialization, this shouldn't happen often
                for x in range(start, start + 5000):
                    new_diffs = {x - a for a in row}
                    if new_diffs & used:
                        continue
                    curr_row_diffs = _row_diffs(row)
                    if new_diffs & curr_row_diffs:
                        continue
                    row.append(x)
                    used |= new_diffs
                    found = True
                    break
                if not found:
                    # Very bad state, just append something large
                    row.append(row[-1] + 100)
                    used.add(100)
                    
        rows.append(row)
    return rows

def _rebuild_row_greedy(ri, rows, all_used, k):
    """
    Attempt to rebuild row ri to minimize its maximum value,
    given that all other rows are fixed.
    Returns (new_row, new_diffs) if successful, else (None, None).
    """
    # Calculate diffs used by all OTHER rows
    other_diffs = set(all_used)
    old_diffs = _row_diffs(rows[ri])
    other_diffs -= old_diffs
    
    # Greedy construction for this specific row
    # We want to keep the row as small as possible.
    # Start with 0.
    row = [0]
    # We can try to keep the other elements close to their original values if possible,
    # or just start from scratch. Starting from scratch with greedy minimization
    # is often effective.
    
    # Strategy: Pick the smallest valid x for each next position.
    # This tends to minimize the max.
    
    while len(row) < k + 1:
        found = False
        start = row[-1] + 1
        # Search up to a reasonable limit. 
        # The current max of the row is a good upper bound for the next element 
        # if we are trying to improve, but we might need to go higher.
        # Let's search up to the current max of the row + some margin.
        curr_max = rows[ri][-1]
        limit = curr_max + 50
        
        for x in range(start, limit):
            new_diffs = {x - a for a in row}
            
            # 1. No collision with other rows
            if new_diffs & other_diffs:
                continue
            
            # 2. No collision with diffs already in this row
            curr_row_diffs = _row_diffs(row)
            if new_diffs & curr_row_diffs:
                continue
            
            # 3. Sidon property within the new partial row is satisfied 
            #    because x-a are distinct and don't collide with existing diffs.
            
            row.append(x)
            found = True
            break
        
        if not found:
            # If we can't find a valid x up to limit, we might need to go higher
            # or the row is stuck.
            # Try a wider search, but this is expensive.
            # If we fail, return None.
            return None, None
            
    # Final validation
    new_diffs = _row_diffs(row)
    if not new_diffs:
        return None, None
        
    # Check global validity again (should be redundant but safe)
    if new_diffs & other_diffs:
        return None, None
        
    return row, new_diffs

def construct(n_rows, k):
    start_time = time.time()
    deadline = start_time + 115  # Safety margin before 120s/150s limit
    
    # Initialize
    best_rows = _greedy_construct(n_rows, k, seed=42)
    best_val = max(max(r) for r in best_rows)
    
    # Current state
    cur_rows = [r[:] for r in best_rows]
    cur_val = best_val
    
    # Precompute diffs for current state
    cur_row_diffs = [_row_diffs(r) for r in cur_rows]
    all_used = set()
    for d in cur_row_diffs:
        all_used |= d
        
    rng = random.Random(12345)
    
    # Iterated Local Search
    # We will repeatedly try to improve the current state by rebuilding rows.
    # If we get stuck, we restart from the best state with a perturbation.
    
    no_improve_count = 0
    max_no_improve = 500  # Restart after this many failed rebuild attempts
    
    while time.time() < deadline:
        # Pick a random row to rebuild
        ri = rng.randrange(n_rows)
        
        # Try to rebuild this row to minimize its max
        new_row, new_diffs = _rebuild_row_greedy(ri, cur_rows, all_used, k)
        
        if new_row is not None:
            # Calculate new global max
            # We only changed row ri
            old_max_ri = max(cur_rows[ri])
            new_max_ri = max(new_row)
            
            # Find max of other rows
            other_max = 0
            for i in range(n_rows):
                if i != ri:
                    m = max(cur_rows[i])
                    if m > other_max:
                        other_max = m
            
            new_global_max = max(other_max, new_max_ri)
            
            # Accept if it improves or is equal (to allow movement)
            # Strict improvement is better for convergence, but equal moves help exploration
            if new_global_max < cur_val:
                # Accept
                all_used -= cur_row_diffs[ri]
                all_used |= new_diffs
                cur_rows[ri] = new_row
                cur_row_diffs[ri] = new_diffs
                cur_val = new_global_max
                no_improve_count = 0
                
                if cur_val < best_val:
                    best_val = cur_val
                    best_rows = [r[:] for r in cur_rows]
                    
            elif new_global_max == cur_val:
                # Accept with some probability to explore
                if rng.random() < 0.1:
                    all_used -= cur_row_diffs[ri]
                    all_used |= new_diffs
                    cur_rows[ri] = new_row
                    cur_row_diffs[ri] = new_diffs
                    # cur_val remains same
                    no_improve_count += 1
            else:
                # Reject
                no_improve_count += 1
        else:
            no_improve_count += 1
            
        # Check for restart
        if no_improve_count > max_no_improve:
            # Restart from best
            cur_rows = [r[:] for r in best_rows]
            cur_val = best_val
            cur_row_diffs = [_row_diffs(r) for r in cur_rows]
            all_used = set()
            for d in cur_row_diffs:
                all_used |= d
            no_improve_count = 0
            
            # Optional: Perturb the best state before restarting
            # e.g., swap two rows, or slightly modify a row
            # For now, simple restart is robust.
            
    # Final validation
    if not _validate(best_rows, n_rows, k):
        # Fallback to a valid greedy solution if something went wrong
        best_rows = _greedy_construct(n_rows, k, seed=1)
        
    return best_rows

def _validate(rows, n_rows, k):
    """Check all rows are valid and all differences are globally distinct."""
    used = set()
    for row in rows:
        if len(row) != k + 1:
            return False
        if row[0] != 0:
            return False
        for i in range(1, len(row)):
            if row[i] <= row[i - 1]:
                return False
        # Check Sidon
        diff_list = []
        n = len(row)
        for i in range(n):
            for j in range(i + 1, n):
                diff_list.append(row[j] - row[i])
        if len(diff_list) != len(set(diff_list)):
            return False
        for d in diff_list:
            if d in used:
                return False
            used.add(d)
    return True

