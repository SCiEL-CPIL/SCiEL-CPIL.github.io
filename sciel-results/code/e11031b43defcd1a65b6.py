def _verify(U, V, W):
    """Verify that sum_r U[:,r] ⊗ V[:,r] ⊗ W[:,r] reproduces the matrix mult tensor."""
    n, m, p = _DIMS
    rank = len(U[0])
    for i in range(n):
        for j in range(m):
            for k in range(p):
                s = 0.0
                for r in range(rank):
                    s += U[i * m + j][r] * V[j * p + k][r] * W[k * n + i][r]
                if s != 1:
                    return False
    # Check off-diagonal entries are zero
    for r in range(rank):
        for i in range(n):
            for j in range(m):
                if U[i * m + j][r] == 0:
                    continue
                for k2 in range(p):
                    if k2 == j:
                        continue
                    if V[j * p + k2][r] != 0:
                        return False
    return True


def construct():
    """
    Construct a rank-28 tensor decomposition for 2x4 * 4x4 matrix multiplication
    using Strassen's algorithm on four 2x2 block products.

    Returns dict with keys 'U', 'V', 'W':
      U: (8, 28) list of lists
      V: (16, 28) list of lists
      W: (8, 28) list of lists
    """
