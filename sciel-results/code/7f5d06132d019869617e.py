import numpy as np

def construct():
    n, m, p = 2, 2, 2
    rank = 7
    
    U = np.zeros((n*m, rank))
    V = np.zeros((m*p, rank))
    W = np.zeros((p*n, rank))
    
    # Index mapping:
    # U[i*m+j]
    # V[j*p+k]
    # W[k*n+i]
    
    # r=0: M1 = (A00+A11)(B00+B11) -> C00 + C11
    # U: A00(0), A11(3)
    # V: B00(0), B11(3)
    # W: C00(0), C11(3)
    U[0, 0] = 1
    U[3, 0] = 1
    V[0, 0] = 1
    V[3, 0] = 1
    W[0, 0] = 1
    W[3, 0] = 1
    
    # r=1: M2 = (A10+A11)B00 -> C10 - C11
    # U: A10(2), A11(3)
    # V: B00(0)
    # W: C10(1), C11(3)
    U[2, 1] = 1
    U[3, 1] = 1
    V[0, 1] = 1
    W[1, 1] = 1
    W[3, 1] = -1
    
    # r=2: M3 = A00(B01-B11) -> C01 + C11
    # U: A00(0)
    # V: B01(1), B11(3)
    # W: C01(2), C11(3)
    U[0, 2] = 1
    V[1, 2] = 1
    V[3, 2] = -1
    W[2, 2] = 1
    W[3, 2] = 1
    
    # r=3: M4 = A11(B10-B00) -> C00 + C10
    # U: A11(3)
    # V: B10(2), B00(0)
    # W: C00(0), C10(1)
    U[3, 3] = 1
    V[2, 3] = 1
    V[0, 3] = -1
    W[0, 3] = 1
    W[1, 3] = 1
    
    # r=4: M5 = (A00+A01)B11 -> -C00 + C01
    # U: A00(0), A01(1)
    # V: B11(3)
    # W: C00(0), C01(2)
    U[0, 4] = 1
    U[1, 4] = 1
    V[3, 4] = 1
    W[0, 4] = -1
    W[2, 4] = 1
    
    # r=5: M6 = (A10-A00)(B00+B01) -> C11
    # U: A10(2), A00(0)
    # V: B00(0), B01(1)
    # W: C11(3)
    U[2, 5] = 1
    U[0, 5] = -1
    V[0, 5] = 1
    V[1, 5] = 1
    W[3, 5] = 1
    
    # r=6: M7 = (A01-A11)(B10+B11) -> C00
    # U: A01(1), A11(3)
    # V: B10(2), B11(3)
    # W: C00(0)
    U[1, 6] = 1
    U[3, 6] = -1
    V[2, 6] = 1
    V[3, 6] = 1
    W[0, 6] = 1
    
    return {"U": U, "V": V, "W": W}
