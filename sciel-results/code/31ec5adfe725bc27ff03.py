def _check_coloring(coloring, edges):
    """Verify: adjacent vertices differ, and each color-pair subgraph is a forest."""
    n = len(coloring)
    for u, v in edges:
        if coloring[u] == coloring[v]:
            return False
    # Union-find per color pair
    from collections import defaultdict
    pair_edges = defaultdict(list)
    for u, v in edges:
        cu, cv = coloring[u], coloring[v]
        if cu != cv:
            pair = (min(cu, cv), max(cu, cv))
            pair_edges[pair].append((u, v))
    for pair, elist in pair_edges.items():
        parent = {}
        def find(x):
            if x not in parent:
                parent[x] = x
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x
        def union(x, y):
            rx, ry = find(x), find(y)
            if rx == ry:
                return False
            parent[rx] = ry
            return True
        for u, v in elist:
            if not union(u, v):
                return False
    return True


def construct():
    n = P['n']
    edges = P['edges']
    
    # The graph is Cay(Z_50, {±1, ±7}). Since 1 ≡ 7 (mod 3),
    # the coloring c[i] = i mod 3 is a proper 3-coloring.
    # Each color-pair subgraph induces disjoint paths (verified: all components are trees).
    coloring = [i % 3 for i in range(n)]
    
    # Verify correctness
    if _check_coloring(coloring, edges):
        return [int(c) for c in coloring]
    
    # Fallback (should never be reached for this specific graph)
    # Greedy with many colors
    adj = [[] for _ in range(n)]
    for u, v in edges:
        adj[u].append(v)
        adj[v].append(u)
    coloring = [0] * n
    for v in range(n):
        used = set(coloring[nb] for nb in adj[v])
        for c in range(50):
            if c not in used:
                coloring[v] = c
                break
    return [int(c) for c in coloring]
