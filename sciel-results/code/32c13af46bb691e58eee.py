def construct():
    # n=2, m=2, p=2
    # Rank 7 (Strassen)
    rank = 7
    
    # U: (4, 7) corresponding to A elements [A00, A01, A10, A11]
    # V: (4, 7) corresponding to B elements [B00, B01, B10, B11]
    # W: (4, 7) corresponding to C elements [C00, C01, C10, C11]
    # Index for C: k*2 + i
    
    U = [[0]*rank for _ in range(4)]
    V = [[0]*rank for _ in range(4)]
    W = [[0]*rank for _ in range(4)]
    
    # r=0: M1 = (A00 + A11)(B00 + B11)
    U[0][0] = 1; U[3][0] = 1
    V[0][0] = 1; V[3][0] = 1
    W[0][0] = 1; W[3][0] = 1 # C00 += 1, C11 += 1
    
    # r=1: M2 = (A10 + A11)B00
    U[2][1] = 1; U[3][1] = 1
    V[0][1] = 1
    W[2][1] = 1; W[3][1] = -1 # C10 += 1, C11 -= 1
    
    # r=2: M3 = A00(B10 - B11)
    U[0][2] = 1
    V[2][2] = 1; V[3][2] = -1
    W[2][2] = 1; W[3][2] = 1 # C10 += 1, C11 += 1
    
    # r=3: M4 = A11(B01 - B00)
    U[3][3] = 1
    V[1][3] = 1; V[0][3] = -1
    W[0][3] = 1; W[3][3] = 1 # C00 += 1, C11 += 1
    
    # r=4: M5 = (A00 + A01)B11
    U[0][4] = 1; U[1][4] = 1
    V[3][4] = 1
    W[0][4] = -1; W[1][4] = 1; W[3][4] = 1 # C00 -= 1, C01 += 1, C11 += 1
    
    # r=5: M6 = (A10 - A00)(B01 + B11)
    U[2][5] = 1; U[0][5] = -1
    V[1][5] = 1; V[3][5] = 1
    W[1][5] = 1; W[3][5] = 1 # C01 += 1, C11 += 1
    
    # r=6: M7 = (A01 - A11)(B00 + B10)
    U[1][6] = 1; U[3][6] = -1
    V[0][6] = 1; V[2][6] = 1
    W[0][6] = 1 # C00 += 1
    
    return {"U": U, "V": V, "W": W}
