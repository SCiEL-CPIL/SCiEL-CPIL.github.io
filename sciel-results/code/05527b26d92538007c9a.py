import numpy as np
import time
from scipy.optimize import minimize

class Optimizer:
    def __init__(self, budget, dim):
        self.budget = budget
        self.dim = dim

    def __call__(self, func):
        start_time = time.time()
        deadline = start_time + 290  # Safety margin for 300s limit
        
        dim = self.dim
        budget = self.budget
        
        # Strategy:
        # 1. Global Phase: Use a Sobol sequence for low-discrepancy sampling.
        #    This ensures broad coverage of the [-5, 5]^dim space more efficiently than random.
        #    We allocate ~50% of the budget to this phase.
        # 2. Local Phase: Take the best point from the global phase and run Nelder-Mead
        #    to refine it to high precision.
        
        # Split budget
        global_budget = budget // 2
        local_budget = budget - global_budget
        
        # 1. Global Search with Sobol
        # Sobol sequences require power of 2 for best properties, but any N works.
        # We will generate 'global_budget' points.
        # To avoid boundary issues and ensure we start inside, we map [0,1]^d to [-5,5]^d.
        
        # We need to be careful with the number of evaluations.
        # Let's use a simple loop to generate Sobol points on the fly or generate a block.
        # scipy.stats.qmc.Sobol is available.
        
        try:
            sampler = qmc.Sobol(d=dim, scramble=True)
            # Generate enough points. We might not use all if we hit time limit.
            # We'll generate in chunks to check time.
            points = []
            values = []
            
            # We want to use global_budget evaluations.
            # Let's generate them in a single batch if possible, or loop.
            # For dim=5 and N=250, a single batch is fine.
            sobol_points = sampler.random(n=global_budget)
            # Map [0, 1] to [-5, 5]
            sobol_points = sobol_points * 10.0 - 5.0
            
            best_x_global = None
            best_f_global = np.inf
            
            for i in range(global_budget):
                if time.time() > deadline:
                    break
                    
                x = sobol_points[i]
                fx = func(x)
                
                if fx < best_f_global:
                    best_f_global = fx
                    best_x_global = x.copy()
                    
            # If we didn't find any points (shouldn't happen), fallback to random
            if best_x_global is None:
                best_x_global = np.zeros(dim)
                best_f_global = func(best_x_global)
                
        except Exception as e:
            # Fallback to random uniform if Sobol fails
            rng = np.random.default_rng(42)
            best_x_global = None
            best_f_global = np.inf
            for i in range(global_budget):
                if time.time() > deadline:
                    break
                x = rng.uniform(-5, 5, dim)
                fx = func(x)
                if fx < best_f_global:
                    best_f_global = fx
                    best_x_global = x.copy()
            
            if best_x_global is None:
                best_x_global = np.zeros(dim)
                best_f_global = func(best_x_global)

        # 2. Local Search with Nelder-Mead
        # Start from the best global point.
        # We have local_budget evaluations left.
        # Nelder-Mead in scipy uses a specific internal logic for iterations.
        # We can limit the number of function calls using 'maxiter' or by wrapping the function.
        # Wrapping the function allows us to count calls and stop if we exceed local_budget or time.
        
        calls_made_local = 0
        
        def wrapped_func(x):
            nonlocal calls_made_local
            if time.time() > deadline:
                raise TimeoutError()
            calls_made_local += 1
            # Ensure x is within bounds for safety, though NM usually stays close
            # The problem statement says func clips, but we should be good.
            return func(x)
            
        try:
            # Initial simplex size
            # The initial simplex is generated by scipy based on the starting point.
            # We can tune 'initial_simplex' if needed, but default is often okay.
            # For dim=5, the default simplex might be too large or small.
            # Let's stick to default but monitor.
            
            res = minimize(
                wrapped_func, 
                best_x_global, 
                method='Nelder-Mead',
                options={
                    'maxiter': local_budget,  # Rough cap on iterations
                    'xatol': 1e-8,
                    'fatol': 1e-8,
                    'adaptive': True
                }
            )
            
            # Nelder-Mead might not use exactly local_budget calls.
            # If it converges early, that's fine.
            # If it doesn't, we stop at maxiter.
            
            if res.success or res.fun < best_f_global:
                best_x_global = res.x
                best_f_global = res.fun
                
        except TimeoutError:
            pass
        except Exception as e:
            # If NM crashes, keep the global best
            pass

        return best_x_global, best_f_global

