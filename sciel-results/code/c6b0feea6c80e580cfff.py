def _validate_fast(colors, n):
    """Fast validation using bitsets or sets. Returns True if valid."""
    if len(colors) != n * (n - 1) // 2:
        return False
    
    adj = [set() for _ in range(4)]
    idx = 0
    for i in range(n):
        for j in range(i + 1, n):
            c = colors[idx]
            if c < 0 or c > 3:
                return False
            adj[c].add((i, j))
            idx += 1

    for c in range(4):
        adj_set = adj[c]
        adj_list = [[] for _ in range(n)]
        for (u, v) in adj_set:
            adj_list[u].append(v)
            adj_list[v].append(u)
        
        for u in range(n):
            nbrs = adj_list[u]
            for i in range(len(nbrs)):
                for j in range(i + 1, len(nbrs)):
                    a, b = nbrs[i], nbrs[j]
                    if a > b:
                        a, b = b, a
                    if (a, b) in adj_set:
                        return False
    return True

def _search_50_backtracking(deadline):
    """
    Fast backtracking search for a valid 50-vertex coloring.
    """
    n = 50
    edges = [(i, j) for i in range(n) for j in range(i + 1, n)]
    num_edges = len(edges)
    
    # Precompute index for edge (u, v)
    # For speed, we will assign edges in a fixed order (lexicographic) 
    # but use bitsets to check validity.
    
    # adj[c][v] : bitset of neighbors of v in color c
    adj = [[0] * n for _ in range(4)]
    colors = [-1] * num_edges
    
    # Map (u, v) to index
    # We can compute index on the fly or precompute.
    # idx = u*(n-1) - u*(u+1)//2 + (v-u-1)
    def get_idx(u, v):
        if u > v: u, v = v, u
        return u * (n - 1) - u * (u + 1) // 2 + (v - u - 1)
    
    # Recursive backtracking
    # To avoid recursion depth issues and overhead, we use a stack.
    # But for 1225 edges, recursion depth is 1225. Python can handle it.
    
    # Optimization: Randomize the color order for each edge?
