def construct():
    n, m, p = DIMENSIONS
    # Try rank 55
    rank = 55
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    
    # Winograd 3x3x3 decomposition
    # I will use a known valid decomposition.
    # If I cannot find one, I will use schoolbook.
    
    # I will use the schoolbook for now to ensure correctness.
    # Rank 63.
    
    rank = n * m * p
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]
    column = 0
    for i in range(n):
        for j in range(m):
            for k in range(p):
                U[i * m + j][column] = 1
                V[j * p + k][column] = 1
