"""Construct a 5-regular graph of girth 9 via the line graph of a 3-regular
girth-14 graph, completed to degree 5 by a perfect matching in the complement.

Strategy (new design, from scratch):
  1. Build a 3-regular base graph G (a "cage-like" cubic graph) with girth >= 14.
  2. Form the line graph L(G). Because G is 3-regular, L(G) is 4-regular.
  3. The girth of L(G) is 2*girth(G) (for a simple cubic G), so girth(L(G)) >= 28,
     which far exceeds the required 9.
  4. L(G) has |E(G)| = 3n/2 vertices. We complete it to a 5-regular graph by adding
     a perfect matching M in the complement of L(G). A perfect matching in the
     complement exists whenever |V(L(G))| is even and L(G) is not complete.
  5. The added matching edges only *increase* the girth (they create no new short
     cycles), so the final graph still has girth >= 9.

Why the girth is preserved / increased:
  - Any cycle in the final graph either uses only L(G) edges (girth >= 28) or uses
    at least one matching edge. A matching edge connects two vertices of L(G) that
    are NOT adjacent in L(G). The shortest such "detour" is at least the distance in
    L(G) between the two matched vertices plus 1. Since matched pairs are chosen to
    be far apart in L(G) (we pick a matching that maximizes minimum distance, or at
    least avoids close pairs), the resulting girth stays well above 9.

The cubic base graph is generated by a greedy "cage" construction: start from a
root, grow a BFS tree of depth >= 7 (so that the induced tree has no cycles below
girth 15), then close the leaves into a 3-regular graph by pairing leaves that are
far apart. This yields a simple 3-regular graph with large girth.
"""
import random
from collections import deque

def construct(k, g):
    """Return (n, edges) for a k-regular graph on n vertices with girth >= g."""
    if k == 5 and g == 9:
        return _line_graph_plus_matching()
    # Fallback for other parameters: simple greedy regular graph with girth check.
    return _generic_construct(k, g)


# ---------------------------------------------------------------------------
# 3-regular base graph with large girth (cage-like cubic graph)
# ---------------------------------------------------------------------------
def _build_cubic_base(target_vertices, max_attempts=200, seed=12345):
    """
    Build a simple 3-regular graph with girth >= 14 (ideally) on about
    target_vertices vertices. Uses a greedy BFS-tree growth + leaf pairing.
    Returns (n, edges) or None on failure.
    """
    rng = random.Random(seed)
    best = None
    best_girth = 0

    for attempt in range(max_attempts):
        # Grow a BFS tree of depth D from a root. For girth >= 14, we need
        # the tree to have no two vertices at distance < 14 that share a
        # "closure" edge. A safe depth is 6 or 7.
        depth = 6
        # Build tree: root has 3 children, each internal node has 2 children
        # (one used for parent edge).
        # Number of vertices in a full 3-regular-ish tree of depth d:
        # level 0: 1, level i (i>=1): 3 * 2^(i-1)
        # total = 1 + 3*(2^d - 1) = 3*2^d - 2
        n_tree = 3 * (1 << depth) - 2
        if n_tree > target_vertices + 200:
            depth -= 1
            n_tree = 3 * (1 << depth) - 2

        # Build the tree structure
        parent = {}
        children = {}
        order = []
        root = 0
        parent[root] = -1
        children[root] = []
        order.append(root)
        next_id = 1

        for node in order:
            deg_used = 0
            if parent[node] != -1:
                deg_used = 1
            for _ in range(3 - deg_used):
                child = next_id
                next_id += 1
                parent[child] = node
                children[node].append(child)
                children[child] = []
                order.append(child)

        n = next_id
        # Now pair the leaves to make the graph 3-regular.
        # Leaves are vertices with no children.
        leaves = [v for v in range(n) if not children[v]]
        # Internal nodes already have degree 3 (1 parent + 2 children) except root
        # which has 3 children (no parent), so root is done.
        # Leaves have degree 1 (only parent edge). Each needs 2 more edges.
        # We pair leaves: each leaf gets 2 "extra" edges to other leaves.
        # Total extra edges needed = len(leaves) (each leaf needs 2, so 2*len(leaves)/2 = len(leaves)).
        # We need to create a 2-regular graph on the leaves (a union of cycles),
        # or more precisely, a 2-regular multigraph-free pairing.
        # Simplest: create a random 2-regular graph on leaves by randomly
        # pairing each leaf's two "slots" to other leaves.

        # Use a greedy approach: for each leaf, connect to two other leaves
        # that are far apart in the tree (to maximize girth).
        # Compute tree distances for girth checking later.
        # For now, just do random pairing and check girth.

        edges = set()
        # Add tree edges
        for v in range(1, n):
            edges.add((min(v, parent[v]), max(v, parent[v])))

        # Pair leaves
        leaf_list = list(leaves)
        rng.shuffle(leaf_list)
        # Each leaf needs 2 more edges. Total edges to add = len(leaves).
        # We'll create a 2-regular graph on the leaves.
        # Approach: randomly assign each leaf 2 partners, ensuring symmetry
        # and no self-loops or duplicates.
        # Simpler: create a random permutation of leaves and connect
        # leaf[i] to leaf[(i+1)%m] and leaf[(i+2)%m] for m = len(leaves).
        # This gives a 2-regular graph (union of cycles) on the leaves.
        m = len(leaf_list)
        if m < 3:
            continue
        # Random permutation
        perm = list(range(m))
        rng.shuffle(perm)
        # Connect leaf[perm[i]] to leaf[perm[(i+1)%m]] and leaf[perm[(i+2)%m]]
        added = set()
        ok = True
        for i in range(m):
            u = leaf_list[perm[i]]
            v1 = leaf_list[perm[(i + 1) % m]]
            v2 = leaf_list[perm[(i + 2) % m]]
            for v in (v1, v2):
                if u == v:
                    ok = False
                    break
                a, b = min(u, v), max(u, v)
                if (a, b) in edges:
                    ok = False
                    break
                if (a, b) in added:
                    ok = False
                    break
                added.add((a, b))
                edges.add((a, b))
            if not ok:
                break
        if not ok:
            continue

        # Check that every vertex has degree exactly 3
        deg = [0] * n
        for a, b in edges:
            deg[a] += 1
            deg[b] += 1
        if any(d != 3 for d in deg):
            continue

        # Check girth
        girth = _compute_girth(n, list(edges))
        if girth >= 14:
            return n, list(edges)
        if girth > best_girth:
            best_girth = girth
            best = (n, list(edges))

    return best


def _compute_girth(n, edges):
    """Compute the girth (shortest cycle length) of a graph. Returns inf if acyclic."""
    adj = [[] for _ in range(n)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)

    best = float('inf')
    # BFS from each vertex, tracking distance and parent
    for start in range(n):
        dist = [-1] * n
        parent = [-1] * n
        dist[start] = 0
        q = deque([start])
        while q:
            u = q.popleft()
            if dist[u] >= best:
                continue
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    parent[v] = u
                    q.append(v)
                elif v != parent[u] and parent[v] != u:
                    # Found a cycle: start -> ... -> u -> v -> ... -> start
                    # The cycle length is dist[u] + dist[v] + 1
                    # But we need the actual cycle through start.
                    # Actually, for girth, we can use the fact that the
                    # shortest cycle through start has length at most
                    # dist[u] + dist[v] + 1 when u and v are both neighbors
                    # of start... this is getting complex.
                    # Simpler: just track the shortest cycle found by BFS
                    # from start where we detect a back-edge.
                    pass
        # For a proper girth computation, use the standard BFS from each
        # vertex with parent tracking.
    # Use a cleaner approach: BFS from each vertex, when we find a back edge
    # (u, v) where v is already visited and v != parent[u] and u != parent[v],
    # the cycle length is dist[u] + dist[v] + 1.
    for start in range(n):
        dist = [-1] * n
        par = [-1] * n
        dist[start] = 0
        q = deque([start])
        while q:
            u = q.popleft()
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    par[v] = u
                    q.append(v)
                elif v != par[u] and u != par[v]:
                    cyc = dist[u] + dist[v] + 1
                    if cyc < best:
                        best = cyc
    return best


# ---------------------------------------------------------------------------
# Line graph construction
# ---------------------------------------------------------------------------
def _line_graph(n, edges):
    """
    Given a graph with n vertices and edges, return the line graph.
    Each vertex in the line graph corresponds to an edge in the original.
    Two vertices in the line graph are adjacent iff the corresponding edges
    share an endpoint in the original graph.
    Returns (m, l_edges) where m = len(edges) and l_edges is the edge list.
    """
    m = len(edges)
    # Map edge index to its endpoints
    edge_to_idx = {}
    for i, (a, b) in enumerate(edges):
        edge_to_idx[(a, b)] = i
        edge_to_idx[(b, a)] = i

    # For each vertex in original, collect incident edge indices
    incident = [[] for _ in range(n)]
    for i, (a, b) in enumerate(edges):
        incident[a].append(i)
        incident[b].append(i)

    # Two edges are adjacent in the line graph if they share a vertex
    l_edges = set()
    for v in range(n):
        inc = incident[v]
        for i in range(len(inc)):
            for j in range(i + 1, len(inc)):
                a, b = inc[i], inc[j]
                if a != b:
                    l_edges.add((min(a, b), max(a, b)))

    return m, list(l_edges)


