# Main construction
# ---------------------------------------------------------------------------
def _line_graph_plus_matching():
    """
    Construct a 5-regular graph of girth >= 9 by:
    1. Building a 3-regular base graph with girth >= 14.
    2. Taking its line graph (4-regular, girth >= 28).
    3. Adding a perfect matching in the complement to reach degree 5.
    """
    # Step 1: Build a 3-regular base graph with girth >= 14
    # The Moore bound for 3-regular girth 14 is 2*(2^7 - 1) = 254, but that's
    # for odd girth. For even girth 14, the bound is different.
    # Let's aim for a graph with around 300-500 vertices.
    base = _build_cubic_base(400, max_attempts=500, seed=7)
    if base is None:
        # Fallback: try a smaller target
        base = _build_cubic_base(200, max_attempts=500, seed=13)
    if base is None:
        # Last resort: return a known valid graph or raise
        raise RuntimeError("Failed to construct 3-regular base graph with girth >= 14")

    n_base, base_edges = base

    # Step 2: Line graph
    m, l_edges = _line_graph(n_base, base_edges)
    # m = 3 * n_base / 2
    # l_edges is 4-regular

    # Step 3: Add perfect matching in complement
    matching = _perfect_matching_in_complement(m, l_edges)
    if matching is None:
        # If no perfect matching found, try a different base
        base = _build_cubic_base(300, max_attempts=500, seed=99)
        if base is None:
            raise RuntimeError("Failed to find perfect matching in complement")
        n_base, base_edges = base
        m, l_edges = _line_graph(n_base, base_edges)
        matching = _perfect_matching_in_complement(m, l_edges)
        if matching is None:
            raise RuntimeError("Failed to find perfect matching in complement (second attempt)")

    # Combine edges
    all_edges = l_edges + matching
    return m, all_edges


def _generic_construct(k, g):
    """Fallback for non-(5,9) parameters: simple greedy construction."""
    # This is a placeholder; the task only requires k=5, g=9.
    # Return a trivial valid graph if possible.
    n = k + 1
    edges = []
    for i in range(n):
        for j in range(i + 1, n):
            edges.append((i, j))
    # This is complete graph K_{k+1}, which is k-regular.
    # Girth is 3, which may not satisfy g, but this is a fallback.
    return n, edges
