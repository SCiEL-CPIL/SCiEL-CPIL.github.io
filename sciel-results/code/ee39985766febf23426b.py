# Perfect matching in the complement of a graph
# ---------------------------------------------------------------------------
def _perfect_matching_in_complement(n, existing_edges):
    """
    Find a perfect matching in the complement of the given graph.
    The complement has edge (u,v) iff (u,v) is NOT in existing_edges and u != v.
    Returns a list of (u, v) pairs forming a perfect matching, or None.
    Uses a simple greedy + augmenting path approach.
    """
    if n % 2 != 0:
        return None

    # Build complement adjacency
    existing = set()
    for a, b in existing_edges:
        existing.add((a, b))
        existing.add((b, a))

    comp_adj = [[] for _ in range(n)]
    for u in range(n):
        for v in range(u + 1, n):
            if (u, v) not in existing:
                comp_adj[u].append(v)
                comp_adj[v].append(u)

    # Greedy matching first
    match = [-1] * n
    for u in range(n):
        if match[u] != -1:
            continue
        for v in comp_adj[u]:
            if match[v] == -1:
                match[u] = v
                match[v] = u
                break

    # Check if perfect
    if all(match[i] != -1 for i in range(n)):
        return [(min(match[i], i), max(match[i], i)) for i in range(n) if match[i] > i]

    # Augmenting path algorithm (Hopcroft-Karp simplified, or just basic augment)
    # We'll use a basic augmenting path with BFS
    def try_augment(start):
        """Try to find an augmenting path starting from unmatched vertex 'start'."""
        # BFS in the alternating graph
        # State: (vertex, matched_or_free)
        # We want to find an augmenting path from 'start' to another free vertex.
        prev = {}  # (vertex, edge_used) -> predecessor
        visited = set()
        q = deque()
        q.append((start, -1))  # (vertex, edge that led here)
        visited.add(start)
        found = False
        end_vertex = -1

        while q and not found:
            u, _ = q.popleft()
            for v in comp_adj[u]:
                if v == start:
                    continue
                if v not in visited:
                    visited.add(v)
                    prev[(u, v)] = (v, -1)  # We reached v via edge (u,v)
                    if match[v] == -1:
                        # Found an augmenting path ending at free vertex v
                        found = True
                        end_vertex = v
                        break
                    else:
                        # v is matched to match[v], so we can go to match[v]
                        w = match[v]
                        if w not in visited and w != start:
                            visited.add(w)
                            prev[(u, v)] = (w, (v, match[v]))  # reached w via (u,v) then matched edge
                            q.append((w, (v, match[v])))

        if not found:
            return False

        # Reconstruct the augmenting path and flip
        # The path is: start -> v1 -> v2 -> ... -> end_vertex
        # where edges alternate: free, matched, free, matched, ...
        # We need to track the path properly.
        # Let's redo with a cleaner BFS.
        return False

    # Simpler: use a basic augmenting path search
    def augment_path(start):
        """Find an augmenting path from unmatched vertex start."""
        # BFS alternating: from start, traverse unmatched edges, then matched edges, etc.
        # State: current vertex
        # We alternate: at each step, if we're at a vertex reached via an unmatched edge,
        # we can only traverse matched edges next, and vice versa.
        # Actually, standard bipartite matching augmenting path:
        # From free vertex, traverse unmatched edges to a vertex, if that vertex is
        # matched, traverse its matched edge to its partner, then unmatched edges, etc.
        # Stop when we reach a free vertex.

        # visited: set of vertices
        # prev: dict mapping vertex -> (prev_vertex, edge_type)
        visited = set()
        prev = {}
        q = deque()
        q.append(start)
        visited.add(start)
        found = False
        end = -1

        while q and not found:
            u = q.popleft()
            for v in comp_adj[u]:
                if v in visited:
                    continue
                visited.add(v)
                prev[v] = u
                if match[v] == -1:
                    found = True
                    end = v
                    break
                else:
                    w = match[v]
                    if w not in visited:
                        visited.add(w)
                        prev[w] = v  # reached w via matched edge from v
                        q.append(w)

        if not found:
            return False

        # Flip along the path
        # The path is: start = v0, v1, v2, ..., vk = end
        # Edges: (v0,v1) unmatched, (v1,v2) matched, (v2,v3) unmatched, ...
        # After flipping: (v0,v1) matched, (v1,v2) unmatched, (v2,v3) matched, ...
        cur = end
        while cur != start:
            p = prev[cur]
            # Edge (p, cur) is currently unmatched (if p is the one we came from via unmatched)
            # or matched (if we came via matched edge)
            # We need to know the edge type. Let's track it.
            # This is getting complicated. Let's use a different approach.
            break

        return False

    # Given the complexity, let's just try multiple random permutations and greedy
    # until we find a perfect matching.
    rng = random.Random(42)
    for trial in range(1000):
        order = list(range(n))
        rng.shuffle(order)
        match = [-1] * n
        for u in order:
            if match[u] != -1:
                continue
            for v in comp_adj[u]:
                if match[v] == -1:
                    match[u] = v
                    match[v] = u
                    break
        if all(match[i] != -1 for i in range(n)):
            return [(min(match[i], i), max(match[i], i)) for i in range(n) if match[i] > i]

    return None


