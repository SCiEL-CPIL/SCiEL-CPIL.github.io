import time
import random
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 55.0
    
    n = 17
    min_dist = 6
    max_size = 340
    
    # Precompute popcount for all 17-bit numbers using a lookup table for 8-bit chunks
    # This is faster than bit_count in a Python loop for many operations if vectorized,
    # but for scalar checks, bit_count is very fast in Python 3.10+.
    # We will use a hybrid approach.
    
    # Strategy 1: Try to construct the known 256-word [17,8,6] QR code.
    # The generator polynomial for the [17,8,6] QR code is often cited.
    # Let's try to generate it.
    # If we can't, we fall back to greedy.
    
    def generate_qr_code_17_8_6():
        # The [17,8,6] code is a subcode of the [17,9,5] code.
        # We will try to find a generator polynomial.
        # A known generator for the [17,9,5] QR code is g9(x).
        # The [17,8,6] code is generated by g8(x) = g9(x) * (x+1)? No.
        # Actually, the [17,8,6] code is the code with generator polynomial:
        # g(x) = x^9 + x^8 + x^5 + x^4 + x^3 + x + 1 (This is a guess)
        
        # Let's use a more robust method:
        # We know the code has 256 words.
        # We will use a greedy algorithm to find a linear code of size 256?
        # No, that's hard.
        
        # Instead, we will use the fact that the [17,8,6] code is the set of all
        # linear combinations of the rows of a generator matrix.
        # We will try to construct the generator matrix using the quadratic residues.
        
        # For now, return None to indicate failure, and use greedy.
        return None

    qr_code = generate_qr_code_17_8_6()
    
    if qr_code is not None and len(qr_code) == 256:
        # Verify the QR code
        valid = True
        for i in range(256):
            for j in range(i+1, 256):
                if (qr_code[i] ^ qr_code[j]).bit_count() < min_dist:
                    valid = False
                    break
            if not valid:
                break
        
        if valid:
            best_codewords = qr_code
            best_size = 256
        else:
            best_codewords = [0]
            best_size = 1
    else:
        best_codewords = [0]
        best_size = 1

    # Local Search / Greedy Expansion
    # We will try to add words to the current best code.
    # To speed up, we use a list of candidates.
    
    # Precompute popcount for all 2^17 values? 
    # 2^17 = 131072. 
    # popcount = [0] * (1 << n)
    # for i in range(1, 1 << n):
    #     popcount[i] = popcount[i >> 1] + (i & 1)
    
    # This takes ~0.1s. Worth it.
    popcount = [0] * (1 << n)
    for i in range(1, 1 << n):
        popcount[i] = popcount[i >> 1] + (i & 1)
        
    candidates = list(range(1, 1 << n))
    
    def run_greedy_pass(order, current_codewords):
        codewords = current_codewords.copy()
        for candidate in order:
            if time.time() > deadline - 2.0:
                break
            valid = True
            for cw in codewords:
                if popcount[candidate ^ cw] < min_dist:
                    valid = False
                    break
            if valid:
                codewords.append(candidate)
        return codewords

    # If we started with 256, we can't just add.
    # We need to do swaps or restarts.
    
    # For simplicity and robustness, we will do random restarts of the greedy algorithm
    # starting from the best found code so far (or [0] if small).
    
    # If we have the 256-word code, we try to improve it via local search.
    # If we don't, we try to find a large code from scratch.
    
    if best_size >= 200:
        # Local search on the large code
        # Try to swap words to allow growth
        while time.time() < deadline - 2.0:
            # Pick a random word to remove
            idx = random.randint(0, len(best_codewords) - 1)
            removed_word = best_codewords[idx]
            current = [w for i, w in enumerate(best_codewords) if i != idx]
            
            # Try to add random words
            random.shuffle(candidates)
            # We only need to check a subset of candidates to save time
            # But we want to find the best addition.
            # Let's try adding the first valid candidate.
            added = False
            for candidate in candidates:
                if candidate == removed_word:
                    continue
                valid = True
                for cw in current:
                    if popcount[candidate ^ cw] < min_dist:
                        valid = False
                        break
                if valid:
                    current.append(candidate)
                    added = True
                    break
            
            if len(current) > best_size:
                best_size = len(current)
                best_codewords = current
                if best_size >= max_size:
                    break
    else:
        # Standard greedy with restarts
        while time.time() < deadline - 2.0:
            random.shuffle(candidates)
            current_cw = run_greedy_pass(candidates, [0])
            if len(current_cw) > best_size:
                best_size = len(current_cw)
                best_codewords = current_cw
                if best_size >= max_size:
                    break

    return best_codewords
