import time
import random
import numpy as np

N = 1000
MAX_SUM = 2 * N
K = 2

def _update_counts_remove(x, S, counts):
    """Remove x from S in the counts array. Assumes x is in S."""
    if S.size > 0:
        # S contains x, so x+x is included in x+S
        # We subtract 1 from counts[x + z] for all z in S
        # Note: if z=x, we subtract 1 from counts[2x].
        # This correctly handles the pair {x,x} and {x,z}.
        counts[x + S] -= 1
    # No separate 2x term needed if x is in S, as x+x is covered by x+S.
    # Wait, if S is a set of distinct integers, x is in S.
    # The sums generated by x with S are x+s for s in S.
    # This includes x+x.
    # So counts[x+S] -= 1 is correct for all pairs involving x.

def _update_counts_add(x, S, counts):
    """Add x to S in the counts array. Assumes x is NOT in S."""
    if S.size > 0:
        counts[x + S] += 1
    counts[2 * x] += 1

def _can_add(x, S, counts):
    """Check if x can be added to S without violating K."""
    if S.size > 0:
        # Check sums x + s for all s in S
        # We need counts[x+s] < K for all s in S
        # AND counts[2x] < K
        if np.any(counts[x + S] >= K):
            return False
    if counts[2 * x] >= K:
        return False
    return True

def _greedy_init(order, noise=0.0, rng=None):
    S = np.empty(0, dtype=np.int64)
    S_set = set()
    counts = np.zeros(MAX_SUM + 1, dtype=np.int64)
    
    for x in order:
        if _can_add(x, S, counts):
            if noise > 0 and rng and rng.random() < noise:
                continue
            _update_counts_add(x, S, counts)
            S = np.concatenate([S, [x]])
            S_set.add(x)
            
    return S, S_set, counts

def _local_search(S, S_set, counts, rng, deadline):
    """
    Local search with insertions and swaps.
    """
    best_S = S.copy()
    best_size = S.size
    avail = np.array([v for v in range(1, N + 1) if v not in S_set], dtype=np.int64)
    rng.shuffle(avail)
    
    # To speed up, we can keep a list of available elements.
    # We will try random insertions first.
    # If we get stuck, we try swaps.
    
    stuck_counter = 0
    
    while time.time() < deadline:
        if avail.size == 0:
            break
            
        # Try a batch of random insertions
        improved = False
        batch_size = min(100, avail.size)
        
        for _ in range(batch_size):
            if avail.size == 0:
                break
            idx = rng.randrange(avail.size)
            x = avail[idx]
            
            if _can_add(x, S, counts):
                _update_counts_add(x, S, counts)
                S = np.concatenate([S, [x]])
                S_set.add(x)
                # Remove x from avail
                avail = np.delete(avail, idx)
                improved = True
                stuck_counter = 0
                if S.size > best_size:
                    best_size = S.size
                    best_S = S.copy()
            else:
                # Move to next candidate
                pass
                
        if improved:
            continue
            
        # If no insertion succeeded, try swaps
        stuck_counter += 1
        
        if S.size == 0:
            break
            
        # Try a few random swaps
        swap_attempts = 50
        for _ in range(swap_attempts):
            if time.time() > deadline:
                break
                
            # Pick a random element to remove from S
            i_rm = rng.randrange(S.size)
            y = S[i_rm]
            
            # Pick a random element to add from avail
            if avail.size == 0:
                break
            i_add = rng.randrange(avail.size)
            x = avail[i_add]
            
            # Temporarily remove y
            # We need to be careful with numpy array deletion
            # It's faster to maintain a boolean mask or just reconstruct if needed, 
            # but for N=1000, np.delete is O(N) which is fine.
            
            # However, updating counts is the expensive part.
            # Let's do the count update on the fly.
            
            # Remove y from counts
            # y is in S.
            # S contains y.
            # counts[y + S] -= 1
            # This is a vectorized operation.
            old_counts_snapshot = None # We won't snapshot, we will revert manually
            
            # Apply removal
            if S.size > 0:
                counts[y + S] -= 1
                
            # Now S effectively is S \ {y} for the purpose of counts?
            # No, S array still has y. 
            # _can_add(x, S_without_y, counts)
            # We need to check x against S \ {y}.
            # Let S_new = S[S != y]
            S_new = S[S != y]
            
            # Check if x can be added to S_new with current counts (which reflect S\{y})
            # Note: counts currently reflect S\{y} because we subtracted y's contributions.
            
            valid = True
            if S_new.size > 0:
                if np.any(counts[x + S_new] >= K):
                    valid = False
            if valid and counts[2 * x] >= K:
                valid = False
                
            if valid:
                # Accept swap
                # Add x to counts
                if S_new.size > 0:
                    counts[x + S_new] += 1
                counts[2 * x] += 1
                
                # Update S and S_set
                S = S_new # S already has y removed in S_new
                S_set.discard(y)
                S_set.add(x)
                
                # Update avail
                # Remove x from avail
                avail = np.delete(avail, i_add)
                # Add y to avail
                avail = np.concatenate([avail, [y]])
                
                improved = True
                stuck_counter = 0
                if S.size > best_size:
                    best_size = S.size
                    best_S = S.copy()
                    
                break # Restart swap attempts as S changed
                
            else:
                # Revert removal of y
                if S.size > 0:
                    counts[y + S] += 1
                    # Note: S still contains y here.
                    # The subtraction was counts[y+S] -= 1.
                    # The addition is counts[y+S] += 1.
                    # This correctly reverts.
                    
        if not improved:
            # If we tried many swaps and failed, we might be stuck.
            # We can try a "restart" or just continue with random insertions.
            # For now, we just continue the loop, which will try insertions again.
            # This might oscillate. 
            # A better strategy: if stuck_counter > 10, try a more aggressive move or break.
            if stuck_counter > 100:
                 # Try to shuffle avail to explore different parts
                 rng.shuffle(avail)
                 stuck_counter = 0
                 
    return best_S

def construct():
    start_time = time.time()
    deadline = start_time + 110.0 # Safety margin
    
    rng = random.Random(42)
    
    best_S_global = np.empty(0, dtype=np.int64)
    best_size_global = 0
    
    # Generate multiple initial candidates
    # 1. Ascending
    # 2. Descending
    # 3. Random
    # 4. Noisy Random
    
    candidates = []
    
    # Ascending
    S, S_set, counts = _greedy_init(list(range(1, N+1)), 0.0, None)
    candidates.append((S, S_set, counts))
    
    # Descending
    S, S_set, counts = _greedy_init(list(range(N, 0, -1)), 0.0, None)
    candidates.append((S, S_set, counts))
    
    # Random
    order = list(range(1, N+1))
    rng.shuffle(order)
    S, S_set, counts = _greedy_init(order, 0.0, None)
    candidates.append((S, S_set, counts))
    
    # Noisy Randoms
    for seed in [1, 2, 3, 4, 5]:
        r = random.Random(seed)
        order = list(range(1, N+1))
        r.shuffle(order)
        S, S_set, counts = _greedy_init(order, 0.1, r)
        candidates.append((S, S_set, counts))
        
    # Run local search on the best few candidates
    # Sort by size descending
    candidates.sort(key=lambda x: x[0].size, reverse=True)
    
    # Take top 3
    for S, S_set, counts in candidates[:3]:
        if time.time() > deadline:
            break
            
        # Make copies to avoid modifying the original candidate if we want to reuse
        S_copy = S.copy()
        S_set_copy = set(S_set)
        counts_copy = counts.copy()
        
        improved_S = _local_search(S_copy, S_set_copy, counts_copy, rng, deadline)
        
        if improved_S.size > best_size_global:
            best_size_global = improved_S.size
            best_S_global = improved_S
            
    # If we have time, run local search on other candidates
    for S, S_set, counts in candidates[3:]:
        if time.time() > deadline:
            break
        S_copy = S.copy()
        S_set_copy = set(S_set)
        counts_copy = counts.copy()
        
        improved_S = _local_search(S_copy, S_set_copy, counts_copy, rng, deadline)
        
        if improved_S.size > best_size_global:
            best_size_global = improved_S.size
            best_S_global = improved_S

    return [int(v) for v in best_S_global]

