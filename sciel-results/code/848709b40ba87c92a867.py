"""Initial program for the suite task; SCiEL evolves the EVOLVE-BLOCK."""
N = 50

# EVOLVE-BLOCK-START
import numpy as np
import time
from scipy.optimize import minimize
from scipy.spatial import ConvexHull

def construct():
    start_time = time.time()
    deadline = 140.0  # Safety margin before 150s kill

    def normalize(pts):
        norms = np.linalg.norm(pts, axis=1, keepdims=True)
        norms[norms == 0] = 1.0
        return pts / norms

    def compute_covering_radius_and_worst_facet(pts):
        """
        Computes the covering radius and returns the indices of the worst facet
        (the one with the largest circumradius) if the circumcenter is inside the facet.
        Returns (radius_in_degrees, worst_face_indices or None)
        """
        try:
            pts = normalize(pts)
            if np.any(np.linalg.norm(pts, axis=1) < 1e-10):
                return 180.0, None
                
            hull = ConvexHull(pts)
            
            max_r = 0.0
            worst_face = None
            worst_r_val = 0.0
            
            for face in hull.simplices:
                p0, p1, p2 = pts[face[0]], pts[face[1]], pts[face[2]]
                p_face = np.array([p0, p1, p2])
                
                # Compute circumcenter of the spherical triangle
                # c = w0*p0 + w1*p1 + w2*p2
                # G @ w = [1, 1, 1]^T where G is Gram matrix
                G = p_face @ p_face.T
                rhs = np.array([1.0, 1.0, 1.0])
                
                try:
                    w = np.linalg.solve(G, rhs)
                except np.linalg.LinAlgError:
                    continue
                    
                c = np.sum(w[:, None] * p_face, axis=0)
                c_norm = np.linalg.norm(c)
                if c_norm < 1e-10:
                    continue
                    
                c /= c_norm
                
                # Check if circumcenter is inside the spherical triangle
                # For a convex hull facet, the circumcenter is the center of the circumscribed cap.
                # The cap is "empty" (contains no other points) if it's a hull facet.
                # The worst point in the Voronoi cell for this facet is the circumcenter IF it lies
                # within the spherical triangle formed by the vertices.
                # How to check if c is inside the triangle (p0, p1, p2) on the sphere?
                # The triangle is the intersection of the sphere with the cone generated by p0, p1, p2.
                # c is inside if it can be written as a positive linear combination of p0, p1, p2?
                # Actually, for the convex hull, the facet is a face. The normal of the facet points outward.
                # The circumcenter c is the point on the sphere furthest from the origin in the direction 
                # of the face normal? No.
                
                # A simpler check: 
                # The circumcenter c is inside the triangle if the barycentric coordinates w_i are all positive?
                # Not exactly, because the "plane" is curved.
                # However, for small triangles, w_i > 0 is a good heuristic.
                # More robustly: c is inside if it lies on the same side of the great circle edges as the interior.
                # Let's just use the distance. If c is very close to the edge, it might be outside.
                # For the purpose of finding the "worst" facet to optimize, we can assume the circumcenter 
                # is the critical point if the triangle is not obtuse.
                
                # Let's compute the angular distance from c to p0
                cos_d = np.clip(c @ p0, -1.0, 1.0)
                d = np.arccos(cos_d)
                
                # Check if c is "inside" the triangle. 
                # If the triangle is obtuse, the circumcenter is outside the triangle, and the 
                # worst point is the midpoint of the longest edge.
                # Let's check edge midpoints too?
                # For now, let's assume the circumcenter is the candidate if d is the max.
                # To be safe, we can check if the circumcenter is inside by checking 
                # if the dot products of c with the cross products of the edges have the correct signs.
                
                # Cross products for edges (oriented consistently)
                # n01 = p0 x p1, n12 = p1 x p2, n20 = p2 x p0
                # If c is inside, c should be on the same side of each edge as the opposite vertex.
                # (c x p0) . p1 ... this is getting complicated.
                
                # Heuristic: If w[0]>0, w[1]>0, w[2]>0, it's likely inside.
                if np.all(w > -1e-8):
                     if d > worst_r_val:
                         worst_r_val = d
                         worst_face = face
                         max_r = d
                else:
                     # If circumcenter is outside, the worst point is on the boundary (edge midpoint)
                     # We can approximate the radius by the max distance to the vertices? 
                     # No, the worst point is the midpoint of the longest edge.
                     # Let's just use the max distance to vertices as a lower bound for this facet
                     # but it's not the exact covering radius contribution.
                     # For optimization targeting, we need the exact worst point.
                     # If circumcenter is outside, the facet is "obtuse".
                     # The worst point is the midpoint of the longest edge.
                     # Let's compute midpoints.
                     m01 = (p0 + p1) / np.linalg.norm(p0 + p1)
                     m12 = (p1 + p2) / np.linalg.norm(p1 + p2)
                     m20 = (p2 + p0) / np.linalg.norm(p2 + p0)
                     
                     d01 = np.arccos(np.clip(m01 @ p0, -1, 1))
                     d12 = np.arccos(np.clip(m12 @ p1, -1, 1))
                     d20 = np.arccos(np.clip(m20 @ p2, -1, 1))
                     
                     # The worst point is the one with the largest distance to the nearest vertex?
                     # Actually, the covering radius is the max distance from any point to nearest config point.
                     # For a facet, the Voronoi cell is the triangle.
                     # If circumcenter is outside, the furthest point in the triangle from the vertices 
                     # is the midpoint of the longest edge.
                     # Let's find the longest edge.
                     d_edges = [
                         np.arccos(np.clip(p0 @ p1, -1, 1)),
                         np.arccos(np.clip(p1 @ p2, -1, 1)),
                         np.arccos(np.clip(p2 @ p0, -1, 1))
                     ]
                     max_edge_idx = np.argmax(d_edges)
                     if max_edge_idx == 0:
                         worst_pt_dist = d01
                         # We don't have a single vertex to move, but we can move p0 and p1
                         # For simplicity, let's skip obtuse facets in the "targeted" optimization
                         # or treat them similarly.
                     elif max_edge_idx == 1:
                         worst_pt_dist = d12
                     else:
                         worst_pt_dist = d20
                         
                     # The distance from the midpoint to the nearest vertex is half the edge length?
                     # No, on the sphere, the distance from midpoint to vertex is half the angular length of the edge.
                     # So worst_pt_dist is already the distance to the vertex.
                     
                     if worst_pt_dist > worst_r_val:
                         worst_r_val = worst_pt_dist
                         # We need to identify which vertices to move.
                         # If it's edge 0 (p0-p1), we move p0 and p1.
                         # Let's store the face and mark it as obtuse.
                         worst_face = face
                         max_r = worst_pt_dist
                         
            return np.degrees(max_r), worst_face
            
        except Exception:
            return 180.0, None

    def facet_objective(x_face, pts, face_idx):
        """
        Objective function for optimizing a specific facet.
        x_face: flattened coordinates of the 3 vertices of the facet (9 values).
        pts: the full array of points (only the facet vertices are updated in the calculation).
        face_idx: indices of the vertices in pts.
        """
        # Extract current positions of other points (fixed)
        # We only modify the 3 vertices of the facet.
        # Create a copy of pts
        pts_temp = pts.copy()
        
        # Update the 3 vertices
        # x_face is 9 values: 3 for p0, 3 for p1, 3 for p2
        p0 = x_face[0:3]
        p1 = x_face[3:6]
        p2 = x_face[6:9]
        
        # Normalize
        p0 = p0 / np.linalg.norm(p0)
        p1 = p1 / np.linalg.norm(p1)
        p2 = p2 / np.linalg.norm(p2)
        
        pts_temp[face_idx[0]] = p0
        pts_temp[face_idx[1]] = p1
        pts_temp[face_idx[2]] = p2
        
        # Compute the circumradius of this specific triangle
        # We don't need the full hull, just the circumradius of this triangle
        # BUT we must ensure the cap is empty? 
        # If we move the vertices, the hull might change.
        # For a local step, assuming the hull topology is stable, 
        # we just minimize the circumradius of this triangle.
        
        G = np.array([
            [p0 @ p0, p0 @ p1, p0 @ p2],
            [p1 @ p0, p1 @ p1, p1 @ p2],
            [p2 @ p0, p2 @ p1, p2 @ p2]
        ])
        rhs = np.array([1.0, 1.0, 1.0])
        
        try:
            w = np.linalg.solve(G, rhs)
        except np.linalg.LinAlgError:
            return 1.0 # Large penalty
            
        c = w[0]*p0 + w[1]*p1 + w[2]*p2
        c_norm = np.linalg.norm(c)
        if c_norm < 1e-10:
            return 1.0
            
        c /= c_norm
        cos_d = np.clip(c @ p0, -1.0, 1.0)
        d = np.arccos(cos_d)
        
        return d

    # Initial configuration: Fibonacci sphere
    i = np.arange(N) + 0.5
    z = 1.0 - 2.0 * i / N
    phi = np.pi * (1.0 + np.sqrt(5.0)) * i
    r = np.sqrt(1.0 - z * z)
    init_pts = np.column_stack([r * np.cos(phi), r * np.sin(phi), z])
    
    best_pts = init_pts.copy()
    best_cr, _ = compute_covering_radius_and_worst_facet(best_pts)
    
    # Iterative Refinement
    # We will iterate: find worst facet, optimize its vertices, repeat.
    # To avoid cycling, we can keep a history or just rely on the objective decreasing.
    
    max_iters = 100
    iter_count = 0
    while time.time() < deadline - 10 and iter_count < max_iters:
        iter_count += 1
        cr, worst_face = compute_covering_radius_and_worst_facet(best_pts)
        
        if worst_face is None:
            break
            
        if cr < best_cr - 1e-5:
            best_cr = cr
            
        # Get the current coordinates of the worst facet vertices
        v0, v1, v2 = worst_face
        x0 = np.concatenate([best_pts[v0], best_pts[v1], best_pts[v2]])
        
        # Optimize these 3 vertices
        # We use L-BFGS-B
        # The objective is the circumradius of the triangle formed by these 3 points.
        # Note: This does not account for the "empty cap" constraint strictly,
        # but for small moves, it's a valid local approximation.
        
        try:
            res = minimize(
                facet_objective,
                x0,
                args=(best_pts, worst_face),
                method='L-BFGS-B',
                options={'maxiter': 50, 'ftol': 1e-10, 'gtol': 1e-6, 'disp': False}
            )
            
            if res.success or res.fun < np.inf:
                # Update the points
                new_p0 = res.x[0:3]
                new_p1 = res.x[3:6]
                new_p2 = res.x[6:9]
                
                # Normalize
                new_p0 = new_p0 / np.linalg.norm(new_p0)
                new_p1 = new_p1 / np.linalg.norm(new_p1)
                new_p2 = new_p2 / np.linalg.norm(new_p2)
                
                candidate_pts = best_pts.copy()
                candidate_pts[v0] = new_p0
                candidate_pts[v1] = new_p1
                candidate_pts[v2] = new_p2
                
                # Check if this improvement is valid (covering radius actually decreased)
                # We must recompute the full covering radius because moving vertices
                # might affect other facets or create new hull facets.
                cr_candidate, _ = compute_covering_radius_and_worst_facet(candidate_pts)
                
                if cr_candidate < best_cr:
                    best_pts = candidate_pts
                    best_cr = cr_candidate
                else:
                    # If it didn't improve globally, maybe we should try a smaller step?
                    # Or just break if we're stagnating.
                    pass
                    
        except Exception:
            pass

    return best_pts
# EVOLVE-BLOCK-END
