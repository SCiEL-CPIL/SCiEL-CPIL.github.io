import time
import numpy as np
import random
from math import gcd
from functools import reduce

DIMENSIONS = [2, 3, 5]

def construct():
    n, m, p = DIMENSIONS
    start_time = time.time()
    deadline = start_time + 140

    # Schoolbook fallback
    def get_schoolbook():
        rank = n * m * p
        U = [[0] * rank for _ in range(n * m)]
        V = [[0] * rank for _ in range(m * p)]
        W = [[0] * rank for _ in range(p * n)]
        col = 0
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    U[i * m + j][col] = 1
                    V[j * p + k][col] = 1
                    W[k * n + i][col] = 1
                    col += 1
        return {"U": U, "V": V, "W": W}

    def validate(U, V, W):
        rank = len(U[0])
        U_arr = np.array(U, dtype=float)
        V_arr = np.array(V, dtype=float)
        W_arr = np.array(W, dtype=float)
        
        for i in range(n):
            for j in range(m):
                for k in range(p):
                    u_val = U_arr[i*m+j]
                    v_val = V_arr[j*p+k]
                    w_val = W_arr[k*n+i]
                    s = np.dot(u_val, v_val * w_val)
                    if abs(s - 1) > 1e-9:
                        return False
        return True

    def solve_diophantine(coeffs, target=1):
        """
        Find integer x such that dot(coeffs, x) = target.
        Returns None if gcd(coeffs) does not divide target.
        """
        g = reduce(gcd, [abs(c) for c in coeffs if c != 0], 0)
        if g == 0:
            return None
        if target % g != 0:
            return None
        
        # Use extended Euclidean algorithm to find one solution
        # We can use a simple search if dimension is small, or use linear programming.
        # Since R is likely < 30, and coeffs are small integers, we can use a heuristic.
        # Or we can use the fact that we just need *some* solution.
        # We can use scipy or numpy to solve a least squares problem and round?
        # No, we need exact.
        
        # Let's find a solution using the extended Euclidean algorithm for 2 variables
        # and set others to 0? Not always possible.
        
        # Better: Use the fact that we can add any vector in the null space.
        # Let's just find *any* integer solution.
        # We can use a simple backtracking or use the property that we can scale.
        
        # For small R, we can try to find a solution with sparse support.
        # Or we can use the following:
        # Find x such that A x = 1.
        # We can use the LLL algorithm if available, but let's stick to standard lib.
        
        # A simple heuristic:
        # 1. Find the index r with max |coeffs[r]|.
        # 2. Try to express 1 as a combination of coeffs[r] and coeffs[r2].
        
        # Actually, since we only need *a* solution, and the entries of W can be large,
        # we can use the following:
        # Solve A x = 1 over integers.
        # This is equivalent to finding a vector in the lattice generated by rows of A (transposed?)
        
        # Let's use a simple randomized approach:
        # Pick random small integers for R-1 variables, solve for the last.
        # If the last is integer, we have a solution.
        
        # However, R can be up to 30.
        # Let's try to find a solution with at most 2 non-zero entries.
        # If gcd(c_i, c_j) == 1, we can find a_i, a_j such that a_i c_i + a_j c_j = 1.
        
        best_x = None
        for r1 in range(len(coeffs)):
            if coeffs[r1] == 0: continue
            for r2 in range(r1 + 1, len(coeffs)):
                if coeffs[r2] == 0: continue
                g = gcd(abs(coeffs[r1]), abs(coeffs[r2]))
                if target % g == 0:
                    # Find a, b such that a*c1 + b*c2 = target
                    # Use extended Euclidean
                    def egcd(a, b):
                        if b == 0:
                            return (a, 1, 0)
                        else:
                            g, x, y = egcd(b, a % b)
                            return (g, y, x - (a // b) * y)
                    
                    g, x, y = egcd(abs(coeffs[r1]), abs(coeffs[r2]))
                    # x * |c1| + y * |c2| = g
                    # We want a * c1 + b * c2 = target
                    # a = x * (target/g) * sign(c1)
                    # b = y * (target/g) * sign(c2)
                    scale = target // g
                    a = x * scale
                    if coeffs[r1] < 0: a = -a
                    b = y * scale
                    if coeffs[r2] < 0: b = -b
                    
                    x_vec = [0] * len(coeffs)
                    x_vec[r1] = a
                    x_vec[r2] = b
                    # Verify
                    if sum(x_vec[i] * coeffs[i] for i in range(len(coeffs))) == target:
                        return x_vec
        return None

    def try_structured_search(target_rank, max_attempts=50000):
        for attempt in range(max_attempts):
            if time.time() > deadline:
                return None
            
            # Generate random U, V with small integers
            # Entries in {-2, -1, 0, 1, 2}
            U = np.random.randint(-2, 3, size=(n*m, target_rank))
            V = np.random.randint(-2, 3, size=(m*p, target_rank))
            
            # Calculate C[i, k, r]
            C = np.zeros((n, p, target_rank), dtype=int)
            for i in range(n):
                for k in range(p):
                    for r in range(target_rank):
                        s = 0
                        for j in range(m):
                            s += U[i*m+j, r] * V[j*p+k, r]
                        C[i, k, r] = s
            
            # Check GCD condition
            valid = True
            W = np.zeros((p*n, target_rank), dtype=float)
            
            for i in range(n):
                for k in range(p):
                    coeffs = C[i, k, :]
                    # Check if gcd(coeffs) is 1 or 2
                    non_zero = [abs(c) for c in coeffs if c != 0]
                    if not non_zero:
                        valid = False
                        break
                    g = reduce(gcd, non_zero)
                    if g not in (1, 2):
                        valid = False
                        break
                    
                    # Solve for W
                    # We need sum_r C[i,k,r] W[k,i,r] = 1
                    # If g=1, we can find integer solution.
                    # If g=2, we can find half-integer solution.
                    # Our solve_diophantine finds integer solution for target=1.
                    # If g=2, we need target=1, which is not divisible by 2.
                    # So we should solve for target=1/2? No, we solve for target=1 with scaled coeffs?
                    # Actually, if g=2, we can find integers w such that sum w_r C_r = 2.
                    # Then W_r = w_r / 2.
                    
                    target = 1
                    if g == 2:
                        target = 2
                        scale_factor = 2.0
                    else:
                        scale_factor = 1.0
                        
                    w_vec = solve_diophantine(coeffs, target)
                    if w_vec is None:
                        valid = False
                        break
                    
                    for r in range(target_rank):
                        W[k*n+i, r] = w_vec[r] / scale_factor
                if not valid:
                    break
            
            if valid:
                U_list = U.tolist()
                V_list = V.tolist()
                W_list = W.tolist()
                
                if validate(U_list, V_list, W_list):
                    return {"U": U_list, "V": V_list, "W": W_list}
        
        return None

    # Try ranks from lower bound upwards
    for rank in range(15, 30):
        if time.time() > deadline:
            break
        result = try_structured_search(rank, max_attempts=20000)
        if result is not None:
            return result

    # Fallback to schoolbook
    return get_schoolbook()
