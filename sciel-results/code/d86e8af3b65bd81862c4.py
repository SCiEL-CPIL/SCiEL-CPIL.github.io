def construct(k, g):
    start_time = time.time()
    deadline = start_time + 115.0  # Safety margin before 120s kill

    # 1. Calculate Moore Bound
    r = (g - 1) // 2
    moore_bound = 1 + k * sum((k - 1) ** i for i in range(r))

    # 2. Fallback: LUW Construction (deterministic, fast)
    best_n, best_edges = construct_luw(k, g)

    # 3. Try Cayley Graph Construction on Z_n x Z_m
    # This is the new strategy: modular arithmetic with sparse linear congruences.
    # We optimize n and m to minimize n*m while ensuring girth >= g.
    try:
        n_cayley, edges_cayley = construct_cayley_grid(k, g, deadline)
        if n_cayley is not None and n_cayley < best_n:
            best_n = n_cayley
            best_edges = edges_cayley
    except Exception:
        pass

    # 4. Try Voltage Graph / Lift Construction
    try:
        n_lift, edges_lift = construct_voltage_lift_optimized(k, g, deadline)
        if n_lift is not None and n_lift < best_n:
            best_n = n_lift
            best_edges = edges_lift
    except Exception:
        pass

    return best_n, best_edges

def construct_luw(k, g):
    # Original LUW logic, kept as fallback
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r_idx, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r_idx]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges

def construct_cayley_grid(k, g, deadline):
    """
    Construct a k-regular Cayley graph on Z_n x Z_m.
    Adjacency is defined by a set of k generators (a, b) in Z_n x Z_m.
    We search for small n, m and generators such that the girth is >= g.
    
    For k=5, we need 5 generators. To ensure regularity and simplicity:
    - No generator is (0,0).
    - No generator is the inverse of another (unless we pair them, but simpler to pick 5 distinct non-inverses or handle symmetry).
    - Actually, for a simple graph, we just need the set of neighbors of 0 to be distinct and not include 0.
    - If g is in S, -g must also be in S for the graph to be undirected? No, if we define adjacency by x ~ x+g, then x ~ x-g is implied if -g is also in S.
    - Wait, if S is the set of generators, the neighbors of v are {v + s | s in S}.
    - For the graph to be undirected, if s in S, then -s must be in S? 
      If s in S, edge (v, v+s). This is same as (v+s, v) which is generated by -s.
      So if S is not symmetric, the graph is directed. We want undirected.
      So S must be symmetric: S = -S.
      If k is odd, we can have one element s such that s = -s (i.e., 2s=0 mod n,m) plus (k-1)/2 pairs.
      Or we can just pick S such that S = -S.
      
    Let's assume k is even for simplicity in this block, or handle odd k by including an element of order 2.
    For k=5, we need 2 pairs and 1 element of order 2.
    Element of order 2: 2*(a,b) = (0,0) mod (n,m).
    
    Strategy:
    Iterate over small n, m.
    For each (n, m), try to find a set S of size k, symmetric, such that girth >= g.
    To speed up, we can precompute the Cayley table or just use BFS on the grid.
    Since n, m are small (we want small n*m), BFS is fast.
    
    We will search for n, m such that n*m is minimized.
    """
    best_n = float('inf')
    best_edges = None
    
    # We want n*m to be small. Let's iterate over total size N from Moore bound upwards?
    # No, Moore bound is 428. LUW gives ~1250.
    # Let's try N from 100 to 1200.
    # But we need n, m to be factors of N? No, n and m are independent dimensions.
    # Total vertices = n * m.
    
    # Let's iterate over n from 10 to 100, m from 10 to 100.
    # If n*m > current best, skip.
    
    # Precompute valid generator sets? Too many.
    # Instead, for each (n, m), we can try to construct a specific S.
    # A common choice for high girth: generators with "large" components.
    
    # Let's try a few heuristic sets of generators for each (n, m).
    
    for n in range(10, 100):
        if time.time() > deadline:
            return best_n, best_edges
        
        for m in range(10, 100):
            total_n = n * m
            if total_n >= best_n:
                continue
            
            # Check if k-regular graph is possible on Z_n x Z_m.
            # Max degree is 2*min(n, m) roughly? No, max degree is n*m - 1.
            # But we need specific structure.
            
            # Try to find a set S of size k.
            # For k=5, we need 5 generators.
            # Let's try random sets of generators, or structured ones.
            
            # Structured: 
            # If n, m are large enough, we can pick small steps.
            # But small steps create short cycles.
            # We need "spread out" generators.
            
            # Let's try a few random attempts for this (n, m).
            found = False
            for _ in range(20):
                if time.time() > deadline:
                    return best_n, best_edges
                
                # Generate random symmetric set S of size k.
                # Ensure no (0,0).
                # Ensure distinct.
                
                S = set()
                # Add pairs (s, -s)
                while len(S) < k - 1:  # Leave room for one order-2 element if k is odd
                    a = random.randint(1, n - 1)
                    b = random.randint(1, m - 1)
                    # Avoid (0,0)
                    if a == 0 and b == 0:
                        continue
                    # Avoid duplicates
                    if (a, b) in S or (-a % n, -b % m) in S:
                        continue
                    S.add((a, b))
                    S.add((-a % n, -b % m))
                
                # If k is odd, add one element of order 2.
                if k % 2 == 1:
                    # Find (a, b) such that 2a=0 mod n, 2b=0 mod m.
                    # a = n/2 if n even, else 0.
                    # b = m/2 if m even, else 0.
                    # We need at least one of n, m to be even for a non-trivial order 2 element?
                    # If n is even, a = n//2 is order 2.
                    # If m is even, b = m//2 is order 2.
                    # If both are odd, only (0,0) has order 1, no order 2.
                    # So if n, m are both odd, we can't have a symmetric set of odd size?
                    # Wait, if n, m are odd, then -1 is not 1 mod n or m.
                    # So s != -s for any s != 0.
                    # So |S| must be even.
                    # Thus, for k=5, we need at least one of n, m to be even.
                    
                    if n % 2 == 0:
                        a = n // 2
                        b = 0
                    elif m % 2 == 0:
                        a = 0
                        b = m // 2
                    else:
                        continue # Skip this (n, m) for odd k
                    
                    # Check if (a, b) is already in S
                    if (a, b) in S:
                        continue
                    S.add((a, b))
                
                # Now S has size k.
                # Check if S is valid (no 0,0, distinct).
                if (0, 0) in S:
                    continue
                if len(S) != k:
                    continue
                
                # Check girth using BFS on the Cayley graph.
                # Vertices are (x, y) in Z_n x Z_m.
                # We only need to check from (0,0) due to symmetry?
                # No, girth is global. But for Cayley graphs, the shortest cycle passing through identity is a good indicator.
                # Actually, we can just do BFS from (0,0) up to depth (g-1)//2.
                # If we find a neighbor of (0,0) at depth < g, we have a short cycle.
                # Wait, a cycle of length L corresponds to a non-backtracking walk of length L from 0 to 0.
                # BFS from 0 finds shortest paths.
                # If dist(0, s) = 1 for s in S.
                # If we find a path 0 -> v1 -> ... -> v_{L-1} -> 0 with L < g, then girth < g.
                # BFS from 0:
                # dist[0] = 0.
                # If we encounter a vertex v that is already visited, and v is not the parent, we found a cycle.
                # Cycle length = dist[u] + dist[v] + 1.
                
                # Let's implement a quick BFS check.
                if _check_cayley_girth(n, m, S, g):
                    # Valid!
                    # Construct edges.
                    edges = []
                    for x in range(n):
                        for y in range(m):
                            v = x * m + y
                            for (a, b) in S:
                                nx = (x + a) % n
                                ny = (y + b) % m
                                u = nx * m + ny
                                if v < u: # Avoid duplicate edges
                                    edges.append((v, u))
                    
                    if total_n < best_n:
                        best_n = total_n
                        best_edges = edges
                    found = True
                    break # Found valid S for this (n, m), move to next (n, m)
            
            # Optional: break if we found a very small one? No, keep searching for smaller n*m.
    
    if best_edges is not None:
        return best_n, best_edges
    return None, None

def _check_cayley_girth(n, m, S, g):
    """
    Check if the Cayley graph on Z_n x Z_m with generators S has girth >= g.
    """
    # BFS from (0,0)
    # dist[(x, y)] = distance from (0,0)
    # parent[(x, y)] = previous vertex
    
    dist = {}
    parent = {}
    queue = deque()
    
    start = (0, 0)
    dist[start] = 0
    parent[start] = None
    queue.append(start)
    
    max_depth = (g - 1) // 2
    
    while queue:
        x, y = queue.popleft()
        d = dist[(x, y)]
        
        if d >= max_depth:
            continue
            
        for (a, b) in S:
            nx = (x + a) % n
            ny = (y + b) % m
            neighbor = (nx, ny)
            
            if neighbor in dist:
                # Found a cycle
                # Length = d + dist[neighbor] + 1
                cycle_len = d + dist[neighbor] + 1
                # Check if this is a backtracking edge (neighbor is parent of (x,y))
                if parent[(x, y)] != neighbor:
                    if cycle_len < g:
                        return False
            else:
                dist[neighbor] = d + 1
                parent[neighbor] = (x, y)
                queue.append(neighbor)
                
    return True

def construct_voltage_lift_optimized(k, g, deadline):
    """
    Optimized voltage graph lift search using DP for girth check.
    """

    def make_circulant_k_reg(n, k):
        """Generate a circulant k-regular graph on n vertices."""
        if k % 2 != 0:
            if n % 2 == 0:
                if (k - 1) // 2 + 1 > n // 2:
                    return None, None
                diffs = list(range(1, (k - 1) // 2 + 1)) + [n // 2]
            else:
                if k >= n:
                    return None, None
                diffs = list(range(1, (k + 1) // 2 + 1))
                if len(diffs) * 2 > n - 1:
                    return None, None
        else:
            if k >= n:
                return None, None
            diffs = list(range(1, k // 2 + 1))
            if len(diffs) * 2 > n - 1:
                return None, None

        edges = set()
        for d in diffs:
            for v in range(n):
                u = (v + d) % n
                edges.add((min(v, u), max(v, u)))

        adj = defaultdict(set)
        for u, v in edges:
            adj[u].add(v)
            adj[v].add(u)

        if all(len(adj[v]) == k for v in range(n)):
            return list(edges), adj
        return None, None

    def make_random_k_reg(n, k):
        """Generate a random k-regular graph on n vertices."""
        if n * k % 2 != 0:
            return None, None
        for _ in range(20):
            stubs = []
            for v in range(n):
                stubs.extend([v] * k)
            random.shuffle(stubs)
            edges = set()
            valid = True
            for i in range(0, n * k, 2):
                u, v = stubs[i], stubs[i+1]
                if u == v:
                    valid = False
                    break
                edge = (min(u,v), max(u,v))
                if edge in edges:
                    valid = False
                    break
                edges.add(edge)
            if valid:
                adj = defaultdict(set)
                for u, v in edges:
                    adj[u].add(v)
                    adj[v].add(u)
                return list(edges), adj
        return None, None

    def check_girth_dp(base_adj, base_edges, voltages, m, g):
        """
        Check if cover has girth >= g using DP on non-backtracking walks.
        Returns True if no closed walk of length < g has voltage sum 0.
        """
        n_base = len(base_adj)
        neighbors = [list(base_adj[v]) for v in range(n_base)]

        # Precompute voltage lookup for speed
        vol_matrix = [[0] * n_base for _ in range(n_base)]
        for (u, v) in base_edges:
            val = voltages[(u, v)]
            vol_matrix[u][v] = val
            vol_matrix[v][u] = (-val) % m

        for L in range(3, g):
            S = {}
            for s in range(n_base):
                for v in neighbors[s]:
                    vol = vol_matrix[s][v]
                    key = (v, s, s)
                    if key in S:
                        S[key].add(vol)
                    else:
                        S[key] = {vol}

            for step in range(2, L + 1):
                S_next = {}
                for (u, v, s), sums in S.items():
                    for w in neighbors[u]:
                        if w == v:
                            continue
                        vol = vol_matrix[u][w]
                        new_sums = set()
                        for x in sums:
                            new_sums.add((x + vol) % m)
                        key = (w, u, s)
                        if key in S_next:
                            S_next[key].update(new_sums)
                        else:
                            S_next[key] = new_sums
                S = S_next

            for (u, v, s), sums in S.items():
                if u == s:
                    if 0 in sums:
                        return False

        return True

    best_result = None

    for base_n in range(10, 40):
        if time.time() > deadline:
            break

        base_edges, base_adj = make_circulant_k_reg(base_n, k)
        if base_edges is None:
            base_edges, base_adj = make_random_k_reg(base_n, k)
        if base_edges is None:
            continue

        if not all(len(base_adj[v]) == k for v in range(base_n)):
            continue

        for m in range(2, 100):
            if time.time() > deadline:
                break

            total_n = m * base_n

            if best_result is not None and total_n >= best_result[0]:
                break

            found_valid = False
            for volt_attempt in range(20):
                if time.time() > deadline:
                    break

                voltages = {}
                for (u, v) in base_edges:
                    val = random.randint(0, m - 1)
                    voltages[(u, v)] = val
                    voltages[(v, u)] = (-val) % m

                if check_girth_dp(base_adj, base_edges, voltages, m, g):
                    cover_edges = []
                    for (u, v) in base_edges:
                        vu = voltages[(u, v)]
                        for t in range(m):
                            u_cover = u * m + t
                            v_cover = v * m + (t + vu) % m
                            cover_edges.append((u_cover, v_cover))

                    if best_result is None or total_n < best_result[0]:
                        best_result = (total_n, cover_edges)
                    found_valid = True
                    break

            if found_valid:
                pass

    return best_result

def construct_greedy_tree(k, g, n_target):
    """
    Try to construct a k-regular graph of girth g on exactly n_target vertices.
    """
    r = (g - 1) // 2
    moore = 1
    for i in range(1, r + 1):
        moore += k * ((k - 1) ** (i - 1))

    if n_target != moore:
        return None, None

    parent = [-1] * n_target
    level = [0] * n_target
    branch = [0] * n_target

    parent[0] = -1
    level[0] = 0

    next_id = 1
    for i in range(k):
        parent[next_id] = 0
        level[next_id] = 1
        branch[next_id] = i
        next_id += 1

    for l in range(2, r + 1):
        nodes_at_prev_level = [v for v in range(next_id) if level[v] == l-1]
        for v in nodes_at_prev_level:
            for j in range(k - 1):
                parent[next_id] = v
                level[next_id] = l
                branch[next_id] = branch[v]
                next_id += 1

    if next_id != n_target:
        return None, None

    leaves = [v for v in range(n_target) if level[v] == r]

    adj = defaultdict(set)
    for v in range(1, n_target):
        u = parent[v]
        adj[u].add(v)
        adj[v].add(u)

    deg_needed = {v: k - len(adj[v]) for v in range(n_target)}

    random.shuffle(leaves)

    for attempt in range(50):
        edges_to_add = []
        used_edges = set()
        success = True

        stubs = []
        for v in leaves:
            for _ in range(deg_needed[v]):
                stubs.append(v)

        random.shuffle(stubs)

        for i in range(0, len(stubs), 2):
            u, v = stubs[i], stubs[i+1]
            if u == v:
                success = False
                break
            if branch[u] == branch[v]:
                success = False
                break
            if v in adj[u]:
                success = False
                break
            if (min(u,v), max(u,v)) in used_edges:
                success = False
                break
            used_edges.add((min(u,v), max(u,v)))
            edges_to_add.append((u, v))

        if not success:
            continue

        final_edges = []
        for v in range(1, n_target):
            final_edges.append((parent[v], v))
        final_edges.extend(edges_to_add)

        deg_check = defaultdict(int)
        for u, v in final_edges:
            deg_check[u] += 1
            deg_check[v] += 1
        if all(deg_check[v] == k for v in range(n_target)):
            return n_target, final_edges

    return None, None
