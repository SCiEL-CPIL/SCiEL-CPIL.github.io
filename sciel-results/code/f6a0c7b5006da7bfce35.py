import time
import random

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    n = 4096
    best_set = []
    
    # Helper to check if x can be added to S
    # S is a list of integers
    # existing_sums is a set of all triple sums of S
    def can_add(x, S, existing_sums):
        # Generate new sums involving x
        # 1. 3x
        # 2. 2x + y for y in S
        # 3. x + y + z for y, z in S, y <= z
        
        new_sums = set()
        
        # 3x
        s3 = 3 * x
        if s3 in existing_sums:
            return False
        new_sums.add(s3)
        
        # 2x + y
        for y in S:
            s2y = 2 * x + y
            if s2y in existing_sums:
                return False
            if s2y in new_sums: # Internal collision
                return False
            new_sums.add(s2y)
            
        # x + y + z
        # We can optimize this by iterating y <= z
        # Note: x is fixed.
        # We must also check internal collisions among these new sums
        # and against previous new_sums (2x+y)
        
        # To avoid O(k^2) set lookups if possible? 
        # k is small, so O(k^2) is fine.
        
        for i in range(len(S)):
            y = S[i]
            # y <= z
            # Sum = x + y + z
            # Check against existing_sums
            # Check against new_sums
            
            # Optimization: 
            # We can precompute pair sums of S? No, S changes.
            
            for j in range(i, len(S)):
                z = S[j]
                s_yz = x + y + z
                if s_yz in existing_sums:
                    return False
                if s_yz in new_sums:
                    return False
                new_sums.add(s_yz)
                
        return True

    # Strategy 1: Greedy smallest-first
    S = []
    existing_sums = set()
    for x in range(1, n + 1):
        if can_add(x, S, existing_sums):
            S.append(x)
            # Update existing_sums
            # We need to add all new sums generated by x to existing_sums
            # This is the expensive part if we don't store them.
            # Let's just recompute or store the list of new sums from can_add?
            # Better: can_add returns the new sums if valid?
            # Or we just re-run the generation logic here.
            
            # To save time, let's modify can_add to return new_sums if valid.
            
            # For now, let's just append and update existing_sums by re-generating.
            # This doubles the work.
            
            # Let's refactor can_add to return (valid, new_sums)
            
    # Let's rewrite with a helper that returns new sums.
    
    def get_new_sums(x, S):
        new_sums = set()
        new_sums.add(3 * x)
        for y in S:
            new_sums.add(2 * x + y)
        for i in range(len(S)):
            y = S[i]
            for j in range(i, len(S)):
                z = S[j]
                new_sums.add(x + y + z)
        return new_sums

    # Run 1: Smallest First
    S1 = []
    sums1 = set()
    for x in range(1, n + 1):
        new_sums = get_new_sums(x, S1)
        if not (new_sums & sums1) and len(new_sums) == 1 + len(S1) + len(S1)*(len(S1)+1)//2:
             # Check internal collisions
             # len(new_sums) should be unique
             # The formula 1 + k + k(k+1)/2 assumes no collisions.
             # If len(new_sums) < expected, there was a collision.
             # So we just check intersection with sums1 and internal uniqueness.
             
             # Actually, get_new_sums returns a set, so internal duplicates are removed.
             # We need to ensure the *number* of unique sums matches the theoretical max.
             expected = 1 + len(S1) + len(S1)*(len(S1)+1)//2
             if len(new_sums) == expected:
                 S1.append(x)
                 sums1.update(new_sums)
                 
    if len(S1) > len(best_set):
        best_set = S1

    # Run 2: Randomized Greedy
    # Use multiple seeds
    for seed in range(100):
        if time.time() > deadline:
            break
        candidates = list(range(1, n + 1))
        random.seed(seed)
        random.shuffle(candidates)
        
        S = []
        existing_sums = set()
        
        for x in candidates:
            if time.time() > deadline:
                break
            new_sums = get_new_sums(x, S)
            expected = 1 + len(S) + len(S)*(len(S)+1)//2
            if len(new_sums) == expected and not (new_sums & existing_sums):
                S.append(x)
                existing_sums.update(new_sums)
                
        if len(S) > len(best_set):
            best_set = S

    return best_set
