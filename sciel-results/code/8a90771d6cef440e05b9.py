import time

# EVOLVE-BLOCK-START
def construct():
    # Deadline guard: 90s wall clock, use 80s limit for safety
    start_time = time.time()
    deadline = start_time + 80.0
    
    # Modular inverses of 1..10 modulo 101
    # pow(x, -1, 101) works in Python 3.8+
    p = 101
    inverses = [0] * 11
    for i in range(1, 11):
        inverses[i] = pow(i, -1, p)
        
    # Precompute all non-empty subsets
    # mask: 1 to (1<<10) - 1
    # We want to assign to each residue r in 0..100 a subset
    # Minimize max size
    
    # List of tuples: (size, mask, residue)
    subsets = []
    for mask in range(1, 1 << 10):
        size = bin(mask).count('1')
        # Calculate sum of inverses
        s = 0
        for i in range(1, 11):
            if mask & (1 << (i - 1)):
                s += inverses[i]
        residue = s % p
        subsets.append((size, mask, residue))
        
    # Sort by size, then by mask to ensure deterministic and smallest-first assignment
    subsets.sort(key=lambda x: (x[0], x[1]))
    
    # assignments: residue -> mask
    assignments = {}
    
    for size, mask, residue in subsets:
        if residue not in assignments:
            assignments[residue] = mask
            if len(assignments) == 101:
                break
                
    # Check if all residues are covered
    # If not, we might need to expand, but with 1023 subsets and 101 residues,
    # and sizes 1..10, it's extremely unlikely we don't cover all.
    # However, if we run out of subsets (we won't), we'd have a problem.
    # The loop above iterates through ALL subsets if needed.
    
    # Construct the final list
    # Row r contains the denominators corresponding to assignments[r]
    result = []
    for r in range(101):
        mask = assignments.get(r)
        if mask is None:
            # Fallback: should not happen
            # Find any subset that gives r
            # This is a safety net
            found = False
            for size, m, res in subsets:
                if res == r:
                    mask = m
                    found = True
                    break
            if not found:
                # This would be a failure of the problem premise
                # But 1023 subsets > 101 residues, so pigeonhole doesn't guarantee coverage
                # but random distribution suggests it.
                # Actually, the set of subset sums might not cover all residues?
                # Let's verify. The group generated by inverses of 1..10 in Z_101.
                # Inverses are distinct. They likely generate the whole group.
                # If not, the task is impossible, but the task implies it's possible.
                # We assume coverage.
                raise RuntimeError(f"Residue {r} not covered")
        
        terms = []
        for i in range(1, 11):
            if mask & (1 << (i - 1)):
                terms.append(i)
        result.append(terms)
        
    return result
# EVOLVE-BLOCK-END
