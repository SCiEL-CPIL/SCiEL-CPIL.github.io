import time
import numpy as np

def construct():
    start_time = time.time()
    deadline = start_time + 55.0  # Safety margin
    
    max_val = 4096
    max_sum = 3 * max_val + 1
    used_sums = np.zeros(max_sum, dtype=bool)
    
    selected = []
    S = np.array([], dtype=np.int32)
    
    def get_new_sums(x, S):
        k = len(S)
        if k == 0:
            return np.array([3*x], dtype=np.int32)
        
        s1 = np.array([3*x], dtype=np.int32)
        s2 = 2*x + S
        i_idx, j_idx = np.triu_indices(k)
        s3 = x + S[i_idx] + S[j_idx]
        return np.concatenate((s1, s2, s3))
    
    def try_add(x):
        nonlocal S, used_sums, selected
        
        new_sums = get_new_sums(x, S)
        
        # Check for duplicates within new sums
        if len(np.unique(new_sums)) != len(new_sums):
            return False
            
        # Check against used_sums
        if np.any(used_sums[new_sums]):
            return False
            
        # If valid, update
        selected.append(x)
        S = np.append(S, x)
        used_sums[new_sums] = True
        return True
    
    def try_swap(remove_idx, add_x):
        """Try to remove element at remove_idx and add add_x"""
        nonlocal S, used_sums, selected
        k = len(S)
        
        # Remove the element
        removed = S[remove_idx]
        S_new = np.delete(S, remove_idx)
        k_new = len(S_new)
        
        # Calculate sums that will be freed
        # We need to remove all sums involving 'removed'
        # This is complex to track incrementally without rebuilding, 
        # so for simplicity in a local search step, we might just check validity of the new set.
        
        # For efficiency, let's just check if adding x to (S - {removed}) is valid.
        # But we also need to ensure that removing 'removed' doesn't break anything (it doesn't, sums are just freed).
        # The constraint is only on the final set.
        
        # Let's simulate the new set
        # We need to check if all triples in (S - {removed}) + {x} are unique.
        # This is equivalent to:
        # 1. All triples in S - {removed} were already unique (they were part of a valid set).
        # 2. New triples involving x must not collide with each other or with existing sums in S - {removed}.
        
        # However, "existing sums in S - {removed}" is a subset of the original used_sums.
        # The original used_sums includes sums involving 'removed'.
        # So we can't just check against used_sums directly because used_sums has "stale" entries for sums involving 'removed'.
        
        # Efficient approach for local search:
        # 1. Compute all sums of the new set: T = (S - {removed}) ∪ {x}
        # 2. Check if all unordered triples of T have unique sums.
        # This is O(k^3) if done naively, but we can be smarter.
        
        # Let's just try to add x to the set S' = S - {removed}.
        # We need a "virtual" used_sums for S'.
        # Rebuilding used_sums for S' is O(k^3).
        # Given k <= 80, k^3 = 512,000. This is fast enough for a few swaps.
        
        # Let's implement a helper to check if a set is valid.
        def is_valid_set(arr):
            n = len(arr)
            if n == 0:
                return True
            sums = set()
            # Iterate over all unordered triples with replacement
            # This is slow in Python. Let's use numpy for the check if possible?
            # No, checking uniqueness of 3-sums is hard to vectorize simply without O(n^3) memory/time.
            # But n is small.
            
            # Optimization: We only need to check new triples if we know the rest is valid.
            # In try_swap, S - {removed} is valid.
            # So we only need to check triples involving x.
            # And we need to ensure these new triples don't collide with triples in S - {removed}.
            
            # Let's compute all sums of triples in S - {removed} that do NOT involve 'removed'.
            # This is still hard to get from the global used_sums.
            
            # Alternative: Just rebuild the validity check for the new set.
            # Since we are in a local search, we can afford O(k^3) checks if we limit the number of swaps.
            
            # Let's do a quick check:
            # 1. Generate all triple sums for T = S_new ∪ {x}
            # 2. Check uniqueness.
            
            # Actually, let's just use the greedy logic but on the new set.
            # Wait, we can just check if x can be added to S_new given that S_new is valid.
            # We need the set of sums generated by S_new.
            
            # Let's compute sums_generated_by_S_new
            # This is O(k^3).
            sums_S_new = set()
            k_n = len(S_new)
            # Triple sums of S_new
            # This is too slow if done in Python loops for every swap.
            
            # Let's stick to a simpler heuristic for the refinement:
            # Try to add a larger number, and if it fails, try to remove a smaller number and retry.
            # But checking validity is the bottleneck.
            
            # Let's just return False for now to avoid complex bugs, and rely on the initial greedy.
            # Or, implement a simple swap check by rebuilding the used_sums for the candidate set.
            
            # Rebuild used_sums for candidate set T
            T = np.append(S_new, x)
            T_sorted = np.sort(T)
            n_t = len(T_sorted)
            candidate_sums = np.zeros(max_sum, dtype=bool)
            
            # Generate all triple sums of T_sorted
            # i <= j <= k
            for i in range(n_t):
                for j in range(i, n_t):
                    for k in range(j, n_t):
                        s = T_sorted[i] + T_sorted[j] + T_sorted[k]
                        if candidate_sums[s]:
                            return False
                        candidate_sums[s] = True
            return True

        # If is_valid_set works, we can use it.
        # But the triple loop is O(n^3). For n=80, 80^3 = 512,000 iterations.
        # In Python, this takes ~0.1s.
        # If we do 100 swaps, that's 10s.
        # We have ~40s left. So we can do ~400 swaps.
        
        if is_valid_set(np.append(S_new, x)):
            # Perform the swap
            selected[remove_idx] = x
            S = np.sort(np.append(S_new, x))
            # Rebuild used_sums
            used_sums[:] = False
            for i in range(len(S)):
                for j in range(i, len(S)):
                    for k in range(j, len(S)):
                        used_sums[S[i] + S[j] + S[k]] = True
            return True
        return False

    # Primary strategy: Greedy from 1
    for x in range(1, max_val + 1):
        if time.time() > deadline:
            break
        try_add(x)
    
    best_set = list(selected)
    best_len = len(best_set)
    
    # Local search refinement: try to swap out smaller elements for larger ones
    # to potentially increase the size or density.
    elapsed = time.time() - start_time
    if elapsed < 40.0:
        import random
        random.seed(42)
        
        # We will try to improve the set by swapping elements.
        # Strategy: Iterate through the set, and for each element, try to replace it
        # with a larger number that allows the set to remain valid.
        # If we can replace an element with a larger one, the set remains the same size.
        # This doesn't increase size, but might allow adding more elements later?
        # No, the size is fixed.
        
        # To increase size, we need to find a "gap" that can be filled.
        # This is hard.
        
        # Alternative: Just try to add more elements by relaxing the "greedy" order?
        # The greedy algorithm adds elements in increasing order.
        # Maybe a different order allows more elements?
        
        # Let's try a randomized greedy:
        # 1. Shuffle the candidate range [1, 4096].
        # 2. Try to add each candidate if it fits.
        
        # This is a different search strategy, but still "greedy-like".
        # Let's try this if we have time.
        
        best_size = len(selected)
        best_set = list(selected)
        
        for restart in range(10):
            if time.time() > deadline - 5:
                break
            
            selected = []
            S = np.array([], dtype=np.int32)
            used_sums = np.zeros(max_sum, dtype=bool)
            
            # Randomize the order of candidates
            candidates = list(range(1, max_val + 1))
            random.shuffle(candidates)
            
            for x in candidates:
                if time.time() > deadline - 5:
                    break
                if try_add(x):
                    pass # try_add updates selected, S, used_sums
            
            if len(selected) > best_size:
                best_size = len(selected)
                best_set = list(selected)
                
    return best_set
