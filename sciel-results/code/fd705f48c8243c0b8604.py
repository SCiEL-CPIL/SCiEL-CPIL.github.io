def _get_rank_20_solution(n=2, m=2, p=5):
    """Schoolbook for 2x2x5. Rank 20."""
    rank = 20
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]

    t = 0
    for j in range(m):
        for k in range(p):
            for i in range(n):
                U[i * m + j][t] = 1
                V[j * p + k][t] = 1
                W[k * n + i][t] = 1
                t += 1

    return {"U": U, "V": V, "W": W}

