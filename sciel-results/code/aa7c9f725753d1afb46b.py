import time
import numpy as np
from scipy.linalg import eigh

def _compute_bands(cell, size=32, num_pw=17, num_k=10, band_max=6):
    """
    Compute the first 'band_max' TM bands for a given cell using plane-wave method.
    Returns (max_omega_4, min_omega_5) in units of a/(2*pi*c).
    """
    # Dielectric function
    eps = np.array(cell, dtype=float)
    eps[eps == 0] = 1.0
    eps[eps == 1] = 12.0
    
    # Inverse dielectric function
    inv_eps = 1.0 / eps
    
    # Plane wave grid
    # We need G vectors such that |k+G| is covered.
    # Let's use a square grid of G vectors centered at 0.
    # num_pw is the half-width of the G grid (including 0).
    # G = (nx, ny) * 2*pi/a.
    # k is in units of 2*pi/a.
    
    g_vals = np.arange(-num_pw, num_pw + 1)
    Gx, Gy = np.meshgrid(g_vals, g_vals, indexing='ij')
    G_flat = np.stack([Gx.ravel(), Gy.ravel()], axis=1)
    num_G = len(G_flat)
    
    # Fourier coefficients of inv_eps
    # inv_eps(x) = sum_G inv_eps_G exp(i G . x)
    # For a pixelated cell, we can compute inv_eps_G directly.
    # inv_eps_G = (1/N^2) sum_{i,j} inv_eps(i,j) exp(-i G . (i,j))
    # Using FFT is efficient.
    # We need to align the pixel grid with the FFT.
    # The cell is size x size.
    # Let's compute the FFT of inv_eps.
    # Note: The plane wave expansion assumes periodicity.
    # The pixels are at (i+0.5, j+0.5) or (i, j)?
    # Usually, the pixel value represents the average over the pixel area.
    # For simplicity, let's assume the pixel value is the value at the center.
    # inv_eps_G = (1/size^2) * sum_{i,j} inv_eps[i,j] * exp(-i 2*pi (Gx*i + Gy*j)/size)
    # This is exactly (1/size^2) * FFT2(inv_eps)[Gx+size//2, Gy+size//2] if we shift.
    
    inv_eps_fft = np.fft.fft2(inv_eps)
    inv_eps_fft = inv_eps_fft / (size * size)
    
    # Extract coefficients for our G grid.
    # The FFT index k corresponds to frequency k/size.
    # G = 2*pi * (n/size). So n = G * size / (2*pi).
    # In our G_flat, G is in units of 2*pi/a. So the integer index is G.
    # Wait, if a is the lattice constant, G = 2*pi * (m, n) / a.
    # The FFT gives frequencies m/size.
    # So the G vector corresponding to FFT index (i, j) is 2*pi * (i/size, j/size) * a?
    # No. The physical domain is [0, a]. Pixels are size x size.
    # Pixel size dx = a/size.
    # Coordinate x_i = i * dx.
    # G . x = 2*pi (m, n) . (i, j) / size.
    # So the FFT coefficient at (i, j) corresponds to G = 2*pi (i, j) / a?
    # Let's check.
    # exp(-i G . x_i) = exp(-i 2*pi (m, n) . (i, j) / size).
    # This matches the DFT definition.
    # So inv_eps_G for G = 2*pi (m, n) / a is inv_eps_fft[m, n] (with appropriate wrapping).
    
    # Map G_flat to FFT indices
    # G_flat contains integer coordinates m, n.
    # We need to wrap them to [0, size).
    fft_idx_m = G_flat[:, 0] % size
    fft_idx_n = G_flat[:, 1] % size
    
    inv_eps_G = inv_eps_fft[fft_idx_m, fft_idx_n]
    
    # Construct the dielectric matrix for a given k
    # H = sum_{G', G''} inv_eps_{G'-G''} |k+G'|^2 delta_{G', G''}
    # Actually, the eigenvalue equation is:
    # sum_{G'} inv_eps_{G-G'} |k+G'|^2 c_{G'} = omega^2 c_G
    # Let A be the matrix. A_{G, G'} = inv_eps_{G-G'} |k+G'|^2
    # Note: inv_eps_{G-G'} is the Fourier coefficient of inv_eps at frequency G-G'.
    
    def get_band_structure(kx, ky):
        # k is in units of 2*pi/a
        k_vec = np.array([kx, ky])
        
        # |k+G|^2
        k_plus_G = G_flat + k_vec
        k_plus_G_sq = np.sum(k_plus_G**2, axis=1)
        
        # Build matrix A
        # A[i, j] = inv_eps_{G_i - G_j} * |k + G_j|^2
        # We need inv_eps_{G_i - G_j} for all pairs.
        # This is a convolution in G-space.
        # Let's compute the difference matrix.
        # G_diff = G_i - G_j
        # We can precompute the Fourier coefficients for all possible differences?
        # Or just compute on the fly.
        
        # Efficient way:
        # For each G_i, we need the vector of inv_eps_{G_i - G_j} for all j.
        # This is a circular convolution of the G-grid with inv_eps_G?
        
        # Let's just build it directly for small num_G.
        # num_G = (2*num_pw+1)^2. If num_pw=10, num_G=441. 441x441 matrix is fine.
        
        A = np.zeros((num_G, num_G), dtype=complex)
        
        for i in range(num_G):
            Gi = G_flat[i]
            for j in range(num_G):
                Gj = G_flat[j]
                G_diff = Gi - Gj
                # Find index of G_diff in G_flat
                # Since G_flat is a regular grid, we can calculate the index directly.
                # G_flat is generated by meshgrid(-num_pw, ..., num_pw).
                # Index in the original grid:
                # idx_m = G_diff[0] + num_pw
                # idx_n = G_diff[1] + num_pw
                # But we need the coefficient inv_eps_{G_diff}.
                # We have inv_eps_G for G in G_flat.
                # Is G_diff in G_flat?
                # G_flat range is [-num_pw, num_pw].
                # G_diff range is [-2*num_pw, 2*num_pw].
                # So G_diff might be outside the G_flat range!
                # We need the Fourier coefficient of inv_eps at G_diff.
                # We can get this from the FFT if |G_diff| < size/2 (Nyquist).
                # If num_pw is small (e.g., 10), and size=32, then 2*num_pw=20 < 16? No.
                # 20 > 16. So some G_diff are aliased or outside FFT range.
                # We must ensure num_pw is small enough such that 2*num_pw < size/2.
                # size=32. size/2=16.
                # If num_pw=7, 2*7=14 < 16. OK.
                # Let's use num_pw=7. num_G = 15^2 = 225.
                
                # Get coefficient from FFT
                m_diff = G_diff[0] % size
                n_diff = G_diff[1] % size
                coeff = inv_eps_fft[m_diff, n_diff]
                
                A[i, j] = coeff * k_plus_G_sq[j]
        
        # Solve A c = omega^2 c
        # A is Hermitian if inv_eps is real and symmetric?
        # inv_eps_{-G} = conj(inv_eps_G).
        # A_{ij} = inv_eps_{G_i-G_j} |k+G_j|^2.
        # A_{ji} = inv_eps_{G_j-G_i} |k+G_i|^2.
        # Is A Hermitian?
        # A_{ij}^* = inv_eps_{G_i-G_j}^* |k+G_j|^2 = inv_eps_{G_j-G_i} |k+G_j|^2.
        # This is not equal to A_{ji} unless |k+G_i|^2 = |k+G_j|^2, which is false.
        # Wait, the eigenvalue problem for TM is:
        # sum_{G'} inv_eps_{G-G'} (k+G')^2 c_{G'} = omega^2 c_G
        # This matrix is NOT Hermitian in general?
        # Actually, the standard formulation is:
        # H_{G, G'} = (k+G)^2 delta_{G,G'} inv_eps_{G-G'} ? No.
        
        # Let's check the standard plane-wave formulation for TM.
        # Maxwell: curl curl E = (omega^2/c^2) epsilon E
        # In Fourier space:
        # (k+G)^2 c_G - sum_{G'} (k+G) . (k+G') / (k+G)^2 * epsilon_{G-G'} c_{G'} = omega^2 c_G ?
        # No, that's for TE.
        
        # For TM (E perpendicular to plane, E_z):
        # -1/epsilon(r) div (1/epsilon(r) grad E_z) = (omega^2/c^2) E_z
        # In Fourier space:
        # sum_{G'} (1/epsilon)_{G-G'} (k+G')^2 c_{G'} = (omega^2/c^2) c_G
        # Let A_{G, G'} = (1/epsilon)_{G-G'} (k+G')^2.
        # Is A Hermitian?
        # A_{G, G'}^* = (1/epsilon)_{G-G'}^* (k+G')^2 = (1/epsilon)_{G'-G} (k+G')^2.
        # A_{G', G} = (1/epsilon)_{G'-G} (k+G)^2.
        # They are not equal.
        
        # However, the operator is self-adjoint with respect to a weighted inner product?
        # Or is my matrix construction wrong?
        
        # Let's look at the standard code (e.g., from Joannopoulos book).
        # The matrix is H_{G, G'} = (k+G) . (k+G') / epsilon_{G-G'} ?
        # No.
        
        # Correct TM formulation:
        # The eigenvalue equation is:
        # sum_{G'} [(k+G) . (k+G') / epsilon_{G-G'}] c_{G'} = (omega a / 2pi c)^2 c_G
        # Wait, this is for TE?
        
        # Let's derive it.
        # E = E_z z-hat.
        # H = -i/omega mu0 curl E.
        # curl E = (dE_z/dy, -dE_z/dx, 0).
        # div H = 0 is satisfied.
        # curl H = i omega epsilon E.
        # curl (curl E) = -grad^2 E.
        # -1/epsilon grad^2 E = (omega^2/c^2) E.
        # grad^2 E = sum_G (k+G)^2 c_G exp(i(k+G).r).
        # 1/epsilon grad^2 E = sum_G' (1/epsilon)_{G'-G} sum_G (k+G)^2 c_G exp(i(k+G').r) ?
        # Product of two Fourier series:
        # (1/epsilon(r)) (grad^2 E(r)) = sum_{G1} (1/epsilon)_{G1} exp(i G1 r) sum_{G2} (k+G2)^2 c_{G2} exp(i (k+G2) r)
        # = sum_{G1, G2} (1/epsilon)_{G1} (k+G2)^2 c_{G2} exp(i (G1 + k + G2) r)
        # We want the coefficient of exp(i (k+G) r).
        # So G1 + G2 = G => G1 = G - G2.
        # Coeff = sum_{G2} (1/epsilon)_{G-G2} (k+G2)^2 c_{G2}.
        # Equation: sum_{G'} (1/epsilon)_{G-G'} (k+G')^2 c_{G'} = (omega^2/c^2) c_G.
        
        # So my matrix A_{G, G'} = (1/epsilon)_{G-G'} (k+G')^2 is correct.
        # Is it Hermitian?
        # A_{G, G'} = inv_eps_{G-G'} (k+G')^2.
        # A_{G', G} = inv_eps_{G'-G} (k+G)^2.
        # A_{G, G'}^* = inv_eps_{G-G'}^* (k+G')^2 = inv_eps_{G'-G} (k+G')^2.
        # So A is NOT Hermitian.
        
        # However, the eigenvalues are real.
        # We can use scipy.linalg.eig or eigh?
        # If A is not Hermitian, eigh is invalid.
        # But we can transform it to a Hermitian problem.
        # Let D be a diagonal matrix with D_{G,G} = (k+G)^2.
        # Then A = S D, where S_{G,G'} = inv_eps_{G-G'}. S is Hermitian.
        # A c = omega^2 c => S D c = omega^2 c.
        # Let c = D^{-1/2} y.
        # S D D^{-1/2} y = omega^2 D^{-1/2} y
        # S D^{1/2} y = omega^2 D^{-1/2} y
        # Multiply by D^{1/2}:
        # D^{1/2} S D^{1/2} y = omega^2 y.
        # B = D^{1/2} S D^{1/2} is Hermitian.
        # B_{G, G'} = sqrt((k+G)^2) inv_eps_{G-G'} sqrt((k+G')^2).
        
        # So we should construct B and use eigh.
        
        k_plus_G_sq = np.sum(k_plus_G**2, axis=1)
        # Ensure positive
        k_plus_G_sq = np.maximum(k_plus_G_sq, 1e-12)
        sqrt_k_plus_G = np.sqrt(k_plus_G_sq)
        
        B = np.zeros((num_G, num_G), dtype=complex)
        for i in range(num_G):
            Gi = G_flat[i]
            for j in range(num_G):
                Gj = G_flat[j]
                G_diff = Gi - Gj
                m_diff = G_diff[0] % size
                n_diff = G_diff[1] % size
                coeff = inv_eps_fft[m_diff, n_diff]
                B[i, j] = sqrt_k_plus_G[i] * coeff * sqrt_k_plus_G[j]
        
        # B is Hermitian
        # Solve B y = omega^2 y
        vals, vecs = eigh(B, subset_by_index=[0, band_max-1])
        return vals
    
    # Sample k-points in irreducible BZ
    # Square BZ: kx, ky in [0, 1] (units 2pi/a).
    # Irreducible: kx >= ky, kx+ky <= 1? No, 0<=ky<=kx<=1 and kx+ky<=1?
    # Symmetry: C4v.
    # Triangle: (0,0) to (0.5, 0.5) to (0.5, 0) ?
    # Gamma (0,0), M (0.5, 0.5), X (0.5, 0).
    # Path: Gamma-X-M-Gamma.
    # We want the global min of band 5 and max of band 4.
    # Sample points along the boundary and interior.
    
    max_omega_4 = 0.0
    min_omega_5 = float('inf')
    
    # Define a set of k-points
    # 1. Gamma (0,0)
    # 2. X (0.5, 0)
    # 3. M (0.5, 0.5)
    # 4. Midpoints and random points in the triangle
    
    k_points = []
    # Grid in the triangle
    for i in range(num_k):
        for j in range(num_k):
            # Map to triangle
            # Use barycentric or simple mapping
            # Let's just use a dense grid and filter
            pass
            
    # Simpler: specific high symmetry points + random
    k_points.append((0.0, 0.0))
    k_points.append((0.5, 0.0))
    k_points.append((0.5, 0.5))
    k_points.append((0.25, 0.0))
    k_points.append((0.25, 0.25))
    k_points.append((0.5, 0.25))
    
    # Add some random points in the irreducible zone
    # Condition: 0 <= ky <= kx <= 0.5 AND kx + ky <= 0.5? No.
    # The irreducible zone for C4v in the first BZ quadrant (0,0)-(1,0)-(1,1)-(0,1)
    # is the triangle (0,0)-(0.5,0)-(0.5,0.5).
    # Condition: 0 <= ky <= kx <= 0.5.
    
    rng = np.random.default_rng(42)
    for _ in range(20):
        kx = rng.uniform(0, 0.5)
        ky = rng.uniform(0, kx)
        k_points.append((kx, ky))
    
    for kx, ky in k_points:
        vals = get_band_structure(kx, ky)
        # vals are omega^2
        # We want omega
        omegas = np.sqrt(vals)
        if len(omegas) >= 5:
            max_omega_4 = max(max_omega_4, omegas[3])
            min_omega_5 = min(min_omega_5, omegas[4])
            
    if min_omega_5 == float('inf'):
        return 0.0, 0.0
        
    return max_omega_4, min_omega_5

def _score_cell(cell):
    """
    Calculate the gap-midgap ratio.
    """
    max_4, min_5 = _compute_bands(cell, num_pw=7, num_k=5, band_max=6)
    if min_5 == 0 or max_4 == 0:
        return 0.0
    gap = min_5 - max_4
    midgap = min_5 + max_4
    if midgap == 0:
        return 0.0
    return 2.0 * gap / midgap

def _make_cell_from_rings(size, ring_bits):
    cell = [[0] * size for _ in range(size)]
    half = size / 2.0
    for i in range(size):
        dx = abs(i - (size - 1) / 2.0)
        for j in range(size):
            dy = abs(j - (size - 1) / 2.0)
            r = int(max(dx, dy))
            if r < len(ring_bits):
                cell[i][j] = ring_bits[r]
    return cell

def design(problem):
    size = problem["pixels"]
    t0 = time.time()
    deadline = t0 + 110.0

    # 1. Generate Seed (Circle)
    seed_cell = [[0] * size for _ in range(size)]
    for i in range(size):
        x = (i + 0.5) / size - 0.5
        for j in range(size):
            y = (j + 0.5) / size - 0.5
            if x * x + y * y < 0.2 ** 2:
                seed_cell[i][j] = 1

    best_cell = seed_cell
    best_score = _score_cell(seed_cell)
    
    # 2. Generate Candidates
    candidates = [seed_cell]
    
    # Square rods
    for r in range(3, 8):
        rings = [1 if i < r else 0 for i in range(size//2)]
        candidates.append(_make_cell_from_rings(size, rings))
        
    # Checkerboard
    checker = [[0]*size for _ in range(size)]
    for i in range(size):
        for j in range(size):
            if (i//2 + j//2) % 2 == 0:
                checker[i][j] = 1
    candidates.append(checker)
    
    # 3. Evaluate Candidates
    for cell in candidates:
        if time.time() > deadline - 10:
            break
        score = _score_cell(cell)
        if score > best_score:
            best_score = score
            best_cell = [row[:] for row in cell]
            
    # 4. Local Search (Hill Climbing)
    # Flip pixels in symmetric orbits to improve score
    # We need to identify orbits under C4v symmetry.
    # An orbit is a set of pixels that map to each other under symmetry.
    # If we flip all pixels in an orbit, symmetry is preserved.
    
    # Precompute orbits
    # Represent cell as 1D array for speed?
    # Let's stick to 2D list but use numpy for scoring?
    # _score_cell takes a 2D list.
    
    # Generate all orbits
    orbits = []
    visited = set()
    for i in range(size):
        for j in range(size):
            if (i, j) in visited:
                continue
            orbit = []
            # Generate symmetry equivalents
            # (i, j)
            # (size-1-i, j) ? No, reflection about center.
            # Center is (size-1)/2.
            # i' = size-1-i.
            # j' = size-1-j.
            # Rotations:
            # 90 deg: (i, j) -> (j, size-1-i)
            # 180 deg: (i, j) -> (size-1-i, size-1-j)
            # 270 deg: (i, j) -> (size-1-j, i)
            
            pts = [
                (i, j),
                (j, size-1-i),
                (size-1-i, size-1-j),
                (size-1-j, i),
                (size-1-i, j),
                (j, i),
                (size-1-i, size-1-j), # Duplicate of 180
                (size-1-j, size-1-i)
            ]
            # Unique points
            orbit = list(set(pts))
            # Mark visited
            for p in orbit:
                visited.add(p)
            orbits.append(orbit)
            
    # Shuffle orbits to avoid bias
    np.random.seed(42)
    np.random.shuffle(orbits)
    
    current_cell = [row[:] for row in best_cell]
    current_score = best_score
    
    # Hill climbing
    # Try flipping each orbit
    # If score improves, accept.
    # Limit number of flips to fit in time.
    
    max_flips = 500
    flips_done = 0
    
    while flips_done < max_flips and time.time() < deadline - 5:
        improved = False
        # Try a random subset of orbits? Or all?
        # All orbits is too many (32*32 / orbit_size).
        # Orbit size is usually 8. 1024/8 = 128 orbits.
        # 128 evaluations per iteration.
        # Each evaluation takes ~0.1s?
        # 128 * 0.1 = 12.8s per iteration.
        # We have 100s. So ~7 iterations.
        
        # Let's try all orbits in one pass.
        for orbit in orbits:
            if time.time() > deadline - 5:
                break
            # Flip orbit
            for (r, c) in orbit:
                current_cell[r][c] = 1 - current_cell[r][c]
                
            new_score = _score_cell(current_cell)
            
            if new_score > current_score:
                current_score = new_score
                if new_score > best_score:
                    best_score = new_score
                    best_cell = [row[:] for row in current_cell]
                improved = True
            else:
                # Revert
                for (r, c) in orbit:
                    current_cell[r][c] = 1 - current_cell[r][c]
                    
        flips_done += 1
        if not improved:
            # Stagnation? Try random restarts or break.
            # Let's break to save time for other candidates?
            # Or try a few random flips?
            break
            
    return best_cell

