import time
import random
import math

_BEST = None
_DEADLINE = time.time() + 110.0

def _generate_initial(k, n_rows, rng):
    """
    Generate a valid initial set of rows using a spread-out greedy strategy.
    This ensures we start in a valid state for SA.
    """
    used_diffs = set()
    rows = []
    for _ in range(n_rows):
        row = [0]
        x = 0
        # Spread out initial points to avoid immediate collisions and allow room
        # We aim for a roughly uniform distribution in [0, estimated_scope]
        # A simple heuristic: step size ~ 2*k initially, then refine
        while len(row) < k + 1:
            # Try to place next point
            # We search in a window to keep it compact but valid
            found = False
            # Start from x+1, but maybe jump a bit to avoid tight clusters
            start = x + 1
            # Limit search window to avoid O(N^2) blowup in initial gen
            # If we can't find one in window, expand
            window = 50 
            for attempt in range(10):
                end = x + 1 + window * (attempt + 1)
                for t in range(start, end + 1):
                    new_diffs = {t - a for a in row}
                    if not (new_diffs & used_diffs):
                        row.append(t)
                        used_diffs.update(new_diffs)
                        x = t
                        found = True
                        break
                if found:
                    break
            if not found:
                # Fallback: force placement by increasing x until valid
                t = x + 1
                while True:
                    new_diffs = {t - a for a in row}
                    if not (new_diffs & used_diffs):
                        row.append(t)
                        used_diffs.update(new_diffs)
                        x = t
                        break
                    t += 1
        rows.append(row)
    return rows

def _get_scope(rows):
    return max(max(r) for r in rows)

def _validate_move(row, idx, new_val, used_diffs_global, row_diffs_local):
    """
    Check if moving row[idx] to new_val is valid.
    row: list of ints
    idx: index of element to change
    new_val: new value
    used_diffs_global: set of all diffs in all rows EXCEPT this row's current diffs? 
                   No, better to pass the set of diffs for this row to remove, then add new.
    Actually, for speed, we pre-compute the diffs of the current row.
    
    Returns: (is_valid, new_row_diffs)
    """
    # Remove old diffs
    old_val = row[idx]
    old_diffs = set()
    for i, a in enumerate(row):
        if i != idx:
            d = abs(a - old_val)
            old_diffs.add(d)
            
    # Check if new_val is valid within the row
    # 1. Strictly increasing?
    if idx > 0 and new_val <= row[idx-1]:
        return False, None
    if idx < len(row) - 1 and new_val >= row[idx+1]:
        return False, None
        
    # 2. Internal collisions in row
    new_diffs = set()
    for i, a in enumerate(row):
        if i != idx:
            d = abs(a - new_val)
            if d in new_diffs:
                return False, None
            new_diffs.add(d)
            
    # 3. Global collisions
    # We need to check if any d in new_diffs is in (used_diffs_global - old_diffs)
    # used_diffs_global contains ALL diffs from ALL rows.
    # We must exclude the diffs that were generated by the old_val in this row.
    # But used_diffs_global is a set. We can't easily subtract.
    # Strategy: Pass a set of 'forbidden' diffs. 
    # forbidden = used_diffs_global - old_diffs
    # If new_diffs & forbidden is empty, it's valid.
    
    # To avoid creating 'forbidden' set every time (expensive), 
    # we can check: for d in new_diffs: if d in used_diffs_global and d not in old_diffs: invalid.
    
    for d in new_diffs:
        if d in used_diffs_global:
            if d not in old_diffs:
                return False, None
                
    return True, new_diffs

def _simulated_annealing(rows, k, n_rows, rng, time_limit):
    """
    Perform SA on the set of rows.
    """
    global _BEST, _DEADLINE
    
    # Deep copy
    cur_rows = [list(r) for r in rows]
    cur_scope = _get_scope(cur_rows)
    
    # Precompute all diffs
    all_diffs = set()
    row_diffs = []
    for r in cur_rows:
        r_d = set()
        for i in range(len(r)):
            for j in range(i+1, len(r)):
                d = r[j] - r[i]
                r_d.add(d)
                all_diffs.add(d)
        row_diffs.append(r_d)
        
    best_rows = [list(r) for r in cur_rows]
    best_scope = cur_scope
    
    T = 100.0 # Initial temperature
    T_min = 0.1
    alpha = 0.995 # Cooling rate
    
    start_time = time.time()
    
    while time.time() < time_limit:
        # Choose a random row and a random index
        r_idx = rng.randint(0, n_rows - 1)
        row = cur_rows[r_idx]
        # Don't move 0 (index 0)
        if len(row) <= 1:
            continue
        i_idx = rng.randint(1, len(row) - 1)
        
        old_val = row[i_idx]
        
        # Propose a new value
        # Bias towards reducing scope if we are high, or random local move
        if rng.random() < 0.5:
            # Try to move inwards (reduce scope potential)
            # Range: (row[i_idx-1], row[i_idx+1])
            lo = row[i_idx-1] + 1
            hi = row[i_idx+1] - 1 if i_idx < len(row)-1 else cur_scope
            if lo > hi:
                continue
            # Sample a few candidates
            candidates = []
            for _ in range(10):
                cand = rng.randint(lo, hi)
                candidates.append(cand)
        else:
            # Random local move
            delta = rng.randint(-5, 5)
            cand = old_val + delta
            # Ensure bounds
            if i_idx > 0 and cand <= row[i_idx-1]:
                continue
            if i_idx < len(row)-1 and cand >= row[i_idx+1]:
                continue
            candidates = [cand]
            
        moved = False
        for new_val in candidates:
            if new_val == old_val:
                continue
                
            # Validate
            valid, new_row_diffs = _validate_move(row, i_idx, new_val, all_diffs, row_diffs[r_idx])
            if not valid:
                continue
                
            # Calculate new scope
            # Only the max of this row might change
            old_row_max = max(row)
            # Update row temporarily to find max? 
            # new_row_max = max(row[:i_idx] + [new_val] + row[i_idx+1:])
            # But we can just check: if new_val > old_row_max, new_scope = max(cur_scope, new_val)
            # else if old_val == old_row_max and no other element is max, new_scope might decrease.
            
            # Let's just compute new scope properly for accuracy in acceptance
            # Since k is small (6 elements), max() is fast.
            temp_row = row[:]
            temp_row[i_idx] = new_val
            new_row_max = max(temp_row)
            
            # Update global scope
            # If this row had the global max, and we reduced it, we need to check other rows.
            # For simplicity, if new_row_max < cur_scope, we don't know if scope decreases unless this row WAS the max holder.
            # Let's track which row holds the max.
            # Actually, just calculating max of all rows is O(N*K). N=7, K=6. 42 ops. Fast enough.
            new_scope = cur_scope
            if new_row_max > cur_scope:
                new_scope = new_row_max
            else:
                # Check if scope decreases
                # Only possible if old_val was the global max
                if old_val == cur_scope:
                    # Recalculate global max
                    new_scope = max(max(r) for r in cur_rows) # This uses old row for others, but we are changing this row.
                    # Better:
                    max_others = max(max(r) for j, r in enumerate(cur_rows) if j != r_idx)
                    new_scope = max(new_row_max, max_others)
            
            delta_e = new_scope - cur_scope
            
            # Acceptance
            if delta_e <= 0 or rng.random() < math.exp(-delta_e / T):
                # Accept move
                # Update data structures
                # 1. Update all_diffs
                old_row_diffs = row_diffs[r_idx]
                # Remove old diffs
                for d in old_row_diffs:
                    all_diffs.discard(d)
                # Add new diffs
                for d in new_row_diffs:
                    all_diffs.add(d)
                row_diffs[r_idx] = new_row_diffs
                
                # 2. Update row
                row[i_idx] = new_val
                
                # 3. Update scope
                cur_scope = new_scope
                
                # Track best
                if cur_scope < best_scope:
                    best_scope = cur_scope
                    best_rows = [list(r) for r in cur_rows]
                    if _BEST is None or best_scope < _BEST[0]:
                        _BEST = (best_scope, [list(r) for r in best_rows])
                        
                moved = True
                break
                
        if not moved:
            # Cooling
            T *= alpha
            if T < T_min:
                T = T_min
                # Optional: Restart with new initial if stuck? 
                # For now, just keep going at min T.
        
        # Check deadline
        if time.time() > _DEADLINE:
            break
            
    return best_rows, best_scope

def construct(n_rows, k):
    global _BEST, _DEADLINE
    _BEST = None
    _DEADLINE = time.time() + 110.0
    
    rng = random.Random()
    
    # 1. Generate initial valid set
    initial_rows = _generate_initial(k, n_rows, rng)
    initial_scope = _get_scope(initial_rows)
    _BEST = (initial_scope, [list(r) for r in initial_rows])
    
    # 2. Run SA
    # We have ~110s. Let's use 100s for SA.
    sa_time_limit = time.time() + 100.0
    best_rows, best_scope = _simulated_annealing(initial_rows, k, n_rows, rng, sa_time_limit)
    
    # Update best if SA found something better
    if best_scope < _BEST[0]:
        _BEST = (best_scope, [list(r) for r in best_rows])
        
    # 3. Final Local Search Polish (optional, if time remains)
    if time.time() < _DEADLINE - 5:
        # Simple hill climbing on the best found
        current_rows = [list(r) for r in _BEST[1]]
        current_scope = _BEST[0]
        
        # Re-diff for local search
        all_diffs = set()
        row_diffs = []
        for r in current_rows:
            r_d = set()
            for i in range(len(r)):
                for j in range(i+1, len(r)):
                    d = r[j] - r[i]
                    r_d.add(d)
                    all_diffs.add(d)
            row_diffs.append(r_d)
            
        improved = True
        while improved and time.time() < _DEADLINE - 2:
            improved = False
            for r_idx in range(n_rows):
                if time.time() > _DEADLINE - 2: break
                row = current_rows[r_idx]
                for i_idx in range(1, len(row)):
                    if time.time() > _DEADLINE - 2: break
                    old_val = row[i_idx]
                    # Try to move to smaller valid values
                    # Search downwards from old_val to row[i_idx-1]+1
                    lo = row[i_idx-1] + 1
                    # Also check upwards if it helps reduce global max? No, local search usually minimizes.
                    # If we move down, scope might decrease.
                    # If we move up, scope might increase (bad) unless it allows others to move down later.
                    # Stick to "move to any valid position" and check scope.
                    
                    # Try a few random valid positions in the allowed range
                    # Allowed range: (row[i_idx-1], row[i_idx+1])
                    hi = row[i_idx+1] - 1 if i_idx < len(row)-1 else current_scope
                    
                    if lo >= hi:
                        continue
                        
                    # Sample candidates
                    tried = set()
                    for _ in range(20):
                        new_val = rng.randint(lo, hi)
                        if new_val in tried:
                            continue
                        tried.add(new_val)
                        
                        valid, new_row_diffs = _validate_move(row, i_idx, new_val, all_diffs, row_diffs[r_idx])
                        if not valid:
                            continue
                        
                        temp_row = row[:]
                        temp_row[i_idx] = new_val
                        new_row_max = max(temp_row)
                        
                        new_scope = current_scope
                        if new_row_max > current_scope:
                            new_scope = new_row_max
                        else:
                            if old_val == current_scope:
                                max_others = max(max(r) for j, r in enumerate(current_rows) if j != r_idx)
                                new_scope = max(new_row_max, max_others)
                            
                        if new_scope < current_scope:
                            # Accept improvement
                            # Update structures
                            for d in row_diffs[r_idx]:
                                all_diffs.discard(d)
                            for d in new_row_diffs:
                                all_diffs.add(d)
                            row_diffs[r_idx] = new_row_diffs
                            
                            row[i_idx] = new_val
                            current_scope = new_scope
                            _BEST = (current_scope, [list(r) for r in current_rows])
                            improved = True
                            break # Restart loop for this row? Or continue?
                            # Continue to next i_idx to see if we can improve more in same row
                            
    if _BEST is not None:
        return _BEST[1]
    return initial_rows
