_RANK17_VALID = _validate(_U17, _V17, _W17, _n, _m, _p)


def construct():
    n, m, p = DIMENSIONS
    if _RANK17_VALID:
        return {"U": _U17, "V": _V17, "W": _W17}
    # Fallback: guaranteed-correct schoolbook.
    return _schoolbook(n, m, p)
