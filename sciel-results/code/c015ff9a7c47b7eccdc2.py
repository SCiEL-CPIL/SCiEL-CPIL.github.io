import time

def synthesize(matrix, depth_limit):
    start_time = time.time()
    # 90s wall clock limit. Use a generous but safe internal deadline.
    DEADLINE = start_time + 55.0

    m = len(matrix)
    n = len(matrix[0]) if m > 0 else 0

    if m == 0:
        return {'gates': [], 'outputs': []}

    # Wire assignment:
    # Inputs: 0 .. n-1
    # Constant zero: n
    # Gates produce wires: n+1, n+2, ...

    next_wire = n + 1
    gates = []

    # memo: bitmask -> wire_id
    memo = {}
    # Initialize with inputs and zero
    for j in range(n):
        memo[1 << j] = j
    memo[0] = n

    def elapsed():
        return time.time() - start_time

    def add_gate(a, b):
        nonlocal next_wire
        gates.append([a, b])
        w = next_wire
        next_wire += 1
        return w

    def build_tree_from_bits(bits):
        """
        Build a balanced XOR tree from a list of input indices.
        Memoizes intermediate results to allow sharing.
        Returns the final wire.
        """
        if not bits:
            return n
        if len(bits) == 1:
            return bits[0]

        # Start with wires and their corresponding masks
        current_wires = []
        current_masks = []
        for b in bits:
            mask = 1 << b
            if mask in memo:
                current_wires.append(memo[mask])
            else:
                current_wires.append(b)
            current_masks.append(mask)

        while len(current_wires) > 1:
            next_wires = []
            next_masks = []
            for i in range(0, len(current_wires), 2):
                if i + 1 < len(current_wires):
                    a_w = current_wires[i]
                    a_m = current_masks[i]
                    b_w = current_wires[i + 1]
                    b_m = current_masks[i + 1]

                    new_m = a_m ^ b_m
                    if new_m in memo:
                        next_wires.append(memo[new_m])
                    else:
                        new_w = add_gate(a_w, b_w)
                        memo[new_m] = new_w
                        next_wires.append(new_w)
                    next_masks.append(new_m)
                else:
                    next_wires.append(current_wires[i])
                    next_masks.append(current_masks[i])
            current_wires = next_wires
            current_masks = next_masks

        return current_wires[0]

    def compute_mask(mask):
        """
        Compute the wire for the given bitmask.
        Uses memoization.
        Strategy:
        1. If in memo, return it.
        2. Search for a best existing mask M in memo such that (mask ^ M) has minimal popcount.
        3. If the remainder is in memo, XOR the two wires.
        4. If not, compute the remainder (recursively or via tree) and XOR.
        """
        if mask in memo:
            return memo[mask]

        if mask == 0:
            return n

        # Check deadline
        if elapsed() > DEADLINE - 2.0:
            # Fallback: direct tree construction
            bits = [j for j in range(n) if (mask >> j) & 1]
            w = build_tree_from_bits(bits)
            memo[mask] = w
            return w

        # Find best M
        best_M = 0
        best_rem = mask
        min_pop = mask.bit_count()

        # Optimization: Iterate over memo keys.
        # For n=16, memo size can grow, but usually stays manageable (< 1000s) for 16x16.
        # We want to find M that minimizes popcount(mask ^ M).
        # If we find M such that popcount(mask ^ M) == 1, we stop (best possible non-zero remainder).
        # Note: popcount 0 means mask == M, which is handled by the memo check at the start.

        # To speed up search, we can prioritize masks with high popcount or similar structure?
        # Simple iteration is O(|memo|).
        # If |memo| is large, this can be slow.
        # However, for 16x16, the number of unique linear combinations generated by the rows
        # is at most 2^16 = 65536. But we only generate what we need.
        # With greedy sharing, memo size should be much smaller.

        for M in memo.keys():
            rem = mask ^ M
            pc = rem.bit_count()
            if pc < min_pop:
                min_pop = pc
                best_M = M
                best_rem = rem
                if pc == 1:
                    break # Best possible

        # Compute remainder
        if best_rem in memo:
            w_rem = memo[best_rem]
        else:
            if best_M == 0:
                # No good base found, build from bits
                bits = [j for j in range(n) if (best_rem >> j) & 1]
                w_rem = build_tree_from_bits(bits)
            else:
                # Recursive call
                # Ensure termination: best_rem < mask in popcount?
                # min_pop < mask.bit_count() because best_M != 0 implies rem != mask?
                # If best_M != 0, rem = mask ^ M.
                # popcount(rem) can be larger than popcount(mask) if M has bits not in mask.
                # But we chose M to MINIMIZE popcount(rem).
                # So min_pop <= mask.bit_count() (since M=0 is a candidate).
                # If min_pop == mask.bit_count(), best_M might be 0 or another M with same popcount.
                # If best_M != 0 and min_pop == mask.bit_count(), then popcount(rem) == popcount(mask).
                # This doesn't guarantee termination by popcount reduction.
                # However, the set of masks in memo is finite.
                # We should check if we are in a loop?
                # Actually, if best_M != 0, then rem != mask.
                # And rem is a different mask.
                # Since we add mask to memo at the end, and rem is computed before,
                # if rem is not in memo, it will be computed.
                # The recursion depth is bounded by the number of unique masks.
                w_rem = compute_mask(best_rem)

        w_m = memo[best_M]
        w_new = add_gate(w_m, w_rem)
        memo[mask] = w_new
        return w_new

    # Convert matrix to row masks
    row_masks = []
    for i in range(m):
        mask = 0
        for j in range(n):
            if matrix[i][j] % 2 == 1:
                mask |= (1 << j)
        row_masks.append(mask)

    # Sort rows by popcount descending to build strong bases early
    # This helps in finding good M for subsequent rows.
    sorted_indices = sorted(range(m), key=lambda i: row_masks[i].bit_count(), reverse=True)

    outputs = [0] * m
    computed = [False] * m

    for idx in sorted_indices:
        if elapsed() > DEADLINE - 5.0:
            # Fast path for remaining rows: direct tree if not in memo
            mask = row_masks[idx]
            if mask in memo:
                outputs[idx] = memo[mask]
            else:
                bits = [j for j in range(n) if (mask >> j) & 1]
                w = build_tree_from_bits(bits)
                memo[mask] = w
                outputs[idx] = w
            computed[idx] = True
        else:
            w = compute_mask(row_masks[idx])
            outputs[idx] = w
            computed[idx] = True

    # Fill any uncomputed (should not happen if loop completes)
    for i in range(m):
        if not computed[i]:
            mask = row_masks[i]
            if mask in memo:
                outputs[i] = memo[mask]
            else:
                bits = [j for j in range(n) if (mask >> j) & 1]
                w = build_tree_from_bits(bits)
                memo[mask] = w
                outputs[i] = w

    return {'gates': gates, 'outputs': outputs}
# EVOLVE-BLOCK-END
