import time
import itertools
import numpy as np

def _ball_indices(q, n, radius):
    """
    Precompute, for each word index, the list of indices within Hamming distance <= radius.
    Returns a list of lists.
    """
    total = q ** n
    # Map index -> tuple for generation, but we can work with integers
    # For q=3, n=8, total=6561.
    # We need to map integer index to word.
    # Let's precompute neighbors for each integer index.
    
    # To be fast, we can precompute the "differences" for radius 1.
    # For each index i, neighbors are i itself and i +/- q^j (mod q^n logic is tricky with carry)
    # Better: convert i to base-q digits, modify, convert back.
    
    # Precompute digit vectors? 6561 * 8 integers is fine.
    words = np.zeros((total, n), dtype=np.int8)
    for i in range(total):
        x = i
        for j in range(n - 1, -1, -1):
            words[i, j] = x % q
            x //= q
            
    balls = []
    # Precompute powers of q for fast index calculation?
    # Or just use the words array.
    
    # For radius 1:
    # Neighbors of i:
    # 1. i itself
    # 2. For each position j, change digit d to d' != d.
    #    New index = i + (d' - d) * q^j
    
    powers = [1] * n
    for j in range(1, n):
        powers[j] = powers[j-1] * q
        
    for i in range(total):
        neighbors = {i}
        w = words[i]
        for j in range(n):
            base_diff = powers[j]
            current_digit = w[j]
            for new_digit in range(q):
                if new_digit != current_digit:
                    new_idx = i + (new_digit - current_digit) * base_diff
                    neighbors.add(new_idx)
        # If radius > 1, we would need to expand further, but for this task radius is likely 1.
        # The prompt says "at most one position", so radius=1.
        # However, the function signature takes radius. Let's handle radius=1 efficiently.
        # If radius > 1, we'd need a more complex BFS or precomputation, but 120s limit and n=8, q=3
        # implies radius 1 is the main case. If radius > 1, the space is small enough for simple checks?
        # Actually, if radius > 1, the ball size is larger.
        # Let's stick to radius 1 optimization as it's the standard case for this problem.
        # If radius != 1, fall back to a slower method or just assume 1?
        # The task says "radius" is passed. I will assume radius=1 for the optimization path.
        # If radius > 1, I will compute balls by checking all pairs? No, that's O(N^2).
        # For q=3, n=8, N=6561. N^2 is 43M. Might be too slow in Python if done naively.
        # But radius 1 is the intended case.
        
        balls.append(sorted(neighbors))
        
    return balls

def _tetracode_solution(q, n):
    """
    Construct a valid code using the tetracode direct sum.
    Tetracode is a (9, 3) ternary code? No, Tetracode is length 9?
    Wait, the seed code used:
    _TETRA = [[a, b, (a + b) % 3, (a + 2 * b) % 3] for a in range(3) for b in range(3)]
    This is length 4. It has 9 words.
    Does it cover {0,1,2}^4 with radius 1?
    Total words 3^4 = 81.
    Ball size for radius 1 in q=3, n=4: 1 + 4*2 = 9.
    9 words * 9 coverage = 81. Perfect packing?
    Let's check if it's a perfect code.
    Yes, the tetracode (or a related code) is a perfect ternary code of length 4?
    Actually, the code generated by the seed is a (3^2, 3^4, 3) code?
    Let's assume it is valid for radius 1.
    
    For n > 4, we extend by direct sum with {0,1,2}^(n-4).
    Size = 9 * 3^(n-4).
    For n=8: 9 * 3^4 = 9 * 81 = 729.
    This is a valid upper bound, though 486 is better.
    """
    if n < 4:
        # Brute force or simple construction
        return [list(t) for t in itertools.product(range(q), repeat=n)]
        
    _TETRA = [[a, b, (a + b) % q, (a + 2 * b) % q] for a in range(q) for b in range(q)]
    # Note: This construction relies on q=3 properties for perfect packing.
    # For general q, it might not be perfect, but it's a valid code?
    # The task specifies q=3 usually, but interface takes q.
    # If q != 3, this might not be valid or optimal.
    # However, the problem is specifically "Football pool problem for 8 matches... alphabet {0,1,2}".
    # So q=3, n=8, radius=1 is the main case.
    
    # To be safe for general q, n, radius:
    # If q != 3 or radius != 1, this tetracode logic might fail validity.
    # But the prompt implies the specific instance.
    # I will use this as a fallback.
    
    result = []
    for h in _TETRA:
        for tail in itertools.product(range(q), repeat=n - 4):
            result.append(h + list(tail))
    return result

def _greedy_cover(balls, deadline):
    """
    Greedy set cover.
    """
    total = len(balls)
    uncovered = np.ones(total, dtype=bool)
    covered_count = total
    chosen = []
    
    # Precompute ball arrays
    # balls[i] is a list of indices.
    
    while covered_count > 0 and time.time() < deadline:
        best_idx = -1
        best_gain = 0
        
        # Optimization: Iterate through uncovered points?
        # Standard greedy: pick set with max gain.
        # Gain of set i = count of uncovered points in balls[i].
        
        for i in range(total):
            # If i is already chosen, gain is 0? No, we just don't pick it again.
            # But we don't track chosen in a set for gain calculation easily without overhead.
            # We can skip if i is in chosen?
            # Actually, if i is in chosen, all its points are covered, so gain is 0.
            # We can maintain a set of chosen indices.
            pass
            
        # Faster:
        # We can iterate and count.
        # To speed up, we can break early if possible? No.
        
        # Let's use a slightly smarter approach:
        # Maintain 'uncovered' as a boolean array.
        # For each i, gain = sum(uncovered[balls[i]]).
        
        # Since balls[i] is small (9 for q=3, n=4, or 17 for q=3, n=8?
        # Ball size for q=3, n=8, r=1: 1 + 8*2 = 17.
        
        for i in range(total):
            # Check if i is already in chosen?
            # We can just compute gain. If i is chosen, gain will be 0.
            gain = 0
            for idx in balls[i]:
                if uncovered[idx]:
                    gain += 1
            if gain > best_gain:
                best_gain = gain
                best_idx = i
                
        if best_gain == 0:
            break
            
        chosen.append(best_idx)
        for idx in balls[best_idx]:
            if uncovered[idx]:
                uncovered[idx] = False
                covered_count -= 1
                
    return chosen

def _prune(chosen, balls):
    """
    Remove redundant codewords.
    """
    if not chosen:
        return []
        
    total = len(balls)
    coverage_count = np.zeros(total, dtype=np.int32)
    for c in chosen:
        for j in balls[c]:
            coverage_count[j] += 1
            
    keep = [True] * len(chosen)
    any_removed = True
    
    while any_removed:
        any_removed = False
        for i, c in enumerate(chosen):
            if not keep[i]:
                continue
            redundant = True
            for j in balls[c]:
                if coverage_count[j] <= 1:
                    redundant = False
                    break
            if redundant:
                keep[i] = False
                any_removed = True
                for j in balls[c]:
                    coverage_count[j] -= 1
                    
    return [chosen[i] for i in range(len(chosen)) if keep[i]]

def _local_search(chosen, balls, deadline):
    """
    Local search: try to swap a codeword with another to allow pruning.
    """
    chosen = _prune(chosen, balls)
    total = len(balls)
    chosen_set = set(chosen)
    
    while time.time() < deadline:
        improved = False
        coverage_count = np.zeros(total, dtype=np.int32)
        for c in chosen:
            for j in balls[c]:
                coverage_count[j] += 1
                
        new_chosen = list(chosen)
        
        for i, c in enumerate(new_chosen):
            if time.time() > deadline:
                break
                
            # Points uniquely covered by c
            unique_points = [j for j in balls[c] if coverage_count[j] == 1]
            
            if not unique_points:
                # Redundant, should be pruned, but let's try to remove it
                # Actually, if unique_points is empty, c is redundant.
                # We can just remove it.
                new_chosen.pop(i)
                improved = True
                break
            
            # Find candidates that cover all unique_points
            # Intersection of balls[uj] for uj in unique_points
            candidates = set(balls[unique_points[0]])
            for uj in unique_points[1:]:
                candidates &= set(balls[uj])
                
            # Filter valid candidates
            # c' must not be in chosen_set - {c}
            # c' can be c (no change) or new
            valid_candidates = []
            for c_prime in candidates:
                if c_prime in chosen_set and c_prime != c:
                    continue
                if c_prime == c:
                    continue # No change
                valid_candidates.append(c_prime)
                
            for c_prime in valid_candidates:
                # Tentative swap
                tentative = list(new_chosen)
                tentative[i] = c_prime
                pruned = _prune(tentative, balls)
                
                if len(pruned) < len(new_chosen):
                    new_chosen = pruned
                    chosen_set = set(new_chosen)
                    improved = True
                    break
            
            if improved:
                break
        
        if not improved:
            # Try random swaps?
            # Or break.
            # Let's try a few random moves to escape local minima.
            rng = np.random.default_rng(42)
            random_improved = False
            for _ in range(50):
                if time.time() > deadline:
                    break
                if not new_chosen:
                    break
                i = rng.integers(0, len(new_chosen))
                c = new_chosen[i]
                c_prime = rng.integers(0, total)
                if c_prime in new_chosen and c_prime != c:
                    continue
                
                tentative = list(new_chosen)
                tentative[i] = c_prime
                # Check validity of tentative set
                # We need to ensure all points are covered.
                # This is expensive.
                # Instead, we can just prune and check if size is smaller AND valid?
                # _prune doesn't check validity.
                # We need a validity check.
                
                # Quick validity check:
                # Union of balls[c] for c in tentative must be all points.
                # This is O(N * ball_size).
                # With N~500, ball_size=17, it's 8500 ops. Fast.
                
                covered = np.zeros(total, dtype=bool)
                valid = True
                for cc in tentative:
                    for j in balls[cc]:
                        covered[j] = True
                if not np.all(covered):
                    continue
                    
                pruned = _prune(tentative, balls)
                if len(pruned) < len(new_chosen):
                    new_chosen = pruned
                    random_improved = True
                    break
            
            if not random_improved:
                break
                
    return new_chosen

def construct(q, n, radius):
    deadline = time.time() + 110.0
    
    try:
        balls = _ball_indices(q, n, radius)
        
        # Greedy
        chosen = _greedy_cover(balls, deadline)
        
        # Prune
        chosen = _prune(chosen, balls)
        
        # Local Search
        chosen = _local_search(chosen, balls, deadline)
        
        # Final Prune
        chosen = _prune(chosen, balls)
        
        # Convert indices to words
        # We need to map index back to word tuple/list.
        # We used integer indices in balls.
        result = []
        for idx in chosen:
            x = idx
            word = [0] * n
            for j in range(n - 1, -1, -1):
                word[j] = x % q
                x //= q
            result.append(word)
            
        # Verify validity
        if len(result) > 0:
            covered = np.zeros(len(balls), dtype=bool)
            for w_idx in chosen:
                for j in balls[w_idx]:
                    covered[j] = True
            if not np.all(covered):
                return _tetracode_solution(q, n)
                
        return result
        
    except Exception:
        return _tetracode_solution(q, n)
