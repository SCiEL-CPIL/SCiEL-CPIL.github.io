def construct(v, k, t):
    """
    Find a covering of t-subsets of v points using k-subsets (blocks).
    Returns a list of blocks (each is a sorted list of k distinct ints in 0..v-1).
    Every t-subset must be contained in at least one block.
    """
    start_time = time.time()
    deadline = start_time + 145.0 # Safety margin

    def check_time(budget=5.0):
        return time.time() - start_time > deadline - budget

    # Precompute all t-subsets
    all_tsubs = list(itertools.combinations(range(v), t))
    num_tsubs = len(all_tsubs)
    tsub_index = {ts: i for i, ts in enumerate(all_tsubs)}
    
    # Full universe mask: all bits set to 1
    full_mask = (1 << num_tsubs) - 1

    # Precompute all blocks and their corresponding t-subset masks
    all_blocks = list(itertools.combinations(range(v), k))
    num_blocks = len(all_blocks)
    
    # block_masks[i] is an integer where bit j is 1 if t-subset j is in block i
    block_masks = [0] * num_blocks
    for i, b in enumerate(all_blocks):
        mask = 0
        for ts in itertools.combinations(b, t):
            idx = tsub_index[ts]
            mask |= (1 << idx)
        block_masks[i] = mask

    # --- Combinatorial Group Construction ---
    # Partition 19 points into groups: G0 (size 7), G1 (size 6), G2 (size 6)
    # Points 0-6 are in G0, 7-12 in G1, 13-18 in G2
    
    # Generate blocks using affine transformations over F7 and F5 (approximated for size 6)
    # Since F5 has 5 elements, we can't directly use affine for size 6.
    # Instead, we use a mix of:
    # 1. Blocks heavily within G0 using F7 affine lines/planes.
    # 2. Blocks mixing G0, G1, G2 using random but structured sampling.
    
    initial_indices = set()
    
    # Helper to add a block if it's valid and new
    def add_block(block):
        if not block:
            return
        block = tuple(sorted(block))
        # Find index of this block
        # We can't easily find index without a dict, but we have all_blocks.
        # For efficiency in construction phase, we might just keep a set of tuples.
        # But we need indices for the rest of the algorithm.
        # Let's create a map from block tuple to index.
        pass
        
    # Create a fast lookup for block index
    block_to_idx = {b: i for i, b in enumerate(all_blocks)}
    
    # 1. Generate F7-based blocks for G0 (0-6)
    # Affine lines in AG(2, 3) or similar? No, 7 points is F7.
    # Let's just use all 5-subsets of G0? No, we need 8-subsets.
    # Strategy: Take a "core" of 5 points from G0, and 3 points from G1/G2.
    
    # Let's try a simpler structured generation:
    # Generate random blocks but bias towards group structures.
    # Or, use the "La Jolla" style: start with a known good configuration if we had one.
    # Since we don't, let's use a "Greedy with Structure" initialization.
    
    # Alternative: Use the greedy algorithm but start with a "seed" of blocks
    # that are likely to be in an optimal solution.
    # Heuristic: Blocks that cover many "popular" t-subsets.
    # But let's stick to the prompt's inspiration: Affine transformations.
    
    # For G0 (7 pts), consider all 5-subsets of G0. There are C(7,5)=21.
    # For each 5-subset S5 of G0, we need to add 3 points from G1 U G2 (12 pts).
    # To cover 5-subsets that span groups, we need variety.
    
    # Let's generate a set of candidate blocks:
    # Type A: 5 from G0, 3 from G1
    # Type B: 5 from G0, 3 from G2
    # Type C: 4 from G0, 4 from G1
    # Type D: 4 from G0, 4 from G2
    # Type E: 3 from G0, 5 from G1
    # Type F: 3 from G0, 5 from G2
    # Type G: 2 from G0, 6 from G1
    # Type H: 2 from G0, 6 from G2
    # Type I: 6 from G0, 2 from G1
    # Type J: 6 from G0, 2 from G2
    # Type K: 0 from G0, 8 from G1 U G2 (mixed)
    
    # This is getting complex. Let's use a simpler "Structured Random" approach.
    # Randomly select 8 points, but with a bias to include points from different groups.
    
    # Actually, the most effective "structural" change for C(19,8,5) is often
    # using a **Greedy Algorithm with a specific ordering** or **Simulated Annealing**
    # starting from a good heuristic.
    
    # Let's implement a "Greedy with Restart" using the bitmask approach,
    # but initialize with a "Greedy Maximal Independent Set" style heuristic?
    # No, let's use the **Probabilistic Group Construction** as suggested.
    
    # We will generate a pool of candidate blocks based on group partitions.
    # Then we will run a greedy set cover on this pool? No, the pool must cover everything.
    # Better: Use the pool to *seed* the greedy algorithm.
    
    # Let's just use the standard Greedy Set Cover, but with a **Randomized Initial Set**
    # generated by the group structure, and then **Repair** it.
    
    # Step 1: Generate a "Structured" Initial Cover
    # We will greedily add blocks, but we will prioritize blocks that have a "balanced"
    # distribution across the 3 groups (7, 6, 6).
    
    # Calculate group of each point
    def get_group(p):
        if p < 7: return 0
        elif p < 13: return 1
        else: return 2
        
    # Score a block based on group balance?
    # Let's just run the standard Greedy, but with a **Randomized Tie-Breaking**
    # and **Multiple Restarts** with different random seeds, keeping the best.
    
    # However, the prompt asks for a *different* strategy.
    # Let's try **Local Search starting from a Random Valid Cover**.
    # How to get a random valid cover?
    # 1. Greedy to get a valid cover (this is fast).
    # 2. Then, perform **2-Opt Moves**: Remove 2 blocks, add 1 block if coverage is maintained.
    # This allows escaping 1-Opt local minima.
    
    def greedy_cover():
        uncovered = full_mask
        selected_indices = []
        remaining_blocks = set(range(num_blocks))
        
        while uncovered:
            if check_time(10.0):
                break
            best_gain = -1
            best_block = -1
            
            # Randomized tie-breaking to allow different paths in restarts
            # But for the first pass, let's be deterministic or lightly randomized.
            
            for i in remaining_blocks:
                gain = (uncovered & block_masks[i]).bit_count()
                if gain > best_gain:
                    best_gain = gain
                    best_block = i
                elif gain == best_gain and best_block != -1:
                    # Random tie-breaker
                    if random.random() < 0.1:
                        best_block = i
                        
            if best_block == -1:
                break
                
            selected_indices.append(best_block)
            remaining_blocks.remove(best_block)
            uncovered &= ~block_masks[best_block]
            
        return selected_indices

    def local_search_remove(indices):
        indices = list(indices)
        if not indices:
            return indices
            
        union_mask = 0
        for idx in indices:
            union_mask |= block_masks[idx]
            
        changed = True
        while changed and not check_time(5.0):
            changed = False
            new_indices = []
            for i, idx in enumerate(indices):
                others_union = 0
                for j, other_idx in enumerate(indices):
                    if j != i:
                        others_union |= block_masks[other_idx]
                        
                if (block_masks[idx] & ~others_union) == 0:
                    changed = True
                else:
                    new_indices.append(idx)
                    
            indices = new_indices
            
        return indices

    def two_opt_search(indices, seed=42):
        """
        Perform 2-Opt moves: Remove 2 blocks, add 1 block.
        This is more powerful than 1-Opt removal.
        """
        rng = random.Random(seed)
        indices = list(indices)
        if not indices:
            return indices
            
        union_mask = 0
        for idx in indices:
            union_mask |= block_masks[idx]
            
        current_len = len(indices)
        best_indices = list(indices)
        best_len = current_len
        
        T = 10.0
        alpha = 0.99
        iters = 0
        max_iters = 50000
        
        while T > 0.1 and iters < max_iters and not check_time(10.0):
            iters += 1
            
            if len(indices) < 3:
                break
                
            # Pick 2 blocks to remove
            i1, i2 = rng.sample(range(len(indices)), 2)
            remove_set = {indices[i1], indices[i2]}
            
            # New indices without these two
            new_indices = [x for x in indices if x not in remove_set]
            
            # Calculate new union
            new_union = 0
            for idx in new_indices:
                new_union |= block_masks[idx]
                
            missing = full_mask & ~new_union
            
            if missing == 0:
                # We removed 2 blocks and coverage is still full!
                # This is a huge improvement.
                indices = new_indices
                union_mask = new_union
                current_len = len(indices)
                if current_len < best_len:
                    best_len = current_len
                    best_indices = list(indices)
                continue
            
            # Coverage is broken. Try to repair by adding 1 block.
            # Find a block that covers the most missing t-subsets.
            best_gain = -1
            best_add = -1
            
            # Sample candidates to speed up
            # We need a block that covers 'missing'.
            # We can pre-compute for each t-subset which blocks cover it?
            # That's too big.
            
            # Let's sample 2000 random blocks.
            candidates = rng.sample(range(num_blocks), min(2000, num_blocks))
            
            for i in candidates:
                if i in remove_set:
                    continue
                gain = (missing & block_masks[i]).bit_count()
                if gain > best_gain:
                    best_gain = gain
                    best_add = i
                    
            if best_add != -1 and (missing & ~block_masks[best_add]) == 0:
                # The single block covers all missing parts!
                # New set is new_indices + [best_add]
                # Size: len(new_indices) + 1 = (current_len - 2) + 1 = current_len - 1
                # This is an improvement!
                indices = new_indices + [best_add]
                union_mask = full_mask
                current_len = len(indices)
                if current_len < best_len:
                    best_len = current_len
                    best_indices = list(indices)
            else:
                # If we can't repair with 1 block, we might try 2 blocks?
                # That would be a 3-Opt move (remove 2, add 2 -> size same).
                # Or remove 2, add 3 (size +1, bad).
                # Let's stick to 1-block repair for now.
                pass
            
            T *= alpha
            
        return best_indices

    # Main Execution
    # 1. Greedy Initialization
    initial = greedy_cover()
    
    if not initial:
        return []
        
    # 2. 1-Opt Reduction
    reduced = local_search_remove(initial)
    
    best_blocks = list(reduced)
    best_len = len(best_blocks)
    
    # 3. 2-Opt Search with Restarts
    for seed in range(10):
        if check_time(15.0):
            break
        result = two_opt_search(reduced, seed=seed * 100 + 1)
        if result and len(result) < best_len:
            best_len = len(result)
            best_blocks = result
            
    # 4. Final 1-Opt pass on the best result
    best_blocks = local_search_remove(best_blocks)
    
    # Convert indices back to blocks
    return [list(all_blocks[i]) for i in best_blocks]

