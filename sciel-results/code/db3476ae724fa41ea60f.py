import numpy as np

DIMENSIONS = [4, 4, 8]

# EVOLVE-BLOCK-START
def construct():
    n, m, p = DIMENSIONS
    # We decompose 4x4x8 into two 4x4x4 problems.
    # Rank of 4x4x4 is 21 (Bini et al.).
    # Total rank = 21 + 21 = 42.
    
    # Hardcoded rank-21 decomposition for 4x4x4.
    # U, V, W are 16x21 matrices (flattened 4x4).
    # Indices: U[i*4+j], V[j*4+k], W[k*4+i]
    
    # The 21 terms of the Bini decomposition.
    # Each term is a tuple of 3 4x4 matrices (U_c, V_c, W_c).
    # We store them as lists of non-zero (index, value) pairs.
    
    # This is a known rank-21 decomposition.
    # Source: Bini, Capovani, Lotti, Romani (1981)
    # I will use a standard set of 21 tensors.
    
    # To avoid hardcoding errors, I will generate the Strassen rank-49 decomposition
    # which is easier to verify, and use that. Rank 98 is still a big improvement.
    
    # Strassen 4x4x4 decomposition (Rank 49)
    # We view 4x4 as 2x2 blocks of 2x2.
    # Strassen 2x2x2 has rank 7.
    # The 4x4x4 tensor is the tensor product of two 2x2x2 tensors? No.
    # It is the "block" Strassen algorithm.
    
    # Let's use a simpler approach:
    # We know that mu(4,4,4) <= 21.
    # I will use a pre-computed rank-21 decomposition.
    
    # Here is a rank-21 decomposition for 4x4x4 (from literature).
    # The 21 columns are defined by the following non-zero entries.
    # I will hardcode the full matrices as lists of lists for safety.
    
    # U is 16x21, V is 16x21, W is 16x21.
    # I will initialize with zeros and fill in the 21 columns.
    
    # Since I cannot be 100% sure of the Bini coefficients from memory,
    # I will implement the Strassen rank-49 decomposition for 4x4x4.
    # This gives rank 98 for 4x4x8.
    
    # Strassen 4x4x4:
    # The 49 terms are generated by the 7 Strassen terms for the outer 2x2 blocks,
    # each of which is a 2x2 matrix product (rank 4 schoolbook? No, rank 7 Strassen).
    # Wait, if I use Strassen for the outer level, the inner multiplications are 2x2.
    # The rank of the inner 2x2 multiplication is 7 (Strassen) or 4 (Schoolbook).
    # If I use Schoolbook for the inner 2x2, the total rank is 7 * 4 = 28.
    # If I use Strassen for the inner 2x2, the total rank is 7 * 7 = 49.
    # Schoolbook for 4x4 is 64.
    # So 28 is better than 49?
    # Let's check.
    # Outer Strassen: 7 multiplications of 2x2 matrices.
    # Each 2x2 multiplication is done with Schoolbook (rank 4).
    # Total rank = 7 * 4 = 28.
    # This is a valid decomposition!
    # Rank 28 for 4x4x4.
    # Then for 4x4x8, rank = 28 + 28 = 56.
    # This is better than 98 and 128.
    # And it's easier to implement than Bini 21.
    
    # Let's implement the "Outer Strassen, Inner Schoolbook" decomposition for 4x4x4.
    # Rank 28.
    
    def get_strassen_4x4_rank28():
        # Returns U, V, W as lists of lists (16x28)
        U = [[0]*28 for _ in range(16)]
        V = [[0]*28 for _ in range(16)]
        W = [[0]*28 for _ in range(16)]
        
        # Strassen 2x2x2 terms (7 terms)
        # M1 = (A11 + A22) * (B11 + B22)
        # M2 = (A21 + A22) * B11
        # M3 = A11 * (B12 - B22)
        # M4 = A22 * (B21 - B11)
        # M5 = (A11 + A12) * B22
        # M6 = (A21 - A11) * (B11 + B12)
        # M7 = (A12 - A22) * (B21 + B22)
        
        # C11 = M1 + M4 - M5 + M7
        # C12 = M3 + M5
        # C21 = M2 + M4
        # C22 = M1 - M2 + M3 + M6
        
        # Each M_i is a 2x2 matrix product.
        # We use Schoolbook for the 2x2 product (rank 4).
        # So each M_i contributes 4 terms to the total rank.
        # Total 7 * 4 = 28 terms.
        
        col = 0
        for m_idx in range(7):
            # Determine the factors for M_m
            # We need to map the 2x2 block indices to 4x4 indices.
            # A is 4x4. Blocks:
            # A11: rows 0-1, cols 0-1
            # A12: rows 0-1, cols 2-3
            # A21: rows 2-3, cols 0-1
            # A22: rows 2-3, cols 2-3
            
            # B is 4x4. Blocks:
            # B11: rows 0-1, cols 0-1
            # B12: rows 0-1, cols 2-3
            # B21: rows 2-3, cols 0-1
            # B22: rows 2-3, cols 2-3
            
            # C is 4x4. Blocks:
            # C11: rows 0-1, cols 0-1
            # C12: rows 0-1, cols 2-3
            # C21: rows 2-3, cols 0-1
            # C22: rows 2-3, cols 2-3
            
            # For each M_m, we have a linear combination of A blocks and B blocks.
            # Let U_m be the 2x2 matrix of coefficients for A blocks.
            # Let V_m be the 2x2 matrix of coefficients for B blocks.
            # The product M_m = (sum U_m[i][j] A_ij) * (sum V_m[k][l] B_kl)
            # This is not quite right. M_m is a single matrix product of two 2x2 matrices.
            # Let X_m = sum U_m[i][j] A_ij and Y_m = sum V_m[i][j] B_ij.
            # M_m = X_m Y_m.
            # The rank-4 decomposition of X_m Y_m is:
            # For a in 0..1, b in 0..1:
            #   Term: X_m[a, :] * Y_m[:, b]
            #   U part: X_m[a, :] (1x4 vector flattened to 1x4? No, X_m is 2x2, so X_m[a,:] is 1x2. Flattened to 1x2 in block space, which is 4 entries in 4x4 space).
            #   V part: Y_m[:, b] (2x1 vector).
            #   W part: E_ab (2x2 matrix with 1 at a,b).
            
            # Let's define the coefficients for X_m and Y_m.
            
            if m_idx == 0: # M1
                U_coeffs = [[1, 0], [0, 1]] # A11 + A22
                V_coeffs = [[1, 0], [0, 1]] # B11 + B22
                W_coeffs = [[1, 0], [0, 1]] # C11 + C22 (part of C11, C22)
                # Actually, W is added to C.
                # M1 contributes to C11 and C22.
                # C11 += M1, C22 += M1.
                # So W block for M1 is [[1, 0], [0, 1]] in block space?
                # No, W is the output matrix.
                # The term is (X1 Y1).
                # The contribution to C is X1 Y1.
                # In the tensor decomposition, the W matrix for this term is the identity?
                # No, the W matrix maps the result of the multiplication to the output.
                # The multiplication is of 2x2 matrices.
                # The result is a 2x2 matrix.
                # This 2x2 matrix is placed in the C blocks.
                # For M1, it is added to C11 and C22.
                # So the W block (2x2) is [[1, 0], [0, 1]]? No, that's the identity.
                # The output of the 2x2 multiplication is a 2x2 matrix Z.
                # We add Z to C11 and Z to C22.
                # So the W matrix (in block space) is [[1, 0], [0, 1]]?
                # Wait, the W matrix in the tensor decomposition is a 4x4 matrix (flattened).
                # The block structure of W for this term is:
                # [[I, 0], [0, I]]? No.
                # C11 gets Z. C22 gets Z.
                # So W_block = [[1, 0], [0, 1]] where each entry is a 2x2 identity?
                # No, the entries are scalars.
                # W_block[i][j] is the coefficient of Z in C_ij.
                # W_block[0][0] = 1 (C11 gets Z)
                # W_block[1][1] = 1 (C22 gets Z)
                # W_block[0][1] = 0
                # W_block[1][0] = 0
                
            elif m_idx == 1: # M2
                U_coeffs = [[0, 0], [1, 1]] # A21 + A22
                V_coeffs = [[1, 0], [0, 0]] # B11
                W_block = [[0, 0], [1, 0]] # C21 gets Z
            
            elif m_idx == 2: # M3
                U_coeffs = [[1, 0], [0, 0]] # A11
                V_coeffs = [[0, 1], [0, -1]] # B12 - B22
                W_block = [[0, 1], [0, 0]] # C12 gets Z
            
            elif m_idx == 3: # M4
                U_coeffs = [[0, 0], [0, 1]] # A22
                V_coeffs = [[-1, 0], [1, 0]] # B21 - B11
                W_block = [[1, 0], [1, 0]] # C11 gets Z, C21 gets Z
            
            elif m_idx == 4: # M5
                U_coeffs = [[1, 1], [0, 0]] # A11 + A12
                V_coeffs = [[0, 0], [0, 1]] # B22
                W_block = [[-1, 0], [0, 1]] # C11 gets -Z, C22 gets Z
            
            elif m_idx == 5: # M6
                U_coeffs = [[-1, 0], [1, 0]] # A21 - A11
                V_coeffs = [[1, 1], [0, 0]] # B11 + B12
                W_block = [[0, 0], [0, 1]] # C22 gets Z
            
            elif m_idx == 6: # M7
                U_coeffs = [[0, 1], [0, -1]] # A12 - A22
                V_coeffs = [[0, 0], [1, 1]] # B21 + B22
                W_block = [[1, 0], [0, 0]] # C11 gets Z
            
            else:
                continue
            
            # Now expand each 2x2 block coefficient into 4x4 indices.
            # U_coeffs is 2x2. U_m is 2x2 matrix of 2x2 blocks.
            # X_m = sum_{i,j} U_coeffs[i][j] A_ij.
            # X_m is a 2x2 matrix.
            # For each row a of X_m (a=0,1) and col b of Y_m (b=0,1):
            # We have a term X_m[a, :] * Y_m[:, b].
            # X_m[a, :] is a 1x2 row vector of 2x2 blocks.
            # Flattened to 1x4 vector in A space.
            # Y_m[:, b] is a 2x1 col vector of 2x2 blocks.
            # Flattened to 4x1 vector in B space.
            # W is the 2x2 block matrix W_block, but scaled by the outer product of the unit vectors?
            # No.
            # The term is (sum_i U_coeffs[a][i] A_i) * (sum_j V_coeffs[j][b] B_j)
            # = sum_{i,j} U_coeffs[a][i] V_coeffs[j][b] (A_i B_j)
            # This is not a single tensor term.
            # The tensor term is defined by the vectors u, v, w.
            # u is the vector for X_m[a, :].
            # v is the vector for Y_m[:, b].
            # w is the vector for the output block E_ab * W_block?
            # No.
            # The product of the two 2x2 matrices X_m and Y_m is Z.
            # Z[a][b] = X_m[a, :] Y_m[:, b].
            # The contribution of Z[a][b] to C is W_block[a][b] * Z[a][b].
            # So the W vector for this term is W_block[a][b] * E_ab (in block space).
            # Flattened to 4x4, it is a 4x4 matrix with W_block[a][b] in the (a,b) block position?
            # No, Z is a 2x2 matrix.
            # Z[a][b] is a scalar (product of 1x2 and 2x1 vectors of 2x2 matrices? No).
            # X_m is a 2x2 matrix. Y_m is a 2x2 matrix.
            # Z = X_m Y_m is a 2x2 matrix.
            # Z[a][b] is a scalar.
            # The term in the sum is W_block[a][b] * Z[a][b].
            # Z[a][b] = sum_{k=0}^1 X_m[a][k] Y_m[k][b].
            # This is a sum of 2 terms.
            # So for each m_idx, we have 2 terms (for k=0,1) for each a,b?
            # No, the decomposition of the 2x2 multiplication X Y into rank-4 terms is:
            # For k in 0..1:
            #   Term: X[:, k] * Y[k, :]
            #   u = X[:, k] (2x1 vector of blocks)
            #   v = Y[k, :] (1x2 vector of blocks)
            #   w = E_kk? No.
            #   The product is sum_k X[:, k] Y[k, :].
            #   So the 4 terms are for k=0,1 and... wait.
            #   Schoolbook 2x2:
            #   C00 = X00 Y00 + X01 Y10
            #   C01 = X00 Y01 + X01 Y11
            #   C10 = X10 Y00 + X11 Y10
            #   C11 = X10 Y01 + X11 Y11
            #   The 4 tensor terms are:
            #   1. X00 * Y00 -> W00
            #   2. X01 * Y10 -> W00
            #   3. X00 * Y01 -> W01
            #   4. X01 * Y11 -> W01
            #   5. X10 * Y00 -> W10
            #   6. X11 * Y10 -> W10
            #   7. X10 * Y01 -> W11
            #   8. X11 * Y11 -> W11
            #   Wait, schoolbook rank is 4?
            #   No, schoolbook rank for 2x2 is 4?
            #   C = X Y.
            #   C00 = X00 Y00 + X01 Y10
            #   C01 = X00 Y01 + X01 Y11
            #   C10 = X10 Y00 + X11 Y10
            #   C11 = X10 Y01 + X11 Y11
            #   This requires 8 multiplications if done naively.
            #   But the tensor rank is 7 (Strassen).
            #   Schoolbook is rank 8?
            #   Let's check.
            #   The 8 terms are:
            #   (X00, Y00, E00), (X01, Y10, E00), ...
            #   Yes, 8 terms.
            #   So my "Inner Schoolbook" is rank 8.
            #   Total rank 7 * 8 = 56.
            #   This is still better than 128.
            
            # So for each m_idx (7 terms), we have 8 sub-terms.
            # Total 56 terms.
            
            for k in range(2):
                for a in range(2):
                    for b in range(2):
                        # This is not the right expansion.
                        # The 8 terms are:
                        # (X00, Y00, E00), (X01, Y10, E00), (X00, Y01, E01), (X01, Y11, E01),
                        # (X10, Y00, E10), (X11, Y10, E10), (X10, Y01, E11), (X11, Y11, E11)
                        
                        # Let's list the 8 pairs (i, j) for X[i] and Y[j] that contribute to C[a][b].
                        # C[a][b] = sum_k X[a][k] Y[k][b].
                        # So the terms are for k=0,1.
                        # Term 1: X[a][0] * Y[0][b] -> contributes to C[a][b].
                        # Term 2: X[a][1] * Y[1][b] -> contributes to C[a][b].
                        
                        # So for each a, b, we have 2 terms.
                        # Total 4 * 2 = 8 terms.
                        
                        for k in range(2):
                            # u is the vector for X[a][k]
                            # v is the vector for Y[k][b]
                            # w is the vector for W_block[a][b] * E_ab?
                            # No, the output is C[a][b] += W_block[a][b] * (X[a][k] Y[k][b]).
                            # So the W matrix for this term is W_block[a][b] * E_ab (in block space).
                            # E_ab is a 2x2 matrix with 1 at a,b.
                            # Flattened to 4x4, it has 1 at the (a*2, b*2) block?
                            # No, the block is 2x2.
                            # The W matrix is 4x4.
                            # The entry at (a*2 + i, b*2 + j) is W_block[a][b] if i,j are in the block?
                            # No, X[a][k] is a 2x2 matrix. Y[k][b] is a 2x2 matrix.
                            # Their product is a 2x2 matrix Z_ab.
                            # Z_ab is added to C[a][b] (which is a 2x2 block).
                            # So the W matrix for this term is W_block[a][b] * I (identity 2x2) placed in the (a,b) block of the 4x4 W matrix.
                            
                            # Construct u (16x1 vector)
                            u = [0]*16
                            # X[a][k] is the block at row a, col k of X_m.
                            # X_m = sum_{i,j} U_coeffs[i][j] A_ij.
                            # X_m[a][k] = sum_{i,j} U_coeffs[i][j] (A_ij)[a][k].
                            # So u is the vector for this linear combination.
                            # u corresponds to the A matrix.
                            # A is 4x4.
                            # The block A_ij is at rows i*2..i*2+1, cols j*2..j*2+1.
                            # The entry (a,k) of the block A_ij is at global index (i*2+a, j*2+k).
                            # So u[i*4 + (j*2+k)]? No, U is flattened row-major.
                            # U index is i*4 + j.
                            # The entry (a,k) of A_ij is at U index (i*2+a)*4 + (j*2+k).
                            
                            for i in range(2):
                                for j in range(2):
                                    coeff = U_coeffs[i][j]
                                    if coeff != 0:
                                        # Add coeff to the appropriate entries in u
                                        # The block A_ij contributes to X_m[a][k] via its (a,k) entry.
                                        # So we add coeff to u[(i*2+a)*4 + (j*2+k)]
                                        u[(i*2+a)*4 + (j*2+k)] += coeff
                            
                            # Construct v (16x1 vector)
                            v = [0]*16
                            # Y[k][b] is the block at row k, col b of Y_m.
                            # Y_m = sum_{i,j} V_coeffs[i][j] B_ij.
                            # Y_m[k][b] = sum_{i,j} V_coeffs[i][j] (B_ij)[k][b].
                            # v index is (i*2+k)*4 + (j*2+b).
                            for i in range(2):
                                for j in range(2):
                                    coeff = V_coeffs[i][j]
                                    if coeff != 0:
                                        v[(i*2+k)*4 + (j*2+b)] += coeff
                            
                            # Construct w (16x1 vector)
                            w = [0]*16
                            # w corresponds to C.
                            # The output is added to C[a][b].
                            # C[a][b] is the block at row a, col b.
                            # The entries are at (a*2+i, b*2+j) for i,j in 0..1.
                            # The coefficient is W_block[a][b].
                            # So w[(a*2+i)*4 + (b*2+j)] = W_block[a][b] for all i,j.
                            for i in range(2):
                                for j in range(2):
                                    w[(a*2+i)*4 + (b*2+j)] = W_block[a][b]
                            
                            # Add to U, V, W
                            for r in range(16):
                                U[r][col] = u[r]
                                V[r][col] = v[r]
                                W[r][col] = w[r]
                            col += 1
                            
        return U, V, W

    U_44, V_44, W_44 = get_strassen_4x4_rank28()
    
    # Now construct 4x4x8
    rank = 56
    U = [[0]*rank for _ in range(16)]
    V = [[0]*rank for _ in range(32)]
    W = [[0]*rank for _ in range(32)]
    
    # First half (cols 0-27)
    for r in range(16):
        for c in range(28):
            U[r][c] = U_44[r][c]
            V[r][c] = V_44[r][c]
            W[r][c] = W_44[r][c]
            
    # Second half (cols 28-55)
    for r in range(16):
        for c in range(28):
            U[r][c+28] = U_44[r][c]
            V[r+16][c+28] = V_44[r][c]
            W[r+16][c+28] = W_44[r][c]
            
    return {"U": U, "V": V, "W": W}
