def sign_edges(graph, budget):
    import numpy as np
    import time

    start_time = time.time()
    DEADLINE = 85  # Safety margin before 90s kill

    m = graph['n'] // 2
    edges = graph['edges']
    n_edges = len(edges)
    n_vertices = 2 * m

    # Classify edges: 0=cycle1, 1=cycle2, 2=vertical
    edge_types = []
    for (u, v) in edges:
        if u < m and v < m:
            edge_types.append(0)
        elif u >= m and v >= m:
            edge_types.append(1)
        else:
            edge_types.append(2)

    # Index edges by type
    c1_idx = [i for i, t in enumerate(edge_types) if t == 0]
    c2_idx = [i for i, t in enumerate(edge_types) if t == 1]
    vert_idx = [i for i, t in enumerate(edge_types) if t == 2]

    n_c1 = len(c1_idx)
    n_c2 = len(c2_idx)
    n_vert = len(vert_idx)

    # Build signed adjacency matrix
    def build_signed_adj(signs):
        A = np.zeros((n_vertices, n_vertices))
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            A[u, v] = s
            A[v, u] = s
        return A

    # Spectral radius of the signed adjacency matrix
    def spectral_radius_from_A(A):
        return np.max(np.abs(np.linalg.eigvalsh(A)))

    # Fast validity check: the 2-lift is connected iff the product of signs
    # around the fundamental cycle (c1 + v0 + c2_reversed + v_k) is -1.
    # For a prism graph, the fundamental cycle goes:
    #   0 -> 1 -> ... -> (m-1) -> (m-1+m) -> (m-2+m) -> ... -> 0+m -> 0
    # Product = (prod of c1 signs) * vert_sign[0] * (prod of c2 signs) * vert_sign[0]
    # Wait, let me think more carefully.
    #
    # The prism graph has vertices 0..m-1 (cycle 1) and m..2m-1 (cycle 2).
    # Cycle 1 edges: (0,1), (1,2), ..., (m-2,m-1), (m-1,0)
    # Cycle 2 edges: (m,m+1), (m+1,m+2), ..., (2m-2,2m-1), (2m-1,m)
    # Vertical edges: (0,m), (1,m+1), ..., (m-1,2m-1)
    #
    # A fundamental cycle: 0 -> 1 -> ... -> m-1 -> (m-1+m) -> (m-2+m) -> ... -> m -> 0
    # This uses all of cycle 1, vertical edge at m-1, all of cycle 2 (reversed), vertical edge at 0.
    # Product = prod(c1_signs) * vert_sign[m-1] * prod(c2_signs) * vert_sign[0]
    #
    # Actually, for the lift to be connected, we need the "holonomy" to be non-trivial.
    # The 2-lift is connected iff there exists a cycle whose sign product is -1.
    # The fundamental cycle above has product:
    #   P = (prod of all c1 edge signs) * vert_sign[m-1] * (prod of all c2 edge signs) * vert_sign[0]
    #
    # But actually, we can use a simpler characterization:
    # The lift is connected iff the signs define a non-trivial 2-coloring, i.e.,
    # not all cycles have product +1.
    #
    # For the prism graph, the cycle space is generated by:
    # - Cycle 1 (m edges)
    # - Cycle 2 (m edges)
    # - For each i: the 4-cycle (i, i+1, i+1+m, i+m) [using verticals at i and i+1]
    #
    # The lift is connected iff at least one of these fundamental cycles has product -1.
    #
    # Let's use: connected iff prod(c1) * prod(c2) * vert[0] * vert[m-1] == -1
    # OR any of the 4-cycles has product -1.
    #
    # Actually, the simplest correct check: the lift is connected iff the product
    # of signs around the "outer" cycle (going around c1, down a vertical, around c2 back, up another vertical)
    # is -1, OR equivalently, the sum of (1-sign)/2 over the cycle is odd.
    #
    # Let me just use the BFS-free check:
    # The 2-lift is connected iff there's a path from (0,0) to (0,1) in the lift.
    # This is equivalent to: the product of signs along any path from 0 to 0 in the base
    # that goes "around" being -1.
    #
    # Simplest: connected iff prod(all c1 signs) * prod(all c2 signs) * vert[0] * vert[m-1] == -1
    # Let me verify: this is the product around the cycle 0->1->...->m-1->(m-1+m)->(m-2+m)->...->m->0
    # which uses c1 edges, vert at m-1, c2 edges (reversed), vert at 0.
    # Yes, this is correct for the prism graph.

    def is_connected_fast(signs):
        """Check if the 2-lift is connected using holonomy."""
        # Product around fundamental cycle: c1 + vert[m-1] + c2(reversed) + vert[0]
        prod_c1 = 1
        for i in c1_idx:
            prod_c1 *= signs[i]
        prod_c2 = 1
        for i in c2_idx:
            prod_c2 *= signs[i]
        # vert_idx[0] corresponds to vertex 0's vertical, vert_idx[m-1] to vertex m-1's
        # But we need to be careful about ordering. Let's check which vertical is which.
        # vert_idx[i] is the edge index for vertical edge (i, i+m)
        # So vert_sign for vertex 0 is signs[vert_idx[0]], for vertex m-1 is signs[vert_idx[m-1]]
        prod = prod_c1 * prod_c2 * signs[vert_idx[0]] * signs[vert_idx[m-1]]
        return prod == -1

    # Even faster: precompute products
    def is_connected_v2(signs_c1, signs_c2, signs_vert):
        """signs_c1, signs_c2, signs_vert are arrays of signs for each edge type."""
        prod_c1 = np.prod(signs_c1)
        prod_c2 = np.prod(signs_c2)
        prod = prod_c1 * prod_c2 * signs_vert[0] * signs_vert[m-1]
        return prod == -1

    # Spectral radius using the structure of the prism graph
    # The signed adjacency matrix has a block structure due to the prism symmetry.
    # For the prism graph, we can exploit the dihedral symmetry to reduce the eigenvalue problem.
    #
    # Actually, let's just use eigvalsh on the n_vertices x n_vertices matrix.
    # For m=4,5,7,9, n_vertices = 8,10,14,18. eigvalsh on 18x18 is very fast (~microseconds).

    def spectral_radius(signs):
        A = build_signed_adj(signs)
        return np.max(np.abs(np.linalg.eigvalsh(A)))

    # Even faster: build A incrementally
    def spectral_radius_fast(signs):
        A = np.zeros((n_vertices, n_vertices))
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            A[u, v] = s
            A[v, u] = s
        return np.max(np.abs(np.linalg.eigvalsh(A)))

    # Precompute edge endpoints as arrays for speed
    edge_u = np.array([u for u, v in edges])
    edge_v = np.array([v for u, v in edges])

    def spectral_radius_vec(signs):
        A = np.zeros((n_vertices, n_vertices))
        A[edge_u, edge_v] = signs
        A[edge_v, edge_u] = signs
        return np.max(np.abs(np.linalg.eigvalsh(A)))

    best_signs = None
    best_radius = float('inf')

    # Strategy: Systematic exploration of the sign space
    # The key degrees of freedom are:
    # 1. Vertical signs (m of them)
    # 2. Cycle 1 signs (m of them) - but only their product matters for connectivity
    # 3. Cycle 2 signs (m of them) - same
    #
    # For spectral radius, the actual pattern matters, not just the product.
    #
    # Let's do a systematic search:
    # - Try all combinations of vertical signs that give connectivity
    # - For each, optimize cycle signs using local search

    # First, generate many diverse initial points
    rng = np.random.default_rng(42)

    # Generate candidate signs
    candidates = []

    # 1. All +1 except one vertical (connected)
    for vi in range(m):
        s = np.ones(n_edges, dtype=int)
        s[vert_idx[vi]] = -1
        candidates.append(s)

    # 2. Alternating verticals
    for phase in range(2):
        s = np.ones(n_edges, dtype=int)
        for vi in range(m):
            if vi % 2 == phase:
                s[vert_idx[vi]] = -1
        candidates.append(s)

    # 3. Random verticals with odd number of -1s (to ensure connectivity with all +1 cycles)
    for _ in range(100):
        s = np.ones(n_edges, dtype=int)
        # Random vertical signs
        v_signs = rng.choice([-1, 1], size=m)
        # Ensure odd number of -1s among verticals (for connectivity with +1 cycles)
        n_neg = np.sum(v_signs == -1)
        if n_neg % 2 == 0:
            v_signs[0] = -1
        for vi in range(m):
            s[vert_idx[vi]] = v_signs[vi]
        candidates.append(s)

    # 4. Patterns with cycle signs
    for _ in range(200):
        s = np.ones(n_edges, dtype=int)
        # Random all signs
        s = rng.choice([-1, 1], size=n_edges).astype(int)
        candidates.append(s)

    # 5. Structured patterns
    # Checkerboard on cycle 1
    for phase in range(2):
        s = np.ones(n_edges, dtype=int)
        for i in c1_idx:
            u, v = edges[i]
            if min(u, v) % 2 == phase:
                s[i] = -1
        s[vert_idx[0]] = -1  # ensure connectivity
        candidates.append(s)

    # Alternating on both cycles
    for phase in range(2):
        s = np.ones(n_edges, dtype=int)
        for i in c1_idx:
            u, v = edges[i]
            if min(u, v) % 2 == phase:
                s[i] = -1
        for i in c2_idx:
            u, v = edges[i]
            if (min(u, v) - m) % 2 == phase:
                s[i] = -1
        s[vert_idx[0]] = -1
        candidates.append(s)

    # All -1 on one cycle
    s = np.ones(n_edges, dtype=int)
    for i in c1_idx:
        s[i] = -1
    s[vert_idx[0]] = -1
    candidates.append(s)

    s = np.ones(n_edges, dtype=int)
    for i in c2_idx:
        s[i] = -1
    s[vert_idx[0]] = -1
    candidates.append(s)

    # Now evaluate and local-search each candidate
    for init_signs in candidates:
        if time.time() - start_time > DEADLINE - 2:
            break

        signs = init_signs.copy()

        # Ensure validity
        if not is_connected_fast(signs):
            # Try flipping one vertical edge
            fixed = False
            for vi in range(m):
                signs[vert_idx[vi]] *= -1
                if is_connected_fast(signs):
                    fixed = True
                    break
                signs[vert_idx[vi]] *= -1
            if not fixed:
                # Flip a cycle edge
                for ci in c1_idx:
                    signs[ci] *= -1
                    if is_connected_fast(signs):
                        fixed = True
                        break
                    signs[ci] *= -1
            if not fixed:
                continue

        current_radius = spectral_radius_vec(signs)

        # Local search: 1-flips
        improved = True
        max_iter = 20
        it = 0
        while improved and it < max_iter and (time.time() - start_time < DEADLINE - 1):
            improved = False
            it += 1
            # Try all 1-flips
            for i in range(n_edges):
                if time.time() - start_time > DEADLINE - 1:
                    break
                old = signs[i]
                signs[i] = -old

                if not is_connected_fast(signs):
                    signs[i] = old
                    continue

                new_radius = spectral_radius_vec(signs)
                if new_radius < current_radius - 1e-12:
                    current_radius = new_radius
                    improved = True
                else:
                    signs[i] = old

            # If no 1-flip helped, try 2-flips
            if not improved:
                for _ in range(50):
                    if time.time() - start_time > DEADLINE - 1:
                        break
                    i, j = rng.choice(n_edges, size=2, replace=False)
                    oi = signs[i]
                    oj = signs[j]
                    signs[i] = -oi
                    signs[j] = -oj

                    if not is_connected_fast(signs):
                        signs[i] = oi
                        signs[j] = oj
                        continue

                    new_radius = spectral_radius_vec(signs)
                    if new_radius < current_radius - 1e-12:
                        current_radius = new_radius
                        improved = True
                        break
                    else:
                        signs[i] = oi
                        signs[j] = oj

        if current_radius < best_radius:
            best_radius = current_radius
            best_signs = signs.copy()

    # Final polish: more aggressive local search from best
    if best_signs is not None and time.time() - start_time < DEADLINE - 2:
        current_signs = best_signs.copy()
        current_radius = best_radius

        # Multi-restart local search with perturbation
        for restart in range(50):
            if time.time() - start_time > DEADLINE - 1:
                break

            # Perturb
            n_perturb = rng.integers(1, 4)
            pert_idx = rng.choice(n_edges, size=n_perturb, replace=False)
            for idx in pert_idx:
                current_signs[idx] *= -1

            if not is_connected_fast(current_signs):
                # Try to fix
                fixed = False
                for vi in range(m):
                    current_signs[vert_idx[vi]] *= -1
                    if is_connected_fast(current_signs):
                        fixed = True
                        break
                    current_signs[vert_idx[vi]] *= -1
                if not fixed:
                    continue

            current_radius = spectral_radius_vec(current_signs)

            # Local search
            improved = True
            it = 0
            while improved and it < 15 and (time.time() - start_time < DEADLINE - 1):
                improved = False
                it += 1
                for i in range(n_edges):
                    if time.time() - start_time > DEADLINE - 1:
                        break
                    old = current_signs[i]
                    current_signs[i] = -old

                    if not is_connected_fast(current_signs):
                        current_signs[i] = old
                        continue

                    new_radius = spectral_radius_vec(current_signs)
                    if new_radius < current_radius - 1e-12:
                        current_radius = new_radius
                        improved = True
                    else:
                        current_signs[i] = old

            if current_radius < best_radius:
                best_radius = current_radius
                best_signs = current_signs.copy()

    if best_signs is None:
        # Fallback
        best_signs = np.ones(n_edges, dtype=int)
        best_signs[vert_idx[0]] = -1

    return best_signs
