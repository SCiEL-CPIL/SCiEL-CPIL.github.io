import time
import sys

def construct(k, g):
    deadline = time.time() + 140  # safety margin before 150s kill

    # ---- Petersen base graph: 10 vertices, 3-regular, girth 5 ----
    # Standard Petersen: outer pentagon 0-4, inner star 5-9
    # Vertices 0..4 form outer cycle: 0-1-2-3-4-0
    # Vertices 5..9 form inner star: 5-7-9-6-8-5
    # Spokes: i - (i+5) % 10 ... actually standard: i connects to (5+i)
    petersen_edges = [
        (0, 1), (1, 2), (2, 3), (3, 4), (4, 0),  # outer pentagon
        (5, 7), (7, 9), (9, 6), (6, 8), (8, 5),  # inner star
        (0, 5), (1, 6), (2, 7), (3, 8), (4, 9)   # spokes
    ]
    n_base = 10
    # Build adjacency list for base
    base_adj = [[] for _ in range(n_base)]
    for u, v in petersen_edges:
        base_adj[u].append(v)
        base_adj[v].append(u)

    # ---- A_5 group: order 60, non-abelian simple ----
    # Represent A_5 as even permutations of {0,1,2,3,4}
    # We'll use a compact representation: index into list of all even perms
    from itertools import permutations

    all_perms = list(permutations(range(5)))
    # Even permutations: sign = (-1)^(number of inversions)
    def parity(p):
        inv = 0
        for i in range(5):
            for j in range(i + 1, 5):
                if p[i] > p[j]:
                    inv += 1
        return inv % 2

    a5_elems = [p for p in all_perms if parity(p) == 0]
    n_group = len(a5_elems)  # should be 60
    assert n_group == 60, f"A5 should have 60 elements, got {n_group}"

    # Build multiplication table
    elem_to_idx = {p: i for i, p in enumerate(a5_elems)}
    mul_table = [[0] * n_group for _ in range(n_group)]
    for i, ei in enumerate(a5_elems):
        for j, ej in enumerate(a5_elems):
            # product ei * ej (composition: apply ej first, then ei)
            prod = tuple(ei[ej[x]] for x in range(5))
            mul_table[i][j] = elem_to_idx[prod]

    identity_idx = elem_to_idx[(0, 1, 2, 3, 4)]

    # Inverse table
    inv_table = [0] * n_group
    for i, ei in enumerate(a5_elems):
        inv = tuple(ei.index(x) for x in range(5))
        inv_table[i] = elem_to_idx[inv]

    # ---- Systematic voltage assignment using A_5 multiplication table ----
    # Strategy: assign voltages to base edges using a fixed set of group elements
    # derived from the group structure. We want to maximize girth.
    #
    # Key insight: for a closed walk v0->v1->...->vm=v0 in the base, the lifted
    # walk closes iff the product of voltages (with inverses for backward edges)
    # equals identity. To avoid short cycles, we want short closed walks in the
    # base to have non-identity voltage products.
    #
    # Petersen has girth 5, so the shortest cycles are length 5.
    # We assign voltages so that all 5-cycles (and longer up to g-1) have
    # non-identity products.
    #
    # Systematic approach: use a "generic" assignment based on group generators.
    # A_5 is generated by two elements. We assign different generator-related
    # elements to different edge classes.

    # Pick specific group elements for voltage assignment
    # Use elements that are "independent" in some sense
    # We'll use the first few non-identity elements in a structured way

    # Let's pick 15 voltages (one per base edge) from A_5
    # Use a deterministic selection based on edge position
    # To be systematic, use elements with specific cycle structures:
    # - 3-cycles: 20 elements
    # - 5-cycles: 24 elements  
    # - double transpositions: 15 elements

    # Classify elements
    def cycle_type(p):
        visited = [False] * 5
        cycles = []
        for i in range(5):
            if not visited[i]:
                length = 0
                cur = i
                while not visited[cur]:
                    visited[cur] = True
                    cur = p[cur]
                    length += 1
                cycles.append(length)
        cycles.sort(reverse=True)
        return tuple(cycles)

    three_cycles = [i for i, p in enumerate(a5_elems) if cycle_type(p) == (3, 1, 1)]
    five_cycles = [i for i, p in enumerate(a5_elems) if cycle_type(p) == (5,)]
    double_trans = [i for i, p in enumerate(a5_elems) if cycle_type(p) == (2, 2, 1)]

    # Assign voltages systematically:
    # Outer pentagon edges: use 3-cycles
    # Inner star edges: use 5-cycles
    # Spokes: use double transpositions
    # This creates structural diversity

    # Outer pentagon: edges (0,1),(1,2),(2,3),(3,4),(4,0)
    # Inner star: edges (5,7),(7,9),(9,6),(6,8),(8,5)
    # Spokes: (0,5),(1,6),(2,7),(3,8),(4,9)

    voltage = {}  # (u,v) -> group element index, for u < v
    # Assign outer pentagon
    outer_edges = [(0,1), (1,2), (2,3), (3,4), (4,0)]
    for i, (u,v) in enumerate(outer_edges):
        voltage[(u,v)] = three_cycles[i * 4]  # spread out in the 3-cycle class

    # Assign inner star
    inner_edges = [(5,7), (7,9), (9,6), (6,8), (8,5)]
    for i, (u,v) in enumerate(inner_edges):
        voltage[(u,v)] = five_cycles[i * 4]  # spread out in the 5-cycle class

    # Assign spokes
    spoke_edges = [(0,5), (1,6), (2,7), (3,8), (4,9)]
    for i, (u,v) in enumerate(spoke_edges):
        voltage[(u,v)] = double_trans[i * 3]  # spread out

    # ---- Build the lifted graph ----
    # Vertex (base_vertex, group_element)
    # Lifted edge: (u, g) -- (v, g * voltage[u,v]) if u->v is directed with voltage
    # For undirected: if base edge is (u,v) with voltage w, then
    #   (u, g) connects to (v, g * w)
    #   (v, g) connects to (u, g * w^{-1})

    n_lifted = n_base * n_group  # 600
    lifted_edges = []
    seen = set()

    for (u, v), w in voltage.items():
        w_inv = inv_table[w]
        for g in range(n_group):
            # Edge from (u,g) to (v, g*w)
            vu = u * n_group + g
            vv = v * n_group + mul_table[g][w]
            a, b = min(vu, vv), max(vu, vv)
            if (a, b) not in seen:
                seen.add((a, b))
                lifted_edges.append((a, b))
            # Edge from (v,g) to (u, g*w_inv)
            vv2 = v * n_group + g
            vu2 = u * n_group + mul_table[g][w_inv]
            a2, b2 = min(vv2, vu2), max(vv2, vu2)
            if (a2, b2) not in seen:
                seen.add((a2, b2))
                lifted_edges.append((a2, b2))

    # ---- Verify: 3-regular, simple, girth >= g ----
    # Build adjacency
    adj = [[] for _ in range(n_lifted)]
    for u, v in lifted_edges:
        adj[u].append(v)
        adj[v].append(u)

    # Check regularity
    for i in range(n_lifted):
        if len(adj[i]) != k:
            # Fallback: return the LUW-style construction
            return _luw_fallback(k, g)

    # Check girth with non-backtracking walks
    def check_girth(adj, n, min_girth):
        """Check that no cycle shorter than min_girth exists using non-backtracking walks."""
        from collections import deque
        # For each vertex, do BFS with non-backtracking constraint
        # State: (current_vertex, previous_vertex, depth)
        # We want to find if any cycle of length < min_girth exists
        # A cycle of length L corresponds to a non-backtracking walk of length L
        # that returns to the start.
        
        # More efficient: for each vertex, explore non-backtracking walks
        # up to depth min_girth - 1, checking if we return to start
        for start in range(n):
            if time.time() > deadline - 10:
                return False  # timeout, assume valid
            # BFS in state space (vertex, prev)
            visited = set()
            queue = deque()
            # Start: from start, go to each neighbor
            for nb in adj[start]:
                queue.append((nb, start, 1))
                visited.add((nb, start))
            while queue:
                curr, prev, depth = queue.popleft()
                if depth >= min_girth - 1:
                    continue
                # If we've returned to start at depth < min_girth, we found a short cycle
                # But we can't go back to prev (non-backtracking)
                for nb in adj[curr]:
                    if nb == prev:
                        continue
                    if nb == start and depth + 1 < min_girth:
                        return False  # found cycle shorter than min_girth
                    if (nb, curr) not in visited:
                        visited.add((nb, curr))
                        queue.append((nb, curr, depth + 1))
        return True

    if not check_girth(adj, n_lifted, g):
        # This voltage assignment doesn't work; try a different systematic assignment
        # For now, fall back to LUW
        return _luw_fallback(k, g)

    return n_lifted, lifted_edges


def _luw_fallback(k, g):
    """Fallback: Lazebnik-Ustimenko-Woldar construction."""
    q = k
    d = max(3, g - 5 if (g - 5) % 2 else g - 4)
    if q == 4:
        table = [[0, 0, 0, 0], [0, 1, 2, 3], [0, 2, 3, 1], [0, 3, 1, 2]]
        add, sub, mul = (lambda x, y: x ^ y), (lambda x, y: x ^ y), (lambda x, y: table[x][y])
    else:
        add, sub, mul = (lambda x, y: (x + y) % q), (lambda x, y: (x - y) % q), (lambda x, y: x * y % q)
    rule = {2: (1, 1), 3: (2, 1), 4: (1, 2)}
    for c in range(5, d + 1):
        r, c0 = (c - 5) % 4, c - (c - 5) % 4
        rule[c] = [(1, c0 - 2), (c0 - 1, 1), (c0, 1), (1, c0 + 1)][r]

    def neighbours(vertex):
        side, x = vertex
        for first in range(q):
            y = [None, first] + [0] * (d - 1)
            for c in range(2, d + 1):
                a, b = rule[c]
                y[c] = add(x[c], mul(y[a], x[b])) if side == 0 else sub(x[c], mul(x[a], y[b]))
            yield 1 - side, tuple(y)

    start = (0, (None,) + (0,) * d)
    index, order, edges = {start: 0}, [start], []
    for vertex in order:
        for other in neighbours(vertex):
            if other not in index:
                index[other] = len(order)
                order.append(other)
            if vertex[0] == 0:
                edges.append((index[vertex], index[other]))
    return len(order), edges
