"""Optimized solver for spectral graph lifts on prism graphs."""
import time
import numpy as np
from itertools import product

def sign_edges(graph, budget):
    """
    Returns an array of signs (-1 or +1) for each edge in the prism graph,
    aiming to minimize the spectral radius of the signed adjacency matrix
    while ensuring the resulting 2-lift is connected and 3-regular.
    """
    start_time = time.time()
    deadline = start_time + 55.0  # 5s safety margin for 60s limit

    m = graph['n'] // 2
    n = graph['n']
    edges = graph['edges']
    num_edges = len(edges)
    
    # Map edges to indices for quick lookup
    # Edge structure of prism graph:
    # 1. Top cycle: (i, i+1) for i in 0..m-1 (with wrap)
    # 2. Bottom cycle: (m+i, m+i+1) for i in 0..m-1 (with wrap)
    # 3. Matching: (i, m+i) for i in 0..m-1
    
    # We need to identify which edge is which to efficiently update the matrix
    # or just rebuild it. Rebuilding is O(E) which is small (3m).
    
    def build_signed_adj(signs):
        A = np.zeros((n, n), dtype=np.float64)
        for (u, v), s in zip(edges, signs):
            A[u, v] = float(s)
            A[v, u] = float(s)
        return A

    def spectral_radius(A):
        try:
            eigvals = np.linalg.eigvalsh(A)
            return float(np.max(np.abs(eigvals)))
        except Exception:
            return float('inf')

    def check_validity(graph, signs):
        """
        Checks if the lift is connected and 3-regular.
        Since the base graph is 3-regular and we use a 2-lift, 
        the lift is always 3-regular. 
        The lift is connected iff the signed graph is "balanced" in a specific way?
        No, for a 2-lift of a graph G with signs, the lift is connected iff 
        the subgroup generated by the cycles' signs is the whole group {+1, -1}.
        i.e., there must be at least one odd cycle (product of signs = -1)
        in the signed graph. If all cycles are even (product +1), the lift
        consists of two disconnected copies of G.
        
        So validity condition: The signed graph must contain at least one cycle 
        with product of signs = -1.
        """
        # A faster check: 
        # The lift is disconnected if and only if the signs are "balanced", 
        # meaning there exists a vertex labeling b: V -> {+1, -1} such that 
        # for every edge (u, v) with sign s, s = b(u) * b(v).
        # If such a labeling exists, the lift is disconnected.
        # We can check this via BFS/DFS on the signed graph.
        
        # Build adjacency list for the signed graph
        adj = [[] for _ in range(n)]
        for i, (u, v) in enumerate(edges):
            s = signs[i]
            adj[u].append((v, s))
            adj[v].append((u, s))
            
        # Try to assign labels
        labels = [0] * n  # 0: unvisited, 1: +1, -1: -1
        labels[0] = 1
        
        for start in range(n):
            if labels[start] != 0:
                continue
            queue = [start]
            while queue:
                u = queue.pop(0)
                for v, s in adj[u]:
                    expected_label = labels[u] * s
                    if labels[v] == 0:
                        labels[v] = expected_label
                        queue.append(v)
                    else:
                        if labels[v] != expected_label:
                            # Contradiction found -> Not balanced -> Connected lift
                            return True
        # If we finish without contradiction, it is balanced -> Disconnected lift
        return False

    def evaluate(signs):
        if not check_validity(graph, signs):
            return float('inf')
        A = build_signed_adj(signs)
        r = spectral_radius(A)
        return r

    # Initialize with a random valid sign assignment
    # Start with all +1 (which is balanced, so invalid). 
    # Flip one edge to make it unbalanced.
    # Actually, let's just generate a random one and check.
    
    best_signs = None
    best_score = float('inf')
    
    # Strategy:
    # 1. Try a few specific patterns known to be good (e.g., alternating signs on cycles).
    # 2. Use local search (flip one sign at a time) to minimize spectral radius.
    
    # Pattern 1: Alternating signs on the top cycle, all +1 elsewhere.
    # This creates odd cycles involving the matching edges.
    # Let's just do a random restart and local search.
    
    rng = np.random.default_rng(3)
    
    # Generate initial random signs
    signs = rng.choice([-1, 1], size=num_edges)
    
    # Ensure validity
    # If invalid (balanced), flip a random edge until valid.
    # Max 10 attempts for initial validity
    for _ in range(10):
        if check_validity(graph, signs):
            break
        idx = rng.integers(num_edges)
        signs[idx] *= -1
        
    if not check_validity(graph, signs):
        # Fallback: force a specific unbalanced pattern
        # e.g. make one triangle have product -1
        # Prism graph has triangles (i, i+1, m+i) if m=3? No, m>=4.
        # Prism graph has 4-cycles (i, i+1, m+i+1, m+i).
        # Product of signs on a 4-cycle: s(i,i+1)*s(i+1,m+i+1)*s(m+i+1,m+i)*s(m+i,i)
        # If we set all signs to +1 except one edge in a cycle to -1, it becomes unbalanced.
        signs[:] = 1
        signs[0] = -1  # Flip first edge (0,1)
        # This makes the cycle 0-1-(m+1)-m-0 have product -1?
        # Edges: (0,1), (1, m+1), (m+1, m), (m, 0)
        # Signs: -1, 1, 1, 1 -> Product -1. Valid.
        
    current_signs = signs.copy()
    current_score = evaluate(current_signs)
    if current_score < best_score:
        best_score = current_score
        best_signs = current_signs.copy()
        
    # Local Search
    # Flip one sign at a time.
    # Since n is small (8, 10, 14, 18), E is small (12, 15, 21, 27).
    # We can evaluate all single flips.
    
    improved = True
    while improved and time.time() < deadline:
        improved = False
        best_neighbor_score = current_score
        best_neighbor_signs = current_signs
        
        for i in range(num_edges):
            if time.time() > deadline:
                break
            # Flip sign i
            new_signs = current_signs.copy()
            new_signs[i] *= -1
            
            # Quick validity check
            if not check_validity(graph, new_signs):
                continue
                
            score = evaluate(new_signs)
            
            if score < best_neighbor_score - 1e-9:
                best_neighbor_score = score
                best_neighbor_signs = new_signs
        
        if best_neighbor_score < current_score - 1e-9:
            current_signs = best_neighbor_signs
            current_score = best_neighbor_score
            improved = True
            
            if current_score < best_score:
                best_score = current_score
                best_signs = current_signs.copy()
        else:
            # No improvement found in single flips. 
            # Try double flips? Or random restarts?
            # Let's try a few random restarts if time permits.
            break
            
    # If we have time, try some random restarts with local search
    if time.time() < deadline:
        for restart in range(20):
            if time.time() > deadline:
                break
            signs = rng.choice([-1, 1], size=num_edges)
            # Ensure validity
            valid = False
            for _ in range(10):
                if check_validity(graph, signs):
                    valid = True
                    break
                idx = rng.integers(num_edges)
                signs[idx] *= -1
            if not valid:
                continue
                
            current_signs = signs.copy()
            current_score = evaluate(current_signs)
            
            # Local search for this restart
            improved = True
            while improved and time.time() < deadline:
                improved = False
                best_neighbor_score = current_score
                best_neighbor_signs = current_signs
                
                for i in range(num_edges):
                    if time.time() > deadline:
                        break
                    new_signs = current_signs.copy()
                    new_signs[i] *= -1
                    if not check_validity(graph, new_signs):
                        continue
                    score = evaluate(new_signs)
                    if score < best_neighbor_score - 1e-9:
                        best_neighbor_score = score
                        best_neighbor_signs = new_signs
                        
                if best_neighbor_score < current_score - 1e-9:
                    current_signs = best_neighbor_signs
                    current_score = best_neighbor_score
                    improved = True
                    if current_score < best_score:
                        best_score = current_score
                        best_signs = current_signs.copy()
                else:
                    break

    return best_signs
