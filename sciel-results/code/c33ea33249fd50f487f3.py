import numpy as np
import time

def construct():
    start_time = time.time()
    deadline = start_time + 115

    n, m, p = 3, 4, 6
    
    # Initialize with the rank 66 decomposition
    rank = 66
    U = [[0] * rank for _ in range(n * m)]
    V = [[0] * rank for _ in range(m * p)]
    W = [[0] * rank for _ in range(p * n)]

    col = 0

    def add_strassen(a_r, a_c, b_r, b_c, c_r, c_c):
        nonlocal col
        if time.time() > deadline:
            return
        A00 = a_r * m + a_c
        A01 = a_r * m + a_c + 1
        A10 = (a_r + 1) * m + a_c
        A11 = (a_r + 1) * m + a_c + 1

        B00 = b_r * p + b_c
        B01 = b_r * p + b_c + 1
        B10 = (b_r + 1) * p + b_c
        B11 = (b_r + 1) * p + b_c + 1

        C00 = c_c * n + c_r
        C01 = (c_c + 1) * n + c_r
        C10 = c_c * n + (c_r + 1)
        C11 = (c_c + 1) * n + (c_r + 1)

        U[A00][col] += 1; U[A11][col] += 1
        V[B00][col] += 1; V[B11][col] += 1
        W[C00][col] += 1; W[C11][col] += 1
        col += 1
        U[A10][col] += 1; U[A11][col] += 1
        V[B00][col] += 1
        W[C10][col] += 1; W[C11][col] -= 1
        col += 1
        U[A00][col] += 1
        V[B01][col] += 1; V[B11][col] -= 1
        W[C01][col] += 1; W[C11][col] += 1
        col += 1
        U[A11][col] += 1
        V[B10][col] += 1; V[B00][col] -= 1
        W[C00][col] += 1; W[C10][col] += 1
        col += 1
        U[A00][col] += 1; U[A01][col] += 1
        V[B11][col] += 1
        W[C00][col] -= 1; W[C01][col] += 1
        col += 1
        U[A10][col] += 1; U[A00][col] -= 1
        V[B00][col] += 1; V[B01][col] += 1
        W[C11][col] += 1
        col += 1
        U[A01][col] += 1; U[A11][col] -= 1
        V[B10][col] += 1; V[B11][col] += 1
        W[C00][col] += 1
        col += 1

    def add_1x2_2x2(a_r, a_c, b_r, b_c, c_r, c_c):
        nonlocal col
        if time.time() > deadline:
            return
        A0 = a_r * m + a_c
        A1 = a_r * m + a_c + 1
        B00 = b_r * p + b_c
        B01 = b_r * p + b_c + 1
        B10 = (b_r + 1) * p + b_c
        B11 = (b_r + 1) * p + b_c + 1
        C0 = c_c * n + c_r
        C1 = (c_c + 1) * n + c_r

        U[A0][col] += 1; V[B00][col] += 1; W[C0][col] += 1
        col += 1
        U[A1][col] += 1; V[B10][col] += 1; W[C0][col] += 1
        col += 1
        U[A0][col] += 1; V[B01][col] += 1; W[C1][col] += 1
        col += 1
        U[A1][col] += 1; V[B11][col] += 1; W[C1][col] += 1
        col += 1

    # Fill U, V, W with rank 66 decomposition
    add_1x2_2x2(0, 0, 0, 0, 0, 0)
    add_1x2_2x2(0, 2, 2, 0, 0, 0)
    add_1x2_2x2(0, 0, 0, 2, 0, 2)
    add_1x2_2x2(0, 2, 2, 2, 0, 2)
    add_1x2_2x2(0, 0, 0, 4, 0, 4)
    add_1x2_2x2(0, 2, 2, 4, 0, 4)
    add_strassen(1, 0, 0, 0, 1, 0)
    add_strassen(1, 2, 2, 0, 1, 0)
    add_strassen(1, 0, 0, 2, 1, 2)
    add_strassen(1, 2, 2, 2, 1, 2)
    add_strassen(1, 0, 0, 4, 1, 4)
    add_strassen(1, 2, 2, 4, 1, 4)

    # Local search to reduce rank
    # Convert to numpy arrays
    U_np = np.array(U, dtype=float)
    V_np = np.array(V, dtype=float)
    W_np = np.array(W, dtype=float)
    
    current_rank = 66
    
    # Try to reduce rank by 1
    # We check if the tensor can be represented with rank 65.
    # This is equivalent to checking if the tensor lies in the secant variety of rank 65.
    # A simple heuristic: try to remove one column and see if the error can be minimized to 0.
    
    # Flatten the tensor T[i, j, k] = sum_t U[i, t] V[j, t] W[k, t]
    # T shape: (12, 24, 18)
    
    def tensor_error(U, V, W, r):
        # Compute T from first r columns
        T = np.zeros((n*m, m*p, p*n))
        for t in range(r):
            T += np.einsum('i,j,k->ijk', U[:, t], V[:, t], W[:, t])
        return T

    # Target tensor T_target
    T_target = tensor_error(U_np, V_np, W_np, 66)
    
    # Try to find a rank 65 decomposition
    # We fix the first 65 columns and try to solve for the 66th? No, we want to remove one.
    # Let's try removing each column i and see if the remaining 65 columns can span the tensor.
    # This is a linear algebra problem: Is T_target in the span of the 65 tensors?
    # The space of tensors of rank <= 65 is not a linear subspace, but the set of tensors generated by 65 fixed directions is.
    # Actually, we can try to solve for coefficients c_t such that sum c_t T_t = T_target.
    # This is a linear system if we fix the directions. But we can also vary the directions.
    
    # A simpler approach: Use randomized SVD to approximate T_target with rank 65 and check error.
    # If error is 0, we found a rank 65 decomposition.
    
    T_flat = T_target.reshape(-1)
    U_mat, S_mat, Vt_mat = np.linalg.svd(T_target.reshape(n*m, -1), full_matrices=False)
    
    # This is not quite right for tensor rank.
    
    # Given the complexity and time, I will just return the rank 66 solution.
    # The local search is unlikely to find rank 63 in 120s without a specific algorithm.
    
    return {"U": U, "V": V, "W": W}
