import math
from itertools import combinations

def calc_score(U):
    if not U:
        return 0
    U = list(set(U))
    if 0 not in U:
        return 0
    max_u = max(U)
    if max_u == 0:
        return 0
    sums = set()
    diffs = set()
    for a in U:
        for b in U:
            sums.add(a + b)
            diffs.add(a - b)
    num = len(diffs) / len(sums)
    den = math.log(2 * max_u + 1)
    if den == 0:
        return 0
    return 1 + math.log(num) / den

def construct():
    # Search for optimal digit set D and base B
    best_score = 0
    best_D = [0, 1]
    best_B = 2
    
    # Search small digit sets
    for size in range(2, 6):
        for D_tuple in combinations(range(16), size):
            if 0 not in D_tuple:
                continue
            D = list(D_tuple)
            sums_D = set()
            diffs_D = set()
            for a in D:
                for b in D:
                    sums_D.add(a + b)
                    diffs_D.add(a - b)
            
            max_sum = max(sums_D)
            B = max_sum + 1
            if B < 2:
                continue
            
            # The score for infinite digits is 1 + log(|D-D|/|D+U|)/log(B)
            # But we use finite n. The term is n*log(ratio)/n*log(B)
            ratio = len(diffs_D) / len(sums_D)
            if ratio <= 1:
                continue
            
            # We need to ensure that for the chosen n, the score is actually achieved.
            # The formula 1 + log(|U-U|/|U+U|)/log(2 max U + 1)
            # For U generated by n digits, |U-U| = |D-D|^n, |U+U| = |D+U|^n.
            # max U = B^n - 1 (approx).
            # log(2 max U + 1) approx n log B.
            # So score approx 1 + log(ratio) / log B.
            
            score_est = 1 + math.log(ratio) / math.log(B)
            
            if score_est > best_score:
                best_score = score_est
                best_D = D
                best_B = B

    # Generate the set U using the best D and B
    # Use n=10 to ensure it's a "finite set" and large enough
    n = 10
    U = [0]
    # Generate all combinations of digits
    # We can do this recursively or with itertools
    from itertools import product
    for digits in product(best_D, repeat=n):
        val = 0
        for j in range(n):
            val += digits[j] * (best_B ** j)
        U.append(val)
    
    # Remove duplicates and ensure 0 is present
    U = list(set(U))
    if 0 not in U:
        U.append(0)
        
    return U
