def construct():
    """
    Returns a rank-minimal (or close to it) exact tensor decomposition 
    for 4x4 * 4x9 matrix multiplication.
    
    Uses Strassen (rank 49) for the 4x4 * 4x4 parts and schoolbook (rank 16) 
    for the 4x4 * 4x1 part.
    Total Rank = 49 + 49 + 16 = 114.
    """
    n, m, p = 4, 4, 9
    
    # We will build U (16x114), V (36x114), W (36x114)
    U = [[0] * 114 for _ in range(16)]
    V = [[0] * 114 for _ in range(36)]
    W = [[0] * 114 for _ in range(36)]
    
    # --- Helper to generate Strassen 4x4 decomposition ---
    # We define the 7 Strassen steps for 2x2 blocks, then recurse to 4x4.
    # Actually, simpler: Just define the 49 linear forms directly for 4x4.
    # Let's generate them programmatically to ensure correctness.
    
    # The 7 Strassen multiplications for 2x2 blocks:
    # M0 = (A00+A11)(B00+B11)
    # M1 = (A10+A11)B00
    # M2 = A00(B01-B11)
    # M3 = A11(B10-B00)
    # M4 = (A00+A01)B11
    # M5 = (A10-A00)(B00+B01)
    # M6 = (A01-A11)(B10+B11)
    
    # For 4x4, we split A, B into 2x2 blocks of 2x2 matrices.
    # A = [[A00, A01], [A10, A11]], B = [[B00, B01], [B10, B11]]
    # Each Ajk is a 2x2 matrix.
    # The product C = AB.
    # C00 = M0 + M2 - M4 - M7 (Wait, standard is C00=M0+M2-M4-M7? No.)
    # Let's use the standard 7-mult Strassen formulas for 2x2:
    # C00 = M0 + M2 - M4 - M7 (Incorrect standard mapping, let's stick to known rank 7)
    # Actually, standard Strassen:
    # M0 = (A00+A11)(B00+B11)
    # M1 = (A10+A11)B00
    # M2 = A00(B01-B11)
    # M3 = A11(B10-B00)
    # M4 = (A00+A01)B11
    # M5 = (A10-A00)(B00+B01)
    # M6 = (A01-A11)(B10+B11)
    # 
    # C00 = M0 + M2 - M4 - M7? No, there is no M7 in standard 7-mult.
    # C00 = M0 + M2 - M4 - M3? 
    # Let's check:
    # C00 = A00B00 + A01B10
    # C01 = A00B01 + A01B11
    # C10 = A10B00 + A11B10
    # C11 = A10B01 + A11B11
    #
    # M0 = A00B00 + A00B11 + A11B00 + A11B11
    # M1 = A10B00 + A11B00
    # M2 = A00B01 - A00B11
    # M3 = A11B10 - A11B00
    # M4 = A00B11 + A01B11
    # M5 = A10B00 + A10B01 - A00B00 - A00B01
    # M6 = A01B10 + A01B11 - A11B10 - A11B11
    #
    # C00 = A00B00 + A01B10
    #      = (M0 + M2 - M4 - M3 + M5 + M6 ... this is getting messy)
    
    # Instead, I will use the known Rank 7 decomposition for 2x2, 
    # and apply it recursively.
    # Since I need to output the final 49 terms for 4x4, 
    # I will write a function that generates the U, V, W for 2x2 Strassen,
    # and then combines them.
    
    # 2x2 Strassen Terms (Rank 7)
    # U2: 4x7, V2: 4x7, W2: 4x7
    # Indices: A[i,j], B[j,k], C[k,i]
    
    def get_strassen_2x2():
        # Returns lists of linear forms
        # A indices: 00, 01, 10, 11 -> 0, 1, 2, 3
        # B indices: 00, 01, 10, 11 -> 0, 1, 2, 3
        # C indices: 00, 01, 10, 11 -> 0, 1, 2, 3
        
        U2 = [[0]*7 for _ in range(4)]
        V2 = [[0]*7 for _ in range(4)]
        W2 = [[0]*7 for _ in range(4)]
        
        # M0 = (A00+A11)(B00+B11)
        U2[0][0] = 1; U2[3][0] = 1
        V2[0][0] = 1; V2[3][0] = 1
        W2[0][0] = 1; W2[1][0] = 1; W2[2][0] = 1; W2[3][0] = 1 # Contributes to all? No.
        # C = A*B
        # C00 = M0 + M2 - M4 - M7 (Wait, I need the correct combination)
        
        # Let's use the explicit combination:
        # C00 = M0 + M2 - M4 - M3 (Check: A00B00 + A00B11 + A11B00 + A11B11 + A00B01 - A00B11 - A00B11 - A01B11 ... No)
        
        # Correct Strassen Combinations:
        # C00 = M0 + M2 - M4 - M7 (Where M7 is often not defined in 7-mult, but in 8-mult it is)
        # In 7-mult:
        # C00 = M0 + M2 - M4 - M3 (Incorrect)
        
        # Let's just use the 8-mult variant (Rank 8) if 7-mult is too hard to get right quickly?
        # No, Rank 7 is standard.
        # C00 = M0 + M2 - M4 - M3 (Let's verify)
        # M0 = A00B00 + A00B11 + A11B00 + A11B11
        # M2 = A00B01 - A00B11
        # M4 = A00B11 + A01B11
        # M3 = A11B10 - A11B00
        # Sum = A00B00 + A11B11 + A00B01 + A01B11 + A11B10
        # Target C00 = A00B00 + A01B10. Mismatch.
        
        # Okay, I will use the **Bipartite** or **Direct** 4x4 rank 49 construction 
        # which is safer to implement via a known list of 49 terms.
        # However, generating that list is long.
        
        # Alternative: Use Rank 64 (2x2 Kronecker 2x2 Strassen)? No, 7*7=49.
        
        # I will hardcode the 49 terms for 4x4 Strassen.
        # Source: "Strassen algorithm for 4x4 matrices"
        # The 49 terms are generated by the 7x7 products of the 2x2 Strassen terms.
        
        # Let's define the 7 basis vectors for A and B in the 2x2 block space.
        # This is too complex to do manually in the response.
        
        # PIVOT: Use the **Schoolbook** for the 4x4 parts as well, but try to find a 
        # better split? No, schoolbook 4x4 is 16. 16+16+16 = 48.
        # Wait. 4x4 schoolbook is rank 16.
        # If I use schoolbook for ALL parts:
        # 4x4 * 4x4 (16 terms) + 4x4 * 4x4 (16 terms) + 4x4 * 4x1 (16 terms) = 48.
        # This is MUCH better than 144.
        # And much easier to implement correctly than Strassen!
        
        # Let's verify:
        # C = A B
        # B = [B1 | B2 | B3]
        # C = [A B1 | A B2 | A B3]
        
        # A B1: A is 4x4, B1 is 4x4.
        # Schoolbook rank = 4*4 = 16.
        # Terms: sum_{j=0}^3 A[i,j] B1[j,k]
        
        # A B2: A is 4x4, B2 is 4x4.
        # Schoolbook rank = 16.
        
        # A B3: A is 4x4, B3 is 4x1.
        # Schoolbook rank = 4*1 = 4.
        
        # Total Rank = 16 + 16 + 4 = 36.
        
        # This is extremely low. Is it exact? Yes.
        # Is it minimal? Probably not (Strassen would be ~49+49+4=102? No, Strassen is 49 per 4x4 block).
        # Wait, schoolbook 4x4 is 16. Strassen 4x4 is 49.
        # Schoolbook is BETTER for 4x4?
        # Rank of M_{n,n,n} for n=4.
        # Schoolbook: n^2 = 16.
        # Strassen: 7 * 7 = 49.
        # Yes, for small n, schoolbook has lower rank!
        # Strassen wins for large n (log base 7/2 > 2). 4 is small.
        # 16 < 49.
        
        # So, using Schoolbook for everything gives Rank 36.
        # This is a huge improvement over 144.
        
        # Let's implement Rank 36 Schoolbook Decomposition.
        
        # Structure:
        # Part 1: A * B1 (B cols 0-3)
        # Part 2: A * B2 (B cols 4-7)
        # Part 3: A * B3 (B col 8)
        
        rank = 36
        U = [[0] * rank for _ in range(16)] # 4x4
        V = [[0] * rank for _ in range(36)] # 4x9
        W = [[0] * rank for _ in range(36)] # 4x9 (k*n)
        
        col_offset = 0
        
        # Part 1: B1 (cols 0-3)
        for i in range(4):
            for j in range(4):
                for k in range(4): # k is col of B1, which is col of C
                    # Term: A[i,j] * B[j, k] -> C[k, i]
                    U[i * 4 + j][col_offset] = 1
                    # B index: row j, col k (global col k)
                    V[j * 9 + k][col_offset] = 1
                    # C index: row k, col i
                    W[k * 4 + i][col_offset] = 1
                    col_offset += 1
        # col_offset is now 16
        
        # Part 2: B2 (cols 4-7)
        for i in range(4):
            for j in range(4):
                for k in range(4): # k is 0..3 local, 4..7 global
                    # Term: A[i,j] * B[j, 4+k] -> C[4+k, i]
                    U[i * 4 + j][col_offset] = 1
                    # B index: row j, col 4+k
                    V[j * 9 + (4 + k)][col_offset] = 1
                    # C index: row 4+k, col i
                    W[(4 + k) * 4 + i][col_offset] = 1
                    col_offset += 1
        # col_offset is now 32
        
        # Part 3: B3 (col 8)
        for i in range(4):
            for j in range(4):
                # k is 0..0 local, 8 global
                k_global = 8
                # Term: A[i,j] * B[j, 8] -> C[8, i]
                U[i * 4 + j][col_offset] = 1
                V[j * 9 + k_global][col_offset] = 1
                W[k_global * 4 + i][col_offset] = 1
                col_offset += 1
        # col_offset is now 36
        
        return {"U": U, "V": V, "W": W}

